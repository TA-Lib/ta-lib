   /// <summary>
   /// Wilder's Relative Strength Index, a momentum oscillator bounded 0-100 from
   /// the ratio of average gains to average losses over the period. Used to
   /// gauge overbought/oversold conditions. &gt;70 overbought, &lt;30 oversold.
   /// </summary>
   /// <remarks>
   /// <b>Formula</b>
   /// <code>
   /// $$
   /// \begin{aligned}
   /// U_t &amp;= \max(X_t - X_{t-1},\ 0)
   /// &amp;  D_t &amp;= \max(X_{t-1} - X_t,\ 0) \\[4pt]
   /// \overline{U}_t &amp;= \begin{cases}
   /// \operatorname{SMA}(U, n)_t                 &amp; \text{if } t = n \\[4pt]
   /// \dfrac{(n-1)\,\overline{U}_{t-1} + U_t}{n} &amp; \text{if } t &gt; n
   /// \end{cases}
   /// &amp;  \overline{D}_t &amp;= \begin{cases}
   /// \operatorname{SMA}(D, n)_t                 &amp; \text{if } t = n \\[4pt]
   /// \dfrac{(n-1)\,\overline{D}_{t-1} + D_t}{n} &amp; \text{if } t &gt; n
   /// \end{cases} \\[4pt]
   /// \mathrm{RS}_t &amp;= \frac{\overline{U}_t}{\overline{D}_t}
   /// &amp;  \mathrm{RSI}_t &amp;= 100 - \frac{100}{1 + \mathrm{RS}_t}
   /// \end{aligned}
   /// $$
   /// where $X$ is the input series and $n$ the period.
   /// </code>
   /// <para>
   /// This is the <c>float[]</c> overload: input elements are widened to
   /// <c>double</c> as they are read and all arithmetic is performed in
   /// <c>double</c>, so a result beyond <c>float</c> range is still
   /// representable.
   /// </para>
   /// <para>
   /// Values are written only where the indicator is defined. The returned
   /// <see cref="OutRange"/> says where they start and how many there are;
   /// nothing outside that range is touched, and the library never pads with
   /// NaN. A valid range shorter than <c>RsiLookback</c> is a <b>success with no
   /// values</b> (<c>Count == 0</c>), not an error.
   /// </para>
   /// </remarks>
   /// <param name="startIdx">First bar of the requested range (inclusive).</param>
   /// <param name="endIdx">Last bar of the requested range (inclusive).</param>
   /// <param name="inReal">Price series (typically close)</param>
   /// <param name="optInTimePeriod">Lookback for the gain/loss averaging (default 14; range 2..100000;
   /// <c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">RSI value. Must hold at least <c>endIdx - startIdx + 1</c> values.</param>
   /// <returns>The range written: <c>BegIdx</c> is the first bar with a value,
   /// <c>Count</c> how many were written.</returns>
   /// <exception cref="System.ArgumentOutOfRangeException"><c>startIdx</c> or <c>endIdx</c> is negative, or <c>endIdx &lt;
   /// startIdx</c>.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or two outputs
   /// share one array.</exception>
   /// <exception cref="System.NullReferenceException">An input or output array is null. (Unlike the C library, the managed tier
   /// does not pre-validate nulls; the first array access throws.)</exception>
   public OutRange Rsi( int startIdx,
                        int endIdx,
                        float[] inReal,
                        int optInTimePeriod,
                        double[] outReal )
   {
      RetCode retCode = Rsi(startIdx, endIdx, inReal, optInTimePeriod, out int outBegIdx, out int outNBElement, outReal);
      if( retCode != RetCode.Success ) {
         throw Failure("RSI", retCode);
      }
      return new OutRange(outBegIdx, outNBElement);
   }
