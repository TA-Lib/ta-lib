      return new OutRange(outBegIdx, outNBElement);
   }
   /// <summary>
   /// The rolling Sharpe ratio: the mean return in excess of a risk-free rate,
   /// divided by the standard deviation of that excess return, over a trailing
   /// window. A drift-over-volatility measure of the series itself, scaled to a
   /// year. Above 0 the window's returns beat the risk-free rate on average; the
   /// larger the value, the more return per unit of volatility.
   /// </summary>
   /// <remarks>
   /// <para>
   /// Formula and more info at
   /// <see href="https://ta-lib.org/functions/sharpe">ta-lib.org/functions/sharpe</see>.
   /// </para>
   /// <list type="bullet">
   /// <item><description>This is Sharpe's 1994 <i>ex post</i> ratio with a constant benchmark, over simple returns and the sample (<c>n−1</c>) standard deviation.</description></item>
   /// <item><description>A window whose returns are all equal has no spread: the result is +Inf or -Inf by the sign of the mean excess return, and NaN when that mean is exactly 0. With an annualization of 0 it is NaN there and 0 elsewhere.</description></item>
   /// <item><description>The risk-free rate is per bar, in the same unit as the returns. For an annual rate <c>R</c>, pass <c>(1+R)^(1/A) − 1</c>, where <c>A</c> is the annualization; it is not de-annualized for you.</description></item>
   /// <item><description>An annualization of 1 gives the raw per-bar ratio.</description></item>
   /// <item><description>A zero price leaves no return to measure from it: the return of the bar after it counts as 0.</description></item>
   /// </list>
   /// <para>
   /// This is the <c>float[]</c> overload: input elements are widened to
   /// <c>double</c> as they are read and all arithmetic is performed in
   /// <c>double</c>, so a result beyond <c>float</c> range is still
   /// representable.
   /// </para>
   /// <para>
   /// Values are written only where the indicator is defined. The returned
   /// <see cref="OutRange"/> says where they start and how many there are, and
   /// the library never pads with NaN. A valid range that ends before
   /// <c>SharpeLookback</c> is a <b>success with no values</b> (<c>Count ==
   /// 0</c>), not an error.
   /// </para>
   /// <para>
   /// Every exception it throws, except the runtime's own
   /// <c>OutOfMemoryException</c>, implements <see cref="ITALibFailure"/>, which
   /// carries the <see cref="RetCode"/>.
   /// </para>
   /// </remarks>
   /// <param name="startIdx">First bar of the requested range (inclusive).</param>
   /// <param name="endIdx">Last bar of the requested range (inclusive).</param>
   /// <param name="inReal">The price series; its returns are computed internally.</param>
   /// <param name="optInTimePeriod">Number of returns in the window; one price more is read (default 20; range
   /// 2..100000; <c>int.MinValue</c> selects the default).</param>
   /// <param name="optInRiskFreeRate">Risk-free return per bar, subtracted from each return (default 0;
   /// <see cref="Core.RealDefault"/> selects the default).</param>
   /// <param name="optInAnnualization">Bars per year; the per-bar ratio is multiplied by its square root (default
   /// 252; minimum 0; <see cref="Core.RealDefault"/> selects the default).</param>
   /// <param name="outReal">Annualized Sharpe ratio of the trailing window, or ±Inf or NaN where the
   /// window has no spread. Must hold at least <c>endIdx - max(startIdx,
   /// SharpeLookback(...)) + 1</c> values, and never be empty: an empty span is
   /// an absent output.</param>
   /// <returns>The range written: <c>BegIdx</c> is the first bar with a value,
   /// <c>Count</c> how many were written.</returns>
   /// <exception cref="System.ArgumentOutOfRangeException"><c>startIdx</c> or <c>endIdx</c> is negative or above
   /// <see cref="Core.IndexMax"/>, or <c>endIdx &lt; startIdx</c>.</exception>
   /// <exception cref="System.ArgumentException">
   /// One of the following, checked before anything is written, so a rejected
   /// call leaves every buffer untouched:
   /// <list type="bullet">
   /// <item><description>An optional parameter is outside its documented range.</description></item>
   /// <item><description>A span is too short for the range requested: any input this function
   /// <i>declares</i> that does not reach <c>endIdx</c>, or an output that
   /// cannot hold the values produced. Declared, not read: a few candlestick
   /// patterns take an OHLC series they never index, and it is required all the
   /// same. A null array arrives as an empty span, and an empty span is an
   /// absent argument: for an input or an output, it is rejected even when the
   /// call would produce nothing.</description></item>
   /// <item><description>Two outputs overlap or are one array
   /// (<see href="https://ta-lib.org/spec/errors/#rb6">rule rB6</see>), or an
   /// output overlaps an input. An output and a real input never share an
   /// element type in this overload, so the two can never be the same span:
   /// there is no in-place case to allow, and any overlap of their byte ranges
   /// is rejected.</description></item>
   /// </list>
   /// </exception>
   /// <seealso cref="Core.Stddev(int, int, ReadOnlySpan{double}, int, double, Span{double})"/>
   /// <seealso cref="Core.Var(int, int, ReadOnlySpan{double}, int, double, Span{double})"/>
   /// <seealso cref="Core.Beta(int, int, ReadOnlySpan{double}, ReadOnlySpan{double}, int, Span{double})"/>
   /// <seealso cref="Core.Rocp(int, int, ReadOnlySpan{double}, int, Span{double})"/>
   public OutRange Sharpe( int startIdx,
                           int endIdx,
                           ReadOnlySpan<float> inReal,
                           int optInTimePeriod,
                           double optInRiskFreeRate,
                           double optInAnnualization,
                           Span<double> outReal )
   {
      int guardStart = ClampedStart(startIdx, endIdx, SharpeLookback(optInTimePeriod, optInRiskFreeRate, optInAnnualization));
      int guardInLen = guardStart < 0 ? 0 : endIdx + 1;
      int guardOutLen = guardStart < 0 || guardStart > endIdx ? 0 : endIdx - guardStart + 1;
      RequireLength("SHARPE", "inReal", inReal.Length, guardInLen);
      if( guardStart >= 0 ) RequirePresent("SHARPE", "outReal", outReal.Length);
      RequireLength("SHARPE", "outReal", outReal.Length, guardOutLen);
      RetCode retCode = SharpeImpl(startIdx, endIdx, inReal, optInTimePeriod, optInRiskFreeRate, optInAnnualization, out int outBegIdx, out int outNBElement, outReal);
      if( retCode != RetCode.Success ) {
         throw Failure("SHARPE", retCode);
      }
      return new OutRange(outBegIdx, outNBElement);
   }
   /**** Streaming API *****/

   /// <summary>A live <c>SHARPE</c> stream: one value per closed bar, bit-identical to
   /// <c>SHARPE</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.SharpeOpen"/>. There is no close and nothing to
   /// dispose — the handle is ordinary managed state, and an unreferenced handle
   /// is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class SharpeStream
   {
      internal Core core;
      internal int optInTimePeriod;
      internal double optInRiskFreeRate;
      internal double optInAnnualization;
      internal double shift;
      internal double periodTotal1;
      internal double periodTotal2;
      internal double peakTotal2;
      internal double prevPrice;
      internal double dPeriod;
      internal double invPeriod;
      internal double sqrtAnnual;
      internal int trailingIdx;
      internal int barsSinceReseed;
      internal int j;
      internal int windowStart;
      internal int i;
      internal int xMask;
      internal double[] x_inReal = [];
      internal double cur_outReal;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal SharpeStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Sharpe</c> reports over the same bars: the opener sets
      /// it to <c>(lookback, historyLen - lookback)</c>, every accepted
      /// <c>Update</c> adds one to the count — a rejected one changes nothing, and
      /// neither does <c>Peek</c> — and <c>Clone</c> carries it verbatim. A plain
      /// <c>Open</c> hands back only the last value, a subset of this range,
      /// because the caller chose not to take the fill.</para>
      /// <para>The last bar it can reach is <see cref="Core.IndexMax"/>; past that
      /// <c>Update</c> and <c>Advance</c> throw.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      /// <summary>Count one bar this stream was not fed: <see cref="OutRange"/> advances by
      /// one and nothing else moves.</summary>
      /// <remarks>
      /// <para><see cref="Value"/> keeps answering the previous output, which is this
      /// bar's output too. For a bar the caller leaves out: one an <c>Update</c>
      /// rejected and that will not be re-fed, or a session with no print. Without
      /// it two handles on one feed drift a bar apart when only one of them skips.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, the last one the batch tier
      /// can address and the last this handle will count. <c>Update</c> throws the
      /// same there.</para>
      /// </remarks>
      public void Advance()
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("SHARPE", "advance", RetCode.OutOfRangeEndIndex);
         outRangeCount++;
      }

      internal SharpeStream( SharpeStream other )
      {
         this.core = other.core;
         this.optInTimePeriod = other.optInTimePeriod;
         this.optInRiskFreeRate = other.optInRiskFreeRate;
         this.optInAnnualization = other.optInAnnualization;
         this.shift = other.shift;
         this.periodTotal1 = other.periodTotal1;
         this.periodTotal2 = other.periodTotal2;
         this.peakTotal2 = other.peakTotal2;
         this.prevPrice = other.prevPrice;
         this.dPeriod = other.dPeriod;
         this.invPeriod = other.invPeriod;
         this.sqrtAnnual = other.sqrtAnnual;
         this.trailingIdx = other.trailingIdx;
         this.barsSinceReseed = other.barsSinceReseed;
         this.j = other.j;
         this.windowStart = other.windowStart;
         this.i = other.i;
         this.xMask = other.xMask;
         this.x_inReal = new double[other.x_inReal.Length];
         Array.Copy( other.x_inReal, this.x_inReal, other.x_inReal.Length );
         this.cur_outReal = other.cur_outReal;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so nothing moves — <see cref="OutRange"/> included — and
      /// <see cref="Value"/> still answers the previous value. Re-feed the bar when
      /// a corrected value arrives, or call <see cref="Advance"/> to count it and
      /// carry on; two handles on one feed drift a bar apart if neither happens.
      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, which no re-feed clears: the
      /// handle has run out of index domain and only a shorter history can start a
      /// new one.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inReal )
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("SHARPE", "update", RetCode.OutOfRangeEndIndex);
         if( !double.IsFinite(inReal) ) throw Core.NonFiniteBar("SHARPE", "update", nameof(inReal));
         core.SharpeStepImpl(this, inReal);
         outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.IndexMax"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public double Peek( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.NonFiniteBar("SHARPE", "peek", nameof(inReal));
         SharpeStream sp = this;
         double price = 0.0;
         double trailingPrevPrice = 0.0;
         double windowPrevPrice = 0.0;
         double ret = 0.0;
         double dev = 0.0;
         double meanDev = 0.0;
         double moment2 = 0.0;
         double excess = 0.0;
         double ratio = 0.0;
         int barsSinceReseed = sp.barsSinceReseed;
         double cur_outReal = 0.0;
         int j = sp.j;
         double peakTotal2 = sp.peakTotal2;
         double periodTotal1 = sp.periodTotal1;
         double periodTotal2 = sp.periodTotal2;
         double prevPrice = sp.prevPrice;
         double shift = sp.shift;
         int trailingIdx = sp.trailingIdx;
         int windowStart = sp.windowStart;
         int pkSlot0 = -1;
         double pkVal0 = 0.0;
         pkSlot0 = sp.i & sp.xMask;
         pkVal0 = inReal;
         price = ((sp.i & sp.xMask) != pkSlot0) ? sp.x_inReal[sp.i & sp.xMask] : pkVal0;
         ret = 0.0;
         if( prevPrice != 0.0 ) {
            ret = (price - prevPrice) / prevPrice;
         }
         prevPrice = price;
         dev = ret - shift;
         periodTotal1 += dev;
         periodTotal2 += dev * dev;
         peakTotal2 = MaxGt(periodTotal2, peakTotal2);
         meanDev = periodTotal1 * sp.invPeriod;
         moment2 = periodTotal2 - meanDev * periodTotal1;
         /* inReal and outReal may be the same buffer, and the trailing prices
          * sit in slots the output reaches: every read of the window happens
          * before this bar's write. The oldest price read is the trailing
          * return's base, so the index stays on it.
          */
         trailingPrevPrice = ((trailingIdx & sp.xMask) != pkSlot0) ? sp.x_inReal[trailingIdx & sp.xMask] : pkVal0;
         trailingIdx += 1;
         price = ((trailingIdx & sp.xMask) != pkSlot0) ? sp.x_inReal[trailingIdx & sp.xMask] : pkVal0;
         ret = 0.0;
         if( trailingPrevPrice != 0.0 ) {
            ret = (price - trailingPrevPrice) / trailingPrevPrice;
         }
         dev = ret - shift;
         periodTotal1 -= dev;
         periodTotal2 -= dev * dev;
         /* Rebuild against the window mean when the spread has shrunk below 1% of
          * the largest sum of squares held since the last rebuild, or at least
          * every 32 windows. The rounding the running sums carry scales with that
          * peak, so once a large return leaves, the current sum can be all
          * rounding; a flat run after a move must still come out exactly flat.
          * The spread is a divisor, so its relative error reaches the ratio.
          */
         barsSinceReseed -= 1;
         if( moment2 < 0.01 * peakTotal2 || barsSinceReseed <= 0 ) {
            barsSinceReseed = 32 * sp.optInTimePeriod;
            windowStart = sp.i - sp.optInTimePeriod + 1;
            windowPrevPrice = (((windowStart - 1) & sp.xMask) != pkSlot0) ? sp.x_inReal[(windowStart - 1) & sp.xMask] : pkVal0;
            dev = 0.0;
            for( j = windowStart; j <= sp.i; j += 1 ) {
               price = ((j & sp.xMask) != pkSlot0) ? sp.x_inReal[j & sp.xMask] : pkVal0;
               ret = 0.0;
               if( windowPrevPrice != 0.0 ) {
                  ret = (price - windowPrevPrice) / windowPrevPrice;
               }
               windowPrevPrice = price;
               dev += ret;
            }
            shift = dev * sp.invPeriod;
            windowPrevPrice = (((windowStart - 1) & sp.xMask) != pkSlot0) ? sp.x_inReal[(windowStart - 1) & sp.xMask] : pkVal0;
            periodTotal1 = 0.0;
            periodTotal2 = 0.0;
            for( j = windowStart; j <= sp.i; j += 1 ) {
               price = ((j & sp.xMask) != pkSlot0) ? sp.x_inReal[j & sp.xMask] : pkVal0;
               ret = 0.0;
               if( windowPrevPrice != 0.0 ) {
                  ret = (price - windowPrevPrice) / windowPrevPrice;
               }
               windowPrevPrice = price;
               dev = ret - shift;
               periodTotal1 += dev;
               periodTotal2 += dev * dev;
            }
            meanDev = periodTotal1 * sp.invPeriod;
            moment2 = periodTotal2 - meanDev * periodTotal1;
            /* A window of equal returns can sit off this mean by rounding, which
             * leaves a spread of rounding where the ratio must be the plain
             * quotient, and fires the trigger again on every bar. Anchored on
             * one of its own returns, its deviations are exactly zero.
             */
            if( moment2 < 0.000001 * periodTotal2 ) {
               shift = ret;
               windowPrevPrice = (((windowStart - 1) & sp.xMask) != pkSlot0) ? sp.x_inReal[(windowStart - 1) & sp.xMask] : pkVal0;
               periodTotal1 = 0.0;
               periodTotal2 = 0.0;
               for( j = windowStart; j <= sp.i; j += 1 ) {
                  price = ((j & sp.xMask) != pkSlot0) ? sp.x_inReal[j & sp.xMask] : pkVal0;
                  ret = 0.0;
                  if( windowPrevPrice != 0.0 ) {
                     ret = (price - windowPrevPrice) / windowPrevPrice;
                  }
                  windowPrevPrice = price;
                  dev = ret - shift;
                  periodTotal1 += dev;
                  periodTotal2 += dev * dev;
               }
               meanDev = periodTotal1 * sp.invPeriod;
               moment2 = periodTotal2 - meanDev * periodTotal1;
            }
            peakTotal2 = periodTotal2;
            /* Re-remove the trailing return under the new shift so the carried
             * state matches the path without a rebuild.
             */
            price = ((windowStart & sp.xMask) != pkSlot0) ? sp.x_inReal[windowStart & sp.xMask] : pkVal0;
            ret = 0.0;
            if( ((((windowStart - 1) & sp.xMask) != pkSlot0) ? sp.x_inReal[(windowStart - 1) & sp.xMask] : pkVal0) != 0.0 ) {
               ret = (price - ((((windowStart - 1) & sp.xMask) != pkSlot0) ? sp.x_inReal[(windowStart - 1) & sp.xMask] : pkVal0)) / ((((windowStart - 1) & sp.xMask) != pkSlot0) ? sp.x_inReal[(windowStart - 1) & sp.xMask] : pkVal0);
            }
            dev = ret - shift;
            periodTotal1 -= dev;
            periodTotal2 -= dev * dev;
         }
         /* No spread is the plain quotient: +/-Inf by the sign of the excess
          * mean, NaN when it is exactly zero (ruled on #571). Annualize the
          * per-bar ratio last, so an annualization of 1 is that ratio bit for
          * bit.
          */
         excess = shift + meanDev - sp.optInRiskFreeRate;
         ratio = excess / Math.Sqrt(moment2 / (sp.dPeriod - 1.0));
         cur_outReal = sp.sqrtAnnual * ratio;
         return cur_outReal;
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public SharpeStream Clone()
      {
         return new SharpeStream(this);
      }
   }

   private void SharpeStepImpl( SharpeStream sp, double inReal )
   {
      double price = 0.0;
      double trailingPrevPrice = 0.0;
      double windowPrevPrice = 0.0;
      double ret = 0.0;
      double dev = 0.0;
      double meanDev = 0.0;
      double moment2 = 0.0;
      double excess = 0.0;
      double ratio = 0.0;
      sp.x_inReal[sp.i & sp.xMask] = inReal;
      price = sp.x_inReal[sp.i & sp.xMask];
      ret = 0.0;
      if( sp.prevPrice != 0.0 ) {
         ret = (price - sp.prevPrice) / sp.prevPrice;
      }
      sp.prevPrice = price;
      dev = ret - sp.shift;
      sp.periodTotal1 += dev;
      sp.periodTotal2 += dev * dev;
      sp.peakTotal2 = MaxGt(sp.periodTotal2, sp.peakTotal2);
      meanDev = sp.periodTotal1 * sp.invPeriod;
      moment2 = sp.periodTotal2 - meanDev * sp.periodTotal1;
      /* inReal and outReal may be the same buffer, and the trailing prices
       * sit in slots the output reaches: every read of the window happens
       * before this bar's write. The oldest price read is the trailing
       * return's base, so the index stays on it.
       */
      trailingPrevPrice = sp.x_inReal[sp.trailingIdx & sp.xMask];
      sp.trailingIdx += 1;
      price = sp.x_inReal[sp.trailingIdx & sp.xMask];
      ret = 0.0;
      if( trailingPrevPrice != 0.0 ) {
         ret = (price - trailingPrevPrice) / trailingPrevPrice;
      }
      dev = ret - sp.shift;
      sp.periodTotal1 -= dev;
      sp.periodTotal2 -= dev * dev;
      /* Rebuild against the window mean when the spread has shrunk below 1% of
       * the largest sum of squares held since the last rebuild, or at least
       * every 32 windows. The rounding the running sums carry scales with that
       * peak, so once a large return leaves, the current sum can be all
       * rounding; a flat run after a move must still come out exactly flat.
       * The spread is a divisor, so its relative error reaches the ratio.
       */
      sp.barsSinceReseed -= 1;
      if( moment2 < 0.01 * sp.peakTotal2 || sp.barsSinceReseed <= 0 ) {
         sp.barsSinceReseed = 32 * sp.optInTimePeriod;
         sp.windowStart = sp.i - sp.optInTimePeriod + 1;
         windowPrevPrice = sp.x_inReal[(sp.windowStart - 1) & sp.xMask];
         dev = 0.0;
         for( sp.j = sp.windowStart; sp.j <= sp.i; sp.j += 1 ) {
            price = sp.x_inReal[sp.j & sp.xMask];
            ret = 0.0;
            if( windowPrevPrice != 0.0 ) {
               ret = (price - windowPrevPrice) / windowPrevPrice;
            }
            windowPrevPrice = price;
            dev += ret;
         }
         sp.shift = dev * sp.invPeriod;
         windowPrevPrice = sp.x_inReal[(sp.windowStart - 1) & sp.xMask];
         sp.periodTotal1 = 0.0;
         sp.periodTotal2 = 0.0;
         for( sp.j = sp.windowStart; sp.j <= sp.i; sp.j += 1 ) {
            price = sp.x_inReal[sp.j & sp.xMask];
            ret = 0.0;
            if( windowPrevPrice != 0.0 ) {
               ret = (price - windowPrevPrice) / windowPrevPrice;
            }
            windowPrevPrice = price;
            dev = ret - sp.shift;
            sp.periodTotal1 += dev;
            sp.periodTotal2 += dev * dev;
         }
         meanDev = sp.periodTotal1 * sp.invPeriod;
         moment2 = sp.periodTotal2 - meanDev * sp.periodTotal1;
         /* A window of equal returns can sit off this mean by rounding, which
          * leaves a spread of rounding where the ratio must be the plain
          * quotient, and fires the trigger again on every bar. Anchored on
          * one of its own returns, its deviations are exactly zero.
          */
         if( moment2 < 0.000001 * sp.periodTotal2 ) {
            sp.shift = ret;
            windowPrevPrice = sp.x_inReal[(sp.windowStart - 1) & sp.xMask];
            sp.periodTotal1 = 0.0;
            sp.periodTotal2 = 0.0;
            for( sp.j = sp.windowStart; sp.j <= sp.i; sp.j += 1 ) {
               price = sp.x_inReal[sp.j & sp.xMask];
               ret = 0.0;
               if( windowPrevPrice != 0.0 ) {
                  ret = (price - windowPrevPrice) / windowPrevPrice;
               }
               windowPrevPrice = price;
               dev = ret - sp.shift;
               sp.periodTotal1 += dev;
               sp.periodTotal2 += dev * dev;
            }
            meanDev = sp.periodTotal1 * sp.invPeriod;
            moment2 = sp.periodTotal2 - meanDev * sp.periodTotal1;
         }
         sp.peakTotal2 = sp.periodTotal2;
         /* Re-remove the trailing return under the new shift so the carried
          * state matches the path without a rebuild.
          */
         price = sp.x_inReal[sp.windowStart & sp.xMask];
         ret = 0.0;
         if( sp.x_inReal[(sp.windowStart - 1) & sp.xMask] != 0.0 ) {
            ret = (price - sp.x_inReal[(sp.windowStart - 1) & sp.xMask]) / sp.x_inReal[(sp.windowStart - 1) & sp.xMask];
         }
         dev = ret - sp.shift;
         sp.periodTotal1 -= dev;
         sp.periodTotal2 -= dev * dev;
      }
      /* No spread is the plain quotient: +/-Inf by the sign of the excess
       * mean, NaN when it is exactly zero (ruled on #571). Annualize the
       * per-bar ratio last, so an annualization of 1 is that ratio bit for
       * bit.
       */
      excess = sp.shift + meanDev - sp.optInRiskFreeRate;
      ratio = excess / Math.Sqrt(moment2 / (sp.dPeriod - 1.0));
      sp.cur_outReal = sp.sqrtAnnual * ratio;
      sp.i += 1;
   }

   private RetCode SharpeOpenImpl( SharpeStream sp, ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, double optInRiskFreeRate, double optInAnnualization, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double shift = 0;
      double periodTotal1 = 0;
      double periodTotal2 = 0;
      double peakTotal2 = 0;
      double price = 0;
      double prevPrice = 0;
      double trailingPrevPrice = 0;
      double windowPrevPrice = 0;
      double ret = 0;
      double dev = 0;
      double dPeriod = 0;
      double invPeriod = 0;
      double meanDev = 0;
      double moment2 = 0;
      double excess = 0;
      double sqrtAnnual = 0;
      double ratio = 0;
      int i = 0;
      int j = 0;
      int outIdx = 0;
      int trailingIdx = 0;
      int windowStart = 0;
      int barsSinceReseed = 0;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen > IndexMax + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 20;
      } else if( optInTimePeriod < 2 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInRiskFreeRate == RealDefault ) {
         optInRiskFreeRate = 0e0;
      } else if( !(optInRiskFreeRate >= RealMin && optInRiskFreeRate <= RealMax) ) {
         return RetCode.BadParam;
      }
      if( optInAnnualization == RealDefault ) {
         optInAnnualization = 2.52e2;
      } else if( !(optInAnnualization >= 0e0 && optInAnnualization <= RealMax) ) {
         return RetCode.BadParam;
      }
      if( startIdx >= historyLen ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      if( startIdx < optInTimePeriod ) {
         startIdx = optInTimePeriod;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      dPeriod = (double)optInTimePeriod;
      invPeriod = 1.0 / dPeriod;
      sqrtAnnual = Math.Sqrt(optInAnnualization);
      /* The window holds the returns of the bars after trailingIdx up to i; a
       * bar's return reads the price before it.
       *
       * The variance of the excess returns is the variance of the returns, so
       * the risk-free rate enters only the mean. That keeps the sums at return
       * scale whatever the rate, and lets a flat price window reach an exact
       * zero spread.
       */
      trailingIdx = startIdx - optInTimePeriod;
      prevPrice = inReal[trailingIdx];
      /* A return needs a non-zero base price and nothing more: the test is
       * exact, never a band, since a price carries the quote unit. A zero base
       * gives a zero return.
       */
      price = inReal[trailingIdx + 1];
      ret = 0.0;
      if( prevPrice != 0.0 ) {
         ret = (price - prevPrice) / prevPrice;
      }
      shift = ret;
      periodTotal1 = 0.0;
      periodTotal2 = 0.0;
      for( j = trailingIdx + 1; j < startIdx; j += 1 ) {
         price = inReal[j];
         ret = 0.0;
         if( prevPrice != 0.0 ) {
            ret = (price - prevPrice) / prevPrice;
         }
         prevPrice = price;
         dev = ret - shift;
         periodTotal1 += dev;
         periodTotal2 += dev * dev;
      }
      i = startIdx;
      outIdx = 0;
      barsSinceReseed = 32 * optInTimePeriod;
      peakTotal2 = periodTotal2;
      do {
         price = inReal[i];
         ret = 0.0;
         if( prevPrice != 0.0 ) {
            ret = (price - prevPrice) / prevPrice;
         }
         prevPrice = price;
         dev = ret - shift;
         periodTotal1 += dev;
         periodTotal2 += dev * dev;
         peakTotal2 = MaxGt(periodTotal2, peakTotal2);
         meanDev = periodTotal1 * invPeriod;
         moment2 = periodTotal2 - meanDev * periodTotal1;
         /* inReal and outReal may be the same buffer, and the trailing prices
          * sit in slots the output reaches: every read of the window happens
          * before this bar's write. The oldest price read is the trailing
          * return's base, so the index stays on it.
          */
         trailingPrevPrice = inReal[trailingIdx];
         trailingIdx += 1;
         price = inReal[trailingIdx];
         ret = 0.0;
         if( trailingPrevPrice != 0.0 ) {
            ret = (price - trailingPrevPrice) / trailingPrevPrice;
         }
         dev = ret - shift;
         periodTotal1 -= dev;
         periodTotal2 -= dev * dev;
         /* Rebuild against the window mean when the spread has shrunk below 1% of
          * the largest sum of squares held since the last rebuild, or at least
          * every 32 windows. The rounding the running sums carry scales with that
          * peak, so once a large return leaves, the current sum can be all
          * rounding; a flat run after a move must still come out exactly flat.
          * The spread is a divisor, so its relative error reaches the ratio.
          */
         barsSinceReseed -= 1;
         if( moment2 < 0.01 * peakTotal2 || barsSinceReseed <= 0 ) {
            barsSinceReseed = 32 * optInTimePeriod;
            windowStart = i - optInTimePeriod + 1;
            windowPrevPrice = inReal[windowStart - 1];
            dev = 0.0;
            for( j = windowStart; j <= i; j += 1 ) {
               price = inReal[j];
               ret = 0.0;
               if( windowPrevPrice != 0.0 ) {
                  ret = (price - windowPrevPrice) / windowPrevPrice;
               }
               windowPrevPrice = price;
               dev += ret;
            }
            shift = dev * invPeriod;
            windowPrevPrice = inReal[windowStart - 1];
            periodTotal1 = 0.0;
            periodTotal2 = 0.0;
            for( j = windowStart; j <= i; j += 1 ) {
               price = inReal[j];
               ret = 0.0;
               if( windowPrevPrice != 0.0 ) {
                  ret = (price - windowPrevPrice) / windowPrevPrice;
               }
               windowPrevPrice = price;
               dev = ret - shift;
               periodTotal1 += dev;
               periodTotal2 += dev * dev;
            }
            meanDev = periodTotal1 * invPeriod;
            moment2 = periodTotal2 - meanDev * periodTotal1;
            /* A window of equal returns can sit off this mean by rounding, which
             * leaves a spread of rounding where the ratio must be the plain
             * quotient, and fires the trigger again on every bar. Anchored on
             * one of its own returns, its deviations are exactly zero.
             */
            if( moment2 < 0.000001 * periodTotal2 ) {
               shift = ret;
               windowPrevPrice = inReal[windowStart - 1];
               periodTotal1 = 0.0;
               periodTotal2 = 0.0;
               for( j = windowStart; j <= i; j += 1 ) {
                  price = inReal[j];
                  ret = 0.0;
                  if( windowPrevPrice != 0.0 ) {
                     ret = (price - windowPrevPrice) / windowPrevPrice;
                  }
                  windowPrevPrice = price;
                  dev = ret - shift;
                  periodTotal1 += dev;
                  periodTotal2 += dev * dev;
               }
               meanDev = periodTotal1 * invPeriod;
               moment2 = periodTotal2 - meanDev * periodTotal1;
            }
            peakTotal2 = periodTotal2;
            /* Re-remove the trailing return under the new shift so the carried
             * state matches the path without a rebuild.
             */
            price = inReal[windowStart];
            ret = 0.0;
            if( inReal[windowStart - 1] != 0.0 ) {
               ret = (price - inReal[windowStart - 1]) / inReal[windowStart - 1];
            }
            dev = ret - shift;
            periodTotal1 -= dev;
            periodTotal2 -= dev * dev;
         }
         /* No spread is the plain quotient: +/-Inf by the sign of the excess
          * mean, NaN when it is exactly zero (ruled on #571). Annualize the
          * per-bar ratio last, so an annualization of 1 is that ratio bit for
          * bit.
          */
         excess = shift + meanDev - optInRiskFreeRate;
         ratio = excess / Math.Sqrt(moment2 / (dPeriod - 1.0));
         outReal[outIdx++ * outStride] = sqrtAnnual * ratio;
         i += 1;
      } while( i <= endIdx );
      outNBElement = outIdx;
      outBegIdx = startIdx;
      /* Capture the live batch state into the handle. */
      int capX = i - trailingIdx + 1;
      if( capX < 1 || capX > historyLen ) {
         return RetCode.InternalError;
      }
      int physX = 1;
      while( physX < capX ) {
         physX <<= 1;
      }
      double[] capX_inReal = new double[physX];
      for( int fillJ = historyLen - capX; fillJ < historyLen; fillJ++ ) {
         capX_inReal[fillJ & (physX - 1)] = inReal[fillJ];
      }
      sp.optInTimePeriod = optInTimePeriod;
      sp.optInRiskFreeRate = optInRiskFreeRate;
      sp.optInAnnualization = optInAnnualization;
      sp.shift = shift;
      sp.periodTotal1 = periodTotal1;
      sp.periodTotal2 = periodTotal2;
      sp.peakTotal2 = peakTotal2;
      sp.prevPrice = prevPrice;
      sp.dPeriod = dPeriod;
      sp.invPeriod = invPeriod;
      sp.sqrtAnnual = sqrtAnnual;
      sp.trailingIdx = trailingIdx;
      sp.barsSinceReseed = barsSinceReseed;
      sp.j = j;
      sp.windowStart = windowStart;
      sp.i = i;
      sp.xMask = physX - 1;
      sp.x_inReal = capX_inReal;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* SharpeOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal SharpeStream SharpeOpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, double optInRiskFreeRate, double optInAnnualization, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      SharpeStream sp = new SharpeStream(this);
      RetCode retCode = SharpeOpenImpl(sp, inReal, startIdx, optInTimePeriod, optInRiskFreeRate, optInAnnualization, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("SHARPE", "openAndFill", nameof(inReal), inReal.Length, startIdx, SharpeLookback(optInTimePeriod, optInRiskFreeRate, optInAnnualization));
      }
      throw StreamFailure("SHARPE", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind SharpeOpen (composition seam). */
   internal SharpeStream SharpeOpenInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, double optInRiskFreeRate, double optInAnnualization )
   {
      SharpeStream sp = new SharpeStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = SharpeOpenImpl(sp, inReal, startIdx, optInTimePeriod, optInRiskFreeRate, optInAnnualization, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("SHARPE", "open", nameof(inReal), inReal.Length, startIdx, SharpeLookback(optInTimePeriod, optInRiskFreeRate, optInAnnualization));
      }
      throw StreamFailure("SHARPE", "open", retCode);
   }

   /// <summary>Open a live <c>SHARPE</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="SharpeStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>SHARPE</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>SharpeLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>SharpeOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">The price series; its returns are computed internally. The warm-up
   /// history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="SharpeLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInRiskFreeRate">As in the batch call; see <see cref="SharpeLookback"/> for its default and
   /// range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <param name="optInAnnualization">As in the batch call; see <see cref="SharpeLookback"/> for its default and
   /// range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>SharpeLookback(...) + 1</c> bars, an empty
   /// one included — which is what a null array becomes, since a span cannot be
   /// null.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is longer than <see cref="Core.IndexMax"/> + 1, the one index
   /// fault an opener can have (rule rS2).</exception>
   public SharpeStream SharpeOpen( ReadOnlySpan<double> inReal, int optInTimePeriod, double optInRiskFreeRate, double optInAnnualization )
   {
      if( inReal.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "SHARPE open: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      return SharpeOpenInternal(inReal, 0, optInTimePeriod, optInRiskFreeRate, optInAnnualization);
   }

   /// <summary><c>SharpeOpen</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>SHARPE</c> produces over
   /// the same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - SharpeLookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="SharpeStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">The price series; its returns are computed internally. The warm-up
   /// history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="SharpeLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInRiskFreeRate">As in the batch call; see <see cref="SharpeLookback"/> for its default and
   /// range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <param name="optInAnnualization">As in the batch call; see <see cref="SharpeLookback"/> for its default and
   /// range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <param name="outReal">Annualized Sharpe ratio of the trailing window, or ±Inf or NaN where the
   /// window has no spread. Must hold at least <c>historyLen -
   /// SharpeLookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>SharpeLookback(...) + 1</c> bars, an empty
   /// one included — which is what a null array becomes, since a span cannot be
   /// null.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is longer than <see cref="Core.IndexMax"/> + 1, the one index
   /// fault an opener can have (rule rS2).</exception>
   public SharpeStream SharpeOpenAndFill( ReadOnlySpan<double> inReal, int optInTimePeriod, double optInRiskFreeRate, double optInAnnualization, Span<double> outReal )
   {
      if( inReal.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "SHARPE openAndFill: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      int guardOutLen = OpenFillCount("SHARPE", "openAndFill", inReal.Length, SharpeLookback(optInTimePeriod, optInRiskFreeRate, optInAnnualization));
      RequireFillLength("SHARPE", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( SameBuffer(outReal, inReal) ) {
         throw StreamFailure("SHARPE", "openAndFill", RetCode.BadParam);
      }
      if( guardOutLen > 0 && ( outReal.Overlaps(inReal) ) ) {
         throw StreamFailure("SHARPE", "openAndFill", RetCode.BadParam);
      }
      return SharpeOpenAndFillInternal(inReal, 0, optInTimePeriod, optInRiskFreeRate, optInAnnualization, out _, out _, outReal);
   }
