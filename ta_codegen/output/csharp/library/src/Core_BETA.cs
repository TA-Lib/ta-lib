         Array.Copy( other.x_inReal0, this.x_inReal0, other.x_inReal0.Length );
         this.x_inReal1 = new double[other.x_inReal1.Length];
         Array.Copy( other.x_inReal1, this.x_inReal1, other.x_inReal1.Length );
