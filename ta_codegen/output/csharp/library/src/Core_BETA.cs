               if( prev_y != 0.0 ) {
                  y = ((double)inReal1[j] - prev_y) / prev_y - shift_y;
               } else {
                  y = 0 - shift_y;
               }
               prev_y = (double)inReal1[j];
               S_xx += x * x;
               S_yy += y * y;
               S_xy += x * y;
               S_x += x;
               S_y += y;
            }
            denom_scale = n * S_xx;
            denom = denom_scale - S_x * S_x;
            if( denom < 0.0 ) {
               denom = 0.0;
            }
         }
         tmp_real = (double)inReal0[trailingIdx];
         if( trailing_last_price_x != 0.0 ) {
            x = (tmp_real - trailing_last_price_x) / trailing_last_price_x - shift_x;
         } else {
            x = 0 - shift_x;
         }
         trailing_last_price_x = tmp_real;
         tmp_real = (double)inReal1[trailingIdx];
         trailingIdx += 1;
         if( trailing_last_price_y != 0.0 ) {
            y = (tmp_real - trailing_last_price_y) / trailing_last_price_y - shift_y;
         } else {
            y = 0 - shift_y;
         }
         trailing_last_price_y = tmp_real;
         if( denom > 0.00000000000001 * denom_scale ) {
            outReal[outIdx++] = (n * S_xy - S_x * S_y) / denom;
         } else {
            outReal[outIdx++] = 0.0;
         }
         leaving_xx = x * x;
         leaving_yy = y * y;
         S_xx -= x * x;
         S_yy -= y * y;
         S_xy -= x * y;
         S_x -= x;
         S_y -= y;
      } while( i <= endIdx );
      outNBElement = outIdx;
      outBegIdx = startIdx;
      return RetCode.Success ;
   }
   /// <summary>
   /// Beta: the slope of a least-squares linear regression of one series'
   /// percentage returns (y, from inReal1) against another's (x, from inReal0)
   /// over a rolling window. Measures how much a security moves relative to a
   /// market index. Beta = 1 moves with the index; &lt; 1 less volatile, &gt; 1
   /// more volatile.
   /// </summary>
   /// <remarks>
   /// <b>Formula</b>
   /// <code>
   /// Per-bar returns: $x_i=(p^0_i-p^0_{i-1})/p^0_{i-1}$ from inReal0, $y_i=(p^1_i-p^1_{i-1})/p^1_{i-1}$ from inReal1. With $n$=period over the window: $\beta = \dfrac{n\,S_{xy}-S_x S_y}{n\,S_{xx}-S_x^2}$, where $S_{xx}=\sum x^2,\ S_{xy}=\sum xy,\ S_x=\sum x,\ S_y=\sum y$.
   /// </code>
   /// <para>
   /// Values are written only where the indicator is defined. The returned
   /// <see cref="OutRange"/> says where they start and how many there are;
   /// nothing outside that range is touched, and the library never pads with
   /// NaN. A valid range shorter than <c>BETA_Lookback</c> is a <b>success with
   /// no values</b> (<c>Count == 0</c>), not an error.
   /// </para>
   /// </remarks>
   /// <param name="startIdx">First bar of the requested range (inclusive).</param>
   /// <param name="endIdx">Last bar of the requested range (inclusive).</param>
   /// <param name="inReal0">Series whose returns are the regression x (market/index)</param>
   /// <param name="inReal1">Series whose returns are the regression y (security)</param>
   /// <param name="optInTimePeriod">Rolling window length (number of returns) for the regression sums (default
   /// 5; range 1..100000; <c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Beta: regression slope of inReal1-returns on inReal0-returns. Must hold at
   /// least <c>endIdx - startIdx + 1</c> values.</param>
   /// <returns>The range written: <c>BegIdx</c> is the first bar with a value,
   /// <c>Count</c> how many were written.</returns>
   /// <exception cref="System.ArgumentOutOfRangeException"><c>startIdx</c> or <c>endIdx</c> is negative or above
   /// <see cref="Core.MAX_INDEX"/>, or <c>endIdx &lt; startIdx</c>.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or two outputs
   /// share one array.</exception>
   /// <exception cref="System.ArgumentException">A span is too short for the range requested: any input this function
   /// <i>declares</i> that does not reach <c>endIdx</c>, or an output that
   /// cannot hold the values produced. Checked before anything is written, so a
   /// rejected call leaves every buffer untouched. Declared, not read: a few
   /// candlestick patterns take an OHLC series they never index, and it is
   /// required all the same. An empty span — which is what a null array becomes,
   /// since a span cannot be null — is rejected on the same terms and no others:
   /// it is too short whenever the range produces a value, and fine when it
   /// produces none, and on an output this function documents as declinable it
   /// is how you decline.</exception>
   /// <exception cref="System.ArgumentException">Two output buffers overlap, or an output partially overlaps an input.
   /// Computing wholly in place (an output that IS an input) is allowed.</exception>
   public OutRange BETA( int startIdx,
                         int endIdx,
                         ReadOnlySpan<double> inReal0,
                         ReadOnlySpan<double> inReal1,
                         int optInTimePeriod,
                         Span<double> outReal )
   {
      int guardStart = ClampedStart(startIdx, endIdx, BETA_Lookback(optInTimePeriod));
      int guardInLen = guardStart < 0 ? 0 : endIdx + 1;
      int guardOutLen = guardStart < 0 || guardStart > endIdx ? 0 : endIdx - guardStart + 1;
      RequireLength("BETA", "inReal0", inReal0.Length, guardInLen);
      RequireLength("BETA", "inReal1", inReal1.Length, guardInLen);
      RequireLength("BETA", "outReal", outReal.Length, guardOutLen);
      RetCode retCode = BETA_Impl(startIdx, endIdx, inReal0, inReal1, optInTimePeriod, out int outBegIdx, out int outNBElement, outReal);
      if( retCode != RetCode.Success ) {
         throw Failure("BETA", retCode);
      }
      return new OutRange(outBegIdx, outNBElement);
   }
