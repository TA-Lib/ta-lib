      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.IndexMax"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inOpen">This bar's open price.</param>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public double Peek( double inOpen, double inHigh, double inLow, double inClose )
      {
         if( !double.IsFinite(inOpen) || !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) ) throw Core.NonFiniteBar("ASI", "peek", !double.IsFinite(inOpen) ? nameof(inOpen) : !double.IsFinite(inHigh) ? nameof(inHigh) : !double.IsFinite(inLow) ? nameof(inLow) : nameof(inClose));
         AsiStream sp = this;
         double tempOpen = 0.0;
         double tempHigh = 0.0;
         double tempLow = 0.0;
         double tempClose = 0.0;
         double body = 0.0;
         double n = 0.0;
         double up = 0.0;
         double dn = 0.0;
         double rg = 0.0;
         double k = 0.0;
         double r = 0.0;
         double swing = 0.0;
         double cur_outReal = 0.0;
         double sum = sp.sum;
         tempOpen = inOpen;
         tempHigh = inHigh;
         tempLow = inLow;
         tempClose = inClose;
         body = tempClose - tempOpen;
         n = tempClose - sp.prevClose;
         n += 0.5 * body;
         n += 0.25 * sp.prevBody;
         up = Math.Abs(tempHigh - sp.prevClose);
         dn = Math.Abs(tempLow - sp.prevClose);
         rg = Math.Abs(tempHigh - tempLow);
         k = MaxGt(up, dn);
         r = MaxGt(up - 0.5 * dn, dn - 0.5 * up);
         r = MaxGt(r, rg);
         r += 0.25 * Math.Abs(sp.prevBody);
         if( r == 0.0 ) {
            swing = 0.0;
         } else {
            swing = 50.0 * (n / r) * (k / sp.optInLimitMove);
         }
         sum += swing;
         cur_outReal = sum;
         return cur_outReal;
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public AsiStream Clone()
      {
         return new AsiStream(this);
      }
   }

   private void AsiStepImpl( AsiStream sp, double inOpen, double inHigh, double inLow, double inClose )
   {
      double tempOpen = 0.0;
      double tempHigh = 0.0;
      double tempLow = 0.0;
      double tempClose = 0.0;
      double body = 0.0;
      double n = 0.0;
      double up = 0.0;
      double dn = 0.0;
      double rg = 0.0;
      double k = 0.0;
      double r = 0.0;
      double swing = 0.0;
      tempOpen = inOpen;
      tempHigh = inHigh;
      tempLow = inLow;
      tempClose = inClose;
      body = tempClose - tempOpen;
      n = tempClose - sp.prevClose;
      n += 0.5 * body;
      n += 0.25 * sp.prevBody;
      up = Math.Abs(tempHigh - sp.prevClose);
      dn = Math.Abs(tempLow - sp.prevClose);
      rg = Math.Abs(tempHigh - tempLow);
      k = MaxGt(up, dn);
      r = MaxGt(up - 0.5 * dn, dn - 0.5 * up);
      r = MaxGt(r, rg);
      r += 0.25 * Math.Abs(sp.prevBody);
      if( r == 0.0 ) {
         swing = 0.0;
      } else {
         swing = 50.0 * (n / r) * (k / sp.optInLimitMove);
      }
      sp.sum += swing;
      sp.cur_outReal = sp.sum;
      sp.prevClose = tempClose;
      sp.prevBody = body;
   }

   private RetCode AsiOpenImpl( AsiStream sp, ReadOnlySpan<double> inOpen, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, double optInLimitMove, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      int i = 0;
      int outIdx = 0;
      double prevClose = 0;
      double prevBody = 0;
      double tempOpen = 0;
      double tempHigh = 0;
      double tempLow = 0;
      double tempClose = 0;
      double body = 0;
      double n = 0;
      double up = 0;
      double dn = 0;
      double rg = 0;
      double k = 0;
      double r = 0;
      double swing = 0;
      double sum = 0;
      int historyLen = inOpen.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > IndexMax + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inHigh.Length != inOpen.Length || inLow.Length != inOpen.Length || inClose.Length != inOpen.Length ) {
         return RetCode.BadParam;
      }
      if( optInLimitMove == RealDefault ) {
         optInLimitMove = 3e0;
      } else if( !(optInLimitMove >= 1e-8 && optInLimitMove <= RealMax) ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      /* SI's per-bar statements, kept identical: the regression test holds this
       * function bit for bit to CUMSUM over SI. Bar startIdx is read before the
       * anchor store, which may overwrite it when outReal aliases an input.
       */
      prevClose = inClose[startIdx];
      prevBody = prevClose - inOpen[startIdx];
      sum = 0.0;
      outReal[0 * outStride] = sum;
      outIdx = 1;
      for( i = startIdx + 1; i <= endIdx; i += 1 ) {
         tempOpen = inOpen[i];
         tempHigh = inHigh[i];
         tempLow = inLow[i];
         tempClose = inClose[i];
         body = tempClose - tempOpen;
         n = tempClose - prevClose;
         n += 0.5 * body;
         n += 0.25 * prevBody;
         up = Math.Abs(tempHigh - prevClose);
         dn = Math.Abs(tempLow - prevClose);
         rg = Math.Abs(tempHigh - tempLow);
         k = MaxGt(up, dn);
         r = MaxGt(up - 0.5 * dn, dn - 0.5 * up);
         r = MaxGt(r, rg);
         r += 0.25 * Math.Abs(prevBody);
         if( r == 0.0 ) {
            swing = 0.0;
         } else {
            swing = 50.0 * (n / r) * (k / optInLimitMove);
         }
         sum += swing;
         outReal[outIdx * outStride] = sum;
         outIdx += 1;
         prevClose = tempClose;
         prevBody = body;
      }
      outBegIdx = startIdx;
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      sp.optInLimitMove = optInLimitMove;
      sp.prevClose = prevClose;
      sp.prevBody = prevBody;
      sp.sum = sum;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* AsiOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal AsiStream AsiOpenAndFillInternal( ReadOnlySpan<double> inOpen, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, double optInLimitMove, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      AsiStream sp = new AsiStream(this);
      RetCode retCode = AsiOpenImpl(sp, inOpen, inHigh, inLow, inClose, startIdx, optInLimitMove, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("ASI", "openAndFill", nameof(inOpen), inOpen.Length, startIdx, AsiLookback(optInLimitMove));
      }
      throw StreamFailure("ASI", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind AsiOpen (composition seam). */
   internal AsiStream AsiOpenInternal( ReadOnlySpan<double> inOpen, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, double optInLimitMove )
   {
      AsiStream sp = new AsiStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = AsiOpenImpl(sp, inOpen, inHigh, inLow, inClose, startIdx, optInLimitMove, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("ASI", "open", nameof(inOpen), inOpen.Length, startIdx, AsiLookback(optInLimitMove));
      }
      throw StreamFailure("ASI", "open", retCode);
   }

   /// <summary>Open a live <c>ASI</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="AsiStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>ASI</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>AsiLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>AsiOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inOpen">Open price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInLimitMove">As in the batch call; see <see cref="AsiLookback"/> for its default and
   /// range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>AsiLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules S1 and S2).</exception>
   public AsiStream AsiOpen( ReadOnlySpan<double> inOpen, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, double optInLimitMove )
   {
      if( inOpen.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inOpen), "ASI open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inOpen.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inOpen), "ASI open: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( inHigh.IsEmpty ) throw new TALibArgumentException("ASI open: inHigh is empty", nameof(inHigh), RetCode.BadParam);
      if( inLow.IsEmpty ) throw new TALibArgumentException("ASI open: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TALibArgumentException("ASI open: inClose is empty", nameof(inClose), RetCode.BadParam);
      RequireHistoryLength("ASI", "open", "inHigh", inHigh.Length, inOpen.Length);
      RequireHistoryLength("ASI", "open", "inLow", inLow.Length, inOpen.Length);
      RequireHistoryLength("ASI", "open", "inClose", inClose.Length, inOpen.Length);
      return AsiOpenInternal(inOpen, inHigh, inLow, inClose, 0, optInLimitMove);
   }

   /// <summary><c>AsiOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>ASI</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - AsiLookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="AsiStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inOpen">Open price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInLimitMove">As in the batch call; see <see cref="AsiLookback"/> for its default and
   /// range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <param name="outReal">Running total of the swing index from the first bar of the range. Must
   /// hold at least <c>historyLen - AsiLookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>AsiLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules S1 and S2).</exception>
   public AsiStream AsiOpenAndFill( ReadOnlySpan<double> inOpen, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, double optInLimitMove, Span<double> outReal )
   {
      if( inOpen.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inOpen), "ASI openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inOpen.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inOpen), "ASI openAndFill: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( inHigh.IsEmpty ) throw new TALibArgumentException("ASI openAndFill: inHigh is empty", nameof(inHigh), RetCode.BadParam);
      if( inLow.IsEmpty ) throw new TALibArgumentException("ASI openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TALibArgumentException("ASI openAndFill: inClose is empty", nameof(inClose), RetCode.BadParam);
      int guardOutLen = OpenFillCount("ASI", "openAndFill", inOpen.Length, AsiLookback(optInLimitMove));
      RequireHistoryLength("ASI", "openAndFill", "inHigh", inHigh.Length, inOpen.Length);
      RequireHistoryLength("ASI", "openAndFill", "inLow", inLow.Length, inOpen.Length);
      RequireHistoryLength("ASI", "openAndFill", "inClose", inClose.Length, inOpen.Length);
      RequireFillLength("ASI", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( outReal.Overlaps(inOpen) || outReal.Overlaps(inHigh) || outReal.Overlaps(inLow) || outReal.Overlaps(inClose) ) {
         throw StreamFailure("ASI", "openAndFill", RetCode.BadParam);
      }
      return AsiOpenAndFillInternal(inOpen, inHigh, inLow, inClose, 0, optInLimitMove, out _, out _, outReal);
   }
