   /// <summary>A live <c>VIDYA</c> stream: one value per closed bar, bit-identical to
   /// <c>VIDYA</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.VidyaOpen"/>. There is no close and nothing to
   /// dispose — the handle is ordinary managed state, and an unreferenced handle
   /// is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class VidyaStream
   {
      internal Core core;
      internal int optInTimePeriod;
      internal int optInCMOPeriod;
      internal int nullRun;
      internal double upSum;
      internal double downSum;
      internal double prevValue;
      internal double trailingValue;
      internal double alpha;
      internal double prevVIDYA;
      internal int ringPos_trailingIdx;
      internal int ringCap_trailingIdx;
      internal double[] ring_trailingIdx_inReal = [];
      internal double cur_outReal;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal VidyaStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Vidya</c> reports over the same bars: the opener sets
      /// it to <c>(lookback, historyLen - lookback)</c>, every accepted
      /// <c>Update</c> adds one to the count — a rejected one changes nothing, and
      /// neither does <c>Peek</c> — and <c>Clone</c> carries it verbatim. A plain
      /// <c>Open</c> hands back only the last value, a subset of this range,
      /// because the caller chose not to take the fill.</para>
      /// <para>The last bar it can reach is <see cref="Core.IndexMax"/>; past that
      /// <c>Update</c> and <c>Advance</c> throw.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      /// <summary>Count one bar this stream was not fed: <see cref="OutRange"/> advances by
      /// one and nothing else moves.</summary>
      /// <remarks>
      /// <para><see cref="Value"/> keeps answering the previous output, which is this
      /// bar's output too. For a bar the caller leaves out: one an <c>Update</c>
      /// rejected and that will not be re-fed, or a session with no print. Without
      /// it two handles on one feed drift a bar apart when only one of them skips.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, the last one the batch tier
      /// can address and the last this handle will count. <c>Update</c> throws the
      /// same there.</para>
      /// </remarks>
      public void Advance()
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("VIDYA", "advance", RetCode.OutOfRangeEndIndex);
         outRangeCount++;
      }

      internal VidyaStream( VidyaStream other )
      {
         this.core = other.core;
         this.optInTimePeriod = other.optInTimePeriod;
         this.optInCMOPeriod = other.optInCMOPeriod;
         this.nullRun = other.nullRun;
         this.upSum = other.upSum;
         this.downSum = other.downSum;
         this.prevValue = other.prevValue;
         this.trailingValue = other.trailingValue;
         this.alpha = other.alpha;
         this.prevVIDYA = other.prevVIDYA;
         this.ringPos_trailingIdx = other.ringPos_trailingIdx;
         this.ringCap_trailingIdx = other.ringCap_trailingIdx;
         this.ring_trailingIdx_inReal = new double[other.ring_trailingIdx_inReal.Length];
         Array.Copy( other.ring_trailingIdx_inReal, this.ring_trailingIdx_inReal, other.ring_trailingIdx_inReal.Length );
         this.cur_outReal = other.cur_outReal;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so nothing moves — <see cref="OutRange"/> included — and
      /// <see cref="Value"/> still answers the previous value. Re-feed the bar when
      /// a corrected value arrives, or call <see cref="Advance"/> to count it and
      /// carry on; two handles on one feed drift a bar apart if neither happens.
      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, which no re-feed clears: the
      /// handle has run out of index domain and only a shorter history can start a
      /// new one.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inReal )
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("VIDYA", "update", RetCode.OutOfRangeEndIndex);
         if( !double.IsFinite(inReal) ) throw Core.NonFiniteBar("VIDYA", "update", nameof(inReal));
         core.VidyaStepImpl(this, inReal);
         outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.IndexMax"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public double Peek( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.NonFiniteBar("VIDYA", "peek", nameof(inReal));
         VidyaStream sp = this;
         double sum = 0.0;
         double diff = 0.0;
         double tempReal = 0.0;
         double k = 0.0;
         double cur_outReal = 0.0;
         double downSum = sp.downSum;
         int nullRun = sp.nullRun;
         double prevVIDYA = sp.prevVIDYA;
         double prevValue = sp.prevValue;
         double trailingValue = sp.trailingValue;
         double upSum = sp.upSum;
         if( sp.optInTimePeriod == 1 ) {
            cur_outReal = inReal;
            return cur_outReal ;
         }
         tempReal = sp.ring_trailingIdx_inReal[sp.ringPos_trailingIdx];
         diff = tempReal - trailingValue;
         trailingValue = tempReal;
         if( diff > 0.0 ) {
            upSum -= diff;
         } else if( diff < 0.0 ) {
            downSum += diff;
         }
         tempReal = inReal;
         diff = tempReal - prevValue;
         prevValue = tempReal;
         if( diff > 0.0 ) {
            upSum += diff;
         } else if( diff < 0.0 ) {
            downSum -= diff;
         }
         if( diff == 0.0 ) {
            nullRun += 1;
         } else {
            nullRun = 0;
         }
         if( nullRun >= sp.optInCMOPeriod ) {
            nullRun = sp.optInCMOPeriod;
            upSum = 0.0;
            downSum = 0.0;
         }
         sum = upSum + downSum;
         if( sum > 0.0 ) {
            k = sp.alpha * (Math.Abs(100.0 * (upSum - downSum) / sum) / 100.0);
         } else {
            k = 0.0;
         }
         prevVIDYA = Math.FusedMultiplyAdd(prevValue - prevVIDYA, k, prevVIDYA);
         cur_outReal = prevVIDYA;
         return cur_outReal;
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public VidyaStream Clone()
      {
         return new VidyaStream(this);
      }
   }

   private void VidyaStepImpl( VidyaStream sp, double inReal )
   {
      double sum = 0.0;
      double diff = 0.0;
      double tempReal = 0.0;
      double k = 0.0;
      int ringCapL_trailingIdx = 0;
      if( sp.optInTimePeriod == 1 ) {
         sp.cur_outReal = inReal;
         return ;
      }
      tempReal = sp.ring_trailingIdx_inReal[sp.ringPos_trailingIdx];
      diff = tempReal - sp.trailingValue;
      sp.trailingValue = tempReal;
      if( diff > 0.0 ) {
         sp.upSum -= diff;
      } else if( diff < 0.0 ) {
         sp.downSum += diff;
      }
      tempReal = inReal;
      diff = tempReal - sp.prevValue;
      sp.prevValue = tempReal;
      if( diff > 0.0 ) {
         sp.upSum += diff;
      } else if( diff < 0.0 ) {
         sp.downSum -= diff;
      }
      if( diff == 0.0 ) {
         sp.nullRun += 1;
      } else {
         sp.nullRun = 0;
      }
      if( sp.nullRun >= sp.optInCMOPeriod ) {
         sp.nullRun = sp.optInCMOPeriod;
         sp.upSum = 0.0;
         sp.downSum = 0.0;
      }
      sum = sp.upSum + sp.downSum;
      if( sum > 0.0 ) {
         k = sp.alpha * (Math.Abs(100.0 * (sp.upSum - sp.downSum) / sum) / 100.0);
      } else {
         k = 0.0;
      }
      sp.prevVIDYA = Math.FusedMultiplyAdd(sp.prevValue - sp.prevVIDYA, k, sp.prevVIDYA);
      sp.cur_outReal = sp.prevVIDYA;
      ringCapL_trailingIdx = sp.ringCap_trailingIdx;
      sp.ring_trailingIdx_inReal[sp.ringPos_trailingIdx] = inReal;
      sp.ringPos_trailingIdx = sp.ringPos_trailingIdx + 1;
      if( sp.ringPos_trailingIdx >= ringCapL_trailingIdx ) {
         sp.ringPos_trailingIdx = 0;
      }
   }

   private RetCode VidyaOpenImpl( VidyaStream sp, ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, int optInCMOPeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      int outIdx = 0;
      int today = 0;
      int trailingIdx = 0;
      int lookbackTotal = 0;
      int i = 0;
      int nullRun = 0;
      double upSum = 0;
      double downSum = 0;
      double sum = 0;
      double diff = 0;
      double tempReal = 0;
      double prevValue = 0;
      double trailingValue = 0;
      double alpha = 0;
      double k = 0;
      double prevVIDYA = 0;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > IndexMax + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 12;
      } else if( optInTimePeriod < 1 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInCMOPeriod == int.MinValue ) {
         optInCMOPeriod = 9;
      } else if( optInCMOPeriod < 2 || optInCMOPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      if( optInTimePeriod == 1 ) {
         int fillLb = VidyaLookback(optInTimePeriod, optInCMOPeriod);
         if( startIdx > fillLb ) fillLb = startIdx;
         if( historyLen < fillLb + 1 ) {
            return RetCode.InsufficientHistory;
         }
         sp.optInTimePeriod = optInTimePeriod;
         sp.optInCMOPeriod = optInCMOPeriod;
         sp.nullRun = 0;
         sp.upSum = 0.0;
         sp.downSum = 0.0;
         sp.prevValue = 0.0;
         sp.trailingValue = 0.0;
         sp.alpha = 0.0;
         sp.prevVIDYA = 0.0;
         sp.ringPos_trailingIdx = 0;
         sp.ringCap_trailingIdx = 0;
         sp.ring_trailingIdx_inReal = new double[1];
         outBegIdx = fillLb;
         outNBElement = historyLen - fillLb;
         if( outStride == 0 ) {
            outReal[0] = inReal[historyLen - 1];
         } else {
            for( int fillIdx = 0; fillIdx < historyLen - fillLb; fillIdx++ ) {
               outReal[fillIdx] = inReal[fillLb + fillIdx];
            }
         }
         sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
         return RetCode.Success;
      }
      outBegIdx = 0;
      outNBElement = 0;
      lookbackTotal = VidyaLookback(optInTimePeriod, optInCMOPeriod);
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      if( startIdx > endIdx ) {
         return RetCode.InsufficientHistory ;
      }
      alpha = 2.0 / (double)(optInTimePeriod + 1);
      /* The CMO below is TA_CMOU's loop, spelling and nullRun reset included, so
       * that from the first full window on VIDYA equals the composite of TA_CMOU
       * bit for bit. The recursion is seeded on the window's first price and
       * steps through the warm-up with the CMO of the changes seen so far. The
       * unstable period enters it that many bars before startIdx.
       */
      today = startIdx - lookbackTotal;
      trailingIdx = today + 1;
      prevValue = inReal[today];
      trailingValue = prevValue;
      prevVIDYA = prevValue;
      upSum = 0.0;
      downSum = 0.0;
      nullRun = 0;
      for( i = 0; i < optInCMOPeriod; i += 1 ) {
         today += 1;
         tempReal = inReal[today];
         diff = tempReal - prevValue;
         prevValue = tempReal;
         if( diff > 0.0 ) {
            upSum += diff;
         } else if( diff < 0.0 ) {
            downSum -= diff;
         }
         if( diff == 0.0 ) {
            nullRun += 1;
         } else {
            nullRun = 0;
         }
         sum = upSum + downSum;
         if( sum > 0.0 ) {
            k = alpha * (Math.Abs(100.0 * (upSum - downSum) / sum) / 100.0);
         } else {
            k = 0.0;
         }
         prevVIDYA = Math.FusedMultiplyAdd(prevValue - prevVIDYA, k, prevVIDYA);
      }
      today += 1;
      /* Skip the unstable period: the whole computation, nothing written. */
      while( today <= startIdx ) {
         tempReal = inReal[trailingIdx];
         diff = tempReal - trailingValue;
         trailingValue = tempReal;
         trailingIdx += 1;
         if( diff > 0.0 ) {
            upSum -= diff;
         } else if( diff < 0.0 ) {
            downSum += diff;
         }
         tempReal = inReal[today];
         diff = tempReal - prevValue;
         prevValue = tempReal;
         if( diff > 0.0 ) {
            upSum += diff;
         } else if( diff < 0.0 ) {
            downSum -= diff;
         }
         if( diff == 0.0 ) {
            nullRun += 1;
         } else {
            nullRun = 0;
         }
         if( nullRun >= optInCMOPeriod ) {
            nullRun = optInCMOPeriod;
            upSum = 0.0;
            downSum = 0.0;
         }
         sum = upSum + downSum;
         if( sum > 0.0 ) {
            k = alpha * (Math.Abs(100.0 * (upSum - downSum) / sum) / 100.0);
         } else {
            k = 0.0;
         }
         prevVIDYA = Math.FusedMultiplyAdd(prevValue - prevVIDYA, k, prevVIDYA);
         today += 1;
      }
      outReal[0 * outStride] = prevVIDYA;
      outIdx = 1;
      while( today <= endIdx ) {
         tempReal = inReal[trailingIdx];
         diff = tempReal - trailingValue;
         trailingValue = tempReal;
         trailingIdx += 1;
         if( diff > 0.0 ) {
            upSum -= diff;
         } else if( diff < 0.0 ) {
            downSum += diff;
         }
         tempReal = inReal[today];
         diff = tempReal - prevValue;
         prevValue = tempReal;
         if( diff > 0.0 ) {
            upSum += diff;
         } else if( diff < 0.0 ) {
            downSum -= diff;
         }
         if( diff == 0.0 ) {
            nullRun += 1;
         } else {
            nullRun = 0;
         }
         if( nullRun >= optInCMOPeriod ) {
            nullRun = optInCMOPeriod;
            upSum = 0.0;
            downSum = 0.0;
         }
         sum = upSum + downSum;
         if( sum > 0.0 ) {
            k = alpha * (Math.Abs(100.0 * (upSum - downSum) / sum) / 100.0);
         } else {
            k = 0.0;
         }
         prevVIDYA = Math.FusedMultiplyAdd(prevValue - prevVIDYA, k, prevVIDYA);
         outReal[outIdx++ * outStride] = prevVIDYA;
         today += 1;
      }
      outBegIdx = startIdx;
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      int cap_trailingIdx = today - trailingIdx;
      if( cap_trailingIdx < 1 || cap_trailingIdx > historyLen ) {
         return RetCode.InternalError;
      }
      int allocN_trailingIdx = (cap_trailingIdx > 0)? cap_trailingIdx : 1;
      double[] capRing_trailingIdx_inReal = new double[allocN_trailingIdx];
      inReal.Slice(historyLen - cap_trailingIdx, cap_trailingIdx).CopyTo(capRing_trailingIdx_inReal);
      sp.optInTimePeriod = optInTimePeriod;
      sp.optInCMOPeriod = optInCMOPeriod;
      sp.nullRun = nullRun;
      sp.upSum = upSum;
      sp.downSum = downSum;
      sp.prevValue = prevValue;
      sp.trailingValue = trailingValue;
      sp.alpha = alpha;
      sp.prevVIDYA = prevVIDYA;
      sp.ringPos_trailingIdx = 0;
      sp.ringCap_trailingIdx = cap_trailingIdx;
      sp.ring_trailingIdx_inReal = capRing_trailingIdx_inReal;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* VidyaOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal VidyaStream VidyaOpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, int optInCMOPeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      VidyaStream sp = new VidyaStream(this);
      RetCode retCode = VidyaOpenImpl(sp, inReal, startIdx, optInTimePeriod, optInCMOPeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("VIDYA", "openAndFill", nameof(inReal), inReal.Length, startIdx, VidyaLookback(optInTimePeriod, optInCMOPeriod));
      }
      throw StreamFailure("VIDYA", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind VidyaOpen (composition seam). */
   internal VidyaStream VidyaOpenInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, int optInCMOPeriod )
   {
      VidyaStream sp = new VidyaStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = VidyaOpenImpl(sp, inReal, startIdx, optInTimePeriod, optInCMOPeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("VIDYA", "open", nameof(inReal), inReal.Length, startIdx, VidyaLookback(optInTimePeriod, optInCMOPeriod));
      }
      throw StreamFailure("VIDYA", "open", retCode);
   }

   /// <summary>Open a live <c>VIDYA</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="VidyaStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>VIDYA</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>VidyaLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>VidyaOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">Data on which to compute the average. The warm-up history, oldest bar
   /// first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="VidyaLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInCMOPeriod">As in the batch call; see <see cref="VidyaLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>VidyaLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules S1 and S2).</exception>
   public VidyaStream VidyaOpen( ReadOnlySpan<double> inReal, int optInTimePeriod, int optInCMOPeriod )
   {
      if( inReal.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "VIDYA open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "VIDYA open: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      return VidyaOpenInternal(inReal, 0, optInTimePeriod, optInCMOPeriod);
   }

   /// <summary><c>VidyaOpen</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>VIDYA</c> produces over
   /// the same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - VidyaLookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="VidyaStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">Data on which to compute the average. The warm-up history, oldest bar
   /// first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="VidyaLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInCMOPeriod">As in the batch call; see <see cref="VidyaLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Variable Index Dynamic Average line. Must hold at least <c>historyLen -
   /// VidyaLookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>VidyaLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules S1 and S2).</exception>
   public VidyaStream VidyaOpenAndFill( ReadOnlySpan<double> inReal, int optInTimePeriod, int optInCMOPeriod, Span<double> outReal )
   {
      if( inReal.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "VIDYA openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "VIDYA openAndFill: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      int guardOutLen = OpenFillCount("VIDYA", "openAndFill", inReal.Length, VidyaLookback(optInTimePeriod, optInCMOPeriod));
      RequireFillLength("VIDYA", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( outReal.Overlaps(inReal) ) {
         throw StreamFailure("VIDYA", "openAndFill", RetCode.BadParam);
      }
      return VidyaOpenAndFillInternal(inReal, 0, optInTimePeriod, optInCMOPeriod, out _, out _, outReal);
   }

   private double VidyaStepTape( VidyaStream sp, ReadOnlySpan<double> tape, int tapeBase, int tapeMask, double inReal )
   {
      double sum = 0.0;
      double diff = 0.0;
      double tempReal = 0.0;
      double k = 0.0;
      tempReal = tape[(tapeBase - sp.ringCap_trailingIdx) & tapeMask];
      diff = tempReal - sp.trailingValue;
      sp.trailingValue = tempReal;
      if( diff > 0.0 ) {
         sp.upSum -= diff;
      } else if( diff < 0.0 ) {
         sp.downSum += diff;
      }
      tempReal = inReal;
      diff = tempReal - sp.prevValue;
      sp.prevValue = tempReal;
      if( diff > 0.0 ) {
         sp.upSum += diff;
      } else if( diff < 0.0 ) {
         sp.downSum -= diff;
      }
      if( diff == 0.0 ) {
         sp.nullRun += 1;
      } else {
         sp.nullRun = 0;
      }
      if( sp.nullRun >= sp.optInCMOPeriod ) {
         sp.nullRun = sp.optInCMOPeriod;
         sp.upSum = 0.0;
         sp.downSum = 0.0;
      }
      sum = sp.upSum + sp.downSum;
      if( sum > 0.0 ) {
         k = sp.alpha * (Math.Abs(100.0 * (sp.upSum - sp.downSum) / sum) / 100.0);
      } else {
         k = 0.0;
      }
      sp.prevVIDYA = Math.FusedMultiplyAdd(sp.prevValue - sp.prevVIDYA, k, sp.prevVIDYA);
      sp.cur_outReal = sp.prevVIDYA;
      sp.outRangeCount++;
      return sp.cur_outReal;
   }

   private double VidyaPeekTape( VidyaStream sp, ReadOnlySpan<double> tape, int tapeBase, int tapeMask, double inReal )
   {
      double sum = 0.0;
      double diff = 0.0;
      double tempReal = 0.0;
      double k = 0.0;
      double cur_outReal = 0.0;
      double downSum = sp.downSum;
      int nullRun = sp.nullRun;
      double prevVIDYA = sp.prevVIDYA;
      double prevValue = sp.prevValue;
      double trailingValue = sp.trailingValue;
      double upSum = sp.upSum;
      tempReal = tape[(tapeBase - sp.ringCap_trailingIdx) & tapeMask];
      diff = tempReal - trailingValue;
      trailingValue = tempReal;
      if( diff > 0.0 ) {
         upSum -= diff;
      } else if( diff < 0.0 ) {
         downSum += diff;
      }
      tempReal = inReal;
      diff = tempReal - prevValue;
      prevValue = tempReal;
      if( diff > 0.0 ) {
         upSum += diff;
      } else if( diff < 0.0 ) {
         downSum -= diff;
      }
      if( diff == 0.0 ) {
         nullRun += 1;
      } else {
         nullRun = 0;
      }
      if( nullRun >= sp.optInCMOPeriod ) {
         nullRun = sp.optInCMOPeriod;
         upSum = 0.0;
         downSum = 0.0;
      }
      sum = upSum + downSum;
      if( sum > 0.0 ) {
         k = sp.alpha * (Math.Abs(100.0 * (upSum - downSum) / sum) / 100.0);
      } else {
         k = 0.0;
      }
      prevVIDYA = Math.FusedMultiplyAdd(prevValue - prevVIDYA, k, prevVIDYA);
      cur_outReal = prevVIDYA;
      return cur_outReal;
   }

   private int VidyaTapeDetach( VidyaStream sp )
   {
      int reach = 0;
      sp.ring_trailingIdx_inReal = [];
      if( sp.ringCap_trailingIdx > reach ) {
         reach = sp.ringCap_trailingIdx;
      }
      return reach;
   }
