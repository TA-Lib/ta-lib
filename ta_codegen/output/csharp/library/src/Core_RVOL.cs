      double periodTotal = 0;
      double baseline = 0;
      double todayVolume = 0;
      int i = 0;
      int outIdx = 0;
      int trailingIdx = 0;
      int lookbackTotal = 0;
      int historyLen = inVolume.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 20;
      } else if( optInTimePeriod < 1 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      /* One bar more than a moving average of the same period: today is excluded
       * from its own baseline.
       */
      lookbackTotal = (int)optInTimePeriod;
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      periodTotal = 0.0;
      trailingIdx = startIdx - lookbackTotal;
      i = trailingIdx;
      while( i < startIdx ) {
         periodTotal += (double)inVolume[i];
         i = i + 1;
      }
      outIdx = 0;
      while( i <= endIdx ) {
         /* Drop the trailing bar BEFORE adding today's. That order makes each
          * baseline bit-identical to the moving average of the same period at the
          * previous bar; the reverse order differs only in the last ulp, so no
          * tolerance can tell the two apart.
          */
         baseline = periodTotal / (double)optInTimePeriod;
         periodTotal -= (double)inVolume[trailingIdx];
         trailingIdx = trailingIdx + 1;
         todayVolume = (double)inVolume[i];
         i = i + 1;
         periodTotal += todayVolume;
         outReal[outIdx * outStride] = todayVolume / baseline;
         outIdx = outIdx + 1;
      }
      outNBElement = outIdx;
      outBegIdx = startIdx;
      /* Capture the live batch state into the handle. */
      int cap_trailingIdx = i - trailingIdx;
      if( cap_trailingIdx < 0 || cap_trailingIdx > historyLen ) {
         return RetCode.InternalError;
      }
      int allocN_trailingIdx = (cap_trailingIdx > 0)? cap_trailingIdx : 1;
      double[] capRing_trailingIdx_inVolume = new double[allocN_trailingIdx];
      inVolume.Slice(historyLen - cap_trailingIdx, cap_trailingIdx).CopyTo(capRing_trailingIdx_inVolume);
      sp.optInTimePeriod = optInTimePeriod;
      sp.periodTotal = periodTotal;
      sp.ringPos_trailingIdx = 0;
      sp.ringCap_trailingIdx = cap_trailingIdx;
      sp.ring_trailingIdx_inVolume = capRing_trailingIdx_inVolume;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* RvolOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal RvolStream RvolOpenAndFillInternal( ReadOnlySpan<double> inVolume, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      RvolStream sp = new RvolStream(this);
      RetCode retCode = RvolOpenImpl(sp, inVolume, startIdx, optInTimePeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("RVOL", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind RvolOpen (composition seam). */
   internal RvolStream RvolOpenInternal( ReadOnlySpan<double> inVolume, int startIdx, int optInTimePeriod )
   {
      RvolStream sp = new RvolStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = RvolOpenImpl(sp, inVolume, startIdx, optInTimePeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("RVOL", "open", retCode);
   }

   /// <summary>Open a live <c>RVOL</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="RvolStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>RVOL</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>RVOL_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>RvolOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inVolume">Volume of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="RVOL_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>RVOL_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public RvolStream RvolOpen( ReadOnlySpan<double> inVolume, int optInTimePeriod )
   {
      if( inVolume.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inVolume), "RVOL open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inVolume.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inVolume), "RVOL open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      return RvolOpenInternal(inVolume, 0, optInTimePeriod);
   }

   /// <summary><c>RvolOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>RVOL</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - RVOL_Lookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="RvolStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inVolume">Volume of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="RVOL_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Ratio of the current bar's volume to the average of the preceding window.
   /// Must hold at least <c>historyLen - RVOL_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>RVOL_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public RvolStream RvolOpenAndFill( ReadOnlySpan<double> inVolume, int optInTimePeriod, Span<double> outReal )
   {
      if( inVolume.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inVolume), "RVOL openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inVolume.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inVolume), "RVOL openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      int guardOutLen = OpenFillCount("RVOL", "openAndFill", inVolume.Length, RVOL_Lookback(optInTimePeriod));
      RequireFillLength("RVOL", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( outReal.Overlaps(inVolume) ) {
         throw StreamFailure("RVOL", "openAndFill", RetCode.BadParam);
      }
      return RvolOpenAndFillInternal(inVolume, 0, optInTimePeriod, out _, out _, outReal);
   }
