      CDLLONGLINE_Stream sp = new CDLLONGLINE_Stream(this);
      RetCode retCode = CDLLONGLINE_OpenBody(sp, inOpen, inHigh, inLow, inClose, startIdx);
      if( retCode == RetCode.Success ) {
         return sp;
