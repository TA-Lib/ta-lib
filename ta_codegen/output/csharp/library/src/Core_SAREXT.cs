               sar = Math.FusedMultiplyAdd(afLong, ep - sar, sar);
               if( sar > prevLow ) {
                  sar = prevLow;
               }
               if( sar > newLow ) {
                  sar = newLow;
               }
            }
         } else if( newHigh >= sar ) {
            isLong = 1;
            sar = ep;
            if( sar > prevLow ) {
               sar = prevLow;
            }
            if( sar > newLow ) {
               sar = newLow;
            }
            if( optInOffsetOnReverse != 0.0 ) {
               sar -= sar * optInOffsetOnReverse;
            }
            outReal[outIdx++] = sar;
            afLong = optInAccelerationInitLong;
            ep = newHigh;
            sar = Math.FusedMultiplyAdd(afLong, ep - sar, sar);
            if( sar > prevLow ) {
               sar = prevLow;
            }
            if( sar > newLow ) {
               sar = newLow;
            }
         } else {
            outReal[outIdx++] = 0 - sar;
            if( newLow < ep ) {
               ep = newLow;
               afShort += optInAccelerationShort;
               if( afShort > optInAccelerationMaxShort ) {
                  afShort = optInAccelerationMaxShort;
               }
            }
            sar = Math.FusedMultiplyAdd(afShort, ep - sar, sar);
            if( sar < prevHigh ) {
               sar = prevHigh;
            }
            if( sar < newHigh ) {
               sar = newHigh;
            }
         }
      }
      outNBElement = outIdx;
      return RetCode.Success ;
   }
   /// <summary>
   /// Extended Parabolic SAR (stop and reverse) giving the caller full control
   /// over the initial state and separate acceleration factors for long and
   /// short positions. Unlike SAR, it returns negative values while short so
   /// reversals are distinguishable. Sign flip of the output marks a trend
   /// reversal (positive=long stop, negative=short stop).
   /// </summary>
   /// <remarks>
   /// <b>Formula</b>
   /// <code>
   /// SAR_next = SAR + AF*(EP - SAR), then clamped within the prior and current bar's range. On penetration, reverse: set SAR=EP (clamped), reset AF to its Init value, EP=extreme of the new direction. Output is +SAR when long, -SAR when short. On reversal an optional offset is applied: long-&gt;short SAR*(1+offset), short-&gt;long SAR*(1-offset).
