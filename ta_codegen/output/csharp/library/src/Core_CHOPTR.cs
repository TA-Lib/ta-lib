         Array.Copy( other.win_i_inHigh, this.win_i_inHigh, other.win_i_inHigh.Length );
         this.win_i_inLow = new double[other.win_i_inLow.Length];
         Array.Copy( other.win_i_inLow, this.win_i_inLow, other.win_i_inLow.Length );
         this.win_i_inClose = new double[other.win_i_inClose.Length];
         Array.Copy( other.win_i_inClose, this.win_i_inClose, other.win_i_inClose.Length );
         this.cur_outReal = other.cur_outReal;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so nothing moves — <see cref="OutRange"/> included — and
      /// <see cref="Value"/> still answers the previous value. Re-feed the bar when
      /// a corrected value arrives, or call <see cref="Advance"/> to count it and
      /// carry on; two handles on one feed drift a bar apart if neither happens.
      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, which no re-feed clears: the
      /// handle has run out of index domain and only a shorter history can start a
      /// new one.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inHigh, double inLow, double inClose )
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("CHOPTR", "update", RetCode.OutOfRangeEndIndex);
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) ) throw Core.NonFiniteBar("CHOPTR", "update", !double.IsFinite(inHigh) ? nameof(inHigh) : !double.IsFinite(inLow) ? nameof(inLow) : nameof(inClose));
         core.ChoptrStepImpl(this, inHigh, inLow, inClose);
         outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.IndexMax"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public double Peek( double inHigh, double inLow, double inClose )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) ) throw Core.NonFiniteBar("CHOPTR", "peek", !double.IsFinite(inHigh) ? nameof(inHigh) : !double.IsFinite(inLow) ? nameof(inLow) : nameof(inClose));
         ChoptrStream sp = this;
         int i = 0;
         double highest = 0.0;
         double lowest = 0.0;
         double sumTR = 0.0;
         double tempHT = 0.0;
         double tempLT = 0.0;
         double prevClose = 0.0;
         double trueHigh = 0.0;
         double trueLow = 0.0;
         double cur_outReal = 0.0;
         int pkSlot0 = -1;
         double pkVal0 = 0.0;
         int pkSlot1 = -1;
         double pkVal1 = 0.0;
         int pkSlot2 = -1;
         double pkVal2 = 0.0;
         pkSlot0 = sp.winPos_i;
         pkVal0 = inHigh;
         pkSlot1 = sp.winPos_i;
         pkVal1 = inLow;
         pkSlot2 = sp.winPos_i;
         pkVal2 = inClose;
         /* Re-summed oldest to newest every bar, never a running total: a
          * running total leaves a residue on a window of zero true ranges, which
          * the exact guard below would then read as a trend.
          */
         highest = inHigh;
         lowest = inLow;
         sumTR = 0.0;
         prevClose = 0.0;
         for( i = sp.optInTimePeriod; i >= 0; i -= 1 ) {
            if( i < sp.optInTimePeriod ) {
               tempHT = (((sp.winPos_i + sp.winCap_i - i >= sp.winCap_i) ? sp.winPos_i + sp.winCap_i - i - sp.winCap_i : sp.winPos_i + sp.winCap_i - i) != pkSlot0) ? sp.win_i_inHigh[(sp.winPos_i + sp.winCap_i - i >= sp.winCap_i) ? sp.winPos_i + sp.winCap_i - i - sp.winCap_i : sp.winPos_i + sp.winCap_i - i] : pkVal0;
               tempLT = (((sp.winPos_i + sp.winCap_i - i >= sp.winCap_i) ? sp.winPos_i + sp.winCap_i - i - sp.winCap_i : sp.winPos_i + sp.winCap_i - i) != pkSlot1) ? sp.win_i_inLow[(sp.winPos_i + sp.winCap_i - i >= sp.winCap_i) ? sp.winPos_i + sp.winCap_i - i - sp.winCap_i : sp.winPos_i + sp.winCap_i - i] : pkVal1;
               trueHigh = tempHT;
               trueHigh = MaxGt(prevClose, trueHigh);
               trueLow = tempLT;
               trueLow = MinLt(prevClose, trueLow);
               sumTR += trueHigh - trueLow;
               highest = MaxGt(trueHigh, highest);
               lowest = MinLt(trueLow, lowest);
            }
            prevClose = (((sp.winPos_i + sp.winCap_i - i >= sp.winCap_i) ? sp.winPos_i + sp.winCap_i - i - sp.winCap_i : sp.winPos_i + sp.winCap_i - i) != pkSlot2) ? sp.win_i_inClose[(sp.winPos_i + sp.winCap_i - i >= sp.winCap_i) ? sp.winPos_i + sp.winCap_i - i - sp.winCap_i : sp.winPos_i + sp.winCap_i - i] : pkVal2;
         }
         /* The seeds are the raw extrema of today's bar, which its own true
          * high and low always enclose, so they never outrun the true box.
          *
          * Exact test, never an epsilon band (issue #253). Every true range lies
          * inside the box, so a positive sum implies a positive box. Keep the
          * "<=" form: a NaN sum must fall through to the log, not read as 100.
          * Keep the parenthesised quotient: it returns exactly 100 whenever the
          * computed ratio is exactly the period.
          */
         if( sumTR <= 0.0 ) {
            cur_outReal = 100.0;
         } else {
            cur_outReal = 100.0 * (Math.Log10(sumTR / (highest - lowest)) / sp.logPeriod);
         }
         return cur_outReal;
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public ChoptrStream Clone()
      {
         return new ChoptrStream(this);
      }
   }

   private void ChoptrStepImpl( ChoptrStream sp, double inHigh, double inLow, double inClose )
   {
      int i = 0;
      double highest = 0.0;
      double lowest = 0.0;
      double sumTR = 0.0;
      double tempHT = 0.0;
      double tempLT = 0.0;
      double prevClose = 0.0;
      double trueHigh = 0.0;
      double trueLow = 0.0;
      sp.win_i_inHigh[sp.winPos_i] = inHigh;
      sp.win_i_inLow[sp.winPos_i] = inLow;
      sp.win_i_inClose[sp.winPos_i] = inClose;
      /* Re-summed oldest to newest every bar, never a running total: a
       * running total leaves a residue on a window of zero true ranges, which
       * the exact guard below would then read as a trend.
       */
      highest = inHigh;
      lowest = inLow;
      sumTR = 0.0;
      prevClose = 0.0;
      for( i = sp.optInTimePeriod; i >= 0; i -= 1 ) {
         if( i < sp.optInTimePeriod ) {
            tempHT = sp.win_i_inHigh[(sp.winPos_i + sp.winCap_i - i >= sp.winCap_i) ? sp.winPos_i + sp.winCap_i - i - sp.winCap_i : sp.winPos_i + sp.winCap_i - i];
            tempLT = sp.win_i_inLow[(sp.winPos_i + sp.winCap_i - i >= sp.winCap_i) ? sp.winPos_i + sp.winCap_i - i - sp.winCap_i : sp.winPos_i + sp.winCap_i - i];
            trueHigh = tempHT;
            trueHigh = MaxGt(prevClose, trueHigh);
            trueLow = tempLT;
            trueLow = MinLt(prevClose, trueLow);
            sumTR += trueHigh - trueLow;
            highest = MaxGt(trueHigh, highest);
            lowest = MinLt(trueLow, lowest);
         }
         prevClose = sp.win_i_inClose[(sp.winPos_i + sp.winCap_i - i >= sp.winCap_i) ? sp.winPos_i + sp.winCap_i - i - sp.winCap_i : sp.winPos_i + sp.winCap_i - i];
      }
      /* The seeds are the raw extrema of today's bar, which its own true
       * high and low always enclose, so they never outrun the true box.
       *
       * Exact test, never an epsilon band (issue #253). Every true range lies
       * inside the box, so a positive sum implies a positive box. Keep the
       * "<=" form: a NaN sum must fall through to the log, not read as 100.
       * Keep the parenthesised quotient: it returns exactly 100 whenever the
       * computed ratio is exactly the period.
       */
      if( sumTR <= 0.0 ) {
         sp.cur_outReal = 100.0;
      } else {
         sp.cur_outReal = 100.0 * (Math.Log10(sumTR / (highest - lowest)) / sp.logPeriod);
      }
      sp.winPos_i = sp.winPos_i + 1;
      if( sp.winPos_i >= sp.winCap_i ) {
         sp.winPos_i = 0;
      }
   }

   private RetCode ChoptrOpenImpl( ChoptrStream sp, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      int today = 0;
      int outIdx = 0;
      int lookbackTotal = 0;
      int i = 0;
      double highest = 0;
      double lowest = 0;
      double sumTR = 0;
      double logPeriod = 0;
      double tempHT = 0;
      double tempLT = 0;
      double prevClose = 0;
      double trueHigh = 0;
      double trueLow = 0;
      int historyLen = inHigh.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > IndexMax + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inLow.Length != inHigh.Length || inClose.Length != inHigh.Length ) {
         return RetCode.BadParam;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 14;
      } else if( optInTimePeriod < 2 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      outBegIdx = 0;
      outNBElement = 0;
      lookbackTotal = ChoptrLookback(optInTimePeriod);
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         return RetCode.InsufficientHistory ;
      }
      logPeriod = Math.Log10((double)optInTimePeriod);
      outIdx = 0;
      today = startIdx;
      while( today <= endIdx ) {
         /* Re-summed oldest to newest every bar, never a running total: a
          * running total leaves a residue on a window of zero true ranges, which
          * the exact guard below would then read as a trend.
          */
         highest = inHigh[today];
         lowest = inLow[today];
         sumTR = 0.0;
         prevClose = 0.0;
         for( i = optInTimePeriod; i >= 0; i -= 1 ) {
            if( i < optInTimePeriod ) {
               tempHT = inHigh[today - i];
               tempLT = inLow[today - i];
               trueHigh = tempHT;
               trueHigh = MaxGt(prevClose, trueHigh);
               trueLow = tempLT;
               trueLow = MinLt(prevClose, trueLow);
               sumTR += trueHigh - trueLow;
               highest = MaxGt(trueHigh, highest);
               lowest = MinLt(trueLow, lowest);
            }
            prevClose = inClose[today - i];
         }
         /* The seeds are the raw extrema of today's bar, which its own true
          * high and low always enclose, so they never outrun the true box.
          *
          * Exact test, never an epsilon band (issue #253). Every true range lies
          * inside the box, so a positive sum implies a positive box. Keep the
          * "<=" form: a NaN sum must fall through to the log, not read as 100.
          * Keep the parenthesised quotient: it returns exactly 100 whenever the
          * computed ratio is exactly the period.
          */
         if( sumTR <= 0.0 ) {
            outReal[outIdx * outStride] = 100.0;
         } else {
            outReal[outIdx * outStride] = 100.0 * (Math.Log10(sumTR / (highest - lowest)) / logPeriod);
         }
         outIdx += 1;
         today += 1;
      }
      outBegIdx = startIdx;
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      int cap_i = (int)(optInTimePeriod + 1);
      if( cap_i < 1 || cap_i > historyLen ) {
         return RetCode.InternalError;
      }
      double[] capWin_i_inHigh = new double[cap_i];
      inHigh.Slice(historyLen - cap_i, cap_i).CopyTo(capWin_i_inHigh);
      double[] capWin_i_inLow = new double[cap_i];
      inLow.Slice(historyLen - cap_i, cap_i).CopyTo(capWin_i_inLow);
      double[] capWin_i_inClose = new double[cap_i];
      inClose.Slice(historyLen - cap_i, cap_i).CopyTo(capWin_i_inClose);
      sp.optInTimePeriod = optInTimePeriod;
      sp.logPeriod = logPeriod;
      sp.winPos_i = 0;
      sp.winCap_i = cap_i;
      sp.win_i_inHigh = capWin_i_inHigh;
      sp.win_i_inLow = capWin_i_inLow;
      sp.win_i_inClose = capWin_i_inClose;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* ChoptrOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal ChoptrStream ChoptrOpenAndFillInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      ChoptrStream sp = new ChoptrStream(this);
      RetCode retCode = ChoptrOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInTimePeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("CHOPTR", "openAndFill", nameof(inHigh), inHigh.Length, startIdx, ChoptrLookback(optInTimePeriod));
      }
      throw StreamFailure("CHOPTR", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind ChoptrOpen (composition seam). */
   internal ChoptrStream ChoptrOpenInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod )
   {
      ChoptrStream sp = new ChoptrStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = ChoptrOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInTimePeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("CHOPTR", "open", nameof(inHigh), inHigh.Length, startIdx, ChoptrLookback(optInTimePeriod));
      }
      throw StreamFailure("CHOPTR", "open", retCode);
   }

   /// <summary>Open a live <c>CHOPTR</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="ChoptrStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>CHOPTR</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>ChoptrLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>ChoptrOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="ChoptrLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>ChoptrLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public ChoptrStream ChoptrOpen( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInTimePeriod )
   {
      if( inHigh.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "CHOPTR open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "CHOPTR open: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TALibArgumentException("CHOPTR open: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TALibArgumentException("CHOPTR open: inClose is empty", nameof(inClose), RetCode.BadParam);
      RequireHistoryLength("CHOPTR", "open", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("CHOPTR", "open", "inClose", inClose.Length, inHigh.Length);
      return ChoptrOpenInternal(inHigh, inLow, inClose, 0, optInTimePeriod);
   }

   /// <summary><c>ChoptrOpen</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>CHOPTR</c> produces over
   /// the same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - ChoptrLookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="ChoptrStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="ChoptrLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Choppiness Index value. Must hold at least <c>historyLen -
   /// ChoptrLookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>ChoptrLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public ChoptrStream ChoptrOpenAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInTimePeriod, Span<double> outReal )
   {
      if( inHigh.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "CHOPTR openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "CHOPTR openAndFill: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TALibArgumentException("CHOPTR openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TALibArgumentException("CHOPTR openAndFill: inClose is empty", nameof(inClose), RetCode.BadParam);
      int guardOutLen = OpenFillCount("CHOPTR", "openAndFill", inHigh.Length, ChoptrLookback(optInTimePeriod));
      RequireHistoryLength("CHOPTR", "openAndFill", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("CHOPTR", "openAndFill", "inClose", inClose.Length, inHigh.Length);
      RequireFillLength("CHOPTR", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( SameBuffer(outReal, inHigh) || SameBuffer(outReal, inLow) || SameBuffer(outReal, inClose) ) {
         throw StreamFailure("CHOPTR", "openAndFill", RetCode.BadParam);
      }
      if( guardOutLen > 0 && ( outReal.Overlaps(inHigh) || outReal.Overlaps(inLow) || outReal.Overlaps(inClose) ) ) {
         throw StreamFailure("CHOPTR", "openAndFill", RetCode.BadParam);
      }
      return ChoptrOpenAndFillInternal(inHigh, inLow, inClose, 0, optInTimePeriod, out _, out _, outReal);
   }
