      /// stricter than the batch API, which computes on whatever it is given: a
      /// handle retains its state, so a single non-finite bar would poison every
      /// later value it produces.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>The value at the bar just committed.</returns>
      public EriValue Update( double inHigh, double inLow, double inClose )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) )
         {
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
            throw Core.StreamFailure("ERI", "update", RetCode.BadParam);
         }
         core.EriStepImpl(this, inHigh, inLow, inClose);
         if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         return new EriValue(cur_outBullPower, cur_outBearPower);
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It copies nothing: the frame runs against this handle, reading its buffers
      /// and holding what the step would commit in locals. The cost does not grow
      /// with the period, and <c>Peek</c> never allocates.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>What <see cref="Update"/> would return for this bar.</returns>
      public EriValue Peek( double inHigh, double inLow, double inClose )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) ) throw Core.StreamFailure("ERI", "peek", RetCode.BadParam);
         EriStream sp = this;
         double cur_outBullPower = 0.0;
         double cur_outBearPower = 0.0;
         if( sp.optInTimePeriod == 1 ) {
            double tempReal = 0.0;
            double tempHT = 0.0;
            double tempLT = 0.0;
            tempHT = inHigh;
            tempLT = inLow;
            tempReal = inClose;
            cur_outBullPower = tempHT - tempReal;
            cur_outBearPower = tempLT - tempReal;
         } else {
            double tempHT = 0.0;
            double tempLT = 0.0;
            double prevMA = sp.prevMA;
            prevMA = Math.FusedMultiplyAdd(inClose - prevMA, sp.k, prevMA);
            tempHT = inHigh;
            tempLT = inLow;
            cur_outBullPower = tempHT - prevMA;
            cur_outBearPower = tempLT - prevMA;
         }
         return new EriValue(cur_outBullPower, cur_outBearPower);
      }

      /// <summary>Commit <c>n</c> closed bars and write their <c>n</c> values, in one call.</summary>
      /// <remarks>
      /// <para>Exactly <c>n</c> back-to-back <see cref="Update"/> calls, with one set of
      /// argument checks instead of <c>n</c>. The outputs must hold at least
      /// <c>n</c> values and must not overlap an input or each other.</para>
      /// <para><see cref="OutRange"/> counts what this call took in, which is what makes
      /// a rejection readable: a non-finite bar <c>k</c> throws
      /// <see cref="System.ArgumentException"/> exactly as <see cref="Update"/>
      /// would, with the bars before <c>k</c> committed and written, bar <c>k</c>
      /// and everything after it not written, and the count advanced by <c>k +
      /// 1</c> — the committed bars plus the rejected one, so the last bar counted
      /// is the one that failed.</para>
      /// </remarks>
      /// <param name="inHigh">Closed bars for <c>inHigh</c>, oldest first.</param>
      /// <param name="inLow">Closed bars for <c>inLow</c>, oldest first.</param>
      /// <param name="inClose">Closed bars for <c>inClose</c>, oldest first.</param>
      /// <param name="outBullPower">Receives one <c>outBullPower</c> value per bar committed.</param>
      /// <param name="outBearPower">Receives one <c>outBearPower</c> value per bar committed.</param>
      public void UpdateAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, Span<double> outBullPower, Span<double> outBearPower )
      {
         int barCount = inHigh.Length;
         if( inLow.Length != barCount || inClose.Length != barCount || outBullPower.Length < barCount || outBearPower.Length < barCount || outBullPower.Overlaps(inHigh) || outBullPower.Overlaps(inLow) || outBullPower.Overlaps(inClose) || outBearPower.Overlaps(inHigh) || outBearPower.Overlaps(inLow) || outBearPower.Overlaps(inClose) || outBullPower.Overlaps(outBearPower) ) throw Core.StreamFailure("ERI", "updateAndFill", RetCode.BadParam);
         for( int i = 0; i < barCount; i++ )
         {
            if( !double.IsFinite(inHigh[i]) || !double.IsFinite(inLow[i]) || !double.IsFinite(inClose[i]) )
            {
               if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
               throw Core.StreamFailure("ERI", "updateAndFill", RetCode.BadParam);
            }
            core.EriStepImpl(this, inHigh[i], inLow[i], inClose[i]);
            outBullPower[i] = cur_outBullPower;
            outBearPower[i] = cur_outBearPower;
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         }
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public EriValue Value => new EriValue(cur_outBullPower, cur_outBearPower);

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public EriStream Clone()
      {
         return new EriStream(this);
      }
   }

   internal void EriStepImpl( EriStream sp, double inHigh, double inLow, double inClose )
   {
      if( sp.optInTimePeriod == 1 ) {
         double tempReal = 0.0;
         double tempHT = 0.0;
         double tempLT = 0.0;
         tempHT = inHigh;
         tempLT = inLow;
         tempReal = inClose;
         sp.cur_outBullPower = tempHT - tempReal;
         sp.cur_outBearPower = tempLT - tempReal;
      } else {
         double tempHT = 0.0;
         double tempLT = 0.0;
         sp.prevMA = Math.FusedMultiplyAdd(inClose - sp.prevMA, sp.k, sp.prevMA);
         tempHT = inHigh;
         tempLT = inLow;
         sp.cur_outBullPower = tempHT - sp.prevMA;
         sp.cur_outBearPower = tempLT - sp.prevMA;
      }
   }

   private RetCode EriOpenImpl( EriStream sp, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outBullPower, Span<double> outBearPower, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      int historyLen = inHigh.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inLow.Length != inHigh.Length || inClose.Length != inHigh.Length ) {
         return RetCode.BadParam;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 13;
      } else if( optInTimePeriod < 1 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInTimePeriod == 1 ) {
         int outIdx = 0;
         int today = 0;
         int lookbackTotal = 0;
         int i = 0;
         double prevMA = 0;
         double tempReal = 0;
         double k = 0;
         double tempHT = 0;
         double tempLT = 0;
         /* Elder Ray Index (Alexander Elder, Trading for a Living, 1993): how far
          * the bar's extremes sit from one shared EMA of close.
          *
          *   Bull Power = High - EMA(Close, n)
          *   Bear Power = Low  - EMA(Close, n)
          *
          * One fused loop, not ema() + a combine map: a composed form cannot
          * stream (raw bar inputs are outside check_map_step's provenance), which
          * is the same reason ACCBANDS is fused. The EMA is ema.c's DEFAULT arm
          * op for op -- sequential seed sum from 0.0 then one divide, the
          * unstable-period warm-up consumed bar by bar -- so the differential
          * against shipped TA_EMA holds bitwise. No compatibility branch: the
          * Metastock arm is unreachable from three of the four backends, and a
          * new function honouring it would make C diverge from them (EFI/SMI
          * precedent).
          *
          * No division in the per-bar map: no 0/0, no NaN path (#112 by
          * construction). Bull >= Bear on every bar since high >= low.
          */
         lookbackTotal = ERI_Lookback(optInTimePeriod);
         if( startIdx < lookbackTotal ) {
            startIdx = lookbackTotal;
         }
         /* Make sure there is still something to evaluate. */
         if( startIdx > endIdx ) {
            outBegIdx = 0;
            outNBElement = 0;
            return RetCode.InsufficientHistory ;
         }
         /* Period 1: ema.c's explicit copy arm, kept here for the same reason it
          * exists there. At n == 1 the recursion below is fl(fl(x-prev)+prev),
          * which returns x only while consecutive closes stay within a factor of
          * two (Sterbenz), so without this arm `High - TA_EMA(Close, 1)` is not
          * what this function returns. The unstable period still delays the first
          * output, through the shared lookback above.
          */
         outIdx = 0;
         today = startIdx;
         while( today <= endIdx ) {
            tempHT = inHigh[today];
            tempLT = inLow[today];
            tempReal = inClose[today];
            outBullPower[outIdx * outStride] = tempHT - tempReal;
            outBearPower[outIdx * outStride] = tempLT - tempReal;
            outIdx += 1;
            today += 1;
         }
         outBegIdx = startIdx;
         outNBElement = outIdx;
         /* Capture the live batch state into the handle. */
         sp.optInTimePeriod = optInTimePeriod;
         sp.prevMA = prevMA;
         sp.k = k;
         sp.cur_outBullPower = outBullPower[(outNBElement - 1) * outStride];
         sp.cur_outBearPower = outBearPower[(outNBElement - 1) * outStride];
         return RetCode.Success;
      } else {
         int outIdx = 0;
         int today = 0;
         int lookbackTotal = 0;
         int i = 0;
         double prevMA = 0;
         double tempReal = 0;
         double k = 0;
         double tempHT = 0;
         double tempLT = 0;
         /* Elder Ray Index (Alexander Elder, Trading for a Living, 1993): how far
          * the bar's extremes sit from one shared EMA of close.
          *
          *   Bull Power = High - EMA(Close, n)
          *   Bear Power = Low  - EMA(Close, n)
          *
          * One fused loop, not ema() + a combine map: a composed form cannot
          * stream (raw bar inputs are outside check_map_step's provenance), which
          * is the same reason ACCBANDS is fused. The EMA is ema.c's DEFAULT arm
          * op for op -- sequential seed sum from 0.0 then one divide, the
          * unstable-period warm-up consumed bar by bar -- so the differential
          * against shipped TA_EMA holds bitwise. No compatibility branch: the
          * Metastock arm is unreachable from three of the four backends, and a
          * new function honouring it would make C diverge from them (EFI/SMI
          * precedent).
          *
          * No division in the per-bar map: no 0/0, no NaN path (#112 by
          * construction). Bull >= Bear on every bar since high >= low.
          */
         lookbackTotal = ERI_Lookback(optInTimePeriod);
         if( startIdx < lookbackTotal ) {
            startIdx = lookbackTotal;
         }
         /* Make sure there is still something to evaluate. */
         if( startIdx > endIdx ) {
            outBegIdx = 0;
            outNBElement = 0;
            return RetCode.InsufficientHistory ;
         }
         /* Period 1: ema.c's explicit copy arm, kept here for the same reason it
          * exists there. At n == 1 the recursion below is fl(fl(x-prev)+prev),
          * which returns x only while consecutive closes stay within a factor of
          * two (Sterbenz), so without this arm `High - TA_EMA(Close, 1)` is not
          * what this function returns. The unstable period still delays the first
          * output, through the shared lookback above.
          */
         k = 2.0 / ((double)optInTimePeriod + 1.0);
         /* Seed: ema.c's DEFAULT arm, op for op. */
         today = startIdx - lookbackTotal;
         i = optInTimePeriod;
         tempReal = 0.0;
         while( i-- > 0 ) {
            tempReal += inClose[today++];
         }
         prevMA = tempReal / optInTimePeriod;
         /* The warm-up also consumes the EMA unstable period. */
         while( today <= startIdx ) {
            prevMA = Math.FusedMultiplyAdd(inClose[today++] - prevMA, k, prevMA);
         }
         /* prevMA is the EMA at bar startIdx; today == startIdx + 1. Load the
          * extremes into temps BEFORE writing either output: with two outputs
          * over three inputs the caller may alias any pair, and the second write
          * must not read a clobbered bar.
          */
         tempHT = inHigh[startIdx];
         tempLT = inLow[startIdx];
         outBullPower[0 * outStride] = tempHT - prevMA;
         outBearPower[0 * outStride] = tempLT - prevMA;
         outIdx = 1;
         while( today <= endIdx ) {
            prevMA = Math.FusedMultiplyAdd(inClose[today] - prevMA, k, prevMA);
            tempHT = inHigh[today];
            tempLT = inLow[today];
            outBullPower[outIdx * outStride] = tempHT - prevMA;
            outBearPower[outIdx * outStride] = tempLT - prevMA;
            outIdx += 1;
            today += 1;
         }
         outBegIdx = startIdx;
         outNBElement = outIdx;
         /* Capture the live batch state into the handle. */
         sp.optInTimePeriod = optInTimePeriod;
         sp.prevMA = prevMA;
         sp.k = k;
         sp.cur_outBullPower = outBullPower[(outNBElement - 1) * outStride];
         sp.cur_outBearPower = outBearPower[(outNBElement - 1) * outStride];
         return RetCode.Success;
      }
   }

   /* EriOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal EriStream EriOpenAndFillInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outBullPower, Span<double> outBearPower )
   {
      EriStream sp = new EriStream(this);
      RetCode retCode = EriOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInTimePeriod, out outBegIdx, out outNBElement, outBullPower, outBearPower, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("ERI", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind EriOpen (composition seam). */
   internal EriStream EriOpenInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod )
   {
      EriStream sp = new EriStream(this);
      double[] sink_outBullPower = new double[1];
      double[] sink_outBearPower = new double[1];
      RetCode retCode = EriOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInTimePeriod, out int outBegIdx, out int outNBElement, sink_outBullPower, sink_outBearPower, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("ERI", "open", retCode);
   }

   /// <summary>Open a live <c>ERI</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="EriStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>ERI</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>ERI_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>EriOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inHigh">High price series. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price series. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price series. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="ERI_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>ERI_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public EriStream EriOpen( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInTimePeriod )
   {
      if( inHigh.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "ERI open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "ERI open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("ERI open: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TaLibArgumentException("ERI open: inClose is empty", nameof(inClose), RetCode.BadParam);
      RequireHistoryLength("ERI", "open", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("ERI", "open", "inClose", inClose.Length, inHigh.Length);
      return EriOpenInternal(inHigh, inLow, inClose, 0, optInTimePeriod);
   }

   /// <summary><c>EriOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>ERI</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - ERI_Lookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="EriStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inHigh">High price series. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price series. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price series. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="ERI_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outBullPower">High minus the EMA of close. Must hold at least <c>historyLen -
   /// ERI_Lookback(...)</c> values.</param>
   /// <param name="outBearPower">Low minus the EMA of close. Must hold at least <c>historyLen -
   /// ERI_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>ERI_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public EriStream EriOpenAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInTimePeriod, Span<double> outBullPower, Span<double> outBearPower )
   {
      if( inHigh.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "ERI openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "ERI openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("ERI openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TaLibArgumentException("ERI openAndFill: inClose is empty", nameof(inClose), RetCode.BadParam);
      int guardOutLen = OpenFillCount("ERI", "openAndFill", inHigh.Length, ERI_Lookback(optInTimePeriod));
      RequireHistoryLength("ERI", "openAndFill", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("ERI", "openAndFill", "inClose", inClose.Length, inHigh.Length);
      RequireFillLength("ERI", "openAndFill", "outBullPower", outBullPower.Length, guardOutLen);
      RequireFillLength("ERI", "openAndFill", "outBearPower", outBearPower.Length, guardOutLen);
      if( outBullPower.Overlaps(inHigh) || outBullPower.Overlaps(inLow) || outBullPower.Overlaps(inClose) || outBearPower.Overlaps(inHigh) || outBearPower.Overlaps(inLow) || outBearPower.Overlaps(inClose) || outBullPower.Overlaps(outBearPower) ) {
         throw StreamFailure("ERI", "openAndFill", RetCode.BadParam);
      }
      return EriOpenAndFillInternal(inHigh, inLow, inClose, 0, optInTimePeriod, out _, out _, outBullPower, outBearPower);
   }
