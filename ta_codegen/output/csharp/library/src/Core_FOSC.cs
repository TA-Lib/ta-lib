      public double Update( double inReal )
      {
         if( !double.IsFinite(inReal) )
         {
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
            throw Core.StreamFailure("FOSC", "update", RetCode.BadParam);
         }
         core.FoscStepImpl(this, inReal);
         if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It copies nothing: the frame runs against this handle, reading its buffers
      /// and holding what the step would commit in locals. The cost does not grow
      /// with the period, and <c>Peek</c> never allocates.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>What <see cref="Update"/> would return for this bar.</returns>
      public double Peek( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.StreamFailure("FOSC", "peek", RetCode.BadParam);
         FoscStream sp = this;
         double m = 0.0;
         double b = 0.0;
         double closeValue = 0.0;
         int windowStart = 0;
         double tempValue1 = 0.0;
         double tempValue2 = 0.0;
         double weightedTrailing = 0.0;
         double SumXY = sp.SumXY;
         double SumY = sp.SumY;
         int barsSinceReseed = sp.barsSinceReseed;
         double cur_outReal = 0.0;
         int j = sp.j;
         double sumAbs = sp.sumAbs;
         int today = sp.today;
         int trailingIdx = sp.trailingIdx;
         double trailingValue = sp.trailingValue;
         int pkSlot0 = -1;
         double pkVal0 = 0.0;
         if( today >= 1073741824 ) {
            int rebaseShift = trailingIdx & ~sp.xMask;
            today -= rebaseShift;
            trailingIdx -= rebaseShift;
            j -= rebaseShift;
         }
         pkSlot0 = today & sp.xMask;
         pkVal0 = inReal;
         weightedTrailing = (double)sp.optInTimePeriod * trailingValue;
         SumXY = SumXY + SumY - weightedTrailing;
         SumY = SumY - trailingValue + ((((today - 1) & sp.xMask) != pkSlot0) ? sp.x_inReal[(today - 1) & sp.xMask] : pkVal0);
         sumAbs = sumAbs - Math.Abs(trailingValue) + Math.Abs((((today - 1) & sp.xMask) != pkSlot0) ? sp.x_inReal[(today - 1) & sp.xMask] : pkVal0);
         barsSinceReseed -= 1;
         if( barsSinceReseed <= 0 || Math.Abs(weightedTrailing) > 100.0 * sumAbs ) {
            barsSinceReseed = 32 * sp.optInTimePeriod;
            windowStart = today - sp.lookbackTotal;
            SumY = 0;
            SumXY = 0;
            sumAbs = 0;
            tempValue2 = (double)(sp.optInTimePeriod - 1);
            for( j = windowStart; j < today; j += 1 ) {
               tempValue1 = ((j & sp.xMask) != pkSlot0) ? sp.x_inReal[j & sp.xMask] : pkVal0;
               SumY += tempValue1;
               SumXY += tempValue2 * tempValue1;
               sumAbs += Math.Abs(tempValue1);
               tempValue2 -= 1.0;
            }
         }
         m = (sp.optInTimePeriod * SumXY - sp.SumX * SumY) / sp.Divisor;
         b = (SumY - m * sp.SumX) / (double)sp.optInTimePeriod;
         trailingValue = ((trailingIdx & sp.xMask) != pkSlot0) ? sp.x_inReal[trailingIdx & sp.xMask] : pkVal0;
         trailingIdx += 1;
         closeValue = ((today & sp.xMask) != pkSlot0) ? sp.x_inReal[today & sp.xMask] : pkVal0;
         if( closeValue != 0.0 ) {
            cur_outReal = 100.0 * (closeValue - (Math.FusedMultiplyAdd(m, (double)sp.optInTimePeriod, b))) / closeValue;
         } else {
            cur_outReal = 0.0;
         }
         return cur_outReal;
      }

      /// <summary>Commit <c>n</c> closed bars and write their <c>n</c> values, in one call.</summary>
      /// <remarks>
      /// <para>Exactly <c>n</c> back-to-back <see cref="Update"/> calls, with one set of
      /// argument checks instead of <c>n</c>. The outputs must hold at least
      /// <c>n</c> values and must not overlap an input or each other.</para>
      /// <para><see cref="OutRange"/> counts what this call took in, which is what makes
      /// a rejection readable: a non-finite bar <c>k</c> throws
      /// <see cref="System.ArgumentException"/> exactly as <see cref="Update"/>
      /// would, with the bars before <c>k</c> committed and written, bar <c>k</c>
      /// and everything after it not written, and the count advanced by <c>k +
      /// 1</c> — the committed bars plus the rejected one, so the last bar counted
      /// is the one that failed.</para>
      /// </remarks>
      /// <param name="inReal">Closed bars for <c>inReal</c>, oldest first.</param>
      /// <param name="outReal">Receives one <c>outReal</c> value per bar committed.</param>
      public void UpdateAndFill( ReadOnlySpan<double> inReal, Span<double> outReal )
      {
         int barCount = inReal.Length;
         if( outReal.Length < barCount || outReal.Overlaps(inReal) ) throw Core.StreamFailure("FOSC", "updateAndFill", RetCode.BadParam);
         for( int i = 0; i < barCount; i++ )
         {
            if( !double.IsFinite(inReal[i]) )
            {
               if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
               throw Core.StreamFailure("FOSC", "updateAndFill", RetCode.BadParam);
            }
            core.FoscStepImpl(this, inReal[i]);
            outReal[i] = cur_outReal;
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         }
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public FoscStream Clone()
      {
         return new FoscStream(this);
      }
   }

   internal void FoscStepImpl( FoscStream sp, double inReal )
   {
      double m = 0.0;
      double b = 0.0;
      double closeValue = 0.0;
      int windowStart = 0;
      double tempValue1 = 0.0;
      double tempValue2 = 0.0;
      double weightedTrailing = 0.0;
      if( sp.today >= 1073741824 ) {
         int rebaseShift = sp.trailingIdx & ~sp.xMask;
         sp.today -= rebaseShift;
         sp.trailingIdx -= rebaseShift;
         sp.j -= rebaseShift;
      }
      sp.x_inReal[sp.today & sp.xMask] = inReal;
      weightedTrailing = (double)sp.optInTimePeriod * sp.trailingValue;
      sp.SumXY = sp.SumXY + sp.SumY - weightedTrailing;
      sp.SumY = sp.SumY - sp.trailingValue + sp.x_inReal[(sp.today - 1) & sp.xMask];
      sp.sumAbs = sp.sumAbs - Math.Abs(sp.trailingValue) + Math.Abs(sp.x_inReal[(sp.today - 1) & sp.xMask]);
      sp.barsSinceReseed -= 1;
      if( sp.barsSinceReseed <= 0 || Math.Abs(weightedTrailing) > 100.0 * sp.sumAbs ) {
         sp.barsSinceReseed = 32 * sp.optInTimePeriod;
         windowStart = sp.today - sp.lookbackTotal;
         sp.SumY = 0;
         sp.SumXY = 0;
         sp.sumAbs = 0;
         tempValue2 = (double)(sp.optInTimePeriod - 1);
         for( sp.j = windowStart; sp.j < sp.today; sp.j += 1 ) {
            tempValue1 = sp.x_inReal[sp.j & sp.xMask];
            sp.SumY += tempValue1;
            sp.SumXY += tempValue2 * tempValue1;
            sp.sumAbs += Math.Abs(tempValue1);
            tempValue2 -= 1.0;
         }
      }
      m = (sp.optInTimePeriod * sp.SumXY - sp.SumX * sp.SumY) / sp.Divisor;
      b = (sp.SumY - m * sp.SumX) / (double)sp.optInTimePeriod;
      sp.trailingValue = sp.x_inReal[sp.trailingIdx & sp.xMask];
      sp.trailingIdx += 1;
      closeValue = sp.x_inReal[sp.today & sp.xMask];
      if( closeValue != 0.0 ) {
         sp.cur_outReal = 100.0 * (closeValue - (Math.FusedMultiplyAdd(m, (double)sp.optInTimePeriod, b))) / closeValue;
      } else {
         sp.cur_outReal = 0.0;
      }
      sp.today += 1;
      sp.lag1_inReal = inReal;
   }

   private RetCode FoscOpenImpl( FoscStream sp, ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      int outIdx = 0;
      int today = 0;
      int lookbackTotal = 0;
      int trailingIdx = 0;
      double SumX = 0;
      double SumXY = 0;
      double SumY = 0;
      double SumXSqr = 0;
      double Divisor = 0;
      double m = 0;
      double b = 0;
      double closeValue = 0;
      int i = 0;
      int j = 0;
      int windowStart = 0;
      int barsSinceReseed = 0;
      double tempValue1 = 0;
      double tempValue2 = 0;
      double trailingValue = 0;
      double weightedTrailing = 0;
      double sumAbs = 0;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 5;
      } else if( optInTimePeriod < 2 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      /* The forecast compared against the close is the one made one bar EARLIER:
       * FOSC[t] = 100*(inReal[t] - TSF[t-1])/inReal[t]. The regression window
       * ends at t-1, so the lookback is period, not period-1.
       *
       * The window arithmetic below is TA_TSF's verbatim -- priming scan, O(1)
       * recurrence, both re-anchor triggers (#254) and the fused
       * `b + m*(double)optInTimePeriod` -- which is what makes FOSC bit-identical
       * to a TA_TSF call anchored one bar earlier. Reshaping any of it breaks
       * that silently.
       *
       * trailingValue -- the value the NEXT bar's window drops -- is read before
       * the output write because with outReal==inReal (#130) that write lands on
       * exactly that cell whenever startIdx is the clamped minimum. closeValue
       * carries no such constraint: it sits startIdx bars ahead of the cursor.
       */
      lookbackTotal = FOSC_Lookback(optInTimePeriod);
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      outIdx = 0;
      today = startIdx;
      trailingIdx = startIdx - lookbackTotal;
      SumX = (double)optInTimePeriod * (optInTimePeriod - 1) * 0.5;
      SumXSqr = (double)optInTimePeriod * (optInTimePeriod - 1) * (2 * optInTimePeriod - 1) / 6.0;
      Divisor = SumX * SumX - optInTimePeriod * SumXSqr;
      SumXY = 0;
      SumY = 0;
      sumAbs = 0;
      for( i = optInTimePeriod; i-- != 0;  ) {
         tempValue1 = inReal[today - 1 - i];
         SumY += tempValue1;
         SumXY += (double)i * tempValue1;
         sumAbs += Math.Abs(tempValue1);
      }
      m = (optInTimePeriod * SumXY - SumX * SumY) / Divisor;
      b = (SumY - m * SumX) / (double)optInTimePeriod;
      barsSinceReseed = 32 * optInTimePeriod;
      trailingValue = inReal[trailingIdx];
      trailingIdx += 1;
      closeValue = inReal[today];
      if( closeValue != 0.0 ) {
         outReal[outIdx++ * outStride] = 100.0 * (closeValue - (Math.FusedMultiplyAdd(m, (double)optInTimePeriod, b))) / closeValue;
      } else {
         outReal[outIdx++ * outStride] = 0.0;
      }
      today += 1;
      while( today <= endIdx ) {
         weightedTrailing = (double)optInTimePeriod * trailingValue;
         SumXY = SumXY + SumY - weightedTrailing;
         SumY = SumY - trailingValue + inReal[today - 1];
         sumAbs = sumAbs - Math.Abs(trailingValue) + Math.Abs(inReal[today - 1]);
         barsSinceReseed -= 1;
         if( barsSinceReseed <= 0 || Math.Abs(weightedTrailing) > 100.0 * sumAbs ) {
            barsSinceReseed = 32 * optInTimePeriod;
            windowStart = today - lookbackTotal;
            SumY = 0;
            SumXY = 0;
            sumAbs = 0;
            tempValue2 = (double)(optInTimePeriod - 1);
            for( j = windowStart; j < today; j += 1 ) {
               tempValue1 = inReal[j];
               SumY += tempValue1;
               SumXY += tempValue2 * tempValue1;
               sumAbs += Math.Abs(tempValue1);
               tempValue2 -= 1.0;
            }
         }
         m = (optInTimePeriod * SumXY - SumX * SumY) / Divisor;
         b = (SumY - m * SumX) / (double)optInTimePeriod;
         trailingValue = inReal[trailingIdx];
         trailingIdx += 1;
         closeValue = inReal[today];
         if( closeValue != 0.0 ) {
            outReal[outIdx++ * outStride] = 100.0 * (closeValue - (Math.FusedMultiplyAdd(m, (double)optInTimePeriod, b))) / closeValue;
         } else {
            outReal[outIdx++ * outStride] = 0.0;
         }
         today += 1;
      }
      outBegIdx = startIdx;
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      int capX = today - trailingIdx + 1;
      if( capX < 1 || capX > historyLen ) {
         return RetCode.InternalError;
      }
      int physX = 1;
      while( physX < capX ) {
         physX <<= 1;
      }
      double[] capX_inReal = new double[physX];
      for( int fillJ = historyLen - capX; fillJ < historyLen; fillJ++ ) {
         capX_inReal[fillJ & (physX - 1)] = inReal[fillJ];
      }
      sp.optInTimePeriod = optInTimePeriod;
      sp.lookbackTotal = lookbackTotal;
      sp.trailingIdx = trailingIdx;
      sp.SumX = SumX;
      sp.SumXY = SumXY;
      sp.SumY = SumY;
      sp.Divisor = Divisor;
      sp.barsSinceReseed = barsSinceReseed;
      sp.trailingValue = trailingValue;
      sp.sumAbs = sumAbs;
      sp.j = j;
      sp.today = today;
      sp.lag1_inReal = inReal[historyLen - 1];
      sp.xMask = physX - 1;
      sp.x_inReal = capX_inReal;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* FoscOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal FoscStream FoscOpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      FoscStream sp = new FoscStream(this);
      RetCode retCode = FoscOpenImpl(sp, inReal, startIdx, optInTimePeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("FOSC", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind FoscOpen (composition seam). */
   internal FoscStream FoscOpenInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod )
   {
      FoscStream sp = new FoscStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = FoscOpenImpl(sp, inReal, startIdx, optInTimePeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("FOSC", "open", retCode);
   }

   /// <summary>Open a live <c>FOSC</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="FoscStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>FOSC</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>FOSC_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>FoscOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">Source price/value series. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="FOSC_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>FOSC_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public FoscStream FoscOpen( ReadOnlySpan<double> inReal, int optInTimePeriod )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "FOSC open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "FOSC open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      return FoscOpenInternal(inReal, 0, optInTimePeriod);
   }

   /// <summary><c>FoscOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>FOSC</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - FOSC_Lookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="FoscStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">Source price/value series. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="FOSC_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Percentage deviation of the close from the previous bar's forecast. Must
   /// hold at least <c>historyLen - FOSC_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>FOSC_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public FoscStream FoscOpenAndFill( ReadOnlySpan<double> inReal, int optInTimePeriod, Span<double> outReal )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "FOSC openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "FOSC openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      int guardOutLen = OpenFillCount("FOSC", "openAndFill", inReal.Length, FOSC_Lookback(optInTimePeriod));
      RequireFillLength("FOSC", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( outReal.Overlaps(inReal) ) {
         throw StreamFailure("FOSC", "openAndFill", RetCode.BadParam);
      }
      return FoscOpenAndFillInternal(inReal, 0, optInTimePeriod, out _, out _, outReal);
   }
