   /// <exception cref="System.ArgumentException">A span is too short for the range requested: any input this function
   /// <i>declares</i> that does not reach <c>endIdx</c>, or an output that
   /// cannot hold the values produced. Checked before anything is written, so a
   /// rejected call leaves every buffer untouched. Declared, not read: a few
   /// candlestick patterns take an OHLC series they never index, and it is
   /// required all the same. An empty span — which is what a null array becomes,
   /// since a span cannot be null — is rejected on the same terms and no others:
   /// it is too short whenever the range produces a value, and fine when it
   /// produces none, and on an output this function documents as declinable it
   /// is how you decline.</exception>
   /// <exception cref="System.ArgumentException">Two output buffers overlap, or an output partially overlaps an input.
   /// Computing wholly in place (an output that IS an input) is allowed.</exception>
   public OutRange KDJ( int startIdx,
                        int endIdx,
                        ReadOnlySpan<float> inHigh,
                        ReadOnlySpan<float> inLow,
                        ReadOnlySpan<float> inClose,
                        int optInFastK_Period,
                        int optInSlowK_Period,
                        MAType optInSlowK_MAType,
                        int optInSlowD_Period,
                        MAType optInSlowD_MAType,
                        Span<double> outK,
                        Span<double> outD,
                        Span<double> outJ )
   {
      int guardStart = ClampedStart(startIdx, endIdx, KDJ_Lookback(optInFastK_Period, optInSlowK_Period, optInSlowK_MAType, optInSlowD_Period, optInSlowD_MAType));
      int guardInLen = guardStart < 0 ? 0 : endIdx + 1;
      int guardOutLen = guardStart < 0 || guardStart > endIdx ? 0 : endIdx - guardStart + 1;
      RequireLength("KDJ", "inHigh", inHigh.Length, guardInLen);
      RequireLength("KDJ", "inLow", inLow.Length, guardInLen);
      RequireLength("KDJ", "inClose", inClose.Length, guardInLen);
      RequireLength("KDJ", "outK", outK.Length, guardOutLen);
      RequireLength("KDJ", "outD", outD.Length, guardOutLen);
      RequireLength("KDJ", "outJ", outJ.Length, guardOutLen);
      RetCode retCode = KDJ_Impl(startIdx, endIdx, inHigh, inLow, inClose, optInFastK_Period, optInSlowK_Period, optInSlowK_MAType, optInSlowD_Period, optInSlowD_MAType, out int outBegIdx, out int outNBElement, outK, outD, outJ);
      if( retCode != RetCode.Success ) {
         throw Failure("KDJ", retCode);
      }
      return new OutRange(outBegIdx, outNBElement);
   }
   /**** Streaming API *****/

   /// <summary>One <c>KDJ</c> output set, in batch output order.</summary>
   /// <remarks>
   /// <para>Equality is the compiler-generated record-struct equality, which compares
   /// the components with <c>==</c>: <c>NaN</c> does not equal <c>NaN</c>, and
   /// <c>0.0</c> equals <c>-0.0</c>. That is deliberately <em>not</em> the Java
   /// <c>Value</c> contract, which compares bitwise — compare
   /// <see cref="System.BitConverter.DoubleToInt64Bits(double)"/> per component
   /// when bit-level identity is what you mean.</para>
   /// </remarks>
   /// <param name="K">Raw stochastic smoothed by SlowK_Period MA.</param>
   /// <param name="D">Signal line: K smoothed by SlowD_Period MA.</param>
   /// <param name="J">Divergence line, three parts K less two parts D.</param>
   public readonly record struct KdjValue( double K, double D, double J );

   /// <summary>A live <c>KDJ</c> stream: one value per closed bar, bit-identical to
   /// <c>KDJ</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.KdjOpen"/>. There is no close and nothing to
   /// dispose — the handle is ordinary managed state, and an unreferenced handle
   /// is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class KdjStream
   {
      internal Core core;
      internal int optInFastK_Period;
      internal int optInSlowK_Period;
      internal MAType optInSlowK_MAType;
      internal int optInSlowD_Period;
      internal MAType optInSlowD_MAType;
      internal double cur_outK;
      internal double cur_outD;
      internal double cur_outJ;
      internal StochStream sub0 = null!;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal KdjStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Kdj</c> reports over the same bars: the opener sets it
      /// to <c>(lookback, historyLen - lookback)</c>, every <c>Update</c> adds one
      /// to the count — a non-finite bar is rejected but still counted, because the
      /// bar happened — <c>Peek</c> leaves it alone, and <c>Clone</c> carries it
      /// verbatim. A plain <c>Open</c> hands back only the last value, a subset of
      /// this range, because the caller chose not to take the fill.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      internal KdjStream( KdjStream other )
      {
         this.core = other.core;
         this.optInFastK_Period = other.optInFastK_Period;
         this.optInSlowK_Period = other.optInSlowK_Period;
         this.optInSlowK_MAType = other.optInSlowK_MAType;
         this.optInSlowD_Period = other.optInSlowD_Period;
         this.optInSlowD_MAType = other.optInSlowD_MAType;
         this.cur_outK = other.cur_outK;
         this.cur_outD = other.cur_outD;
         this.cur_outJ = other.cur_outJ;
         this.sub0 = new StochStream(other.sub0);
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Allocates nothing — neither handle state nor a return value.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so no state moves, <see cref="Value"/> still answers the previous value,
      /// and the stream stays usable — just carry on with the next bar.
      /// <see cref="OutRange"/> does advance: the bar happened, so it is counted,
      /// which keeps two handles fed the same series positionally aligned when only
      /// one of them rejects a bar. This is the one place the streaming tier is
      /// stricter than the batch API, which computes on whatever it is given: a
      /// handle retains its state, so a single non-finite bar would poison every
      /// later value it produces.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>The value at the bar just committed.</returns>
      public KdjValue Update( double inHigh, double inLow, double inClose )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) )
         {
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
            throw Core.StreamFailure("KDJ", "update", RetCode.BadParam);
         }
         core.KdjStepImpl(this, inHigh, inLow, inClose);
         if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         return new KdjValue(cur_outK, cur_outD, cur_outJ);
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It copies nothing: the frame runs against this handle, reading its buffers
      /// and holding what the step would commit in locals. The cost does not grow
      /// with the period, and <c>Peek</c> never allocates.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>What <see cref="Update"/> would return for this bar.</returns>
      public KdjValue Peek( double inHigh, double inLow, double inClose )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) ) throw Core.StreamFailure("KDJ", "peek", RetCode.BadParam);
         KdjStream sp = this;
         double cur_outK = 0.0;
         double cur_outD = 0.0;
         double cur_outJ = 0.0;
         /* Pipeline the new bar through the sub-streams (batch tail order). */
         {
            StochValue subOut0 = sp.sub0.Peek(inHigh, inLow, inClose);
            cur_outK = subOut0.SlowK;
            cur_outD = subOut0.SlowD;
         }
         /* Combine map (batch tail, per bar). */
         cur_outJ = 3.0 * cur_outK - 2.0 * cur_outD;
         return new KdjValue(cur_outK, cur_outD, cur_outJ);
      }

      /// <summary>Commit <c>n</c> closed bars and write their <c>n</c> values, in one call.</summary>
      /// <remarks>
      /// <para>Exactly <c>n</c> back-to-back <see cref="Update"/> calls, with one set of
      /// argument checks instead of <c>n</c>. The outputs must hold at least
      /// <c>n</c> values and must not overlap an input or each other.</para>
      /// <para><see cref="OutRange"/> counts what this call took in, which is what makes
      /// a rejection readable: a non-finite bar <c>k</c> throws
      /// <see cref="System.ArgumentException"/> exactly as <see cref="Update"/>
      /// would, with the bars before <c>k</c> committed and written, bar <c>k</c>
      /// and everything after it not written, and the count advanced by <c>k +
      /// 1</c> — the committed bars plus the rejected one, so the last bar counted
      /// is the one that failed.</para>
      /// </remarks>
      /// <param name="inHigh">Closed bars for <c>inHigh</c>, oldest first.</param>
      /// <param name="inLow">Closed bars for <c>inLow</c>, oldest first.</param>
      /// <param name="inClose">Closed bars for <c>inClose</c>, oldest first.</param>
      /// <param name="outK">Receives one <c>outK</c> value per bar committed.</param>
      /// <param name="outD">Receives one <c>outD</c> value per bar committed.</param>
      /// <param name="outJ">Receives one <c>outJ</c> value per bar committed.</param>
      public void UpdateAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, Span<double> outK, Span<double> outD, Span<double> outJ )
      {
         int barCount = inHigh.Length;
         if( inLow.Length != barCount || inClose.Length != barCount || outK.Length < barCount || outD.Length < barCount || outJ.Length < barCount || outK.Overlaps(inHigh) || outK.Overlaps(inLow) || outK.Overlaps(inClose) || outD.Overlaps(inHigh) || outD.Overlaps(inLow) || outD.Overlaps(inClose) || outJ.Overlaps(inHigh) || outJ.Overlaps(inLow) || outJ.Overlaps(inClose) || outK.Overlaps(outD) || outK.Overlaps(outJ) || outD.Overlaps(outJ) ) throw Core.StreamFailure("KDJ", "updateAndFill", RetCode.BadParam);
         for( int i = 0; i < barCount; i++ )
         {
            if( !double.IsFinite(inHigh[i]) || !double.IsFinite(inLow[i]) || !double.IsFinite(inClose[i]) )
            {
               if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
               throw Core.StreamFailure("KDJ", "updateAndFill", RetCode.BadParam);
            }
            core.KdjStepImpl(this, inHigh[i], inLow[i], inClose[i]);
            outK[i] = cur_outK;
            outD[i] = cur_outD;
            outJ[i] = cur_outJ;
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         }
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public KdjValue Value => new KdjValue(cur_outK, cur_outD, cur_outJ);

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public KdjStream Clone()
      {
         return new KdjStream(this);
      }
   }

   internal void KdjStepImpl( KdjStream sp, double inHigh, double inLow, double inClose )
   {
      double cur_outK = 0.0;
      double cur_outD = 0.0;
      double cur_outJ = 0.0;
      /* Pipeline the new bar through the sub-streams (batch tail order). */
      {
         StochValue subOut0 = sp.sub0.Update(inHigh, inLow, inClose);
         cur_outK = subOut0.SlowK;
         cur_outD = subOut0.SlowD;
      }
      /* Combine map (batch tail, per bar). */
      cur_outJ = 3.0 * cur_outK - 2.0 * cur_outD;
      sp.cur_outK = cur_outK;
      sp.cur_outD = cur_outD;
      sp.cur_outJ = cur_outJ;
   }

   private RetCode KdjOpenImpl( KdjStream sp, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInFastK_Period, int optInSlowK_Period, MAType optInSlowK_MAType, int optInSlowD_Period, MAType optInSlowD_MAType, out int outBegIdx, out int outNBElement, Span<double> outK, Span<double> outD, Span<double> outJ, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      RetCode retCode;
      int i = 0;
      int lookbackTotal = 0;
      int historyLen = inHigh.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inLow.Length != inHigh.Length || inClose.Length != inHigh.Length ) {
         return RetCode.BadParam;
      }
      if( optInFastK_Period == int.MinValue ) {
         optInFastK_Period = 9;
      } else if( optInFastK_Period < 1 || optInFastK_Period > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInSlowK_Period == int.MinValue ) {
         optInSlowK_Period = 3;
      } else if( optInSlowK_Period < 1 || optInSlowK_Period > 100000 ) {
         return RetCode.BadParam;
      }
      if( (int)optInSlowK_MAType == int.MinValue || optInSlowK_MAType == MAType.DEFAULT ) {
         optInSlowK_MAType = MAType.RMA;
      } else if( (int)optInSlowK_MAType < MATypes.Min || (int)optInSlowK_MAType > MATypes.Max ) {
         return RetCode.BadParam;
      }
      if( optInSlowD_Period == int.MinValue ) {
         optInSlowD_Period = 3;
      } else if( optInSlowD_Period < 1 || optInSlowD_Period > 100000 ) {
         return RetCode.BadParam;
      }
      if( (int)optInSlowD_MAType == int.MinValue || optInSlowD_MAType == MAType.DEFAULT ) {
         optInSlowD_MAType = MAType.RMA;
      } else if( (int)optInSlowD_MAType < MATypes.Min || (int)optInSlowD_MAType > MATypes.Max ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      if( historyLen < KDJ_Lookback(optInFastK_Period, optInSlowK_Period, optInSlowK_MAType, optInSlowD_Period, optInSlowD_MAType) + 1 ) {
         return RetCode.InsufficientHistory;
      }
      Span<double> sc_outK = outStride == 1 ? outK : new double[historyLen];
      Span<double> sc_outD = outStride == 1 ? outD : new double[historyLen];
      Span<double> sc_outJ = outStride == 1 ? outJ : new double[historyLen];
      lookbackTotal = KDJ_Lookback(optInFastK_Period, optInSlowK_Period, optInSlowK_MAType, optInSlowD_Period, optInSlowD_MAType);
      /* Nothing to produce: the range is shorter than the lookback. Answering here
       * keeps the sub-call out of the phantom-I/O sweep's zero-length range, where
       * its own argument check would reject before any array is touched.
       */
      if( lookbackTotal > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      /* Sub-stream 0: stoch over `inHigh, inLow, inClose`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      StochStream sub0 = StochOpenAndFillInternal(inHigh, inLow, inClose, startIdx, optInFastK_Period, optInSlowK_Period, optInSlowK_MAType, optInSlowD_Period, optInSlowD_MAType, out outBegIdx, out outNBElement, sc_outK, sc_outD);
      retCode = RetCode.Success;
      if( (int)outNBElement == 0 ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      /* Keep this one Sub expression: spelling it as an Add of a negated term
       * would arm the multiply-add fusion and move the last bits of J.
       */
      for( i = 0; i < (int)outNBElement; i += 1 ) {
         sc_outJ[i] = 3.0 * sc_outK[i] - 2.0 * sc_outD[i];
      }
      /* Capture the live producer state + sub handles. */
      if( outNBElement < 1 ) {
         return RetCode.InsufficientHistory;
      }
      sp.optInFastK_Period = optInFastK_Period;
      sp.optInSlowK_Period = optInSlowK_Period;
      sp.optInSlowK_MAType = optInSlowK_MAType;
      sp.optInSlowD_Period = optInSlowD_Period;
      sp.optInSlowD_MAType = optInSlowD_MAType;
      sp.sub0 = sub0;
      sp.cur_outK = sc_outK[outNBElement - 1];
      sp.cur_outD = sc_outD[outNBElement - 1];
      sp.cur_outJ = sc_outJ[outNBElement - 1];
      return RetCode.Success;
   }

   /* KdjOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal KdjStream KdjOpenAndFillInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInFastK_Period, int optInSlowK_Period, MAType optInSlowK_MAType, int optInSlowD_Period, MAType optInSlowD_MAType, out int outBegIdx, out int outNBElement, Span<double> outK, Span<double> outD, Span<double> outJ )
   {
      KdjStream sp = new KdjStream(this);
      RetCode retCode = KdjOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInFastK_Period, optInSlowK_Period, optInSlowK_MAType, optInSlowD_Period, optInSlowD_MAType, out outBegIdx, out outNBElement, outK, outD, outJ, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("KDJ", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind KdjOpen (composition seam). */
   internal KdjStream KdjOpenInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInFastK_Period, int optInSlowK_Period, MAType optInSlowK_MAType, int optInSlowD_Period, MAType optInSlowD_MAType )
   {
      KdjStream sp = new KdjStream(this);
      double[] sink_outK = new double[1];
      double[] sink_outD = new double[1];
      double[] sink_outJ = new double[1];
      RetCode retCode = KdjOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInFastK_Period, optInSlowK_Period, optInSlowK_MAType, optInSlowD_Period, optInSlowD_MAType, out int outBegIdx, out int outNBElement, sink_outK, sink_outD, sink_outJ, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("KDJ", "open", retCode);
   }

   /// <summary>Open a live <c>KDJ</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="KdjStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>KDJ</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>KDJ_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>KdjOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInFastK_Period">As in the batch call; see <see cref="KDJ_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowK_Period">As in the batch call; see <see cref="KDJ_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowK_MAType">As in the batch call; see <see cref="KDJ_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowD_Period">As in the batch call; see <see cref="KDJ_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowD_MAType">As in the batch call; see <see cref="KDJ_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>KDJ_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public KdjStream KdjOpen( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInFastK_Period, int optInSlowK_Period, MAType optInSlowK_MAType, int optInSlowD_Period, MAType optInSlowD_MAType )
   {
      if( inHigh.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "KDJ open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "KDJ open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("KDJ open: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TaLibArgumentException("KDJ open: inClose is empty", nameof(inClose), RetCode.BadParam);
      RequireHistoryLength("KDJ", "open", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("KDJ", "open", "inClose", inClose.Length, inHigh.Length);
      return KdjOpenInternal(inHigh, inLow, inClose, 0, optInFastK_Period, optInSlowK_Period, optInSlowK_MAType, optInSlowD_Period, optInSlowD_MAType);
   }

   /// <summary><c>KdjOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>KDJ</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - KDJ_Lookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="KdjStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInFastK_Period">As in the batch call; see <see cref="KDJ_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowK_Period">As in the batch call; see <see cref="KDJ_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowK_MAType">As in the batch call; see <see cref="KDJ_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowD_Period">As in the batch call; see <see cref="KDJ_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowD_MAType">As in the batch call; see <see cref="KDJ_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outK">Raw stochastic smoothed by SlowK_Period MA. Must hold at least
   /// <c>historyLen - KDJ_Lookback(...)</c> values.</param>
   /// <param name="outD">Signal line: K smoothed by SlowD_Period MA. Must hold at least
   /// <c>historyLen - KDJ_Lookback(...)</c> values.</param>
   /// <param name="outJ">Divergence line, three parts K less two parts D. Must hold at least
   /// <c>historyLen - KDJ_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>KDJ_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public KdjStream KdjOpenAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInFastK_Period, int optInSlowK_Period, MAType optInSlowK_MAType, int optInSlowD_Period, MAType optInSlowD_MAType, Span<double> outK, Span<double> outD, Span<double> outJ )
   {
      if( inHigh.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "KDJ openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "KDJ openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("KDJ openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TaLibArgumentException("KDJ openAndFill: inClose is empty", nameof(inClose), RetCode.BadParam);
      int guardOutLen = OpenFillCount("KDJ", "openAndFill", inHigh.Length, KDJ_Lookback(optInFastK_Period, optInSlowK_Period, optInSlowK_MAType, optInSlowD_Period, optInSlowD_MAType));
      RequireHistoryLength("KDJ", "openAndFill", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("KDJ", "openAndFill", "inClose", inClose.Length, inHigh.Length);
      RequireFillLength("KDJ", "openAndFill", "outK", outK.Length, guardOutLen);
      RequireFillLength("KDJ", "openAndFill", "outD", outD.Length, guardOutLen);
      RequireFillLength("KDJ", "openAndFill", "outJ", outJ.Length, guardOutLen);
      if( outK.Overlaps(inHigh) || outK.Overlaps(inLow) || outK.Overlaps(inClose) || outD.Overlaps(inHigh) || outD.Overlaps(inLow) || outD.Overlaps(inClose) || outJ.Overlaps(inHigh) || outJ.Overlaps(inLow) || outJ.Overlaps(inClose) || outK.Overlaps(outD) || outK.Overlaps(outJ) || outD.Overlaps(outJ) ) {
         throw StreamFailure("KDJ", "openAndFill", RetCode.BadParam);
      }
      return KdjOpenAndFillInternal(inHigh, inLow, inClose, 0, optInFastK_Period, optInSlowK_Period, optInSlowK_MAType, optInSlowD_Period, optInSlowD_MAType, out _, out _, outK, outD, outJ);
   }
