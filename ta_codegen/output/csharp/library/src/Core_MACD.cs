   /// <summary>One <c>MACD</c> output set, in batch output order.</summary>
   /// <remarks>
   /// <para>Equality is the compiler-generated record-struct equality, which compares
   /// each component with <see cref="System.Double.Equals(System.Double)"/>, not
   /// <c>==</c>: any two <c>NaN</c> payloads compare equal, and <c>0.0</c>
   /// equals <c>-0.0</c>. Compare
   /// <see cref="System.BitConverter.DoubleToInt64Bits(double)"/> per component
   /// when bit-level identity is what you mean.</para>
   /// </remarks>
   /// <param name="MACD">Fast EMA minus slow EMA.</param>
   /// <param name="MACDSignal">EMA of the MACD line.</param>
   /// <param name="MACDHist">MACD minus signal line.</param>
   public readonly record struct MacdValue( double MACD, double MACDSignal, double MACDHist );

   /// <summary>A live <c>MACD</c> stream: one value per closed bar, bit-identical to
   /// <c>MACD</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.MacdOpen"/>. There is no close and nothing to
   /// dispose — the handle is ordinary managed state, and an unreferenced handle
   /// is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class MacdStream
   {
      internal Core core;
      internal int optInFastPeriod;
      internal int optInSlowPeriod;
      internal int optInSignalPeriod;
      internal double prevFast;
      internal double prevSlow;
      internal double prevSignal;
      internal double slowK;
      internal double fastK;
      internal double signalK;
      internal double slowBeta;
      internal double fastBeta;
      internal double signalBeta;
      internal double cur_outMACD;
      internal double cur_outMACDSignal;
      internal double cur_outMACDHist;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal MacdStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Macd</c> reports over the same bars: the opener sets it
      /// to <c>(lookback, historyLen - lookback)</c>, every accepted <c>Update</c>
      /// adds one to the count — a rejected one changes nothing, and neither does
      /// <c>Peek</c> — and <c>Clone</c> carries it verbatim. A plain <c>Open</c>
      /// hands back only the last value, a subset of this range, because the caller
      /// chose not to take the fill.</para>
      /// <para>The last bar it can reach is <see cref="Core.IndexMax"/>; past that
      /// <c>Update</c> and <c>Advance</c> throw.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      /// <summary>Count one bar this stream was not fed: <see cref="OutRange"/> advances by
      /// one and nothing else moves.</summary>
      /// <remarks>
      /// <para><see cref="Value"/> keeps answering the previous output, which is this
      /// bar's output too. For a bar the caller leaves out: one an <c>Update</c>
      /// rejected and that will not be re-fed, or a session with no print. Without
      /// it two handles on one feed drift a bar apart when only one of them skips.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, the last one the batch tier
      /// can address and the last this handle will count. <c>Update</c> throws the
      /// same there.</para>
      /// </remarks>
      public void Advance()
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("MACD", "advance", RetCode.OutOfRangeEndIndex);
         outRangeCount++;
      }

      internal MacdStream( MacdStream other )
      {
         this.core = other.core;
         this.optInFastPeriod = other.optInFastPeriod;
         this.optInSlowPeriod = other.optInSlowPeriod;
         this.optInSignalPeriod = other.optInSignalPeriod;
         this.prevFast = other.prevFast;
         this.prevSlow = other.prevSlow;
         this.prevSignal = other.prevSignal;
         this.slowK = other.slowK;
         this.fastK = other.fastK;
         this.signalK = other.signalK;
         this.slowBeta = other.slowBeta;
         this.fastBeta = other.fastBeta;
         this.signalBeta = other.signalBeta;
         this.cur_outMACD = other.cur_outMACD;
         this.cur_outMACDSignal = other.cur_outMACDSignal;
         this.cur_outMACDHist = other.cur_outMACDHist;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so nothing moves — <see cref="OutRange"/> included — and
      /// <see cref="Value"/> still answers the previous value. Re-feed the bar when
      /// a corrected value arrives, or call <see cref="Advance"/> to count it and
      /// carry on; two handles on one feed drift a bar apart if neither happens.
      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, which no re-feed clears: the
      /// handle has run out of index domain and only a shorter history can start a
      /// new one.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value at the bar just committed.</returns>
      public MacdValue Update( double inReal )
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("MACD", "update", RetCode.OutOfRangeEndIndex);
         if( !double.IsFinite(inReal) ) throw Core.NonFiniteBar("MACD", "update", nameof(inReal));
         core.MacdStepImpl(this, inReal);
         outRangeCount++;
         return new MacdValue(cur_outMACD, cur_outMACDSignal, cur_outMACDHist);
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.IndexMax"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public MacdValue Peek( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.NonFiniteBar("MACD", "peek", nameof(inReal));
         MacdStream sp = this;
         double macdValue = 0.0;
         double tempReal = 0.0;
         double cur_outMACD = 0.0;
         double cur_outMACDHist = 0.0;
         double cur_outMACDSignal = 0.0;
         double prevFast = sp.prevFast;
         double prevSignal = sp.prevSignal;
         double prevSlow = sp.prevSlow;
         tempReal = inReal;
         prevFast = Math.FusedMultiplyAdd(sp.fastBeta, prevFast, sp.fastK * tempReal);
         prevSlow = Math.FusedMultiplyAdd(sp.slowBeta, prevSlow, sp.slowK * tempReal);
         macdValue = prevFast - prevSlow;
         if( sp.optInSignalPeriod == 1 ) {
            prevSignal = macdValue;
         } else {
            prevSignal = Math.FusedMultiplyAdd(sp.signalBeta, prevSignal, sp.signalK * macdValue);
         }
         cur_outMACD = macdValue;
         cur_outMACDSignal = prevSignal;
         cur_outMACDHist = macdValue - prevSignal;
         return new MacdValue(cur_outMACD, cur_outMACDSignal, cur_outMACDHist);
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public MacdValue Value => new MacdValue(cur_outMACD, cur_outMACDSignal, cur_outMACDHist);

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public MacdStream Clone()
      {
         return new MacdStream(this);
      }
   }

   private void MacdStepImpl( MacdStream sp, double inReal )
   {
      double macdValue = 0.0;
      double tempReal = 0.0;
      tempReal = inReal;
      sp.prevFast = Math.FusedMultiplyAdd(sp.fastBeta, sp.prevFast, sp.fastK * tempReal);
      sp.prevSlow = Math.FusedMultiplyAdd(sp.slowBeta, sp.prevSlow, sp.slowK * tempReal);
      macdValue = sp.prevFast - sp.prevSlow;
      if( sp.optInSignalPeriod == 1 ) {
         sp.prevSignal = macdValue;
      } else {
         sp.prevSignal = Math.FusedMultiplyAdd(sp.signalBeta, sp.prevSignal, sp.signalK * macdValue);
      }
      sp.cur_outMACD = macdValue;
      sp.cur_outMACDSignal = sp.prevSignal;
      sp.cur_outMACDHist = macdValue - sp.prevSignal;
   }

   private RetCode MacdOpenImpl( MacdStream sp, ReadOnlySpan<double> inReal, int startIdx, int optInFastPeriod, int optInSlowPeriod, int optInSignalPeriod, out int outBegIdx, out int outNBElement, Span<double> outMACD, Span<double> outMACDSignal, Span<double> outMACDHist, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double prevFast = 0;
      double prevSlow = 0;
      double prevSignal = 0;
      double macdValue = 0;
      double tempReal = 0;
      double slowK = 0;
      double fastK = 0;
      double signalK = 0;
      double slowBeta = 0;
      double fastBeta = 0;
      double signalBeta = 0;
      int i = 0;
      int today = 0;
      int outIdx = 0;
      int tempInteger = 0;
      int lookbackTotal = 0;
      int lookbackSignal = 0;
      int lookbackSlow = 0;
      int fastToday = 0;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > IndexMax + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInFastPeriod == int.MinValue ) {
         optInFastPeriod = 12;
      } else if( optInFastPeriod < 2 || optInFastPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInSlowPeriod == int.MinValue ) {
         optInSlowPeriod = 26;
      } else if( optInSlowPeriod < 2 || optInSlowPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInSignalPeriod == int.MinValue ) {
         optInSignalPeriod = 9;
      } else if( optInSignalPeriod < 1 || optInSignalPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      /* Make sure slow is really slower than
       * the fast period! if not, swap...
       */
      if( optInSlowPeriod < optInFastPeriod ) {
         /* swap */
         tempInteger = optInSlowPeriod;
         optInSlowPeriod = optInFastPeriod;
         optInFastPeriod = tempInteger;
      }
      /* The fixed 26/12 MACD: k of 0.075 and 0.15, as near as a pair summing
       * to exactly 1.0 comes.
       */
      if( optInSlowPeriod == 0 ) {
         /* Fix 26 */
         optInSlowPeriod = 26;
         slowBeta = 1.0 - 0.075;
      } else {
         slowBeta = (double)(optInSlowPeriod - 1) / (double)(optInSlowPeriod + 1);
      }
      slowK = 1.0 - slowBeta;
      slowBeta = 1.0 - slowK;
      if( optInFastPeriod == 0 ) {
         /* Fix 12 */
         optInFastPeriod = 12;
         fastBeta = 1.0 - 0.15;
      } else {
         fastBeta = (double)(optInFastPeriod - 1) / (double)(optInFastPeriod + 1);
      }
      fastK = 1.0 - fastBeta;
      fastBeta = 1.0 - fastK;
      /* A signal period of 1 disables signal-line smoothing: the signal IS the
       * MACD line and the histogram is exactly zero. The recursion
       * below, at a k of 1.0 and a beta of 0.0, does not keep the sign of a
       * -0.0 line value; hence the explicit arm at each step.
       */
      signalBeta = (double)(optInSignalPeriod - 1) / (double)(optInSignalPeriod + 1);
      signalK = 1.0 - signalBeta;
      signalBeta = 1.0 - signalK;
      lookbackSignal = EmaLookback(optInSignalPeriod);
      /* Move up the start index if there is not
       * enough initial data.
       */
      lookbackSlow = EmaLookback(optInSlowPeriod);
      lookbackTotal = lookbackSignal + lookbackSlow;
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      /* Everything is computed in a single lockstep pass: each bar
       * advances the fast and slow EMA (two independent recursions),
       * their difference is the MACD line, and each MACD-line value
       * is immediately fed into the signal EMA. No temporary buffers.
       *
       * The arithmetic order below is the bit-exactness contract
       * (do not reorder or fuse operations):
       *  - EMA recursion: k*x + beta*prev, with ema.c's k and beta.
       *  - Each EMA is seeded with the sum of its first 'period'
       *    inputs, accumulated from 0.0 in input order, divided by
       *    the period. The signal EMA is seeded the same way from the
       *    first 'signal period' MACD-line values.
       *
       * In-place (an output == inReal) is supported: outputs at
       * [outIdx] are written only after inReal[startIdx+outIdx] was
       * read.
       */
      /* Seed each price EMA with a simple average of its first
       * 'period' price bars, each window placed by that EMA's own
       * lookback, so that the line is TA_EMA(fast) - TA_EMA(slow) bit
       * for bit. The slow EMA then runs alone to the end of the fast
       * window.
       *
       * ema_lookback(n) - n must never decrease as n grows: a fast
       * window ending before the slow one would skip bars of the fast
       * EMA, and one starting before it would read below the lookback.
       */
      today = startIdx - lookbackTotal;
      tempReal = 0.0;
      i = optInSlowPeriod;
      while( i-- > 0 ) {
         tempReal += inReal[today++];
      }
      prevSlow = tempReal / optInSlowPeriod;
      fastToday = startIdx - lookbackTotal + (lookbackSlow - EmaLookback(optInFastPeriod));
      prevFast = 0.0;
      i = optInFastPeriod;
      while( i-- > 0 ) {
         prevFast += inReal[fastToday++];
      }
      prevFast = prevFast / optInFastPeriod;
      while( today < fastToday ) {
         tempReal = inReal[today++];
         prevSlow = Math.FusedMultiplyAdd(slowBeta, prevSlow, slowK * tempReal);
      }
      /* Advance both EMA through their unstable period, up to the
       * first MACD-line bar.
       */
      while( today <= startIdx - lookbackSignal ) {
         tempReal = inReal[today++];
         prevFast = Math.FusedMultiplyAdd(fastBeta, prevFast, fastK * tempReal);
         prevSlow = Math.FusedMultiplyAdd(slowBeta, prevSlow, slowK * tempReal);
      }
      macdValue = prevFast - prevSlow;
      /* Seed the signal EMA with a simple average of the first
       * 'signal period' MACD-line values, accumulated as they are
       * produced.
       */
      prevSignal = 0.0;
      prevSignal += macdValue;
      i = optInSignalPeriod - 1;
      while( i-- > 0 ) {
         tempReal = inReal[today++];
         prevFast = Math.FusedMultiplyAdd(fastBeta, prevFast, fastK * tempReal);
         prevSlow = Math.FusedMultiplyAdd(slowBeta, prevSlow, slowK * tempReal);
         macdValue = prevFast - prevSlow;
         prevSignal += macdValue;
      }
      prevSignal = prevSignal / optInSignalPeriod;
      /* Advance everything in lockstep through the unstable period
       * of the signal EMA, up to the first output bar.
       */
      while( today <= startIdx ) {
         tempReal = inReal[today++];
         prevFast = Math.FusedMultiplyAdd(fastBeta, prevFast, fastK * tempReal);
         prevSlow = Math.FusedMultiplyAdd(slowBeta, prevSlow, slowK * tempReal);
         macdValue = prevFast - prevSlow;
         if( optInSignalPeriod == 1 ) {
            prevSignal = macdValue;
         } else {
            prevSignal = Math.FusedMultiplyAdd(signalBeta, prevSignal, signalK * macdValue);
         }
      }
      /* Stable zone: keep advancing in lockstep and write the three
       * outputs.
       */
      outMACD[0 * outStride] = macdValue;
      outMACDSignal[0 * outStride] = prevSignal;
      outMACDHist[0 * outStride] = macdValue - prevSignal;
      outIdx = 1;
      while( today <= endIdx ) {
         tempReal = inReal[today++];
         prevFast = Math.FusedMultiplyAdd(fastBeta, prevFast, fastK * tempReal);
         prevSlow = Math.FusedMultiplyAdd(slowBeta, prevSlow, slowK * tempReal);
         macdValue = prevFast - prevSlow;
         if( optInSignalPeriod == 1 ) {
            prevSignal = macdValue;
         } else {
            prevSignal = Math.FusedMultiplyAdd(signalBeta, prevSignal, signalK * macdValue);
         }
         outMACD[outIdx * outStride] = macdValue;
         outMACDSignal[outIdx * outStride] = prevSignal;
         outMACDHist[outIdx * outStride] = macdValue - prevSignal;
         outIdx += 1;
      }
      /* All done! Indicate the output limits and return success. */
      outBegIdx = startIdx;
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      sp.optInFastPeriod = optInFastPeriod;
      sp.optInSlowPeriod = optInSlowPeriod;
      sp.optInSignalPeriod = optInSignalPeriod;
      sp.prevFast = prevFast;
      sp.prevSlow = prevSlow;
      sp.prevSignal = prevSignal;
      sp.slowK = slowK;
      sp.fastK = fastK;
      sp.signalK = signalK;
      sp.slowBeta = slowBeta;
      sp.fastBeta = fastBeta;
      sp.signalBeta = signalBeta;
      sp.cur_outMACD = outMACD[(outNBElement - 1) * outStride];
      sp.cur_outMACDSignal = outMACDSignal[(outNBElement - 1) * outStride];
      sp.cur_outMACDHist = outMACDHist[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* MacdOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal MacdStream MacdOpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, int optInFastPeriod, int optInSlowPeriod, int optInSignalPeriod, out int outBegIdx, out int outNBElement, Span<double> outMACD, Span<double> outMACDSignal, Span<double> outMACDHist )
   {
      MacdStream sp = new MacdStream(this);
      RetCode retCode = MacdOpenImpl(sp, inReal, startIdx, optInFastPeriod, optInSlowPeriod, optInSignalPeriod, out outBegIdx, out outNBElement, outMACD, outMACDSignal, outMACDHist, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("MACD", "openAndFill", nameof(inReal), inReal.Length, startIdx, MacdLookback(optInFastPeriod, optInSlowPeriod, optInSignalPeriod));
      }
      throw StreamFailure("MACD", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind MacdOpen (composition seam). */
   internal MacdStream MacdOpenInternal( ReadOnlySpan<double> inReal, int startIdx, int optInFastPeriod, int optInSlowPeriod, int optInSignalPeriod )
   {
      MacdStream sp = new MacdStream(this);
      double[] sink_outMACD = new double[1];
      double[] sink_outMACDSignal = new double[1];
      double[] sink_outMACDHist = new double[1];
      RetCode retCode = MacdOpenImpl(sp, inReal, startIdx, optInFastPeriod, optInSlowPeriod, optInSignalPeriod, out int outBegIdx, out int outNBElement, sink_outMACD, sink_outMACDSignal, sink_outMACDHist, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("MACD", "open", nameof(inReal), inReal.Length, startIdx, MacdLookback(optInFastPeriod, optInSlowPeriod, optInSignalPeriod));
      }
      throw StreamFailure("MACD", "open", retCode);
   }

   /// <summary>Open a live <c>MACD</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="MacdStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>MACD</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>MacdLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>MacdOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">Input series (typically close) The warm-up history, oldest bar first.</param>
   /// <param name="optInFastPeriod">As in the batch call; see <see cref="MacdLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowPeriod">As in the batch call; see <see cref="MacdLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSignalPeriod">As in the batch call; see <see cref="MacdLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>MacdLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public MacdStream MacdOpen( ReadOnlySpan<double> inReal, int optInFastPeriod, int optInSlowPeriod, int optInSignalPeriod )
   {
      if( inReal.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "MACD open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "MACD open: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      return MacdOpenInternal(inReal, 0, optInFastPeriod, optInSlowPeriod, optInSignalPeriod);
   }

   /// <summary><c>MacdOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>MACD</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - MacdLookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="MacdStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">Input series (typically close) The warm-up history, oldest bar first.</param>
   /// <param name="optInFastPeriod">As in the batch call; see <see cref="MacdLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowPeriod">As in the batch call; see <see cref="MacdLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSignalPeriod">As in the batch call; see <see cref="MacdLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outMACD">Fast EMA minus slow EMA. Must hold at least <c>historyLen -
   /// MacdLookback(...)</c> values.</param>
   /// <param name="outMACDSignal">EMA of the MACD line. Must hold at least <c>historyLen -
   /// MacdLookback(...)</c> values.</param>
   /// <param name="outMACDHist">MACD minus signal line. Must hold at least <c>historyLen -
   /// MacdLookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>MacdLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public MacdStream MacdOpenAndFill( ReadOnlySpan<double> inReal, int optInFastPeriod, int optInSlowPeriod, int optInSignalPeriod, Span<double> outMACD, Span<double> outMACDSignal, Span<double> outMACDHist )
   {
      if( inReal.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "MACD openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "MACD openAndFill: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      int guardOutLen = OpenFillCount("MACD", "openAndFill", inReal.Length, MacdLookback(optInFastPeriod, optInSlowPeriod, optInSignalPeriod));
      RequireFillLength("MACD", "openAndFill", "outMACD", outMACD.Length, guardOutLen);
      RequireFillLength("MACD", "openAndFill", "outMACDSignal", outMACDSignal.Length, guardOutLen);
      RequireFillLength("MACD", "openAndFill", "outMACDHist", outMACDHist.Length, guardOutLen);
      if( SameBuffer(outMACD, inReal) || SameBuffer(outMACDSignal, inReal) || SameBuffer(outMACDHist, inReal) || SameBuffer(outMACD, outMACDSignal) || SameBuffer(outMACD, outMACDHist) || SameBuffer(outMACDSignal, outMACDHist) ) {
         throw StreamFailure("MACD", "openAndFill", RetCode.BadParam);
      }
      if( guardOutLen > 0 && ( outMACD.Overlaps(inReal) || outMACDSignal.Overlaps(inReal) || outMACDHist.Overlaps(inReal) || OutputsAlias(outMACD, outMACDSignal) || OutputsAlias(outMACD, outMACDHist) || OutputsAlias(outMACDSignal, outMACDHist) ) ) {
         throw StreamFailure("MACD", "openAndFill", RetCode.BadParam);
      }
      return MacdOpenAndFillInternal(inReal, 0, optInFastPeriod, optInSlowPeriod, optInSignalPeriod, out _, out _, outMACD, outMACDSignal, outMACDHist);
   }
