   /// <summary>A live <c>COPPOCK</c> stream: one value per closed bar, bit-identical to
   /// <c>COPPOCK</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.CoppockOpen"/>. There is no close and nothing to
   /// dispose — the handle is ordinary managed state, and an unreferenced handle
   /// is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class CoppockStream
   {
      internal Core core;
      internal int optInWMAPeriod;
      internal int optInROC1Period;
      internal int optInROC2Period;
      internal int ringSize;
      internal int barsSinceReseed;
      internal double periodSum;
      internal double periodSub;
      internal double trailingValue;
      internal double divider;
      internal int sRing_Idx;
      internal int maxIdx_sRing;
      internal int ringPos_roc1Idx;
      internal int ringCap_roc1Idx;
      internal double[] ring_roc1Idx_inReal = [];
      internal int ringPos_roc2Idx;
      internal int ringCap_roc2Idx;
      internal double[] ring_roc2Idx_inReal = [];
      internal int cbSize_sRing;
      internal double[] cb_sRing = [];
      internal double cur_outReal;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal CoppockStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Coppock</c> reports over the same bars: the opener sets
      /// it to <c>(lookback, historyLen - lookback)</c>, every <c>Update</c> adds
      /// one to the count — a non-finite bar is rejected but still counted, because
      /// the bar happened — <c>Peek</c> leaves it alone, and <c>Clone</c> carries
      /// it verbatim. A plain <c>Open</c> hands back only the last value, a subset
      /// of this range, because the caller chose not to take the fill.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      internal CoppockStream( CoppockStream other )
      {
         this.core = other.core;
         this.optInWMAPeriod = other.optInWMAPeriod;
         this.optInROC1Period = other.optInROC1Period;
         this.optInROC2Period = other.optInROC2Period;
         this.ringSize = other.ringSize;
         this.barsSinceReseed = other.barsSinceReseed;
         this.periodSum = other.periodSum;
         this.periodSub = other.periodSub;
         this.trailingValue = other.trailingValue;
         this.divider = other.divider;
         this.sRing_Idx = other.sRing_Idx;
         this.maxIdx_sRing = other.maxIdx_sRing;
         this.ringPos_roc1Idx = other.ringPos_roc1Idx;
         this.ringCap_roc1Idx = other.ringCap_roc1Idx;
         this.ring_roc1Idx_inReal = new double[other.ring_roc1Idx_inReal.Length];
         Array.Copy( other.ring_roc1Idx_inReal, this.ring_roc1Idx_inReal, other.ring_roc1Idx_inReal.Length );
         this.ringPos_roc2Idx = other.ringPos_roc2Idx;
         this.ringCap_roc2Idx = other.ringCap_roc2Idx;
         this.ring_roc2Idx_inReal = new double[other.ring_roc2Idx_inReal.Length];
         Array.Copy( other.ring_roc2Idx_inReal, this.ring_roc2Idx_inReal, other.ring_roc2Idx_inReal.Length );
         this.cbSize_sRing = other.cbSize_sRing;
         this.cb_sRing = new double[other.cb_sRing.Length];
         Array.Copy( other.cb_sRing, this.cb_sRing, other.cb_sRing.Length );
         this.cur_outReal = other.cur_outReal;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Allocates nothing — neither handle state nor a return value.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so no state moves, <see cref="Value"/> still answers the previous value,
      /// and the stream stays usable — just carry on with the next bar.
      /// <see cref="OutRange"/> does advance: the bar happened, so it is counted,
      /// which keeps two handles fed the same series positionally aligned when only
      /// one of them rejects a bar. This is the one place the streaming tier is
      /// stricter than the batch API, which computes on whatever it is given: a
      /// handle retains its state, so a single non-finite bar would poison every
      /// later value it produces.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inReal )
      {
         if( !double.IsFinite(inReal) )
         {
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
            throw Core.StreamFailure("COPPOCK", "update", RetCode.BadParam);
         }
         core.CoppockStepImpl(this, inReal);
         if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It copies nothing: the frame runs against this handle, reading its buffers
      /// and holding what the step would commit in locals. The cost does not grow
      /// with the period, and <c>Peek</c> never allocates.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>What <see cref="Update"/> would return for this bar.</returns>
      public double Peek( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.StreamFailure("COPPOCK", "peek", RetCode.BadParam);
         CoppockStream sp = this;
         int q = 0;
         int rw = 0;
         int ringWalk = 0;
         double tempReal = 0.0;
         double tempReal2 = 0.0;
         double base1 = 0.0;
         double base2 = 0.0;
         double roc1 = 0.0;
         double roc2 = 0.0;
         int barsSinceReseed = sp.barsSinceReseed;
         double cur_outReal = 0.0;
         double periodSub = sp.periodSub;
         double periodSum = sp.periodSum;
         int sRing_Idx = sp.sRing_Idx;
         double trailingValue = sp.trailingValue;
         int pkSlot0 = -1;
         double pkVal0 = 0.0;
         int pkSlot1 = -1;
         double pkVal1 = 0.0;
         if( sp.ringCap_roc1Idx == 0 ) {
            pkSlot0 = 0;
            pkVal0 = inReal;
         }
         if( sp.ringCap_roc2Idx == 0 ) {
            pkSlot1 = 0;
            pkVal1 = inReal;
         }
         base1 = (sp.ringPos_roc1Idx != pkSlot0) ? sp.ring_roc1Idx_inReal[sp.ringPos_roc1Idx] : pkVal0;
         base2 = (sp.ringPos_roc2Idx != pkSlot1) ? sp.ring_roc2Idx_inReal[sp.ringPos_roc2Idx] : pkVal1;
         roc1 = (base1 != 0.0) ? (inReal / base1 - 1.0) * 100.0 : 0.0;
         roc2 = (base2 != 0.0) ? (inReal / base2 - 1.0) * 100.0 : 0.0;
         tempReal = roc1 + roc2;
         periodSub += tempReal;
         periodSub -= trailingValue;
         periodSum += tempReal * sp.optInWMAPeriod;
         /* Re-anchor every 8*w bars: rebuild both totals from the window
          * itself -- TA_WMA's #254 fix, same single trigger, same interval.
          * The window lives in the ring (w-1 prior S values, sRing_Idx the
          * oldest) plus the current bar's tempReal at weight w.
          */
         barsSinceReseed -= 1;
         if( barsSinceReseed <= 0 ) {
            barsSinceReseed = 8 * sp.optInWMAPeriod;
            periodSub = (double)0.0;
            periodSum = (double)0.0;
            rw = 1;
            ringWalk = sRing_Idx;
            for( q = 0; q < sp.ringSize; q += 1 ) {
               tempReal2 = sp.cb_sRing[ringWalk];
               periodSub += tempReal2;
               periodSum += tempReal2 * rw;
               rw += 1;
               ringWalk += 1;
               if( ringWalk >= sp.ringSize ) {
                  ringWalk = 0;
               }
            }
            periodSub += tempReal;
            periodSum += tempReal * sp.optInWMAPeriod;
         }
         /* Read the expiring S value BEFORE overwriting its slot with the
          * current one -- the ring is the aliasing-safe stand-in for TA_WMA's
          * "save the trailing value before the store" rule.
          */
         trailingValue = sp.cb_sRing[sRing_Idx];
         sRing_Idx = sRing_Idx + 1;
         if( sRing_Idx > sp.maxIdx_sRing ) {
            sRing_Idx = 0;
         }
         /* Load-bearing, not a rounding nicety: keep it. WMA(1) is the identity
          * and TA_WMA ships an exact copy fast path, but the recurrence here is
          * off by a whole term at w == 1 -- ringSize clamps to 1, so the
          * read-before-write ring hands back the wrong trailing value. Deleting
          * this arm moves TA_SREF bar 16 at (1,11,14) from -11.311839169954585
          * to -6.4591709868291103.
          */
         if( sp.optInWMAPeriod == 1 ) {
            cur_outReal = tempReal;
         } else {
            cur_outReal = periodSum / sp.divider;
         }
         return cur_outReal;
      }

      /// <summary>Commit <c>n</c> closed bars and write their <c>n</c> values, in one call.</summary>
      /// <remarks>
      /// <para>Exactly <c>n</c> back-to-back <see cref="Update"/> calls, with one set of
      /// argument checks instead of <c>n</c>. The outputs must hold at least
      /// <c>n</c> values and must not overlap an input or each other.</para>
      /// <para><see cref="OutRange"/> counts what this call took in, which is what makes
      /// a rejection readable: a non-finite bar <c>k</c> throws
      /// <see cref="System.ArgumentException"/> exactly as <see cref="Update"/>
      /// would, with the bars before <c>k</c> committed and written, bar <c>k</c>
      /// and everything after it not written, and the count advanced by <c>k +
      /// 1</c> — the committed bars plus the rejected one, so the last bar counted
      /// is the one that failed.</para>
      /// </remarks>
      /// <param name="inReal">Closed bars for <c>inReal</c>, oldest first.</param>
      /// <param name="outReal">Receives one <c>outReal</c> value per bar committed.</param>
      public void UpdateAndFill( ReadOnlySpan<double> inReal, Span<double> outReal )
      {
         int barCount = inReal.Length;
         if( outReal.Length < barCount || outReal.Overlaps(inReal) ) throw Core.StreamFailure("COPPOCK", "updateAndFill", RetCode.BadParam);
         for( int i = 0; i < barCount; i++ )
         {
            if( !double.IsFinite(inReal[i]) )
            {
               if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
               throw Core.StreamFailure("COPPOCK", "updateAndFill", RetCode.BadParam);
            }
            core.CoppockStepImpl(this, inReal[i]);
            outReal[i] = cur_outReal;
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         }
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public CoppockStream Clone()
      {
         return new CoppockStream(this);
      }
   }

   internal void CoppockStepImpl( CoppockStream sp, double inReal )
   {
      int q = 0;
      int rw = 0;
      int ringWalk = 0;
      double tempReal = 0.0;
      double tempReal2 = 0.0;
      double base1 = 0.0;
      double base2 = 0.0;
      double roc1 = 0.0;
      double roc2 = 0.0;
      if( sp.ringCap_roc1Idx == 0 ) {
         sp.ring_roc1Idx_inReal[0] = inReal;
      }
      if( sp.ringCap_roc2Idx == 0 ) {
         sp.ring_roc2Idx_inReal[0] = inReal;
      }
      base1 = sp.ring_roc1Idx_inReal[sp.ringPos_roc1Idx];
      base2 = sp.ring_roc2Idx_inReal[sp.ringPos_roc2Idx];
      roc1 = (base1 != 0.0) ? (inReal / base1 - 1.0) * 100.0 : 0.0;
      roc2 = (base2 != 0.0) ? (inReal / base2 - 1.0) * 100.0 : 0.0;
      tempReal = roc1 + roc2;
      sp.periodSub += tempReal;
      sp.periodSub -= sp.trailingValue;
      sp.periodSum += tempReal * sp.optInWMAPeriod;
      /* Re-anchor every 8*w bars: rebuild both totals from the window
       * itself -- TA_WMA's #254 fix, same single trigger, same interval.
       * The window lives in the ring (w-1 prior S values, sRing_Idx the
       * oldest) plus the current bar's tempReal at weight w.
       */
      sp.barsSinceReseed -= 1;
      if( sp.barsSinceReseed <= 0 ) {
         sp.barsSinceReseed = 8 * sp.optInWMAPeriod;
         sp.periodSub = (double)0.0;
         sp.periodSum = (double)0.0;
         rw = 1;
         ringWalk = sp.sRing_Idx;
         for( q = 0; q < sp.ringSize; q += 1 ) {
            tempReal2 = sp.cb_sRing[ringWalk];
            sp.periodSub += tempReal2;
            sp.periodSum += tempReal2 * rw;
            rw += 1;
            ringWalk += 1;
            if( ringWalk >= sp.ringSize ) {
               ringWalk = 0;
            }
         }
         sp.periodSub += tempReal;
         sp.periodSum += tempReal * sp.optInWMAPeriod;
      }
      /* Read the expiring S value BEFORE overwriting its slot with the
       * current one -- the ring is the aliasing-safe stand-in for TA_WMA's
       * "save the trailing value before the store" rule.
       */
      sp.trailingValue = sp.cb_sRing[sp.sRing_Idx];
      sp.cb_sRing[sp.sRing_Idx] = tempReal;
      sp.sRing_Idx = sp.sRing_Idx + 1;
      if( sp.sRing_Idx > sp.maxIdx_sRing ) {
         sp.sRing_Idx = 0;
      }
      /* Load-bearing, not a rounding nicety: keep it. WMA(1) is the identity
       * and TA_WMA ships an exact copy fast path, but the recurrence here is
       * off by a whole term at w == 1 -- ringSize clamps to 1, so the
       * read-before-write ring hands back the wrong trailing value. Deleting
       * this arm moves TA_SREF bar 16 at (1,11,14) from -11.311839169954585
       * to -6.4591709868291103.
       */
      if( sp.optInWMAPeriod == 1 ) {
         sp.cur_outReal = tempReal;
      } else {
         sp.cur_outReal = sp.periodSum / sp.divider;
      }
      sp.periodSum -= sp.periodSub;
      sp.ring_roc1Idx_inReal[sp.ringPos_roc1Idx] = inReal;
      sp.ringPos_roc1Idx = sp.ringPos_roc1Idx + 1;
      if( sp.ringPos_roc1Idx >= sp.ringCap_roc1Idx ) {
         sp.ringPos_roc1Idx = 0;
      }
      sp.ring_roc2Idx_inReal[sp.ringPos_roc2Idx] = inReal;
      sp.ringPos_roc2Idx = sp.ringPos_roc2Idx + 1;
      if( sp.ringPos_roc2Idx >= sp.ringCap_roc2Idx ) {
         sp.ringPos_roc2Idx = 0;
      }
   }

   private RetCode CoppockOpenImpl( CoppockStream sp, ReadOnlySpan<double> inReal, int startIdx, int optInWMAPeriod, int optInROC1Period, int optInROC2Period, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      int outIdx = 0;
      int inIdx = 0;
      int lookbackTotal = 0;
      int i = 0;
      int q = 0;
      int rw = 0;
      int ringWalk = 0;
      int ringSize = 0;
      int barsSinceReseed = 0;
      int roc1Idx = 0;
      int roc2Idx = 0;
      double periodSum = 0;
      double periodSub = 0;
      double tempReal = 0;
      double tempReal2 = 0;
      double trailingValue = 0;
      double divider = 0;
      double base1 = 0;
      double base2 = 0;
      double roc1 = 0;
      double roc2 = 0;
      double[] sRing = [];
      int sRing_Idx = 0;
      int maxIdx_sRing = (50)-1;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInWMAPeriod == int.MinValue ) {
         optInWMAPeriod = 10;
      } else if( optInWMAPeriod < 1 || optInWMAPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInROC1Period == int.MinValue ) {
         optInROC1Period = 11;
      } else if( optInROC1Period < 1 || optInROC1Period > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInROC2Period == int.MinValue ) {
         optInROC2Period = 14;
      } else if( optInROC2Period < 1 || optInROC2Period > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      /* Coppock Curve: a WMA(optInWMAPeriod) of the SUM of two rates of change,
       * ROC(optInROC1Period) + ROC(optInROC2Period). The sum, not the mean:
       * every published definition sums them; Tulip's beta/copp.c averages and
       * therefore reads at exactly half this amplitude. A clean 2.000000x ratio
       * against Tulip is Tulip's variant, not a defect here (issue #362).
       *
       * The smoothed series is the inline expression
       *    S(j) = R(j,p1) + R(j,p2)
       *    R(j,p) = (inReal[j-p] != 0.0) ? ((inReal[j]/inReal[j-p])-1.0)*100.0
       *                                  : 0.0
       * -- TA_ROC's own zero guard included, so a zero price yields 0.0 exactly
       * where TA_ROC yields 0.0, never an inf that pollutes the window. Each
       * lagged denominator goes through its own trailing cursor advanced in
       * lock-step (TA_ROC's own shape) -- a parameter-sized lag subscript is
       * outside the stream classifier's index grammar.
       *
       * The WMA stage reproduces TA_WMA's recurrence verbatim -- the triangle
       * divider computed in double (#142), the periodSum/periodSub carry and the
       * 8*w re-anchor (#254) -- because anything short of verbatim breaks the
       * bit-exact composite differential against TA_ROC + TA_ROC + TA_WMA. S is
       * a DERIVED series that is never materialised, so, exactly as in TA_HMA's
       * outer stage, each S value is computed once and carried in a
       * (optInWMAPeriod-1)-slot ring: the trailing subtraction reads the
       * expiring slot and the re-anchor walks the ring, oldest first, weight
       * counting up from 1, then adds the current bar at weight w.
       */
      lookbackTotal = COPPOCK_Lookback(optInWMAPeriod, optInROC1Period, optInROC2Period);
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      /* Triangle divider in double: the int product w*(w+1) overflows int32 at
       * w >= 46341 (#142), exactly as in TA_WMA.
       */
      divider = (double)optInWMAPeriod * (optInWMAPeriod + 1) / 2.0;
      outIdx = 0;
      /* The S value computed at bar t expires optInWMAPeriod-1 bars later, so a
       * single-cursor ring of optInWMAPeriod-1 slots is enough: read the
       * expiring value, overwrite the slot, advance. At w == 1 the recurrence's
       * state is never consumed (see the identity output below), but the ring
       * still needs one slot for the reads to stay in bounds.
       */
      ringSize = optInWMAPeriod - 1;
      if( ringSize < 1 ) {
         ringSize = 1;
      }
      if( ringSize < 1 ) return RetCode.InternalError;
      sRing = new double[ringSize];
      maxIdx_sRing = (ringSize)-1;
      sRing_Idx = 0;
      /* At w == 1 the priming loop below never runs, so the first trailing read
       * would see an undefined slot; at w > 1 priming overwrites every slot.
       */
      sRing[0] = 0.0;
      /* One trailing cursor per ROC denominator, advanced in lock-step from the
       * priming scan onward.
       */
      inIdx = startIdx - (optInWMAPeriod - 1);
      roc1Idx = inIdx - optInROC1Period;
      roc2Idx = inIdx - optInROC2Period;
      /* Priming: the w-1 S values before the first output, oldest first with
       * the weight counting up from 1 -- TA_WMA's own priming order, which the
       * re-anchor below must reproduce. They also fill the ring.
       */
      periodSub = (double)0.0;
      periodSum = periodSub;
      i = 1;
      while( inIdx < startIdx ) {
         base1 = inReal[roc1Idx];
         roc1Idx += 1;
         base2 = inReal[roc2Idx];
         roc2Idx += 1;
         roc1 = (base1 != 0.0) ? (inReal[inIdx] / base1 - 1.0) * 100.0 : 0.0;
         roc2 = (base2 != 0.0) ? (inReal[inIdx] / base2 - 1.0) * 100.0 : 0.0;
         tempReal = roc1 + roc2;
         periodSub += tempReal;
         periodSum += tempReal * i;
         i += 1;
         sRing[sRing_Idx] = tempReal;
         sRing_Idx++;
         if( sRing_Idx > maxIdx_sRing ) { sRing_Idx = 0; }
         inIdx += 1;
      }
      barsSinceReseed = 8 * optInWMAPeriod;
      trailingValue = 0.0;
      /* Tight loop for the requested range. */
      while( inIdx <= endIdx ) {
         base1 = inReal[roc1Idx];
         roc1Idx += 1;
         base2 = inReal[roc2Idx];
         roc2Idx += 1;
         roc1 = (base1 != 0.0) ? (inReal[inIdx] / base1 - 1.0) * 100.0 : 0.0;
         roc2 = (base2 != 0.0) ? (inReal[inIdx] / base2 - 1.0) * 100.0 : 0.0;
         tempReal = roc1 + roc2;
         periodSub += tempReal;
         periodSub -= trailingValue;
         periodSum += tempReal * optInWMAPeriod;
         /* Re-anchor every 8*w bars: rebuild both totals from the window
          * itself -- TA_WMA's #254 fix, same single trigger, same interval.
          * The window lives in the ring (w-1 prior S values, sRing_Idx the
          * oldest) plus the current bar's tempReal at weight w.
          */
         barsSinceReseed -= 1;
         if( barsSinceReseed <= 0 ) {
            barsSinceReseed = 8 * optInWMAPeriod;
            periodSub = (double)0.0;
            periodSum = (double)0.0;
            rw = 1;
            ringWalk = sRing_Idx;
            for( q = 0; q < ringSize; q += 1 ) {
               tempReal2 = sRing[ringWalk];
               periodSub += tempReal2;
               periodSum += tempReal2 * rw;
               rw += 1;
               ringWalk += 1;
               if( ringWalk >= ringSize ) {
                  ringWalk = 0;
               }
            }
            periodSub += tempReal;
            periodSum += tempReal * optInWMAPeriod;
         }
         /* Read the expiring S value BEFORE overwriting its slot with the
          * current one -- the ring is the aliasing-safe stand-in for TA_WMA's
          * "save the trailing value before the store" rule.
          */
         trailingValue = sRing[sRing_Idx];
         sRing[sRing_Idx] = tempReal;
         sRing_Idx++;
         if( sRing_Idx > maxIdx_sRing ) { sRing_Idx = 0; }
         /* Load-bearing, not a rounding nicety: keep it. WMA(1) is the identity
          * and TA_WMA ships an exact copy fast path, but the recurrence here is
          * off by a whole term at w == 1 -- ringSize clamps to 1, so the
          * read-before-write ring hands back the wrong trailing value. Deleting
          * this arm moves TA_SREF bar 16 at (1,11,14) from -11.311839169954585
          * to -6.4591709868291103.
          */
         if( optInWMAPeriod == 1 ) {
            outReal[outIdx * outStride] = tempReal;
         } else {
            outReal[outIdx * outStride] = periodSum / divider;
         }
         outIdx += 1;
         periodSum -= periodSub;
         inIdx += 1;
      }
      outBegIdx = startIdx;
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      int cap_roc1Idx = inIdx - roc1Idx;
      if( cap_roc1Idx < 0 || cap_roc1Idx > historyLen ) {
         return RetCode.InternalError;
      }
      int allocN_roc1Idx = (cap_roc1Idx > 0)? cap_roc1Idx : 1;
      double[] capRing_roc1Idx_inReal = new double[allocN_roc1Idx];
      inReal.Slice(historyLen - cap_roc1Idx, cap_roc1Idx).CopyTo(capRing_roc1Idx_inReal);
      int cap_roc2Idx = inIdx - roc2Idx;
      if( cap_roc2Idx < 0 || cap_roc2Idx > historyLen ) {
         return RetCode.InternalError;
      }
      int allocN_roc2Idx = (cap_roc2Idx > 0)? cap_roc2Idx : 1;
      double[] capRing_roc2Idx_inReal = new double[allocN_roc2Idx];
      inReal.Slice(historyLen - cap_roc2Idx, cap_roc2Idx).CopyTo(capRing_roc2Idx_inReal);
      int capCb_sRing = maxIdx_sRing + 1;
      if( capCb_sRing > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      sp.optInWMAPeriod = optInWMAPeriod;
      sp.optInROC1Period = optInROC1Period;
      sp.optInROC2Period = optInROC2Period;
      sp.ringSize = ringSize;
      sp.barsSinceReseed = barsSinceReseed;
      sp.periodSum = periodSum;
      sp.periodSub = periodSub;
      sp.trailingValue = trailingValue;
      sp.divider = divider;
      sp.sRing_Idx = sRing_Idx;
      sp.maxIdx_sRing = maxIdx_sRing;
      sp.ringPos_roc1Idx = 0;
      sp.ringCap_roc1Idx = cap_roc1Idx;
      sp.ring_roc1Idx_inReal = capRing_roc1Idx_inReal;
      sp.ringPos_roc2Idx = 0;
      sp.ringCap_roc2Idx = cap_roc2Idx;
      sp.ring_roc2Idx_inReal = capRing_roc2Idx_inReal;
      sp.cbSize_sRing = capCb_sRing;
      sp.cb_sRing = sRing;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* CoppockOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal CoppockStream CoppockOpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, int optInWMAPeriod, int optInROC1Period, int optInROC2Period, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      CoppockStream sp = new CoppockStream(this);
      RetCode retCode = CoppockOpenImpl(sp, inReal, startIdx, optInWMAPeriod, optInROC1Period, optInROC2Period, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("COPPOCK", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind CoppockOpen (composition seam). */
   internal CoppockStream CoppockOpenInternal( ReadOnlySpan<double> inReal, int startIdx, int optInWMAPeriod, int optInROC1Period, int optInROC2Period )
   {
      CoppockStream sp = new CoppockStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = CoppockOpenImpl(sp, inReal, startIdx, optInWMAPeriod, optInROC1Period, optInROC2Period, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("COPPOCK", "open", retCode);
   }

   /// <summary>Open a live <c>COPPOCK</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="CoppockStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>COPPOCK</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>COPPOCK_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>CoppockOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">Source price/value series (canonically a monthly close) The warm-up
   /// history, oldest bar first.</param>
   /// <param name="optInWMAPeriod">As in the batch call; see <see cref="COPPOCK_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInROC1Period">As in the batch call; see <see cref="COPPOCK_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInROC2Period">As in the batch call; see <see cref="COPPOCK_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>COPPOCK_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public CoppockStream CoppockOpen( ReadOnlySpan<double> inReal, int optInWMAPeriod, int optInROC1Period, int optInROC2Period )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "COPPOCK open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "COPPOCK open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      return CoppockOpenInternal(inReal, 0, optInWMAPeriod, optInROC1Period, optInROC2Period);
   }

   /// <summary><c>CoppockOpen</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>COPPOCK</c> produces over
   /// the same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - COPPOCK_Lookback(...)</c> values
   /// and must not alias the inputs or each other — this path writes the outputs
   /// and then reads the input tail to seed its rings, so the batch tier's
   /// in-place allowance does not carry over here. Both are checked before
   /// anything is written, so an undersized span is an <c>ArgumentException</c>
   /// naming it rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="CoppockStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">Source price/value series (canonically a monthly close) The warm-up
   /// history, oldest bar first.</param>
   /// <param name="optInWMAPeriod">As in the batch call; see <see cref="COPPOCK_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInROC1Period">As in the batch call; see <see cref="COPPOCK_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInROC2Period">As in the batch call; see <see cref="COPPOCK_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Coppock Curve value. Must hold at least <c>historyLen -
   /// COPPOCK_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>COPPOCK_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public CoppockStream CoppockOpenAndFill( ReadOnlySpan<double> inReal, int optInWMAPeriod, int optInROC1Period, int optInROC2Period, Span<double> outReal )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "COPPOCK openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "COPPOCK openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      int guardOutLen = OpenFillCount("COPPOCK", "openAndFill", inReal.Length, COPPOCK_Lookback(optInWMAPeriod, optInROC1Period, optInROC2Period));
      RequireFillLength("COPPOCK", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( outReal.Overlaps(inReal) ) {
         throw StreamFailure("COPPOCK", "openAndFill", RetCode.BadParam);
      }
      return CoppockOpenAndFillInternal(inReal, 0, optInWMAPeriod, optInROC1Period, optInROC2Period, out _, out _, outReal);
   }
