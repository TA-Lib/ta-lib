      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It copies nothing: the frame runs against this handle, reading its buffers
      /// and holding what the step would commit in locals. The cost does not grow
      /// with the period, and <c>Peek</c> never allocates.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>What <see cref="Update"/> would return for this bar.</returns>
      public double Peek( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.StreamFailure("RMA", "peek", RetCode.BadParam);
         RmaStream sp = this;
         double cur_outReal = 0.0;
         double prevRMA = sp.prevRMA;
         prevRMA = Math.FusedMultiplyAdd(sp.wBeta, prevRMA, sp.wAlpha * inReal);
         cur_outReal = prevRMA;
         return cur_outReal;
      }

      /// <summary>Commit <c>n</c> closed bars and write their <c>n</c> values, in one call.</summary>
      /// <remarks>
      /// <para>Exactly <c>n</c> back-to-back <see cref="Update"/> calls, with one set of
      /// argument checks instead of <c>n</c>. The outputs must hold at least
      /// <c>n</c> values and must not overlap an input or each other.</para>
      /// <para><see cref="OutRange"/> counts what this call took in, which is what makes
      /// a rejection readable: a non-finite bar <c>k</c> throws
      /// <see cref="System.ArgumentException"/> exactly as <see cref="Update"/>
      /// would, with the bars before <c>k</c> committed and written, bar <c>k</c>
      /// and everything after it not written, and the count advanced by <c>k +
      /// 1</c> — the committed bars plus the rejected one, so the last bar counted
      /// is the one that failed.</para>
      /// </remarks>
      /// <param name="inReal">Closed bars for <c>inReal</c>, oldest first.</param>
      /// <param name="outReal">Receives one <c>outReal</c> value per bar committed.</param>
      public void UpdateAndFill( ReadOnlySpan<double> inReal, Span<double> outReal )
      {
         int barCount = inReal.Length;
         if( outReal.Length < barCount || outReal.Overlaps(inReal) ) throw Core.StreamFailure("RMA", "updateAndFill", RetCode.BadParam);
         for( int i = 0; i < barCount; i++ )
         {
            if( !double.IsFinite(inReal[i]) )
            {
               if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
               throw Core.StreamFailure("RMA", "updateAndFill", RetCode.BadParam);
            }
            core.RmaStepImpl(this, inReal[i]);
            outReal[i] = cur_outReal;
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         }
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public RmaStream Clone()
      {
         return new RmaStream(this);
      }
   }

   internal void RmaStepImpl( RmaStream sp, double inReal )
   {
      sp.prevRMA = Math.FusedMultiplyAdd(sp.wBeta, sp.prevRMA, sp.wAlpha * inReal);
      sp.cur_outReal = sp.prevRMA;
   }

   private RetCode RmaOpenImpl( RmaStream sp, ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      int i = 0;
      int outIdx = 0;
      int today = 0;
      int lookbackTotal = 0;
      int nbRMA = 0;
      double prevRMA = 0;
      double periodTotal = 0;
      double wAlpha = 0;
      double wBeta = 0;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 30;
      } else if( optInTimePeriod < 1 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      outBegIdx = 0;
      outNBElement = 0;
      /* Adjust startIdx to account for the lookback period. */
      lookbackTotal = RMA_Lookback(optInTimePeriod);
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         return RetCode.InsufficientHistory ;
      }
      /* wAlpha is derived FROM wBeta, never the reverse: only that order makes
       * wAlpha + wBeta exactly 1 (Sterbenz -- wBeta lands in [0.5, 1)), and it
       * measures closer to the exact recursion than the 1/period-first spelling
       * at nearly every period. The order is a gated contract, not a preference:
       * TA_RMA(TA_TRANGE(h,l,c),n) must equal TA_ATR(n) bit for bit.
       * The pair is exactly (1, 0) at period 1 -- hence no period-1 arm.
       */
      wBeta = (double)(optInTimePeriod - 1) / (double)optInTimePeriod;
      wAlpha = 1.0 - wBeta;
      /* The arithmetic order is the rest of that contract: the seed accumulates
       * from 0.0 in input order, and the smoothing step stays ONE statement --
       * splitting it unfuses the multiply-add and puts a second latency on the
       * recurrence's dependency chain.
       *
       * In-place (outReal being inReal) is supported: the output index never
       * passes the bar index of any remaining read.
       */
      today = startIdx - lookbackTotal;
      /* Seed with a simple average of the first 'period' values. */
      periodTotal = 0.0;
      i = optInTimePeriod;
      while( i-- > 0 ) {
         periodTotal += inReal[today];
         today += 1;
      }
      prevRMA = periodTotal / optInTimePeriod;
      /* Skip the unstable period. */
      i = this.unstablePeriod[(int)FuncUnstId.RMA];
      while( i != 0 ) {
         prevRMA = Math.FusedMultiplyAdd(wBeta, prevRMA, wAlpha * inReal[today]);
         today += 1;
         i -= 1;
      }
      /* Now start to write the final RMA in the caller
       * provided outReal.
       */
      outIdx = 1;
      outReal[0 * outStride] = prevRMA;
      /* Now do the number of requested RMA. */
      nbRMA = endIdx - startIdx + 1;
      while( --nbRMA != 0 ) {
         prevRMA = Math.FusedMultiplyAdd(wBeta, prevRMA, wAlpha * inReal[today]);
         outReal[outIdx++ * outStride] = prevRMA;
         today += 1;
      }
      outBegIdx = startIdx;
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      sp.optInTimePeriod = optInTimePeriod;
      sp.prevRMA = prevRMA;
      sp.wAlpha = wAlpha;
      sp.wBeta = wBeta;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* RmaOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal RmaStream RmaOpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      RmaStream sp = new RmaStream(this);
      RetCode retCode = RmaOpenImpl(sp, inReal, startIdx, optInTimePeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("RMA", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind RmaOpen (composition seam). */
   internal RmaStream RmaOpenInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod )
   {
      RmaStream sp = new RmaStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = RmaOpenImpl(sp, inReal, startIdx, optInTimePeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("RMA", "open", retCode);
   }

   /// <summary>Open a live <c>RMA</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="RmaStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>RMA</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>RMA_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>RmaOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">Data on which to compute the average. The warm-up history, oldest bar
   /// first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="RMA_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>RMA_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public RmaStream RmaOpen( ReadOnlySpan<double> inReal, int optInTimePeriod )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "RMA open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "RMA open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      return RmaOpenInternal(inReal, 0, optInTimePeriod);
   }

   /// <summary><c>RmaOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>RMA</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - RMA_Lookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="RmaStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">Data on which to compute the average. The warm-up history, oldest bar
   /// first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="RMA_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Wilder's smoothed moving average of the input. Must hold at least
   /// <c>historyLen - RMA_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>RMA_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public RmaStream RmaOpenAndFill( ReadOnlySpan<double> inReal, int optInTimePeriod, Span<double> outReal )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "RMA openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "RMA openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      int guardOutLen = OpenFillCount("RMA", "openAndFill", inReal.Length, RMA_Lookback(optInTimePeriod));
      RequireFillLength("RMA", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( outReal.Overlaps(inReal) ) {
         throw StreamFailure("RMA", "openAndFill", RetCode.BadParam);
      }
      return RmaOpenAndFillInternal(inReal, 0, optInTimePeriod, out _, out _, outReal);
   }
