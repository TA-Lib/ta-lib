   /// </para>
   /// </remarks>
   /// <param name="startIdx">First bar of the requested range (inclusive).</param>
   /// <param name="endIdx">Last bar of the requested range (inclusive).</param>
   /// <param name="inOpen">Open price of each bar.</param>
   /// <param name="inHigh">High price of each bar.</param>
   /// <param name="inLow">Low price of each bar.</param>
   /// <param name="inClose">Close price of each bar.</param>
   /// <param name="outInteger">+100 for three inside up (bullish reversal, first candle black), -100 for
   /// three inside down (bearish reversal, first candle white), 0 when no
   /// pattern. Computed as -candlecolor(1st)*100. Must hold at least <c>endIdx -
   /// startIdx + 1</c> values.</param>
   /// <returns>The range written: <c>BegIdx</c> is the first bar with a value,
   /// <c>Count</c> how many were written.</returns>
   /// <exception cref="System.ArgumentOutOfRangeException"><c>startIdx</c> or <c>endIdx</c> is negative or above
   /// <see cref="Core.MAX_INDEX"/>, or <c>endIdx &lt; startIdx</c>.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or two outputs
   /// share one array.</exception>
   /// <exception cref="System.ArgumentNullException">An input or output array is null.</exception>
   public OutRange CDL3INSIDE( int startIdx,
                               int endIdx,
                               float[] inOpen,
                               float[] inHigh,
                               float[] inLow,
                               float[] inClose,
                               int[] outInteger )
   {
      ArgumentNullException.ThrowIfNull(inOpen);
      ArgumentNullException.ThrowIfNull(inHigh);
      ArgumentNullException.ThrowIfNull(inLow);
      ArgumentNullException.ThrowIfNull(inClose);
      ArgumentNullException.ThrowIfNull(outInteger);
      RetCode retCode = CDL3INSIDE(startIdx, endIdx, inOpen, inHigh, inLow, inClose, out int outBegIdx, out int outNBElement, outInteger);
      if( retCode != RetCode.Success ) {
         throw Failure("CDL3INSIDE", retCode);
      }
      return new OutRange(outBegIdx, outNBElement);
   }
