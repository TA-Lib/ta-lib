         this.ring_trailingIdx_inReal = new double[other.ring_trailingIdx_inReal.Length];
         Array.Copy( other.ring_trailingIdx_inReal, this.ring_trailingIdx_inReal, other.ring_trailingIdx_inReal.Length );
         this.cur_outReal = other.cur_outReal;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Allocates nothing — neither handle state nor a return value.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so nothing moves — <see cref="OutRange"/> included — and
      /// <see cref="Value"/> still answers the previous value. Re-feed the bar when
      /// a corrected value arrives, or call <see cref="Advance"/> to count it and
      /// carry on; two handles on one feed drift a bar apart if neither happens.
      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.StreamFailure("ER", "update", RetCode.BadParam);
         core.ErStepImpl(this, inReal);
         if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It copies nothing: the frame runs against this handle, reading its buffers
      /// and holding what the step would commit in locals. The cost does not grow
      /// with the period, and <c>Peek</c> never allocates.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>What <see cref="Update"/> would return for this bar.</returns>
      public double Peek( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.StreamFailure("ER", "peek", RetCode.BadParam);
         ErStream sp = this;
         double periodROC = 0.0;
         double tempReal = 0.0;
         double tempReal2 = 0.0;
         double cur_outReal = 0.0;
         int nullRun = sp.nullRun;
         double sumROC1 = sp.sumROC1;
         double trailingValue = sp.trailingValue;
         int pkSlot0 = -1;
         double pkVal0 = 0.0;
         if( sp.ringCap_trailingIdx == 0 ) {
            pkSlot0 = 0;
            pkVal0 = inReal;
         }
         tempReal = inReal;
         tempReal2 = (sp.ringPos_trailingIdx != pkSlot0) ? sp.ring_trailingIdx_inReal[sp.ringPos_trailingIdx] : pkVal0;
         periodROC = tempReal - tempReal2;
         /* Subtract-then-add, TA_SUM's own order. */
         sumROC1 -= Math.Abs(trailingValue - tempReal2);
         sumROC1 += Math.Abs(tempReal - sp.lag1_inReal);
         /* Once a whole window of one-bar changes is exactly zero, the sum's
          * only content is rounding residue from the subtract/add carry --
          * purge it so the flat window is recognized exactly (kama.c #253).
          */
         if( tempReal - sp.lag1_inReal == 0.0 ) {
            nullRun += 1;
         } else {
            nullRun = 0;
         }
         if( nullRun >= sp.optInTimePeriod ) {
            nullRun = sp.optInTimePeriod;
            sumROC1 = 0.0;
         }
         /* Save the trailing value: outReal may alias inReal, and the next
          * iteration's subtraction needs the ORIGINAL bar, not the slot the
          * write below may have clobbered.
          */
         trailingValue = tempReal2;
         if( sumROC1 <= 0.0 || sumROC1 <= periodROC ) {
            cur_outReal = 1.0;
         } else {
            tempReal = Math.Abs(periodROC / sumROC1);
            if( tempReal > 1.0 ) {
               tempReal = 1.0;
            }
            cur_outReal = tempReal;
         }
         return cur_outReal;
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public ErStream Clone()
      {
         return new ErStream(this);
      }
   }

   internal void ErStepImpl( ErStream sp, double inReal )
   {
      double periodROC = 0.0;
      double tempReal = 0.0;
      double tempReal2 = 0.0;
      if( sp.ringCap_trailingIdx == 0 ) {
         sp.ring_trailingIdx_inReal[0] = inReal;
      }
      tempReal = inReal;
      tempReal2 = sp.ring_trailingIdx_inReal[sp.ringPos_trailingIdx];
      periodROC = tempReal - tempReal2;
      /* Subtract-then-add, TA_SUM's own order. */
      sp.sumROC1 -= Math.Abs(sp.trailingValue - tempReal2);
      sp.sumROC1 += Math.Abs(tempReal - sp.lag1_inReal);
      /* Once a whole window of one-bar changes is exactly zero, the sum's
       * only content is rounding residue from the subtract/add carry --
       * purge it so the flat window is recognized exactly (kama.c #253).
       */
      if( tempReal - sp.lag1_inReal == 0.0 ) {
         sp.nullRun += 1;
      } else {
         sp.nullRun = 0;
      }
      if( sp.nullRun >= sp.optInTimePeriod ) {
         sp.nullRun = sp.optInTimePeriod;
         sp.sumROC1 = 0.0;
      }
      /* Save the trailing value: outReal may alias inReal, and the next
       * iteration's subtraction needs the ORIGINAL bar, not the slot the
       * write below may have clobbered.
       */
      sp.trailingValue = tempReal2;
      if( sp.sumROC1 <= 0.0 || sp.sumROC1 <= periodROC ) {
         sp.cur_outReal = 1.0;
      } else {
         tempReal = Math.Abs(periodROC / sp.sumROC1);
         if( tempReal > 1.0 ) {
            tempReal = 1.0;
         }
         sp.cur_outReal = tempReal;
      }
      sp.lag1_inReal = inReal;
      sp.ring_trailingIdx_inReal[sp.ringPos_trailingIdx] = inReal;
      sp.ringPos_trailingIdx = sp.ringPos_trailingIdx + 1;
      if( sp.ringPos_trailingIdx >= sp.ringCap_trailingIdx ) {
         sp.ringPos_trailingIdx = 0;
      }
   }

   private RetCode ErOpenImpl( ErStream sp, ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      int outIdx = 0;
      int today = 0;
      int trailingIdx = 0;
      int lookbackTotal = 0;
      int i = 0;
      int nullRun = 0;
      double sumROC1 = 0;
      double periodROC = 0;
      double tempReal = 0;
      double tempReal2 = 0;
      double trailingValue = 0;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 10;
      } else if( optInTimePeriod < 2 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      /* Kaufman Efficiency Ratio (Perry J. Kaufman, Smarter Trading, 1995):
       * net directional movement over the period divided by the total path
       * travelled,
       *
       *   ER[t] = |c[t] - c[t-P]| / SUM(k = t-P+1 .. t) |c[k] - c[k-1]|
       *
       * The ratio is in [0,1] in exact arithmetic, but sumROC1 drifts, so the
       * clamp to 1.0 is what makes the declared range a bound rather than a
       * hope -- and in kama.c what keeps its recurrence a convex combination.
       *
       * This is a lift of TA_KAMA's inner efficiency ratio (kama.c) so the
       * two stay bit-identical -- the KAMA-reconstruction differential in
       * test_composite2.c exists to keep it that way. Three more guards are
       * load-bearing and shared with kama.c:
       *
       *   - `sumROC1 <= periodROC` pins the ratio to exactly 1.0 where FP
       *     would give 1.0000000000000002, on up-moves. It compares against
       *     the SIGNED numerator, so it is false for every down move: it
       *     bounds nothing on its own, which is what the clamp is for.
       *   - a genuinely flat window is recognized by COUNTING exactly-zero
       *     one-bar changes (nullRun >= P forces sumROC1 to 0.0, purging the
       *     running sum's rounding residue), after which `0 <= 0` pins the
       *     0/0 to 1.0 -- never NaN (#112). This is kama.c's #253 form; the
       *     absolute TA_IS_ZERO band it replaced fails the QUOTE-UNIT/SCALE
       *     gate (ER is homogeneous of degree 0, and a fixed 1e-14 met a
       *     price-carrying sum).
       *
       * The third is the denominator test (#385): a subtract-then-add sum can
       * reach 0.0, or below it, on a window that is not flat. The clamp
       * subsumes it numerically, so it is held by the structural sweep over
       * divisors, not by any value test.
       *
       * The subtract-then-add update order matches TA_SUM's recurrence,
       * which is what makes the composite differential bit-exact. The
       * trailing value is cached one iteration ahead, which is what keeps
       * outReal == inReal aliasing safe.
       */
      lookbackTotal = ER_Lookback(optInTimePeriod);
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      /* Prime the path sum over the optInTimePeriod one-bar changes ending
       * at the first output bar's predecessor.
       */
      sumROC1 = 0.0;
      nullRun = 0;
      today = startIdx - lookbackTotal;
      trailingIdx = today;
      i = optInTimePeriod;
      while( i-- > 0 ) {
         tempReal = inReal[today++];
         tempReal -= inReal[today];
         sumROC1 += Math.Abs(tempReal);
         if( tempReal == 0.0 ) {
            nullRun += 1;
         } else {
            nullRun = 0;
         }
      }
      /* First output: today == startIdx. */
      tempReal = inReal[today];
      tempReal2 = inReal[trailingIdx++];
      periodROC = tempReal - tempReal2;
      trailingValue = tempReal2;
      /* A fully flat priming window sums to an exact 0.0 (no residue yet), so
       * `0 <= 0` already answers 1.0 here without the nullRun purge. The
       * denominator test below is unreachable at this site -- a priming sum only
       * ever has non-negative terms added to it -- and is written anyway so both
       * sites read as one rule.
       */
      if( sumROC1 <= 0.0 || sumROC1 <= periodROC ) {
         outReal[0 * outStride] = 1.0;
      } else {
         tempReal = Math.Abs(periodROC / sumROC1);
         if( tempReal > 1.0 ) {
            tempReal = 1.0;
         }
         outReal[0 * outStride] = tempReal;
      }
      outIdx = 1;
      today += 1;
      while( today <= endIdx ) {
         tempReal = inReal[today];
         tempReal2 = inReal[trailingIdx++];
         periodROC = tempReal - tempReal2;
         /* Subtract-then-add, TA_SUM's own order. */
         sumROC1 -= Math.Abs(trailingValue - tempReal2);
         sumROC1 += Math.Abs(tempReal - inReal[today - 1]);
         /* Once a whole window of one-bar changes is exactly zero, the sum's
          * only content is rounding residue from the subtract/add carry --
          * purge it so the flat window is recognized exactly (kama.c #253).
          */
         if( tempReal - inReal[today - 1] == 0.0 ) {
            nullRun += 1;
         } else {
            nullRun = 0;
         }
         if( nullRun >= optInTimePeriod ) {
            nullRun = optInTimePeriod;
            sumROC1 = 0.0;
         }
         /* Save the trailing value: outReal may alias inReal, and the next
          * iteration's subtraction needs the ORIGINAL bar, not the slot the
          * write below may have clobbered.
          */
         trailingValue = tempReal2;
         if( sumROC1 <= 0.0 || sumROC1 <= periodROC ) {
            outReal[outIdx++ * outStride] = 1.0;
         } else {
            tempReal = Math.Abs(periodROC / sumROC1);
            if( tempReal > 1.0 ) {
               tempReal = 1.0;
            }
            outReal[outIdx++ * outStride] = tempReal;
         }
         today += 1;
      }
      outBegIdx = startIdx;
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      int cap_trailingIdx = today - trailingIdx;
      if( cap_trailingIdx < 0 || cap_trailingIdx > historyLen ) {
         return RetCode.InternalError;
      }
      int allocN_trailingIdx = (cap_trailingIdx > 0)? cap_trailingIdx : 1;
      double[] capRing_trailingIdx_inReal = new double[allocN_trailingIdx];
      inReal.Slice(historyLen - cap_trailingIdx, cap_trailingIdx).CopyTo(capRing_trailingIdx_inReal);
      sp.optInTimePeriod = optInTimePeriod;
      sp.nullRun = nullRun;
      sp.sumROC1 = sumROC1;
      sp.trailingValue = trailingValue;
      sp.lag1_inReal = inReal[historyLen - 1];
      sp.ringPos_trailingIdx = 0;
      sp.ringCap_trailingIdx = cap_trailingIdx;
      sp.ring_trailingIdx_inReal = capRing_trailingIdx_inReal;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* ErOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal ErStream ErOpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      ErStream sp = new ErStream(this);
      RetCode retCode = ErOpenImpl(sp, inReal, startIdx, optInTimePeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("ER", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind ErOpen (composition seam). */
   internal ErStream ErOpenInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod )
   {
      ErStream sp = new ErStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = ErOpenImpl(sp, inReal, startIdx, optInTimePeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("ER", "open", retCode);
   }

   /// <summary>Open a live <c>ER</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="ErStream.Value"/> starts at the last history bar's
   /// value — bit-identical to what <c>ER</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>ER_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>ErOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">Source price/value series (canonically close) The warm-up history, oldest
   /// bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="ER_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>ER_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public ErStream ErOpen( ReadOnlySpan<double> inReal, int optInTimePeriod )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "ER open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "ER open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      return ErOpenInternal(inReal, 0, optInTimePeriod);
   }

   /// <summary><c>ErOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>ER</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - ER_Lookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="ErStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">Source price/value series (canonically close) The warm-up history, oldest
   /// bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="ER_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Efficiency ratio. Must hold at least <c>historyLen - ER_Lookback(...)</c>
   /// values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>ER_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public ErStream ErOpenAndFill( ReadOnlySpan<double> inReal, int optInTimePeriod, Span<double> outReal )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "ER openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "ER openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      int guardOutLen = OpenFillCount("ER", "openAndFill", inReal.Length, ER_Lookback(optInTimePeriod));
      RequireFillLength("ER", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( outReal.Overlaps(inReal) ) {
         throw StreamFailure("ER", "openAndFill", RetCode.BadParam);
      }
      return ErOpenAndFillInternal(inReal, 0, optInTimePeriod, out _, out _, outReal);
   }
