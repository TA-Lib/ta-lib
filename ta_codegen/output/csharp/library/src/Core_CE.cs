   /// <summary>One <c>CE</c> output set, in batch output order.</summary>
   /// <remarks>
   /// <para>Equality is the compiler-generated record-struct equality, which compares
   /// each component with <see cref="System.Double.Equals(System.Double)"/>, not
   /// <c>==</c>: any two <c>NaN</c> payloads compare equal, and <c>0.0</c>
   /// equals <c>-0.0</c>. Compare
   /// <see cref="System.BitConverter.DoubleToInt64Bits(double)"/> per component
   /// when bit-level identity is what you mean.</para>
   /// </remarks>
   /// <param name="RealLong">Highest high less the multiple of the Average True Range; the stop for a
   /// long position.</param>
   /// <param name="RealShort">Lowest low plus the multiple of the Average True Range; the stop for a
   /// short position.</param>
   public readonly record struct CeValue( double RealLong, double RealShort );

   /// <summary>A live <c>CE</c> stream: one value per closed bar, bit-identical to
   /// <c>CE</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.CeOpen"/>. There is no close and nothing to
   /// dispose — the handle is ordinary managed state, and an unreferenced handle
   /// is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class CeStream
   {
      internal Core core;
      internal int optInTimePeriod;
      internal double optInMultiplier;
      internal int lastP;
      internal double prevATR;
      internal double wAlpha;
      internal double wBeta;
      internal double hhPre;
      internal double llPre;
      internal int hhBuf_Idx;
      internal int maxIdx_hhBuf;
      internal int llBuf_Idx;
      internal int maxIdx_llBuf;
      internal double lag1_inClose;
      internal int cbSize_hhBuf;
      internal double[] cb_hhBuf = [];
      internal int cbSize_llBuf;
      internal double[] cb_llBuf = [];
      internal double cur_outRealLong;
      internal double cur_outRealShort;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal CeStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Ce</c> reports over the same bars: the opener sets it
      /// to <c>(lookback, historyLen - lookback)</c>, every accepted <c>Update</c>
      /// adds one to the count — a rejected one changes nothing, and neither does
      /// <c>Peek</c> — and <c>Clone</c> carries it verbatim. A plain <c>Open</c>
      /// hands back only the last value, a subset of this range, because the caller
      /// chose not to take the fill.</para>
      /// <para>The last bar it can reach is <see cref="Core.IndexMax"/>; past that
      /// <c>Update</c> and <c>Advance</c> throw.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      /// <summary>Count one bar this stream was not fed: <see cref="OutRange"/> advances by
      /// one and nothing else moves.</summary>
      /// <remarks>
      /// <para><see cref="Value"/> keeps answering the previous output, which is this
      /// bar's output too. For a bar the caller leaves out: one an <c>Update</c>
      /// rejected and that will not be re-fed, or a session with no print. Without
      /// it two handles on one feed drift a bar apart when only one of them skips.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, the last one the batch tier
      /// can address and the last this handle will count. <c>Update</c> throws the
      /// same there.</para>
      /// </remarks>
      public void Advance()
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("CE", "advance", RetCode.OutOfRangeEndIndex);
         outRangeCount++;
      }

      internal CeStream( CeStream other )
      {
         this.core = other.core;
         this.optInTimePeriod = other.optInTimePeriod;
         this.optInMultiplier = other.optInMultiplier;
         this.lastP = other.lastP;
         this.prevATR = other.prevATR;
         this.wAlpha = other.wAlpha;
         this.wBeta = other.wBeta;
         this.hhPre = other.hhPre;
         this.llPre = other.llPre;
         this.hhBuf_Idx = other.hhBuf_Idx;
         this.maxIdx_hhBuf = other.maxIdx_hhBuf;
         this.llBuf_Idx = other.llBuf_Idx;
         this.maxIdx_llBuf = other.maxIdx_llBuf;
         this.lag1_inClose = other.lag1_inClose;
         this.cbSize_hhBuf = other.cbSize_hhBuf;
         this.cb_hhBuf = new double[other.cb_hhBuf.Length];
         Array.Copy( other.cb_hhBuf, this.cb_hhBuf, other.cb_hhBuf.Length );
         this.cbSize_llBuf = other.cbSize_llBuf;
         this.cb_llBuf = new double[other.cb_llBuf.Length];
         Array.Copy( other.cb_llBuf, this.cb_llBuf, other.cb_llBuf.Length );
         this.cur_outRealLong = other.cur_outRealLong;
         this.cur_outRealShort = other.cur_outRealShort;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so nothing moves — <see cref="OutRange"/> included — and
      /// <see cref="Value"/> still answers the previous value. Re-feed the bar when
      /// a corrected value arrives, or call <see cref="Advance"/> to count it and
      /// carry on; two handles on one feed drift a bar apart if neither happens.
      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, which no re-feed clears: the
      /// handle has run out of index domain and only a shorter history can start a
      /// new one.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>The value at the bar just committed.</returns>
      public CeValue Update( double inHigh, double inLow, double inClose )
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("CE", "update", RetCode.OutOfRangeEndIndex);
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) ) throw Core.NonFiniteBar("CE", "update", !double.IsFinite(inHigh) ? nameof(inHigh) : !double.IsFinite(inLow) ? nameof(inLow) : nameof(inClose));
         core.CeStepImpl(this, inHigh, inLow, inClose);
         outRangeCount++;
         return new CeValue(cur_outRealLong, cur_outRealShort);
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.IndexMax"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public CeValue Peek( double inHigh, double inLow, double inClose )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) ) throw Core.NonFiniteBar("CE", "peek", !double.IsFinite(inHigh) ? nameof(inHigh) : !double.IsFinite(inLow) ? nameof(inLow) : nameof(inClose));
         CeStream sp = this;
         double val2 = 0.0;
         double val3 = 0.0;
         double greatest = 0.0;
         double tempCY = 0.0;
         double tempLT = 0.0;
         double tempHT = 0.0;
         double tempReal = 0.0;
         double highest = 0.0;
         double lowest = 0.0;
         double band = 0.0;
         double cur_outRealLong = 0.0;
         double cur_outRealShort = 0.0;
         int hhBuf_Idx = sp.hhBuf_Idx;
         double hhPre = sp.hhPre;
         double llPre = sp.llPre;
         double prevATR = sp.prevATR;
         tempLT = inLow;
         tempHT = inHigh;
         tempCY = sp.lag1_inClose;
         greatest = tempHT - tempLT;
         /* val1 */
         val2 = Math.Abs(tempCY - tempHT);
         greatest = MaxGt(val2, greatest);
         val3 = Math.Abs(tempCY - tempLT);
         greatest = MaxGt(val3, greatest);
         prevATR = Math.FusedMultiplyAdd(sp.wBeta, prevATR, sp.wAlpha * greatest);
         /* Keep this shape: the prefix extreme selected in a local, the
          * block-start override after it, one store. A store made only when the
          * bar sets a new extreme, or the override ahead of the select, compiles
          * to a data-dependent branch in the stream step, where the prefix lives
          * in the handle.
          */
         highest = hhPre;
         lowest = llPre;
         highest = MaxGt(tempHT, highest);
         lowest = MinLt(tempLT, lowest);
         if( hhBuf_Idx == 0 ) {
            highest = tempHT;
            lowest = tempLT;
         }
         hhPre = highest;
         llPre = lowest;
         if( hhBuf_Idx < sp.lastP ) {
            tempReal = sp.cb_hhBuf[hhBuf_Idx + 1];
            highest = MaxGt(tempReal, highest);
            tempReal = sp.cb_llBuf[hhBuf_Idx + 1];
            lowest = MinLt(tempReal, lowest);
         }
         hhBuf_Idx = hhBuf_Idx + 1;
         if( hhBuf_Idx > sp.maxIdx_hhBuf ) {
            hhBuf_Idx = 0;
         }
         band = sp.optInMultiplier * prevATR;
         cur_outRealLong = highest - band;
         cur_outRealShort = lowest + band;
         return new CeValue(cur_outRealLong, cur_outRealShort);
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public CeValue Value => new CeValue(cur_outRealLong, cur_outRealShort);

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public CeStream Clone()
      {
         return new CeStream(this);
      }
   }

   private void CeStepImpl( CeStream sp, double inHigh, double inLow, double inClose )
   {
      int ip = 0;
      double val2 = 0.0;
      double val3 = 0.0;
      double greatest = 0.0;
      double tempCY = 0.0;
      double tempLT = 0.0;
      double tempHT = 0.0;
      double tempReal = 0.0;
      double sufHi = 0.0;
      double sufLo = 0.0;
      double highest = 0.0;
      double lowest = 0.0;
      double band = 0.0;
      tempLT = inLow;
      tempHT = inHigh;
      tempCY = sp.lag1_inClose;
      greatest = tempHT - tempLT;
      /* val1 */
      val2 = Math.Abs(tempCY - tempHT);
      greatest = MaxGt(val2, greatest);
      val3 = Math.Abs(tempCY - tempLT);
      greatest = MaxGt(val3, greatest);
      sp.prevATR = Math.FusedMultiplyAdd(sp.wBeta, sp.prevATR, sp.wAlpha * greatest);
      /* Keep this shape: the prefix extreme selected in a local, the
       * block-start override after it, one store. A store made only when the
       * bar sets a new extreme, or the override ahead of the select, compiles
       * to a data-dependent branch in the stream step, where the prefix lives
       * in the handle.
       */
      highest = sp.hhPre;
      lowest = sp.llPre;
      highest = MaxGt(tempHT, highest);
      lowest = MinLt(tempLT, lowest);
      if( sp.hhBuf_Idx == 0 ) {
         highest = tempHT;
         lowest = tempLT;
      }
      sp.hhPre = highest;
      sp.llPre = lowest;
      if( sp.hhBuf_Idx < sp.lastP ) {
         tempReal = sp.cb_hhBuf[sp.hhBuf_Idx + 1];
         highest = MaxGt(tempReal, highest);
         tempReal = sp.cb_llBuf[sp.hhBuf_Idx + 1];
         lowest = MinLt(tempReal, lowest);
      }
      sp.cb_hhBuf[sp.hhBuf_Idx] = tempHT;
      sp.cb_llBuf[sp.hhBuf_Idx] = tempLT;
      sp.hhBuf_Idx = sp.hhBuf_Idx + 1;
      if( sp.hhBuf_Idx > sp.maxIdx_hhBuf ) {
         sp.hhBuf_Idx = 0;
      }
      band = sp.optInMultiplier * sp.prevATR;
      sp.cur_outRealLong = highest - band;
      sp.cur_outRealShort = lowest + band;
      /* A completed block becomes its suffix extrema. Nothing this bar reads
       * them, so the pass stays below the output stores, where the peek
       * frame never runs it.
       */
      if( sp.hhBuf_Idx == 0 ) {
         sufHi = sp.cb_hhBuf[sp.lastP];
         sufLo = sp.cb_llBuf[sp.lastP];
         ip = sp.lastP;
         while( ip > 1 ) {
            ip -= 1;
            tempReal = sp.cb_hhBuf[ip];
            sufHi = MaxGt(tempReal, sufHi);
            sp.cb_hhBuf[ip] = sufHi;
            tempReal = sp.cb_llBuf[ip];
            sufLo = MinLt(tempReal, sufLo);
            sp.cb_llBuf[ip] = sufLo;
         }
      }
      sp.lag1_inClose = inClose;
   }

   private RetCode CeOpenImpl( CeStream sp, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, double optInMultiplier, out int outBegIdx, out int outNBElement, Span<double> outRealLong, Span<double> outRealShort, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double[] hhBuf = [];
      int hhBuf_Idx = 0;
      int maxIdx_hhBuf = (30)-1;
      double[] llBuf = [];
      int llBuf_Idx = 0;
      int maxIdx_llBuf = (30)-1;
      int i = 0;
      int ip = 0;
      int today = 0;
      int outIdx = 0;
      int lookbackTotal = 0;
      int lastP = 0;
      double prevATR = 0;
      double periodTotal = 0;
      double wAlpha = 0;
      double wBeta = 0;
      double val2 = 0;
      double val3 = 0;
      double greatest = 0;
      double tempCY = 0;
      double tempLT = 0;
      double tempHT = 0;
      double tempReal = 0;
      double hhPre = 0;
      double llPre = 0;
      double sufHi = 0;
      double sufLo = 0;
      double highest = 0;
      double lowest = 0;
      double band = 0;
      int historyLen = inHigh.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.InsufficientHistory;
      }
      if( historyLen > IndexMax + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inLow.Length != inHigh.Length || inClose.Length != inHigh.Length ) {
         return RetCode.BadParam;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 22;
      } else if( optInTimePeriod < 2 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInMultiplier == RealDefault ) {
         optInMultiplier = 3e0;
      } else if( !(optInMultiplier >= 0e0 && optInMultiplier <= RealMax) ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      outBegIdx = 0;
      outNBElement = 0;
      lookbackTotal = CeLookback(optInTimePeriod, optInMultiplier);
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         return RetCode.InsufficientHistory ;
      }
      /* Two rolling extrema, van Herk / Gil-Werman, one buffer each: the window
       * ending in slot j is the current block's prefix extremum joined with the
       * previous block's suffix extremum from slot j+1. A slot holds the raw value
       * while its block is filling and is turned into the suffix extremum, in
       * place, when the block completes; slot j+1 is always still the previous
       * block's when slot j is filled. The high and low sides share an index.
       *
       * The extrema are exact, so both outputs must stay bit-identical to
       * TA_MAX(high) - x*TA_ATR and its mirror, whatever the block phase; only
       * the sign of a zero tied between +0.0 and -0.0 is free.
       */
      if( optInTimePeriod < 1 ) return RetCode.InternalError;
      hhBuf = new double[optInTimePeriod];
      maxIdx_hhBuf = (optInTimePeriod)-1;
      hhBuf_Idx = 0;
      if( optInTimePeriod < 1 ) return RetCode.InternalError;
      llBuf = new double[optInTimePeriod];
      maxIdx_llBuf = (optInTimePeriod)-1;
      llBuf_Idx = 0;
      lastP = optInTimePeriod - 1;
      /* The Average True Range is carried inline rather than taken from a call,
       * so that the extreme window and the average advance together one bar at
       * a time and the body streams.
       *
       * The arithmetic order below is the bit-exactness contract with TA_ATR (do
       * not reorder): True Range from high-low, then the two previous-close
       * distances in that order; the seed summed from 0.0 over the first 'period'
       * True Ranges and divided once; the same two Wilder coefficients, wBeta
       * rounded and wAlpha derived from it, in one fused statement.
       */
      wBeta = (double)(optInTimePeriod - 1) / (double)optInTimePeriod;
      wAlpha = 1.0 - wBeta;
      today = startIdx - lookbackTotal + 1;
      periodTotal = 0.0;
      i = optInTimePeriod;
      while( i-- > 0 ) {
         tempLT = inLow[today];
         tempHT = inHigh[today];
         tempCY = inClose[today - 1];
         greatest = tempHT - tempLT;
         /* val1 */
         val2 = Math.Abs(tempCY - tempHT);
         greatest = MaxGt(val2, greatest);
         val3 = Math.Abs(tempCY - tempLT);
         greatest = MaxGt(val3, greatest);
         periodTotal += greatest;
         today += 1;
      }
      prevATR = periodTotal / optInTimePeriod;
      /* Skip the bars the lookback adds for the unstable period. Taking the count
       * from the lookback rather than naming the setting keeps the two from
       * disagreeing.
       */
      i = lookbackTotal - optInTimePeriod;
      while( i != 0 ) {
         tempLT = inLow[today];
         tempHT = inHigh[today];
         tempCY = inClose[today - 1];
         greatest = tempHT - tempLT;
         /* val1 */
         val2 = Math.Abs(tempCY - tempHT);
         greatest = MaxGt(val2, greatest);
         val3 = Math.Abs(tempCY - tempLT);
         greatest = MaxGt(val3, greatest);
         prevATR = Math.FusedMultiplyAdd(wBeta, prevATR, wAlpha * greatest);
         today += 1;
         i -= 1;
      }
      /* prevATR is now the Average True Range of bar today-1, the first output
       * bar. Its extreme window is one whole block, taken straight from the
       * input.
       */
      highest = inHigh[today - 1];
      lowest = inLow[today - 1];
      hhBuf[lastP] = highest;
      llBuf[lastP] = lowest;
      ip = lastP;
      while( ip > 0 ) {
         ip -= 1;
         tempHT = inHigh[today - 1 - lastP + ip];
         tempLT = inLow[today - 1 - lastP + ip];
         highest = MaxGt(tempHT, highest);
         lowest = MinLt(tempLT, lowest);
         hhBuf[ip] = highest;
         llBuf[ip] = lowest;
      }
      hhPre = highest;
      llPre = lowest;
      /* The multiple of the ATR is formed on its own, never fused into the
       * offset, so that each line is TA_MAX - x*TA_ATR (or its mirror) as a
       * caller composing the three functions would compute it.
       */
      band = optInMultiplier * prevATR;
      outRealLong[0 * outStride] = highest - band;
      outRealShort[0 * outStride] = lowest + band;
      outIdx = 1;
      while( today <= endIdx ) {
         tempLT = inLow[today];
         tempHT = inHigh[today];
         tempCY = inClose[today - 1];
         greatest = tempHT - tempLT;
         /* val1 */
         val2 = Math.Abs(tempCY - tempHT);
         greatest = MaxGt(val2, greatest);
         val3 = Math.Abs(tempCY - tempLT);
         greatest = MaxGt(val3, greatest);
         prevATR = Math.FusedMultiplyAdd(wBeta, prevATR, wAlpha * greatest);
         /* Keep this shape: the prefix extreme selected in a local, the
          * block-start override after it, one store. A store made only when the
          * bar sets a new extreme, or the override ahead of the select, compiles
          * to a data-dependent branch in the stream step, where the prefix lives
          * in the handle.
          */
         highest = hhPre;
         lowest = llPre;
         highest = MaxGt(tempHT, highest);
         lowest = MinLt(tempLT, lowest);
         if( hhBuf_Idx == 0 ) {
            highest = tempHT;
            lowest = tempLT;
         }
         hhPre = highest;
         llPre = lowest;
         if( hhBuf_Idx < lastP ) {
            tempReal = hhBuf[hhBuf_Idx + 1];
            highest = MaxGt(tempReal, highest);
            tempReal = llBuf[hhBuf_Idx + 1];
            lowest = MinLt(tempReal, lowest);
         }
         hhBuf[hhBuf_Idx] = tempHT;
         llBuf[hhBuf_Idx] = tempLT;
         hhBuf_Idx++;
         if( hhBuf_Idx > maxIdx_hhBuf ) { hhBuf_Idx = 0; }
         band = optInMultiplier * prevATR;
         outRealLong[outIdx * outStride] = highest - band;
         outRealShort[outIdx * outStride] = lowest + band;
         /* A completed block becomes its suffix extrema. Nothing this bar reads
          * them, so the pass stays below the output stores, where the peek
          * frame never runs it.
          */
         if( hhBuf_Idx == 0 ) {
            sufHi = hhBuf[lastP];
            sufLo = llBuf[lastP];
            ip = lastP;
            while( ip > 1 ) {
               ip -= 1;
               tempReal = hhBuf[ip];
               sufHi = MaxGt(tempReal, sufHi);
               hhBuf[ip] = sufHi;
               tempReal = llBuf[ip];
               sufLo = MinLt(tempReal, sufLo);
               llBuf[ip] = sufLo;
            }
         }
         outIdx += 1;
         today += 1;
      }
      outBegIdx = startIdx;
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      int capCb_hhBuf = maxIdx_hhBuf + 1;
      if( capCb_hhBuf > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      int capCb_llBuf = maxIdx_llBuf + 1;
      if( capCb_llBuf > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      sp.optInTimePeriod = optInTimePeriod;
      sp.optInMultiplier = optInMultiplier;
      sp.lastP = lastP;
      sp.prevATR = prevATR;
      sp.wAlpha = wAlpha;
      sp.wBeta = wBeta;
      sp.hhPre = hhPre;
      sp.llPre = llPre;
      sp.hhBuf_Idx = hhBuf_Idx;
      sp.maxIdx_hhBuf = maxIdx_hhBuf;
      sp.llBuf_Idx = llBuf_Idx;
      sp.maxIdx_llBuf = maxIdx_llBuf;
      sp.lag1_inClose = inClose[historyLen - 1];
      sp.cbSize_hhBuf = capCb_hhBuf;
      sp.cb_hhBuf = hhBuf;
      sp.cbSize_llBuf = capCb_llBuf;
      sp.cb_llBuf = llBuf;
      sp.cur_outRealLong = outRealLong[(outNBElement - 1) * outStride];
      sp.cur_outRealShort = outRealShort[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* CeOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal CeStream CeOpenAndFillInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, double optInMultiplier, out int outBegIdx, out int outNBElement, Span<double> outRealLong, Span<double> outRealShort )
   {
      CeStream sp = new CeStream(this);
      RetCode retCode = CeOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInTimePeriod, optInMultiplier, out outBegIdx, out outNBElement, outRealLong, outRealShort, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("CE", "openAndFill", nameof(inHigh), inHigh.Length, startIdx, CeLookback(optInTimePeriod, optInMultiplier));
      }
      throw StreamFailure("CE", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind CeOpen (composition seam). */
   internal CeStream CeOpenInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, double optInMultiplier )
   {
      CeStream sp = new CeStream(this);
      double[] sink_outRealLong = new double[1];
      double[] sink_outRealShort = new double[1];
      RetCode retCode = CeOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInTimePeriod, optInMultiplier, out int outBegIdx, out int outNBElement, sink_outRealLong, sink_outRealShort, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("CE", "open", nameof(inHigh), inHigh.Length, startIdx, CeLookback(optInTimePeriod, optInMultiplier));
      }
      throw StreamFailure("CE", "open", retCode);
   }

   /// <summary>Open a live <c>CE</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="CeStream.Value"/> starts at the last history bar's
   /// value — bit-identical to what <c>CE</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>CeLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>CeOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="CeLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInMultiplier">As in the batch call; see <see cref="CeLookback"/> for its default and
   /// range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>CeLookback(...) + 1</c> bars, an empty one
   /// included — which is what a null array becomes, since a span cannot be
   /// null.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is longer than <see cref="Core.IndexMax"/> + 1, the one index
   /// fault an opener can have (rule rS2).</exception>
   public CeStream CeOpen( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInTimePeriod, double optInMultiplier )
   {
      if( inHigh.IsEmpty ) throw new InsufficientHistoryException("CE open: history is empty", nameof(inHigh));
      if( inHigh.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "CE open: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TALibArgumentException("CE open: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TALibArgumentException("CE open: inClose is empty", nameof(inClose), RetCode.BadParam);
      RequireHistoryLength("CE", "open", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("CE", "open", "inClose", inClose.Length, inHigh.Length);
      return CeOpenInternal(inHigh, inLow, inClose, 0, optInTimePeriod, optInMultiplier);
   }

   /// <summary><c>CeOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>CE</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - CeLookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="CeStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="CeLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInMultiplier">As in the batch call; see <see cref="CeLookback"/> for its default and
   /// range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <param name="outRealLong">Highest high less the multiple of the Average True Range; the stop for a
   /// long position. Must hold at least <c>historyLen - CeLookback(...)</c>
   /// values.</param>
   /// <param name="outRealShort">Lowest low plus the multiple of the Average True Range; the stop for a
   /// short position. Must hold at least <c>historyLen - CeLookback(...)</c>
   /// values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>CeLookback(...) + 1</c> bars, an empty one
   /// included — which is what a null array becomes, since a span cannot be
   /// null.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is longer than <see cref="Core.IndexMax"/> + 1, the one index
   /// fault an opener can have (rule rS2).</exception>
   public CeStream CeOpenAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInTimePeriod, double optInMultiplier, Span<double> outRealLong, Span<double> outRealShort )
   {
      if( inHigh.IsEmpty ) throw new InsufficientHistoryException("CE openAndFill: history is empty", nameof(inHigh));
      if( inHigh.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "CE openAndFill: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TALibArgumentException("CE openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TALibArgumentException("CE openAndFill: inClose is empty", nameof(inClose), RetCode.BadParam);
      int guardOutLen = OpenFillCount("CE", "openAndFill", inHigh.Length, CeLookback(optInTimePeriod, optInMultiplier));
      RequireHistoryLength("CE", "openAndFill", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("CE", "openAndFill", "inClose", inClose.Length, inHigh.Length);
      RequireFillLength("CE", "openAndFill", "outRealLong", outRealLong.Length, guardOutLen);
      RequireFillLength("CE", "openAndFill", "outRealShort", outRealShort.Length, guardOutLen);
      if( SameBuffer(outRealLong, inHigh) || SameBuffer(outRealLong, inLow) || SameBuffer(outRealLong, inClose) || SameBuffer(outRealShort, inHigh) || SameBuffer(outRealShort, inLow) || SameBuffer(outRealShort, inClose) || SameBuffer(outRealLong, outRealShort) ) {
         throw StreamFailure("CE", "openAndFill", RetCode.BadParam);
      }
      if( guardOutLen > 0 && ( outRealLong.Overlaps(inHigh) || outRealLong.Overlaps(inLow) || outRealLong.Overlaps(inClose) || outRealShort.Overlaps(inHigh) || outRealShort.Overlaps(inLow) || outRealShort.Overlaps(inClose) || OutputsAlias(outRealLong, outRealShort) ) ) {
         throw StreamFailure("CE", "openAndFill", RetCode.BadParam);
      }
      return CeOpenAndFillInternal(inHigh, inLow, inClose, 0, optInTimePeriod, optInMultiplier, out _, out _, outRealLong, outRealShort);
   }
