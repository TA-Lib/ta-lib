      RequireLength("CE", "outRealLong", outRealLong.Length, guardOutLen);
      if( guardStart >= 0 ) RequirePresent("CE", "outRealShort", outRealShort.Length);
      RequireLength("CE", "outRealShort", outRealShort.Length, guardOutLen);
