   public OutRange Ce( int startIdx,
                       int endIdx,
                       ReadOnlySpan<double> inHigh,
                       ReadOnlySpan<double> inLow,
                       ReadOnlySpan<double> inClose,
                       int optInTimePeriod,
                       double optInMultiplier,
                       Span<double> outRealLong,
                       Span<double> outRealShort )
   {
      int guardStart = ClampedStart(startIdx, endIdx, CeLookback(optInTimePeriod, optInMultiplier));
      int guardInLen = guardStart < 0 ? 0 : endIdx + 1;
      int guardOutLen = guardStart < 0 || guardStart > endIdx ? 0 : endIdx - guardStart + 1;
      RequireLength("CE", "inHigh", inHigh.Length, guardInLen);
      RequireLength("CE", "inLow", inLow.Length, guardInLen);
