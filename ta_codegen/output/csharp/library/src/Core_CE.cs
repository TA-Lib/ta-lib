   /// <summary>
   /// Le Beau's Chandelier Exit, a two-line volatility stop. The highest high of
   /// the window is offset down, and the lowest low up, by a multiple of the
   /// Average True Range, so each line hangs from the recent extreme at a
   /// distance that widens as the true range grows. The long line is the exit
   /// for a long position and hangs below the recent highs; the short line is
   /// the mirror for a short position, above the recent lows.
   /// </summary>
   /// <remarks>
   /// <para>
   /// Formula and more info at
   /// <see href="https://ta-lib.org/functions/ce">ta-lib.org/functions/ce</see>.
   /// </para>
   /// <list type="bullet">
   /// <item><description>The extremes are taken over the last TimePeriod bars. Le Beau anchors the highest high at the entry of the trade, which a function over a price series cannot know; the rolling window is what charting platforms plot under this name.</description></item>
   /// <item><description>The Average True Range is this library's, whose first value is the average of the first full period of true ranges that have a previous close. Platforms that start the true range on the very first bar give slightly different values on early bars; the difference decays as the average warms up.</description></item>
   /// <item><description>Both lines are emitted on every bar, each from the highs or the lows. A popular variant takes the extremes of the closes and keeps a single stop that only moves toward price until the trend flips; that variant is not this function.</description></item>
   /// <item><description>Neither line is always on its side of the other: with a small multiplier the long line sits above the short one.</description></item>
   /// <item><description>Both lines inherit the Average True Range's warm-up, so a caller who wants them converged sets <c>TA_FUNC_UNST_ATR</c>, exactly as when calling that function directly.</description></item>
   /// <item><description>The two lines are the Chande Kroll Stop with a stop period of 1, <c>outRealLong</c> being CKSP's <c>outHighStop</c>.</description></item>
   /// </list>
   /// <para>
   /// This is the <c>float[]</c> overload: input elements are widened to
   /// <c>double</c> as they are read and all arithmetic is performed in
   /// <c>double</c>, so a result beyond <c>float</c> range is still
   /// representable.
   /// </para>
   /// <para>
   /// Values are written only where the indicator is defined. The returned
   /// <see cref="OutRange"/> says where they start and how many there are, and
   /// the library never pads with NaN. A valid range that ends before
   /// <c>CeLookback</c> is a <b>success with no values</b> (<c>Count == 0</c>),
   /// not an error.
   /// </para>
   /// <para>
   /// Every exception it throws, except the runtime's own
   /// <c>OutOfMemoryException</c>, implements <see cref="ITALibFailure"/>, which
   /// carries the <see cref="RetCode"/>.
   /// </para>
   /// </remarks>
   /// <param name="startIdx">First bar of the requested range (inclusive).</param>
   /// <param name="endIdx">Last bar of the requested range (inclusive).</param>
   /// <param name="inHigh">High price of each bar.</param>
   /// <param name="inLow">Low price of each bar.</param>
   /// <param name="inClose">Close price of each bar.</param>
   /// <param name="optInTimePeriod">Window of the highest high and lowest low, and smoothing period of the
   /// Average True Range (default 22; range 2..100000; <c>int.MinValue</c>
   /// selects the default).</param>
   /// <param name="optInMultiplier">Multiplier applied to the Average True Range to offset the lines (default
   /// 3; minimum 0; <see cref="Core.RealDefault"/> selects the default).</param>
   /// <param name="outRealLong">Highest high less the multiple of the Average True Range; the stop for a
   /// long position. Must hold at least <c>endIdx - max(startIdx,
   /// CeLookback(...)) + 1</c> values, and never be empty: an empty span is an
   /// absent output.</param>
   /// <param name="outRealShort">Lowest low plus the multiple of the Average True Range; the stop for a
   /// short position. Must hold at least <c>endIdx - max(startIdx,
   /// CeLookback(...)) + 1</c> values, and never be empty: an empty span is an
   /// absent output.</param>
   /// <returns>The range written: <c>BegIdx</c> is the first bar with a value,
   /// <c>Count</c> how many were written.</returns>
   /// <exception cref="System.ArgumentOutOfRangeException"><c>startIdx</c> or <c>endIdx</c> is negative or above
   /// <see cref="Core.IndexMax"/>, or <c>endIdx &lt; startIdx</c>.</exception>
   /// <exception cref="System.ArgumentException">
   /// One of the following, checked before anything is written, so a rejected
   /// call leaves every buffer untouched:
   /// <list type="bullet">
   /// <item><description>An optional parameter is outside its documented range.</description></item>
   /// <item><description>A span is too short for the range requested: any input this function
   /// <i>declares</i> that does not reach <c>endIdx</c>, or an output that
   /// cannot hold the values produced. Declared, not read: a few candlestick
   /// patterns take an OHLC series they never index, and it is required all the
   /// same. A null array arrives as an empty span, and an empty span is an
   /// absent argument: for an input or an output, it is rejected even when the
   /// call would produce nothing.</description></item>
   /// <item><description>Two outputs overlap or are one array
   /// (<see href="https://ta-lib.org/spec/errors/#rb6">rule rB6</see>), or an
   /// output overlaps an input. An output and a real input never share an
   /// element type in this overload, so the two can never be the same span:
   /// there is no in-place case to allow, and any overlap of their byte ranges
   /// is rejected.</description></item>
   /// </list>
   /// </exception>
   /// <seealso cref="Core.Atr(int, int, ReadOnlySpan{double}, ReadOnlySpan{double}, ReadOnlySpan{double}, int, Span{double})"/>
   /// <seealso cref="Core.Max(int, int, ReadOnlySpan{double}, int, Span{double})"/>
