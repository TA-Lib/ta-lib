      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("CDLONNECK", "open", retCode);
   }

   /// <summary>Open a live <c>CDLONNECK</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="CDLONNECK_Stream.Value"/> starts at the last
   /// history bar's value — bit-identical to what <c>CDLONNECK</c> reports for
   /// that bar.</para>
   /// <para>The history must hold at least <c>CDLONNECK_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>CDLONNECK_OpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inOpen">Open price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>CDLONNECK_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentNullException">An input array is null.</exception>
   public CDLONNECK_Stream CDLONNECK_Open( double[] inOpen, double[] inHigh, double[] inLow, double[] inClose )
   {
      ArgumentNullException.ThrowIfNull(inOpen);
      ArgumentNullException.ThrowIfNull(inHigh);
      ArgumentNullException.ThrowIfNull(inLow);
      ArgumentNullException.ThrowIfNull(inClose);
      return CDLONNECK_OpenInternal(inOpen, inHigh, inLow, inClose, 0);
   }

   /// <summary><c>CDLONNECK_Open</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>CDLONNECK</c> produces
   /// over the same series, so no separate batch call is needed for the warm-up
   /// plot.</para>
   /// <para>Output arrays must hold <c>historyLen - CDLONNECK_Lookback(...)</c> values
   /// and must not alias the inputs or each other — this path writes the outputs
   /// and then reads the input tail to seed its rings, so the batch tier's
   /// in-place allowance does not carry over here.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="CDLONNECK_Stream.FillRange"/>.</para>
   /// </remarks>
   /// <param name="inOpen">Open price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="outInteger">-100 on a match, 0 otherwise. Only -100 is ever emitted (never +100);
   /// on-neck is always bearish. Must hold at least <c>historyLen -
   /// CDLONNECK_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>CDLONNECK_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, or an output array aliases an input or another
   /// output.</exception>
   /// <exception cref="System.ArgumentNullException">An input or output array is null.</exception>
   public CDLONNECK_Stream CDLONNECK_OpenAndFill( double[] inOpen, double[] inHigh, double[] inLow, double[] inClose, int[] outInteger )
   {
      ArgumentNullException.ThrowIfNull(inOpen);
      ArgumentNullException.ThrowIfNull(inHigh);
      ArgumentNullException.ThrowIfNull(inLow);
      ArgumentNullException.ThrowIfNull(inClose);
      ArgumentNullException.ThrowIfNull(outInteger);
      CDLONNECK_Stream sp = new CDLONNECK_Stream(this);
      RetCode retCode = CDLONNECK_OpenAndFillBody(sp, inOpen, inHigh, inLow, inClose, out int outBegIdx, out int outNBElement, outInteger);
      sp.fillRange = new OutRange(outBegIdx, outNBElement);
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("CDLONNECK", "openAndFill", retCode);
   }
