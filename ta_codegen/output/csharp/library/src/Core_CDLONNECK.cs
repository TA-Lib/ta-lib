   }

   /* Internal startIdx-anchored open behind CDLONNECK_Open (composition seam). */
   internal CDLONNECK_Stream CDLONNECK_OpenInternal( double[] inOpen, double[] inHigh, double[] inLow, double[] inClose, int startIdx )
