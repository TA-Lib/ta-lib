   /// <summary>A live <c>ROGERSSATCHELL</c> stream: one value per closed bar,
   /// bit-identical to <c>ROGERSSATCHELL</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.RogerssatchellOpen"/>. There is no close and
   /// nothing to dispose — the handle is ordinary managed state, and an
   /// unreferenced handle is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class RogerssatchellStream
   {
      internal Core core;
      internal int optInTimePeriod;
      internal double optInAnnualization;
      internal double periodTotal;
      internal double peakTotal;
      internal double sqrtA;
      internal int barsSinceRebuild;
      internal int termRing_Idx;
      internal int maxIdx_termRing;
      internal int cbSize_termRing;
      internal double[] cb_termRing = [];
      internal double cur_outReal;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal RogerssatchellStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Rogerssatchell</c> reports over the same bars: the
      /// opener sets it to <c>(lookback, historyLen - lookback)</c>, every accepted
      /// <c>Update</c> adds one to the count — a rejected one changes nothing, and
      /// neither does <c>Peek</c> — and <c>Clone</c> carries it verbatim. A plain
      /// <c>Open</c> hands back only the last value, a subset of this range,
      /// because the caller chose not to take the fill.</para>
      /// <para>The last bar it can reach is <see cref="Core.IndexMax"/>; past that
      /// <c>Update</c> and <c>Advance</c> throw.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      /// <summary>Count one bar this stream was not fed: <see cref="OutRange"/> advances by
      /// one and nothing else moves.</summary>
      /// <remarks>
      /// <para><see cref="Value"/> keeps answering the previous output, which is this
      /// bar's output too. For a bar the caller leaves out: one an <c>Update</c>
      /// rejected and that will not be re-fed, or a session with no print. Without
      /// it two handles on one feed drift a bar apart when only one of them skips.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, the last one the batch tier
      /// can address and the last this handle will count. <c>Update</c> throws the
      /// same there.</para>
      /// </remarks>
      public void Advance()
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("ROGERSSATCHELL", "advance", RetCode.OutOfRangeEndIndex);
         outRangeCount++;
      }

      internal RogerssatchellStream( RogerssatchellStream other )
      {
         this.core = other.core;
         this.optInTimePeriod = other.optInTimePeriod;
         this.optInAnnualization = other.optInAnnualization;
         this.periodTotal = other.periodTotal;
         this.peakTotal = other.peakTotal;
         this.sqrtA = other.sqrtA;
         this.barsSinceRebuild = other.barsSinceRebuild;
         this.termRing_Idx = other.termRing_Idx;
         this.maxIdx_termRing = other.maxIdx_termRing;
         this.cbSize_termRing = other.cbSize_termRing;
         this.cb_termRing = new double[other.cb_termRing.Length];
         Array.Copy( other.cb_termRing, this.cb_termRing, other.cb_termRing.Length );
         this.cur_outReal = other.cur_outReal;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so nothing moves — <see cref="OutRange"/> included — and
      /// <see cref="Value"/> still answers the previous value. Re-feed the bar when
      /// a corrected value arrives, or call <see cref="Advance"/> to count it and
      /// carry on; two handles on one feed drift a bar apart if neither happens.
      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, which no re-feed clears: the
      /// handle has run out of index domain and only a shorter history can start a
      /// new one.</para>
      /// </remarks>
      /// <param name="inOpen">This bar's open price.</param>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inOpen, double inHigh, double inLow, double inClose )
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("ROGERSSATCHELL", "update", RetCode.OutOfRangeEndIndex);
         if( !double.IsFinite(inOpen) || !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) ) throw Core.NonFiniteBar("ROGERSSATCHELL", "update", !double.IsFinite(inOpen) ? nameof(inOpen) : !double.IsFinite(inHigh) ? nameof(inHigh) : !double.IsFinite(inLow) ? nameof(inLow) : nameof(inClose));
         core.RogerssatchellStepImpl(this, inOpen, inHigh, inLow, inClose);
         outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.IndexMax"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inOpen">This bar's open price.</param>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public double Peek( double inOpen, double inHigh, double inLow, double inClose )
      {
         if( !double.IsFinite(inOpen) || !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) ) throw Core.NonFiniteBar("ROGERSSATCHELL", "peek", !double.IsFinite(inOpen) ? nameof(inOpen) : !double.IsFinite(inHigh) ? nameof(inHigh) : !double.IsFinite(inLow) ? nameof(inLow) : nameof(inClose));
         RogerssatchellStream sp = this;
         double o = 0.0;
         double h = 0.0;
         double l = 0.0;
         double c = 0.0;
         double p1 = 0.0;
         double p2 = 0.0;
         double term = 0.0;
         double windowTotal = 0.0;
         double windowMagnitude = 0.0;
         int j = 0;
         int barsSinceRebuild = sp.barsSinceRebuild;
         double cur_outReal = 0.0;
         double peakTotal = sp.peakTotal;
         double periodTotal = sp.periodTotal;
         int termRing_Idx = sp.termRing_Idx;
         int pkSlot0 = -1;
         double pkVal0 = 0.0;
         o = inOpen;
         h = inHigh;
         l = inLow;
         c = inClose;
         if( o > 0.0 && h > 0.0 && l > 0.0 && c > 0.0 ) {
            p1 = Math.Log(h / c) * Math.Log(h / o);
            p2 = Math.Log(l / c) * Math.Log(l / o);
            term = p1 + p2;
         } else {
            term = 0.0;
         }
         /* Add, publish, subtract: the slot written here was taken out of the
          * sum at the end of the previous bar, and the advance lands on the
          * oldest term, the one that leaves next.
          */
         pkSlot0 = termRing_Idx;
         pkVal0 = term;
         periodTotal += term;
         windowTotal = periodTotal;
         windowMagnitude = Math.Abs(windowTotal);
         peakTotal = MaxGt(windowMagnitude, peakTotal);
         termRing_Idx = termRing_Idx + 1;
         if( termRing_Idx > sp.maxIdx_termRing ) {
            termRing_Idx = 0;
         }
         periodTotal -= (termRing_Idx != pkSlot0) ? sp.cb_termRing[termRing_Idx] : pkVal0;
         /* A running sum carries rounding at the scale of the largest window it
          * has held, so it is rebuilt as a fresh sum once it falls below 1e-6 of
          * that peak, and at least every 32 windows. Compare against the peak,
          * not the current sum: after a quiet stretch arrives the current sum
          * can be nothing but that rounding, of either sign, where a fresh sum
          * of an all-flat window is exactly 0.0.
          *
          * Compare magnitudes. A window holding a bar whose high or low sits
          * inside its open and close can sum below zero, and a signed test
          * would then rebuild on every bar for as long as it does.
          *
          * Sum oldest first, so the rebuilt value is the one a fresh pass over
          * the bars gives.
          */
         barsSinceRebuild -= 1;
         if( windowMagnitude < 0.000001 * peakTotal || barsSinceRebuild <= 0 ) {
            barsSinceRebuild = 32 * sp.optInTimePeriod;
            windowTotal = 0.0;
            for( j = termRing_Idx; j < sp.optInTimePeriod; j += 1 ) {
               windowTotal += (j != pkSlot0) ? sp.cb_termRing[j] : pkVal0;
            }
            for( j = 0; j < termRing_Idx; j += 1 ) {
               windowTotal += (j != pkSlot0) ? sp.cb_termRing[j] : pkVal0;
            }
            peakTotal = Math.Abs(windowTotal);
            periodTotal = windowTotal;
            periodTotal -= (termRing_Idx != pkSlot0) ? sp.cb_termRing[termRing_Idx] : pkVal0;
         }
         /* Divide, then root, then scale. A sum at or below zero answers 0.0
          * instead of reaching the root: only a bar whose high or low sits
          * strictly inside its open and close can make a fresh sum negative,
          * and the estimator is not defined on such a bar.
          */
         if( windowTotal > 0.0 ) {
            cur_outReal = sp.sqrtA * Math.Sqrt(windowTotal / (double)sp.optInTimePeriod);
         } else {
            cur_outReal = 0.0;
         }
         return cur_outReal;
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public RogerssatchellStream Clone()
      {
         return new RogerssatchellStream(this);
      }
   }

   private void RogerssatchellStepImpl( RogerssatchellStream sp, double inOpen, double inHigh, double inLow, double inClose )
   {
      double o = 0.0;
      double h = 0.0;
      double l = 0.0;
      double c = 0.0;
      double p1 = 0.0;
      double p2 = 0.0;
      double term = 0.0;
      double windowTotal = 0.0;
      double windowMagnitude = 0.0;
      int j = 0;
      o = inOpen;
      h = inHigh;
      l = inLow;
      c = inClose;
      if( o > 0.0 && h > 0.0 && l > 0.0 && c > 0.0 ) {
         p1 = Math.Log(h / c) * Math.Log(h / o);
         p2 = Math.Log(l / c) * Math.Log(l / o);
         term = p1 + p2;
      } else {
         term = 0.0;
      }
      /* Add, publish, subtract: the slot written here was taken out of the
       * sum at the end of the previous bar, and the advance lands on the
       * oldest term, the one that leaves next.
       */
      sp.cb_termRing[sp.termRing_Idx] = term;
      sp.periodTotal += term;
      windowTotal = sp.periodTotal;
      windowMagnitude = Math.Abs(windowTotal);
      sp.peakTotal = MaxGt(windowMagnitude, sp.peakTotal);
      sp.termRing_Idx = sp.termRing_Idx + 1;
      if( sp.termRing_Idx > sp.maxIdx_termRing ) {
         sp.termRing_Idx = 0;
      }
      sp.periodTotal -= sp.cb_termRing[sp.termRing_Idx];
      /* A running sum carries rounding at the scale of the largest window it
       * has held, so it is rebuilt as a fresh sum once it falls below 1e-6 of
       * that peak, and at least every 32 windows. Compare against the peak,
       * not the current sum: after a quiet stretch arrives the current sum
       * can be nothing but that rounding, of either sign, where a fresh sum
       * of an all-flat window is exactly 0.0.
       *
       * Compare magnitudes. A window holding a bar whose high or low sits
       * inside its open and close can sum below zero, and a signed test
       * would then rebuild on every bar for as long as it does.
       *
       * Sum oldest first, so the rebuilt value is the one a fresh pass over
       * the bars gives.
       */
      sp.barsSinceRebuild -= 1;
      if( windowMagnitude < 0.000001 * sp.peakTotal || sp.barsSinceRebuild <= 0 ) {
         sp.barsSinceRebuild = 32 * sp.optInTimePeriod;
         windowTotal = 0.0;
         for( j = sp.termRing_Idx; j < sp.optInTimePeriod; j += 1 ) {
            windowTotal += sp.cb_termRing[j];
         }
         for( j = 0; j < sp.termRing_Idx; j += 1 ) {
            windowTotal += sp.cb_termRing[j];
         }
         sp.peakTotal = Math.Abs(windowTotal);
         sp.periodTotal = windowTotal;
         sp.periodTotal -= sp.cb_termRing[sp.termRing_Idx];
      }
      /* Divide, then root, then scale. A sum at or below zero answers 0.0
       * instead of reaching the root: only a bar whose high or low sits
       * strictly inside its open and close can make a fresh sum negative,
       * and the estimator is not defined on such a bar.
       */
      if( windowTotal > 0.0 ) {
         sp.cur_outReal = sp.sqrtA * Math.Sqrt(windowTotal / (double)sp.optInTimePeriod);
      } else {
         sp.cur_outReal = 0.0;
      }
   }

   private RetCode RogerssatchellOpenImpl( RogerssatchellStream sp, ReadOnlySpan<double> inOpen, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, double optInAnnualization, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double o = 0;
      double h = 0;
      double l = 0;
      double c = 0;
      double p1 = 0;
      double p2 = 0;
      double term = 0;
      double periodTotal = 0;
      double windowTotal = 0;
      double windowMagnitude = 0;
      double peakTotal = 0;
      double sqrtA = 0;
      int i = 0;
      int j = 0;
      int outIdx = 0;
      int nbInitialElementNeeded = 0;
      int barsSinceRebuild = 0;
      double[] termRing = [];
      int termRing_Idx = 0;
      int maxIdx_termRing = (32)-1;
      int historyLen = inOpen.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > IndexMax + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inHigh.Length != inOpen.Length || inLow.Length != inOpen.Length || inClose.Length != inOpen.Length ) {
         return RetCode.BadParam;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 10;
      } else if( optInTimePeriod < 1 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInAnnualization == RealDefault ) {
         optInAnnualization = 2.52e2;
      } else if( !(optInAnnualization >= 0e0 && optInAnnualization <= RealMax) ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      /* Each bar's term costs four logarithms, so it is computed once and kept
       * until it leaves the window. That also makes outReal safe to alias any
       * input: a bar is never read again once it has been consumed.
       */
      nbInitialElementNeeded = optInTimePeriod - 1;
      if( startIdx < nbInitialElementNeeded ) {
         startIdx = nbInitialElementNeeded;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      if( optInTimePeriod < 1 ) return RetCode.InternalError;
      termRing = new double[optInTimePeriod];
      maxIdx_termRing = (optInTimePeriod)-1;
      termRing_Idx = 0;
      /* Rogers and Satchell, The Annals of Applied Probability 1(4):504-512 (1991),
       * eq. (2): with the log price measured from the bar's open, S1 = ln(H/O),
       * I1 = ln(L/O) and X1 = ln(C/O), one bar's estimate of its variance is
       * S1(S1 - X1) + I1(I1 - X1) = ln(H/C)ln(H/O) + ln(L/C)ln(L/O), unbiased
       * whatever the drift. The window mean, the root and the annual scale are
       * convention, not the paper's.
       *
       * Keep sqrt(A) a separate factor applied last: A = 1.0 is then an exact
       * identity and the annualised output is exactly sqrt(A) times the per-bar
       * one. Folding A under the root moves both by an ulp.
       */
      sqrtA = Math.Sqrt(optInAnnualization);
      periodTotal = 0.0;
      for( j = startIdx - nbInitialElementNeeded; j < startIdx; j += 1 ) {
         /* Keep the two products separate statements. As one expression the
          * first product is fused into the add, which changes the values and
          * breaks bit equality with the same estimator composed from LN, DIV,
          * MULT, ADD and SUM.
          *
          * A bar with any price at or below zero contributes a 0.0 term and
          * still counts toward the window. The test is exact, not a band, so a
          * small-unit quote is not zeroed.
          */
         o = inOpen[j];
         h = inHigh[j];
         l = inLow[j];
         c = inClose[j];
         if( o > 0.0 && h > 0.0 && l > 0.0 && c > 0.0 ) {
            p1 = Math.Log(h / c) * Math.Log(h / o);
            p2 = Math.Log(l / c) * Math.Log(l / o);
            term = p1 + p2;
         } else {
            term = 0.0;
         }
         termRing[termRing_Idx] = term;
         periodTotal += term;
         termRing_Idx++;
         if( termRing_Idx > maxIdx_termRing ) { termRing_Idx = 0; }
      }
      i = startIdx;
      outIdx = 0;
      barsSinceRebuild = 32 * optInTimePeriod;
      peakTotal = Math.Abs(periodTotal);
      do {
         o = inOpen[i];
         h = inHigh[i];
         l = inLow[i];
         c = inClose[i];
         if( o > 0.0 && h > 0.0 && l > 0.0 && c > 0.0 ) {
            p1 = Math.Log(h / c) * Math.Log(h / o);
            p2 = Math.Log(l / c) * Math.Log(l / o);
            term = p1 + p2;
         } else {
            term = 0.0;
         }
         /* Add, publish, subtract: the slot written here was taken out of the
          * sum at the end of the previous bar, and the advance lands on the
          * oldest term, the one that leaves next.
          */
         termRing[termRing_Idx] = term;
         periodTotal += term;
         windowTotal = periodTotal;
         windowMagnitude = Math.Abs(windowTotal);
         peakTotal = MaxGt(windowMagnitude, peakTotal);
         termRing_Idx++;
         if( termRing_Idx > maxIdx_termRing ) { termRing_Idx = 0; }
         periodTotal -= termRing[termRing_Idx];
         /* A running sum carries rounding at the scale of the largest window it
          * has held, so it is rebuilt as a fresh sum once it falls below 1e-6 of
          * that peak, and at least every 32 windows. Compare against the peak,
          * not the current sum: after a quiet stretch arrives the current sum
          * can be nothing but that rounding, of either sign, where a fresh sum
          * of an all-flat window is exactly 0.0.
          *
          * Compare magnitudes. A window holding a bar whose high or low sits
          * inside its open and close can sum below zero, and a signed test
          * would then rebuild on every bar for as long as it does.
          *
          * Sum oldest first, so the rebuilt value is the one a fresh pass over
          * the bars gives.
          */
         barsSinceRebuild -= 1;
         if( windowMagnitude < 0.000001 * peakTotal || barsSinceRebuild <= 0 ) {
            barsSinceRebuild = 32 * optInTimePeriod;
            windowTotal = 0.0;
            for( j = termRing_Idx; j < optInTimePeriod; j += 1 ) {
               windowTotal += termRing[j];
            }
            for( j = 0; j < termRing_Idx; j += 1 ) {
               windowTotal += termRing[j];
            }
            peakTotal = Math.Abs(windowTotal);
            periodTotal = windowTotal;
            periodTotal -= termRing[termRing_Idx];
         }
         /* Divide, then root, then scale. A sum at or below zero answers 0.0
          * instead of reaching the root: only a bar whose high or low sits
          * strictly inside its open and close can make a fresh sum negative,
          * and the estimator is not defined on such a bar.
          */
         if( windowTotal > 0.0 ) {
            outReal[outIdx * outStride] = sqrtA * Math.Sqrt(windowTotal / (double)optInTimePeriod);
         } else {
            outReal[outIdx * outStride] = 0.0;
         }
         outIdx = outIdx + 1;
         i += 1;
      } while( i <= endIdx );
      outNBElement = outIdx;
      outBegIdx = startIdx;
      /* Capture the live batch state into the handle. */
      int capCb_termRing = maxIdx_termRing + 1;
      if( capCb_termRing > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      sp.optInTimePeriod = optInTimePeriod;
      sp.optInAnnualization = optInAnnualization;
      sp.periodTotal = periodTotal;
      sp.peakTotal = peakTotal;
      sp.sqrtA = sqrtA;
      sp.barsSinceRebuild = barsSinceRebuild;
      sp.termRing_Idx = termRing_Idx;
      sp.maxIdx_termRing = maxIdx_termRing;
      sp.cbSize_termRing = capCb_termRing;
      sp.cb_termRing = termRing;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* RogerssatchellOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal RogerssatchellStream RogerssatchellOpenAndFillInternal( ReadOnlySpan<double> inOpen, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, double optInAnnualization, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      RogerssatchellStream sp = new RogerssatchellStream(this);
      RetCode retCode = RogerssatchellOpenImpl(sp, inOpen, inHigh, inLow, inClose, startIdx, optInTimePeriod, optInAnnualization, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("ROGERSSATCHELL", "openAndFill", nameof(inOpen), inOpen.Length, startIdx, RogerssatchellLookback(optInTimePeriod, optInAnnualization));
      }
      throw StreamFailure("ROGERSSATCHELL", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind RogerssatchellOpen (composition seam). */
   internal RogerssatchellStream RogerssatchellOpenInternal( ReadOnlySpan<double> inOpen, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, double optInAnnualization )
   {
      RogerssatchellStream sp = new RogerssatchellStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = RogerssatchellOpenImpl(sp, inOpen, inHigh, inLow, inClose, startIdx, optInTimePeriod, optInAnnualization, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("ROGERSSATCHELL", "open", nameof(inOpen), inOpen.Length, startIdx, RogerssatchellLookback(optInTimePeriod, optInAnnualization));
      }
      throw StreamFailure("ROGERSSATCHELL", "open", retCode);
   }

   /// <summary>Open a live <c>ROGERSSATCHELL</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="RogerssatchellStream.Value"/> starts at the last
   /// history bar's value — bit-identical to what <c>ROGERSSATCHELL</c> reports
   /// for that bar.</para>
   /// <para>The history must hold at least <c>RogerssatchellLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>RogerssatchellOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inOpen">Open price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="RogerssatchellLookback"/> for its
   /// default and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInAnnualization">As in the batch call; see <see cref="RogerssatchellLookback"/> for its
   /// default and range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>RogerssatchellLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public RogerssatchellStream RogerssatchellOpen( ReadOnlySpan<double> inOpen, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInTimePeriod, double optInAnnualization )
   {
      if( inOpen.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inOpen), "ROGERSSATCHELL open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inOpen.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inOpen), "ROGERSSATCHELL open: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( inHigh.IsEmpty ) throw new TALibArgumentException("ROGERSSATCHELL open: inHigh is empty", nameof(inHigh), RetCode.BadParam);
      if( inLow.IsEmpty ) throw new TALibArgumentException("ROGERSSATCHELL open: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TALibArgumentException("ROGERSSATCHELL open: inClose is empty", nameof(inClose), RetCode.BadParam);
      RequireHistoryLength("ROGERSSATCHELL", "open", "inHigh", inHigh.Length, inOpen.Length);
      RequireHistoryLength("ROGERSSATCHELL", "open", "inLow", inLow.Length, inOpen.Length);
      RequireHistoryLength("ROGERSSATCHELL", "open", "inClose", inClose.Length, inOpen.Length);
      return RogerssatchellOpenInternal(inOpen, inHigh, inLow, inClose, 0, optInTimePeriod, optInAnnualization);
   }

   /// <summary><c>RogerssatchellOpen</c> that also fills the output array(s) over the
   /// whole history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>ROGERSSATCHELL</c>
   /// produces over the same series, so no separate batch call is needed for the
   /// warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - RogerssatchellLookback(...)</c>
   /// values and must not alias the inputs or each other — this path writes the
   /// outputs and then reads the input tail to seed its rings, so the batch
   /// tier's in-place allowance does not carry over here. Both are checked
   /// before anything is written, so an undersized span is an
   /// <c>ArgumentException</c> naming it rather than a fault from inside the
   /// fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="RogerssatchellStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inOpen">Open price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="RogerssatchellLookback"/> for its
   /// default and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInAnnualization">As in the batch call; see <see cref="RogerssatchellLookback"/> for its
   /// default and range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <param name="outReal">Estimated volatility, in log-return units. Must hold at least
   /// <c>historyLen - RogerssatchellLookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>RogerssatchellLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public RogerssatchellStream RogerssatchellOpenAndFill( ReadOnlySpan<double> inOpen, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInTimePeriod, double optInAnnualization, Span<double> outReal )
   {
      if( inOpen.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inOpen), "ROGERSSATCHELL openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inOpen.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inOpen), "ROGERSSATCHELL openAndFill: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( inHigh.IsEmpty ) throw new TALibArgumentException("ROGERSSATCHELL openAndFill: inHigh is empty", nameof(inHigh), RetCode.BadParam);
      if( inLow.IsEmpty ) throw new TALibArgumentException("ROGERSSATCHELL openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TALibArgumentException("ROGERSSATCHELL openAndFill: inClose is empty", nameof(inClose), RetCode.BadParam);
      int guardOutLen = OpenFillCount("ROGERSSATCHELL", "openAndFill", inOpen.Length, RogerssatchellLookback(optInTimePeriod, optInAnnualization));
      RequireHistoryLength("ROGERSSATCHELL", "openAndFill", "inHigh", inHigh.Length, inOpen.Length);
      RequireHistoryLength("ROGERSSATCHELL", "openAndFill", "inLow", inLow.Length, inOpen.Length);
      RequireHistoryLength("ROGERSSATCHELL", "openAndFill", "inClose", inClose.Length, inOpen.Length);
      RequireFillLength("ROGERSSATCHELL", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( SameBuffer(outReal, inOpen) || SameBuffer(outReal, inHigh) || SameBuffer(outReal, inLow) || SameBuffer(outReal, inClose) ) {
         throw StreamFailure("ROGERSSATCHELL", "openAndFill", RetCode.BadParam);
      }
      if( guardOutLen > 0 && ( outReal.Overlaps(inOpen) || outReal.Overlaps(inHigh) || outReal.Overlaps(inLow) || outReal.Overlaps(inClose) ) ) {
         throw StreamFailure("ROGERSSATCHELL", "openAndFill", RetCode.BadParam);
      }
      return RogerssatchellOpenAndFillInternal(inOpen, inHigh, inLow, inClose, 0, optInTimePeriod, optInAnnualization, out _, out _, outReal);
   }
