   /// <param name="startIdx">First bar of the requested range (inclusive).</param>
   /// <param name="endIdx">Last bar of the requested range (inclusive).</param>
   /// <param name="inOpen">Open price of each bar.</param>
   /// <param name="inHigh">High price of each bar.</param>
   /// <param name="inLow">Low price of each bar.</param>
   /// <param name="inClose">Close price of each bar.</param>
   /// <param name="optInTimePeriod">Number of bars in the window. <c>n = 1</c> is the paper's own single-bar
   /// estimator (default 10; range 1..100000; <c>int.MinValue</c> selects the
   /// default).</param>
   /// <param name="optInAnnualization">Periods per year. Pass 1 for the per-bar figure (default 252; minimum 0;
   /// <see cref="Core.RealDefault"/> selects the default).</param>
   /// <param name="outReal">Estimated volatility, in log-return units. Must hold at least <c>endIdx -
   /// max(startIdx, RogerssatchellLookback(...)) + 1</c> values, and never be
   /// empty: an empty span is an absent output.</param>
   /// <returns>The range written: <c>BegIdx</c> is the first bar with a value,
   /// <c>Count</c> how many were written.</returns>
   /// <exception cref="System.ArgumentOutOfRangeException"><c>startIdx</c> or <c>endIdx</c> is negative or above
   /// <see cref="Core.IndexMax"/>, or <c>endIdx &lt; startIdx</c>.</exception>
   /// <exception cref="System.ArgumentException">
   /// One of the following, checked before anything is written, so a rejected
   /// call leaves every buffer untouched:
   /// <list type="bullet">
   /// <item><description>An optional parameter is outside its documented range.</description></item>
   /// <item><description>A span is too short for the range requested: any input this function
   /// <i>declares</i> that does not reach <c>endIdx</c>, or an output that
   /// cannot hold the values produced. Declared, not read: a few candlestick
   /// patterns take an OHLC series they never index, and it is required all the
   /// same. A null array arrives as an empty span, and an empty span is an
   /// absent argument: for an input, or an output that cannot be declined, it is
   /// rejected even when the call would produce nothing.</description></item>
   /// <item><description>Two outputs overlap or are one array
   /// (<see href="https://ta-lib.org/spec/errors/#rb6">rule rB6</see>), or an
   /// output overlaps an input. An output and a real input never share an
   /// element type in this overload, so the two can never be the same span:
   /// there is no in-place case to allow, and any overlap of their byte ranges
   /// is rejected.</description></item>
   /// </list>
   /// </exception>
   /// <seealso cref="Core.Atr(int, int, ReadOnlySpan{double}, ReadOnlySpan{double}, ReadOnlySpan{double}, int, Span{double})"/>
   /// <seealso cref="Core.Natr(int, int, ReadOnlySpan{double}, ReadOnlySpan{double}, ReadOnlySpan{double}, int, Span{double})"/>
   /// <seealso cref="Core.Var(int, int, ReadOnlySpan{double}, int, double, Span{double})"/>
   public OutRange Rogerssatchell( int startIdx,
                                   int endIdx,
                                   ReadOnlySpan<float> inOpen,
                                   ReadOnlySpan<float> inHigh,
                                   ReadOnlySpan<float> inLow,
                                   ReadOnlySpan<float> inClose,
                                   int optInTimePeriod,
                                   double optInAnnualization,
                                   Span<double> outReal )
   {
      int guardStart = ClampedStart(startIdx, endIdx, RogerssatchellLookback(optInTimePeriod, optInAnnualization));
      int guardInLen = guardStart < 0 ? 0 : endIdx + 1;
      int guardOutLen = guardStart < 0 || guardStart > endIdx ? 0 : endIdx - guardStart + 1;
      RequireLength("ROGERSSATCHELL", "inOpen", inOpen.Length, guardInLen);
      RequireLength("ROGERSSATCHELL", "inHigh", inHigh.Length, guardInLen);
      RequireLength("ROGERSSATCHELL", "inLow", inLow.Length, guardInLen);
      RequireLength("ROGERSSATCHELL", "inClose", inClose.Length, guardInLen);
      if( guardStart >= 0 ) RequirePresent("ROGERSSATCHELL", "outReal", outReal.Length);
      RequireLength("ROGERSSATCHELL", "outReal", outReal.Length, guardOutLen);
      RetCode retCode = RogerssatchellImpl(startIdx, endIdx, inOpen, inHigh, inLow, inClose, optInTimePeriod, optInAnnualization, out int outBegIdx, out int outNBElement, outReal);
      if( retCode != RetCode.Success ) {
         throw Failure("ROGERSSATCHELL", retCode);
      }
      return new OutRange(outBegIdx, outNBElement);
   }
