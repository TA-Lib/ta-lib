         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Allocates nothing — neither handle state nor a return value.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so the handle is left exactly as it was and the stream stays usable: skip
      /// the bar, or re-open on a clean history. This is the one place the
      /// streaming tier is stricter than the batch API, which computes on whatever
      /// it is given: a handle retains its state, so a single non-finite bar would
      /// poison every later value it produces.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value at the bar just committed.</returns>
      public MINMAX_Value Update( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.StreamFailure("MINMAX", "update", RetCode.BadParam);
         core.MINMAX_StepImpl(this, inReal);
         if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         return new MINMAX_Value(cur_outMin, cur_outMax);
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — it is the same generated code, run on a copy. Never writes
      /// this handle, so peeks may run concurrently with each other.</para>
      /// <para>It runs on a fresh copy of this handle, so it allocates one — proportional
      /// to the state this indicator carries. If you peek on every tick and that
      /// matters, hold the value <see cref="Update"/> returns instead.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>What <see cref="Update"/> would return for this bar.</returns>
      public MINMAX_Value Peek( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.StreamFailure("MINMAX", "peek", RetCode.BadParam);
         MINMAX_Stream scratch = new MINMAX_Stream(this);
         core.MINMAX_StepImpl(scratch, inReal);
         return new MINMAX_Value(scratch.cur_outMin, scratch.cur_outMax);
      }

      /// <summary>Commit <c>n</c> closed bars and write their <c>n</c> values, in one call.</summary>
      /// <remarks>
      /// <para>Exactly <c>n</c> back-to-back <see cref="Update"/> calls, with one set of
      /// argument checks instead of <c>n</c>. The outputs must hold at least
      /// <c>n</c> values and must not overlap an input or each other.</para>
      /// <para><see cref="OutRange"/> counts what was committed, which is what makes a
      /// rejection readable: a non-finite bar <c>k</c> throws
      /// <see cref="System.ArgumentException"/> exactly as <see cref="Update"/>
      /// would, with bars <c>0..k</c> committed and written, bar <c>k</c> and
      /// everything after it not, and the count advanced by <c>k</c>.</para>
      /// </remarks>
      /// <param name="inReal">Closed bars for <c>inReal</c>, oldest first.</param>
      /// <param name="outMin">Receives one <c>outMin</c> value per bar committed.</param>
      /// <param name="outMax">Receives one <c>outMax</c> value per bar committed.</param>
      public void UpdateAndFill( ReadOnlySpan<double> inReal, Span<double> outMin, Span<double> outMax )
      {
         int barCount = inReal.Length;
         if( outMin.Length < barCount || outMax.Length < barCount || outMin.Overlaps(inReal) || outMax.Overlaps(inReal) || outMin.Overlaps(outMax) ) throw Core.StreamFailure("MINMAX", "updateAndFill", RetCode.BadParam);
         for( int i = 0; i < barCount; i++ )
         {
            if( !double.IsFinite(inReal[i]) ) throw Core.StreamFailure("MINMAX", "updateAndFill", RetCode.BadParam);
            core.MINMAX_StepImpl(this, inReal[i]);
            outMin[i] = cur_outMin;
            outMax[i] = cur_outMax;
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         }
      }

      /// <summary>The value at the most recently committed bar — the last history bar right
      /// after open, then whatever the latest <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public MINMAX_Value Value => new MINMAX_Value(cur_outMin, cur_outMax);

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public MINMAX_Stream Clone()
      {
         return new MINMAX_Stream(this);
      }
   }

   internal void MINMAX_StepImpl( MINMAX_Stream sp, double inReal )
   {
      double tmpHigh = 0.0;
      double tmpLow = 0.0;
      if( sp.today >= 1073741824 ) {
         int rebaseShift = sp.trailingIdx & ~sp.xMask;
         sp.today -= rebaseShift;
         sp.trailingIdx -= rebaseShift;
         sp.highestIdx -= rebaseShift;
         sp.i -= rebaseShift;
         sp.lowestIdx -= rebaseShift;
      }
      sp.x_inReal[sp.today & sp.xMask] = inReal;
      tmpHigh = sp.x_inReal[sp.today & sp.xMask];
      tmpLow = tmpHigh;
      if( sp.highestIdx < sp.trailingIdx ) {
         sp.highestIdx = sp.trailingIdx;
         sp.highest = sp.x_inReal[sp.highestIdx & sp.xMask];
         sp.i = sp.highestIdx;
         while( ++sp.i <= sp.today ) {
            tmpHigh = sp.x_inReal[sp.i & sp.xMask];
            if( tmpHigh > sp.highest ) {
               sp.highestIdx = sp.i;
               sp.highest = tmpHigh;
            }
         }
      } else if( tmpHigh >= sp.highest ) {
         sp.highestIdx = sp.today;
         sp.highest = tmpHigh;
      }
      if( sp.lowestIdx < sp.trailingIdx ) {
         sp.lowestIdx = sp.trailingIdx;
         sp.lowest = sp.x_inReal[sp.lowestIdx & sp.xMask];
         sp.i = sp.lowestIdx;
         while( ++sp.i <= sp.today ) {
            tmpLow = sp.x_inReal[sp.i & sp.xMask];
            if( tmpLow < sp.lowest ) {
               sp.lowestIdx = sp.i;
               sp.lowest = tmpLow;
            }
         }
      } else if( tmpLow <= sp.lowest ) {
         sp.lowestIdx = sp.today;
         sp.lowest = tmpLow;
      }
      sp.cur_outMax = sp.highest;
      sp.cur_outMin = sp.lowest;
      sp.trailingIdx += 1;
      sp.today += 1;
   }

   private RetCode MINMAX_OpenImpl( MINMAX_Stream sp, ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outMin, Span<double> outMax, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double highest = 0;
      double lowest = 0;
      double tmpHigh = 0;
      double tmpLow = 0;
      int outIdx = 0;
      int nbInitialElementNeeded = 0;
      int trailingIdx = 0;
      int today = 0;
      int i = 0;
      int highestIdx = 0;
      int lowestIdx = 0;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.BadParam;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 30;
      } else if( optInTimePeriod < 2 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      /* Identify the minimum number of price bar needed
       * to identify at least one output over the specified
       * period.
       */
      nbInitialElementNeeded = optInTimePeriod - 1;
      /* Move up the start index if there is not
       * enough initial data.
       */
      if( startIdx < nbInitialElementNeeded ) {
         startIdx = nbInitialElementNeeded;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      /* Proceed with the calculation for the requested range.
       * Note that this algorithm allows the input and
       * output to be the same buffer.
       *
       * The highest and lowest values of the window are cached with their
       * indices; the window is rescanned only when a cached extremum drops out
       * of it. That is O(1)
       * per bar while the extremum sits away from the trailing edge, but it is
       * not amortized O(1): an extremum on the oldest in-window bar drops out
       * on the very next bar, so the rescan repeats and the cost stays
       * O(period) per bar for as long as that persists.
       *
       * Tracking both extrema keeps that state going through a trend: while
       * the high is refreshed by each new bar, the low stays pinned at the
       * oldest bar for the whole leg (and the reverse on the way down). A flat
       * stretch pins both. Random-walk input is the favourable case, where
       * rescans are rare.
       *
       * Slower than the block scan the batch tier runs; it is here because one
       * bar at a time is exactly what the streaming tier needs. See issue #147.
       */
      outIdx = 0;
      today = startIdx;
      trailingIdx = startIdx - nbInitialElementNeeded;
      highestIdx = 0 - 1;
      highest = 0.0;
      lowestIdx = 0 - 1;
      lowest = 0.0;
      while( today <= endIdx ) {
         tmpHigh = inReal[today];
         tmpLow = tmpHigh;
         if( highestIdx < trailingIdx ) {
            highestIdx = trailingIdx;
            highest = inReal[highestIdx];
            i = highestIdx;
            while( ++i <= today ) {
               tmpHigh = inReal[i];
               if( tmpHigh > highest ) {
                  highestIdx = i;
                  highest = tmpHigh;
               }
            }
         } else if( tmpHigh >= highest ) {
            highestIdx = today;
            highest = tmpHigh;
         }
         if( lowestIdx < trailingIdx ) {
            lowestIdx = trailingIdx;
            lowest = inReal[lowestIdx];
            i = lowestIdx;
            while( ++i <= today ) {
               tmpLow = inReal[i];
               if( tmpLow < lowest ) {
                  lowestIdx = i;
                  lowest = tmpLow;
               }
            }
         } else if( tmpLow <= lowest ) {
            lowestIdx = today;
            lowest = tmpLow;
         }
         outMax[outIdx * outStride] = highest;
         outMin[outIdx * outStride] = lowest;
         outIdx += 1;
         trailingIdx += 1;
         today += 1;
      }
      /* Keep the outBegIdx relative to the
       * caller input before returning.
       */
      outBegIdx = startIdx;
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      int capX = today - trailingIdx + 1;
      if( capX < 1 || capX > historyLen ) {
         return RetCode.InternalError;
      }
      int physX = 1;
      while( physX < capX ) {
         physX <<= 1;
      }
      double[] capX_inReal = new double[physX];
      for( int fillJ = historyLen - capX; fillJ < historyLen; fillJ++ ) {
         capX_inReal[fillJ & (physX - 1)] = inReal[fillJ];
      }
      sp.optInTimePeriod = optInTimePeriod;
      sp.highest = highest;
      sp.lowest = lowest;
      sp.trailingIdx = trailingIdx;
      sp.highestIdx = highestIdx;
      sp.lowestIdx = lowestIdx;
      sp.i = i;
      sp.today = today;
      sp.xMask = physX - 1;
      sp.x_inReal = capX_inReal;
      sp.cur_outMin = outMin[(outNBElement - 1) * outStride];
      sp.cur_outMax = outMax[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* MINMAX_OpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal MINMAX_Stream MINMAX_OpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outMin, Span<double> outMax )
   {
      MINMAX_Stream sp = new MINMAX_Stream(this);
      RetCode retCode = MINMAX_OpenImpl(sp, inReal, startIdx, optInTimePeriod, out outBegIdx, out outNBElement, outMin, outMax, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("MINMAX", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind MINMAX_Open (composition seam). */
   internal MINMAX_Stream MINMAX_OpenInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod )
   {
      MINMAX_Stream sp = new MINMAX_Stream(this);
      double[] sink_outMin = new double[1];
      double[] sink_outMax = new double[1];
      RetCode retCode = MINMAX_OpenImpl(sp, inReal, startIdx, optInTimePeriod, out int outBegIdx, out int outNBElement, sink_outMin, sink_outMax, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("MINMAX", "open", retCode);
   }

   /// <summary>Open a live <c>MINMAX</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="MINMAX_Stream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>MINMAX</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>MINMAX_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>MINMAX_OpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">Values scanned for the window min and max. The warm-up history, oldest bar
   /// first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="MINMAX_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>MINMAX_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentException">An input series is empty — which is what a null array becomes, since a
   /// span cannot be null.</exception>
   public MINMAX_Stream MINMAX_Open( ReadOnlySpan<double> inReal, int optInTimePeriod )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentException("inReal is empty", nameof(inReal), RetCode.BadParam);
      return MINMAX_OpenInternal(inReal, 0, optInTimePeriod);
   }

   /// <summary><c>MINMAX_Open</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>MINMAX</c> produces over
   /// the same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - MINMAX_Lookback(...)</c> values
   /// and must not alias the inputs or each other — this path writes the outputs
   /// and then reads the input tail to seed its rings, so the batch tier's
   /// in-place allowance does not carry over here.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="MINMAX_Stream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">Values scanned for the window min and max. The warm-up history, oldest bar
   /// first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="MINMAX_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outMin">Lowest value in each rolling window. Must hold at least <c>historyLen -
   /// MINMAX_Lookback(...)</c> values.</param>
   /// <param name="outMax">Highest value in each rolling window. Must hold at least <c>historyLen -
   /// MINMAX_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>MINMAX_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, or an output array aliases an input or another
   /// output.</exception>
   /// <exception cref="System.ArgumentException">An input series is empty, or an output overlaps an input or another
   /// output.</exception>
   public MINMAX_Stream MINMAX_OpenAndFill( ReadOnlySpan<double> inReal, int optInTimePeriod, Span<double> outMin, Span<double> outMax )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentException("inReal is empty", nameof(inReal), RetCode.BadParam);
      if( outMin.Overlaps(inReal) || outMax.Overlaps(inReal) || outMin.Overlaps(outMax) ) {
         throw StreamFailure("MINMAX", "openAndFill", RetCode.BadParam);
      }
      return MINMAX_OpenAndFillInternal(inReal, 0, optInTimePeriod, out _, out _, outMin, outMax);
   }
