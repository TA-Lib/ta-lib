   /// <summary>A live <c>FRAMA</c> stream: one value per closed bar, bit-identical to
   /// <c>FRAMA</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.FramaOpen"/>. There is no close and nothing to
   /// dispose — the handle is ordinary managed state, and an unreferenced handle
   /// is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class FramaStream
   {
      internal Core core;
      internal int optInTimePeriod;
      internal double expScale;
      internal double preHigh;
      internal double preLow;
      internal double prevFRAMA;
      internal int lastSlot;
      internal int slot_Idx;
      internal int maxIdx_slot;
      internal int cbSize_slot;
      internal double[] cb_slot_sufHigh = [];
      internal double[] cb_slot_sufLow = [];
      internal double[] cb_slot_oldHigh = [];
      internal double[] cb_slot_oldLow = [];
      internal double cur_outReal;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal FramaStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Frama</c> reports over the same bars: the opener sets
      /// it to <c>(lookback, historyLen - lookback)</c>, every accepted
      /// <c>Update</c> adds one to the count — a rejected one changes nothing, and
      /// neither does <c>Peek</c> — and <c>Clone</c> carries it verbatim. A plain
      /// <c>Open</c> hands back only the last value, a subset of this range,
      /// because the caller chose not to take the fill.</para>
      /// <para>The last bar it can reach is <see cref="Core.IndexMax"/>; past that
      /// <c>Update</c> and <c>Advance</c> throw.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      /// <summary>Count one bar this stream was not fed: <see cref="OutRange"/> advances by
      /// one and nothing else moves.</summary>
      /// <remarks>
      /// <para><see cref="Value"/> keeps answering the previous output, which is this
      /// bar's output too. For a bar the caller leaves out: one an <c>Update</c>
      /// rejected and that will not be re-fed, or a session with no print. Without
      /// it two handles on one feed drift a bar apart when only one of them skips.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, the last one the batch tier
      /// can address and the last this handle will count. <c>Update</c> throws the
      /// same there.</para>
      /// </remarks>
      public void Advance()
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("FRAMA", "advance", RetCode.OutOfRangeEndIndex);
         outRangeCount++;
      }

      internal FramaStream( FramaStream other )
      {
         this.core = other.core;
         this.optInTimePeriod = other.optInTimePeriod;
         this.expScale = other.expScale;
         this.preHigh = other.preHigh;
         this.preLow = other.preLow;
         this.prevFRAMA = other.prevFRAMA;
         this.lastSlot = other.lastSlot;
         this.slot_Idx = other.slot_Idx;
         this.maxIdx_slot = other.maxIdx_slot;
         this.cbSize_slot = other.cbSize_slot;
         this.cb_slot_sufHigh = new double[other.cb_slot_sufHigh.Length];
         Array.Copy( other.cb_slot_sufHigh, this.cb_slot_sufHigh, other.cb_slot_sufHigh.Length );
         this.cb_slot_sufLow = new double[other.cb_slot_sufLow.Length];
         Array.Copy( other.cb_slot_sufLow, this.cb_slot_sufLow, other.cb_slot_sufLow.Length );
         this.cb_slot_oldHigh = new double[other.cb_slot_oldHigh.Length];
         Array.Copy( other.cb_slot_oldHigh, this.cb_slot_oldHigh, other.cb_slot_oldHigh.Length );
         this.cb_slot_oldLow = new double[other.cb_slot_oldLow.Length];
         Array.Copy( other.cb_slot_oldLow, this.cb_slot_oldLow, other.cb_slot_oldLow.Length );
         this.cur_outReal = other.cur_outReal;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Allocates nothing — neither handle state nor a return value.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so nothing moves — <see cref="OutRange"/> included — and
      /// <see cref="Value"/> still answers the previous value. Re-feed the bar when
      /// a corrected value arrives, or call <see cref="Advance"/> to count it and
      /// carry on; two handles on one feed drift a bar apart if neither happens.
      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, which no re-feed clears: the
      /// handle has run out of index domain and only a shorter history can start a
      /// new one.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inHigh, double inLow )
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("FRAMA", "update", RetCode.OutOfRangeEndIndex);
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) ) throw Core.NonFiniteBar("FRAMA", "update", !double.IsFinite(inHigh) ? nameof(inHigh) : nameof(inLow));
         core.FramaStepImpl(this, inHigh, inLow);
         outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.IndexMax"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public double Peek( double inHigh, double inLow )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) ) throw Core.NonFiniteBar("FRAMA", "peek", !double.IsFinite(inHigh) ? nameof(inHigh) : nameof(inLow));
         FramaStream sp = this;
         double tmpHigh = 0.0;
         double tmpLow = 0.0;
         double hi1 = 0.0;
         double lo1 = 0.0;
         double hi2 = 0.0;
         double lo2 = 0.0;
         double r1 = 0.0;
         double r2 = 0.0;
         double r = 0.0;
         double price = 0.0;
         double alpha = 0.0;
         double cur_outReal = 0.0;
         double preHigh = sp.preHigh;
         double preLow = sp.preLow;
         double prevFRAMA = sp.prevFRAMA;
         tmpHigh = inHigh;
         tmpLow = inLow;
         price = (tmpHigh + tmpLow) / 2.0;
         if( sp.slot_Idx == 0 ) {
            preHigh = tmpHigh;
            preLow = tmpLow;
         } else {
            preHigh = MaxGt(tmpHigh, preHigh);
            preLow = MinLt(tmpLow, preLow);
         }
         if( sp.slot_Idx == sp.lastSlot ) {
            hi1 = preHigh;
            lo1 = preLow;
         } else {
            hi1 = sp.cb_slot_sufHigh[sp.slot_Idx + 1];
            hi1 = MaxGt(preHigh, hi1);
            lo1 = sp.cb_slot_sufLow[sp.slot_Idx + 1];
            lo1 = MinLt(preLow, lo1);
         }
         hi2 = sp.cb_slot_oldHigh[sp.slot_Idx];
         lo2 = sp.cb_slot_oldLow[sp.slot_Idx];
         r1 = hi1 - lo1;
         r2 = hi2 - lo2;
         r = (MaxGt(hi1, hi2)) - (MinLt(lo1, lo2));
         /* R >= max(R1,R2) makes R1+R2 <= R exactly the alpha >= 1 clamp, so a
          * clamped or flat bar returns the price with no transcendental. Keep the
          * recursion as alpha*P + (1-alpha)*prev: a computed alpha of 1.0 then
          * returns the price exactly too.
          */
         if( r1 > 0.0 && r2 > 0.0 && r1 + r2 > r ) {
            alpha = Math.Exp(sp.expScale * Math.Log((r1 + r2) / r));
            prevFRAMA = Math.FusedMultiplyAdd(1.0 - alpha, prevFRAMA, alpha * price);
         } else {
            prevFRAMA = price;
         }
         cur_outReal = prevFRAMA;
         return cur_outReal;
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public FramaStream Clone()
      {
         return new FramaStream(this);
      }
   }

   private void FramaStepImpl( FramaStream sp, double inHigh, double inLow )
   {
      double tmpHigh = 0.0;
      double tmpLow = 0.0;
      double hi1 = 0.0;
      double lo1 = 0.0;
      double hi2 = 0.0;
      double lo2 = 0.0;
      double r1 = 0.0;
      double r2 = 0.0;
      double r = 0.0;
      double price = 0.0;
      double alpha = 0.0;
      int i = 0;
      tmpHigh = inHigh;
      tmpLow = inLow;
      price = (tmpHigh + tmpLow) / 2.0;
      if( sp.slot_Idx == 0 ) {
         sp.preHigh = tmpHigh;
         sp.preLow = tmpLow;
      } else {
         sp.preHigh = MaxGt(tmpHigh, sp.preHigh);
         sp.preLow = MinLt(tmpLow, sp.preLow);
      }
      if( sp.slot_Idx == sp.lastSlot ) {
         hi1 = sp.preHigh;
         lo1 = sp.preLow;
      } else {
         hi1 = sp.cb_slot_sufHigh[sp.slot_Idx + 1];
         hi1 = MaxGt(sp.preHigh, hi1);
         lo1 = sp.cb_slot_sufLow[sp.slot_Idx + 1];
         lo1 = MinLt(sp.preLow, lo1);
      }
      hi2 = sp.cb_slot_oldHigh[sp.slot_Idx];
      lo2 = sp.cb_slot_oldLow[sp.slot_Idx];
      r1 = hi1 - lo1;
      r2 = hi2 - lo2;
      r = (MaxGt(hi1, hi2)) - (MinLt(lo1, lo2));
      /* R >= max(R1,R2) makes R1+R2 <= R exactly the alpha >= 1 clamp, so a
       * clamped or flat bar returns the price with no transcendental. Keep the
       * recursion as alpha*P + (1-alpha)*prev: a computed alpha of 1.0 then
       * returns the price exactly too.
       */
      if( r1 > 0.0 && r2 > 0.0 && r1 + r2 > r ) {
         alpha = Math.Exp(sp.expScale * Math.Log((r1 + r2) / r));
         sp.prevFRAMA = Math.FusedMultiplyAdd(1.0 - alpha, sp.prevFRAMA, alpha * price);
      } else {
         sp.prevFRAMA = price;
      }
      sp.cur_outReal = sp.prevFRAMA;
      sp.cb_slot_oldHigh[sp.slot_Idx] = hi1;
      sp.cb_slot_oldLow[sp.slot_Idx] = lo1;
      sp.cb_slot_sufHigh[sp.slot_Idx] = tmpHigh;
      sp.cb_slot_sufLow[sp.slot_Idx] = tmpLow;
      if( sp.slot_Idx == sp.lastSlot ) {
         i = sp.lastSlot;
         while( i > 0 ) {
            i -= 1;
            if( sp.cb_slot_sufHigh[i + 1] > sp.cb_slot_sufHigh[i] ) {
               sp.cb_slot_sufHigh[i] = sp.cb_slot_sufHigh[i + 1];
            }
            if( sp.cb_slot_sufLow[i + 1] < sp.cb_slot_sufLow[i] ) {
               sp.cb_slot_sufLow[i] = sp.cb_slot_sufLow[i + 1];
            }
         }
      }
      sp.slot_Idx = sp.slot_Idx + 1;
      if( sp.slot_Idx > sp.maxIdx_slot ) {
         sp.slot_Idx = 0;
      }
   }

   private RetCode FramaOpenImpl( FramaStream sp, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double expScale = 0;
      double[] slot_sufHigh = [];
      double[] slot_sufLow = [];
      double[] slot_oldHigh = [];
      double[] slot_oldLow = [];
      int slot_Idx = 0;
      int maxIdx_slot = (32)-1;
      double tmpHigh = 0;
      double tmpLow = 0;
      double preHigh = 0;
      double preLow = 0;
      double hi1 = 0;
      double lo1 = 0;
      double hi2 = 0;
      double lo2 = 0;
      double r1 = 0;
      double r2 = 0;
      double r = 0;
      double price = 0;
      double alpha = 0;
      double prevFRAMA = 0;
      int i = 0;
      int today = 0;
      int outIdx = 0;
      int lookbackTotal = 0;
      int half = 0;
      int lastSlot = 0;
      int seedIdx = 0;
      int historyLen = inHigh.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > IndexMax + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inLow.Length != inHigh.Length ) {
         return RetCode.BadParam;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 16;
      } else if( optInTimePeriod < 2 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      expScale = -4.6 / 0.6931471805599453;
      /* -4.6/ln(2): alpha = exp(-4.6*(D-1)) with D-1 = log2((R1+R2)/R). */
      /* Id, Type, Static Size */
      outBegIdx = 0;
      outNBElement = 0;
      if( optInTimePeriod % 2 != 0 ) {
         return RetCode.BadParam ;
      }
      lookbackTotal = optInTimePeriod + this._unstablePeriod[(int)FuncUnstId.FRAMA];
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      if( startIdx > endIdx ) {
         return RetCode.InsufficientHistory ;
      }
      half = optInTimePeriod / 2;
      lastSlot = half - 1;
      /* van Herk / Gil-Werman over blocks of `half` bars. Slot j holds the current
       * block's bar j (or, past the running position, the previous block's suffix
       * extremes), and in oldHigh/oldLow the newer half's extremes from `half` bars
       * ago, which are the older half's extremes now: R2[t] = R1[t-half].
       *
       * Every slot store must stay below the output store: that is what keeps the
       * stream's Peek read-only and O(1). The slots hold copies, so outReal may
       * alias an input.
       */
      if( half < 1 ) return RetCode.InternalError;
      slot_sufHigh = new double[half];
      slot_sufLow = new double[half];
      slot_oldHigh = new double[half];
      slot_oldLow = new double[half];
      maxIdx_slot = (half)-1;
      slot_Idx = 0;
      today = startIdx - lookbackTotal + 1;
      seedIdx = startIdx - this._unstablePeriod[(int)FuncUnstId.FRAMA] - 1;
      /* The first block's suffix reads must see a bar inside the window. */
      i = 0;
      while( i < half ) {
         slot_sufHigh[i] = inHigh[today];
         slot_sufLow[i] = inLow[today];
         slot_oldHigh[i] = inHigh[today];
         slot_oldLow[i] = inLow[today];
         i += 1;
      }
      preHigh = 0.0;
      preLow = 0.0;
      /* Through seedIdx only the blocks are built: the seed discards every value
       * before it, so no alpha is computed there.
       */
      while( today <= seedIdx ) {
         tmpHigh = inHigh[today];
         tmpLow = inLow[today];
         if( slot_Idx == 0 ) {
            preHigh = tmpHigh;
            preLow = tmpLow;
         } else {
            preHigh = MaxGt(tmpHigh, preHigh);
            preLow = MinLt(tmpLow, preLow);
         }
         if( slot_Idx == lastSlot ) {
            hi1 = preHigh;
            lo1 = preLow;
         } else {
            hi1 = slot_sufHigh[slot_Idx + 1];
            hi1 = MaxGt(preHigh, hi1);
            lo1 = slot_sufLow[slot_Idx + 1];
            lo1 = MinLt(preLow, lo1);
         }
         slot_oldHigh[slot_Idx] = hi1;
         slot_oldLow[slot_Idx] = lo1;
         slot_sufHigh[slot_Idx] = tmpHigh;
         slot_sufLow[slot_Idx] = tmpLow;
         if( slot_Idx == lastSlot ) {
            i = lastSlot;
            while( i > 0 ) {
               i -= 1;
               if( slot_sufHigh[i + 1] > slot_sufHigh[i] ) {
                  slot_sufHigh[i] = slot_sufHigh[i + 1];
               }
               if( slot_sufLow[i + 1] < slot_sufLow[i] ) {
                  slot_sufLow[i] = slot_sufLow[i + 1];
               }
            }
         }
         slot_Idx++;
         if( slot_Idx > maxIdx_slot ) { slot_Idx = 0; }
         today += 1;
      }
      prevFRAMA = (inHigh[seedIdx] + inLow[seedIdx]) / 2.0;
      outIdx = 0;
      while( today <= endIdx ) {
         tmpHigh = inHigh[today];
         tmpLow = inLow[today];
         price = (tmpHigh + tmpLow) / 2.0;
         if( slot_Idx == 0 ) {
            preHigh = tmpHigh;
            preLow = tmpLow;
         } else {
            preHigh = MaxGt(tmpHigh, preHigh);
            preLow = MinLt(tmpLow, preLow);
         }
         if( slot_Idx == lastSlot ) {
            hi1 = preHigh;
            lo1 = preLow;
         } else {
            hi1 = slot_sufHigh[slot_Idx + 1];
            hi1 = MaxGt(preHigh, hi1);
            lo1 = slot_sufLow[slot_Idx + 1];
            lo1 = MinLt(preLow, lo1);
         }
         hi2 = slot_oldHigh[slot_Idx];
         lo2 = slot_oldLow[slot_Idx];
         r1 = hi1 - lo1;
         r2 = hi2 - lo2;
         r = (MaxGt(hi1, hi2)) - (MinLt(lo1, lo2));
         /* R >= max(R1,R2) makes R1+R2 <= R exactly the alpha >= 1 clamp, so a
          * clamped or flat bar returns the price with no transcendental. Keep the
          * recursion as alpha*P + (1-alpha)*prev: a computed alpha of 1.0 then
          * returns the price exactly too.
          */
         if( r1 > 0.0 && r2 > 0.0 && r1 + r2 > r ) {
            alpha = Math.Exp(expScale * Math.Log((r1 + r2) / r));
            prevFRAMA = Math.FusedMultiplyAdd(1.0 - alpha, prevFRAMA, alpha * price);
         } else {
            prevFRAMA = price;
         }
         if( today >= startIdx ) {
            outReal[outIdx++ * outStride] = prevFRAMA;
         }
         slot_oldHigh[slot_Idx] = hi1;
         slot_oldLow[slot_Idx] = lo1;
         slot_sufHigh[slot_Idx] = tmpHigh;
         slot_sufLow[slot_Idx] = tmpLow;
         if( slot_Idx == lastSlot ) {
            i = lastSlot;
            while( i > 0 ) {
               i -= 1;
               if( slot_sufHigh[i + 1] > slot_sufHigh[i] ) {
                  slot_sufHigh[i] = slot_sufHigh[i + 1];
               }
               if( slot_sufLow[i + 1] < slot_sufLow[i] ) {
                  slot_sufLow[i] = slot_sufLow[i + 1];
               }
            }
         }
         slot_Idx++;
         if( slot_Idx > maxIdx_slot ) { slot_Idx = 0; }
         today += 1;
      }
      outBegIdx = startIdx;
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      int capCb_slot = maxIdx_slot + 1;
      if( capCb_slot > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      sp.optInTimePeriod = optInTimePeriod;
      sp.expScale = expScale;
      sp.preHigh = preHigh;
      sp.preLow = preLow;
      sp.prevFRAMA = prevFRAMA;
      sp.lastSlot = lastSlot;
      sp.slot_Idx = slot_Idx;
      sp.maxIdx_slot = maxIdx_slot;
      sp.cbSize_slot = capCb_slot;
      sp.cb_slot_sufHigh = slot_sufHigh;
      sp.cb_slot_sufLow = slot_sufLow;
      sp.cb_slot_oldHigh = slot_oldHigh;
      sp.cb_slot_oldLow = slot_oldLow;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* FramaOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal FramaStream FramaOpenAndFillInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      FramaStream sp = new FramaStream(this);
      RetCode retCode = FramaOpenImpl(sp, inHigh, inLow, startIdx, optInTimePeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("FRAMA", "openAndFill", nameof(inHigh), inHigh.Length, startIdx, FramaLookback(optInTimePeriod));
      }
      throw StreamFailure("FRAMA", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind FramaOpen (composition seam). */
   internal FramaStream FramaOpenInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int startIdx, int optInTimePeriod )
   {
      FramaStream sp = new FramaStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = FramaOpenImpl(sp, inHigh, inLow, startIdx, optInTimePeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("FRAMA", "open", nameof(inHigh), inHigh.Length, startIdx, FramaLookback(optInTimePeriod));
      }
      throw StreamFailure("FRAMA", "open", retCode);
   }

   /// <summary>Open a live <c>FRAMA</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="FramaStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>FRAMA</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>FramaLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>FramaOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="FramaLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>FramaLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules S1 and S2).</exception>
   public FramaStream FramaOpen( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int optInTimePeriod )
   {
      if( inHigh.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "FRAMA open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "FRAMA open: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TALibArgumentException("FRAMA open: inLow is empty", nameof(inLow), RetCode.BadParam);
      RequireHistoryLength("FRAMA", "open", "inLow", inLow.Length, inHigh.Length);
      return FramaOpenInternal(inHigh, inLow, 0, optInTimePeriod);
   }

   /// <summary><c>FramaOpen</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>FRAMA</c> produces over
   /// the same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - FramaLookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="FramaStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="FramaLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Adaptive moving average line. Must hold at least <c>historyLen -
   /// FramaLookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>FramaLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules S1 and S2).</exception>
   public FramaStream FramaOpenAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int optInTimePeriod, Span<double> outReal )
   {
      if( inHigh.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "FRAMA openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "FRAMA openAndFill: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TALibArgumentException("FRAMA openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      int guardOutLen = OpenFillCount("FRAMA", "openAndFill", inHigh.Length, FramaLookback(optInTimePeriod));
      RequireHistoryLength("FRAMA", "openAndFill", "inLow", inLow.Length, inHigh.Length);
      RequireFillLength("FRAMA", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( outReal.Overlaps(inHigh) || outReal.Overlaps(inLow) ) {
         throw StreamFailure("FRAMA", "openAndFill", RetCode.BadParam);
      }
      return FramaOpenAndFillInternal(inHigh, inLow, 0, optInTimePeriod, out _, out _, outReal);
   }
