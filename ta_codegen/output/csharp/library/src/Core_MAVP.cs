   /// NaN. A valid range shorter than <c>MovingAverageVariablePeriodLookback</c>
   /// is a <b>success with no values</b> (<c>Count == 0</c>), not an error.
   /// </para>
   /// </remarks>
   /// <param name="startIdx">First bar of the requested range (inclusive).</param>
   /// <param name="endIdx">Last bar of the requested range (inclusive).</param>
   /// <param name="inReal">series to be averaged.</param>
   /// <param name="inPeriods">per-bar desired MA period.</param>
   /// <param name="optInMinPeriod">Lower clamp for the per-bar period (default 2; range 1..100000;
   /// <c>int.MinValue</c> selects the default).</param>
   /// <param name="optInMaxPeriod">Upper clamp for the per-bar period (default 30; range 1..100000;
   /// <c>int.MinValue</c> selects the default).</param>
   /// <param name="optInMAType">Moving-average type applied (default 0 = SMA; values: 0=SMA, 1=EMA, 2=WMA,
   /// 3=DEMA, 4=TEMA, 5=TRIMA, 6=KAMA, 7=MAMA, 8=T3, 9=HMA, 10=DISABLED;
   /// <c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">variable-period moving average. Must hold at least <c>endIdx - startIdx +
   /// 1</c> values.</param>
   /// <returns>The range written: <c>BegIdx</c> is the first bar with a value,
   /// <c>Count</c> how many were written.</returns>
   /// <exception cref="System.ArgumentOutOfRangeException"><c>startIdx</c> or <c>endIdx</c> is negative, or <c>endIdx &lt;
   /// startIdx</c>.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or two outputs
   /// share one array.</exception>
   /// <exception cref="System.NullReferenceException">An input or output array is null. (Unlike the C library, the managed tier
   /// does not pre-validate nulls; the first array access throws.)</exception>
   public OutRange MovingAverageVariablePeriod( int startIdx,
                                                int endIdx,
                                                float[] inReal,
                                                float[] inPeriods,
                                                int optInMinPeriod,
                                                int optInMaxPeriod,
                                                MAType optInMAType,
                                                double[] outReal )
   {
      RetCode retCode = MovingAverageVariablePeriod(startIdx, endIdx, inReal, inPeriods, optInMinPeriod, optInMaxPeriod, optInMAType, out int outBegIdx, out int outNBElement, outReal);
      if( retCode != RetCode.Success ) {
         throw Failure("MAVP", retCode);
      }
      return new OutRange(outBegIdx, outNBElement);
   }
