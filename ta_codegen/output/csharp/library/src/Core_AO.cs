      /// handle retains its state, so a single non-finite bar would poison every
      /// later value it produces.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inHigh, double inLow )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) )
         {
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
            throw Core.StreamFailure("AO", "update", RetCode.BadParam);
         }
         core.AoStepImpl(this, inHigh, inLow);
         if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It copies nothing: the frame runs against this handle, reading its buffers
      /// and holding what the step would commit in locals. The cost does not grow
      /// with the period, and <c>Peek</c> never allocates.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <returns>What <see cref="Update"/> would return for this bar.</returns>
      public double Peek( double inHigh, double inLow )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) ) throw Core.StreamFailure("AO", "peek", RetCode.BadParam);
         AoStream sp = this;
         double medianPrice = 0.0;
         double tempReal = 0.0;
         double cur_outReal = sp.cur_outReal;
         int ringPos_trailingFastIdx = sp.ringPos_trailingFastIdx;
         int ringPos_trailingSlowIdx = sp.ringPos_trailingSlowIdx;
         double sumFast = sp.sumFast;
         double sumSlow = sp.sumSlow;
         int pkSlot0 = -1;
         double pkVal0 = 0.0;
         int pkSlot1 = -1;
         double pkVal1 = 0.0;
         if( sp.ringCap_trailingFastIdx == 0 ) {
            pkSlot0 = 0;
            pkVal0 = (inHigh + inLow) / 2.0;
         }
         if( sp.ringCap_trailingSlowIdx == 0 ) {
            pkSlot1 = 0;
            pkVal1 = (inHigh + inLow) / 2.0;
         }
         medianPrice = (inHigh + inLow) / 2.0;
         sumFast += medianPrice;
         sumSlow += medianPrice;
         /* Snapshot the oscillator before either total drops its trailing bar,
          * mirroring the add-new / snapshot / subtract-old order of TA_SMA.
          */
         tempReal = sumFast / (double)sp.optInFastPeriod - sumSlow / (double)sp.optInSlowPeriod;
         /* Read both trailing bars before writing the output. When startIdx is
          * clamped to the lookback the longer window's trailing index equals
          * outIdx exactly, so a store hoisted above this would read back the
          * value it had just overwritten whenever the caller aliases outReal
          * over inHigh or inLow.
          */
         sumFast -= (ringPos_trailingFastIdx != pkSlot0) ? sp.ring_trailingFastIdx_derived[ringPos_trailingFastIdx] : pkVal0;
         sumSlow -= (ringPos_trailingSlowIdx != pkSlot1) ? sp.ring_trailingSlowIdx_derived[ringPos_trailingSlowIdx] : pkVal1;
         cur_outReal = tempReal;
         ringPos_trailingFastIdx = ringPos_trailingFastIdx + 1;
         if( ringPos_trailingFastIdx >= sp.ringCap_trailingFastIdx ) {
            ringPos_trailingFastIdx = 0;
         }
         ringPos_trailingSlowIdx = ringPos_trailingSlowIdx + 1;
         if( ringPos_trailingSlowIdx >= sp.ringCap_trailingSlowIdx ) {
            ringPos_trailingSlowIdx = 0;
         }
         return cur_outReal;
      }

      /// <summary>Commit <c>n</c> closed bars and write their <c>n</c> values, in one call.</summary>
      /// <remarks>
      /// <para>Exactly <c>n</c> back-to-back <see cref="Update"/> calls, with one set of
      /// argument checks instead of <c>n</c>. The outputs must hold at least
      /// <c>n</c> values and must not overlap an input or each other.</para>
      /// <para><see cref="OutRange"/> counts what this call took in, which is what makes
      /// a rejection readable: a non-finite bar <c>k</c> throws
      /// <see cref="System.ArgumentException"/> exactly as <see cref="Update"/>
      /// would, with the bars before <c>k</c> committed and written, bar <c>k</c>
      /// and everything after it not written, and the count advanced by <c>k +
      /// 1</c> — the committed bars plus the rejected one, so the last bar counted
      /// is the one that failed.</para>
      /// </remarks>
      /// <param name="inHigh">Closed bars for <c>inHigh</c>, oldest first.</param>
      /// <param name="inLow">Closed bars for <c>inLow</c>, oldest first.</param>
      /// <param name="outReal">Receives one <c>outReal</c> value per bar committed.</param>
      public void UpdateAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, Span<double> outReal )
      {
         int barCount = inHigh.Length;
         if( inLow.Length != barCount || outReal.Length < barCount || outReal.Overlaps(inHigh) || outReal.Overlaps(inLow) ) throw Core.StreamFailure("AO", "updateAndFill", RetCode.BadParam);
         for( int i = 0; i < barCount; i++ )
         {
            if( !double.IsFinite(inHigh[i]) || !double.IsFinite(inLow[i]) )
            {
               if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
               throw Core.StreamFailure("AO", "updateAndFill", RetCode.BadParam);
            }
            core.AoStepImpl(this, inHigh[i], inLow[i]);
            outReal[i] = cur_outReal;
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         }
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public AoStream Clone()
      {
         return new AoStream(this);
      }
   }

   internal void AoStepImpl( AoStream sp, double inHigh, double inLow )
   {
      double medianPrice = 0.0;
      double tempReal = 0.0;
      if( sp.ringCap_trailingFastIdx == 0 ) {
         sp.ring_trailingFastIdx_derived[0] = (inHigh + inLow) / 2.0;
      }
      if( sp.ringCap_trailingSlowIdx == 0 ) {
         sp.ring_trailingSlowIdx_derived[0] = (inHigh + inLow) / 2.0;
      }
      medianPrice = (inHigh + inLow) / 2.0;
      sp.sumFast += medianPrice;
      sp.sumSlow += medianPrice;
      /* Snapshot the oscillator before either total drops its trailing bar,
       * mirroring the add-new / snapshot / subtract-old order of TA_SMA.
       */
      tempReal = sp.sumFast / (double)sp.optInFastPeriod - sp.sumSlow / (double)sp.optInSlowPeriod;
      /* Read both trailing bars before writing the output. When startIdx is
       * clamped to the lookback the longer window's trailing index equals
       * outIdx exactly, so a store hoisted above this would read back the
       * value it had just overwritten whenever the caller aliases outReal
       * over inHigh or inLow.
       */
      sp.sumFast -= sp.ring_trailingFastIdx_derived[sp.ringPos_trailingFastIdx];
      sp.sumSlow -= sp.ring_trailingSlowIdx_derived[sp.ringPos_trailingSlowIdx];
      sp.cur_outReal = tempReal;
      sp.ring_trailingFastIdx_derived[sp.ringPos_trailingFastIdx] = (inHigh + inLow) / 2.0;
      sp.ringPos_trailingFastIdx = sp.ringPos_trailingFastIdx + 1;
      if( sp.ringPos_trailingFastIdx >= sp.ringCap_trailingFastIdx ) {
         sp.ringPos_trailingFastIdx = 0;
      }
      sp.ring_trailingSlowIdx_derived[sp.ringPos_trailingSlowIdx] = (inHigh + inLow) / 2.0;
      sp.ringPos_trailingSlowIdx = sp.ringPos_trailingSlowIdx + 1;
      if( sp.ringPos_trailingSlowIdx >= sp.ringCap_trailingSlowIdx ) {
         sp.ringPos_trailingSlowIdx = 0;
      }
   }

   private RetCode AoOpenImpl( AoStream sp, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int startIdx, int optInFastPeriod, int optInSlowPeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double sumFast = 0;
      double sumSlow = 0;
      double medianPrice = 0;
      double tempReal = 0;
      int i = 0;
      int outIdx = 0;
      int trailingFastIdx = 0;
      int trailingSlowIdx = 0;
      int lookbackTotal = 0;
      int historyLen = inHigh.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inLow.Length != inHigh.Length ) {
         return RetCode.BadParam;
      }
      if( optInFastPeriod == int.MinValue ) {
         optInFastPeriod = 5;
      } else if( optInFastPeriod < 2 || optInFastPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInSlowPeriod == int.MinValue ) {
         optInSlowPeriod = 34;
      } else if( optInSlowPeriod < 2 || optInSlowPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      /* Bill Williams' Awesome Oscillator (New Trading Dimensions, 1998): the
       * spread between a short and a long simple moving average of the median
       * price, drawn as a zero-centred histogram.
       *
       *    median_t = (high_t + low_t) / 2
       *    AO_t     = SMA(median, fast)_t - SMA(median, slow)_t
       *
       * Both legs are plain SMAs, so there is no seeding convention to get wrong
       * and no cross-library divergence of the kind an EMA brings.
       *
       * This is two copies of ta_codegen/input/sma/sma.c walking one derived
       * series, sharing a single pass: the same running-sum order, the same
       * snapshot of each total before the trailing bar leaves it, and the same
       * divide by the period. Keeping the arithmetic identical is what makes the
       * composed reference in test_composite.c -- TA_MEDPRICE, two TA_SMA calls
       * and a TA_SUB -- bit-exact rather than merely close, so any future drift
       * in either path is a hard failure instead of a tolerance argument.
       *
       * In particular each total is DIVIDED by its period; it is not multiplied
       * by a precomputed 1/period. Tulip's ao.c multiplies by per5/per34, which
       * costs it up to one ULP against TA_SMA. Dividing buys the memcmp
       * differential, which is the stronger of the two gates (#117, #118).
       *
       * An inverted pair (fast > slow) is NOT swapped, unlike MACD and APO. The
       * lookback is well defined either way and the result is simply -AO, so the
       * swap would buy nothing and would have to be duplicated in ao_lookback.
       */
      /* Identify the minimum number of price bar needed
       * to calculate at least one output.
       */
      lookbackTotal = (int)AO_Lookback(optInFastPeriod, optInSlowPeriod);
      /* Move up the start index if there is not
       * enough initial data.
       */
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      sumFast = 0.0;
      sumSlow = 0.0;
      trailingFastIdx = startIdx - (int)(optInFastPeriod - 1);
      trailingSlowIdx = startIdx - (int)(optInSlowPeriod - 1);
      /* Add-up both initial periods, except for the last value.
       *
       * One pass over the longer warm-up window replaces two overlapping passes.
       * A bar inside the shorter window is added to that total as it is reached,
       * so each total still accumulates exactly the same bars in exactly the same
       * ascending order two separate loops would have given it -- which is what
       * keeps each leg bit-identical to the TA_SMA called with this same startIdx.
       */
      i = startIdx - lookbackTotal;
      while( i < startIdx ) {
         medianPrice = (inHigh[i] + inLow[i]) / 2.0;
         if( i >= trailingFastIdx ) {
            sumFast += medianPrice;
         }
         if( i >= trailingSlowIdx ) {
            sumSlow += medianPrice;
         }
         i = i + 1;
      }
      /* Proceed with the calculation for the requested range.
       * Note that this algorithm allows outReal to be the same
       * buffer as either input.
       */
      outIdx = 0;
      while( i <= endIdx ) {
         medianPrice = (inHigh[i] + inLow[i]) / 2.0;
         sumFast += medianPrice;
         sumSlow += medianPrice;
         i = i + 1;
         /* Snapshot the oscillator before either total drops its trailing bar,
          * mirroring the add-new / snapshot / subtract-old order of TA_SMA.
          */
         tempReal = sumFast / (double)optInFastPeriod - sumSlow / (double)optInSlowPeriod;
         /* Read both trailing bars before writing the output. When startIdx is
          * clamped to the lookback the longer window's trailing index equals
          * outIdx exactly, so a store hoisted above this would read back the
          * value it had just overwritten whenever the caller aliases outReal
          * over inHigh or inLow.
          */
         sumFast -= (inHigh[trailingFastIdx] + inLow[trailingFastIdx]) / 2.0;
         sumSlow -= (inHigh[trailingSlowIdx] + inLow[trailingSlowIdx]) / 2.0;
         trailingFastIdx = trailingFastIdx + 1;
         trailingSlowIdx = trailingSlowIdx + 1;
         outReal[outIdx * outStride] = tempReal;
         outIdx = outIdx + 1;
      }
      /* All done. Indicate the output limits and return. */
      outNBElement = outIdx;
      outBegIdx = startIdx;
      /* Capture the live batch state into the handle. */
      int cap_trailingFastIdx = i - trailingFastIdx;
      if( cap_trailingFastIdx < 0 || cap_trailingFastIdx > historyLen ) {
         return RetCode.InternalError;
      }
      int allocN_trailingFastIdx = (cap_trailingFastIdx > 0)? cap_trailingFastIdx : 1;
      double[] capRing_trailingFastIdx_derived = new double[allocN_trailingFastIdx];
      for( int fillJ = historyLen - cap_trailingFastIdx; fillJ < historyLen; fillJ++ ) {
         capRing_trailingFastIdx_derived[fillJ - (historyLen - cap_trailingFastIdx)] = (inHigh[fillJ] + inLow[fillJ]) / 2.0;
      }
      int cap_trailingSlowIdx = i - trailingSlowIdx;
      if( cap_trailingSlowIdx < 0 || cap_trailingSlowIdx > historyLen ) {
         return RetCode.InternalError;
      }
      int allocN_trailingSlowIdx = (cap_trailingSlowIdx > 0)? cap_trailingSlowIdx : 1;
      double[] capRing_trailingSlowIdx_derived = new double[allocN_trailingSlowIdx];
      for( int fillJ = historyLen - cap_trailingSlowIdx; fillJ < historyLen; fillJ++ ) {
         capRing_trailingSlowIdx_derived[fillJ - (historyLen - cap_trailingSlowIdx)] = (inHigh[fillJ] + inLow[fillJ]) / 2.0;
      }
      sp.optInFastPeriod = optInFastPeriod;
      sp.optInSlowPeriod = optInSlowPeriod;
      sp.sumFast = sumFast;
      sp.sumSlow = sumSlow;
      sp.ringPos_trailingFastIdx = 0;
      sp.ringCap_trailingFastIdx = cap_trailingFastIdx;
      sp.ring_trailingFastIdx_derived = capRing_trailingFastIdx_derived;
      sp.ringPos_trailingSlowIdx = 0;
      sp.ringCap_trailingSlowIdx = cap_trailingSlowIdx;
      sp.ring_trailingSlowIdx_derived = capRing_trailingSlowIdx_derived;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* AoOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal AoStream AoOpenAndFillInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int startIdx, int optInFastPeriod, int optInSlowPeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      AoStream sp = new AoStream(this);
      RetCode retCode = AoOpenImpl(sp, inHigh, inLow, startIdx, optInFastPeriod, optInSlowPeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("AO", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind AoOpen (composition seam). */
   internal AoStream AoOpenInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int startIdx, int optInFastPeriod, int optInSlowPeriod )
   {
      AoStream sp = new AoStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = AoOpenImpl(sp, inHigh, inLow, startIdx, optInFastPeriod, optInSlowPeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("AO", "open", retCode);
   }

   /// <summary>Open a live <c>AO</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="AoStream.Value"/> starts at the last history bar's
   /// value — bit-identical to what <c>AO</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>AO_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>AoOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInFastPeriod">As in the batch call; see <see cref="AO_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowPeriod">As in the batch call; see <see cref="AO_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>AO_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public AoStream AoOpen( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int optInFastPeriod, int optInSlowPeriod )
   {
      if( inHigh.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "AO open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "AO open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("AO open: inLow is empty", nameof(inLow), RetCode.BadParam);
      RequireHistoryLength("AO", "open", "inLow", inLow.Length, inHigh.Length);
      return AoOpenInternal(inHigh, inLow, 0, optInFastPeriod, optInSlowPeriod);
   }

   /// <summary><c>AoOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>AO</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - AO_Lookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="AoStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInFastPeriod">As in the batch call; see <see cref="AO_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowPeriod">As in the batch call; see <see cref="AO_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Spread between the two moving averages, centred on zero. Must hold at
   /// least <c>historyLen - AO_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>AO_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public AoStream AoOpenAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int optInFastPeriod, int optInSlowPeriod, Span<double> outReal )
   {
      if( inHigh.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "AO openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "AO openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("AO openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      int guardOutLen = OpenFillCount("AO", "openAndFill", inHigh.Length, AO_Lookback(optInFastPeriod, optInSlowPeriod));
      RequireHistoryLength("AO", "openAndFill", "inLow", inLow.Length, inHigh.Length);
      RequireFillLength("AO", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( outReal.Overlaps(inHigh) || outReal.Overlaps(inLow) ) {
         throw StreamFailure("AO", "openAndFill", RetCode.BadParam);
      }
      return AoOpenAndFillInternal(inHigh, inLow, 0, optInFastPeriod, optInSlowPeriod, out _, out _, outReal);
   }
