   /// <item><description><b>Which estimator.</b> This is <c>G2</c>, what Excel <c>KURT</c>, <c>scipy.stats.kurtosis(bias=False)</c> and R <c>e1071::kurtosis(type=2)</c> all compute, and the one that is unbiased under normality. The other form in circulation is the biased <c>g2 = m₄/m₂² − 3</c> over population moments, which NIST/SEMATECH gives. They are not a rounding convention apart: on a 9-point normal sample <c>G2 = 1.79450407519901</c> against <c>g2 = 0.342114639479481</c>.</description></item>
   /// <item><description><b>A window with no spread returns NaN, not a number.</b> Excess kurtosis has no defensible neutral to fall back on — <c>0</c> asserts normality and <c>−1.2</c> asserts uniformity, and a point mass supports neither. <c>scipy.stats.kurtosis</c> returns <c>nan</c> at both bias settings, and Excel <c>KURT</c> documents <c>#DIV/0!</c> when the sample's standard deviation is zero. This function declares <c>nan_inf_output</c> and leaves the division unguarded, so the answer arrives from IEEE rather than from a branch. It is deliberately a <i>different</i> answer from <c>VAR</c>'s floor-to-zero: a variance of zero says something true about the window, a kurtosis of a point mass does not.</description></item>
   /// <item><description><b>Cancellation, and why the rebuild period is not <c>VAR</c>'s.</b> Deviations are taken against a shift near the window and the central moments recovered from the shifted sums, as <c>var.c</c> does. What does not carry over is the period: a fourth moment recovered against a stale shift pays <c>(u/σ)⁴</c> where a second pays <c>(u/σ)²</c>, so the shift goes stale four times faster in the exponent. MEASURED on 1200-bar series at <c>n = 30</c>, worst relative error per bar against a 60-digit reference: | rebuild every | 32n (<c>VAR</c>'s) | 8n | 2n | n | n/4 | |---|---|---|---|---|---| | random walk around 100 | 1.18e-06 | 9.33e-07 | 1.61e-08 | 1.28e-09 | 4.58e-12 | | random walk on 3.1e10 | 4.99e-06 | 4.99e-06 | 6.27e-10 | 1.45e-09 | 1.76e-12 | | outlier 1e5 every 200 bars | 2.84e-13 | 2.84e-13 | 2.68e-13 | 1.51e-13 | 4.48e-14 | <c>VAR</c>'s <c>32n</c> leaves 1e-6 on an ordinary random walk, and the collapse trigger cannot catch it — the ratio it tests sits around 0.24 there, six orders from firing. Hence <c>n/4</c>.</description></item>
   /// <item><description><b>Rebuilding beats rescanning.</b> Rescanning the whole window every bar measures 5.34e-11 and 4.30e-11 on those two walks — worse than the <c>n/4</c> rebuild, at roughly ten times the arithmetic. The rebuild anchors the shift at the window <i>mean</i>; a per-bar rescan can only anchor it at a window <i>value</i>, which sits further from centre.</description></item>
   /// <item><description><b>The result is not bounded.</b> There is no clamp and no range assertion; a window dominated by one outlier is legitimately far above 0.</description></item>
   /// </list>
   /// <para>
   /// This is the <c>float[]</c> overload: input elements are widened to
   /// <c>double</c> as they are read and all arithmetic is performed in
   /// <c>double</c>, so a result beyond <c>float</c> range is still
   /// representable.
   /// </para>
   /// <para>
   /// Values are written only where the indicator is defined. The returned
   /// <see cref="OutRange"/> says where they start and how many there are;
   /// nothing outside that range is touched, and the library never pads with
   /// NaN. A valid range shorter than <c>KURTOSIS_Lookback</c> is a <b>success
   /// with no values</b> (<c>Count == 0</c>), not an error.
   /// </para>
   /// </remarks>
   /// <param name="startIdx">First bar of the requested range (inclusive).</param>
   /// <param name="endIdx">Last bar of the requested range (inclusive).</param>
   /// <param name="inReal">The series to measure.</param>
   /// <param name="optInTimePeriod">Number of trailing values in the window, at least 4 (default 30; range
   /// 4..100000; <c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Excess kurtosis of the trailing window, or NaN where the window has no
   /// spread. Must hold at least <c>endIdx - startIdx + 1</c> values.</param>
   /// <returns>The range written: <c>BegIdx</c> is the first bar with a value,
   /// <c>Count</c> how many were written.</returns>
   /// <exception cref="System.ArgumentOutOfRangeException"><c>startIdx</c> or <c>endIdx</c> is negative or above
   /// <see cref="Core.MAX_INDEX"/>, or <c>endIdx &lt; startIdx</c>.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or two outputs
   /// share one array.</exception>
   /// <exception cref="System.ArgumentException">A span is too short for the range requested: any input this function
   /// <i>declares</i> that does not reach <c>endIdx</c>, or an output that
   /// cannot hold the values produced. Checked before anything is written, so a
   /// rejected call leaves every buffer untouched. Declared, not read: a few
   /// candlestick patterns take an OHLC series they never index, and it is
   /// required all the same. An empty span — which is what a null array becomes,
   /// since a span cannot be null — is rejected on the same terms and no others:
   /// it is too short whenever the range produces a value, and fine when it
   /// produces none, and on an output this function documents as declinable it
   /// is how you decline.</exception>
   /// <exception cref="System.ArgumentException">Two output buffers overlap, or an output overlaps an input. An output and
   /// a real input never share an element type in this overload, so the two can
   /// never be the same span: there is no in-place case to allow, and any
   /// overlap of their byte ranges is rejected.</exception>
   public OutRange KURTOSIS( int startIdx,
                             int endIdx,
                             ReadOnlySpan<float> inReal,
                             int optInTimePeriod,
                             Span<double> outReal )
   {
      int guardStart = ClampedStart(startIdx, endIdx, KURTOSIS_Lookback(optInTimePeriod));
      int guardInLen = guardStart < 0 ? 0 : endIdx + 1;
      int guardOutLen = guardStart < 0 || guardStart > endIdx ? 0 : endIdx - guardStart + 1;
      RequireLength("KURTOSIS", "inReal", inReal.Length, guardInLen);
      RequireLength("KURTOSIS", "outReal", outReal.Length, guardOutLen);
      RetCode retCode = KURTOSIS_Impl(startIdx, endIdx, inReal, optInTimePeriod, out int outBegIdx, out int outNBElement, outReal);
      if( retCode != RetCode.Success ) {
         throw Failure("KURTOSIS", retCode);
      }
      return new OutRange(outBegIdx, outNBElement);
   }
   /**** Streaming API *****/

   /// <summary>A live <c>KURTOSIS</c> stream: one value per closed bar, bit-identical to
   /// <c>KURTOSIS</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.KurtosisOpen"/>. There is no close and nothing
   /// to dispose — the handle is ordinary managed state, and an unreferenced
   /// handle is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class KurtosisStream
   {
      internal Core core;
      internal int optInTimePeriod;
      internal double shift;
      internal double total1;
      internal double total2;
      internal double total3;
      internal double total4;
      internal double dPeriod;
      internal double coefA;
      internal double coefB;
      internal double invPeriod;
      internal int trailingIdx;
      internal int nbInitialElementNeeded;
      internal int barsSinceReseed;
      internal int reseedPeriod;
      internal int j;
      internal int windowStart;
      internal int i;
      internal int xMask;
      internal double[] x_inReal = [];
      internal double cur_outReal;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal KurtosisStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Kurtosis</c> reports over the same bars: the opener
      /// sets it to <c>(lookback, historyLen - lookback)</c>, every accepted
      /// <c>Update</c> adds one to the count — a rejected one changes nothing, and
      /// neither does <c>Peek</c> — and <c>Clone</c> carries it verbatim. A plain
      /// <c>Open</c> hands back only the last value, a subset of this range,
      /// because the caller chose not to take the fill.</para>
      /// <para>The last bar it can reach is <see cref="Core.MAX_INDEX"/>; past that
      /// <c>Update</c> and <c>Advance</c> throw.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      /// <summary>Count one bar this stream was not fed: <see cref="OutRange"/> advances by
      /// one and nothing else moves.</summary>
      /// <remarks>
      /// <para><see cref="Value"/> keeps answering the previous output, which is this
      /// bar's output too. For a bar the caller leaves out: one an <c>Update</c>
      /// rejected and that will not be re-fed, or a session with no print. Without
      /// it two handles on one feed drift a bar apart when only one of them skips.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.MAX_INDEX"/>, the last one the batch tier
      /// can address and the last this handle will count. <c>Update</c> throws the
      /// same there.</para>
      /// </remarks>
      public void Advance()
      {
         if( outRangeBegIdx + outRangeCount > Core.MAX_INDEX )
            throw Core.StreamFailure("KURTOSIS", "advance", RetCode.OutOfRangeEndIndex);
         outRangeCount++;
      }

      internal KurtosisStream( KurtosisStream other )
      {
         this.core = other.core;
         this.optInTimePeriod = other.optInTimePeriod;
         this.shift = other.shift;
         this.total1 = other.total1;
         this.total2 = other.total2;
         this.total3 = other.total3;
         this.total4 = other.total4;
         this.dPeriod = other.dPeriod;
         this.coefA = other.coefA;
         this.coefB = other.coefB;
         this.invPeriod = other.invPeriod;
         this.trailingIdx = other.trailingIdx;
         this.nbInitialElementNeeded = other.nbInitialElementNeeded;
         this.barsSinceReseed = other.barsSinceReseed;
         this.reseedPeriod = other.reseedPeriod;
         this.j = other.j;
         this.windowStart = other.windowStart;
         this.i = other.i;
         this.xMask = other.xMask;
         this.x_inReal = new double[other.x_inReal.Length];
         Array.Copy( other.x_inReal, this.x_inReal, other.x_inReal.Length );
         this.cur_outReal = other.cur_outReal;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Allocates nothing — neither handle state nor a return value.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so nothing moves — <see cref="OutRange"/> included — and
      /// <see cref="Value"/> still answers the previous value. Re-feed the bar when
      /// a corrected value arrives, or call <see cref="Advance"/> to count it and
      /// carry on; two handles on one feed drift a bar apart if neither happens.
      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.MAX_INDEX"/>, which no re-feed clears: the
      /// handle has run out of index domain and only a shorter history can start a
      /// new one.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inReal )
      {
         if( outRangeBegIdx + outRangeCount > Core.MAX_INDEX )
            throw Core.StreamFailure("KURTOSIS", "update", RetCode.OutOfRangeEndIndex);
         if( !double.IsFinite(inReal) ) throw Core.StreamFailure("KURTOSIS", "update", RetCode.BadParam);
         core.KurtosisStepImpl(this, inReal);
         outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>Its cost does not grow with the period.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.MAX_INDEX"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public double Peek( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.StreamFailure("KURTOSIS", "peek", RetCode.BadParam);
         KurtosisStream sp = this;
         double tempReal = 0.0;
         double dev = 0.0;
         double dev2 = 0.0;
         double residue = 0.0;
         double residueSq = 0.0;
         double moment2 = 0.0;
         double moment4 = 0.0;
         double sampleVar = 0.0;
         double varSquared = 0.0;
         double kurt = 0.0;
         int barsSinceReseed = sp.barsSinceReseed;
         double cur_outReal = 0.0;
         int j = sp.j;
         double shift = sp.shift;
         double total1 = sp.total1;
         double total2 = sp.total2;
         double total3 = sp.total3;
         double total4 = sp.total4;
         int trailingIdx = sp.trailingIdx;
         int windowStart = sp.windowStart;
         int pkSlot0 = -1;
         double pkVal0 = 0.0;
         pkSlot0 = sp.i & sp.xMask;
         pkVal0 = inReal;
         dev = (((sp.i & sp.xMask) != pkSlot0) ? sp.x_inReal[sp.i & sp.xMask] : pkVal0) - shift;
         dev2 = dev * dev;
         total1 += dev;
         total2 += dev2;
         total3 += dev2 * dev;
         total4 += dev2 * dev2;
         /* Central moments from the shifted sums. `residue` is what the shift
          * left behind: ~0 right after a rebuild, growing as the window walks
          * away from the anchor. That growth is the quantity the rebuild period
          * bounds, and the reason a fourth moment needs a shorter period than a
          * second -- it enters here raised to the fourth power.
          */
         residue = total1 * sp.invPeriod;
         residueSq = residue * residue;
         moment2 = total2 - sp.dPeriod * residueSq;
         moment4 = Math.FusedMultiplyAdd(6.0 * residueSq, total2, total4 - 4.0 * residue * total3) - 3.0 * sp.dPeriod * residueSq * residueSq;
         /* Remove the trailing value (prepares the next window). */
         dev = (((trailingIdx & sp.xMask) != pkSlot0) ? sp.x_inReal[trailingIdx & sp.xMask] : pkVal0) - shift;
         dev2 = dev * dev;
         total1 -= dev;
         total2 -= dev2;
         total3 -= dev2 * dev;
         total4 -= dev2 * dev2;
         trailingIdx += 1;
         /* Rebuild when the window walked far enough from the anchor for the
          * expansion above to be subtracting like-sized quantities; when the value
          * just removed sat so far from the shift that its fourth power dwarfs
          * what survives (a large outlier passing through buries the small terms
          * below its ulp, and the residue it leaves is cancellation garbage); or
          * on the period derived above regardless.
          */
         barsSinceReseed -= 1;
         if( moment2 < 0.000001 * total2 || dev2 * dev2 > 1000000.0 * total4 || barsSinceReseed <= 0 ) {
            barsSinceReseed = sp.reseedPeriod;
            windowStart = sp.i - sp.nbInitialElementNeeded;
            tempReal = 0.0;
            for( j = windowStart; j <= sp.i; j += 1 ) {
               tempReal += ((j & sp.xMask) != pkSlot0) ? sp.x_inReal[j & sp.xMask] : pkVal0;
            }
            shift = tempReal * sp.invPeriod;
            total1 = 0.0;
            total2 = 0.0;
            total3 = 0.0;
            total4 = 0.0;
            for( j = windowStart; j <= sp.i; j += 1 ) {
               dev = (((j & sp.xMask) != pkSlot0) ? sp.x_inReal[j & sp.xMask] : pkVal0) - shift;
               dev2 = dev * dev;
               total1 += dev;
               total2 += dev2;
               total3 += dev2 * dev;
               total4 += dev2 * dev2;
            }
            residue = total1 * sp.invPeriod;
            residueSq = residue * residue;
            moment2 = total2 - sp.dPeriod * residueSq;
            moment4 = Math.FusedMultiplyAdd(6.0 * residueSq, total2, total4 - 4.0 * residue * total3) - 3.0 * sp.dPeriod * residueSq * residueSq;
            /* Re-remove the trailing value under the new shift so the carried
             * state matches the non-rebuild path.
             */
            dev = (((windowStart & sp.xMask) != pkSlot0) ? sp.x_inReal[windowStart & sp.xMask] : pkVal0) - shift;
            dev2 = dev * dev;
            total1 -= dev;
            total2 -= dev2;
            total3 -= dev2 * dev;
            total4 -= dev2 * dev2;
         }
         /* A window with no spread has no kurtosis to report, and there is no
          * defensible neutral to substitute: 0 asserts normality and -1.2 asserts
          * uniformity, neither of which a point mass supports. scipy returns nan
          * at both bias settings and Excel KURT answers #DIV/0!.
          *
          * So the division is left UNGUARDED, as rvol.c leaves its own, and the
          * function declares nan_inf_output. On a point mass the rebuild anchors
          * the shift at the single value, every deviation is exactly 0, and both
          * moments are exactly 0 -- so this is 0/0 and IEEE answers NaN without a
          * branch. A guard with an absolute epsilon would be a cliff at a price
          * level rather than a noise floor, which is the mistake #243 fixed in the
          * var/stddev/bbands family: a $100 instrument quoted in 1e-8 ticks had
          * every bar zeroed.
          *
          * Nothing NaN re-enters the running sums -- the division happens here, at
          * the output write, on sums that stay finite.
          */
         sampleVar = moment2 / (sp.dPeriod - 1.0);
         varSquared = sampleVar * sampleVar;
         kurt = sp.coefA * (moment4 / varSquared) - sp.coefB;
         cur_outReal = kurt;
         return cur_outReal;
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public KurtosisStream Clone()
      {
         return new KurtosisStream(this);
      }
   }

   internal void KurtosisStepImpl( KurtosisStream sp, double inReal )
   {
      double tempReal = 0.0;
      double dev = 0.0;
      double dev2 = 0.0;
      double residue = 0.0;
      double residueSq = 0.0;
      double moment2 = 0.0;
      double moment4 = 0.0;
      double sampleVar = 0.0;
      double varSquared = 0.0;
      double kurt = 0.0;
      sp.x_inReal[sp.i & sp.xMask] = inReal;
      dev = sp.x_inReal[sp.i & sp.xMask] - sp.shift;
      dev2 = dev * dev;
      sp.total1 += dev;
      sp.total2 += dev2;
      sp.total3 += dev2 * dev;
      sp.total4 += dev2 * dev2;
      /* Central moments from the shifted sums. `residue` is what the shift
       * left behind: ~0 right after a rebuild, growing as the window walks
       * away from the anchor. That growth is the quantity the rebuild period
       * bounds, and the reason a fourth moment needs a shorter period than a
       * second -- it enters here raised to the fourth power.
       */
      residue = sp.total1 * sp.invPeriod;
      residueSq = residue * residue;
      moment2 = sp.total2 - sp.dPeriod * residueSq;
      moment4 = Math.FusedMultiplyAdd(6.0 * residueSq, sp.total2, sp.total4 - 4.0 * residue * sp.total3) - 3.0 * sp.dPeriod * residueSq * residueSq;
      /* Remove the trailing value (prepares the next window). */
      dev = sp.x_inReal[sp.trailingIdx & sp.xMask] - sp.shift;
      dev2 = dev * dev;
      sp.total1 -= dev;
      sp.total2 -= dev2;
      sp.total3 -= dev2 * dev;
      sp.total4 -= dev2 * dev2;
      sp.trailingIdx += 1;
      /* Rebuild when the window walked far enough from the anchor for the
       * expansion above to be subtracting like-sized quantities; when the value
       * just removed sat so far from the shift that its fourth power dwarfs
       * what survives (a large outlier passing through buries the small terms
       * below its ulp, and the residue it leaves is cancellation garbage); or
       * on the period derived above regardless.
       */
      sp.barsSinceReseed -= 1;
      if( moment2 < 0.000001 * sp.total2 || dev2 * dev2 > 1000000.0 * sp.total4 || sp.barsSinceReseed <= 0 ) {
         sp.barsSinceReseed = sp.reseedPeriod;
         sp.windowStart = sp.i - sp.nbInitialElementNeeded;
         tempReal = 0.0;
         for( sp.j = sp.windowStart; sp.j <= sp.i; sp.j += 1 ) {
            tempReal += sp.x_inReal[sp.j & sp.xMask];
         }
         sp.shift = tempReal * sp.invPeriod;
         sp.total1 = 0.0;
         sp.total2 = 0.0;
         sp.total3 = 0.0;
         sp.total4 = 0.0;
         for( sp.j = sp.windowStart; sp.j <= sp.i; sp.j += 1 ) {
            dev = sp.x_inReal[sp.j & sp.xMask] - sp.shift;
            dev2 = dev * dev;
            sp.total1 += dev;
            sp.total2 += dev2;
            sp.total3 += dev2 * dev;
            sp.total4 += dev2 * dev2;
         }
         residue = sp.total1 * sp.invPeriod;
         residueSq = residue * residue;
         moment2 = sp.total2 - sp.dPeriod * residueSq;
         moment4 = Math.FusedMultiplyAdd(6.0 * residueSq, sp.total2, sp.total4 - 4.0 * residue * sp.total3) - 3.0 * sp.dPeriod * residueSq * residueSq;
         /* Re-remove the trailing value under the new shift so the carried
          * state matches the non-rebuild path.
          */
         dev = sp.x_inReal[sp.windowStart & sp.xMask] - sp.shift;
         dev2 = dev * dev;
         sp.total1 -= dev;
         sp.total2 -= dev2;
         sp.total3 -= dev2 * dev;
         sp.total4 -= dev2 * dev2;
      }
      /* A window with no spread has no kurtosis to report, and there is no
       * defensible neutral to substitute: 0 asserts normality and -1.2 asserts
       * uniformity, neither of which a point mass supports. scipy returns nan
       * at both bias settings and Excel KURT answers #DIV/0!.
       *
       * So the division is left UNGUARDED, as rvol.c leaves its own, and the
       * function declares nan_inf_output. On a point mass the rebuild anchors
       * the shift at the single value, every deviation is exactly 0, and both
       * moments are exactly 0 -- so this is 0/0 and IEEE answers NaN without a
       * branch. A guard with an absolute epsilon would be a cliff at a price
       * level rather than a noise floor, which is the mistake #243 fixed in the
       * var/stddev/bbands family: a $100 instrument quoted in 1e-8 ticks had
       * every bar zeroed.
       *
       * Nothing NaN re-enters the running sums -- the division happens here, at
       * the output write, on sums that stay finite.
       */
      sampleVar = moment2 / (sp.dPeriod - 1.0);
      varSquared = sampleVar * sampleVar;
      kurt = sp.coefA * (moment4 / varSquared) - sp.coefB;
      sp.cur_outReal = kurt;
      sp.i += 1;
   }

   private RetCode KurtosisOpenImpl( KurtosisStream sp, ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double tempReal = 0;
      double shift = 0;
      double total1 = 0;
      double total2 = 0;
      double total3 = 0;
      double total4 = 0;
      double dev = 0;
      double dev2 = 0;
      double residue = 0;
      double residueSq = 0;
      double moment2 = 0;
      double moment4 = 0;
      double sampleVar = 0;
      double varSquared = 0;
      double dPeriod = 0;
      double coefA = 0;
      double coefB = 0;
      double invPeriod = 0;
      double kurt = 0;
      int i = 0;
      int j = 0;
      int outIdx = 0;
      int trailingIdx = 0;
      int windowStart = 0;
      int nbInitialElementNeeded = 0;
      int barsSinceReseed = 0;
      int reseedPeriod = 0;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 30;
      } else if( optInTimePeriod < 4 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      nbInitialElementNeeded = optInTimePeriod - 1;
      if( startIdx < nbInitialElementNeeded ) {
         startIdx = nbInitialElementNeeded;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      /* G2, the sample-adjusted Fisher excess kurtosis. The two coefficients are
       * computed in double because their integer forms overflow: at the top of the
       * parameter range (n-1)(n-2)(n-3) is ~1e15, far past what an int holds, and
       * the product would wrap silently rather than fail.
       *
       * The (n-2)(n-3) denominators are why the range starts at 4 rather than 1.
       * The argument contract rejects anything below it, and the n-1 lookback
       * guarantees a full window at the first emitted bar, so the estimator is
       * never handed fewer than four points and needs no runtime branch for it.
       */
      dPeriod = (double)optInTimePeriod;
      coefA = dPeriod * (dPeriod + 1.0) / ((dPeriod - 1.0) * (dPeriod - 2.0) * (dPeriod - 3.0));
      coefB = 3.0 * (dPeriod - 1.0) * (dPeriod - 1.0) / ((dPeriod - 2.0) * (dPeriod - 3.0));
      invPeriod = 1.0 / dPeriod;
      /* Deviations are measured against a shift near the window, as var.c does, so
       * the running sums stay at deviation scale instead of at price scale. The
       * central moments are then recovered from the shifted sums by the binomial
       * expansion below, which puts back the residue the shift left behind.
       *
       * The RESEED PERIOD IS NOT var.c's. MEASURED on 1200-bar series at n=30,
       * worst relative error against a 60-digit reference computed per window:
       *
       *   rebuild every    32n (var.c)    8n        2n        n         n/4
       *   walk around 100   1.18e-06   9.33e-07  1.61e-08  1.28e-09  4.58e-12
       *   walk on 3.1e10    4.99e-06   4.99e-06  6.27e-10  1.45e-09  1.76e-12
       *   outlier 1e5/200   2.84e-13   2.84e-13  2.68e-13  1.51e-13  4.48e-14
       *
       * A fourth moment recovered against a stale shift pays (u/sigma)^4 where a
       * second pays (u/sigma)^2, so the shift goes stale four times faster in the
       * exponent and var.c's 32n leaves 1e-6 on an ordinary random walk. The
       * collapse trigger cannot catch that case -- the ratio it tests sits around
       * 0.24 there, six orders from firing -- so only the periodic rebuild can,
       * and it has to run at n/4.
       *
       * Rebuilding that often also beats rescanning the window every bar
       * (5.34e-11 and 4.30e-11 on the two walks): the rebuild anchors the shift at
       * the window MEAN, while a per-bar rescan can only anchor it at a window
       * VALUE, which sits further from centre and leaves a larger u. About a tenth
       * of the arithmetic, and more accurate.
       */
      reseedPeriod = optInTimePeriod / 4;
      trailingIdx = startIdx - nbInitialElementNeeded;
      shift = inReal[trailingIdx];
      total1 = 0.0;
      total2 = 0.0;
      total3 = 0.0;
      total4 = 0.0;
      for( j = trailingIdx; j < startIdx; j += 1 ) {
         dev = inReal[j] - shift;
         dev2 = dev * dev;
         total1 += dev;
         total2 += dev2;
         total3 += dev2 * dev;
         total4 += dev2 * dev2;
      }
      /* inReal and outReal may be the same buffer: each trailing value is consumed
       * before its slot is overwritten by the output.
       */
      i = startIdx;
      outIdx = 0;
      barsSinceReseed = reseedPeriod;
      do {
         dev = inReal[i] - shift;
         dev2 = dev * dev;
         total1 += dev;
         total2 += dev2;
         total3 += dev2 * dev;
         total4 += dev2 * dev2;
         /* Central moments from the shifted sums. `residue` is what the shift
          * left behind: ~0 right after a rebuild, growing as the window walks
          * away from the anchor. That growth is the quantity the rebuild period
          * bounds, and the reason a fourth moment needs a shorter period than a
          * second -- it enters here raised to the fourth power.
          */
         residue = total1 * invPeriod;
         residueSq = residue * residue;
         moment2 = total2 - dPeriod * residueSq;
         moment4 = Math.FusedMultiplyAdd(6.0 * residueSq, total2, total4 - 4.0 * residue * total3) - 3.0 * dPeriod * residueSq * residueSq;
         /* Remove the trailing value (prepares the next window). */
         dev = inReal[trailingIdx] - shift;
         dev2 = dev * dev;
         total1 -= dev;
         total2 -= dev2;
         total3 -= dev2 * dev;
         total4 -= dev2 * dev2;
         trailingIdx += 1;
         /* Rebuild when the window walked far enough from the anchor for the
          * expansion above to be subtracting like-sized quantities; when the value
          * just removed sat so far from the shift that its fourth power dwarfs
          * what survives (a large outlier passing through buries the small terms
          * below its ulp, and the residue it leaves is cancellation garbage); or
          * on the period derived above regardless.
          */
         barsSinceReseed -= 1;
         if( moment2 < 0.000001 * total2 || dev2 * dev2 > 1000000.0 * total4 || barsSinceReseed <= 0 ) {
            barsSinceReseed = reseedPeriod;
            windowStart = i - nbInitialElementNeeded;
            tempReal = 0.0;
            for( j = windowStart; j <= i; j += 1 ) {
               tempReal += inReal[j];
            }
            shift = tempReal * invPeriod;
            total1 = 0.0;
            total2 = 0.0;
            total3 = 0.0;
            total4 = 0.0;
            for( j = windowStart; j <= i; j += 1 ) {
               dev = inReal[j] - shift;
               dev2 = dev * dev;
               total1 += dev;
               total2 += dev2;
               total3 += dev2 * dev;
               total4 += dev2 * dev2;
            }
            residue = total1 * invPeriod;
            residueSq = residue * residue;
            moment2 = total2 - dPeriod * residueSq;
            moment4 = Math.FusedMultiplyAdd(6.0 * residueSq, total2, total4 - 4.0 * residue * total3) - 3.0 * dPeriod * residueSq * residueSq;
            /* Re-remove the trailing value under the new shift so the carried
             * state matches the non-rebuild path.
             */
            dev = inReal[windowStart] - shift;
            dev2 = dev * dev;
            total1 -= dev;
            total2 -= dev2;
            total3 -= dev2 * dev;
            total4 -= dev2 * dev2;
         }
         /* A window with no spread has no kurtosis to report, and there is no
          * defensible neutral to substitute: 0 asserts normality and -1.2 asserts
          * uniformity, neither of which a point mass supports. scipy returns nan
          * at both bias settings and Excel KURT answers #DIV/0!.
          *
          * So the division is left UNGUARDED, as rvol.c leaves its own, and the
          * function declares nan_inf_output. On a point mass the rebuild anchors
          * the shift at the single value, every deviation is exactly 0, and both
          * moments are exactly 0 -- so this is 0/0 and IEEE answers NaN without a
          * branch. A guard with an absolute epsilon would be a cliff at a price
          * level rather than a noise floor, which is the mistake #243 fixed in the
          * var/stddev/bbands family: a $100 instrument quoted in 1e-8 ticks had
          * every bar zeroed.
          *
          * Nothing NaN re-enters the running sums -- the division happens here, at
          * the output write, on sums that stay finite.
          */
         sampleVar = moment2 / (dPeriod - 1.0);
         varSquared = sampleVar * sampleVar;
         kurt = coefA * (moment4 / varSquared) - coefB;
         outReal[outIdx++ * outStride] = kurt;
         i += 1;
      } while( i <= endIdx );
      outNBElement = outIdx;
      outBegIdx = startIdx;
      /* Capture the live batch state into the handle. */
      int capX = i - trailingIdx + 1;
      if( capX < 1 || capX > historyLen ) {
         return RetCode.InternalError;
      }
      int physX = 1;
      while( physX < capX ) {
         physX <<= 1;
      }
      double[] capX_inReal = new double[physX];
      for( int fillJ = historyLen - capX; fillJ < historyLen; fillJ++ ) {
         capX_inReal[fillJ & (physX - 1)] = inReal[fillJ];
      }
      sp.optInTimePeriod = optInTimePeriod;
      sp.shift = shift;
      sp.total1 = total1;
      sp.total2 = total2;
      sp.total3 = total3;
      sp.total4 = total4;
      sp.dPeriod = dPeriod;
      sp.coefA = coefA;
      sp.coefB = coefB;
      sp.invPeriod = invPeriod;
      sp.trailingIdx = trailingIdx;
      sp.nbInitialElementNeeded = nbInitialElementNeeded;
      sp.barsSinceReseed = barsSinceReseed;
      sp.reseedPeriod = reseedPeriod;
      sp.j = j;
      sp.windowStart = windowStart;
      sp.i = i;
      sp.xMask = physX - 1;
      sp.x_inReal = capX_inReal;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* KurtosisOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal KurtosisStream KurtosisOpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      KurtosisStream sp = new KurtosisStream(this);
      RetCode retCode = KurtosisOpenImpl(sp, inReal, startIdx, optInTimePeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("KURTOSIS", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind KurtosisOpen (composition seam). */
   internal KurtosisStream KurtosisOpenInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod )
   {
      KurtosisStream sp = new KurtosisStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = KurtosisOpenImpl(sp, inReal, startIdx, optInTimePeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("KURTOSIS", "open", retCode);
   }

   /// <summary>Open a live <c>KURTOSIS</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="KurtosisStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>KURTOSIS</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>KURTOSIS_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>KurtosisOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">The series to measure. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="KURTOSIS_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>KURTOSIS_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public KurtosisStream KurtosisOpen( ReadOnlySpan<double> inReal, int optInTimePeriod )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "KURTOSIS open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "KURTOSIS open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      return KurtosisOpenInternal(inReal, 0, optInTimePeriod);
   }

   /// <summary><c>KurtosisOpen</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>KURTOSIS</c> produces over
   /// the same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - KURTOSIS_Lookback(...)</c> values
   /// and must not alias the inputs or each other — this path writes the outputs
   /// and then reads the input tail to seed its rings, so the batch tier's
   /// in-place allowance does not carry over here. Both are checked before
   /// anything is written, so an undersized span is an <c>ArgumentException</c>
   /// naming it rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="KurtosisStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">The series to measure. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="KURTOSIS_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Excess kurtosis of the trailing window, or NaN where the window has no
   /// spread. Must hold at least <c>historyLen - KURTOSIS_Lookback(...)</c>
   /// values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>KURTOSIS_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public KurtosisStream KurtosisOpenAndFill( ReadOnlySpan<double> inReal, int optInTimePeriod, Span<double> outReal )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "KURTOSIS openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "KURTOSIS openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      int guardOutLen = OpenFillCount("KURTOSIS", "openAndFill", inReal.Length, KURTOSIS_Lookback(optInTimePeriod));
      RequireFillLength("KURTOSIS", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( outReal.Overlaps(inReal) ) {
         throw StreamFailure("KURTOSIS", "openAndFill", RetCode.BadParam);
      }
      return KurtosisOpenAndFillInternal(inReal, 0, optInTimePeriod, out _, out _, outReal);
   }
