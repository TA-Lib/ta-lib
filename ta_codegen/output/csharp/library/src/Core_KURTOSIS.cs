   /// <param name="outReal">Excess kurtosis of the trailing window, or NaN where the window has no
   /// spread. Must hold at least <c>endIdx - max(startIdx,
   /// KurtosisLookback(...)) + 1</c> values, the count the call produces (none
   /// when that is not positive).</param>
   /// <returns>The range written: <c>BegIdx</c> is the first bar with a value,
   /// <c>Count</c> how many were written.</returns>
   /// <exception cref="System.ArgumentOutOfRangeException"><c>startIdx</c> or <c>endIdx</c> is negative or above
   /// <see cref="Core.IndexMax"/>, or <c>endIdx &lt; startIdx</c>.</exception>
   /// <exception cref="System.ArgumentException">
   /// One of the following, checked before anything is written, so a rejected
   /// call leaves every buffer untouched:
   /// <list type="bullet">
   /// <item><description>An optional parameter is outside its documented range.</description></item>
   /// <item><description>A span is too short for the range requested: any input this function
   /// <i>declares</i> that does not reach <c>endIdx</c>, or an output that
   /// cannot hold the values produced. Declared, not read: a few candlestick
   /// patterns take an OHLC series they never index, and it is required all the
   /// same. An empty span — which is what a null array becomes, since a span
   /// cannot be null — is rejected on the same terms and no others: it is too
   /// short whenever the range produces a value, and fine when it produces none,
   /// and on an output this function documents as declinable it is how you
   /// decline.</description></item>
   /// <item><description>Two output buffers overlap, or an output overlaps an input. An output and
   /// a real input never share an element type in this overload, so the two can
   /// never be the same span: there is no in-place case to allow, and any
   /// overlap of their byte ranges is rejected.</description></item>
   /// </list>
   /// </exception>
   /// <seealso cref="Core.Var(int, int, ReadOnlySpan{double}, int, double, Span{double})"/>
   /// <seealso cref="Core.Stddev(int, int, ReadOnlySpan{double}, int, double, Span{double})"/>
   /// <seealso cref="Core.Bbands(int, int, ReadOnlySpan{double}, int, double, double, MAType, Span{double}, Span{double}, Span{double})"/>
   public OutRange Kurtosis( int startIdx,
                             int endIdx,
                             ReadOnlySpan<float> inReal,
                             int optInTimePeriod,
                             Span<double> outReal )
   {
      int guardStart = ClampedStart(startIdx, endIdx, KurtosisLookback(optInTimePeriod));
      int guardInLen = guardStart < 0 ? 0 : endIdx + 1;
      int guardOutLen = guardStart < 0 || guardStart > endIdx ? 0 : endIdx - guardStart + 1;
      RequireLength("KURTOSIS", "inReal", inReal.Length, guardInLen);
      RequireLength("KURTOSIS", "outReal", outReal.Length, guardOutLen);
      RetCode retCode = KurtosisImpl(startIdx, endIdx, inReal, optInTimePeriod, out int outBegIdx, out int outNBElement, outReal);
      if( retCode != RetCode.Success ) {
         throw Failure("KURTOSIS", retCode);
      }
      return new OutRange(outBegIdx, outNBElement);
   }
