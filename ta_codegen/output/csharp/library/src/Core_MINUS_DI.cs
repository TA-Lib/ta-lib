   /// <summary>A live <c>MINUS_DI</c> stream: one value per closed bar, bit-identical to
   /// <c>MINUS_DI</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.MinusDiOpen"/>. There is no close and nothing to
   /// dispose — the handle is ordinary managed state, and an unreferenced handle
   /// is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class MinusDiStream
   {
      internal Core core;
      internal int optInTimePeriod;
      internal double prevHigh;
      internal double prevLow;
      internal double prevClose;
      internal double prevMinusDM;
      internal double prevTR;
      internal double cur_outReal;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal MinusDiStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.MinusDi</c> reports over the same bars: the opener sets
      /// it to <c>(lookback, historyLen - lookback)</c>, every <c>Update</c> adds
      /// one to the count — a non-finite bar is rejected but still counted, because
      /// the bar happened — <c>Peek</c> leaves it alone, and <c>Clone</c> carries
      /// it verbatim. A plain <c>Open</c> hands back only the last value, a subset
      /// of this range, because the caller chose not to take the fill.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      internal MinusDiStream( MinusDiStream other )
      {
         this.core = other.core;
         this.optInTimePeriod = other.optInTimePeriod;
         this.prevHigh = other.prevHigh;
         this.prevLow = other.prevLow;
         this.prevClose = other.prevClose;
         this.prevMinusDM = other.prevMinusDM;
         this.prevTR = other.prevTR;
         this.cur_outReal = other.cur_outReal;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Allocates nothing — neither handle state nor a return value.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so no state moves, <see cref="Value"/> still answers the previous value,
      /// and the stream stays usable — just carry on with the next bar.
      /// <see cref="OutRange"/> does advance: the bar happened, so it is counted,
      /// which keeps two handles fed the same series positionally aligned when only
      /// one of them rejects a bar. This is the one place the streaming tier is
      /// stricter than the batch API, which computes on whatever it is given: a
      /// handle retains its state, so a single non-finite bar would poison every
      /// later value it produces.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inHigh, double inLow, double inClose )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) )
         {
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
            throw Core.StreamFailure("MINUS_DI", "update", RetCode.BadParam);
         }
         core.MinusDiStepImpl(this, inHigh, inLow, inClose);
         if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It copies nothing: the frame runs against this handle, reading its buffers
      /// and holding what the step would commit in locals. The cost does not grow
      /// with the period, and <c>Peek</c> never allocates.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>What <see cref="Update"/> would return for this bar.</returns>
      public double Peek( double inHigh, double inLow, double inClose )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) ) throw Core.StreamFailure("MINUS_DI", "peek", RetCode.BadParam);
         MinusDiStream sp = this;
         double cur_outReal = 0.0;
         if( sp.optInTimePeriod <= 1 ) {
            double tempReal = 0.0;
            double diffP = 0.0;
            double diffM = 0.0;
            double prevHigh = sp.prevHigh;
            double prevLow = sp.prevLow;
            tempReal = inHigh;
            diffP = tempReal - prevHigh;
            /* Plus Delta */
            prevHigh = tempReal;
            tempReal = inLow;
            diffM = prevLow - tempReal;
            /* Minus Delta */
            prevLow = tempReal;
            if( diffM > 0 && diffP < diffM ) {
               /* Case 2 and 4: +DM=0,-DM=diffM */
               double _true_range_0 = 0;
               double range_0 = prevHigh - prevLow;
               double tmp_0 = Math.Abs(prevHigh - sp.prevClose);
               if( tmp_0 > range_0 ) {
                  range_0 = tmp_0;
               }
               tmp_0 = Math.Abs(prevLow - sp.prevClose);
               if( tmp_0 > range_0 ) {
                  range_0 = tmp_0;
               }
               _true_range_0 = range_0;
               tempReal = _true_range_0;
               if( tempReal <= 0.0 ) {
                  cur_outReal = (double)0.0;
               } else {
                  cur_outReal = diffM / tempReal;
               }
            } else {
               cur_outReal = (double)0.0;
            }
         } else {
            double tempReal = 0.0;
            double diffP = 0.0;
            double diffM = 0.0;
            double prevClose = sp.prevClose;
            double prevHigh = sp.prevHigh;
            double prevLow = sp.prevLow;
            double prevMinusDM = sp.prevMinusDM;
            double prevTR = sp.prevTR;
            /* Calculate the prevMinusDM */
            tempReal = inHigh;
            diffP = tempReal - prevHigh;
            /* Plus Delta */
            prevHigh = tempReal;
            tempReal = inLow;
            diffM = prevLow - tempReal;
            /* Minus Delta */
            prevLow = tempReal;
            if( diffM > 0 && diffP < diffM ) {
               /* Case 2 and 4: +DM=0,-DM=diffM */
               prevMinusDM = prevMinusDM - prevMinusDM / sp.optInTimePeriod + diffM;
            } else {
               /* Case 1,3,5 and 7 */
               prevMinusDM = prevMinusDM - prevMinusDM / sp.optInTimePeriod;
            }
            /* Calculate the prevTR */
            double _true_range_1 = 0;
            double range_1 = prevHigh - prevLow;
            double tmp_1 = Math.Abs(prevHigh - prevClose);
            if( tmp_1 > range_1 ) {
               range_1 = tmp_1;
            }
            tmp_1 = Math.Abs(prevLow - prevClose);
            if( tmp_1 > range_1 ) {
               range_1 = tmp_1;
            }
            _true_range_1 = range_1;
            tempReal = _true_range_1;
            prevTR = prevTR - prevTR / sp.optInTimePeriod + tempReal;
            prevClose = inClose;
            /* Calculate the DI. The value is rounded (see Wilder book). */
            if( prevTR > 0.0 ) {
               cur_outReal = (100.0 * (prevMinusDM / prevTR));
            } else {
               cur_outReal = 0.0;
            }
         }
         return cur_outReal;
      }

      /// <summary>Commit <c>n</c> closed bars and write their <c>n</c> values, in one call.</summary>
      /// <remarks>
      /// <para>Exactly <c>n</c> back-to-back <see cref="Update"/> calls, with one set of
      /// argument checks instead of <c>n</c>. The outputs must hold at least
      /// <c>n</c> values and must not overlap an input or each other.</para>
      /// <para><see cref="OutRange"/> counts what this call took in, which is what makes
      /// a rejection readable: a non-finite bar <c>k</c> throws
      /// <see cref="System.ArgumentException"/> exactly as <see cref="Update"/>
      /// would, with the bars before <c>k</c> committed and written, bar <c>k</c>
      /// and everything after it not written, and the count advanced by <c>k +
      /// 1</c> — the committed bars plus the rejected one, so the last bar counted
      /// is the one that failed.</para>
      /// </remarks>
      /// <param name="inHigh">Closed bars for <c>inHigh</c>, oldest first.</param>
      /// <param name="inLow">Closed bars for <c>inLow</c>, oldest first.</param>
      /// <param name="inClose">Closed bars for <c>inClose</c>, oldest first.</param>
      /// <param name="outReal">Receives one <c>outReal</c> value per bar committed.</param>
      public void UpdateAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, Span<double> outReal )
      {
         int barCount = inHigh.Length;
         if( inLow.Length != barCount || inClose.Length != barCount || outReal.Length < barCount || outReal.Overlaps(inHigh) || outReal.Overlaps(inLow) || outReal.Overlaps(inClose) ) throw Core.StreamFailure("MINUS_DI", "updateAndFill", RetCode.BadParam);
         for( int i = 0; i < barCount; i++ )
         {
            if( !double.IsFinite(inHigh[i]) || !double.IsFinite(inLow[i]) || !double.IsFinite(inClose[i]) )
            {
               if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
               throw Core.StreamFailure("MINUS_DI", "updateAndFill", RetCode.BadParam);
            }
            core.MinusDiStepImpl(this, inHigh[i], inLow[i], inClose[i]);
            outReal[i] = cur_outReal;
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         }
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public MinusDiStream Clone()
      {
         return new MinusDiStream(this);
      }
   }

   internal void MinusDiStepImpl( MinusDiStream sp, double inHigh, double inLow, double inClose )
   {
      if( sp.optInTimePeriod <= 1 ) {
         double tempReal = 0.0;
         double diffP = 0.0;
         double diffM = 0.0;
         tempReal = inHigh;
         diffP = tempReal - sp.prevHigh;
         /* Plus Delta */
         sp.prevHigh = tempReal;
         tempReal = inLow;
         diffM = sp.prevLow - tempReal;
         /* Minus Delta */
         sp.prevLow = tempReal;
         if( diffM > 0 && diffP < diffM ) {
            /* Case 2 and 4: +DM=0,-DM=diffM */
            double _true_range_2 = 0;
            double range_2 = sp.prevHigh - sp.prevLow;
            double tmp_2 = Math.Abs(sp.prevHigh - sp.prevClose);
            if( tmp_2 > range_2 ) {
               range_2 = tmp_2;
            }
            tmp_2 = Math.Abs(sp.prevLow - sp.prevClose);
            if( tmp_2 > range_2 ) {
               range_2 = tmp_2;
            }
            _true_range_2 = range_2;
            tempReal = _true_range_2;
            if( tempReal <= 0.0 ) {
               sp.cur_outReal = (double)0.0;
            } else {
               sp.cur_outReal = diffM / tempReal;
            }
         } else {
            sp.cur_outReal = (double)0.0;
         }
         sp.prevClose = inClose;
      } else {
         double tempReal = 0.0;
         double diffP = 0.0;
         double diffM = 0.0;
         /* Calculate the prevMinusDM */
         tempReal = inHigh;
         diffP = tempReal - sp.prevHigh;
         /* Plus Delta */
         sp.prevHigh = tempReal;
         tempReal = inLow;
         diffM = sp.prevLow - tempReal;
         /* Minus Delta */
         sp.prevLow = tempReal;
         if( diffM > 0 && diffP < diffM ) {
            /* Case 2 and 4: +DM=0,-DM=diffM */
            sp.prevMinusDM = sp.prevMinusDM - sp.prevMinusDM / sp.optInTimePeriod + diffM;
         } else {
            /* Case 1,3,5 and 7 */
            sp.prevMinusDM = sp.prevMinusDM - sp.prevMinusDM / sp.optInTimePeriod;
         }
         /* Calculate the prevTR */
         double _true_range_3 = 0;
         double range_3 = sp.prevHigh - sp.prevLow;
         double tmp_3 = Math.Abs(sp.prevHigh - sp.prevClose);
         if( tmp_3 > range_3 ) {
            range_3 = tmp_3;
         }
         tmp_3 = Math.Abs(sp.prevLow - sp.prevClose);
         if( tmp_3 > range_3 ) {
            range_3 = tmp_3;
         }
         _true_range_3 = range_3;
         tempReal = _true_range_3;
         sp.prevTR = sp.prevTR - sp.prevTR / sp.optInTimePeriod + tempReal;
         sp.prevClose = inClose;
         /* Calculate the DI. The value is rounded (see Wilder book). */
         if( sp.prevTR > 0.0 ) {
            sp.cur_outReal = (100.0 * (sp.prevMinusDM / sp.prevTR));
         } else {
            sp.cur_outReal = 0.0;
         }
      }
   }

   private RetCode MinusDiOpenImpl( MinusDiStream sp, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      int historyLen = inHigh.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inLow.Length != inHigh.Length || inClose.Length != inHigh.Length ) {
         return RetCode.BadParam;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 14;
      } else if( optInTimePeriod < 1 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInTimePeriod <= 1 ) {
         int today = 0;
         int lookbackTotal = 0;
         int outIdx = 0;
         double prevHigh = 0;
         double prevLow = 0;
         double prevClose = 0;
         double prevMinusDM = 0;
         double prevTR = 0;
         double tempReal = 0;
         double diffP = 0;
         double diffM = 0;
         int i = 0;
         /*
          * The DM1 (one period) is base on the largest part of
          * today's range that is outside of yesterdays range.
          *
          * The following 7 cases explain how the +DM and -DM are
          * calculated on one period:
          *
          * Case 1:                       Case 2:
          *    C|                        A|
          *     |                         | C|
          *     | +DM1 = (C-A)           B|  | +DM1 = 0
          *     | -DM1 = 0                   | -DM1 = (B-D)
          * A|  |                           D|
          *  | D|
          * B|
          *
          * Case 3:                       Case 4:
          *    C|                           C|
          *     |                        A|  |
          *     | +DM1 = (C-A)            |  | +DM1 = 0
          *     | -DM1 = 0               B|  | -DM1 = (B-D)
          * A|  |                            |
          *  |  |                           D|
          * B|  |
          *    D|
          *
          * Case 5:                      Case 6:
          * A|                           A| C|
          *  | C| +DM1 = 0                |  |  +DM1 = 0
          *  |  | -DM1 = 0                |  |  -DM1 = 0
          *  | D|                         |  |
          * B|                           B| D|
          *
          *
          * Case 7:
          *
          *    C|
          * A|  |
          *  |  | +DM1=0
          * B|  | -DM1=0
          *    D|
          *
          * In case 3 and 4, the rule is that the smallest delta between
          * (C-A) and (B-D) determine which of +DM or -DM is zero.
          *
          * In case 7, (C-A) and (B-D) are equal, so both +DM and -DM are
          * zero.
          *
          * The rules remain the same when A=B and C=D (when the highs
          * equal the lows).
          *
          * When calculating the DM over a period > 1, the one-period DM
          * for the desired period are initialy sum. In other word,
          * for a -DM14, sum the -DM1 for the first 14 days (that's
          * 13 values because there is no DM for the first day!)
          * Subsequent DM are calculated using the Wilder's
          * smoothing approach:
          *
          *                                    Previous -DM14
          *  Today's -DM14 = Previous -DM14 -  -------------- + Today's -DM1
          *                                         14
          *
          * Calculation of a -DI14 is as follow:
          *
          *               -DM14
          *     -DI14 =  --------
          *                TR14
          *
          * Calculation of the TR14 is:
          *
          *                                   Previous TR14
          *    Today's TR14 = Previous TR14 - -------------- + Today's TR1
          *                                         14
          *
          *    The first TR14 is the summation of the first 14 TR1. See the
          *    TA_TRANGE function on how to calculate the true range.
          *
          * Reference:
          *    New Concepts In Technical Trading Systems, J. Welles Wilder Jr
          */
         /* Original implementation from Wilder's book was doing some integer
          * rounding in its calculations.
          *
          * This was understandable in the context that at the time the book
          * was written, most user were doing the calculation by hand.
          *
          * For a computer, rounding is unnecessary (and even problematic when inputs
          * are close to 1).
          *
          * TA-Lib does not do the rounding. Still, if you want to reproduce Wilder's examples,
          * you can comment out the following #undef/#define and rebuild the library.
          */
         if( optInTimePeriod > 1 ) {
            lookbackTotal = optInTimePeriod + this.unstablePeriod[(int)FuncUnstId.MINUS_DI];
         } else {
            lookbackTotal = 1;
         }
         /* Adjust startIdx to account for the lookback period. */
         if( startIdx < lookbackTotal ) {
            startIdx = lookbackTotal;
         }
         /* Make sure there is still something to evaluate. */
         if( startIdx > endIdx ) {
            outBegIdx = 0;
            outNBElement = 0;
            return RetCode.InsufficientHistory ;
         }
         /* Indicate where the next output should be put
          * in the outReal.
          */
         outIdx = 0;
         /* Trap the case where no smoothing is needed. */
         /* No smoothing needed. Just do the following:
          * for each price bar.
          *          -DM1
          *   -DI1 = ----
          *           TR1
          */
         outBegIdx = startIdx;
         today = startIdx - 1;
         prevHigh = inHigh[today];
         prevLow = inLow[today];
         prevClose = inClose[today];
         while( today < endIdx ) {
            today += 1;
            tempReal = inHigh[today];
            diffP = tempReal - prevHigh;
            /* Plus Delta */
            prevHigh = tempReal;
            tempReal = inLow[today];
            diffM = prevLow - tempReal;
            /* Minus Delta */
            prevLow = tempReal;
            if( diffM > 0 && diffP < diffM ) {
               /* Case 2 and 4: +DM=0,-DM=diffM */
               double _true_range_4 = 0;
               double range_4 = prevHigh - prevLow;
               double tmp_4 = Math.Abs(prevHigh - prevClose);
               if( tmp_4 > range_4 ) {
                  range_4 = tmp_4;
               }
               tmp_4 = Math.Abs(prevLow - prevClose);
               if( tmp_4 > range_4 ) {
                  range_4 = tmp_4;
               }
               _true_range_4 = range_4;
               tempReal = _true_range_4;
               if( tempReal <= 0.0 ) {
                  outReal[outIdx++ * outStride] = (double)0.0;
               } else {
                  outReal[outIdx++ * outStride] = diffM / tempReal;
               }
            } else {
               outReal[outIdx++ * outStride] = (double)0.0;
            }
            prevClose = inClose[today];
         }
         outNBElement = outIdx;
         /* Capture the live batch state into the handle. */
         sp.optInTimePeriod = optInTimePeriod;
         sp.prevHigh = prevHigh;
         sp.prevLow = prevLow;
         sp.prevClose = prevClose;
         sp.prevMinusDM = prevMinusDM;
         sp.prevTR = prevTR;
         sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
         return RetCode.Success;
      } else {
         int today = 0;
         int lookbackTotal = 0;
         int outIdx = 0;
         double prevHigh = 0;
         double prevLow = 0;
         double prevClose = 0;
         double prevMinusDM = 0;
         double prevTR = 0;
         double tempReal = 0;
         double diffP = 0;
         double diffM = 0;
         int i = 0;
         /*
          * The DM1 (one period) is base on the largest part of
          * today's range that is outside of yesterdays range.
          *
          * The following 7 cases explain how the +DM and -DM are
          * calculated on one period:
          *
          * Case 1:                       Case 2:
          *    C|                        A|
          *     |                         | C|
          *     | +DM1 = (C-A)           B|  | +DM1 = 0
          *     | -DM1 = 0                   | -DM1 = (B-D)
          * A|  |                           D|
          *  | D|
          * B|
          *
          * Case 3:                       Case 4:
          *    C|                           C|
          *     |                        A|  |
          *     | +DM1 = (C-A)            |  | +DM1 = 0
          *     | -DM1 = 0               B|  | -DM1 = (B-D)
          * A|  |                            |
          *  |  |                           D|
          * B|  |
          *    D|
          *
          * Case 5:                      Case 6:
          * A|                           A| C|
          *  | C| +DM1 = 0                |  |  +DM1 = 0
          *  |  | -DM1 = 0                |  |  -DM1 = 0
          *  | D|                         |  |
          * B|                           B| D|
          *
          *
          * Case 7:
          *
          *    C|
          * A|  |
          *  |  | +DM1=0
          * B|  | -DM1=0
          *    D|
          *
          * In case 3 and 4, the rule is that the smallest delta between
          * (C-A) and (B-D) determine which of +DM or -DM is zero.
          *
          * In case 7, (C-A) and (B-D) are equal, so both +DM and -DM are
          * zero.
          *
          * The rules remain the same when A=B and C=D (when the highs
          * equal the lows).
          *
          * When calculating the DM over a period > 1, the one-period DM
          * for the desired period are initialy sum. In other word,
          * for a -DM14, sum the -DM1 for the first 14 days (that's
          * 13 values because there is no DM for the first day!)
          * Subsequent DM are calculated using the Wilder's
          * smoothing approach:
          *
          *                                    Previous -DM14
          *  Today's -DM14 = Previous -DM14 -  -------------- + Today's -DM1
          *                                         14
          *
          * Calculation of a -DI14 is as follow:
          *
          *               -DM14
          *     -DI14 =  --------
          *                TR14
          *
          * Calculation of the TR14 is:
          *
          *                                   Previous TR14
          *    Today's TR14 = Previous TR14 - -------------- + Today's TR1
          *                                         14
          *
          *    The first TR14 is the summation of the first 14 TR1. See the
          *    TA_TRANGE function on how to calculate the true range.
          *
          * Reference:
          *    New Concepts In Technical Trading Systems, J. Welles Wilder Jr
          */
         /* Original implementation from Wilder's book was doing some integer
          * rounding in its calculations.
          *
          * This was understandable in the context that at the time the book
          * was written, most user were doing the calculation by hand.
          *
          * For a computer, rounding is unnecessary (and even problematic when inputs
          * are close to 1).
          *
          * TA-Lib does not do the rounding. Still, if you want to reproduce Wilder's examples,
          * you can comment out the following #undef/#define and rebuild the library.
          */
         if( optInTimePeriod > 1 ) {
            lookbackTotal = optInTimePeriod + this.unstablePeriod[(int)FuncUnstId.MINUS_DI];
         } else {
            lookbackTotal = 1;
         }
         /* Adjust startIdx to account for the lookback period. */
         if( startIdx < lookbackTotal ) {
            startIdx = lookbackTotal;
         }
         /* Make sure there is still something to evaluate. */
         if( startIdx > endIdx ) {
            outBegIdx = 0;
            outNBElement = 0;
            return RetCode.InsufficientHistory ;
         }
         /* Indicate where the next output should be put
          * in the outReal.
          */
         outIdx = 0;
         /* Trap the case where no smoothing is needed. */
         /* Process the initial DM and TR */
         today = startIdx;
         outBegIdx = today;
         prevMinusDM = 0.0;
         prevTR = 0.0;
         today = startIdx - lookbackTotal;
         prevHigh = inHigh[today];
         prevLow = inLow[today];
         prevClose = inClose[today];
         i = optInTimePeriod - 1;
         while( i-- > 0 ) {
            today += 1;
            tempReal = inHigh[today];
            diffP = tempReal - prevHigh;
            /* Plus Delta */
            prevHigh = tempReal;
            tempReal = inLow[today];
            diffM = prevLow - tempReal;
            /* Minus Delta */
            prevLow = tempReal;
            if( diffM > 0 && diffP < diffM ) {
               /* Case 2 and 4: +DM=0,-DM=diffM */
               prevMinusDM += diffM;
            }
            double _true_range_5 = 0;
            double range_5 = prevHigh - prevLow;
            double tmp_5 = Math.Abs(prevHigh - prevClose);
            if( tmp_5 > range_5 ) {
               range_5 = tmp_5;
            }
            tmp_5 = Math.Abs(prevLow - prevClose);
            if( tmp_5 > range_5 ) {
               range_5 = tmp_5;
            }
            _true_range_5 = range_5;
            tempReal = _true_range_5;
            prevTR += tempReal;
            prevClose = inClose[today];
         }
         /* Process subsequent DI */
         /* Skip the unstable period. Note that this loop must be executed
          * at least ONCE to calculate the first DI.
          */
         i = this.unstablePeriod[(int)FuncUnstId.MINUS_DI] + 1;
         while( i-- != 0 ) {
            /* Calculate the prevMinusDM */
            today += 1;
            tempReal = inHigh[today];
            diffP = tempReal - prevHigh;
            /* Plus Delta */
            prevHigh = tempReal;
            tempReal = inLow[today];
            diffM = prevLow - tempReal;
            /* Minus Delta */
            prevLow = tempReal;
            if( diffM > 0 && diffP < diffM ) {
               /* Case 2 and 4: +DM=0,-DM=diffM */
               prevMinusDM = prevMinusDM - prevMinusDM / optInTimePeriod + diffM;
            } else {
               /* Case 1,3,5 and 7 */
               prevMinusDM = prevMinusDM - prevMinusDM / optInTimePeriod;
            }
            /* Calculate the prevTR */
            double _true_range_6 = 0;
            double range_6 = prevHigh - prevLow;
            double tmp_6 = Math.Abs(prevHigh - prevClose);
            if( tmp_6 > range_6 ) {
               range_6 = tmp_6;
            }
            tmp_6 = Math.Abs(prevLow - prevClose);
            if( tmp_6 > range_6 ) {
               range_6 = tmp_6;
            }
            _true_range_6 = range_6;
            tempReal = _true_range_6;
            prevTR = prevTR - prevTR / optInTimePeriod + tempReal;
            prevClose = inClose[today];
         }
         /* Now start to write the output in
          * the caller provided outReal.
          */
         /* prevTR is a running sum of true ranges: non-negative by construction and
          * built only by adding, so it carries no cancellation residue and reaches
          * zero only for a window whose every range is exactly zero. Test it exactly.
          * A true range carries the quote unit, so the fixed TA_IS_ZERO band it used
          * to be compared against was a constant in some arbitrary unit, and zeroed
          * the index for any instrument quoted below it (issue #253).
          */
         if( prevTR > 0.0 ) {
            outReal[0 * outStride] = (100.0 * (prevMinusDM / prevTR));
         } else {
            outReal[0 * outStride] = 0.0;
         }
         outIdx = 1;
         while( today < endIdx ) {
            /* Calculate the prevMinusDM */
            today += 1;
            tempReal = inHigh[today];
            diffP = tempReal - prevHigh;
            /* Plus Delta */
            prevHigh = tempReal;
            tempReal = inLow[today];
            diffM = prevLow - tempReal;
            /* Minus Delta */
            prevLow = tempReal;
            if( diffM > 0 && diffP < diffM ) {
               /* Case 2 and 4: +DM=0,-DM=diffM */
               prevMinusDM = prevMinusDM - prevMinusDM / optInTimePeriod + diffM;
            } else {
               /* Case 1,3,5 and 7 */
               prevMinusDM = prevMinusDM - prevMinusDM / optInTimePeriod;
            }
            /* Calculate the prevTR */
            double _true_range_7 = 0;
            double range_7 = prevHigh - prevLow;
            double tmp_7 = Math.Abs(prevHigh - prevClose);
            if( tmp_7 > range_7 ) {
               range_7 = tmp_7;
            }
            tmp_7 = Math.Abs(prevLow - prevClose);
            if( tmp_7 > range_7 ) {
               range_7 = tmp_7;
            }
            _true_range_7 = range_7;
            tempReal = _true_range_7;
            prevTR = prevTR - prevTR / optInTimePeriod + tempReal;
            prevClose = inClose[today];
            /* Calculate the DI. The value is rounded (see Wilder book). */
            if( prevTR > 0.0 ) {
               outReal[outIdx++ * outStride] = (100.0 * (prevMinusDM / prevTR));
            } else {
               outReal[outIdx++ * outStride] = 0.0;
            }
         }
         outNBElement = outIdx;
         /* Capture the live batch state into the handle. */
         sp.optInTimePeriod = optInTimePeriod;
         sp.prevHigh = prevHigh;
         sp.prevLow = prevLow;
         sp.prevClose = prevClose;
         sp.prevMinusDM = prevMinusDM;
         sp.prevTR = prevTR;
         sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
         return RetCode.Success;
      }
   }

   /* MinusDiOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal MinusDiStream MinusDiOpenAndFillInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      MinusDiStream sp = new MinusDiStream(this);
      RetCode retCode = MinusDiOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInTimePeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("MINUS_DI", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind MinusDiOpen (composition seam). */
   internal MinusDiStream MinusDiOpenInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod )
   {
      MinusDiStream sp = new MinusDiStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = MinusDiOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInTimePeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("MINUS_DI", "open", retCode);
   }

   /// <summary>Open a live <c>MINUS_DI</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="MinusDiStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>MINUS_DI</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>MINUS_DI_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>MinusDiOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="MINUS_DI_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>MINUS_DI_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public MinusDiStream MinusDiOpen( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInTimePeriod )
   {
      if( inHigh.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "MINUS_DI open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "MINUS_DI open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("MINUS_DI open: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TaLibArgumentException("MINUS_DI open: inClose is empty", nameof(inClose), RetCode.BadParam);
      RequireHistoryLength("MINUS_DI", "open", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("MINUS_DI", "open", "inClose", inClose.Length, inHigh.Length);
      return MinusDiOpenInternal(inHigh, inLow, inClose, 0, optInTimePeriod);
   }

   /// <summary><c>MinusDiOpen</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>MINUS_DI</c> produces over
   /// the same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - MINUS_DI_Lookback(...)</c> values
   /// and must not alias the inputs or each other — this path writes the outputs
   /// and then reads the input tail to seed its rings, so the batch tier's
   /// in-place allowance does not carry over here. Both are checked before
   /// anything is written, so an undersized span is an <c>ArgumentException</c>
   /// naming it rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="MinusDiStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="MINUS_DI_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">The Minus Directional Indicator (-DI) line. Must hold at least
   /// <c>historyLen - MINUS_DI_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>MINUS_DI_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public MinusDiStream MinusDiOpenAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInTimePeriod, Span<double> outReal )
   {
      if( inHigh.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "MINUS_DI openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "MINUS_DI openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("MINUS_DI openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TaLibArgumentException("MINUS_DI openAndFill: inClose is empty", nameof(inClose), RetCode.BadParam);
      int guardOutLen = OpenFillCount("MINUS_DI", "openAndFill", inHigh.Length, MINUS_DI_Lookback(optInTimePeriod));
      RequireHistoryLength("MINUS_DI", "openAndFill", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("MINUS_DI", "openAndFill", "inClose", inClose.Length, inHigh.Length);
      RequireFillLength("MINUS_DI", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( outReal.Overlaps(inHigh) || outReal.Overlaps(inLow) || outReal.Overlaps(inClose) ) {
         throw StreamFailure("MINUS_DI", "openAndFill", RetCode.BadParam);
      }
      return MinusDiOpenAndFillInternal(inHigh, inLow, inClose, 0, optInTimePeriod, out _, out _, outReal);
   }
