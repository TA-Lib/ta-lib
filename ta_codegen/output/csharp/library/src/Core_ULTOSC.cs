   /// <summary>A live <c>ULTOSC</c> stream: one value per closed bar, bit-identical to
   /// <c>ULTOSC</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.UltoscOpen"/>. There is no close and nothing to
   /// dispose — the handle is ordinary managed state, and an unreferenced handle
   /// is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class UltoscStream
   {
      internal Core core;
      internal int optInTimePeriod1;
      internal int optInTimePeriod2;
      internal int optInTimePeriod3;
      internal double a1Total;
      internal double a2Total;
      internal double a3Total;
      internal double b1Total;
      internal double b2Total;
      internal double b3Total;
      internal int trailingPos1;
      internal int trailingPos2;
      internal int nullRun;
      internal int term_Idx;
      internal int maxIdx_term;
      internal double lag1_inClose;
      internal int cbSize_term;
      internal double[] cb_term_closeMinusTrueLow = [];
      internal double[] cb_term_trueRange = [];
      internal double cur_outReal;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal UltoscStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Ultosc</c> reports over the same bars: the opener sets
      /// it to <c>(lookback, historyLen - lookback)</c>, every <c>Update</c> adds
      /// one to the count — a non-finite bar is rejected but still counted, because
      /// the bar happened — <c>Peek</c> leaves it alone, and <c>Clone</c> carries
      /// it verbatim. A plain <c>Open</c> hands back only the last value, a subset
      /// of this range, because the caller chose not to take the fill.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      internal UltoscStream( UltoscStream other )
      {
         this.core = other.core;
         this.optInTimePeriod1 = other.optInTimePeriod1;
         this.optInTimePeriod2 = other.optInTimePeriod2;
         this.optInTimePeriod3 = other.optInTimePeriod3;
         this.a1Total = other.a1Total;
         this.a2Total = other.a2Total;
         this.a3Total = other.a3Total;
         this.b1Total = other.b1Total;
         this.b2Total = other.b2Total;
         this.b3Total = other.b3Total;
         this.trailingPos1 = other.trailingPos1;
         this.trailingPos2 = other.trailingPos2;
         this.nullRun = other.nullRun;
         this.term_Idx = other.term_Idx;
         this.maxIdx_term = other.maxIdx_term;
         this.lag1_inClose = other.lag1_inClose;
         this.cbSize_term = other.cbSize_term;
         this.cb_term_closeMinusTrueLow = new double[other.cb_term_closeMinusTrueLow.Length];
         Array.Copy( other.cb_term_closeMinusTrueLow, this.cb_term_closeMinusTrueLow, other.cb_term_closeMinusTrueLow.Length );
         this.cb_term_trueRange = new double[other.cb_term_trueRange.Length];
         Array.Copy( other.cb_term_trueRange, this.cb_term_trueRange, other.cb_term_trueRange.Length );
         this.cur_outReal = other.cur_outReal;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Allocates nothing — neither handle state nor a return value.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so no state moves, <see cref="Value"/> still answers the previous value,
      /// and the stream stays usable — just carry on with the next bar.
      /// <see cref="OutRange"/> does advance: the bar happened, so it is counted,
      /// which keeps two handles fed the same series positionally aligned when only
      /// one of them rejects a bar. This is the one place the streaming tier is
      /// stricter than the batch API, which computes on whatever it is given: a
      /// handle retains its state, so a single non-finite bar would poison every
      /// later value it produces.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inHigh, double inLow, double inClose )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) )
         {
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
            throw Core.StreamFailure("ULTOSC", "update", RetCode.BadParam);
         }
         core.UltoscStepImpl(this, inHigh, inLow, inClose);
         if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It copies nothing: the frame runs against this handle, reading its buffers
      /// and holding what the step would commit in locals. The cost does not grow
      /// with the period, and <c>Peek</c> never allocates.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>What <see cref="Update"/> would return for this bar.</returns>
      public double Peek( double inHigh, double inLow, double inClose )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) ) throw Core.StreamFailure("ULTOSC", "peek", RetCode.BadParam);
         UltoscStream sp = this;
         double trueLow = 0.0;
         double trueRange = 0.0;
         double closeMinusTrueLow = 0.0;
         double tempDouble = 0.0;
         double output = 0.0;
         double tempHT = 0.0;
         double tempLT = 0.0;
         double tempCY = 0.0;
         double a1Total = sp.a1Total;
         double a2Total = sp.a2Total;
         double a3Total = sp.a3Total;
         double b1Total = sp.b1Total;
         double b2Total = sp.b2Total;
         double b3Total = sp.b3Total;
         double cur_outReal = sp.cur_outReal;
         double lag1_inClose = sp.lag1_inClose;
         int nullRun = sp.nullRun;
         int term_Idx = sp.term_Idx;
         int trailingPos1 = sp.trailingPos1;
         int trailingPos2 = sp.trailingPos2;
         int pkSlot0 = -1;
         double pkVal0 = 0.0;
         int pkSlot1 = -1;
         double pkVal1 = 0.0;
         /* Add on today's terms */
         tempLT = inLow;
         tempHT = inHigh;
         tempCY = lag1_inClose;
         trueLow = Math.Min(tempLT, tempCY);
         closeMinusTrueLow = inClose - trueLow;
         trueRange = tempHT - tempLT;
         tempDouble = Math.Abs(tempCY - tempHT);
         if( tempDouble > trueRange ) {
            trueRange = tempDouble;
         }
         tempDouble = Math.Abs(tempCY - tempLT);
         if( tempDouble > trueRange ) {
            trueRange = tempDouble;
         }
         pkSlot0 = term_Idx;
         pkVal0 = closeMinusTrueLow;
         pkSlot1 = term_Idx;
         pkVal1 = trueRange;
         a1Total += closeMinusTrueLow;
         a2Total += closeMinusTrueLow;
         a3Total += closeMinusTrueLow;
         b1Total += trueRange;
         b2Total += trueRange;
         b3Total += trueRange;
         /* Once a whole window of no-contribution bars has gone by, every slot it
          * spans is 0.0, so its totals are known to be exactly zero and the
          * residue can be dropped. The periods are sorted shortest-first, so a
          * run long enough for a longer window is long enough for every shorter
          * one.
          */
         if( trueRange == 0.0 && closeMinusTrueLow == 0.0 ) {
            nullRun += 1;
         } else {
            nullRun = 0;
         }
         if( nullRun >= sp.optInTimePeriod1 ) {
            a1Total = 0.0;
            b1Total = 0.0;
            if( nullRun >= sp.optInTimePeriod2 ) {
               a2Total = 0.0;
               b2Total = 0.0;
               if( nullRun >= sp.optInTimePeriod3 ) {
                  nullRun = sp.optInTimePeriod3;
                  a3Total = 0.0;
                  b3Total = 0.0;
               }
            }
         }
         /* Calculate the oscillator value for today. Each window contributes only
          * when it holds a true range; the totals are sums of non-negative terms
          * and the reseed above removes their residue, so the test is exact.
          */
         output = 0.0;
         if( b1Total > 0.0 ) {
            output += 4.0 * (a1Total / b1Total);
         }
         if( b2Total > 0.0 ) {
            output += 2.0 * (a2Total / b2Total);
         }
         if( b3Total > 0.0 ) {
            output += a3Total / b3Total;
         }
         /* Remove the trailing terms to prepare for next day. Each was evaluated
          * once, when its bar entered the ring.
          */
         a1Total -= (trailingPos1 != pkSlot0) ? sp.cb_term_closeMinusTrueLow[trailingPos1] : pkVal0;
         b1Total -= (trailingPos1 != pkSlot1) ? sp.cb_term_trueRange[trailingPos1] : pkVal1;
         trailingPos1 += 1;
         if( trailingPos1 >= sp.optInTimePeriod3 ) {
            trailingPos1 = 0;
         }
         a2Total -= (trailingPos2 != pkSlot0) ? sp.cb_term_closeMinusTrueLow[trailingPos2] : pkVal0;
         b2Total -= (trailingPos2 != pkSlot1) ? sp.cb_term_trueRange[trailingPos2] : pkVal1;
         trailingPos2 += 1;
         if( trailingPos2 >= sp.optInTimePeriod3 ) {
            trailingPos2 = 0;
         }
         term_Idx = term_Idx + 1;
         if( term_Idx > sp.maxIdx_term ) {
            term_Idx = 0;
         }
         a3Total -= (term_Idx != pkSlot0) ? sp.cb_term_closeMinusTrueLow[term_Idx] : pkVal0;
         b3Total -= (term_Idx != pkSlot1) ? sp.cb_term_trueRange[term_Idx] : pkVal1;
         /* Last operation is to write the output. Must
          * be done after the trailing index have all been
          * taken care of because the caller is allowed
          * to have the input array to be also the output
          * array.
          */
         cur_outReal = 100.0 * (output / 7.0);
         /* Increment indexes */
         lag1_inClose = inClose;
         return cur_outReal;
      }

      /// <summary>Commit <c>n</c> closed bars and write their <c>n</c> values, in one call.</summary>
      /// <remarks>
      /// <para>Exactly <c>n</c> back-to-back <see cref="Update"/> calls, with one set of
      /// argument checks instead of <c>n</c>. The outputs must hold at least
      /// <c>n</c> values and must not overlap an input or each other.</para>
      /// <para><see cref="OutRange"/> counts what this call took in, which is what makes
      /// a rejection readable: a non-finite bar <c>k</c> throws
      /// <see cref="System.ArgumentException"/> exactly as <see cref="Update"/>
      /// would, with the bars before <c>k</c> committed and written, bar <c>k</c>
      /// and everything after it not written, and the count advanced by <c>k +
      /// 1</c> — the committed bars plus the rejected one, so the last bar counted
      /// is the one that failed.</para>
      /// </remarks>
      /// <param name="inHigh">Closed bars for <c>inHigh</c>, oldest first.</param>
      /// <param name="inLow">Closed bars for <c>inLow</c>, oldest first.</param>
      /// <param name="inClose">Closed bars for <c>inClose</c>, oldest first.</param>
      /// <param name="outReal">Receives one <c>outReal</c> value per bar committed.</param>
      public void UpdateAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, Span<double> outReal )
      {
         int barCount = inHigh.Length;
         if( inLow.Length != barCount || inClose.Length != barCount || outReal.Length < barCount || outReal.Overlaps(inHigh) || outReal.Overlaps(inLow) || outReal.Overlaps(inClose) ) throw Core.StreamFailure("ULTOSC", "updateAndFill", RetCode.BadParam);
         for( int i = 0; i < barCount; i++ )
         {
            if( !double.IsFinite(inHigh[i]) || !double.IsFinite(inLow[i]) || !double.IsFinite(inClose[i]) )
            {
               if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
               throw Core.StreamFailure("ULTOSC", "updateAndFill", RetCode.BadParam);
            }
            core.UltoscStepImpl(this, inHigh[i], inLow[i], inClose[i]);
            outReal[i] = cur_outReal;
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         }
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public UltoscStream Clone()
      {
         return new UltoscStream(this);
      }
   }

   internal void UltoscStepImpl( UltoscStream sp, double inHigh, double inLow, double inClose )
   {
      double trueLow = 0.0;
      double trueRange = 0.0;
      double closeMinusTrueLow = 0.0;
      double tempDouble = 0.0;
      double output = 0.0;
      double tempHT = 0.0;
      double tempLT = 0.0;
      double tempCY = 0.0;
      /* Add on today's terms */
      tempLT = inLow;
      tempHT = inHigh;
      tempCY = sp.lag1_inClose;
      trueLow = Math.Min(tempLT, tempCY);
      closeMinusTrueLow = inClose - trueLow;
      trueRange = tempHT - tempLT;
      tempDouble = Math.Abs(tempCY - tempHT);
      if( tempDouble > trueRange ) {
         trueRange = tempDouble;
      }
      tempDouble = Math.Abs(tempCY - tempLT);
      if( tempDouble > trueRange ) {
         trueRange = tempDouble;
      }
      sp.cb_term_closeMinusTrueLow[sp.term_Idx] = closeMinusTrueLow;
      sp.cb_term_trueRange[sp.term_Idx] = trueRange;
      sp.a1Total += closeMinusTrueLow;
      sp.a2Total += closeMinusTrueLow;
      sp.a3Total += closeMinusTrueLow;
      sp.b1Total += trueRange;
      sp.b2Total += trueRange;
      sp.b3Total += trueRange;
      /* Once a whole window of no-contribution bars has gone by, every slot it
       * spans is 0.0, so its totals are known to be exactly zero and the
       * residue can be dropped. The periods are sorted shortest-first, so a
       * run long enough for a longer window is long enough for every shorter
       * one.
       */
      if( trueRange == 0.0 && closeMinusTrueLow == 0.0 ) {
         sp.nullRun += 1;
      } else {
         sp.nullRun = 0;
      }
      if( sp.nullRun >= sp.optInTimePeriod1 ) {
         sp.a1Total = 0.0;
         sp.b1Total = 0.0;
         if( sp.nullRun >= sp.optInTimePeriod2 ) {
            sp.a2Total = 0.0;
            sp.b2Total = 0.0;
            if( sp.nullRun >= sp.optInTimePeriod3 ) {
               sp.nullRun = sp.optInTimePeriod3;
               sp.a3Total = 0.0;
               sp.b3Total = 0.0;
            }
         }
      }
      /* Calculate the oscillator value for today. Each window contributes only
       * when it holds a true range; the totals are sums of non-negative terms
       * and the reseed above removes their residue, so the test is exact.
       */
      output = 0.0;
      if( sp.b1Total > 0.0 ) {
         output += 4.0 * (sp.a1Total / sp.b1Total);
      }
      if( sp.b2Total > 0.0 ) {
         output += 2.0 * (sp.a2Total / sp.b2Total);
      }
      if( sp.b3Total > 0.0 ) {
         output += sp.a3Total / sp.b3Total;
      }
      /* Remove the trailing terms to prepare for next day. Each was evaluated
       * once, when its bar entered the ring.
       */
      sp.a1Total -= sp.cb_term_closeMinusTrueLow[sp.trailingPos1];
      sp.b1Total -= sp.cb_term_trueRange[sp.trailingPos1];
      sp.trailingPos1 += 1;
      if( sp.trailingPos1 >= sp.optInTimePeriod3 ) {
         sp.trailingPos1 = 0;
      }
      sp.a2Total -= sp.cb_term_closeMinusTrueLow[sp.trailingPos2];
      sp.b2Total -= sp.cb_term_trueRange[sp.trailingPos2];
      sp.trailingPos2 += 1;
      if( sp.trailingPos2 >= sp.optInTimePeriod3 ) {
         sp.trailingPos2 = 0;
      }
      sp.term_Idx = sp.term_Idx + 1;
      if( sp.term_Idx > sp.maxIdx_term ) {
         sp.term_Idx = 0;
      }
      sp.a3Total -= sp.cb_term_closeMinusTrueLow[sp.term_Idx];
      sp.b3Total -= sp.cb_term_trueRange[sp.term_Idx];
      /* Last operation is to write the output. Must
       * be done after the trailing index have all been
       * taken care of because the caller is allowed
       * to have the input array to be also the output
       * array.
       */
      sp.cur_outReal = 100.0 * (output / 7.0);
      /* Increment indexes */
      sp.lag1_inClose = inClose;
   }

   private RetCode UltoscOpenImpl( UltoscStream sp, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod1, int optInTimePeriod2, int optInTimePeriod3, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double a1Total = 0;
      double a2Total = 0;
      double a3Total = 0;
      double b1Total = 0;
      double b2Total = 0;
      double b3Total = 0;
      double trueLow = 0;
      double trueRange = 0;
      double closeMinusTrueLow = 0;
      double tempDouble = 0;
      double output = 0;
      double tempHT = 0;
      double tempLT = 0;
      double tempCY = 0;
      int lookbackTotal = 0;
      int longestPeriod = 0;
      int longestIndex = 0;
      int i = 0;
      int j = 0;
      int today = 0;
      int outIdx = 0;
      int trailingPos1 = 0;
      int trailingPos2 = 0;
      int nullRun = 0;
      int[] usedFlag = new int[3];
      int[] periods = new int[3];
      int[] sortedPeriods = new int[3];
      double[] term_closeMinusTrueLow = [];
      double[] term_trueRange = [];
      int term_Idx = 0;
      int maxIdx_term = (32)-1;
      int historyLen = inHigh.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inLow.Length != inHigh.Length || inClose.Length != inHigh.Length ) {
         return RetCode.BadParam;
      }
      if( optInTimePeriod1 == int.MinValue ) {
         optInTimePeriod1 = 7;
      } else if( optInTimePeriod1 < 1 || optInTimePeriod1 > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInTimePeriod2 == int.MinValue ) {
         optInTimePeriod2 = 14;
      } else if( optInTimePeriod2 < 1 || optInTimePeriod2 > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInTimePeriod3 == int.MinValue ) {
         optInTimePeriod3 = 28;
      } else if( optInTimePeriod3 < 1 || optInTimePeriod3 > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      /* The two per-bar terms the three moving sums are built from. Both are a
       * pure function of the bar, so each bar is evaluated once on entry and read
       * back when it leaves each of the three windows.
       */
      /* One entry per bar of the longest window. Stays on the stack for every
       * period up to 32, which covers the 7/14/28 default.
       */
      /* Id, Type, Static Size */
      outBegIdx = 0;
      outNBElement = 0;
      /* Ensure that the time periods are ordered from shortest to longest.
       * Sort.
       */
      periods[0] = optInTimePeriod1;
      periods[1] = optInTimePeriod2;
      periods[2] = optInTimePeriod3;
      usedFlag[0] = 0;
      usedFlag[1] = 0;
      usedFlag[2] = 0;
      for( i = 0; i < 3; i += 1 ) {
         longestPeriod = 0;
         longestIndex = 0;
         for( j = 0; j < 3; j += 1 ) {
            if( usedFlag[j] == 0 && periods[j] > longestPeriod ) {
               longestPeriod = periods[j];
               longestIndex = j;
            }
         }
         usedFlag[longestIndex] = 1;
         sortedPeriods[i] = longestPeriod;
      }
      optInTimePeriod1 = sortedPeriods[2];
      optInTimePeriod2 = sortedPeriods[1];
      optInTimePeriod3 = sortedPeriods[0];
      /* Adjust startIdx for lookback period. */
      lookbackTotal = ULTOSC_Lookback(optInTimePeriod1, optInTimePeriod2, optInTimePeriod3);
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         return RetCode.InsufficientHistory ;
      }
      if( optInTimePeriod3 < 1 ) return RetCode.InternalError;
      term_closeMinusTrueLow = new double[optInTimePeriod3];
      term_trueRange = new double[optInTimePeriod3];
      maxIdx_term = (optInTimePeriod3)-1;
      term_Idx = 0;
      /* Prime running totals used in moving averages.
       *
       * One pass over the longest warm-up window replaces three overlapping
       * passes. A bar inside the shorter windows is added to those totals as it
       * is reached, so every total still accumulates exactly the same bars in
       * exactly the same ascending order as three separate loops did.
       */
      a1Total = 0;
      b1Total = 0;
      a2Total = 0;
      b2Total = 0;
      a3Total = 0;
      b3Total = 0;
      /* Consecutive bars that put nothing into the windows, counted so that an
       * empty window can be recognized exactly (the shape #244 needed for MFI).
       * The running totals cannot answer that question themselves: they are
       * maintained by add-then-subtract, so once a window empties they hold
       * rounding residue of arbitrary sign rather than zero, and v0.6.4 divides
       * one residue by another there -- it returns -92.9 for an oscillator
       * documented to run 0..100. Both of a bar's terms have to be zero for it to
       * count, which for valid bars is one condition (a zero true range means
       * H == L == the previous close, which leaves the close on the true low).
       * Reseeding on the count is what lets the divides below be guarded exactly
       * rather than against a fixed band -- a true range carries the quote unit,
       * so the band they used to carry zeroed the oscillator for any instrument
       * quoted below it (issue #253).
       */
      nullRun = 0;
      for( i = startIdx - optInTimePeriod3 + 1; i < startIdx; i += 1 ) {
         tempLT = inLow[i];
         tempHT = inHigh[i];
         tempCY = inClose[i - 1];
         trueLow = Math.Min(tempLT, tempCY);
         closeMinusTrueLow = inClose[i] - trueLow;
         trueRange = tempHT - tempLT;
         tempDouble = Math.Abs(tempCY - tempHT);
         if( tempDouble > trueRange ) {
            trueRange = tempDouble;
         }
         tempDouble = Math.Abs(tempCY - tempLT);
         if( tempDouble > trueRange ) {
            trueRange = tempDouble;
         }
         term_closeMinusTrueLow[term_Idx] = closeMinusTrueLow;
         term_trueRange[term_Idx] = trueRange;
         term_Idx++;
         if( term_Idx > maxIdx_term ) { term_Idx = 0; }
         if( trueRange == 0.0 && closeMinusTrueLow == 0.0 ) {
            nullRun += 1;
         } else {
            nullRun = 0;
         }
         if( i >= startIdx - optInTimePeriod1 + 1 ) {
            a1Total += closeMinusTrueLow;
            b1Total += trueRange;
         }
         if( i >= startIdx - optInTimePeriod2 + 1 ) {
            a2Total += closeMinusTrueLow;
            b2Total += trueRange;
         }
         a3Total += closeMinusTrueLow;
         b3Total += trueRange;
      }
      /* Calculate oscillator */
      today = startIdx;
      outIdx = 0;
      /* The warm-up wrote optInTimePeriod3-1 bars, so term_Idx is the slot for
       * `today` and, once advanced past it, the slot of the bar leaving the
       * longest window. The two shorter windows trail it by a fixed offset.
       */
      trailingPos1 = term_Idx + optInTimePeriod3 - optInTimePeriod1 + 1;
      if( trailingPos1 >= optInTimePeriod3 ) {
         trailingPos1 -= optInTimePeriod3;
      }
      trailingPos2 = term_Idx + optInTimePeriod3 - optInTimePeriod2 + 1;
      if( trailingPos2 >= optInTimePeriod3 ) {
         trailingPos2 -= optInTimePeriod3;
      }
      while( today <= endIdx ) {
         /* Add on today's terms */
         tempLT = inLow[today];
         tempHT = inHigh[today];
         tempCY = inClose[today - 1];
         trueLow = Math.Min(tempLT, tempCY);
         closeMinusTrueLow = inClose[today] - trueLow;
         trueRange = tempHT - tempLT;
         tempDouble = Math.Abs(tempCY - tempHT);
         if( tempDouble > trueRange ) {
            trueRange = tempDouble;
         }
         tempDouble = Math.Abs(tempCY - tempLT);
         if( tempDouble > trueRange ) {
            trueRange = tempDouble;
         }
         term_closeMinusTrueLow[term_Idx] = closeMinusTrueLow;
         term_trueRange[term_Idx] = trueRange;
         a1Total += closeMinusTrueLow;
         a2Total += closeMinusTrueLow;
         a3Total += closeMinusTrueLow;
         b1Total += trueRange;
         b2Total += trueRange;
         b3Total += trueRange;
         /* Once a whole window of no-contribution bars has gone by, every slot it
          * spans is 0.0, so its totals are known to be exactly zero and the
          * residue can be dropped. The periods are sorted shortest-first, so a
          * run long enough for a longer window is long enough for every shorter
          * one.
          */
         if( trueRange == 0.0 && closeMinusTrueLow == 0.0 ) {
            nullRun += 1;
         } else {
            nullRun = 0;
         }
         if( nullRun >= optInTimePeriod1 ) {
            a1Total = 0.0;
            b1Total = 0.0;
            if( nullRun >= optInTimePeriod2 ) {
               a2Total = 0.0;
               b2Total = 0.0;
               if( nullRun >= optInTimePeriod3 ) {
                  nullRun = optInTimePeriod3;
                  a3Total = 0.0;
                  b3Total = 0.0;
               }
            }
         }
         /* Calculate the oscillator value for today. Each window contributes only
          * when it holds a true range; the totals are sums of non-negative terms
          * and the reseed above removes their residue, so the test is exact.
          */
         output = 0.0;
         if( b1Total > 0.0 ) {
            output += 4.0 * (a1Total / b1Total);
         }
         if( b2Total > 0.0 ) {
            output += 2.0 * (a2Total / b2Total);
         }
         if( b3Total > 0.0 ) {
            output += a3Total / b3Total;
         }
         /* Remove the trailing terms to prepare for next day. Each was evaluated
          * once, when its bar entered the ring.
          */
         a1Total -= term_closeMinusTrueLow[trailingPos1];
         b1Total -= term_trueRange[trailingPos1];
         trailingPos1 += 1;
         if( trailingPos1 >= optInTimePeriod3 ) {
            trailingPos1 = 0;
         }
         a2Total -= term_closeMinusTrueLow[trailingPos2];
         b2Total -= term_trueRange[trailingPos2];
         trailingPos2 += 1;
         if( trailingPos2 >= optInTimePeriod3 ) {
            trailingPos2 = 0;
         }
         term_Idx++;
         if( term_Idx > maxIdx_term ) { term_Idx = 0; }
         a3Total -= term_closeMinusTrueLow[term_Idx];
         b3Total -= term_trueRange[term_Idx];
         /* Last operation is to write the output. Must
          * be done after the trailing index have all been
          * taken care of because the caller is allowed
          * to have the input array to be also the output
          * array.
          */
         outReal[outIdx * outStride] = 100.0 * (output / 7.0);
         /* Increment indexes */
         outIdx += 1;
         today += 1;
      }
      /* All done. Indicate the output limits and return. */
      outNBElement = outIdx;
      outBegIdx = startIdx;
      /* Capture the live batch state into the handle. */
      int capCb_term = maxIdx_term + 1;
      if( capCb_term > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      sp.optInTimePeriod1 = optInTimePeriod1;
      sp.optInTimePeriod2 = optInTimePeriod2;
      sp.optInTimePeriod3 = optInTimePeriod3;
      sp.a1Total = a1Total;
      sp.a2Total = a2Total;
      sp.a3Total = a3Total;
      sp.b1Total = b1Total;
      sp.b2Total = b2Total;
      sp.b3Total = b3Total;
      sp.trailingPos1 = trailingPos1;
      sp.trailingPos2 = trailingPos2;
      sp.nullRun = nullRun;
      sp.term_Idx = term_Idx;
      sp.maxIdx_term = maxIdx_term;
      sp.lag1_inClose = inClose[historyLen - 1];
      sp.cbSize_term = capCb_term;
      sp.cb_term_closeMinusTrueLow = term_closeMinusTrueLow;
      sp.cb_term_trueRange = term_trueRange;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* UltoscOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal UltoscStream UltoscOpenAndFillInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod1, int optInTimePeriod2, int optInTimePeriod3, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      UltoscStream sp = new UltoscStream(this);
      RetCode retCode = UltoscOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInTimePeriod1, optInTimePeriod2, optInTimePeriod3, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("ULTOSC", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind UltoscOpen (composition seam). */
   internal UltoscStream UltoscOpenInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod1, int optInTimePeriod2, int optInTimePeriod3 )
   {
      UltoscStream sp = new UltoscStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = UltoscOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInTimePeriod1, optInTimePeriod2, optInTimePeriod3, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("ULTOSC", "open", retCode);
   }

   /// <summary>Open a live <c>ULTOSC</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="UltoscStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>ULTOSC</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>ULTOSC_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>UltoscOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod1">As in the batch call; see <see cref="ULTOSC_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInTimePeriod2">As in the batch call; see <see cref="ULTOSC_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInTimePeriod3">As in the batch call; see <see cref="ULTOSC_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>ULTOSC_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public UltoscStream UltoscOpen( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInTimePeriod1, int optInTimePeriod2, int optInTimePeriod3 )
   {
      if( inHigh.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "ULTOSC open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "ULTOSC open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("ULTOSC open: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TaLibArgumentException("ULTOSC open: inClose is empty", nameof(inClose), RetCode.BadParam);
      RequireHistoryLength("ULTOSC", "open", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("ULTOSC", "open", "inClose", inClose.Length, inHigh.Length);
      return UltoscOpenInternal(inHigh, inLow, inClose, 0, optInTimePeriod1, optInTimePeriod2, optInTimePeriod3);
   }

   /// <summary><c>UltoscOpen</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>ULTOSC</c> produces over
   /// the same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - ULTOSC_Lookback(...)</c> values
   /// and must not alias the inputs or each other — this path writes the outputs
   /// and then reads the input tail to seed its rings, so the batch tier's
   /// in-place allowance does not carry over here. Both are checked before
   /// anything is written, so an undersized span is an <c>ArgumentException</c>
   /// naming it rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="UltoscStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod1">As in the batch call; see <see cref="ULTOSC_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInTimePeriod2">As in the batch call; see <see cref="ULTOSC_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInTimePeriod3">As in the batch call; see <see cref="ULTOSC_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Ultimate Oscillator value. Must hold at least <c>historyLen -
   /// ULTOSC_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>ULTOSC_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public UltoscStream UltoscOpenAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInTimePeriod1, int optInTimePeriod2, int optInTimePeriod3, Span<double> outReal )
   {
      if( inHigh.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "ULTOSC openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "ULTOSC openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("ULTOSC openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TaLibArgumentException("ULTOSC openAndFill: inClose is empty", nameof(inClose), RetCode.BadParam);
      int guardOutLen = OpenFillCount("ULTOSC", "openAndFill", inHigh.Length, ULTOSC_Lookback(optInTimePeriod1, optInTimePeriod2, optInTimePeriod3));
      RequireHistoryLength("ULTOSC", "openAndFill", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("ULTOSC", "openAndFill", "inClose", inClose.Length, inHigh.Length);
      RequireFillLength("ULTOSC", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( outReal.Overlaps(inHigh) || outReal.Overlaps(inLow) || outReal.Overlaps(inClose) ) {
         throw StreamFailure("ULTOSC", "openAndFill", RetCode.BadParam);
      }
      return UltoscOpenAndFillInternal(inHigh, inLow, inClose, 0, optInTimePeriod1, optInTimePeriod2, optInTimePeriod3, out _, out _, outReal);
   }
