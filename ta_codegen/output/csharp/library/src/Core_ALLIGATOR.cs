   /// <summary>A live <c>ALLIGATOR</c> stream: one value per closed bar, bit-identical to
   /// <c>ALLIGATOR</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.AlligatorOpen"/>. There is no close and nothing
   /// to dispose — the handle is ordinary managed state, and an unreferenced
   /// handle is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class AlligatorStream
   {
      internal Core core;
      internal int optInJawPeriod;
      internal int optInJawShift;
      internal int optInTeethPeriod;
      internal int optInTeethShift;
      internal int optInLipsPeriod;
      internal int optInLipsShift;
      internal double cur_outJaw;
      internal double cur_outTeeth;
      internal double cur_outLips;
      internal MedpriceStream sub0 = null!;
      internal RmaStream sub1 = null!;
      internal RmaStream sub2 = null!;
      internal RmaStream sub3 = null!;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal AlligatorStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Alligator</c> reports over the same bars: the opener
      /// sets it to <c>(lookback, historyLen - lookback)</c>, every accepted
      /// <c>Update</c> adds one to the count — a rejected one changes nothing, and
      /// neither does <c>Peek</c> — and <c>Clone</c> carries it verbatim. A plain
      /// <c>Open</c> hands back only the last value, a subset of this range,
      /// because the caller chose not to take the fill.</para>
      /// <para>The last bar it can reach is <see cref="Core.IndexMax"/>; past that
      /// <c>Update</c> and <c>Advance</c> throw.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      /// <summary>Count one bar this stream was not fed: <see cref="OutRange"/> advances by
      /// one and nothing else moves.</summary>
      /// <remarks>
      /// <para><see cref="Value"/> keeps answering the previous output, which is this
      /// bar's output too. For a bar the caller leaves out: one an <c>Update</c>
      /// rejected and that will not be re-fed, or a session with no print. Without
      /// it two handles on one feed drift a bar apart when only one of them skips.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, the last one the batch tier
      /// can address and the last this handle will count. <c>Update</c> throws the
      /// same there.</para>
      /// </remarks>
      public void Advance()
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("ALLIGATOR", "advance", RetCode.OutOfRangeEndIndex);
         outRangeCount++;
      }

      internal AlligatorStream( AlligatorStream other )
      {
         this.core = other.core;
         this.optInJawPeriod = other.optInJawPeriod;
         this.optInJawShift = other.optInJawShift;
         this.optInTeethPeriod = other.optInTeethPeriod;
         this.optInTeethShift = other.optInTeethShift;
         this.optInLipsPeriod = other.optInLipsPeriod;
         this.optInLipsShift = other.optInLipsShift;
         this.cur_outJaw = other.cur_outJaw;
         this.cur_outTeeth = other.cur_outTeeth;
         this.cur_outLips = other.cur_outLips;
         this.sub0 = new MedpriceStream(other.sub0);
         this.sub1 = new RmaStream(other.sub1);
         this.sub2 = new RmaStream(other.sub2);
         this.sub3 = new RmaStream(other.sub3);
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so nothing moves — <see cref="OutRange"/> included — and
      /// <see cref="Value"/> still answers the previous value. Re-feed the bar when
      /// a corrected value arrives, or call <see cref="Advance"/> to count it and
      /// carry on; two handles on one feed drift a bar apart if neither happens.
      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, which no re-feed clears: the
      /// handle has run out of index domain and only a shorter history can start a
      /// new one.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <returns>The value at the bar just committed.</returns>
      public AlligatorValue Update( double inHigh, double inLow )
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("ALLIGATOR", "update", RetCode.OutOfRangeEndIndex);
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) ) throw Core.NonFiniteBar("ALLIGATOR", "update", !double.IsFinite(inHigh) ? nameof(inHigh) : nameof(inLow));
         core.AlligatorStepImpl(this, inHigh, inLow);
         outRangeCount++;
         return new AlligatorValue(cur_outJaw, cur_outTeeth, cur_outLips);
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.IndexMax"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public AlligatorValue Peek( double inHigh, double inLow )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) ) throw Core.NonFiniteBar("ALLIGATOR", "peek", !double.IsFinite(inHigh) ? nameof(inHigh) : nameof(inLow));
         AlligatorStream sp = this;
         double cur_tempMP = 0.0;
         double cur_outJaw = 0.0;
         double cur_outTeeth = 0.0;
         double cur_outLips = 0.0;
         /* Pipeline the new bar through the sub-streams (batch tail order). */
         cur_tempMP = sp.sub0.Peek(inHigh, inLow);
         cur_outJaw = sp.sub1.Peek(cur_tempMP);
         cur_outTeeth = sp.sub2.Peek(cur_tempMP);
         cur_outLips = sp.sub3.Peek(cur_tempMP);
         return new AlligatorValue(cur_outJaw, cur_outTeeth, cur_outLips);
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public AlligatorValue Value => new AlligatorValue(cur_outJaw, cur_outTeeth, cur_outLips);

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public AlligatorStream Clone()
      {
         return new AlligatorStream(this);
      }
   }

   private void AlligatorStepImpl( AlligatorStream sp, double inHigh, double inLow )
   {
      double cur_tempMP = 0.0;
      double cur_outJaw = 0.0;
      double cur_outTeeth = 0.0;
      double cur_outLips = 0.0;
      /* Pipeline the new bar through the sub-streams (batch tail order). */
      cur_tempMP = sp.sub0.Update(inHigh, inLow);
      cur_outJaw = sp.sub1.Update(cur_tempMP);
      cur_outTeeth = sp.sub2.Update(cur_tempMP);
      cur_outLips = sp.sub3.Update(cur_tempMP);
      sp.cur_outJaw = cur_outJaw;
      sp.cur_outTeeth = cur_outTeeth;
      sp.cur_outLips = cur_outLips;
   }

   private RetCode AlligatorOpenImpl( AlligatorStream sp, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int startIdx, int optInJawPeriod, int optInJawShift, int optInTeethPeriod, int optInTeethShift, int optInLipsPeriod, int optInLipsShift, out int outBegIdx, out int outNBElement, Span<double> outJaw, Span<double> outTeeth, Span<double> outLips, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      RetCode retCode;
      int lookbackTotal = 0;
      int mpStartIdx = 0;
      int tempBegIdx = 0;
      int tempNbElement = 0;
      Span<double> tempMP;
      int historyLen = inHigh.Length;
      int endIdx = historyLen - 1;
      if( historyLen > IndexMax + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inLow.Length != inHigh.Length ) {
         return RetCode.BadParam;
      }
      if( optInJawPeriod == int.MinValue ) {
         optInJawPeriod = 13;
      } else if( optInJawPeriod < 1 || optInJawPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInJawShift == int.MinValue ) {
         optInJawShift = 8;
      } else if( optInJawShift < 0 || optInJawShift > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInTeethPeriod == int.MinValue ) {
         optInTeethPeriod = 8;
      } else if( optInTeethPeriod < 1 || optInTeethPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInTeethShift == int.MinValue ) {
         optInTeethShift = 5;
      } else if( optInTeethShift < 0 || optInTeethShift > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInLipsPeriod == int.MinValue ) {
         optInLipsPeriod = 5;
      } else if( optInLipsPeriod < 1 || optInLipsPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInLipsShift == int.MinValue ) {
         optInLipsShift = 3;
      } else if( optInLipsShift < 0 || optInLipsShift > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx >= historyLen ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      if( historyLen < AlligatorLookback(optInJawPeriod, optInJawShift, optInTeethPeriod, optInTeethShift, optInLipsPeriod, optInLipsShift) + 1 ) {
         return RetCode.InsufficientHistory;
      }
      Span<double> sc_outJaw = outStride == 1 ? outJaw : new double[historyLen];
      Span<double> sc_outTeeth = outStride == 1 ? outTeeth : new double[historyLen];
      Span<double> sc_outLips = outStride == 1 ? outLips : new double[historyLen];
      lookbackTotal = AlligatorLookback(optInJawPeriod, optInJawShift, optInTeethPeriod, optInTeethShift, optInLipsPeriod, optInLipsShift);
      /* Return before touching anything, so that an input which stops short of
       * endIdx is never read past its end.
       */
      if( lookbackTotal > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      mpStartIdx = startIdx - lookbackTotal;
      tempMP = new double[(int)((endIdx - mpStartIdx + 1) * 1)];
      /* Every price is consumed here, before any output is written: an output
       * may be aliased onto inHigh or inLow.
       */
      /* Sub-stream 0: medprice over `inHigh, inLow`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      MedpriceStream sub0 = MedpriceOpenAndFillInternal(inHigh, inLow, mpStartIdx, out tempBegIdx, out tempNbElement, tempMP);
      retCode = RetCode.Success;
      /* Each leg is entered at startIdx (local index lookbackTotal) and seeds at
       * its OWN lookback before it, so each is exactly TA_RMA over the bars it
       * reads and no leg moves when another leg's period changes. A caller who
       * wants the short legs converged sets TA_FUNC_UNST_RMA.
       */
      /* Sub-stream 1: rma over `tempMP`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      int subLen1 = (endIdx - mpStartIdx) + 1;
      double[] subSrc1_0 = new double[subLen1];
      tempMP.Slice(0, subLen1).CopyTo(subSrc1_0);
      RmaStream sub1 = RmaOpenAndFillInternal(subSrc1_0, lookbackTotal, optInJawPeriod, out tempBegIdx, out tempNbElement, sc_outJaw);
      retCode = RetCode.Success;
      if( tempNbElement == 0 ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      /* Sub-stream 2: rma over `tempMP`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      int subLen2 = (endIdx - mpStartIdx) + 1;
      double[] subSrc2_0 = new double[subLen2];
      tempMP.Slice(0, subLen2).CopyTo(subSrc2_0);
      RmaStream sub2 = RmaOpenAndFillInternal(subSrc2_0, lookbackTotal, optInTeethPeriod, out tempBegIdx, out tempNbElement, sc_outTeeth);
      retCode = RetCode.Success;
      if( tempNbElement == 0 ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      /* Sub-stream 3: rma over `tempMP`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      int subLen3 = (endIdx - mpStartIdx) + 1;
      double[] subSrc3_0 = new double[subLen3];
      tempMP.Slice(0, subLen3).CopyTo(subSrc3_0);
      RmaStream sub3 = RmaOpenAndFillInternal(subSrc3_0, lookbackTotal, optInLipsPeriod, out tempBegIdx, out tempNbElement, sc_outLips);
      retCode = RetCode.Success;
      if( tempNbElement == 0 ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      outBegIdx = startIdx;
      outNBElement = tempNbElement;
      /* Capture the live producer state + sub handles. */
      if( outNBElement < 1 ) {
         return RetCode.InsufficientHistory;
      }
      sp.optInJawPeriod = optInJawPeriod;
      sp.optInJawShift = optInJawShift;
      sp.optInTeethPeriod = optInTeethPeriod;
      sp.optInTeethShift = optInTeethShift;
      sp.optInLipsPeriod = optInLipsPeriod;
      sp.optInLipsShift = optInLipsShift;
      sp.sub0 = sub0;
      sp.sub1 = sub1;
      sp.sub2 = sub2;
      sp.sub3 = sub3;
      sp.cur_outJaw = sc_outJaw[outNBElement - 1];
      sp.cur_outTeeth = sc_outTeeth[outNBElement - 1];
      sp.cur_outLips = sc_outLips[outNBElement - 1];
      return RetCode.Success;
   }

   /* AlligatorOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal AlligatorStream AlligatorOpenAndFillInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int startIdx, int optInJawPeriod, int optInJawShift, int optInTeethPeriod, int optInTeethShift, int optInLipsPeriod, int optInLipsShift, out int outBegIdx, out int outNBElement, Span<double> outJaw, Span<double> outTeeth, Span<double> outLips )
   {
      AlligatorStream sp = new AlligatorStream(this);
      RetCode retCode = AlligatorOpenImpl(sp, inHigh, inLow, startIdx, optInJawPeriod, optInJawShift, optInTeethPeriod, optInTeethShift, optInLipsPeriod, optInLipsShift, out outBegIdx, out outNBElement, outJaw, outTeeth, outLips, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("ALLIGATOR", "openAndFill", nameof(inHigh), inHigh.Length, startIdx, AlligatorLookback(optInJawPeriod, optInJawShift, optInTeethPeriod, optInTeethShift, optInLipsPeriod, optInLipsShift));
      }
      throw StreamFailure("ALLIGATOR", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind AlligatorOpen (composition seam). */
   internal AlligatorStream AlligatorOpenInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int startIdx, int optInJawPeriod, int optInJawShift, int optInTeethPeriod, int optInTeethShift, int optInLipsPeriod, int optInLipsShift )
   {
      AlligatorStream sp = new AlligatorStream(this);
      double[] sink_outJaw = new double[1];
      double[] sink_outTeeth = new double[1];
      double[] sink_outLips = new double[1];
      RetCode retCode = AlligatorOpenImpl(sp, inHigh, inLow, startIdx, optInJawPeriod, optInJawShift, optInTeethPeriod, optInTeethShift, optInLipsPeriod, optInLipsShift, out int outBegIdx, out int outNBElement, sink_outJaw, sink_outTeeth, sink_outLips, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("ALLIGATOR", "open", nameof(inHigh), inHigh.Length, startIdx, AlligatorLookback(optInJawPeriod, optInJawShift, optInTeethPeriod, optInTeethShift, optInLipsPeriod, optInLipsShift));
      }
      throw StreamFailure("ALLIGATOR", "open", retCode);
   }

   /// <summary>Open a live <c>ALLIGATOR</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="AlligatorStream.Value"/> starts at the last
   /// history bar's value — bit-identical to what <c>ALLIGATOR</c> reports for
   /// that bar.</para>
   /// <para>The history must hold at least <c>AlligatorLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>AlligatorOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInJawPeriod">As in the batch call; see <see cref="AlligatorLookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInJawShift">As in the batch call; see <see cref="AlligatorLookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInTeethPeriod">As in the batch call; see <see cref="AlligatorLookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInTeethShift">As in the batch call; see <see cref="AlligatorLookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInLipsPeriod">As in the batch call; see <see cref="AlligatorLookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInLipsShift">As in the batch call; see <see cref="AlligatorLookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>AlligatorLookback(...) + 1</c> bars, an
   /// empty one included — which is what a null array becomes, since a span
   /// cannot be null.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is longer than <see cref="Core.IndexMax"/> + 1, the one index
   /// fault an opener can have (rule rS2).</exception>
   public AlligatorStream AlligatorOpen( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int optInJawPeriod, int optInJawShift, int optInTeethPeriod, int optInTeethShift, int optInLipsPeriod, int optInLipsShift )
   {
      if( inHigh.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "ALLIGATOR open: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( !inHigh.IsEmpty ) {
         if( inLow.IsEmpty ) throw new TALibArgumentException("ALLIGATOR open: inLow is empty", nameof(inLow), RetCode.BadParam);
      }
      RequireHistoryLength("ALLIGATOR", "open", "inLow", inLow.Length, inHigh.Length);
      return AlligatorOpenInternal(inHigh, inLow, 0, optInJawPeriod, optInJawShift, optInTeethPeriod, optInTeethShift, optInLipsPeriod, optInLipsShift);
   }

   /// <summary><c>AlligatorOpen</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>ALLIGATOR</c> produces
   /// over the same series, so no separate batch call is needed for the warm-up
   /// plot.</para>
   /// <para>Output arrays must hold <c>historyLen - AlligatorLookback(...)</c> values
   /// and must not alias the inputs or each other — this path writes the outputs
   /// and then reads the input tail to seed its rings, so the batch tier's
   /// in-place allowance does not carry over here. Both are checked before
   /// anything is written, so an undersized span is an <c>ArgumentException</c>
   /// naming it rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="AlligatorStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInJawPeriod">As in the batch call; see <see cref="AlligatorLookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInJawShift">As in the batch call; see <see cref="AlligatorLookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInTeethPeriod">As in the batch call; see <see cref="AlligatorLookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInTeethShift">As in the batch call; see <see cref="AlligatorLookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInLipsPeriod">As in the batch call; see <see cref="AlligatorLookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInLipsShift">As in the batch call; see <see cref="AlligatorLookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outJaw">Jaw: the slowest line, drawn ahead by the jaw shift. Must hold at least
   /// <c>historyLen - AlligatorLookback(...)</c> values.</param>
   /// <param name="outTeeth">Teeth: the middle line, drawn ahead by the teeth shift. Must hold at least
   /// <c>historyLen - AlligatorLookback(...)</c> values.</param>
   /// <param name="outLips">Lips: the fastest line, drawn ahead by the lips shift. Must hold at least
   /// <c>historyLen - AlligatorLookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>AlligatorLookback(...) + 1</c> bars, an
   /// empty one included — which is what a null array becomes, since a span
   /// cannot be null.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is longer than <see cref="Core.IndexMax"/> + 1, the one index
   /// fault an opener can have (rule rS2).</exception>
   public AlligatorStream AlligatorOpenAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int optInJawPeriod, int optInJawShift, int optInTeethPeriod, int optInTeethShift, int optInLipsPeriod, int optInLipsShift, Span<double> outJaw, Span<double> outTeeth, Span<double> outLips )
   {
      if( inHigh.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "ALLIGATOR openAndFill: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( !inHigh.IsEmpty ) {
         if( inLow.IsEmpty ) throw new TALibArgumentException("ALLIGATOR openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      }
      int guardOutLen = OpenFillCount("ALLIGATOR", "openAndFill", inHigh.Length, AlligatorLookback(optInJawPeriod, optInJawShift, optInTeethPeriod, optInTeethShift, optInLipsPeriod, optInLipsShift));
      RequireHistoryLength("ALLIGATOR", "openAndFill", "inLow", inLow.Length, inHigh.Length);
      RequireFillLength("ALLIGATOR", "openAndFill", "outJaw", outJaw.Length, guardOutLen);
      RequireFillLength("ALLIGATOR", "openAndFill", "outTeeth", outTeeth.Length, guardOutLen);
      RequireFillLength("ALLIGATOR", "openAndFill", "outLips", outLips.Length, guardOutLen);
      if( SameBuffer(outJaw, inHigh) || SameBuffer(outJaw, inLow) || SameBuffer(outTeeth, inHigh) || SameBuffer(outTeeth, inLow) || SameBuffer(outLips, inHigh) || SameBuffer(outLips, inLow) || SameBuffer(outJaw, outTeeth) || SameBuffer(outJaw, outLips) || SameBuffer(outTeeth, outLips) ) {
         throw StreamFailure("ALLIGATOR", "openAndFill", RetCode.BadParam);
      }
      if( guardOutLen > 0 && ( outJaw.Overlaps(inHigh) || outJaw.Overlaps(inLow) || outTeeth.Overlaps(inHigh) || outTeeth.Overlaps(inLow) || outLips.Overlaps(inHigh) || outLips.Overlaps(inLow) || OutputsAlias(outJaw, outTeeth) || OutputsAlias(outJaw, outLips) || OutputsAlias(outTeeth, outLips) ) ) {
         throw StreamFailure("ALLIGATOR", "openAndFill", RetCode.BadParam);
      }
      return AlligatorOpenAndFillInternal(inHigh, inLow, 0, optInJawPeriod, optInJawShift, optInTeethPeriod, optInTeethShift, optInLipsPeriod, optInLipsShift, out _, out _, outJaw, outTeeth, outLips);
   }
