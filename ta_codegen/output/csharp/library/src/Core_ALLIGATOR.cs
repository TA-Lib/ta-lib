   /// 5; range 0..100000; <c>int.MinValue</c> selects the default).</param>
   /// <param name="optInLipsPeriod">Number of bars in the lips' smoothed moving average (default 5; range
   /// 1..100000; <c>int.MinValue</c> selects the default).</param>
   /// <param name="optInLipsShift">Bars ahead of the computing bar at which a chart draws the lips (default
   /// 3; range 0..100000; <c>int.MinValue</c> selects the default).</param>
