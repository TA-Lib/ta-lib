   /// when bit-level identity is what you mean.</para>
   /// </remarks>
   /// <param name="Jaw">Jaw: the slowest line, drawn ahead by the jaw shift.</param>
   /// <param name="Teeth">Teeth: the middle line, drawn ahead by the teeth shift.</param>
