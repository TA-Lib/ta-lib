   /// <summary>
   /// Bill Williams' Alligator (<i>Trading Chaos</i>, 1995): three smoothed
   /// moving averages of the median price. The Jaw, Teeth and Lips are each
   /// drawn a few bars ahead of the bar that computed it. When the three lines
   /// are intertwined the alligator sleeps and the market has no trend; when
   /// they fan out in order, Lips above Teeth above Jaw or the reverse, it is
   /// feeding and a trend is under way. Price crossing back into the lines is
   /// read as the trend tiring. The Alligator is a leg of Williams' Profitunity
   /// system, alongside the Awesome Oscillator
   /// (<see href="https://ta-lib.org/functions/ao"><c>AO</c></see>) and the
   /// Accelerator/Decelerator
   /// (<see href="https://ta-lib.org/functions/ac"><c>AC</c></see>).
   /// </summary>
   /// <remarks>
   /// <para>
   /// Formula and more info at
   /// <see href="https://ta-lib.org/functions/alligator">ta-lib.org/functions/alligator</see>.
   /// </para>
   /// <list type="bullet">
   /// <item><description>Each line is <c>TA_RMA</c> of <c>TA_MEDPRICE</c> over its own period. Williams draws the lines ahead of price; that is a display shift: <c>TA_ALLIGATOR_DisplayShift</c> reports each line's shift, and it changes nothing about the values, the lookback or the returned range. Every output is written at the bar that computed it, so the last <c>shift</c> values of a line are the part a chart draws past the last bar.</description></item>
   /// <item><description>All three lines start at the bar of the longest period, and each shorter line seeds over the bars its own lookback reaches back from there, not at the first bar of the series. A chart that seeds every line at the first bar draws different short lines until the seed has decayed; setting the <c>RMA</c> unstable period closes the gap.</description></item>
   /// </list>
   /// <para>
   /// This is the <c>float[]</c> overload: input elements are widened to
   /// <c>double</c> as they are read and all arithmetic is performed in
   /// <c>double</c>, so a result beyond <c>float</c> range is still
   /// representable.
   /// </para>
   /// <para>
   /// Values are written only where the indicator is defined. The returned
   /// <see cref="OutRange"/> says where they start and how many there are, and
