   /// <param name="endIdx">Last bar of the requested range (inclusive).</param>
   /// <param name="inHigh">High price of each bar.</param>
   /// <param name="inLow">Low price of each bar.</param>
   /// <param name="optInJawPeriod">Number of bars in the jaw's smoothed moving average (default 13; range
   /// 1..100000; <c>int.MinValue</c> selects the default).</param>
   /// <param name="optInJawShift">Bars ahead of the computing bar at which a chart draws the jaw (default 8;
