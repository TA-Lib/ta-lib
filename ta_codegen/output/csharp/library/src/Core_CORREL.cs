         } else {
            scratch.CopyFrom(this);
         }
         core.CORREL_StreamStep(scratch, inReal0, inReal1);
         return scratch.cur_outReal;
      }

      /// <summary>The value at the most recently committed bar — the last history bar right
      /// after open, then whatever the latest <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public CORREL_Stream Clone()
      {
         return new CORREL_Stream(this);
      }
   }

   internal void CORREL_StreamStep( CORREL_Stream sp, double inReal0, double inReal1 )
   {
      if( sp.ringCap_trailingIdx == 0 ) {
         sp.ring_trailingIdx_inReal0[0] = inReal0;
         sp.ring_trailingIdx_inReal1[0] = inReal1;
      }
      /* Remove trailing values */
      sp.sumX -= sp.trailingX;
      sp.sumX2 -= sp.trailingX * sp.trailingX;
      sp.sumXY -= sp.trailingX * sp.trailingY;
      sp.sumY -= sp.trailingY;
      sp.sumY2 -= sp.trailingY * sp.trailingY;
      /* Add new values */
      sp.x = inReal0;
      sp.sumX += sp.x;
      sp.sumX2 += sp.x * sp.x;
      sp.y = inReal1;
      sp.sumXY += sp.x * sp.y;
      sp.sumY += sp.y;
      sp.sumY2 += sp.y * sp.y;
      /* Output new coefficient.
       * Save first the trailing values since the input
       * and output might be the same array,
       */
      sp.trailingX = sp.ring_trailingIdx_inReal0[sp.ringPos_trailingIdx];
      sp.trailingY = sp.ring_trailingIdx_inReal1[sp.ringPos_trailingIdx];
      sp.tempReal = (sp.sumX2 - sp.sumX * sp.sumX / sp.optInTimePeriod) * (sp.sumY2 - sp.sumY * sp.sumY / sp.optInTimePeriod);
      if( !(sp.tempReal < 0.00000000000001) ) {
         sp.cur_outReal = (sp.sumXY - sp.sumX * sp.sumY / sp.optInTimePeriod) / Math.Sqrt(sp.tempReal);
      } else {
         sp.cur_outReal = 0.0;
      }
      sp.ring_trailingIdx_inReal0[sp.ringPos_trailingIdx] = inReal0;
      sp.ring_trailingIdx_inReal1[sp.ringPos_trailingIdx] = inReal1;
      sp.ringPos_trailingIdx = sp.ringPos_trailingIdx + 1;
      if( sp.ringPos_trailingIdx >= sp.ringCap_trailingIdx ) {
         sp.ringPos_trailingIdx = 0;
      }
   }

   private RetCode CORREL_OpenPass( CORREL_Stream sp, ReadOnlySpan<double> inReal0, ReadOnlySpan<double> inReal1, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double sumXY = 0;
      double sumX = 0;
      double sumY = 0;
      double sumX2 = 0;
      double sumY2 = 0;
      double x = 0;
      double y = 0;
      double trailingX = 0;
      double trailingY = 0;
      double tempReal = 0;
      int lookbackTotal = 0;
      int today = 0;
      int trailingIdx = 0;
      int outIdx = 0;
      int historyLen = inReal0.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 || inReal1.Length != inReal0.Length ) {
         return RetCode.BadParam;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 30;
      } else if( optInTimePeriod < 1 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      /* Move up the start index if there is not
       * enough initial data.
       */
      lookbackTotal = optInTimePeriod - 1;
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      outBegIdx = startIdx;
      trailingIdx = startIdx - lookbackTotal;
      /* Calculate the initial values. */
      sumY2 = 0.0;
      sumX2 = sumY2;
      sumY = sumX2;
      sumX = sumY;
      sumXY = sumX;
      for( today = trailingIdx; today <= startIdx; today += 1 ) {
         x = inReal0[today];
         sumX += x;
         sumX2 += x * x;
         y = inReal1[today];
         sumXY += x * y;
         sumY += y;
         sumY2 += y * y;
      }
      /* Write the first output.
       * Save first the trailing values since the input
       * and output might be the same array,
       */
      trailingX = inReal0[trailingIdx];
      trailingY = inReal1[trailingIdx++];
      tempReal = (sumX2 - sumX * sumX / optInTimePeriod) * (sumY2 - sumY * sumY / optInTimePeriod);
      if( !(tempReal < 0.00000000000001) ) {
         outReal[0 * outStride] = (sumXY - sumX * sumY / optInTimePeriod) / Math.Sqrt(tempReal);
      } else {
         outReal[0 * outStride] = 0.0;
      }
      /* Tight loop to do subsequent values. */
      outIdx = 1;
      while( today <= endIdx ) {
         /* Remove trailing values */
         sumX -= trailingX;
         sumX2 -= trailingX * trailingX;
         sumXY -= trailingX * trailingY;
         sumY -= trailingY;
         sumY2 -= trailingY * trailingY;
         /* Add new values */
         x = inReal0[today];
         sumX += x;
         sumX2 += x * x;
         y = inReal1[today++];
         sumXY += x * y;
         sumY += y;
         sumY2 += y * y;
         /* Output new coefficient.
          * Save first the trailing values since the input
          * and output might be the same array,
          */
         trailingX = inReal0[trailingIdx];
         trailingY = inReal1[trailingIdx++];
         tempReal = (sumX2 - sumX * sumX / optInTimePeriod) * (sumY2 - sumY * sumY / optInTimePeriod);
         if( !(tempReal < 0.00000000000001) ) {
            outReal[outIdx++ * outStride] = (sumXY - sumX * sumY / optInTimePeriod) / Math.Sqrt(tempReal);
         } else {
            outReal[outIdx++ * outStride] = 0.0;
         }
      }
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      int cap_trailingIdx = today - trailingIdx;
      if( cap_trailingIdx < 0 || cap_trailingIdx > historyLen ) {
         return RetCode.InternalError;
      }
      int allocN_trailingIdx = (cap_trailingIdx > 0)? cap_trailingIdx : 1;
      double[] capRing_trailingIdx_inReal0 = new double[allocN_trailingIdx];
      inReal0.Slice(historyLen - cap_trailingIdx, cap_trailingIdx).CopyTo(capRing_trailingIdx_inReal0);
      double[] capRing_trailingIdx_inReal1 = new double[allocN_trailingIdx];
      inReal1.Slice(historyLen - cap_trailingIdx, cap_trailingIdx).CopyTo(capRing_trailingIdx_inReal1);
      sp.optInTimePeriod = optInTimePeriod;
      sp.sumXY = sumXY;
      sp.sumX = sumX;
      sp.sumY = sumY;
      sp.sumX2 = sumX2;
      sp.sumY2 = sumY2;
      sp.x = x;
      sp.y = y;
      sp.trailingX = trailingX;
      sp.trailingY = trailingY;
      sp.tempReal = tempReal;
      sp.ringPos_trailingIdx = 0;
      sp.ringCap_trailingIdx = cap_trailingIdx;
      sp.ring_trailingIdx_inReal0 = capRing_trailingIdx_inReal0;
      sp.ring_trailingIdx_inReal1 = capRing_trailingIdx_inReal1;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   private RetCode CORREL_OpenImpl( CORREL_Stream sp, ReadOnlySpan<double> inReal0, ReadOnlySpan<double> inReal1, int startIdx, int optInTimePeriod )
   {
      double[] sink_outReal = new double[1];
      return CORREL_OpenPass( sp, inReal0, inReal1, startIdx, optInTimePeriod, out _, out _, sink_outReal, 0 );
   }

   private RetCode CORREL_OpenAndFillImpl( CORREL_Stream sp, ReadOnlySpan<double> inReal0, ReadOnlySpan<double> inReal1, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      outBegIdx = 0;
      outNBElement = 0;
      if( outReal.Overlaps(inReal0) || outReal.Overlaps(inReal1) ) {
         return RetCode.BadParam;
      }
      return CORREL_OpenPass( sp, inReal0, inReal1, 0, optInTimePeriod, out outBegIdx, out outNBElement, outReal, 1 );
   }

   private RetCode CORREL_OpenAndFillInternalImpl( CORREL_Stream sp, ReadOnlySpan<double> inReal0, ReadOnlySpan<double> inReal1, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      return CORREL_OpenPass(sp, inReal0, inReal1, startIdx, optInTimePeriod, out outBegIdx, out outNBElement, outReal, 1);
   }

   /* CORREL_OpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal CORREL_Stream CORREL_OpenAndFillInternal( ReadOnlySpan<double> inReal0, ReadOnlySpan<double> inReal1, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      CORREL_Stream sp = new CORREL_Stream(this);
      RetCode retCode = CORREL_OpenAndFillInternalImpl(sp, inReal0, inReal1, startIdx, optInTimePeriod, out outBegIdx, out outNBElement, outReal);
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("CORREL", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind CORREL_Open (composition seam). */
   internal CORREL_Stream CORREL_OpenInternal( ReadOnlySpan<double> inReal0, ReadOnlySpan<double> inReal1, int startIdx, int optInTimePeriod )
   {
      CORREL_Stream sp = new CORREL_Stream(this);
      RetCode retCode = CORREL_OpenImpl(sp, inReal0, inReal1, startIdx, optInTimePeriod);
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("CORREL", "open", retCode);
   }

   /// <summary>Open a live <c>CORREL</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="CORREL_Stream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>CORREL</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>CORREL_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>CORREL_OpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal0">First data series (X) The warm-up history, oldest bar first.</param>
   /// <param name="inReal1">Second data series (Y) The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="CORREL_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>CORREL_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentException">An input series is empty — which is what a null array becomes, since a
   /// span cannot be null.</exception>
   public CORREL_Stream CORREL_Open( ReadOnlySpan<double> inReal0, ReadOnlySpan<double> inReal1, int optInTimePeriod )
   {
      if( inReal0.IsEmpty ) throw new TaLibArgumentException("inReal0 is empty", nameof(inReal0), RetCode.BadParam);
      if( inReal1.IsEmpty ) throw new TaLibArgumentException("inReal1 is empty", nameof(inReal1), RetCode.BadParam);
      return CORREL_OpenInternal(inReal0, inReal1, 0, optInTimePeriod);
   }

   /// <summary><c>CORREL_Open</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>CORREL</c> produces over
   /// the same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - CORREL_Lookback(...)</c> values
   /// and must not alias the inputs or each other — this path writes the outputs
   /// and then reads the input tail to seed its rings, so the batch tier's
   /// in-place allowance does not carry over here.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="CORREL_Stream.FillRange"/>.</para>
   /// </remarks>
   /// <param name="inReal0">First data series (X) The warm-up history, oldest bar first.</param>
   /// <param name="inReal1">Second data series (Y) The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="CORREL_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Correlation coefficient r in [-1, 1]. Must hold at least <c>historyLen -
   /// CORREL_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>CORREL_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, or an output array aliases an input or another
   /// output.</exception>
   /// <exception cref="System.ArgumentException">An input series is empty, or an output overlaps an input or another
   /// output.</exception>
   public CORREL_Stream CORREL_OpenAndFill( ReadOnlySpan<double> inReal0, ReadOnlySpan<double> inReal1, int optInTimePeriod, Span<double> outReal )
   {
      if( inReal0.IsEmpty ) throw new TaLibArgumentException("inReal0 is empty", nameof(inReal0), RetCode.BadParam);
      if( inReal1.IsEmpty ) throw new TaLibArgumentException("inReal1 is empty", nameof(inReal1), RetCode.BadParam);
      CORREL_Stream sp = new CORREL_Stream(this);
      RetCode retCode = CORREL_OpenAndFillImpl(sp, inReal0, inReal1, optInTimePeriod, out int outBegIdx, out int outNBElement, outReal);
      sp.fillRange = new OutRange(outBegIdx, outNBElement);
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("CORREL", "openAndFill", retCode);
   }
