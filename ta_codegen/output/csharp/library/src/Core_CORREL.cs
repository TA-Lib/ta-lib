   /// <summary>A live <c>CORREL</c> stream: one value per closed bar, bit-identical to
   /// <c>CORREL</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.CORREL_Open"/>. There is no close and nothing to
   /// dispose — the handle is ordinary managed state, and an unreferenced handle
   /// is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class CORREL_Stream
   {
      internal Core core;
      internal int optInTimePeriod;
      internal double sumXY;
      internal double sumX;
      internal double sumY;
      internal double sumX2;
      internal double sumY2;
      internal double shiftX;
      internal double shiftY;
      internal double leavingX;
      internal double leavingY;
      internal double invPeriod;
      internal int lookbackTotal;
      internal int trailingIdx;
      internal int barsSinceReseed;
      internal int j;
      internal int today;
      internal int xMask;
      internal double[] x_inReal0 = [];
      internal double[] x_inReal1 = [];
      internal double cur_outReal;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal CORREL_Stream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has produced a value for, in the input series'
      /// coordinates: <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.CORREL</c> reports over the same bars: the opener sets
      /// it to <c>(lookback, historyLen - lookback)</c>, every accepted
      /// <c>Update</c> adds one to the count, <c>Peek</c> leaves it alone, and
      /// <c>Clone</c> carries it verbatim. A plain <c>Open</c> hands back only the
      /// last value, a subset of this range, because the caller chose not to take
      /// the fill.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      internal CORREL_Stream( CORREL_Stream other )
