   /// </remarks>
   /// <param name="WT1">WaveTrend oscillator line.</param>
   /// <param name="WT2">Simple average of the oscillator line.</param>
   public readonly record struct WavetrendValue( double WT1, double WT2 );

   /// <summary>A live <c>WAVETREND</c> stream: one value per closed bar, bit-identical to
   /// <c>WAVETREND</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.WavetrendOpen"/>. There is no close and nothing
   /// to dispose — the handle is ordinary managed state, and an unreferenced
   /// handle is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class WavetrendStream
   {
      internal Core core;
      internal int optInChannelPeriod;
      internal int optInAveragePeriod;
      internal int optInSignalPeriod;
      internal double k1;
      internal double beta1;
      internal double k2;
      internal double beta2;
      internal double esa;
      internal double d;
      internal double wt1;
      internal double prevAp;
      internal double prevEsa;
      internal double sumSignal;
      internal int wtBuffer_Idx;
      internal int maxIdx_wtBuffer;
      internal int cbSize_wtBuffer;
      internal double[] cb_wtBuffer = [];
      internal double cur_outWT1;
      internal double cur_outWT2;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal WavetrendStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Wavetrend</c> reports over the same bars: the opener
      /// sets it to <c>(lookback, historyLen - lookback)</c>, every accepted
      /// <c>Update</c> adds one to the count — a rejected one changes nothing, and
      /// neither does <c>Peek</c> — and <c>Clone</c> carries it verbatim. A plain
      /// <c>Open</c> hands back only the last value, a subset of this range,
      /// because the caller chose not to take the fill.</para>
      /// <para>The last bar it can reach is <see cref="Core.IndexMax"/>; past that
      /// <c>Update</c> and <c>Advance</c> throw.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      /// <summary>Count one bar this stream was not fed: <see cref="OutRange"/> advances by
      /// one and nothing else moves.</summary>
      /// <remarks>
      /// <para><see cref="Value"/> keeps answering the previous output, which is this
      /// bar's output too. For a bar the caller leaves out: one an <c>Update</c>
      /// rejected and that will not be re-fed, or a session with no print. Without
      /// it two handles on one feed drift a bar apart when only one of them skips.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, the last one the batch tier
      /// can address and the last this handle will count. <c>Update</c> throws the
      /// same there.</para>
      /// </remarks>
      public void Advance()
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("WAVETREND", "advance", RetCode.OutOfRangeEndIndex);
         outRangeCount++;
      }

      internal WavetrendStream( WavetrendStream other )
      {
         this.core = other.core;
         this.optInChannelPeriod = other.optInChannelPeriod;
         this.optInAveragePeriod = other.optInAveragePeriod;
         this.optInSignalPeriod = other.optInSignalPeriod;
         this.k1 = other.k1;
         this.beta1 = other.beta1;
         this.k2 = other.k2;
         this.beta2 = other.beta2;
         this.esa = other.esa;
         this.d = other.d;
         this.wt1 = other.wt1;
         this.prevAp = other.prevAp;
         this.prevEsa = other.prevEsa;
         this.sumSignal = other.sumSignal;
         this.wtBuffer_Idx = other.wtBuffer_Idx;
         this.maxIdx_wtBuffer = other.maxIdx_wtBuffer;
         this.cbSize_wtBuffer = other.cbSize_wtBuffer;
         this.cb_wtBuffer = new double[other.cb_wtBuffer.Length];
         Array.Copy( other.cb_wtBuffer, this.cb_wtBuffer, other.cb_wtBuffer.Length );
         this.cur_outWT1 = other.cur_outWT1;
         this.cur_outWT2 = other.cur_outWT2;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so nothing moves — <see cref="OutRange"/> included — and
      /// <see cref="Value"/> still answers the previous value. Re-feed the bar when
      /// a corrected value arrives, or call <see cref="Advance"/> to count it and
      /// carry on; two handles on one feed drift a bar apart if neither happens.
      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, which no re-feed clears: the
      /// handle has run out of index domain and only a shorter history can start a
      /// new one.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>The value at the bar just committed.</returns>
      public WavetrendValue Update( double inHigh, double inLow, double inClose )
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("WAVETREND", "update", RetCode.OutOfRangeEndIndex);
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) ) throw Core.NonFiniteBar("WAVETREND", "update", !double.IsFinite(inHigh) ? nameof(inHigh) : !double.IsFinite(inLow) ? nameof(inLow) : nameof(inClose));
         core.WavetrendStepImpl(this, inHigh, inLow, inClose);
         outRangeCount++;
         return new WavetrendValue(cur_outWT1, cur_outWT2);
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.IndexMax"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public WavetrendValue Peek( double inHigh, double inLow, double inClose )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) ) throw Core.NonFiniteBar("WAVETREND", "peek", !double.IsFinite(inHigh) ? nameof(inHigh) : !double.IsFinite(inLow) ? nameof(inLow) : nameof(inClose));
         WavetrendStream sp = this;
         double ap = 0.0;
         double dev = 0.0;
         double ci = 0.0;
         double num = 0.0;
         double scaledDev = 0.0;
         double cur_outWT1 = 0.0;
         double cur_outWT2 = 0.0;
         double d = sp.d;
         double esa = sp.esa;
         double sumSignal = sp.sumSignal;
         double wt1 = sp.wt1;
         ap = (inHigh + inLow + inClose) / 3.0;
         esa = Math.FusedMultiplyAdd(sp.beta1, esa, sp.k1 * ap);
         num = ap - esa;
         if( ap == sp.prevAp && esa == sp.prevEsa ) {
            num = 0.0;
         }
         dev = num;
         if( dev < 0.0 ) {
            dev = -dev;
         }
         d = Math.FusedMultiplyAdd(sp.beta1, d, sp.k1 * dev);
         scaledDev = 0.015 * d;
         if( scaledDev > 0.0 ) {
            ci = num / scaledDev;
         } else {
            ci = 0.0;
         }
         wt1 = Math.FusedMultiplyAdd(sp.beta2, wt1, sp.k2 * ci);
         sumSignal = sumSignal + wt1;
         cur_outWT1 = wt1;
         cur_outWT2 = sumSignal / (double)sp.optInSignalPeriod;
         return new WavetrendValue(cur_outWT1, cur_outWT2);
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public WavetrendValue Value => new WavetrendValue(cur_outWT1, cur_outWT2);

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public WavetrendStream Clone()
      {
         return new WavetrendStream(this);
      }
   }

   private void WavetrendStepImpl( WavetrendStream sp, double inHigh, double inLow, double inClose )
   {
      double ap = 0.0;
      double dev = 0.0;
      double ci = 0.0;
      double num = 0.0;
      double scaledDev = 0.0;
      ap = (inHigh + inLow + inClose) / 3.0;
      sp.esa = Math.FusedMultiplyAdd(sp.beta1, sp.esa, sp.k1 * ap);
      num = ap - sp.esa;
      if( ap == sp.prevAp && sp.esa == sp.prevEsa ) {
         num = 0.0;
      }
      dev = num;
      if( dev < 0.0 ) {
         dev = -dev;
      }
      sp.d = Math.FusedMultiplyAdd(sp.beta1, sp.d, sp.k1 * dev);
      scaledDev = 0.015 * sp.d;
      if( scaledDev > 0.0 ) {
         ci = num / scaledDev;
      } else {
         ci = 0.0;
      }
      sp.wt1 = Math.FusedMultiplyAdd(sp.beta2, sp.wt1, sp.k2 * ci);
      sp.cb_wtBuffer[sp.wtBuffer_Idx] = sp.wt1;
      sp.sumSignal = sp.sumSignal + sp.wt1;
      sp.cur_outWT1 = sp.wt1;
      sp.cur_outWT2 = sp.sumSignal / (double)sp.optInSignalPeriod;
      sp.wtBuffer_Idx = sp.wtBuffer_Idx + 1;
      if( sp.wtBuffer_Idx > sp.maxIdx_wtBuffer ) {
         sp.wtBuffer_Idx = 0;
      }
      sp.sumSignal = sp.sumSignal - sp.cb_wtBuffer[sp.wtBuffer_Idx];
      sp.prevAp = ap;
      sp.prevEsa = sp.esa;
   }

   private RetCode WavetrendOpenImpl( WavetrendStream sp, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInChannelPeriod, int optInAveragePeriod, int optInSignalPeriod, out int outBegIdx, out int outNBElement, Span<double> outWT1, Span<double> outWT2, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double k1 = 0;
      double beta1 = 0;
      double k2 = 0;
      double beta2 = 0;
      double ap = 0;
      double esa = 0;
      double dev = 0;
      double d = 0;
      double ci = 0;
      double wt1 = 0;
      double prevAp = 0;
      double prevEsa = 0;
      double num = 0;
      double scaledDev = 0;
      double sumEsa = 0;
      double sumD = 0;
      double sumCi = 0;
      double sumSignal = 0;
      int lookbackTotal = 0;
      int lookbackChannel = 0;
      int lookbackAverage = 0;
      int today = 0;
      int outIdx = 0;
      int nAp = 0;
      int nDev = 0;
      int nCi = 0;
      int nSig = 0;
      double[] wtBuffer = [];
      int wtBuffer_Idx = 0;
      int maxIdx_wtBuffer = (32)-1;
      int historyLen = inHigh.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > IndexMax + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inLow.Length != inHigh.Length || inClose.Length != inHigh.Length ) {
         return RetCode.BadParam;
      }
      if( optInChannelPeriod == int.MinValue ) {
         optInChannelPeriod = 10;
      } else if( optInChannelPeriod < 2 || optInChannelPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInAveragePeriod == int.MinValue ) {
         optInAveragePeriod = 21;
      } else if( optInAveragePeriod < 1 || optInAveragePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInSignalPeriod == int.MinValue ) {
         optInSignalPeriod = 4;
      } else if( optInSignalPeriod < 1 || optInSignalPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      /* LazyBear's WaveTrend Oscillator (TradingView, 2014), lines 14 to 21: the
       * typical price's distance from its own exponential average, normalised by
       * an exponential average of that distance's absolute value and by Lambert's
       * CCI constant, then smoothed.
       *
       *    ap  = (H + L + C)/3
       *    esa = EMA(ap, n1)
       *    d   = EMA(|ap - esa|, n1)
       *    ci  = (ap - esa) / (0.015 * d)
       *    WT1 = EMA(ci, n2)        WT2 = SMA(WT1, n3)
       *
       * The middle stage is an exponential CCI, not TA_CCI: cci.c averages with
       * an SMA and takes the mean deviation around that window's own SMA, where
       * this uses two exponential averages.
       *
       * Each stage seeds the way ema.c and sma.c seed, and each stage boundary
       * below is the callee's LOOKBACK rather than (period-1), so the result is
       * bit-identical to the composed chain on moving data and a warm unstable
       * period folds in. The two guards are what the chain cannot express; they
       * are the reason this ships as a function.
       */
      /* This ptr will point on a circular buffer of at least
       * "optInSignalPeriod" element.
       */
      lookbackTotal = WavetrendLookback(optInChannelPeriod, optInAveragePeriod, optInSignalPeriod);
      /* Move up the start index if there is not
       * enough initial data.
       */
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      if( optInSignalPeriod < 1 ) return RetCode.InternalError;
      wtBuffer = new double[optInSignalPeriod];
      maxIdx_wtBuffer = (optInSignalPeriod)-1;
      wtBuffer_Idx = 0;
      lookbackChannel = EmaLookback(optInChannelPeriod);
      lookbackAverage = EmaLookback(optInAveragePeriod);
      beta1 = (double)(optInChannelPeriod - 1) / (double)(optInChannelPeriod + 1);
      k1 = 1.0 - beta1;
      beta1 = 1.0 - k1;
      beta2 = (double)(optInAveragePeriod - 1) / (double)(optInAveragePeriod + 1);
      k2 = 1.0 - beta2;
      beta2 = 1.0 - k2;
      esa = 0.0;
      d = 0.0;
      ci = 0.0;
      wt1 = 0.0;
      sumEsa = 0.0;
      sumD = 0.0;
      sumCi = 0.0;
      sumSignal = 0.0;
      nAp = 0;
      /* The fixpoint test compares against the previous bar's pair. Starting both
       * at 0.0 cannot make it fire spuriously: it would need a bar whose typical
       * price and whose exponential average are both exactly zero, and a zero
       * typical price makes the numerator zero anyway, which is what the test
       * would have substituted.
       */
      prevAp = 0.0;
      prevEsa = 0.0;
      today = startIdx - lookbackTotal;
      /* Warm-up. Runs through startIdx inclusive: the last pass is the one that
       * completes the signal window, so it leaves the first output in the state.
       */
      while( today <= startIdx ) {
         ap = (inHigh[today] + inLow[today] + inClose[today]) / 3.0;
         /* Stage 1: the exponential average of the typical price. */
         if( nAp < optInChannelPeriod ) {
            sumEsa = sumEsa + ap;
            if( nAp == optInChannelPeriod - 1 ) {
               esa = sumEsa / optInChannelPeriod;
            }
         } else {
            esa = Math.FusedMultiplyAdd(beta1, esa, k1 * ap);
         }
         /* Stage 2: the exponential average of the absolute distance, over what
          * stage 1 publishes. The counter is compared before it is subtracted,
          * never after: the Rust backend renders these as usize.
          */
         if( nAp >= lookbackChannel ) {
            nDev = nAp - lookbackChannel;
            /* GUARD 1, the fixpoint test. With a constant input the exponential
             * step stops moving once k*|ap - esa| falls under half an ulp, and
             * esa then FREEZES up to (n1+1)/4 ulps away from the price. That
             * frozen residue is a real non-zero distance, so the naive form
             * divides it by its own exponential average and walks to
             * +/-1/0.015 = +/-66.67 -- an extreme reading produced by nothing
             * but rounding. When the pair has not moved, the average has reached
             * its fixpoint and the distance is exactly that residue, so the
             * numerator is taken as zero. The test is exact, so it is
             * independent of scale and period, unlike a fixed epsilon band.
             */
            num = ap - esa;
            if( ap == prevAp && esa == prevEsa ) {
               num = 0.0;
            }
            dev = num;
            if( dev < 0.0 ) {
               dev = -dev;
            }
            if( nDev < optInChannelPeriod ) {
               sumD = sumD + dev;
               if( nDev == optInChannelPeriod - 1 ) {
                  d = sumD / optInChannelPeriod;
               }
            } else {
               d = Math.FusedMultiplyAdd(beta1, d, k1 * dev);
            }
            /* Stage 3: the oscillator, then its own smoothing. */
            if( nDev >= lookbackChannel ) {
               nCi = nDev - lookbackChannel;
               /* GUARD 2, the exact divisor. Test the PRODUCT the division uses,
                * not the deviation: 0.015*d underflows to zero while d is still
                * non-zero (#395). A zero divisor is 0/0 -- no distance against no
                * average distance -- so the oscillator reads its neutral 0.0
                * (#112), as tsi.c does.
                */
               scaledDev = 0.015 * d;
               if( scaledDev > 0.0 ) {
                  ci = num / scaledDev;
               } else {
                  ci = 0.0;
               }
               if( nCi < optInAveragePeriod ) {
                  sumCi = sumCi + ci;
                  if( nCi == optInAveragePeriod - 1 ) {
                     wt1 = sumCi / optInAveragePeriod;
                  }
               } else {
                  wt1 = Math.FusedMultiplyAdd(beta2, wt1, k2 * ci);
               }
               if( nCi >= lookbackAverage ) {
                  wtBuffer[wtBuffer_Idx] = wt1;
                  sumSignal = sumSignal + wt1;
                  wtBuffer_Idx++;
                  if( wtBuffer_Idx > maxIdx_wtBuffer ) { wtBuffer_Idx = 0; }
               }
            }
         }
         prevAp = ap;
         prevEsa = esa;
         nAp = nAp + 1;
         today = today + 1;
      }
      /* The first output. The warm-up's last pass stored this bar's WT1 into the
       * ring and added it to the running sum, so the average is ready here.
       */
      outWT1[0 * outStride] = wt1;
      outWT2[0 * outStride] = sumSignal / (double)optInSignalPeriod;
      outIdx = 1;
      sumSignal = sumSignal - wtBuffer[wtBuffer_Idx];
      /* Stable zone. One bar past the first output every stage is past its seed,
       * at every reachable parameter triple: the shortest case, 2/1/1, arrives
       * with the deviation average and the oscillator smoothing both one bar
       * into their recursions. So nothing here branches on a counter, and the
       * stores always run -- which is what keeps the managed backends' peek
       * frames from carrying a seeded output local.
       */
      while( today <= endIdx ) {
         ap = (inHigh[today] + inLow[today] + inClose[today]) / 3.0;
         esa = Math.FusedMultiplyAdd(beta1, esa, k1 * ap);
         num = ap - esa;
         if( ap == prevAp && esa == prevEsa ) {
            num = 0.0;
         }
         dev = num;
         if( dev < 0.0 ) {
            dev = -dev;
         }
         d = Math.FusedMultiplyAdd(beta1, d, k1 * dev);
         scaledDev = 0.015 * d;
         if( scaledDev > 0.0 ) {
            ci = num / scaledDev;
         } else {
            ci = 0.0;
         }
         wt1 = Math.FusedMultiplyAdd(beta2, wt1, k2 * ci);
         wtBuffer[wtBuffer_Idx] = wt1;
         sumSignal = sumSignal + wt1;
         outWT1[outIdx * outStride] = wt1;
         outWT2[outIdx * outStride] = sumSignal / (double)optInSignalPeriod;
         outIdx = outIdx + 1;
         wtBuffer_Idx++;
         if( wtBuffer_Idx > maxIdx_wtBuffer ) { wtBuffer_Idx = 0; }
         sumSignal = sumSignal - wtBuffer[wtBuffer_Idx];
         prevAp = ap;
         prevEsa = esa;
         today = today + 1;
      }
      outNBElement = outIdx;
      outBegIdx = startIdx;
      /* Capture the live batch state into the handle. */
      int capCb_wtBuffer = maxIdx_wtBuffer + 1;
      if( capCb_wtBuffer > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      sp.optInChannelPeriod = optInChannelPeriod;
      sp.optInAveragePeriod = optInAveragePeriod;
      sp.optInSignalPeriod = optInSignalPeriod;
      sp.k1 = k1;
      sp.beta1 = beta1;
      sp.k2 = k2;
      sp.beta2 = beta2;
      sp.esa = esa;
      sp.d = d;
      sp.wt1 = wt1;
      sp.prevAp = prevAp;
      sp.prevEsa = prevEsa;
      sp.sumSignal = sumSignal;
      sp.wtBuffer_Idx = wtBuffer_Idx;
      sp.maxIdx_wtBuffer = maxIdx_wtBuffer;
      sp.cbSize_wtBuffer = capCb_wtBuffer;
      sp.cb_wtBuffer = wtBuffer;
      sp.cur_outWT1 = outWT1[(outNBElement - 1) * outStride];
      sp.cur_outWT2 = outWT2[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* WavetrendOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal WavetrendStream WavetrendOpenAndFillInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInChannelPeriod, int optInAveragePeriod, int optInSignalPeriod, out int outBegIdx, out int outNBElement, Span<double> outWT1, Span<double> outWT2 )
   {
      WavetrendStream sp = new WavetrendStream(this);
      RetCode retCode = WavetrendOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInChannelPeriod, optInAveragePeriod, optInSignalPeriod, out outBegIdx, out outNBElement, outWT1, outWT2, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("WAVETREND", "openAndFill", nameof(inHigh), inHigh.Length, startIdx, WavetrendLookback(optInChannelPeriod, optInAveragePeriod, optInSignalPeriod));
      }
      throw StreamFailure("WAVETREND", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind WavetrendOpen (composition seam). */
   internal WavetrendStream WavetrendOpenInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInChannelPeriod, int optInAveragePeriod, int optInSignalPeriod )
   {
      WavetrendStream sp = new WavetrendStream(this);
      double[] sink_outWT1 = new double[1];
      double[] sink_outWT2 = new double[1];
      RetCode retCode = WavetrendOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInChannelPeriod, optInAveragePeriod, optInSignalPeriod, out int outBegIdx, out int outNBElement, sink_outWT1, sink_outWT2, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("WAVETREND", "open", nameof(inHigh), inHigh.Length, startIdx, WavetrendLookback(optInChannelPeriod, optInAveragePeriod, optInSignalPeriod));
      }
      throw StreamFailure("WAVETREND", "open", retCode);
   }

   /// <summary>Open a live <c>WAVETREND</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="WavetrendStream.Value"/> starts at the last
   /// history bar's value — bit-identical to what <c>WAVETREND</c> reports for
   /// that bar.</para>
   /// <para>The history must hold at least <c>WavetrendLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>WavetrendOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inHigh">High price series. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price series. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price series. The warm-up history, oldest bar first.</param>
   /// <param name="optInChannelPeriod">As in the batch call; see <see cref="WavetrendLookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInAveragePeriod">As in the batch call; see <see cref="WavetrendLookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSignalPeriod">As in the batch call; see <see cref="WavetrendLookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>WavetrendLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public WavetrendStream WavetrendOpen( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInChannelPeriod, int optInAveragePeriod, int optInSignalPeriod )
   {
      if( inHigh.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "WAVETREND open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "WAVETREND open: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TALibArgumentException("WAVETREND open: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TALibArgumentException("WAVETREND open: inClose is empty", nameof(inClose), RetCode.BadParam);
      RequireHistoryLength("WAVETREND", "open", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("WAVETREND", "open", "inClose", inClose.Length, inHigh.Length);
      return WavetrendOpenInternal(inHigh, inLow, inClose, 0, optInChannelPeriod, optInAveragePeriod, optInSignalPeriod);
   }

   /// <summary><c>WavetrendOpen</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>WAVETREND</c> produces
   /// over the same series, so no separate batch call is needed for the warm-up
   /// plot.</para>
   /// <para>Output arrays must hold <c>historyLen - WavetrendLookback(...)</c> values
   /// and must not alias the inputs or each other — this path writes the outputs
   /// and then reads the input tail to seed its rings, so the batch tier's
   /// in-place allowance does not carry over here. Both are checked before
   /// anything is written, so an undersized span is an <c>ArgumentException</c>
   /// naming it rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="WavetrendStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inHigh">High price series. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price series. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price series. The warm-up history, oldest bar first.</param>
   /// <param name="optInChannelPeriod">As in the batch call; see <see cref="WavetrendLookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInAveragePeriod">As in the batch call; see <see cref="WavetrendLookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSignalPeriod">As in the batch call; see <see cref="WavetrendLookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outWT1">WaveTrend oscillator line. Must hold at least <c>historyLen -
   /// WavetrendLookback(...)</c> values.</param>
   /// <param name="outWT2">Simple average of the oscillator line. Must hold at least <c>historyLen -
   /// WavetrendLookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>WavetrendLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public WavetrendStream WavetrendOpenAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInChannelPeriod, int optInAveragePeriod, int optInSignalPeriod, Span<double> outWT1, Span<double> outWT2 )
   {
      if( inHigh.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "WAVETREND openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "WAVETREND openAndFill: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TALibArgumentException("WAVETREND openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TALibArgumentException("WAVETREND openAndFill: inClose is empty", nameof(inClose), RetCode.BadParam);
      int guardOutLen = OpenFillCount("WAVETREND", "openAndFill", inHigh.Length, WavetrendLookback(optInChannelPeriod, optInAveragePeriod, optInSignalPeriod));
      RequireHistoryLength("WAVETREND", "openAndFill", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("WAVETREND", "openAndFill", "inClose", inClose.Length, inHigh.Length);
      RequireFillLength("WAVETREND", "openAndFill", "outWT1", outWT1.Length, guardOutLen);
      RequireFillLength("WAVETREND", "openAndFill", "outWT2", outWT2.Length, guardOutLen);
      if( SameBuffer(outWT1, inHigh) || SameBuffer(outWT1, inLow) || SameBuffer(outWT1, inClose) || SameBuffer(outWT2, inHigh) || SameBuffer(outWT2, inLow) || SameBuffer(outWT2, inClose) || SameBuffer(outWT1, outWT2) ) {
         throw StreamFailure("WAVETREND", "openAndFill", RetCode.BadParam);
      }
      if( guardOutLen > 0 && ( outWT1.Overlaps(inHigh) || outWT1.Overlaps(inLow) || outWT1.Overlaps(inClose) || outWT2.Overlaps(inHigh) || outWT2.Overlaps(inLow) || outWT2.Overlaps(inClose) || OutputsAlias(outWT1, outWT2) ) ) {
         throw StreamFailure("WAVETREND", "openAndFill", RetCode.BadParam);
      }
      return WavetrendOpenAndFillInternal(inHigh, inLow, inClose, 0, optInChannelPeriod, optInAveragePeriod, optInSignalPeriod, out _, out _, outWT1, outWT2);
   }
