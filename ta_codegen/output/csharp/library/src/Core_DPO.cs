      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public DpoStream Clone()
      {
         return new DpoStream(this);
      }
   }

   internal void DpoStepImpl( DpoStream sp, double inReal )
   {
      double tempReal = 0.0;
      double dispVal = 0.0;
      if( sp.ringCap_dispIdx == 0 ) {
         sp.ring_dispIdx_inReal[0] = inReal;
      }
      if( sp.ringCap_trailingIdx == 0 ) {
         sp.ring_trailingIdx_inReal[0] = inReal;
      }
      sp.periodTotal += inReal;
      tempReal = sp.periodTotal;
      sp.periodTotal -= sp.ring_trailingIdx_inReal[sp.ringPos_trailingIdx];
      /* Both reads precede the store. Either cursor can EQUAL outIdx -- the
       * displaced one whenever startIdx equals the displacement, the trailing
       * one whenever startIdx sits at the lookback -- so a store hoisted above
       * them would read back what it had just overwritten when the caller
       * aliases outReal over inReal.
       */
      dispVal = sp.ring_dispIdx_inReal[sp.ringPos_dispIdx];
      sp.cur_outReal = dispVal - tempReal / (double)sp.optInTimePeriod;
      sp.ring_dispIdx_inReal[sp.ringPos_dispIdx] = inReal;
      sp.ringPos_dispIdx = sp.ringPos_dispIdx + 1;
      if( sp.ringPos_dispIdx >= sp.ringCap_dispIdx ) {
         sp.ringPos_dispIdx = 0;
      }
      sp.ring_trailingIdx_inReal[sp.ringPos_trailingIdx] = inReal;
      sp.ringPos_trailingIdx = sp.ringPos_trailingIdx + 1;
      if( sp.ringPos_trailingIdx >= sp.ringCap_trailingIdx ) {
         sp.ringPos_trailingIdx = 0;
      }
   }

   private RetCode DpoOpenImpl( DpoStream sp, ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double periodTotal = 0;
      double tempReal = 0;
      double dispVal = 0;
      int i = 0;
      int outIdx = 0;
      int trailingIdx = 0;
      int dispIdx = 0;
      int lookbackTotal = 0;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 20;
      } else if( optInTimePeriod < 2 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      /* The running sum is accumulated, snapshot and divided in exactly the order
       * ta_codegen/input/sma/sma.c uses, so this fused loop is bit-for-bit equal
       * to a TA_SMA anchored at the same startIdx. That equality is what makes
       * the composite differential in test_dpo.c a memcmp instead of a tolerance
       * argument, and it is lost by dividing once into a reciprocal or by
       * reordering the add/snapshot/subtract.
       */
      lookbackTotal = DPO_Lookback(optInTimePeriod);
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      periodTotal = 0.0;
      trailingIdx = startIdx - (optInTimePeriod - 1);
      dispIdx = startIdx - (optInTimePeriod / 2 + 1);
      i = trailingIdx;
      while( i < startIdx ) {
         periodTotal += inReal[i];
         i = i + 1;
      }
      outIdx = 0;
      while( i <= endIdx ) {
         periodTotal += inReal[i];
         i = i + 1;
         tempReal = periodTotal;
         periodTotal -= inReal[trailingIdx];
         trailingIdx = trailingIdx + 1;
         /* Both reads precede the store. Either cursor can EQUAL outIdx -- the
          * displaced one whenever startIdx equals the displacement, the trailing
          * one whenever startIdx sits at the lookback -- so a store hoisted above
          * them would read back what it had just overwritten when the caller
          * aliases outReal over inReal.
          */
         dispVal = inReal[dispIdx];
         dispIdx = dispIdx + 1;
         outReal[outIdx * outStride] = dispVal - tempReal / (double)optInTimePeriod;
         outIdx = outIdx + 1;
      }
      outNBElement = outIdx;
      outBegIdx = startIdx;
      /* Capture the live batch state into the handle. */
      int cap_dispIdx = i - dispIdx;
      if( cap_dispIdx < 0 || cap_dispIdx > historyLen ) {
         return RetCode.InternalError;
      }
      int allocN_dispIdx = (cap_dispIdx > 0)? cap_dispIdx : 1;
      double[] capRing_dispIdx_inReal = new double[allocN_dispIdx];
      inReal.Slice(historyLen - cap_dispIdx, cap_dispIdx).CopyTo(capRing_dispIdx_inReal);
      int cap_trailingIdx = i - trailingIdx;
      if( cap_trailingIdx < 0 || cap_trailingIdx > historyLen ) {
         return RetCode.InternalError;
      }
      int allocN_trailingIdx = (cap_trailingIdx > 0)? cap_trailingIdx : 1;
      double[] capRing_trailingIdx_inReal = new double[allocN_trailingIdx];
      inReal.Slice(historyLen - cap_trailingIdx, cap_trailingIdx).CopyTo(capRing_trailingIdx_inReal);
      sp.optInTimePeriod = optInTimePeriod;
      sp.periodTotal = periodTotal;
      sp.ringPos_dispIdx = 0;
      sp.ringCap_dispIdx = cap_dispIdx;
      sp.ring_dispIdx_inReal = capRing_dispIdx_inReal;
      sp.ringPos_trailingIdx = 0;
      sp.ringCap_trailingIdx = cap_trailingIdx;
      sp.ring_trailingIdx_inReal = capRing_trailingIdx_inReal;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* DpoOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal DpoStream DpoOpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      DpoStream sp = new DpoStream(this);
      RetCode retCode = DpoOpenImpl(sp, inReal, startIdx, optInTimePeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("DPO", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind DpoOpen (composition seam). */
   internal DpoStream DpoOpenInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod )
   {
      DpoStream sp = new DpoStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = DpoOpenImpl(sp, inReal, startIdx, optInTimePeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("DPO", "open", retCode);
   }

   /// <summary>Open a live <c>DPO</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="DpoStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>DPO</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>DPO_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>DpoOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">Source price/value series, canonically the close. The warm-up history,
   /// oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="DPO_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>DPO_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public DpoStream DpoOpen( ReadOnlySpan<double> inReal, int optInTimePeriod )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "DPO open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "DPO open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      return DpoOpenInternal(inReal, 0, optInTimePeriod);
   }

   /// <summary><c>DpoOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>DPO</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - DPO_Lookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="DpoStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">Source price/value series, canonically the close. The warm-up history,
   /// oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="DPO_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Detrended Price Oscillator value, in the units of the input. Must hold at
   /// least <c>historyLen - DPO_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>DPO_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public DpoStream DpoOpenAndFill( ReadOnlySpan<double> inReal, int optInTimePeriod, Span<double> outReal )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "DPO openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "DPO openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      int guardOutLen = OpenFillCount("DPO", "openAndFill", inReal.Length, DPO_Lookback(optInTimePeriod));
      RequireFillLength("DPO", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( outReal.Overlaps(inReal) ) {
         throw StreamFailure("DPO", "openAndFill", RetCode.BadParam);
      }
      return DpoOpenAndFillInternal(inReal, 0, optInTimePeriod, out _, out _, outReal);
   }
