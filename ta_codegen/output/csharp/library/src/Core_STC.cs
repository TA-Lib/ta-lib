      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so nothing moves — <see cref="OutRange"/> included — and
      /// <see cref="Value"/> still answers the previous value. Re-feed the bar when
      /// a corrected value arrives, or call <see cref="Advance"/> to count it and
      /// carry on; two handles on one feed drift a bar apart if neither happens.
      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, which no re-feed clears: the
      /// handle has run out of index domain and only a shorter history can start a
      /// new one.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inReal )
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("STC", "update", RetCode.OutOfRangeEndIndex);
         if( !double.IsFinite(inReal) ) throw Core.NonFiniteBar("STC", "update", nameof(inReal));
         core.StcStepImpl(this, inReal);
         outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.IndexMax"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public double Peek( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.NonFiniteBar("STC", "peek", nameof(inReal));
         StcStream sp = this;
         double tempReal = 0.0;
         double lineValue = 0.0;
         double lowest = 0.0;
         double highest = 0.0;
         double range = 0.0;
         double sufHi = 0.0;
         double sufLo = 0.0;
         int i = 0;
         double cur_outReal = 0.0;
         double frac1 = sp.frac1;
         double frac2 = sp.frac2;
         double lineHi = sp.lineHi;
         double lineLo = sp.lineLo;
         int lineRing_Idx = sp.lineRing_Idx;
         double pf = sp.pf;
         double pfHi = sp.pfHi;
         double pfLo = sp.pfLo;
         int pfRing_Idx = sp.pfRing_Idx;
         double pff = sp.pff;
         double prevFast = sp.prevFast;
         double prevSlow = sp.prevSlow;
         int pkSlot0 = -1;
         double pkVal0 = 0.0;
         int pkSlot1 = -1;
         double pkVal1 = 0.0;
         tempReal = inReal;
         prevFast = Math.FusedMultiplyAdd(tempReal - prevFast, sp.fastK, prevFast);
         prevSlow = Math.FusedMultiplyAdd(tempReal - prevSlow, sp.slowK, prevSlow);
         lineValue = prevFast - prevSlow;
         pkSlot0 = lineRing_Idx;
         pkVal0 = lineValue;
         if( lineRing_Idx == 0 ) {
            lineHi = lineValue;
            lineLo = lineValue;
         } else {
            lineHi = MaxGt(lineValue, lineHi);
            lineLo = MinLt(lineValue, lineLo);
         }
         highest = lineHi;
         lowest = lineLo;
         if( lineRing_Idx < sp.lastIdx ) {
            tempReal = sp.cb_lineSufHi[lineRing_Idx + 1];
            highest = MaxGt(tempReal, highest);
            tempReal = sp.cb_lineSufLo[lineRing_Idx + 1];
            lowest = MinLt(tempReal, lowest);
         }
         lineRing_Idx = lineRing_Idx + 1;
         if( lineRing_Idx > sp.maxIdx_lineRing ) {
            lineRing_Idx = 0;
         }
         if( lineRing_Idx == 0 ) {
            sufHi = (sp.lastIdx != pkSlot0) ? sp.cb_lineRing[sp.lastIdx] : pkVal0;
            sufLo = sufHi;
            i = sp.lastIdx;
            while( i > 0 ) {
               i -= 1;
               tempReal = (i != pkSlot0) ? sp.cb_lineRing[i] : pkVal0;
               sufHi = MaxGt(tempReal, sufHi);
               sufLo = MinLt(tempReal, sufLo);
            }
         }
         range = highest - lowest;
         if( range > 0.0 ) {
            frac1 = (lineValue - lowest) / range * 100.0;
         }
         pf = Math.FusedMultiplyAdd(0.5, frac1 - pf, pf);
         pkSlot1 = pfRing_Idx;
         pkVal1 = pf;
         if( pfRing_Idx == 0 ) {
            pfHi = pf;
            pfLo = pf;
         } else {
            pfHi = MaxGt(pf, pfHi);
            pfLo = MinLt(pf, pfLo);
         }
         highest = pfHi;
         lowest = pfLo;
         if( pfRing_Idx < sp.lastIdx ) {
            tempReal = sp.cb_pfSufHi[pfRing_Idx + 1];
            highest = MaxGt(tempReal, highest);
            tempReal = sp.cb_pfSufLo[pfRing_Idx + 1];
            lowest = MinLt(tempReal, lowest);
         }
         pfRing_Idx = pfRing_Idx + 1;
         if( pfRing_Idx > sp.maxIdx_pfRing ) {
            pfRing_Idx = 0;
         }
         if( pfRing_Idx == 0 ) {
            sufHi = (sp.lastIdx != pkSlot1) ? sp.cb_pfRing[sp.lastIdx] : pkVal1;
            sufLo = sufHi;
            i = sp.lastIdx;
            while( i > 0 ) {
               i -= 1;
               tempReal = (i != pkSlot1) ? sp.cb_pfRing[i] : pkVal1;
               sufHi = MaxGt(tempReal, sufHi);
               sufLo = MinLt(tempReal, sufLo);
            }
         }
         range = highest - lowest;
         if( range > 0.0 ) {
            frac2 = (pf - lowest) / range * 100.0;
         }
         pff = Math.FusedMultiplyAdd(0.5, frac2 - pff, pff);
         cur_outReal = pff;
         return cur_outReal;
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public StcStream Clone()
      {
         return new StcStream(this);
      }
   }

   private void StcStepImpl( StcStream sp, double inReal )
   {
      double tempReal = 0.0;
      double lineValue = 0.0;
      double lowest = 0.0;
      double highest = 0.0;
      double range = 0.0;
      double sufHi = 0.0;
      double sufLo = 0.0;
      int i = 0;
      tempReal = inReal;
      sp.prevFast = Math.FusedMultiplyAdd(tempReal - sp.prevFast, sp.fastK, sp.prevFast);
      sp.prevSlow = Math.FusedMultiplyAdd(tempReal - sp.prevSlow, sp.slowK, sp.prevSlow);
      lineValue = sp.prevFast - sp.prevSlow;
      sp.cb_lineRing[sp.lineRing_Idx] = lineValue;
      if( sp.lineRing_Idx == 0 ) {
         sp.lineHi = lineValue;
         sp.lineLo = lineValue;
      } else {
         sp.lineHi = MaxGt(lineValue, sp.lineHi);
         sp.lineLo = MinLt(lineValue, sp.lineLo);
      }
      highest = sp.lineHi;
      lowest = sp.lineLo;
      if( sp.lineRing_Idx < sp.lastIdx ) {
         tempReal = sp.cb_lineSufHi[sp.lineRing_Idx + 1];
         highest = MaxGt(tempReal, highest);
         tempReal = sp.cb_lineSufLo[sp.lineRing_Idx + 1];
         lowest = MinLt(tempReal, lowest);
      }
      sp.lineRing_Idx = sp.lineRing_Idx + 1;
      if( sp.lineRing_Idx > sp.maxIdx_lineRing ) {
         sp.lineRing_Idx = 0;
      }
      if( sp.lineRing_Idx == 0 ) {
         sufHi = sp.cb_lineRing[sp.lastIdx];
         sufLo = sufHi;
         sp.cb_lineSufHi[sp.lastIdx] = sufHi;
         sp.cb_lineSufLo[sp.lastIdx] = sufLo;
         i = sp.lastIdx;
         while( i > 0 ) {
            i -= 1;
            tempReal = sp.cb_lineRing[i];
            sufHi = MaxGt(tempReal, sufHi);
            sufLo = MinLt(tempReal, sufLo);
            sp.cb_lineSufHi[i] = sufHi;
            sp.cb_lineSufLo[i] = sufLo;
         }
      }
      range = highest - lowest;
      if( range > 0.0 ) {
         sp.frac1 = (lineValue - lowest) / range * 100.0;
      }
      sp.pf = Math.FusedMultiplyAdd(0.5, sp.frac1 - sp.pf, sp.pf);
      sp.cb_pfRing[sp.pfRing_Idx] = sp.pf;
      if( sp.pfRing_Idx == 0 ) {
         sp.pfHi = sp.pf;
         sp.pfLo = sp.pf;
      } else {
         sp.pfHi = MaxGt(sp.pf, sp.pfHi);
         sp.pfLo = MinLt(sp.pf, sp.pfLo);
      }
      highest = sp.pfHi;
      lowest = sp.pfLo;
      if( sp.pfRing_Idx < sp.lastIdx ) {
         tempReal = sp.cb_pfSufHi[sp.pfRing_Idx + 1];
         highest = MaxGt(tempReal, highest);
         tempReal = sp.cb_pfSufLo[sp.pfRing_Idx + 1];
         lowest = MinLt(tempReal, lowest);
      }
      sp.pfRing_Idx = sp.pfRing_Idx + 1;
      if( sp.pfRing_Idx > sp.maxIdx_pfRing ) {
         sp.pfRing_Idx = 0;
      }
      if( sp.pfRing_Idx == 0 ) {
         sufHi = sp.cb_pfRing[sp.lastIdx];
         sufLo = sufHi;
         sp.cb_pfSufHi[sp.lastIdx] = sufHi;
         sp.cb_pfSufLo[sp.lastIdx] = sufLo;
         i = sp.lastIdx;
         while( i > 0 ) {
            i -= 1;
            tempReal = sp.cb_pfRing[i];
            sufHi = MaxGt(tempReal, sufHi);
            sufLo = MinLt(tempReal, sufLo);
            sp.cb_pfSufHi[i] = sufHi;
            sp.cb_pfSufLo[i] = sufLo;
         }
      }
      range = highest - lowest;
      if( range > 0.0 ) {
         sp.frac2 = (sp.pf - lowest) / range * 100.0;
      }
      sp.pff = Math.FusedMultiplyAdd(0.5, sp.frac2 - sp.pff, sp.pff);
      sp.cur_outReal = sp.pff;
   }

   private RetCode StcOpenImpl( StcStream sp, ReadOnlySpan<double> inReal, int startIdx, int optInFastPeriod, int optInSlowPeriod, int optInCyclePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double[] lineRing = [];
      int lineRing_Idx = 0;
      int maxIdx_lineRing = (30)-1;
      double[] lineSufHi = [];
      int lineSufHi_Idx = 0;
      int maxIdx_lineSufHi = (30)-1;
      double[] lineSufLo = [];
      int lineSufLo_Idx = 0;
      int maxIdx_lineSufLo = (30)-1;
      double[] pfRing = [];
      int pfRing_Idx = 0;
      int maxIdx_pfRing = (30)-1;
      double[] pfSufHi = [];
      int pfSufHi_Idx = 0;
      int maxIdx_pfSufHi = (30)-1;
      double[] pfSufLo = [];
      int pfSufLo_Idx = 0;
      int maxIdx_pfSufLo = (30)-1;
      double prevFast = 0;
      double prevSlow = 0;
      double fastK = 0;
      double slowK = 0;
      double tempReal = 0;
      double lineValue = 0;
      double lowest = 0;
      double highest = 0;
      double range = 0;
      double frac1 = 0;
      double frac2 = 0;
      double pf = 0;
      double pff = 0;
      double lineHi = 0;
      double lineLo = 0;
      double pfHi = 0;
      double pfLo = 0;
      double sufHi = 0;
      double sufLo = 0;
      int i = 0;
      int today = 0;
      int lineStart = 0;
      int outIdx = 0;
      int tempInteger = 0;
      int lookbackTotal = 0;
      int lastIdx = 0;
      int nLine = 0;
      int nPF = 0;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > IndexMax + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInFastPeriod == int.MinValue ) {
         optInFastPeriod = 23;
      } else if( optInFastPeriod < 2 || optInFastPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInSlowPeriod == int.MinValue ) {
         optInSlowPeriod = 50;
      } else if( optInSlowPeriod < 2 || optInSlowPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInCyclePeriod == int.MinValue ) {
         optInCyclePeriod = 10;
      } else if( optInCyclePeriod < 2 || optInCyclePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      if( optInSlowPeriod < optInFastPeriod ) {
         tempInteger = optInSlowPeriod;
         optInSlowPeriod = optInFastPeriod;
         optInFastPeriod = tempInteger;
      }
      lookbackTotal = StcLookback(optInFastPeriod, optInSlowPeriod, optInCyclePeriod);
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      outBegIdx = startIdx;
      fastK = 2.0 / (double)(optInFastPeriod + 1);
      slowK = 2.0 / (double)(optInSlowPeriod + 1);
      /* Rolling extrema, van Herk / Gil-Werman: the window ending in slot j is
       * the current block's prefix extremum joined with the previous block's
       * suffix extremum from slot j+1. The extrema are exact, so the output must
       * stay bit-identical to a full rescan of each window.
       */
      if( optInCyclePeriod < 1 ) return RetCode.InternalError;
      lineRing = new double[optInCyclePeriod];
      maxIdx_lineRing = (optInCyclePeriod)-1;
      lineRing_Idx = 0;
      if( optInCyclePeriod < 1 ) return RetCode.InternalError;
      lineSufHi = new double[optInCyclePeriod];
      maxIdx_lineSufHi = (optInCyclePeriod)-1;
      lineSufHi_Idx = 0;
      if( optInCyclePeriod < 1 ) return RetCode.InternalError;
      lineSufLo = new double[optInCyclePeriod];
      maxIdx_lineSufLo = (optInCyclePeriod)-1;
      lineSufLo_Idx = 0;
      if( optInCyclePeriod < 1 ) return RetCode.InternalError;
      pfRing = new double[optInCyclePeriod];
      maxIdx_pfRing = (optInCyclePeriod)-1;
      pfRing_Idx = 0;
      if( optInCyclePeriod < 1 ) return RetCode.InternalError;
      pfSufHi = new double[optInCyclePeriod];
      maxIdx_pfSufHi = (optInCyclePeriod)-1;
      pfSufHi_Idx = 0;
      if( optInCyclePeriod < 1 ) return RetCode.InternalError;
      pfSufLo = new double[optInCyclePeriod];
      maxIdx_pfSufLo = (optInCyclePeriod)-1;
      pfSufLo_Idx = 0;
      lastIdx = optInCyclePeriod - 1;
      /* The line is TA_MACD's: co-terminal SMA seeds, then both EMAs advanced
       * through TA_FUNC_UNST_EMA to lineStart, so that from lineStart on it is
       * TA_EMA(fast) - TA_EMA(slow) bit for bit. The chain is fed from
       * lineStart, not from the EMA seed: TA_FUNC_UNST_EMA then reaches only the
       * line, while TA_FUNC_UNST_STC moves the whole chain back and so warms the
       * line and both smoothers.
       */
      lineStart = startIdx - (lookbackTotal - EmaLookback(optInSlowPeriod));
      today = startIdx - lookbackTotal;
      tempReal = 0.0;
      i = optInSlowPeriod - optInFastPeriod;
      while( i-- > 0 ) {
         tempReal += inReal[today++];
      }
      prevFast = 0.0;
      i = optInFastPeriod;
      while( i-- > 0 ) {
         prevFast += inReal[today];
         tempReal += inReal[today++];
      }
      prevSlow = tempReal / optInSlowPeriod;
      prevFast = prevFast / optInFastPeriod;
      while( today <= lineStart ) {
         tempReal = inReal[today++];
         prevFast = Math.FusedMultiplyAdd(tempReal - prevFast, fastK, prevFast);
         prevSlow = Math.FusedMultiplyAdd(tempReal - prevSlow, slowK, prevSlow);
      }
      /* A zero range holds the previous fraction (0.0 before any), and the test
       * is exact: in a sustained trend PF saturates at 100 and the second
       * range reaches exactly 0 while the output must stay at 100.
       */
      frac1 = 0.0;
      frac2 = 0.0;
      pf = 0.0;
      pff = 0.0;
      pfHi = 0.0;
      pfLo = 0.0;
      nPF = 0;
      lineValue = prevFast - prevSlow;
      lineRing[lineRing_Idx] = lineValue;
      lineRing_Idx++;
      if( lineRing_Idx > maxIdx_lineRing ) { lineRing_Idx = 0; }
      lineHi = lineValue;
      lineLo = lineValue;
      nLine = 1;
      /* Warm-up, through startIdx inclusive. Each stage starts once its
       * window is full, and each smoother is seeded on its first input.
       */
      while( today <= startIdx ) {
         tempReal = inReal[today];
         prevFast = Math.FusedMultiplyAdd(tempReal - prevFast, fastK, prevFast);
         prevSlow = Math.FusedMultiplyAdd(tempReal - prevSlow, slowK, prevSlow);
         lineValue = prevFast - prevSlow;
         nLine = nLine + 1;
         lineRing[lineRing_Idx] = lineValue;
         if( lineRing_Idx == 0 ) {
            lineHi = lineValue;
            lineLo = lineValue;
         } else {
            lineHi = MaxGt(lineValue, lineHi);
            lineLo = MinLt(lineValue, lineLo);
         }
         highest = lineHi;
         lowest = lineLo;
         if( nLine >= optInCyclePeriod && lineRing_Idx < lastIdx ) {
            tempReal = lineSufHi[lineRing_Idx + 1];
            highest = MaxGt(tempReal, highest);
            tempReal = lineSufLo[lineRing_Idx + 1];
            lowest = MinLt(tempReal, lowest);
         }
         lineRing_Idx++;
         if( lineRing_Idx > maxIdx_lineRing ) { lineRing_Idx = 0; }
         if( lineRing_Idx == 0 ) {
            sufHi = lineRing[lastIdx];
            sufLo = sufHi;
            lineSufHi[lastIdx] = sufHi;
            lineSufLo[lastIdx] = sufLo;
            i = lastIdx;
            while( i > 0 ) {
               i -= 1;
               tempReal = lineRing[i];
               sufHi = MaxGt(tempReal, sufHi);
               sufLo = MinLt(tempReal, sufLo);
               lineSufHi[i] = sufHi;
               lineSufLo[i] = sufLo;
            }
         }
         if( nLine >= optInCyclePeriod ) {
            range = highest - lowest;
            if( range > 0.0 ) {
               frac1 = (lineValue - lowest) / range * 100.0;
            }
            if( nPF == 0 ) {
               pf = frac1;
            } else {
               pf = Math.FusedMultiplyAdd(0.5, frac1 - pf, pf);
            }
            nPF = nPF + 1;
            pfRing[pfRing_Idx] = pf;
            if( pfRing_Idx == 0 ) {
               pfHi = pf;
               pfLo = pf;
            } else {
               pfHi = MaxGt(pf, pfHi);
               pfLo = MinLt(pf, pfLo);
            }
            highest = pfHi;
            lowest = pfLo;
            if( nPF >= optInCyclePeriod && pfRing_Idx < lastIdx ) {
               tempReal = pfSufHi[pfRing_Idx + 1];
               highest = MaxGt(tempReal, highest);
               tempReal = pfSufLo[pfRing_Idx + 1];
               lowest = MinLt(tempReal, lowest);
            }
            pfRing_Idx++;
            if( pfRing_Idx > maxIdx_pfRing ) { pfRing_Idx = 0; }
            if( pfRing_Idx == 0 ) {
               sufHi = pfRing[lastIdx];
               sufLo = sufHi;
               pfSufHi[lastIdx] = sufHi;
               pfSufLo[lastIdx] = sufLo;
               i = lastIdx;
               while( i > 0 ) {
                  i -= 1;
                  tempReal = pfRing[i];
                  sufHi = MaxGt(tempReal, sufHi);
                  sufLo = MinLt(tempReal, sufLo);
                  pfSufHi[i] = sufHi;
                  pfSufLo[i] = sufLo;
               }
            }
            if( nPF >= optInCyclePeriod ) {
               range = highest - lowest;
               if( range > 0.0 ) {
                  frac2 = (pf - lowest) / range * 100.0;
               }
               if( nPF == optInCyclePeriod ) {
                  pff = frac2;
               } else {
                  pff = Math.FusedMultiplyAdd(0.5, frac2 - pff, pff);
               }
            }
         }
         today = today + 1;
      }
      outReal[0 * outStride] = pff;
      outIdx = 1;
      while( today <= endIdx ) {
         tempReal = inReal[today];
         prevFast = Math.FusedMultiplyAdd(tempReal - prevFast, fastK, prevFast);
         prevSlow = Math.FusedMultiplyAdd(tempReal - prevSlow, slowK, prevSlow);
         lineValue = prevFast - prevSlow;
         lineRing[lineRing_Idx] = lineValue;
         if( lineRing_Idx == 0 ) {
            lineHi = lineValue;
            lineLo = lineValue;
         } else {
            lineHi = MaxGt(lineValue, lineHi);
            lineLo = MinLt(lineValue, lineLo);
         }
         highest = lineHi;
         lowest = lineLo;
         if( lineRing_Idx < lastIdx ) {
            tempReal = lineSufHi[lineRing_Idx + 1];
            highest = MaxGt(tempReal, highest);
            tempReal = lineSufLo[lineRing_Idx + 1];
            lowest = MinLt(tempReal, lowest);
         }
         lineRing_Idx++;
         if( lineRing_Idx > maxIdx_lineRing ) { lineRing_Idx = 0; }
         if( lineRing_Idx == 0 ) {
            sufHi = lineRing[lastIdx];
            sufLo = sufHi;
            lineSufHi[lastIdx] = sufHi;
            lineSufLo[lastIdx] = sufLo;
            i = lastIdx;
            while( i > 0 ) {
               i -= 1;
               tempReal = lineRing[i];
               sufHi = MaxGt(tempReal, sufHi);
               sufLo = MinLt(tempReal, sufLo);
               lineSufHi[i] = sufHi;
               lineSufLo[i] = sufLo;
            }
         }
         range = highest - lowest;
         if( range > 0.0 ) {
            frac1 = (lineValue - lowest) / range * 100.0;
         }
         pf = Math.FusedMultiplyAdd(0.5, frac1 - pf, pf);
         pfRing[pfRing_Idx] = pf;
         if( pfRing_Idx == 0 ) {
            pfHi = pf;
            pfLo = pf;
         } else {
            pfHi = MaxGt(pf, pfHi);
            pfLo = MinLt(pf, pfLo);
         }
         highest = pfHi;
         lowest = pfLo;
         if( pfRing_Idx < lastIdx ) {
            tempReal = pfSufHi[pfRing_Idx + 1];
            highest = MaxGt(tempReal, highest);
            tempReal = pfSufLo[pfRing_Idx + 1];
            lowest = MinLt(tempReal, lowest);
         }
         pfRing_Idx++;
         if( pfRing_Idx > maxIdx_pfRing ) { pfRing_Idx = 0; }
         if( pfRing_Idx == 0 ) {
            sufHi = pfRing[lastIdx];
            sufLo = sufHi;
            pfSufHi[lastIdx] = sufHi;
            pfSufLo[lastIdx] = sufLo;
            i = lastIdx;
            while( i > 0 ) {
               i -= 1;
               tempReal = pfRing[i];
               sufHi = MaxGt(tempReal, sufHi);
               sufLo = MinLt(tempReal, sufLo);
               pfSufHi[i] = sufHi;
               pfSufLo[i] = sufLo;
            }
         }
         range = highest - lowest;
         if( range > 0.0 ) {
            frac2 = (pf - lowest) / range * 100.0;
         }
         pff = Math.FusedMultiplyAdd(0.5, frac2 - pff, pff);
         outReal[outIdx++ * outStride] = pff;
         today = today + 1;
      }
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      int capCb_lineRing = maxIdx_lineRing + 1;
      if( capCb_lineRing > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      int capCb_lineSufHi = maxIdx_lineSufHi + 1;
      if( capCb_lineSufHi > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      int capCb_lineSufLo = maxIdx_lineSufLo + 1;
      if( capCb_lineSufLo > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      int capCb_pfRing = maxIdx_pfRing + 1;
      if( capCb_pfRing > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      int capCb_pfSufHi = maxIdx_pfSufHi + 1;
      if( capCb_pfSufHi > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      int capCb_pfSufLo = maxIdx_pfSufLo + 1;
      if( capCb_pfSufLo > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      sp.optInFastPeriod = optInFastPeriod;
      sp.optInSlowPeriod = optInSlowPeriod;
      sp.optInCyclePeriod = optInCyclePeriod;
      sp.prevFast = prevFast;
      sp.prevSlow = prevSlow;
      sp.fastK = fastK;
      sp.slowK = slowK;
      sp.frac1 = frac1;
      sp.frac2 = frac2;
      sp.pf = pf;
      sp.pff = pff;
      sp.lineHi = lineHi;
      sp.lineLo = lineLo;
      sp.pfHi = pfHi;
      sp.pfLo = pfLo;
      sp.lastIdx = lastIdx;
      sp.lineRing_Idx = lineRing_Idx;
      sp.pfRing_Idx = pfRing_Idx;
      sp.maxIdx_lineRing = maxIdx_lineRing;
      sp.lineSufHi_Idx = lineSufHi_Idx;
      sp.maxIdx_lineSufHi = maxIdx_lineSufHi;
      sp.lineSufLo_Idx = lineSufLo_Idx;
      sp.maxIdx_lineSufLo = maxIdx_lineSufLo;
      sp.maxIdx_pfRing = maxIdx_pfRing;
      sp.pfSufHi_Idx = pfSufHi_Idx;
      sp.maxIdx_pfSufHi = maxIdx_pfSufHi;
      sp.pfSufLo_Idx = pfSufLo_Idx;
      sp.maxIdx_pfSufLo = maxIdx_pfSufLo;
      sp.cbSize_lineRing = capCb_lineRing;
      sp.cb_lineRing = lineRing;
      sp.cbSize_lineSufHi = capCb_lineSufHi;
      sp.cb_lineSufHi = lineSufHi;
      sp.cbSize_lineSufLo = capCb_lineSufLo;
      sp.cb_lineSufLo = lineSufLo;
      sp.cbSize_pfRing = capCb_pfRing;
      sp.cb_pfRing = pfRing;
      sp.cbSize_pfSufHi = capCb_pfSufHi;
      sp.cb_pfSufHi = pfSufHi;
      sp.cbSize_pfSufLo = capCb_pfSufLo;
      sp.cb_pfSufLo = pfSufLo;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* StcOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal StcStream StcOpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, int optInFastPeriod, int optInSlowPeriod, int optInCyclePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      StcStream sp = new StcStream(this);
      RetCode retCode = StcOpenImpl(sp, inReal, startIdx, optInFastPeriod, optInSlowPeriod, optInCyclePeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("STC", "openAndFill", nameof(inReal), inReal.Length, startIdx, StcLookback(optInFastPeriod, optInSlowPeriod, optInCyclePeriod));
      }
      throw StreamFailure("STC", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind StcOpen (composition seam). */
   internal StcStream StcOpenInternal( ReadOnlySpan<double> inReal, int startIdx, int optInFastPeriod, int optInSlowPeriod, int optInCyclePeriod )
   {
      StcStream sp = new StcStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = StcOpenImpl(sp, inReal, startIdx, optInFastPeriod, optInSlowPeriod, optInCyclePeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("STC", "open", nameof(inReal), inReal.Length, startIdx, StcLookback(optInFastPeriod, optInSlowPeriod, optInCyclePeriod));
      }
      throw StreamFailure("STC", "open", retCode);
   }

   /// <summary>Open a live <c>STC</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="StcStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>STC</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>StcLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>StcOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">Input series (typically close) The warm-up history, oldest bar first.</param>
   /// <param name="optInFastPeriod">As in the batch call; see <see cref="StcLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowPeriod">As in the batch call; see <see cref="StcLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInCyclePeriod">As in the batch call; see <see cref="StcLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>StcLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules S1 and S2).</exception>
   public StcStream StcOpen( ReadOnlySpan<double> inReal, int optInFastPeriod, int optInSlowPeriod, int optInCyclePeriod )
   {
      if( inReal.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "STC open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "STC open: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      return StcOpenInternal(inReal, 0, optInFastPeriod, optInSlowPeriod, optInCyclePeriod);
   }

   /// <summary><c>StcOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>STC</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - StcLookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="StcStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">Input series (typically close) The warm-up history, oldest bar first.</param>
   /// <param name="optInFastPeriod">As in the batch call; see <see cref="StcLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowPeriod">As in the batch call; see <see cref="StcLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInCyclePeriod">As in the batch call; see <see cref="StcLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Schaff Trend Cycle, from 0 to 100. Must hold at least <c>historyLen -
   /// StcLookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>StcLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules S1 and S2).</exception>
   public StcStream StcOpenAndFill( ReadOnlySpan<double> inReal, int optInFastPeriod, int optInSlowPeriod, int optInCyclePeriod, Span<double> outReal )
   {
      if( inReal.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "STC openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "STC openAndFill: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      int guardOutLen = OpenFillCount("STC", "openAndFill", inReal.Length, StcLookback(optInFastPeriod, optInSlowPeriod, optInCyclePeriod));
      RequireFillLength("STC", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( outReal.Overlaps(inReal) ) {
         throw StreamFailure("STC", "openAndFill", RetCode.BadParam);
      }
      return StcOpenAndFillInternal(inReal, 0, optInFastPeriod, optInSlowPeriod, optInCyclePeriod, out _, out _, outReal);
   }
