   /* Internal startIdx-anchored open behind MA_Open (composition seam). */
   internal MA_Stream MA_OpenInternal( double[] inReal, int startIdx, int optInTimePeriod, MAType optInMAType )
   {
      MA_Stream sp = new MA_Stream(this);
      RetCode retCode = MA_OpenBody(sp, inReal, startIdx, optInTimePeriod, optInMAType);
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("MA", "open", retCode);
   }

   /// <summary>Open a live <c>MA</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="MA_Stream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>MA</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>MA_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>MA_OpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">Series to average. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="MA_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInMAType">As in the batch call; see <see cref="MA_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>MA_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.NullReferenceException">An input array is null. (Unlike the C library, the managed tier does not
   /// pre-validate nulls; the first array access throws.)</exception>
   public MA_Stream MA_Open( double[] inReal, int optInTimePeriod, MAType optInMAType )
   {
      return MA_OpenInternal(inReal, 0, optInTimePeriod, optInMAType);
   }

   /// <summary><c>MA_Open</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>MA</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - MA_Lookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="MA_Stream.FillRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">Series to average. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="MA_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInMAType">As in the batch call; see <see cref="MA_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Selected moving average of the input. Must hold at least <c>historyLen -
   /// MA_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>MA_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, or an output array aliases an input or another
   /// output.</exception>
   /// <exception cref="System.NullReferenceException">An input or output array is null. (Unlike the C library, the managed tier
   /// does not pre-validate nulls; the first array access throws.)</exception>
   public MA_Stream MA_OpenAndFill( double[] inReal, int optInTimePeriod, MAType optInMAType, double[] outReal )
   {
      MA_Stream sp = new MA_Stream(this);
      RetCode retCode = MA_OpenAndFillBody(sp, inReal, optInTimePeriod, optInMAType, out int outBegIdx, out int outNBElement, outReal);
      sp.fillRange = new OutRange(outBegIdx, outNBElement);
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("MA", "openAndFill", retCode);
   }

