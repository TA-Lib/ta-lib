         sp.cur_outReal = outReal[outNBElement - 1];
         return RetCode.Success;
      }
      switch( optInMAType )
      {
      case MAType.SMA: {
         SMA_Stream sub = SMA_OpenAndFill(inReal, optInTimePeriod, outReal);
