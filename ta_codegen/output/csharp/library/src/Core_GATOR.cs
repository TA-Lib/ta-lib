      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so nothing moves — <see cref="OutRange"/> included — and
      /// <see cref="Value"/> still answers the previous value. Re-feed the bar when
      /// a corrected value arrives, or call <see cref="Advance"/> to count it and
      /// carry on; two handles on one feed drift a bar apart if neither happens.
      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, which no re-feed clears: the
      /// handle has run out of index domain and only a shorter history can start a
      /// new one.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <returns>The value at the bar just committed.</returns>
      public GatorValue Update( double inHigh, double inLow )
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("GATOR", "update", RetCode.OutOfRangeEndIndex);
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) ) throw Core.NonFiniteBar("GATOR", "update", !double.IsFinite(inHigh) ? nameof(inHigh) : nameof(inLow));
         core.GatorStepImpl(this, inHigh, inLow);
         outRangeCount++;
         return new GatorValue(cur_outUpper, cur_outLower);
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.IndexMax"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public GatorValue Peek( double inHigh, double inLow )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) ) throw Core.NonFiniteBar("GATOR", "peek", !double.IsFinite(inHigh) ? nameof(inHigh) : nameof(inLow));
         GatorStream sp = this;
         double cur_tempMP = 0.0;
         double cur_tempA = 0.0;
         double cur_tempB = 0.0;
         double cur_outUpper = 0.0;
         double cur_outLower = 0.0;
         double lagIn0 = 0.0;
         double lagTap0_0 = 0.0;
         double lagIn1 = 0.0;
         double lagTap1_0 = 0.0;
         double lagIn2 = 0.0;
         double lagTap2_0 = 0.0;
         double lagIn3 = 0.0;
         double lagTap3_0 = 0.0;
         /* Pipeline the new bar through the sub-streams (batch tail order). */
         cur_tempMP = sp.sub0.Peek(inHigh, inLow);
         cur_tempA = sp.sub1.Peek(cur_tempMP);
         lagIn0 = cur_tempA;
         cur_tempB = sp.sub2.Peek(cur_tempMP);
         lagIn1 = cur_tempB;
         /* Combine map (batch tail, per bar). */
         lagTap0_0 = sp.lagBuf0[sp.lagPos0];
         lagTap0_0 = (sp.lagCap0 == 0) ? lagIn0 : lagTap0_0;
         lagTap1_0 = sp.lagBuf1[sp.lagPos1];
         lagTap1_0 = (sp.lagCap1 == 0) ? lagIn1 : lagTap1_0;
         cur_outUpper = Math.Abs(lagTap0_0 - lagTap1_0);
         cur_tempA = sp.sub3.Peek(cur_tempMP);
         lagIn2 = cur_tempA;
         cur_tempB = sp.sub4.Peek(cur_tempMP);
         lagIn3 = cur_tempB;
         /* Combine map (batch tail, per bar). */
         lagTap2_0 = sp.lagBuf2[sp.lagPos2];
         lagTap2_0 = (sp.lagCap2 == 0) ? lagIn2 : lagTap2_0;
         lagTap3_0 = sp.lagBuf3[sp.lagPos3];
         lagTap3_0 = (sp.lagCap3 == 0) ? lagIn3 : lagTap3_0;
         cur_outLower = (lagTap2_0 < lagTap3_0) ? lagTap2_0 - lagTap3_0 : lagTap3_0 - lagTap2_0;
         return new GatorValue(cur_outUpper, cur_outLower);
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public GatorValue Value => new GatorValue(cur_outUpper, cur_outLower);

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public GatorStream Clone()
      {
         return new GatorStream(this);
      }
   }

   private void GatorStepImpl( GatorStream sp, double inHigh, double inLow )
   {
      double cur_tempMP = 0.0;
      double cur_tempA = 0.0;
      double cur_tempB = 0.0;
      double cur_outUpper = 0.0;
      double cur_outLower = 0.0;
      double lagIn0 = 0.0;
      double lagTap0_0 = 0.0;
      double lagIn1 = 0.0;
      double lagTap1_0 = 0.0;
      double lagIn2 = 0.0;
      double lagTap2_0 = 0.0;
      double lagIn3 = 0.0;
      double lagTap3_0 = 0.0;
      int lagCapL0 = 0;
      int lagPosL0 = 0;
      int lagCapL1 = 0;
      int lagPosL1 = 0;
      int lagCapL2 = 0;
      int lagPosL2 = 0;
      int lagCapL3 = 0;
      int lagPosL3 = 0;
      /* Pipeline the new bar through the sub-streams (batch tail order). */
      cur_tempMP = sp.sub0.Update(inHigh, inLow);
      cur_tempA = sp.sub1.Update(cur_tempMP);
      lagIn0 = cur_tempA;
      cur_tempB = sp.sub2.Update(cur_tempMP);
      lagIn1 = cur_tempB;
      /* Combine map (batch tail, per bar). */
      lagTap0_0 = sp.lagBuf0[sp.lagPos0];
      lagTap0_0 = (sp.lagCap0 == 0) ? lagIn0 : lagTap0_0;
      lagTap1_0 = sp.lagBuf1[sp.lagPos1];
      lagTap1_0 = (sp.lagCap1 == 0) ? lagIn1 : lagTap1_0;
      cur_outUpper = Math.Abs(lagTap0_0 - lagTap1_0);
      cur_tempA = sp.sub3.Update(cur_tempMP);
      lagIn2 = cur_tempA;
      cur_tempB = sp.sub4.Update(cur_tempMP);
      lagIn3 = cur_tempB;
      /* Combine map (batch tail, per bar). */
      lagTap2_0 = sp.lagBuf2[sp.lagPos2];
      lagTap2_0 = (sp.lagCap2 == 0) ? lagIn2 : lagTap2_0;
      lagTap3_0 = sp.lagBuf3[sp.lagPos3];
      lagTap3_0 = (sp.lagCap3 == 0) ? lagIn3 : lagTap3_0;
      cur_outLower = (lagTap2_0 < lagTap3_0) ? lagTap2_0 - lagTap3_0 : lagTap3_0 - lagTap2_0;
      lagCapL0 = sp.lagCap0;
      lagPosL0 = sp.lagPos0;
      sp.lagBuf0[lagPosL0] = lagIn0;
      lagPosL0 = lagPosL0 + 1;
      if( lagPosL0 >= lagCapL0 ) {
         lagPosL0 = 0;
      }
      sp.lagPos0 = lagPosL0;
      lagCapL1 = sp.lagCap1;
      lagPosL1 = sp.lagPos1;
      sp.lagBuf1[lagPosL1] = lagIn1;
      lagPosL1 = lagPosL1 + 1;
      if( lagPosL1 >= lagCapL1 ) {
         lagPosL1 = 0;
      }
      sp.lagPos1 = lagPosL1;
      lagCapL2 = sp.lagCap2;
      lagPosL2 = sp.lagPos2;
      sp.lagBuf2[lagPosL2] = lagIn2;
      lagPosL2 = lagPosL2 + 1;
      if( lagPosL2 >= lagCapL2 ) {
         lagPosL2 = 0;
      }
      sp.lagPos2 = lagPosL2;
      lagCapL3 = sp.lagCap3;
      lagPosL3 = sp.lagPos3;
      sp.lagBuf3[lagPosL3] = lagIn3;
      lagPosL3 = lagPosL3 + 1;
      if( lagPosL3 >= lagCapL3 ) {
         lagPosL3 = 0;
      }
      sp.lagPos3 = lagPosL3;
      sp.cur_outUpper = cur_outUpper;
      sp.cur_outLower = cur_outLower;
   }

   private RetCode GatorOpenImpl( GatorStream sp, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int startIdx, int optInJawPeriod, int optInJawShift, int optInTeethPeriod, int optInTeethShift, int optInLipsPeriod, int optInLipsShift, out int outBegIdx, out int outNBElement, Span<double> outUpper, Span<double> outLower, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      RetCode retCode;
      int i = 0;
      int nbElement = 0;
      int maxBack = 0;
      int lookbackTotal = 0;
      int mpStartIdx = 0;
      int localStart = 0;
      int localEnd = 0;
      int backJaw = 0;
      int backTeethUpper = 0;
      int backTeethLower = 0;
      int backLips = 0;
      int tempBegIdx = 0;
      int tempNbElement = 0;
      Span<double> tempMP;
      Span<double> tempA;
      Span<double> tempB;
      int historyLen = inHigh.Length;
      int endIdx = historyLen - 1;
      if( historyLen > IndexMax + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inLow.Length != inHigh.Length ) {
         return RetCode.BadParam;
      }
      if( optInJawPeriod == int.MinValue ) {
         optInJawPeriod = 13;
      } else if( optInJawPeriod < 1 || optInJawPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInJawShift == int.MinValue ) {
         optInJawShift = 8;
      } else if( optInJawShift < 0 || optInJawShift > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInTeethPeriod == int.MinValue ) {
         optInTeethPeriod = 8;
      } else if( optInTeethPeriod < 1 || optInTeethPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInTeethShift == int.MinValue ) {
         optInTeethShift = 5;
      } else if( optInTeethShift < 0 || optInTeethShift > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInLipsPeriod == int.MinValue ) {
         optInLipsPeriod = 5;
      } else if( optInLipsPeriod < 1 || optInLipsPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInLipsShift == int.MinValue ) {
         optInLipsShift = 3;
      } else if( optInLipsShift < 0 || optInLipsShift > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx >= historyLen ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      if( historyLen < GatorLookback(optInJawPeriod, optInJawShift, optInTeethPeriod, optInTeethShift, optInLipsPeriod, optInLipsShift) + 1 ) {
         return RetCode.InsufficientHistory;
      }
      Span<double> sc_outUpper = outStride == 1 ? outUpper : new double[historyLen];
      Span<double> sc_outLower = outStride == 1 ? outLower : new double[historyLen];
      int lagPos0 = 0;
      int lagCap0 = 0;
      double[] lagBuf0 = [];
      int lagPos1 = 0;
      int lagCap1 = 0;
      double[] lagBuf1 = [];
      int lagPos2 = 0;
      int lagCap2 = 0;
      double[] lagBuf2 = [];
      int lagPos3 = 0;
      int lagCap3 = 0;
      double[] lagBuf3 = [];
      int lagD0_0 = 0;
      int lagD1_0 = 0;
      int lagD2_0 = 0;
      int lagD3_0 = 0;
      int lagNb0 = 0;
      int lagNb1 = 0;
      int lagNb2 = 0;
      int lagNb3 = 0;
      lookbackTotal = GatorLookback(optInJawPeriod, optInJawShift, optInTeethPeriod, optInTeethShift, optInLipsPeriod, optInLipsShift);
      /* Return before touching anything, so that an input which stops short of
       * endIdx is never read past its end.
       */
      if( lookbackTotal > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      backJaw = 0;
      backTeethUpper = 0;
      if( optInJawShift > optInTeethShift ) {
         backJaw = optInJawShift - optInTeethShift;
      } else {
         backTeethUpper = optInTeethShift - optInJawShift;
      }
      backTeethLower = 0;
      backLips = 0;
      if( optInTeethShift > optInLipsShift ) {
         backTeethLower = optInTeethShift - optInLipsShift;
      } else {
         backLips = optInLipsShift - optInTeethShift;
      }
      maxBack = backJaw + backTeethUpper;
      if( backTeethLower + backLips > maxBack ) {
         maxBack = backTeethLower + backLips;
      }
      mpStartIdx = startIdx - lookbackTotal;
      localStart = lookbackTotal;
      localEnd = endIdx - mpStartIdx;
      nbElement = endIdx - startIdx + 1;
      tempMP = new double[(int)((endIdx - mpStartIdx + 1) * 1)];
      tempA = new double[(int)((nbElement + maxBack) * 1)];
      tempB = new double[(int)((nbElement + maxBack) * 1)];
      /* Every price is consumed here, before any output is written: an output
       * may be aliased onto inHigh or inLow.
       */
      /* Sub-stream 0: medprice over `inHigh, inLow`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      MedpriceStream sub0 = MedpriceOpenAndFillInternal(inHigh, inLow, mpStartIdx, out tempBegIdx, out tempNbElement, tempMP);
      retCode = RetCode.Success;
      /* Each leg is its own rma call starting at its read-back bar and seeded at
       * its own lookback before that, so neither histogram moves when the line it
       * does not read changes; the teeth is therefore computed once per
       * histogram. A leg read back by `back` bars starts that many bars early, so
       * element i of its buffer is the bar the output's element i pairs it with.
       */
      /* Sub-stream 1: rma over `tempMP`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      int subLen1 = (localEnd) + 1;
      double[] subSrc1_0 = new double[subLen1];
      tempMP.Slice(0, subLen1).CopyTo(subSrc1_0);
      RmaStream sub1 = RmaOpenAndFillInternal(subSrc1_0, localStart - backJaw, optInJawPeriod, out tempBegIdx, out tempNbElement, tempA);
      retCode = RetCode.Success;
      lagNb0 = tempNbElement;
      /* Sub-stream 2: rma over `tempMP`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      int subLen2 = (localEnd) + 1;
      double[] subSrc2_0 = new double[subLen2];
      tempMP.Slice(0, subLen2).CopyTo(subSrc2_0);
      RmaStream sub2 = RmaOpenAndFillInternal(subSrc2_0, localStart - backTeethUpper, optInTeethPeriod, out tempBegIdx, out tempNbElement, tempB);
      retCode = RetCode.Success;
      lagNb1 = tempNbElement;
      if( nbElement < 1 ) {
         return RetCode.InsufficientHistory;
      }
      lagD0_0 = lagNb0 - nbElement;
      if( lagD0_0 < 0 || lagD0_0 > lagNb0 - 1 ) {
         return RetCode.InternalError;
      }
      lagD1_0 = lagNb1 - nbElement;
      if( lagD1_0 < 0 || lagD1_0 > lagNb1 - 1 ) {
         return RetCode.InternalError;
      }
      lagCap0 = lagD0_0;
      lagBuf0 = new double[Math.Max(lagCap0, 1)];
      for( int lagI0 = 0; lagI0 < lagCap0; lagI0++ ) {
         lagBuf0[lagI0] = tempA[lagNb0 - lagCap0 + lagI0];
      }
      lagPos0 = 0;
      lagCap1 = lagD1_0;
      lagBuf1 = new double[Math.Max(lagCap1, 1)];
      for( int lagI1 = 0; lagI1 < lagCap1; lagI1++ ) {
         lagBuf1[lagI1] = tempB[lagNb1 - lagCap1 + lagI1];
      }
      lagPos1 = 0;
      for( i = 0; i < nbElement; i += 1 ) {
         sc_outUpper[i] = Math.Abs(tempA[i] - tempB[i]);
      }
      /* Sub-stream 3: rma over `tempMP`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      int subLen3 = (localEnd) + 1;
      double[] subSrc3_0 = new double[subLen3];
      tempMP.Slice(0, subLen3).CopyTo(subSrc3_0);
      RmaStream sub3 = RmaOpenAndFillInternal(subSrc3_0, localStart - backTeethLower, optInTeethPeriod, out tempBegIdx, out tempNbElement, tempA);
      retCode = RetCode.Success;
      lagNb2 = tempNbElement;
      /* Sub-stream 4: rma over `tempMP`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      int subLen4 = (localEnd) + 1;
      double[] subSrc4_0 = new double[subLen4];
      tempMP.Slice(0, subLen4).CopyTo(subSrc4_0);
      RmaStream sub4 = RmaOpenAndFillInternal(subSrc4_0, localStart - backLips, optInLipsPeriod, out tempBegIdx, out tempNbElement, tempB);
      retCode = RetCode.Success;
      lagNb3 = tempNbElement;
      /* A zero spread must come out +0.0. Keep the select: gcc folds the literal
       * 0.0 - fabs(x) into -fabs(x), which is -0.0 there.
       */
      if( nbElement < 1 ) {
         return RetCode.InsufficientHistory;
      }
      lagD2_0 = lagNb2 - nbElement;
      if( lagD2_0 < 0 || lagD2_0 > lagNb2 - 1 ) {
         return RetCode.InternalError;
      }
      lagD3_0 = lagNb3 - nbElement;
      if( lagD3_0 < 0 || lagD3_0 > lagNb3 - 1 ) {
         return RetCode.InternalError;
      }
      lagCap2 = lagD2_0;
      lagBuf2 = new double[Math.Max(lagCap2, 1)];
      for( int lagI2 = 0; lagI2 < lagCap2; lagI2++ ) {
         lagBuf2[lagI2] = tempA[lagNb2 - lagCap2 + lagI2];
      }
      lagPos2 = 0;
      lagCap3 = lagD3_0;
      lagBuf3 = new double[Math.Max(lagCap3, 1)];
      for( int lagI3 = 0; lagI3 < lagCap3; lagI3++ ) {
         lagBuf3[lagI3] = tempB[lagNb3 - lagCap3 + lagI3];
      }
      lagPos3 = 0;
      for( i = 0; i < nbElement; i += 1 ) {
         sc_outLower[i] = (tempA[i] < tempB[i]) ? tempA[i] - tempB[i] : tempB[i] - tempA[i];
      }
      outBegIdx = startIdx;
      outNBElement = nbElement;
      /* Capture the live producer state + sub handles. */
      if( outNBElement < 1 ) {
         return RetCode.InsufficientHistory;
      }
      sp.optInJawPeriod = optInJawPeriod;
      sp.optInJawShift = optInJawShift;
      sp.optInTeethPeriod = optInTeethPeriod;
      sp.optInTeethShift = optInTeethShift;
      sp.optInLipsPeriod = optInLipsPeriod;
      sp.optInLipsShift = optInLipsShift;
      sp.sub0 = sub0;
      sp.sub1 = sub1;
      sp.sub2 = sub2;
      sp.sub3 = sub3;
      sp.sub4 = sub4;
      sp.lagPos0 = lagPos0;
      sp.lagCap0 = lagCap0;
      sp.lagBuf0 = lagBuf0;
      sp.lagPos1 = lagPos1;
      sp.lagCap1 = lagCap1;
      sp.lagBuf1 = lagBuf1;
      sp.lagPos2 = lagPos2;
      sp.lagCap2 = lagCap2;
      sp.lagBuf2 = lagBuf2;
      sp.lagPos3 = lagPos3;
      sp.lagCap3 = lagCap3;
      sp.lagBuf3 = lagBuf3;
      sp.cur_outUpper = sc_outUpper[outNBElement - 1];
      sp.cur_outLower = sc_outLower[outNBElement - 1];
      return RetCode.Success;
   }

   /* GatorOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal GatorStream GatorOpenAndFillInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int startIdx, int optInJawPeriod, int optInJawShift, int optInTeethPeriod, int optInTeethShift, int optInLipsPeriod, int optInLipsShift, out int outBegIdx, out int outNBElement, Span<double> outUpper, Span<double> outLower )
   {
      GatorStream sp = new GatorStream(this);
      RetCode retCode = GatorOpenImpl(sp, inHigh, inLow, startIdx, optInJawPeriod, optInJawShift, optInTeethPeriod, optInTeethShift, optInLipsPeriod, optInLipsShift, out outBegIdx, out outNBElement, outUpper, outLower, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("GATOR", "openAndFill", nameof(inHigh), inHigh.Length, startIdx, GatorLookback(optInJawPeriod, optInJawShift, optInTeethPeriod, optInTeethShift, optInLipsPeriod, optInLipsShift));
      }
      throw StreamFailure("GATOR", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind GatorOpen (composition seam). */
   internal GatorStream GatorOpenInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int startIdx, int optInJawPeriod, int optInJawShift, int optInTeethPeriod, int optInTeethShift, int optInLipsPeriod, int optInLipsShift )
   {
      GatorStream sp = new GatorStream(this);
      double[] sink_outUpper = new double[1];
      double[] sink_outLower = new double[1];
      RetCode retCode = GatorOpenImpl(sp, inHigh, inLow, startIdx, optInJawPeriod, optInJawShift, optInTeethPeriod, optInTeethShift, optInLipsPeriod, optInLipsShift, out int outBegIdx, out int outNBElement, sink_outUpper, sink_outLower, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("GATOR", "open", nameof(inHigh), inHigh.Length, startIdx, GatorLookback(optInJawPeriod, optInJawShift, optInTeethPeriod, optInTeethShift, optInLipsPeriod, optInLipsShift));
      }
      throw StreamFailure("GATOR", "open", retCode);
   }

   /// <summary>Open a live <c>GATOR</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="GatorStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>GATOR</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>GatorLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>GatorOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInJawPeriod">As in the batch call; see <see cref="GatorLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInJawShift">As in the batch call; see <see cref="GatorLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInTeethPeriod">As in the batch call; see <see cref="GatorLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInTeethShift">As in the batch call; see <see cref="GatorLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInLipsPeriod">As in the batch call; see <see cref="GatorLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInLipsShift">As in the batch call; see <see cref="GatorLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>GatorLookback(...) + 1</c> bars, an empty
   /// one included — which is what a null array becomes, since a span cannot be
   /// null.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is longer than <see cref="Core.IndexMax"/> + 1, the one index
   /// fault an opener can have (rule rS2).</exception>
   public GatorStream GatorOpen( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int optInJawPeriod, int optInJawShift, int optInTeethPeriod, int optInTeethShift, int optInLipsPeriod, int optInLipsShift )
   {
      if( inHigh.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "GATOR open: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( !inHigh.IsEmpty ) {
         if( inLow.IsEmpty ) throw new TALibArgumentException("GATOR open: inLow is empty", nameof(inLow), RetCode.BadParam);
      }
      RequireHistoryLength("GATOR", "open", "inLow", inLow.Length, inHigh.Length);
      return GatorOpenInternal(inHigh, inLow, 0, optInJawPeriod, optInJawShift, optInTeethPeriod, optInTeethShift, optInLipsPeriod, optInLipsShift);
   }

   /// <summary><c>GatorOpen</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>GATOR</c> produces over
   /// the same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - GatorLookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="GatorStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInJawPeriod">As in the batch call; see <see cref="GatorLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInJawShift">As in the batch call; see <see cref="GatorLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInTeethPeriod">As in the batch call; see <see cref="GatorLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInTeethShift">As in the batch call; see <see cref="GatorLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInLipsPeriod">As in the batch call; see <see cref="GatorLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInLipsShift">As in the batch call; see <see cref="GatorLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outUpper">Gap between the Jaw and the Teeth, zero or above. Must hold at least
   /// <c>historyLen - GatorLookback(...)</c> values.</param>
   /// <param name="outLower">Gap between the Teeth and the Lips, zero or below. Must hold at least
   /// <c>historyLen - GatorLookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>GatorLookback(...) + 1</c> bars, an empty
   /// one included — which is what a null array becomes, since a span cannot be
   /// null.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is longer than <see cref="Core.IndexMax"/> + 1, the one index
   /// fault an opener can have (rule rS2).</exception>
   public GatorStream GatorOpenAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int optInJawPeriod, int optInJawShift, int optInTeethPeriod, int optInTeethShift, int optInLipsPeriod, int optInLipsShift, Span<double> outUpper, Span<double> outLower )
   {
      if( inHigh.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "GATOR openAndFill: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( !inHigh.IsEmpty ) {
         if( inLow.IsEmpty ) throw new TALibArgumentException("GATOR openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      }
      int guardOutLen = OpenFillCount("GATOR", "openAndFill", inHigh.Length, GatorLookback(optInJawPeriod, optInJawShift, optInTeethPeriod, optInTeethShift, optInLipsPeriod, optInLipsShift));
      RequireHistoryLength("GATOR", "openAndFill", "inLow", inLow.Length, inHigh.Length);
      RequireFillLength("GATOR", "openAndFill", "outUpper", outUpper.Length, guardOutLen);
      RequireFillLength("GATOR", "openAndFill", "outLower", outLower.Length, guardOutLen);
      if( SameBuffer(outUpper, inHigh) || SameBuffer(outUpper, inLow) || SameBuffer(outLower, inHigh) || SameBuffer(outLower, inLow) || SameBuffer(outUpper, outLower) ) {
         throw StreamFailure("GATOR", "openAndFill", RetCode.BadParam);
      }
      if( guardOutLen > 0 && ( outUpper.Overlaps(inHigh) || outUpper.Overlaps(inLow) || outLower.Overlaps(inHigh) || outLower.Overlaps(inLow) || OutputsAlias(outUpper, outLower) ) ) {
         throw StreamFailure("GATOR", "openAndFill", RetCode.BadParam);
      }
      return GatorOpenAndFillInternal(inHigh, inLow, 0, optInJawPeriod, optInJawShift, optInTeethPeriod, optInTeethShift, optInLipsPeriod, optInLipsShift, out _, out _, outUpper, outLower);
   }
