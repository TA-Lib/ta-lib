         this.lagCap0 = other.lagCap0;
         this.lagBuf0 = new double[other.lagBuf0.Length];
         Array.Copy( other.lagBuf0, this.lagBuf0, other.lagBuf0.Length );
         this.lagPos1 = other.lagPos1;
         this.lagCap1 = other.lagCap1;
         this.lagBuf1 = new double[other.lagBuf1.Length];
         Array.Copy( other.lagBuf1, this.lagBuf1, other.lagBuf1.Length );
         this.lagPos2 = other.lagPos2;
         this.lagCap2 = other.lagCap2;
         this.lagBuf2 = new double[other.lagBuf2.Length];
         Array.Copy( other.lagBuf2, this.lagBuf2, other.lagBuf2.Length );
         this.lagPos3 = other.lagPos3;
         this.lagCap3 = other.lagCap3;
         this.lagBuf3 = new double[other.lagBuf3.Length];
         Array.Copy( other.lagBuf3, this.lagBuf3, other.lagBuf3.Length );
         this.sub0 = new MedpriceStream(other.sub0);
         this.sub1 = new RmaStream(other.sub1);
         this.sub2 = new RmaStream(other.sub2);
         this.sub3 = new RmaStream(other.sub3);
         this.sub4 = new RmaStream(other.sub4);
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
