   /// <summary>A live <c>MEDIAN</c> stream: one value per closed bar, bit-identical to
   /// <c>MEDIAN</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.MedianOpen"/>. There is no close and nothing to
   /// dispose — the handle is ordinary managed state, and an unreferenced handle
   /// is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class MedianStream
   {
      internal Core core;
      internal int optInTimePeriod;
      internal int lookbackTotal;
      internal int lowerIdx;
      internal int upperIdx;
      internal int ring_Idx;
      internal int maxIdx_ring;
      internal int sorted_Idx;
      internal int maxIdx_sorted;
      internal int cbSize_ring;
      internal double[] cb_ring = [];
      internal int cbSize_sorted;
      internal double[] cb_sorted = [];
      internal double cur_outReal;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal MedianStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Median</c> reports over the same bars: the opener sets
      /// it to <c>(lookback, historyLen - lookback)</c>, every accepted
      /// <c>Update</c> adds one to the count — a rejected one changes nothing, and
      /// neither does <c>Peek</c> — and <c>Clone</c> carries it verbatim. A plain
      /// <c>Open</c> hands back only the last value, a subset of this range,
      /// because the caller chose not to take the fill.</para>
      /// <para>The last bar it can reach is <see cref="Core.MaxIndex"/>; past that
      /// <c>Update</c> and <c>Advance</c> throw.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      /// <summary>Count one bar this stream was not fed: <see cref="OutRange"/> advances by
      /// one and nothing else moves.</summary>
      /// <remarks>
      /// <para><see cref="Value"/> keeps answering the previous output, which is this
      /// bar's output too. For a bar the caller leaves out: one an <c>Update</c>
      /// rejected and that will not be re-fed, or a session with no print. Without
      /// it two handles on one feed drift a bar apart when only one of them skips.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.MaxIndex"/>, the last one the batch tier
      /// can address and the last this handle will count. <c>Update</c> throws the
      /// same there.</para>
      /// </remarks>
      public void Advance()
      {
         if( outRangeBegIdx + outRangeCount > Core.MaxIndex )
            throw Core.StreamFailure("MEDIAN", "advance", RetCode.OutOfRangeEndIndex);
         outRangeCount++;
      }

      internal MedianStream( MedianStream other )
      {
         this.core = other.core;
         this.optInTimePeriod = other.optInTimePeriod;
         this.lookbackTotal = other.lookbackTotal;
         this.lowerIdx = other.lowerIdx;
         this.upperIdx = other.upperIdx;
         this.ring_Idx = other.ring_Idx;
         this.maxIdx_ring = other.maxIdx_ring;
         this.sorted_Idx = other.sorted_Idx;
         this.maxIdx_sorted = other.maxIdx_sorted;
         this.cbSize_ring = other.cbSize_ring;
         this.cb_ring = new double[other.cb_ring.Length];
         Array.Copy( other.cb_ring, this.cb_ring, other.cb_ring.Length );
         this.cbSize_sorted = other.cbSize_sorted;
         this.cb_sorted = new double[other.cb_sorted.Length];
         Array.Copy( other.cb_sorted, this.cb_sorted, other.cb_sorted.Length );
         this.cur_outReal = other.cur_outReal;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Allocates nothing — neither handle state nor a return value.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so nothing moves — <see cref="OutRange"/> included — and
      /// <see cref="Value"/> still answers the previous value. Re-feed the bar when
      /// a corrected value arrives, or call <see cref="Advance"/> to count it and
      /// carry on; two handles on one feed drift a bar apart if neither happens.
      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.MaxIndex"/>, which no re-feed clears: the
      /// handle has run out of index domain and only a shorter history can start a
      /// new one.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inReal )
      {
         if( outRangeBegIdx + outRangeCount > Core.MaxIndex )
            throw Core.StreamFailure("MEDIAN", "update", RetCode.OutOfRangeEndIndex);
         if( !double.IsFinite(inReal) ) throw Core.StreamFailure("MEDIAN", "update", RetCode.BadParam);
         core.MedianStepImpl(this, inReal);
         outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>Its cost does not grow with the period.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.MaxIndex"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public double Peek( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.StreamFailure("MEDIAN", "peek", RetCode.BadParam);
         MedianStream sp = this;
         double newValue = 0.0;
         double result = 0.0;
         double lower = 0.0;
         double upper = 0.0;
         int pos = 0;
         double cur_outReal = 0.0;
         newValue = inReal;
         /* `sorted` holds the window's other optInTimePeriod-1 values and `pos` is
          * where the incoming one belongs, so the full window is
          * sorted[0..pos-1], newValue, sorted[pos..]. The k-th of it is read
          * without materialising it.
          */
         pos = 0;
         while( pos < sp.lookbackTotal && sp.cb_sorted[pos] <= newValue ) {
            pos += 1;
         }
         if( sp.lowerIdx < pos ) {
            lower = sp.cb_sorted[sp.lowerIdx];
         } else if( sp.lowerIdx == pos ) {
            lower = newValue;
         } else {
            lower = sp.cb_sorted[sp.lowerIdx - 1];
         }
         if( sp.upperIdx < pos ) {
            upper = sp.cb_sorted[sp.upperIdx];
         } else if( sp.upperIdx == pos ) {
            upper = newValue;
         } else {
            upper = sp.cb_sorted[sp.upperIdx - 1];
         }
         /* At odd optInTimePeriod the two ordinals are the same slot, and the
          * branch returns that read untouched. Writing it as (v + v) / 2.0
          * instead would be exact for every value this library is ever handed --
          * doubling moves the exponent with the mantissa untouched and halving
          * moves it back -- but it overflows to +/-inf above DBL_MAX/2, and this
          * function does not declare nan_inf_output. The branch costs nothing:
          * the condition is loop-invariant.
          *
          * At even optInTimePeriod the mean of the two central values is the
          * universal convention (NumPy, R, scipy, Excel). Dividing by 2.0 and
          * multiplying by 0.5 give the same double, so that spelling is not a
          * variant; the sum itself can still overflow on inputs near DBL_MAX,
          * which is exactly what NumPy does with them too.
          */
         if( sp.lowerIdx == sp.upperIdx ) {
            result = lower;
         } else {
            result = (lower + upper) / 2.0;
         }
         cur_outReal = result;
         return cur_outReal;
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public MedianStream Clone()
      {
         return new MedianStream(this);
      }
   }

   internal void MedianStepImpl( MedianStream sp, double inReal )
   {
      double newValue = 0.0;
      double oldValue = 0.0;
      double result = 0.0;
      double lower = 0.0;
      double upper = 0.0;
      int j = 0;
      int pos = 0;
      newValue = inReal;
      /* `sorted` holds the window's other optInTimePeriod-1 values and `pos` is
       * where the incoming one belongs, so the full window is
       * sorted[0..pos-1], newValue, sorted[pos..]. The k-th of it is read
       * without materialising it.
       */
      pos = 0;
      while( pos < sp.lookbackTotal && sp.cb_sorted[pos] <= newValue ) {
         pos += 1;
      }
      if( sp.lowerIdx < pos ) {
         lower = sp.cb_sorted[sp.lowerIdx];
      } else if( sp.lowerIdx == pos ) {
         lower = newValue;
      } else {
         lower = sp.cb_sorted[sp.lowerIdx - 1];
      }
      if( sp.upperIdx < pos ) {
         upper = sp.cb_sorted[sp.upperIdx];
      } else if( sp.upperIdx == pos ) {
         upper = newValue;
      } else {
         upper = sp.cb_sorted[sp.upperIdx - 1];
      }
      /* At odd optInTimePeriod the two ordinals are the same slot, and the
       * branch returns that read untouched. Writing it as (v + v) / 2.0
       * instead would be exact for every value this library is ever handed --
       * doubling moves the exponent with the mantissa untouched and halving
       * moves it back -- but it overflows to +/-inf above DBL_MAX/2, and this
       * function does not declare nan_inf_output. The branch costs nothing:
       * the condition is loop-invariant.
       *
       * At even optInTimePeriod the mean of the two central values is the
       * universal convention (NumPy, R, scipy, Excel). Dividing by 2.0 and
       * multiplying by 0.5 give the same double, so that spelling is not a
       * variant; the sum itself can still overflow on inputs near DBL_MAX,
       * which is exactly what NumPy does with them too.
       */
      if( sp.lowerIdx == sp.upperIdx ) {
         result = lower;
      } else {
         result = (lower + upper) / 2.0;
      }
      sp.cur_outReal = result;
      /* Shifting only the strictly greater entries leaves equal values in
       * insertion order, which is age order -- that is what lets the delete
       * below evict the oldest of a run by value alone, with no slot array.
       *
       * The order within a run of equal values is NOT observable at the output,
       * and deliberately so: MEASURED, flipping this scan's `<=` to `<` (which
       * inserts at the front of a run instead of the back) leaves every value
       * bit-identical over 14820 windows on both a 7-distinct-value series and
       * a random walk. Equal members are interchangeable, which is precisely
       * why the removal can identify one by value and needs no identity.
       */
      j = sp.lookbackTotal;
      while( j > pos ) {
         sp.cb_sorted[j] = sp.cb_sorted[j - 1];
         j -= 1;
      }
      sp.cb_sorted[pos] = newValue;
      sp.cb_ring[sp.ring_Idx] = newValue;
      sp.ring_Idx = sp.ring_Idx + 1;
      if( sp.ring_Idx > sp.maxIdx_ring ) {
         sp.ring_Idx = 0;
      }
      oldValue = sp.cb_ring[sp.ring_Idx];
      j = 0;
      while( j < sp.lookbackTotal && sp.cb_sorted[j] < oldValue ) {
         j += 1;
      }
      while( j < sp.lookbackTotal ) {
         sp.cb_sorted[j] = sp.cb_sorted[j + 1];
         j += 1;
      }
   }

   private RetCode MedianOpenImpl( MedianStream sp, ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double newValue = 0;
      double oldValue = 0;
      double result = 0;
      double lower = 0;
      double upper = 0;
      int lookbackTotal = 0;
      int outIdx = 0;
      int i = 0;
      int j = 0;
      int pos = 0;
      int nbSorted = 0;
      int lowerIdx = 0;
      int upperIdx = 0;
      double[] ring = [];
      int ring_Idx = 0;
      int maxIdx_ring = (30)-1;
      double[] sorted = [];
      int sorted_Idx = 0;
      int maxIdx_sorted = (30)-1;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MaxIndex + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 30;
      } else if( optInTimePeriod < 2 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      /* The window is carried twice: "ring" by age, "sorted" by value. Both are
       * hand-written here as they are in percentile.c, which is the precedent for
       * this shape -- a generator-derived ring does not carry the by-value copy.
       */
      lookbackTotal = optInTimePeriod - 1;
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      if( optInTimePeriod < 1 ) return RetCode.InternalError;
      ring = new double[optInTimePeriod];
      maxIdx_ring = (optInTimePeriod)-1;
      ring_Idx = 0;
      if( optInTimePeriod < 1 ) return RetCode.InternalError;
      sorted = new double[optInTimePeriod];
      maxIdx_sorted = (optInTimePeriod)-1;
      sorted_Idx = 0;
      /* The two central ordinals, zero-based over the full window. At odd
       * optInTimePeriod they are the same slot and the average below is the value
       * itself; at even optInTimePeriod they straddle the centre and the mean of
       * the two is the median. Computed once rather than per bar.
       */
      lowerIdx = (optInTimePeriod - 1) / 2;
      upperIdx = optInTimePeriod / 2;
      nbSorted = 0;
      i = startIdx - lookbackTotal;
      while( i < startIdx ) {
         newValue = inReal[i];
         j = nbSorted;
         while( j > 0 && sorted[j - 1] > newValue ) {
            sorted[j] = sorted[j - 1];
            j -= 1;
         }
         sorted[j] = newValue;
         nbSorted += 1;
         ring[ring_Idx] = newValue;
         i += 1;
         ring_Idx++;
         if( ring_Idx > maxIdx_ring ) { ring_Idx = 0; }
      }
      /* Both scratch buffers hold copies and inReal is never read below i, so
       * inReal and outReal may be the same buffer.
       *
       * Every buffer store sits BELOW the output store on purpose (percentile.c):
       * deriving the whole answer read-only above it is what lets the streaming
       * peek frame drop the state update rather than shadow a shift loop.
       */
      outIdx = 0;
      do {
         newValue = inReal[i];
         /* `sorted` holds the window's other optInTimePeriod-1 values and `pos` is
          * where the incoming one belongs, so the full window is
          * sorted[0..pos-1], newValue, sorted[pos..]. The k-th of it is read
          * without materialising it.
          */
         pos = 0;
         while( pos < lookbackTotal && sorted[pos] <= newValue ) {
            pos += 1;
         }
         if( lowerIdx < pos ) {
            lower = sorted[lowerIdx];
         } else if( lowerIdx == pos ) {
            lower = newValue;
         } else {
            lower = sorted[lowerIdx - 1];
         }
         if( upperIdx < pos ) {
            upper = sorted[upperIdx];
         } else if( upperIdx == pos ) {
            upper = newValue;
         } else {
            upper = sorted[upperIdx - 1];
         }
         /* At odd optInTimePeriod the two ordinals are the same slot, and the
          * branch returns that read untouched. Writing it as (v + v) / 2.0
          * instead would be exact for every value this library is ever handed --
          * doubling moves the exponent with the mantissa untouched and halving
          * moves it back -- but it overflows to +/-inf above DBL_MAX/2, and this
          * function does not declare nan_inf_output. The branch costs nothing:
          * the condition is loop-invariant.
          *
          * At even optInTimePeriod the mean of the two central values is the
          * universal convention (NumPy, R, scipy, Excel). Dividing by 2.0 and
          * multiplying by 0.5 give the same double, so that spelling is not a
          * variant; the sum itself can still overflow on inputs near DBL_MAX,
          * which is exactly what NumPy does with them too.
          */
         if( lowerIdx == upperIdx ) {
            result = lower;
         } else {
            result = (lower + upper) / 2.0;
         }
         outReal[outIdx * outStride] = result;
         outIdx += 1;
         /* Shifting only the strictly greater entries leaves equal values in
          * insertion order, which is age order -- that is what lets the delete
          * below evict the oldest of a run by value alone, with no slot array.
          *
          * The order within a run of equal values is NOT observable at the output,
          * and deliberately so: MEASURED, flipping this scan's `<=` to `<` (which
          * inserts at the front of a run instead of the back) leaves every value
          * bit-identical over 14820 windows on both a 7-distinct-value series and
          * a random walk. Equal members are interchangeable, which is precisely
          * why the removal can identify one by value and needs no identity.
          */
         j = lookbackTotal;
         while( j > pos ) {
            sorted[j] = sorted[j - 1];
            j -= 1;
         }
         sorted[pos] = newValue;
         ring[ring_Idx] = newValue;
         ring_Idx++;
         if( ring_Idx > maxIdx_ring ) { ring_Idx = 0; }
         oldValue = ring[ring_Idx];
         j = 0;
         while( j < lookbackTotal && sorted[j] < oldValue ) {
            j += 1;
         }
         while( j < lookbackTotal ) {
            sorted[j] = sorted[j + 1];
            j += 1;
         }
         i += 1;
      } while( i <= endIdx );
      outNBElement = outIdx;
      outBegIdx = startIdx;
      /* Capture the live batch state into the handle. */
      int capCb_ring = maxIdx_ring + 1;
      if( capCb_ring > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      int capCb_sorted = maxIdx_sorted + 1;
      if( capCb_sorted > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      sp.optInTimePeriod = optInTimePeriod;
      sp.lookbackTotal = lookbackTotal;
      sp.lowerIdx = lowerIdx;
      sp.upperIdx = upperIdx;
      sp.ring_Idx = ring_Idx;
      sp.maxIdx_ring = maxIdx_ring;
      sp.sorted_Idx = sorted_Idx;
      sp.maxIdx_sorted = maxIdx_sorted;
      sp.cbSize_ring = capCb_ring;
      sp.cb_ring = ring;
      sp.cbSize_sorted = capCb_sorted;
      sp.cb_sorted = sorted;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* MedianOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal MedianStream MedianOpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      MedianStream sp = new MedianStream(this);
      RetCode retCode = MedianOpenImpl(sp, inReal, startIdx, optInTimePeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("MEDIAN", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind MedianOpen (composition seam). */
   internal MedianStream MedianOpenInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod )
   {
      MedianStream sp = new MedianStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = MedianOpenImpl(sp, inReal, startIdx, optInTimePeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("MEDIAN", "open", retCode);
   }

   /// <summary>Open a live <c>MEDIAN</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="MedianStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>MEDIAN</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>MedianLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>MedianOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">The series to take the median of. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="MedianLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>MedianLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MaxIndex"/> + 1, the
   /// two index faults an opener can have (rules S1 and S2).</exception>
   public MedianStream MedianOpen( ReadOnlySpan<double> inReal, int optInTimePeriod )
   {
      if( inReal.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "MEDIAN open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MaxIndex + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "MEDIAN open: history is longer than MaxIndex + 1", RetCode.OutOfRangeEndIndex);
      return MedianOpenInternal(inReal, 0, optInTimePeriod);
   }

   /// <summary><c>MedianOpen</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>MEDIAN</c> produces over
   /// the same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - MedianLookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="MedianStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">The series to take the median of. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="MedianLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Median of the trailing window. Must hold at least <c>historyLen -
   /// MedianLookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>MedianLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MaxIndex"/> + 1, the
   /// two index faults an opener can have (rules S1 and S2).</exception>
   public MedianStream MedianOpenAndFill( ReadOnlySpan<double> inReal, int optInTimePeriod, Span<double> outReal )
   {
      if( inReal.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "MEDIAN openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MaxIndex + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "MEDIAN openAndFill: history is longer than MaxIndex + 1", RetCode.OutOfRangeEndIndex);
      int guardOutLen = OpenFillCount("MEDIAN", "openAndFill", inReal.Length, MedianLookback(optInTimePeriod));
      RequireFillLength("MEDIAN", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( outReal.Overlaps(inReal) ) {
         throw StreamFailure("MEDIAN", "openAndFill", RetCode.BadParam);
      }
      return MedianOpenAndFillInternal(inReal, 0, optInTimePeriod, out _, out _, outReal);
   }
