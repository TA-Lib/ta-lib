      int guardOutLen = guardStart < 0 || guardStart > endIdx ? 0 : endIdx - guardStart + 1;
      RequireLength("MEDIAN", "inReal", inReal.Length, guardInLen);
      RequireLength("MEDIAN", "outReal", outReal.Length, guardOutLen);
      RetCode retCode = MedianImpl(startIdx, endIdx, inReal, optInTimePeriod, out int outBegIdx, out int outNBElement, outReal);
      if( retCode != RetCode.Success ) {
         throw Failure("MEDIAN", retCode);
      }
      return new OutRange(outBegIdx, outNBElement);
   }
