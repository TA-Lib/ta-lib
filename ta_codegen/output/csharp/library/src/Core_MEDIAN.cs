   /// never be the same span: there is no in-place case to allow, and any
   /// overlap of their byte ranges is rejected.</description></item>
   /// </list>
   /// </exception>
   /// <seealso cref="Core.Percentile(int, int, ReadOnlySpan{double}, int, double, Span{double})"/>
   /// <seealso cref="Core.Sma(int, int, ReadOnlySpan{double}, int, Span{double})"/>
   /// <seealso cref="Core.Medprice(int, int, ReadOnlySpan{double}, ReadOnlySpan{double}, Span{double})"/>
   public OutRange Median( int startIdx,
                           int endIdx,
                           ReadOnlySpan<float> inReal,
                           int optInTimePeriod,
                           Span<double> outReal )
   {
      int guardStart = ClampedStart(startIdx, endIdx, MedianLookback(optInTimePeriod));
      int guardInLen = guardStart < 0 ? 0 : endIdx + 1;
      int guardOutLen = guardStart < 0 || guardStart > endIdx ? 0 : endIdx - guardStart + 1;
      RequireLength("MEDIAN", "inReal", inReal.Length, guardInLen);
      RequireLength("MEDIAN", "outReal", outReal.Length, guardOutLen);
      RetCode retCode = MedianImpl(startIdx, endIdx, inReal, optInTimePeriod, out int outBegIdx, out int outNBElement, outReal);
      if( retCode != RetCode.Success ) {
         throw Failure("MEDIAN", retCode);
      }
      return new OutRange(outBegIdx, outNBElement);
   }
