   /// <remarks>
   /// <para>Open with <see cref="Core.EmvOpen"/>. There is no close and nothing to
   /// dispose — the handle is ordinary managed state, and an unreferenced handle
   /// is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class EmvStream
   {
      internal Core core;
      internal int optInTimePeriod;
      internal double optInVolumeDivisor;
      internal double periodTotal;
      internal double prevMid;
      internal int rawBuffer_Idx;
      internal int maxIdx_rawBuffer;
      internal int cbSize_rawBuffer;
      internal double[] cb_rawBuffer = [];
      internal double cur_outReal;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal EmvStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Emv</c> reports over the same bars: the opener sets it
      /// to <c>(lookback, historyLen - lookback)</c>, every accepted <c>Update</c>
      /// adds one to the count — a rejected one changes nothing, and neither does
      /// <c>Peek</c> — and <c>Clone</c> carries it verbatim. A plain <c>Open</c>
      /// hands back only the last value, a subset of this range, because the caller
      /// chose not to take the fill.</para>
      /// <para>The last bar it can reach is <see cref="Core.IndexMax"/>; past that
      /// <c>Update</c> and <c>Advance</c> throw.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      /// <summary>Count one bar this stream was not fed: <see cref="OutRange"/> advances by
      /// one and nothing else moves.</summary>
      /// <remarks>
      /// <para><see cref="Value"/> keeps answering the previous output, which is this
      /// bar's output too. For a bar the caller leaves out: one an <c>Update</c>
      /// rejected and that will not be re-fed, or a session with no print. Without
      /// it two handles on one feed drift a bar apart when only one of them skips.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, the last one the batch tier
      /// can address and the last this handle will count. <c>Update</c> throws the
      /// same there.</para>
      /// </remarks>
      public void Advance()
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("EMV", "advance", RetCode.OutOfRangeEndIndex);
         outRangeCount++;
      }

      internal EmvStream( EmvStream other )
      {
         this.core = other.core;
         this.optInTimePeriod = other.optInTimePeriod;
         this.optInVolumeDivisor = other.optInVolumeDivisor;
         this.periodTotal = other.periodTotal;
         this.prevMid = other.prevMid;
         this.rawBuffer_Idx = other.rawBuffer_Idx;
         this.maxIdx_rawBuffer = other.maxIdx_rawBuffer;
         this.cbSize_rawBuffer = other.cbSize_rawBuffer;
         this.cb_rawBuffer = new double[other.cb_rawBuffer.Length];
         Array.Copy( other.cb_rawBuffer, this.cb_rawBuffer, other.cb_rawBuffer.Length );
         this.cur_outReal = other.cur_outReal;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so nothing moves — <see cref="OutRange"/> included — and
      /// <see cref="Value"/> still answers the previous value. Re-feed the bar when
      /// a corrected value arrives, or call <see cref="Advance"/> to count it and
      /// carry on; two handles on one feed drift a bar apart if neither happens.
      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, which no re-feed clears: the
      /// handle has run out of index domain and only a shorter history can start a
      /// new one.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inVolume">This bar's volume.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inHigh, double inLow, double inVolume )
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("EMV", "update", RetCode.OutOfRangeEndIndex);
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inVolume) ) throw Core.NonFiniteBar("EMV", "update", !double.IsFinite(inHigh) ? nameof(inHigh) : !double.IsFinite(inLow) ? nameof(inLow) : nameof(inVolume));
         core.EmvStepImpl(this, inHigh, inLow, inVolume);
         outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.IndexMax"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inVolume">This bar's volume.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public double Peek( double inHigh, double inLow, double inVolume )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inVolume) ) throw Core.NonFiniteBar("EMV", "peek", !double.IsFinite(inHigh) ? nameof(inHigh) : !double.IsFinite(inLow) ? nameof(inLow) : nameof(inVolume));
         EmvStream sp = this;
         double mid = 0.0;
         double range = 0.0;
         double boxRatio = 0.0;
         double raw = 0.0;
         double tempReal = 0.0;
         double cur_outReal = 0.0;
         double periodTotal = sp.periodTotal;
         double prevMid = sp.prevMid;
         int rawBuffer_Idx = sp.rawBuffer_Idx;
         int pkSlot0 = -1;
         double pkVal0 = 0.0;
         mid = (inHigh + inLow) / 2.0;
         range = inHigh - inLow;
         raw = 0.0;
         if( range != 0.0 ) {
            boxRatio = inVolume / sp.optInVolumeDivisor / range;
            if( boxRatio != 0.0 ) {
               raw = (mid - prevMid) / boxRatio;
            }
         }
         prevMid = mid;
         pkSlot0 = rawBuffer_Idx;
         pkVal0 = raw;
         periodTotal += raw;
         tempReal = periodTotal;
         rawBuffer_Idx = rawBuffer_Idx + 1;
         if( rawBuffer_Idx > sp.maxIdx_rawBuffer ) {
            rawBuffer_Idx = 0;
         }
         periodTotal -= (rawBuffer_Idx != pkSlot0) ? sp.cb_rawBuffer[rawBuffer_Idx] : pkVal0;
         cur_outReal = tempReal / (double)sp.optInTimePeriod;
         return cur_outReal;
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public EmvStream Clone()
      {
         return new EmvStream(this);
      }
   }

   private void EmvStepImpl( EmvStream sp, double inHigh, double inLow, double inVolume )
   {
      double mid = 0.0;
      double range = 0.0;
      double boxRatio = 0.0;
      double raw = 0.0;
      double tempReal = 0.0;
      mid = (inHigh + inLow) / 2.0;
      range = inHigh - inLow;
      raw = 0.0;
      if( range != 0.0 ) {
         boxRatio = inVolume / sp.optInVolumeDivisor / range;
         if( boxRatio != 0.0 ) {
            raw = (mid - sp.prevMid) / boxRatio;
         }
      }
      sp.prevMid = mid;
      sp.cb_rawBuffer[sp.rawBuffer_Idx] = raw;
      sp.periodTotal += raw;
      tempReal = sp.periodTotal;
      sp.rawBuffer_Idx = sp.rawBuffer_Idx + 1;
      if( sp.rawBuffer_Idx > sp.maxIdx_rawBuffer ) {
         sp.rawBuffer_Idx = 0;
      }
      sp.periodTotal -= sp.cb_rawBuffer[sp.rawBuffer_Idx];
      sp.cur_outReal = tempReal / (double)sp.optInTimePeriod;
   }

   private RetCode EmvOpenImpl( EmvStream sp, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inVolume, int startIdx, int optInTimePeriod, double optInVolumeDivisor, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double periodTotal = 0;
      double prevMid = 0;
      double mid = 0;
      double range = 0;
      double boxRatio = 0;
      double raw = 0;
      double tempReal = 0;
      int lookbackTotal = 0;
      int outIdx = 0;
      int i = 0;
      double[] rawBuffer = [];
      int rawBuffer_Idx = 0;
      int maxIdx_rawBuffer = (50)-1;
      int historyLen = inHigh.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > IndexMax + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inLow.Length != inHigh.Length || inVolume.Length != inHigh.Length ) {
         return RetCode.BadParam;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 14;
      } else if( optInTimePeriod < 1 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInVolumeDivisor == RealDefault ) {
         optInVolumeDivisor = 1e4;
      } else if( !(optInVolumeDivisor >= 1e0 && optInVolumeDivisor <= RealMax) ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      /* The one-bar values are kept in a ring rather than recomputed at the
       * trailing index: outReal may alias an input, and those bars may already
       * hold outputs.
       */
      lookbackTotal = EmvLookback(optInTimePeriod, optInVolumeDivisor);
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      if( optInTimePeriod < 1 ) return RetCode.InternalError;
      rawBuffer = new double[optInTimePeriod];
      maxIdx_rawBuffer = (optInTimePeriod)-1;
      rawBuffer_Idx = 0;
      /* Keep the operand order and sma.c's add / snapshot / subtract order: the
       * composite gate rebuilds this from MEDPRICE, MOM, SUB, DIV and SMA and
       * compares bitwise.
       *
       * The zero guards are exact != 0.0 tests, never TA_IS_ZERO: the output
       * scale follows the volume and the divisor, so no absolute band fits. A
       * nonzero range with a box ratio that underflows to 0 takes the guard too.
       */
      i = startIdx - lookbackTotal;
      prevMid = (inHigh[i] + inLow[i]) / 2.0;
      i = i + 1;
      periodTotal = 0.0;
      while( i < startIdx ) {
         mid = (inHigh[i] + inLow[i]) / 2.0;
         range = inHigh[i] - inLow[i];
         raw = 0.0;
         if( range != 0.0 ) {
            boxRatio = inVolume[i] / optInVolumeDivisor / range;
            if( boxRatio != 0.0 ) {
               raw = (mid - prevMid) / boxRatio;
            }
         }
         prevMid = mid;
         i = i + 1;
         rawBuffer[rawBuffer_Idx] = raw;
         periodTotal += raw;
         rawBuffer_Idx++;
         if( rawBuffer_Idx > maxIdx_rawBuffer ) { rawBuffer_Idx = 0; }
      }
      outIdx = 0;
      while( i <= endIdx ) {
         mid = (inHigh[i] + inLow[i]) / 2.0;
         range = inHigh[i] - inLow[i];
         raw = 0.0;
         if( range != 0.0 ) {
            boxRatio = inVolume[i] / optInVolumeDivisor / range;
            if( boxRatio != 0.0 ) {
               raw = (mid - prevMid) / boxRatio;
            }
         }
         prevMid = mid;
         i = i + 1;
         rawBuffer[rawBuffer_Idx] = raw;
         periodTotal += raw;
         tempReal = periodTotal;
         rawBuffer_Idx++;
         if( rawBuffer_Idx > maxIdx_rawBuffer ) { rawBuffer_Idx = 0; }
         periodTotal -= rawBuffer[rawBuffer_Idx];
         outReal[outIdx * outStride] = tempReal / (double)optInTimePeriod;
         outIdx = outIdx + 1;
      }
      outBegIdx = startIdx;
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      int capCb_rawBuffer = maxIdx_rawBuffer + 1;
      if( capCb_rawBuffer > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      sp.optInTimePeriod = optInTimePeriod;
      sp.optInVolumeDivisor = optInVolumeDivisor;
      sp.periodTotal = periodTotal;
      sp.prevMid = prevMid;
      sp.rawBuffer_Idx = rawBuffer_Idx;
      sp.maxIdx_rawBuffer = maxIdx_rawBuffer;
      sp.cbSize_rawBuffer = capCb_rawBuffer;
      sp.cb_rawBuffer = rawBuffer;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* EmvOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal EmvStream EmvOpenAndFillInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inVolume, int startIdx, int optInTimePeriod, double optInVolumeDivisor, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      EmvStream sp = new EmvStream(this);
      RetCode retCode = EmvOpenImpl(sp, inHigh, inLow, inVolume, startIdx, optInTimePeriod, optInVolumeDivisor, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("EMV", "openAndFill", nameof(inHigh), inHigh.Length, startIdx, EmvLookback(optInTimePeriod, optInVolumeDivisor));
      }
      throw StreamFailure("EMV", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind EmvOpen (composition seam). */
   internal EmvStream EmvOpenInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inVolume, int startIdx, int optInTimePeriod, double optInVolumeDivisor )
   {
      EmvStream sp = new EmvStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = EmvOpenImpl(sp, inHigh, inLow, inVolume, startIdx, optInTimePeriod, optInVolumeDivisor, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("EMV", "open", nameof(inHigh), inHigh.Length, startIdx, EmvLookback(optInTimePeriod, optInVolumeDivisor));
      }
      throw StreamFailure("EMV", "open", retCode);
   }

   /// <summary>Open a live <c>EMV</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="EmvStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>EMV</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>EmvLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>EmvOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inVolume">Volume of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="EmvLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInVolumeDivisor">As in the batch call; see <see cref="EmvLookback"/> for its default and
   /// range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>EmvLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public EmvStream EmvOpen( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inVolume, int optInTimePeriod, double optInVolumeDivisor )
   {
      if( inHigh.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "EMV open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "EMV open: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TALibArgumentException("EMV open: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inVolume.IsEmpty ) throw new TALibArgumentException("EMV open: inVolume is empty", nameof(inVolume), RetCode.BadParam);
      RequireHistoryLength("EMV", "open", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("EMV", "open", "inVolume", inVolume.Length, inHigh.Length);
      return EmvOpenInternal(inHigh, inLow, inVolume, 0, optInTimePeriod, optInVolumeDivisor);
   }

   /// <summary><c>EmvOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>EMV</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - EmvLookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="EmvStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inVolume">Volume of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="EmvLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInVolumeDivisor">As in the batch call; see <see cref="EmvLookback"/> for its default and
   /// range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <param name="outReal">Ease of Movement, averaged over the window. Must hold at least
   /// <c>historyLen - EmvLookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>EmvLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public EmvStream EmvOpenAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inVolume, int optInTimePeriod, double optInVolumeDivisor, Span<double> outReal )
   {
      if( inHigh.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "EMV openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "EMV openAndFill: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TALibArgumentException("EMV openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inVolume.IsEmpty ) throw new TALibArgumentException("EMV openAndFill: inVolume is empty", nameof(inVolume), RetCode.BadParam);
      int guardOutLen = OpenFillCount("EMV", "openAndFill", inHigh.Length, EmvLookback(optInTimePeriod, optInVolumeDivisor));
      RequireHistoryLength("EMV", "openAndFill", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("EMV", "openAndFill", "inVolume", inVolume.Length, inHigh.Length);
      RequireFillLength("EMV", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( outReal.Overlaps(inHigh) || outReal.Overlaps(inLow) || outReal.Overlaps(inVolume) ) {
         throw StreamFailure("EMV", "openAndFill", RetCode.BadParam);
      }
      return EmvOpenAndFillInternal(inHigh, inLow, inVolume, 0, optInTimePeriod, optInVolumeDivisor, out _, out _, outReal);
   }
