   {
      int guardStart = ClampedStart(startIdx, endIdx, MACDEXT_Lookback(optInFastPeriod, optInFastMAType, optInSlowPeriod, optInSlowMAType, optInSignalPeriod, optInSignalMAType));
      int guardInLen = guardStart < 0 ? 0 : endIdx + 1;
