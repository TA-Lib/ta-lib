   /// <param name="optInSignalMAType">MA type for the signal line (default 0 = SMA; values: 0=SMA, 1=EMA, 2=WMA,
   /// 3=DEMA, 4=TEMA, 5=TRIMA, 6=KAMA, 7=MAMA, 8=T3, 9=HMA, 10=DISABLED;
   /// <c>int.MinValue</c> selects the default).</param>
   /// <param name="outMACD">MACD line: fast MA minus slow MA. Must hold at least <c>endIdx - startIdx
   /// + 1</c> values.</param>
   /// <param name="outMACDSignal">Signal line: MA of the MACD line. Must hold at least <c>endIdx - startIdx
   /// + 1</c> values.</param>
   /// <param name="outMACDHist">Histogram: MACD minus signal. Must hold at least <c>endIdx - startIdx +
   /// 1</c> values.</param>
   /// <returns>The range written: <c>BegIdx</c> is the first bar with a value,
   /// <c>Count</c> how many were written.</returns>
   /// <exception cref="System.ArgumentOutOfRangeException"><c>startIdx</c> or <c>endIdx</c> is negative or above
   /// <see cref="Core.MAX_INDEX"/>, or <c>endIdx &lt; startIdx</c>.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or two outputs
   /// share one array.</exception>
   /// <exception cref="System.NullReferenceException">An input or output array is null. (Unlike the C library, the managed tier
   /// does not pre-validate nulls; the first array access throws.)</exception>
   public OutRange MACDEXT( int startIdx,
                            int endIdx,
                            float[] inReal,
                            int optInFastPeriod,
                            MAType optInFastMAType,
                            int optInSlowPeriod,
                            MAType optInSlowMAType,
                            int optInSignalPeriod,
                            MAType optInSignalMAType,
                            double[] outMACD,
                            double[] outMACDSignal,
                            double[] outMACDHist )
   {
      RetCode retCode = MACDEXT(startIdx, endIdx, inReal, optInFastPeriod, optInFastMAType, optInSlowPeriod, optInSlowMAType, optInSignalPeriod, optInSignalMAType, out int outBegIdx, out int outNBElement, outMACD, outMACDSignal, outMACDHist);
      if( retCode != RetCode.Success ) {
         throw Failure("MACDEXT", retCode);
      }
      return new OutRange(outBegIdx, outNBElement);
   }
