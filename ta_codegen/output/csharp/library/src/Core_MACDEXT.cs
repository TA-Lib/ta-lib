   /// <summary>One <c>MACDEXT</c> output set, in batch output order.</summary>
   /// <remarks>
   /// <para>Equality is the compiler-generated record-struct equality, which compares
   /// the components with <c>==</c>: <c>NaN</c> does not equal <c>NaN</c>, and
   /// <c>0.0</c> equals <c>-0.0</c>. That is deliberately <em>not</em> the Java
   /// <c>Value</c> contract, which compares bitwise — compare
   /// <see cref="System.BitConverter.DoubleToInt64Bits(double)"/> per component
   /// when bit-level identity is what you mean.</para>
   /// </remarks>
   /// <param name="MACD">MACD line: fast MA minus slow MA.</param>
   /// <param name="MACDSignal">Signal line: MA of the MACD line.</param>
   /// <param name="MACDHist">Histogram: MACD minus signal.</param>
   public readonly record struct MacdextValue( double MACD, double MACDSignal, double MACDHist );

   /// <summary>A live <c>MACDEXT</c> stream: one value per closed bar, bit-identical to
   /// <c>MACDEXT</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.MacdextOpen"/>. There is no close and nothing to
   /// dispose — the handle is ordinary managed state, and an unreferenced handle
   /// is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class MacdextStream
   {
      internal Core core;
      internal int optInFastPeriod;
      internal MAType optInFastMAType;
      internal int optInSlowPeriod;
      internal MAType optInSlowMAType;
      internal int optInSignalPeriod;
      internal MAType optInSignalMAType;
      internal double cur_outMACD;
      internal double cur_outMACDSignal;
      internal double cur_outMACDHist;
      internal MaStream sub0 = null!;
      internal MaStream sub1 = null!;
      internal MaStream sub2 = null!;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal MacdextStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Macdext</c> reports over the same bars: the opener sets
      /// it to <c>(lookback, historyLen - lookback)</c>, every <c>Update</c> adds
      /// one to the count — a non-finite bar is rejected but still counted, because
      /// the bar happened — <c>Peek</c> leaves it alone, and <c>Clone</c> carries
      /// it verbatim. A plain <c>Open</c> hands back only the last value, a subset
      /// of this range, because the caller chose not to take the fill.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      internal MacdextStream( MacdextStream other )
      {
         this.core = other.core;
         this.optInFastPeriod = other.optInFastPeriod;
         this.optInFastMAType = other.optInFastMAType;
         this.optInSlowPeriod = other.optInSlowPeriod;
         this.optInSlowMAType = other.optInSlowMAType;
         this.optInSignalPeriod = other.optInSignalPeriod;
         this.optInSignalMAType = other.optInSignalMAType;
         this.cur_outMACD = other.cur_outMACD;
         this.cur_outMACDSignal = other.cur_outMACDSignal;
         this.cur_outMACDHist = other.cur_outMACDHist;
         this.sub0 = new MaStream(other.sub0);
         this.sub1 = new MaStream(other.sub1);
         this.sub2 = new MaStream(other.sub2);
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Allocates nothing — neither handle state nor a return value.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so no state moves, <see cref="Value"/> still answers the previous value,
      /// and the stream stays usable — just carry on with the next bar.
      /// <see cref="OutRange"/> does advance: the bar happened, so it is counted,
      /// which keeps two handles fed the same series positionally aligned when only
      /// one of them rejects a bar. This is the one place the streaming tier is
      /// stricter than the batch API, which computes on whatever it is given: a
      /// handle retains its state, so a single non-finite bar would poison every
      /// later value it produces.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value at the bar just committed.</returns>
      public MacdextValue Update( double inReal )
      {
         if( !double.IsFinite(inReal) )
         {
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
            throw Core.StreamFailure("MACDEXT", "update", RetCode.BadParam);
         }
         core.MacdextStepImpl(this, inReal);
         if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         return new MacdextValue(cur_outMACD, cur_outMACDSignal, cur_outMACDHist);
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It copies nothing: the frame runs against this handle, reading its buffers
      /// and holding what the step would commit in locals. The cost does not grow
      /// with the period, and <c>Peek</c> never allocates.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>What <see cref="Update"/> would return for this bar.</returns>
      public MacdextValue Peek( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.StreamFailure("MACDEXT", "peek", RetCode.BadParam);
         MacdextStream sp = this;
         double cur_slowMABuffer = 0.0;
         double cur_fastMABuffer = 0.0;
         double cur_outMACDSignal = 0.0;
         double cur_outMACDHist = 0.0;
         double cur_outMACD = 0.0;
         /* Pipeline the new bar through the sub-streams (batch tail order). */
         cur_slowMABuffer = sp.sub0.Peek(inReal);
         cur_fastMABuffer = sp.sub1.Peek(inReal);
         /* Combine map (batch tail, per bar). */
         cur_fastMABuffer = cur_fastMABuffer - cur_slowMABuffer;
         cur_outMACDSignal = sp.sub2.Peek(cur_fastMABuffer);
         /* Combine map (batch tail, per bar). */
         cur_outMACDHist = cur_fastMABuffer - cur_outMACDSignal;
         cur_outMACD = cur_fastMABuffer;
         return new MacdextValue(cur_outMACD, cur_outMACDSignal, cur_outMACDHist);
      }

      /// <summary>Commit <c>n</c> closed bars and write their <c>n</c> values, in one call.</summary>
      /// <remarks>
      /// <para>Exactly <c>n</c> back-to-back <see cref="Update"/> calls, with one set of
      /// argument checks instead of <c>n</c>. The outputs must hold at least
      /// <c>n</c> values and must not overlap an input or each other.</para>
      /// <para><see cref="OutRange"/> counts what this call took in, which is what makes
      /// a rejection readable: a non-finite bar <c>k</c> throws
      /// <see cref="System.ArgumentException"/> exactly as <see cref="Update"/>
      /// would, with the bars before <c>k</c> committed and written, bar <c>k</c>
      /// and everything after it not written, and the count advanced by <c>k +
      /// 1</c> — the committed bars plus the rejected one, so the last bar counted
      /// is the one that failed.</para>
      /// </remarks>
      /// <param name="inReal">Closed bars for <c>inReal</c>, oldest first.</param>
      /// <param name="outMACD">Receives one <c>outMACD</c> value per bar committed.</param>
      /// <param name="outMACDSignal">Receives one <c>outMACDSignal</c> value per bar committed.</param>
      /// <param name="outMACDHist">Receives one <c>outMACDHist</c> value per bar committed.</param>
      public void UpdateAndFill( ReadOnlySpan<double> inReal, Span<double> outMACD, Span<double> outMACDSignal, Span<double> outMACDHist )
      {
         int barCount = inReal.Length;
         if( outMACD.Length < barCount || outMACDSignal.Length < barCount || outMACDHist.Length < barCount || outMACD.Overlaps(inReal) || outMACDSignal.Overlaps(inReal) || outMACDHist.Overlaps(inReal) || outMACD.Overlaps(outMACDSignal) || outMACD.Overlaps(outMACDHist) || outMACDSignal.Overlaps(outMACDHist) ) throw Core.StreamFailure("MACDEXT", "updateAndFill", RetCode.BadParam);
         for( int i = 0; i < barCount; i++ )
         {
            if( !double.IsFinite(inReal[i]) )
            {
               if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
               throw Core.StreamFailure("MACDEXT", "updateAndFill", RetCode.BadParam);
            }
            core.MacdextStepImpl(this, inReal[i]);
            outMACD[i] = cur_outMACD;
            outMACDSignal[i] = cur_outMACDSignal;
            outMACDHist[i] = cur_outMACDHist;
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         }
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public MacdextValue Value => new MacdextValue(cur_outMACD, cur_outMACDSignal, cur_outMACDHist);

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public MacdextStream Clone()
      {
         return new MacdextStream(this);
      }
   }

   internal void MacdextStepImpl( MacdextStream sp, double inReal )
   {
      double cur_slowMABuffer = 0.0;
      double cur_fastMABuffer = 0.0;
      double cur_outMACDSignal = 0.0;
      double cur_outMACDHist = 0.0;
      /* Pipeline the new bar through the sub-streams (batch tail order). */
      cur_slowMABuffer = sp.sub0.Update(inReal);
      cur_fastMABuffer = sp.sub1.Update(inReal);
      /* Combine map (batch tail, per bar). */
      cur_fastMABuffer = cur_fastMABuffer - cur_slowMABuffer;
      cur_outMACDSignal = sp.sub2.Update(cur_fastMABuffer);
      /* Combine map (batch tail, per bar). */
      cur_outMACDHist = cur_fastMABuffer - cur_outMACDSignal;
      sp.cur_outMACD = cur_fastMABuffer;
      sp.cur_outMACDSignal = cur_outMACDSignal;
      sp.cur_outMACDHist = cur_outMACDHist;
   }

   private RetCode MacdextOpenImpl( MacdextStream sp, ReadOnlySpan<double> inReal, int startIdx, int optInFastPeriod, MAType optInFastMAType, int optInSlowPeriod, MAType optInSlowMAType, int optInSignalPeriod, MAType optInSignalMAType, out int outBegIdx, out int outNBElement, Span<double> outMACD, Span<double> outMACDSignal, Span<double> outMACDHist, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      Span<double> slowMABuffer;
      Span<double> fastMABuffer;
      RetCode retCode;
      int tempInteger = 0;
      int outBegIdx1 = 0;
      int outNbElement1 = 0;
      int outBegIdx2 = 0;
      int outNbElement2 = 0;
      int lookbackTotal = 0;
      int lookbackSignal = 0;
      int lookbackLargest = 0;
      int i = 0;
      MAType tempMAType;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInFastPeriod == int.MinValue ) {
         optInFastPeriod = 12;
      } else if( optInFastPeriod < 2 || optInFastPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( (int)optInFastMAType == int.MinValue || optInFastMAType == MAType.DEFAULT ) {
         optInFastMAType = MAType.SMA;
      } else if( (int)optInFastMAType < MATypes.Min || (int)optInFastMAType > MATypes.Max ) {
         return RetCode.BadParam;
      }
      if( optInSlowPeriod == int.MinValue ) {
         optInSlowPeriod = 26;
      } else if( optInSlowPeriod < 2 || optInSlowPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( (int)optInSlowMAType == int.MinValue || optInSlowMAType == MAType.DEFAULT ) {
         optInSlowMAType = MAType.SMA;
      } else if( (int)optInSlowMAType < MATypes.Min || (int)optInSlowMAType > MATypes.Max ) {
         return RetCode.BadParam;
      }
      if( optInSignalPeriod == int.MinValue ) {
         optInSignalPeriod = 9;
      } else if( optInSignalPeriod < 1 || optInSignalPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( (int)optInSignalMAType == int.MinValue || optInSignalMAType == MAType.DEFAULT ) {
         optInSignalMAType = MAType.SMA;
      } else if( (int)optInSignalMAType < MATypes.Min || (int)optInSignalMAType > MATypes.Max ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      if( historyLen < MACDEXT_Lookback(optInFastPeriod, optInFastMAType, optInSlowPeriod, optInSlowMAType, optInSignalPeriod, optInSignalMAType) + 1 ) {
         return RetCode.InsufficientHistory;
      }
      Span<double> sc_outMACD = outStride == 1 ? outMACD : new double[historyLen];
      Span<double> sc_outMACDSignal = outStride == 1 ? outMACDSignal : new double[historyLen];
      Span<double> sc_outMACDHist = outStride == 1 ? outMACDHist : new double[historyLen];
      /* Make sure slow is really slower than
       * the fast period! if not, swap...
       */
      if( optInSlowPeriod < optInFastPeriod ) {
         /* swap period */
         tempInteger = optInSlowPeriod;
         optInSlowPeriod = optInFastPeriod;
         optInFastPeriod = tempInteger;
         /* swap type */
         tempMAType = optInSlowMAType;
         optInSlowMAType = optInFastMAType;
         optInFastMAType = tempMAType;
      }
      /* Find the MA with the largest lookback */
      lookbackLargest = MA_Lookback(optInFastPeriod, optInFastMAType);
      tempInteger = MA_Lookback(optInSlowPeriod, optInSlowMAType);
      if( tempInteger > lookbackLargest ) {
         lookbackLargest = tempInteger;
      }
      /* Add the lookback needed for the signal line */
      lookbackSignal = MA_Lookback(optInSignalPeriod, optInSignalMAType);
      lookbackTotal = lookbackSignal + lookbackLargest;
      /* Move up the start index if there is not
       * enough initial data.
       */
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      /* Allocate intermediate buffer for fast/slow MA. */
      tempInteger = endIdx - startIdx + 1 + lookbackSignal;
      fastMABuffer = new double[(int)(tempInteger * 1)];
      slowMABuffer = new double[(int)(tempInteger * 1)];
      /* Calculate the slow MA.
       *
       * Move back the startIdx to get enough data
       * for the signal period. That way, once the
       * signal calculation is done, all the output
       * will start at the requested 'startIdx'.
       */
      tempInteger = startIdx - lookbackSignal;
      /* Sub-stream 0: ma over `inReal`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      MaStream sub0 = MaOpenAndFillInternal(inReal, tempInteger, optInSlowPeriod, optInSlowMAType, out outBegIdx1, out outNbElement1, slowMABuffer);
      retCode = RetCode.Success;
      /* Calculate the fast MA. */
      /* Sub-stream 1: ma over `inReal`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      MaStream sub1 = MaOpenAndFillInternal(inReal, tempInteger, optInFastPeriod, optInFastMAType, out outBegIdx2, out outNbElement2, fastMABuffer);
      retCode = RetCode.Success;
      /* Parano tests. Will be removed eventually. */
      if( outBegIdx1 != tempInteger || outBegIdx2 != tempInteger || outNbElement1 != outNbElement2 || outNbElement1 != endIdx - startIdx + 1 + lookbackSignal ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.BadParam ;
      }
      /* Calculate (fast MA) - (slow MA). */
      for( i = 0; i < outNbElement1; i += 1 ) {
         fastMABuffer[i] = fastMABuffer[i] - slowMABuffer[i];
      }
      /* Copy the result into the output for the caller. */
      /* memmove, not memcpy: fastMABuffer aliases outMACD when the caller buffer is
       * reused as scratch, so source and destination overlap (issue #94).
       */
      fastMABuffer.Slice(lookbackSignal, (endIdx - startIdx + 1) * 1).CopyTo(sc_outMACD.Slice(0));
      /* Calculate the signal/trigger line. */
      /* Sub-stream 2: ma over `fastMABuffer`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      int subLen2 = (outNbElement1 - 1) + 1;
      double[] subSrc2_0 = new double[subLen2];
      fastMABuffer.Slice(0, subLen2).CopyTo(subSrc2_0);
      MaStream sub2 = MaOpenAndFillInternal(subSrc2_0, 0, optInSignalPeriod, optInSignalMAType, out outBegIdx2, out outNbElement2, sc_outMACDSignal);
      retCode = RetCode.Success;
      /* Calculate the histogram. */
      for( i = 0; i < outNbElement2; i += 1 ) {
         sc_outMACDHist[i] = sc_outMACD[i] - sc_outMACDSignal[i];
      }
      /* All done! Indicate the output limits and return success. */
      outBegIdx = startIdx;
      outNBElement = outNbElement2;
      /* Capture the live producer state + sub handles. */
      if( outNBElement < 1 ) {
         return RetCode.InsufficientHistory;
      }
      sp.optInFastPeriod = optInFastPeriod;
      sp.optInFastMAType = optInFastMAType;
      sp.optInSlowPeriod = optInSlowPeriod;
      sp.optInSlowMAType = optInSlowMAType;
      sp.optInSignalPeriod = optInSignalPeriod;
      sp.optInSignalMAType = optInSignalMAType;
      sp.sub0 = sub0;
      sp.sub1 = sub1;
      sp.sub2 = sub2;
      sp.cur_outMACD = sc_outMACD[outNBElement - 1];
      sp.cur_outMACDSignal = sc_outMACDSignal[outNBElement - 1];
      sp.cur_outMACDHist = sc_outMACDHist[outNBElement - 1];
      return RetCode.Success;
   }

   /* MacdextOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal MacdextStream MacdextOpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, int optInFastPeriod, MAType optInFastMAType, int optInSlowPeriod, MAType optInSlowMAType, int optInSignalPeriod, MAType optInSignalMAType, out int outBegIdx, out int outNBElement, Span<double> outMACD, Span<double> outMACDSignal, Span<double> outMACDHist )
   {
      MacdextStream sp = new MacdextStream(this);
      RetCode retCode = MacdextOpenImpl(sp, inReal, startIdx, optInFastPeriod, optInFastMAType, optInSlowPeriod, optInSlowMAType, optInSignalPeriod, optInSignalMAType, out outBegIdx, out outNBElement, outMACD, outMACDSignal, outMACDHist, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("MACDEXT", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind MacdextOpen (composition seam). */
   internal MacdextStream MacdextOpenInternal( ReadOnlySpan<double> inReal, int startIdx, int optInFastPeriod, MAType optInFastMAType, int optInSlowPeriod, MAType optInSlowMAType, int optInSignalPeriod, MAType optInSignalMAType )
   {
      MacdextStream sp = new MacdextStream(this);
      double[] sink_outMACD = new double[1];
      double[] sink_outMACDSignal = new double[1];
      double[] sink_outMACDHist = new double[1];
      RetCode retCode = MacdextOpenImpl(sp, inReal, startIdx, optInFastPeriod, optInFastMAType, optInSlowPeriod, optInSlowMAType, optInSignalPeriod, optInSignalMAType, out int outBegIdx, out int outNBElement, sink_outMACD, sink_outMACDSignal, sink_outMACDHist, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("MACDEXT", "open", retCode);
   }

   /// <summary>Open a live <c>MACDEXT</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="MacdextStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>MACDEXT</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>MACDEXT_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>MacdextOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">Source series. The warm-up history, oldest bar first.</param>
   /// <param name="optInFastPeriod">As in the batch call; see <see cref="MACDEXT_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInFastMAType">As in the batch call; see <see cref="MACDEXT_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowPeriod">As in the batch call; see <see cref="MACDEXT_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowMAType">As in the batch call; see <see cref="MACDEXT_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSignalPeriod">As in the batch call; see <see cref="MACDEXT_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSignalMAType">As in the batch call; see <see cref="MACDEXT_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>MACDEXT_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public MacdextStream MacdextOpen( ReadOnlySpan<double> inReal, int optInFastPeriod, MAType optInFastMAType, int optInSlowPeriod, MAType optInSlowMAType, int optInSignalPeriod, MAType optInSignalMAType )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "MACDEXT open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "MACDEXT open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      return MacdextOpenInternal(inReal, 0, optInFastPeriod, optInFastMAType, optInSlowPeriod, optInSlowMAType, optInSignalPeriod, optInSignalMAType);
   }

   /// <summary><c>MacdextOpen</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>MACDEXT</c> produces over
   /// the same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - MACDEXT_Lookback(...)</c> values
   /// and must not alias the inputs or each other — this path writes the outputs
   /// and then reads the input tail to seed its rings, so the batch tier's
   /// in-place allowance does not carry over here. Both are checked before
   /// anything is written, so an undersized span is an <c>ArgumentException</c>
   /// naming it rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="MacdextStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">Source series. The warm-up history, oldest bar first.</param>
   /// <param name="optInFastPeriod">As in the batch call; see <see cref="MACDEXT_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInFastMAType">As in the batch call; see <see cref="MACDEXT_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowPeriod">As in the batch call; see <see cref="MACDEXT_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowMAType">As in the batch call; see <see cref="MACDEXT_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSignalPeriod">As in the batch call; see <see cref="MACDEXT_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSignalMAType">As in the batch call; see <see cref="MACDEXT_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outMACD">MACD line: fast MA minus slow MA. Must hold at least <c>historyLen -
   /// MACDEXT_Lookback(...)</c> values.</param>
   /// <param name="outMACDSignal">Signal line: MA of the MACD line. Must hold at least <c>historyLen -
   /// MACDEXT_Lookback(...)</c> values.</param>
   /// <param name="outMACDHist">Histogram: MACD minus signal. Must hold at least <c>historyLen -
   /// MACDEXT_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>MACDEXT_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public MacdextStream MacdextOpenAndFill( ReadOnlySpan<double> inReal, int optInFastPeriod, MAType optInFastMAType, int optInSlowPeriod, MAType optInSlowMAType, int optInSignalPeriod, MAType optInSignalMAType, Span<double> outMACD, Span<double> outMACDSignal, Span<double> outMACDHist )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "MACDEXT openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "MACDEXT openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      int guardOutLen = OpenFillCount("MACDEXT", "openAndFill", inReal.Length, MACDEXT_Lookback(optInFastPeriod, optInFastMAType, optInSlowPeriod, optInSlowMAType, optInSignalPeriod, optInSignalMAType));
      RequireFillLength("MACDEXT", "openAndFill", "outMACD", outMACD.Length, guardOutLen);
      RequireFillLength("MACDEXT", "openAndFill", "outMACDSignal", outMACDSignal.Length, guardOutLen);
      RequireFillLength("MACDEXT", "openAndFill", "outMACDHist", outMACDHist.Length, guardOutLen);
      if( outMACD.Overlaps(inReal) || outMACDSignal.Overlaps(inReal) || outMACDHist.Overlaps(inReal) || outMACD.Overlaps(outMACDSignal) || outMACD.Overlaps(outMACDHist) || outMACDSignal.Overlaps(outMACDHist) ) {
         throw StreamFailure("MACDEXT", "openAndFill", RetCode.BadParam);
      }
      return MacdextOpenAndFillInternal(inReal, 0, optInFastPeriod, optInFastMAType, optInSlowPeriod, optInSlowMAType, optInSignalPeriod, optInSignalMAType, out _, out _, outMACD, outMACDSignal, outMACDHist);
   }
