               tempReal = tempBuffer2[i];
               tempReal2 = outRealMiddleBand[i];
               outRealUpperBand[i] = Math.FusedMultiplyAdd(tempReal, optInNbDevUp, tempReal2);
               outRealLowerBand[i] = tempReal2 - tempReal * optInNbDevDn;
            }
         }
         return RetCode.Success ;
      }
      if( BBANDS_Lookback(optInTimePeriod, optInNbDevUp, optInNbDevDn, optInMAType) > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.Success ;
      }
      tempBuffer1 = new double[(int)((endIdx - startIdx + 1) * 1)];
      tempBuffer2 = new double[(int)((endIdx - startIdx + 1) * 1)];
      OutRange _xr0 = MA(startIdx, endIdx, inReal, optInTimePeriod, optInMAType, tempBuffer1);
      outBegIdx = _xr0.BegIdx;
      outNBElement = _xr0.Count;
      retCode = RetCode.Success;
      if( retCode != RetCode.Success || (int)outNBElement == 0 ) {
         outNBElement = 0;
         return retCode ;
      }
      maBegIdx = (int)outBegIdx;
      OutRange _xr1 = STDDEV((int)outBegIdx, endIdx, inReal, optInTimePeriod, 1.0, tempBuffer2);
      outBegIdx = _xr1.BegIdx;
      outNBElement = _xr1.Count;
      retCode = RetCode.Success;
      if( retCode != RetCode.Success ) {
         outNBElement = 0;
         return retCode ;
      }
      if( (int)outBegIdx > maBegIdx ) {
         shiftIdx = (int)outBegIdx - maBegIdx;
      } else {
         shiftIdx = 0;
      }
      tempBuffer1.Slice(shiftIdx, outNBElement * 1).CopyTo(outRealMiddleBand.Slice(0));
      if( optInNbDevUp == optInNbDevDn ) {
         for( i = 0; i < (int)outNBElement; i += 1 ) {
            tempReal = tempBuffer2[i] * optInNbDevUp;
            tempReal2 = outRealMiddleBand[i];
            outRealUpperBand[i] = tempReal2 + tempReal;
            outRealLowerBand[i] = tempReal2 - tempReal;
         }
      } else {
         for( i = 0; i < (int)outNBElement; i += 1 ) {
            tempReal2 = outRealMiddleBand[i];
            outRealUpperBand[i] = Math.FusedMultiplyAdd(tempBuffer2[i], optInNbDevUp, tempReal2);
            outRealLowerBand[i] = tempReal2 - tempBuffer2[i] * optInNbDevDn;
         }
      }
      return RetCode.Success ;
   }
   /// <summary>
   /// Bollinger Bands: a moving-average middle band with upper and lower bands
   /// offset by a multiple of the standard deviation. Used to gauge relative
   /// price volatility.
   /// </summary>
   /// <remarks>
   /// <b>Formula</b>
   /// <code>
   /// $$
   /// \begin{aligned}
   /// \text{middle}_t &amp;= \operatorname{MA}(X, n, \text{matype})_t \\
   /// \sigma_t &amp;= \operatorname{STDDEV}(X, n)_t \\
   /// \text{upper}_t &amp;= \text{middle}_t + k_{\text{up}}\,\sigma_t \\
   /// \text{lower}_t &amp;= \text{middle}_t - k_{\text{dn}}\,\sigma_t
   /// \end{aligned}
   /// $$
   /// </code>
   /// where $X$ is the input series, $n$ the period, $\text{matype}$ the
   /// moving-average type, and $k_{\text{up}}$, $k_{\text{dn}}$ the upper and
   /// lower deviation multipliers.
   /// <list type="bullet">
   /// <item><description>The defaults reproduce Bollinger's original definition: a 20-period SMA middle band with $k_{\text{up}} = k_{\text{dn}} = 2$. Any other $\text{matype}$ is a TA-Lib generalisation.</description></item>
   /// <item><description>$\text{matype}$ sets where the envelope is centred; $n$ and $k$ set how wide it is. The two are independent — $\sigma$ depends only on the price window, so changing the middle band re-centres the bands without resizing them.</description></item>
   /// </list>
   /// <para>
   /// Values are written only where the indicator is defined. The returned
   /// <see cref="OutRange"/> says where they start and how many there are;
   /// nothing outside that range is touched, and the library never pads with
   /// NaN. A valid range shorter than <c>BBANDS_Lookback</c> is a <b>success
   /// with no values</b> (<c>Count == 0</c>), not an error.
   /// </para>
   /// </remarks>
   /// <param name="startIdx">First bar of the requested range (inclusive).</param>
   /// <param name="endIdx">Last bar of the requested range (inclusive).</param>
   /// <param name="inReal">Input data series.</param>
