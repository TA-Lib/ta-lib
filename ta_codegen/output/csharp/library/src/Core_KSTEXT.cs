   /// <summary>Open a live <c>KSTEXT</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="KstextStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>KSTEXT</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>KstextLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>KstextOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">Source price series (canonically the close) The warm-up history, oldest
   /// bar first.</param>
   /// <param name="optInROC1Period">As in the batch call; see <see cref="KstextLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInROC2Period">As in the batch call; see <see cref="KstextLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInROC3Period">As in the batch call; see <see cref="KstextLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInROC4Period">As in the batch call; see <see cref="KstextLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInMA1Period">As in the batch call; see <see cref="KstextLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInMA2Period">As in the batch call; see <see cref="KstextLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInMA3Period">As in the batch call; see <see cref="KstextLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInMA4Period">As in the batch call; see <see cref="KstextLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSignalPeriod">As in the batch call; see <see cref="KstextLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInROCMAType">As in the batch call; see <see cref="KstextLookback"/> for its default and
   /// range (<c>MAType.DEFAULT</c> selects the default).</param>
   /// <param name="optInSignalMAType">As in the batch call; see <see cref="KstextLookback"/> for its default and
   /// range (<c>MAType.DEFAULT</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>KstextLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules S1 and S2).</exception>
   public KstextStream KstextOpen( ReadOnlySpan<double> inReal, int optInROC1Period, int optInROC2Period, int optInROC3Period, int optInROC4Period, int optInMA1Period, int optInMA2Period, int optInMA3Period, int optInMA4Period, int optInSignalPeriod, MAType optInROCMAType, MAType optInSignalMAType )
   {
      if( inReal.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "KSTEXT open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "KSTEXT open: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      return KstextOpenInternal(inReal, 0, optInROC1Period, optInROC2Period, optInROC3Period, optInROC4Period, optInMA1Period, optInMA2Period, optInMA3Period, optInMA4Period, optInSignalPeriod, optInROCMAType, optInSignalMAType);
   }

   /// <summary><c>KstextOpen</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>KSTEXT</c> produces over
   /// the same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - KstextLookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="KstextStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">Source price series (canonically the close) The warm-up history, oldest
   /// bar first.</param>
   /// <param name="optInROC1Period">As in the batch call; see <see cref="KstextLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInROC2Period">As in the batch call; see <see cref="KstextLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInROC3Period">As in the batch call; see <see cref="KstextLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInROC4Period">As in the batch call; see <see cref="KstextLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInMA1Period">As in the batch call; see <see cref="KstextLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInMA2Period">As in the batch call; see <see cref="KstextLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInMA3Period">As in the batch call; see <see cref="KstextLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInMA4Period">As in the batch call; see <see cref="KstextLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSignalPeriod">As in the batch call; see <see cref="KstextLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInROCMAType">As in the batch call; see <see cref="KstextLookback"/> for its default and
   /// range (<c>MAType.DEFAULT</c> selects the default).</param>
   /// <param name="optInSignalMAType">As in the batch call; see <see cref="KstextLookback"/> for its default and
   /// range (<c>MAType.DEFAULT</c> selects the default).</param>
   /// <param name="outKST">Know Sure Thing line. Must hold at least <c>historyLen -
   /// KstextLookback(...)</c> values.</param>
   /// <param name="outKSTSignal">Signal line: MA of the line. Must hold at least <c>historyLen -
   /// KstextLookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>KstextLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules S1 and S2).</exception>
   public KstextStream KstextOpenAndFill( ReadOnlySpan<double> inReal, int optInROC1Period, int optInROC2Period, int optInROC3Period, int optInROC4Period, int optInMA1Period, int optInMA2Period, int optInMA3Period, int optInMA4Period, int optInSignalPeriod, MAType optInROCMAType, MAType optInSignalMAType, Span<double> outKST, Span<double> outKSTSignal )
   {
      if( inReal.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "KSTEXT openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "KSTEXT openAndFill: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      int guardOutLen = OpenFillCount("KSTEXT", "openAndFill", inReal.Length, KstextLookback(optInROC1Period, optInROC2Period, optInROC3Period, optInROC4Period, optInMA1Period, optInMA2Period, optInMA3Period, optInMA4Period, optInSignalPeriod, optInROCMAType, optInSignalMAType));
      RequireFillLength("KSTEXT", "openAndFill", "outKST", outKST.Length, guardOutLen);
      RequireFillLength("KSTEXT", "openAndFill", "outKSTSignal", outKSTSignal.Length, guardOutLen);
      if( outKST.Overlaps(inReal) || outKSTSignal.Overlaps(inReal) || OutputsAlias(outKST, outKSTSignal) ) {
         throw StreamFailure("KSTEXT", "openAndFill", RetCode.BadParam);
      }
      return KstextOpenAndFillInternal(inReal, 0, optInROC1Period, optInROC2Period, optInROC3Period, optInROC4Period, optInMA1Period, optInMA2Period, optInMA3Period, optInMA4Period, optInSignalPeriod, optInROCMAType, optInSignalMAType, out _, out _, outKST, outKSTSignal);
   }
