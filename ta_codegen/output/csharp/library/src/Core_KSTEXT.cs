      internal MaStream sub8 = null!;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal KstextStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Kstext</c> reports over the same bars: the opener sets
      /// it to <c>(lookback, historyLen - lookback)</c>, every accepted
      /// <c>Update</c> adds one to the count — a rejected one changes nothing, and
      /// neither does <c>Peek</c> — and <c>Clone</c> carries it verbatim. A plain
      /// <c>Open</c> hands back only the last value, a subset of this range,
      /// because the caller chose not to take the fill.</para>
      /// <para>The last bar it can reach is <see cref="Core.IndexMax"/>; past that
      /// <c>Update</c> and <c>Advance</c> throw.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      /// <summary>Count one bar this stream was not fed: <see cref="OutRange"/> advances by
      /// one and nothing else moves.</summary>
      /// <remarks>
      /// <para><see cref="Value"/> keeps answering the previous output, which is this
      /// bar's output too. For a bar the caller leaves out: one an <c>Update</c>
      /// rejected and that will not be re-fed, or a session with no print. Without
      /// it two handles on one feed drift a bar apart when only one of them skips.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, the last one the batch tier
      /// can address and the last this handle will count. <c>Update</c> throws the
      /// same there.</para>
      /// </remarks>
      public void Advance()
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("KSTEXT", "advance", RetCode.OutOfRangeEndIndex);
         outRangeCount++;
      }

      internal KstextStream( KstextStream other )
      {
         this.core = other.core;
         this.optInROC1Period = other.optInROC1Period;
         this.optInROC2Period = other.optInROC2Period;
         this.optInROC3Period = other.optInROC3Period;
         this.optInROC4Period = other.optInROC4Period;
         this.optInMA1Period = other.optInMA1Period;
         this.optInMA2Period = other.optInMA2Period;
         this.optInMA3Period = other.optInMA3Period;
         this.optInMA4Period = other.optInMA4Period;
         this.optInSignalPeriod = other.optInSignalPeriod;
         this.optInROCMAType = other.optInROCMAType;
         this.optInSignalMAType = other.optInSignalMAType;
         this.cur_outKST = other.cur_outKST;
         this.cur_outKSTSignal = other.cur_outKSTSignal;
         this.sub0 = new RocStream(other.sub0);
         this.sub1 = new MaStream(other.sub1);
         this.sub2 = new RocStream(other.sub2);
         this.sub3 = new MaStream(other.sub3);
         this.sub4 = new RocStream(other.sub4);
         this.sub5 = new MaStream(other.sub5);
         this.sub6 = new RocStream(other.sub6);
         this.sub7 = new MaStream(other.sub7);
         this.sub8 = new MaStream(other.sub8);
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so nothing moves — <see cref="OutRange"/> included — and
      /// <see cref="Value"/> still answers the previous value. Re-feed the bar when
      /// a corrected value arrives, or call <see cref="Advance"/> to count it and
      /// carry on; two handles on one feed drift a bar apart if neither happens.
      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, which no re-feed clears: the
      /// handle has run out of index domain and only a shorter history can start a
      /// new one.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value at the bar just committed.</returns>
      public KstextValue Update( double inReal )
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("KSTEXT", "update", RetCode.OutOfRangeEndIndex);
         if( !double.IsFinite(inReal) ) throw Core.NonFiniteBar("KSTEXT", "update", nameof(inReal));
         core.KstextStepImpl(this, inReal);
         outRangeCount++;
         return new KstextValue(cur_outKST, cur_outKSTSignal);
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.IndexMax"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public KstextValue Peek( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.NonFiniteBar("KSTEXT", "peek", nameof(inReal));
         KstextStream sp = this;
         double cur_kstBuffer = 0.0;
         double cur_tempBuffer = 0.0;
         double cur_outKSTSignal = 0.0;
         double cur_outKST = 0.0;
         /* Pipeline the new bar through the sub-streams (batch tail order). */
         cur_kstBuffer = sp.sub0.Peek(inReal);
         cur_kstBuffer = sp.sub1.Peek(cur_kstBuffer);
         cur_tempBuffer = sp.sub2.Peek(inReal);
         cur_tempBuffer = sp.sub3.Peek(cur_tempBuffer);
         /* Combine map (batch tail, per bar). */
         cur_kstBuffer = Math.FusedMultiplyAdd(2.0, cur_tempBuffer, cur_kstBuffer);
         cur_tempBuffer = sp.sub4.Peek(inReal);
         cur_tempBuffer = sp.sub5.Peek(cur_tempBuffer);
         /* Combine map (batch tail, per bar). */
         cur_kstBuffer = Math.FusedMultiplyAdd(3.0, cur_tempBuffer, cur_kstBuffer);
         cur_tempBuffer = sp.sub6.Peek(inReal);
         cur_tempBuffer = sp.sub7.Peek(cur_tempBuffer);
         /* Combine map (batch tail, per bar). */
         cur_kstBuffer = Math.FusedMultiplyAdd(4.0, cur_tempBuffer, cur_kstBuffer);
         cur_outKSTSignal = sp.sub8.Peek(cur_kstBuffer);
         cur_outKST = cur_kstBuffer;
         return new KstextValue(cur_outKST, cur_outKSTSignal);
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public KstextValue Value => new KstextValue(cur_outKST, cur_outKSTSignal);

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public KstextStream Clone()
      {
         return new KstextStream(this);
      }
   }

   private void KstextStepImpl( KstextStream sp, double inReal )
   {
      double cur_kstBuffer = 0.0;
      double cur_tempBuffer = 0.0;
      double cur_outKSTSignal = 0.0;
      /* Pipeline the new bar through the sub-streams (batch tail order). */
      cur_kstBuffer = sp.sub0.Update(inReal);
      cur_kstBuffer = sp.sub1.Update(cur_kstBuffer);
      cur_tempBuffer = sp.sub2.Update(inReal);
      cur_tempBuffer = sp.sub3.Update(cur_tempBuffer);
      /* Combine map (batch tail, per bar). */
      cur_kstBuffer = Math.FusedMultiplyAdd(2.0, cur_tempBuffer, cur_kstBuffer);
      cur_tempBuffer = sp.sub4.Update(inReal);
      cur_tempBuffer = sp.sub5.Update(cur_tempBuffer);
      /* Combine map (batch tail, per bar). */
      cur_kstBuffer = Math.FusedMultiplyAdd(3.0, cur_tempBuffer, cur_kstBuffer);
      cur_tempBuffer = sp.sub6.Update(inReal);
      cur_tempBuffer = sp.sub7.Update(cur_tempBuffer);
      /* Combine map (batch tail, per bar). */
      cur_kstBuffer = Math.FusedMultiplyAdd(4.0, cur_tempBuffer, cur_kstBuffer);
      cur_outKSTSignal = sp.sub8.Update(cur_kstBuffer);
      sp.cur_outKST = cur_kstBuffer;
      sp.cur_outKSTSignal = cur_outKSTSignal;
   }

   private RetCode KstextOpenImpl( KstextStream sp, ReadOnlySpan<double> inReal, int startIdx, int optInROC1Period, int optInROC2Period, int optInROC3Period, int optInROC4Period, int optInMA1Period, int optInMA2Period, int optInMA3Period, int optInMA4Period, int optInSignalPeriod, MAType optInROCMAType, MAType optInSignalMAType, out int outBegIdx, out int outNBElement, Span<double> outKST, Span<double> outKSTSignal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      Span<double> kstBuffer;
      Span<double> tempBuffer;
      RetCode retCode;
      int lookbackTotal = 0;
      int lookbackSignal = 0;
      int lookbackMA = 0;
      int sigStart = 0;
      int tempInteger = 0;
      int tempBegIdx = 0;
      int rocNb = 0;
      int kstNb = 0;
      int legNb = 0;
      int sigNb = 0;
      int i = 0;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > IndexMax + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInROC1Period == int.MinValue ) {
         optInROC1Period = 10;
      } else if( optInROC1Period < 1 || optInROC1Period > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInROC2Period == int.MinValue ) {
         optInROC2Period = 15;
      } else if( optInROC2Period < 1 || optInROC2Period > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInROC3Period == int.MinValue ) {
         optInROC3Period = 20;
      } else if( optInROC3Period < 1 || optInROC3Period > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInROC4Period == int.MinValue ) {
         optInROC4Period = 30;
      } else if( optInROC4Period < 1 || optInROC4Period > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInMA1Period == int.MinValue ) {
         optInMA1Period = 10;
      } else if( optInMA1Period < 1 || optInMA1Period > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInMA2Period == int.MinValue ) {
         optInMA2Period = 10;
      } else if( optInMA2Period < 1 || optInMA2Period > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInMA3Period == int.MinValue ) {
         optInMA3Period = 10;
      } else if( optInMA3Period < 1 || optInMA3Period > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInMA4Period == int.MinValue ) {
         optInMA4Period = 15;
      } else if( optInMA4Period < 1 || optInMA4Period > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInSignalPeriod == int.MinValue ) {
         optInSignalPeriod = 9;
      } else if( optInSignalPeriod < 1 || optInSignalPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( (int)optInROCMAType == int.MinValue || optInROCMAType == MAType.DEFAULT ) {
         optInROCMAType = MAType.SMA;
      } else if( (int)optInROCMAType < MATypes.Min || (int)optInROCMAType > MATypes.Max ) {
         return RetCode.BadParam;
      }
      if( (int)optInSignalMAType == int.MinValue || optInSignalMAType == MAType.DEFAULT ) {
         optInSignalMAType = MAType.SMA;
      } else if( (int)optInSignalMAType < MATypes.Min || (int)optInSignalMAType > MATypes.Max ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      if( historyLen < KstextLookback(optInROC1Period, optInROC2Period, optInROC3Period, optInROC4Period, optInMA1Period, optInMA2Period, optInMA3Period, optInMA4Period, optInSignalPeriod, optInROCMAType, optInSignalMAType) + 1 ) {
         return RetCode.InsufficientHistory;
      }
      Span<double> sc_outKST = outStride == 1 ? outKST : new double[historyLen];
      Span<double> sc_outKSTSignal = outStride == 1 ? outKSTSignal : new double[historyLen];
      /* With every type SMA this is bit-exact with kst(): each leg's average
       * starts on the first bar the signal consumes, and the line accumulates
       * its legs left to right. Changing either breaks the equality.
       */
      outBegIdx = 0;
      outNBElement = 0;
      lookbackSignal = MaLookback(optInSignalPeriod, optInSignalMAType);
      lookbackTotal = KstextLookback(optInROC1Period, optInROC2Period, optInROC3Period, optInROC4Period, optInMA1Period, optInMA2Period, optInMA3Period, optInMA4Period, optInSignalPeriod, optInROCMAType, optInSignalMAType);
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      if( startIdx > endIdx ) {
         return RetCode.InsufficientHistory ;
      }
      sigStart = startIdx - lookbackSignal;
      /* Both buffers are sized by the longest leg average: a rate of change
       * starts its average's lookback before sigStart.
       */
      lookbackMA = MaLookback(optInMA1Period, optInROCMAType);
      tempInteger = MaLookback(optInMA2Period, optInROCMAType);
      if( tempInteger > lookbackMA ) {
         lookbackMA = tempInteger;
      }
      tempInteger = MaLookback(optInMA3Period, optInROCMAType);
      if( tempInteger > lookbackMA ) {
         lookbackMA = tempInteger;
      }
      tempInteger = MaLookback(optInMA4Period, optInROCMAType);
      if( tempInteger > lookbackMA ) {
         lookbackMA = tempInteger;
      }
      tempInteger = endIdx - sigStart + 1 + lookbackMA;
      kstBuffer = new double[(int)(tempInteger * 1)];
      tempBuffer = new double[(int)(tempInteger * 1)];
      /* Sub-stream 0: roc over `inReal`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      RocStream sub0 = RocOpenAndFillInternal(inReal, sigStart - MaLookback(optInMA1Period, optInROCMAType), optInROC1Period, out tempBegIdx, out rocNb, kstBuffer);
      retCode = RetCode.Success;
      /* Sub-stream 1: ma over `kstBuffer`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      int subLen1 = (rocNb - 1) + 1;
      double[] subSrc1_0 = new double[subLen1];
      kstBuffer.Slice(0, subLen1).CopyTo(subSrc1_0);
      MaStream sub1 = MaOpenInternal(subSrc1_0, 0, optInMA1Period, optInROCMAType);
      OutRange _xr0 = Ma(0, rocNb - 1, kstBuffer, optInMA1Period, optInROCMAType, kstBuffer);
      tempBegIdx = _xr0.BegIdx;
      kstNb = _xr0.Count;
      retCode = RetCode.Success;
      /* Sub-stream 2: roc over `inReal`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      RocStream sub2 = RocOpenAndFillInternal(inReal, sigStart - MaLookback(optInMA2Period, optInROCMAType), optInROC2Period, out tempBegIdx, out rocNb, tempBuffer);
      retCode = RetCode.Success;
      /* Sub-stream 3: ma over `tempBuffer`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      int subLen3 = (rocNb - 1) + 1;
      double[] subSrc3_0 = new double[subLen3];
      tempBuffer.Slice(0, subLen3).CopyTo(subSrc3_0);
      MaStream sub3 = MaOpenInternal(subSrc3_0, 0, optInMA2Period, optInROCMAType);
      OutRange _xr1 = Ma(0, rocNb - 1, tempBuffer, optInMA2Period, optInROCMAType, tempBuffer);
      tempBegIdx = _xr1.BegIdx;
      legNb = _xr1.Count;
      retCode = RetCode.Success;
      for( i = 0; i < kstNb; i += 1 ) {
         kstBuffer[i] = Math.FusedMultiplyAdd(2.0, tempBuffer[i], kstBuffer[i]);
      }
      /* Sub-stream 4: roc over `inReal`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      RocStream sub4 = RocOpenAndFillInternal(inReal, sigStart - MaLookback(optInMA3Period, optInROCMAType), optInROC3Period, out tempBegIdx, out rocNb, tempBuffer);
      retCode = RetCode.Success;
      /* Sub-stream 5: ma over `tempBuffer`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      int subLen5 = (rocNb - 1) + 1;
      double[] subSrc5_0 = new double[subLen5];
      tempBuffer.Slice(0, subLen5).CopyTo(subSrc5_0);
      MaStream sub5 = MaOpenInternal(subSrc5_0, 0, optInMA3Period, optInROCMAType);
      OutRange _xr2 = Ma(0, rocNb - 1, tempBuffer, optInMA3Period, optInROCMAType, tempBuffer);
      tempBegIdx = _xr2.BegIdx;
      legNb = _xr2.Count;
      retCode = RetCode.Success;
      for( i = 0; i < kstNb; i += 1 ) {
         kstBuffer[i] = Math.FusedMultiplyAdd(3.0, tempBuffer[i], kstBuffer[i]);
      }
      /* Sub-stream 6: roc over `inReal`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      RocStream sub6 = RocOpenAndFillInternal(inReal, sigStart - MaLookback(optInMA4Period, optInROCMAType), optInROC4Period, out tempBegIdx, out rocNb, tempBuffer);
      retCode = RetCode.Success;
      /* Sub-stream 7: ma over `tempBuffer`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      int subLen7 = (rocNb - 1) + 1;
      double[] subSrc7_0 = new double[subLen7];
      tempBuffer.Slice(0, subLen7).CopyTo(subSrc7_0);
      MaStream sub7 = MaOpenInternal(subSrc7_0, 0, optInMA4Period, optInROCMAType);
      OutRange _xr3 = Ma(0, rocNb - 1, tempBuffer, optInMA4Period, optInROCMAType, tempBuffer);
      tempBegIdx = _xr3.BegIdx;
      legNb = _xr3.Count;
      retCode = RetCode.Success;
      for( i = 0; i < kstNb; i += 1 ) {
         kstBuffer[i] = Math.FusedMultiplyAdd(4.0, tempBuffer[i], kstBuffer[i]);
      }
      /* Every read of inReal is done: an output may alias it. */
      kstBuffer.Slice(lookbackSignal, (endIdx - startIdx + 1) * 1).CopyTo(sc_outKST.Slice(0));
      /* Sub-stream 8: ma over `kstBuffer`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      int subLen8 = (kstNb - 1) + 1;
      double[] subSrc8_0 = new double[subLen8];
      kstBuffer.Slice(0, subLen8).CopyTo(subSrc8_0);
      MaStream sub8 = MaOpenAndFillInternal(subSrc8_0, 0, optInSignalPeriod, optInSignalMAType, out tempBegIdx, out sigNb, sc_outKSTSignal);
      retCode = RetCode.Success;
      outBegIdx = startIdx;
      outNBElement = sigNb;
      /* Capture the live producer state + sub handles. */
      if( outNBElement < 1 ) {
         return RetCode.InsufficientHistory;
      }
      sp.optInROC1Period = optInROC1Period;
      sp.optInROC2Period = optInROC2Period;
      sp.optInROC3Period = optInROC3Period;
      sp.optInROC4Period = optInROC4Period;
      sp.optInMA1Period = optInMA1Period;
      sp.optInMA2Period = optInMA2Period;
      sp.optInMA3Period = optInMA3Period;
      sp.optInMA4Period = optInMA4Period;
      sp.optInSignalPeriod = optInSignalPeriod;
      sp.optInROCMAType = optInROCMAType;
      sp.optInSignalMAType = optInSignalMAType;
      sp.sub0 = sub0;
      sp.sub1 = sub1;
      sp.sub2 = sub2;
      sp.sub3 = sub3;
      sp.sub4 = sub4;
      sp.sub5 = sub5;
      sp.sub6 = sub6;
      sp.sub7 = sub7;
      sp.sub8 = sub8;
      sp.cur_outKST = sc_outKST[outNBElement - 1];
      sp.cur_outKSTSignal = sc_outKSTSignal[outNBElement - 1];
      return RetCode.Success;
   }

