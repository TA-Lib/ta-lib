   /// <summary>A live <c>RVI</c> stream: one value per closed bar, bit-identical to
   /// <c>RVI</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.RviOpen"/>. There is no close and nothing to
   /// dispose — the handle is ordinary managed state, and an unreferenced handle
   /// is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class RviStream
   {
      internal Core core;
      internal int optInTimePeriod;
      internal int optInStdDevPeriod;
      internal double shift;
      internal double periodTotal1;
      internal double periodTotal2;
      internal double invPeriod;
      internal double prevUp;
      internal double prevDn;
      internal double wAlpha;
      internal double wBeta;
      internal int trailingIdx;
      internal int barsSinceReseed;
      internal int nbInitialElementNeeded;
      internal int j;
      internal int windowStart;
      internal int today;
      internal double lag1_inReal;
      internal int xMask;
      internal double[] x_inReal = [];
      internal double cur_outReal;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal RviStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Rvi</c> reports over the same bars: the opener sets it
      /// to <c>(lookback, historyLen - lookback)</c>, every <c>Update</c> adds one
      /// to the count — a non-finite bar is rejected but still counted, because the
      /// bar happened — <c>Peek</c> leaves it alone, and <c>Clone</c> carries it
      /// verbatim. A plain <c>Open</c> hands back only the last value, a subset of
      /// this range, because the caller chose not to take the fill.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      internal RviStream( RviStream other )
      {
         this.core = other.core;
         this.optInTimePeriod = other.optInTimePeriod;
         this.optInStdDevPeriod = other.optInStdDevPeriod;
         this.shift = other.shift;
         this.periodTotal1 = other.periodTotal1;
         this.periodTotal2 = other.periodTotal2;
         this.invPeriod = other.invPeriod;
         this.prevUp = other.prevUp;
         this.prevDn = other.prevDn;
         this.wAlpha = other.wAlpha;
         this.wBeta = other.wBeta;
         this.trailingIdx = other.trailingIdx;
         this.barsSinceReseed = other.barsSinceReseed;
         this.nbInitialElementNeeded = other.nbInitialElementNeeded;
         this.j = other.j;
         this.windowStart = other.windowStart;
         this.today = other.today;
         this.lag1_inReal = other.lag1_inReal;
         this.xMask = other.xMask;
         this.x_inReal = new double[other.x_inReal.Length];
         Array.Copy( other.x_inReal, this.x_inReal, other.x_inReal.Length );
         this.cur_outReal = other.cur_outReal;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Allocates nothing — neither handle state nor a return value.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so no state moves, <see cref="Value"/> still answers the previous value,
      /// and the stream stays usable — just carry on with the next bar.
      /// <see cref="OutRange"/> does advance: the bar happened, so it is counted,
      /// which keeps two handles fed the same series positionally aligned when only
      /// one of them rejects a bar. This is the one place the streaming tier is
      /// stricter than the batch API, which computes on whatever it is given: a
      /// handle retains its state, so a single non-finite bar would poison every
      /// later value it produces.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inReal )
      {
         if( !double.IsFinite(inReal) )
         {
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
            throw Core.StreamFailure("RVI", "update", RetCode.BadParam);
         }
         core.RviStepImpl(this, inReal);
         if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It copies nothing: the frame runs against this handle, reading its buffers
      /// and holding what the step would commit in locals. The cost does not grow
      /// with the period, and <c>Peek</c> never allocates.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>What <see cref="Update"/> would return for this bar.</returns>
      public double Peek( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.StreamFailure("RVI", "peek", RetCode.BadParam);
         RviStream sp = this;
         double tempReal = 0.0;
         double meanValue1 = 0.0;
         double variance = 0.0;
         double sigma = 0.0;
         double delta = 0.0;
         double upValue = 0.0;
         double dnValue = 0.0;
         double total = 0.0;
         int barsSinceReseed = sp.barsSinceReseed;
         double cur_outReal = 0.0;
         int j = sp.j;
         double periodTotal1 = sp.periodTotal1;
         double periodTotal2 = sp.periodTotal2;
         double prevDn = sp.prevDn;
         double prevUp = sp.prevUp;
         double shift = sp.shift;
         int today = sp.today;
         int trailingIdx = sp.trailingIdx;
         int windowStart = sp.windowStart;
         int pkSlot0 = -1;
         double pkVal0 = 0.0;
         if( today >= 1073741824 ) {
            int rebaseShift = trailingIdx & ~sp.xMask;
            today -= rebaseShift;
            trailingIdx -= rebaseShift;
            j -= rebaseShift;
            windowStart -= rebaseShift;
         }
         pkSlot0 = today & sp.xMask;
         pkVal0 = inReal;
         tempReal = (((today & sp.xMask) != pkSlot0) ? sp.x_inReal[today & sp.xMask] : pkVal0) - shift;
         periodTotal1 += tempReal;
         tempReal *= tempReal;
         periodTotal2 += tempReal;
         meanValue1 = periodTotal1 * sp.invPeriod;
         variance = periodTotal2 * sp.invPeriod - meanValue1 * meanValue1;
         tempReal = (((trailingIdx & sp.xMask) != pkSlot0) ? sp.x_inReal[trailingIdx & sp.xMask] : pkVal0) - shift;
         periodTotal1 -= tempReal;
         tempReal *= tempReal;
         periodTotal2 -= tempReal;
         trailingIdx += 1;
         barsSinceReseed -= 1;
         if( variance < 0.000001 * (periodTotal2 * sp.invPeriod) || tempReal > 1000000.0 * periodTotal2 || barsSinceReseed <= 0 ) {
            barsSinceReseed = 32 * sp.optInStdDevPeriod;
            windowStart = today - sp.nbInitialElementNeeded;
            tempReal = 0.0;
            for( j = windowStart; j <= today; j += 1 ) {
               tempReal += ((j & sp.xMask) != pkSlot0) ? sp.x_inReal[j & sp.xMask] : pkVal0;
            }
            shift = tempReal * sp.invPeriod;
            periodTotal1 = 0.0;
            periodTotal2 = 0.0;
            for( j = windowStart; j <= today; j += 1 ) {
               tempReal = (((j & sp.xMask) != pkSlot0) ? sp.x_inReal[j & sp.xMask] : pkVal0) - shift;
               periodTotal1 += tempReal;
               tempReal *= tempReal;
               periodTotal2 += tempReal;
            }
            meanValue1 = periodTotal1 * sp.invPeriod;
            variance = periodTotal2 * sp.invPeriod - meanValue1 * meanValue1;
            if( variance < 0.000000000001 * (periodTotal2 * sp.invPeriod) ) {
               variance = 0.0;
            }
            tempReal = (((windowStart & sp.xMask) != pkSlot0) ? sp.x_inReal[windowStart & sp.xMask] : pkVal0) - shift;
            periodTotal1 -= tempReal;
            tempReal *= tempReal;
            periodTotal2 -= tempReal;
         }
         sigma = Math.Sqrt(variance);
         delta = (((today & sp.xMask) != pkSlot0) ? sp.x_inReal[today & sp.xMask] : pkVal0) - ((((today - 1) & sp.xMask) != pkSlot0) ? sp.x_inReal[(today - 1) & sp.xMask] : pkVal0);
         upValue = 0.0;
         dnValue = 0.0;
         if( delta > 0.0 ) {
            upValue = sigma;
         } else if( delta < 0.0 ) {
            dnValue = sigma;
         }
         prevUp = Math.FusedMultiplyAdd(sp.wBeta, prevUp, sp.wAlpha * upValue);
         prevDn = Math.FusedMultiplyAdd(sp.wBeta, prevDn, sp.wAlpha * dnValue);
         total = prevUp + prevDn;
         cur_outReal = (total == 0.0) ? 50.0 : 100.0 * (prevUp / total);
         return cur_outReal;
      }

      /// <summary>Commit <c>n</c> closed bars and write their <c>n</c> values, in one call.</summary>
      /// <remarks>
      /// <para>Exactly <c>n</c> back-to-back <see cref="Update"/> calls, with one set of
      /// argument checks instead of <c>n</c>. The outputs must hold at least
      /// <c>n</c> values and must not overlap an input or each other.</para>
      /// <para><see cref="OutRange"/> counts what this call took in, which is what makes
      /// a rejection readable: a non-finite bar <c>k</c> throws
      /// <see cref="System.ArgumentException"/> exactly as <see cref="Update"/>
      /// would, with the bars before <c>k</c> committed and written, bar <c>k</c>
      /// and everything after it not written, and the count advanced by <c>k +
      /// 1</c> — the committed bars plus the rejected one, so the last bar counted
      /// is the one that failed.</para>
      /// </remarks>
      /// <param name="inReal">Closed bars for <c>inReal</c>, oldest first.</param>
      /// <param name="outReal">Receives one <c>outReal</c> value per bar committed.</param>
      public void UpdateAndFill( ReadOnlySpan<double> inReal, Span<double> outReal )
      {
         int barCount = inReal.Length;
         if( outReal.Length < barCount || outReal.Overlaps(inReal) ) throw Core.StreamFailure("RVI", "updateAndFill", RetCode.BadParam);
         for( int i = 0; i < barCount; i++ )
         {
            if( !double.IsFinite(inReal[i]) )
            {
               if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
               throw Core.StreamFailure("RVI", "updateAndFill", RetCode.BadParam);
            }
            core.RviStepImpl(this, inReal[i]);
            outReal[i] = cur_outReal;
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         }
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public RviStream Clone()
      {
         return new RviStream(this);
      }
   }

   internal void RviStepImpl( RviStream sp, double inReal )
   {
      double tempReal = 0.0;
      double meanValue1 = 0.0;
      double variance = 0.0;
      double sigma = 0.0;
      double delta = 0.0;
      double upValue = 0.0;
      double dnValue = 0.0;
      double total = 0.0;
      if( sp.today >= 1073741824 ) {
         int rebaseShift = sp.trailingIdx & ~sp.xMask;
         sp.today -= rebaseShift;
         sp.trailingIdx -= rebaseShift;
         sp.j -= rebaseShift;
         sp.windowStart -= rebaseShift;
      }
      sp.x_inReal[sp.today & sp.xMask] = inReal;
      tempReal = sp.x_inReal[sp.today & sp.xMask] - sp.shift;
      sp.periodTotal1 += tempReal;
      tempReal *= tempReal;
      sp.periodTotal2 += tempReal;
      meanValue1 = sp.periodTotal1 * sp.invPeriod;
      variance = sp.periodTotal2 * sp.invPeriod - meanValue1 * meanValue1;
      tempReal = sp.x_inReal[sp.trailingIdx & sp.xMask] - sp.shift;
      sp.periodTotal1 -= tempReal;
      tempReal *= tempReal;
      sp.periodTotal2 -= tempReal;
      sp.trailingIdx += 1;
      sp.barsSinceReseed -= 1;
      if( variance < 0.000001 * (sp.periodTotal2 * sp.invPeriod) || tempReal > 1000000.0 * sp.periodTotal2 || sp.barsSinceReseed <= 0 ) {
         sp.barsSinceReseed = 32 * sp.optInStdDevPeriod;
         sp.windowStart = sp.today - sp.nbInitialElementNeeded;
         tempReal = 0.0;
         for( sp.j = sp.windowStart; sp.j <= sp.today; sp.j += 1 ) {
            tempReal += sp.x_inReal[sp.j & sp.xMask];
         }
         sp.shift = tempReal * sp.invPeriod;
         sp.periodTotal1 = 0.0;
         sp.periodTotal2 = 0.0;
         for( sp.j = sp.windowStart; sp.j <= sp.today; sp.j += 1 ) {
            tempReal = sp.x_inReal[sp.j & sp.xMask] - sp.shift;
            sp.periodTotal1 += tempReal;
            tempReal *= tempReal;
            sp.periodTotal2 += tempReal;
         }
         meanValue1 = sp.periodTotal1 * sp.invPeriod;
         variance = sp.periodTotal2 * sp.invPeriod - meanValue1 * meanValue1;
         if( variance < 0.000000000001 * (sp.periodTotal2 * sp.invPeriod) ) {
            variance = 0.0;
         }
         tempReal = sp.x_inReal[sp.windowStart & sp.xMask] - sp.shift;
         sp.periodTotal1 -= tempReal;
         tempReal *= tempReal;
         sp.periodTotal2 -= tempReal;
      }
      sigma = Math.Sqrt(variance);
      delta = sp.x_inReal[sp.today & sp.xMask] - sp.x_inReal[(sp.today - 1) & sp.xMask];
      upValue = 0.0;
      dnValue = 0.0;
      if( delta > 0.0 ) {
         upValue = sigma;
      } else if( delta < 0.0 ) {
         dnValue = sigma;
      }
      sp.prevUp = Math.FusedMultiplyAdd(sp.wBeta, sp.prevUp, sp.wAlpha * upValue);
      sp.prevDn = Math.FusedMultiplyAdd(sp.wBeta, sp.prevDn, sp.wAlpha * dnValue);
      total = sp.prevUp + sp.prevDn;
      sp.cur_outReal = (total == 0.0) ? 50.0 : 100.0 * (sp.prevUp / total);
      sp.today += 1;
      sp.lag1_inReal = inReal;
   }

   private RetCode RviOpenImpl( RviStream sp, ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, int optInStdDevPeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double tempReal = 0;
      double shift = 0;
      double periodTotal1 = 0;
      double periodTotal2 = 0;
      double meanValue1 = 0;
      double variance = 0;
      double invPeriod = 0;
      double sigma = 0;
      double delta = 0;
      double upValue = 0;
      double dnValue = 0;
      double upTotal = 0;
      double dnTotal = 0;
      double prevUp = 0;
      double prevDn = 0;
      double wAlpha = 0;
      double wBeta = 0;
      double total = 0;
      int i = 0;
      int j = 0;
      int outIdx = 0;
      int today = 0;
      int anchorIdx = 0;
      int trailingIdx = 0;
      int windowStart = 0;
      int barsSinceReseed = 0;
      int nbInitialElementNeeded = 0;
      int lookbackTotal = 0;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 14;
      } else if( optInTimePeriod < 1 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInStdDevPeriod == int.MinValue ) {
         optInStdDevPeriod = 10;
      } else if( optInStdDevPeriod < 2 || optInStdDevPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      outBegIdx = 0;
      outNBElement = 0;
      lookbackTotal = RVI_Lookback(optInTimePeriod, optInStdDevPeriod);
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         return RetCode.InsufficientHistory ;
      }
      /* wAlpha is derived FROM wBeta, never the reverse (rma.c): only that order
       * makes the pair sum to exactly 1, and TA_RMA over this function's two legs
       * has to be bit for bit what the fused step below computes.
       */
      wBeta = (double)(optInTimePeriod - 1) / (double)optInTimePeriod;
      wAlpha = 1.0 - wBeta;
      /* The per-bar sigma is var.c's step transcribed unchanged -- shifted running
       * sums against a near-window anchor, the reseed trigger, its floor, and the
       * re-remove under the new shift. Any algebraically equal spelling is a
       * different double, and the reference this is differenced against is
       * TA_STDDEV anchored at this call's own start.
       */
      nbInitialElementNeeded = optInStdDevPeriod - 1;
      invPeriod = 1.0 / (double)optInStdDevPeriod;
      anchorIdx = startIdx - lookbackTotal;
      trailingIdx = anchorIdx;
      shift = inReal[anchorIdx];
      periodTotal1 = 0.0;
      periodTotal2 = 0.0;
      today = anchorIdx + nbInitialElementNeeded;
      for( j = anchorIdx; j < today; j += 1 ) {
         tempReal = inReal[j] - shift;
         periodTotal1 += tempReal;
         tempReal *= tempReal;
         periodTotal2 += tempReal;
      }
      barsSinceReseed = 32 * optInStdDevPeriod;
      /* Seed both legs with the simple average of the first 'optInTimePeriod'
       * volatilities, as rma.c seeds. optInStdDevPeriod >= 2 is what keeps the
       * inReal[today-1] below in bounds on the very first bar.
       */
      upTotal = 0.0;
      dnTotal = 0.0;
      for( i = optInTimePeriod; i > 0; i -= 1 ) {
         tempReal = inReal[today] - shift;
         periodTotal1 += tempReal;
         tempReal *= tempReal;
         periodTotal2 += tempReal;
         meanValue1 = periodTotal1 * invPeriod;
         variance = periodTotal2 * invPeriod - meanValue1 * meanValue1;
         tempReal = inReal[trailingIdx] - shift;
         periodTotal1 -= tempReal;
         tempReal *= tempReal;
         periodTotal2 -= tempReal;
         trailingIdx += 1;
         barsSinceReseed -= 1;
         if( variance < 0.000001 * (periodTotal2 * invPeriod) || tempReal > 1000000.0 * periodTotal2 || barsSinceReseed <= 0 ) {
            barsSinceReseed = 32 * optInStdDevPeriod;
            windowStart = today - nbInitialElementNeeded;
            tempReal = 0.0;
            for( j = windowStart; j <= today; j += 1 ) {
               tempReal += inReal[j];
            }
            shift = tempReal * invPeriod;
            periodTotal1 = 0.0;
            periodTotal2 = 0.0;
            for( j = windowStart; j <= today; j += 1 ) {
               tempReal = inReal[j] - shift;
               periodTotal1 += tempReal;
               tempReal *= tempReal;
               periodTotal2 += tempReal;
            }
            meanValue1 = periodTotal1 * invPeriod;
            variance = periodTotal2 * invPeriod - meanValue1 * meanValue1;
            if( variance < 0.000000000001 * (periodTotal2 * invPeriod) ) {
               variance = 0.0;
            }
            tempReal = inReal[windowStart] - shift;
            periodTotal1 -= tempReal;
            tempReal *= tempReal;
            periodTotal2 -= tempReal;
         }
         sigma = Math.Sqrt(variance);
         delta = inReal[today] - inReal[today - 1];
         if( delta > 0.0 ) {
            upTotal += sigma;
         } else if( delta < 0.0 ) {
            dnTotal += sigma;
         }
         today += 1;
      }
      prevUp = upTotal / optInTimePeriod;
      prevDn = dnTotal / optInTimePeriod;
      /* Skip the unstable period. Same step, smoothed but not stored. */
      i = this.unstablePeriod[(int)FuncUnstId.RVI];
      while( i != 0 ) {
         tempReal = inReal[today] - shift;
         periodTotal1 += tempReal;
         tempReal *= tempReal;
         periodTotal2 += tempReal;
         meanValue1 = periodTotal1 * invPeriod;
         variance = periodTotal2 * invPeriod - meanValue1 * meanValue1;
         tempReal = inReal[trailingIdx] - shift;
         periodTotal1 -= tempReal;
         tempReal *= tempReal;
         periodTotal2 -= tempReal;
         trailingIdx += 1;
         barsSinceReseed -= 1;
         if( variance < 0.000001 * (periodTotal2 * invPeriod) || tempReal > 1000000.0 * periodTotal2 || barsSinceReseed <= 0 ) {
            barsSinceReseed = 32 * optInStdDevPeriod;
            windowStart = today - nbInitialElementNeeded;
            tempReal = 0.0;
            for( j = windowStart; j <= today; j += 1 ) {
               tempReal += inReal[j];
            }
            shift = tempReal * invPeriod;
            periodTotal1 = 0.0;
            periodTotal2 = 0.0;
            for( j = windowStart; j <= today; j += 1 ) {
               tempReal = inReal[j] - shift;
               periodTotal1 += tempReal;
               tempReal *= tempReal;
               periodTotal2 += tempReal;
            }
            meanValue1 = periodTotal1 * invPeriod;
            variance = periodTotal2 * invPeriod - meanValue1 * meanValue1;
            if( variance < 0.000000000001 * (periodTotal2 * invPeriod) ) {
               variance = 0.0;
            }
            tempReal = inReal[windowStart] - shift;
            periodTotal1 -= tempReal;
            tempReal *= tempReal;
            periodTotal2 -= tempReal;
         }
         sigma = Math.Sqrt(variance);
         delta = inReal[today] - inReal[today - 1];
         upValue = 0.0;
         dnValue = 0.0;
         if( delta > 0.0 ) {
            upValue = sigma;
         } else if( delta < 0.0 ) {
            dnValue = sigma;
         }
         prevUp = Math.FusedMultiplyAdd(wBeta, prevUp, wAlpha * upValue);
         prevDn = Math.FusedMultiplyAdd(wBeta, prevDn, wAlpha * dnValue);
         today += 1;
         i -= 1;
      }
      /* A tie feeds neither leg, so both can be exactly zero at the same bar --
       * reachable on real data whenever the smoothing has no memory. Test the
       * total exactly: a band would carry the quote unit and zero the oscillator
       * for any instrument priced under it.
       */
      total = prevUp + prevDn;
      outReal[0 * outStride] = (total == 0.0) ? 50.0 : 100.0 * (prevUp / total);
      outIdx = 1;
      while( today <= endIdx ) {
         tempReal = inReal[today] - shift;
         periodTotal1 += tempReal;
         tempReal *= tempReal;
         periodTotal2 += tempReal;
         meanValue1 = periodTotal1 * invPeriod;
         variance = periodTotal2 * invPeriod - meanValue1 * meanValue1;
         tempReal = inReal[trailingIdx] - shift;
         periodTotal1 -= tempReal;
         tempReal *= tempReal;
         periodTotal2 -= tempReal;
         trailingIdx += 1;
         barsSinceReseed -= 1;
         if( variance < 0.000001 * (periodTotal2 * invPeriod) || tempReal > 1000000.0 * periodTotal2 || barsSinceReseed <= 0 ) {
            barsSinceReseed = 32 * optInStdDevPeriod;
            windowStart = today - nbInitialElementNeeded;
            tempReal = 0.0;
            for( j = windowStart; j <= today; j += 1 ) {
               tempReal += inReal[j];
            }
            shift = tempReal * invPeriod;
            periodTotal1 = 0.0;
            periodTotal2 = 0.0;
            for( j = windowStart; j <= today; j += 1 ) {
               tempReal = inReal[j] - shift;
               periodTotal1 += tempReal;
               tempReal *= tempReal;
               periodTotal2 += tempReal;
            }
            meanValue1 = periodTotal1 * invPeriod;
            variance = periodTotal2 * invPeriod - meanValue1 * meanValue1;
            if( variance < 0.000000000001 * (periodTotal2 * invPeriod) ) {
               variance = 0.0;
            }
            tempReal = inReal[windowStart] - shift;
            periodTotal1 -= tempReal;
            tempReal *= tempReal;
            periodTotal2 -= tempReal;
         }
         sigma = Math.Sqrt(variance);
         delta = inReal[today] - inReal[today - 1];
         upValue = 0.0;
         dnValue = 0.0;
         if( delta > 0.0 ) {
            upValue = sigma;
         } else if( delta < 0.0 ) {
            dnValue = sigma;
         }
         prevUp = Math.FusedMultiplyAdd(wBeta, prevUp, wAlpha * upValue);
         prevDn = Math.FusedMultiplyAdd(wBeta, prevDn, wAlpha * dnValue);
         total = prevUp + prevDn;
         outReal[outIdx++ * outStride] = (total == 0.0) ? 50.0 : 100.0 * (prevUp / total);
         today += 1;
      }
      outBegIdx = startIdx;
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      int capX = today - trailingIdx + 1;
      if( capX < 1 || capX > historyLen ) {
         return RetCode.InternalError;
      }
      int physX = 1;
      while( physX < capX ) {
         physX <<= 1;
      }
      double[] capX_inReal = new double[physX];
      for( int fillJ = historyLen - capX; fillJ < historyLen; fillJ++ ) {
         capX_inReal[fillJ & (physX - 1)] = inReal[fillJ];
      }
      sp.optInTimePeriod = optInTimePeriod;
      sp.optInStdDevPeriod = optInStdDevPeriod;
      sp.shift = shift;
      sp.periodTotal1 = periodTotal1;
      sp.periodTotal2 = periodTotal2;
      sp.invPeriod = invPeriod;
      sp.prevUp = prevUp;
      sp.prevDn = prevDn;
      sp.wAlpha = wAlpha;
      sp.wBeta = wBeta;
      sp.trailingIdx = trailingIdx;
      sp.barsSinceReseed = barsSinceReseed;
      sp.nbInitialElementNeeded = nbInitialElementNeeded;
      sp.j = j;
      sp.windowStart = windowStart;
      sp.today = today;
      sp.lag1_inReal = inReal[historyLen - 1];
      sp.xMask = physX - 1;
      sp.x_inReal = capX_inReal;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* RviOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal RviStream RviOpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, int optInStdDevPeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      RviStream sp = new RviStream(this);
      RetCode retCode = RviOpenImpl(sp, inReal, startIdx, optInTimePeriod, optInStdDevPeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("RVI", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind RviOpen (composition seam). */
   internal RviStream RviOpenInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, int optInStdDevPeriod )
   {
      RviStream sp = new RviStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = RviOpenImpl(sp, inReal, startIdx, optInTimePeriod, optInStdDevPeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("RVI", "open", retCode);
   }

   /// <summary>Open a live <c>RVI</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="RviStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>RVI</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>RVI_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>RviOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">Source price/value series, canonically the close. The warm-up history,
   /// oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="RVI_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInStdDevPeriod">As in the batch call; see <see cref="RVI_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>RVI_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public RviStream RviOpen( ReadOnlySpan<double> inReal, int optInTimePeriod, int optInStdDevPeriod )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "RVI open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "RVI open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      return RviOpenInternal(inReal, 0, optInTimePeriod, optInStdDevPeriod);
   }

   /// <summary><c>RviOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>RVI</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - RVI_Lookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="RviStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">Source price/value series, canonically the close. The warm-up history,
   /// oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="RVI_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInStdDevPeriod">As in the batch call; see <see cref="RVI_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Relative Volatility Index value. Must hold at least <c>historyLen -
   /// RVI_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>RVI_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public RviStream RviOpenAndFill( ReadOnlySpan<double> inReal, int optInTimePeriod, int optInStdDevPeriod, Span<double> outReal )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "RVI openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "RVI openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      int guardOutLen = OpenFillCount("RVI", "openAndFill", inReal.Length, RVI_Lookback(optInTimePeriod, optInStdDevPeriod));
      RequireFillLength("RVI", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( outReal.Overlaps(inReal) ) {
         throw StreamFailure("RVI", "openAndFill", RetCode.BadParam);
      }
      return RviOpenAndFillInternal(inReal, 0, optInTimePeriod, optInStdDevPeriod, out _, out _, outReal);
   }
