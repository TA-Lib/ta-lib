   /// <summary>
   /// Relative Volatility Index: Donald Dorsey's volatility oscillator, built
   /// exactly like RSI except that the quantity routed to the up and down
   /// buckets is the rolling standard deviation of price rather than the size of
   /// the move. The direction of the close-to-close change still decides which
   /// bucket a bar feeds. Bounded in 0..100. High values mean the recent
   /// volatility arrived mostly on up bars, low values that it arrived mostly on
   /// down bars. Dorsey proposed it as a confirming filter rather than a
   /// stand-alone signal: take a long entry only while RVI is above 50, a short
   /// only while it is below.
   /// </summary>
   /// <remarks>
   /// <b>Formula</b>
   /// <code>
   /// With `S` the standard deviation of the last `optInStdDevPeriod` values of `inReal`, and `C` the input series:
   /// U[i] = S[i] if C[i] &gt; C[i-1], else 0
   /// D[i] = S[i] if C[i] &lt; C[i-1], else 0
   /// RVI  = 100 * RMA(U, optInTimePeriod) / ( RMA(U, optInTimePeriod) + RMA(D, optInTimePeriod) )
   /// `RMA` is Wilder's smoothed moving average, seeded with the simple average of its first `optInTimePeriod` inputs. A bar whose close equals the previous close feeds neither bucket.
   /// </code>
   /// <list type="bullet">
   /// <item><description>This is Dorsey's 1993 original, which measures the closes alone. His 1995 revision averages the index of the highs with the index of the lows; some vendors reserve the name RVI for that revision and call this one RVIorig. It is not implemented here.</description></item>
   /// <item><description>A tie contributes to neither bucket, matching RSI's treatment of an unchanged close. Descriptions that write the denominator as a smoothed <c>S</c> instead of <c>U + D</c> are counting ties as down bars, which is a different indicator.</description></item>
   /// <item><description>Both smoothed legs can be exactly zero at the same bar, which happens whenever the smoothing carries no memory and the bar is a tie. RVI reports its neutral centre, 50, there rather than a non-finite value.</description></item>
   /// <item><description>The standard deviation is the population form. The sample form differs by a constant factor that cancels in the ratio, so it is not a variant.</description></item>
   /// <item><description>Sources publishing something else under this name, and how far from this function they land on a 252-bar equity series: a plain exponential smoother instead of Wilder's, up to 11.6 index points; one shared period for both the deviation and the smoothing, up to 15.6; an RSI taken over the standard-deviation series, up to 35.2; a linear-regression residual, up to 36.0. These are different indicators, not errors.</description></item>
   /// <item><description>Unrelated to the Relative Vigor Index, which several platforms also abbreviate RVI.</description></item>
   /// </list>
   /// <para>
   /// Values are written only where the indicator is defined. The returned
   /// <see cref="OutRange"/> says where they start and how many there are;
   /// nothing outside that range is touched, and the library never pads with
   /// NaN. A valid range shorter than <c>RVI_Lookback</c> is a <b>success with
   /// no values</b> (<c>Count == 0</c>), not an error.
   /// </para>
   /// </remarks>
   /// <param name="startIdx">First bar of the requested range (inclusive).</param>
   /// <param name="endIdx">Last bar of the requested range (inclusive).</param>
   /// <param name="inReal">Source price/value series, canonically the close.</param>
   /// <param name="optInTimePeriod">Wilder smoothing period applied to both legs (default 14; range 1..100000;
   /// <c>int.MinValue</c> selects the default).</param>
   /// <param name="optInStdDevPeriod">Number of trailing values the standard deviation spans (default 10; range
   /// 2..100000; <c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Relative Volatility Index value. Must hold at least <c>endIdx - startIdx +
   /// 1</c> values.</param>
   /// <returns>The range written: <c>BegIdx</c> is the first bar with a value,
   /// <c>Count</c> how many were written.</returns>
   /// <exception cref="System.ArgumentOutOfRangeException"><c>startIdx</c> or <c>endIdx</c> is negative or above
   /// <see cref="Core.MAX_INDEX"/>, or <c>endIdx &lt; startIdx</c>.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or two outputs
   /// share one array.</exception>
   /// <exception cref="System.ArgumentException">A span is too short for the range requested: any input this function
   /// <i>declares</i> that does not reach <c>endIdx</c>, or an output that
   /// cannot hold the values produced. Checked before anything is written, so a
   /// rejected call leaves every buffer untouched. Declared, not read: a few
   /// candlestick patterns take an OHLC series they never index, and it is
   /// required all the same. An empty span — which is what a null array becomes,
   /// since a span cannot be null — is rejected on the same terms and no others:
   /// it is too short whenever the range produces a value, and fine when it
   /// produces none, and on an output this function documents as declinable it
   /// is how you decline.</exception>
   /// <exception cref="System.ArgumentException">Two output buffers overlap, or an output partially overlaps an input.
   /// Computing wholly in place (an output that IS an input) is allowed.</exception>
   public OutRange RVI( int startIdx,
                        int endIdx,
                        ReadOnlySpan<double> inReal,
                        int optInTimePeriod,
                        int optInStdDevPeriod,
                        Span<double> outReal )
   {
      int guardStart = ClampedStart(startIdx, endIdx, RVI_Lookback(optInTimePeriod, optInStdDevPeriod));
      int guardInLen = guardStart < 0 ? 0 : endIdx + 1;
      int guardOutLen = guardStart < 0 || guardStart > endIdx ? 0 : endIdx - guardStart + 1;
      RequireLength("RVI", "inReal", inReal.Length, guardInLen);
      RequireLength("RVI", "outReal", outReal.Length, guardOutLen);
      RetCode retCode = RVI_Impl(startIdx, endIdx, inReal, optInTimePeriod, optInStdDevPeriod, out int outBegIdx, out int outNBElement, outReal);
      if( retCode != RetCode.Success ) {
         throw Failure("RVI", retCode);
      }
      return new OutRange(outBegIdx, outNBElement);
   }
   /// <summary>
   /// Relative Volatility Index: Donald Dorsey's volatility oscillator, built
   /// exactly like RSI except that the quantity routed to the up and down
   /// buckets is the rolling standard deviation of price rather than the size of
   /// the move. The direction of the close-to-close change still decides which
   /// bucket a bar feeds. Bounded in 0..100. High values mean the recent
   /// volatility arrived mostly on up bars, low values that it arrived mostly on
   /// down bars. Dorsey proposed it as a confirming filter rather than a
   /// stand-alone signal: take a long entry only while RVI is above 50, a short
   /// only while it is below.
   /// </summary>
   /// <remarks>
   /// <b>Formula</b>
   /// <code>
   /// With `S` the standard deviation of the last `optInStdDevPeriod` values of `inReal`, and `C` the input series:
   /// U[i] = S[i] if C[i] &gt; C[i-1], else 0
   /// D[i] = S[i] if C[i] &lt; C[i-1], else 0
   /// RVI  = 100 * RMA(U, optInTimePeriod) / ( RMA(U, optInTimePeriod) + RMA(D, optInTimePeriod) )
   /// `RMA` is Wilder's smoothed moving average, seeded with the simple average of its first `optInTimePeriod` inputs. A bar whose close equals the previous close feeds neither bucket.
   /// </code>
   /// <list type="bullet">
   /// <item><description>This is Dorsey's 1993 original, which measures the closes alone. His 1995 revision averages the index of the highs with the index of the lows; some vendors reserve the name RVI for that revision and call this one RVIorig. It is not implemented here.</description></item>
   /// <item><description>A tie contributes to neither bucket, matching RSI's treatment of an unchanged close. Descriptions that write the denominator as a smoothed <c>S</c> instead of <c>U + D</c> are counting ties as down bars, which is a different indicator.</description></item>
   /// <item><description>Both smoothed legs can be exactly zero at the same bar, which happens whenever the smoothing carries no memory and the bar is a tie. RVI reports its neutral centre, 50, there rather than a non-finite value.</description></item>
   /// <item><description>The standard deviation is the population form. The sample form differs by a constant factor that cancels in the ratio, so it is not a variant.</description></item>
   /// <item><description>Sources publishing something else under this name, and how far from this function they land on a 252-bar equity series: a plain exponential smoother instead of Wilder's, up to 11.6 index points; one shared period for both the deviation and the smoothing, up to 15.6; an RSI taken over the standard-deviation series, up to 35.2; a linear-regression residual, up to 36.0. These are different indicators, not errors.</description></item>
   /// <item><description>Unrelated to the Relative Vigor Index, which several platforms also abbreviate RVI.</description></item>
   /// </list>
   /// <para>
   /// This is the <c>float[]</c> overload: input elements are widened to
   /// <c>double</c> as they are read and all arithmetic is performed in
   /// <c>double</c>, so a result beyond <c>float</c> range is still
   /// representable.
   /// </para>
   /// <para>
   /// Values are written only where the indicator is defined. The returned
   /// <see cref="OutRange"/> says where they start and how many there are;
   /// nothing outside that range is touched, and the library never pads with
   /// NaN. A valid range shorter than <c>RVI_Lookback</c> is a <b>success with
   /// no values</b> (<c>Count == 0</c>), not an error.
   /// </para>
   /// </remarks>
   /// <param name="startIdx">First bar of the requested range (inclusive).</param>
   /// <param name="endIdx">Last bar of the requested range (inclusive).</param>
   /// <param name="inReal">Source price/value series, canonically the close.</param>
   /// <param name="optInTimePeriod">Wilder smoothing period applied to both legs (default 14; range 1..100000;
   /// <c>int.MinValue</c> selects the default).</param>
   /// <param name="optInStdDevPeriod">Number of trailing values the standard deviation spans (default 10; range
   /// 2..100000; <c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Relative Volatility Index value. Must hold at least <c>endIdx - startIdx +
   /// 1</c> values.</param>
   /// <returns>The range written: <c>BegIdx</c> is the first bar with a value,
   /// <c>Count</c> how many were written.</returns>
   /// <exception cref="System.ArgumentOutOfRangeException"><c>startIdx</c> or <c>endIdx</c> is negative or above
   /// <see cref="Core.MAX_INDEX"/>, or <c>endIdx &lt; startIdx</c>.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or two outputs
   /// share one array.</exception>
   /// <exception cref="System.ArgumentException">A span is too short for the range requested: any input this function
   /// <i>declares</i> that does not reach <c>endIdx</c>, or an output that
   /// cannot hold the values produced. Checked before anything is written, so a
   /// rejected call leaves every buffer untouched. Declared, not read: a few
   /// candlestick patterns take an OHLC series they never index, and it is
   /// required all the same. An empty span — which is what a null array becomes,
   /// since a span cannot be null — is rejected on the same terms and no others:
   /// it is too short whenever the range produces a value, and fine when it
   /// produces none, and on an output this function documents as declinable it
   /// is how you decline.</exception>
   /// <exception cref="System.ArgumentException">Two output buffers overlap, or an output partially overlaps an input.
   /// Computing wholly in place (an output that IS an input) is allowed.</exception>
   public OutRange RVI( int startIdx,
                        int endIdx,
                        ReadOnlySpan<float> inReal,
                        int optInTimePeriod,
                        int optInStdDevPeriod,
                        Span<double> outReal )
   {
