   /// <item><description>The band inherits the Average True Range's warm-up, so a caller who wants it converged sets <c>TA_FUNC_UNST_ATR</c>, exactly as when calling that function directly.</description></item>
   /// </list>
   /// <para>
   /// This is the <c>float[]</c> overload: input elements are widened to
   /// <c>double</c> as they are read and all arithmetic is performed in
   /// <c>double</c>, so a result beyond <c>float</c> range is still
   /// representable.
   /// </para>
   /// <para>
   /// Values are written only where the indicator is defined. The returned
   /// <see cref="OutRange"/> says where they start and how many there are;
   /// nothing outside that range is touched, and the library never pads with
   /// NaN. A valid range shorter than <c>SUPERTREND_Lookback</c> is a <b>success
   /// with no values</b> (<c>Count == 0</c>), not an error.
   /// </para>
   /// </remarks>
   /// <param name="startIdx">First bar of the requested range (inclusive).</param>
   /// <param name="endIdx">Last bar of the requested range (inclusive).</param>
   /// <param name="inHigh">High price of each bar.</param>
   /// <param name="inLow">Low price of each bar.</param>
   /// <param name="inClose">Close price of each bar.</param>
   /// <param name="optInTimePeriod">Smoothing period of the Average True Range (default 10; range 2..100000;
   /// <c>int.MinValue</c> selects the default).</param>
   /// <param name="optInMultiplier">Multiplier applied to the Average True Range to set the band width
   /// (default 3; minimum 0; <c>-4e37</c> selects the default).</param>
   /// <param name="outReal">The SuperTrend line: the band the trend is currently riding. Must hold at
   /// least <c>endIdx - startIdx + 1</c> values.</param>
   /// <param name="outInteger">Trend direction: +1 while the trend rides the lower band, -1 while it
   /// rides the upper one. Must hold at least <c>endIdx - startIdx + 1</c>
   /// values.</param>
   /// <returns>The range written: <c>BegIdx</c> is the first bar with a value,
   /// <c>Count</c> how many were written.</returns>
   /// <exception cref="System.ArgumentOutOfRangeException"><c>startIdx</c> or <c>endIdx</c> is negative or above
   /// <see cref="Core.MAX_INDEX"/>, or <c>endIdx &lt; startIdx</c>.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or two outputs
   /// share one array.</exception>
   /// <exception cref="System.ArgumentException">A span is too short for the range requested: any input this function
   /// <i>declares</i> that does not reach <c>endIdx</c>, or an output that
   /// cannot hold the values produced. Checked before anything is written, so a
   /// rejected call leaves every buffer untouched. Declared, not read: a few
   /// candlestick patterns take an OHLC series they never index, and it is
   /// required all the same. An empty span — which is what a null array becomes,
   /// since a span cannot be null — is rejected on the same terms and no others:
   /// it is too short whenever the range produces a value, and fine when it
   /// produces none, and on an output this function documents as declinable it
   /// is how you decline.</exception>
   /// <exception cref="System.ArgumentException">Two output buffers overlap, or an output partially overlaps an input.
   /// Computing wholly in place (an output that IS an input) is allowed.</exception>
   public OutRange SUPERTREND( int startIdx,
                               int endIdx,
                               ReadOnlySpan<float> inHigh,
                               ReadOnlySpan<float> inLow,
                               ReadOnlySpan<float> inClose,
                               int optInTimePeriod,
                               double optInMultiplier,
                               Span<double> outReal,
                               Span<int> outInteger )
   {
      int guardStart = ClampedStart(startIdx, endIdx, SUPERTREND_Lookback(optInTimePeriod, optInMultiplier));
      int guardInLen = guardStart < 0 ? 0 : endIdx + 1;
      int guardOutLen = guardStart < 0 || guardStart > endIdx ? 0 : endIdx - guardStart + 1;
      RequireLength("SUPERTREND", "inHigh", inHigh.Length, guardInLen);
      RequireLength("SUPERTREND", "inLow", inLow.Length, guardInLen);
      RequireLength("SUPERTREND", "inClose", inClose.Length, guardInLen);
      RequireLength("SUPERTREND", "outReal", outReal.Length, guardOutLen);
      RequireLength("SUPERTREND", "outInteger", outInteger.Length, guardOutLen);
      RetCode retCode = SUPERTREND_Impl(startIdx, endIdx, inHigh, inLow, inClose, optInTimePeriod, optInMultiplier, out int outBegIdx, out int outNBElement, outReal, outInteger);
      if( retCode != RetCode.Success ) {
         throw Failure("SUPERTREND", retCode);
      }
      return new OutRange(outBegIdx, outNBElement);
   }
   /**** Streaming API *****/

   /// <summary>One <c>SUPERTREND</c> output set, in batch output order.</summary>
   /// <remarks>
   /// <para>Equality is the compiler-generated record-struct equality, which compares
   /// the components with <c>==</c>: <c>NaN</c> does not equal <c>NaN</c>, and
   /// <c>0.0</c> equals <c>-0.0</c>. That is deliberately <em>not</em> the Java
   /// <c>Value</c> contract, which compares bitwise — compare
   /// <see cref="System.BitConverter.DoubleToInt64Bits(double)"/> per component
   /// when bit-level identity is what you mean.</para>
   /// </remarks>
   /// <param name="Real">The SuperTrend line: the band the trend is currently riding.</param>
   /// <param name="Integer">Trend direction: +1 while the trend rides the lower band, -1 while it
   /// rides the upper one.</param>
   public readonly record struct SupertrendValue( double Real, int Integer );

   /// <summary>A live <c>SUPERTREND</c> stream: one value per closed bar, bit-identical
   /// to <c>SUPERTREND</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.SupertrendOpen"/>. There is no close and nothing
   /// to dispose — the handle is ordinary managed state, and an unreferenced
   /// handle is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class SupertrendStream
   {
      internal Core core;
      internal int optInTimePeriod;
      internal double optInMultiplier;
      internal int isUptrend;
      internal double prevATR;
      internal double finalUpper;
      internal double finalLower;
      internal double prevClose;
      internal double lag1_inClose;
      internal double cur_outReal;
      internal int cur_outInteger;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal SupertrendStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Supertrend</c> reports over the same bars: the opener
      /// sets it to <c>(lookback, historyLen - lookback)</c>, every <c>Update</c>
      /// adds one to the count — a non-finite bar is rejected but still counted,
      /// because the bar happened — <c>Peek</c> leaves it alone, and <c>Clone</c>
      /// carries it verbatim. A plain <c>Open</c> hands back only the last value, a
      /// subset of this range, because the caller chose not to take the fill.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      internal SupertrendStream( SupertrendStream other )
      {
         this.core = other.core;
         this.optInTimePeriod = other.optInTimePeriod;
         this.optInMultiplier = other.optInMultiplier;
         this.isUptrend = other.isUptrend;
         this.prevATR = other.prevATR;
         this.finalUpper = other.finalUpper;
         this.finalLower = other.finalLower;
         this.prevClose = other.prevClose;
         this.lag1_inClose = other.lag1_inClose;
         this.cur_outReal = other.cur_outReal;
         this.cur_outInteger = other.cur_outInteger;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Allocates nothing — neither handle state nor a return value.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so no state moves, <see cref="Value"/> still answers the previous value,
      /// and the stream stays usable — just carry on with the next bar.
      /// <see cref="OutRange"/> does advance: the bar happened, so it is counted,
      /// which keeps two handles fed the same series positionally aligned when only
      /// one of them rejects a bar. This is the one place the streaming tier is
      /// stricter than the batch API, which computes on whatever it is given: a
      /// handle retains its state, so a single non-finite bar would poison every
      /// later value it produces.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>The value at the bar just committed.</returns>
      public SupertrendValue Update( double inHigh, double inLow, double inClose )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) )
         {
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
            throw Core.StreamFailure("SUPERTREND", "update", RetCode.BadParam);
         }
         core.SupertrendStepImpl(this, inHigh, inLow, inClose);
         if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         return new SupertrendValue(cur_outReal, cur_outInteger);
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It copies nothing: the frame runs against this handle, reading its buffers
      /// and holding what the step would commit in locals. The cost does not grow
      /// with the period, and <c>Peek</c> never allocates.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>What <see cref="Update"/> would return for this bar.</returns>
      public SupertrendValue Peek( double inHigh, double inLow, double inClose )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) ) throw Core.StreamFailure("SUPERTREND", "peek", RetCode.BadParam);
         SupertrendStream sp = this;
         double val2 = 0.0;
         double val3 = 0.0;
         double greatest = 0.0;
         double tempCY = 0.0;
         double tempLT = 0.0;
         double tempHT = 0.0;
         double medianPrice = 0.0;
         double band = 0.0;
         double basicUpper = 0.0;
         double basicLower = 0.0;
         double closeToday = 0.0;
         int cur_outInteger = sp.cur_outInteger;
         double cur_outReal = sp.cur_outReal;
         double finalLower = sp.finalLower;
         double finalUpper = sp.finalUpper;
         int isUptrend = sp.isUptrend;
         double prevATR = sp.prevATR;
         tempLT = inLow;
         tempHT = inHigh;
         tempCY = sp.lag1_inClose;
         greatest = tempHT - tempLT;
         /* val1 */
         val2 = Math.Abs(tempCY - tempHT);
         if( val2 > greatest ) {
            greatest = val2;
         }
         val3 = Math.Abs(tempCY - tempLT);
         if( val3 > greatest ) {
            greatest = val3;
         }
         prevATR *= sp.optInTimePeriod - 1;
         prevATR += greatest;
         prevATR /= sp.optInTimePeriod;
         medianPrice = (tempHT + tempLT) / 2.0;
         band = sp.optInMultiplier * prevATR;
         basicUpper = medianPrice + band;
         basicLower = medianPrice - band;
         /* Each band ratchets toward price and is released only by a close on its
          * far side. Nothing keeps the two ordered -- each is released by its own
          * condition, so the lower one can end up above the upper one -- and where
          * that happens a flip puts the emitted band on the far side of the close.
          * The line is therefore NOT monotone within a trend, and the flag does not
          * always say which side of the line price is on; both read as invariants
          * and neither is one.
          */
         if( basicUpper < finalUpper || sp.prevClose > finalUpper ) {
            finalUpper = basicUpper;
         }
         if( basicLower > finalLower || sp.prevClose < finalLower ) {
            finalLower = basicLower;
         }
         closeToday = inClose;
         /* The trend is carried in its own variable rather than recovered by
          * comparing the previous output against the previous bands. The two
          * carried bands do coincide on some bars -- always on a bar with no true
          * range, and on some of them at a multiplier of zero -- and there that
          * comparison cannot tell them apart, so it would silently lose the
          * hysteresis on exactly the flat input a corpus of real prices lacks.
          */
         if( (isUptrend) != 0 ) {
            if( closeToday < finalLower ) {
               isUptrend = 0;
            }
         } else if( closeToday > finalUpper ) {
            isUptrend = 1;
         }
         if( (isUptrend) != 0 ) {
            cur_outReal = finalLower;
            cur_outInteger = 1;
         } else {
            cur_outReal = finalUpper;
            cur_outInteger = 0 - 1;
         }
         return new SupertrendValue(cur_outReal, cur_outInteger);
      }

      /// <summary>Commit <c>n</c> closed bars and write their <c>n</c> values, in one call.</summary>
      /// <remarks>
      /// <para>Exactly <c>n</c> back-to-back <see cref="Update"/> calls, with one set of
      /// argument checks instead of <c>n</c>. The outputs must hold at least
      /// <c>n</c> values and must not overlap an input or each other.</para>
      /// <para><see cref="OutRange"/> counts what this call took in, which is what makes
      /// a rejection readable: a non-finite bar <c>k</c> throws
      /// <see cref="System.ArgumentException"/> exactly as <see cref="Update"/>
      /// would, with the bars before <c>k</c> committed and written, bar <c>k</c>
      /// and everything after it not written, and the count advanced by <c>k +
      /// 1</c> — the committed bars plus the rejected one, so the last bar counted
      /// is the one that failed.</para>
      /// </remarks>
      /// <param name="inHigh">Closed bars for <c>inHigh</c>, oldest first.</param>
      /// <param name="inLow">Closed bars for <c>inLow</c>, oldest first.</param>
      /// <param name="inClose">Closed bars for <c>inClose</c>, oldest first.</param>
      /// <param name="outReal">Receives one <c>outReal</c> value per bar committed.</param>
      /// <param name="outInteger">Receives one <c>outInteger</c> value per bar committed.</param>
      public void UpdateAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, Span<double> outReal, Span<int> outInteger )
      {
         int barCount = inHigh.Length;
         if( inLow.Length != barCount || inClose.Length != barCount || outReal.Length < barCount || outInteger.Length < barCount || outReal.Overlaps(inHigh) || outReal.Overlaps(inLow) || outReal.Overlaps(inClose) ) throw Core.StreamFailure("SUPERTREND", "updateAndFill", RetCode.BadParam);
         for( int i = 0; i < barCount; i++ )
         {
            if( !double.IsFinite(inHigh[i]) || !double.IsFinite(inLow[i]) || !double.IsFinite(inClose[i]) )
            {
               if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
               throw Core.StreamFailure("SUPERTREND", "updateAndFill", RetCode.BadParam);
            }
            core.SupertrendStepImpl(this, inHigh[i], inLow[i], inClose[i]);
            outReal[i] = cur_outReal;
            outInteger[i] = cur_outInteger;
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         }
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public SupertrendValue Value => new SupertrendValue(cur_outReal, cur_outInteger);

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public SupertrendStream Clone()
      {
         return new SupertrendStream(this);
      }
   }

   internal void SupertrendStepImpl( SupertrendStream sp, double inHigh, double inLow, double inClose )
   {
      double val2 = 0.0;
      double val3 = 0.0;
      double greatest = 0.0;
      double tempCY = 0.0;
      double tempLT = 0.0;
      double tempHT = 0.0;
      double medianPrice = 0.0;
      double band = 0.0;
      double basicUpper = 0.0;
      double basicLower = 0.0;
      double closeToday = 0.0;
      tempLT = inLow;
      tempHT = inHigh;
      tempCY = sp.lag1_inClose;
      greatest = tempHT - tempLT;
      /* val1 */
      val2 = Math.Abs(tempCY - tempHT);
      if( val2 > greatest ) {
         greatest = val2;
      }
      val3 = Math.Abs(tempCY - tempLT);
      if( val3 > greatest ) {
         greatest = val3;
      }
      sp.prevATR *= sp.optInTimePeriod - 1;
      sp.prevATR += greatest;
      sp.prevATR /= sp.optInTimePeriod;
      medianPrice = (tempHT + tempLT) / 2.0;
      band = sp.optInMultiplier * sp.prevATR;
      basicUpper = medianPrice + band;
      basicLower = medianPrice - band;
      /* Each band ratchets toward price and is released only by a close on its
       * far side. Nothing keeps the two ordered -- each is released by its own
       * condition, so the lower one can end up above the upper one -- and where
       * that happens a flip puts the emitted band on the far side of the close.
       * The line is therefore NOT monotone within a trend, and the flag does not
       * always say which side of the line price is on; both read as invariants
       * and neither is one.
       */
      if( basicUpper < sp.finalUpper || sp.prevClose > sp.finalUpper ) {
         sp.finalUpper = basicUpper;
      }
      if( basicLower > sp.finalLower || sp.prevClose < sp.finalLower ) {
         sp.finalLower = basicLower;
      }
      closeToday = inClose;
      /* The trend is carried in its own variable rather than recovered by
       * comparing the previous output against the previous bands. The two
       * carried bands do coincide on some bars -- always on a bar with no true
       * range, and on some of them at a multiplier of zero -- and there that
       * comparison cannot tell them apart, so it would silently lose the
       * hysteresis on exactly the flat input a corpus of real prices lacks.
       */
      if( (sp.isUptrend) != 0 ) {
         if( closeToday < sp.finalLower ) {
            sp.isUptrend = 0;
         }
      } else if( closeToday > sp.finalUpper ) {
         sp.isUptrend = 1;
      }
      if( (sp.isUptrend) != 0 ) {
         sp.cur_outReal = sp.finalLower;
         sp.cur_outInteger = 1;
      } else {
         sp.cur_outReal = sp.finalUpper;
         sp.cur_outInteger = 0 - 1;
      }
      sp.prevClose = closeToday;
      sp.lag1_inClose = inClose;
   }

   private RetCode SupertrendOpenImpl( SupertrendStream sp, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, double optInMultiplier, out int outBegIdx, out int outNBElement, Span<double> outReal, Span<int> outInteger, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      int i = 0;
      int today = 0;
      int outIdx = 0;
      int lookbackTotal = 0;
      int isUptrend = 0;
      double prevATR = 0;
      double periodTotal = 0;
      double val2 = 0;
      double val3 = 0;
      double greatest = 0;
      double tempCY = 0;
      double tempLT = 0;
      double tempHT = 0;
      double medianPrice = 0;
      double band = 0;
      double basicUpper = 0;
      double basicLower = 0;
      double finalUpper = 0;
      double finalLower = 0;
      double closeToday = 0;
      double prevClose = 0;
      int historyLen = inHigh.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inLow.Length != inHigh.Length || inClose.Length != inHigh.Length ) {
         return RetCode.BadParam;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 10;
      } else if( optInTimePeriod < 2 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInMultiplier == TA_REAL_DEFAULT ) {
         optInMultiplier = 3e0;
      } else if( !(optInMultiplier >= 0e0 && optInMultiplier <= TA_REAL_MAX) ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      outBegIdx = 0;
      outNBElement = 0;
      lookbackTotal = SUPERTREND_Lookback(optInTimePeriod, optInMultiplier);
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         return RetCode.InsufficientHistory ;
      }
      /* The Average True Range is carried inline rather than taken from a call,
       * because the band and the ratchet advance together one bar at a time and a
       * whole-range buffer between them would not stream.
       *
       * The arithmetic order below is the bit-exactness contract with TA_ATR (do
       * not reorder or fuse operations): True Range from high-low, then the two
       * previous-close distances in that order; the seed summed from 0.0 over the
       * first 'period' True Ranges and divided once; Wilder smoothing as three
       * separate statements.
       */
      today = startIdx - lookbackTotal + 1;
      periodTotal = 0.0;
      i = optInTimePeriod;
      while( i-- > 0 ) {
         tempLT = inLow[today];
         tempHT = inHigh[today];
         tempCY = inClose[today - 1];
         greatest = tempHT - tempLT;
         /* val1 */
         val2 = Math.Abs(tempCY - tempHT);
         if( val2 > greatest ) {
            greatest = val2;
         }
         val3 = Math.Abs(tempCY - tempLT);
         if( val3 > greatest ) {
            greatest = val3;
         }
         periodTotal += greatest;
         today += 1;
      }
      prevATR = periodTotal / optInTimePeriod;
      /* Skip the Average True Range's unstable period. Taking the count from the
       * lookback rather than naming the setting keeps the two from disagreeing.
       */
      i = lookbackTotal - optInTimePeriod;
      while( i != 0 ) {
         tempLT = inLow[today];
         tempHT = inHigh[today];
         tempCY = inClose[today - 1];
         greatest = tempHT - tempLT;
         /* val1 */
         val2 = Math.Abs(tempCY - tempHT);
         if( val2 > greatest ) {
            greatest = val2;
         }
         val3 = Math.Abs(tempCY - tempLT);
         if( val3 > greatest ) {
            greatest = val3;
         }
         prevATR *= optInTimePeriod - 1;
         prevATR += greatest;
         prevATR /= optInTimePeriod;
         today += 1;
         i -= 1;
      }
      /* The first bar has no band to ratchet against and no trend to carry, so
       * both bands take their unclamped value and the trend is seeded long, as
       * ta4j's SuperTrendIndicator does. The formula does not settle this and the
       * published implementations are split on it, so the choice is a convention:
       * it stays visible for as long as the first trend lasts, and on a series
       * whose close never leaves the band it never washes out at all.
       */
      medianPrice = (inHigh[startIdx] + inLow[startIdx]) / 2.0;
      band = optInMultiplier * prevATR;
      finalUpper = medianPrice + band;
      finalLower = medianPrice - band;
      isUptrend = 1;
      prevClose = inClose[startIdx];
      outReal[0 * outStride] = finalLower;
      outInteger[0 * outStride] = 1;
      outIdx = 1;
      today = startIdx + 1;
      while( today <= endIdx ) {
         tempLT = inLow[today];
         tempHT = inHigh[today];
         tempCY = inClose[today - 1];
         greatest = tempHT - tempLT;
         /* val1 */
         val2 = Math.Abs(tempCY - tempHT);
         if( val2 > greatest ) {
            greatest = val2;
         }
         val3 = Math.Abs(tempCY - tempLT);
         if( val3 > greatest ) {
            greatest = val3;
         }
         prevATR *= optInTimePeriod - 1;
         prevATR += greatest;
         prevATR /= optInTimePeriod;
         medianPrice = (tempHT + tempLT) / 2.0;
         band = optInMultiplier * prevATR;
         basicUpper = medianPrice + band;
         basicLower = medianPrice - band;
         /* Each band ratchets toward price and is released only by a close on its
          * far side. Nothing keeps the two ordered -- each is released by its own
          * condition, so the lower one can end up above the upper one -- and where
          * that happens a flip puts the emitted band on the far side of the close.
          * The line is therefore NOT monotone within a trend, and the flag does not
          * always say which side of the line price is on; both read as invariants
          * and neither is one.
          */
         if( basicUpper < finalUpper || prevClose > finalUpper ) {
            finalUpper = basicUpper;
         }
         if( basicLower > finalLower || prevClose < finalLower ) {
            finalLower = basicLower;
         }
         closeToday = inClose[today];
         /* The trend is carried in its own variable rather than recovered by
          * comparing the previous output against the previous bands. The two
          * carried bands do coincide on some bars -- always on a bar with no true
          * range, and on some of them at a multiplier of zero -- and there that
          * comparison cannot tell them apart, so it would silently lose the
          * hysteresis on exactly the flat input a corpus of real prices lacks.
          */
         if( (isUptrend) != 0 ) {
            if( closeToday < finalLower ) {
               isUptrend = 0;
            }
         } else if( closeToday > finalUpper ) {
            isUptrend = 1;
         }
         if( (isUptrend) != 0 ) {
            outReal[outIdx * outStride] = finalLower;
            outInteger[outIdx * outStride] = 1;
         } else {
            outReal[outIdx * outStride] = finalUpper;
            outInteger[outIdx * outStride] = 0 - 1;
         }
         prevClose = closeToday;
         outIdx += 1;
         today += 1;
      }
      outBegIdx = startIdx;
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      sp.optInTimePeriod = optInTimePeriod;
      sp.optInMultiplier = optInMultiplier;
      sp.isUptrend = isUptrend;
      sp.prevATR = prevATR;
      sp.finalUpper = finalUpper;
      sp.finalLower = finalLower;
      sp.prevClose = prevClose;
      sp.lag1_inClose = inClose[historyLen - 1];
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      sp.cur_outInteger = outInteger[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* SupertrendOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal SupertrendStream SupertrendOpenAndFillInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, double optInMultiplier, out int outBegIdx, out int outNBElement, Span<double> outReal, Span<int> outInteger )
   {
      SupertrendStream sp = new SupertrendStream(this);
      RetCode retCode = SupertrendOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInTimePeriod, optInMultiplier, out outBegIdx, out outNBElement, outReal, outInteger, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("SUPERTREND", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind SupertrendOpen (composition seam). */
   internal SupertrendStream SupertrendOpenInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, double optInMultiplier )
   {
      SupertrendStream sp = new SupertrendStream(this);
      double[] sink_outReal = new double[1];
      int[] sink_outInteger = new int[1];
      RetCode retCode = SupertrendOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInTimePeriod, optInMultiplier, out int outBegIdx, out int outNBElement, sink_outReal, sink_outInteger, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("SUPERTREND", "open", retCode);
   }

   /// <summary>Open a live <c>SUPERTREND</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="SupertrendStream.Value"/> starts at the last
   /// history bar's value — bit-identical to what <c>SUPERTREND</c> reports for
   /// that bar.</para>
   /// <para>The history must hold at least <c>SUPERTREND_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>SupertrendOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="SUPERTREND_Lookback"/> for its
   /// default and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInMultiplier">As in the batch call; see <see cref="SUPERTREND_Lookback"/> for its
   /// default and range (<c>-4e37</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>SUPERTREND_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public SupertrendStream SupertrendOpen( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInTimePeriod, double optInMultiplier )
   {
      if( inHigh.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "SUPERTREND open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "SUPERTREND open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("SUPERTREND open: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TaLibArgumentException("SUPERTREND open: inClose is empty", nameof(inClose), RetCode.BadParam);
      RequireHistoryLength("SUPERTREND", "open", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("SUPERTREND", "open", "inClose", inClose.Length, inHigh.Length);
      return SupertrendOpenInternal(inHigh, inLow, inClose, 0, optInTimePeriod, optInMultiplier);
   }

   /// <summary><c>SupertrendOpen</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>SUPERTREND</c> produces
   /// over the same series, so no separate batch call is needed for the warm-up
   /// plot.</para>
   /// <para>Output arrays must hold <c>historyLen - SUPERTREND_Lookback(...)</c>
   /// values and must not alias the inputs or each other — this path writes the
   /// outputs and then reads the input tail to seed its rings, so the batch
   /// tier's in-place allowance does not carry over here. Both are checked
   /// before anything is written, so an undersized span is an
   /// <c>ArgumentException</c> naming it rather than a fault from inside the
   /// fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="SupertrendStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="SUPERTREND_Lookback"/> for its
   /// default and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInMultiplier">As in the batch call; see <see cref="SUPERTREND_Lookback"/> for its
   /// default and range (<c>-4e37</c> selects the default).</param>
   /// <param name="outReal">The SuperTrend line: the band the trend is currently riding. Must hold at
   /// least <c>historyLen - SUPERTREND_Lookback(...)</c> values.</param>
   /// <param name="outInteger">Trend direction: +1 while the trend rides the lower band, -1 while it
   /// rides the upper one. Must hold at least <c>historyLen -
   /// SUPERTREND_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>SUPERTREND_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public SupertrendStream SupertrendOpenAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInTimePeriod, double optInMultiplier, Span<double> outReal, Span<int> outInteger )
   {
      if( inHigh.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "SUPERTREND openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "SUPERTREND openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("SUPERTREND openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TaLibArgumentException("SUPERTREND openAndFill: inClose is empty", nameof(inClose), RetCode.BadParam);
      int guardOutLen = OpenFillCount("SUPERTREND", "openAndFill", inHigh.Length, SUPERTREND_Lookback(optInTimePeriod, optInMultiplier));
      RequireHistoryLength("SUPERTREND", "openAndFill", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("SUPERTREND", "openAndFill", "inClose", inClose.Length, inHigh.Length);
      RequireFillLength("SUPERTREND", "openAndFill", "outReal", outReal.Length, guardOutLen);
      RequireFillLength("SUPERTREND", "openAndFill", "outInteger", outInteger.Length, guardOutLen);
      if( outReal.Overlaps(inHigh) || outReal.Overlaps(inLow) || outReal.Overlaps(inClose) ) {
         throw StreamFailure("SUPERTREND", "openAndFill", RetCode.BadParam);
      }
      return SupertrendOpenAndFillInternal(inHigh, inLow, inClose, 0, optInTimePeriod, optInMultiplier, out _, out _, outReal, outInteger);
   }
