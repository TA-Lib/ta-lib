   /// <summary>
   /// Slow Stochastic oscillator: locates the close within the high-low range
   /// over a lookback period, then double-smooths it. Returns the Slow-%K and
   /// Slow-%D lines. SlowK/SlowD &gt; 80 overbought, &lt; 20 oversold; %K
   /// crossing %D signals momentum shifts.
   /// </summary>
   /// <remarks>
   /// <b>Formula</b>
   /// <code>
   /// FastK = 100*(Close - LL_n)/(HH_n - LL_n), n = FastK_Period (LL/HH = lowest low / highest high over n)
   /// SlowK = MA(FastK, SlowK_Period, SlowK_MAType)
   /// SlowD = MA(SlowK, SlowD_Period, SlowD_MAType)
   /// </code>
   /// <list type="bullet">
   /// <item><description>When the high-low range over the window is zero, the raw stochastic is set to 0 instead of being undefined.</description></item>
   /// </list>
   /// <para>
   /// This is the <c>float[]</c> overload: input elements are widened to
   /// <c>double</c> as they are read and all arithmetic is performed in
   /// <c>double</c>, so a result beyond <c>float</c> range is still
   /// representable.
   /// </para>
   /// <para>
   /// Values are written only where the indicator is defined. The returned
   /// <see cref="OutRange"/> says where they start and how many there are;
   /// nothing outside that range is touched, and the library never pads with
   /// NaN. A valid range shorter than <c>STOCH_Lookback</c> is a <b>success with
   /// no values</b> (<c>Count == 0</c>), not an error.
   /// </para>
   /// </remarks>
   /// <param name="startIdx">First bar of the requested range (inclusive).</param>
   /// <param name="endIdx">Last bar of the requested range (inclusive).</param>
   /// <param name="inHigh">High price of each bar.</param>
   /// <param name="inLow">Low price of each bar.</param>
   /// <param name="inClose">Close price of each bar.</param>
   /// <param name="optInFastK_Period">Lookback window for the raw %K high-low range (default 5; range 1..100000;
   /// <c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowK_Period">Smoothing period turning FastK into SlowK (default 3; range 1..100000;
   /// <c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowK_MAType">MA type used to smooth into SlowK (default 0 = SMA; values: 0=SMA, 1=EMA,
   /// 2=WMA, 3=DEMA, 4=TEMA, 5=TRIMA, 6=KAMA, 7=MAMA, 8=T3, 9=HMA, 10=DISABLED,
   /// 11=DEFAULT; <c>MAType.DEFAULT</c> (or <c>(MAType)int.MinValue</c>) selects
   /// the default).</param>
   /// <param name="optInSlowD_Period">Smoothing period for the SlowD signal line (default 3; range 1..100000;
   /// <c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowD_MAType">MA type used for the SlowD line (default 0 = SMA; values: 0=SMA, 1=EMA,
   /// 2=WMA, 3=DEMA, 4=TEMA, 5=TRIMA, 6=KAMA, 7=MAMA, 8=T3, 9=HMA, 10=DISABLED,
   /// 11=DEFAULT; <c>MAType.DEFAULT</c> (or <c>(MAType)int.MinValue</c>) selects
   /// the default).</param>
   /// <param name="outSlowK">Raw FastK smoothed by SlowK_Period MA. Must hold at least <c>endIdx -
   /// startIdx + 1</c> values.</param>
   /// <param name="outSlowD">Signal line: SlowK smoothed by SlowD_Period MA. Must hold at least
   /// <c>endIdx - startIdx + 1</c> values.</param>
   /// <returns>The range written: <c>BegIdx</c> is the first bar with a value,
   /// <c>Count</c> how many were written.</returns>
   /// <exception cref="System.ArgumentOutOfRangeException"><c>startIdx</c> or <c>endIdx</c> is negative or above
   /// <see cref="Core.MAX_INDEX"/>, or <c>endIdx &lt; startIdx</c>.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or two outputs
   /// share one array.</exception>
   /// <exception cref="System.NullReferenceException">An input or output array is null. (Unlike the C library, the managed tier
   /// does not pre-validate nulls; the first array access throws.)</exception>
   public OutRange STOCH( int startIdx,
                          int endIdx,
                          float[] inHigh,
                          float[] inLow,
                          float[] inClose,
                          int optInFastK_Period,
                          int optInSlowK_Period,
                          MAType optInSlowK_MAType,
                          int optInSlowD_Period,
                          MAType optInSlowD_MAType,
                          double[] outSlowK,
                          double[] outSlowD )
   {
      RetCode retCode = STOCH(startIdx, endIdx, inHigh, inLow, inClose, optInFastK_Period, optInSlowK_Period, optInSlowK_MAType, optInSlowD_Period, optInSlowD_MAType, out int outBegIdx, out int outNBElement, outSlowK, outSlowD);
      if( retCode != RetCode.Success ) {
         throw Failure("STOCH", retCode);
      }
      return new OutRange(outBegIdx, outNBElement);
   }
