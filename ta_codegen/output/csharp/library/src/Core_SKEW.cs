   /// element type in this overload, so the two can never be the same span:
   /// there is no in-place case to allow, and any overlap of their byte ranges
   /// is rejected.</description></item>
   /// </list>
   /// </exception>
   /// <seealso cref="Core.Kurtosis(int, int, ReadOnlySpan{double}, int, Span{double})"/>
   /// <seealso cref="Core.Var(int, int, ReadOnlySpan{double}, int, double, Span{double})"/>
   /// <seealso cref="Core.Stddev(int, int, ReadOnlySpan{double}, int, double, Span{double})"/>
   public OutRange Skew( int startIdx,
                         int endIdx,
                         ReadOnlySpan<float> inReal,
                         int optInTimePeriod,
                         Span<double> outReal )
   {
      int guardStart = ClampedStart(startIdx, endIdx, SkewLookback(optInTimePeriod));
      int guardInLen = guardStart < 0 ? 0 : endIdx + 1;
      int guardOutLen = guardStart < 0 || guardStart > endIdx ? 0 : endIdx - guardStart + 1;
      RequireLength("SKEW", "inReal", inReal.Length, guardInLen);
      if( guardStart >= 0 ) RequirePresent("SKEW", "outReal", outReal.Length);
      RequireLength("SKEW", "outReal", outReal.Length, guardOutLen);
      RetCode retCode = SkewImpl(startIdx, endIdx, inReal, optInTimePeriod, out int outBegIdx, out int outNBElement, outReal);
      if( retCode != RetCode.Success ) {
         throw Failure("SKEW", retCode);
      }
      return new OutRange(outBegIdx, outNBElement);
   }
