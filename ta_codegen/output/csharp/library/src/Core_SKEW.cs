   /// <summary>A live <c>SKEW</c> stream: one value per closed bar, bit-identical to
   /// <c>SKEW</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.SkewOpen"/>. There is no close and nothing to
   /// dispose — the handle is ordinary managed state, and an unreferenced handle
   /// is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class SkewStream
   {
      internal Core core;
      internal int optInTimePeriod;
      internal double shift;
      internal double total1;
      internal double total2;
      internal double total3;
      internal double dPeriod;
      internal double coef;
      internal double invPeriod;
      internal double peak2;
      internal int trailingIdx;
      internal int nbInitialElementNeeded;
      internal int barsSinceReseed;
      internal int reseedPeriod;
      internal int j;
      internal int i;
      internal int xMask;
      internal double[] x_inReal = [];
      internal double cur_outReal;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal SkewStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Skew</c> reports over the same bars: the opener sets it
      /// to <c>(lookback, historyLen - lookback)</c>, every accepted <c>Update</c>
      /// adds one to the count — a rejected one changes nothing, and neither does
      /// <c>Peek</c> — and <c>Clone</c> carries it verbatim. A plain <c>Open</c>
      /// hands back only the last value, a subset of this range, because the caller
      /// chose not to take the fill.</para>
      /// <para>The last bar it can reach is <see cref="Core.IndexMax"/>; past that
      /// <c>Update</c> and <c>Advance</c> throw.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      /// <summary>Count one bar this stream was not fed: <see cref="OutRange"/> advances by
      /// one and nothing else moves.</summary>
      /// <remarks>
      /// <para><see cref="Value"/> keeps answering the previous output, which is this
      /// bar's output too. For a bar the caller leaves out: one an <c>Update</c>
      /// rejected and that will not be re-fed, or a session with no print. Without
      /// it two handles on one feed drift a bar apart when only one of them skips.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, the last one the batch tier
      /// can address and the last this handle will count. <c>Update</c> throws the
      /// same there.</para>
      /// </remarks>
      public void Advance()
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("SKEW", "advance", RetCode.OutOfRangeEndIndex);
         outRangeCount++;
      }

      internal SkewStream( SkewStream other )
      {
         this.core = other.core;
         this.optInTimePeriod = other.optInTimePeriod;
         this.shift = other.shift;
         this.total1 = other.total1;
         this.total2 = other.total2;
         this.total3 = other.total3;
         this.dPeriod = other.dPeriod;
         this.coef = other.coef;
         this.invPeriod = other.invPeriod;
         this.peak2 = other.peak2;
         this.trailingIdx = other.trailingIdx;
         this.nbInitialElementNeeded = other.nbInitialElementNeeded;
         this.barsSinceReseed = other.barsSinceReseed;
         this.reseedPeriod = other.reseedPeriod;
         this.j = other.j;
         this.i = other.i;
         this.xMask = other.xMask;
         this.x_inReal = new double[other.x_inReal.Length];
         Array.Copy( other.x_inReal, this.x_inReal, other.x_inReal.Length );
         this.cur_outReal = other.cur_outReal;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so nothing moves — <see cref="OutRange"/> included — and
      /// <see cref="Value"/> still answers the previous value. Re-feed the bar when
      /// a corrected value arrives, or call <see cref="Advance"/> to count it and
      /// carry on; two handles on one feed drift a bar apart if neither happens.
      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, which no re-feed clears: the
      /// handle has run out of index domain and only a shorter history can start a
      /// new one.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inReal )
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("SKEW", "update", RetCode.OutOfRangeEndIndex);
         if( !double.IsFinite(inReal) ) throw Core.NonFiniteBar("SKEW", "update", nameof(inReal));
         core.SkewStepImpl(this, inReal);
         outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.IndexMax"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public double Peek( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.NonFiniteBar("SKEW", "peek", nameof(inReal));
         SkewStream sp = this;
         double tempReal = 0.0;
         double dev = 0.0;
         double dev2 = 0.0;
         double residue = 0.0;
         double residueSq = 0.0;
         double moment2 = 0.0;
         double moment3 = 0.0;
         double skewness = 0.0;
         double denominator = 0.0;
         int windowStart = 0;
         int barsSinceReseed = sp.barsSinceReseed;
         double cur_outReal = 0.0;
         int j = sp.j;
         double peak2 = sp.peak2;
         double shift = sp.shift;
         double total1 = sp.total1;
         double total2 = sp.total2;
         double total3 = sp.total3;
         int trailingIdx = sp.trailingIdx;
         int pkSlot0 = -1;
         double pkVal0 = 0.0;
         pkSlot0 = sp.i & sp.xMask;
         pkVal0 = inReal;
         dev = (((sp.i & sp.xMask) != pkSlot0) ? sp.x_inReal[sp.i & sp.xMask] : pkVal0) - shift;
         dev2 = dev * dev;
         total1 += dev;
         total2 += dev2;
         total3 += dev2 * dev;
         peak2 = MaxGt(total2, peak2);
         residue = total1 * sp.invPeriod;
         residueSq = residue * residue;
         moment2 = total2 - sp.dPeriod * residueSq;
         moment3 = Math.FusedMultiplyAdd(2.0 * sp.dPeriod * residueSq, residue, total3 - 3.0 * residue * total2);
         /* Each bar rounds the cubic sum by at most eps times the peak second
          * sum to the power 3/2, so G1's error grows as (peak/M2)^(3/2), at most
          * 1000x before the rebuild at 1% of the peak.
          */
         barsSinceReseed -= 1;
         if( moment2 < 0.01 * peak2 || barsSinceReseed <= 0 ) {
            barsSinceReseed = sp.reseedPeriod;
            windowStart = sp.i - sp.nbInitialElementNeeded;
            tempReal = 0.0;
            for( j = windowStart; j <= sp.i; j += 1 ) {
               tempReal += ((j & sp.xMask) != pkSlot0) ? sp.x_inReal[j & sp.xMask] : pkVal0;
            }
            shift = tempReal * sp.invPeriod;
            total1 = 0.0;
            total2 = 0.0;
            total3 = 0.0;
            for( j = windowStart; j <= sp.i; j += 1 ) {
               dev = (((j & sp.xMask) != pkSlot0) ? sp.x_inReal[j & sp.xMask] : pkVal0) - shift;
               dev2 = dev * dev;
               total1 += dev;
               total2 += dev2;
               total3 += dev2 * dev;
            }
            residue = total1 * sp.invPeriod;
            residueSq = residue * residue;
            moment2 = total2 - sp.dPeriod * residueSq;
            moment3 = Math.FusedMultiplyAdd(2.0 * sp.dPeriod * residueSq, residue, total3 - 3.0 * residue * total2);
            /* The left-to-right sum can miss the mean by more than the window's
             * spread, and the trigger would then fire again on every bar. Adding
             * the measured miss back lands within about an ulp of the mean, where
             * a flat window's deviations are exactly 0. Keep this threshold the
             * trigger's.
             */
            if( moment2 < 0.01 * total2 ) {
               shift += residue;
               total1 = 0.0;
               total2 = 0.0;
               total3 = 0.0;
               for( j = windowStart; j <= sp.i; j += 1 ) {
                  dev = (((j & sp.xMask) != pkSlot0) ? sp.x_inReal[j & sp.xMask] : pkVal0) - shift;
                  dev2 = dev * dev;
                  total1 += dev;
                  total2 += dev2;
                  total3 += dev2 * dev;
               }
               residue = total1 * sp.invPeriod;
               residueSq = residue * residue;
               moment2 = total2 - sp.dPeriod * residueSq;
               moment3 = Math.FusedMultiplyAdd(2.0 * sp.dPeriod * residueSq, residue, total3 - 3.0 * residue * total2);
            }
            peak2 = total2;
         }
         /* A window of equal values is symmetric, and reaches here with every
          * deviation exactly 0. The bound is the smallest normal double, not a
          * scale: a denominator under it comes with cubed deviations that have
          * lost their precision in the subnormals.
          */
         denominator = moment2 * Math.Sqrt(moment2);
         if( denominator < 2.2250738585072014e-308 ) {
            skewness = 0.0;
         } else {
            skewness = sp.coef * moment3 / denominator;
         }
         /* inReal and outReal may be the same buffer: read the trailing value
          * before the output write.
          */
         dev = (((trailingIdx & sp.xMask) != pkSlot0) ? sp.x_inReal[trailingIdx & sp.xMask] : pkVal0) - shift;
         dev2 = dev * dev;
         total1 -= dev;
         total2 -= dev2;
         total3 -= dev2 * dev;
         trailingIdx += 1;
         cur_outReal = skewness;
         return cur_outReal;
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public SkewStream Clone()
      {
         return new SkewStream(this);
      }
   }

   private void SkewStepImpl( SkewStream sp, double inReal )
   {
      double tempReal = 0.0;
      double dev = 0.0;
      double dev2 = 0.0;
      double residue = 0.0;
      double residueSq = 0.0;
      double moment2 = 0.0;
      double moment3 = 0.0;
      double skewness = 0.0;
      double denominator = 0.0;
      int windowStart = 0;
      sp.x_inReal[sp.i & sp.xMask] = inReal;
      dev = sp.x_inReal[sp.i & sp.xMask] - sp.shift;
      dev2 = dev * dev;
      sp.total1 += dev;
      sp.total2 += dev2;
      sp.total3 += dev2 * dev;
      sp.peak2 = MaxGt(sp.total2, sp.peak2);
      residue = sp.total1 * sp.invPeriod;
      residueSq = residue * residue;
      moment2 = sp.total2 - sp.dPeriod * residueSq;
      moment3 = Math.FusedMultiplyAdd(2.0 * sp.dPeriod * residueSq, residue, sp.total3 - 3.0 * residue * sp.total2);
      /* Each bar rounds the cubic sum by at most eps times the peak second
       * sum to the power 3/2, so G1's error grows as (peak/M2)^(3/2), at most
       * 1000x before the rebuild at 1% of the peak.
       */
      sp.barsSinceReseed -= 1;
      if( moment2 < 0.01 * sp.peak2 || sp.barsSinceReseed <= 0 ) {
         sp.barsSinceReseed = sp.reseedPeriod;
         windowStart = sp.i - sp.nbInitialElementNeeded;
         tempReal = 0.0;
         for( sp.j = windowStart; sp.j <= sp.i; sp.j += 1 ) {
            tempReal += sp.x_inReal[sp.j & sp.xMask];
         }
         sp.shift = tempReal * sp.invPeriod;
         sp.total1 = 0.0;
         sp.total2 = 0.0;
         sp.total3 = 0.0;
         for( sp.j = windowStart; sp.j <= sp.i; sp.j += 1 ) {
            dev = sp.x_inReal[sp.j & sp.xMask] - sp.shift;
            dev2 = dev * dev;
            sp.total1 += dev;
            sp.total2 += dev2;
            sp.total3 += dev2 * dev;
         }
         residue = sp.total1 * sp.invPeriod;
         residueSq = residue * residue;
         moment2 = sp.total2 - sp.dPeriod * residueSq;
         moment3 = Math.FusedMultiplyAdd(2.0 * sp.dPeriod * residueSq, residue, sp.total3 - 3.0 * residue * sp.total2);
         /* The left-to-right sum can miss the mean by more than the window's
          * spread, and the trigger would then fire again on every bar. Adding
          * the measured miss back lands within about an ulp of the mean, where
          * a flat window's deviations are exactly 0. Keep this threshold the
          * trigger's.
          */
         if( moment2 < 0.01 * sp.total2 ) {
            sp.shift += residue;
            sp.total1 = 0.0;
            sp.total2 = 0.0;
            sp.total3 = 0.0;
            for( sp.j = windowStart; sp.j <= sp.i; sp.j += 1 ) {
               dev = sp.x_inReal[sp.j & sp.xMask] - sp.shift;
               dev2 = dev * dev;
               sp.total1 += dev;
               sp.total2 += dev2;
               sp.total3 += dev2 * dev;
            }
            residue = sp.total1 * sp.invPeriod;
            residueSq = residue * residue;
            moment2 = sp.total2 - sp.dPeriod * residueSq;
            moment3 = Math.FusedMultiplyAdd(2.0 * sp.dPeriod * residueSq, residue, sp.total3 - 3.0 * residue * sp.total2);
         }
         sp.peak2 = sp.total2;
      }
      /* A window of equal values is symmetric, and reaches here with every
       * deviation exactly 0. The bound is the smallest normal double, not a
       * scale: a denominator under it comes with cubed deviations that have
       * lost their precision in the subnormals.
       */
      denominator = moment2 * Math.Sqrt(moment2);
      if( denominator < 2.2250738585072014e-308 ) {
         skewness = 0.0;
      } else {
         skewness = sp.coef * moment3 / denominator;
      }
      /* inReal and outReal may be the same buffer: read the trailing value
       * before the output write.
       */
      dev = sp.x_inReal[sp.trailingIdx & sp.xMask] - sp.shift;
      dev2 = dev * dev;
      sp.total1 -= dev;
      sp.total2 -= dev2;
      sp.total3 -= dev2 * dev;
      sp.trailingIdx += 1;
      sp.cur_outReal = skewness;
      sp.i += 1;
   }

   private RetCode SkewOpenImpl( SkewStream sp, ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double tempReal = 0;
      double shift = 0;
      double total1 = 0;
      double total2 = 0;
      double total3 = 0;
      double dev = 0;
      double dev2 = 0;
      double residue = 0;
      double residueSq = 0;
      double moment2 = 0;
      double moment3 = 0;
      double dPeriod = 0;
      double coef = 0;
      double invPeriod = 0;
      double skewness = 0;
      double peak2 = 0;
      double denominator = 0;
      int i = 0;
      int j = 0;
      int outIdx = 0;
      int trailingIdx = 0;
      int windowStart = 0;
      int nbInitialElementNeeded = 0;
      int barsSinceReseed = 0;
      int reseedPeriod = 0;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > IndexMax + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 30;
      } else if( optInTimePeriod < 3 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      nbInitialElementNeeded = optInTimePeriod - 1;
      if( startIdx < nbInitialElementNeeded ) {
         startIdx = nbInitialElementNeeded;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      /* G1 = n*sqrt(n-1)/(n-2) * M3 / M2^(3/2), over the central sums M2 and
       * M3. The n-2 is why the range starts at 3, and the n-1 lookback hands the
       * estimator a full window at the first emitted bar.
       */
      dPeriod = (double)optInTimePeriod;
      coef = dPeriod * Math.Sqrt(dPeriod - 1.0) / (dPeriod - 2.0);
      invPeriod = 1.0 / dPeriod;
      /* Deviations are measured against a shift near the window, and the
       * central sums are recovered from them below. The periodic rebuild bounds
       * the rounding the slide accumulates, and is the only way out of a NaN or
       * Inf input, on which every trigger comparison is false.
       */
      reseedPeriod = 32 * optInTimePeriod;
      trailingIdx = startIdx - nbInitialElementNeeded;
      shift = inReal[trailingIdx];
      total1 = 0.0;
      total2 = 0.0;
      total3 = 0.0;
      for( j = trailingIdx; j < startIdx; j += 1 ) {
         dev = inReal[j] - shift;
         dev2 = dev * dev;
         total1 += dev;
         total2 += dev2;
         total3 += dev2 * dev;
      }
      i = startIdx;
      outIdx = 0;
      barsSinceReseed = reseedPeriod;
      peak2 = total2;
      do {
         dev = inReal[i] - shift;
         dev2 = dev * dev;
         total1 += dev;
         total2 += dev2;
         total3 += dev2 * dev;
         peak2 = MaxGt(total2, peak2);
         residue = total1 * invPeriod;
         residueSq = residue * residue;
         moment2 = total2 - dPeriod * residueSq;
         moment3 = Math.FusedMultiplyAdd(2.0 * dPeriod * residueSq, residue, total3 - 3.0 * residue * total2);
         /* Each bar rounds the cubic sum by at most eps times the peak second
          * sum to the power 3/2, so G1's error grows as (peak/M2)^(3/2), at most
          * 1000x before the rebuild at 1% of the peak.
          */
         barsSinceReseed -= 1;
         if( moment2 < 0.01 * peak2 || barsSinceReseed <= 0 ) {
            barsSinceReseed = reseedPeriod;
            windowStart = i - nbInitialElementNeeded;
            tempReal = 0.0;
            for( j = windowStart; j <= i; j += 1 ) {
               tempReal += inReal[j];
            }
            shift = tempReal * invPeriod;
            total1 = 0.0;
            total2 = 0.0;
            total3 = 0.0;
            for( j = windowStart; j <= i; j += 1 ) {
               dev = inReal[j] - shift;
               dev2 = dev * dev;
               total1 += dev;
               total2 += dev2;
               total3 += dev2 * dev;
            }
            residue = total1 * invPeriod;
            residueSq = residue * residue;
            moment2 = total2 - dPeriod * residueSq;
            moment3 = Math.FusedMultiplyAdd(2.0 * dPeriod * residueSq, residue, total3 - 3.0 * residue * total2);
            /* The left-to-right sum can miss the mean by more than the window's
             * spread, and the trigger would then fire again on every bar. Adding
             * the measured miss back lands within about an ulp of the mean, where
             * a flat window's deviations are exactly 0. Keep this threshold the
             * trigger's.
             */
            if( moment2 < 0.01 * total2 ) {
               shift += residue;
               total1 = 0.0;
               total2 = 0.0;
               total3 = 0.0;
               for( j = windowStart; j <= i; j += 1 ) {
                  dev = inReal[j] - shift;
                  dev2 = dev * dev;
                  total1 += dev;
                  total2 += dev2;
                  total3 += dev2 * dev;
               }
               residue = total1 * invPeriod;
               residueSq = residue * residue;
               moment2 = total2 - dPeriod * residueSq;
               moment3 = Math.FusedMultiplyAdd(2.0 * dPeriod * residueSq, residue, total3 - 3.0 * residue * total2);
            }
            peak2 = total2;
         }
         /* A window of equal values is symmetric, and reaches here with every
          * deviation exactly 0. The bound is the smallest normal double, not a
          * scale: a denominator under it comes with cubed deviations that have
          * lost their precision in the subnormals.
          */
         denominator = moment2 * Math.Sqrt(moment2);
         if( denominator < 2.2250738585072014e-308 ) {
            skewness = 0.0;
         } else {
            skewness = coef * moment3 / denominator;
         }
         /* inReal and outReal may be the same buffer: read the trailing value
          * before the output write.
          */
         dev = inReal[trailingIdx] - shift;
         dev2 = dev * dev;
         total1 -= dev;
         total2 -= dev2;
         total3 -= dev2 * dev;
         trailingIdx += 1;
         outReal[outIdx++ * outStride] = skewness;
         i += 1;
      } while( i <= endIdx );
      outNBElement = outIdx;
      outBegIdx = startIdx;
      /* Capture the live batch state into the handle. */
      int capX = i - trailingIdx + 1;
      if( capX < 1 || capX > historyLen ) {
         return RetCode.InternalError;
      }
      int physX = 1;
      while( physX < capX ) {
         physX <<= 1;
      }
      double[] capX_inReal = new double[physX];
      for( int fillJ = historyLen - capX; fillJ < historyLen; fillJ++ ) {
         capX_inReal[fillJ & (physX - 1)] = inReal[fillJ];
      }
      sp.optInTimePeriod = optInTimePeriod;
      sp.shift = shift;
      sp.total1 = total1;
      sp.total2 = total2;
      sp.total3 = total3;
      sp.dPeriod = dPeriod;
      sp.coef = coef;
      sp.invPeriod = invPeriod;
      sp.peak2 = peak2;
      sp.trailingIdx = trailingIdx;
      sp.nbInitialElementNeeded = nbInitialElementNeeded;
      sp.barsSinceReseed = barsSinceReseed;
      sp.reseedPeriod = reseedPeriod;
      sp.j = j;
      sp.i = i;
      sp.xMask = physX - 1;
      sp.x_inReal = capX_inReal;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* SkewOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal SkewStream SkewOpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      SkewStream sp = new SkewStream(this);
      RetCode retCode = SkewOpenImpl(sp, inReal, startIdx, optInTimePeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("SKEW", "openAndFill", nameof(inReal), inReal.Length, startIdx, SkewLookback(optInTimePeriod));
      }
      throw StreamFailure("SKEW", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind SkewOpen (composition seam). */
   internal SkewStream SkewOpenInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod )
   {
      SkewStream sp = new SkewStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = SkewOpenImpl(sp, inReal, startIdx, optInTimePeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("SKEW", "open", nameof(inReal), inReal.Length, startIdx, SkewLookback(optInTimePeriod));
      }
      throw StreamFailure("SKEW", "open", retCode);
   }

   /// <summary>Open a live <c>SKEW</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="SkewStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>SKEW</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>SkewLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>SkewOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">The series to measure. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="SkewLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>SkewLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public SkewStream SkewOpen( ReadOnlySpan<double> inReal, int optInTimePeriod )
   {
      if( inReal.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "SKEW open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "SKEW open: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      return SkewOpenInternal(inReal, 0, optInTimePeriod);
   }

   /// <summary><c>SkewOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>SKEW</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - SkewLookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="SkewStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">The series to measure. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="SkewLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Skewness of the trailing window, or 0 where the window has no spread. Must
   /// hold at least <c>historyLen - SkewLookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>SkewLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public SkewStream SkewOpenAndFill( ReadOnlySpan<double> inReal, int optInTimePeriod, Span<double> outReal )
   {
      if( inReal.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "SKEW openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "SKEW openAndFill: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      int guardOutLen = OpenFillCount("SKEW", "openAndFill", inReal.Length, SkewLookback(optInTimePeriod));
      RequireFillLength("SKEW", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( SameBuffer(outReal, inReal) ) {
         throw StreamFailure("SKEW", "openAndFill", RetCode.BadParam);
      }
      if( guardOutLen > 0 && ( outReal.Overlaps(inReal) ) ) {
         throw StreamFailure("SKEW", "openAndFill", RetCode.BadParam);
      }
      return SkewOpenAndFillInternal(inReal, 0, optInTimePeriod, out _, out _, outReal);
   }
