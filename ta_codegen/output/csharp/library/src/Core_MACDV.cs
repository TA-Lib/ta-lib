   {
      internal Core core;
      internal int optInFastPeriod;
      internal int optInSlowPeriod;
      internal int optInSignalPeriod;
      internal double prevFast;
      internal double prevSlow;
      internal double prevATR;
      internal double prevSignal;
      internal double slowK;
      internal double fastK;
      internal double signalK;
      internal double slowBeta;
      internal double fastBeta;
      internal double signalBeta;
