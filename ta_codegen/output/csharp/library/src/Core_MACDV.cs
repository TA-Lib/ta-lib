   /// <summary>A live <c>MACDV</c> stream: one value per closed bar, bit-identical to
   /// <c>MACDV</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.MacdvOpen"/>. There is no close and nothing to
