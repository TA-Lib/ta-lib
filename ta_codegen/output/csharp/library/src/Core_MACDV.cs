      /// bar's output too. For a bar the caller leaves out: one an <c>Update</c>
      /// rejected and that will not be re-fed, or a session with no print. Without
      /// it two handles on one feed drift a bar apart when only one of them skips.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, the last one the batch tier
      /// can address and the last this handle will count. <c>Update</c> throws the
      /// same there.</para>
      /// </remarks>
      public void Advance()
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("MACDV", "advance", RetCode.OutOfRangeEndIndex);
         outRangeCount++;
      }

      internal MacdvStream( MacdvStream other )
      {
         this.core = other.core;
         this.optInFastPeriod = other.optInFastPeriod;
         this.optInSlowPeriod = other.optInSlowPeriod;
         this.optInSignalPeriod = other.optInSignalPeriod;
         this.prevFast = other.prevFast;
         this.prevSlow = other.prevSlow;
         this.prevATR = other.prevATR;
         this.prevSignal = other.prevSignal;
         this.slowK = other.slowK;
         this.fastK = other.fastK;
         this.signalK = other.signalK;
         this.slowBeta = other.slowBeta;
         this.fastBeta = other.fastBeta;
         this.signalBeta = other.signalBeta;
         this.wAlpha = other.wAlpha;
         this.wBeta = other.wBeta;
         this.lag1_inClose = other.lag1_inClose;
         this.cur_outMACDV = other.cur_outMACDV;
         this.cur_outMACDVSignal = other.cur_outMACDVSignal;
         this.cur_outMACDVHist = other.cur_outMACDVHist;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so nothing moves — <see cref="OutRange"/> included — and
      /// <see cref="Value"/> still answers the previous value. Re-feed the bar when
      /// a corrected value arrives, or call <see cref="Advance"/> to count it and
      /// carry on; two handles on one feed drift a bar apart if neither happens.
      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, which no re-feed clears: the
      /// handle has run out of index domain and only a shorter history can start a
      /// new one.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>The value at the bar just committed.</returns>
      public MacdvValue Update( double inHigh, double inLow, double inClose )
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("MACDV", "update", RetCode.OutOfRangeEndIndex);
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) ) throw Core.NonFiniteBar("MACDV", "update", !double.IsFinite(inHigh) ? nameof(inHigh) : !double.IsFinite(inLow) ? nameof(inLow) : nameof(inClose));
         core.MacdvStepImpl(this, inHigh, inLow, inClose);
         outRangeCount++;
         return new MacdvValue(cur_outMACDV, cur_outMACDVSignal, cur_outMACDVHist);
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.IndexMax"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public MacdvValue Peek( double inHigh, double inLow, double inClose )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) ) throw Core.NonFiniteBar("MACDV", "peek", !double.IsFinite(inHigh) ? nameof(inHigh) : !double.IsFinite(inLow) ? nameof(inLow) : nameof(inClose));
         MacdvStream sp = this;
         double lineValue = 0.0;
         double tempReal = 0.0;
         double val2 = 0.0;
         double val3 = 0.0;
         double greatest = 0.0;
         double spread = 0.0;
         double tempCY = 0.0;
         double tempLT = 0.0;
         double tempHT = 0.0;
         double cur_outMACDV = 0.0;
         double cur_outMACDVHist = 0.0;
         double cur_outMACDVSignal = 0.0;
         double prevATR = sp.prevATR;
         double prevFast = sp.prevFast;
         double prevSignal = sp.prevSignal;
         double prevSlow = sp.prevSlow;
         tempLT = inLow;
         tempHT = inHigh;
         tempCY = sp.lag1_inClose;
         tempReal = inClose;
         greatest = tempHT - tempLT;
         /* val1 */
         val2 = Math.Abs(tempCY - tempHT);
         greatest = MaxGt(val2, greatest);
         val3 = Math.Abs(tempCY - tempLT);
         greatest = MaxGt(val3, greatest);
         prevATR = Math.FusedMultiplyAdd(sp.wBeta, prevATR, sp.wAlpha * greatest);
         prevFast = Math.FusedMultiplyAdd(sp.fastBeta, prevFast, sp.fastK * tempReal);
         prevSlow = Math.FusedMultiplyAdd(sp.slowBeta, prevSlow, sp.slowK * tempReal);
         spread = prevFast - prevSlow;
         tempReal = Math.Abs(tempReal);
         lineValue = 0.0;
         if( !(Math.Abs(spread) <= 0.00000000000001 * (tempReal)) && !(Math.Abs(prevATR) <= 0.00000000000001 * (tempReal)) ) {
            lineValue = spread / prevATR * 100.0;
         }
         if( sp.optInSignalPeriod == 1 ) {
            prevSignal = lineValue;
         } else {
            prevSignal = Math.FusedMultiplyAdd(sp.signalBeta, prevSignal, sp.signalK * lineValue);
         }
         cur_outMACDV = lineValue;
         cur_outMACDVSignal = prevSignal;
         cur_outMACDVHist = lineValue - prevSignal;
         return new MacdvValue(cur_outMACDV, cur_outMACDVSignal, cur_outMACDVHist);
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public MacdvValue Value => new MacdvValue(cur_outMACDV, cur_outMACDVSignal, cur_outMACDVHist);

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public MacdvStream Clone()
      {
         return new MacdvStream(this);
      }
   }

   private void MacdvStepImpl( MacdvStream sp, double inHigh, double inLow, double inClose )
   {
      double lineValue = 0.0;
      double tempReal = 0.0;
      double val2 = 0.0;
      double val3 = 0.0;
      double greatest = 0.0;
      double spread = 0.0;
      double tempCY = 0.0;
      double tempLT = 0.0;
      double tempHT = 0.0;
      tempLT = inLow;
      tempHT = inHigh;
      tempCY = sp.lag1_inClose;
      tempReal = inClose;
      greatest = tempHT - tempLT;
      /* val1 */
      val2 = Math.Abs(tempCY - tempHT);
      greatest = MaxGt(val2, greatest);
      val3 = Math.Abs(tempCY - tempLT);
      greatest = MaxGt(val3, greatest);
      sp.prevATR = Math.FusedMultiplyAdd(sp.wBeta, sp.prevATR, sp.wAlpha * greatest);
      sp.prevFast = Math.FusedMultiplyAdd(sp.fastBeta, sp.prevFast, sp.fastK * tempReal);
      sp.prevSlow = Math.FusedMultiplyAdd(sp.slowBeta, sp.prevSlow, sp.slowK * tempReal);
      spread = sp.prevFast - sp.prevSlow;
      tempReal = Math.Abs(tempReal);
      lineValue = 0.0;
      if( !(Math.Abs(spread) <= 0.00000000000001 * (tempReal)) && !(Math.Abs(sp.prevATR) <= 0.00000000000001 * (tempReal)) ) {
         lineValue = spread / sp.prevATR * 100.0;
      }
      if( sp.optInSignalPeriod == 1 ) {
         sp.prevSignal = lineValue;
      } else {
         sp.prevSignal = Math.FusedMultiplyAdd(sp.signalBeta, sp.prevSignal, sp.signalK * lineValue);
      }
      sp.cur_outMACDV = lineValue;
      sp.cur_outMACDVSignal = sp.prevSignal;
      sp.cur_outMACDVHist = lineValue - sp.prevSignal;
      sp.lag1_inClose = inClose;
   }

   private RetCode MacdvOpenImpl( MacdvStream sp, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInFastPeriod, int optInSlowPeriod, int optInSignalPeriod, out int outBegIdx, out int outNBElement, Span<double> outMACDV, Span<double> outMACDVSignal, Span<double> outMACDVHist, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double prevFast = 0;
      double prevSlow = 0;
      double prevATR = 0;
      double prevSignal = 0;
      double lineValue = 0;
      double tempReal = 0;
      double slowK = 0;
      double fastK = 0;
      double signalK = 0;
      double slowBeta = 0;
      double fastBeta = 0;
      double signalBeta = 0;
      double wAlpha = 0;
      double wBeta = 0;
      double periodTotal = 0;
      double val2 = 0;
      double val3 = 0;
      double greatest = 0;
      double spread = 0;
      double tempCY = 0;
      double tempLT = 0;
      double tempHT = 0;
      int i = 0;
      int today = 0;
      int outIdx = 0;
      int tempInteger = 0;
      int lookbackTotal = 0;
      int lookbackSignal = 0;
      int lookbackSlow = 0;
      int lookbackFast = 0;
      int lookbackATR = 0;
      int lineIdx = 0;
      int historyLen = inHigh.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > IndexMax + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inLow.Length != inHigh.Length || inClose.Length != inHigh.Length ) {
         return RetCode.BadParam;
      }
      if( optInFastPeriod == int.MinValue ) {
         optInFastPeriod = 12;
      } else if( optInFastPeriod < 2 || optInFastPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInSlowPeriod == int.MinValue ) {
         optInSlowPeriod = 26;
      } else if( optInSlowPeriod < 2 || optInSlowPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInSignalPeriod == int.MinValue ) {
         optInSignalPeriod = 9;
      } else if( optInSignalPeriod < 1 || optInSignalPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      /* Make sure slow is really slower than
       * the fast period! if not, swap...
       */
      if( optInSlowPeriod < optInFastPeriod ) {
         /* swap */
         tempInteger = optInSlowPeriod;
         optInSlowPeriod = optInFastPeriod;
         optInFastPeriod = tempInteger;
      }
      /* ema.c's k and beta for the three EMA, macd.c's spelling. */
      slowBeta = (double)(optInSlowPeriod - 1) / (double)(optInSlowPeriod + 1);
      slowK = 1.0 - slowBeta;
      if( slowBeta < 0.5 ) {
         slowBeta = 1.0 - slowK;
      }
      fastBeta = (double)(optInFastPeriod - 1) / (double)(optInFastPeriod + 1);
      fastK = 1.0 - fastBeta;
      if( fastBeta < 0.5 ) {
         fastBeta = 1.0 - fastK;
      }
      /* A signal period of 1 disables signal-line smoothing: the signal IS the
       * MACD-V line and the histogram is exactly zero. The recursion below, at a
       * k of 1.0 and a beta of 0.0, does not keep the sign of a -0.0 line value;
       * hence the explicit arm at each step.
       */
      signalBeta = (double)(optInSignalPeriod - 1) / (double)(optInSignalPeriod + 1);
      signalK = 1.0 - signalBeta;
      if( signalBeta < 0.5 ) {
         signalBeta = 1.0 - signalK;
      }
      /* atr.c's Wilder coefficients: wAlpha derived FROM wBeta, never the
       * reverse, so that the pair is the one TA_ATR runs.
       */
      wBeta = (double)(optInSlowPeriod - 1) / (double)optInSlowPeriod;
      wAlpha = 1.0 - wBeta;
      lookbackSignal = EmaLookback(optInSignalPeriod);
      lookbackSlow = EmaLookback(optInSlowPeriod);
      lookbackFast = EmaLookback(optInFastPeriod);
      lookbackATR = AtrLookback(optInSlowPeriod);
      lookbackTotal = MacdvLookback(optInFastPeriod, optInSlowPeriod, optInSignalPeriod);
      /* Move up the start index if there is not
       * enough initial data.
       */
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      /* Everything is computed in a single lockstep pass: each bar advances the
       * fast EMA, the slow EMA and the Average True Range, the scaled quotient
       * is the MACD-V line, and each line value is immediately fed into the
       * signal EMA. No temporary buffers.
       *
       * The arithmetic order below is the bit-exactness contract with TA_EMA,
       * TA_MACD and TA_ATR (do not reorder or fuse operations):
       *  - EMA recursion: k*x + beta*prev, with ema.c's k and beta.
       *  - True Range: start from high-low, then compare/replace with the two
       *    previous-close distances, in that order; Wilder smoothing in ONE
       *    statement.
       *  - Each recursion is seeded with the sum of its first 'period' inputs,
       *    accumulated from 0.0 in input order, divided by the period. The
       *    signal EMA is seeded the same way from the first 'signal period'
       *    line values.
       *  - The line is the spread divided by the Average True Range, then
       *    scaled: what a caller dividing TA_MACD by TA_ATR computes.
       *
       * In-place (an output == an input) is supported: outputs at [outIdx] are
       * written only after every input at or before bar startIdx+outIdx was
       * read, and the previous close is re-read from the input one bar back,
       * which no output store has reached.
       */
      /* Each leg is seeded at its OWN lookback and warmed up to lineIdx, the
       * first MACD-V line bar, so each is the shipped function entered at that
       * bar and nothing here over-warms the shorter one: a caller who wants a
       * leg converged sets that function's unstable period, exactly as when
       * calling it directly.
       */
      lineIdx = startIdx - lookbackSignal;
      /* Slow EMA. */
      today = lineIdx - lookbackSlow;
      tempReal = 0.0;
      i = optInSlowPeriod;
      while( i-- > 0 ) {
         tempReal += inClose[today++];
      }
      prevSlow = tempReal / optInSlowPeriod;
      while( today <= lineIdx ) {
         tempReal = inClose[today++];
         prevSlow = Math.FusedMultiplyAdd(slowBeta, prevSlow, slowK * tempReal);
      }
      /* Fast EMA. */
      today = lineIdx - lookbackFast;
      tempReal = 0.0;
      i = optInFastPeriod;
      while( i-- > 0 ) {
         tempReal += inClose[today++];
      }
      prevFast = tempReal / optInFastPeriod;
      while( today <= lineIdx ) {
         tempReal = inClose[today++];
         prevFast = Math.FusedMultiplyAdd(fastBeta, prevFast, fastK * tempReal);
      }
      /* Average True Range: the first True Range consumes a previous close. */
      today = lineIdx - lookbackATR + 1;
      periodTotal = 0.0;
      i = optInSlowPeriod;
      while( i-- > 0 ) {
         tempLT = inLow[today];
         tempHT = inHigh[today];
         tempCY = inClose[today - 1];
         greatest = tempHT - tempLT;
         /* val1 */
         val2 = Math.Abs(tempCY - tempHT);
         greatest = MaxGt(val2, greatest);
         val3 = Math.Abs(tempCY - tempLT);
         greatest = MaxGt(val3, greatest);
         periodTotal += greatest;
         today += 1;
      }
      prevATR = periodTotal / optInSlowPeriod;
      while( today <= lineIdx ) {
         tempLT = inLow[today];
         tempHT = inHigh[today];
         tempCY = inClose[today - 1];
         greatest = tempHT - tempLT;
         /* val1 */
         val2 = Math.Abs(tempCY - tempHT);
         greatest = MaxGt(val2, greatest);
         val3 = Math.Abs(tempCY - tempLT);
         greatest = MaxGt(val3, greatest);
         prevATR = Math.FusedMultiplyAdd(wBeta, prevATR, wAlpha * greatest);
         today += 1;
      }
      /* Without price movement the line answers its neutral point, 0.0 (#570).
       * Both tests are relative to the price: a Wilder average entered before a
       * flat run only decays toward zero, sticking at a subnormal, while the
       * spread keeps a residue of a few ulps of the price, so an exact test lets
       * their quotient grow without bound and overflow.
       */
      spread = prevFast - prevSlow;
      tempReal = Math.Abs(inClose[lineIdx]);
      lineValue = 0.0;
      if( !(Math.Abs(spread) <= 0.00000000000001 * (tempReal)) && !(Math.Abs(prevATR) <= 0.00000000000001 * (tempReal)) ) {
         lineValue = spread / prevATR * 100.0;
      }
      /* Seed the signal EMA with a simple average of the first 'signal period'
       * line values, accumulated as they are produced.
       */
      prevSignal = 0.0;
      prevSignal += lineValue;
      i = optInSignalPeriod - 1;
      while( i-- > 0 ) {
         tempLT = inLow[today];
         tempHT = inHigh[today];
         tempCY = inClose[today - 1];
         tempReal = inClose[today];
         greatest = tempHT - tempLT;
         /* val1 */
         val2 = Math.Abs(tempCY - tempHT);
         greatest = MaxGt(val2, greatest);
         val3 = Math.Abs(tempCY - tempLT);
         greatest = MaxGt(val3, greatest);
         prevATR = Math.FusedMultiplyAdd(wBeta, prevATR, wAlpha * greatest);
         prevFast = Math.FusedMultiplyAdd(fastBeta, prevFast, fastK * tempReal);
         prevSlow = Math.FusedMultiplyAdd(slowBeta, prevSlow, slowK * tempReal);
         spread = prevFast - prevSlow;
         tempReal = Math.Abs(tempReal);
         lineValue = 0.0;
         if( !(Math.Abs(spread) <= 0.00000000000001 * (tempReal)) && !(Math.Abs(prevATR) <= 0.00000000000001 * (tempReal)) ) {
            lineValue = spread / prevATR * 100.0;
         }
         prevSignal += lineValue;
         today += 1;
      }
      prevSignal = prevSignal / optInSignalPeriod;
      /* Advance everything in lockstep through the unstable period of the
       * signal EMA, up to the first output bar.
       */
      while( today <= startIdx ) {
         tempLT = inLow[today];
         tempHT = inHigh[today];
         tempCY = inClose[today - 1];
         tempReal = inClose[today];
         greatest = tempHT - tempLT;
         /* val1 */
         val2 = Math.Abs(tempCY - tempHT);
         greatest = MaxGt(val2, greatest);
         val3 = Math.Abs(tempCY - tempLT);
         greatest = MaxGt(val3, greatest);
         prevATR = Math.FusedMultiplyAdd(wBeta, prevATR, wAlpha * greatest);
         prevFast = Math.FusedMultiplyAdd(fastBeta, prevFast, fastK * tempReal);
         prevSlow = Math.FusedMultiplyAdd(slowBeta, prevSlow, slowK * tempReal);
         spread = prevFast - prevSlow;
         tempReal = Math.Abs(tempReal);
         lineValue = 0.0;
         if( !(Math.Abs(spread) <= 0.00000000000001 * (tempReal)) && !(Math.Abs(prevATR) <= 0.00000000000001 * (tempReal)) ) {
            lineValue = spread / prevATR * 100.0;
         }
         if( optInSignalPeriod == 1 ) {
            prevSignal = lineValue;
         } else {
            prevSignal = Math.FusedMultiplyAdd(signalBeta, prevSignal, signalK * lineValue);
         }
         today += 1;
      }
      /* Stable zone: keep advancing in lockstep and write the three outputs. */
      outMACDV[0 * outStride] = lineValue;
      outMACDVSignal[0 * outStride] = prevSignal;
      outMACDVHist[0 * outStride] = lineValue - prevSignal;
      outIdx = 1;
      while( today <= endIdx ) {
         tempLT = inLow[today];
         tempHT = inHigh[today];
         tempCY = inClose[today - 1];
         tempReal = inClose[today];
         greatest = tempHT - tempLT;
         /* val1 */
         val2 = Math.Abs(tempCY - tempHT);
         greatest = MaxGt(val2, greatest);
         val3 = Math.Abs(tempCY - tempLT);
         greatest = MaxGt(val3, greatest);
         prevATR = Math.FusedMultiplyAdd(wBeta, prevATR, wAlpha * greatest);
         prevFast = Math.FusedMultiplyAdd(fastBeta, prevFast, fastK * tempReal);
         prevSlow = Math.FusedMultiplyAdd(slowBeta, prevSlow, slowK * tempReal);
         spread = prevFast - prevSlow;
         tempReal = Math.Abs(tempReal);
         lineValue = 0.0;
         if( !(Math.Abs(spread) <= 0.00000000000001 * (tempReal)) && !(Math.Abs(prevATR) <= 0.00000000000001 * (tempReal)) ) {
            lineValue = spread / prevATR * 100.0;
         }
         if( optInSignalPeriod == 1 ) {
            prevSignal = lineValue;
         } else {
            prevSignal = Math.FusedMultiplyAdd(signalBeta, prevSignal, signalK * lineValue);
         }
         outMACDV[outIdx * outStride] = lineValue;
         outMACDVSignal[outIdx * outStride] = prevSignal;
         outMACDVHist[outIdx * outStride] = lineValue - prevSignal;
         outIdx += 1;
         today += 1;
      }
      /* All done! Indicate the output limits and return success. */
      outBegIdx = startIdx;
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      sp.optInFastPeriod = optInFastPeriod;
      sp.optInSlowPeriod = optInSlowPeriod;
      sp.optInSignalPeriod = optInSignalPeriod;
      sp.prevFast = prevFast;
      sp.prevSlow = prevSlow;
      sp.prevATR = prevATR;
      sp.prevSignal = prevSignal;
      sp.slowK = slowK;
      sp.fastK = fastK;
      sp.signalK = signalK;
      sp.slowBeta = slowBeta;
      sp.fastBeta = fastBeta;
      sp.signalBeta = signalBeta;
      sp.wAlpha = wAlpha;
      sp.wBeta = wBeta;
      sp.lag1_inClose = inClose[historyLen - 1];
      sp.cur_outMACDV = outMACDV[(outNBElement - 1) * outStride];
      sp.cur_outMACDVSignal = outMACDVSignal[(outNBElement - 1) * outStride];
      sp.cur_outMACDVHist = outMACDVHist[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* MacdvOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal MacdvStream MacdvOpenAndFillInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInFastPeriod, int optInSlowPeriod, int optInSignalPeriod, out int outBegIdx, out int outNBElement, Span<double> outMACDV, Span<double> outMACDVSignal, Span<double> outMACDVHist )
   {
      MacdvStream sp = new MacdvStream(this);
      RetCode retCode = MacdvOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInFastPeriod, optInSlowPeriod, optInSignalPeriod, out outBegIdx, out outNBElement, outMACDV, outMACDVSignal, outMACDVHist, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("MACDV", "openAndFill", nameof(inHigh), inHigh.Length, startIdx, MacdvLookback(optInFastPeriod, optInSlowPeriod, optInSignalPeriod));
      }
      throw StreamFailure("MACDV", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind MacdvOpen (composition seam). */
   internal MacdvStream MacdvOpenInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInFastPeriod, int optInSlowPeriod, int optInSignalPeriod )
   {
      MacdvStream sp = new MacdvStream(this);
      double[] sink_outMACDV = new double[1];
      double[] sink_outMACDVSignal = new double[1];
      double[] sink_outMACDVHist = new double[1];
      RetCode retCode = MacdvOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInFastPeriod, optInSlowPeriod, optInSignalPeriod, out int outBegIdx, out int outNBElement, sink_outMACDV, sink_outMACDVSignal, sink_outMACDVHist, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("MACDV", "open", nameof(inHigh), inHigh.Length, startIdx, MacdvLookback(optInFastPeriod, optInSlowPeriod, optInSignalPeriod));
      }
      throw StreamFailure("MACDV", "open", retCode);
   }

   /// <summary>Open a live <c>MACDV</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="MacdvStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>MACDV</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>MacdvLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>MacdvOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInFastPeriod">As in the batch call; see <see cref="MacdvLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowPeriod">As in the batch call; see <see cref="MacdvLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSignalPeriod">As in the batch call; see <see cref="MacdvLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>MacdvLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public MacdvStream MacdvOpen( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInFastPeriod, int optInSlowPeriod, int optInSignalPeriod )
   {
      if( inHigh.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "MACDV open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "MACDV open: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TALibArgumentException("MACDV open: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TALibArgumentException("MACDV open: inClose is empty", nameof(inClose), RetCode.BadParam);
      RequireHistoryLength("MACDV", "open", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("MACDV", "open", "inClose", inClose.Length, inHigh.Length);
      return MacdvOpenInternal(inHigh, inLow, inClose, 0, optInFastPeriod, optInSlowPeriod, optInSignalPeriod);
   }

   /// <summary><c>MacdvOpen</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>MACDV</c> produces over
   /// the same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - MacdvLookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="MacdvStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInFastPeriod">As in the batch call; see <see cref="MacdvLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowPeriod">As in the batch call; see <see cref="MacdvLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSignalPeriod">As in the batch call; see <see cref="MacdvLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outMACDV">Fast EMA minus slow EMA, divided by the Average True Range, times 100.
   /// Must hold at least <c>historyLen - MacdvLookback(...)</c> values.</param>
   /// <param name="outMACDVSignal">EMA of the MACD-V line. Must hold at least <c>historyLen -
   /// MacdvLookback(...)</c> values.</param>
   /// <param name="outMACDVHist">MACD-V minus signal line. Must hold at least <c>historyLen -
   /// MacdvLookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>MacdvLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public MacdvStream MacdvOpenAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInFastPeriod, int optInSlowPeriod, int optInSignalPeriod, Span<double> outMACDV, Span<double> outMACDVSignal, Span<double> outMACDVHist )
   {
      if( inHigh.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "MACDV openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "MACDV openAndFill: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TALibArgumentException("MACDV openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TALibArgumentException("MACDV openAndFill: inClose is empty", nameof(inClose), RetCode.BadParam);
      int guardOutLen = OpenFillCount("MACDV", "openAndFill", inHigh.Length, MacdvLookback(optInFastPeriod, optInSlowPeriod, optInSignalPeriod));
      RequireHistoryLength("MACDV", "openAndFill", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("MACDV", "openAndFill", "inClose", inClose.Length, inHigh.Length);
      RequireFillLength("MACDV", "openAndFill", "outMACDV", outMACDV.Length, guardOutLen);
      RequireFillLength("MACDV", "openAndFill", "outMACDVSignal", outMACDVSignal.Length, guardOutLen);
      RequireFillLength("MACDV", "openAndFill", "outMACDVHist", outMACDVHist.Length, guardOutLen);
      if( SameBuffer(outMACDV, inHigh) || SameBuffer(outMACDV, inLow) || SameBuffer(outMACDV, inClose) || SameBuffer(outMACDVSignal, inHigh) || SameBuffer(outMACDVSignal, inLow) || SameBuffer(outMACDVSignal, inClose) || SameBuffer(outMACDVHist, inHigh) || SameBuffer(outMACDVHist, inLow) || SameBuffer(outMACDVHist, inClose) || SameBuffer(outMACDV, outMACDVSignal) || SameBuffer(outMACDV, outMACDVHist) || SameBuffer(outMACDVSignal, outMACDVHist) ) {
         throw StreamFailure("MACDV", "openAndFill", RetCode.BadParam);
      }
      if( guardOutLen > 0 && ( outMACDV.Overlaps(inHigh) || outMACDV.Overlaps(inLow) || outMACDV.Overlaps(inClose) || outMACDVSignal.Overlaps(inHigh) || outMACDVSignal.Overlaps(inLow) || outMACDVSignal.Overlaps(inClose) || outMACDVHist.Overlaps(inHigh) || outMACDVHist.Overlaps(inLow) || outMACDVHist.Overlaps(inClose) || OutputsAlias(outMACDV, outMACDVSignal) || OutputsAlias(outMACDV, outMACDVHist) || OutputsAlias(outMACDVSignal, outMACDVHist) ) ) {
         throw StreamFailure("MACDV", "openAndFill", RetCode.BadParam);
      }
      return MacdvOpenAndFillInternal(inHigh, inLow, inClose, 0, optInFastPeriod, optInSlowPeriod, optInSignalPeriod, out _, out _, outMACDV, outMACDVSignal, outMACDVHist);
   }
