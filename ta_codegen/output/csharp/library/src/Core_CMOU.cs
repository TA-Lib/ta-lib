      public double Update( double inReal )
      {
         if( !double.IsFinite(inReal) )
         {
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
            throw Core.StreamFailure("CMOU", "update", RetCode.BadParam);
         }
         core.CmouStepImpl(this, inReal);
         if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It copies nothing: the frame runs against this handle, reading its buffers
      /// and holding what the step would commit in locals. The cost does not grow
      /// with the period, and <c>Peek</c> never allocates.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>What <see cref="Update"/> would return for this bar.</returns>
      public double Peek( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.StreamFailure("CMOU", "peek", RetCode.BadParam);
         CmouStream sp = this;
         double sum = 0.0;
         double diff = 0.0;
         double tempReal = 0.0;
         double cur_outReal = sp.cur_outReal;
         double downSum = sp.downSum;
         int nullRun = sp.nullRun;
         double prevValue = sp.prevValue;
         int ringPos_trailingIdx = sp.ringPos_trailingIdx;
         double trailingValue = sp.trailingValue;
         double upSum = sp.upSum;
         int pkSlot0 = -1;
         double pkVal0 = 0.0;
         if( sp.ringCap_trailingIdx == 0 ) {
            pkSlot0 = 0;
            pkVal0 = inReal;
         }
         /* Drop the oldest change: inReal[trailingIdx] - inReal[trailingIdx-1].
          * inReal[trailingIdx-1] comes from the cache (already overwritten when
          * outReal == inReal); inReal[trailingIdx] is read here, before this
          * iteration writes outReal[outIdx], so it is still the original price.
          */
         tempReal = (ringPos_trailingIdx != pkSlot0) ? sp.ring_trailingIdx_inReal[ringPos_trailingIdx] : pkVal0;
         diff = tempReal - trailingValue;
         trailingValue = tempReal;
         if( diff > 0.0 ) {
            upSum -= diff;
         } else if( diff < 0.0 ) {
            downSum += diff;
         }
         /* Add the newest change: inReal[today] - inReal[today-1]. */
         tempReal = inReal;
         diff = tempReal - prevValue;
         prevValue = tempReal;
         if( diff > 0.0 ) {
            upSum += diff;
         } else if( diff < 0.0 ) {
            downSum -= diff;
         }
         /* Once a whole period of flat bars has gone by, every change in the
          * window is exactly zero, so both sums are known to be exactly zero and
          * the residue can be dropped.
          */
         if( diff == 0.0 ) {
            nullRun += 1;
         } else {
            nullRun = 0;
         }
         if( nullRun >= sp.optInTimePeriod ) {
            nullRun = sp.optInTimePeriod;
            upSum = 0.0;
            downSum = 0.0;
         }
         sum = upSum + downSum;
         if( sum > 0.0 ) {
            cur_outReal = 100.0 * (upSum - downSum) / sum;
         } else {
            cur_outReal = 0.0;
         }
         ringPos_trailingIdx = ringPos_trailingIdx + 1;
         if( ringPos_trailingIdx >= sp.ringCap_trailingIdx ) {
            ringPos_trailingIdx = 0;
         }
         return cur_outReal;
      }

      /// <summary>Commit <c>n</c> closed bars and write their <c>n</c> values, in one call.</summary>
      /// <remarks>
      /// <para>Exactly <c>n</c> back-to-back <see cref="Update"/> calls, with one set of
      /// argument checks instead of <c>n</c>. The outputs must hold at least
      /// <c>n</c> values and must not overlap an input or each other.</para>
      /// <para><see cref="OutRange"/> counts what this call took in, which is what makes
      /// a rejection readable: a non-finite bar <c>k</c> throws
      /// <see cref="System.ArgumentException"/> exactly as <see cref="Update"/>
      /// would, with the bars before <c>k</c> committed and written, bar <c>k</c>
      /// and everything after it not written, and the count advanced by <c>k +
      /// 1</c> — the committed bars plus the rejected one, so the last bar counted
      /// is the one that failed.</para>
      /// </remarks>
      /// <param name="inReal">Closed bars for <c>inReal</c>, oldest first.</param>
      /// <param name="outReal">Receives one <c>outReal</c> value per bar committed.</param>
      public void UpdateAndFill( ReadOnlySpan<double> inReal, Span<double> outReal )
      {
         int barCount = inReal.Length;
         if( outReal.Length < barCount || outReal.Overlaps(inReal) ) throw Core.StreamFailure("CMOU", "updateAndFill", RetCode.BadParam);
         for( int i = 0; i < barCount; i++ )
         {
            if( !double.IsFinite(inReal[i]) )
            {
               if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
               throw Core.StreamFailure("CMOU", "updateAndFill", RetCode.BadParam);
            }
            core.CmouStepImpl(this, inReal[i]);
            outReal[i] = cur_outReal;
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         }
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public CmouStream Clone()
      {
         return new CmouStream(this);
      }
   }

   internal void CmouStepImpl( CmouStream sp, double inReal )
   {
      double sum = 0.0;
      double diff = 0.0;
      double tempReal = 0.0;
      if( sp.ringCap_trailingIdx == 0 ) {
         sp.ring_trailingIdx_inReal[0] = inReal;
      }
      /* Drop the oldest change: inReal[trailingIdx] - inReal[trailingIdx-1].
       * inReal[trailingIdx-1] comes from the cache (already overwritten when
       * outReal == inReal); inReal[trailingIdx] is read here, before this
       * iteration writes outReal[outIdx], so it is still the original price.
       */
      tempReal = sp.ring_trailingIdx_inReal[sp.ringPos_trailingIdx];
      diff = tempReal - sp.trailingValue;
      sp.trailingValue = tempReal;
      if( diff > 0.0 ) {
         sp.upSum -= diff;
      } else if( diff < 0.0 ) {
         sp.downSum += diff;
      }
      /* Add the newest change: inReal[today] - inReal[today-1]. */
      tempReal = inReal;
      diff = tempReal - sp.prevValue;
      sp.prevValue = tempReal;
      if( diff > 0.0 ) {
         sp.upSum += diff;
      } else if( diff < 0.0 ) {
         sp.downSum -= diff;
      }
      /* Once a whole period of flat bars has gone by, every change in the
       * window is exactly zero, so both sums are known to be exactly zero and
       * the residue can be dropped.
       */
      if( diff == 0.0 ) {
         sp.nullRun += 1;
      } else {
         sp.nullRun = 0;
      }
      if( sp.nullRun >= sp.optInTimePeriod ) {
         sp.nullRun = sp.optInTimePeriod;
         sp.upSum = 0.0;
         sp.downSum = 0.0;
      }
      sum = sp.upSum + sp.downSum;
      if( sum > 0.0 ) {
         sp.cur_outReal = 100.0 * (sp.upSum - sp.downSum) / sum;
      } else {
         sp.cur_outReal = 0.0;
      }
      sp.ring_trailingIdx_inReal[sp.ringPos_trailingIdx] = inReal;
      sp.ringPos_trailingIdx = sp.ringPos_trailingIdx + 1;
      if( sp.ringPos_trailingIdx >= sp.ringCap_trailingIdx ) {
         sp.ringPos_trailingIdx = 0;
      }
   }

   private RetCode CmouOpenImpl( CmouStream sp, ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      int outIdx = 0;
      int today = 0;
      int trailingIdx = 0;
      int lookbackTotal = 0;
      int i = 0;
      int nullRun = 0;
      double upSum = 0;
      double downSum = 0;
      double sum = 0;
      double diff = 0;
      double tempReal = 0;
      double prevValue = 0;
      double trailingValue = 0;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 14;
      } else if( optInTimePeriod < 2 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      /* CMOU -- unsmoothed Chande Momentum Oscillator (as in TradingView ta.cmo,
       * QuantConnect, pandas-ta default). Over the trailing optInTimePeriod changes
       * d = inReal[i]-inReal[i-1]: Su = sum of up-moves (d>0), Sd = sum of
       * |down-moves| (d<0); CMOU = 100*(Su-Sd)/(Su+Sd), 0 for a flat window. A plain
       * moving-window sum (drop oldest change, add newest), NOT TA_CMO's Wilder
       * smoothing -- hence no unstable period.
       *
       * In-place safe (outReal == inReal): the trailing read inReal[trailingIdx]
       * precedes this iteration's write (trailingIdx >= outIdx), and the oldest
       * change's older endpoint comes from the `trailingValue` cache, not a re-read.
       */
      outBegIdx = 0;
      outNBElement = 0;
      lookbackTotal = CMOU_Lookback(optInTimePeriod);
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         return RetCode.InsufficientHistory ;
      }
      /* Accumulate the up/down sums over the first window: the optInTimePeriod
       * changes ending at startIdx (prices inReal[startIdx-optInTimePeriod ..
       * startIdx]). `trailingValue` caches the oldest price so the window's oldest
       * change can later be dropped by reading only the newer of its two prices.
       * `trailingIdx` points AT that newer price (one past the cached one).
       */
      today = startIdx - lookbackTotal;
      trailingIdx = today + 1;
      prevValue = inReal[today];
      trailingValue = prevValue;
      upSum = 0.0;
      downSum = 0.0;
      /* Consecutive changes of exactly zero, counted so that an empty window can
       * be recognized exactly (the shape #244 needed for MFI). The sums cannot
       * answer that question themselves once the window starts sliding: they are
       * maintained by add-then-subtract, so an emptied window leaves them holding
       * rounding residue of arbitrary sign rather than zero.
       */
      nullRun = 0;
      for( i = 0; i < optInTimePeriod; i += 1 ) {
         today += 1;
         tempReal = inReal[today];
         diff = tempReal - prevValue;
         prevValue = tempReal;
         if( diff > 0.0 ) {
            upSum += diff;
         } else if( diff < 0.0 ) {
            downSum -= diff;
         }
         if( diff == 0.0 ) {
            nullRun += 1;
         } else {
            nullRun = 0;
         }
      }
      /* Emit the first output (bar startIdx). Su+Sd is a sum of non-negative
       * magnitudes, so it is zero only for an exactly flat window; guard the 0/0
       * exactly and emit 0.0. Not against a fixed band: a price change carries the
       * quote unit, so a constant put against the total zeroed the oscillator for
       * any instrument quoted below it (issue #253).
       *
       * Scale-then-divide -- (100*(Su-Sd))/(Su+Sd), NOT the 100*((Su-Sd)/(Su+Sd))
       * order TA_CMO/RSI use -- so CMOU is BIT-IDENTICAL to the reference unsmoothed
       * CMO of Tulip Indicators (ti_cmo) and pandas-ta-classic (cmo, talib=False),
       * which both scale before dividing. The two orders differ by <=1 ULP.
       */
      outIdx = 0;
      sum = upSum + downSum;
      if( sum > 0.0 ) {
         outReal[outIdx++ * outStride] = 100.0 * (upSum - downSum) / sum;
      } else {
         outReal[outIdx++ * outStride] = 0.0;
      }
      /* Slide the window forward one bar at a time. */
      today += 1;
      while( today <= endIdx ) {
         /* Drop the oldest change: inReal[trailingIdx] - inReal[trailingIdx-1].
          * inReal[trailingIdx-1] comes from the cache (already overwritten when
          * outReal == inReal); inReal[trailingIdx] is read here, before this
          * iteration writes outReal[outIdx], so it is still the original price.
          */
         tempReal = inReal[trailingIdx];
         diff = tempReal - trailingValue;
         trailingValue = tempReal;
         trailingIdx += 1;
         if( diff > 0.0 ) {
            upSum -= diff;
         } else if( diff < 0.0 ) {
            downSum += diff;
         }
         /* Add the newest change: inReal[today] - inReal[today-1]. */
         tempReal = inReal[today];
         diff = tempReal - prevValue;
         prevValue = tempReal;
         if( diff > 0.0 ) {
            upSum += diff;
         } else if( diff < 0.0 ) {
            downSum -= diff;
         }
         /* Once a whole period of flat bars has gone by, every change in the
          * window is exactly zero, so both sums are known to be exactly zero and
          * the residue can be dropped.
          */
         if( diff == 0.0 ) {
            nullRun += 1;
         } else {
            nullRun = 0;
         }
         if( nullRun >= optInTimePeriod ) {
            nullRun = optInTimePeriod;
            upSum = 0.0;
            downSum = 0.0;
         }
         sum = upSum + downSum;
         if( sum > 0.0 ) {
            outReal[outIdx++ * outStride] = 100.0 * (upSum - downSum) / sum;
         } else {
            outReal[outIdx++ * outStride] = 0.0;
         }
         today += 1;
      }
      outBegIdx = startIdx;
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      int cap_trailingIdx = today - trailingIdx;
      if( cap_trailingIdx < 0 || cap_trailingIdx > historyLen ) {
         return RetCode.InternalError;
      }
      int allocN_trailingIdx = (cap_trailingIdx > 0)? cap_trailingIdx : 1;
      double[] capRing_trailingIdx_inReal = new double[allocN_trailingIdx];
      inReal.Slice(historyLen - cap_trailingIdx, cap_trailingIdx).CopyTo(capRing_trailingIdx_inReal);
      sp.optInTimePeriod = optInTimePeriod;
      sp.nullRun = nullRun;
      sp.upSum = upSum;
      sp.downSum = downSum;
      sp.prevValue = prevValue;
      sp.trailingValue = trailingValue;
      sp.ringPos_trailingIdx = 0;
      sp.ringCap_trailingIdx = cap_trailingIdx;
      sp.ring_trailingIdx_inReal = capRing_trailingIdx_inReal;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* CmouOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal CmouStream CmouOpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      CmouStream sp = new CmouStream(this);
      RetCode retCode = CmouOpenImpl(sp, inReal, startIdx, optInTimePeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("CMOU", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind CmouOpen (composition seam). */
   internal CmouStream CmouOpenInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod )
   {
      CmouStream sp = new CmouStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = CmouOpenImpl(sp, inReal, startIdx, optInTimePeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("CMOU", "open", retCode);
   }

   /// <summary>Open a live <c>CMOU</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="CmouStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>CMOU</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>CMOU_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>CmouOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">Source price/value series. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="CMOU_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>CMOU_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public CmouStream CmouOpen( ReadOnlySpan<double> inReal, int optInTimePeriod )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "CMOU open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "CMOU open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      return CmouOpenInternal(inReal, 0, optInTimePeriod);
   }

   /// <summary><c>CmouOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>CMOU</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - CMOU_Lookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="CmouStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">Source price/value series. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="CMOU_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">CMOU oscillator value. Must hold at least <c>historyLen -
   /// CMOU_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>CMOU_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public CmouStream CmouOpenAndFill( ReadOnlySpan<double> inReal, int optInTimePeriod, Span<double> outReal )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "CMOU openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "CMOU openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      int guardOutLen = OpenFillCount("CMOU", "openAndFill", inReal.Length, CMOU_Lookback(optInTimePeriod));
      RequireFillLength("CMOU", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( outReal.Overlaps(inReal) ) {
         throw StreamFailure("CMOU", "openAndFill", RetCode.BadParam);
      }
      return CmouOpenAndFillInternal(inReal, 0, optInTimePeriod, out _, out _, outReal);
   }
