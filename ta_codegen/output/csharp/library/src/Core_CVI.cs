         this.core = other.core;
         this.optInTimePeriod = other.optInTimePeriod;
         this.optInROCPeriod = other.optInROCPeriod;
         this.prevEMA = other.prevEMA;
         this.optInK_1 = other.optInK_1;
         this.emaRing_Idx = other.emaRing_Idx;
         this.maxIdx_emaRing = other.maxIdx_emaRing;
         this.cbSize_emaRing = other.cbSize_emaRing;
         this.cb_emaRing = new double[other.cb_emaRing.Length];
         Array.Copy( other.cb_emaRing, this.cb_emaRing, other.cb_emaRing.Length );
         this.cur_outReal = other.cur_outReal;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Allocates nothing — neither handle state nor a return value.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so no state moves, <see cref="Value"/> still answers the previous value,
      /// and the stream stays usable — just carry on with the next bar.
      /// <see cref="OutRange"/> does advance: the bar happened, so it is counted,
      /// which keeps two handles fed the same series positionally aligned when only
      /// one of them rejects a bar. This is the one place the streaming tier is
      /// stricter than the batch API, which computes on whatever it is given: a
      /// handle retains its state, so a single non-finite bar would poison every
      /// later value it produces.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inHigh, double inLow )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) )
         {
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
            throw Core.StreamFailure("CVI", "update", RetCode.BadParam);
         }
         core.CviStepImpl(this, inHigh, inLow);
         if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It copies nothing: the frame runs against this handle, reading its buffers
      /// and holding what the step would commit in locals. The cost does not grow
      /// with the period, and <c>Peek</c> never allocates.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <returns>What <see cref="Update"/> would return for this bar.</returns>
      public double Peek( double inHigh, double inLow )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) ) throw Core.StreamFailure("CVI", "peek", RetCode.BadParam);
         CviStream sp = this;
         double laggedEMA = 0.0;
         double tempReal = 0.0;
         double cur_outReal = 0.0;
         int emaRing_Idx = sp.emaRing_Idx;
         double prevEMA = sp.prevEMA;
         tempReal = inHigh - inLow;
         prevEMA = Math.FusedMultiplyAdd(tempReal - prevEMA, sp.optInK_1, prevEMA);
         laggedEMA = sp.cb_emaRing[emaRing_Idx];
         emaRing_Idx = emaRing_Idx + 1;
         if( emaRing_Idx > sp.maxIdx_emaRing ) {
            emaRing_Idx = 0;
         }
         if( laggedEMA != 0.0 ) {
            cur_outReal = 100.0 * ((prevEMA - laggedEMA) / laggedEMA);
         } else {
            cur_outReal = 0.0;
         }
         return cur_outReal;
      }

      /// <summary>Commit <c>n</c> closed bars and write their <c>n</c> values, in one call.</summary>
      /// <remarks>
      /// <para>Exactly <c>n</c> back-to-back <see cref="Update"/> calls, with one set of
      /// argument checks instead of <c>n</c>. The outputs must hold at least
      /// <c>n</c> values and must not overlap an input or each other.</para>
      /// <para><see cref="OutRange"/> counts what this call took in, which is what makes
      /// a rejection readable: a non-finite bar <c>k</c> throws
      /// <see cref="System.ArgumentException"/> exactly as <see cref="Update"/>
      /// would, with the bars before <c>k</c> committed and written, bar <c>k</c>
      /// and everything after it not written, and the count advanced by <c>k +
      /// 1</c> — the committed bars plus the rejected one, so the last bar counted
      /// is the one that failed.</para>
      /// </remarks>
      /// <param name="inHigh">Closed bars for <c>inHigh</c>, oldest first.</param>
      /// <param name="inLow">Closed bars for <c>inLow</c>, oldest first.</param>
      /// <param name="outReal">Receives one <c>outReal</c> value per bar committed.</param>
      public void UpdateAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, Span<double> outReal )
      {
         int barCount = inHigh.Length;
         if( inLow.Length != barCount || outReal.Length < barCount || outReal.Overlaps(inHigh) || outReal.Overlaps(inLow) ) throw Core.StreamFailure("CVI", "updateAndFill", RetCode.BadParam);
         for( int i = 0; i < barCount; i++ )
         {
            if( !double.IsFinite(inHigh[i]) || !double.IsFinite(inLow[i]) )
            {
               if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
               throw Core.StreamFailure("CVI", "updateAndFill", RetCode.BadParam);
            }
            core.CviStepImpl(this, inHigh[i], inLow[i]);
            outReal[i] = cur_outReal;
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         }
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public CviStream Clone()
      {
         return new CviStream(this);
      }
   }

   internal void CviStepImpl( CviStream sp, double inHigh, double inLow )
   {
      double laggedEMA = 0.0;
      double tempReal = 0.0;
      tempReal = inHigh - inLow;
      sp.prevEMA = Math.FusedMultiplyAdd(tempReal - sp.prevEMA, sp.optInK_1, sp.prevEMA);
      laggedEMA = sp.cb_emaRing[sp.emaRing_Idx];
      sp.cb_emaRing[sp.emaRing_Idx] = sp.prevEMA;
      sp.emaRing_Idx = sp.emaRing_Idx + 1;
      if( sp.emaRing_Idx > sp.maxIdx_emaRing ) {
         sp.emaRing_Idx = 0;
      }
      if( laggedEMA != 0.0 ) {
         sp.cur_outReal = 100.0 * ((sp.prevEMA - laggedEMA) / laggedEMA);
      } else {
         sp.cur_outReal = 0.0;
      }
   }

   private RetCode CviOpenImpl( CviStream sp, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int startIdx, int optInTimePeriod, int optInROCPeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double prevEMA = 0;
      double laggedEMA = 0;
      double tempReal = 0;
      double optInK_1 = 0;
      int i = 0;
      int today = 0;
      int outIdx = 0;
      int lookbackTotal = 0;
      double[] emaRing = [];
      int emaRing_Idx = 0;
      int maxIdx_emaRing = (32)-1;
      int historyLen = inHigh.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inLow.Length != inHigh.Length ) {
         return RetCode.BadParam;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 10;
      } else if( optInTimePeriod < 2 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInROCPeriod == int.MinValue ) {
         optInROCPeriod = 10;
      } else if( optInROCPeriod < 1 || optInROCPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      /* CVI[t] = 100 * (E[t] - E[t-optInROCPeriod]) / E[t-optInROCPeriod], with E
       * an EMA of the high-low spread. The spread is never materialised and the
       * EMA is anchored optInROCPeriod bars behind startIdx.
       *
       * The arithmetic below is TA_EMA's and TA_ROCP's verbatim -- seed sum
       * accumulated from 0.0 in ascending bar order, ((x-prev)*k)+prev, and
       * 100*((a-b)/b) under an exact zero test. That is what makes this fused pass
       * bit-identical to composing TA_SUB, TA_EMA and TA_ROCP, which test_cvi.c
       * holds it to memcmp-exact; reshaping any of it breaks that silently. The
       * guard stays an exact `!= 0.0` and never TA_IS_ZERO -- an epsilon band
       * carries the quote unit and would zero the indicator for anything priced
       * under it (issue #253).
       */
      outBegIdx = 0;
      outNBElement = 0;
      lookbackTotal = EMA_Lookback(optInTimePeriod) + ROCP_Lookback(optInROCPeriod);
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         return RetCode.InsufficientHistory ;
      }
      if( optInROCPeriod < 1 ) return RetCode.InternalError;
      emaRing = new double[optInROCPeriod];
      maxIdx_emaRing = (optInROCPeriod)-1;
      emaRing_Idx = 0;
      optInK_1 = 2.0 / (double)(optInTimePeriod + 1);
      today = startIdx - lookbackTotal;
      i = optInTimePeriod;
      tempReal = 0.0;
      while( i-- > 0 ) {
         tempReal += inHigh[today] - inLow[today];
         today += 1;
      }
      prevEMA = tempReal / optInTimePeriod;
      /* The ring keeps only the newest optInROCPeriod values, so pushing every EMA
       * value from the seed bar on leaves exactly the lagged terms the output
       * loop reads.
       */
      emaRing[emaRing_Idx] = prevEMA;
      emaRing_Idx++;
      if( emaRing_Idx > maxIdx_emaRing ) { emaRing_Idx = 0; }
      while( today < startIdx ) {
         tempReal = inHigh[today] - inLow[today];
         prevEMA = Math.FusedMultiplyAdd(tempReal - prevEMA, optInK_1, prevEMA);
         today += 1;
         emaRing[emaRing_Idx] = prevEMA;
         emaRing_Idx++;
         if( emaRing_Idx > maxIdx_emaRing ) { emaRing_Idx = 0; }
      }
      /* Read the expiring slot before overwriting it: that is what makes the lag
       * exactly optInROCPeriod rather than one less.
       */
      outIdx = 0;
      while( today <= endIdx ) {
         tempReal = inHigh[today] - inLow[today];
         prevEMA = Math.FusedMultiplyAdd(tempReal - prevEMA, optInK_1, prevEMA);
         today += 1;
         laggedEMA = emaRing[emaRing_Idx];
         emaRing[emaRing_Idx] = prevEMA;
         emaRing_Idx++;
         if( emaRing_Idx > maxIdx_emaRing ) { emaRing_Idx = 0; }
         if( laggedEMA != 0.0 ) {
            outReal[outIdx++ * outStride] = 100.0 * ((prevEMA - laggedEMA) / laggedEMA);
         } else {
            outReal[outIdx++ * outStride] = 0.0;
         }
      }
      outBegIdx = startIdx;
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      int capCb_emaRing = maxIdx_emaRing + 1;
      if( capCb_emaRing > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      sp.optInTimePeriod = optInTimePeriod;
      sp.optInROCPeriod = optInROCPeriod;
      sp.prevEMA = prevEMA;
      sp.optInK_1 = optInK_1;
      sp.emaRing_Idx = emaRing_Idx;
      sp.maxIdx_emaRing = maxIdx_emaRing;
      sp.cbSize_emaRing = capCb_emaRing;
      sp.cb_emaRing = emaRing;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* CviOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal CviStream CviOpenAndFillInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int startIdx, int optInTimePeriod, int optInROCPeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      CviStream sp = new CviStream(this);
      RetCode retCode = CviOpenImpl(sp, inHigh, inLow, startIdx, optInTimePeriod, optInROCPeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("CVI", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind CviOpen (composition seam). */
   internal CviStream CviOpenInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int startIdx, int optInTimePeriod, int optInROCPeriod )
   {
      CviStream sp = new CviStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = CviOpenImpl(sp, inHigh, inLow, startIdx, optInTimePeriod, optInROCPeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("CVI", "open", retCode);
   }

   /// <summary>Open a live <c>CVI</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="CviStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>CVI</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>CVI_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>CviOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inHigh">High price. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="CVI_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInROCPeriod">As in the batch call; see <see cref="CVI_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>CVI_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public CviStream CviOpen( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int optInTimePeriod, int optInROCPeriod )
   {
      if( inHigh.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "CVI open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "CVI open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("CVI open: inLow is empty", nameof(inLow), RetCode.BadParam);
      RequireHistoryLength("CVI", "open", "inLow", inLow.Length, inHigh.Length);
      return CviOpenInternal(inHigh, inLow, 0, optInTimePeriod, optInROCPeriod);
   }

   /// <summary><c>CviOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>CVI</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - CVI_Lookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="CviStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inHigh">High price. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="CVI_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInROCPeriod">As in the batch call; see <see cref="CVI_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Percent change of the smoothed high-low spread. Must hold at least
   /// <c>historyLen - CVI_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>CVI_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public CviStream CviOpenAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int optInTimePeriod, int optInROCPeriod, Span<double> outReal )
   {
      if( inHigh.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "CVI openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "CVI openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("CVI openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      int guardOutLen = OpenFillCount("CVI", "openAndFill", inHigh.Length, CVI_Lookback(optInTimePeriod, optInROCPeriod));
      RequireHistoryLength("CVI", "openAndFill", "inLow", inLow.Length, inHigh.Length);
      RequireFillLength("CVI", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( outReal.Overlaps(inHigh) || outReal.Overlaps(inLow) ) {
         throw StreamFailure("CVI", "openAndFill", RetCode.BadParam);
      }
      return CviOpenAndFillInternal(inHigh, inLow, 0, optInTimePeriod, optInROCPeriod, out _, out _, outReal);
   }
