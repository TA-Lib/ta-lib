         double cur_outReal = 0.0;
         int pkSlot0 = -1;
         double pkVal0 = 0.0;
         lastValue = (inHigh + inLow + inClose) / 3;
         pkSlot0 = sp.circBuffer_Idx;
         pkVal0 = lastValue;
         /* Calculate the average for the whole period. */
         theAverage = 0;
         for( j = 0; j < sp.optInTimePeriod; j += 1 ) {
            theAverage += (j != pkSlot0) ? sp.cb_circBuffer[j] : pkVal0;
         }
         theAverage /= sp.optInTimePeriod;
         /* Do the summation of the ABS(TypePrice-average)
          * for the whole period, then its mean.
          */
         tempReal2 = 0;
         for( j = 0; j < sp.optInTimePeriod; j += 1 ) {
            tempReal2 += Math.Abs(((j != pkSlot0) ? sp.cb_circBuffer[j] : pkVal0) - theAverage);
         }
         tempReal2 /= sp.optInTimePeriod;
         /* And finally, the CCI... */
         tempReal = lastValue - theAverage;
         /* Both tests are relative to the window's own price level (issue #253).
          * They ask "is this window flat?", and flatness is a property of the
          * prices relative to each other -- but a deviation carries the quote
          * unit, so the fixed TA_IS_ZERO band these used to be answered "flat" for
          * every window of an instrument quoted below it and zeroed the whole
          * output. The band is still wide enough (~90 ulp of the average) to
          * absorb the sub-epsilon residue an identical-price window leaves in the
          * average, which is what it was widened for in the first place (#7).
          */
         tempReal3 = Math.Abs(theAverage);
         if( !(Math.Abs(tempReal) <= 0.00000000000001 * (tempReal3)) && !(Math.Abs(tempReal2) <= 0.00000000000001 * (tempReal3)) ) {
            cur_outReal = tempReal / (0.015 * tempReal2);
         } else {
            cur_outReal = 0.0;
         }
         return cur_outReal;
      }

      /// <summary>Commit <c>n</c> closed bars and write their <c>n</c> values, in one call.</summary>
      /// <remarks>
      /// <para>Exactly <c>n</c> back-to-back <see cref="Update"/> calls, with one set of
      /// argument checks instead of <c>n</c>. The outputs must hold at least
      /// <c>n</c> values and must not overlap an input or each other.</para>
      /// <para><see cref="OutRange"/> counts what this call took in, which is what makes
      /// a rejection readable: a non-finite bar <c>k</c> throws
      /// <see cref="System.ArgumentException"/> exactly as <see cref="Update"/>
      /// would, with the bars before <c>k</c> committed and written, bar <c>k</c>
      /// and everything after it not written, and the count advanced by <c>k +
      /// 1</c> — the committed bars plus the rejected one, so the last bar counted
      /// is the one that failed.</para>
      /// </remarks>
      /// <param name="inHigh">Closed bars for <c>inHigh</c>, oldest first.</param>
      /// <param name="inLow">Closed bars for <c>inLow</c>, oldest first.</param>
      /// <param name="inClose">Closed bars for <c>inClose</c>, oldest first.</param>
      /// <param name="outReal">Receives one <c>outReal</c> value per bar committed.</param>
      public void UpdateAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, Span<double> outReal )
      {
         int barCount = inHigh.Length;
         if( inLow.Length != barCount || inClose.Length != barCount || outReal.Length < barCount || outReal.Overlaps(inHigh) || outReal.Overlaps(inLow) || outReal.Overlaps(inClose) ) throw Core.StreamFailure("CCI", "updateAndFill", RetCode.BadParam);
         for( int i = 0; i < barCount; i++ )
         {
            if( !double.IsFinite(inHigh[i]) || !double.IsFinite(inLow[i]) || !double.IsFinite(inClose[i]) )
            {
               if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
               throw Core.StreamFailure("CCI", "updateAndFill", RetCode.BadParam);
            }
            core.CciStepImpl(this, inHigh[i], inLow[i], inClose[i]);
            outReal[i] = cur_outReal;
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         }
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public CciStream Clone()
      {
         return new CciStream(this);
      }
   }

   internal void CciStepImpl( CciStream sp, double inHigh, double inLow, double inClose )
   {
      double tempReal = 0.0;
      double tempReal2 = 0.0;
      double tempReal3 = 0.0;
      double theAverage = 0.0;
      double lastValue = 0.0;
      int j = 0;
      lastValue = (inHigh + inLow + inClose) / 3;
      sp.cb_circBuffer[sp.circBuffer_Idx] = lastValue;
      /* Calculate the average for the whole period. */
      theAverage = 0;
      for( j = 0; j < sp.optInTimePeriod; j += 1 ) {
         theAverage += sp.cb_circBuffer[j];
      }
      theAverage /= sp.optInTimePeriod;
      /* Do the summation of the ABS(TypePrice-average)
       * for the whole period, then its mean.
       */
      tempReal2 = 0;
      for( j = 0; j < sp.optInTimePeriod; j += 1 ) {
         tempReal2 += Math.Abs(sp.cb_circBuffer[j] - theAverage);
      }
      tempReal2 /= sp.optInTimePeriod;
      /* And finally, the CCI... */
      tempReal = lastValue - theAverage;
      /* Both tests are relative to the window's own price level (issue #253).
       * They ask "is this window flat?", and flatness is a property of the
       * prices relative to each other -- but a deviation carries the quote
       * unit, so the fixed TA_IS_ZERO band these used to be answered "flat" for
       * every window of an instrument quoted below it and zeroed the whole
       * output. The band is still wide enough (~90 ulp of the average) to
       * absorb the sub-epsilon residue an identical-price window leaves in the
       * average, which is what it was widened for in the first place (#7).
       */
      tempReal3 = Math.Abs(theAverage);
      if( !(Math.Abs(tempReal) <= 0.00000000000001 * (tempReal3)) && !(Math.Abs(tempReal2) <= 0.00000000000001 * (tempReal3)) ) {
         sp.cur_outReal = tempReal / (0.015 * tempReal2);
      } else {
         sp.cur_outReal = 0.0;
      }
      /* Move forward the circular buffer indexes. */
      sp.circBuffer_Idx = sp.circBuffer_Idx + 1;
      if( sp.circBuffer_Idx > sp.maxIdx_circBuffer ) {
         sp.circBuffer_Idx = 0;
      }
   }

   private RetCode CciOpenImpl( CciStream sp, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double tempReal = 0;
      double tempReal2 = 0;
      double tempReal3 = 0;
      double theAverage = 0;
      double lastValue = 0;
      int i = 0;
      int j = 0;
      int outIdx = 0;
      int lookbackTotal = 0;
      double[] circBuffer = [];
      int circBuffer_Idx = 0;
      int maxIdx_circBuffer = (30)-1;
      int historyLen = inHigh.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inLow.Length != inHigh.Length || inClose.Length != inHigh.Length ) {
         return RetCode.BadParam;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 14;
      } else if( optInTimePeriod < 2 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      /* This ptr will points on a circular buffer of
       * at least "optInTimePeriod" element.
       */
      /* Identify the minimum number of price bar needed
       * to calculate at least one output.
       */
      lookbackTotal = optInTimePeriod - 1;
      /* Move up the start index if there is not
       * enough initial data.
       */
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      /* Allocate a circular buffer equal to the requested
       * period.
       */
      if( optInTimePeriod < 1 ) return RetCode.InternalError;
      circBuffer = new double[optInTimePeriod];
      maxIdx_circBuffer = (optInTimePeriod)-1;
      circBuffer_Idx = 0;
      /* Do the MA calculation using tight loops. */
      /* Add-up the initial period, except for the last value.
       * Fill up the circular buffer at the same time.
       */
      i = startIdx - lookbackTotal;
      if( optInTimePeriod > 1 ) {
         while( i < startIdx ) {
            circBuffer[circBuffer_Idx] = (inHigh[i] + inLow[i] + inClose[i]) / 3;
            i += 1;
            circBuffer_Idx++;
            if( circBuffer_Idx > maxIdx_circBuffer ) { circBuffer_Idx = 0; }
         }
      }
      /* Proceed with the calculation for the requested range.
       * Note that this algorithm allows the inReal and
       * outReal to be the same buffer.
       */
      outIdx = 0;
      do {
         lastValue = (inHigh[i] + inLow[i] + inClose[i]) / 3;
         circBuffer[circBuffer_Idx] = lastValue;
         /* Calculate the average for the whole period. */
         theAverage = 0;
         for( j = 0; j < optInTimePeriod; j += 1 ) {
            theAverage += circBuffer[j];
         }
         theAverage /= optInTimePeriod;
         /* Do the summation of the ABS(TypePrice-average)
          * for the whole period, then its mean.
          */
         tempReal2 = 0;
         for( j = 0; j < optInTimePeriod; j += 1 ) {
            tempReal2 += Math.Abs(circBuffer[j] - theAverage);
         }
         tempReal2 /= optInTimePeriod;
         /* And finally, the CCI... */
         tempReal = lastValue - theAverage;
         /* Both tests are relative to the window's own price level (issue #253).
          * They ask "is this window flat?", and flatness is a property of the
          * prices relative to each other -- but a deviation carries the quote
          * unit, so the fixed TA_IS_ZERO band these used to be answered "flat" for
          * every window of an instrument quoted below it and zeroed the whole
          * output. The band is still wide enough (~90 ulp of the average) to
          * absorb the sub-epsilon residue an identical-price window leaves in the
          * average, which is what it was widened for in the first place (#7).
          */
         tempReal3 = Math.Abs(theAverage);
         if( !(Math.Abs(tempReal) <= 0.00000000000001 * (tempReal3)) && !(Math.Abs(tempReal2) <= 0.00000000000001 * (tempReal3)) ) {
            outReal[outIdx++ * outStride] = tempReal / (0.015 * tempReal2);
         } else {
            outReal[outIdx++ * outStride] = 0.0;
         }
         /* Move forward the circular buffer indexes. */
         circBuffer_Idx++;
         if( circBuffer_Idx > maxIdx_circBuffer ) { circBuffer_Idx = 0; }
         i += 1;
      } while( i <= endIdx );
      /* All done. Indicate the output limits and return. */
      outNBElement = outIdx;
      outBegIdx = startIdx;
      /* Free the circular buffer if it was dynamically allocated. */
      /* Capture the live batch state into the handle. */
      int capCb_circBuffer = maxIdx_circBuffer + 1;
      if( capCb_circBuffer > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      sp.optInTimePeriod = optInTimePeriod;
      sp.circBuffer_Idx = circBuffer_Idx;
      sp.maxIdx_circBuffer = maxIdx_circBuffer;
      sp.cbSize_circBuffer = capCb_circBuffer;
      sp.cb_circBuffer = circBuffer;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* CciOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal CciStream CciOpenAndFillInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      CciStream sp = new CciStream(this);
      RetCode retCode = CciOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInTimePeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("CCI", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind CciOpen (composition seam). */
   internal CciStream CciOpenInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod )
   {
      CciStream sp = new CciStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = CciOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInTimePeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("CCI", "open", retCode);
   }

   /// <summary>Open a live <c>CCI</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="CciStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>CCI</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>CCI_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>CciOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="CCI_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>CCI_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public CciStream CciOpen( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInTimePeriod )
   {
      if( inHigh.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "CCI open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "CCI open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("CCI open: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TaLibArgumentException("CCI open: inClose is empty", nameof(inClose), RetCode.BadParam);
      RequireHistoryLength("CCI", "open", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("CCI", "open", "inClose", inClose.Length, inHigh.Length);
      return CciOpenInternal(inHigh, inLow, inClose, 0, optInTimePeriod);
   }

   /// <summary><c>CciOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>CCI</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - CCI_Lookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="CciStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="CCI_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">CCI value per bar. Must hold at least <c>historyLen -
   /// CCI_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>CCI_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public CciStream CciOpenAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInTimePeriod, Span<double> outReal )
   {
      if( inHigh.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "CCI openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "CCI openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("CCI openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TaLibArgumentException("CCI openAndFill: inClose is empty", nameof(inClose), RetCode.BadParam);
      int guardOutLen = OpenFillCount("CCI", "openAndFill", inHigh.Length, CCI_Lookback(optInTimePeriod));
      RequireHistoryLength("CCI", "openAndFill", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("CCI", "openAndFill", "inClose", inClose.Length, inHigh.Length);
      RequireFillLength("CCI", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( outReal.Overlaps(inHigh) || outReal.Overlaps(inLow) || outReal.Overlaps(inClose) ) {
         throw StreamFailure("CCI", "openAndFill", RetCode.BadParam);
      }
      return CciOpenAndFillInternal(inHigh, inLow, inClose, 0, optInTimePeriod, out _, out _, outReal);
   }
