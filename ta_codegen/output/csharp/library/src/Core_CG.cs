               y = Math.Abs(x * scale2Lo);
               if( !(y < sp.ylim2) || y < 4.503599627370496e15 && y + 4.503599627370496e15 - 4.503599627370496e15 != y || y == 0.0 && x != 0.0 ) {
                  fit2Lo = 0;
               }
               y = Math.Abs(x * scale3Mid);
               if( !(y < sp.ylim3) || y < 4.503599627370496e15 && y + 4.503599627370496e15 - 4.503599627370496e15 != y || y == 0.0 && x != 0.0 ) {
                  fit3Mid = 0;
               }
               y = Math.Abs(x * scale3Lo);
               if( !(y < sp.ylim3) || y < 4.503599627370496e15 && y + 4.503599627370496e15 - 4.503599627370496e15 != y || y == 0.0 && x != 0.0 ) {
                  failAt = k;
               }
               k += 1;
            }
            limbs = 0;
            if( failAt >= 0 ) {
               if( failAt < maxAt ) {
                  stickyBars = failAt;
               } else {
                  stickyBars = maxAt;
               }
            } else {
               if( fit2Mid == 1 || fit2Lo == 1 ) {
                  limbs = 2;
                  width = sp.width2;
                  ylim = sp.ylim2;
                  if( fit2Mid == 1 ) {
                     scale = scale2Mid;
                  } else {
                     scale = scale2Lo;
                  }
               } else {
                  limbs = 3;
                  width = sp.width3;
                  ylim = sp.ylim3;
                  if( fit3Mid == 1 ) {
                     scale = scale3Mid;
                  } else {
                     scale = scale3Lo;
                  }
               }
               invWidth = 1.0 / width;
               widthSq = width * width;
               invWidthSq = invWidth * invWidth;
               denA = 0.0;
               denB = 0.0;
               denC = 0.0;
               numA = 0.0;
               numB = 0.0;
               numC = 0.0;
               if( limbs == 2 ) {
                  for( j = sp.lookbackTotal; j >= 0; j -= 1 ) {
                     y = ((((sp.winPos_j + sp.winCap_j - j >= sp.winCap_j) ? sp.winPos_j + sp.winCap_j - j - sp.winCap_j : sp.winPos_j + sp.winCap_j - j) != pkSlot0) ? sp.win_j_inReal[(sp.winPos_j + sp.winCap_j - j >= sp.winCap_j) ? sp.winPos_j + sp.winCap_j - j - sp.winCap_j : sp.winPos_j + sp.winCap_j - j] : pkVal0) * scale;
