            sp.invWidthSq = sp.invWidth * sp.invWidth;
            sp.denA = 0.0;
            sp.denB = 0.0;
            sp.denC = 0.0;
            sp.numA = 0.0;
            sp.numB = 0.0;
            sp.numC = 0.0;
            if( sp.limbs == 2 ) {
               for( j = sp.lookbackTotal; j >= 0; j -= 1 ) {
                  y = sp.win_j_inReal[(sp.winPos_j + sp.winCap_j - j >= sp.winCap_j) ? sp.winPos_j + sp.winCap_j - j - sp.winCap_j : sp.winPos_j + sp.winCap_j - j] * sp.scale;
                  t = y * sp.invWidth;
                  a = t + 6.755399441055744e15 - 6.755399441055744e15;
                  t = a * sp.width;
                  c = y - t;
                  sp.denA += a;
                  sp.denC += c;
                  sp.numA += sp.denA;
                  sp.numC += sp.denC;
               }
            } else {
               for( j = sp.lookbackTotal; j >= 0; j -= 1 ) {
                  y = sp.win_j_inReal[(sp.winPos_j + sp.winCap_j - j >= sp.winCap_j) ? sp.winPos_j + sp.winCap_j - j - sp.winCap_j : sp.winPos_j + sp.winCap_j - j] * sp.scale;
                  t = y * sp.invWidthSq;
                  a = t + 6.755399441055744e15 - 6.755399441055744e15;
                  t = a * sp.widthSq;
                  q = y - t;
                  t = q * sp.invWidth;
                  b = t + 6.755399441055744e15 - 6.755399441055744e15;
                  t = b * sp.width;
                  c = q - t;
                  sp.denA += a;
                  sp.denB += b;
                  sp.denC += c;
                  sp.numA += sp.denA;
                  sp.numB += sp.denB;
                  sp.numC += sp.denC;
               }
            }
         }
      }
      /* One rounding each: the limbs are carried into range first, so the
       * last add sees two exact values.
       */
      if( sp.limbs == 2 ) {
         t = sp.denA * sp.width;
         sp.den = t + sp.denC;
         t = sp.numA * sp.width;
         sp.num = t + sp.numC;
      } else if( sp.limbs == 3 ) {
         t = sp.denC * sp.invWidth;
         q = t + 6.755399441055744e15 - 6.755399441055744e15;
         b = sp.denB + q;
         t = q * sp.width;
         c = sp.denC - t;
         t = b * sp.invWidth;
         q = t + 6.755399441055744e15 - 6.755399441055744e15;
         t = q * sp.width;
         b = b - t;
         t = b * sp.width;
         c = t + c;
         t = sp.denA + q;
         t = t * sp.widthSq;
         sp.den = t + c;
         t = sp.numC * sp.invWidth;
         q = t + 6.755399441055744e15 - 6.755399441055744e15;
         b = sp.numB + q;
         t = q * sp.width;
         c = sp.numC - t;
         t = b * sp.invWidth;
         q = t + 6.755399441055744e15 - 6.755399441055744e15;
         t = q * sp.width;
         b = b - t;
         t = b * sp.width;
         c = t + c;
         t = sp.numA + q;
         t = t * sp.widthSq;
         sp.num = t + c;
      }
      /* The denominator is a signed sum, so only an exact zero is degenerate.
       * It is answered with the flat-window value, which keeps every output a
       * function of its own window; an epsilon band would carry the quote unit
       * (#253).
       */
      if( sp.den != 0.0 ) {
         value = -sp.num / sp.den;
      } else {
         value = sp.flatValue;
      }
      if( sp.limbs == 2 ) {
         y = sp.ring_trailingIdx_inReal[sp.ringPos_trailingIdx] * sp.scale;
         t = y * sp.invWidth;
         a = t + 6.755399441055744e15 - 6.755399441055744e15;
         t = a * sp.width;
         c = y - t;
         sp.denA -= a;
         sp.denC -= c;
         sp.numA -= sp.periodDouble * a;
         sp.numC -= sp.periodDouble * c;
      } else if( sp.limbs == 3 ) {
         y = sp.ring_trailingIdx_inReal[sp.ringPos_trailingIdx] * sp.scale;
         t = y * sp.invWidthSq;
         a = t + 6.755399441055744e15 - 6.755399441055744e15;
         t = a * sp.widthSq;
         q = y - t;
         t = q * sp.invWidth;
         b = t + 6.755399441055744e15 - 6.755399441055744e15;
         t = b * sp.width;
         c = q - t;
         sp.denA -= a;
         sp.denB -= b;
         sp.denC -= c;
         sp.numA -= sp.periodDouble * a;
         sp.numB -= sp.periodDouble * b;
         sp.numC -= sp.periodDouble * c;
      }
      /* After the trailing value is read: outReal may be inReal. */
      sp.cur_outReal = value;
      ringCapL_trailingIdx = sp.ringCap_trailingIdx;
      sp.ring_trailingIdx_inReal[sp.ringPos_trailingIdx] = inReal;
      sp.ringPos_trailingIdx = sp.ringPos_trailingIdx + 1;
      if( sp.ringPos_trailingIdx >= ringCapL_trailingIdx ) {
         sp.ringPos_trailingIdx = 0;
      }
      sp.winPos_j = sp.winPos_j + 1;
      if( sp.winPos_j >= sp.winCap_j ) {
         sp.winPos_j = 0;
      }
   }

   private RetCode CgOpenImpl( CgStream sp, ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      int today = 0;
      int outIdx = 0;
      int lookbackTotal = 0;
      int trailingIdx = 0;
      int j = 0;
      int k = 0;
      int limbs = 0;
      int fits = 0;
      int maxAt = 0;
      int failAt = 0;
      int stickyBars = 0;
      int fit2Mid = 0;
      int fit2Lo = 0;
      int fit3Mid = 0;
      double num = 0;
      double den = 0;
      double value = 0;
      double periodDouble = 0;
      double flatValue = 0;
      double weightTotal = 0;
      double width2 = 0;
      double width3 = 0;
      double ylim2 = 0;
      double ylim3 = 0;
      double head2 = 0;
      double head3 = 0;
      double scale = 0;
      double width = 0;
      double invWidth = 0;
      double widthSq = 0;
      double invWidthSq = 0;
      double ylim = 0;
      double maxAbs = 0;
      double half = 0;
      double scale2Mid = 0;
      double scale2Lo = 0;
      double scale3Mid = 0;
      double scale3Lo = 0;
      double x = 0;
      double y = 0;
      double a = 0;
      double b = 0;
      double c = 0;
      double q = 0;
      double t = 0;
      double denA = 0;
      double denB = 0;
      double denC = 0;
      double numA = 0;
      double numB = 0;
      double numC = 0;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > IndexMax + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 10;
      } else if( optInTimePeriod < 2 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      outBegIdx = 0;
      outNBElement = 0;
      lookbackTotal = CgLookback(optInTimePeriod);
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      if( startIdx > endIdx ) {
         return RetCode.InsufficientHistory ;
      }
      periodDouble = (double)optInTimePeriod;
      flatValue = -(periodDouble + 1.0) * 0.5;
      /* Each window value is held as y = x*scale, an integer, split into 2 or 3
       * integer-valued limbs of `width`. The bounds keep every limb of both the
       * weighted and the plain sum below 2^53 while the total weight is at most
       * 2^tb, so every add and subtract below is exact, and every product is by a
       * power of two or of two integers whose result is below 2^53. That makes
       * each output depend on its window alone, whatever scale or limb count the
       * call reached it with. Keep it that way: a rounded operation anywhere in
       * the limb arithmetic makes the output depend on the start index.
       *
       * 2 limbs: width 2^(53-tb), |y| < 2^(104-2tb).
       * 3 limbs: width min(2^(53-tb), 2^26), |y| < 2^(51-tb) * width^2.
       *
       * Keep every product out of an addition in the same expression: each
       * product is exact, so fusing would change no value, only cost a call
       * where FMA is not inlined.
       */
      weightTotal = 1.0;
      while( weightTotal < periodDouble * (periodDouble + 1.0) * 0.5 ) {
         weightTotal *= 2.0;
      }
      width2 = 9.007199254740992e15 / weightTotal;
      ylim2 = 0.25 * width2 * width2;
      width3 = width2;
      width3 = MinLt(67108864.0, width3);
      ylim3 = 0.25 * width2 * width3 * width3;
      /* A scale below the largest that fits leaves room for the window's
       * magnitude to grow before a rebuild, split evenly with the room left for
       * finer values.
       */
      head2 = 1.0;
      while( head2 * head2 * 9.007199254740992e15 < ylim2 ) {
         head2 *= 2.0;
      }
      head3 = 1.0;
      while( head3 * head3 * 9.007199254740992e15 < ylim3 ) {
         head3 *= 2.0;
      }
      limbs = 0;
      stickyBars = 0;
      scale = 1.0;
      width = 1.0;
      invWidth = 1.0;
      widthSq = 1.0;
      invWidthSq = 1.0;
      ylim = 0.0;
      half = 1.0;
      denA = 0.0;
      denB = 0.0;
      denC = 0.0;
      numA = 0.0;
      numB = 0.0;
      numC = 0.0;
      num = 0.0;
      den = 0.0;
      outIdx = 0;
      today = startIdx;
      trailingIdx = startIdx - lookbackTotal;
      while( today <= endIdx ) {
         /* Between bars the sums hold the window less its oldest value. */
         fits = 0;
         x = inReal[today];
         y = x * scale;
         if( limbs == 2 ) {
            if( Math.Abs(y) < ylim && (y != 0.0 || x == 0.0) ) {
               t = y * invWidth;
               a = t + 6.755399441055744e15 - 6.755399441055744e15;
               t = a * width;
               c = y - t;
               if( c + 6.755399441055744e15 - 6.755399441055744e15 == c ) {
                  denA += a;
                  denC += c;
                  numA += denA;
                  numC += denC;
                  fits = 1;
               }
            }
         } else if( limbs == 3 ) {
            if( Math.Abs(y) < ylim && (y != 0.0 || x == 0.0) ) {
               t = y * invWidthSq;
               a = t + 6.755399441055744e15 - 6.755399441055744e15;
               t = a * widthSq;
               q = y - t;
               t = q * invWidth;
               b = t + 6.755399441055744e15 - 6.755399441055744e15;
               t = b * width;
               c = q - t;
               if( c + 6.755399441055744e15 - 6.755399441055744e15 == c ) {
                  denA += a;
                  denB += b;
                  denC += c;
                  numA += denA;
                  numB += denB;
                  numC += denC;
                  fits = 1;
               }
            }
         }
         if( fits == 0 && limbs == 0 && stickyBars > 0 ) {
            /* Both witnesses of the last failed fit are still in the window, so
             * it cannot fit either: its largest value can only be larger, which
             * only coarsens the scale the failing value already missed.
             */
            stickyBars -= 1;
            num = 0.0;
            den = 0.0;
            for( j = today - lookbackTotal; j <= today; j += 1 ) {
               den += inReal[j];
               num += den;
            }
         } else if( fits == 0 ) {
            /* The incoming value does not fit the scale: pick one from the
             * window alone.
             */
            maxAbs = 0.0;
            maxAt = 0;
            k = 0;
            for( j = today - lookbackTotal; j <= today; j += 1 ) {
               x = Math.Abs(inReal[j]);
               if( x >= maxAbs ) {
                  maxAbs = x;
                  maxAt = k;
               }
               k += 1;
            }
            /* The largest power of two not above the window's largest
             * magnitude. The search may start from any finite power of two, so
             * it starts from the last window's; keep it uncapped, or a start far
             * from the answer stops short and the fit then depends on the
             * previous window. A window with an infinite magnitude fails the fit
             * at any scale, so it keeps the last one.
             */
            if( maxAbs > 0.0 && maxAbs <= 1.7976931348623157e308 ) {
               while( half * 65536.0 <= maxAbs ) {
                  half *= 65536.0;
               }
               while( half * 2.0 <= maxAbs ) {
                  half *= 2.0;
               }
               while( half > maxAbs * 65536.0 ) {
                  half *= 0.0000152587890625;
               }
               while( half > maxAbs ) {
                  half *= 0.5;
               }
            }
            /* The largest scale each limb count allows, and the same with
             * headroom, at most 2^1022 so that the scale itself is finite. The
             * largest 3-limb scale is the most permissive there is: the window
             * fits some scale only if every value is an integer at that one. A
             * scale below 1 can round a small value to 0, which is not a fit.
             */
            scale2Lo = ylim2 * 0.5 / half;
            scale2Lo = MinLt(4.49423283715579e307, scale2Lo);
            scale2Mid = scale2Lo / head2;
            scale3Lo = ylim3 * 0.5 / half;
            scale3Lo = MinLt(4.49423283715579e307, scale3Lo);
            scale3Mid = scale3Lo / head3;
            /* The same pass sums the window as it stands, oldest first, for when
             * nothing fits: non-finite values, bits below 2^-1022, or too wide a
             * span of magnitudes.
             */
            fit2Mid = 1;
            fit2Lo = 1;
            fit3Mid = 1;
            failAt = -1;
            num = 0.0;
            den = 0.0;
            k = 0;
            for( j = today - lookbackTotal; j <= today; j += 1 ) {
               x = inReal[j];
               den += x;
               num += den;
               y = Math.Abs(x * scale2Mid);
               if( !(y < ylim2) || y < 4.503599627370496e15 && y + 4.503599627370496e15 - 4.503599627370496e15 != y || y == 0.0 && x != 0.0 ) {
                  fit2Mid = 0;
               }
               y = Math.Abs(x * scale2Lo);
               if( !(y < ylim2) || y < 4.503599627370496e15 && y + 4.503599627370496e15 - 4.503599627370496e15 != y || y == 0.0 && x != 0.0 ) {
                  fit2Lo = 0;
               }
               y = Math.Abs(x * scale3Mid);
               if( !(y < ylim3) || y < 4.503599627370496e15 && y + 4.503599627370496e15 - 4.503599627370496e15 != y || y == 0.0 && x != 0.0 ) {
                  fit3Mid = 0;
               }
               y = Math.Abs(x * scale3Lo);
               if( !(y < ylim3) || y < 4.503599627370496e15 && y + 4.503599627370496e15 - 4.503599627370496e15 != y || y == 0.0 && x != 0.0 ) {
                  failAt = k;
               }
               k += 1;
            }
            limbs = 0;
            if( failAt >= 0 ) {
               if( failAt < maxAt ) {
                  stickyBars = failAt;
               } else {
                  stickyBars = maxAt;
               }
            } else {
               if( fit2Mid == 1 || fit2Lo == 1 ) {
                  limbs = 2;
                  width = width2;
                  ylim = ylim2;
                  if( fit2Mid == 1 ) {
                     scale = scale2Mid;
                  } else {
                     scale = scale2Lo;
                  }
               } else {
                  limbs = 3;
                  width = width3;
                  ylim = ylim3;
                  if( fit3Mid == 1 ) {
                     scale = scale3Mid;
                  } else {
                     scale = scale3Lo;
                  }
               }
               invWidth = 1.0 / width;
               widthSq = width * width;
               invWidthSq = invWidth * invWidth;
               denA = 0.0;
               denB = 0.0;
               denC = 0.0;
               numA = 0.0;
               numB = 0.0;
               numC = 0.0;
               if( limbs == 2 ) {
                  for( j = today - lookbackTotal; j <= today; j += 1 ) {
                     y = inReal[j] * scale;
                     t = y * invWidth;
                     a = t + 6.755399441055744e15 - 6.755399441055744e15;
                     t = a * width;
                     c = y - t;
                     denA += a;
                     denC += c;
                     numA += denA;
                     numC += denC;
                  }
               } else {
                  for( j = today - lookbackTotal; j <= today; j += 1 ) {
                     y = inReal[j] * scale;
                     t = y * invWidthSq;
                     a = t + 6.755399441055744e15 - 6.755399441055744e15;
                     t = a * widthSq;
                     q = y - t;
                     t = q * invWidth;
                     b = t + 6.755399441055744e15 - 6.755399441055744e15;
                     t = b * width;
                     c = q - t;
                     denA += a;
                     denB += b;
                     denC += c;
                     numA += denA;
                     numB += denB;
                     numC += denC;
                  }
               }
            }
         }
         /* One rounding each: the limbs are carried into range first, so the
          * last add sees two exact values.
          */
         if( limbs == 2 ) {
            t = denA * width;
            den = t + denC;
            t = numA * width;
            num = t + numC;
         } else if( limbs == 3 ) {
            t = denC * invWidth;
            q = t + 6.755399441055744e15 - 6.755399441055744e15;
            b = denB + q;
            t = q * width;
            c = denC - t;
            t = b * invWidth;
            q = t + 6.755399441055744e15 - 6.755399441055744e15;
            t = q * width;
            b = b - t;
            t = b * width;
            c = t + c;
            t = denA + q;
            t = t * widthSq;
            den = t + c;
            t = numC * invWidth;
            q = t + 6.755399441055744e15 - 6.755399441055744e15;
            b = numB + q;
            t = q * width;
            c = numC - t;
            t = b * invWidth;
            q = t + 6.755399441055744e15 - 6.755399441055744e15;
            t = q * width;
            b = b - t;
            t = b * width;
            c = t + c;
            t = numA + q;
            t = t * widthSq;
            num = t + c;
         }
         /* The denominator is a signed sum, so only an exact zero is degenerate.
          * It is answered with the flat-window value, which keeps every output a
          * function of its own window; an epsilon band would carry the quote unit
          * (#253).
          */
         if( den != 0.0 ) {
            value = -num / den;
         } else {
            value = flatValue;
         }
         if( limbs == 2 ) {
            y = inReal[trailingIdx] * scale;
            t = y * invWidth;
            a = t + 6.755399441055744e15 - 6.755399441055744e15;
            t = a * width;
            c = y - t;
            denA -= a;
            denC -= c;
            numA -= periodDouble * a;
            numC -= periodDouble * c;
         } else if( limbs == 3 ) {
            y = inReal[trailingIdx] * scale;
            t = y * invWidthSq;
            a = t + 6.755399441055744e15 - 6.755399441055744e15;
            t = a * widthSq;
            q = y - t;
            t = q * invWidth;
            b = t + 6.755399441055744e15 - 6.755399441055744e15;
            t = b * width;
            c = q - t;
            denA -= a;
            denB -= b;
            denC -= c;
            numA -= periodDouble * a;
            numB -= periodDouble * b;
            numC -= periodDouble * c;
         }
         /* After the trailing value is read: outReal may be inReal. */
         outReal[outIdx * outStride] = value;
         trailingIdx += 1;
         outIdx += 1;
         today += 1;
      }
      outBegIdx = startIdx;
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      int cap_trailingIdx = today - trailingIdx;
      if( cap_trailingIdx < 1 || cap_trailingIdx > historyLen ) {
         return RetCode.InternalError;
      }
      int allocN_trailingIdx = (cap_trailingIdx > 0)? cap_trailingIdx : 1;
      double[] capRing_trailingIdx_inReal = new double[allocN_trailingIdx];
      inReal.Slice(historyLen - cap_trailingIdx, cap_trailingIdx).CopyTo(capRing_trailingIdx_inReal);
      int cap_j = (int)(lookbackTotal + 1);
      if( cap_j < 1 || cap_j > historyLen ) {
         return RetCode.InternalError;
      }
      double[] capWin_j_inReal = new double[cap_j];
      inReal.Slice(historyLen - cap_j, cap_j).CopyTo(capWin_j_inReal);
      sp.optInTimePeriod = optInTimePeriod;
      sp.lookbackTotal = lookbackTotal;
      sp.limbs = limbs;
      sp.stickyBars = stickyBars;
      sp.num = num;
      sp.den = den;
      sp.periodDouble = periodDouble;
      sp.flatValue = flatValue;
      sp.width2 = width2;
      sp.width3 = width3;
      sp.ylim2 = ylim2;
      sp.ylim3 = ylim3;
      sp.head2 = head2;
      sp.head3 = head3;
      sp.scale = scale;
      sp.width = width;
      sp.invWidth = invWidth;
      sp.widthSq = widthSq;
      sp.invWidthSq = invWidthSq;
      sp.ylim = ylim;
      sp.half = half;
      sp.denA = denA;
      sp.denB = denB;
      sp.denC = denC;
      sp.numA = numA;
      sp.numB = numB;
      sp.numC = numC;
      sp.ringPos_trailingIdx = 0;
      sp.ringCap_trailingIdx = cap_trailingIdx;
      sp.ring_trailingIdx_inReal = capRing_trailingIdx_inReal;
      sp.winPos_j = 0;
      sp.winCap_j = cap_j;
      sp.win_j_inReal = capWin_j_inReal;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* CgOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal CgStream CgOpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      CgStream sp = new CgStream(this);
      RetCode retCode = CgOpenImpl(sp, inReal, startIdx, optInTimePeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("CG", "openAndFill", nameof(inReal), inReal.Length, startIdx, CgLookback(optInTimePeriod));
      }
      throw StreamFailure("CG", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind CgOpen (composition seam). */
   internal CgStream CgOpenInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod )
   {
      CgStream sp = new CgStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = CgOpenImpl(sp, inReal, startIdx, optInTimePeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("CG", "open", nameof(inReal), inReal.Length, startIdx, CgLookback(optInTimePeriod));
      }
      throw StreamFailure("CG", "open", retCode);
   }

   /// <summary>Open a live <c>CG</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="CgStream.Value"/> starts at the last history bar's
   /// value — bit-identical to what <c>CG</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>CgLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>CgOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">The series to measure. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="CgLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>CgLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public CgStream CgOpen( ReadOnlySpan<double> inReal, int optInTimePeriod )
   {
      if( inReal.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "CG open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "CG open: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      return CgOpenInternal(inReal, 0, optInTimePeriod);
   }

   /// <summary><c>CgOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>CG</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - CgLookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="CgStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">The series to measure. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="CgLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Negated center of gravity of the window. Must hold at least <c>historyLen
   /// - CgLookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>CgLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public CgStream CgOpenAndFill( ReadOnlySpan<double> inReal, int optInTimePeriod, Span<double> outReal )
   {
      if( inReal.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "CG openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "CG openAndFill: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      int guardOutLen = OpenFillCount("CG", "openAndFill", inReal.Length, CgLookback(optInTimePeriod));
      RequireFillLength("CG", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( SameBuffer(outReal, inReal) ) {
         throw StreamFailure("CG", "openAndFill", RetCode.BadParam);
      }
      if( guardOutLen > 0 && ( outReal.Overlaps(inReal) ) ) {
         throw StreamFailure("CG", "openAndFill", RetCode.BadParam);
      }
      return CgOpenAndFillInternal(inReal, 0, optInTimePeriod, out _, out _, outReal);
   }
}
