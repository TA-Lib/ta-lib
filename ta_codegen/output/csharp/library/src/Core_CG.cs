         int k = 0;
         int fits = 0;
         int maxAt = 0;
         int failAt = 0;
         int fit2Mid = 0;
         int fit2Lo = 0;
         int fit3Mid = 0;
         double value = 0.0;
         double maxAbs = 0.0;
         double scale2Mid = 0.0;
         double scale2Lo = 0.0;
         double scale3Mid = 0.0;
         double scale3Lo = 0.0;
         double x = 0.0;
         double y = 0.0;
         double a = 0.0;
         double b = 0.0;
         double c = 0.0;
         double q = 0.0;
         double t = 0.0;
         double cur_outReal = 0.0;
         double den = sp.den;
         double denA = sp.denA;
         double denB = sp.denB;
         double denC = sp.denC;
         double half = sp.half;
         double invWidth = sp.invWidth;
         double invWidthSq = sp.invWidthSq;
         int limbs = sp.limbs;
         double num = sp.num;
         double numA = sp.numA;
         double numB = sp.numB;
         double numC = sp.numC;
         double scale = sp.scale;
         int stickyBars = sp.stickyBars;
         double width = sp.width;
         double widthSq = sp.widthSq;
         double ylim = sp.ylim;
         int pkSlot0 = -1;
         double pkVal0 = 0.0;
         pkSlot0 = sp.winPos_j;
         pkVal0 = inReal;
