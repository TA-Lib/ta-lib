            t = q * width;
            c = numC - t;
            t = b * invWidth;
            q = t + 6.755399441055744e15 - 6.755399441055744e15;
            t = q * width;
            b = b - t;
            t = b * width;
            c = t + c;
            t = numA + q;
            t = t * widthSq;
            num = t + c;
         }
         /* The denominator is a signed sum, so only an exact zero is degenerate.
          * It is answered with the flat-window value, which keeps every output a
          * function of its own window; an epsilon band would carry the quote unit
          * (#253).
          */
         if( den != 0.0 ) {
            value = -num / den;
         } else {
            value = sp.flatValue;
         }
         if( limbs == 2 ) {
            y = sp.ring_trailingIdx_inReal[sp.ringPos_trailingIdx] * scale;
            t = y * invWidth;
            a = t + 6.755399441055744e15 - 6.755399441055744e15;
            t = a * width;
            c = y - t;
            denA -= a;
            denC -= c;
            numA -= sp.periodDouble * a;
            numC -= sp.periodDouble * c;
         } else if( limbs == 3 ) {
            y = sp.ring_trailingIdx_inReal[sp.ringPos_trailingIdx] * scale;
            t = y * invWidthSq;
            a = t + 6.755399441055744e15 - 6.755399441055744e15;
            t = a * widthSq;
            q = y - t;
            t = q * invWidth;
            b = t + 6.755399441055744e15 - 6.755399441055744e15;
            t = b * width;
            c = q - t;
            denA -= a;
            denB -= b;
            denC -= c;
            numA -= sp.periodDouble * a;
            numB -= sp.periodDouble * b;
            numC -= sp.periodDouble * c;
         }
         /* After the trailing value is read: outReal may be inReal. */
         cur_outReal = value;
         return cur_outReal;
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public CgStream Clone()
      {
         return new CgStream(this);
      }
