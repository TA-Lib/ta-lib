         } else if( fits == 0 ) {
            maxAbs = 0.0;
            maxAt = 0;
            k = 0;
            for( j = today - lookbackTotal; j <= today; j += 1 ) {
               x = Math.Abs((double)inReal[j]);
               if( x >= maxAbs ) {
                  maxAbs = x;
                  maxAt = k;
               }
               k += 1;
            }
            if( maxAbs > 0.0 && maxAbs <= 1.7976931348623157e308 ) {
               while( half * 65536.0 <= maxAbs ) {
                  half *= 65536.0;
               }
               while( half * 2.0 <= maxAbs ) {
                  half *= 2.0;
               }
               while( half > maxAbs * 65536.0 ) {
                  half *= 0.0000152587890625;
               }
               while( half > maxAbs ) {
                  half *= 0.5;
               }
            }
            scale2Lo = ylim2 * 0.5 / half;
            scale2Lo = MinLt(4.49423283715579e307, scale2Lo);
            scale2Mid = scale2Lo / head2;
            scale3Lo = ylim3 * 0.5 / half;
            scale3Lo = MinLt(4.49423283715579e307, scale3Lo);
            scale3Mid = scale3Lo / head3;
            fit2Mid = 1;
            fit2Lo = 1;
            fit3Mid = 1;
            failAt = -1;
            num = 0.0;
            den = 0.0;
            k = 0;
            for( j = today - lookbackTotal; j <= today; j += 1 ) {
               x = (double)inReal[j];
               den += x;
               num += den;
               y = Math.Abs(x * scale2Mid);
               if( !(y < ylim2) || y < 4.503599627370496e15 && y + 4.503599627370496e15 - 4.503599627370496e15 != y || y == 0.0 && x != 0.0 ) {
                  fit2Mid = 0;
               }
               y = Math.Abs(x * scale2Lo);
               if( !(y < ylim2) || y < 4.503599627370496e15 && y + 4.503599627370496e15 - 4.503599627370496e15 != y || y == 0.0 && x != 0.0 ) {
                  fit2Lo = 0;
               }
               y = Math.Abs(x * scale3Mid);
               if( !(y < ylim3) || y < 4.503599627370496e15 && y + 4.503599627370496e15 - 4.503599627370496e15 != y || y == 0.0 && x != 0.0 ) {
                  fit3Mid = 0;
               }
               y = Math.Abs(x * scale3Lo);
               if( !(y < ylim3) || y < 4.503599627370496e15 && y + 4.503599627370496e15 - 4.503599627370496e15 != y || y == 0.0 && x != 0.0 ) {
                  failAt = k;
               }
               k += 1;
            }
            limbs = 0;
            if( failAt >= 0 ) {
               if( failAt < maxAt ) {
                  stickyBars = failAt;
               } else {
                  stickyBars = maxAt;
               }
            } else {
               if( fit2Mid == 1 || fit2Lo == 1 ) {
                  limbs = 2;
                  width = width2;
                  ylim = ylim2;
                  if( fit2Mid == 1 ) {
                     scale = scale2Mid;
                  } else {
                     scale = scale2Lo;
                  }
               } else {
                  limbs = 3;
                  width = width3;
                  ylim = ylim3;
                  if( fit3Mid == 1 ) {
                     scale = scale3Mid;
                  } else {
                     scale = scale3Lo;
                  }
               }
               invWidth = 1.0 / width;
               widthSq = width * width;
               invWidthSq = invWidth * invWidth;
               denA = 0.0;
               denB = 0.0;
               denC = 0.0;
               numA = 0.0;
               numB = 0.0;
               numC = 0.0;
               if( limbs == 2 ) {
                  for( j = today - lookbackTotal; j <= today; j += 1 ) {
                     y = (double)inReal[j] * scale;
                     t = y * invWidth;
                     a = t + 6.755399441055744e15 - 6.755399441055744e15;
                     t = a * width;
                     c = y - t;
                     denA += a;
                     denC += c;
                     numA += denA;
                     numC += denC;
                  }
               } else {
                  for( j = today - lookbackTotal; j <= today; j += 1 ) {
                     y = (double)inReal[j] * scale;
                     t = y * invWidthSq;
                     a = t + 6.755399441055744e15 - 6.755399441055744e15;
                     t = a * widthSq;
                     q = y - t;
                     t = q * invWidth;
                     b = t + 6.755399441055744e15 - 6.755399441055744e15;
                     t = b * width;
                     c = q - t;
                     denA += a;
                     denB += b;
                     denC += c;
                     numA += denA;
                     numB += denB;
                     numC += denC;
                  }
               }
            }
         }
         if( limbs == 2 ) {
            t = denA * width;
            den = t + denC;
            t = numA * width;
            num = t + numC;
         } else if( limbs == 3 ) {
            t = denC * invWidth;
            q = t + 6.755399441055744e15 - 6.755399441055744e15;
            b = denB + q;
            t = q * width;
            c = denC - t;
            t = b * invWidth;
            q = t + 6.755399441055744e15 - 6.755399441055744e15;
            t = q * width;
            b = b - t;
            t = b * width;
            c = t + c;
            t = denA + q;
            t = t * widthSq;
            den = t + c;
            t = numC * invWidth;
            q = t + 6.755399441055744e15 - 6.755399441055744e15;
            b = numB + q;
            t = q * width;
            c = numC - t;
            t = b * invWidth;
            q = t + 6.755399441055744e15 - 6.755399441055744e15;
            t = q * width;
            b = b - t;
            t = b * width;
            c = t + c;
            t = numA + q;
            t = t * widthSq;
            num = t + c;
         }
         if( den != 0.0 ) {
            value = -num / den;
         } else {
            value = flatValue;
         }
         if( limbs == 2 ) {
            y = (double)inReal[trailingIdx] * scale;
            t = y * invWidth;
            a = t + 6.755399441055744e15 - 6.755399441055744e15;
            t = a * width;
            c = y - t;
            denA -= a;
            denC -= c;
            numA -= periodDouble * a;
            numC -= periodDouble * c;
         } else if( limbs == 3 ) {
            y = (double)inReal[trailingIdx] * scale;
            t = y * invWidthSq;
            a = t + 6.755399441055744e15 - 6.755399441055744e15;
            t = a * widthSq;
            q = y - t;
            t = q * invWidth;
            b = t + 6.755399441055744e15 - 6.755399441055744e15;
            t = b * width;
            c = q - t;
            denA -= a;
            denB -= b;
            denC -= c;
            numA -= periodDouble * a;
            numB -= periodDouble * b;
            numC -= periodDouble * c;
         }
         outReal[outIdx] = value;
         trailingIdx += 1;
         outIdx += 1;
         today += 1;
      }
      outBegIdx = startIdx;
      outNBElement = outIdx;
      return RetCode.Success ;
   }
   /// <summary>
   /// John Ehlers' Center of Gravity oscillator: the balance point of the last
   /// <c>optInTimePeriod</c> values, each weighted by its value and placed at
   /// its position counting back from the current bar, which is position 1,
   /// negated so that it rises with price. It is smooth and has essentially no
   /// lag. Ehlers reads turning points from it and trades its crossings with a
   /// copy of itself delayed by one bar. For a positive series it stays between
   /// -optInTimePeriod and -1, and a flat window sits at the midpoint,
   /// -(optInTimePeriod+1)/2.
   /// </summary>
   /// <remarks>
   /// <para>
   /// Formula and more info at
   /// <see href="https://ta-lib.org/functions/cg">ta-lib.org/functions/cg</see>.
   /// </para>
   /// <list type="bullet">
   /// <item><description>Ehlers' default input is the median price (H+L)/2: pass the output of MEDPRICE to reproduce it.</description></item>
   /// <item><description>His 2004 book presents the same oscillator shifted up by (optInTimePeriod+1)/2, so that a flat window reads 0: add (optInTimePeriod+1)/2 to the output to obtain that form.</description></item>
   /// <item><description>Where the window sums to exactly zero the author's listing keeps its previous value; TA-Lib returns -(optInTimePeriod+1)/2, so every value depends on its own window alone.</description></item>
   /// <item><description>Both sums are exact before the divide, so a window summing to exactly zero is always recognised and the value does not depend on where the call started. The exception is a window holding a non-finite value, a value with bits below 2^-1022 (every subnormal, and only values under about 2e-292), or values that together span more binary digits than the sums can hold exactly (97 at the default period, 84 at 1000, 58 at 100000): it is summed in floating point, oldest value first.</description></item>
   /// </list>
   /// <para>
   /// Values are written only where the indicator is defined. The returned
   /// <see cref="OutRange"/> says where they start and how many there are, and
   /// the library never pads with NaN. A valid range that ends before
   /// <c>CgLookback</c> is a <b>success with no values</b> (<c>Count == 0</c>),
   /// not an error.
   /// </para>
   /// <para>
   /// Every exception it throws, except the runtime's own
   /// <c>OutOfMemoryException</c>, implements <see cref="ITALibFailure"/>, which
   /// carries the <see cref="RetCode"/>.
   /// </para>
   /// </remarks>
   /// <param name="startIdx">First bar of the requested range (inclusive).</param>
   /// <param name="endIdx">Last bar of the requested range (inclusive).</param>
   /// <param name="inReal">The series to measure.</param>
   /// <param name="optInTimePeriod">Number of bars in the window (default 10; range 2..100000;
   /// <c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Negated center of gravity of the window. Must hold at least <c>endIdx -
   /// max(startIdx, CgLookback(...)) + 1</c> values, and never be empty: an
   /// empty span is an absent output.</param>
   /// <returns>The range written: <c>BegIdx</c> is the first bar with a value,
   /// <c>Count</c> how many were written.</returns>
   /// <exception cref="System.ArgumentOutOfRangeException"><c>startIdx</c> or <c>endIdx</c> is negative or above
   /// <see cref="Core.IndexMax"/>, or <c>endIdx &lt; startIdx</c>.</exception>
   /// <exception cref="System.ArgumentException">
   /// One of the following, checked before anything is written, so a rejected
   /// call leaves every buffer untouched:
   /// <list type="bullet">
   /// <item><description>An optional parameter is outside its documented range.</description></item>
   /// <item><description>A span is too short for the range requested: any input this function
   /// <i>declares</i> that does not reach <c>endIdx</c>, or an output that
   /// cannot hold the values produced. Declared, not read: a few candlestick
   /// patterns take an OHLC series they never index, and it is required all the
   /// same. A null array arrives as an empty span, and an empty span is an
   /// absent argument: for an input, or an output that cannot be declined, it is
   /// rejected even when the call would produce nothing.</description></item>
   /// <item><description>Two outputs overlap or are one array
   /// (<see href="https://ta-lib.org/spec/errors/#rb6">rule rB6</see>), or an
   /// output partially overlaps an input. Computing wholly in place (an output
   /// that IS an input) is allowed.</description></item>
   /// </list>
   /// </exception>
   /// <seealso cref="Core.Wma(int, int, ReadOnlySpan{double}, int, Span{double})"/>
   /// <seealso cref="Core.Medprice(int, int, ReadOnlySpan{double}, ReadOnlySpan{double}, Span{double})"/>
   /// <seealso cref="Core.Cti(int, int, ReadOnlySpan{double}, int, Span{double})"/>
   public OutRange Cg( int startIdx,
                       int endIdx,
                       ReadOnlySpan<double> inReal,
