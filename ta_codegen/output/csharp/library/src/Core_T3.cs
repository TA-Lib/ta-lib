   /// <returns>The range written: <c>BegIdx</c> is the first bar with a value,
   /// <c>Count</c> how many were written.</returns>
   /// <exception cref="System.ArgumentOutOfRangeException"><c>startIdx</c> or <c>endIdx</c> is negative or above
   /// <see cref="Core.MAX_INDEX"/>, or <c>endIdx &lt; startIdx</c>.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or two outputs
   /// share one array.</exception>
   /// <exception cref="System.ArgumentException">A span is too short for the range requested: any input this function
   /// <i>declares</i> that does not reach <c>endIdx</c>, or an output that
   /// cannot hold the values produced. Checked before anything is written, so a
   /// rejected call leaves every buffer untouched. Declared, not read: a few
   /// candlestick patterns take an OHLC series they never index, and it is
   /// required all the same. An empty span — which is what a null array becomes,
   /// since a span cannot be null — is rejected on the same terms and no others:
   /// it is too short whenever the range produces a value, and fine when it
   /// produces none, and on an output this function documents as declinable it
   /// is how you decline.</exception>
   /// <exception cref="System.ArgumentException">Two output buffers overlap, or an output partially overlaps an input.
   /// Computing wholly in place (an output that IS an input) is allowed.</exception>
   public OutRange T3( int startIdx,
                       int endIdx,
                       ReadOnlySpan<float> inReal,
                       int optInTimePeriod,
                       double optInVFactor,
                       Span<double> outReal )
   {
      int guardStart = ClampedStart(startIdx, endIdx, T3_Lookback(optInTimePeriod, optInVFactor));
      int guardInLen = guardStart < 0 ? 0 : endIdx + 1;
      int guardOutLen = guardStart < 0 || guardStart > endIdx ? 0 : endIdx - guardStart + 1;
      RequireLength("T3", "inReal", inReal.Length, guardInLen);
      RequireLength("T3", "outReal", outReal.Length, guardOutLen);
      RetCode retCode = T3_Impl(startIdx, endIdx, inReal, optInTimePeriod, optInVFactor, out int outBegIdx, out int outNBElement, outReal);
      if( retCode != RetCode.Success ) {
         throw Failure("T3", retCode);
      }
      return new OutRange(outBegIdx, outNBElement);
   }
   /**** Streaming API *****/

   /// <summary>A live <c>T3</c> stream: one value per closed bar, bit-identical to
   /// <c>T3</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.T3Open"/>. There is no close and nothing to
   /// dispose — the handle is ordinary managed state, and an unreferenced handle
   /// is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class T3Stream
   {
      internal Core core;
      internal int optInTimePeriod;
      internal double optInVFactor;
      internal double k;
      internal double one_minus_k;
      internal double e1;
      internal double e2;
      internal double e3;
      internal double e4;
      internal double e5;
      internal double e6;
      internal double c1;
      internal double c2;
      internal double c3;
      internal double c4;
      internal double cur_outReal;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal T3Stream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.T3</c> reports over the same bars: the opener sets it
      /// to <c>(lookback, historyLen - lookback)</c>, every <c>Update</c> adds one
      /// to the count — a non-finite bar is rejected but still counted, because the
      /// bar happened — <c>Peek</c> leaves it alone, and <c>Clone</c> carries it
      /// verbatim. A plain <c>Open</c> hands back only the last value, a subset of
      /// this range, because the caller chose not to take the fill.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      internal T3Stream( T3Stream other )
      {
         this.core = other.core;
         this.optInTimePeriod = other.optInTimePeriod;
         this.optInVFactor = other.optInVFactor;
         this.k = other.k;
         this.one_minus_k = other.one_minus_k;
         this.e1 = other.e1;
         this.e2 = other.e2;
         this.e3 = other.e3;
         this.e4 = other.e4;
         this.e5 = other.e5;
         this.e6 = other.e6;
         this.c1 = other.c1;
         this.c2 = other.c2;
         this.c3 = other.c3;
         this.c4 = other.c4;
         this.cur_outReal = other.cur_outReal;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Allocates nothing — neither handle state nor a return value.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so no state moves, <see cref="Value"/> still answers the previous value,
      /// and the stream stays usable — just carry on with the next bar.
      /// <see cref="OutRange"/> does advance: the bar happened, so it is counted,
      /// which keeps two handles fed the same series positionally aligned when only
      /// one of them rejects a bar. This is the one place the streaming tier is
      /// stricter than the batch API, which computes on whatever it is given: a
      /// handle retains its state, so a single non-finite bar would poison every
      /// later value it produces.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inReal )
      {
         if( !double.IsFinite(inReal) )
         {
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
            throw Core.StreamFailure("T3", "update", RetCode.BadParam);
         }
         core.T3StepImpl(this, inReal);
         if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It copies nothing: the frame runs against this handle, reading its buffers
      /// and holding what the step would commit in locals. The cost does not grow
      /// with the period, and <c>Peek</c> never allocates.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>What <see cref="Update"/> would return for this bar.</returns>
      public double Peek( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.StreamFailure("T3", "peek", RetCode.BadParam);
         T3Stream sp = this;
         double cur_outReal = sp.cur_outReal;
         double e1 = sp.e1;
         double e2 = sp.e2;
         double e3 = sp.e3;
         double e4 = sp.e4;
         double e5 = sp.e5;
         double e6 = sp.e6;
         if( sp.optInTimePeriod == 1 ) {
            cur_outReal = inReal;
            return cur_outReal ;
         }
         e1 = Math.FusedMultiplyAdd(sp.one_minus_k, e1, sp.k * inReal);
         e2 = Math.FusedMultiplyAdd(sp.one_minus_k, e2, sp.k * e1);
         e3 = Math.FusedMultiplyAdd(sp.one_minus_k, e3, sp.k * e2);
         e4 = Math.FusedMultiplyAdd(sp.one_minus_k, e4, sp.k * e3);
         e5 = Math.FusedMultiplyAdd(sp.one_minus_k, e5, sp.k * e4);
         e6 = Math.FusedMultiplyAdd(sp.one_minus_k, e6, sp.k * e5);
         cur_outReal = Math.FusedMultiplyAdd(sp.c4, e3, Math.FusedMultiplyAdd(sp.c3, e4, Math.FusedMultiplyAdd(sp.c1, e6, sp.c2 * e5)));
         return cur_outReal;
      }

      /// <summary>Commit <c>n</c> closed bars and write their <c>n</c> values, in one call.</summary>
      /// <remarks>
      /// <para>Exactly <c>n</c> back-to-back <see cref="Update"/> calls, with one set of
      /// argument checks instead of <c>n</c>. The outputs must hold at least
      /// <c>n</c> values and must not overlap an input or each other.</para>
      /// <para><see cref="OutRange"/> counts what this call took in, which is what makes
      /// a rejection readable: a non-finite bar <c>k</c> throws
      /// <see cref="System.ArgumentException"/> exactly as <see cref="Update"/>
      /// would, with the bars before <c>k</c> committed and written, bar <c>k</c>
      /// and everything after it not written, and the count advanced by <c>k +
      /// 1</c> — the committed bars plus the rejected one, so the last bar counted
      /// is the one that failed.</para>
      /// </remarks>
      /// <param name="inReal">Closed bars for <c>inReal</c>, oldest first.</param>
      /// <param name="outReal">Receives one <c>outReal</c> value per bar committed.</param>
      public void UpdateAndFill( ReadOnlySpan<double> inReal, Span<double> outReal )
      {
         int barCount = inReal.Length;
         if( outReal.Length < barCount || outReal.Overlaps(inReal) ) throw Core.StreamFailure("T3", "updateAndFill", RetCode.BadParam);
         for( int i = 0; i < barCount; i++ )
         {
            if( !double.IsFinite(inReal[i]) )
            {
               if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
               throw Core.StreamFailure("T3", "updateAndFill", RetCode.BadParam);
            }
            core.T3StepImpl(this, inReal[i]);
            outReal[i] = cur_outReal;
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         }
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public T3Stream Clone()
      {
         return new T3Stream(this);
      }
   }

   internal void T3StepImpl( T3Stream sp, double inReal )
   {
      if( sp.optInTimePeriod == 1 ) {
         sp.cur_outReal = inReal;
         return ;
      }
      sp.e1 = Math.FusedMultiplyAdd(sp.one_minus_k, sp.e1, sp.k * inReal);
      sp.e2 = Math.FusedMultiplyAdd(sp.one_minus_k, sp.e2, sp.k * sp.e1);
      sp.e3 = Math.FusedMultiplyAdd(sp.one_minus_k, sp.e3, sp.k * sp.e2);
      sp.e4 = Math.FusedMultiplyAdd(sp.one_minus_k, sp.e4, sp.k * sp.e3);
      sp.e5 = Math.FusedMultiplyAdd(sp.one_minus_k, sp.e5, sp.k * sp.e4);
      sp.e6 = Math.FusedMultiplyAdd(sp.one_minus_k, sp.e6, sp.k * sp.e5);
      sp.cur_outReal = Math.FusedMultiplyAdd(sp.c4, sp.e3, Math.FusedMultiplyAdd(sp.c3, sp.e4, Math.FusedMultiplyAdd(sp.c1, sp.e6, sp.c2 * sp.e5)));
   }

   private RetCode T3OpenImpl( T3Stream sp, ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, double optInVFactor, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      int outIdx = 0;
      int lookbackTotal = 0;
      int today = 0;
      int i = 0;
      double k = 0;
      double one_minus_k = 0;
      double e1 = 0;
      double e2 = 0;
      double e3 = 0;
      double e4 = 0;
      double e5 = 0;
      double e6 = 0;
      double c1 = 0;
      double c2 = 0;
      double c3 = 0;
      double c4 = 0;
      double tempReal = 0;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 5;
      } else if( optInTimePeriod < 1 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInVFactor == TA_REAL_DEFAULT ) {
         optInVFactor = 7e-1;
      } else if( !(optInVFactor >= 0e0 && optInVFactor <= 1e0) ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      if( optInTimePeriod == 1 ) {
         int fillLb = T3_Lookback(optInTimePeriod, optInVFactor);
         if( startIdx > fillLb ) fillLb = startIdx;
         if( historyLen < fillLb + 1 ) {
            return RetCode.InsufficientHistory;
         }
         sp.optInTimePeriod = optInTimePeriod;
         sp.optInVFactor = optInVFactor;
         sp.k = 0.0;
         sp.one_minus_k = 0.0;
         sp.e1 = 0.0;
         sp.e2 = 0.0;
         sp.e3 = 0.0;
         sp.e4 = 0.0;
         sp.e5 = 0.0;
         sp.e6 = 0.0;
         sp.c1 = 0.0;
         sp.c2 = 0.0;
         sp.c3 = 0.0;
         sp.c4 = 0.0;
         outBegIdx = fillLb;
         outNBElement = historyLen - fillLb;
         if( outStride == 0 ) {
            outReal[0] = inReal[historyLen - 1];
         } else {
            for( int fillIdx = 0; fillIdx < historyLen - fillLb; fillIdx++ ) {
               outReal[fillIdx] = inReal[fillLb + fillIdx];
            }
         }
         sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
         return RetCode.Success;
      }
      /* For an explanation of this function, please read:
       *
       * Magazine articles written by Tim Tillson
       *
       * Essentially, a T3 of time serie 't' is:
       *   EMA1(x,Period) = EMA(x,Period)
       *   EMA2(x,Period) = EMA(EMA1(x,Period),Period)
       *   GD(x,Period,vFactor) = (EMA1(x,Period)*(1+vFactor)) - (EMA2(x,Period)*vFactor)
       *   T3 = GD (GD ( GD(t, Period, vFactor), Period, vFactor), Period, vFactor);
       *
       * T3 offers a moving average with less lags then the
       * traditional EMA.
       *
       * Do not confuse a T3 with EMA3. Both are called "Triple EMA"
       * in the litterature.
       */
      lookbackTotal = 6 * (optInTimePeriod - 1) + this.unstablePeriod[(int)FuncUnstId.T3];
      if( startIdx <= lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         outNBElement = 0;
         outBegIdx = 0;
         return RetCode.InsufficientHistory ;
      }
      outBegIdx = startIdx;
      today = startIdx - lookbackTotal;
      k = 2.0 / (optInTimePeriod + 1.0);
      one_minus_k = 1.0 - k;
      /* Initialize e1 */
      tempReal = inReal[today++];
      for( i = optInTimePeriod - 1; i > 0; i -= 1 ) {
         tempReal += inReal[today++];
      }
      e1 = tempReal / optInTimePeriod;
      /* Initialize e2 */
      tempReal = e1;
      for( i = optInTimePeriod - 1; i > 0; i -= 1 ) {
         e1 = Math.FusedMultiplyAdd(one_minus_k, e1, k * inReal[today++]);
         tempReal += e1;
      }
      e2 = tempReal / optInTimePeriod;
      /* Initialize e3 */
      tempReal = e2;
      for( i = optInTimePeriod - 1; i > 0; i -= 1 ) {
         e1 = Math.FusedMultiplyAdd(one_minus_k, e1, k * inReal[today++]);
         e2 = Math.FusedMultiplyAdd(one_minus_k, e2, k * e1);
         tempReal += e2;
      }
      e3 = tempReal / optInTimePeriod;
      /* Initialize e4 */
      tempReal = e3;
      for( i = optInTimePeriod - 1; i > 0; i -= 1 ) {
         e1 = Math.FusedMultiplyAdd(one_minus_k, e1, k * inReal[today++]);
         e2 = Math.FusedMultiplyAdd(one_minus_k, e2, k * e1);
         e3 = Math.FusedMultiplyAdd(one_minus_k, e3, k * e2);
         tempReal += e3;
      }
      e4 = tempReal / optInTimePeriod;
      /* Initialize e5 */
      tempReal = e4;
      for( i = optInTimePeriod - 1; i > 0; i -= 1 ) {
         e1 = Math.FusedMultiplyAdd(one_minus_k, e1, k * inReal[today++]);
         e2 = Math.FusedMultiplyAdd(one_minus_k, e2, k * e1);
         e3 = Math.FusedMultiplyAdd(one_minus_k, e3, k * e2);
         e4 = Math.FusedMultiplyAdd(one_minus_k, e4, k * e3);
         tempReal += e4;
      }
      e5 = tempReal / optInTimePeriod;
      /* Initialize e6 */
      tempReal = e5;
      for( i = optInTimePeriod - 1; i > 0; i -= 1 ) {
         e1 = Math.FusedMultiplyAdd(one_minus_k, e1, k * inReal[today++]);
         e2 = Math.FusedMultiplyAdd(one_minus_k, e2, k * e1);
         e3 = Math.FusedMultiplyAdd(one_minus_k, e3, k * e2);
         e4 = Math.FusedMultiplyAdd(one_minus_k, e4, k * e3);
         e5 = Math.FusedMultiplyAdd(one_minus_k, e5, k * e4);
         tempReal += e5;
      }
      e6 = tempReal / optInTimePeriod;
      /* Skip the unstable period */
      while( today <= startIdx ) {
         /* Do the calculation but do not write the output */
         e1 = Math.FusedMultiplyAdd(one_minus_k, e1, k * inReal[today++]);
         e2 = Math.FusedMultiplyAdd(one_minus_k, e2, k * e1);
         e3 = Math.FusedMultiplyAdd(one_minus_k, e3, k * e2);
         e4 = Math.FusedMultiplyAdd(one_minus_k, e4, k * e3);
         e5 = Math.FusedMultiplyAdd(one_minus_k, e5, k * e4);
         e6 = Math.FusedMultiplyAdd(one_minus_k, e6, k * e5);
      }
      /* Calculate the constants */
      tempReal = optInVFactor * optInVFactor;
      c1 = 0 - tempReal * optInVFactor;
      c2 = 3.0 * (tempReal - c1);
      c3 = (0 - 6.0) * tempReal - 3.0 * (optInVFactor - c1);
      c4 = Math.FusedMultiplyAdd(3.0, tempReal, Math.FusedMultiplyAdd(3.0, optInVFactor, 1.0) - c1);
      /* Write the first output */
      outIdx = 0;
      outReal[outIdx++ * outStride] = Math.FusedMultiplyAdd(c4, e3, Math.FusedMultiplyAdd(c3, e4, Math.FusedMultiplyAdd(c1, e6, c2 * e5)));
      /* Calculate and output the remaining of the range. */
      while( today <= endIdx ) {
         e1 = Math.FusedMultiplyAdd(one_minus_k, e1, k * inReal[today++]);
         e2 = Math.FusedMultiplyAdd(one_minus_k, e2, k * e1);
         e3 = Math.FusedMultiplyAdd(one_minus_k, e3, k * e2);
         e4 = Math.FusedMultiplyAdd(one_minus_k, e4, k * e3);
         e5 = Math.FusedMultiplyAdd(one_minus_k, e5, k * e4);
         e6 = Math.FusedMultiplyAdd(one_minus_k, e6, k * e5);
         outReal[outIdx++ * outStride] = Math.FusedMultiplyAdd(c4, e3, Math.FusedMultiplyAdd(c3, e4, Math.FusedMultiplyAdd(c1, e6, c2 * e5)));
      }
      /* Indicates to the caller the number of output
       * successfully calculated.
       */
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      sp.optInTimePeriod = optInTimePeriod;
      sp.optInVFactor = optInVFactor;
      sp.k = k;
      sp.one_minus_k = one_minus_k;
      sp.e1 = e1;
      sp.e2 = e2;
      sp.e3 = e3;
      sp.e4 = e4;
      sp.e5 = e5;
      sp.e6 = e6;
      sp.c1 = c1;
      sp.c2 = c2;
      sp.c3 = c3;
      sp.c4 = c4;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* T3OpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal T3Stream T3OpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, double optInVFactor, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      T3Stream sp = new T3Stream(this);
      RetCode retCode = T3OpenImpl(sp, inReal, startIdx, optInTimePeriod, optInVFactor, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("T3", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind T3Open (composition seam). */
   internal T3Stream T3OpenInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, double optInVFactor )
   {
      T3Stream sp = new T3Stream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = T3OpenImpl(sp, inReal, startIdx, optInTimePeriod, optInVFactor, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("T3", "open", retCode);
   }

   /// <summary>Open a live <c>T3</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="T3Stream.Value"/> starts at the last history bar's
   /// value — bit-identical to what <c>T3</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>T3_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>T3OpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">Source series to smooth. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="T3_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInVFactor">As in the batch call; see <see cref="T3_Lookback"/> for its default and
   /// range (<c>-4e37</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>T3_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public T3Stream T3Open( ReadOnlySpan<double> inReal, int optInTimePeriod, double optInVFactor )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "T3 open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "T3 open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      return T3OpenInternal(inReal, 0, optInTimePeriod, optInVFactor);
   }

   /// <summary><c>T3Open</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>T3</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - T3_Lookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="T3Stream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">Source series to smooth. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="T3_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInVFactor">As in the batch call; see <see cref="T3_Lookback"/> for its default and
   /// range (<c>-4e37</c> selects the default).</param>
   /// <param name="outReal">T3 smoothed line. Must hold at least <c>historyLen - T3_Lookback(...)</c>
   /// values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>T3_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public T3Stream T3OpenAndFill( ReadOnlySpan<double> inReal, int optInTimePeriod, double optInVFactor, Span<double> outReal )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "T3 openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "T3 openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      int guardOutLen = OpenFillCount("T3", "openAndFill", inReal.Length, T3_Lookback(optInTimePeriod, optInVFactor));
      RequireFillLength("T3", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( outReal.Overlaps(inReal) ) {
         throw StreamFailure("T3", "openAndFill", RetCode.BadParam);
      }
      return T3OpenAndFillInternal(inReal, 0, optInTimePeriod, optInVFactor, out _, out _, outReal);
   }
}
