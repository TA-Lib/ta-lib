      /// bar's output too. For a bar the caller leaves out: one an <c>Update</c>
      /// rejected and that will not be re-fed, or a session with no print. Without
      /// it two handles on one feed drift a bar apart when only one of them skips.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, the last one the batch tier
      /// can address and the last this handle will count. <c>Update</c> throws the
      /// same there.</para>
      /// </remarks>
      public void Advance()
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("SQZMOM", "advance", RetCode.OutOfRangeEndIndex);
         outRangeCount++;
      }

      internal SqzmomStream( SqzmomStream other )
      {
         this.core = other.core;
         this.optInBBPeriod = other.optInBBPeriod;
         this.optInNbDev = other.optInNbDev;
         this.optInKCPeriod = other.optInKCPeriod;
         this.optInFactorWide = other.optInFactorWide;
         this.optInFactorNormal = other.optInFactorNormal;
         this.optInFactorNarrow = other.optInFactorNarrow;
         this.cur_outMomentum = other.cur_outMomentum;
         this.cur_outSqueeze = other.cur_outSqueeze;
         this.sub0 = new MidpriceStream(other.sub0);
         this.sub1 = new SmaStream(other.sub1);
         this.sub2 = new MedpriceStream(other.sub2);
         this.sub3 = new SmaStream(other.sub3);
         this.sub4 = new SubStream(other.sub4);
         this.sub5 = new TrangeStream(other.sub5);
         this.sub6 = new SmaStream(other.sub6);
         this.sub7 = new SmaStream(other.sub7);
         this.sub8 = new StddevStream(other.sub8);
         this.sub9 = new SmaStream(other.sub9);
         this.sub10 = new LinearregStream(other.sub10);
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so nothing moves — <see cref="OutRange"/> included — and
      /// <see cref="Value"/> still answers the previous value. Re-feed the bar when
      /// a corrected value arrives, or call <see cref="Advance"/> to count it and
      /// carry on; two handles on one feed drift a bar apart if neither happens.
      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, which no re-feed clears: the
      /// handle has run out of index domain and only a shorter history can start a
      /// new one.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>The value at the bar just committed.</returns>
      public SqzmomValue Update( double inHigh, double inLow, double inClose )
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("SQZMOM", "update", RetCode.OutOfRangeEndIndex);
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) ) throw Core.NonFiniteBar("SQZMOM", "update", !double.IsFinite(inHigh) ? nameof(inHigh) : !double.IsFinite(inLow) ? nameof(inLow) : nameof(inClose));
         core.SqzmomStepImpl(this, inHigh, inLow, inClose);
         outRangeCount++;
         return new SqzmomValue(cur_outMomentum, cur_outSqueeze);
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.IndexMax"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public SqzmomValue Peek( double inHigh, double inLow, double inClose )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) ) throw Core.NonFiniteBar("SQZMOM", "peek", !double.IsFinite(inHigh) ? nameof(inHigh) : !double.IsFinite(inLow) ? nameof(inLow) : nameof(inClose));
         SqzmomStream sp = this;
         double band = 0.0;
         double centre = 0.0;
         double lo = 0.0;
         double up = 0.0;
         double cur_tempDev = 0.0;
         double cur_tempWork = 0.0;
         double cur_tempMid = 0.0;
         double cur_tempSD = 0.0;
         double cur_tempKCM = 0.0;
         double cur_outMomentum = 0.0;
         int cur_outSqueeze = 0;
         /* Pipeline the new bar through the sub-streams (batch tail order). */
         cur_tempDev = sp.sub0.Peek(inHigh, inLow);
         cur_tempWork = sp.sub1.Peek(inClose);
         cur_tempDev = sp.sub2.Peek(cur_tempDev, cur_tempWork);
         cur_tempWork = sp.sub3.Peek(inClose);
         cur_tempDev = sp.sub4.Peek(cur_tempWork, cur_tempDev);
         cur_tempWork = sp.sub5.Peek(inHigh, inLow, inClose);
         cur_tempWork = sp.sub6.Peek(cur_tempWork);
         cur_tempMid = sp.sub7.Peek(inClose);
         cur_tempSD = sp.sub8.Peek(inClose);
         cur_tempKCM = sp.sub9.Peek(inClose);
         cur_outMomentum = sp.sub10.Peek(cur_tempDev);
         /* Combine map (batch tail, per bar). */
         up = Math.FusedMultiplyAdd(cur_tempSD, sp.optInNbDev, cur_tempMid);
         lo = cur_tempMid - cur_tempSD * sp.optInNbDev;
         centre = cur_tempKCM;
         band = cur_tempWork;
         if( lo > centre - sp.optInFactorNarrow * band && up < centre + sp.optInFactorNarrow * band ) {
            cur_outSqueeze = 3;
         } else if( lo > centre - sp.optInFactorNormal * band && up < centre + sp.optInFactorNormal * band ) {
            cur_outSqueeze = 2;
         } else if( lo > centre - sp.optInFactorWide * band && up < centre + sp.optInFactorWide * band ) {
            cur_outSqueeze = 1;
         } else if( lo < centre - sp.optInFactorWide * band && up > centre + sp.optInFactorWide * band ) {
            cur_outSqueeze = -1;
         } else {
            cur_outSqueeze = 0;
         }
         return new SqzmomValue(cur_outMomentum, cur_outSqueeze);
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public SqzmomValue Value => new SqzmomValue(cur_outMomentum, cur_outSqueeze);

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public SqzmomStream Clone()
      {
         return new SqzmomStream(this);
      }
   }

   private void SqzmomStepImpl( SqzmomStream sp, double inHigh, double inLow, double inClose )
   {
      double band = 0.0;
      double centre = 0.0;
      double lo = 0.0;
      double up = 0.0;
      double cur_tempDev = 0.0;
      double cur_tempWork = 0.0;
      double cur_tempMid = 0.0;
      double cur_tempSD = 0.0;
      double cur_tempKCM = 0.0;
      double cur_outMomentum = 0.0;
      int cur_outSqueeze = 0;
      /* Pipeline the new bar through the sub-streams (batch tail order). */
      cur_tempDev = sp.sub0.Update(inHigh, inLow);
      cur_tempWork = sp.sub1.Update(inClose);
      cur_tempDev = sp.sub2.Update(cur_tempDev, cur_tempWork);
      cur_tempWork = sp.sub3.Update(inClose);
      cur_tempDev = sp.sub4.Update(cur_tempWork, cur_tempDev);
      cur_tempWork = sp.sub5.Update(inHigh, inLow, inClose);
      cur_tempWork = sp.sub6.Update(cur_tempWork);
      cur_tempMid = sp.sub7.Update(inClose);
      cur_tempSD = sp.sub8.Update(inClose);
      cur_tempKCM = sp.sub9.Update(inClose);
      cur_outMomentum = sp.sub10.Update(cur_tempDev);
      /* Combine map (batch tail, per bar). */
      up = Math.FusedMultiplyAdd(cur_tempSD, sp.optInNbDev, cur_tempMid);
      lo = cur_tempMid - cur_tempSD * sp.optInNbDev;
      centre = cur_tempKCM;
      band = cur_tempWork;
      if( lo > centre - sp.optInFactorNarrow * band && up < centre + sp.optInFactorNarrow * band ) {
         cur_outSqueeze = 3;
      } else if( lo > centre - sp.optInFactorNormal * band && up < centre + sp.optInFactorNormal * band ) {
         cur_outSqueeze = 2;
      } else if( lo > centre - sp.optInFactorWide * band && up < centre + sp.optInFactorWide * band ) {
         cur_outSqueeze = 1;
      } else if( lo < centre - sp.optInFactorWide * band && up > centre + sp.optInFactorWide * band ) {
         cur_outSqueeze = -1;
      } else {
         cur_outSqueeze = 0;
      }
      sp.cur_outMomentum = cur_outMomentum;
      sp.cur_outSqueeze = cur_outSqueeze;
   }

   private RetCode SqzmomOpenImpl( SqzmomStream sp, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInBBPeriod, double optInNbDev, int optInKCPeriod, double optInFactorWide, double optInFactorNormal, double optInFactorNarrow, out int outBegIdx, out int outNBElement, Span<double> outMomentum, Span<int> outSqueeze, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      RetCode retCode;
      int lookbackTotal = 0;
      int stageLookback = 0;
      int stageIdx = 0;
      int stageLen = 0;
      int i = 0;
      int n = 0;
      int tempBegIdx = 0;
      int tempNbElement = 0;
      Span<double> tempDev;
      Span<double> tempWork;
      Span<double> tempKCM;
      Span<double> tempMid;
      Span<double> tempSD;
      double up = 0;
      double lo = 0;
      double centre = 0;
      double band = 0;
      int historyLen = inHigh.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > IndexMax + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inLow.Length != inHigh.Length || inClose.Length != inHigh.Length ) {
         return RetCode.BadParam;
      }
      if( optInBBPeriod == int.MinValue ) {
         optInBBPeriod = 20;
      } else if( optInBBPeriod < 2 || optInBBPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInNbDev == RealDefault ) {
         optInNbDev = 2e0;
      } else if( !(optInNbDev >= 0e0 && optInNbDev <= RealMax) ) {
         return RetCode.BadParam;
      }
      if( optInKCPeriod == int.MinValue ) {
         optInKCPeriod = 20;
      } else if( optInKCPeriod < 2 || optInKCPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInFactorWide == RealDefault ) {
         optInFactorWide = 2e0;
      } else if( !(optInFactorWide >= 0e0 && optInFactorWide <= RealMax) ) {
         return RetCode.BadParam;
      }
      if( optInFactorNormal == RealDefault ) {
         optInFactorNormal = 1.5e0;
      } else if( !(optInFactorNormal >= 0e0 && optInFactorNormal <= RealMax) ) {
         return RetCode.BadParam;
      }
      if( optInFactorNarrow == RealDefault ) {
         optInFactorNarrow = 1e0;
      } else if( !(optInFactorNarrow >= 0e0 && optInFactorNarrow <= RealMax) ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      if( historyLen < SqzmomLookback(optInBBPeriod, optInNbDev, optInKCPeriod, optInFactorWide, optInFactorNormal, optInFactorNarrow) + 1 ) {
         return RetCode.InsufficientHistory;
      }
      Span<double> sc_outMomentum = outStride == 1 ? outMomentum : new double[historyLen];
      Span<int> sc_outSqueeze = outStride == 1 ? outSqueeze : new int[historyLen];
      /* Every leg is a shipped function, CALLED rather than transcribed, so both
       * outputs carry each callee's own arithmetic bit for bit:
       *
       *   BBU, BBL = sma(close, b) +/- nbdev * stddev(close, b, 1.0)
       *   KCM      = sma(close, k)
       *   BAND     = sma(trange(high,low,close), k)      the simple mean of TR
       *   DMID     = midprice(high, low, k)
       *   DEV      = close - (DMID + KCM)/2
       *   momentum = linearreg(DEV, k)
       *
       * The bands are taken as the MA + STDDEV pair rather than through bbands
       * because bbands' SMA fast path states it is bit-identical to that pair, and
       * it is what bbands' own stream tier composes; taking the pair here keeps
       * every optional argument a parameter or a literal.
       *
       * DEV is built from shipped functions too, not in a loop of its own:
       * medprice is (a+b)/2 over any two series, and sma at a period of 1 is the
       * identity -- a one-element sum divided by 1.0, exact for every double --
       * which is what puts the close into the staged range's own indexing so that
       * sub can take the difference.
       *
       * Two chains need their input one window earlier than the first output bar:
       * sma(k) over TR, and linearreg(k) over DEV. Both windows are k-1 long, so
       * one staged range serves both.
       */
      lookbackTotal = SqzmomLookback(optInBBPeriod, optInNbDev, optInKCPeriod, optInFactorWide, optInFactorNormal, optInFactorNarrow);
      if( lookbackTotal > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      n = endIdx - startIdx + 1;
      stageLookback = LinearregLookback(optInKCPeriod);
      stageIdx = startIdx - stageLookback;
      stageLen = n + stageLookback;
      tempDev = new double[(int)(stageLen * 1)];
      tempWork = new double[(int)(stageLen * 1)];
      tempKCM = new double[(int)(n * 1)];
      tempMid = new double[(int)(n * 1)];
      tempSD = new double[(int)(n * 1)];
      /* The momentum anchor: the Donchian midpoint and the Keltner centre, averaged.
       * midprice is bit-identical to donchian's middle band.
       */
      /* Sub-stream 0: midprice over `inHigh, inLow`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      MidpriceStream sub0 = MidpriceOpenAndFillInternal(inHigh, inLow, stageIdx, optInKCPeriod, out tempBegIdx, out tempNbElement, tempDev);
      retCode = RetCode.Success;
      /* Sub-stream 1: sma over `inClose`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      SmaStream sub1 = SmaOpenAndFillInternal(inClose, stageIdx, optInKCPeriod, out tempBegIdx, out tempNbElement, tempWork);
      retCode = RetCode.Success;
      /* tempDev becomes (DMID + KCM)/2 in place: medprice reads and writes the same
       * index, so the overwrite is safe.
       */
      /* Sub-stream 2: medprice over `tempDev, tempWork`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      int subLen2 = (stageLen - 1) + 1;
      double[] subSrc2_0 = new double[subLen2];
      tempDev.Slice(0, subLen2).CopyTo(subSrc2_0);
      double[] subSrc2_1 = new double[subLen2];
      tempWork.Slice(0, subLen2).CopyTo(subSrc2_1);
      MedpriceStream sub2 = MedpriceOpenInternal(subSrc2_0, subSrc2_1, 0);
      OutRange _xr0 = Medprice(0, stageLen - 1, tempDev, tempWork, tempDev);
      tempBegIdx = _xr0.BegIdx;
      tempNbElement = _xr0.Count;
      retCode = RetCode.Success;
      /* The close over the staged range, in that range's own indexing. */
      /* Sub-stream 3: sma over `inClose`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      SmaStream sub3 = SmaOpenAndFillInternal(inClose, stageIdx, 1, out tempBegIdx, out tempNbElement, tempWork);
      retCode = RetCode.Success;
      /* Sub-stream 4: sub over `tempWork, tempDev`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      int subLen4 = (stageLen - 1) + 1;
      double[] subSrc4_0 = new double[subLen4];
      tempWork.Slice(0, subLen4).CopyTo(subSrc4_0);
      double[] subSrc4_1 = new double[subLen4];
      tempDev.Slice(0, subLen4).CopyTo(subSrc4_1);
      SubStream sub4 = SubOpenInternal(subSrc4_0, subSrc4_1, 0);
      OutRange _xr1 = Sub(0, stageLen - 1, tempWork, tempDev, tempDev);
      tempBegIdx = _xr1.BegIdx;
      tempNbElement = _xr1.Count;
      retCode = RetCode.Success;
      /* The compression band: the simple mean of the true range, not an ATR.
       * trange's own lookback is 1, and stageIdx is at least 1 because the
       * compression chain alone puts lookbackTotal at k or more.
       */
      /* Sub-stream 5: trange over `inHigh, inLow, inClose`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      TrangeStream sub5 = TrangeOpenAndFillInternal(inHigh, inLow, inClose, stageIdx, out tempBegIdx, out tempNbElement, tempWork);
      retCode = RetCode.Success;
      /* Sub-stream 6: sma over `tempWork`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      int subLen6 = (stageLen - 1) + 1;
      double[] subSrc6_0 = new double[subLen6];
      tempWork.Slice(0, subLen6).CopyTo(subSrc6_0);
      SmaStream sub6 = SmaOpenInternal(subSrc6_0, 0, optInKCPeriod);
      OutRange _xr2 = Sma(0, stageLen - 1, tempWork, optInKCPeriod, tempWork);
      tempBegIdx = _xr2.BegIdx;
      tempNbElement = _xr2.Count;
      retCode = RetCode.Success;
      /* Sub-stream 7: sma over `inClose`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      SmaStream sub7 = SmaOpenAndFillInternal(inClose, startIdx, optInBBPeriod, out tempBegIdx, out tempNbElement, tempMid);
      retCode = RetCode.Success;
      /* Sub-stream 8: stddev over `inClose`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      StddevStream sub8 = StddevOpenAndFillInternal(inClose, startIdx, optInBBPeriod, 1.0, out tempBegIdx, out tempNbElement, tempSD);
      retCode = RetCode.Success;
      /* Sub-stream 9: sma over `inClose`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      SmaStream sub9 = SmaOpenAndFillInternal(inClose, startIdx, optInKCPeriod, out tempBegIdx, out tempNbElement, tempKCM);
      retCode = RetCode.Success;
      /* LAST of the calls, because it is the first to write a caller buffer. Every
       * read of high, low and close is above it, so an output aliased onto one of
       * them -- which the abstract layer tests on purpose -- is still intact when it
       * is read.
       *
       * The regression window closes on the first output bar, so entering it at 0 of
       * the staged range puts its first fitted value on startIdx.
       */
      /* Sub-stream 10: linearreg over `tempDev`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      int subLen10 = (stageLen - 1) + 1;
      double[] subSrc10_0 = new double[subLen10];
      tempDev.Slice(0, subLen10).CopyTo(subSrc10_0);
      LinearregStream sub10 = LinearregOpenAndFillInternal(subSrc10_0, 0, optInKCPeriod, out tempBegIdx, out tempNbElement, sc_outMomentum);
      retCode = RetCode.Success;
      /* The ordinal. The three Keltner widths share the centre and BAND >= 0, so
       * the tests nest: inside(narrow) implies inside(normal) implies inside(wide).
       * Testing narrow first is what makes the ordinal monotone without comparing
       * the factors to each other, which is why the card asks for
       * `wide >= normal >= narrow >= 0` and not for a strict order.
       */
      for( i = 0; i < n; i += 1 ) {
         up = Math.FusedMultiplyAdd(tempSD[i], optInNbDev, tempMid[i]);
         lo = tempMid[i] - tempSD[i] * optInNbDev;
         centre = tempKCM[i];
         band = tempWork[i];
         if( lo > centre - optInFactorNarrow * band && up < centre + optInFactorNarrow * band ) {
            sc_outSqueeze[i] = 3;
         } else if( lo > centre - optInFactorNormal * band && up < centre + optInFactorNormal * band ) {
            sc_outSqueeze[i] = 2;
         } else if( lo > centre - optInFactorWide * band && up < centre + optInFactorWide * band ) {
            sc_outSqueeze[i] = 1;
         } else if( lo < centre - optInFactorWide * band && up > centre + optInFactorWide * band ) {
            sc_outSqueeze[i] = -1;
         } else {
            sc_outSqueeze[i] = 0;
         }
      }
      outBegIdx = startIdx;
      outNBElement = n;
      /* Capture the live producer state + sub handles. */
      if( outNBElement < 1 ) {
         return RetCode.InsufficientHistory;
      }
      sp.optInBBPeriod = optInBBPeriod;
      sp.optInNbDev = optInNbDev;
      sp.optInKCPeriod = optInKCPeriod;
      sp.optInFactorWide = optInFactorWide;
      sp.optInFactorNormal = optInFactorNormal;
      sp.optInFactorNarrow = optInFactorNarrow;
      sp.sub0 = sub0;
      sp.sub1 = sub1;
      sp.sub2 = sub2;
      sp.sub3 = sub3;
      sp.sub4 = sub4;
      sp.sub5 = sub5;
      sp.sub6 = sub6;
      sp.sub7 = sub7;
      sp.sub8 = sub8;
      sp.sub9 = sub9;
      sp.sub10 = sub10;
      sp.cur_outMomentum = sc_outMomentum[outNBElement - 1];
      sp.cur_outSqueeze = sc_outSqueeze[outNBElement - 1];
      return RetCode.Success;
   }

   /* SqzmomOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal SqzmomStream SqzmomOpenAndFillInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInBBPeriod, double optInNbDev, int optInKCPeriod, double optInFactorWide, double optInFactorNormal, double optInFactorNarrow, out int outBegIdx, out int outNBElement, Span<double> outMomentum, Span<int> outSqueeze )
   {
      SqzmomStream sp = new SqzmomStream(this);
      RetCode retCode = SqzmomOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInBBPeriod, optInNbDev, optInKCPeriod, optInFactorWide, optInFactorNormal, optInFactorNarrow, out outBegIdx, out outNBElement, outMomentum, outSqueeze, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("SQZMOM", "openAndFill", nameof(inHigh), inHigh.Length, startIdx, SqzmomLookback(optInBBPeriod, optInNbDev, optInKCPeriod, optInFactorWide, optInFactorNormal, optInFactorNarrow));
      }
      throw StreamFailure("SQZMOM", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind SqzmomOpen (composition seam). */
   internal SqzmomStream SqzmomOpenInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInBBPeriod, double optInNbDev, int optInKCPeriod, double optInFactorWide, double optInFactorNormal, double optInFactorNarrow )
   {
      SqzmomStream sp = new SqzmomStream(this);
      double[] sink_outMomentum = new double[1];
      int[] sink_outSqueeze = new int[1];
      RetCode retCode = SqzmomOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInBBPeriod, optInNbDev, optInKCPeriod, optInFactorWide, optInFactorNormal, optInFactorNarrow, out int outBegIdx, out int outNBElement, sink_outMomentum, sink_outSqueeze, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("SQZMOM", "open", nameof(inHigh), inHigh.Length, startIdx, SqzmomLookback(optInBBPeriod, optInNbDev, optInKCPeriod, optInFactorWide, optInFactorNormal, optInFactorNarrow));
      }
      throw StreamFailure("SQZMOM", "open", retCode);
   }

   /// <summary>Open a live <c>SQZMOM</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="SqzmomStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>SQZMOM</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>SqzmomLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>SqzmomOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Closing price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInBBPeriod">As in the batch call; see <see cref="SqzmomLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInNbDev">As in the batch call; see <see cref="SqzmomLookback"/> for its default and
   /// range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <param name="optInKCPeriod">As in the batch call; see <see cref="SqzmomLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInFactorWide">As in the batch call; see <see cref="SqzmomLookback"/> for its default and
   /// range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <param name="optInFactorNormal">As in the batch call; see <see cref="SqzmomLookback"/> for its default and
   /// range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <param name="optInFactorNarrow">As in the batch call; see <see cref="SqzmomLookback"/> for its default and
   /// range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>SqzmomLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public SqzmomStream SqzmomOpen( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInBBPeriod, double optInNbDev, int optInKCPeriod, double optInFactorWide, double optInFactorNormal, double optInFactorNarrow )
   {
      if( inHigh.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "SQZMOM open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "SQZMOM open: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TALibArgumentException("SQZMOM open: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TALibArgumentException("SQZMOM open: inClose is empty", nameof(inClose), RetCode.BadParam);
      RequireHistoryLength("SQZMOM", "open", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("SQZMOM", "open", "inClose", inClose.Length, inHigh.Length);
      return SqzmomOpenInternal(inHigh, inLow, inClose, 0, optInBBPeriod, optInNbDev, optInKCPeriod, optInFactorWide, optInFactorNormal, optInFactorNarrow);
   }

   /// <summary><c>SqzmomOpen</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>SQZMOM</c> produces over
   /// the same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - SqzmomLookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="SqzmomStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Closing price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInBBPeriod">As in the batch call; see <see cref="SqzmomLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInNbDev">As in the batch call; see <see cref="SqzmomLookback"/> for its default and
   /// range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <param name="optInKCPeriod">As in the batch call; see <see cref="SqzmomLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInFactorWide">As in the batch call; see <see cref="SqzmomLookback"/> for its default and
   /// range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <param name="optInFactorNormal">As in the batch call; see <see cref="SqzmomLookback"/> for its default and
   /// range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <param name="optInFactorNarrow">As in the batch call; see <see cref="SqzmomLookback"/> for its default and
   /// range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <param name="outMomentum">Linear regression of the close against the Donchian/SMA anchor. Must hold
   /// at least <c>historyLen - SqzmomLookback(...)</c> values.</param>
   /// <param name="outSqueeze">Compression level: 3 narrow, 2 normal, 1 wide, -1 released, 0 otherwise.
   /// Must hold at least <c>historyLen - SqzmomLookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>SqzmomLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public SqzmomStream SqzmomOpenAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInBBPeriod, double optInNbDev, int optInKCPeriod, double optInFactorWide, double optInFactorNormal, double optInFactorNarrow, Span<double> outMomentum, Span<int> outSqueeze )
   {
      if( inHigh.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "SQZMOM openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "SQZMOM openAndFill: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TALibArgumentException("SQZMOM openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TALibArgumentException("SQZMOM openAndFill: inClose is empty", nameof(inClose), RetCode.BadParam);
      int guardOutLen = OpenFillCount("SQZMOM", "openAndFill", inHigh.Length, SqzmomLookback(optInBBPeriod, optInNbDev, optInKCPeriod, optInFactorWide, optInFactorNormal, optInFactorNarrow));
      RequireHistoryLength("SQZMOM", "openAndFill", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("SQZMOM", "openAndFill", "inClose", inClose.Length, inHigh.Length);
      RequireFillLength("SQZMOM", "openAndFill", "outMomentum", outMomentum.Length, guardOutLen);
      RequireFillLength("SQZMOM", "openAndFill", "outSqueeze", outSqueeze.Length, guardOutLen);
      if( SameBuffer(outMomentum, inHigh) || SameBuffer(outMomentum, inLow) || SameBuffer(outMomentum, inClose) || SameBuffer(System.Runtime.InteropServices.MemoryMarshal.AsBytes(outSqueeze), System.Runtime.InteropServices.MemoryMarshal.AsBytes(inHigh)) || SameBuffer(System.Runtime.InteropServices.MemoryMarshal.AsBytes(outSqueeze), System.Runtime.InteropServices.MemoryMarshal.AsBytes(inLow)) || SameBuffer(System.Runtime.InteropServices.MemoryMarshal.AsBytes(outSqueeze), System.Runtime.InteropServices.MemoryMarshal.AsBytes(inClose)) || SameBuffer(System.Runtime.InteropServices.MemoryMarshal.AsBytes(outMomentum), System.Runtime.InteropServices.MemoryMarshal.AsBytes(outSqueeze)) ) {
         throw StreamFailure("SQZMOM", "openAndFill", RetCode.BadParam);
      }
      if( guardOutLen > 0 && ( outMomentum.Overlaps(inHigh) || outMomentum.Overlaps(inLow) || outMomentum.Overlaps(inClose) || System.Runtime.InteropServices.MemoryMarshal.AsBytes(outSqueeze).Overlaps(System.Runtime.InteropServices.MemoryMarshal.AsBytes(inHigh)) || System.Runtime.InteropServices.MemoryMarshal.AsBytes(outSqueeze).Overlaps(System.Runtime.InteropServices.MemoryMarshal.AsBytes(inLow)) || System.Runtime.InteropServices.MemoryMarshal.AsBytes(outSqueeze).Overlaps(System.Runtime.InteropServices.MemoryMarshal.AsBytes(inClose)) || OutputsAlias(System.Runtime.InteropServices.MemoryMarshal.AsBytes(outMomentum), System.Runtime.InteropServices.MemoryMarshal.AsBytes(outSqueeze)) ) ) {
         throw StreamFailure("SQZMOM", "openAndFill", RetCode.BadParam);
      }
      return SqzmomOpenAndFillInternal(inHigh, inLow, inClose, 0, optInBBPeriod, optInNbDev, optInKCPeriod, optInFactorWide, optInFactorNormal, optInFactorNarrow, out _, out _, outMomentum, outSqueeze);
   }
