      tempBegIdx = _xr8.BegIdx;
      tempNbElement = _xr8.Count;
      retCode = RetCode.Success;
      OutRange _xr9 = Sma(startIdx, endIdx, inClose, optInKCPeriod, tempKCM);
      tempBegIdx = _xr9.BegIdx;
      tempNbElement = _xr9.Count;
      retCode = RetCode.Success;
      OutRange _xr10 = Linearreg(0, stageLen - 1, tempDev, optInKCPeriod, outMomentum);
      tempBegIdx = _xr10.BegIdx;
      tempNbElement = _xr10.Count;
      retCode = RetCode.Success;
      for( i = 0; i < n; i += 1 ) {
         up = Math.FusedMultiplyAdd(tempSD[i], optInNbDev, tempMid[i]);
         lo = tempMid[i] - tempSD[i] * optInNbDev;
         centre = tempKCM[i];
         band = tempWork[i];
         if( lo > centre - optInFactorNarrow * band && up < centre + optInFactorNarrow * band ) {
            outSqueeze[i] = 3;
         } else if( lo > centre - optInFactorNormal * band && up < centre + optInFactorNormal * band ) {
            outSqueeze[i] = 2;
         } else if( lo > centre - optInFactorWide * band && up < centre + optInFactorWide * band ) {
            outSqueeze[i] = 1;
         } else if( lo < centre - optInFactorWide * band && up > centre + optInFactorWide * band ) {
            outSqueeze[i] = -1;
         } else {
            outSqueeze[i] = 0;
         }
      }
      ReturnScratch(ref _rent_tempDev);
      ReturnScratch(ref _rent_tempWork);
      ReturnScratch(ref _rent_tempKCM);
      ReturnScratch(ref _rent_tempMid);
      ReturnScratch(ref _rent_tempSD);
      outBegIdx = startIdx;
      outNBElement = n;
      return RetCode.Success ;
   }
