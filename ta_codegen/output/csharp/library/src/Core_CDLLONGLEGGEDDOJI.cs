   /// <param name="outInteger">+100 when the pattern is present, 0 otherwise. Only +100 is emitted; the
   /// code never emits -100, and the positive sign does NOT mean bullish. Must
   /// hold at least <c>historyLen - CDLLONGLEGGEDDOJI_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>CDLLONGLEGGEDDOJI_Lookback(...) + 1</c>
   /// bars.</exception>
