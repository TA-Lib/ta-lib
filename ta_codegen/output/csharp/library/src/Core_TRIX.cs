         if( !double.IsFinite(inReal) ) throw Core.StreamFailure("TRIX", "peek", RetCode.BadParam);
         TrixStream scratch = new TrixStream(this);
         core.TrixStepImpl(scratch, inReal);
         return scratch.cur_outReal;
      }

      /// <summary>Commit <c>n</c> closed bars and write their <c>n</c> values, in one call.</summary>
      /// <remarks>
      /// <para>Exactly <c>n</c> back-to-back <see cref="Update"/> calls, with one set of
      /// argument checks instead of <c>n</c>. The outputs must hold at least
      /// <c>n</c> values and must not overlap an input or each other.</para>
      /// <para><see cref="OutRange"/> counts what was committed, which is what makes a
      /// rejection readable: a non-finite bar <c>k</c> throws
      /// <see cref="System.ArgumentException"/> exactly as <see cref="Update"/>
      /// would, with bars <c>0..k</c> committed and written, bar <c>k</c> and
      /// everything after it not, and the count advanced by <c>k</c>.</para>
      /// </remarks>
      /// <param name="inReal">Closed bars for <c>inReal</c>, oldest first.</param>
      /// <param name="outReal">Receives one <c>outReal</c> value per bar committed.</param>
      public void UpdateAndFill( ReadOnlySpan<double> inReal, Span<double> outReal )
      {
         int barCount = inReal.Length;
         if( outReal.Length < barCount || outReal.Overlaps(inReal) ) throw Core.StreamFailure("TRIX", "updateAndFill", RetCode.BadParam);
         for( int i = 0; i < barCount; i++ )
         {
            if( !double.IsFinite(inReal[i]) ) throw Core.StreamFailure("TRIX", "updateAndFill", RetCode.BadParam);
            core.TrixStepImpl(this, inReal[i]);
            outReal[i] = cur_outReal;
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         }
      }

      /// <summary>The value at the most recently committed bar — the last history bar right
      /// after open, then whatever the latest <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public TrixStream Clone()
      {
         return new TrixStream(this);
      }
   }

   internal void TrixStepImpl( TrixStream sp, double inReal )
   {
      double tempReal = 0.0;
      tempReal = sp.prevEMA3;
      sp.prevEMA1 = Math.FusedMultiplyAdd(inReal - sp.prevEMA1, sp.optInK_1, sp.prevEMA1);
      sp.prevEMA2 = Math.FusedMultiplyAdd(sp.prevEMA1 - sp.prevEMA2, sp.optInK_1, sp.prevEMA2);
      sp.prevEMA3 = Math.FusedMultiplyAdd(sp.prevEMA2 - sp.prevEMA3, sp.optInK_1, sp.prevEMA3);
      if( tempReal != 0.0 ) {
         sp.cur_outReal = (sp.prevEMA3 / tempReal - 1.0) * 100.0;
      } else {
         sp.cur_outReal = 0.0;
      }
   }

   private RetCode TrixOpenImpl( TrixStream sp, ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double prevEMA1 = 0;
      double prevEMA2 = 0;
      double prevEMA3 = 0;
      double tempReal = 0;
      double optInK_1 = 0;
      int i = 0;
      int today = 0;
      int outIdx = 0;
      int lookbackEMA = 0;
      int lookbackTotal = 0;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 30;
      } else if( optInTimePeriod < 1 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      /* TRIX = 1-day percent rate-of-change of a triple EMA. */
      /* Will change only on success. */
      outNBElement = 0;
      outBegIdx = 0;
      /* Adjust startIdx to account for the lookback period. */
      lookbackEMA = EMA_Lookback(optInTimePeriod);
      lookbackTotal = lookbackEMA * 3 + ROCR_Lookback(1);
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         return RetCode.InsufficientHistory ;
      }
      /* Single lockstep pass: EMA1 feeds EMA2 feeds EMA3, output is the
       * roc() of consecutive EMA3 values. Output element j is the TRIX
       * of bar startIdx+j (fix #98). The arithmetic order below is the
       * bit-exactness contract — do not reorder or fuse operations; the
       * seed sums accumulate from 0.0 in production order (0.0+x is not
       * x for x=-0.0). In-place safe: outReal[outIdx] is written after
       * inReal[startIdx+outIdx] was read.
       */
      optInK_1 = 2.0 / (double)(optInTimePeriod + 1);
      /* Seed EMA1 with a simple average of the first
       * 'period' price bars.
       */
      today = startIdx - lookbackTotal;
      i = optInTimePeriod;
      tempReal = 0.0;
      while( i-- > 0 ) {
         tempReal += inReal[today++];
      }
      prevEMA1 = tempReal / optInTimePeriod;
      /* Advance EMA1 alone through its unstable period, up to
       * the bar where EMA2 seeding begins.
       */
      while( today <= startIdx - (lookbackEMA * 2 + 1) ) {
         prevEMA1 = Math.FusedMultiplyAdd(inReal[today++] - prevEMA1, optInK_1, prevEMA1);
      }
      /* Seed EMA2 with a simple average of the first 'period'
       * EMA1 values, accumulated as EMA1 produces them.
       */
      tempReal = 0.0;
      tempReal += prevEMA1;
      i = optInTimePeriod - 1;
      while( i-- > 0 ) {
         prevEMA1 = Math.FusedMultiplyAdd(inReal[today++] - prevEMA1, optInK_1, prevEMA1);
         tempReal += prevEMA1;
      }
      prevEMA2 = tempReal / optInTimePeriod;
      /* Advance EMA1 and EMA2 in lockstep through the unstable
       * period of EMA2, up to the bar where EMA3 seeding begins.
       */
      while( today <= startIdx - (lookbackEMA + 1) ) {
         prevEMA1 = Math.FusedMultiplyAdd(inReal[today++] - prevEMA1, optInK_1, prevEMA1);
         prevEMA2 = Math.FusedMultiplyAdd(prevEMA1 - prevEMA2, optInK_1, prevEMA2);
      }
      /* Seed EMA3 with a simple average of the first 'period'
       * EMA2 values, accumulated as EMA2 produces them.
       */
      tempReal = 0.0;
      tempReal += prevEMA2;
      i = optInTimePeriod - 1;
      while( i-- > 0 ) {
         prevEMA1 = Math.FusedMultiplyAdd(inReal[today++] - prevEMA1, optInK_1, prevEMA1);
         prevEMA2 = Math.FusedMultiplyAdd(prevEMA1 - prevEMA2, optInK_1, prevEMA2);
         tempReal += prevEMA2;
      }
      prevEMA3 = tempReal / optInTimePeriod;
      /* Advance all three EMA in lockstep through the unstable
       * period of EMA3, up to the bar before the first output.
       */
      while( today <= startIdx - 1 ) {
         prevEMA1 = Math.FusedMultiplyAdd(inReal[today++] - prevEMA1, optInK_1, prevEMA1);
         prevEMA2 = Math.FusedMultiplyAdd(prevEMA1 - prevEMA2, optInK_1, prevEMA2);
         prevEMA3 = Math.FusedMultiplyAdd(prevEMA2 - prevEMA3, optInK_1, prevEMA3);
      }
      /* Stable zone: keep advancing the three EMA in lockstep and
       * write the 1-day rate-of-change of EMA3 into the output.
       */
      outIdx = 0;
      while( today <= endIdx ) {
         tempReal = prevEMA3;
         prevEMA1 = Math.FusedMultiplyAdd(inReal[today++] - prevEMA1, optInK_1, prevEMA1);
         prevEMA2 = Math.FusedMultiplyAdd(prevEMA1 - prevEMA2, optInK_1, prevEMA2);
         prevEMA3 = Math.FusedMultiplyAdd(prevEMA2 - prevEMA3, optInK_1, prevEMA3);
         if( tempReal != 0.0 ) {
            outReal[outIdx++ * outStride] = (prevEMA3 / tempReal - 1.0) * 100.0;
         } else {
            outReal[outIdx++ * outStride] = 0.0;
         }
      }
      /* Succeed. Indicate where the output starts relative to
       * the caller input.
       */
      outBegIdx = startIdx;
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      sp.optInTimePeriod = optInTimePeriod;
      sp.prevEMA1 = prevEMA1;
      sp.prevEMA2 = prevEMA2;
      sp.prevEMA3 = prevEMA3;
      sp.optInK_1 = optInK_1;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* TrixOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal TrixStream TrixOpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      TrixStream sp = new TrixStream(this);
      RetCode retCode = TrixOpenImpl(sp, inReal, startIdx, optInTimePeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("TRIX", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind TrixOpen (composition seam). */
   internal TrixStream TrixOpenInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod )
   {
      TrixStream sp = new TrixStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = TrixOpenImpl(sp, inReal, startIdx, optInTimePeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("TRIX", "open", retCode);
   }

   /// <summary>Open a live <c>TRIX</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="TrixStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>TRIX</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>TRIX_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>TrixOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">Source series to smooth. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="TRIX_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>TRIX_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public TrixStream TrixOpen( ReadOnlySpan<double> inReal, int optInTimePeriod )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "TRIX open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "TRIX open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      return TrixOpenInternal(inReal, 0, optInTimePeriod);
   }

   /// <summary><c>TrixOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>TRIX</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - TRIX_Lookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="TrixStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">Source series to smooth. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="TRIX_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">1-day percent ROC of the triple EMA. Must hold at least <c>historyLen -
   /// TRIX_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>TRIX_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public TrixStream TrixOpenAndFill( ReadOnlySpan<double> inReal, int optInTimePeriod, Span<double> outReal )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "TRIX openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "TRIX openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      int guardOutLen = OpenFillCount("TRIX", "openAndFill", inReal.Length, TRIX_Lookback(optInTimePeriod));
      RequireFillLength("TRIX", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( outReal.Overlaps(inReal) ) {
         throw StreamFailure("TRIX", "openAndFill", RetCode.BadParam);
      }
      return TrixOpenAndFillInternal(inReal, 0, optInTimePeriod, out _, out _, outReal);
   }
