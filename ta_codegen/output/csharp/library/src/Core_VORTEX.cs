   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or two outputs
   /// share one array.</exception>
   /// <exception cref="System.ArgumentException">A span is too short for the range requested: any input this function
   /// <i>declares</i> that does not reach <c>endIdx</c>, or an output that
   /// cannot hold the values produced. Checked before anything is written, so a
   /// rejected call leaves every buffer untouched. Declared, not read: a few
   /// candlestick patterns take an OHLC series they never index, and it is
   /// required all the same. An empty span — which is what a null array becomes,
   /// since a span cannot be null — is rejected on the same terms and no others:
   /// it is too short whenever the range produces a value, and fine when it
   /// produces none, and on an output this function documents as declinable it
   /// is how you decline.</exception>
   /// <exception cref="System.ArgumentException">Two output buffers overlap, or an output partially overlaps an input.
   /// Computing wholly in place (an output that IS an input) is allowed.</exception>
   public OutRange VORTEX( int startIdx,
                           int endIdx,
                           ReadOnlySpan<float> inHigh,
                           ReadOnlySpan<float> inLow,
                           ReadOnlySpan<float> inClose,
                           int optInTimePeriod,
                           Span<double> outPlusVI,
                           Span<double> outMinusVI )
   {
      int guardStart = ClampedStart(startIdx, endIdx, VORTEX_Lookback(optInTimePeriod));
      int guardInLen = guardStart < 0 ? 0 : endIdx + 1;
      int guardOutLen = guardStart < 0 || guardStart > endIdx ? 0 : endIdx - guardStart + 1;
      RequireLength("VORTEX", "inHigh", inHigh.Length, guardInLen);
      RequireLength("VORTEX", "inLow", inLow.Length, guardInLen);
      RequireLength("VORTEX", "inClose", inClose.Length, guardInLen);
      RequireLength("VORTEX", "outPlusVI", outPlusVI.Length, guardOutLen);
      RequireLength("VORTEX", "outMinusVI", outMinusVI.Length, guardOutLen);
      RetCode retCode = VORTEX_Impl(startIdx, endIdx, inHigh, inLow, inClose, optInTimePeriod, out int outBegIdx, out int outNBElement, outPlusVI, outMinusVI);
      if( retCode != RetCode.Success ) {
         throw Failure("VORTEX", retCode);
      }
      return new OutRange(outBegIdx, outNBElement);
   }
   /**** Streaming API *****/

   /// <summary>One <c>VORTEX</c> output set, in batch output order.</summary>
   /// <remarks>
   /// <para>Equality is the compiler-generated record-struct equality, which compares
   /// the components with <c>==</c>: <c>NaN</c> does not equal <c>NaN</c>, and
   /// <c>0.0</c> equals <c>-0.0</c>. That is deliberately <em>not</em> the Java
   /// <c>Value</c> contract, which compares bitwise — compare
   /// <see cref="System.BitConverter.DoubleToInt64Bits(double)"/> per component
   /// when bit-level identity is what you mean.</para>
   /// </remarks>
   /// <param name="PlusVI">Positive vortex line (+VI)</param>
   /// <param name="MinusVI">Negative vortex line (−VI)</param>
   public readonly record struct VortexValue( double PlusVI, double MinusVI );

   /// <summary>A live <c>VORTEX</c> stream: one value per closed bar, bit-identical to
   /// <c>VORTEX</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.VortexOpen"/>. There is no close and nothing to
   /// dispose — the handle is ordinary managed state, and an unreferenced handle
   /// is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class VortexStream
   {
      internal Core core;
      internal int optInTimePeriod;
      internal int nullRun;
      internal double sTR;
      internal double sVMP;
      internal double sVMM;
      internal double lag1_inHigh;
      internal double lag1_inLow;
      internal double lag1_inClose;
      internal int ringPos_trailingIdx;
      internal int ringCap_trailingIdx;
      internal int ringLag_trailingIdx;
      internal double[] ring_trailingIdx_inHigh = [];
      internal double[] ring_trailingIdx_inLow = [];
      internal double[] ring_trailingIdx_inClose = [];
      internal double cur_outPlusVI;
      internal double cur_outMinusVI;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal VortexStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Vortex</c> reports over the same bars: the opener sets
      /// it to <c>(lookback, historyLen - lookback)</c>, every <c>Update</c> adds
      /// one to the count — a non-finite bar is rejected but still counted, because
      /// the bar happened — <c>Peek</c> leaves it alone, and <c>Clone</c> carries
      /// it verbatim. A plain <c>Open</c> hands back only the last value, a subset
      /// of this range, because the caller chose not to take the fill.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      internal VortexStream( VortexStream other )
      {
         this.core = other.core;
         this.optInTimePeriod = other.optInTimePeriod;
         this.nullRun = other.nullRun;
         this.sTR = other.sTR;
         this.sVMP = other.sVMP;
         this.sVMM = other.sVMM;
         this.lag1_inHigh = other.lag1_inHigh;
         this.lag1_inLow = other.lag1_inLow;
         this.lag1_inClose = other.lag1_inClose;
         this.ringPos_trailingIdx = other.ringPos_trailingIdx;
         this.ringCap_trailingIdx = other.ringCap_trailingIdx;
         this.ringLag_trailingIdx = other.ringLag_trailingIdx;
         this.ring_trailingIdx_inHigh = new double[other.ring_trailingIdx_inHigh.Length];
         Array.Copy( other.ring_trailingIdx_inHigh, this.ring_trailingIdx_inHigh, other.ring_trailingIdx_inHigh.Length );
         this.ring_trailingIdx_inLow = new double[other.ring_trailingIdx_inLow.Length];
         Array.Copy( other.ring_trailingIdx_inLow, this.ring_trailingIdx_inLow, other.ring_trailingIdx_inLow.Length );
         this.ring_trailingIdx_inClose = new double[other.ring_trailingIdx_inClose.Length];
         Array.Copy( other.ring_trailingIdx_inClose, this.ring_trailingIdx_inClose, other.ring_trailingIdx_inClose.Length );
         this.cur_outPlusVI = other.cur_outPlusVI;
         this.cur_outMinusVI = other.cur_outMinusVI;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Allocates nothing — neither handle state nor a return value.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so no state moves, <see cref="Value"/> still answers the previous value,
      /// and the stream stays usable — just carry on with the next bar.
      /// <see cref="OutRange"/> does advance: the bar happened, so it is counted,
      /// which keeps two handles fed the same series positionally aligned when only
      /// one of them rejects a bar. This is the one place the streaming tier is
      /// stricter than the batch API, which computes on whatever it is given: a
      /// handle retains its state, so a single non-finite bar would poison every
      /// later value it produces.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>The value at the bar just committed.</returns>
      public VortexValue Update( double inHigh, double inLow, double inClose )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) )
         {
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
            throw Core.StreamFailure("VORTEX", "update", RetCode.BadParam);
         }
         core.VortexStepImpl(this, inHigh, inLow, inClose);
         if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         return new VortexValue(cur_outPlusVI, cur_outMinusVI);
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It copies nothing: the frame runs against this handle, reading its buffers
      /// and holding what the step would commit in locals. The cost does not grow
      /// with the period, and <c>Peek</c> never allocates.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>What <see cref="Update"/> would return for this bar.</returns>
      public VortexValue Peek( double inHigh, double inLow, double inClose )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) ) throw Core.StreamFailure("VORTEX", "peek", RetCode.BadParam);
         VortexStream sp = this;
         double curTR = 0.0;
         double curVMP = 0.0;
         double curVMM = 0.0;
         double trueRange = 0.0;
         double tempDouble = 0.0;
         double tempLT = 0.0;
         double tempHT = 0.0;
         double tempCY = 0.0;
         double cur_outMinusVI = 0.0;
         double cur_outPlusVI = 0.0;
         int nullRun = sp.nullRun;
         double sTR = sp.sTR;
         double sVMM = sp.sVMM;
         double sVMP = sp.sVMP;
         int pkSlot0 = -1;
         double pkVal0 = 0.0;
         int pkSlot1 = -1;
         double pkVal1 = 0.0;
         int pkSlot2 = -1;
         double pkVal2 = 0.0;
         pkSlot0 = sp.ringPos_trailingIdx;
         pkVal0 = inHigh;
         pkSlot1 = sp.ringPos_trailingIdx;
         pkVal1 = inLow;
         pkSlot2 = sp.ringPos_trailingIdx;
         pkVal2 = inClose;
         /* Add on today's terms. */
         tempLT = inLow;
         tempHT = inHigh;
         tempCY = sp.lag1_inClose;
         trueRange = tempHT - tempLT;
         tempDouble = Math.Abs(tempCY - tempHT);
         if( tempDouble > trueRange ) {
            trueRange = tempDouble;
         }
         tempDouble = Math.Abs(tempCY - tempLT);
         if( tempDouble > trueRange ) {
            trueRange = tempDouble;
         }
         sTR += trueRange;
         sVMP += Math.Abs(inHigh - sp.lag1_inLow);
         sVMM += Math.Abs(inLow - sp.lag1_inHigh);
         if( trueRange == 0.0 ) {
            nullRun += 1;
         } else {
            nullRun = 0;
         }
         /* Once the whole window is flat, every TRUE-RANGE term in it is
          * provably zero (nullRun counts exactly that), so sTR's only content
          * is the running add/subtract's rounding residue -- purge it, and the
          * exact division gate below recognizes the case with no absolute
          * band. ONLY sTR: a zero true range (H == L == prevClose) does NOT
          * zero that bar's vortex terms, which read the PREVIOUS bar's
          * extremes -- a spread bar followed by a halt leaves |H - prevL| and
          * |L - prevH| alive inside the window, and zeroing the numerator sums
          * would poison both lines permanently (an unreachable negative -VI).
          * ULTOSC can reseed all its totals because its predicate covers both
          * of its per-bar terms; VORTEX's covers only the denominator's.
          */
         if( nullRun >= sp.optInTimePeriod ) {
            nullRun = sp.optInTimePeriod;
            sTR = 0.0;
         }
         /* Record the current window sums, then retire the trailing bar's
          * terms so the sums are ready for the next iteration.
          */
         curTR = sTR;
         curVMP = sVMP;
         curVMM = sVMM;
         tempLT = ((sp.ringPos_trailingIdx + sp.ringCap_trailingIdx - sp.ringLag_trailingIdx) % sp.ringCap_trailingIdx != pkSlot1) ? sp.ring_trailingIdx_inLow[(sp.ringPos_trailingIdx + sp.ringCap_trailingIdx - sp.ringLag_trailingIdx) % sp.ringCap_trailingIdx] : pkVal1;
         tempHT = ((sp.ringPos_trailingIdx + sp.ringCap_trailingIdx - sp.ringLag_trailingIdx) % sp.ringCap_trailingIdx != pkSlot0) ? sp.ring_trailingIdx_inHigh[(sp.ringPos_trailingIdx + sp.ringCap_trailingIdx - sp.ringLag_trailingIdx) % sp.ringCap_trailingIdx] : pkVal0;
         tempCY = ((sp.ringPos_trailingIdx + sp.ringCap_trailingIdx - sp.ringLag_trailingIdx - 1) % sp.ringCap_trailingIdx != pkSlot2) ? sp.ring_trailingIdx_inClose[(sp.ringPos_trailingIdx + sp.ringCap_trailingIdx - sp.ringLag_trailingIdx - 1) % sp.ringCap_trailingIdx] : pkVal2;
         trueRange = tempHT - tempLT;
         tempDouble = Math.Abs(tempCY - tempHT);
         if( tempDouble > trueRange ) {
            trueRange = tempDouble;
         }
         tempDouble = Math.Abs(tempCY - tempLT);
         if( tempDouble > trueRange ) {
            trueRange = tempDouble;
         }
         sTR -= trueRange;
         sVMP -= Math.Abs((((sp.ringPos_trailingIdx + sp.ringCap_trailingIdx - sp.ringLag_trailingIdx) % sp.ringCap_trailingIdx != pkSlot0) ? sp.ring_trailingIdx_inHigh[(sp.ringPos_trailingIdx + sp.ringCap_trailingIdx - sp.ringLag_trailingIdx) % sp.ringCap_trailingIdx] : pkVal0) - (((sp.ringPos_trailingIdx + sp.ringCap_trailingIdx - sp.ringLag_trailingIdx - 1) % sp.ringCap_trailingIdx != pkSlot1) ? sp.ring_trailingIdx_inLow[(sp.ringPos_trailingIdx + sp.ringCap_trailingIdx - sp.ringLag_trailingIdx - 1) % sp.ringCap_trailingIdx] : pkVal1));
         sVMM -= Math.Abs((((sp.ringPos_trailingIdx + sp.ringCap_trailingIdx - sp.ringLag_trailingIdx) % sp.ringCap_trailingIdx != pkSlot1) ? sp.ring_trailingIdx_inLow[(sp.ringPos_trailingIdx + sp.ringCap_trailingIdx - sp.ringLag_trailingIdx) % sp.ringCap_trailingIdx] : pkVal1) - (((sp.ringPos_trailingIdx + sp.ringCap_trailingIdx - sp.ringLag_trailingIdx - 1) % sp.ringCap_trailingIdx != pkSlot0) ? sp.ring_trailingIdx_inHigh[(sp.ringPos_trailingIdx + sp.ringCap_trailingIdx - sp.ringLag_trailingIdx - 1) % sp.ringCap_trailingIdx] : pkVal0));
         /* Last operation is to write the outputs. Must be done after the
          * trailing bar has been fully consumed: the caller is allowed to pass
          * an output buffer aliasing any input, and the trailing reads above
          * touch bars trailingIdx-1 == outIdx and trailingIdx == outIdx+1 --
          * an emit-first order would have clobbered them (ULTOSC's own rule;
          * ACCBANDS' multi-output form).
          *
          * Zero-denominator gate, on the DENOMINATOR itself and exact: the
          * flat-run reseed above removes the running sums' residue, so
          * `curTR > 0.0` is a precise test -- ULTOSC gates its divisions the
          * same way after the same reseed. The flat-bar count alone is only a
          * proxy for sTR == 0 in exact arithmetic: floating-point absorption
          * can zero the running sum while the window still holds a live term
          * (a large spread swallows a 1-ULP one; the later subtract leaves
          * exactly 0.0 with nullRun far below n), and an ungated division
          * then emits NaN/Inf, which VORTEX does not declare. An absolute
          * TA_IS_ZERO band is no better: it zeroes legitimate ratios on any
          * instrument quoted below 1e-14, and the QUOTE-UNIT/SCALE gate
          * rejects it (VORTEX is homogeneous of degree 0).
          */
         if( curTR > 0.0 ) {
            cur_outPlusVI = curVMP / curTR;
            cur_outMinusVI = curVMM / curTR;
         } else {
            cur_outPlusVI = 0.0;
            cur_outMinusVI = 0.0;
         }
         return new VortexValue(cur_outPlusVI, cur_outMinusVI);
      }

      /// <summary>Commit <c>n</c> closed bars and write their <c>n</c> values, in one call.</summary>
      /// <remarks>
      /// <para>Exactly <c>n</c> back-to-back <see cref="Update"/> calls, with one set of
      /// argument checks instead of <c>n</c>. The outputs must hold at least
      /// <c>n</c> values and must not overlap an input or each other.</para>
      /// <para><see cref="OutRange"/> counts what this call took in, which is what makes
      /// a rejection readable: a non-finite bar <c>k</c> throws
      /// <see cref="System.ArgumentException"/> exactly as <see cref="Update"/>
      /// would, with the bars before <c>k</c> committed and written, bar <c>k</c>
      /// and everything after it not written, and the count advanced by <c>k +
      /// 1</c> — the committed bars plus the rejected one, so the last bar counted
      /// is the one that failed.</para>
      /// </remarks>
      /// <param name="inHigh">Closed bars for <c>inHigh</c>, oldest first.</param>
      /// <param name="inLow">Closed bars for <c>inLow</c>, oldest first.</param>
      /// <param name="inClose">Closed bars for <c>inClose</c>, oldest first.</param>
      /// <param name="outPlusVI">Receives one <c>outPlusVI</c> value per bar committed.</param>
      /// <param name="outMinusVI">Receives one <c>outMinusVI</c> value per bar committed.</param>
      public void UpdateAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, Span<double> outPlusVI, Span<double> outMinusVI )
      {
         int barCount = inHigh.Length;
         if( inLow.Length != barCount || inClose.Length != barCount || outPlusVI.Length < barCount || outMinusVI.Length < barCount || outPlusVI.Overlaps(inHigh) || outPlusVI.Overlaps(inLow) || outPlusVI.Overlaps(inClose) || outMinusVI.Overlaps(inHigh) || outMinusVI.Overlaps(inLow) || outMinusVI.Overlaps(inClose) || outPlusVI.Overlaps(outMinusVI) ) throw Core.StreamFailure("VORTEX", "updateAndFill", RetCode.BadParam);
         for( int i = 0; i < barCount; i++ )
         {
            if( !double.IsFinite(inHigh[i]) || !double.IsFinite(inLow[i]) || !double.IsFinite(inClose[i]) )
            {
               if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
               throw Core.StreamFailure("VORTEX", "updateAndFill", RetCode.BadParam);
            }
            core.VortexStepImpl(this, inHigh[i], inLow[i], inClose[i]);
            outPlusVI[i] = cur_outPlusVI;
            outMinusVI[i] = cur_outMinusVI;
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         }
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public VortexValue Value => new VortexValue(cur_outPlusVI, cur_outMinusVI);

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public VortexStream Clone()
      {
         return new VortexStream(this);
      }
   }

   internal void VortexStepImpl( VortexStream sp, double inHigh, double inLow, double inClose )
   {
      double curTR = 0.0;
      double curVMP = 0.0;
      double curVMM = 0.0;
      double trueRange = 0.0;
      double tempDouble = 0.0;
      double tempLT = 0.0;
      double tempHT = 0.0;
      double tempCY = 0.0;
      sp.ring_trailingIdx_inHigh[sp.ringPos_trailingIdx] = inHigh;
      sp.ring_trailingIdx_inLow[sp.ringPos_trailingIdx] = inLow;
      sp.ring_trailingIdx_inClose[sp.ringPos_trailingIdx] = inClose;
      /* Add on today's terms. */
      tempLT = inLow;
      tempHT = inHigh;
      tempCY = sp.lag1_inClose;
      trueRange = tempHT - tempLT;
      tempDouble = Math.Abs(tempCY - tempHT);
      if( tempDouble > trueRange ) {
         trueRange = tempDouble;
      }
      tempDouble = Math.Abs(tempCY - tempLT);
      if( tempDouble > trueRange ) {
         trueRange = tempDouble;
      }
      sp.sTR += trueRange;
      sp.sVMP += Math.Abs(inHigh - sp.lag1_inLow);
      sp.sVMM += Math.Abs(inLow - sp.lag1_inHigh);
      if( trueRange == 0.0 ) {
         sp.nullRun += 1;
      } else {
         sp.nullRun = 0;
      }
      /* Once the whole window is flat, every TRUE-RANGE term in it is
       * provably zero (nullRun counts exactly that), so sTR's only content
       * is the running add/subtract's rounding residue -- purge it, and the
       * exact division gate below recognizes the case with no absolute
       * band. ONLY sTR: a zero true range (H == L == prevClose) does NOT
       * zero that bar's vortex terms, which read the PREVIOUS bar's
       * extremes -- a spread bar followed by a halt leaves |H - prevL| and
       * |L - prevH| alive inside the window, and zeroing the numerator sums
       * would poison both lines permanently (an unreachable negative -VI).
       * ULTOSC can reseed all its totals because its predicate covers both
       * of its per-bar terms; VORTEX's covers only the denominator's.
       */
      if( sp.nullRun >= sp.optInTimePeriod ) {
         sp.nullRun = sp.optInTimePeriod;
         sp.sTR = 0.0;
      }
      /* Record the current window sums, then retire the trailing bar's
       * terms so the sums are ready for the next iteration.
       */
      curTR = sp.sTR;
      curVMP = sp.sVMP;
      curVMM = sp.sVMM;
      tempLT = sp.ring_trailingIdx_inLow[(sp.ringPos_trailingIdx + sp.ringCap_trailingIdx - sp.ringLag_trailingIdx) % sp.ringCap_trailingIdx];
      tempHT = sp.ring_trailingIdx_inHigh[(sp.ringPos_trailingIdx + sp.ringCap_trailingIdx - sp.ringLag_trailingIdx) % sp.ringCap_trailingIdx];
      tempCY = sp.ring_trailingIdx_inClose[(sp.ringPos_trailingIdx + sp.ringCap_trailingIdx - sp.ringLag_trailingIdx - 1) % sp.ringCap_trailingIdx];
      trueRange = tempHT - tempLT;
      tempDouble = Math.Abs(tempCY - tempHT);
      if( tempDouble > trueRange ) {
         trueRange = tempDouble;
      }
      tempDouble = Math.Abs(tempCY - tempLT);
      if( tempDouble > trueRange ) {
         trueRange = tempDouble;
      }
      sp.sTR -= trueRange;
      sp.sVMP -= Math.Abs(sp.ring_trailingIdx_inHigh[(sp.ringPos_trailingIdx + sp.ringCap_trailingIdx - sp.ringLag_trailingIdx) % sp.ringCap_trailingIdx] - sp.ring_trailingIdx_inLow[(sp.ringPos_trailingIdx + sp.ringCap_trailingIdx - sp.ringLag_trailingIdx - 1) % sp.ringCap_trailingIdx]);
      sp.sVMM -= Math.Abs(sp.ring_trailingIdx_inLow[(sp.ringPos_trailingIdx + sp.ringCap_trailingIdx - sp.ringLag_trailingIdx) % sp.ringCap_trailingIdx] - sp.ring_trailingIdx_inHigh[(sp.ringPos_trailingIdx + sp.ringCap_trailingIdx - sp.ringLag_trailingIdx - 1) % sp.ringCap_trailingIdx]);
      /* Last operation is to write the outputs. Must be done after the
       * trailing bar has been fully consumed: the caller is allowed to pass
       * an output buffer aliasing any input, and the trailing reads above
       * touch bars trailingIdx-1 == outIdx and trailingIdx == outIdx+1 --
       * an emit-first order would have clobbered them (ULTOSC's own rule;
       * ACCBANDS' multi-output form).
       *
       * Zero-denominator gate, on the DENOMINATOR itself and exact: the
       * flat-run reseed above removes the running sums' residue, so
       * `curTR > 0.0` is a precise test -- ULTOSC gates its divisions the
       * same way after the same reseed. The flat-bar count alone is only a
       * proxy for sTR == 0 in exact arithmetic: floating-point absorption
       * can zero the running sum while the window still holds a live term
       * (a large spread swallows a 1-ULP one; the later subtract leaves
       * exactly 0.0 with nullRun far below n), and an ungated division
       * then emits NaN/Inf, which VORTEX does not declare. An absolute
       * TA_IS_ZERO band is no better: it zeroes legitimate ratios on any
       * instrument quoted below 1e-14, and the QUOTE-UNIT/SCALE gate
       * rejects it (VORTEX is homogeneous of degree 0).
       */
      if( curTR > 0.0 ) {
         sp.cur_outPlusVI = curVMP / curTR;
         sp.cur_outMinusVI = curVMM / curTR;
      } else {
         sp.cur_outPlusVI = 0.0;
         sp.cur_outMinusVI = 0.0;
      }
      sp.lag1_inHigh = inHigh;
      sp.lag1_inLow = inLow;
      sp.lag1_inClose = inClose;
      sp.ringPos_trailingIdx = sp.ringPos_trailingIdx + 1;
      if( sp.ringPos_trailingIdx >= sp.ringCap_trailingIdx ) {
         sp.ringPos_trailingIdx = 0;
      }
   }

   private RetCode VortexOpenImpl( VortexStream sp, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outPlusVI, Span<double> outMinusVI, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      int outIdx = 0;
      int today = 0;
      int trailingIdx = 0;
      int lookbackTotal = 0;
      int i = 0;
      int nullRun = 0;
      double sTR = 0;
      double sVMP = 0;
      double sVMM = 0;
      double curTR = 0;
      double curVMP = 0;
      double curVMM = 0;
      double trueRange = 0;
      double tempDouble = 0;
      double tempLT = 0;
      double tempHT = 0;
      double tempCY = 0;
      int historyLen = inHigh.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inLow.Length != inHigh.Length || inClose.Length != inHigh.Length ) {
         return RetCode.BadParam;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 14;
      } else if( optInTimePeriod < 1 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      /* Vortex Indicator (Botes & Siepman, TASC 28:1, Jan 2010): two lines,
       * each a rolling sum of "vortex movement" normalized by the rolling sum
       * of true range over the same optInTimePeriod bars.
       *
       *   TR[i]  = max( H[i]-L[i], |C[i-1]-H[i]|, |C[i-1]-L[i]| )   == TA_TRANGE
       *   VMP[i] = |H[i] - L[i-1]|
       *   VMM[i] = |L[i] - H[i-1]|
       *   +VI = SUM(VMP, n) / SUM(TR, n),  -VI = SUM(VMM, n) / SUM(TR, n)
       *
       * No smoothing, no recursion, nothing to seed. The TR expansion below is
       * TA_TRANGE's own operation order, bit for bit -- the differential test
       * composes TA_TRANGE + TA_SUM and asserts equality with memcmp.
       *
       * The trailing terms are recomputed from the inputs rather than carried
       * in a ring; the subtraction re-reads bars trailingIdx and trailingIdx-1,
       * both of which sit at or ahead of the output slot, which is why the
       * outputs are written LAST (see the loop comment).
       */
      lookbackTotal = VORTEX_Lookback(optInTimePeriod);
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      /* Prime the three window sums over the optInTimePeriod-1 terms before the
       * first output bar: [startIdx-optInTimePeriod+1, startIdx). Each term at
       * bar i reads bar i-1, so the earliest read is bar startIdx-optInTimePeriod
       * >= 0.
       */
      sTR = 0.0;
      sVMP = 0.0;
      sVMM = 0.0;
      nullRun = 0;
      for( i = startIdx - optInTimePeriod + 1; i < startIdx; i += 1 ) {
         tempLT = inLow[i];
         tempHT = inHigh[i];
         tempCY = inClose[i - 1];
         trueRange = tempHT - tempLT;
         tempDouble = Math.Abs(tempCY - tempHT);
         if( tempDouble > trueRange ) {
            trueRange = tempDouble;
         }
         tempDouble = Math.Abs(tempCY - tempLT);
         if( tempDouble > trueRange ) {
            trueRange = tempDouble;
         }
         sTR += trueRange;
         sVMP += Math.Abs(inHigh[i] - inLow[i - 1]);
         sVMM += Math.Abs(inLow[i] - inHigh[i - 1]);
         if( trueRange == 0.0 ) {
            nullRun += 1;
         } else {
            nullRun = 0;
         }
      }
      outIdx = 0;
      today = startIdx;
      trailingIdx = startIdx - optInTimePeriod + 1;
      while( today <= endIdx ) {
         /* Add on today's terms. */
         tempLT = inLow[today];
         tempHT = inHigh[today];
         tempCY = inClose[today - 1];
         trueRange = tempHT - tempLT;
         tempDouble = Math.Abs(tempCY - tempHT);
         if( tempDouble > trueRange ) {
            trueRange = tempDouble;
         }
         tempDouble = Math.Abs(tempCY - tempLT);
         if( tempDouble > trueRange ) {
            trueRange = tempDouble;
         }
         sTR += trueRange;
         sVMP += Math.Abs(inHigh[today] - inLow[today - 1]);
         sVMM += Math.Abs(inLow[today] - inHigh[today - 1]);
         if( trueRange == 0.0 ) {
            nullRun += 1;
         } else {
            nullRun = 0;
         }
         /* Once the whole window is flat, every TRUE-RANGE term in it is
          * provably zero (nullRun counts exactly that), so sTR's only content
          * is the running add/subtract's rounding residue -- purge it, and the
          * exact division gate below recognizes the case with no absolute
          * band. ONLY sTR: a zero true range (H == L == prevClose) does NOT
          * zero that bar's vortex terms, which read the PREVIOUS bar's
          * extremes -- a spread bar followed by a halt leaves |H - prevL| and
          * |L - prevH| alive inside the window, and zeroing the numerator sums
          * would poison both lines permanently (an unreachable negative -VI).
          * ULTOSC can reseed all its totals because its predicate covers both
          * of its per-bar terms; VORTEX's covers only the denominator's.
          */
         if( nullRun >= optInTimePeriod ) {
            nullRun = optInTimePeriod;
            sTR = 0.0;
         }
         /* Record the current window sums, then retire the trailing bar's
          * terms so the sums are ready for the next iteration.
          */
         curTR = sTR;
         curVMP = sVMP;
         curVMM = sVMM;
         tempLT = inLow[trailingIdx];
         tempHT = inHigh[trailingIdx];
         tempCY = inClose[trailingIdx - 1];
         trueRange = tempHT - tempLT;
         tempDouble = Math.Abs(tempCY - tempHT);
         if( tempDouble > trueRange ) {
            trueRange = tempDouble;
         }
         tempDouble = Math.Abs(tempCY - tempLT);
         if( tempDouble > trueRange ) {
            trueRange = tempDouble;
         }
         sTR -= trueRange;
         sVMP -= Math.Abs(inHigh[trailingIdx] - inLow[trailingIdx - 1]);
         sVMM -= Math.Abs(inLow[trailingIdx] - inHigh[trailingIdx - 1]);
         trailingIdx += 1;
         /* Last operation is to write the outputs. Must be done after the
          * trailing bar has been fully consumed: the caller is allowed to pass
          * an output buffer aliasing any input, and the trailing reads above
          * touch bars trailingIdx-1 == outIdx and trailingIdx == outIdx+1 --
          * an emit-first order would have clobbered them (ULTOSC's own rule;
          * ACCBANDS' multi-output form).
          *
          * Zero-denominator gate, on the DENOMINATOR itself and exact: the
          * flat-run reseed above removes the running sums' residue, so
          * `curTR > 0.0` is a precise test -- ULTOSC gates its divisions the
          * same way after the same reseed. The flat-bar count alone is only a
          * proxy for sTR == 0 in exact arithmetic: floating-point absorption
          * can zero the running sum while the window still holds a live term
          * (a large spread swallows a 1-ULP one; the later subtract leaves
          * exactly 0.0 with nullRun far below n), and an ungated division
          * then emits NaN/Inf, which VORTEX does not declare. An absolute
          * TA_IS_ZERO band is no better: it zeroes legitimate ratios on any
          * instrument quoted below 1e-14, and the QUOTE-UNIT/SCALE gate
          * rejects it (VORTEX is homogeneous of degree 0).
          */
         if( curTR > 0.0 ) {
            outPlusVI[outIdx * outStride] = curVMP / curTR;
            outMinusVI[outIdx * outStride] = curVMM / curTR;
         } else {
            outPlusVI[outIdx * outStride] = 0.0;
            outMinusVI[outIdx * outStride] = 0.0;
         }
         outIdx += 1;
         today += 1;
      }
      outBegIdx = startIdx;
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      int capLag_trailingIdx = today - trailingIdx;
      int cap_trailingIdx = capLag_trailingIdx + 2;
      if( capLag_trailingIdx < 0 || cap_trailingIdx > historyLen ) {
         return RetCode.InternalError;
      }
      int allocN_trailingIdx = (cap_trailingIdx > 0)? cap_trailingIdx : 1;
      double[] capRing_trailingIdx_inHigh = new double[allocN_trailingIdx];
      for( int fillJ = historyLen - cap_trailingIdx; fillJ < historyLen; fillJ++ ) {
         capRing_trailingIdx_inHigh[fillJ % cap_trailingIdx] = inHigh[fillJ];
      }
      double[] capRing_trailingIdx_inLow = new double[allocN_trailingIdx];
      for( int fillJ = historyLen - cap_trailingIdx; fillJ < historyLen; fillJ++ ) {
         capRing_trailingIdx_inLow[fillJ % cap_trailingIdx] = inLow[fillJ];
      }
      double[] capRing_trailingIdx_inClose = new double[allocN_trailingIdx];
      for( int fillJ = historyLen - cap_trailingIdx; fillJ < historyLen; fillJ++ ) {
         capRing_trailingIdx_inClose[fillJ % cap_trailingIdx] = inClose[fillJ];
      }
      sp.optInTimePeriod = optInTimePeriod;
      sp.nullRun = nullRun;
      sp.sTR = sTR;
      sp.sVMP = sVMP;
      sp.sVMM = sVMM;
      sp.lag1_inHigh = inHigh[historyLen - 1];
      sp.lag1_inLow = inLow[historyLen - 1];
      sp.lag1_inClose = inClose[historyLen - 1];
      sp.ringPos_trailingIdx = historyLen % cap_trailingIdx;
      sp.ringCap_trailingIdx = cap_trailingIdx;
      sp.ringLag_trailingIdx = capLag_trailingIdx;
      sp.ring_trailingIdx_inHigh = capRing_trailingIdx_inHigh;
      sp.ring_trailingIdx_inLow = capRing_trailingIdx_inLow;
      sp.ring_trailingIdx_inClose = capRing_trailingIdx_inClose;
      sp.cur_outPlusVI = outPlusVI[(outNBElement - 1) * outStride];
      sp.cur_outMinusVI = outMinusVI[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* VortexOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal VortexStream VortexOpenAndFillInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outPlusVI, Span<double> outMinusVI )
   {
      VortexStream sp = new VortexStream(this);
      RetCode retCode = VortexOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInTimePeriod, out outBegIdx, out outNBElement, outPlusVI, outMinusVI, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("VORTEX", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind VortexOpen (composition seam). */
   internal VortexStream VortexOpenInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod )
   {
      VortexStream sp = new VortexStream(this);
      double[] sink_outPlusVI = new double[1];
      double[] sink_outMinusVI = new double[1];
      RetCode retCode = VortexOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInTimePeriod, out int outBegIdx, out int outNBElement, sink_outPlusVI, sink_outMinusVI, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("VORTEX", "open", retCode);
   }

   /// <summary>Open a live <c>VORTEX</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="VortexStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>VORTEX</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>VORTEX_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>VortexOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inHigh">High price series. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price series. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price series. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="VORTEX_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>VORTEX_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public VortexStream VortexOpen( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInTimePeriod )
   {
      if( inHigh.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "VORTEX open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "VORTEX open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("VORTEX open: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TaLibArgumentException("VORTEX open: inClose is empty", nameof(inClose), RetCode.BadParam);
      RequireHistoryLength("VORTEX", "open", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("VORTEX", "open", "inClose", inClose.Length, inHigh.Length);
      return VortexOpenInternal(inHigh, inLow, inClose, 0, optInTimePeriod);
   }

   /// <summary><c>VortexOpen</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>VORTEX</c> produces over
   /// the same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - VORTEX_Lookback(...)</c> values
   /// and must not alias the inputs or each other — this path writes the outputs
   /// and then reads the input tail to seed its rings, so the batch tier's
   /// in-place allowance does not carry over here. Both are checked before
   /// anything is written, so an undersized span is an <c>ArgumentException</c>
   /// naming it rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="VortexStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inHigh">High price series. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price series. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price series. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="VORTEX_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outPlusVI">Positive vortex line (+VI) Must hold at least <c>historyLen -
   /// VORTEX_Lookback(...)</c> values.</param>
   /// <param name="outMinusVI">Negative vortex line (−VI) Must hold at least <c>historyLen -
   /// VORTEX_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>VORTEX_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public VortexStream VortexOpenAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInTimePeriod, Span<double> outPlusVI, Span<double> outMinusVI )
   {
      if( inHigh.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "VORTEX openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "VORTEX openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("VORTEX openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TaLibArgumentException("VORTEX openAndFill: inClose is empty", nameof(inClose), RetCode.BadParam);
      int guardOutLen = OpenFillCount("VORTEX", "openAndFill", inHigh.Length, VORTEX_Lookback(optInTimePeriod));
      RequireHistoryLength("VORTEX", "openAndFill", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("VORTEX", "openAndFill", "inClose", inClose.Length, inHigh.Length);
      RequireFillLength("VORTEX", "openAndFill", "outPlusVI", outPlusVI.Length, guardOutLen);
      RequireFillLength("VORTEX", "openAndFill", "outMinusVI", outMinusVI.Length, guardOutLen);
      if( outPlusVI.Overlaps(inHigh) || outPlusVI.Overlaps(inLow) || outPlusVI.Overlaps(inClose) || outMinusVI.Overlaps(inHigh) || outMinusVI.Overlaps(inLow) || outMinusVI.Overlaps(inClose) || outPlusVI.Overlaps(outMinusVI) ) {
         throw StreamFailure("VORTEX", "openAndFill", RetCode.BadParam);
      }
      return VortexOpenAndFillInternal(inHigh, inLow, inClose, 0, optInTimePeriod, out _, out _, outPlusVI, outMinusVI);
   }
