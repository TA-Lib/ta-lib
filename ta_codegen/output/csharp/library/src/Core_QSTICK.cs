      public QstickStream Clone()
      {
         return new QstickStream(this);
      }
   }

   internal void QstickStepImpl( QstickStream sp, double inOpen, double inClose )
   {
      double tempReal = 0.0;
      if( sp.ringCap_trailingIdx == 0 ) {
         sp.ring_trailingIdx_derived[0] = (double)(inClose - inOpen);
      }
      sp.periodTotal += (double)(inClose - inOpen);
      tempReal = sp.periodTotal;
      sp.periodTotal -= sp.ring_trailingIdx_derived[sp.ringPos_trailingIdx];
      sp.cur_outReal = tempReal / (double)sp.optInTimePeriod;
      sp.ring_trailingIdx_derived[sp.ringPos_trailingIdx] = (double)(inClose - inOpen);
      sp.ringPos_trailingIdx = sp.ringPos_trailingIdx + 1;
      if( sp.ringPos_trailingIdx >= sp.ringCap_trailingIdx ) {
         sp.ringPos_trailingIdx = 0;
      }
   }

   private RetCode QstickOpenImpl( QstickStream sp, ReadOnlySpan<double> inOpen, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double periodTotal = 0;
      double tempReal = 0;
      int i = 0;
      int outIdx = 0;
      int trailingIdx = 0;
      int lookbackTotal = 0;
      int historyLen = inOpen.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inClose.Length != inOpen.Length ) {
         return RetCode.BadParam;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 10;
      } else if( optInTimePeriod < 1 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      /* Qstick (Chande & Kroll, The New Technical Trader, 1994): a simple moving
       * average of the candle body, close minus open. Above zero means bodies
       * were predominantly bullish over the window; the zero crossings are the
       * signal.
       *
       * This is ta_codegen/input/sma/sma.c with inReal[x] replaced by
       * (inClose[x] - inOpen[x]), and deliberately nothing else: the same
       * running-sum order, the same read-before-write of the trailing term, and
       * the same divide by the period. Keeping the arithmetic identical is what
       * makes the composed reference in test_composite.c -- TA_SUB followed by
       * TA_SMA -- bit-exact rather than merely close, so any future drift in
       * either path is a hard failure instead of a tolerance argument.
       *
       * In particular the last statement divides; it does NOT multiply by a
       * precomputed 1/period. Tulip's qstick.c multiplies, which costs it up to
       * one ULP against TA_SMA. Dividing buys the memcmp differential, which is
       * the stronger of the two gates.
       */
      /* Identify the minimum number of price bar needed
       * to calculate at least one output.
       */
      lookbackTotal = (int)(optInTimePeriod - 1);
      /* Move up the start index if there is not
       * enough initial data.
       */
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      /* Do the MA calculation using tight loops. */
      /* Add-up the initial period, except for the last value. */
      periodTotal = 0.0;
      trailingIdx = startIdx - lookbackTotal;
      i = trailingIdx;
      if( optInTimePeriod > 1 ) {
         while( i < startIdx ) {
            periodTotal += (double)(inClose[i] - inOpen[i]);
            i = i + 1;
         }
      }
      /* Proceed with the calculation for the requested range.
       * Note that this algorithm allows outReal to be the same
       * buffer as either input.
       */
      outIdx = 0;
      while( i <= endIdx ) {
         periodTotal += (double)(inClose[i] - inOpen[i]);
         i = i + 1;
         tempReal = periodTotal;
         periodTotal -= (double)(inClose[trailingIdx] - inOpen[trailingIdx]);
         trailingIdx = trailingIdx + 1;
         outReal[outIdx * outStride] = tempReal / (double)optInTimePeriod;
         outIdx = outIdx + 1;
      }
      /* All done. Indicate the output limits and return. */
      outNBElement = outIdx;
      outBegIdx = startIdx;
      /* Capture the live batch state into the handle. */
      int cap_trailingIdx = i - trailingIdx;
      if( cap_trailingIdx < 0 || cap_trailingIdx > historyLen ) {
         return RetCode.InternalError;
      }
      int allocN_trailingIdx = (cap_trailingIdx > 0)? cap_trailingIdx : 1;
      double[] capRing_trailingIdx_derived = new double[allocN_trailingIdx];
      for( int fillJ = historyLen - cap_trailingIdx; fillJ < historyLen; fillJ++ ) {
         capRing_trailingIdx_derived[fillJ - (historyLen - cap_trailingIdx)] = (double)(inClose[fillJ] - inOpen[fillJ]);
      }
      sp.optInTimePeriod = optInTimePeriod;
      sp.periodTotal = periodTotal;
      sp.ringPos_trailingIdx = 0;
      sp.ringCap_trailingIdx = cap_trailingIdx;
      sp.ring_trailingIdx_derived = capRing_trailingIdx_derived;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* QstickOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal QstickStream QstickOpenAndFillInternal( ReadOnlySpan<double> inOpen, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      QstickStream sp = new QstickStream(this);
      RetCode retCode = QstickOpenImpl(sp, inOpen, inClose, startIdx, optInTimePeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("QSTICK", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind QstickOpen (composition seam). */
   internal QstickStream QstickOpenInternal( ReadOnlySpan<double> inOpen, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod )
   {
      QstickStream sp = new QstickStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = QstickOpenImpl(sp, inOpen, inClose, startIdx, optInTimePeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("QSTICK", "open", retCode);
   }

   /// <summary>Open a live <c>QSTICK</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="QstickStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>QSTICK</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>QSTICK_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>QstickOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inOpen">Open price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="QSTICK_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>QSTICK_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public QstickStream QstickOpen( ReadOnlySpan<double> inOpen, ReadOnlySpan<double> inClose, int optInTimePeriod )
   {
      if( inOpen.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inOpen), "QSTICK open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inOpen.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inOpen), "QSTICK open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inClose.IsEmpty ) throw new TaLibArgumentException("QSTICK open: inClose is empty", nameof(inClose), RetCode.BadParam);
      RequireHistoryLength("QSTICK", "open", "inClose", inClose.Length, inOpen.Length);
      return QstickOpenInternal(inOpen, inClose, 0, optInTimePeriod);
   }

   /// <summary><c>QstickOpen</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>QSTICK</c> produces over
   /// the same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - QSTICK_Lookback(...)</c> values
   /// and must not alias the inputs or each other — this path writes the outputs
   /// and then reads the input tail to seed its rings, so the batch tier's
   /// in-place allowance does not carry over here. Both are checked before
   /// anything is written, so an undersized span is an <c>ArgumentException</c>
   /// naming it rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="QstickStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inOpen">Open price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="QSTICK_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Average candle body over the window. Must hold at least <c>historyLen -
   /// QSTICK_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>QSTICK_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public QstickStream QstickOpenAndFill( ReadOnlySpan<double> inOpen, ReadOnlySpan<double> inClose, int optInTimePeriod, Span<double> outReal )
   {
      if( inOpen.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inOpen), "QSTICK openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inOpen.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inOpen), "QSTICK openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inClose.IsEmpty ) throw new TaLibArgumentException("QSTICK openAndFill: inClose is empty", nameof(inClose), RetCode.BadParam);
      int guardOutLen = OpenFillCount("QSTICK", "openAndFill", inOpen.Length, QSTICK_Lookback(optInTimePeriod));
      RequireHistoryLength("QSTICK", "openAndFill", "inClose", inClose.Length, inOpen.Length);
      RequireFillLength("QSTICK", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( outReal.Overlaps(inOpen) || outReal.Overlaps(inClose) ) {
         throw StreamFailure("QSTICK", "openAndFill", RetCode.BadParam);
      }
      return QstickOpenAndFillInternal(inOpen, inClose, 0, optInTimePeriod, out _, out _, outReal);
   }
