   /// <summary><c>CDLGRAVESTONEDOJI_Open</c> that also fills the output array(s) over the
   /// whole history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>CDLGRAVESTONEDOJI</c>
   /// produces over the same series, so no separate batch call is needed for the
   /// warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen -
   /// CDLGRAVESTONEDOJI_Lookback(...)</c> values and must not alias the inputs
   /// or each other — this path writes the outputs and then reads the input tail
   /// to seed its rings, so the batch tier's in-place allowance does not carry
   /// over here.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="CDLGRAVESTONEDOJI_Stream.FillRange"/>.</para>
   /// </remarks>
   /// <param name="inOpen">Open price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="outInteger">+100 on a detected gravestone doji, 0 otherwise. Never negative; the
   /// positive sign is not a directional signal (evaluate relative to the trend)
   /// Must hold at least <c>historyLen - CDLGRAVESTONEDOJI_Lookback(...)</c>
   /// values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>CDLGRAVESTONEDOJI_Lookback(...) + 1</c>
   /// bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, or an output array aliases an input or another
   /// output.</exception>
   /// <exception cref="System.ArgumentException">An input series is empty, or an output overlaps an input or another
   /// output.</exception>
   public CDLGRAVESTONEDOJI_Stream CDLGRAVESTONEDOJI_OpenAndFill( ReadOnlySpan<double> inOpen, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, Span<int> outInteger )
