   /// reversal meaning must be read against the prevailing trend, which this
   /// function does not check.
   /// </summary>
   /// <remarks>
   /// <b>Formula</b>
   /// <code>
   /// One candle. Detected when all hold: (1) doji body: realbody |close-open| &lt;= BodyDoji average; (2) very short/absent lower shadow: lowerShadow &lt; ShadowVeryShort average; (3) non-short upper shadow: upperShadow &gt; ShadowVeryShort average (open/close at the low with an upper shadow).
   /// </code>
   /// <list type="bullet">
   /// <item><description>Does not verify the prior trend that determines the pattern's bullish/bearish meaning.</description></item>
   /// <item><description>Bulkowski's testing found the bearish reversal traders expect actually shows up only 51% of the time — essentially random — and it ranks 77th of 103 patterns for post-breakout performance. ([thepatternsite.com](https://thepatternsite.com/Gravestone.html))</description></item>
   /// </list>
   /// <para>
   /// This is the <c>float[]</c> overload: input elements are widened to
   /// <c>double</c> as they are read and all arithmetic is performed in
   /// <c>double</c>, so a result beyond <c>float</c> range is still
   /// representable.
   /// </para>
   /// <para>
   /// Values are written only where the indicator is defined. The returned
   /// <see cref="OutRange"/> says where they start and how many there are;
   /// nothing outside that range is touched, and the library never pads with
   /// NaN. A valid range shorter than <c>CDLGRAVESTONEDOJI_Lookback</c> is a
   /// <b>success with no values</b> (<c>Count == 0</c>), not an error.
   /// </para>
   /// </remarks>
   /// <param name="startIdx">First bar of the requested range (inclusive).</param>
   /// <param name="endIdx">Last bar of the requested range (inclusive).</param>
   /// <param name="inOpen">Open price of each bar.</param>
   /// <param name="inHigh">High price of each bar.</param>
   /// <param name="inLow">Low price of each bar.</param>
   /// <param name="inClose">Close price of each bar.</param>
   /// <param name="outInteger">+100 on a detected gravestone doji, 0 otherwise. Never negative; the
   /// positive sign is not a directional signal (evaluate relative to the trend)
   /// Must hold at least <c>endIdx - startIdx + 1</c> values.</param>
   /// <returns>The range written: <c>BegIdx</c> is the first bar with a value,
   /// <c>Count</c> how many were written.</returns>
   /// <exception cref="System.ArgumentOutOfRangeException"><c>startIdx</c> or <c>endIdx</c> is negative or above
   /// <see cref="Core.MAX_INDEX"/>, or <c>endIdx &lt; startIdx</c>.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or two outputs
   /// share one array.</exception>
   /// <exception cref="System.ArgumentException">A span is too short for the range requested: an input this function
   /// <i>reads</i> that does not reach <c>endIdx</c>, or an output that cannot
   /// hold the values produced. Checked before anything is written, so a
   /// rejected call leaves every buffer untouched. An empty span — which is what
   /// a null array becomes, since a span cannot be null — fails the same check,
   /// because any valid range needs at least one element. A few candlestick
   /// patterns declare an OHLC series they never index; those are not checked at
   /// all, because rejecting them would refuse a call the algorithm can answer.</exception>
   /// <exception cref="System.ArgumentException">Two output buffers overlap, or an output partially overlaps an input.
   /// Computing wholly in place (an output that IS an input) is allowed.</exception>
   public OutRange CDLGRAVESTONEDOJI( int startIdx,
                                      int endIdx,
                                      ReadOnlySpan<float> inOpen,
                                      ReadOnlySpan<float> inHigh,
                                      ReadOnlySpan<float> inLow,
                                      ReadOnlySpan<float> inClose,
                                      Span<int> outInteger )
   {
      int guardStart = ClampedStart(startIdx, endIdx, CDLGRAVESTONEDOJI_Lookback());
      int guardInLen = guardStart < 0 ? 0 : endIdx + 1;
      int guardOutLen = guardStart < 0 || guardStart > endIdx ? 0 : endIdx - guardStart + 1;
      RequireLength("CDLGRAVESTONEDOJI", "inOpen", inOpen.Length, guardInLen);
      RequireLength("CDLGRAVESTONEDOJI", "inHigh", inHigh.Length, guardInLen);
      RequireLength("CDLGRAVESTONEDOJI", "inLow", inLow.Length, guardInLen);
      RequireLength("CDLGRAVESTONEDOJI", "inClose", inClose.Length, guardInLen);
      RequireLength("CDLGRAVESTONEDOJI", "outInteger", outInteger.Length, guardOutLen);
      RetCode retCode = CDLGRAVESTONEDOJI_Impl(startIdx, endIdx, inOpen, inHigh, inLow, inClose, out int outBegIdx, out int outNBElement, outInteger);
      if( retCode != RetCode.Success ) {
         throw Failure("CDLGRAVESTONEDOJI", retCode);
      }
      return new OutRange(outBegIdx, outNBElement);
   }
