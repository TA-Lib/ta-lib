      /// hands back only the last value, a subset of this range, because the caller
      /// chose not to take the fill.</para>
      /// <para>The last bar it can reach is <see cref="Core.MaxIndex"/>; past that
      /// <c>Update</c> and <c>Advance</c> throw.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      /// <summary>Count one bar this stream was not fed: <see cref="OutRange"/> advances by
      /// one and nothing else moves.</summary>
      /// <remarks>
      /// <para><see cref="Value"/> keeps answering the previous output, which is this
      /// bar's output too. For a bar the caller leaves out: one an <c>Update</c>
      /// rejected and that will not be re-fed, or a session with no print. Without
      /// it two handles on one feed drift a bar apart when only one of them skips.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.MaxIndex"/>, the last one the batch tier
      /// can address and the last this handle will count. <c>Update</c> throws the
      /// same there.</para>
      /// </remarks>
      public void Advance()
      {
         if( outRangeBegIdx + outRangeCount > Core.MaxIndex )
            throw Core.StreamFailure("CRSI", "advance", RetCode.OutOfRangeEndIndex);
         outRangeCount++;
      }

      internal CrsiStream( CrsiStream other )
      {
         this.core = other.core;
         this.optInTimePeriod = other.optInTimePeriod;
         this.optInStreakPeriod = other.optInStreakPeriod;
         this.optInRankPeriod = other.optInRankPeriod;
         this.prevClose = other.prevClose;
         this.streak = other.streak;
         this.cur_outReal = other.cur_outReal;
         this.sub0 = new RsiStream(other.sub0);
         this.sub1 = new RsiStream(other.sub1);
         this.sub2 = new RocpStream(other.sub2);
         this.sub3 = new PercentrankStream(other.sub3);
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Allocates nothing — neither handle state nor a return value.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so nothing moves — <see cref="OutRange"/> included — and
      /// <see cref="Value"/> still answers the previous value. Re-feed the bar when
      /// a corrected value arrives, or call <see cref="Advance"/> to count it and
      /// carry on; two handles on one feed drift a bar apart if neither happens.
      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.MaxIndex"/>, which no re-feed clears: the
      /// handle has run out of index domain and only a shorter history can start a
      /// new one.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inReal )
      {
         if( outRangeBegIdx + outRangeCount > Core.MaxIndex )
            throw Core.StreamFailure("CRSI", "update", RetCode.OutOfRangeEndIndex);
         if( !double.IsFinite(inReal) ) throw Core.StreamFailure("CRSI", "update", RetCode.BadParam);
         core.CrsiStepImpl(this, inReal);
         outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>Its cost does not grow with the period.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.MaxIndex"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public double Peek( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.StreamFailure("CRSI", "peek", RetCode.BadParam);
         CrsiStream sp = this;
         double cur_tempStreak = 0.0;
         double cur_tempStreakRSI = 0.0;
         double cur_tempRSI = 0.0;
         double cur_outReal = 0.0;
         double close = 0.0;
         double streak = sp.streak;
         close = inReal;
         if( close > sp.prevClose ) {
            streak = (streak > 0.0) ? streak + 1.0 : 1.0;
         } else if( close < sp.prevClose ) {
            streak = (streak < 0.0) ? streak - 1.0 : 0 - 1.0;
         } else {
            streak = 0.0;
         }
         cur_tempStreak = streak;
         /* Pipeline the new bar through the sub-streams (batch tail order). */
         cur_tempStreakRSI = sp.sub0.Peek(cur_tempStreak);
         cur_tempRSI = sp.sub1.Peek(inReal);
         cur_tempStreak = sp.sub2.Peek(inReal);
         cur_outReal = sp.sub3.Peek(cur_tempStreak);
         /* Combine map (batch tail, per bar). */
         cur_outReal = (cur_tempRSI + cur_tempStreakRSI + cur_outReal) / 3.0;
         return cur_outReal;
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public CrsiStream Clone()
      {
         return new CrsiStream(this);
      }
   }

   internal void CrsiStepImpl( CrsiStream sp, double inReal )
   {
      double close = 0.0;
      double cur_tempStreak = 0.0;
      double cur_tempStreakRSI = 0.0;
      double cur_tempRSI = 0.0;
      double cur_outReal = 0.0;
      close = inReal;
      if( close > sp.prevClose ) {
         sp.streak = (sp.streak > 0.0) ? sp.streak + 1.0 : 1.0;
      } else if( close < sp.prevClose ) {
         sp.streak = (sp.streak < 0.0) ? sp.streak - 1.0 : 0 - 1.0;
      } else {
         sp.streak = 0.0;
      }
      cur_tempStreak = sp.streak;
      sp.prevClose = close;
      /* Pipeline the new bar through the sub-streams (batch tail order). */
      cur_tempStreakRSI = sp.sub0.Update(cur_tempStreak);
      cur_tempRSI = sp.sub1.Update(inReal);
      cur_tempStreak = sp.sub2.Update(inReal);
      cur_outReal = sp.sub3.Update(cur_tempStreak);
      /* Combine map (batch tail, per bar). */
      cur_outReal = (cur_tempRSI + cur_tempStreakRSI + cur_outReal) / 3.0;
      sp.cur_outReal = cur_outReal;
   }

   private RetCode CrsiOpenImpl( CrsiStream sp, ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, int optInStreakPeriod, int optInRankPeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      Span<double> tempRSI;
      Span<double> tempStreak;
      Span<double> tempStreakRSI;
      RetCode retCode;
      int lookbackTotal = 0;
      int anchorIdx = 0;
      int today = 0;
      int outIdx = 0;
      int i = 0;
      int offsetRSI = 0;
      int offsetStreak = 0;
      int tempBegIdx = 0;
      int rsiNb = 0;
      int streakNb = 0;
      int rocNb = 0;
      double prevClose = 0;
      double close = 0;
      double streak = 0;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MaxIndex + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 3;
      } else if( optInTimePeriod < 2 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInStreakPeriod == int.MinValue ) {
         optInStreakPeriod = 2;
      } else if( optInStreakPeriod < 2 || optInStreakPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInRankPeriod == int.MinValue ) {
         optInRankPeriod = 100;
      } else if( optInRankPeriod < 2 || optInRankPeriod > 10000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      if( historyLen < CrsiLookback(optInTimePeriod, optInStreakPeriod, optInRankPeriod) + 1 ) {
         return RetCode.InsufficientHistory;
      }
      Span<double> sc_outReal = outStride == 1 ? outReal : new double[historyLen];
      outBegIdx = 0;
      outNBElement = 0;
      lookbackTotal = CrsiLookback(optInTimePeriod, optInStreakPeriod, optInRankPeriod);
      if( lookbackTotal > endIdx ) {
         return RetCode.InsufficientHistory ;
      }
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Both RSI legs start on the bar lookbackTotal before startIdx (the streak,
       * a difference, one bar later), so the leg with the shorter lookback warms
       * up over the spare bars instead of starting cold at its own lookback.
       */
      anchorIdx = startIdx - lookbackTotal;
      tempStreak = new double[(int)((endIdx - anchorIdx) * 1)];
      tempRSI = new double[(int)((endIdx - anchorIdx - RsiLookback(optInTimePeriod) + 1) * 1)];
      tempStreakRSI = new double[(int)((endIdx - anchorIdx - RsiLookback(optInStreakPeriod)) * 1)];
      streak = 0.0;
      prevClose = inReal[anchorIdx];
      outIdx = 0;
      today = anchorIdx + 1;
      while( today <= endIdx ) {
         close = inReal[today];
         if( close > prevClose ) {
            streak = (streak > 0.0) ? streak + 1.0 : 1.0;
         } else if( close < prevClose ) {
            streak = (streak < 0.0) ? streak - 1.0 : 0 - 1.0;
         } else {
            streak = 0.0;
         }
         tempStreak[outIdx++] = streak;
         prevClose = close;
         today += 1;
      }
      /* Sub-stream 0: rsi over `tempStreak`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      int subLen0 = (outIdx - 1) + 1;
      double[] subSrc0_0 = new double[subLen0];
      tempStreak.Slice(0, subLen0).CopyTo(subSrc0_0);
      RsiStream sub0 = RsiOpenAndFillInternal(subSrc0_0, 0, optInStreakPeriod, out tempBegIdx, out streakNb, tempStreakRSI);
      retCode = RetCode.Success;
      /* Sub-stream 1: rsi over `inReal`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      RsiStream sub1 = RsiOpenAndFillInternal(inReal, anchorIdx + RsiLookback(optInTimePeriod), optInTimePeriod, out tempBegIdx, out rsiNb, tempRSI);
      retCode = RetCode.Success;
      /* The streak is consumed: its buffer holds the returns. */
      /* Sub-stream 2: rocp over `inReal`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      RocpStream sub2 = RocpOpenAndFillInternal(inReal, startIdx - optInRankPeriod, 1, out tempBegIdx, out rocNb, tempStreak);
      retCode = RetCode.Success;
      /* Sub-stream 3: percentrank over `tempStreak`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      int subLen3 = (rocNb - 1) + 1;
      double[] subSrc3_0 = new double[subLen3];
      tempStreak.Slice(0, subLen3).CopyTo(subSrc3_0);
      PercentrankStream sub3 = PercentrankOpenAndFillInternal(subSrc3_0, 0, optInRankPeriod, out outBegIdx, out outNBElement, sc_outReal);
      retCode = RetCode.Success;
      offsetRSI = rsiNb - outNBElement;
      offsetStreak = streakNb - outNBElement;
      for( i = 0; i < (int)outNBElement; i += 1 ) {
         sc_outReal[i] = (tempRSI[i + offsetRSI] + tempStreakRSI[i + offsetStreak] + sc_outReal[i]) / 3.0;
      }
      outBegIdx = startIdx;
      /* Capture the live producer state + sub handles. */
      if( outNBElement < 1 ) {
         return RetCode.InsufficientHistory;
      }
      /* Capture the live batch state into the handle. */
      sp.optInTimePeriod = optInTimePeriod;
      sp.optInStreakPeriod = optInStreakPeriod;
      sp.optInRankPeriod = optInRankPeriod;
      sp.prevClose = prevClose;
      sp.streak = streak;
      sp.sub0 = sub0;
      sp.sub1 = sub1;
      sp.sub2 = sub2;
      sp.sub3 = sub3;
      sp.cur_outReal = sc_outReal[outNBElement - 1];
      return RetCode.Success;
   }

   /* CrsiOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal CrsiStream CrsiOpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, int optInStreakPeriod, int optInRankPeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      CrsiStream sp = new CrsiStream(this);
      RetCode retCode = CrsiOpenImpl(sp, inReal, startIdx, optInTimePeriod, optInStreakPeriod, optInRankPeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("CRSI", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind CrsiOpen (composition seam). */
   internal CrsiStream CrsiOpenInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, int optInStreakPeriod, int optInRankPeriod )
   {
      CrsiStream sp = new CrsiStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = CrsiOpenImpl(sp, inReal, startIdx, optInTimePeriod, optInStreakPeriod, optInRankPeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("CRSI", "open", retCode);
   }

   /// <summary>Open a live <c>CRSI</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="CrsiStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>CRSI</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>CrsiLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>CrsiOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">Close price series. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="CrsiLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInStreakPeriod">As in the batch call; see <see cref="CrsiLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInRankPeriod">As in the batch call; see <see cref="CrsiLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>CrsiLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MaxIndex"/> + 1, the
   /// two index faults an opener can have (rules S1 and S2).</exception>
   public CrsiStream CrsiOpen( ReadOnlySpan<double> inReal, int optInTimePeriod, int optInStreakPeriod, int optInRankPeriod )
   {
      if( inReal.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "CRSI open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MaxIndex + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "CRSI open: history is longer than MaxIndex + 1", RetCode.OutOfRangeEndIndex);
      return CrsiOpenInternal(inReal, 0, optInTimePeriod, optInStreakPeriod, optInRankPeriod);
   }

   /// <summary><c>CrsiOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>CRSI</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - CrsiLookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="CrsiStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">Close price series. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="CrsiLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInStreakPeriod">As in the batch call; see <see cref="CrsiLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInRankPeriod">As in the batch call; see <see cref="CrsiLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">The averaged reading, 0 to 100. Must hold at least <c>historyLen -
   /// CrsiLookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>CrsiLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MaxIndex"/> + 1, the
   /// two index faults an opener can have (rules S1 and S2).</exception>
   public CrsiStream CrsiOpenAndFill( ReadOnlySpan<double> inReal, int optInTimePeriod, int optInStreakPeriod, int optInRankPeriod, Span<double> outReal )
   {
      if( inReal.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "CRSI openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MaxIndex + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "CRSI openAndFill: history is longer than MaxIndex + 1", RetCode.OutOfRangeEndIndex);
      int guardOutLen = OpenFillCount("CRSI", "openAndFill", inReal.Length, CrsiLookback(optInTimePeriod, optInStreakPeriod, optInRankPeriod));
      RequireFillLength("CRSI", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( outReal.Overlaps(inReal) ) {
         throw StreamFailure("CRSI", "openAndFill", RetCode.BadParam);
      }
      return CrsiOpenAndFillInternal(inReal, 0, optInTimePeriod, optInStreakPeriod, optInRankPeriod, out _, out _, outReal);
   }
