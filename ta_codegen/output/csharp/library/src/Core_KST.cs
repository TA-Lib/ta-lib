      int guardStart = ClampedStart(startIdx, endIdx, KstLookback(optInROC1Period, optInROC2Period, optInROC3Period, optInROC4Period, optInSMA1Period, optInSMA2Period, optInSMA3Period, optInSMA4Period, optInSignalPeriod));
      int guardInLen = guardStart < 0 ? 0 : endIdx + 1;
      int guardOutLen = guardStart < 0 || guardStart > endIdx ? 0 : endIdx - guardStart + 1;
      RequireLength("KST", "inReal", inReal.Length, guardInLen);
      RequireLength("KST", "outKST", outKST.Length, guardOutLen);
      RequireLength("KST", "outKSTSignal", outKSTSignal.Length, guardOutLen);
      RetCode retCode = KstImpl(startIdx, endIdx, inReal, optInROC1Period, optInROC2Period, optInROC3Period, optInROC4Period, optInSMA1Period, optInSMA2Period, optInSMA3Period, optInSMA4Period, optInSignalPeriod, out int outBegIdx, out int outNBElement, outKST, outKSTSignal);
      if( retCode != RetCode.Success ) {
         throw Failure("KST", retCode);
      }
      return new OutRange(outBegIdx, outNBElement);
   }
