            imagPart += Math.Cos(tempReal) * tempReal2;
            if( idx == 0 ) {
               idx = 50 - 1;
            } else {
               idx -= 1;
            }
         }
         tempReal = Math.Abs(imagPart);
         if( tempReal > 0.0 ) {
            DCPhase = Math.Atan(realPart / imagPart) * rad2Deg;
         } else if( tempReal <= 0.01 ) {
            if( realPart < 0.0 ) {
               DCPhase -= 90.0;
            } else if( realPart > 0.0 ) {
               DCPhase += 90.0;
            }
         }
         DCPhase += 90.0;
         DCPhase += 360.0 / smoothPeriod;
         if( imagPart < 0.0 ) {
            DCPhase += 180.0;
         }
         if( DCPhase > 315.0 ) {
            DCPhase -= 360.0;
         }
         prevSine = sine;
         prevLeadSine = leadSine;
         sine = Math.Sin(DCPhase * deg2Rad);
         leadSine = Math.Sin((DCPhase + 45) * deg2Rad);
         DCPeriod = smoothPeriod + 0.5;
         DCPeriodInt = (int)DCPeriod;
         tempReal = 0.0;
         for( j = 0; j < 50; j += 1 ) {
            if( j < DCPeriodInt ) {
               tempReal += (double)inReal[today - j];
            }
         }
         if( DCPeriodInt > 0 ) {
            tempReal = tempReal / (double)DCPeriodInt;
         }
         trendline = (Math.FusedMultiplyAdd(2.0, iTrend2, Math.FusedMultiplyAdd(4.0, tempReal, 3.0 * iTrend1)) + iTrend3) / 10.0;
         iTrend3 = iTrend2;
         iTrend2 = iTrend1;
         iTrend1 = tempReal;
         trend = 1;
         if( sine > leadSine && prevSine <= prevLeadSine || sine < leadSine && prevSine >= prevLeadSine ) {
            daysInTrend = 0;
            trend = 0;
         }
         daysInTrend += 1;
         if( daysInTrend < 0.5 * smoothPeriod ) {
            trend = 0;
         }
         tempReal = DCPhase - prevDCPhase;
         if( smoothPeriod != 0.0 && (tempReal > 0.67 * 360.0 / smoothPeriod && tempReal < 1.5 * 360.0 / smoothPeriod) ) {
            trend = 0;
         }
         tempReal = smoothPrice[smoothPrice_Idx];
         if( trendline != 0.0 && Math.Abs((tempReal - trendline) / trendline) >= 0.015 ) {
            trend = 1;
         }
         if( today >= startIdx ) {
            outInteger[outIdx++] = trend;
         }
         smoothPrice_Idx++;
         if( smoothPrice_Idx > maxIdx_smoothPrice ) { smoothPrice_Idx = 0; }
         today += 1;
      }
      outNBElement = outIdx;
      return RetCode.Success ;
   }
