      iTrend3 = 0.0;
      iTrend2 = iTrend3;
      iTrend1 = iTrend2;
      daysInTrend = 0;
      DCPhase = 0.0;
      prevDCPhase = DCPhase;
      sine = 0.0;
      prevSine = sine;
      leadSine = 0.0;
      prevLeadSine = leadSine;
