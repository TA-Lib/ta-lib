         this.jQ_Odd = new double[other.jQ_Odd.Length];
         Array.Copy( other.jQ_Odd, this.jQ_Odd, other.jQ_Odd.Length );
         this.jQ_Even = new double[other.jQ_Even.Length];
         Array.Copy( other.jQ_Even, this.jQ_Even, other.jQ_Even.Length );
         this.prev_jQ_Odd = other.prev_jQ_Odd;
         this.prev_jQ_Even = other.prev_jQ_Even;
         this.prev_jQ_input_Odd = other.prev_jQ_input_Odd;
         this.prev_jQ_input_Even = other.prev_jQ_input_Even;
         this.prevQ2 = other.prevQ2;
         this.prevI2 = other.prevI2;
         this.Re = other.Re;
         this.Im = other.Im;
         this.I1ForOddPrev2 = other.I1ForOddPrev2;
         this.I1ForOddPrev3 = other.I1ForOddPrev3;
         this.I1ForEvenPrev2 = other.I1ForEvenPrev2;
         this.I1ForEvenPrev3 = other.I1ForEvenPrev3;
         this.rad2Deg = other.rad2Deg;
         this.mama = other.mama;
         this.fama = other.fama;
         this.prevPhase = other.prevPhase;
         this.streamParity = other.streamParity;
         this.ringPos_trailingWMAIdx = other.ringPos_trailingWMAIdx;
         this.ringCap_trailingWMAIdx = other.ringCap_trailingWMAIdx;
         this.ring_trailingWMAIdx_inReal = new double[other.ring_trailingWMAIdx_inReal.Length];
         Array.Copy( other.ring_trailingWMAIdx_inReal, this.ring_trailingWMAIdx_inReal, other.ring_trailingWMAIdx_inReal.Length );
         this.cur_outMAMA = other.cur_outMAMA;
         this.cur_outFAMA = other.cur_outFAMA;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Allocates nothing — neither handle state nor a return value.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so no state moves, <see cref="Value"/> still answers the previous value,
      /// and the stream stays usable — just carry on with the next bar.
      /// <see cref="OutRange"/> does advance: the bar happened, so it is counted,
      /// which keeps two handles fed the same series positionally aligned when only
      /// one of them rejects a bar. This is the one place the streaming tier is
      /// stricter than the batch API, which computes on whatever it is given: a
      /// handle retains its state, so a single non-finite bar would poison every
      /// later value it produces.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value at the bar just committed.</returns>
      public MamaValue Update( double inReal )
      {
         if( !double.IsFinite(inReal) )
         {
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
            throw Core.StreamFailure("MAMA", "update", RetCode.BadParam);
         }
         core.MamaStepImpl(this, inReal);
         if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         return new MamaValue(cur_outMAMA, cur_outFAMA);
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It copies nothing: the frame runs against this handle, reading its buffers
      /// and holding what the step would commit in locals. The cost does not grow
      /// with the period, and <c>Peek</c> never allocates.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>What <see cref="Update"/> would return for this bar.</returns>
      public MamaValue Peek( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.StreamFailure("MAMA", "peek", RetCode.BadParam);
         MamaStream sp = this;
         double tempReal = 0.0;
         double tempReal2 = 0.0;
         double adjustedPrevPeriod = 0.0;
         double smoothedValue = 0.0;
         double hilbertTempReal = 0.0;
         double detrender = 0.0;
         double Q1 = 0.0;
         double todayValue = 0.0;
         double I1ForEvenPrev2 = sp.I1ForEvenPrev2;
         double I1ForEvenPrev3 = sp.I1ForEvenPrev3;
         double I1ForOddPrev2 = sp.I1ForOddPrev2;
         double I1ForOddPrev3 = sp.I1ForOddPrev3;
         double cur_outFAMA = 0.0;
         double cur_outMAMA = 0.0;
         double fama = sp.fama;
         int hilbertIdx = sp.hilbertIdx;
         double mama = sp.mama;
         double periodWMASub = sp.periodWMASub;
         double periodWMASum = sp.periodWMASum;
         double prevPhase = sp.prevPhase;
         double prev_Q1_Even = sp.prev_Q1_Even;
         double prev_Q1_Odd = sp.prev_Q1_Odd;
         double prev_Q1_input_Even = sp.prev_Q1_input_Even;
         double prev_Q1_input_Odd = sp.prev_Q1_input_Odd;
         double prev_detrender_Even = sp.prev_detrender_Even;
         double prev_detrender_Odd = sp.prev_detrender_Odd;
         double prev_detrender_input_Even = sp.prev_detrender_input_Even;
         double prev_detrender_input_Odd = sp.prev_detrender_input_Odd;
         double prev_jI_Even = sp.prev_jI_Even;
         double prev_jI_Odd = sp.prev_jI_Odd;
         double prev_jI_input_Even = sp.prev_jI_input_Even;
         double prev_jI_input_Odd = sp.prev_jI_input_Odd;
         double prev_jQ_Even = sp.prev_jQ_Even;
         double prev_jQ_Odd = sp.prev_jQ_Odd;
         double prev_jQ_input_Even = sp.prev_jQ_input_Even;
         double prev_jQ_input_Odd = sp.prev_jQ_input_Odd;
         double trailingWMAValue = sp.trailingWMAValue;
         int pkSlot0 = -1;
         double pkVal0 = 0.0;
         if( sp.ringCap_trailingWMAIdx == 0 ) {
            pkSlot0 = 0;
            pkVal0 = inReal;
         }
         adjustedPrevPeriod = Math.FusedMultiplyAdd(0.075, sp.period, 0.54);
         todayValue = inReal;
         periodWMASub += todayValue;
         periodWMASub -= trailingWMAValue;
         periodWMASum += todayValue * 4.0;
         trailingWMAValue = (sp.ringPos_trailingWMAIdx != pkSlot0) ? sp.ring_trailingWMAIdx_inReal[sp.ringPos_trailingWMAIdx] : pkVal0;
         smoothedValue = periodWMASum * 0.1;
         periodWMASum -= periodWMASub;
         if( sp.streamParity == 0 ) {
            /* Do the Hilbert Transforms for even price bar */
            hilbertTempReal = sp.a * smoothedValue;
            detrender = 0 - sp.detrender_Even[hilbertIdx];
            detrender += hilbertTempReal;
            detrender -= prev_detrender_Even;
            prev_detrender_Even = sp.b * prev_detrender_input_Even;
            detrender += prev_detrender_Even;
            prev_detrender_input_Even = smoothedValue;
            detrender *= adjustedPrevPeriod;
            hilbertTempReal = sp.a * detrender;
            Q1 = 0 - sp.Q1_Even[hilbertIdx];
            Q1 += hilbertTempReal;
            Q1 -= prev_Q1_Even;
            prev_Q1_Even = sp.b * prev_Q1_input_Even;
            Q1 += prev_Q1_Even;
            prev_Q1_input_Even = detrender;
            Q1 *= adjustedPrevPeriod;
            hilbertTempReal = sp.a * I1ForEvenPrev3;
            prev_jI_Even = sp.b * prev_jI_input_Even;
            prev_jI_input_Even = I1ForEvenPrev3;
            hilbertTempReal = sp.a * Q1;
            prev_jQ_Even = sp.b * prev_jQ_input_Even;
            prev_jQ_input_Even = Q1;
            if( ++hilbertIdx == 3 ) {
               hilbertIdx = 0;
            }
            /* The variable I1 is the detrender delayed for
             * 3 price bars.
             *
             * Save the current detrender value for being
             * used by the "odd" logic later.
             */
            I1ForOddPrev3 = I1ForOddPrev2;
            I1ForOddPrev2 = detrender;
            /* Put Alpha in tempReal2 */
            if( I1ForEvenPrev3 != 0.0 ) {
               tempReal2 = Math.Atan(Q1 / I1ForEvenPrev3) * sp.rad2Deg;
            } else {
               tempReal2 = 0.0;
            }
         } else {
            /* Do the Hilbert Transforms for odd price bar */
            hilbertTempReal = sp.a * smoothedValue;
            detrender = 0 - sp.detrender_Odd[hilbertIdx];
            detrender += hilbertTempReal;
            detrender -= prev_detrender_Odd;
            prev_detrender_Odd = sp.b * prev_detrender_input_Odd;
            detrender += prev_detrender_Odd;
            prev_detrender_input_Odd = smoothedValue;
            detrender *= adjustedPrevPeriod;
            hilbertTempReal = sp.a * detrender;
            Q1 = 0 - sp.Q1_Odd[hilbertIdx];
            Q1 += hilbertTempReal;
            Q1 -= prev_Q1_Odd;
            prev_Q1_Odd = sp.b * prev_Q1_input_Odd;
            Q1 += prev_Q1_Odd;
            prev_Q1_input_Odd = detrender;
            Q1 *= adjustedPrevPeriod;
            hilbertTempReal = sp.a * I1ForOddPrev3;
            prev_jI_Odd = sp.b * prev_jI_input_Odd;
            prev_jI_input_Odd = I1ForOddPrev3;
            hilbertTempReal = sp.a * Q1;
            prev_jQ_Odd = sp.b * prev_jQ_input_Odd;
            prev_jQ_input_Odd = Q1;
            /* The varaiable I1 is the detrender delayed for
             * 3 price bars.
             *
             * Save the current detrender value for being
             * used by the "odd" logic later.
             */
            I1ForEvenPrev3 = I1ForEvenPrev2;
            I1ForEvenPrev2 = detrender;
            /* Put Alpha in tempReal2 */
            if( I1ForOddPrev3 != 0.0 ) {
               tempReal2 = Math.Atan(Q1 / I1ForOddPrev3) * sp.rad2Deg;
            } else {
               tempReal2 = 0.0;
            }
         }
         /* Put Delta Phase into tempReal */
         tempReal = prevPhase - tempReal2;
         prevPhase = tempReal2;
         if( tempReal < 1.0 ) {
            tempReal = 1.0;
         }
         /* Put Alpha into tempReal */
         if( tempReal > 1.0 ) {
            tempReal = sp.optInFastLimit / tempReal;
            if( tempReal < sp.optInSlowLimit ) {
               tempReal = sp.optInSlowLimit;
            }
         } else {
            tempReal = sp.optInFastLimit;
         }
         /* Calculate MAMA, FAMA */
         mama = Math.FusedMultiplyAdd(1 - tempReal, mama, tempReal * todayValue);
         tempReal *= 0.5;
         fama = Math.FusedMultiplyAdd(1 - tempReal, fama, tempReal * mama);
         /* FAMA is nullable (issue #125): its write carries no outIdx advance so
          * the codegen can NULL-guard it; outMAMA (never NULL) owns the ++.
          */
         cur_outFAMA = fama;
         cur_outMAMA = mama;
         return new MamaValue(cur_outMAMA, cur_outFAMA);
      }

      /// <summary>Commit <c>n</c> closed bars and write their <c>n</c> values, in one call.</summary>
      /// <remarks>
      /// <para>Exactly <c>n</c> back-to-back <see cref="Update"/> calls, with one set of
      /// argument checks instead of <c>n</c>. The outputs must hold at least
      /// <c>n</c> values and must not overlap an input or each other.</para>
      /// <para><see cref="OutRange"/> counts what this call took in, which is what makes
      /// a rejection readable: a non-finite bar <c>k</c> throws
      /// <see cref="System.ArgumentException"/> exactly as <see cref="Update"/>
      /// would, with the bars before <c>k</c> committed and written, bar <c>k</c>
      /// and everything after it not written, and the count advanced by <c>k +
      /// 1</c> — the committed bars plus the rejected one, so the last bar counted
      /// is the one that failed.</para>
      /// <para><c>outFAMA</c> may be declined with an empty span, per call and
      /// independently of what the opener was given: the value is still computed —
      /// <see cref="Value"/> reports it — and nothing is written out.</para>
      /// </remarks>
      /// <param name="inReal">Closed bars for <c>inReal</c>, oldest first.</param>
      /// <param name="outMAMA">Receives one <c>outMAMA</c> value per bar committed.</param>
      /// <param name="outFAMA">Receives one <c>outFAMA</c> value per bar committed.</param>
      public void UpdateAndFill( ReadOnlySpan<double> inReal, Span<double> outMAMA, Span<double> outFAMA )
      {
         int barCount = inReal.Length;
         if( outMAMA.Length < barCount || (!outFAMA.IsEmpty && outFAMA.Length < barCount) || outMAMA.Overlaps(inReal) || outFAMA.Overlaps(inReal) || outMAMA.Overlaps(outFAMA) ) throw Core.StreamFailure("MAMA", "updateAndFill", RetCode.BadParam);
         for( int i = 0; i < barCount; i++ )
         {
            if( !double.IsFinite(inReal[i]) )
            {
               if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
               throw Core.StreamFailure("MAMA", "updateAndFill", RetCode.BadParam);
            }
            core.MamaStepImpl(this, inReal[i]);
            outMAMA[i] = cur_outMAMA;
            if( !outFAMA.IsEmpty ) outFAMA[i] = cur_outFAMA;
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         }
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public MamaValue Value => new MamaValue(cur_outMAMA, cur_outFAMA);

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public MamaStream Clone()
      {
         return new MamaStream(this);
      }
   }

   internal void MamaStepImpl( MamaStream sp, double inReal )
   {
      double tempReal = 0.0;
      double tempReal2 = 0.0;
      double adjustedPrevPeriod = 0.0;
      double smoothedValue = 0.0;
      double hilbertTempReal = 0.0;
      double detrender = 0.0;
      double Q1 = 0.0;
      double jI = 0.0;
      double jQ = 0.0;
      double Q2 = 0.0;
      double I2 = 0.0;
      double todayValue = 0.0;
      if( sp.ringCap_trailingWMAIdx == 0 ) {
         sp.ring_trailingWMAIdx_inReal[0] = inReal;
      }
      adjustedPrevPeriod = Math.FusedMultiplyAdd(0.075, sp.period, 0.54);
      todayValue = inReal;
      sp.periodWMASub += todayValue;
      sp.periodWMASub -= sp.trailingWMAValue;
      sp.periodWMASum += todayValue * 4.0;
      sp.trailingWMAValue = sp.ring_trailingWMAIdx_inReal[sp.ringPos_trailingWMAIdx];
      smoothedValue = sp.periodWMASum * 0.1;
      sp.periodWMASum -= sp.periodWMASub;
      if( sp.streamParity == 0 ) {
         /* Do the Hilbert Transforms for even price bar */
         hilbertTempReal = sp.a * smoothedValue;
         detrender = 0 - sp.detrender_Even[sp.hilbertIdx];
         sp.detrender_Even[sp.hilbertIdx] = hilbertTempReal;
         detrender += hilbertTempReal;
         detrender -= sp.prev_detrender_Even;
         sp.prev_detrender_Even = sp.b * sp.prev_detrender_input_Even;
         detrender += sp.prev_detrender_Even;
         sp.prev_detrender_input_Even = smoothedValue;
         detrender *= adjustedPrevPeriod;
         hilbertTempReal = sp.a * detrender;
         Q1 = 0 - sp.Q1_Even[sp.hilbertIdx];
         sp.Q1_Even[sp.hilbertIdx] = hilbertTempReal;
         Q1 += hilbertTempReal;
         Q1 -= sp.prev_Q1_Even;
         sp.prev_Q1_Even = sp.b * sp.prev_Q1_input_Even;
         Q1 += sp.prev_Q1_Even;
         sp.prev_Q1_input_Even = detrender;
         Q1 *= adjustedPrevPeriod;
         hilbertTempReal = sp.a * sp.I1ForEvenPrev3;
         jI = 0 - sp.jI_Even[sp.hilbertIdx];
         sp.jI_Even[sp.hilbertIdx] = hilbertTempReal;
         jI += hilbertTempReal;
         jI -= sp.prev_jI_Even;
         sp.prev_jI_Even = sp.b * sp.prev_jI_input_Even;
         jI += sp.prev_jI_Even;
         sp.prev_jI_input_Even = sp.I1ForEvenPrev3;
         jI *= adjustedPrevPeriod;
         hilbertTempReal = sp.a * Q1;
         jQ = 0 - sp.jQ_Even[sp.hilbertIdx];
         sp.jQ_Even[sp.hilbertIdx] = hilbertTempReal;
         jQ += hilbertTempReal;
         jQ -= sp.prev_jQ_Even;
         sp.prev_jQ_Even = sp.b * sp.prev_jQ_input_Even;
         jQ += sp.prev_jQ_Even;
         sp.prev_jQ_input_Even = Q1;
         jQ *= adjustedPrevPeriod;
         if( ++sp.hilbertIdx == 3 ) {
            sp.hilbertIdx = 0;
         }
         Q2 = Math.FusedMultiplyAdd(0.2, Q1 + jI, 0.8 * sp.prevQ2);
         I2 = Math.FusedMultiplyAdd(0.2, sp.I1ForEvenPrev3 - jQ, 0.8 * sp.prevI2);
         /* The variable I1 is the detrender delayed for
          * 3 price bars.
          *
          * Save the current detrender value for being
          * used by the "odd" logic later.
          */
         sp.I1ForOddPrev3 = sp.I1ForOddPrev2;
         sp.I1ForOddPrev2 = detrender;
         /* Put Alpha in tempReal2 */
         if( sp.I1ForEvenPrev3 != 0.0 ) {
            tempReal2 = Math.Atan(Q1 / sp.I1ForEvenPrev3) * sp.rad2Deg;
         } else {
            tempReal2 = 0.0;
         }
      } else {
         /* Do the Hilbert Transforms for odd price bar */
         hilbertTempReal = sp.a * smoothedValue;
         detrender = 0 - sp.detrender_Odd[sp.hilbertIdx];
         sp.detrender_Odd[sp.hilbertIdx] = hilbertTempReal;
         detrender += hilbertTempReal;
         detrender -= sp.prev_detrender_Odd;
         sp.prev_detrender_Odd = sp.b * sp.prev_detrender_input_Odd;
         detrender += sp.prev_detrender_Odd;
         sp.prev_detrender_input_Odd = smoothedValue;
         detrender *= adjustedPrevPeriod;
         hilbertTempReal = sp.a * detrender;
         Q1 = 0 - sp.Q1_Odd[sp.hilbertIdx];
         sp.Q1_Odd[sp.hilbertIdx] = hilbertTempReal;
         Q1 += hilbertTempReal;
         Q1 -= sp.prev_Q1_Odd;
         sp.prev_Q1_Odd = sp.b * sp.prev_Q1_input_Odd;
         Q1 += sp.prev_Q1_Odd;
         sp.prev_Q1_input_Odd = detrender;
         Q1 *= adjustedPrevPeriod;
         hilbertTempReal = sp.a * sp.I1ForOddPrev3;
         jI = 0 - sp.jI_Odd[sp.hilbertIdx];
         sp.jI_Odd[sp.hilbertIdx] = hilbertTempReal;
         jI += hilbertTempReal;
         jI -= sp.prev_jI_Odd;
         sp.prev_jI_Odd = sp.b * sp.prev_jI_input_Odd;
         jI += sp.prev_jI_Odd;
         sp.prev_jI_input_Odd = sp.I1ForOddPrev3;
         jI *= adjustedPrevPeriod;
         hilbertTempReal = sp.a * Q1;
         jQ = 0 - sp.jQ_Odd[sp.hilbertIdx];
         sp.jQ_Odd[sp.hilbertIdx] = hilbertTempReal;
         jQ += hilbertTempReal;
         jQ -= sp.prev_jQ_Odd;
         sp.prev_jQ_Odd = sp.b * sp.prev_jQ_input_Odd;
         jQ += sp.prev_jQ_Odd;
         sp.prev_jQ_input_Odd = Q1;
         jQ *= adjustedPrevPeriod;
         Q2 = Math.FusedMultiplyAdd(0.2, Q1 + jI, 0.8 * sp.prevQ2);
         I2 = Math.FusedMultiplyAdd(0.2, sp.I1ForOddPrev3 - jQ, 0.8 * sp.prevI2);
         /* The varaiable I1 is the detrender delayed for
          * 3 price bars.
          *
          * Save the current detrender value for being
          * used by the "odd" logic later.
          */
         sp.I1ForEvenPrev3 = sp.I1ForEvenPrev2;
         sp.I1ForEvenPrev2 = detrender;
         /* Put Alpha in tempReal2 */
         if( sp.I1ForOddPrev3 != 0.0 ) {
            tempReal2 = Math.Atan(Q1 / sp.I1ForOddPrev3) * sp.rad2Deg;
         } else {
            tempReal2 = 0.0;
         }
      }
      /* Put Delta Phase into tempReal */
      tempReal = sp.prevPhase - tempReal2;
      sp.prevPhase = tempReal2;
      if( tempReal < 1.0 ) {
         tempReal = 1.0;
      }
      /* Put Alpha into tempReal */
      if( tempReal > 1.0 ) {
         tempReal = sp.optInFastLimit / tempReal;
         if( tempReal < sp.optInSlowLimit ) {
            tempReal = sp.optInSlowLimit;
         }
      } else {
         tempReal = sp.optInFastLimit;
      }
      /* Calculate MAMA, FAMA */
      sp.mama = Math.FusedMultiplyAdd(1 - tempReal, sp.mama, tempReal * todayValue);
      tempReal *= 0.5;
      sp.fama = Math.FusedMultiplyAdd(1 - tempReal, sp.fama, tempReal * sp.mama);
      /* FAMA is nullable (issue #125): its write carries no outIdx advance so
       * the codegen can NULL-guard it; outMAMA (never NULL) owns the ++.
       */
      sp.cur_outFAMA = sp.fama;
      sp.cur_outMAMA = sp.mama;
      /* Adjust the period for next price bar */
      sp.Re = Math.FusedMultiplyAdd(0.8, sp.Re, 0.2 * (Math.FusedMultiplyAdd(I2, sp.prevI2, Q2 * sp.prevQ2)));
      sp.Im = Math.FusedMultiplyAdd(0.8, sp.Im, 0.2 * (I2 * sp.prevQ2 - Q2 * sp.prevI2));
      sp.prevQ2 = Q2;
      sp.prevI2 = I2;
      tempReal = sp.period;
      if( sp.Im != 0.0 && sp.Re != 0.0 ) {
         sp.period = 360.0 / (Math.Atan(sp.Im / sp.Re) * sp.rad2Deg);
      }
      tempReal2 = 1.5 * tempReal;
      if( sp.period > tempReal2 ) {
         sp.period = tempReal2;
      }
      tempReal2 = 0.67 * tempReal;
      if( sp.period < tempReal2 ) {
         sp.period = tempReal2;
      }
      if( sp.period < 6 ) {
         sp.period = 6;
      } else if( sp.period > 50 ) {
         sp.period = 50;
      }
      sp.period = Math.FusedMultiplyAdd(0.2, sp.period, 0.8 * tempReal);
      /* Ooof... let's do the next price bar now! */
      sp.ring_trailingWMAIdx_inReal[sp.ringPos_trailingWMAIdx] = inReal;
      sp.ringPos_trailingWMAIdx = sp.ringPos_trailingWMAIdx + 1;
      if( sp.ringPos_trailingWMAIdx >= sp.ringCap_trailingWMAIdx ) {
         sp.ringPos_trailingWMAIdx = 0;
      }
      sp.streamParity = 1 - sp.streamParity;
   }

   private RetCode MamaOpenImpl( MamaStream sp, ReadOnlySpan<double> inReal, int startIdx, double optInFastLimit, double optInSlowLimit, out int outBegIdx, out int outNBElement, Span<double> outMAMA, Span<double> outFAMA, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double lastCur_outFAMA = 0;
      int outIdx = 0;
      int i = 0;
      int lookbackTotal = 0;
      int today = 0;
      double tempReal = 0;
      double tempReal2 = 0;
      double adjustedPrevPeriod = 0;
      double period = 0;
      int trailingWMAIdx = 0;
      double periodWMASum = 0;
      double periodWMASub = 0;
      double trailingWMAValue = 0;
      double smoothedValue = 0;
      double a = 0;
      double b = 0;
      double hilbertTempReal = 0;
      int hilbertIdx = 0;
      double[] detrender_Odd = new double[3];
      double[] detrender_Even = new double[3];
      double detrender = 0;
      double prev_detrender_Odd = 0;
      double prev_detrender_Even = 0;
      double prev_detrender_input_Odd = 0;
      double prev_detrender_input_Even = 0;
      double[] Q1_Odd = new double[3];
      double[] Q1_Even = new double[3];
      double Q1 = 0;
      double prev_Q1_Odd = 0;
      double prev_Q1_Even = 0;
      double prev_Q1_input_Odd = 0;
      double prev_Q1_input_Even = 0;
      double[] jI_Odd = new double[3];
      double[] jI_Even = new double[3];
      double jI = 0;
      double prev_jI_Odd = 0;
      double prev_jI_Even = 0;
      double prev_jI_input_Odd = 0;
      double prev_jI_input_Even = 0;
      double[] jQ_Odd = new double[3];
      double[] jQ_Even = new double[3];
      double jQ = 0;
      double prev_jQ_Odd = 0;
      double prev_jQ_Even = 0;
      double prev_jQ_input_Odd = 0;
      double prev_jQ_input_Even = 0;
      double Q2 = 0;
      double I2 = 0;
      double prevQ2 = 0;
      double prevI2 = 0;
      double Re = 0;
      double Im = 0;
      double I1ForOddPrev2 = 0;
      double I1ForOddPrev3 = 0;
      double I1ForEvenPrev2 = 0;
      double I1ForEvenPrev3 = 0;
      double rad2Deg = 0;
      double mama = 0;
      double fama = 0;
      double todayValue = 0;
      double prevPhase = 0;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInFastLimit == TA_REAL_DEFAULT ) {
         optInFastLimit = 5e-1;
      } else if( !(optInFastLimit >= 1e-2 && optInFastLimit <= 9.9e-1) ) {
         return RetCode.BadParam;
      }
      if( optInSlowLimit == TA_REAL_DEFAULT ) {
         optInSlowLimit = 5e-2;
      } else if( !(optInSlowLimit >= 1e-2 && optInSlowLimit <= 9.9e-1) ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      a = 0.0962;
      b = 0.5769;
      /* Variable used for the price smoother (a weighted moving average). */
      /* Variables used for the Hilbert Transormation */
      /* Constant */
      rad2Deg = 180.0 / (4.0 * Math.Atan(1));
      /* Identify the minimum number of price bar needed
       * to calculate at least one output.
       */
      lookbackTotal = 32 + this.unstablePeriod[(int)FuncUnstId.MAMA];
      /* Move up the start index if there is not
       * enough initial data.
       */
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      outBegIdx = startIdx;
      /* Initialize the price smoother, which is simply a weighted
       * moving average of the price.
       * To understand this algorithm, I strongly suggest to understand
       * first how TA_WMA is done.
       */
      trailingWMAIdx = startIdx - lookbackTotal;
      today = trailingWMAIdx;
      /* Initialization is same as WMA, except loop is unrolled
       * for speed optimization.
       */
      tempReal = inReal[today++];
      periodWMASub = tempReal;
      periodWMASum = tempReal;
      tempReal = inReal[today++];
      periodWMASub += tempReal;
      periodWMASum += tempReal * 2.0;
      tempReal = inReal[today++];
      periodWMASub += tempReal;
      periodWMASum += tempReal * 3.0;
      trailingWMAValue = 0.0;
      /* Subsequent WMA value are evaluated by using
       * the DO_PRICE_WMA macro.
       */
      i = 9;
      do {
         tempReal = inReal[today++];
         periodWMASub += tempReal;
         periodWMASub -= trailingWMAValue;
         periodWMASum += tempReal * 4.0;
         trailingWMAValue = inReal[trailingWMAIdx++];
         smoothedValue = periodWMASum * 0.1;
         periodWMASum -= periodWMASub;
      } while( --i != 0 );
      /* Initialize the circular buffers used by the hilbert
       * transform logic.
       * A buffer is used for odd day and another for even days.
       * This minimize the number of memory access and floating point
       * operations needed (note also that by using static circular buffer,
       * no large dynamic memory allocation is needed for storing
       * intermediate calculation!).
       */
      hilbertIdx = 0;
      detrender_Odd[0] = 0.0;
      detrender_Odd[1] = 0.0;
      detrender_Odd[2] = 0.0;
      detrender_Even[0] = 0.0;
      detrender_Even[1] = 0.0;
      detrender_Even[2] = 0.0;
      detrender = 0.0;
      prev_detrender_Odd = 0.0;
      prev_detrender_Even = 0.0;
      prev_detrender_input_Odd = 0.0;
      prev_detrender_input_Even = 0.0;
      Q1_Odd[0] = 0.0;
      Q1_Odd[1] = 0.0;
      Q1_Odd[2] = 0.0;
      Q1_Even[0] = 0.0;
      Q1_Even[1] = 0.0;
      Q1_Even[2] = 0.0;
      Q1 = 0.0;
      prev_Q1_Odd = 0.0;
      prev_Q1_Even = 0.0;
      prev_Q1_input_Odd = 0.0;
      prev_Q1_input_Even = 0.0;
      jI_Odd[0] = 0.0;
      jI_Odd[1] = 0.0;
      jI_Odd[2] = 0.0;
      jI_Even[0] = 0.0;
      jI_Even[1] = 0.0;
      jI_Even[2] = 0.0;
      jI = 0.0;
      prev_jI_Odd = 0.0;
      prev_jI_Even = 0.0;
      prev_jI_input_Odd = 0.0;
      prev_jI_input_Even = 0.0;
      jQ_Odd[0] = 0.0;
      jQ_Odd[1] = 0.0;
      jQ_Odd[2] = 0.0;
      jQ_Even[0] = 0.0;
      jQ_Even[1] = 0.0;
      jQ_Even[2] = 0.0;
      jQ = 0.0;
      prev_jQ_Odd = 0.0;
      prev_jQ_Even = 0.0;
      prev_jQ_input_Odd = 0.0;
      prev_jQ_input_Even = 0.0;
      period = 0.0;
      outIdx = 0;
      prevQ2 = 0.0;
      prevI2 = prevQ2;
      Im = 0.0;
      Re = Im;
      fama = 0.0;
      mama = fama;
      I1ForEvenPrev3 = 0.0;
      I1ForOddPrev3 = I1ForEvenPrev3;
      I1ForEvenPrev2 = 0.0;
      I1ForOddPrev2 = I1ForEvenPrev2;
      prevPhase = 0.0;
      /* The code is speed optimized and is most likely very
       * hard to follow if you do not already know well the
       * original algorithm.
       * To understadn better, it is strongly suggested to look
       * first at the Excel implementation in "test_MAMA.xls" included
       * in this package.
       */
      while( today <= endIdx ) {
         adjustedPrevPeriod = Math.FusedMultiplyAdd(0.075, period, 0.54);
         todayValue = inReal[today];
         periodWMASub += todayValue;
         periodWMASub -= trailingWMAValue;
         periodWMASum += todayValue * 4.0;
         trailingWMAValue = inReal[trailingWMAIdx++];
         smoothedValue = periodWMASum * 0.1;
         periodWMASum -= periodWMASub;
         if( today % 2 == 0 ) {
            /* Do the Hilbert Transforms for even price bar */
            hilbertTempReal = a * smoothedValue;
            detrender = 0 - detrender_Even[hilbertIdx];
            detrender_Even[hilbertIdx] = hilbertTempReal;
            detrender += hilbertTempReal;
            detrender -= prev_detrender_Even;
            prev_detrender_Even = b * prev_detrender_input_Even;
            detrender += prev_detrender_Even;
            prev_detrender_input_Even = smoothedValue;
            detrender *= adjustedPrevPeriod;
            hilbertTempReal = a * detrender;
            Q1 = 0 - Q1_Even[hilbertIdx];
            Q1_Even[hilbertIdx] = hilbertTempReal;
            Q1 += hilbertTempReal;
            Q1 -= prev_Q1_Even;
            prev_Q1_Even = b * prev_Q1_input_Even;
            Q1 += prev_Q1_Even;
            prev_Q1_input_Even = detrender;
            Q1 *= adjustedPrevPeriod;
            hilbertTempReal = a * I1ForEvenPrev3;
            jI = 0 - jI_Even[hilbertIdx];
            jI_Even[hilbertIdx] = hilbertTempReal;
            jI += hilbertTempReal;
            jI -= prev_jI_Even;
            prev_jI_Even = b * prev_jI_input_Even;
            jI += prev_jI_Even;
            prev_jI_input_Even = I1ForEvenPrev3;
            jI *= adjustedPrevPeriod;
            hilbertTempReal = a * Q1;
            jQ = 0 - jQ_Even[hilbertIdx];
            jQ_Even[hilbertIdx] = hilbertTempReal;
            jQ += hilbertTempReal;
            jQ -= prev_jQ_Even;
            prev_jQ_Even = b * prev_jQ_input_Even;
            jQ += prev_jQ_Even;
            prev_jQ_input_Even = Q1;
            jQ *= adjustedPrevPeriod;
            if( ++hilbertIdx == 3 ) {
               hilbertIdx = 0;
            }
            Q2 = Math.FusedMultiplyAdd(0.2, Q1 + jI, 0.8 * prevQ2);
            I2 = Math.FusedMultiplyAdd(0.2, I1ForEvenPrev3 - jQ, 0.8 * prevI2);
            /* The variable I1 is the detrender delayed for
             * 3 price bars.
             *
             * Save the current detrender value for being
             * used by the "odd" logic later.
             */
            I1ForOddPrev3 = I1ForOddPrev2;
            I1ForOddPrev2 = detrender;
            /* Put Alpha in tempReal2 */
            if( I1ForEvenPrev3 != 0.0 ) {
               tempReal2 = Math.Atan(Q1 / I1ForEvenPrev3) * rad2Deg;
            } else {
               tempReal2 = 0.0;
            }
         } else {
            /* Do the Hilbert Transforms for odd price bar */
            hilbertTempReal = a * smoothedValue;
            detrender = 0 - detrender_Odd[hilbertIdx];
            detrender_Odd[hilbertIdx] = hilbertTempReal;
            detrender += hilbertTempReal;
            detrender -= prev_detrender_Odd;
            prev_detrender_Odd = b * prev_detrender_input_Odd;
            detrender += prev_detrender_Odd;
            prev_detrender_input_Odd = smoothedValue;
            detrender *= adjustedPrevPeriod;
            hilbertTempReal = a * detrender;
            Q1 = 0 - Q1_Odd[hilbertIdx];
            Q1_Odd[hilbertIdx] = hilbertTempReal;
            Q1 += hilbertTempReal;
            Q1 -= prev_Q1_Odd;
            prev_Q1_Odd = b * prev_Q1_input_Odd;
            Q1 += prev_Q1_Odd;
            prev_Q1_input_Odd = detrender;
            Q1 *= adjustedPrevPeriod;
            hilbertTempReal = a * I1ForOddPrev3;
            jI = 0 - jI_Odd[hilbertIdx];
            jI_Odd[hilbertIdx] = hilbertTempReal;
            jI += hilbertTempReal;
            jI -= prev_jI_Odd;
            prev_jI_Odd = b * prev_jI_input_Odd;
            jI += prev_jI_Odd;
            prev_jI_input_Odd = I1ForOddPrev3;
            jI *= adjustedPrevPeriod;
            hilbertTempReal = a * Q1;
            jQ = 0 - jQ_Odd[hilbertIdx];
            jQ_Odd[hilbertIdx] = hilbertTempReal;
            jQ += hilbertTempReal;
            jQ -= prev_jQ_Odd;
            prev_jQ_Odd = b * prev_jQ_input_Odd;
            jQ += prev_jQ_Odd;
            prev_jQ_input_Odd = Q1;
            jQ *= adjustedPrevPeriod;
            Q2 = Math.FusedMultiplyAdd(0.2, Q1 + jI, 0.8 * prevQ2);
            I2 = Math.FusedMultiplyAdd(0.2, I1ForOddPrev3 - jQ, 0.8 * prevI2);
            /* The varaiable I1 is the detrender delayed for
             * 3 price bars.
             *
             * Save the current detrender value for being
             * used by the "odd" logic later.
             */
            I1ForEvenPrev3 = I1ForEvenPrev2;
            I1ForEvenPrev2 = detrender;
            /* Put Alpha in tempReal2 */
            if( I1ForOddPrev3 != 0.0 ) {
               tempReal2 = Math.Atan(Q1 / I1ForOddPrev3) * rad2Deg;
            } else {
               tempReal2 = 0.0;
            }
         }
         /* Put Delta Phase into tempReal */
         tempReal = prevPhase - tempReal2;
         prevPhase = tempReal2;
         if( tempReal < 1.0 ) {
            tempReal = 1.0;
         }
         /* Put Alpha into tempReal */
         if( tempReal > 1.0 ) {
            tempReal = optInFastLimit / tempReal;
            if( tempReal < optInSlowLimit ) {
               tempReal = optInSlowLimit;
            }
         } else {
            tempReal = optInFastLimit;
         }
         /* Calculate MAMA, FAMA */
         mama = Math.FusedMultiplyAdd(1 - tempReal, mama, tempReal * todayValue);
         tempReal *= 0.5;
         fama = Math.FusedMultiplyAdd(1 - tempReal, fama, tempReal * mama);
         if( today >= startIdx ) {
            /* FAMA is nullable (issue #125): its write carries no outIdx advance so
             * the codegen can NULL-guard it; outMAMA (never NULL) owns the ++.
             */
            lastCur_outFAMA = fama;
            if( !outFAMA.IsEmpty )
               outFAMA[outIdx * outStride] = fama;
            outMAMA[outIdx++ * outStride] = mama;
         }
         /* Adjust the period for next price bar */
         Re = Math.FusedMultiplyAdd(0.8, Re, 0.2 * (Math.FusedMultiplyAdd(I2, prevI2, Q2 * prevQ2)));
         Im = Math.FusedMultiplyAdd(0.8, Im, 0.2 * (I2 * prevQ2 - Q2 * prevI2));
         prevQ2 = Q2;
         prevI2 = I2;
         tempReal = period;
         if( Im != 0.0 && Re != 0.0 ) {
            period = 360.0 / (Math.Atan(Im / Re) * rad2Deg);
         }
         tempReal2 = 1.5 * tempReal;
         if( period > tempReal2 ) {
            period = tempReal2;
         }
         tempReal2 = 0.67 * tempReal;
         if( period < tempReal2 ) {
            period = tempReal2;
         }
         if( period < 6 ) {
            period = 6;
         } else if( period > 50 ) {
            period = 50;
         }
         period = Math.FusedMultiplyAdd(0.2, period, 0.8 * tempReal);
         /* Ooof... let's do the next price bar now! */
         today += 1;
      }
      /* Default return values */
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      int cap_trailingWMAIdx = today - trailingWMAIdx;
      if( cap_trailingWMAIdx < 0 || cap_trailingWMAIdx > historyLen ) {
         return RetCode.InternalError;
      }
      int allocN_trailingWMAIdx = (cap_trailingWMAIdx > 0)? cap_trailingWMAIdx : 1;
      double[] capRing_trailingWMAIdx_inReal = new double[allocN_trailingWMAIdx];
      inReal.Slice(historyLen - cap_trailingWMAIdx, cap_trailingWMAIdx).CopyTo(capRing_trailingWMAIdx_inReal);
      sp.optInFastLimit = optInFastLimit;
      sp.optInSlowLimit = optInSlowLimit;
      sp.period = period;
      sp.periodWMASum = periodWMASum;
      sp.periodWMASub = periodWMASub;
      sp.trailingWMAValue = trailingWMAValue;
      sp.a = a;
      sp.b = b;
      sp.hilbertIdx = hilbertIdx;
      sp.detrender_Odd = detrender_Odd;
      sp.detrender_Even = detrender_Even;
      sp.prev_detrender_Odd = prev_detrender_Odd;
      sp.prev_detrender_Even = prev_detrender_Even;
      sp.prev_detrender_input_Odd = prev_detrender_input_Odd;
      sp.prev_detrender_input_Even = prev_detrender_input_Even;
      sp.Q1_Odd = Q1_Odd;
      sp.Q1_Even = Q1_Even;
      sp.prev_Q1_Odd = prev_Q1_Odd;
      sp.prev_Q1_Even = prev_Q1_Even;
      sp.prev_Q1_input_Odd = prev_Q1_input_Odd;
      sp.prev_Q1_input_Even = prev_Q1_input_Even;
      sp.jI_Odd = jI_Odd;
      sp.jI_Even = jI_Even;
      sp.prev_jI_Odd = prev_jI_Odd;
      sp.prev_jI_Even = prev_jI_Even;
      sp.prev_jI_input_Odd = prev_jI_input_Odd;
      sp.prev_jI_input_Even = prev_jI_input_Even;
      sp.jQ_Odd = jQ_Odd;
      sp.jQ_Even = jQ_Even;
      sp.prev_jQ_Odd = prev_jQ_Odd;
      sp.prev_jQ_Even = prev_jQ_Even;
      sp.prev_jQ_input_Odd = prev_jQ_input_Odd;
      sp.prev_jQ_input_Even = prev_jQ_input_Even;
      sp.prevQ2 = prevQ2;
      sp.prevI2 = prevI2;
      sp.Re = Re;
      sp.Im = Im;
      sp.I1ForOddPrev2 = I1ForOddPrev2;
      sp.I1ForOddPrev3 = I1ForOddPrev3;
      sp.I1ForEvenPrev2 = I1ForEvenPrev2;
      sp.I1ForEvenPrev3 = I1ForEvenPrev3;
      sp.rad2Deg = rad2Deg;
      sp.mama = mama;
      sp.fama = fama;
      sp.prevPhase = prevPhase;
      sp.streamParity = historyLen % 2;
      sp.ringPos_trailingWMAIdx = 0;
      sp.ringCap_trailingWMAIdx = cap_trailingWMAIdx;
      sp.ring_trailingWMAIdx_inReal = capRing_trailingWMAIdx_inReal;
      sp.cur_outMAMA = outMAMA[(outNBElement - 1) * outStride];
      sp.cur_outFAMA = lastCur_outFAMA;
      return RetCode.Success;
   }

   /* MamaOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal MamaStream MamaOpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, double optInFastLimit, double optInSlowLimit, out int outBegIdx, out int outNBElement, Span<double> outMAMA, Span<double> outFAMA )
   {
      MamaStream sp = new MamaStream(this);
      RetCode retCode = MamaOpenImpl(sp, inReal, startIdx, optInFastLimit, optInSlowLimit, out outBegIdx, out outNBElement, outMAMA, outFAMA, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("MAMA", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind MamaOpen (composition seam). */
   internal MamaStream MamaOpenInternal( ReadOnlySpan<double> inReal, int startIdx, double optInFastLimit, double optInSlowLimit )
   {
      MamaStream sp = new MamaStream(this);
      double[] sink_outMAMA = new double[1];
      double[] sink_outFAMA = new double[1];
      RetCode retCode = MamaOpenImpl(sp, inReal, startIdx, optInFastLimit, optInSlowLimit, out int outBegIdx, out int outNBElement, sink_outMAMA, sink_outFAMA, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("MAMA", "open", retCode);
   }

   /// <summary>Open a live <c>MAMA</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="MamaStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>MAMA</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>MAMA_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>MamaOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">Price series to smooth. The warm-up history, oldest bar first.</param>
   /// <param name="optInFastLimit">As in the batch call; see <see cref="MAMA_Lookback"/> for its default and
   /// range (<c>-4e37</c> selects the default).</param>
   /// <param name="optInSlowLimit">As in the batch call; see <see cref="MAMA_Lookback"/> for its default and
   /// range (<c>-4e37</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>MAMA_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public MamaStream MamaOpen( ReadOnlySpan<double> inReal, double optInFastLimit, double optInSlowLimit )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "MAMA open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "MAMA open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      return MamaOpenInternal(inReal, 0, optInFastLimit, optInSlowLimit);
   }

   /// <summary><c>MamaOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>MAMA</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - MAMA_Lookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="MamaStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">Price series to smooth. The warm-up history, oldest bar first.</param>
   /// <param name="optInFastLimit">As in the batch call; see <see cref="MAMA_Lookback"/> for its default and
   /// range (<c>-4e37</c> selects the default).</param>
   /// <param name="optInSlowLimit">As in the batch call; see <see cref="MAMA_Lookback"/> for its default and
   /// range (<c>-4e37</c> selects the default).</param>
   /// <param name="outMAMA">Adaptive moving average (fast line) Must hold at least <c>historyLen -
   /// MAMA_Lookback(...)</c> values.</param>
   /// <param name="outFAMA">Following adaptive moving average, using half the alpha (slow line) Pass
   /// an empty span to decline it: the value is still computed — the handle's
   /// <c>Value</c> reports it — and nothing is written out. Must hold at least
   /// <c>historyLen - MAMA_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>MAMA_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public MamaStream MamaOpenAndFill( ReadOnlySpan<double> inReal, double optInFastLimit, double optInSlowLimit, Span<double> outMAMA, Span<double> outFAMA )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "MAMA openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "MAMA openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      int guardOutLen = OpenFillCount("MAMA", "openAndFill", inReal.Length, MAMA_Lookback(optInFastLimit, optInSlowLimit));
      RequireFillLength("MAMA", "openAndFill", "outMAMA", outMAMA.Length, guardOutLen);
      if( !outFAMA.IsEmpty ) RequireFillLength("MAMA", "openAndFill", "outFAMA", outFAMA.Length, guardOutLen);
      if( outMAMA.Overlaps(inReal) || outFAMA.Overlaps(inReal) || outMAMA.Overlaps(outFAMA) ) {
         throw StreamFailure("MAMA", "openAndFill", RetCode.BadParam);
