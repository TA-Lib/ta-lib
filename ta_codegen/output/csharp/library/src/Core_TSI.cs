   /// <exception cref="System.ArgumentException">A span is too short for the range requested: any input this function
   /// <i>declares</i> that does not reach <c>endIdx</c>, or an output that
   /// cannot hold the values produced. Checked before anything is written, so a
   /// rejected call leaves every buffer untouched. Declared, not read: a few
   /// candlestick patterns take an OHLC series they never index, and it is
   /// required all the same. An empty span — which is what a null array becomes,
   /// since a span cannot be null — is rejected on the same terms and no others:
   /// it is too short whenever the range produces a value, and fine when it
   /// produces none, and on an output this function documents as declinable it
   /// is how you decline.</exception>
   /// <exception cref="System.ArgumentException">Two output buffers overlap, or an output partially overlaps an input.
   /// Computing wholly in place (an output that IS an input) is allowed.</exception>
   public OutRange TSI( int startIdx,
                        int endIdx,
                        ReadOnlySpan<float> inReal,
                        int optInFirstPeriod,
                        int optInSecondPeriod,
                        Span<double> outReal )
   {
      int guardStart = ClampedStart(startIdx, endIdx, TSI_Lookback(optInFirstPeriod, optInSecondPeriod));
      int guardInLen = guardStart < 0 ? 0 : endIdx + 1;
      int guardOutLen = guardStart < 0 || guardStart > endIdx ? 0 : endIdx - guardStart + 1;
      RequireLength("TSI", "inReal", inReal.Length, guardInLen);
      RequireLength("TSI", "outReal", outReal.Length, guardOutLen);
      RetCode retCode = TSI_Impl(startIdx, endIdx, inReal, optInFirstPeriod, optInSecondPeriod, out int outBegIdx, out int outNBElement, outReal);
      if( retCode != RetCode.Success ) {
         throw Failure("TSI", retCode);
      }
      return new OutRange(outBegIdx, outNBElement);
   }
   /**** Streaming API *****/

   /// <summary>A live <c>TSI</c> stream: one value per closed bar, bit-identical to
   /// <c>TSI</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.TsiOpen"/>. There is no close and nothing to
   /// dispose — the handle is ordinary managed state, and an unreferenced handle
   /// is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class TsiStream
   {
      internal Core core;
      internal int optInFirstPeriod;
      internal int optInSecondPeriod;
      internal double kFirst;
      internal double kSecond;
      internal double emaFirstNum;
      internal double emaFirstDen;
      internal double emaSecondNum;
      internal double emaSecondDen;
      internal double prevClose;
      internal double cur_outReal;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal TsiStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Tsi</c> reports over the same bars: the opener sets it
      /// to <c>(lookback, historyLen - lookback)</c>, every <c>Update</c> adds one
      /// to the count — a non-finite bar is rejected but still counted, because the
      /// bar happened — <c>Peek</c> leaves it alone, and <c>Clone</c> carries it
      /// verbatim. A plain <c>Open</c> hands back only the last value, a subset of
      /// this range, because the caller chose not to take the fill.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      internal TsiStream( TsiStream other )
      {
         this.core = other.core;
         this.optInFirstPeriod = other.optInFirstPeriod;
         this.optInSecondPeriod = other.optInSecondPeriod;
         this.kFirst = other.kFirst;
         this.kSecond = other.kSecond;
         this.emaFirstNum = other.emaFirstNum;
         this.emaFirstDen = other.emaFirstDen;
         this.emaSecondNum = other.emaSecondNum;
         this.emaSecondDen = other.emaSecondDen;
         this.prevClose = other.prevClose;
         this.cur_outReal = other.cur_outReal;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Allocates nothing — neither handle state nor a return value.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so no state moves, <see cref="Value"/> still answers the previous value,
      /// and the stream stays usable — just carry on with the next bar.
      /// <see cref="OutRange"/> does advance: the bar happened, so it is counted,
      /// which keeps two handles fed the same series positionally aligned when only
      /// one of them rejects a bar. This is the one place the streaming tier is
      /// stricter than the batch API, which computes on whatever it is given: a
      /// handle retains its state, so a single non-finite bar would poison every
      /// later value it produces.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inReal )
      {
         if( !double.IsFinite(inReal) )
         {
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
            throw Core.StreamFailure("TSI", "update", RetCode.BadParam);
         }
         core.TsiStepImpl(this, inReal);
         if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It copies nothing: the frame runs against this handle, reading its buffers
      /// and holding what the step would commit in locals. The cost does not grow
      /// with the period, and <c>Peek</c> never allocates.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>What <see cref="Update"/> would return for this bar.</returns>
      public double Peek( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.StreamFailure("TSI", "peek", RetCode.BadParam);
         TsiStream sp = this;
         double mom = 0.0;
         double absMom = 0.0;
         double tsiValue = 0.0;
         double cur_outReal = 0.0;
         double emaFirstDen = sp.emaFirstDen;
         double emaFirstNum = sp.emaFirstNum;
         double emaSecondDen = sp.emaSecondDen;
         double emaSecondNum = sp.emaSecondNum;
         double prevClose = sp.prevClose;
         mom = inReal - prevClose;
         prevClose = inReal;
         absMom = Math.Abs(mom);
         emaFirstNum = Math.FusedMultiplyAdd(mom - emaFirstNum, sp.kFirst, emaFirstNum);
         emaFirstDen = Math.FusedMultiplyAdd(absMom - emaFirstDen, sp.kFirst, emaFirstDen);
         emaSecondNum = Math.FusedMultiplyAdd(emaFirstNum - emaSecondNum, sp.kSecond, emaSecondNum);
         emaSecondDen = Math.FusedMultiplyAdd(emaFirstDen - emaSecondDen, sp.kSecond, emaSecondDen);
         if( emaSecondDen > 0.0 ) {
            tsiValue = 100.0 * emaSecondNum / emaSecondDen;
         } else {
            tsiValue = 0.0;
         }
         cur_outReal = tsiValue;
         return cur_outReal;
      }

      /// <summary>Commit <c>n</c> closed bars and write their <c>n</c> values, in one call.</summary>
      /// <remarks>
      /// <para>Exactly <c>n</c> back-to-back <see cref="Update"/> calls, with one set of
      /// argument checks instead of <c>n</c>. The outputs must hold at least
      /// <c>n</c> values and must not overlap an input or each other.</para>
      /// <para><see cref="OutRange"/> counts what this call took in, which is what makes
      /// a rejection readable: a non-finite bar <c>k</c> throws
      /// <see cref="System.ArgumentException"/> exactly as <see cref="Update"/>
      /// would, with the bars before <c>k</c> committed and written, bar <c>k</c>
      /// and everything after it not written, and the count advanced by <c>k +
      /// 1</c> — the committed bars plus the rejected one, so the last bar counted
      /// is the one that failed.</para>
      /// </remarks>
      /// <param name="inReal">Closed bars for <c>inReal</c>, oldest first.</param>
      /// <param name="outReal">Receives one <c>outReal</c> value per bar committed.</param>
      public void UpdateAndFill( ReadOnlySpan<double> inReal, Span<double> outReal )
      {
         int barCount = inReal.Length;
         if( outReal.Length < barCount || outReal.Overlaps(inReal) ) throw Core.StreamFailure("TSI", "updateAndFill", RetCode.BadParam);
         for( int i = 0; i < barCount; i++ )
         {
            if( !double.IsFinite(inReal[i]) )
            {
               if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
               throw Core.StreamFailure("TSI", "updateAndFill", RetCode.BadParam);
            }
            core.TsiStepImpl(this, inReal[i]);
            outReal[i] = cur_outReal;
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         }
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public TsiStream Clone()
      {
         return new TsiStream(this);
      }
   }

   internal void TsiStepImpl( TsiStream sp, double inReal )
   {
      double mom = 0.0;
      double absMom = 0.0;
      double tsiValue = 0.0;
      mom = inReal - sp.prevClose;
      sp.prevClose = inReal;
      absMom = Math.Abs(mom);
      sp.emaFirstNum = Math.FusedMultiplyAdd(mom - sp.emaFirstNum, sp.kFirst, sp.emaFirstNum);
      sp.emaFirstDen = Math.FusedMultiplyAdd(absMom - sp.emaFirstDen, sp.kFirst, sp.emaFirstDen);
      sp.emaSecondNum = Math.FusedMultiplyAdd(sp.emaFirstNum - sp.emaSecondNum, sp.kSecond, sp.emaSecondNum);
      sp.emaSecondDen = Math.FusedMultiplyAdd(sp.emaFirstDen - sp.emaSecondDen, sp.kSecond, sp.emaSecondDen);
      if( sp.emaSecondDen > 0.0 ) {
         tsiValue = 100.0 * sp.emaSecondNum / sp.emaSecondDen;
      } else {
         tsiValue = 0.0;
      }
      sp.cur_outReal = tsiValue;
   }

   private RetCode TsiOpenImpl( TsiStream sp, ReadOnlySpan<double> inReal, int startIdx, int optInFirstPeriod, int optInSecondPeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double kFirst = 0;
      double kSecond = 0;
      double emaFirstNum = 0;
      double emaFirstDen = 0;
      double emaSecondNum = 0;
      double emaSecondDen = 0;
      double sumFirstNum = 0;
      double sumFirstDen = 0;
      double sumSecondNum = 0;
      double sumSecondDen = 0;
      double prevClose = 0;
      double mom = 0;
      double absMom = 0;
      double tsiValue = 0;
      int lookbackTotal = 0;
      int lookbackFirst = 0;
      int today = 0;
      int outIdx = 0;
      int nBar = 0;
      int nSecond = 0;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInFirstPeriod == int.MinValue ) {
         optInFirstPeriod = 25;
      } else if( optInFirstPeriod < 2 || optInFirstPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInSecondPeriod == int.MinValue ) {
         optInSecondPeriod = 13;
      } else if( optInSecondPeriod < 2 || optInSecondPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      lookbackTotal = TSI_Lookback(optInFirstPeriod, optInSecondPeriod);
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      outBegIdx = startIdx;
      /* Blau's double smoothing in one pass: the signed momentum and its
       * magnitude are carried through the same two EMA stages, then divided.
       *
       * Each stage seeds the way ema.c does -- a simple average of that stage's
       * first 'period' inputs -- so the result is bit-identical to TA_MOM(1)
       * followed by two TA_EMA calls on each chain. The stage boundary below is
       * the callee LOOKBACK, not (period-1), so that a warm
       * TA_SetUnstablePeriod(TA_FUNC_UNST_EMA) folds in: the second stage then
       * seeds from the values the first would have published. The seed sums
       * accumulate from 0.0 in production order and the recurrence is
       * ((x-prev)*k)+prev rather than the algebraically equal k*x+(1-k)*prev; do
       * not reorder or fuse them (0.0+x is not x for x=-0.0). That order IS the
       * bit-exactness contract against the composed reference.
       *
       * TA_GetCompatibility() is deliberately NOT consulted, for the reason
       * spelled out in efi.c: ema.c's TA_COMPATIBILITY_METASTOCK seeding arm is
       * preserved for the functions that already shipped with it and dropped from
       * new ones, and it is not reachable at all from the Rust, Java and C# APIs.
       *
       * prevClose is carried in a scalar rather than re-read from inReal[t-1]
       * because outReal may alias inReal: the slot holding close[t-1] may already
       * hold an output written a bar earlier.
       */
      kFirst = 2.0 / (double)(optInFirstPeriod + 1);
      kSecond = 2.0 / (double)(optInSecondPeriod + 1);
      lookbackFirst = EMA_Lookback(optInFirstPeriod);
      emaFirstNum = 0.0;
      emaFirstDen = 0.0;
      emaSecondNum = 0.0;
      emaSecondDen = 0.0;
      sumFirstNum = 0.0;
      sumFirstDen = 0.0;
      sumSecondNum = 0.0;
      sumSecondDen = 0.0;
      /* The first bar carrying a close-to-close change. */
      today = startIdx - lookbackTotal + 1;
      prevClose = inReal[today - 1];
      nBar = 0;
      /* Warm-up. Runs through startIdx inclusive: the last pass here completes
       * the second stage's seed, so it produces the first output.
       */
      while( today <= startIdx ) {
         mom = inReal[today] - prevClose;
         prevClose = inReal[today];
         absMom = Math.Abs(mom);
         /* Stage 1: the first EMA, over the raw momentum and its magnitude. */
         if( nBar < optInFirstPeriod ) {
            sumFirstNum = sumFirstNum + mom;
            sumFirstDen = sumFirstDen + absMom;
            if( nBar == optInFirstPeriod - 1 ) {
               emaFirstNum = sumFirstNum / optInFirstPeriod;
               emaFirstDen = sumFirstDen / optInFirstPeriod;
            }
         } else {
            emaFirstNum = Math.FusedMultiplyAdd(mom - emaFirstNum, kFirst, emaFirstNum);
            emaFirstDen = Math.FusedMultiplyAdd(absMom - emaFirstDen, kFirst, emaFirstDen);
         }
         /* Stage 2: the second EMA, over what stage 1 publishes.
          *
          * The stage counter is compared BEFORE it is subtracted, never after.
          * Writing this as `nSecond = nBar - lookbackFirst; if( nSecond >= 0 )`
          * is correct in C, where the counters are signed, and broken everywhere
          * else: the Rust backend renders them as usize, so the subtraction
          * underflows for the first lookbackFirst bars -- a panic in a debug
          * build and a wrap in release. It would also be invisible to the
          * cross-language gate, which runs release servers at unstable period 0,
          * where the branch the wrap wrongly takes happens to be a no-op because
          * both accumulators are still 0.0. smi.c states the same rule.
          */
         if( nBar >= lookbackFirst ) {
            nSecond = nBar - lookbackFirst;
            if( nSecond < optInSecondPeriod ) {
               sumSecondNum = sumSecondNum + emaFirstNum;
               sumSecondDen = sumSecondDen + emaFirstDen;
               if( nSecond == optInSecondPeriod - 1 ) {
                  emaSecondNum = sumSecondNum / optInSecondPeriod;
                  emaSecondDen = sumSecondDen / optInSecondPeriod;
               }
            } else {
               emaSecondNum = Math.FusedMultiplyAdd(emaFirstNum - emaSecondNum, kSecond, emaSecondNum);
               emaSecondDen = Math.FusedMultiplyAdd(emaFirstDen - emaSecondDen, kSecond, emaSecondDen);
            }
         }
         nBar = nBar + 1;
         today = today + 1;
      }
      /* The denominator is an EMA of an EMA of |momentum|: every term is
       * non-negative and every weight positive, so it is zero only when every
       * change that reached it was exactly zero -- 0/0, since the numerator is
       * zero with it, reported as the neutral 0.0 by the CCI (#7) and IMI (#112)
       * convention. Tested exactly rather than against a fixed band: a price
       * change carries the quote unit, and TA_IS_ZERO zeroes the oscillator for
       * any instrument quoted below it (issue #253).
       */
      if( emaSecondDen > 0.0 ) {
         tsiValue = 100.0 * emaSecondNum / emaSecondDen;
      } else {
         tsiValue = 0.0;
      }
      outReal[0 * outStride] = tsiValue;
      outIdx = 1;
      /* Stable zone. Both stages are a pure recursion from here on. */
      while( today <= endIdx ) {
         mom = inReal[today] - prevClose;
         prevClose = inReal[today];
         absMom = Math.Abs(mom);
         emaFirstNum = Math.FusedMultiplyAdd(mom - emaFirstNum, kFirst, emaFirstNum);
         emaFirstDen = Math.FusedMultiplyAdd(absMom - emaFirstDen, kFirst, emaFirstDen);
         emaSecondNum = Math.FusedMultiplyAdd(emaFirstNum - emaSecondNum, kSecond, emaSecondNum);
         emaSecondDen = Math.FusedMultiplyAdd(emaFirstDen - emaSecondDen, kSecond, emaSecondDen);
         if( emaSecondDen > 0.0 ) {
            tsiValue = 100.0 * emaSecondNum / emaSecondDen;
         } else {
            tsiValue = 0.0;
         }
         outReal[outIdx * outStride] = tsiValue;
         outIdx = outIdx + 1;
         today = today + 1;
      }
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      sp.optInFirstPeriod = optInFirstPeriod;
      sp.optInSecondPeriod = optInSecondPeriod;
      sp.kFirst = kFirst;
      sp.kSecond = kSecond;
      sp.emaFirstNum = emaFirstNum;
      sp.emaFirstDen = emaFirstDen;
      sp.emaSecondNum = emaSecondNum;
      sp.emaSecondDen = emaSecondDen;
      sp.prevClose = prevClose;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* TsiOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal TsiStream TsiOpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, int optInFirstPeriod, int optInSecondPeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      TsiStream sp = new TsiStream(this);
      RetCode retCode = TsiOpenImpl(sp, inReal, startIdx, optInFirstPeriod, optInSecondPeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("TSI", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind TsiOpen (composition seam). */
   internal TsiStream TsiOpenInternal( ReadOnlySpan<double> inReal, int startIdx, int optInFirstPeriod, int optInSecondPeriod )
   {
      TsiStream sp = new TsiStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = TsiOpenImpl(sp, inReal, startIdx, optInFirstPeriod, optInSecondPeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("TSI", "open", retCode);
   }

   /// <summary>Open a live <c>TSI</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="TsiStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>TSI</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>TSI_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>TsiOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">Source price/value series, canonically the close. The warm-up history,
   /// oldest bar first.</param>
   /// <param name="optInFirstPeriod">As in the batch call; see <see cref="TSI_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSecondPeriod">As in the batch call; see <see cref="TSI_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>TSI_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public TsiStream TsiOpen( ReadOnlySpan<double> inReal, int optInFirstPeriod, int optInSecondPeriod )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "TSI open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "TSI open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      return TsiOpenInternal(inReal, 0, optInFirstPeriod, optInSecondPeriod);
   }

   /// <summary><c>TsiOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>TSI</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - TSI_Lookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="TsiStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">Source price/value series, canonically the close. The warm-up history,
   /// oldest bar first.</param>
   /// <param name="optInFirstPeriod">As in the batch call; see <see cref="TSI_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSecondPeriod">As in the batch call; see <see cref="TSI_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">True Strength Index, -100 to +100. Must hold at least <c>historyLen -
   /// TSI_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>TSI_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public TsiStream TsiOpenAndFill( ReadOnlySpan<double> inReal, int optInFirstPeriod, int optInSecondPeriod, Span<double> outReal )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "TSI openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
