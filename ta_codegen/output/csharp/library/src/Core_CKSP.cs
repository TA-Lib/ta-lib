      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so nothing moves — <see cref="OutRange"/> included — and
      /// <see cref="Value"/> still answers the previous value. Re-feed the bar when
      /// a corrected value arrives, or call <see cref="Advance"/> to count it and
      /// carry on; two handles on one feed drift a bar apart if neither happens.
      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, which no re-feed clears: the
      /// handle has run out of index domain and only a shorter history can start a
      /// new one.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>The value at the bar just committed.</returns>
      public CkspValue Update( double inHigh, double inLow, double inClose )
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("CKSP", "update", RetCode.OutOfRangeEndIndex);
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) ) throw Core.NonFiniteBar("CKSP", "update", !double.IsFinite(inHigh) ? nameof(inHigh) : !double.IsFinite(inLow) ? nameof(inLow) : nameof(inClose));
         core.CkspStepImpl(this, inHigh, inLow, inClose);
         outRangeCount++;
         return new CkspValue(cur_outHighStop, cur_outLowStop);
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.IndexMax"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public CkspValue Peek( double inHigh, double inLow, double inClose )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) ) throw Core.NonFiniteBar("CKSP", "peek", !double.IsFinite(inHigh) ? nameof(inHigh) : !double.IsFinite(inLow) ? nameof(inLow) : nameof(inClose));
         CkspStream sp = this;
         int jh = 0;
         int jl = 0;
         int kh = 0;
         int kl = 0;
         double val2 = 0.0;
         double val3 = 0.0;
         double greatest = 0.0;
         double tempCY = 0.0;
         double tempLT = 0.0;
         double tempHT = 0.0;
         double hh = 0.0;
         double ll = 0.0;
         double best = 0.0;
         double cur_outHighStop = 0.0;
         double cur_outLowStop = 0.0;
         double prevATR = sp.prevATR;
         int pkSlot0 = -1;
         double pkVal0 = 0.0;
         int pkSlot1 = -1;
         double pkVal1 = 0.0;
         int pkSlot2 = -1;
         double pkVal2 = 0.0;
         int pkSlot3 = -1;
         double pkVal3 = 0.0;
         tempLT = inLow;
         tempHT = inHigh;
         tempCY = sp.lag1_inClose;
         greatest = tempHT - tempLT;
         val2 = Math.Abs(tempCY - tempHT);
         greatest = MaxGt(val2, greatest);
         val3 = Math.Abs(tempCY - tempLT);
         greatest = MaxGt(val3, greatest);
         prevATR = Math.FusedMultiplyAdd(sp.wBeta, prevATR, sp.wAlpha * greatest);
         pkSlot0 = sp.hRing_Idx;
         pkVal0 = tempHT;
         pkSlot1 = sp.lRing_Idx;
         pkVal1 = tempLT;
         /* The extremes of the p bars ending here. The newest sits at the ring's
          * own index, so the oldest is the slot after it and the walk is two
          * straight runs.
          */
         hh = (sp.hRing_Idx != pkSlot0) ? sp.cb_hRing[sp.hRing_Idx] : pkVal0;
         for( jh = sp.hRing_Idx + 1; jh < sp.optInTimePeriod; jh += 1 ) {
            best = sp.cb_hRing[jh];
            hh = MaxGt(best, hh);
         }
         for( jh = 0; jh < sp.hRing_Idx; jh += 1 ) {
            best = sp.cb_hRing[jh];
            hh = MaxGt(best, hh);
         }
         ll = (sp.lRing_Idx != pkSlot1) ? sp.cb_lRing[sp.lRing_Idx] : pkVal1;
         for( jl = sp.lRing_Idx + 1; jl < sp.optInTimePeriod; jl += 1 ) {
            best = sp.cb_lRing[jl];
            ll = MinLt(best, ll);
         }
         for( jl = 0; jl < sp.lRing_Idx; jl += 1 ) {
            best = sp.cb_lRing[jl];
            ll = MinLt(best, ll);
         }
         pkSlot2 = sp.fhRing_Idx;
         pkVal2 = hh - sp.optInMultiplier * prevATR;
         pkSlot3 = sp.flRing_Idx;
         pkVal3 = ll + sp.optInMultiplier * prevATR;
         /* The second stage, over the q first-stage bars ending here. At q = 1
          * both runs are empty and the value is the bar's own, which is the
          * Chandelier Exit form.
          */
         hh = (sp.fhRing_Idx != pkSlot2) ? sp.cb_fhRing[sp.fhRing_Idx] : pkVal2;
         for( kh = sp.fhRing_Idx + 1; kh < sp.optInStopPeriod; kh += 1 ) {
            best = sp.cb_fhRing[kh];
            hh = MaxGt(best, hh);
         }
         for( kh = 0; kh < sp.fhRing_Idx; kh += 1 ) {
            best = sp.cb_fhRing[kh];
            hh = MaxGt(best, hh);
         }
         ll = (sp.flRing_Idx != pkSlot3) ? sp.cb_flRing[sp.flRing_Idx] : pkVal3;
         for( kl = sp.flRing_Idx + 1; kl < sp.optInStopPeriod; kl += 1 ) {
            best = sp.cb_flRing[kl];
            ll = MinLt(best, ll);
         }
         for( kl = 0; kl < sp.flRing_Idx; kl += 1 ) {
            best = sp.cb_flRing[kl];
            ll = MinLt(best, ll);
         }
         cur_outHighStop = hh;
         cur_outLowStop = ll;
         return new CkspValue(cur_outHighStop, cur_outLowStop);
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public CkspValue Value => new CkspValue(cur_outHighStop, cur_outLowStop);

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public CkspStream Clone()
      {
         return new CkspStream(this);
      }
   }

   private void CkspStepImpl( CkspStream sp, double inHigh, double inLow, double inClose )
   {
      int jh = 0;
      int jl = 0;
      int kh = 0;
      int kl = 0;
      double val2 = 0.0;
      double val3 = 0.0;
      double greatest = 0.0;
      double tempCY = 0.0;
      double tempLT = 0.0;
      double tempHT = 0.0;
      double hh = 0.0;
      double ll = 0.0;
      double best = 0.0;
      tempLT = inLow;
      tempHT = inHigh;
      tempCY = sp.lag1_inClose;
      greatest = tempHT - tempLT;
      val2 = Math.Abs(tempCY - tempHT);
      greatest = MaxGt(val2, greatest);
      val3 = Math.Abs(tempCY - tempLT);
      greatest = MaxGt(val3, greatest);
      sp.prevATR = Math.FusedMultiplyAdd(sp.wBeta, sp.prevATR, sp.wAlpha * greatest);
      sp.cb_hRing[sp.hRing_Idx] = tempHT;
      sp.cb_lRing[sp.lRing_Idx] = tempLT;
      /* The extremes of the p bars ending here. The newest sits at the ring's
       * own index, so the oldest is the slot after it and the walk is two
       * straight runs.
       */
      hh = sp.cb_hRing[sp.hRing_Idx];
      for( jh = sp.hRing_Idx + 1; jh < sp.optInTimePeriod; jh += 1 ) {
         best = sp.cb_hRing[jh];
         hh = MaxGt(best, hh);
      }
      for( jh = 0; jh < sp.hRing_Idx; jh += 1 ) {
         best = sp.cb_hRing[jh];
         hh = MaxGt(best, hh);
      }
      ll = sp.cb_lRing[sp.lRing_Idx];
      for( jl = sp.lRing_Idx + 1; jl < sp.optInTimePeriod; jl += 1 ) {
         best = sp.cb_lRing[jl];
         ll = MinLt(best, ll);
      }
      for( jl = 0; jl < sp.lRing_Idx; jl += 1 ) {
         best = sp.cb_lRing[jl];
         ll = MinLt(best, ll);
      }
      sp.cb_fhRing[sp.fhRing_Idx] = hh - sp.optInMultiplier * sp.prevATR;
      sp.cb_flRing[sp.flRing_Idx] = ll + sp.optInMultiplier * sp.prevATR;
      /* The second stage, over the q first-stage bars ending here. At q = 1
       * both runs are empty and the value is the bar's own, which is the
       * Chandelier Exit form.
       */
      hh = sp.cb_fhRing[sp.fhRing_Idx];
      for( kh = sp.fhRing_Idx + 1; kh < sp.optInStopPeriod; kh += 1 ) {
         best = sp.cb_fhRing[kh];
         hh = MaxGt(best, hh);
      }
      for( kh = 0; kh < sp.fhRing_Idx; kh += 1 ) {
         best = sp.cb_fhRing[kh];
         hh = MaxGt(best, hh);
      }
      ll = sp.cb_flRing[sp.flRing_Idx];
      for( kl = sp.flRing_Idx + 1; kl < sp.optInStopPeriod; kl += 1 ) {
         best = sp.cb_flRing[kl];
         ll = MinLt(best, ll);
      }
      for( kl = 0; kl < sp.flRing_Idx; kl += 1 ) {
         best = sp.cb_flRing[kl];
         ll = MinLt(best, ll);
      }
      sp.cur_outHighStop = hh;
      sp.cur_outLowStop = ll;
      sp.hRing_Idx = sp.hRing_Idx + 1;
      if( sp.hRing_Idx > sp.maxIdx_hRing ) {
         sp.hRing_Idx = 0;
      }
      sp.lRing_Idx = sp.lRing_Idx + 1;
      if( sp.lRing_Idx > sp.maxIdx_lRing ) {
         sp.lRing_Idx = 0;
      }
      sp.fhRing_Idx = sp.fhRing_Idx + 1;
      if( sp.fhRing_Idx > sp.maxIdx_fhRing ) {
         sp.fhRing_Idx = 0;
      }
      sp.flRing_Idx = sp.flRing_Idx + 1;
      if( sp.flRing_Idx > sp.maxIdx_flRing ) {
         sp.flRing_Idx = 0;
      }
      sp.lag1_inClose = inClose;
   }

   private RetCode CkspOpenImpl( CkspStream sp, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, double optInMultiplier, int optInStopPeriod, out int outBegIdx, out int outNBElement, Span<double> outHighStop, Span<double> outLowStop, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      int i = 0;
      int jh = 0;
      int jl = 0;
      int kh = 0;
      int kl = 0;
      int today = 0;
      int outIdx = 0;
      int lookbackTotal = 0;
      int stageOneIdx = 0;
      double prevATR = 0;
      double periodTotal = 0;
      double wAlpha = 0;
      double wBeta = 0;
      double val2 = 0;
      double val3 = 0;
      double greatest = 0;
      double tempCY = 0;
      double tempLT = 0;
      double tempHT = 0;
      double hh = 0;
      double ll = 0;
      double best = 0;
      double[] hRing = [];
      int hRing_Idx = 0;
      int maxIdx_hRing = (50)-1;
      double[] lRing = [];
      int lRing_Idx = 0;
      int maxIdx_lRing = (50)-1;
      double[] fhRing = [];
      int fhRing_Idx = 0;
      int maxIdx_fhRing = (50)-1;
      double[] flRing = [];
      int flRing_Idx = 0;
      int maxIdx_flRing = (50)-1;
      int historyLen = inHigh.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > IndexMax + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inLow.Length != inHigh.Length || inClose.Length != inHigh.Length ) {
         return RetCode.BadParam;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 10;
      } else if( optInTimePeriod < 2 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInMultiplier == RealDefault ) {
         optInMultiplier = 1e0;
      } else if( !(optInMultiplier >= 0e0 && optInMultiplier <= RealMax) ) {
         return RetCode.BadParam;
      }
      if( optInStopPeriod == int.MinValue ) {
         optInStopPeriod = 9;
      } else if( optInStopPeriod < 1 || optInStopPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      /* Four windows, all carried as rings and all walked oldest-first, the
       * cci.c:112-117 shape: an index that wrapped would be one more thing the
       * stream derivation has to prove, and the walk is the same values either
       * way.
       */
      outBegIdx = 0;
      outNBElement = 0;
      lookbackTotal = CkspLookback(optInTimePeriod, optInMultiplier, optInStopPeriod);
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      if( startIdx > endIdx ) {
         return RetCode.InsufficientHistory ;
      }
      if( optInTimePeriod < 1 ) return RetCode.InternalError;
      hRing = new double[optInTimePeriod];
      maxIdx_hRing = (optInTimePeriod)-1;
      hRing_Idx = 0;
      if( optInTimePeriod < 1 ) return RetCode.InternalError;
      lRing = new double[optInTimePeriod];
      maxIdx_lRing = (optInTimePeriod)-1;
      lRing_Idx = 0;
      if( optInStopPeriod < 1 ) return RetCode.InternalError;
      fhRing = new double[optInStopPeriod];
      maxIdx_fhRing = (optInStopPeriod)-1;
      fhRing_Idx = 0;
      if( optInStopPeriod < 1 ) return RetCode.InternalError;
      flRing = new double[optInStopPeriod];
      maxIdx_flRing = (optInStopPeriod)-1;
      flRing_Idx = 0;
      /* The first stage is entered q-1 bars before the first output, because the
       * second stage's window reaches that far back. Each leg is anchored on its
       * own bar rather than on the caller's startIdx (the kc.c:73-77 rule): the
       * Average True Range is seeded as if TA_ATR had been entered here, and the
       * extremes are the p-windows ending on these same bars.
       */
      stageOneIdx = startIdx - (optInStopPeriod - 1);
      /* The Average True Range, carried inline rather than taken from a call: the
       * two stages advance together one bar at a time and a whole-range buffer
       * between them would not stream (supertrend.c:47-50).
       *
       * The arithmetic order is the bit-exactness contract with TA_ATR and is not
       * to be reordered: the range first, then the two previous-close distances in
       * that order; the seed summed from 0.0 over the first optInTimePeriod True
       * Ranges and divided once; wBeta rounded first and wAlpha derived from it.
       */
      wBeta = (double)(optInTimePeriod - 1) / (double)optInTimePeriod;
      wAlpha = 1.0 - wBeta;
      today = stageOneIdx - AtrLookback(optInTimePeriod) + 1;
      periodTotal = 0.0;
      i = optInTimePeriod;
      while( i-- > 0 ) {
         tempLT = inLow[today];
         tempHT = inHigh[today];
         tempCY = inClose[today - 1];
         greatest = tempHT - tempLT;
         val2 = Math.Abs(tempCY - tempHT);
         greatest = MaxGt(val2, greatest);
         val3 = Math.Abs(tempCY - tempLT);
         greatest = MaxGt(val3, greatest);
         periodTotal += greatest;
         today += 1;
      }
      prevATR = periodTotal / optInTimePeriod;
      /* Skip the Average True Range's unstable period. The count comes from the
       * lookback rather than from the setting, so the two cannot disagree.
       */
      i = AtrLookback(optInTimePeriod) - optInTimePeriod;
      while( i != 0 ) {
         tempLT = inLow[today];
         tempHT = inHigh[today];
         tempCY = inClose[today - 1];
         greatest = tempHT - tempLT;
         val2 = Math.Abs(tempCY - tempHT);
         greatest = MaxGt(val2, greatest);
         val3 = Math.Abs(tempCY - tempLT);
         greatest = MaxGt(val3, greatest);
         prevATR = Math.FusedMultiplyAdd(wBeta, prevATR, wAlpha * greatest);
         today += 1;
         i -= 1;
      }
      /* `today` is now stageOneIdx and prevATR is the Average True Range of the
       * bar before it. Seed the price rings with the p-1 bars the first extreme
       * window needs behind that bar.
       */
      i = stageOneIdx - optInTimePeriod + 1;
      while( i < stageOneIdx ) {
         hRing[hRing_Idx] = inHigh[i];
         lRing[lRing_Idx] = inLow[i];
         i += 1;
         hRing_Idx++;
         if( hRing_Idx > maxIdx_hRing ) { hRing_Idx = 0; }
         lRing_Idx++;
         if( lRing_Idx > maxIdx_lRing ) { lRing_Idx = 0; }
      }
      /* The prologue leaves prevATR as the Average True Range of stageOneIdx and
       * `today` one past it, so that bar is finished here rather than in the loop:
       * entering the loop with it would apply a second Wilder update and shift the
       * whole series one bar early. supertrend.c takes the same step for the same
       * reason.
       */
      today = stageOneIdx;
      hRing[hRing_Idx] = inHigh[today];
      lRing[lRing_Idx] = inLow[today];
      hh = hRing[hRing_Idx];
      for( jh = hRing_Idx + 1; jh < optInTimePeriod; jh += 1 ) {
         best = hRing[jh];
         hh = MaxGt(best, hh);
      }
      for( jh = 0; jh < hRing_Idx; jh += 1 ) {
         best = hRing[jh];
         hh = MaxGt(best, hh);
      }
      ll = lRing[lRing_Idx];
      for( jl = lRing_Idx + 1; jl < optInTimePeriod; jl += 1 ) {
         best = lRing[jl];
         ll = MinLt(best, ll);
      }
      for( jl = 0; jl < lRing_Idx; jl += 1 ) {
         best = lRing[jl];
         ll = MinLt(best, ll);
      }
      fhRing[fhRing_Idx] = hh - optInMultiplier * prevATR;
      flRing[flRing_Idx] = ll + optInMultiplier * prevATR;
      outIdx = 0;
      if( today >= startIdx ) {
         outHighStop[outIdx * outStride] = fhRing[fhRing_Idx];
         outLowStop[outIdx * outStride] = flRing[flRing_Idx];
         outIdx = outIdx + 1;
      }
      today += 1;
      hRing_Idx++;
      if( hRing_Idx > maxIdx_hRing ) { hRing_Idx = 0; }
      lRing_Idx++;
      if( lRing_Idx > maxIdx_lRing ) { lRing_Idx = 0; }
      fhRing_Idx++;
      if( fhRing_Idx > maxIdx_fhRing ) { fhRing_Idx = 0; }
      flRing_Idx++;
      if( flRing_Idx > maxIdx_flRing ) { flRing_Idx = 0; }
      while( today <= endIdx ) {
         tempLT = inLow[today];
         tempHT = inHigh[today];
         tempCY = inClose[today - 1];
         greatest = tempHT - tempLT;
         val2 = Math.Abs(tempCY - tempHT);
         greatest = MaxGt(val2, greatest);
         val3 = Math.Abs(tempCY - tempLT);
         greatest = MaxGt(val3, greatest);
         prevATR = Math.FusedMultiplyAdd(wBeta, prevATR, wAlpha * greatest);
         hRing[hRing_Idx] = tempHT;
         lRing[lRing_Idx] = tempLT;
         /* The extremes of the p bars ending here. The newest sits at the ring's
          * own index, so the oldest is the slot after it and the walk is two
          * straight runs.
          */
         hh = hRing[hRing_Idx];
         for( jh = hRing_Idx + 1; jh < optInTimePeriod; jh += 1 ) {
            best = hRing[jh];
            hh = MaxGt(best, hh);
         }
         for( jh = 0; jh < hRing_Idx; jh += 1 ) {
            best = hRing[jh];
            hh = MaxGt(best, hh);
         }
         ll = lRing[lRing_Idx];
         for( jl = lRing_Idx + 1; jl < optInTimePeriod; jl += 1 ) {
            best = lRing[jl];
            ll = MinLt(best, ll);
         }
         for( jl = 0; jl < lRing_Idx; jl += 1 ) {
            best = lRing[jl];
            ll = MinLt(best, ll);
         }
         fhRing[fhRing_Idx] = hh - optInMultiplier * prevATR;
         flRing[flRing_Idx] = ll + optInMultiplier * prevATR;
         if( today >= startIdx ) {
            /* The second stage, over the q first-stage bars ending here. At q = 1
             * both runs are empty and the value is the bar's own, which is the
             * Chandelier Exit form.
             */
            hh = fhRing[fhRing_Idx];
            for( kh = fhRing_Idx + 1; kh < optInStopPeriod; kh += 1 ) {
               best = fhRing[kh];
               hh = MaxGt(best, hh);
            }
            for( kh = 0; kh < fhRing_Idx; kh += 1 ) {
               best = fhRing[kh];
               hh = MaxGt(best, hh);
            }
            ll = flRing[flRing_Idx];
            for( kl = flRing_Idx + 1; kl < optInStopPeriod; kl += 1 ) {
               best = flRing[kl];
               ll = MinLt(best, ll);
            }
            for( kl = 0; kl < flRing_Idx; kl += 1 ) {
               best = flRing[kl];
               ll = MinLt(best, ll);
            }
            outHighStop[outIdx * outStride] = hh;
            outLowStop[outIdx * outStride] = ll;
            outIdx = outIdx + 1;
         }
         today += 1;
         hRing_Idx++;
         if( hRing_Idx > maxIdx_hRing ) { hRing_Idx = 0; }
         lRing_Idx++;
         if( lRing_Idx > maxIdx_lRing ) { lRing_Idx = 0; }
         fhRing_Idx++;
         if( fhRing_Idx > maxIdx_fhRing ) { fhRing_Idx = 0; }
         flRing_Idx++;
         if( flRing_Idx > maxIdx_flRing ) { flRing_Idx = 0; }
      }
      outNBElement = outIdx;
      outBegIdx = startIdx;
      /* Capture the live batch state into the handle. */
      int capCb_hRing = maxIdx_hRing + 1;
      if( capCb_hRing > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      int capCb_lRing = maxIdx_lRing + 1;
      if( capCb_lRing > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      int capCb_fhRing = maxIdx_fhRing + 1;
      if( capCb_fhRing > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      int capCb_flRing = maxIdx_flRing + 1;
      if( capCb_flRing > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      sp.optInTimePeriod = optInTimePeriod;
      sp.optInMultiplier = optInMultiplier;
      sp.optInStopPeriod = optInStopPeriod;
      sp.prevATR = prevATR;
      sp.wAlpha = wAlpha;
      sp.wBeta = wBeta;
      sp.hRing_Idx = hRing_Idx;
      sp.lRing_Idx = lRing_Idx;
      sp.fhRing_Idx = fhRing_Idx;
      sp.flRing_Idx = flRing_Idx;
      sp.maxIdx_hRing = maxIdx_hRing;
      sp.maxIdx_lRing = maxIdx_lRing;
      sp.maxIdx_fhRing = maxIdx_fhRing;
      sp.maxIdx_flRing = maxIdx_flRing;
      sp.lag1_inClose = inClose[historyLen - 1];
      sp.cbSize_hRing = capCb_hRing;
      sp.cb_hRing = hRing;
      sp.cbSize_lRing = capCb_lRing;
      sp.cb_lRing = lRing;
      sp.cbSize_fhRing = capCb_fhRing;
      sp.cb_fhRing = fhRing;
      sp.cbSize_flRing = capCb_flRing;
      sp.cb_flRing = flRing;
      sp.cur_outHighStop = outHighStop[(outNBElement - 1) * outStride];
      sp.cur_outLowStop = outLowStop[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* CkspOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal CkspStream CkspOpenAndFillInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, double optInMultiplier, int optInStopPeriod, out int outBegIdx, out int outNBElement, Span<double> outHighStop, Span<double> outLowStop )
   {
      CkspStream sp = new CkspStream(this);
      RetCode retCode = CkspOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInTimePeriod, optInMultiplier, optInStopPeriod, out outBegIdx, out outNBElement, outHighStop, outLowStop, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("CKSP", "openAndFill", nameof(inHigh), inHigh.Length, startIdx, CkspLookback(optInTimePeriod, optInMultiplier, optInStopPeriod));
      }
      throw StreamFailure("CKSP", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind CkspOpen (composition seam). */
   internal CkspStream CkspOpenInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, double optInMultiplier, int optInStopPeriod )
   {
      CkspStream sp = new CkspStream(this);
      double[] sink_outHighStop = new double[1];
      double[] sink_outLowStop = new double[1];
      RetCode retCode = CkspOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInTimePeriod, optInMultiplier, optInStopPeriod, out int outBegIdx, out int outNBElement, sink_outHighStop, sink_outLowStop, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("CKSP", "open", nameof(inHigh), inHigh.Length, startIdx, CkspLookback(optInTimePeriod, optInMultiplier, optInStopPeriod));
      }
      throw StreamFailure("CKSP", "open", retCode);
   }

   /// <summary>Open a live <c>CKSP</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="CkspStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>CKSP</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>CkspLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>CkspOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar, read only by the True Range. The warm-up history,
   /// oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="CkspLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInMultiplier">As in the batch call; see <see cref="CkspLookback"/> for its default and
   /// range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <param name="optInStopPeriod">As in the batch call; see <see cref="CkspLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>CkspLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules S1 and S2).</exception>
   public CkspStream CkspOpen( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInTimePeriod, double optInMultiplier, int optInStopPeriod )
   {
      if( inHigh.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "CKSP open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "CKSP open: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TALibArgumentException("CKSP open: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TALibArgumentException("CKSP open: inClose is empty", nameof(inClose), RetCode.BadParam);
      RequireHistoryLength("CKSP", "open", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("CKSP", "open", "inClose", inClose.Length, inHigh.Length);
      return CkspOpenInternal(inHigh, inLow, inClose, 0, optInTimePeriod, optInMultiplier, optInStopPeriod);
   }

   /// <summary><c>CkspOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>CKSP</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - CkspLookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="CkspStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar, read only by the True Range. The warm-up history,
   /// oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="CkspLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInMultiplier">As in the batch call; see <see cref="CkspLookback"/> for its default and
   /// range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <param name="optInStopPeriod">As in the batch call; see <see cref="CkspLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outHighStop">Trailing stop below price, the high side. Must hold at least <c>historyLen
   /// - CkspLookback(...)</c> values.</param>
   /// <param name="outLowStop">Trailing stop above price, the low side. Must hold at least <c>historyLen
   /// - CkspLookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>CkspLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules S1 and S2).</exception>
   public CkspStream CkspOpenAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInTimePeriod, double optInMultiplier, int optInStopPeriod, Span<double> outHighStop, Span<double> outLowStop )
   {
      if( inHigh.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "CKSP openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "CKSP openAndFill: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TALibArgumentException("CKSP openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TALibArgumentException("CKSP openAndFill: inClose is empty", nameof(inClose), RetCode.BadParam);
      int guardOutLen = OpenFillCount("CKSP", "openAndFill", inHigh.Length, CkspLookback(optInTimePeriod, optInMultiplier, optInStopPeriod));
      RequireHistoryLength("CKSP", "openAndFill", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("CKSP", "openAndFill", "inClose", inClose.Length, inHigh.Length);
      RequireFillLength("CKSP", "openAndFill", "outHighStop", outHighStop.Length, guardOutLen);
      RequireFillLength("CKSP", "openAndFill", "outLowStop", outLowStop.Length, guardOutLen);
      if( outHighStop.Overlaps(inHigh) || outHighStop.Overlaps(inLow) || outHighStop.Overlaps(inClose) || outLowStop.Overlaps(inHigh) || outLowStop.Overlaps(inLow) || outLowStop.Overlaps(inClose) || outHighStop.Overlaps(outLowStop) ) {
         throw StreamFailure("CKSP", "openAndFill", RetCode.BadParam);
      }
      return CkspOpenAndFillInternal(inHigh, inLow, inClose, 0, optInTimePeriod, optInMultiplier, optInStopPeriod, out _, out _, outHighStop, outLowStop);
   }
