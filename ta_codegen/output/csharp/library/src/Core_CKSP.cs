      prevATR = periodTotal / optInTimePeriod;
      i = lookbackTotal - lastQ - optInTimePeriod;
      while( i != 0 ) {
         tempLT = (double)inLow[today];
         tempHT = (double)inHigh[today];
         tempCY = (double)inClose[today - 1];
         greatest = tempHT - tempLT;
         val2 = Math.Abs(tempCY - tempHT);
         greatest = MaxGt(val2, greatest);
         val3 = Math.Abs(tempCY - tempLT);
         greatest = MaxGt(val3, greatest);
         prevATR = Math.FusedMultiplyAdd(wBeta, prevATR, wAlpha * greatest);
         today += 1;
         i -= 1;
      }
      highest = (double)inHigh[today - 1];
      lowest = (double)inLow[today - 1];
      hhBuf[lastP] = highest;
      llBuf[lastP] = lowest;
      ip = lastP;
      while( ip > 0 ) {
         ip -= 1;
         tempHT = (double)inHigh[today - 1 - lastP + ip];
         tempLT = (double)inLow[today - 1 - lastP + ip];
         highest = MaxGt(tempHT, highest);
         lowest = MinLt(tempLT, lowest);
         hhBuf[ip] = highest;
         llBuf[ip] = lowest;
      }
      hhPre = highest;
      llPre = lowest;
      band = optInMultiplier * prevATR;
      highStop = highest - band;
      lowStop = lowest + band;
      hsPre = highStop;
      lsPre = lowStop;
      hsBuf[hsBuf_Idx] = highStop;
      lsBuf[hsBuf_Idx] = lowStop;
      hsBuf_Idx++;
      if( hsBuf_Idx > maxIdx_hsBuf ) { hsBuf_Idx = 0; }
      while( today <= startIdx ) {
         tempLT = (double)inLow[today];
         tempHT = (double)inHigh[today];
         tempCY = (double)inClose[today - 1];
         greatest = tempHT - tempLT;
         val2 = Math.Abs(tempCY - tempHT);
         greatest = MaxGt(val2, greatest);
         val3 = Math.Abs(tempCY - tempLT);
         greatest = MaxGt(val3, greatest);
         prevATR = Math.FusedMultiplyAdd(wBeta, prevATR, wAlpha * greatest);
         highest = hhPre;
         lowest = llPre;
         highest = MaxGt(tempHT, highest);
         lowest = MinLt(tempLT, lowest);
         if( hhBuf_Idx == 0 ) {
            highest = tempHT;
            lowest = tempLT;
         }
         hhPre = highest;
         llPre = lowest;
         if( hhBuf_Idx < lastP ) {
            tempReal = hhBuf[hhBuf_Idx + 1];
            highest = MaxGt(tempReal, highest);
            tempReal = llBuf[hhBuf_Idx + 1];
            lowest = MinLt(tempReal, lowest);
         }
         hhBuf[hhBuf_Idx] = tempHT;
         llBuf[hhBuf_Idx] = tempLT;
         hhBuf_Idx++;
         if( hhBuf_Idx > maxIdx_hhBuf ) { hhBuf_Idx = 0; }
         if( hhBuf_Idx == 0 ) {
            sufHi = hhBuf[lastP];
            sufLo = llBuf[lastP];
            ip = lastP;
            while( ip > 1 ) {
               ip -= 1;
               tempReal = hhBuf[ip];
               sufHi = MaxGt(tempReal, sufHi);
               hhBuf[ip] = sufHi;
               tempReal = llBuf[ip];
               sufLo = MinLt(tempReal, sufLo);
               llBuf[ip] = sufLo;
            }
         }
         band = optInMultiplier * prevATR;
         highStop = highest - band;
         lowStop = lowest + band;
         hsPre = MaxGt(highStop, hsPre);
         lsPre = MinLt(lowStop, lsPre);
         hsBuf[hsBuf_Idx] = highStop;
         lsBuf[hsBuf_Idx] = lowStop;
         hsBuf_Idx++;
         if( hsBuf_Idx > maxIdx_hsBuf ) { hsBuf_Idx = 0; }
         today += 1;
      }
      sufHi = hsBuf[lastQ];
      sufLo = lsBuf[lastQ];
      iq = lastQ;
      while( iq > 1 ) {
         iq -= 1;
         tempReal = hsBuf[iq];
         sufHi = MaxGt(tempReal, sufHi);
         hsBuf[iq] = sufHi;
         tempReal = lsBuf[iq];
         sufLo = MinLt(tempReal, sufLo);
         lsBuf[iq] = sufLo;
      }
      outHighStop[0] = hsPre;
      outLowStop[0] = lsPre;
      outIdx = 1;
      while( today <= endIdx ) {
         tempLT = (double)inLow[today];
         tempHT = (double)inHigh[today];
         tempCY = (double)inClose[today - 1];
         greatest = tempHT - tempLT;
         val2 = Math.Abs(tempCY - tempHT);
         greatest = MaxGt(val2, greatest);
         val3 = Math.Abs(tempCY - tempLT);
         greatest = MaxGt(val3, greatest);
         prevATR = Math.FusedMultiplyAdd(wBeta, prevATR, wAlpha * greatest);
         highest = hhPre;
         lowest = llPre;
         highest = MaxGt(tempHT, highest);
         lowest = MinLt(tempLT, lowest);
         if( hhBuf_Idx == 0 ) {
            highest = tempHT;
            lowest = tempLT;
         }
         hhPre = highest;
         llPre = lowest;
         if( hhBuf_Idx < lastP ) {
            tempReal = hhBuf[hhBuf_Idx + 1];
            highest = MaxGt(tempReal, highest);
            tempReal = llBuf[hhBuf_Idx + 1];
            lowest = MinLt(tempReal, lowest);
         }
         hhBuf[hhBuf_Idx] = tempHT;
         llBuf[hhBuf_Idx] = tempLT;
         hhBuf_Idx++;
         if( hhBuf_Idx > maxIdx_hhBuf ) { hhBuf_Idx = 0; }
         band = optInMultiplier * prevATR;
         highStop = highest - band;
         lowStop = lowest + band;
         highest = hsPre;
         lowest = lsPre;
         highest = MaxGt(highStop, highest);
         lowest = MinLt(lowStop, lowest);
         if( hsBuf_Idx == 0 ) {
            highest = highStop;
            lowest = lowStop;
         }
         hsPre = highest;
         lsPre = lowest;
         if( hsBuf_Idx < lastQ ) {
            tempReal = hsBuf[hsBuf_Idx + 1];
            highest = MaxGt(tempReal, highest);
            tempReal = lsBuf[hsBuf_Idx + 1];
            lowest = MinLt(tempReal, lowest);
         }
         hsBuf[hsBuf_Idx] = highStop;
         lsBuf[hsBuf_Idx] = lowStop;
         hsBuf_Idx++;
         if( hsBuf_Idx > maxIdx_hsBuf ) { hsBuf_Idx = 0; }
         outHighStop[outIdx] = highest;
         outLowStop[outIdx] = lowest;
         if( hhBuf_Idx == 0 ) {
            sufHi = hhBuf[lastP];
            sufLo = llBuf[lastP];
            ip = lastP;
            while( ip > 1 ) {
               ip -= 1;
               tempReal = hhBuf[ip];
               sufHi = MaxGt(tempReal, sufHi);
               hhBuf[ip] = sufHi;
               tempReal = llBuf[ip];
               sufLo = MinLt(tempReal, sufLo);
               llBuf[ip] = sufLo;
            }
         }
         if( hsBuf_Idx == 0 ) {
            sufHi = hsBuf[lastQ];
            sufLo = lsBuf[lastQ];
            iq = lastQ;
            while( iq > 1 ) {
               iq -= 1;
               tempReal = hsBuf[iq];
               sufHi = MaxGt(tempReal, sufHi);
               hsBuf[iq] = sufHi;
               tempReal = lsBuf[iq];
               sufLo = MinLt(tempReal, sufLo);
               lsBuf[iq] = sufLo;
            }
         }
         outIdx += 1;
         today += 1;
      }
      outBegIdx = startIdx;
      outNBElement = outIdx;
      return RetCode.Success ;
   }
