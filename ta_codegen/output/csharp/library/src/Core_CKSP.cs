      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Cksp</c> reports over the same bars: the opener sets it
      /// to <c>(lookback, historyLen - lookback)</c>, every accepted <c>Update</c>
      /// adds one to the count — a rejected one changes nothing, and neither does
      /// <c>Peek</c> — and <c>Clone</c> carries it verbatim. A plain <c>Open</c>
      /// hands back only the last value, a subset of this range, because the caller
      /// chose not to take the fill.</para>
      /// <para>The last bar it can reach is <see cref="Core.IndexMax"/>; past that
      /// <c>Update</c> and <c>Advance</c> throw.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      /// <summary>Count one bar this stream was not fed: <see cref="OutRange"/> advances by
      /// one and nothing else moves.</summary>
      /// <remarks>
      /// <para><see cref="Value"/> keeps answering the previous output, which is this
      /// bar's output too. For a bar the caller leaves out: one an <c>Update</c>
      /// rejected and that will not be re-fed, or a session with no print. Without
      /// it two handles on one feed drift a bar apart when only one of them skips.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, the last one the batch tier
      /// can address and the last this handle will count. <c>Update</c> throws the
      /// same there.</para>
      /// </remarks>
      public void Advance()
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("CKSP", "advance", RetCode.OutOfRangeEndIndex);
         outRangeCount++;
      }

      internal CkspStream( CkspStream other )
      {
         this.core = other.core;
         this.optInTimePeriod = other.optInTimePeriod;
         this.optInMultiplier = other.optInMultiplier;
         this.optInStopPeriod = other.optInStopPeriod;
         this.lastP = other.lastP;
         this.lastQ = other.lastQ;
         this.prevATR = other.prevATR;
         this.wAlpha = other.wAlpha;
         this.wBeta = other.wBeta;
         this.hhPre = other.hhPre;
         this.llPre = other.llPre;
         this.hsPre = other.hsPre;
         this.lsPre = other.lsPre;
         this.hhBuf_Idx = other.hhBuf_Idx;
         this.hsBuf_Idx = other.hsBuf_Idx;
         this.maxIdx_hhBuf = other.maxIdx_hhBuf;
         this.llBuf_Idx = other.llBuf_Idx;
         this.maxIdx_llBuf = other.maxIdx_llBuf;
         this.maxIdx_hsBuf = other.maxIdx_hsBuf;
         this.lsBuf_Idx = other.lsBuf_Idx;
         this.maxIdx_lsBuf = other.maxIdx_lsBuf;
         this.lag1_inClose = other.lag1_inClose;
         this.cbSize_hhBuf = other.cbSize_hhBuf;
         this.cb_hhBuf = new double[other.cb_hhBuf.Length];
         Array.Copy( other.cb_hhBuf, this.cb_hhBuf, other.cb_hhBuf.Length );
         this.cbSize_llBuf = other.cbSize_llBuf;
         this.cb_llBuf = new double[other.cb_llBuf.Length];
         Array.Copy( other.cb_llBuf, this.cb_llBuf, other.cb_llBuf.Length );
         this.cbSize_hsBuf = other.cbSize_hsBuf;
         this.cb_hsBuf = new double[other.cb_hsBuf.Length];
         Array.Copy( other.cb_hsBuf, this.cb_hsBuf, other.cb_hsBuf.Length );
         this.cbSize_lsBuf = other.cbSize_lsBuf;
         this.cb_lsBuf = new double[other.cb_lsBuf.Length];
         Array.Copy( other.cb_lsBuf, this.cb_lsBuf, other.cb_lsBuf.Length );
         this.cur_outHighStop = other.cur_outHighStop;
         this.cur_outLowStop = other.cur_outLowStop;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so nothing moves — <see cref="OutRange"/> included — and
      /// <see cref="Value"/> still answers the previous value. Re-feed the bar when
      /// a corrected value arrives, or call <see cref="Advance"/> to count it and
      /// carry on; two handles on one feed drift a bar apart if neither happens.
      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, which no re-feed clears: the
      /// handle has run out of index domain and only a shorter history can start a
      /// new one.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>The value at the bar just committed.</returns>
      public CkspValue Update( double inHigh, double inLow, double inClose )
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("CKSP", "update", RetCode.OutOfRangeEndIndex);
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) ) throw Core.NonFiniteBar("CKSP", "update", !double.IsFinite(inHigh) ? nameof(inHigh) : !double.IsFinite(inLow) ? nameof(inLow) : nameof(inClose));
         core.CkspStepImpl(this, inHigh, inLow, inClose);
         outRangeCount++;
         return new CkspValue(cur_outHighStop, cur_outLowStop);
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.IndexMax"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public CkspValue Peek( double inHigh, double inLow, double inClose )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) ) throw Core.NonFiniteBar("CKSP", "peek", !double.IsFinite(inHigh) ? nameof(inHigh) : !double.IsFinite(inLow) ? nameof(inLow) : nameof(inClose));
         CkspStream sp = this;
         double val2 = 0.0;
         double val3 = 0.0;
         double greatest = 0.0;
         double tempCY = 0.0;
         double tempLT = 0.0;
         double tempHT = 0.0;
         double tempReal = 0.0;
         double highest = 0.0;
         double lowest = 0.0;
         double band = 0.0;
         double highStop = 0.0;
         double lowStop = 0.0;
         double cur_outHighStop = 0.0;
         double cur_outLowStop = 0.0;
         int hhBuf_Idx = sp.hhBuf_Idx;
         double hhPre = sp.hhPre;
         int hsBuf_Idx = sp.hsBuf_Idx;
         double hsPre = sp.hsPre;
         double llPre = sp.llPre;
         double lsPre = sp.lsPre;
         double prevATR = sp.prevATR;
         tempLT = inLow;
         tempHT = inHigh;
         tempCY = sp.lag1_inClose;
         greatest = tempHT - tempLT;
         /* val1 */
         val2 = Math.Abs(tempCY - tempHT);
         greatest = MaxGt(val2, greatest);
         val3 = Math.Abs(tempCY - tempLT);
         greatest = MaxGt(val3, greatest);
         prevATR = Math.FusedMultiplyAdd(sp.wBeta, prevATR, sp.wAlpha * greatest);
         highest = hhPre;
         lowest = llPre;
         highest = MaxGt(tempHT, highest);
         lowest = MinLt(tempLT, lowest);
         if( hhBuf_Idx == 0 ) {
            highest = tempHT;
            lowest = tempLT;
         }
         hhPre = highest;
         llPre = lowest;
         if( hhBuf_Idx < sp.lastP ) {
            tempReal = sp.cb_hhBuf[hhBuf_Idx + 1];
            highest = MaxGt(tempReal, highest);
            tempReal = sp.cb_llBuf[hhBuf_Idx + 1];
            lowest = MinLt(tempReal, lowest);
         }
         hhBuf_Idx = hhBuf_Idx + 1;
         if( hhBuf_Idx > sp.maxIdx_hhBuf ) {
            hhBuf_Idx = 0;
         }
         band = sp.optInMultiplier * prevATR;
         highStop = highest - band;
         lowStop = lowest + band;
         highest = hsPre;
         lowest = lsPre;
         highest = MaxGt(highStop, highest);
         lowest = MinLt(lowStop, lowest);
         if( hsBuf_Idx == 0 ) {
            highest = highStop;
            lowest = lowStop;
         }
         hsPre = highest;
         lsPre = lowest;
         if( hsBuf_Idx < sp.lastQ ) {
            tempReal = sp.cb_hsBuf[hsBuf_Idx + 1];
            highest = MaxGt(tempReal, highest);
            tempReal = sp.cb_lsBuf[hsBuf_Idx + 1];
            lowest = MinLt(tempReal, lowest);
         }
         hsBuf_Idx = hsBuf_Idx + 1;
         if( hsBuf_Idx > sp.maxIdx_hsBuf ) {
            hsBuf_Idx = 0;
         }
         cur_outHighStop = highest;
         cur_outLowStop = lowest;
         return new CkspValue(cur_outHighStop, cur_outLowStop);
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public CkspValue Value => new CkspValue(cur_outHighStop, cur_outLowStop);

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public CkspStream Clone()
      {
         return new CkspStream(this);
      }
   }

   private void CkspStepImpl( CkspStream sp, double inHigh, double inLow, double inClose )
   {
      int ip = 0;
      int iq = 0;
      double val2 = 0.0;
      double val3 = 0.0;
      double greatest = 0.0;
      double tempCY = 0.0;
      double tempLT = 0.0;
      double tempHT = 0.0;
      double tempReal = 0.0;
      double sufHi = 0.0;
      double sufLo = 0.0;
      double highest = 0.0;
      double lowest = 0.0;
      double band = 0.0;
      double highStop = 0.0;
      double lowStop = 0.0;
      tempLT = inLow;
      tempHT = inHigh;
      tempCY = sp.lag1_inClose;
      greatest = tempHT - tempLT;
      /* val1 */
      val2 = Math.Abs(tempCY - tempHT);
      greatest = MaxGt(val2, greatest);
      val3 = Math.Abs(tempCY - tempLT);
      greatest = MaxGt(val3, greatest);
      sp.prevATR = Math.FusedMultiplyAdd(sp.wBeta, sp.prevATR, sp.wAlpha * greatest);
      highest = sp.hhPre;
      lowest = sp.llPre;
      highest = MaxGt(tempHT, highest);
      lowest = MinLt(tempLT, lowest);
      if( sp.hhBuf_Idx == 0 ) {
         highest = tempHT;
         lowest = tempLT;
      }
      sp.hhPre = highest;
      sp.llPre = lowest;
      if( sp.hhBuf_Idx < sp.lastP ) {
         tempReal = sp.cb_hhBuf[sp.hhBuf_Idx + 1];
         highest = MaxGt(tempReal, highest);
         tempReal = sp.cb_llBuf[sp.hhBuf_Idx + 1];
         lowest = MinLt(tempReal, lowest);
      }
      sp.cb_hhBuf[sp.hhBuf_Idx] = tempHT;
      sp.cb_llBuf[sp.hhBuf_Idx] = tempLT;
      sp.hhBuf_Idx = sp.hhBuf_Idx + 1;
      if( sp.hhBuf_Idx > sp.maxIdx_hhBuf ) {
         sp.hhBuf_Idx = 0;
      }
      band = sp.optInMultiplier * sp.prevATR;
      highStop = highest - band;
      lowStop = lowest + band;
      highest = sp.hsPre;
      lowest = sp.lsPre;
      highest = MaxGt(highStop, highest);
      lowest = MinLt(lowStop, lowest);
      if( sp.hsBuf_Idx == 0 ) {
         highest = highStop;
         lowest = lowStop;
      }
      sp.hsPre = highest;
      sp.lsPre = lowest;
      if( sp.hsBuf_Idx < sp.lastQ ) {
         tempReal = sp.cb_hsBuf[sp.hsBuf_Idx + 1];
         highest = MaxGt(tempReal, highest);
         tempReal = sp.cb_lsBuf[sp.hsBuf_Idx + 1];
         lowest = MinLt(tempReal, lowest);
      }
      sp.cb_hsBuf[sp.hsBuf_Idx] = highStop;
      sp.cb_lsBuf[sp.hsBuf_Idx] = lowStop;
      sp.hsBuf_Idx = sp.hsBuf_Idx + 1;
      if( sp.hsBuf_Idx > sp.maxIdx_hsBuf ) {
         sp.hsBuf_Idx = 0;
      }
      sp.cur_outHighStop = highest;
      sp.cur_outLowStop = lowest;
      /* A completed block becomes its suffix extrema. Nothing this bar reads
       * them, so both passes stay below the output stores, where the peek
       * frame never runs them.
       */
      if( sp.hhBuf_Idx == 0 ) {
         sufHi = sp.cb_hhBuf[sp.lastP];
         sufLo = sp.cb_llBuf[sp.lastP];
         ip = sp.lastP;
         while( ip > 1 ) {
            ip -= 1;
            tempReal = sp.cb_hhBuf[ip];
            sufHi = MaxGt(tempReal, sufHi);
            sp.cb_hhBuf[ip] = sufHi;
            tempReal = sp.cb_llBuf[ip];
            sufLo = MinLt(tempReal, sufLo);
            sp.cb_llBuf[ip] = sufLo;
         }
      }
      if( sp.hsBuf_Idx == 0 ) {
         sufHi = sp.cb_hsBuf[sp.lastQ];
         sufLo = sp.cb_lsBuf[sp.lastQ];
         iq = sp.lastQ;
         while( iq > 1 ) {
            iq -= 1;
            tempReal = sp.cb_hsBuf[iq];
            sufHi = MaxGt(tempReal, sufHi);
            sp.cb_hsBuf[iq] = sufHi;
            tempReal = sp.cb_lsBuf[iq];
            sufLo = MinLt(tempReal, sufLo);
            sp.cb_lsBuf[iq] = sufLo;
         }
      }
      sp.lag1_inClose = inClose;
   }

   private RetCode CkspOpenImpl( CkspStream sp, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, double optInMultiplier, int optInStopPeriod, out int outBegIdx, out int outNBElement, Span<double> outHighStop, Span<double> outLowStop, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double[] hhBuf = [];
      int hhBuf_Idx = 0;
      int maxIdx_hhBuf = (30)-1;
      double[] llBuf = [];
      int llBuf_Idx = 0;
      int maxIdx_llBuf = (30)-1;
      double[] hsBuf = [];
      int hsBuf_Idx = 0;
      int maxIdx_hsBuf = (30)-1;
      double[] lsBuf = [];
      int lsBuf_Idx = 0;
      int maxIdx_lsBuf = (30)-1;
      int i = 0;
      int ip = 0;
      int iq = 0;
      int today = 0;
      int outIdx = 0;
      int lookbackTotal = 0;
      int lastP = 0;
      int lastQ = 0;
      double prevATR = 0;
      double periodTotal = 0;
      double wAlpha = 0;
      double wBeta = 0;
      double val2 = 0;
      double val3 = 0;
      double greatest = 0;
      double tempCY = 0;
      double tempLT = 0;
      double tempHT = 0;
      double tempReal = 0;
      double hhPre = 0;
      double llPre = 0;
      double hsPre = 0;
      double lsPre = 0;
      double sufHi = 0;
      double sufLo = 0;
      double highest = 0;
      double lowest = 0;
      double band = 0;
      double highStop = 0;
      double lowStop = 0;
      int historyLen = inHigh.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > IndexMax + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inLow.Length != inHigh.Length || inClose.Length != inHigh.Length ) {
         return RetCode.BadParam;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 10;
      } else if( optInTimePeriod < 2 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInMultiplier == RealDefault ) {
         optInMultiplier = 1e0;
      } else if( !(optInMultiplier >= 0e0 && optInMultiplier <= RealMax) ) {
         return RetCode.BadParam;
      }
      if( optInStopPeriod == int.MinValue ) {
         optInStopPeriod = 9;
      } else if( optInStopPeriod < 1 || optInStopPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      outBegIdx = 0;
      outNBElement = 0;
      lookbackTotal = CkspLookback(optInTimePeriod, optInMultiplier, optInStopPeriod);
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         return RetCode.InsufficientHistory ;
      }
      /* Four rolling extrema, van Herk / Gil-Werman, one buffer each: the window
       * ending in slot j is the current block's prefix extremum joined with the
       * previous block's suffix extremum from slot j+1. A slot holds the raw value
       * while its block is filling and is turned into the suffix extremum, in
       * place, when the block completes; slot j+1 is always still the previous
       * block's when slot j is filled. The high and low sides share an index.
       *
       * The extrema are exact, so both outputs must stay bit-identical to
       * TA_MAX( TA_MAX(high) - x*TA_ATR ) and its mirror, whatever the block
       * phase; only the sign of a zero tied between +0.0 and -0.0 is free.
       */
      if( optInTimePeriod < 1 ) return RetCode.InternalError;
      hhBuf = new double[optInTimePeriod];
      maxIdx_hhBuf = (optInTimePeriod)-1;
      hhBuf_Idx = 0;
      if( optInTimePeriod < 1 ) return RetCode.InternalError;
      llBuf = new double[optInTimePeriod];
      maxIdx_llBuf = (optInTimePeriod)-1;
      llBuf_Idx = 0;
      if( optInStopPeriod < 1 ) return RetCode.InternalError;
      hsBuf = new double[optInStopPeriod];
      maxIdx_hsBuf = (optInStopPeriod)-1;
      hsBuf_Idx = 0;
      if( optInStopPeriod < 1 ) return RetCode.InternalError;
      lsBuf = new double[optInStopPeriod];
      maxIdx_lsBuf = (optInStopPeriod)-1;
      lsBuf_Idx = 0;
      lastP = optInTimePeriod - 1;
      lastQ = optInStopPeriod - 1;
      /* The Average True Range is carried inline rather than taken from a call,
       * because the two stages advance together one bar at a time and a
       * whole-range buffer between them would not stream.
       *
       * The arithmetic order below is the bit-exactness contract with TA_ATR (do
       * not reorder): True Range from high-low, then the two previous-close
       * distances in that order; the seed summed from 0.0 over the first 'period'
       * True Ranges and divided once; the same two Wilder coefficients, wBeta
       * rounded and wAlpha derived from it, in one fused statement.
       */
      wBeta = (double)(optInTimePeriod - 1) / (double)optInTimePeriod;
      wAlpha = 1.0 - wBeta;
      today = startIdx - lookbackTotal + 1;
      periodTotal = 0.0;
      i = optInTimePeriod;
      while( i-- > 0 ) {
         tempLT = inLow[today];
         tempHT = inHigh[today];
         tempCY = inClose[today - 1];
         greatest = tempHT - tempLT;
         /* val1 */
         val2 = Math.Abs(tempCY - tempHT);
         greatest = MaxGt(val2, greatest);
         val3 = Math.Abs(tempCY - tempLT);
         greatest = MaxGt(val3, greatest);
         periodTotal += greatest;
         today += 1;
      }
      prevATR = periodTotal / optInTimePeriod;
      /* Skip the Average True Range's unstable period. Taking the count from the
       * lookback rather than naming the setting keeps the two from disagreeing.
       */
      i = lookbackTotal - lastQ - optInTimePeriod;
      while( i != 0 ) {
         tempLT = inLow[today];
         tempHT = inHigh[today];
         tempCY = inClose[today - 1];
         greatest = tempHT - tempLT;
         /* val1 */
         val2 = Math.Abs(tempCY - tempHT);
         greatest = MaxGt(val2, greatest);
         val3 = Math.Abs(tempCY - tempLT);
         greatest = MaxGt(val3, greatest);
         prevATR = Math.FusedMultiplyAdd(wBeta, prevATR, wAlpha * greatest);
         today += 1;
         i -= 1;
      }
      /* prevATR is now the Average True Range of bar today-1, the first bar with
       * a first stop. Its extreme window is one whole block, taken straight from
       * the input.
       */
      highest = inHigh[today - 1];
      lowest = inLow[today - 1];
      hhBuf[lastP] = highest;
      llBuf[lastP] = lowest;
      ip = lastP;
      while( ip > 0 ) {
         ip -= 1;
         tempHT = inHigh[today - 1 - lastP + ip];
         tempLT = inLow[today - 1 - lastP + ip];
         highest = MaxGt(tempHT, highest);
         lowest = MinLt(tempLT, lowest);
         hhBuf[ip] = highest;
         llBuf[ip] = lowest;
      }
      hhPre = highest;
      llPre = lowest;
      /* The multiple of the ATR is formed on its own, never fused into the
       * offset, so that each first stop is TA_MAX - x*TA_ATR (or its mirror) as a
       * caller composing the three functions would compute it.
       */
      band = optInMultiplier * prevATR;
      highStop = highest - band;
      lowStop = lowest + band;
      hsPre = highStop;
      lsPre = lowStop;
      hsBuf[hsBuf_Idx] = highStop;
      lsBuf[hsBuf_Idx] = lowStop;
      hsBuf_Idx++;
      if( hsBuf_Idx > maxIdx_hsBuf ) { hsBuf_Idx = 0; }
      /* Fill the first stop window, through startIdx inclusive. */
      while( today <= startIdx ) {
         tempLT = inLow[today];
         tempHT = inHigh[today];
         tempCY = inClose[today - 1];
         greatest = tempHT - tempLT;
         /* val1 */
         val2 = Math.Abs(tempCY - tempHT);
         greatest = MaxGt(val2, greatest);
         val3 = Math.Abs(tempCY - tempLT);
         greatest = MaxGt(val3, greatest);
         prevATR = Math.FusedMultiplyAdd(wBeta, prevATR, wAlpha * greatest);
         /* Keep this shape: the prefix extreme selected in a local, the
          * block-start override after it, one store. A store made only when the
          * bar sets a new extreme, or the override ahead of the select, compiles
          * to a data-dependent branch in the stream step, where the prefix lives
          * in the handle.
          */
         highest = hhPre;
         lowest = llPre;
         highest = MaxGt(tempHT, highest);
         lowest = MinLt(tempLT, lowest);
         if( hhBuf_Idx == 0 ) {
            highest = tempHT;
            lowest = tempLT;
         }
         hhPre = highest;
         llPre = lowest;
         if( hhBuf_Idx < lastP ) {
            tempReal = hhBuf[hhBuf_Idx + 1];
            highest = MaxGt(tempReal, highest);
            tempReal = llBuf[hhBuf_Idx + 1];
            lowest = MinLt(tempReal, lowest);
         }
         hhBuf[hhBuf_Idx] = tempHT;
         llBuf[hhBuf_Idx] = tempLT;
         hhBuf_Idx++;
         if( hhBuf_Idx > maxIdx_hhBuf ) { hhBuf_Idx = 0; }
         if( hhBuf_Idx == 0 ) {
            sufHi = hhBuf[lastP];
            sufLo = llBuf[lastP];
            ip = lastP;
            while( ip > 1 ) {
               ip -= 1;
               tempReal = hhBuf[ip];
               sufHi = MaxGt(tempReal, sufHi);
               hhBuf[ip] = sufHi;
               tempReal = llBuf[ip];
               sufLo = MinLt(tempReal, sufLo);
               llBuf[ip] = sufLo;
            }
         }
         band = optInMultiplier * prevATR;
         highStop = highest - band;
         lowStop = lowest + band;
         hsPre = MaxGt(highStop, hsPre);
         lsPre = MinLt(lowStop, lsPre);
         hsBuf[hsBuf_Idx] = highStop;
         lsBuf[hsBuf_Idx] = lowStop;
         hsBuf_Idx++;
         if( hsBuf_Idx > maxIdx_hsBuf ) { hsBuf_Idx = 0; }
         today += 1;
      }
      /* The first stop window is one whole block as well: its extremes are the
       * prefix extremes, and the block is complete.
       */
      sufHi = hsBuf[lastQ];
      sufLo = lsBuf[lastQ];
      iq = lastQ;
      while( iq > 1 ) {
         iq -= 1;
         tempReal = hsBuf[iq];
         sufHi = MaxGt(tempReal, sufHi);
         hsBuf[iq] = sufHi;
         tempReal = lsBuf[iq];
         sufLo = MinLt(tempReal, sufLo);
         lsBuf[iq] = sufLo;
      }
      outHighStop[0 * outStride] = hsPre;
      outLowStop[0 * outStride] = lsPre;
      outIdx = 1;
      while( today <= endIdx ) {
         tempLT = inLow[today];
         tempHT = inHigh[today];
         tempCY = inClose[today - 1];
         greatest = tempHT - tempLT;
         /* val1 */
         val2 = Math.Abs(tempCY - tempHT);
         greatest = MaxGt(val2, greatest);
         val3 = Math.Abs(tempCY - tempLT);
         greatest = MaxGt(val3, greatest);
         prevATR = Math.FusedMultiplyAdd(wBeta, prevATR, wAlpha * greatest);
         highest = hhPre;
         lowest = llPre;
         highest = MaxGt(tempHT, highest);
         lowest = MinLt(tempLT, lowest);
         if( hhBuf_Idx == 0 ) {
            highest = tempHT;
            lowest = tempLT;
         }
         hhPre = highest;
         llPre = lowest;
         if( hhBuf_Idx < lastP ) {
            tempReal = hhBuf[hhBuf_Idx + 1];
            highest = MaxGt(tempReal, highest);
            tempReal = llBuf[hhBuf_Idx + 1];
            lowest = MinLt(tempReal, lowest);
         }
         hhBuf[hhBuf_Idx] = tempHT;
         llBuf[hhBuf_Idx] = tempLT;
         hhBuf_Idx++;
         if( hhBuf_Idx > maxIdx_hhBuf ) { hhBuf_Idx = 0; }
         band = optInMultiplier * prevATR;
         highStop = highest - band;
         lowStop = lowest + band;
         highest = hsPre;
         lowest = lsPre;
         highest = MaxGt(highStop, highest);
         lowest = MinLt(lowStop, lowest);
         if( hsBuf_Idx == 0 ) {
            highest = highStop;
            lowest = lowStop;
         }
         hsPre = highest;
         lsPre = lowest;
         if( hsBuf_Idx < lastQ ) {
            tempReal = hsBuf[hsBuf_Idx + 1];
            highest = MaxGt(tempReal, highest);
            tempReal = lsBuf[hsBuf_Idx + 1];
            lowest = MinLt(tempReal, lowest);
         }
         hsBuf[hsBuf_Idx] = highStop;
         lsBuf[hsBuf_Idx] = lowStop;
         hsBuf_Idx++;
         if( hsBuf_Idx > maxIdx_hsBuf ) { hsBuf_Idx = 0; }
         outHighStop[outIdx * outStride] = highest;
         outLowStop[outIdx * outStride] = lowest;
         /* A completed block becomes its suffix extrema. Nothing this bar reads
          * them, so both passes stay below the output stores, where the peek
          * frame never runs them.
          */
         if( hhBuf_Idx == 0 ) {
            sufHi = hhBuf[lastP];
            sufLo = llBuf[lastP];
            ip = lastP;
            while( ip > 1 ) {
               ip -= 1;
               tempReal = hhBuf[ip];
               sufHi = MaxGt(tempReal, sufHi);
               hhBuf[ip] = sufHi;
               tempReal = llBuf[ip];
               sufLo = MinLt(tempReal, sufLo);
               llBuf[ip] = sufLo;
            }
         }
         if( hsBuf_Idx == 0 ) {
            sufHi = hsBuf[lastQ];
            sufLo = lsBuf[lastQ];
            iq = lastQ;
            while( iq > 1 ) {
               iq -= 1;
               tempReal = hsBuf[iq];
               sufHi = MaxGt(tempReal, sufHi);
               hsBuf[iq] = sufHi;
               tempReal = lsBuf[iq];
               sufLo = MinLt(tempReal, sufLo);
               lsBuf[iq] = sufLo;
            }
         }
         outIdx += 1;
         today += 1;
      }
      outBegIdx = startIdx;
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      int capCb_hhBuf = maxIdx_hhBuf + 1;
      if( capCb_hhBuf > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      int capCb_llBuf = maxIdx_llBuf + 1;
      if( capCb_llBuf > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      int capCb_hsBuf = maxIdx_hsBuf + 1;
      if( capCb_hsBuf > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      int capCb_lsBuf = maxIdx_lsBuf + 1;
      if( capCb_lsBuf > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      sp.optInTimePeriod = optInTimePeriod;
      sp.optInMultiplier = optInMultiplier;
      sp.optInStopPeriod = optInStopPeriod;
      sp.lastP = lastP;
      sp.lastQ = lastQ;
      sp.prevATR = prevATR;
      sp.wAlpha = wAlpha;
      sp.wBeta = wBeta;
      sp.hhPre = hhPre;
      sp.llPre = llPre;
      sp.hsPre = hsPre;
      sp.lsPre = lsPre;
      sp.hhBuf_Idx = hhBuf_Idx;
      sp.hsBuf_Idx = hsBuf_Idx;
      sp.maxIdx_hhBuf = maxIdx_hhBuf;
      sp.llBuf_Idx = llBuf_Idx;
      sp.maxIdx_llBuf = maxIdx_llBuf;
      sp.maxIdx_hsBuf = maxIdx_hsBuf;
      sp.lsBuf_Idx = lsBuf_Idx;
      sp.maxIdx_lsBuf = maxIdx_lsBuf;
      sp.lag1_inClose = inClose[historyLen - 1];
      sp.cbSize_hhBuf = capCb_hhBuf;
      sp.cb_hhBuf = hhBuf;
      sp.cbSize_llBuf = capCb_llBuf;
      sp.cb_llBuf = llBuf;
      sp.cbSize_hsBuf = capCb_hsBuf;
      sp.cb_hsBuf = hsBuf;
      sp.cbSize_lsBuf = capCb_lsBuf;
      sp.cb_lsBuf = lsBuf;
      sp.cur_outHighStop = outHighStop[(outNBElement - 1) * outStride];
      sp.cur_outLowStop = outLowStop[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* CkspOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal CkspStream CkspOpenAndFillInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, double optInMultiplier, int optInStopPeriod, out int outBegIdx, out int outNBElement, Span<double> outHighStop, Span<double> outLowStop )
   {
      CkspStream sp = new CkspStream(this);
      RetCode retCode = CkspOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInTimePeriod, optInMultiplier, optInStopPeriod, out outBegIdx, out outNBElement, outHighStop, outLowStop, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("CKSP", "openAndFill", nameof(inHigh), inHigh.Length, startIdx, CkspLookback(optInTimePeriod, optInMultiplier, optInStopPeriod));
      }
      throw StreamFailure("CKSP", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind CkspOpen (composition seam). */
   internal CkspStream CkspOpenInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, double optInMultiplier, int optInStopPeriod )
   {
      CkspStream sp = new CkspStream(this);
      double[] sink_outHighStop = new double[1];
      double[] sink_outLowStop = new double[1];
      RetCode retCode = CkspOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInTimePeriod, optInMultiplier, optInStopPeriod, out int outBegIdx, out int outNBElement, sink_outHighStop, sink_outLowStop, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("CKSP", "open", nameof(inHigh), inHigh.Length, startIdx, CkspLookback(optInTimePeriod, optInMultiplier, optInStopPeriod));
      }
      throw StreamFailure("CKSP", "open", retCode);
   }

   /// <summary>Open a live <c>CKSP</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="CkspStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>CKSP</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>CkspLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>CkspOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="CkspLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInMultiplier">As in the batch call; see <see cref="CkspLookback"/> for its default and
   /// range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <param name="optInStopPeriod">As in the batch call; see <see cref="CkspLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>CkspLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules S1 and S2).</exception>
   public CkspStream CkspOpen( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInTimePeriod, double optInMultiplier, int optInStopPeriod )
   {
      if( inHigh.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "CKSP open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "CKSP open: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TALibArgumentException("CKSP open: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TALibArgumentException("CKSP open: inClose is empty", nameof(inClose), RetCode.BadParam);
      RequireHistoryLength("CKSP", "open", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("CKSP", "open", "inClose", inClose.Length, inHigh.Length);
      return CkspOpenInternal(inHigh, inLow, inClose, 0, optInTimePeriod, optInMultiplier, optInStopPeriod);
   }

   /// <summary><c>CkspOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>CKSP</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - CkspLookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="CkspStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="CkspLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInMultiplier">As in the batch call; see <see cref="CkspLookback"/> for its default and
   /// range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <param name="optInStopPeriod">As in the batch call; see <see cref="CkspLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outHighStop">Highest of the recent first high stops; usually plotted as the short stop.
   /// Must hold at least <c>historyLen - CkspLookback(...)</c> values.</param>
   /// <param name="outLowStop">Lowest of the recent first low stops; usually plotted as the long stop.
   /// Must hold at least <c>historyLen - CkspLookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>CkspLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules S1 and S2).</exception>
   public CkspStream CkspOpenAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInTimePeriod, double optInMultiplier, int optInStopPeriod, Span<double> outHighStop, Span<double> outLowStop )
   {
      if( inHigh.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "CKSP openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "CKSP openAndFill: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TALibArgumentException("CKSP openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TALibArgumentException("CKSP openAndFill: inClose is empty", nameof(inClose), RetCode.BadParam);
      int guardOutLen = OpenFillCount("CKSP", "openAndFill", inHigh.Length, CkspLookback(optInTimePeriod, optInMultiplier, optInStopPeriod));
      RequireHistoryLength("CKSP", "openAndFill", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("CKSP", "openAndFill", "inClose", inClose.Length, inHigh.Length);
      RequireFillLength("CKSP", "openAndFill", "outHighStop", outHighStop.Length, guardOutLen);
      RequireFillLength("CKSP", "openAndFill", "outLowStop", outLowStop.Length, guardOutLen);
      if( outHighStop.Overlaps(inHigh) || outHighStop.Overlaps(inLow) || outHighStop.Overlaps(inClose) || outLowStop.Overlaps(inHigh) || outLowStop.Overlaps(inLow) || outLowStop.Overlaps(inClose) || outHighStop.Overlaps(outLowStop) ) {
         throw StreamFailure("CKSP", "openAndFill", RetCode.BadParam);
      }
      return CkspOpenAndFillInternal(inHigh, inLow, inClose, 0, optInTimePeriod, optInMultiplier, optInStopPeriod, out _, out _, outHighStop, outLowStop);
   }
