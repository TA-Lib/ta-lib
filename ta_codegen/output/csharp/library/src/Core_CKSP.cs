   /// <summary>A live <c>CKSP</c> stream: one value per closed bar, bit-identical to
   /// <c>CKSP</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.CkspOpen"/>. There is no close and nothing to
