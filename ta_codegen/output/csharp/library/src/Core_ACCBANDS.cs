   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class AccbandsStream
   {
      internal Core core;
      internal int optInTimePeriod;
      internal double periodTotalUpper;
      internal double periodTotalMiddle;
      internal double periodTotalLower;
      internal int ringPos_trailingIdx;
      internal int ringCap_trailingIdx;
      internal double[] ring_trailingIdx_inHigh = [];
      internal double[] ring_trailingIdx_inLow = [];
      internal double[] ring_trailingIdx_inClose = [];
      internal double cur_outRealUpperBand;
      internal double cur_outRealMiddleBand;
      internal double cur_outRealLowerBand;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal AccbandsStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Accbands</c> reports over the same bars: the opener
      /// sets it to <c>(lookback, historyLen - lookback)</c>, every <c>Update</c>
      /// adds one to the count — a non-finite bar is rejected but still counted,
      /// because the bar happened — <c>Peek</c> leaves it alone, and <c>Clone</c>
      /// carries it verbatim. A plain <c>Open</c> hands back only the last value, a
      /// subset of this range, because the caller chose not to take the fill.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      internal AccbandsStream( AccbandsStream other )
      {
         this.core = other.core;
         this.optInTimePeriod = other.optInTimePeriod;
         this.periodTotalUpper = other.periodTotalUpper;
         this.periodTotalMiddle = other.periodTotalMiddle;
         this.periodTotalLower = other.periodTotalLower;
         this.ringPos_trailingIdx = other.ringPos_trailingIdx;
         this.ringCap_trailingIdx = other.ringCap_trailingIdx;
         this.ring_trailingIdx_inHigh = new double[other.ring_trailingIdx_inHigh.Length];
         Array.Copy( other.ring_trailingIdx_inHigh, this.ring_trailingIdx_inHigh, other.ring_trailingIdx_inHigh.Length );
         this.ring_trailingIdx_inLow = new double[other.ring_trailingIdx_inLow.Length];
         Array.Copy( other.ring_trailingIdx_inLow, this.ring_trailingIdx_inLow, other.ring_trailingIdx_inLow.Length );
         this.ring_trailingIdx_inClose = new double[other.ring_trailingIdx_inClose.Length];
         Array.Copy( other.ring_trailingIdx_inClose, this.ring_trailingIdx_inClose, other.ring_trailingIdx_inClose.Length );
         this.cur_outRealUpperBand = other.cur_outRealUpperBand;
         this.cur_outRealMiddleBand = other.cur_outRealMiddleBand;
         this.cur_outRealLowerBand = other.cur_outRealLowerBand;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Allocates nothing — neither handle state nor a return value.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so no state moves, <see cref="Value"/> still answers the previous value,
      /// and the stream stays usable — just carry on with the next bar.
      /// <see cref="OutRange"/> does advance: the bar happened, so it is counted,
      /// which keeps two handles fed the same series positionally aligned when only
      /// one of them rejects a bar. This is the one place the streaming tier is
      /// stricter than the batch API, which computes on whatever it is given: a
      /// handle retains its state, so a single non-finite bar would poison every
      /// later value it produces.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>The value at the bar just committed.</returns>
      public AccbandsValue Update( double inHigh, double inLow, double inClose )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) )
         {
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
            throw Core.StreamFailure("ACCBANDS", "update", RetCode.BadParam);
         }
         core.AccbandsStepImpl(this, inHigh, inLow, inClose);
         if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         return new AccbandsValue(cur_outRealUpperBand, cur_outRealMiddleBand, cur_outRealLowerBand);
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It copies nothing: the frame runs against this handle, reading its buffers
      /// and holding what the step would commit in locals. The cost does not grow
      /// with the period, and <c>Peek</c> never allocates.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>What <see cref="Update"/> would return for this bar.</returns>
      public AccbandsValue Peek( double inHigh, double inLow, double inClose )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) ) throw Core.StreamFailure("ACCBANDS", "peek", RetCode.BadParam);
         AccbandsStream sp = this;
         double tempUpper = 0.0;
         double tempMiddle = 0.0;
         double tempLower = 0.0;
         double tempReal = 0.0;
         double cur_outRealLowerBand = sp.cur_outRealLowerBand;
         double cur_outRealMiddleBand = sp.cur_outRealMiddleBand;
         double cur_outRealUpperBand = sp.cur_outRealUpperBand;
         double periodTotalLower = sp.periodTotalLower;
         double periodTotalMiddle = sp.periodTotalMiddle;
         double periodTotalUpper = sp.periodTotalUpper;
         int pkSlot0 = -1;
         double pkVal0 = 0.0;
         int pkSlot1 = -1;
         double pkVal1 = 0.0;
         int pkSlot2 = -1;
         double pkVal2 = 0.0;
         if( sp.ringCap_trailingIdx == 0 ) {
            pkSlot0 = 0;
            pkVal0 = inHigh;
            pkSlot1 = 0;
            pkVal1 = inLow;
            pkSlot2 = 0;
            pkVal2 = inClose;
         }
         /* Add the incoming bar to each running sum. */
         tempReal = inHigh + inLow;
         if( !(Math.Abs(tempReal) <= 0.00000000000001 * (Math.Abs(inHigh) + Math.Abs(inLow))) ) {
            tempReal = 4 * (inHigh - inLow) / tempReal;
            periodTotalUpper += inHigh * (1 + tempReal);
            periodTotalLower += inLow * (1 - tempReal);
         } else {
            periodTotalUpper += inHigh;
            periodTotalLower += inLow;
         }
         periodTotalMiddle += inClose;
         /* Record the current window sums. */
         tempUpper = periodTotalUpper;
         tempMiddle = periodTotalMiddle;
         tempLower = periodTotalLower;
         /* Remove the trailing bar from each running sum. */
         tempReal = ((sp.ringPos_trailingIdx != pkSlot0) ? sp.ring_trailingIdx_inHigh[sp.ringPos_trailingIdx] : pkVal0) + ((sp.ringPos_trailingIdx != pkSlot1) ? sp.ring_trailingIdx_inLow[sp.ringPos_trailingIdx] : pkVal1);
         if( !(Math.Abs(tempReal) <= 0.00000000000001 * (Math.Abs((sp.ringPos_trailingIdx != pkSlot0) ? sp.ring_trailingIdx_inHigh[sp.ringPos_trailingIdx] : pkVal0) + Math.Abs((sp.ringPos_trailingIdx != pkSlot1) ? sp.ring_trailingIdx_inLow[sp.ringPos_trailingIdx] : pkVal1))) ) {
            tempReal = 4 * (((sp.ringPos_trailingIdx != pkSlot0) ? sp.ring_trailingIdx_inHigh[sp.ringPos_trailingIdx] : pkVal0) - ((sp.ringPos_trailingIdx != pkSlot1) ? sp.ring_trailingIdx_inLow[sp.ringPos_trailingIdx] : pkVal1)) / tempReal;
            periodTotalUpper -= ((sp.ringPos_trailingIdx != pkSlot0) ? sp.ring_trailingIdx_inHigh[sp.ringPos_trailingIdx] : pkVal0) * (1 + tempReal);
            periodTotalLower -= ((sp.ringPos_trailingIdx != pkSlot1) ? sp.ring_trailingIdx_inLow[sp.ringPos_trailingIdx] : pkVal1) * (1 - tempReal);
         } else {
            periodTotalUpper -= (sp.ringPos_trailingIdx != pkSlot0) ? sp.ring_trailingIdx_inHigh[sp.ringPos_trailingIdx] : pkVal0;
            periodTotalLower -= (sp.ringPos_trailingIdx != pkSlot1) ? sp.ring_trailingIdx_inLow[sp.ringPos_trailingIdx] : pkVal1;
         }
         periodTotalMiddle -= (sp.ringPos_trailingIdx != pkSlot2) ? sp.ring_trailingIdx_inClose[sp.ringPos_trailingIdx] : pkVal2;
         /* Write the three bands. */
         cur_outRealUpperBand = tempUpper / (double)sp.optInTimePeriod;
         cur_outRealMiddleBand = tempMiddle / (double)sp.optInTimePeriod;
         cur_outRealLowerBand = tempLower / (double)sp.optInTimePeriod;
         return new AccbandsValue(cur_outRealUpperBand, cur_outRealMiddleBand, cur_outRealLowerBand);
      }

      /// <summary>Commit <c>n</c> closed bars and write their <c>n</c> values, in one call.</summary>
      /// <remarks>
      /// <para>Exactly <c>n</c> back-to-back <see cref="Update"/> calls, with one set of
      /// argument checks instead of <c>n</c>. The outputs must hold at least
      /// <c>n</c> values and must not overlap an input or each other.</para>
      /// <para><see cref="OutRange"/> counts what this call took in, which is what makes
      /// a rejection readable: a non-finite bar <c>k</c> throws
      /// <see cref="System.ArgumentException"/> exactly as <see cref="Update"/>
      /// would, with the bars before <c>k</c> committed and written, bar <c>k</c>
      /// and everything after it not written, and the count advanced by <c>k +
      /// 1</c> — the committed bars plus the rejected one, so the last bar counted
      /// is the one that failed.</para>
      /// </remarks>
      /// <param name="inHigh">Closed bars for <c>inHigh</c>, oldest first.</param>
      /// <param name="inLow">Closed bars for <c>inLow</c>, oldest first.</param>
      /// <param name="inClose">Closed bars for <c>inClose</c>, oldest first.</param>
      /// <param name="outRealUpperBand">Receives one <c>outRealUpperBand</c> value per bar committed.</param>
      /// <param name="outRealMiddleBand">Receives one <c>outRealMiddleBand</c> value per bar committed.</param>
      /// <param name="outRealLowerBand">Receives one <c>outRealLowerBand</c> value per bar committed.</param>
      public void UpdateAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, Span<double> outRealUpperBand, Span<double> outRealMiddleBand, Span<double> outRealLowerBand )
      {
         int barCount = inHigh.Length;
         if( inLow.Length != barCount || inClose.Length != barCount || outRealUpperBand.Length < barCount || outRealMiddleBand.Length < barCount || outRealLowerBand.Length < barCount || outRealUpperBand.Overlaps(inHigh) || outRealUpperBand.Overlaps(inLow) || outRealUpperBand.Overlaps(inClose) || outRealMiddleBand.Overlaps(inHigh) || outRealMiddleBand.Overlaps(inLow) || outRealMiddleBand.Overlaps(inClose) || outRealLowerBand.Overlaps(inHigh) || outRealLowerBand.Overlaps(inLow) || outRealLowerBand.Overlaps(inClose) || outRealUpperBand.Overlaps(outRealMiddleBand) || outRealUpperBand.Overlaps(outRealLowerBand) || outRealMiddleBand.Overlaps(outRealLowerBand) ) throw Core.StreamFailure("ACCBANDS", "updateAndFill", RetCode.BadParam);
         for( int i = 0; i < barCount; i++ )
         {
            if( !double.IsFinite(inHigh[i]) || !double.IsFinite(inLow[i]) || !double.IsFinite(inClose[i]) )
            {
               if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
               throw Core.StreamFailure("ACCBANDS", "updateAndFill", RetCode.BadParam);
            }
            core.AccbandsStepImpl(this, inHigh[i], inLow[i], inClose[i]);
            outRealUpperBand[i] = cur_outRealUpperBand;
            outRealMiddleBand[i] = cur_outRealMiddleBand;
            outRealLowerBand[i] = cur_outRealLowerBand;
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         }
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public AccbandsValue Value => new AccbandsValue(cur_outRealUpperBand, cur_outRealMiddleBand, cur_outRealLowerBand);

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public AccbandsStream Clone()
      {
         return new AccbandsStream(this);
      }
   }

   internal void AccbandsStepImpl( AccbandsStream sp, double inHigh, double inLow, double inClose )
   {
      double tempUpper = 0.0;
      double tempMiddle = 0.0;
      double tempLower = 0.0;
      double tempReal = 0.0;
      if( sp.ringCap_trailingIdx == 0 ) {
         sp.ring_trailingIdx_inHigh[0] = inHigh;
         sp.ring_trailingIdx_inLow[0] = inLow;
         sp.ring_trailingIdx_inClose[0] = inClose;
      }
      /* Add the incoming bar to each running sum. */
      tempReal = inHigh + inLow;
      if( !(Math.Abs(tempReal) <= 0.00000000000001 * (Math.Abs(inHigh) + Math.Abs(inLow))) ) {
         tempReal = 4 * (inHigh - inLow) / tempReal;
         sp.periodTotalUpper += inHigh * (1 + tempReal);
         sp.periodTotalLower += inLow * (1 - tempReal);
      } else {
         sp.periodTotalUpper += inHigh;
         sp.periodTotalLower += inLow;
      }
      sp.periodTotalMiddle += inClose;
      /* Record the current window sums. */
      tempUpper = sp.periodTotalUpper;
      tempMiddle = sp.periodTotalMiddle;
      tempLower = sp.periodTotalLower;
      /* Remove the trailing bar from each running sum. */
      tempReal = sp.ring_trailingIdx_inHigh[sp.ringPos_trailingIdx] + sp.ring_trailingIdx_inLow[sp.ringPos_trailingIdx];
      if( !(Math.Abs(tempReal) <= 0.00000000000001 * (Math.Abs(sp.ring_trailingIdx_inHigh[sp.ringPos_trailingIdx]) + Math.Abs(sp.ring_trailingIdx_inLow[sp.ringPos_trailingIdx]))) ) {
         tempReal = 4 * (sp.ring_trailingIdx_inHigh[sp.ringPos_trailingIdx] - sp.ring_trailingIdx_inLow[sp.ringPos_trailingIdx]) / tempReal;
         sp.periodTotalUpper -= sp.ring_trailingIdx_inHigh[sp.ringPos_trailingIdx] * (1 + tempReal);
         sp.periodTotalLower -= sp.ring_trailingIdx_inLow[sp.ringPos_trailingIdx] * (1 - tempReal);
      } else {
         sp.periodTotalUpper -= sp.ring_trailingIdx_inHigh[sp.ringPos_trailingIdx];
         sp.periodTotalLower -= sp.ring_trailingIdx_inLow[sp.ringPos_trailingIdx];
      }
      sp.periodTotalMiddle -= sp.ring_trailingIdx_inClose[sp.ringPos_trailingIdx];
      /* Write the three bands. */
      sp.cur_outRealUpperBand = tempUpper / (double)sp.optInTimePeriod;
      sp.cur_outRealMiddleBand = tempMiddle / (double)sp.optInTimePeriod;
      sp.cur_outRealLowerBand = tempLower / (double)sp.optInTimePeriod;
      sp.ring_trailingIdx_inHigh[sp.ringPos_trailingIdx] = inHigh;
      sp.ring_trailingIdx_inLow[sp.ringPos_trailingIdx] = inLow;
      sp.ring_trailingIdx_inClose[sp.ringPos_trailingIdx] = inClose;
      sp.ringPos_trailingIdx = sp.ringPos_trailingIdx + 1;
      if( sp.ringPos_trailingIdx >= sp.ringCap_trailingIdx ) {
         sp.ringPos_trailingIdx = 0;
      }
   }

   private RetCode AccbandsOpenImpl( AccbandsStream sp, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outRealUpperBand, Span<double> outRealMiddleBand, Span<double> outRealLowerBand, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double periodTotalUpper = 0;
      double periodTotalMiddle = 0;
      double periodTotalLower = 0;
      double tempUpper = 0;
      double tempMiddle = 0;
      double tempLower = 0;
      double tempReal = 0;
      int i = 0;
      int outIdx = 0;
      int trailingIdx = 0;
      int lookbackTotal = 0;
      int historyLen = inHigh.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inLow.Length != inHigh.Length || inClose.Length != inHigh.Length ) {
         return RetCode.BadParam;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 20;
      } else if( optInTimePeriod < 2 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      /* Identify the minimum number of price bar needed
       * to calculate at least one output.
       */
      lookbackTotal = SMA_Lookback(optInTimePeriod);
      /* Move up the start index if there is not
       * enough initial data.
       */
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      /* Each band is a simple moving average maintained as a running sum over a
       * shared trailing window (all three share optInTimePeriod, so one trailing
       * index walks all three windows in lockstep):
       *    middle = SMA( close )
       *    upper  = SMA( high * (1 + 4*(high-low)/(high+low)) )
       *    lower  = SMA( low  * (1 - 4*(high-low)/(high+low)) )
       * When high+low is zero the upper/lower map degenerates to high/low.
       * Fusing the three moving averages into one loop is bit-identical to the
       * former "two scratch buffers + three sma() calls": each accumulator's
       * add/record/subtract order is unchanged, and the High/Low map is a pure
       * function recomputed from the raw trailing bar.
       */
      periodTotalUpper = 0.0;
      periodTotalMiddle = 0.0;
      periodTotalLower = 0.0;
      trailingIdx = startIdx - lookbackTotal;
      /* Warm up the running sums with the initial period,
       * except for the last value.
       */
      i = trailingIdx;
      while( i < startIdx ) {
         /* The band factor 4*(H-L)/(H+L) is a ratio of two prices, so it is
          * scale-free -- but H+L is a sum that CANCELS when the two prices have
          * opposite signs, and the factor then blows up on what is left of the
          * operands' last bits. Test the sum against ITS OWN operands, not against
          * a fixed band: an absolute threshold answers "cancelled" for every bar
          * of an instrument quoted small enough to fall under it, and widened
          * every band it touched (issue #253). Same test on all three sites, so
          * the bar that enters a running sum is the one that later leaves it.
          */
         tempReal = inHigh[i] + inLow[i];
         if( !(Math.Abs(tempReal) <= 0.00000000000001 * (Math.Abs(inHigh[i]) + Math.Abs(inLow[i]))) ) {
            tempReal = 4 * (inHigh[i] - inLow[i]) / tempReal;
            periodTotalUpper += inHigh[i] * (1 + tempReal);
            periodTotalLower += inLow[i] * (1 - tempReal);
         } else {
            periodTotalUpper += inHigh[i];
            periodTotalLower += inLow[i];
         }
         periodTotalMiddle += inClose[i];
         i = i + 1;
      }
      /* Proceed with the calculation for the requested range.
       * Note that this algorithm allows the input and output to be the
       * same buffer: every trailing bar is read before any output is written.
       */
      outIdx = 0;
      while( i <= endIdx ) {
         /* Add the incoming bar to each running sum. */
         tempReal = inHigh[i] + inLow[i];
         if( !(Math.Abs(tempReal) <= 0.00000000000001 * (Math.Abs(inHigh[i]) + Math.Abs(inLow[i]))) ) {
            tempReal = 4 * (inHigh[i] - inLow[i]) / tempReal;
            periodTotalUpper += inHigh[i] * (1 + tempReal);
            periodTotalLower += inLow[i] * (1 - tempReal);
         } else {
            periodTotalUpper += inHigh[i];
            periodTotalLower += inLow[i];
         }
         periodTotalMiddle += inClose[i];
         i = i + 1;
         /* Record the current window sums. */
         tempUpper = periodTotalUpper;
         tempMiddle = periodTotalMiddle;
         tempLower = periodTotalLower;
         /* Remove the trailing bar from each running sum. */
         tempReal = inHigh[trailingIdx] + inLow[trailingIdx];
         if( !(Math.Abs(tempReal) <= 0.00000000000001 * (Math.Abs(inHigh[trailingIdx]) + Math.Abs(inLow[trailingIdx]))) ) {
            tempReal = 4 * (inHigh[trailingIdx] - inLow[trailingIdx]) / tempReal;
            periodTotalUpper -= inHigh[trailingIdx] * (1 + tempReal);
            periodTotalLower -= inLow[trailingIdx] * (1 - tempReal);
         } else {
            periodTotalUpper -= inHigh[trailingIdx];
            periodTotalLower -= inLow[trailingIdx];
         }
         periodTotalMiddle -= inClose[trailingIdx];
         trailingIdx = trailingIdx + 1;
         /* Write the three bands. */
         outRealUpperBand[outIdx * outStride] = tempUpper / (double)optInTimePeriod;
         outRealMiddleBand[outIdx * outStride] = tempMiddle / (double)optInTimePeriod;
         outRealLowerBand[outIdx * outStride] = tempLower / (double)optInTimePeriod;
         outIdx = outIdx + 1;
      }
      outBegIdx = startIdx;
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      int cap_trailingIdx = i - trailingIdx;
      if( cap_trailingIdx < 0 || cap_trailingIdx > historyLen ) {
         return RetCode.InternalError;
      }
      int allocN_trailingIdx = (cap_trailingIdx > 0)? cap_trailingIdx : 1;
      double[] capRing_trailingIdx_inHigh = new double[allocN_trailingIdx];
      inHigh.Slice(historyLen - cap_trailingIdx, cap_trailingIdx).CopyTo(capRing_trailingIdx_inHigh);
      double[] capRing_trailingIdx_inLow = new double[allocN_trailingIdx];
      inLow.Slice(historyLen - cap_trailingIdx, cap_trailingIdx).CopyTo(capRing_trailingIdx_inLow);
      double[] capRing_trailingIdx_inClose = new double[allocN_trailingIdx];
      inClose.Slice(historyLen - cap_trailingIdx, cap_trailingIdx).CopyTo(capRing_trailingIdx_inClose);
      sp.optInTimePeriod = optInTimePeriod;
      sp.periodTotalUpper = periodTotalUpper;
      sp.periodTotalMiddle = periodTotalMiddle;
      sp.periodTotalLower = periodTotalLower;
      sp.ringPos_trailingIdx = 0;
      sp.ringCap_trailingIdx = cap_trailingIdx;
      sp.ring_trailingIdx_inHigh = capRing_trailingIdx_inHigh;
      sp.ring_trailingIdx_inLow = capRing_trailingIdx_inLow;
      sp.ring_trailingIdx_inClose = capRing_trailingIdx_inClose;
      sp.cur_outRealUpperBand = outRealUpperBand[(outNBElement - 1) * outStride];
      sp.cur_outRealMiddleBand = outRealMiddleBand[(outNBElement - 1) * outStride];
      sp.cur_outRealLowerBand = outRealLowerBand[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* AccbandsOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal AccbandsStream AccbandsOpenAndFillInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outRealUpperBand, Span<double> outRealMiddleBand, Span<double> outRealLowerBand )
   {
      AccbandsStream sp = new AccbandsStream(this);
      RetCode retCode = AccbandsOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInTimePeriod, out outBegIdx, out outNBElement, outRealUpperBand, outRealMiddleBand, outRealLowerBand, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("ACCBANDS", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind AccbandsOpen (composition seam). */
   internal AccbandsStream AccbandsOpenInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod )
   {
      AccbandsStream sp = new AccbandsStream(this);
      double[] sink_outRealUpperBand = new double[1];
      double[] sink_outRealMiddleBand = new double[1];
      double[] sink_outRealLowerBand = new double[1];
      RetCode retCode = AccbandsOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInTimePeriod, out int outBegIdx, out int outNBElement, sink_outRealUpperBand, sink_outRealMiddleBand, sink_outRealLowerBand, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("ACCBANDS", "open", retCode);
   }

   /// <summary>Open a live <c>ACCBANDS</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="AccbandsStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>ACCBANDS</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>ACCBANDS_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>AccbandsOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="ACCBANDS_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>ACCBANDS_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public AccbandsStream AccbandsOpen( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInTimePeriod )
   {
      if( inHigh.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "ACCBANDS open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "ACCBANDS open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("ACCBANDS open: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TaLibArgumentException("ACCBANDS open: inClose is empty", nameof(inClose), RetCode.BadParam);
      RequireHistoryLength("ACCBANDS", "open", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("ACCBANDS", "open", "inClose", inClose.Length, inHigh.Length);
      return AccbandsOpenInternal(inHigh, inLow, inClose, 0, optInTimePeriod);
   }

   /// <summary><c>AccbandsOpen</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>ACCBANDS</c> produces over
   /// the same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - ACCBANDS_Lookback(...)</c> values
   /// and must not alias the inputs or each other — this path writes the outputs
   /// and then reads the input tail to seed its rings, so the batch tier's
   /// in-place allowance does not carry over here. Both are checked before
   /// anything is written, so an undersized span is an <c>ArgumentException</c>
   /// naming it rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="AccbandsStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="ACCBANDS_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outRealUpperBand">SMA of the range-scaled high band. Must hold at least <c>historyLen -
   /// ACCBANDS_Lookback(...)</c> values.</param>
   /// <param name="outRealMiddleBand">SMA of the close. Must hold at least <c>historyLen -
   /// ACCBANDS_Lookback(...)</c> values.</param>
   /// <param name="outRealLowerBand">SMA of the range-scaled low band. Must hold at least <c>historyLen -
   /// ACCBANDS_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>ACCBANDS_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public AccbandsStream AccbandsOpenAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInTimePeriod, Span<double> outRealUpperBand, Span<double> outRealMiddleBand, Span<double> outRealLowerBand )
   {
      if( inHigh.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "ACCBANDS openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "ACCBANDS openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("ACCBANDS openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TaLibArgumentException("ACCBANDS openAndFill: inClose is empty", nameof(inClose), RetCode.BadParam);
      int guardOutLen = OpenFillCount("ACCBANDS", "openAndFill", inHigh.Length, ACCBANDS_Lookback(optInTimePeriod));
      RequireHistoryLength("ACCBANDS", "openAndFill", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("ACCBANDS", "openAndFill", "inClose", inClose.Length, inHigh.Length);
      RequireFillLength("ACCBANDS", "openAndFill", "outRealUpperBand", outRealUpperBand.Length, guardOutLen);
      RequireFillLength("ACCBANDS", "openAndFill", "outRealMiddleBand", outRealMiddleBand.Length, guardOutLen);
      RequireFillLength("ACCBANDS", "openAndFill", "outRealLowerBand", outRealLowerBand.Length, guardOutLen);
      if( outRealUpperBand.Overlaps(inHigh) || outRealUpperBand.Overlaps(inLow) || outRealUpperBand.Overlaps(inClose) || outRealMiddleBand.Overlaps(inHigh) || outRealMiddleBand.Overlaps(inLow) || outRealMiddleBand.Overlaps(inClose) || outRealLowerBand.Overlaps(inHigh) || outRealLowerBand.Overlaps(inLow) || outRealLowerBand.Overlaps(inClose) || outRealUpperBand.Overlaps(outRealMiddleBand) || outRealUpperBand.Overlaps(outRealLowerBand) || outRealMiddleBand.Overlaps(outRealLowerBand) ) {
         throw StreamFailure("ACCBANDS", "openAndFill", RetCode.BadParam);
      }
      return AccbandsOpenAndFillInternal(inHigh, inLow, inClose, 0, optInTimePeriod, out _, out _, outRealUpperBand, outRealMiddleBand, outRealLowerBand);
   }
