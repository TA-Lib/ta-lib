   /// <see cref="OutRange"/> says where they start and how many there are;
   /// nothing outside that range is touched, and the library never pads with
   /// NaN. A valid range shorter than <c>AccbandsLookback</c> is a <b>success
   /// with no values</b> (<c>Count == 0</c>), not an error.
   /// </para>
   /// </remarks>
   /// <param name="startIdx">First bar of the requested range (inclusive).</param>
   /// <param name="endIdx">Last bar of the requested range (inclusive).</param>
   /// <param name="inHigh">High price of each bar.</param>
   /// <param name="inLow">Low price of each bar.</param>
   /// <param name="inClose">Close price of each bar.</param>
   /// <param name="optInTimePeriod">SMA smoothing period for all three bands (default 20; range 2..100000;
   /// <c>int.MinValue</c> selects the default).</param>
   /// <param name="outRealUpperBand">SMA of the range-scaled high band. Must hold at least <c>endIdx - startIdx
   /// + 1</c> values.</param>
   /// <param name="outRealMiddleBand">SMA of the close. Must hold at least <c>endIdx - startIdx + 1</c> values.</param>
   /// <param name="outRealLowerBand">SMA of the range-scaled low band. Must hold at least <c>endIdx - startIdx
   /// + 1</c> values.</param>
   /// <returns>The range written: <c>BegIdx</c> is the first bar with a value,
   /// <c>Count</c> how many were written.</returns>
   /// <exception cref="System.ArgumentOutOfRangeException"><c>startIdx</c> or <c>endIdx</c> is negative, or <c>endIdx &lt;
   /// startIdx</c>.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or two outputs
   /// share one array.</exception>
   /// <exception cref="System.NullReferenceException">An input or output array is null. (Unlike the C library, the managed tier
   /// does not pre-validate nulls; the first array access throws.)</exception>
   public OutRange Accbands( int startIdx,
                             int endIdx,
                             float[] inHigh,
                             float[] inLow,
                             float[] inClose,
                             int optInTimePeriod,
                             double[] outRealUpperBand,
                             double[] outRealMiddleBand,
                             double[] outRealLowerBand )
   {
      RetCode retCode = Accbands(startIdx, endIdx, inHigh, inLow, inClose, optInTimePeriod, out int outBegIdx, out int outNBElement, outRealUpperBand, outRealMiddleBand, outRealLowerBand);
      if( retCode != RetCode.Success ) {
         throw Failure("ACCBANDS", retCode);
      }
      return new OutRange(outBegIdx, outNBElement);
   }
   /// <summary>
   /// Acceleration Bands: three overlap lines around price. The middle band is
   /// an SMA of the close; the upper/lower bands are SMAs of the high/low scaled
   /// by an intraday-range factor. — <b>unchecked</b> variant of
   /// <c>Accbands</c>.
   /// </summary>
   /// <remarks>
   /// Skips every parameter check. The caller guarantees: non-negative
   /// <c>startIdx</c>, <c>endIdx &gt;= startIdx</c>, non-null arrays, output
   /// arrays distinct from each other, and every optional parameter already
   /// resolved and within its documented range — a sentinel such as
   /// <c>int.MinValue</c> is <b>not</b> substituted here.
   /// <para>
   /// Breaking any of those yields an empty <see cref="OutRange"/>, silently
   /// wrong output, or a runtime exception thrown from inside the calculation
   /// (the CLR bounds-checks array access, so misuse never reaches C's undefined
   /// behaviour — but it is not turned into a useful diagnostic either; C and
   /// Rust return a status code from this tier, this one has nowhere to report
   /// it). Use the guarded method unless the arguments are already known good.
   /// </para>
   /// <para>
   /// This is the <c>float[]</c> overload; see the guarded method.
   /// </para>
   /// </remarks>
   /// <param name="startIdx">See the guarded method.</param>
   /// <param name="endIdx">See the guarded method.</param>
   /// <param name="inHigh">See the guarded method.</param>
   /// <param name="inLow">See the guarded method.</param>
   /// <param name="inClose">See the guarded method.</param>
