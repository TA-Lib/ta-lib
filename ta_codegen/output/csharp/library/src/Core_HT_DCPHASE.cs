      /* Peek's reusable scratch — one per thread, see CopyFrom. */
      [ThreadStatic] private static HT_DCPHASE_Stream? peekScratch;

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Allocates nothing — neither handle state nor a return value.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so the handle is left exactly as it was and the stream stays usable: skip
      /// the bar, or re-open on a clean history. This is the one place the
      /// streaming tier is stricter than the batch API, which computes on whatever
      /// it is given: a handle retains its state, so a single non-finite bar would
      /// poison every later value it produces.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.StreamFailure("HT_DCPHASE", "update", RetCode.BadParam);
         core.HT_DCPHASE_StreamStep(this, inReal);
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — it is the same generated code, run on a copy. Never writes
      /// this handle, so peeks may run concurrently with each other.</para>
      /// <para>It runs on a scratch handle held per thread and reused, so it allocates
      /// nothing after this thread's first peek of this indicator. That scratch is
      /// retained for the life of the thread.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>What <see cref="Update"/> would return for this bar.</returns>
      public double Peek( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.StreamFailure("HT_DCPHASE", "peek", RetCode.BadParam);
         HT_DCPHASE_Stream? scratch = peekScratch;
         if( scratch is null ) {
            scratch = new HT_DCPHASE_Stream(this);
            peekScratch = scratch;
         } else {
            scratch.CopyFrom(this);
         }
         core.HT_DCPHASE_StreamStep(scratch, inReal);
         return scratch.cur_outReal;
      }

      /// <summary>The value at the most recently committed bar — the last history bar right
      /// after open, then whatever the latest <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public HT_DCPHASE_Stream Clone()
      {
         return new HT_DCPHASE_Stream(this);
      }
   }

   internal void HT_DCPHASE_StreamStep( HT_DCPHASE_Stream sp, double inReal )
   {
      double adjustedPrevPeriod = 0.0;
      double todayValue = 0.0;
      if( sp.ringCap_trailingWMAIdx == 0 ) {
         sp.ring_trailingWMAIdx_inReal[0] = inReal;
      }
      adjustedPrevPeriod = Math.FusedMultiplyAdd(0.075, sp.period, 0.54);
      todayValue = inReal;
      sp.periodWMASub += todayValue;
      sp.periodWMASub -= sp.trailingWMAValue;
      sp.periodWMASum += todayValue * 4.0;
      sp.trailingWMAValue = sp.ring_trailingWMAIdx_inReal[sp.ringPos_trailingWMAIdx];
      sp.smoothedValue = sp.periodWMASum * 0.1;
      sp.periodWMASum -= sp.periodWMASub;
      /* Remember the smoothedValue into the smoothPrice
       * circular buffer.
       */
      sp.cb_smoothPrice[sp.smoothPrice_Idx] = sp.smoothedValue;
      if( sp.streamParity == 0 ) {
         /* Do the Hilbert Transforms for even price bar */
         sp.hilbertTempReal = sp.a * sp.smoothedValue;
         sp.detrender = 0 - sp.detrender_Even[sp.hilbertIdx];
         sp.detrender_Even[sp.hilbertIdx] = sp.hilbertTempReal;
         sp.detrender += sp.hilbertTempReal;
         sp.detrender -= sp.prev_detrender_Even;
         sp.prev_detrender_Even = sp.b * sp.prev_detrender_input_Even;
         sp.detrender += sp.prev_detrender_Even;
         sp.prev_detrender_input_Even = sp.smoothedValue;
         sp.detrender *= adjustedPrevPeriod;
         sp.hilbertTempReal = sp.a * sp.detrender;
         sp.Q1 = 0 - sp.Q1_Even[sp.hilbertIdx];
         sp.Q1_Even[sp.hilbertIdx] = sp.hilbertTempReal;
         sp.Q1 += sp.hilbertTempReal;
         sp.Q1 -= sp.prev_Q1_Even;
         sp.prev_Q1_Even = sp.b * sp.prev_Q1_input_Even;
         sp.Q1 += sp.prev_Q1_Even;
         sp.prev_Q1_input_Even = sp.detrender;
         sp.Q1 *= adjustedPrevPeriod;
         sp.hilbertTempReal = sp.a * sp.I1ForEvenPrev3;
         sp.jI = 0 - sp.jI_Even[sp.hilbertIdx];
         sp.jI_Even[sp.hilbertIdx] = sp.hilbertTempReal;
         sp.jI += sp.hilbertTempReal;
         sp.jI -= sp.prev_jI_Even;
         sp.prev_jI_Even = sp.b * sp.prev_jI_input_Even;
         sp.jI += sp.prev_jI_Even;
         sp.prev_jI_input_Even = sp.I1ForEvenPrev3;
         sp.jI *= adjustedPrevPeriod;
         sp.hilbertTempReal = sp.a * sp.Q1;
         sp.jQ = 0 - sp.jQ_Even[sp.hilbertIdx];
         sp.jQ_Even[sp.hilbertIdx] = sp.hilbertTempReal;
         sp.jQ += sp.hilbertTempReal;
         sp.jQ -= sp.prev_jQ_Even;
         sp.prev_jQ_Even = sp.b * sp.prev_jQ_input_Even;
         sp.jQ += sp.prev_jQ_Even;
         sp.prev_jQ_input_Even = sp.Q1;
         sp.jQ *= adjustedPrevPeriod;
         if( ++sp.hilbertIdx == 3 ) {
            sp.hilbertIdx = 0;
         }
         sp.Q2 = Math.FusedMultiplyAdd(0.2, sp.Q1 + sp.jI, 0.8 * sp.prevQ2);
         sp.I2 = Math.FusedMultiplyAdd(0.2, sp.I1ForEvenPrev3 - sp.jQ, 0.8 * sp.prevI2);
         /* The variable I1 is the detrender delayed for
          * 3 price bars.
          *
          * Save the current detrender value for being
          * used by the "odd" logic later.
          */
         sp.I1ForOddPrev3 = sp.I1ForOddPrev2;
         sp.I1ForOddPrev2 = sp.detrender;
      } else {
         /* Do the Hilbert Transforms for odd price bar */
         sp.hilbertTempReal = sp.a * sp.smoothedValue;
         sp.detrender = 0 - sp.detrender_Odd[sp.hilbertIdx];
         sp.detrender_Odd[sp.hilbertIdx] = sp.hilbertTempReal;
         sp.detrender += sp.hilbertTempReal;
         sp.detrender -= sp.prev_detrender_Odd;
         sp.prev_detrender_Odd = sp.b * sp.prev_detrender_input_Odd;
         sp.detrender += sp.prev_detrender_Odd;
         sp.prev_detrender_input_Odd = sp.smoothedValue;
         sp.detrender *= adjustedPrevPeriod;
         sp.hilbertTempReal = sp.a * sp.detrender;
         sp.Q1 = 0 - sp.Q1_Odd[sp.hilbertIdx];
         sp.Q1_Odd[sp.hilbertIdx] = sp.hilbertTempReal;
         sp.Q1 += sp.hilbertTempReal;
         sp.Q1 -= sp.prev_Q1_Odd;
         sp.prev_Q1_Odd = sp.b * sp.prev_Q1_input_Odd;
         sp.Q1 += sp.prev_Q1_Odd;
         sp.prev_Q1_input_Odd = sp.detrender;
         sp.Q1 *= adjustedPrevPeriod;
         sp.hilbertTempReal = sp.a * sp.I1ForOddPrev3;
         sp.jI = 0 - sp.jI_Odd[sp.hilbertIdx];
         sp.jI_Odd[sp.hilbertIdx] = sp.hilbertTempReal;
         sp.jI += sp.hilbertTempReal;
         sp.jI -= sp.prev_jI_Odd;
         sp.prev_jI_Odd = sp.b * sp.prev_jI_input_Odd;
         sp.jI += sp.prev_jI_Odd;
         sp.prev_jI_input_Odd = sp.I1ForOddPrev3;
         sp.jI *= adjustedPrevPeriod;
         sp.hilbertTempReal = sp.a * sp.Q1;
         sp.jQ = 0 - sp.jQ_Odd[sp.hilbertIdx];
         sp.jQ_Odd[sp.hilbertIdx] = sp.hilbertTempReal;
         sp.jQ += sp.hilbertTempReal;
         sp.jQ -= sp.prev_jQ_Odd;
         sp.prev_jQ_Odd = sp.b * sp.prev_jQ_input_Odd;
         sp.jQ += sp.prev_jQ_Odd;
         sp.prev_jQ_input_Odd = sp.Q1;
         sp.jQ *= adjustedPrevPeriod;
         sp.Q2 = Math.FusedMultiplyAdd(0.2, sp.Q1 + sp.jI, 0.8 * sp.prevQ2);
         sp.I2 = Math.FusedMultiplyAdd(0.2, sp.I1ForOddPrev3 - sp.jQ, 0.8 * sp.prevI2);
         /* The varaiable I1 is the detrender delayed for
          * 3 price bars.
          *
          * Save the current detrender value for being
          * used by the "even" logic later.
          */
         sp.I1ForEvenPrev3 = sp.I1ForEvenPrev2;
         sp.I1ForEvenPrev2 = sp.detrender;
      }
      /* Adjust the period for next price bar */
      sp.Re = Math.FusedMultiplyAdd(0.8, sp.Re, 0.2 * (Math.FusedMultiplyAdd(sp.I2, sp.prevI2, sp.Q2 * sp.prevQ2)));
      sp.Im = Math.FusedMultiplyAdd(0.8, sp.Im, 0.2 * (sp.I2 * sp.prevQ2 - sp.Q2 * sp.prevI2));
      sp.prevQ2 = sp.Q2;
      sp.prevI2 = sp.I2;
      sp.tempReal = sp.period;
      if( sp.Im != 0.0 && sp.Re != 0.0 ) {
         sp.period = 360.0 / (Math.Atan(sp.Im / sp.Re) * sp.rad2Deg);
      }
      sp.tempReal2 = 1.5 * sp.tempReal;
      if( sp.period > sp.tempReal2 ) {
         sp.period = sp.tempReal2;
      }
      sp.tempReal2 = 0.67 * sp.tempReal;
      if( sp.period < sp.tempReal2 ) {
         sp.period = sp.tempReal2;
      }
      if( sp.period < 6 ) {
         sp.period = 6;
      } else if( sp.period > 50 ) {
         sp.period = 50;
      }
      sp.period = Math.FusedMultiplyAdd(0.2, sp.period, 0.8 * sp.tempReal);
      sp.smoothPeriod = Math.FusedMultiplyAdd(0.67, sp.smoothPeriod, 0.33 * sp.period);
      /* Compute Dominant Cycle Phase */
      sp.DCPeriod = sp.smoothPeriod + 0.5;
      sp.DCPeriodInt = (int)sp.DCPeriod;
      sp.realPart = 0.0;
      sp.imagPart = 0.0;
      /* idx is used to iterate for up to 50 of the last
       * value of smoothPrice.
       */
      sp.idx = sp.smoothPrice_Idx;
      for( sp.i = 0; sp.i < sp.DCPeriodInt; sp.i += 1 ) {
         sp.tempReal = (double)sp.i * sp.constDeg2RadBy360 / (double)sp.DCPeriodInt;
         sp.tempReal2 = sp.cb_smoothPrice[sp.idx];
         sp.realPart += Math.Sin(sp.tempReal) * sp.tempReal2;
         sp.imagPart += Math.Cos(sp.tempReal) * sp.tempReal2;
         if( sp.idx == 0 ) {
            sp.idx = 50 - 1;
         } else {
            sp.idx -= 1;
         }
      }
      sp.tempReal = Math.Abs(sp.imagPart);
      if( sp.tempReal > 0.0 ) {
         sp.DCPhase = Math.Atan(sp.realPart / sp.imagPart) * sp.rad2Deg;
      } else if( sp.tempReal <= 0.01 ) {
         if( sp.realPart < 0.0 ) {
            sp.DCPhase -= 90.0;
         } else if( sp.realPart > 0.0 ) {
            sp.DCPhase += 90.0;
         }
      }
      sp.DCPhase += 90.0;
      /* Compensate for one bar lag of the weighted moving average */
      sp.DCPhase += 360.0 / sp.smoothPeriod;
      if( sp.imagPart < 0.0 ) {
         sp.DCPhase += 180.0;
      }
      if( sp.DCPhase > 315.0 ) {
         sp.DCPhase -= 360.0;
      }
      sp.cur_outReal = sp.DCPhase;
      /* Ooof... let's do the next price bar now! */
      sp.smoothPrice_Idx = sp.smoothPrice_Idx + 1;
      if( sp.smoothPrice_Idx > sp.maxIdx_smoothPrice ) {
         sp.smoothPrice_Idx = 0;
      }
      sp.ring_trailingWMAIdx_inReal[sp.ringPos_trailingWMAIdx] = inReal;
      sp.ringPos_trailingWMAIdx = sp.ringPos_trailingWMAIdx + 1;
      if( sp.ringPos_trailingWMAIdx >= sp.ringCap_trailingWMAIdx ) {
         sp.ringPos_trailingWMAIdx = 0;
      }
      sp.streamParity = 1 - sp.streamParity;
   }

   private RetCode HT_DCPHASE_OpenPass( HT_DCPHASE_Stream sp, ReadOnlySpan<double> inReal, int startIdx, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      int outIdx = 0;
      int i = 0;
      int lookbackTotal = 0;
      int today = 0;
      double tempReal = 0;
      double tempReal2 = 0;
      double adjustedPrevPeriod = 0;
      double period = 0;
      int trailingWMAIdx = 0;
      double periodWMASum = 0;
      double periodWMASub = 0;
      double trailingWMAValue = 0;
      double smoothedValue = 0;
      double a = 0;
      double b = 0;
      double hilbertTempReal = 0;
      int hilbertIdx = 0;
      double[] detrender_Odd = new double[3];
      double[] detrender_Even = new double[3];
      double detrender = 0;
      double prev_detrender_Odd = 0;
      double prev_detrender_Even = 0;
      double prev_detrender_input_Odd = 0;
      double prev_detrender_input_Even = 0;
      double[] Q1_Odd = new double[3];
      double[] Q1_Even = new double[3];
      double Q1 = 0;
      double prev_Q1_Odd = 0;
      double prev_Q1_Even = 0;
      double prev_Q1_input_Odd = 0;
      double prev_Q1_input_Even = 0;
      double[] jI_Odd = new double[3];
      double[] jI_Even = new double[3];
      double jI = 0;
      double prev_jI_Odd = 0;
      double prev_jI_Even = 0;
      double prev_jI_input_Odd = 0;
      double prev_jI_input_Even = 0;
      double[] jQ_Odd = new double[3];
      double[] jQ_Even = new double[3];
      double jQ = 0;
      double prev_jQ_Odd = 0;
      double prev_jQ_Even = 0;
      double prev_jQ_input_Odd = 0;
      double prev_jQ_input_Even = 0;
      double Q2 = 0;
      double I2 = 0;
      double prevQ2 = 0;
      double prevI2 = 0;
      double Re = 0;
      double Im = 0;
      double I1ForOddPrev2 = 0;
      double I1ForOddPrev3 = 0;
      double I1ForEvenPrev2 = 0;
      double I1ForEvenPrev3 = 0;
      double rad2Deg = 0;
      double constDeg2RadBy360 = 0;
      double todayValue = 0;
      double smoothPeriod = 0;
      double[] smoothPrice = [];
      int smoothPrice_Idx = 0;
      int maxIdx_smoothPrice = (50)-1;
      int idx = 0;
      int DCPeriodInt = 0;
      double DCPhase = 0;
      double DCPeriod = 0;
      double imagPart = 0;
      double realPart = 0;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.BadParam;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      a = 0.0962;
      b = 0.5769;
      /* Variable used for the price smoother (a weighted moving average). */
      /* Variables used for the Hilbert Transormation */
      /* Varaible used to keep track of the previous
       * smooth price. In the case of this algorithm,
       * we will never need more than 50 values.
       */
      smoothPrice = new double[maxIdx_smoothPrice+1];
      /* Variable used to calculate the dominant cycle phase */
      /* circular buffer already declared */
      /* Constant */
      tempReal = Math.Atan(1);
      rad2Deg = 45.0 / tempReal;
      constDeg2RadBy360 = tempReal * 8.0;
      /* Identify the minimum number of price bar needed
       * to calculate at least one output.
       */
      lookbackTotal = 63 + this.unstablePeriod[(int)FuncUnstId.HT_DCPHASE];
      /* Move up the start index if there is not
       * enough initial data.
       */
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      outBegIdx = startIdx;
      /* Initialize the price smoother, which is simply a weighted
       * moving average of the price.
       * To understand this algorithm, I strongly suggest to understand
       * first how TA_WMA is done.
       */
      trailingWMAIdx = startIdx - lookbackTotal;
      today = trailingWMAIdx;
      /* Initialization is same as WMA, except loop is unrolled
       * for speed optimization.
       */
      tempReal = inReal[today++];
      periodWMASub = tempReal;
      periodWMASum = tempReal;
      tempReal = inReal[today++];
      periodWMASub += tempReal;
      periodWMASum += tempReal * 2.0;
      tempReal = inReal[today++];
      periodWMASub += tempReal;
      periodWMASum += tempReal * 3.0;
      trailingWMAValue = 0.0;
      /* Subsequent WMA value are evaluated by using
       * the DO_PRICE_WMA macro.
       */
      i = 34;
      do {
         tempReal = inReal[today++];
         periodWMASub += tempReal;
         periodWMASub -= trailingWMAValue;
         periodWMASum += tempReal * 4.0;
         trailingWMAValue = inReal[trailingWMAIdx++];
         smoothedValue = periodWMASum * 0.1;
         periodWMASum -= periodWMASub;
      } while( --i != 0 );
      /* Initialize the circular buffers used by the hilbert
       * transform logic.
       * A buffer is used for odd day and another for even days.
       * This minimize the number of memory access and floating point
       * operations needed (note also that by using static circular buffer,
       * no large dynamic memory allocation is needed for storing
       * intermediate calculation!).
       */
      hilbertIdx = 0;
      detrender_Odd[0] = 0.0;
      detrender_Odd[1] = 0.0;
      detrender_Odd[2] = 0.0;
      detrender_Even[0] = 0.0;
      detrender_Even[1] = 0.0;
      detrender_Even[2] = 0.0;
      detrender = 0.0;
      prev_detrender_Odd = 0.0;
      prev_detrender_Even = 0.0;
      prev_detrender_input_Odd = 0.0;
      prev_detrender_input_Even = 0.0;
      Q1_Odd[0] = 0.0;
      Q1_Odd[1] = 0.0;
      Q1_Odd[2] = 0.0;
      Q1_Even[0] = 0.0;
      Q1_Even[1] = 0.0;
      Q1_Even[2] = 0.0;
      Q1 = 0.0;
      prev_Q1_Odd = 0.0;
      prev_Q1_Even = 0.0;
      prev_Q1_input_Odd = 0.0;
      prev_Q1_input_Even = 0.0;
      jI_Odd[0] = 0.0;
      jI_Odd[1] = 0.0;
      jI_Odd[2] = 0.0;
      jI_Even[0] = 0.0;
      jI_Even[1] = 0.0;
      jI_Even[2] = 0.0;
      jI = 0.0;
      prev_jI_Odd = 0.0;
      prev_jI_Even = 0.0;
      prev_jI_input_Odd = 0.0;
      prev_jI_input_Even = 0.0;
      jQ_Odd[0] = 0.0;
      jQ_Odd[1] = 0.0;
      jQ_Odd[2] = 0.0;
      jQ_Even[0] = 0.0;
      jQ_Even[1] = 0.0;
      jQ_Even[2] = 0.0;
      jQ = 0.0;
      prev_jQ_Odd = 0.0;
      prev_jQ_Even = 0.0;
      prev_jQ_input_Odd = 0.0;
      prev_jQ_input_Even = 0.0;
      period = 0.0;
      outIdx = 0;
      prevQ2 = 0.0;
      prevI2 = prevQ2;
      Im = 0.0;
      Re = Im;
      I1ForEvenPrev3 = 0.0;
      I1ForOddPrev3 = I1ForEvenPrev3;
      I1ForEvenPrev2 = 0.0;
      I1ForOddPrev2 = I1ForEvenPrev2;
      smoothPeriod = 0.0;
      for( i = 0; i < 50; i += 1 ) {
         smoothPrice[i] = 0.0;
      }
      /* The code is speed optimized and is most likely very
       * hard to follow if you do not already know well the
       * original algorithm.
       * To understadn better, it is strongly suggested to look
       * first at the Excel implementation in "test_MAMA.xls" included
       * in this package.
       */
      DCPhase = 0.0;
      while( today <= endIdx ) {
         adjustedPrevPeriod = Math.FusedMultiplyAdd(0.075, period, 0.54);
         todayValue = inReal[today];
         periodWMASub += todayValue;
         periodWMASub -= trailingWMAValue;
         periodWMASum += todayValue * 4.0;
         trailingWMAValue = inReal[trailingWMAIdx++];
         smoothedValue = periodWMASum * 0.1;
         periodWMASum -= periodWMASub;
         /* Remember the smoothedValue into the smoothPrice
          * circular buffer.
          */
         smoothPrice[smoothPrice_Idx] = smoothedValue;
         if( today % 2 == 0 ) {
            /* Do the Hilbert Transforms for even price bar */
            hilbertTempReal = a * smoothedValue;
            detrender = 0 - detrender_Even[hilbertIdx];
            detrender_Even[hilbertIdx] = hilbertTempReal;
            detrender += hilbertTempReal;
            detrender -= prev_detrender_Even;
            prev_detrender_Even = b * prev_detrender_input_Even;
            detrender += prev_detrender_Even;
            prev_detrender_input_Even = smoothedValue;
            detrender *= adjustedPrevPeriod;
            hilbertTempReal = a * detrender;
            Q1 = 0 - Q1_Even[hilbertIdx];
            Q1_Even[hilbertIdx] = hilbertTempReal;
            Q1 += hilbertTempReal;
            Q1 -= prev_Q1_Even;
            prev_Q1_Even = b * prev_Q1_input_Even;
            Q1 += prev_Q1_Even;
            prev_Q1_input_Even = detrender;
            Q1 *= adjustedPrevPeriod;
            hilbertTempReal = a * I1ForEvenPrev3;
            jI = 0 - jI_Even[hilbertIdx];
            jI_Even[hilbertIdx] = hilbertTempReal;
            jI += hilbertTempReal;
            jI -= prev_jI_Even;
            prev_jI_Even = b * prev_jI_input_Even;
            jI += prev_jI_Even;
            prev_jI_input_Even = I1ForEvenPrev3;
            jI *= adjustedPrevPeriod;
            hilbertTempReal = a * Q1;
            jQ = 0 - jQ_Even[hilbertIdx];
            jQ_Even[hilbertIdx] = hilbertTempReal;
            jQ += hilbertTempReal;
            jQ -= prev_jQ_Even;
            prev_jQ_Even = b * prev_jQ_input_Even;
            jQ += prev_jQ_Even;
            prev_jQ_input_Even = Q1;
            jQ *= adjustedPrevPeriod;
            if( ++hilbertIdx == 3 ) {
               hilbertIdx = 0;
            }
            Q2 = Math.FusedMultiplyAdd(0.2, Q1 + jI, 0.8 * prevQ2);
            I2 = Math.FusedMultiplyAdd(0.2, I1ForEvenPrev3 - jQ, 0.8 * prevI2);
            /* The variable I1 is the detrender delayed for
             * 3 price bars.
             *
             * Save the current detrender value for being
             * used by the "odd" logic later.
             */
            I1ForOddPrev3 = I1ForOddPrev2;
            I1ForOddPrev2 = detrender;
         } else {
            /* Do the Hilbert Transforms for odd price bar */
            hilbertTempReal = a * smoothedValue;
            detrender = 0 - detrender_Odd[hilbertIdx];
            detrender_Odd[hilbertIdx] = hilbertTempReal;
            detrender += hilbertTempReal;
            detrender -= prev_detrender_Odd;
            prev_detrender_Odd = b * prev_detrender_input_Odd;
            detrender += prev_detrender_Odd;
            prev_detrender_input_Odd = smoothedValue;
            detrender *= adjustedPrevPeriod;
            hilbertTempReal = a * detrender;
            Q1 = 0 - Q1_Odd[hilbertIdx];
            Q1_Odd[hilbertIdx] = hilbertTempReal;
            Q1 += hilbertTempReal;
            Q1 -= prev_Q1_Odd;
            prev_Q1_Odd = b * prev_Q1_input_Odd;
            Q1 += prev_Q1_Odd;
            prev_Q1_input_Odd = detrender;
            Q1 *= adjustedPrevPeriod;
            hilbertTempReal = a * I1ForOddPrev3;
            jI = 0 - jI_Odd[hilbertIdx];
            jI_Odd[hilbertIdx] = hilbertTempReal;
            jI += hilbertTempReal;
            jI -= prev_jI_Odd;
            prev_jI_Odd = b * prev_jI_input_Odd;
            jI += prev_jI_Odd;
            prev_jI_input_Odd = I1ForOddPrev3;
            jI *= adjustedPrevPeriod;
            hilbertTempReal = a * Q1;
            jQ = 0 - jQ_Odd[hilbertIdx];
            jQ_Odd[hilbertIdx] = hilbertTempReal;
            jQ += hilbertTempReal;
            jQ -= prev_jQ_Odd;
            prev_jQ_Odd = b * prev_jQ_input_Odd;
            jQ += prev_jQ_Odd;
            prev_jQ_input_Odd = Q1;
            jQ *= adjustedPrevPeriod;
            Q2 = Math.FusedMultiplyAdd(0.2, Q1 + jI, 0.8 * prevQ2);
            I2 = Math.FusedMultiplyAdd(0.2, I1ForOddPrev3 - jQ, 0.8 * prevI2);
            /* The varaiable I1 is the detrender delayed for
             * 3 price bars.
             *
             * Save the current detrender value for being
             * used by the "even" logic later.
             */
            I1ForEvenPrev3 = I1ForEvenPrev2;
            I1ForEvenPrev2 = detrender;
         }
         /* Adjust the period for next price bar */
         Re = Math.FusedMultiplyAdd(0.8, Re, 0.2 * (Math.FusedMultiplyAdd(I2, prevI2, Q2 * prevQ2)));
         Im = Math.FusedMultiplyAdd(0.8, Im, 0.2 * (I2 * prevQ2 - Q2 * prevI2));
         prevQ2 = Q2;
         prevI2 = I2;
         tempReal = period;
         if( Im != 0.0 && Re != 0.0 ) {
            period = 360.0 / (Math.Atan(Im / Re) * rad2Deg);
         }
         tempReal2 = 1.5 * tempReal;
         if( period > tempReal2 ) {
            period = tempReal2;
         }
         tempReal2 = 0.67 * tempReal;
         if( period < tempReal2 ) {
            period = tempReal2;
         }
         if( period < 6 ) {
            period = 6;
         } else if( period > 50 ) {
            period = 50;
         }
         period = Math.FusedMultiplyAdd(0.2, period, 0.8 * tempReal);
         smoothPeriod = Math.FusedMultiplyAdd(0.67, smoothPeriod, 0.33 * period);
         /* Compute Dominant Cycle Phase */
         DCPeriod = smoothPeriod + 0.5;
         DCPeriodInt = (int)DCPeriod;
         realPart = 0.0;
         imagPart = 0.0;
         /* idx is used to iterate for up to 50 of the last
          * value of smoothPrice.
          */
         idx = smoothPrice_Idx;
         for( i = 0; i < DCPeriodInt; i += 1 ) {
            tempReal = (double)i * constDeg2RadBy360 / (double)DCPeriodInt;
            tempReal2 = smoothPrice[idx];
            realPart += Math.Sin(tempReal) * tempReal2;
            imagPart += Math.Cos(tempReal) * tempReal2;
            if( idx == 0 ) {
               idx = 50 - 1;
            } else {
               idx -= 1;
            }
         }
         tempReal = Math.Abs(imagPart);
         if( tempReal > 0.0 ) {
            DCPhase = Math.Atan(realPart / imagPart) * rad2Deg;
         } else if( tempReal <= 0.01 ) {
            if( realPart < 0.0 ) {
               DCPhase -= 90.0;
            } else if( realPart > 0.0 ) {
               DCPhase += 90.0;
            }
         }
         DCPhase += 90.0;
         /* Compensate for one bar lag of the weighted moving average */
         DCPhase += 360.0 / smoothPeriod;
         if( imagPart < 0.0 ) {
            DCPhase += 180.0;
         }
         if( DCPhase > 315.0 ) {
            DCPhase -= 360.0;
         }
         if( today >= startIdx ) {
            outReal[outIdx++ * outStride] = DCPhase;
         }
         /* Ooof... let's do the next price bar now! */
         smoothPrice_Idx++;
         if( smoothPrice_Idx > maxIdx_smoothPrice ) { smoothPrice_Idx = 0; }
         today += 1;
      }
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      int cap_trailingWMAIdx = today - trailingWMAIdx;
      if( cap_trailingWMAIdx < 0 || cap_trailingWMAIdx > historyLen ) {
         return RetCode.InternalError;
      }
      int allocN_trailingWMAIdx = (cap_trailingWMAIdx > 0)? cap_trailingWMAIdx : 1;
      double[] capRing_trailingWMAIdx_inReal = new double[allocN_trailingWMAIdx];
      inReal.Slice(historyLen - cap_trailingWMAIdx, cap_trailingWMAIdx).CopyTo(capRing_trailingWMAIdx_inReal);
      int capCb_smoothPrice = maxIdx_smoothPrice + 1;
      if( capCb_smoothPrice > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      sp.i = i;
      sp.tempReal = tempReal;
      sp.tempReal2 = tempReal2;
      sp.period = period;
      sp.periodWMASum = periodWMASum;
      sp.periodWMASub = periodWMASub;
      sp.trailingWMAValue = trailingWMAValue;
      sp.smoothedValue = smoothedValue;
      sp.a = a;
      sp.b = b;
      sp.hilbertTempReal = hilbertTempReal;
      sp.hilbertIdx = hilbertIdx;
      sp.detrender_Odd = detrender_Odd;
      sp.detrender_Even = detrender_Even;
      sp.detrender = detrender;
      sp.prev_detrender_Odd = prev_detrender_Odd;
      sp.prev_detrender_Even = prev_detrender_Even;
      sp.prev_detrender_input_Odd = prev_detrender_input_Odd;
      sp.prev_detrender_input_Even = prev_detrender_input_Even;
      sp.Q1_Odd = Q1_Odd;
      sp.Q1_Even = Q1_Even;
      sp.Q1 = Q1;
      sp.prev_Q1_Odd = prev_Q1_Odd;
      sp.prev_Q1_Even = prev_Q1_Even;
      sp.prev_Q1_input_Odd = prev_Q1_input_Odd;
      sp.prev_Q1_input_Even = prev_Q1_input_Even;
      sp.jI_Odd = jI_Odd;
      sp.jI_Even = jI_Even;
      sp.jI = jI;
      sp.prev_jI_Odd = prev_jI_Odd;
      sp.prev_jI_Even = prev_jI_Even;
      sp.prev_jI_input_Odd = prev_jI_input_Odd;
      sp.prev_jI_input_Even = prev_jI_input_Even;
      sp.jQ_Odd = jQ_Odd;
      sp.jQ_Even = jQ_Even;
      sp.jQ = jQ;
      sp.prev_jQ_Odd = prev_jQ_Odd;
      sp.prev_jQ_Even = prev_jQ_Even;
      sp.prev_jQ_input_Odd = prev_jQ_input_Odd;
      sp.prev_jQ_input_Even = prev_jQ_input_Even;
      sp.Q2 = Q2;
      sp.I2 = I2;
      sp.prevQ2 = prevQ2;
      sp.prevI2 = prevI2;
      sp.Re = Re;
      sp.Im = Im;
      sp.I1ForOddPrev2 = I1ForOddPrev2;
      sp.I1ForOddPrev3 = I1ForOddPrev3;
      sp.I1ForEvenPrev2 = I1ForEvenPrev2;
      sp.I1ForEvenPrev3 = I1ForEvenPrev3;
      sp.rad2Deg = rad2Deg;
      sp.constDeg2RadBy360 = constDeg2RadBy360;
      sp.smoothPeriod = smoothPeriod;
      sp.idx = idx;
      sp.DCPeriodInt = DCPeriodInt;
      sp.DCPhase = DCPhase;
      sp.DCPeriod = DCPeriod;
      sp.imagPart = imagPart;
      sp.realPart = realPart;
      sp.smoothPrice_Idx = smoothPrice_Idx;
      sp.maxIdx_smoothPrice = maxIdx_smoothPrice;
      sp.streamParity = historyLen % 2;
      sp.ringPos_trailingWMAIdx = 0;
      sp.ringCap_trailingWMAIdx = cap_trailingWMAIdx;
      sp.ring_trailingWMAIdx_inReal = capRing_trailingWMAIdx_inReal;
      sp.cbSize_smoothPrice = capCb_smoothPrice;
      sp.cb_smoothPrice = smoothPrice;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   private RetCode HT_DCPHASE_OpenImpl( HT_DCPHASE_Stream sp, ReadOnlySpan<double> inReal, int startIdx )
   {
      double[] sink_outReal = new double[1];
      return HT_DCPHASE_OpenPass( sp, inReal, startIdx, out _, out _, sink_outReal, 0 );
   }

   private RetCode HT_DCPHASE_OpenAndFillImpl( HT_DCPHASE_Stream sp, ReadOnlySpan<double> inReal, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      outBegIdx = 0;
      outNBElement = 0;
      if( outReal.Overlaps(inReal) ) {
         return RetCode.BadParam;
      }
      return HT_DCPHASE_OpenPass( sp, inReal, 0, out outBegIdx, out outNBElement, outReal, 1 );
   }

   private RetCode HT_DCPHASE_OpenAndFillInternalImpl( HT_DCPHASE_Stream sp, ReadOnlySpan<double> inReal, int startIdx, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      return HT_DCPHASE_OpenPass(sp, inReal, startIdx, out outBegIdx, out outNBElement, outReal, 1);
   }

   /* HT_DCPHASE_OpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal HT_DCPHASE_Stream HT_DCPHASE_OpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      HT_DCPHASE_Stream sp = new HT_DCPHASE_Stream(this);
      RetCode retCode = HT_DCPHASE_OpenAndFillInternalImpl(sp, inReal, startIdx, out outBegIdx, out outNBElement, outReal);
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("HT_DCPHASE", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind HT_DCPHASE_Open (composition seam). */
   internal HT_DCPHASE_Stream HT_DCPHASE_OpenInternal( ReadOnlySpan<double> inReal, int startIdx )
   {
      HT_DCPHASE_Stream sp = new HT_DCPHASE_Stream(this);
      RetCode retCode = HT_DCPHASE_OpenImpl(sp, inReal, startIdx);
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("HT_DCPHASE", "open", retCode);
   }

   /// <summary>Open a live <c>HT_DCPHASE</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="HT_DCPHASE_Stream.Value"/> starts at the last
   /// history bar's value — bit-identical to what <c>HT_DCPHASE</c> reports for
   /// that bar.</para>
   /// <para>The history must hold at least <c>HT_DCPHASE_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>HT_DCPHASE_OpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">Price series to analyze. The warm-up history, oldest bar first.</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>HT_DCPHASE_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentException">An input series is empty — which is what a null array becomes, since a
   /// span cannot be null.</exception>
   public HT_DCPHASE_Stream HT_DCPHASE_Open( ReadOnlySpan<double> inReal )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentException("inReal is empty", nameof(inReal), RetCode.BadParam);
      return HT_DCPHASE_OpenInternal(inReal, 0);
   }

   /// <summary><c>HT_DCPHASE_Open</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>HT_DCPHASE</c> produces
   /// over the same series, so no separate batch call is needed for the warm-up
   /// plot.</para>
   /// <para>Output arrays must hold <c>historyLen - HT_DCPHASE_Lookback(...)</c>
   /// values and must not alias the inputs or each other — this path writes the
   /// outputs and then reads the input tail to seed its rings, so the batch
   /// tier's in-place allowance does not carry over here.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="HT_DCPHASE_Stream.FillRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">Price series to analyze. The warm-up history, oldest bar first.</param>
   /// <param name="outReal">Dominant cycle phase in degrees. Must hold at least <c>historyLen -
   /// HT_DCPHASE_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>HT_DCPHASE_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, or an output array aliases an input or another
   /// output.</exception>
   /// <exception cref="System.ArgumentException">An input series is empty, or an output overlaps an input or another
   /// output.</exception>
   public HT_DCPHASE_Stream HT_DCPHASE_OpenAndFill( ReadOnlySpan<double> inReal, Span<double> outReal )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentException("inReal is empty", nameof(inReal), RetCode.BadParam);
      HT_DCPHASE_Stream sp = new HT_DCPHASE_Stream(this);
      RetCode retCode = HT_DCPHASE_OpenAndFillImpl(sp, inReal, out int outBegIdx, out int outNBElement, outReal);
      sp.fillRange = new OutRange(outBegIdx, outNBElement);
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("HT_DCPHASE", "openAndFill", retCode);
   }
