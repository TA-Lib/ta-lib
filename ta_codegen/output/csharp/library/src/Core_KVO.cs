   }
   /// <summary>
   /// Klinger Volume Oscillator: each bar's volume is signed by the direction of
   /// its high-low-close sum and weighted by where the bar's own range sits
   /// inside the cumulative range of the current trend run, then the resulting
   /// volume force is smoothed twice and differenced. Klinger's reading is that
   /// volume alone says how much trading happened but not what it accomplished,
   /// so he scales it by the share of the trend's accumulated range that this
   /// bar actually covered. The oscillator crosses zero as the balance of that
   /// force changes hands, and crosses its own trigger line earlier.
   /// </summary>
   /// <remarks>
   /// <para>
   /// Formula and more info at
   /// <see href="https://ta-lib.org/functions/kvo">ta-lib.org/functions/kvo</see>.
   /// </para>
   /// <list type="bullet">
   /// <item><description>The trend is <b>held</b> when the high-low-close sum repeats, which is the article's own tenet: the existing trend is maintained on equality. A reading that breaks the tie in either direction changes every later bar, because the cumulative range is reset by a trend change.</description></item>
   /// <item><description>The cumulative range is reset by every trend change, so two calls starting at different bars carry different range state only until the first trend change after both; what remains between them is the seed error of the three averages, which fades at the rate of the longest period. KVO converges, but as a small difference of two large averages it needs more bars than one of them would.</description></item>
   /// <item><description>All three exponential averages are seeded from the volume force of the same anchor bar rather than from a simple average of their own first inputs, so one warm-up covers all three. KVO is exactly zero on that seed bar, which falls inside the warm-up and is never output. <c>TA_SetUnstablePeriod(TA_FUNC_UNST_EMA, ...)</c> discards more of that warm-up.</description></item>
   /// <item><description>The weight is the 1997 form, <c>|2*(dm/cm) - 1|</c>, which is what the December 1997 Traders' Tips print. Some later implementations use <c>|2*(dm/cm - 1)|</c>, which is a different series.</description></item>
   /// <item><description>A cumulative range of exactly zero leaves the volume force at zero rather than dividing.</description></item>
   /// </list>
   /// <para>
   /// This is the <c>float[]</c> overload: input elements are widened to
   /// <c>double</c> as they are read and all arithmetic is performed in
   /// <c>double</c>, so a result beyond <c>float</c> range is still
   /// representable.
   /// </para>
   /// <para>
   /// Values are written only where the indicator is defined. The returned
   /// <see cref="OutRange"/> says where they start and how many there are, and
   /// the library never pads with NaN. A valid range that ends before
   /// <c>KvoLookback</c> is a <b>success with no values</b> (<c>Count == 0</c>),
   /// not an error.
   /// </para>
   /// <para>
   /// Every exception it throws, except the runtime's own
   /// <c>OutOfMemoryException</c>, implements <see cref="ITALibFailure"/>, which
   /// carries the <see cref="RetCode"/>.
   /// </para>
   /// </remarks>
   /// <param name="startIdx">First bar of the requested range (inclusive).</param>
   /// <param name="endIdx">Last bar of the requested range (inclusive).</param>
   /// <param name="inHigh">High price series.</param>
   /// <param name="inLow">Low price series.</param>
   /// <param name="inClose">Close price series.</param>
   /// <param name="inVolume">Volume series.</param>
   /// <param name="optInFastPeriod">Period of the faster smoothing of the volume force (default 34; range
   /// 2..100000; <c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowPeriod">Period of the slower smoothing of the volume force (default 55; range
   /// 2..100000; <c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSignalPeriod">Smoothing period of the trigger line (default 13; range 2..100000;
   /// <c>int.MinValue</c> selects the default).</param>
   /// <param name="outKVO">Klinger Volume Oscillator. Must hold at least <c>endIdx - max(startIdx,
   /// KvoLookback(...)) + 1</c> values, and never be empty: an empty span is an
   /// absent output.</param>
   /// <param name="outKVOSignal">Trigger line, an exponential average of the oscillator. Must hold at least
   /// <c>endIdx - max(startIdx, KvoLookback(...)) + 1</c> values, and never be
   /// empty: an empty span is an absent output.</param>
   /// <returns>The range written: <c>BegIdx</c> is the first bar with a value,
