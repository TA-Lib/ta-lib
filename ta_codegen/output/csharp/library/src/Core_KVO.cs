   /// <summary>One <c>KVO</c> output set, in batch output order.</summary>
   /// <remarks>
   /// <para>Equality is the compiler-generated record-struct equality, which compares
   /// each component with <see cref="System.Double.Equals(System.Double)"/>, not
   /// <c>==</c>: any two <c>NaN</c> payloads compare equal, and <c>0.0</c>
   /// equals <c>-0.0</c>. Compare
   /// <see cref="System.BitConverter.DoubleToInt64Bits(double)"/> per component
   /// when bit-level identity is what you mean.</para>
   /// </remarks>
   /// <param name="KVO">Klinger Volume Oscillator.</param>
   /// <param name="KVOSignal">Trigger line, an exponential average of the oscillator.</param>
   public readonly record struct KvoValue( double KVO, double KVOSignal );

   /// <summary>A live <c>KVO</c> stream: one value per closed bar, bit-identical to
   /// <c>KVO</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.KvoOpen"/>. There is no close and nothing to
   /// dispose — the handle is ordinary managed state, and an unreferenced handle
   /// is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class KvoStream
   {
      internal Core core;
      internal int optInFastPeriod;
      internal int optInSlowPeriod;
      internal int optInSignalPeriod;
      internal double kFast;
      internal double kSlow;
      internal double kSignal;
      internal double betaFast;
      internal double betaSlow;
      internal double betaSignal;
      internal double prevHlc;
      internal double prevDm;
      internal double cm;
      internal double emaFast;
      internal double emaSlow;
      internal double signalValue;
      internal double prevTrend;
      internal double cur_outKVO;
      internal double cur_outKVOSignal;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal KvoStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Kvo</c> reports over the same bars: the opener sets it
      /// to <c>(lookback, historyLen - lookback)</c>, every accepted <c>Update</c>
      /// adds one to the count — a rejected one changes nothing, and neither does
      /// <c>Peek</c> — and <c>Clone</c> carries it verbatim. A plain <c>Open</c>
      /// hands back only the last value, a subset of this range, because the caller
      /// chose not to take the fill.</para>
      /// <para>The last bar it can reach is <see cref="Core.IndexMax"/>; past that
      /// <c>Update</c> and <c>Advance</c> throw.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      /// <summary>Count one bar this stream was not fed: <see cref="OutRange"/> advances by
      /// one and nothing else moves.</summary>
      /// <remarks>
      /// <para><see cref="Value"/> keeps answering the previous output, which is this
      /// bar's output too. For a bar the caller leaves out: one an <c>Update</c>
      /// rejected and that will not be re-fed, or a session with no print. Without
      /// it two handles on one feed drift a bar apart when only one of them skips.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, the last one the batch tier
      /// can address and the last this handle will count. <c>Update</c> throws the
      /// same there.</para>
      /// </remarks>
      public void Advance()
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("KVO", "advance", RetCode.OutOfRangeEndIndex);
         outRangeCount++;
      }

      internal KvoStream( KvoStream other )
      {
         this.core = other.core;
         this.optInFastPeriod = other.optInFastPeriod;
         this.optInSlowPeriod = other.optInSlowPeriod;
         this.optInSignalPeriod = other.optInSignalPeriod;
         this.kFast = other.kFast;
         this.kSlow = other.kSlow;
         this.kSignal = other.kSignal;
         this.betaFast = other.betaFast;
         this.betaSlow = other.betaSlow;
         this.betaSignal = other.betaSignal;
         this.prevHlc = other.prevHlc;
         this.prevDm = other.prevDm;
         this.cm = other.cm;
         this.emaFast = other.emaFast;
         this.emaSlow = other.emaSlow;
         this.signalValue = other.signalValue;
         this.prevTrend = other.prevTrend;
         this.cur_outKVO = other.cur_outKVO;
         this.cur_outKVOSignal = other.cur_outKVOSignal;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so nothing moves — <see cref="OutRange"/> included — and
      /// <see cref="Value"/> still answers the previous value. Re-feed the bar when
      /// a corrected value arrives, or call <see cref="Advance"/> to count it and
      /// carry on; two handles on one feed drift a bar apart if neither happens.
      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, which no re-feed clears: the
      /// handle has run out of index domain and only a shorter history can start a
      /// new one.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <param name="inVolume">This bar's volume.</param>
      /// <returns>The value at the bar just committed.</returns>
      public KvoValue Update( double inHigh, double inLow, double inClose, double inVolume )
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("KVO", "update", RetCode.OutOfRangeEndIndex);
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) || !double.IsFinite(inVolume) ) throw Core.NonFiniteBar("KVO", "update", !double.IsFinite(inHigh) ? nameof(inHigh) : !double.IsFinite(inLow) ? nameof(inLow) : !double.IsFinite(inClose) ? nameof(inClose) : nameof(inVolume));
         core.KvoStepImpl(this, inHigh, inLow, inClose, inVolume);
         outRangeCount++;
         return new KvoValue(cur_outKVO, cur_outKVOSignal);
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.IndexMax"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <param name="inVolume">This bar's volume.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public KvoValue Peek( double inHigh, double inLow, double inClose, double inVolume )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) || !double.IsFinite(inVolume) ) throw Core.NonFiniteBar("KVO", "peek", !double.IsFinite(inHigh) ? nameof(inHigh) : !double.IsFinite(inLow) ? nameof(inLow) : !double.IsFinite(inClose) ? nameof(inClose) : nameof(inVolume));
         KvoStream sp = this;
         double hlc = 0.0;
         double dmToday = 0.0;
         double cmBase = 0.0;
         double vf = 0.0;
         double kvoValue = 0.0;
         double trend = 0.0;
         double cm = sp.cm;
         double cur_outKVO = 0.0;
         double cur_outKVOSignal = 0.0;
         double emaFast = sp.emaFast;
         double emaSlow = sp.emaSlow;
         double signalValue = sp.signalValue;
         hlc = inHigh + inLow + inClose;
         dmToday = inHigh - inLow;
         trend = (hlc > sp.prevHlc) ? 1.0 : sp.prevTrend;
         trend = (hlc < sp.prevHlc) ? -1.0 : trend;
         cmBase = (trend != sp.prevTrend) ? sp.prevDm : cm;
         cm = cmBase + dmToday;
         if( cm == 0.0 ) {
            vf = 0.0;
         } else {
            vf = inVolume * Math.Abs(2.0 * (dmToday / cm) - 1.0) * 100.0 * trend;
         }
         emaFast = Math.FusedMultiplyAdd(sp.betaFast, emaFast, sp.kFast * vf);
         emaSlow = Math.FusedMultiplyAdd(sp.betaSlow, emaSlow, sp.kSlow * vf);
         kvoValue = emaFast - emaSlow;
         signalValue = Math.FusedMultiplyAdd(sp.betaSignal, signalValue, sp.kSignal * kvoValue);
         cur_outKVO = kvoValue;
         cur_outKVOSignal = signalValue;
         return new KvoValue(cur_outKVO, cur_outKVOSignal);
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public KvoValue Value => new KvoValue(cur_outKVO, cur_outKVOSignal);

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public KvoStream Clone()
      {
         return new KvoStream(this);
      }
   }

   private void KvoStepImpl( KvoStream sp, double inHigh, double inLow, double inClose, double inVolume )
   {
      double hlc = 0.0;
      double dmToday = 0.0;
      double cmBase = 0.0;
      double vf = 0.0;
      double kvoValue = 0.0;
      double trend = 0.0;
      hlc = inHigh + inLow + inClose;
      dmToday = inHigh - inLow;
      trend = (hlc > sp.prevHlc) ? 1.0 : sp.prevTrend;
      trend = (hlc < sp.prevHlc) ? -1.0 : trend;
      cmBase = (trend != sp.prevTrend) ? sp.prevDm : sp.cm;
      sp.cm = cmBase + dmToday;
      if( sp.cm == 0.0 ) {
         vf = 0.0;
      } else {
         vf = inVolume * Math.Abs(2.0 * (dmToday / sp.cm) - 1.0) * 100.0 * trend;
      }
      sp.emaFast = Math.FusedMultiplyAdd(sp.betaFast, sp.emaFast, sp.kFast * vf);
      sp.emaSlow = Math.FusedMultiplyAdd(sp.betaSlow, sp.emaSlow, sp.kSlow * vf);
      kvoValue = sp.emaFast - sp.emaSlow;
      sp.signalValue = Math.FusedMultiplyAdd(sp.betaSignal, sp.signalValue, sp.kSignal * kvoValue);
      sp.cur_outKVO = kvoValue;
      sp.cur_outKVOSignal = sp.signalValue;
      sp.prevHlc = hlc;
      sp.prevDm = dmToday;
      sp.prevTrend = trend;
   }

   private RetCode KvoOpenImpl( KvoStream sp, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, ReadOnlySpan<double> inVolume, int startIdx, int optInFastPeriod, int optInSlowPeriod, int optInSignalPeriod, out int outBegIdx, out int outNBElement, Span<double> outKVO, Span<double> outKVOSignal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double kFast = 0;
      double kSlow = 0;
      double kSignal = 0;
      double betaFast = 0;
      double betaSlow = 0;
      double betaSignal = 0;
      double hlc = 0;
      double prevHlc = 0;
      double dmToday = 0;
      double prevDm = 0;
      double cm = 0;
      double cmBase = 0;
      double vf = 0;
      double emaFast = 0;
      double emaSlow = 0;
      double kvoValue = 0;
      double signalValue = 0;
      double trend = 0;
      double prevTrend = 0;
      int lookbackTotal = 0;
      int today = 0;
      int outIdx = 0;
      int historyLen = inHigh.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > IndexMax + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inLow.Length != inHigh.Length || inClose.Length != inHigh.Length || inVolume.Length != inHigh.Length ) {
         return RetCode.BadParam;
      }
      if( optInFastPeriod == int.MinValue ) {
         optInFastPeriod = 34;
      } else if( optInFastPeriod < 2 || optInFastPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInSlowPeriod == int.MinValue ) {
         optInSlowPeriod = 55;
      } else if( optInSlowPeriod < 2 || optInSlowPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInSignalPeriod == int.MinValue ) {
         optInSignalPeriod = 13;
      } else if( optInSignalPeriod < 2 || optInSignalPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      /* Stephen J. Klinger, "Identifying Trends With Volume Analysis", Technical
       * Analysis of Stocks & Commodities V15:12 (December 1997), with the 1997
       * factor |2*(dm/cm) - 1| (#484, form A; LEAN's differs).
       *
       *    trend = +1 if H+L+C rose, -1 if it fell, unchanged on a tie
       *    cm    = previous + current range on a trend change, else cm + range
       *    vf    = volume * |2*(dm/cm) - 1| * 100 * trend
       *
       * The committed corpus holds a single tie in H+L+C, and reading it any other
       * way moves KVO by up to 1e7 from the next bar on: the tie rule is gated by
       * a built series in test_kvo.c, not by the corpus.
       *
       * All three EMAs seed raw on the first volume force, not on an SMA as
       * TA_EMA does. Each k + beta pair must sum to exactly 1.0, as in ema.c.
       */
      lookbackTotal = KvoLookback(optInFastPeriod, optInSlowPeriod, optInSignalPeriod);
      /* Move up the start index if there is not
       * enough initial data.
       */
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      betaFast = (double)(optInFastPeriod - 1) / (double)(optInFastPeriod + 1);
      kFast = 1.0 - betaFast;
      if( betaFast < 0.5 ) {
         betaFast = 1.0 - kFast;
      }
      betaSlow = (double)(optInSlowPeriod - 1) / (double)(optInSlowPeriod + 1);
      kSlow = 1.0 - betaSlow;
      if( betaSlow < 0.5 ) {
         betaSlow = 1.0 - kSlow;
      }
      betaSignal = (double)(optInSignalPeriod - 1) / (double)(optInSignalPeriod + 1);
      kSignal = 1.0 - betaSignal;
      if( betaSignal < 0.5 ) {
         betaSignal = 1.0 - kSignal;
      }
      /* The anchor: only its H+L+C and range are read, and the trend starts at +1. */
      today = startIdx - lookbackTotal;
      prevHlc = inHigh[today] + inLow[today] + inClose[today];
      prevDm = inHigh[today] - inLow[today];
      prevTrend = 1.0;
      today = today + 1;
      /* The seed bar: cm opens on both ranges whatever the trend, and both
       * averages start at this volume force, so KVO and the trigger are exactly 0.
       */
      hlc = inHigh[today] + inLow[today] + inClose[today];
      dmToday = inHigh[today] - inLow[today];
      trend = (hlc > prevHlc) ? 1.0 : prevTrend;
      trend = (hlc < prevHlc) ? -1.0 : trend;
      cm = prevDm + dmToday;
      if( cm == 0.0 ) {
         vf = 0.0;
      } else {
         vf = inVolume[today] * Math.Abs(2.0 * (dmToday / cm) - 1.0) * 100.0 * trend;
      }
      emaFast = vf;
      emaSlow = vf;
      kvoValue = emaFast - emaSlow;
      signalValue = kvoValue;
      prevHlc = hlc;
      prevDm = dmToday;
      prevTrend = trend;
      today = today + 1;
      while( today < startIdx ) {
         hlc = inHigh[today] + inLow[today] + inClose[today];
         dmToday = inHigh[today] - inLow[today];
         trend = (hlc > prevHlc) ? 1.0 : prevTrend;
         trend = (hlc < prevHlc) ? -1.0 : trend;
         cmBase = (trend != prevTrend) ? prevDm : cm;
         cm = cmBase + dmToday;
         if( cm == 0.0 ) {
            vf = 0.0;
         } else {
            vf = inVolume[today] * Math.Abs(2.0 * (dmToday / cm) - 1.0) * 100.0 * trend;
         }
         emaFast = Math.FusedMultiplyAdd(betaFast, emaFast, kFast * vf);
         emaSlow = Math.FusedMultiplyAdd(betaSlow, emaSlow, kSlow * vf);
         kvoValue = emaFast - emaSlow;
         signalValue = Math.FusedMultiplyAdd(betaSignal, signalValue, kSignal * kvoValue);
         prevHlc = hlc;
         prevDm = dmToday;
         prevTrend = trend;
         today = today + 1;
      }
      outIdx = 0;
      while( today <= endIdx ) {
         hlc = inHigh[today] + inLow[today] + inClose[today];
         dmToday = inHigh[today] - inLow[today];
         trend = (hlc > prevHlc) ? 1.0 : prevTrend;
         trend = (hlc < prevHlc) ? -1.0 : trend;
         cmBase = (trend != prevTrend) ? prevDm : cm;
         cm = cmBase + dmToday;
         if( cm == 0.0 ) {
            vf = 0.0;
         } else {
            vf = inVolume[today] * Math.Abs(2.0 * (dmToday / cm) - 1.0) * 100.0 * trend;
         }
         emaFast = Math.FusedMultiplyAdd(betaFast, emaFast, kFast * vf);
         emaSlow = Math.FusedMultiplyAdd(betaSlow, emaSlow, kSlow * vf);
         kvoValue = emaFast - emaSlow;
         signalValue = Math.FusedMultiplyAdd(betaSignal, signalValue, kSignal * kvoValue);
         outKVO[outIdx * outStride] = kvoValue;
         outKVOSignal[outIdx * outStride] = signalValue;
         outIdx = outIdx + 1;
         prevHlc = hlc;
         prevDm = dmToday;
         prevTrend = trend;
         today = today + 1;
      }
      outNBElement = outIdx;
      outBegIdx = startIdx;
      /* Capture the live batch state into the handle. */
      sp.optInFastPeriod = optInFastPeriod;
      sp.optInSlowPeriod = optInSlowPeriod;
      sp.optInSignalPeriod = optInSignalPeriod;
      sp.kFast = kFast;
      sp.kSlow = kSlow;
      sp.kSignal = kSignal;
      sp.betaFast = betaFast;
      sp.betaSlow = betaSlow;
      sp.betaSignal = betaSignal;
      sp.prevHlc = prevHlc;
      sp.prevDm = prevDm;
      sp.cm = cm;
      sp.emaFast = emaFast;
      sp.emaSlow = emaSlow;
      sp.signalValue = signalValue;
      sp.prevTrend = prevTrend;
      sp.cur_outKVO = outKVO[(outNBElement - 1) * outStride];
      sp.cur_outKVOSignal = outKVOSignal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* KvoOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal KvoStream KvoOpenAndFillInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, ReadOnlySpan<double> inVolume, int startIdx, int optInFastPeriod, int optInSlowPeriod, int optInSignalPeriod, out int outBegIdx, out int outNBElement, Span<double> outKVO, Span<double> outKVOSignal )
   {
      KvoStream sp = new KvoStream(this);
      RetCode retCode = KvoOpenImpl(sp, inHigh, inLow, inClose, inVolume, startIdx, optInFastPeriod, optInSlowPeriod, optInSignalPeriod, out outBegIdx, out outNBElement, outKVO, outKVOSignal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("KVO", "openAndFill", nameof(inHigh), inHigh.Length, startIdx, KvoLookback(optInFastPeriod, optInSlowPeriod, optInSignalPeriod));
      }
      throw StreamFailure("KVO", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind KvoOpen (composition seam). */
   internal KvoStream KvoOpenInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, ReadOnlySpan<double> inVolume, int startIdx, int optInFastPeriod, int optInSlowPeriod, int optInSignalPeriod )
   {
      KvoStream sp = new KvoStream(this);
      double[] sink_outKVO = new double[1];
      double[] sink_outKVOSignal = new double[1];
      RetCode retCode = KvoOpenImpl(sp, inHigh, inLow, inClose, inVolume, startIdx, optInFastPeriod, optInSlowPeriod, optInSignalPeriod, out int outBegIdx, out int outNBElement, sink_outKVO, sink_outKVOSignal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("KVO", "open", nameof(inHigh), inHigh.Length, startIdx, KvoLookback(optInFastPeriod, optInSlowPeriod, optInSignalPeriod));
      }
      throw StreamFailure("KVO", "open", retCode);
   }

   /// <summary>Open a live <c>KVO</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="KvoStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>KVO</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>KvoLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>KvoOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inHigh">High price series. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price series. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price series. The warm-up history, oldest bar first.</param>
   /// <param name="inVolume">Volume series. The warm-up history, oldest bar first.</param>
   /// <param name="optInFastPeriod">As in the batch call; see <see cref="KvoLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowPeriod">As in the batch call; see <see cref="KvoLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSignalPeriod">As in the batch call; see <see cref="KvoLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>KvoLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public KvoStream KvoOpen( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, ReadOnlySpan<double> inVolume, int optInFastPeriod, int optInSlowPeriod, int optInSignalPeriod )
   {
      if( inHigh.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "KVO open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "KVO open: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TALibArgumentException("KVO open: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TALibArgumentException("KVO open: inClose is empty", nameof(inClose), RetCode.BadParam);
      if( inVolume.IsEmpty ) throw new TALibArgumentException("KVO open: inVolume is empty", nameof(inVolume), RetCode.BadParam);
      RequireHistoryLength("KVO", "open", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("KVO", "open", "inClose", inClose.Length, inHigh.Length);
      RequireHistoryLength("KVO", "open", "inVolume", inVolume.Length, inHigh.Length);
      return KvoOpenInternal(inHigh, inLow, inClose, inVolume, 0, optInFastPeriod, optInSlowPeriod, optInSignalPeriod);
   }

   /// <summary><c>KvoOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>KVO</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - KvoLookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="KvoStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inHigh">High price series. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price series. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price series. The warm-up history, oldest bar first.</param>
   /// <param name="inVolume">Volume series. The warm-up history, oldest bar first.</param>
   /// <param name="optInFastPeriod">As in the batch call; see <see cref="KvoLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowPeriod">As in the batch call; see <see cref="KvoLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSignalPeriod">As in the batch call; see <see cref="KvoLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outKVO">Klinger Volume Oscillator. Must hold at least <c>historyLen -
   /// KvoLookback(...)</c> values.</param>
   /// <param name="outKVOSignal">Trigger line, an exponential average of the oscillator. Must hold at least
   /// <c>historyLen - KvoLookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>KvoLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public KvoStream KvoOpenAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, ReadOnlySpan<double> inVolume, int optInFastPeriod, int optInSlowPeriod, int optInSignalPeriod, Span<double> outKVO, Span<double> outKVOSignal )
   {
      if( inHigh.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "KVO openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "KVO openAndFill: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TALibArgumentException("KVO openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TALibArgumentException("KVO openAndFill: inClose is empty", nameof(inClose), RetCode.BadParam);
      if( inVolume.IsEmpty ) throw new TALibArgumentException("KVO openAndFill: inVolume is empty", nameof(inVolume), RetCode.BadParam);
      int guardOutLen = OpenFillCount("KVO", "openAndFill", inHigh.Length, KvoLookback(optInFastPeriod, optInSlowPeriod, optInSignalPeriod));
      RequireHistoryLength("KVO", "openAndFill", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("KVO", "openAndFill", "inClose", inClose.Length, inHigh.Length);
      RequireHistoryLength("KVO", "openAndFill", "inVolume", inVolume.Length, inHigh.Length);
      RequireFillLength("KVO", "openAndFill", "outKVO", outKVO.Length, guardOutLen);
      RequireFillLength("KVO", "openAndFill", "outKVOSignal", outKVOSignal.Length, guardOutLen);
      if( SameBuffer(outKVO, inHigh) || SameBuffer(outKVO, inLow) || SameBuffer(outKVO, inClose) || SameBuffer(outKVO, inVolume) || SameBuffer(outKVOSignal, inHigh) || SameBuffer(outKVOSignal, inLow) || SameBuffer(outKVOSignal, inClose) || SameBuffer(outKVOSignal, inVolume) || SameBuffer(outKVO, outKVOSignal) ) {
         throw StreamFailure("KVO", "openAndFill", RetCode.BadParam);
      }
      if( guardOutLen > 0 && ( outKVO.Overlaps(inHigh) || outKVO.Overlaps(inLow) || outKVO.Overlaps(inClose) || outKVO.Overlaps(inVolume) || outKVOSignal.Overlaps(inHigh) || outKVOSignal.Overlaps(inLow) || outKVOSignal.Overlaps(inClose) || outKVOSignal.Overlaps(inVolume) || OutputsAlias(outKVO, outKVOSignal) ) ) {
         throw StreamFailure("KVO", "openAndFill", RetCode.BadParam);
      }
      return KvoOpenAndFillInternal(inHigh, inLow, inClose, inVolume, 0, optInFastPeriod, optInSlowPeriod, optInSignalPeriod, out _, out _, outKVO, outKVOSignal);
   }
