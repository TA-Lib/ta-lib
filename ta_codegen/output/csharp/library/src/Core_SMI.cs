   /// stochastic measures the close against the bottom of the range; Blau
   /// measures it against the middle, then smooths numerator and denominator
   /// separately with two exponential averages before dividing, which is what
   /// buys the low-lag, smooth-contoured curve. The result runs -100 to +100
   /// rather than 0 to 100, so the zero line is the reference: positive means
   /// the close is above the midpoint of its range, negative below. Extreme
   /// readings mark overbought and oversold conditions, and crossings of the
   /// signal line are the usual trade trigger.
   /// </summary>
   /// <remarks>
   /// <b>Formula</b>
   /// <code>
   /// HH = MAX(high, timePeriod);  LL = MIN(low, timePeriod)
   /// num = close - 0.5 * (HH + LL);  den = HH - LL
   /// SMI = 100 * EMA(EMA(num, slowPeriod), fastPeriod) / (0.5 * EMA(EMA(den, slowPeriod), fastPeriod))
   /// Signal = EMA(SMI, signalPeriod)
   /// </code>
   /// <list type="bullet">
   /// <item><description>A window whose bars are all flat (every high equal to its low) leaves both the numerator and the denominator at zero. Rather than divide, SMI emits 0 there — the same convention as CCI and IMI. Some implementations divide unguarded and return a non-finite value.</description></item>
   /// <item><description>Each exponential average is seeded with a simple average of its own first inputs, the same seeding TA-Lib's EMA uses, so the first published values converge toward an unlimited-history result rather than reproducing it exactly. <c>TA_SetUnstablePeriod(TA_FUNC_UNST_EMA, ...)</c> discards more of that warm-up. Implementations seeding from a single first sample — Tulip and TradingView among them — differ over the transient and agree once it decays.</description></item>
   /// <item><description>One output range covers both outputs, so the SMI values consumed by the signal line's own warm-up are not published.</description></item>
   /// </list>
   /// <para>
   /// Values are written only where the indicator is defined. The returned
   /// <see cref="OutRange"/> says where they start and how many there are;
   /// nothing outside that range is touched, and the library never pads with
   /// NaN. A valid range shorter than <c>SMI_Lookback</c> is a <b>success with
   /// no values</b> (<c>Count == 0</c>), not an error.
   /// </para>
   /// </remarks>
   /// <param name="startIdx">First bar of the requested range (inclusive).</param>
   /// <param name="endIdx">Last bar of the requested range (inclusive).</param>
   /// <param name="inHigh">High price series.</param>
   /// <param name="inLow">Low price series.</param>
   /// <param name="inClose">Close price series.</param>
   /// <param name="optInTimePeriod">Period of the high/low range (default 13; range 2..100000;
   /// <c>int.MinValue</c> selects the default).</param>
   /// <param name="optInFastPeriod">Period of the second smoothing, applied to the first (default 2; range
   /// 2..100000; <c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowPeriod">Period of the first smoothing, applied to the raw momentum (default 25;
   /// range 2..100000; <c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSignalPeriod">Smoothing period of the signal line (default 9; range 2..100000;
   /// <c>int.MinValue</c> selects the default).</param>
   /// <param name="outSMI">Stochastic Momentum Index, -100 to +100. Must hold at least <c>endIdx -
   /// startIdx + 1</c> values.</param>
   /// <param name="outSMISignal">Exponential average of the SMI line. Must hold at least <c>endIdx -
   /// startIdx + 1</c> values.</param>
   /// <returns>The range written: <c>BegIdx</c> is the first bar with a value,
   /// <c>Count</c> how many were written.</returns>
   /// <exception cref="System.ArgumentOutOfRangeException"><c>startIdx</c> or <c>endIdx</c> is negative or above
   /// <see cref="Core.MAX_INDEX"/>, or <c>endIdx &lt; startIdx</c>.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or two outputs
   /// share one array.</exception>
   /// <exception cref="System.ArgumentException">A span is too short for the range requested: an input this function
   /// <i>reads</i> that does not reach <c>endIdx</c>, or an output that cannot
   /// hold the values produced. Checked before anything is written, so a
   /// rejected call leaves every buffer untouched. An empty span — which is what
   /// a null array becomes, since a span cannot be null — fails the same check,
   /// because any valid range needs at least one element. A few candlestick
   /// patterns declare an OHLC series they never index; those are not checked at
   /// all, because rejecting them would refuse a call the algorithm can answer.</exception>
   /// <exception cref="System.ArgumentException">Two output buffers overlap, or an output partially overlaps an input.
   /// Computing wholly in place (an output that IS an input) is allowed.</exception>
   public OutRange SMI( int startIdx,
                        int endIdx,
                        ReadOnlySpan<double> inHigh,
                        ReadOnlySpan<double> inLow,
                        ReadOnlySpan<double> inClose,
                        int optInTimePeriod,
                        int optInFastPeriod,
                        int optInSlowPeriod,
                        int optInSignalPeriod,
                        Span<double> outSMI,
                        Span<double> outSMISignal )
   {
      int guardStart = ClampedStart(startIdx, endIdx, SMI_Lookback(optInTimePeriod, optInFastPeriod, optInSlowPeriod, optInSignalPeriod));
      int guardInLen = guardStart < 0 ? 0 : endIdx + 1;
      int guardOutLen = guardStart < 0 || guardStart > endIdx ? 0 : endIdx - guardStart + 1;
      RequireLength("SMI", "inHigh", inHigh.Length, guardInLen);
      RequireLength("SMI", "inLow", inLow.Length, guardInLen);
      RequireLength("SMI", "inClose", inClose.Length, guardInLen);
      RequireLength("SMI", "outSMI", outSMI.Length, guardOutLen);
      RequireLength("SMI", "outSMISignal", outSMISignal.Length, guardOutLen);
      RetCode retCode = SMI_Impl(startIdx, endIdx, inHigh, inLow, inClose, optInTimePeriod, optInFastPeriod, optInSlowPeriod, optInSignalPeriod, out int outBegIdx, out int outNBElement, outSMI, outSMISignal);
      if( retCode != RetCode.Success ) {
         throw Failure("SMI", retCode);
      }
      return new OutRange(outBegIdx, outNBElement);
   }
