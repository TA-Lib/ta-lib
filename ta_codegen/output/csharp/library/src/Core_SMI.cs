      /* Peek's reusable scratch — one per thread, see CopyFrom. */
      [ThreadStatic] private static SMI_Stream? peekScratch;

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Allocates nothing — neither handle state nor a return value.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so the handle is left exactly as it was and the stream stays usable: skip
      /// the bar, or re-open on a clean history. This is the one place the
      /// streaming tier is stricter than the batch API, which computes on whatever
      /// it is given: a handle retains its state, so a single non-finite bar would
      /// poison every later value it produces.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>The value at the bar just committed.</returns>
      public SMI_Value Update( double inHigh, double inLow, double inClose )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) ) throw Core.StreamFailure("SMI", "update", RetCode.BadParam);
         core.SMI_StepImpl(this, inHigh, inLow, inClose);
         if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         return new SMI_Value(cur_outSMI, cur_outSMISignal);
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — it is the same generated code, run on a copy. Never writes
      /// this handle, so peeks may run concurrently with each other.</para>
      /// <para>It runs on a scratch handle held per thread and reused, so it allocates
      /// nothing after this thread's first peek of this indicator. That scratch is
      /// retained for the life of the thread.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>What <see cref="Update"/> would return for this bar.</returns>
      public SMI_Value Peek( double inHigh, double inLow, double inClose )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) ) throw Core.StreamFailure("SMI", "peek", RetCode.BadParam);
         SMI_Stream? scratch = peekScratch;
         if( scratch is null ) {
            scratch = new SMI_Stream(this);
            peekScratch = scratch;
         } else {
            scratch.CopyFrom(this);
         }
         core.SMI_StepImpl(scratch, inHigh, inLow, inClose);
         return new SMI_Value(scratch.cur_outSMI, scratch.cur_outSMISignal);
      }

      /// <summary>Commit <c>n</c> closed bars and write their <c>n</c> values, in one call.</summary>
      /// <remarks>
      /// <para>Exactly <c>n</c> back-to-back <see cref="Update"/> calls, with one set of
      /// argument checks instead of <c>n</c>. The outputs must hold at least
      /// <c>n</c> values and must not overlap an input or each other.</para>
      /// <para><see cref="OutRange"/> counts what was committed, which is what makes a
      /// rejection readable: a non-finite bar <c>k</c> throws
      /// <see cref="System.ArgumentException"/> exactly as <see cref="Update"/>
      /// would, with bars <c>0..k</c> committed and written, bar <c>k</c> and
      /// everything after it not, and the count advanced by <c>k</c>.</para>
      /// </remarks>
      /// <param name="inHigh">Closed bars for <c>inHigh</c>, oldest first.</param>
      /// <param name="inLow">Closed bars for <c>inLow</c>, oldest first.</param>
      /// <param name="inClose">Closed bars for <c>inClose</c>, oldest first.</param>
      /// <param name="outSMI">Receives one <c>outSMI</c> value per bar committed.</param>
      /// <param name="outSMISignal">Receives one <c>outSMISignal</c> value per bar committed.</param>
      public void UpdateAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, Span<double> outSMI, Span<double> outSMISignal )
      {
         int barCount = inHigh.Length;
         if( inLow.Length != barCount || inClose.Length != barCount || outSMI.Length < barCount || outSMISignal.Length < barCount || outSMI.Overlaps(inHigh) || outSMI.Overlaps(inLow) || outSMI.Overlaps(inClose) || outSMISignal.Overlaps(inHigh) || outSMISignal.Overlaps(inLow) || outSMISignal.Overlaps(inClose) || outSMI.Overlaps(outSMISignal) ) throw Core.StreamFailure("SMI", "updateAndFill", RetCode.BadParam);
         for( int i = 0; i < barCount; i++ )
         {
            if( !double.IsFinite(inHigh[i]) || !double.IsFinite(inLow[i]) || !double.IsFinite(inClose[i]) ) throw Core.StreamFailure("SMI", "updateAndFill", RetCode.BadParam);
            core.SMI_StepImpl(this, inHigh[i], inLow[i], inClose[i]);
            outSMI[i] = cur_outSMI;
            outSMISignal[i] = cur_outSMISignal;
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         }
      }

      /// <summary>The value at the most recently committed bar — the last history bar right
      /// after open, then whatever the latest <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public SMI_Value Value => new SMI_Value(cur_outSMI, cur_outSMISignal);

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public SMI_Stream Clone()
      {
         return new SMI_Stream(this);
      }
   }

   internal void SMI_StepImpl( SMI_Stream sp, double inHigh, double inLow, double inClose )
   {
      double tmp = 0.0;
      double num = 0.0;
      double den = 0.0;
      double halfDen = 0.0;
      double smiValue = 0.0;
      if( sp.today >= 1073741824 ) {
         int rebaseShift = sp.trailingIdx & ~sp.xMask;
         sp.today -= rebaseShift;
         sp.trailingIdx -= rebaseShift;
         sp.highestIdx -= rebaseShift;
         sp.i -= rebaseShift;
         sp.lowestIdx -= rebaseShift;
      }
      sp.x_inHigh[sp.today & sp.xMask] = inHigh;
      sp.x_inLow[sp.today & sp.xMask] = inLow;
      sp.x_inClose[sp.today & sp.xMask] = inClose;
      /* Set the lowest low */
      tmp = sp.x_inLow[sp.today & sp.xMask];
      if( sp.lowestIdx < sp.trailingIdx ) {
         sp.lowestIdx = sp.trailingIdx;
         sp.lowest = sp.x_inLow[sp.lowestIdx & sp.xMask];
         sp.i = sp.lowestIdx;
         while( ++sp.i <= sp.today ) {
            tmp = sp.x_inLow[sp.i & sp.xMask];
            if( tmp < sp.lowest ) {
               sp.lowestIdx = sp.i;
               sp.lowest = tmp;
            }
         }
      } else if( tmp <= sp.lowest ) {
         sp.lowestIdx = sp.today;
         sp.lowest = tmp;
      }
      /* Set the highest high */
      tmp = sp.x_inHigh[sp.today & sp.xMask];
      if( sp.highestIdx < sp.trailingIdx ) {
         sp.highestIdx = sp.trailingIdx;
         sp.highest = sp.x_inHigh[sp.highestIdx & sp.xMask];
         sp.i = sp.highestIdx;
         while( ++sp.i <= sp.today ) {
            tmp = sp.x_inHigh[sp.i & sp.xMask];
            if( tmp > sp.highest ) {
               sp.highestIdx = sp.i;
               sp.highest = tmp;
            }
         }
      } else if( tmp >= sp.highest ) {
         sp.highestIdx = sp.today;
         sp.highest = tmp;
      }
      den = sp.highest - sp.lowest;
      num = sp.x_inClose[sp.today & sp.xMask] - (sp.highest + sp.lowest) * 0.5;
      sp.emaSlowNum = Math.FusedMultiplyAdd(num - sp.emaSlowNum, sp.kSlow, sp.emaSlowNum);
      sp.emaSlowDen = Math.FusedMultiplyAdd(den - sp.emaSlowDen, sp.kSlow, sp.emaSlowDen);
      sp.emaFastNum = Math.FusedMultiplyAdd(sp.emaSlowNum - sp.emaFastNum, sp.kFast, sp.emaFastNum);
      sp.emaFastDen = Math.FusedMultiplyAdd(sp.emaSlowDen - sp.emaFastDen, sp.kFast, sp.emaFastDen);
      /* Guard with TA_IS_ZERO, not an exact `halfDen != 0.0`: a machine-flat
       * window leaves a sub-epsilon residue that an exact check would divide
       * into noise (issue #107 / STOCHRSI). A window whose bars are all
       * H == L makes num zero too, so this is 0/0, and the neutral 0.0 is the
       * CCI (#7) and IMI (#112) convention.
       */
      halfDen = 0.5 * sp.emaFastDen;
      if( !((-0.00000000000001 < halfDen) && (halfDen < 0.00000000000001)) ) {
         smiValue = 100.0 * sp.emaFastNum / halfDen;
      } else {
         smiValue = 0.0;
      }
      sp.prevSignal = Math.FusedMultiplyAdd(smiValue - sp.prevSignal, sp.kSignal, sp.prevSignal);
      sp.cur_outSMI = smiValue;
      sp.cur_outSMISignal = sp.prevSignal;
      sp.trailingIdx = sp.trailingIdx + 1;
      sp.today = sp.today + 1;
   }

   private RetCode SMI_OpenImpl( SMI_Stream sp, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, int optInFastPeriod, int optInSlowPeriod, int optInSignalPeriod, out int outBegIdx, out int outNBElement, Span<double> outSMI, Span<double> outSMISignal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double kSlow = 0;
      double kFast = 0;
      double kSignal = 0;
      double highest = 0;
      double lowest = 0;
      double tmp = 0;
      double emaSlowNum = 0;
      double emaSlowDen = 0;
      double emaFastNum = 0;
      double emaFastDen = 0;
      double sumSlowNum = 0;
      double sumSlowDen = 0;
      double sumFastNum = 0;
      double sumFastDen = 0;
      double sumSignal = 0;
      double num = 0;
      double den = 0;
      double halfDen = 0;
      double smiValue = 0;
      double prevSignal = 0;
      int lookbackTotal = 0;
      int lookbackSlow = 0;
      int lookbackFast = 0;
      int today = 0;
      int trailingIdx = 0;
      int highestIdx = 0;
      int lowestIdx = 0;
      int i = 0;
      int outIdx = 0;
      int nBar = 0;
      int nFast = 0;
      int nSignal = 0;
      int historyLen = inHigh.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 || inLow.Length != inHigh.Length || inClose.Length != inHigh.Length ) {
         return RetCode.BadParam;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 13;
      } else if( optInTimePeriod < 2 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInFastPeriod == int.MinValue ) {
         optInFastPeriod = 2;
      } else if( optInFastPeriod < 2 || optInFastPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInSlowPeriod == int.MinValue ) {
         optInSlowPeriod = 25;
      } else if( optInSlowPeriod < 2 || optInSlowPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInSignalPeriod == int.MinValue ) {
         optInSignalPeriod = 9;
      } else if( optInSignalPeriod < 2 || optInSignalPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      lookbackTotal = SMI_Lookback(optInTimePeriod, optInFastPeriod, optInSlowPeriod, optInSignalPeriod);
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      outBegIdx = startIdx;
      /* Blau's pipeline in one pass. A composed form is not available: the
       * streaming producer model carries exactly one intermediate series
       * (streaming.rs:2076) and SMI has two, the numerator and the denominator,
       * which must be smoothed separately before they are divided.
       *
       * Each of the three stages seeds the way ema.c does -- a simple average of
       * that stage's first 'period' inputs -- so the result is bit-identical to
       * TA_MAX + TA_MIN followed by four TA_EMA calls. The stage boundaries below
       * are the callee LOOKBACKS, not (period-1), so that a warm
       * TA_SetUnstablePeriod(TA_FUNC_UNST_EMA) folds in: each stage then seeds
       * from the values its predecessor would have published, exactly as the
       * composed form does. The seed sums accumulate from 0.0 in production
       * order; do not reorder or fuse them (0.0+x is not x for x=-0.0).
       *
       * TA_GetCompatibility() is deliberately NOT consulted, for the reason
       * spelled out in efi.c: ema.c's TA_COMPATIBILITY_METASTOCK seeding arm is
       * preserved for the functions that already shipped with it and dropped from
       * new ones, and it is not reachable at all from the Rust, Java and C# APIs.
       * The seeding choice itself is measured in docs/studies/ema-seeding/README.md.
       */
      kSlow = 2.0 / (double)(optInSlowPeriod + 1);
      kFast = 2.0 / (double)(optInFastPeriod + 1);
      kSignal = 2.0 / (double)(optInSignalPeriod + 1);
      lookbackSlow = EMA_Lookback(optInSlowPeriod);
      lookbackFast = EMA_Lookback(optInFastPeriod);
      emaSlowNum = 0.0;
      emaSlowDen = 0.0;
      emaFastNum = 0.0;
      emaFastDen = 0.0;
      prevSignal = 0.0;
      smiValue = 0.0;
      sumSlowNum = 0.0;
      sumSlowDen = 0.0;
      sumFastNum = 0.0;
      sumFastDen = 0.0;
      sumSignal = 0.0;
      highest = 0.0;
      lowest = 0.0;
      highestIdx = 0 - 1;
      lowestIdx = 0 - 1;
      /* The first bar carrying a full high/low window. */
      trailingIdx = startIdx - lookbackTotal;
      today = trailingIdx + (optInTimePeriod - 1);
      nBar = 0;
      /* Warm-up. Runs through startIdx inclusive: the last pass here is the one
       * that completes the signal seed, so it produces the first output pair.
       */
      while( today <= startIdx ) {
         /* Set the lowest low */
         tmp = inLow[today];
         if( lowestIdx < trailingIdx ) {
            lowestIdx = trailingIdx;
            lowest = inLow[lowestIdx];
            i = lowestIdx;
            while( ++i <= today ) {
               tmp = inLow[i];
               if( tmp < lowest ) {
                  lowestIdx = i;
                  lowest = tmp;
               }
            }
         } else if( tmp <= lowest ) {
            lowestIdx = today;
            lowest = tmp;
         }
         /* Set the highest high */
         tmp = inHigh[today];
         if( highestIdx < trailingIdx ) {
            highestIdx = trailingIdx;
            highest = inHigh[highestIdx];
            i = highestIdx;
            while( ++i <= today ) {
               tmp = inHigh[i];
               if( tmp > highest ) {
                  highestIdx = i;
                  highest = tmp;
               }
            }
         } else if( tmp >= highest ) {
            highestIdx = today;
            highest = tmp;
         }
         den = highest - lowest;
         num = inClose[today] - (highest + lowest) * 0.5;
         /* Stage 1: the slow EMA, over the raw momentum. */
         if( nBar < optInSlowPeriod ) {
            sumSlowNum = sumSlowNum + num;
            sumSlowDen = sumSlowDen + den;
            if( nBar == optInSlowPeriod - 1 ) {
               emaSlowNum = sumSlowNum / optInSlowPeriod;
               emaSlowDen = sumSlowDen / optInSlowPeriod;
            }
         } else {
            emaSlowNum = Math.FusedMultiplyAdd(num - emaSlowNum, kSlow, emaSlowNum);
            emaSlowDen = Math.FusedMultiplyAdd(den - emaSlowDen, kSlow, emaSlowDen);
         }
         /* Stage 2: the fast EMA, over what stage 1 publishes.
          *
          * The stage counters are compared BEFORE they are subtracted, never
          * after. Writing this as `nFast = nBar - lookbackSlow; if( nFast >= 0 )`
          * is correct in C, where the counters are signed, and broken everywhere
          * else: the Rust backend renders them as `usize`, so the subtraction
          * underflows for the first lookbackSlow bars -- a panic in a debug build
          * and a wrap in release. It would also be invisible to the cross-language
          * gate, which runs release servers at unstable period 0, where the branch
          * the wrap wrongly takes happens to be a no-op because both accumulators
          * are still 0.0.
          */
         if( nBar >= lookbackSlow ) {
            nFast = nBar - lookbackSlow;
            if( nFast < optInFastPeriod ) {
               sumFastNum = sumFastNum + emaSlowNum;
               sumFastDen = sumFastDen + emaSlowDen;
               if( nFast == optInFastPeriod - 1 ) {
                  emaFastNum = sumFastNum / optInFastPeriod;
                  emaFastDen = sumFastDen / optInFastPeriod;
               }
            } else {
               emaFastNum = Math.FusedMultiplyAdd(emaSlowNum - emaFastNum, kFast, emaFastNum);
               emaFastDen = Math.FusedMultiplyAdd(emaSlowDen - emaFastDen, kFast, emaFastDen);
            }
         }
         /* Stage 3: the SMI line, then the signal EMA over it. */
         if( nBar >= lookbackSlow + lookbackFast ) {
            nSignal = nBar - lookbackSlow - lookbackFast;
            halfDen = 0.5 * emaFastDen;
            if( !((-0.00000000000001 < halfDen) && (halfDen < 0.00000000000001)) ) {
               smiValue = 100.0 * emaFastNum / halfDen;
            } else {
               smiValue = 0.0;
            }
            if( nSignal < optInSignalPeriod ) {
               sumSignal = sumSignal + smiValue;
               if( nSignal == optInSignalPeriod - 1 ) {
                  prevSignal = sumSignal / optInSignalPeriod;
               }
            } else {
               prevSignal = Math.FusedMultiplyAdd(smiValue - prevSignal, kSignal, prevSignal);
            }
         }
         nBar = nBar + 1;
         trailingIdx = trailingIdx + 1;
         today = today + 1;
      }
      outSMI[0 * outStride] = smiValue;
      outSMISignal[0 * outStride] = prevSignal;
      outIdx = 1;
      /* Stable zone. Every stage is a pure recursion from here on. */
      while( today <= endIdx ) {
         /* Set the lowest low */
         tmp = inLow[today];
         if( lowestIdx < trailingIdx ) {
            lowestIdx = trailingIdx;
            lowest = inLow[lowestIdx];
            i = lowestIdx;
            while( ++i <= today ) {
               tmp = inLow[i];
               if( tmp < lowest ) {
                  lowestIdx = i;
                  lowest = tmp;
               }
            }
         } else if( tmp <= lowest ) {
            lowestIdx = today;
            lowest = tmp;
         }
         /* Set the highest high */
         tmp = inHigh[today];
         if( highestIdx < trailingIdx ) {
            highestIdx = trailingIdx;
            highest = inHigh[highestIdx];
            i = highestIdx;
            while( ++i <= today ) {
               tmp = inHigh[i];
               if( tmp > highest ) {
                  highestIdx = i;
                  highest = tmp;
               }
            }
         } else if( tmp >= highest ) {
            highestIdx = today;
            highest = tmp;
         }
         den = highest - lowest;
         num = inClose[today] - (highest + lowest) * 0.5;
         emaSlowNum = Math.FusedMultiplyAdd(num - emaSlowNum, kSlow, emaSlowNum);
         emaSlowDen = Math.FusedMultiplyAdd(den - emaSlowDen, kSlow, emaSlowDen);
         emaFastNum = Math.FusedMultiplyAdd(emaSlowNum - emaFastNum, kFast, emaFastNum);
         emaFastDen = Math.FusedMultiplyAdd(emaSlowDen - emaFastDen, kFast, emaFastDen);
         /* Guard with TA_IS_ZERO, not an exact `halfDen != 0.0`: a machine-flat
          * window leaves a sub-epsilon residue that an exact check would divide
          * into noise (issue #107 / STOCHRSI). A window whose bars are all
          * H == L makes num zero too, so this is 0/0, and the neutral 0.0 is the
          * CCI (#7) and IMI (#112) convention.
          */
         halfDen = 0.5 * emaFastDen;
         if( !((-0.00000000000001 < halfDen) && (halfDen < 0.00000000000001)) ) {
            smiValue = 100.0 * emaFastNum / halfDen;
         } else {
            smiValue = 0.0;
         }
         prevSignal = Math.FusedMultiplyAdd(smiValue - prevSignal, kSignal, prevSignal);
         outSMI[outIdx * outStride] = smiValue;
         outSMISignal[outIdx * outStride] = prevSignal;
         outIdx = outIdx + 1;
         trailingIdx = trailingIdx + 1;
         today = today + 1;
      }
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      int capX = today - trailingIdx + 1;
      if( capX < 1 || capX > historyLen ) {
         return RetCode.InternalError;
      }
      int physX = 1;
      while( physX < capX ) {
         physX <<= 1;
      }
      double[] capX_inHigh = new double[physX];
      double[] capX_inLow = new double[physX];
      double[] capX_inClose = new double[physX];
      for( int fillJ = historyLen - capX; fillJ < historyLen; fillJ++ ) {
         capX_inHigh[fillJ & (physX - 1)] = inHigh[fillJ];
         capX_inLow[fillJ & (physX - 1)] = inLow[fillJ];
         capX_inClose[fillJ & (physX - 1)] = inClose[fillJ];
      }
      sp.optInTimePeriod = optInTimePeriod;
      sp.optInFastPeriod = optInFastPeriod;
      sp.optInSlowPeriod = optInSlowPeriod;
      sp.optInSignalPeriod = optInSignalPeriod;
      sp.kSlow = kSlow;
      sp.kFast = kFast;
      sp.kSignal = kSignal;
      sp.highest = highest;
      sp.lowest = lowest;
      sp.emaSlowNum = emaSlowNum;
      sp.emaSlowDen = emaSlowDen;
      sp.emaFastNum = emaFastNum;
      sp.emaFastDen = emaFastDen;
      sp.prevSignal = prevSignal;
      sp.trailingIdx = trailingIdx;
      sp.highestIdx = highestIdx;
      sp.lowestIdx = lowestIdx;
      sp.i = i;
      sp.today = today;
      sp.xMask = physX - 1;
      sp.x_inHigh = capX_inHigh;
      sp.x_inLow = capX_inLow;
      sp.x_inClose = capX_inClose;
      sp.cur_outSMI = outSMI[(outNBElement - 1) * outStride];
      sp.cur_outSMISignal = outSMISignal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* SMI_OpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal SMI_Stream SMI_OpenAndFillInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, int optInFastPeriod, int optInSlowPeriod, int optInSignalPeriod, out int outBegIdx, out int outNBElement, Span<double> outSMI, Span<double> outSMISignal )
   {
      SMI_Stream sp = new SMI_Stream(this);
      RetCode retCode = SMI_OpenImpl(sp, inHigh, inLow, inClose, startIdx, optInTimePeriod, optInFastPeriod, optInSlowPeriod, optInSignalPeriod, out outBegIdx, out outNBElement, outSMI, outSMISignal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("SMI", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind SMI_Open (composition seam). */
   internal SMI_Stream SMI_OpenInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, int optInFastPeriod, int optInSlowPeriod, int optInSignalPeriod )
   {
      SMI_Stream sp = new SMI_Stream(this);
      double[] sink_outSMI = new double[1];
      double[] sink_outSMISignal = new double[1];
      RetCode retCode = SMI_OpenImpl(sp, inHigh, inLow, inClose, startIdx, optInTimePeriod, optInFastPeriod, optInSlowPeriod, optInSignalPeriod, out int outBegIdx, out int outNBElement, sink_outSMI, sink_outSMISignal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("SMI", "open", retCode);
   }

   /// <summary>Open a live <c>SMI</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="SMI_Stream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>SMI</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>SMI_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>SMI_OpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inHigh">High price series. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price series. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price series. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="SMI_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInFastPeriod">As in the batch call; see <see cref="SMI_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowPeriod">As in the batch call; see <see cref="SMI_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSignalPeriod">As in the batch call; see <see cref="SMI_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>SMI_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentException">An input series is empty — which is what a null array becomes, since a
   /// span cannot be null.</exception>
   public SMI_Stream SMI_Open( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInTimePeriod, int optInFastPeriod, int optInSlowPeriod, int optInSignalPeriod )
   {
      if( inHigh.IsEmpty ) throw new TaLibArgumentException("inHigh is empty", nameof(inHigh), RetCode.BadParam);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TaLibArgumentException("inClose is empty", nameof(inClose), RetCode.BadParam);
      return SMI_OpenInternal(inHigh, inLow, inClose, 0, optInTimePeriod, optInFastPeriod, optInSlowPeriod, optInSignalPeriod);
   }

   /// <summary><c>SMI_Open</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>SMI</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - SMI_Lookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="SMI_Stream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inHigh">High price series. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price series. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price series. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="SMI_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInFastPeriod">As in the batch call; see <see cref="SMI_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowPeriod">As in the batch call; see <see cref="SMI_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSignalPeriod">As in the batch call; see <see cref="SMI_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outSMI">Stochastic Momentum Index, -100 to +100. Must hold at least <c>historyLen
   /// - SMI_Lookback(...)</c> values.</param>
   /// <param name="outSMISignal">Exponential average of the SMI line. Must hold at least <c>historyLen -
   /// SMI_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>SMI_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, or an output array aliases an input or another
   /// output.</exception>
   /// <exception cref="System.ArgumentException">An input series is empty, or an output overlaps an input or another
   /// output.</exception>
   public SMI_Stream SMI_OpenAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInTimePeriod, int optInFastPeriod, int optInSlowPeriod, int optInSignalPeriod, Span<double> outSMI, Span<double> outSMISignal )
   {
      if( inHigh.IsEmpty ) throw new TaLibArgumentException("inHigh is empty", nameof(inHigh), RetCode.BadParam);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TaLibArgumentException("inClose is empty", nameof(inClose), RetCode.BadParam);
      if( outSMI.Overlaps(inHigh) || outSMI.Overlaps(inLow) || outSMI.Overlaps(inClose) || outSMISignal.Overlaps(inHigh) || outSMISignal.Overlaps(inLow) || outSMISignal.Overlaps(inClose) || outSMI.Overlaps(outSMISignal) ) {
         throw StreamFailure("SMI", "openAndFill", RetCode.BadParam);
      }
      return SMI_OpenAndFillInternal(inHigh, inLow, inClose, 0, optInTimePeriod, optInFastPeriod, optInSlowPeriod, optInSignalPeriod, out _, out _, outSMI, outSMISignal);
   }
