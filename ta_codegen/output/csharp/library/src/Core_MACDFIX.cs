   /// <summary>
   /// MACD with the fast/slow EMAs fixed to the classic 12/26 periods (with the
   /// classic fixed smoothing factors 0.15 and 0.075), exposing only the signal
   /// period. Signal-line crossovers and histogram sign flag momentum shifts.
   /// </summary>
   /// <remarks>
   /// <b>Formula</b>
   /// <code>
   /// MACD = EMA_12 - EMA_26   (fixed k: 0.15 for 12, 0.075 for 26)
   /// Signal = EMA(MACD, signalPeriod),  k = 2/(signalPeriod+1)
   /// Hist = MACD - Signal
   /// </code>
   /// <list type="bullet">
   /// <item><description>A signal period of 1 disables signal-line smoothing: the signal equals the MACD line and the histogram is zero. Before 0.6.5 this parameter value produced misaligned output (issues #48/#59).</description></item>
   /// </list>
   /// <para>
   /// This is the <c>float[]</c> overload: input elements are widened to
   /// <c>double</c> as they are read and all arithmetic is performed in
   /// <c>double</c>, so a result beyond <c>float</c> range is still
   /// representable.
   /// </para>
   /// <para>
   /// Values are written only where the indicator is defined. The returned
   /// <see cref="OutRange"/> says where they start and how many there are;
   /// nothing outside that range is touched, and the library never pads with
   /// NaN. A valid range shorter than <c>MacdFixLookback</c> is a <b>success
   /// with no values</b> (<c>Count == 0</c>), not an error.
   /// </para>
   /// </remarks>
   /// <param name="startIdx">First bar of the requested range (inclusive).</param>
   /// <param name="endIdx">Last bar of the requested range (inclusive).</param>
   /// <param name="inReal">Source series (typically close)</param>
   /// <param name="optInSignalPeriod">Smoothing period for the signal line (default 9; range 1..100000;
   /// <c>int.MinValue</c> selects the default).</param>
   /// <param name="outMACD">Fixed EMA12 minus EMA26. Must hold at least <c>endIdx - startIdx + 1</c>
   /// values.</param>
   /// <param name="outMACDSignal">EMA of the MACD line. Must hold at least <c>endIdx - startIdx + 1</c>
   /// values.</param>
   /// <param name="outMACDHist">MACD minus signal. Must hold at least <c>endIdx - startIdx + 1</c> values.</param>
   /// <returns>The range written: <c>BegIdx</c> is the first bar with a value,
   /// <c>Count</c> how many were written.</returns>
   /// <exception cref="System.ArgumentOutOfRangeException"><c>startIdx</c> or <c>endIdx</c> is negative, or <c>endIdx &lt;
   /// startIdx</c>.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or two outputs
   /// share one array.</exception>
   /// <exception cref="System.NullReferenceException">An input or output array is null. (Unlike the C library, the managed tier
   /// does not pre-validate nulls; the first array access throws.)</exception>
   public OutRange MacdFix( int startIdx,
                            int endIdx,
                            float[] inReal,
                            int optInSignalPeriod,
                            double[] outMACD,
                            double[] outMACDSignal,
                            double[] outMACDHist )
   {
      RetCode retCode = MacdFix(startIdx, endIdx, inReal, optInSignalPeriod, out int outBegIdx, out int outNBElement, outMACD, outMACDSignal, outMACDHist);
      if( retCode != RetCode.Success ) {
         throw Failure("MACDFIX", retCode);
      }
      return new OutRange(outBegIdx, outNBElement);
   }
