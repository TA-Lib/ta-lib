   /// <para>Open with <see cref="Core.MacdfixOpen"/>. There is no close and nothing to
   /// dispose — the handle is ordinary managed state, and an unreferenced handle
   /// is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class MacdfixStream
   {
      internal Core core;
      internal int optInSignalPeriod;
      internal double prevFast;
      internal double prevSlow;
      internal double prevSignal;
      internal double slowK;
      internal double fastK;
      internal double signalK;
      internal double cur_outMACD;
      internal double cur_outMACDSignal;
      internal double cur_outMACDHist;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal MacdfixStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Macdfix</c> reports over the same bars: the opener sets
      /// it to <c>(lookback, historyLen - lookback)</c>, every <c>Update</c> adds
      /// one to the count — a non-finite bar is rejected but still counted, because
      /// the bar happened — <c>Peek</c> leaves it alone, and <c>Clone</c> carries
      /// it verbatim. A plain <c>Open</c> hands back only the last value, a subset
      /// of this range, because the caller chose not to take the fill.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      internal MacdfixStream( MacdfixStream other )
      {
         this.core = other.core;
         this.optInSignalPeriod = other.optInSignalPeriod;
         this.prevFast = other.prevFast;
         this.prevSlow = other.prevSlow;
         this.prevSignal = other.prevSignal;
         this.slowK = other.slowK;
         this.fastK = other.fastK;
         this.signalK = other.signalK;
         this.cur_outMACD = other.cur_outMACD;
         this.cur_outMACDSignal = other.cur_outMACDSignal;
         this.cur_outMACDHist = other.cur_outMACDHist;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Allocates nothing — neither handle state nor a return value.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so no state moves, <see cref="Value"/> still answers the previous value,
      /// and the stream stays usable — just carry on with the next bar.
      /// <see cref="OutRange"/> does advance: the bar happened, so it is counted,
      /// which keeps two handles fed the same series positionally aligned when only
      /// one of them rejects a bar. This is the one place the streaming tier is
      /// stricter than the batch API, which computes on whatever it is given: a
      /// handle retains its state, so a single non-finite bar would poison every
      /// later value it produces.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value at the bar just committed.</returns>
      public MacdfixValue Update( double inReal )
      {
         if( !double.IsFinite(inReal) )
         {
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
            throw Core.StreamFailure("MACDFIX", "update", RetCode.BadParam);
         }
         core.MacdfixStepImpl(this, inReal);
         if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         return new MacdfixValue(cur_outMACD, cur_outMACDSignal, cur_outMACDHist);
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It copies nothing: the frame runs against this handle, reading its buffers
      /// and holding what the step would commit in locals. The cost does not grow
      /// with the period, and <c>Peek</c> never allocates.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>What <see cref="Update"/> would return for this bar.</returns>
      public MacdfixValue Peek( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.StreamFailure("MACDFIX", "peek", RetCode.BadParam);
         MacdfixStream sp = this;
         double macdValue = 0.0;
         double tempReal = 0.0;
         double cur_outMACD = sp.cur_outMACD;
         double cur_outMACDHist = sp.cur_outMACDHist;
         double cur_outMACDSignal = sp.cur_outMACDSignal;
         double prevFast = sp.prevFast;
         double prevSignal = sp.prevSignal;
         double prevSlow = sp.prevSlow;
         tempReal = inReal;
         prevFast = Math.FusedMultiplyAdd(tempReal - prevFast, sp.fastK, prevFast);
         prevSlow = Math.FusedMultiplyAdd(tempReal - prevSlow, sp.slowK, prevSlow);
         macdValue = prevFast - prevSlow;
         if( sp.optInSignalPeriod == 1 ) {
            prevSignal = macdValue;
         } else {
            prevSignal = Math.FusedMultiplyAdd(macdValue - prevSignal, sp.signalK, prevSignal);
         }
         cur_outMACD = macdValue;
         cur_outMACDSignal = prevSignal;
         cur_outMACDHist = macdValue - prevSignal;
         return new MacdfixValue(cur_outMACD, cur_outMACDSignal, cur_outMACDHist);
      }

      /// <summary>Commit <c>n</c> closed bars and write their <c>n</c> values, in one call.</summary>
      /// <remarks>
      /// <para>Exactly <c>n</c> back-to-back <see cref="Update"/> calls, with one set of
      /// argument checks instead of <c>n</c>. The outputs must hold at least
      /// <c>n</c> values and must not overlap an input or each other.</para>
      /// <para><see cref="OutRange"/> counts what this call took in, which is what makes
      /// a rejection readable: a non-finite bar <c>k</c> throws
      /// <see cref="System.ArgumentException"/> exactly as <see cref="Update"/>
      /// would, with the bars before <c>k</c> committed and written, bar <c>k</c>
      /// and everything after it not written, and the count advanced by <c>k +
      /// 1</c> — the committed bars plus the rejected one, so the last bar counted
      /// is the one that failed.</para>
      /// </remarks>
      /// <param name="inReal">Closed bars for <c>inReal</c>, oldest first.</param>
      /// <param name="outMACD">Receives one <c>outMACD</c> value per bar committed.</param>
      /// <param name="outMACDSignal">Receives one <c>outMACDSignal</c> value per bar committed.</param>
      /// <param name="outMACDHist">Receives one <c>outMACDHist</c> value per bar committed.</param>
      public void UpdateAndFill( ReadOnlySpan<double> inReal, Span<double> outMACD, Span<double> outMACDSignal, Span<double> outMACDHist )
      {
         int barCount = inReal.Length;
         if( outMACD.Length < barCount || outMACDSignal.Length < barCount || outMACDHist.Length < barCount || outMACD.Overlaps(inReal) || outMACDSignal.Overlaps(inReal) || outMACDHist.Overlaps(inReal) || outMACD.Overlaps(outMACDSignal) || outMACD.Overlaps(outMACDHist) || outMACDSignal.Overlaps(outMACDHist) ) throw Core.StreamFailure("MACDFIX", "updateAndFill", RetCode.BadParam);
         for( int i = 0; i < barCount; i++ )
         {
            if( !double.IsFinite(inReal[i]) )
            {
               if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
               throw Core.StreamFailure("MACDFIX", "updateAndFill", RetCode.BadParam);
            }
            core.MacdfixStepImpl(this, inReal[i]);
            outMACD[i] = cur_outMACD;
            outMACDSignal[i] = cur_outMACDSignal;
            outMACDHist[i] = cur_outMACDHist;
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         }
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public MacdfixValue Value => new MacdfixValue(cur_outMACD, cur_outMACDSignal, cur_outMACDHist);

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public MacdfixStream Clone()
      {
         return new MacdfixStream(this);
      }
   }

   internal void MacdfixStepImpl( MacdfixStream sp, double inReal )
   {
      double macdValue = 0.0;
      double tempReal = 0.0;
      tempReal = inReal;
      sp.prevFast = Math.FusedMultiplyAdd(tempReal - sp.prevFast, sp.fastK, sp.prevFast);
      sp.prevSlow = Math.FusedMultiplyAdd(tempReal - sp.prevSlow, sp.slowK, sp.prevSlow);
      macdValue = sp.prevFast - sp.prevSlow;
      if( sp.optInSignalPeriod == 1 ) {
         sp.prevSignal = macdValue;
      } else {
         sp.prevSignal = Math.FusedMultiplyAdd(macdValue - sp.prevSignal, sp.signalK, sp.prevSignal);
      }
      sp.cur_outMACD = macdValue;
      sp.cur_outMACDSignal = sp.prevSignal;
      sp.cur_outMACDHist = macdValue - sp.prevSignal;
   }

   private RetCode MacdfixOpenImpl( MacdfixStream sp, ReadOnlySpan<double> inReal, int startIdx, int optInSignalPeriod, out int outBegIdx, out int outNBElement, Span<double> outMACD, Span<double> outMACDSignal, Span<double> outMACDHist, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double prevFast = 0;
      double prevSlow = 0;
      double prevSignal = 0;
      double macdValue = 0;
      double tempReal = 0;
      double slowK = 0;
      double fastK = 0;
      double signalK = 0;
      int i = 0;
      int today = 0;
      int outIdx = 0;
      int lookbackTotal = 0;
      int lookbackSignal = 0;
      int optInFastPeriod = 0;
      int optInSlowPeriod = 0;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInSignalPeriod == int.MinValue ) {
         optInSignalPeriod = 9;
      } else if( optInSignalPeriod < 1 || optInSignalPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      optInFastPeriod = 12;
      optInSlowPeriod = 26;
      /* MACDFIX is the fixed 26/12 MACD: the fast/slow periods and their
       * smoothing factors are hardcoded (the general MACD selects these
       * exact values when its fast/slow period arguments are 0). Only the
       * signal period is caller-provided.
       *    Fix 12 -> fastK = 0.15
       *    Fix 26 -> slowK = 0.075
       */
      fastK = 0.15;
      slowK = 0.075;
      /* A signal period of 1 disables signal-line smoothing: the signal IS the
       * MACD line and the histogram is exactly zero. signalK is then exactly
       * 1.0, so the recursion below reduces to (x-prev)+prev -- which returns x
       * only while consecutive MACD-line values stay within a factor of two of
       * each other. The MACD line oscillates through zero, so it leaves that
       * window on ordinary data; hence the explicit arm at each step.
       */
      signalK = 2.0 / (double)(optInSignalPeriod + 1);
      lookbackSignal = EMA_Lookback(optInSignalPeriod);
      /* Move up the start index if there is not
       * enough initial data.
       */
      lookbackTotal = lookbackSignal;
      lookbackTotal += EMA_Lookback(26);
      /* fixed slow period */
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      /* Everything is computed in a single lockstep pass: each bar
       * advances the fast and slow EMA (two independent recursions),
       * their difference is the MACD line, and each MACD-line value
       * is immediately fed into the signal EMA. No temporary buffers.
       *
       * The arithmetic order below is the bit-exactness contract
       * (do not reorder or fuse operations):
       *  - EMA recursion: ((x-prev)*k)+prev.
       *  - Default compatibility: each EMA is seeded with the sum of
       *    its first 'period' inputs, accumulated from 0.0 in input
       *    order, divided by the period. The fast and slow seed
       *    windows end on the same bar. The signal EMA is seeded the
       *    same way from the first 'signal period' MACD-line values.
       *  - Metastock compatibility: the fast and slow EMA are seeded
       *    from inReal[0], the signal EMA from the first MACD-line
       *    value.
       * Output alignment is identical for all compatibility modes;
       * only the seed values differ.
       *
       * In-place (an output == inReal) is supported: outputs at
       * [outIdx] are written only after inReal[startIdx+outIdx] was
       * read.
       */
      /* Seed each price EMA with a simple average of its first
       * 'period' price bars. The fast window is the tail of the
       * slow window: consume the leading slow-only bars first,
       * then accumulate both over the shared bars.
       */
      today = startIdx - lookbackTotal;
      tempReal = 0.0;
      i = optInSlowPeriod - optInFastPeriod;
      while( i-- > 0 ) {
         tempReal += inReal[today++];
      }
      prevFast = 0.0;
      i = optInFastPeriod;
      while( i-- > 0 ) {
         prevFast += inReal[today];
         tempReal += inReal[today++];
      }
      prevSlow = tempReal / optInSlowPeriod;
      prevFast = prevFast / optInFastPeriod;
      /* Advance both EMA through their unstable period, up to the
       * first MACD-line bar.
       */
      while( today <= startIdx - lookbackSignal ) {
         tempReal = inReal[today++];
         prevFast = Math.FusedMultiplyAdd(tempReal - prevFast, fastK, prevFast);
         prevSlow = Math.FusedMultiplyAdd(tempReal - prevSlow, slowK, prevSlow);
      }
      macdValue = prevFast - prevSlow;
      /* Seed the signal EMA with a simple average of the first
       * 'signal period' MACD-line values, accumulated as they are
       * produced.
       */
      prevSignal = 0.0;
      prevSignal += macdValue;
      i = optInSignalPeriod - 1;
      while( i-- > 0 ) {
         tempReal = inReal[today++];
         prevFast = Math.FusedMultiplyAdd(tempReal - prevFast, fastK, prevFast);
         prevSlow = Math.FusedMultiplyAdd(tempReal - prevSlow, slowK, prevSlow);
         macdValue = prevFast - prevSlow;
         prevSignal += macdValue;
      }
      prevSignal = prevSignal / optInSignalPeriod;
      /* Advance everything in lockstep through the unstable period
       * of the signal EMA, up to the first output bar.
       */
      while( today <= startIdx ) {
         tempReal = inReal[today++];
         prevFast = Math.FusedMultiplyAdd(tempReal - prevFast, fastK, prevFast);
         prevSlow = Math.FusedMultiplyAdd(tempReal - prevSlow, slowK, prevSlow);
         macdValue = prevFast - prevSlow;
         if( optInSignalPeriod == 1 ) {
            prevSignal = macdValue;
         } else {
            prevSignal = Math.FusedMultiplyAdd(macdValue - prevSignal, signalK, prevSignal);
         }
      }
      /* Stable zone: keep advancing in lockstep and write the three
       * outputs.
       */
      outMACD[0 * outStride] = macdValue;
      outMACDSignal[0 * outStride] = prevSignal;
      outMACDHist[0 * outStride] = macdValue - prevSignal;
      outIdx = 1;
      while( today <= endIdx ) {
         tempReal = inReal[today++];
         prevFast = Math.FusedMultiplyAdd(tempReal - prevFast, fastK, prevFast);
         prevSlow = Math.FusedMultiplyAdd(tempReal - prevSlow, slowK, prevSlow);
         macdValue = prevFast - prevSlow;
         if( optInSignalPeriod == 1 ) {
            prevSignal = macdValue;
         } else {
            prevSignal = Math.FusedMultiplyAdd(macdValue - prevSignal, signalK, prevSignal);
         }
         outMACD[outIdx * outStride] = macdValue;
         outMACDSignal[outIdx * outStride] = prevSignal;
         outMACDHist[outIdx * outStride] = macdValue - prevSignal;
         outIdx += 1;
      }
      /* All done! Indicate the output limits and return success. */
      outBegIdx = startIdx;
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      sp.optInSignalPeriod = optInSignalPeriod;
      sp.prevFast = prevFast;
      sp.prevSlow = prevSlow;
      sp.prevSignal = prevSignal;
      sp.slowK = slowK;
      sp.fastK = fastK;
      sp.signalK = signalK;
      sp.cur_outMACD = outMACD[(outNBElement - 1) * outStride];
      sp.cur_outMACDSignal = outMACDSignal[(outNBElement - 1) * outStride];
      sp.cur_outMACDHist = outMACDHist[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* MacdfixOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal MacdfixStream MacdfixOpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, int optInSignalPeriod, out int outBegIdx, out int outNBElement, Span<double> outMACD, Span<double> outMACDSignal, Span<double> outMACDHist )
   {
      MacdfixStream sp = new MacdfixStream(this);
      RetCode retCode = MacdfixOpenImpl(sp, inReal, startIdx, optInSignalPeriod, out outBegIdx, out outNBElement, outMACD, outMACDSignal, outMACDHist, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("MACDFIX", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind MacdfixOpen (composition seam). */
   internal MacdfixStream MacdfixOpenInternal( ReadOnlySpan<double> inReal, int startIdx, int optInSignalPeriod )
   {
      MacdfixStream sp = new MacdfixStream(this);
      double[] sink_outMACD = new double[1];
      double[] sink_outMACDSignal = new double[1];
      double[] sink_outMACDHist = new double[1];
      RetCode retCode = MacdfixOpenImpl(sp, inReal, startIdx, optInSignalPeriod, out int outBegIdx, out int outNBElement, sink_outMACD, sink_outMACDSignal, sink_outMACDHist, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("MACDFIX", "open", retCode);
   }

   /// <summary>Open a live <c>MACDFIX</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="MacdfixStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>MACDFIX</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>MACDFIX_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>MacdfixOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">Source series (typically close) The warm-up history, oldest bar first.</param>
   /// <param name="optInSignalPeriod">As in the batch call; see <see cref="MACDFIX_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>MACDFIX_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public MacdfixStream MacdfixOpen( ReadOnlySpan<double> inReal, int optInSignalPeriod )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "MACDFIX open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "MACDFIX open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      return MacdfixOpenInternal(inReal, 0, optInSignalPeriod);
   }

   /// <summary><c>MacdfixOpen</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>MACDFIX</c> produces over
   /// the same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - MACDFIX_Lookback(...)</c> values
   /// and must not alias the inputs or each other — this path writes the outputs
   /// and then reads the input tail to seed its rings, so the batch tier's
   /// in-place allowance does not carry over here. Both are checked before
   /// anything is written, so an undersized span is an <c>ArgumentException</c>
   /// naming it rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="MacdfixStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">Source series (typically close) The warm-up history, oldest bar first.</param>
   /// <param name="optInSignalPeriod">As in the batch call; see <see cref="MACDFIX_Lookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outMACD">Fixed EMA12 minus EMA26. Must hold at least <c>historyLen -
   /// MACDFIX_Lookback(...)</c> values.</param>
   /// <param name="outMACDSignal">EMA of the MACD line. Must hold at least <c>historyLen -
   /// MACDFIX_Lookback(...)</c> values.</param>
   /// <param name="outMACDHist">MACD minus signal. Must hold at least <c>historyLen -
   /// MACDFIX_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>MACDFIX_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public MacdfixStream MacdfixOpenAndFill( ReadOnlySpan<double> inReal, int optInSignalPeriod, Span<double> outMACD, Span<double> outMACDSignal, Span<double> outMACDHist )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "MACDFIX openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "MACDFIX openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      int guardOutLen = OpenFillCount("MACDFIX", "openAndFill", inReal.Length, MACDFIX_Lookback(optInSignalPeriod));
      RequireFillLength("MACDFIX", "openAndFill", "outMACD", outMACD.Length, guardOutLen);
      RequireFillLength("MACDFIX", "openAndFill", "outMACDSignal", outMACDSignal.Length, guardOutLen);
      RequireFillLength("MACDFIX", "openAndFill", "outMACDHist", outMACDHist.Length, guardOutLen);
      if( outMACD.Overlaps(inReal) || outMACDSignal.Overlaps(inReal) || outMACDHist.Overlaps(inReal) || outMACD.Overlaps(outMACDSignal) || outMACD.Overlaps(outMACDHist) || outMACDSignal.Overlaps(outMACDHist) ) {
         throw StreamFailure("MACDFIX", "openAndFill", RetCode.BadParam);
      }
      return MacdfixOpenAndFillInternal(inReal, 0, optInSignalPeriod, out _, out _, outMACD, outMACDSignal, outMACDHist);
   }
