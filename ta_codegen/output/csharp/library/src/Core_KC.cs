   /// <c>Value</c> contract, which compares bitwise — compare
   /// <see cref="System.BitConverter.DoubleToInt64Bits(double)"/> per component
   /// when bit-level identity is what you mean.</para>
   /// </remarks>
   /// <param name="RealUpperBand">Centre line plus the scaled Average True Range.</param>
   /// <param name="RealMiddleBand">Exponential moving average of the typical price.</param>
   /// <param name="RealLowerBand">Centre line minus the scaled Average True Range.</param>
   public readonly record struct KcValue( double RealUpperBand, double RealMiddleBand, double RealLowerBand );

   /// <summary>A live <c>KC</c> stream: one value per closed bar, bit-identical to
   /// <c>KC</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.KcOpen"/>. There is no close and nothing to
   /// dispose — the handle is ordinary managed state, and an unreferenced handle
   /// is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class KcStream
   {
      internal Core core;
      internal int optInTimePeriod;
      internal int optInATRPeriod;
      internal double optInNbDev;
      internal double cur_outRealUpperBand;
      internal double cur_outRealMiddleBand;
      internal double cur_outRealLowerBand;
      internal TyppriceStream sub0 = null!;
      internal AtrStream sub1 = null!;
      internal EmaStream sub2 = null!;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal KcStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Kc</c> reports over the same bars: the opener sets it
      /// to <c>(lookback, historyLen - lookback)</c>, every <c>Update</c> adds one
      /// to the count — a non-finite bar is rejected but still counted, because the
      /// bar happened — <c>Peek</c> leaves it alone, and <c>Clone</c> carries it
      /// verbatim. A plain <c>Open</c> hands back only the last value, a subset of
      /// this range, because the caller chose not to take the fill.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      internal KcStream( KcStream other )
      {
         this.core = other.core;
         this.optInTimePeriod = other.optInTimePeriod;
         this.optInATRPeriod = other.optInATRPeriod;
         this.optInNbDev = other.optInNbDev;
         this.cur_outRealUpperBand = other.cur_outRealUpperBand;
         this.cur_outRealMiddleBand = other.cur_outRealMiddleBand;
         this.cur_outRealLowerBand = other.cur_outRealLowerBand;
         this.sub0 = new TyppriceStream(other.sub0);
         this.sub1 = new AtrStream(other.sub1);
         this.sub2 = new EmaStream(other.sub2);
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Allocates nothing — neither handle state nor a return value.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so no state moves, <see cref="Value"/> still answers the previous value,
      /// and the stream stays usable — just carry on with the next bar.
      /// <see cref="OutRange"/> does advance: the bar happened, so it is counted,
      /// which keeps two handles fed the same series positionally aligned when only
      /// one of them rejects a bar. This is the one place the streaming tier is
      /// stricter than the batch API, which computes on whatever it is given: a
      /// handle retains its state, so a single non-finite bar would poison every
      /// later value it produces.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>The value at the bar just committed.</returns>
      public KcValue Update( double inHigh, double inLow, double inClose )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) )
         {
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
            throw Core.StreamFailure("KC", "update", RetCode.BadParam);
         }
         core.KcStepImpl(this, inHigh, inLow, inClose);
         if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         return new KcValue(cur_outRealUpperBand, cur_outRealMiddleBand, cur_outRealLowerBand);
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It copies nothing: the frame runs against this handle, reading its buffers
      /// and holding what the step would commit in locals. The cost does not grow
      /// with the period, and <c>Peek</c> never allocates.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>What <see cref="Update"/> would return for this bar.</returns>
      public KcValue Peek( double inHigh, double inLow, double inClose )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) ) throw Core.StreamFailure("KC", "peek", RetCode.BadParam);
         KcStream sp = this;
         double middle = 0.0;
         double tempReal = 0.0;
         double cur_tempTP = 0.0;
         double cur_tempATR = 0.0;
         double cur_outRealMiddleBand = 0.0;
         double cur_outRealUpperBand = 0.0;
         double cur_outRealLowerBand = 0.0;
         /* Pipeline the new bar through the sub-streams (batch tail order). */
         cur_tempTP = sp.sub0.Peek(inHigh, inLow, inClose);
         cur_tempATR = sp.sub1.Peek(inHigh, inLow, inClose);
         cur_outRealMiddleBand = sp.sub2.Peek(cur_tempTP);
         /* Combine map (batch tail, per bar). */
         middle = cur_outRealMiddleBand;
         tempReal = cur_tempATR * sp.optInNbDev;
         cur_outRealUpperBand = middle + tempReal;
         cur_outRealLowerBand = middle - tempReal;
         return new KcValue(cur_outRealUpperBand, cur_outRealMiddleBand, cur_outRealLowerBand);
      }

      /// <summary>Commit <c>n</c> closed bars and write their <c>n</c> values, in one call.</summary>
      /// <remarks>
      /// <para>Exactly <c>n</c> back-to-back <see cref="Update"/> calls, with one set of
      /// argument checks instead of <c>n</c>. The outputs must hold at least
      /// <c>n</c> values and must not overlap an input or each other.</para>
      /// <para><see cref="OutRange"/> counts what this call took in, which is what makes
      /// a rejection readable: a non-finite bar <c>k</c> throws
      /// <see cref="System.ArgumentException"/> exactly as <see cref="Update"/>
      /// would, with the bars before <c>k</c> committed and written, bar <c>k</c>
      /// and everything after it not written, and the count advanced by <c>k +
      /// 1</c> — the committed bars plus the rejected one, so the last bar counted
      /// is the one that failed.</para>
      /// </remarks>
      /// <param name="inHigh">Closed bars for <c>inHigh</c>, oldest first.</param>
      /// <param name="inLow">Closed bars for <c>inLow</c>, oldest first.</param>
      /// <param name="inClose">Closed bars for <c>inClose</c>, oldest first.</param>
      /// <param name="outRealUpperBand">Receives one <c>outRealUpperBand</c> value per bar committed.</param>
      /// <param name="outRealMiddleBand">Receives one <c>outRealMiddleBand</c> value per bar committed.</param>
      /// <param name="outRealLowerBand">Receives one <c>outRealLowerBand</c> value per bar committed.</param>
      public void UpdateAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, Span<double> outRealUpperBand, Span<double> outRealMiddleBand, Span<double> outRealLowerBand )
      {
         int barCount = inHigh.Length;
         if( inLow.Length != barCount || inClose.Length != barCount || outRealUpperBand.Length < barCount || outRealMiddleBand.Length < barCount || outRealLowerBand.Length < barCount || outRealUpperBand.Overlaps(inHigh) || outRealUpperBand.Overlaps(inLow) || outRealUpperBand.Overlaps(inClose) || outRealMiddleBand.Overlaps(inHigh) || outRealMiddleBand.Overlaps(inLow) || outRealMiddleBand.Overlaps(inClose) || outRealLowerBand.Overlaps(inHigh) || outRealLowerBand.Overlaps(inLow) || outRealLowerBand.Overlaps(inClose) || outRealUpperBand.Overlaps(outRealMiddleBand) || outRealUpperBand.Overlaps(outRealLowerBand) || outRealMiddleBand.Overlaps(outRealLowerBand) ) throw Core.StreamFailure("KC", "updateAndFill", RetCode.BadParam);
         for( int i = 0; i < barCount; i++ )
         {
            if( !double.IsFinite(inHigh[i]) || !double.IsFinite(inLow[i]) || !double.IsFinite(inClose[i]) )
            {
               if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
               throw Core.StreamFailure("KC", "updateAndFill", RetCode.BadParam);
            }
            core.KcStepImpl(this, inHigh[i], inLow[i], inClose[i]);
            outRealUpperBand[i] = cur_outRealUpperBand;
            outRealMiddleBand[i] = cur_outRealMiddleBand;
            outRealLowerBand[i] = cur_outRealLowerBand;
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         }
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public KcValue Value => new KcValue(cur_outRealUpperBand, cur_outRealMiddleBand, cur_outRealLowerBand);

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public KcStream Clone()
      {
         return new KcStream(this);
      }
   }

   internal void KcStepImpl( KcStream sp, double inHigh, double inLow, double inClose )
   {
      double middle = 0.0;
      double tempReal = 0.0;
      double cur_tempTP = 0.0;
      double cur_tempATR = 0.0;
      double cur_outRealMiddleBand = 0.0;
      double cur_outRealUpperBand = 0.0;
      double cur_outRealLowerBand = 0.0;
      /* Pipeline the new bar through the sub-streams (batch tail order). */
      cur_tempTP = sp.sub0.Update(inHigh, inLow, inClose);
      cur_tempATR = sp.sub1.Update(inHigh, inLow, inClose);
      cur_outRealMiddleBand = sp.sub2.Update(cur_tempTP);
      /* Combine map (batch tail, per bar). */
      middle = cur_outRealMiddleBand;
      tempReal = cur_tempATR * sp.optInNbDev;
      cur_outRealUpperBand = middle + tempReal;
      cur_outRealLowerBand = middle - tempReal;
      sp.cur_outRealUpperBand = cur_outRealUpperBand;
      sp.cur_outRealMiddleBand = cur_outRealMiddleBand;
      sp.cur_outRealLowerBand = cur_outRealLowerBand;
   }

   private RetCode KcOpenImpl( KcStream sp, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, int optInATRPeriod, double optInNbDev, out int outBegIdx, out int outNBElement, Span<double> outRealUpperBand, Span<double> outRealMiddleBand, Span<double> outRealLowerBand, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      RetCode retCode;
      int i = 0;
      int lookbackTotal = 0;
      int emaLookback = 0;
      int tpStartIdx = 0;
      int tempBegIdx = 0;
      int tempNbElement = 0;
      double tempReal = 0;
      double middle = 0;
      Span<double> tempTP;
      Span<double> tempATR;
      int historyLen = inHigh.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inLow.Length != inHigh.Length || inClose.Length != inHigh.Length ) {
         return RetCode.BadParam;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 20;
      } else if( optInTimePeriod < 2 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInATRPeriod == int.MinValue ) {
         optInATRPeriod = 10;
      } else if( optInATRPeriod < 1 || optInATRPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInNbDev == TA_REAL_DEFAULT ) {
         optInNbDev = 2e0;
      } else if( !(optInNbDev >= TA_REAL_MIN && optInNbDev <= TA_REAL_MAX) ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      if( historyLen < KC_Lookback(optInTimePeriod, optInATRPeriod, optInNbDev) + 1 ) {
         return RetCode.InsufficientHistory;
      }
      Span<double> sc_outRealUpperBand = outStride == 1 ? outRealUpperBand : new double[historyLen];
      Span<double> sc_outRealMiddleBand = outStride == 1 ? outRealMiddleBand : new double[historyLen];
      Span<double> sc_outRealLowerBand = outStride == 1 ? outRealLowerBand : new double[historyLen];
      emaLookback = EMA_Lookback(optInTimePeriod);
      lookbackTotal = KC_Lookback(optInTimePeriod, optInATRPeriod, optInNbDev);
      /* Nothing to produce: the range is shorter than the lookback. Return before
       * touching anything, so that a caller-supplied input which stops short of
       * endIdx is never read past its end.
       */
      if( lookbackTotal > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Each leg is entered at its OWN lookback, so each is the shipped function
       * over this range and nothing here over-warms the shorter one: a caller who
       * wants the band converged sets TA_FUNC_UNST_ATR, exactly as they would when
       * calling TA_ATR directly. The typical price is a derived input, so it is
       * materialized only over the window the moving average reads.
       */
      tpStartIdx = startIdx - emaLookback;
      tempTP = new double[(int)((endIdx - tpStartIdx + 1) * 1)];
      tempATR = new double[(int)((endIdx - startIdx + 1) * 1)];
      /* Sub-stream 0: typprice over `inHigh, inLow, inClose`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      TyppriceStream sub0 = TyppriceOpenAndFillInternal(inHigh, inLow, inClose, tpStartIdx, out tempBegIdx, out tempNbElement, tempTP);
      retCode = RetCode.Success;
      /* The ATR consumes the price inputs before the moving average below writes
       * the middle band, which may be aliased onto one of them.
       */
      /* Sub-stream 1: atr over `inHigh, inLow, inClose`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      AtrStream sub1 = AtrOpenAndFillInternal(inHigh, inLow, inClose, startIdx, optInATRPeriod, out tempBegIdx, out tempNbElement, tempATR);
      retCode = RetCode.Success;
      /* tempTP is bar-tpStartIdx relative, so entering the moving average at its
       * own lookback puts its first output on startIdx, where the ATR's already is.
       */
      /* Sub-stream 2: ema over `tempTP`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      int subLen2 = (endIdx - tpStartIdx) + 1;
      double[] subSrc2_0 = new double[subLen2];
      tempTP.Slice(0, subLen2).CopyTo(subSrc2_0);
      EmaStream sub2 = EmaOpenAndFillInternal(subSrc2_0, emaLookback, optInTimePeriod, out outBegIdx, out outNBElement, sc_outRealMiddleBand);
      retCode = RetCode.Success;
      if( (int)outNBElement == 0 ) {
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      outBegIdx = startIdx;
      for( i = 0; i < (int)outNBElement; i += 1 ) {
         middle = sc_outRealMiddleBand[i];
         tempReal = tempATR[i] * optInNbDev;
         sc_outRealUpperBand[i] = middle + tempReal;
         sc_outRealLowerBand[i] = middle - tempReal;
      }
      /* Capture the live producer state + sub handles. */
      if( outNBElement < 1 ) {
         return RetCode.InsufficientHistory;
      }
      sp.optInTimePeriod = optInTimePeriod;
      sp.optInATRPeriod = optInATRPeriod;
      sp.optInNbDev = optInNbDev;
      sp.sub0 = sub0;
      sp.sub1 = sub1;
      sp.sub2 = sub2;
      sp.cur_outRealUpperBand = sc_outRealUpperBand[outNBElement - 1];
      sp.cur_outRealMiddleBand = sc_outRealMiddleBand[outNBElement - 1];
      sp.cur_outRealLowerBand = sc_outRealLowerBand[outNBElement - 1];
      return RetCode.Success;
   }

   /* KcOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal KcStream KcOpenAndFillInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, int optInATRPeriod, double optInNbDev, out int outBegIdx, out int outNBElement, Span<double> outRealUpperBand, Span<double> outRealMiddleBand, Span<double> outRealLowerBand )
   {
      KcStream sp = new KcStream(this);
      RetCode retCode = KcOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInTimePeriod, optInATRPeriod, optInNbDev, out outBegIdx, out outNBElement, outRealUpperBand, outRealMiddleBand, outRealLowerBand, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("KC", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind KcOpen (composition seam). */
   internal KcStream KcOpenInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInTimePeriod, int optInATRPeriod, double optInNbDev )
   {
      KcStream sp = new KcStream(this);
      double[] sink_outRealUpperBand = new double[1];
      double[] sink_outRealMiddleBand = new double[1];
      double[] sink_outRealLowerBand = new double[1];
      RetCode retCode = KcOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInTimePeriod, optInATRPeriod, optInNbDev, out int outBegIdx, out int outNBElement, sink_outRealUpperBand, sink_outRealMiddleBand, sink_outRealLowerBand, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("KC", "open", retCode);
   }

   /// <summary>Open a live <c>KC</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="KcStream.Value"/> starts at the last history bar's
   /// value — bit-identical to what <c>KC</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>KC_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>KcOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="KC_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInATRPeriod">As in the batch call; see <see cref="KC_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInNbDev">As in the batch call; see <see cref="KC_Lookback"/> for its default and
   /// range (<c>-4e37</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>KC_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public KcStream KcOpen( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInTimePeriod, int optInATRPeriod, double optInNbDev )
   {
      if( inHigh.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "KC open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "KC open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("KC open: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TaLibArgumentException("KC open: inClose is empty", nameof(inClose), RetCode.BadParam);
      RequireHistoryLength("KC", "open", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("KC", "open", "inClose", inClose.Length, inHigh.Length);
      return KcOpenInternal(inHigh, inLow, inClose, 0, optInTimePeriod, optInATRPeriod, optInNbDev);
   }

   /// <summary><c>KcOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>KC</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - KC_Lookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="KcStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="KC_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInATRPeriod">As in the batch call; see <see cref="KC_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInNbDev">As in the batch call; see <see cref="KC_Lookback"/> for its default and
   /// range (<c>-4e37</c> selects the default).</param>
   /// <param name="outRealUpperBand">Centre line plus the scaled Average True Range. Must hold at least
   /// <c>historyLen - KC_Lookback(...)</c> values.</param>
   /// <param name="outRealMiddleBand">Exponential moving average of the typical price. Must hold at least
   /// <c>historyLen - KC_Lookback(...)</c> values.</param>
   /// <param name="outRealLowerBand">Centre line minus the scaled Average True Range. Must hold at least
   /// <c>historyLen - KC_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>KC_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public KcStream KcOpenAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInTimePeriod, int optInATRPeriod, double optInNbDev, Span<double> outRealUpperBand, Span<double> outRealMiddleBand, Span<double> outRealLowerBand )
   {
      if( inHigh.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "KC openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "KC openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("KC openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TaLibArgumentException("KC openAndFill: inClose is empty", nameof(inClose), RetCode.BadParam);
      int guardOutLen = OpenFillCount("KC", "openAndFill", inHigh.Length, KC_Lookback(optInTimePeriod, optInATRPeriod, optInNbDev));
      RequireHistoryLength("KC", "openAndFill", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("KC", "openAndFill", "inClose", inClose.Length, inHigh.Length);
      RequireFillLength("KC", "openAndFill", "outRealUpperBand", outRealUpperBand.Length, guardOutLen);
      RequireFillLength("KC", "openAndFill", "outRealMiddleBand", outRealMiddleBand.Length, guardOutLen);
      RequireFillLength("KC", "openAndFill", "outRealLowerBand", outRealLowerBand.Length, guardOutLen);
      if( outRealUpperBand.Overlaps(inHigh) || outRealUpperBand.Overlaps(inLow) || outRealUpperBand.Overlaps(inClose) || outRealMiddleBand.Overlaps(inHigh) || outRealMiddleBand.Overlaps(inLow) || outRealMiddleBand.Overlaps(inClose) || outRealLowerBand.Overlaps(inHigh) || outRealLowerBand.Overlaps(inLow) || outRealLowerBand.Overlaps(inClose) || outRealUpperBand.Overlaps(outRealMiddleBand) || outRealUpperBand.Overlaps(outRealLowerBand) || outRealMiddleBand.Overlaps(outRealLowerBand) ) {
         throw StreamFailure("KC", "openAndFill", RetCode.BadParam);
      }
      return KcOpenAndFillInternal(inHigh, inLow, inClose, 0, optInTimePeriod, optInATRPeriod, optInNbDev, out _, out _, outRealUpperBand, outRealMiddleBand, outRealLowerBand);
   }
