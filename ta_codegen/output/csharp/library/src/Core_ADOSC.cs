         this.ad = other.ad;
         this.cur_outReal = other.cur_outReal;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Allocates nothing — neither handle state nor a return value.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so the handle is left exactly as it was and the stream stays usable: skip
      /// the bar, or re-open on a clean history. This is the one place the
      /// streaming tier is stricter than the batch API, which computes on whatever
      /// it is given: a handle retains its state, so a single non-finite bar would
      /// poison every later value it produces.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <param name="inVolume">This bar's volume.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inHigh, double inLow, double inClose, double inVolume )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) || !double.IsFinite(inVolume) ) throw Core.StreamFailure("ADOSC", "update", RetCode.BadParam);
         core.ADOSC_StepImpl(this, inHigh, inLow, inClose, inVolume);
         if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — it is the same generated code, run on a copy. Never writes
      /// this handle, so peeks may run concurrently with each other.</para>
      /// <para>It runs on a fresh copy of this handle, so it allocates one — proportional
      /// to the state this indicator carries. If you peek on every tick and that
      /// matters, hold the value <see cref="Update"/> returns instead.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <param name="inVolume">This bar's volume.</param>
      /// <returns>What <see cref="Update"/> would return for this bar.</returns>
      public double Peek( double inHigh, double inLow, double inClose, double inVolume )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) || !double.IsFinite(inVolume) ) throw Core.StreamFailure("ADOSC", "peek", RetCode.BadParam);
         ADOSC_Stream scratch = new ADOSC_Stream(this);
         core.ADOSC_StepImpl(scratch, inHigh, inLow, inClose, inVolume);
         return scratch.cur_outReal;
      }

      /// <summary>Commit <c>n</c> closed bars and write their <c>n</c> values, in one call.</summary>
      /// <remarks>
      /// <para>Exactly <c>n</c> back-to-back <see cref="Update"/> calls, with one set of
      /// argument checks instead of <c>n</c>. The outputs must hold at least
      /// <c>n</c> values and must not overlap an input or each other.</para>
      /// <para><see cref="OutRange"/> counts what was committed, which is what makes a
      /// rejection readable: a non-finite bar <c>k</c> throws
      /// <see cref="System.ArgumentException"/> exactly as <see cref="Update"/>
      /// would, with bars <c>0..k</c> committed and written, bar <c>k</c> and
      /// everything after it not, and the count advanced by <c>k</c>.</para>
      /// </remarks>
      /// <param name="inHigh">Closed bars for <c>inHigh</c>, oldest first.</param>
      /// <param name="inLow">Closed bars for <c>inLow</c>, oldest first.</param>
      /// <param name="inClose">Closed bars for <c>inClose</c>, oldest first.</param>
      /// <param name="inVolume">Closed bars for <c>inVolume</c>, oldest first.</param>
      /// <param name="outReal">Receives one <c>outReal</c> value per bar committed.</param>
      public void UpdateAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, ReadOnlySpan<double> inVolume, Span<double> outReal )
      {
         int barCount = inHigh.Length;
         if( inLow.Length != barCount || inClose.Length != barCount || inVolume.Length != barCount || outReal.Length < barCount || outReal.Overlaps(inHigh) || outReal.Overlaps(inLow) || outReal.Overlaps(inClose) || outReal.Overlaps(inVolume) ) throw Core.StreamFailure("ADOSC", "updateAndFill", RetCode.BadParam);
         for( int i = 0; i < barCount; i++ )
         {
            if( !double.IsFinite(inHigh[i]) || !double.IsFinite(inLow[i]) || !double.IsFinite(inClose[i]) || !double.IsFinite(inVolume[i]) ) throw Core.StreamFailure("ADOSC", "updateAndFill", RetCode.BadParam);
            core.ADOSC_StepImpl(this, inHigh[i], inLow[i], inClose[i], inVolume[i]);
            outReal[i] = cur_outReal;
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         }
      }

      /// <summary>The value at the most recently committed bar — the last history bar right
      /// after open, then whatever the latest <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public ADOSC_Stream Clone()
      {
         return new ADOSC_Stream(this);
      }
   }

   internal void ADOSC_StepImpl( ADOSC_Stream sp, double inHigh, double inLow, double inClose, double inVolume )
   {
      double high = 0.0;
      double low = 0.0;
      double close = 0.0;
      double tmp = 0.0;
      high = inHigh;
      low = inLow;
      tmp = high - low;
      close = inClose;
      if( tmp > 0.0 ) {
         sp.ad += (close - low - (high - close)) / tmp * (double)inVolume;
      }
      sp.fastEMA = Math.FusedMultiplyAdd(sp.one_minus_fastk, sp.fastEMA, sp.fastk * sp.ad);
      sp.slowEMA = Math.FusedMultiplyAdd(sp.one_minus_slowk, sp.slowEMA, sp.slowk * sp.ad);
      sp.cur_outReal = sp.fastEMA - sp.slowEMA;
   }

   private RetCode ADOSC_OpenImpl( ADOSC_Stream sp, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, ReadOnlySpan<double> inVolume, int startIdx, int optInFastPeriod, int optInSlowPeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      int today = 0;
      int outIdx = 0;
      int lookbackTotal = 0;
      int slowestPeriod = 0;
      double high = 0;
      double low = 0;
      double close = 0;
      double tmp = 0;
      double slowEMA = 0;
      double slowk = 0;
      double one_minus_slowk = 0;
      double fastEMA = 0;
      double fastk = 0;
      double one_minus_fastk = 0;
      double ad = 0;
      int historyLen = inHigh.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inLow.Length != inHigh.Length || inClose.Length != inHigh.Length || inVolume.Length != inHigh.Length ) {
         return RetCode.BadParam;
      }
      if( optInFastPeriod == int.MinValue ) {
         optInFastPeriod = 3;
      } else if( optInFastPeriod < 2 || optInFastPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInSlowPeriod == int.MinValue ) {
         optInSlowPeriod = 10;
      } else if( optInSlowPeriod < 2 || optInSlowPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      /* Implementation Note:
       *     The fastEMA varaible is not neceseraly the
       *     fastest EMA.
       *     In the same way, slowEMA is not neceseraly the
       *     slowest EMA.
       *
       *     The ADOSC is always the (fastEMA - slowEMA) regardless
       *     of the period specified. In other word:
       *
       *     ADOSC(3,10) = EMA(3,AD) - EMA(10,AD)
       *
       *        while
       *
       *     ADOSC(10,3) = EMA(10,AD)- EMA(3,AD)
       *
       *     In the first case the EMA(3) is truly a faster EMA,
       *     while in the second case, the EMA(10) is still call
       *     fastEMA in the algorithm, even if it is in fact slower.
       *
       *     This gives more flexibility to the user if they want to
       *     experiment with unusual parameter settings.
       */
      /* Identify the slowest period.
       * This infomration is used soleley to bootstrap
       * the algorithm (skip the lookback period).
       */
      if( optInFastPeriod < optInSlowPeriod ) {
         slowestPeriod = optInSlowPeriod;
      } else {
         slowestPeriod = optInFastPeriod;
      }
      /* Adjust startIdx to account for the lookback period. */
      lookbackTotal = EMA_Lookback(slowestPeriod);
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      outBegIdx = startIdx;
      today = startIdx - lookbackTotal;
      /* The following variables are used to
       * calculate the "ad".
       */
      ad = 0.0;
      /* Constants for EMA */
      fastk = 2.0 / ((double)optInFastPeriod + 1.0);
      one_minus_fastk = 1.0 - fastk;
      slowk = 2.0 / ((double)optInSlowPeriod + 1.0);
      one_minus_slowk = 1.0 - slowk;
      /* Initialize the two EMA
       *
       * Use the same range of initialization inputs for
       * both EMA and simply seed with the first A/D value.
       *
       * Note: Metastock do the same.
       */
      high = inHigh[today];
      low = inLow[today];
      tmp = high - low;
      close = inClose[today];
      if( tmp > 0.0 ) {
         ad += (close - low - (high - close)) / tmp * (double)inVolume[today];
      }
      today += 1;
      fastEMA = ad;
      slowEMA = ad;
      /* Initialize the EMA and skip the unstable period. */
      while( today < startIdx ) {
         high = inHigh[today];
         low = inLow[today];
         tmp = high - low;
         close = inClose[today];
         if( tmp > 0.0 ) {
            ad += (close - low - (high - close)) / tmp * (double)inVolume[today];
         }
         today += 1;
         fastEMA = Math.FusedMultiplyAdd(one_minus_fastk, fastEMA, fastk * ad);
         slowEMA = Math.FusedMultiplyAdd(one_minus_slowk, slowEMA, slowk * ad);
      }
      /* Perform the calculation for the requested range */
      outIdx = 0;
      while( today <= endIdx ) {
         high = inHigh[today];
         low = inLow[today];
         tmp = high - low;
         close = inClose[today];
         if( tmp > 0.0 ) {
            ad += (close - low - (high - close)) / tmp * (double)inVolume[today];
         }
         today += 1;
         fastEMA = Math.FusedMultiplyAdd(one_minus_fastk, fastEMA, fastk * ad);
         slowEMA = Math.FusedMultiplyAdd(one_minus_slowk, slowEMA, slowk * ad);
         outReal[outIdx++ * outStride] = fastEMA - slowEMA;
      }
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      sp.optInFastPeriod = optInFastPeriod;
      sp.optInSlowPeriod = optInSlowPeriod;
      sp.slowEMA = slowEMA;
      sp.slowk = slowk;
      sp.one_minus_slowk = one_minus_slowk;
      sp.fastEMA = fastEMA;
      sp.fastk = fastk;
      sp.one_minus_fastk = one_minus_fastk;
      sp.ad = ad;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* ADOSC_OpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal ADOSC_Stream ADOSC_OpenAndFillInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, ReadOnlySpan<double> inVolume, int startIdx, int optInFastPeriod, int optInSlowPeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      ADOSC_Stream sp = new ADOSC_Stream(this);
      RetCode retCode = ADOSC_OpenImpl(sp, inHigh, inLow, inClose, inVolume, startIdx, optInFastPeriod, optInSlowPeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("ADOSC", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind ADOSC_Open (composition seam). */
   internal ADOSC_Stream ADOSC_OpenInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, ReadOnlySpan<double> inVolume, int startIdx, int optInFastPeriod, int optInSlowPeriod )
   {
      ADOSC_Stream sp = new ADOSC_Stream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = ADOSC_OpenImpl(sp, inHigh, inLow, inClose, inVolume, startIdx, optInFastPeriod, optInSlowPeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("ADOSC", "open", retCode);
   }

   /// <summary>Open a live <c>ADOSC</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="ADOSC_Stream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>ADOSC</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>ADOSC_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>ADOSC_OpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inVolume">Volume of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInFastPeriod">As in the batch call; see <see cref="ADOSC_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowPeriod">As in the batch call; see <see cref="ADOSC_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>ADOSC_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public ADOSC_Stream ADOSC_Open( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, ReadOnlySpan<double> inVolume, int optInFastPeriod, int optInSlowPeriod )
   {
      if( inHigh.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "ADOSC open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "ADOSC open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("ADOSC open: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TaLibArgumentException("ADOSC open: inClose is empty", nameof(inClose), RetCode.BadParam);
      if( inVolume.IsEmpty ) throw new TaLibArgumentException("ADOSC open: inVolume is empty", nameof(inVolume), RetCode.BadParam);
      RequireHistoryLength("ADOSC", "open", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("ADOSC", "open", "inClose", inClose.Length, inHigh.Length);
      RequireHistoryLength("ADOSC", "open", "inVolume", inVolume.Length, inHigh.Length);
      return ADOSC_OpenInternal(inHigh, inLow, inClose, inVolume, 0, optInFastPeriod, optInSlowPeriod);
   }

   /// <summary><c>ADOSC_Open</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>ADOSC</c> produces over
   /// the same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - ADOSC_Lookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="ADOSC_Stream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inVolume">Volume of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInFastPeriod">As in the batch call; see <see cref="ADOSC_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowPeriod">As in the batch call; see <see cref="ADOSC_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Fast-EMA minus slow-EMA of the A/D line. Must hold at least <c>historyLen
   /// - ADOSC_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>ADOSC_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public ADOSC_Stream ADOSC_OpenAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, ReadOnlySpan<double> inVolume, int optInFastPeriod, int optInSlowPeriod, Span<double> outReal )
   {
      if( inHigh.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "ADOSC openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "ADOSC openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("ADOSC openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TaLibArgumentException("ADOSC openAndFill: inClose is empty", nameof(inClose), RetCode.BadParam);
      if( inVolume.IsEmpty ) throw new TaLibArgumentException("ADOSC openAndFill: inVolume is empty", nameof(inVolume), RetCode.BadParam);
      int guardOutLen = OpenFillCount("ADOSC", "openAndFill", inHigh.Length, ADOSC_Lookback(optInFastPeriod, optInSlowPeriod));
      RequireHistoryLength("ADOSC", "openAndFill", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("ADOSC", "openAndFill", "inClose", inClose.Length, inHigh.Length);
      RequireHistoryLength("ADOSC", "openAndFill", "inVolume", inVolume.Length, inHigh.Length);
      RequireFillLength("ADOSC", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( outReal.Overlaps(inHigh) || outReal.Overlaps(inLow) || outReal.Overlaps(inClose) || outReal.Overlaps(inVolume) ) {
         throw StreamFailure("ADOSC", "openAndFill", RetCode.BadParam);
      }
      return ADOSC_OpenAndFillInternal(inHigh, inLow, inClose, inVolume, 0, optInFastPeriod, optInSlowPeriod, out _, out _, outReal);
   }
