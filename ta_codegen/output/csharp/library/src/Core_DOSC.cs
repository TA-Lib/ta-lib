   /// <summary>A live <c>DOSC</c> stream: one value per closed bar, bit-identical to
   /// <c>DOSC</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.DoscOpen"/>. There is no close and nothing to
   /// dispose — the handle is ordinary managed state, and an unreferenced handle
   /// is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class DoscStream
   {
      internal Core core;
      internal int optInTimePeriod;
      internal int optInFirstPeriod;
      internal int optInSecondPeriod;
      internal int optInSignalPeriod;
      internal double k1;
      internal double beta1;
      internal double k2;
      internal double beta2;
      internal double invPeriod;
      internal double prevGain;
      internal double prevLoss;
      internal double prevValue;
      internal double ema1;
      internal double ema2;
      internal double sumSignal;
      internal int dsBuffer_Idx;
      internal int maxIdx_dsBuffer;
      internal int cbSize_dsBuffer;
      internal double[] cb_dsBuffer = [];
      internal double cur_outReal;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal DoscStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Dosc</c> reports over the same bars: the opener sets it
      /// to <c>(lookback, historyLen - lookback)</c>, every accepted <c>Update</c>
      /// adds one to the count — a rejected one changes nothing, and neither does
      /// <c>Peek</c> — and <c>Clone</c> carries it verbatim. A plain <c>Open</c>
      /// hands back only the last value, a subset of this range, because the caller
      /// chose not to take the fill.</para>
      /// <para>The last bar it can reach is <see cref="Core.IndexMax"/>; past that
      /// <c>Update</c> and <c>Advance</c> throw.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      /// <summary>Count one bar this stream was not fed: <see cref="OutRange"/> advances by
      /// one and nothing else moves.</summary>
      /// <remarks>
      /// <para><see cref="Value"/> keeps answering the previous output, which is this
      /// bar's output too. For a bar the caller leaves out: one an <c>Update</c>
      /// rejected and that will not be re-fed, or a session with no print. Without
      /// it two handles on one feed drift a bar apart when only one of them skips.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, the last one the batch tier
      /// can address and the last this handle will count. <c>Update</c> throws the
      /// same there.</para>
      /// </remarks>
      public void Advance()
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("DOSC", "advance", RetCode.OutOfRangeEndIndex);
         outRangeCount++;
      }

      internal DoscStream( DoscStream other )
      {
         this.core = other.core;
         this.optInTimePeriod = other.optInTimePeriod;
         this.optInFirstPeriod = other.optInFirstPeriod;
         this.optInSecondPeriod = other.optInSecondPeriod;
         this.optInSignalPeriod = other.optInSignalPeriod;
         this.k1 = other.k1;
         this.beta1 = other.beta1;
         this.k2 = other.k2;
         this.beta2 = other.beta2;
         this.invPeriod = other.invPeriod;
         this.prevGain = other.prevGain;
         this.prevLoss = other.prevLoss;
         this.prevValue = other.prevValue;
         this.ema1 = other.ema1;
         this.ema2 = other.ema2;
         this.sumSignal = other.sumSignal;
         this.dsBuffer_Idx = other.dsBuffer_Idx;
         this.maxIdx_dsBuffer = other.maxIdx_dsBuffer;
         this.cbSize_dsBuffer = other.cbSize_dsBuffer;
         this.cb_dsBuffer = new double[other.cb_dsBuffer.Length];
         Array.Copy( other.cb_dsBuffer, this.cb_dsBuffer, other.cb_dsBuffer.Length );
         this.cur_outReal = other.cur_outReal;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so nothing moves — <see cref="OutRange"/> included — and
      /// <see cref="Value"/> still answers the previous value. Re-feed the bar when
      /// a corrected value arrives, or call <see cref="Advance"/> to count it and
      /// carry on; two handles on one feed drift a bar apart if neither happens.
      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, which no re-feed clears: the
      /// handle has run out of index domain and only a shorter history can start a
      /// new one.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inReal )
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("DOSC", "update", RetCode.OutOfRangeEndIndex);
         if( !double.IsFinite(inReal) ) throw Core.NonFiniteBar("DOSC", "update", nameof(inReal));
         core.DoscStepImpl(this, inReal);
         outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.IndexMax"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public double Peek( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.NonFiniteBar("DOSC", "peek", nameof(inReal));
         DoscStream sp = this;
         double gainDelta = 0.0;
         double tempValue1 = 0.0;
         double tempValue2 = 0.0;
         double rsiValue = 0.0;
         double cur_outReal = 0.0;
         double ema1 = sp.ema1;
         double ema2 = sp.ema2;
         double prevGain = sp.prevGain;
         double prevLoss = sp.prevLoss;
         double prevValue = sp.prevValue;
         double sumSignal = sp.sumSignal;
         tempValue1 = inReal;
         tempValue2 = tempValue1 - prevValue;
         prevValue = tempValue1;
         prevLoss *= (double)(sp.optInTimePeriod - 1);
         prevGain *= (double)(sp.optInTimePeriod - 1);
         gainDelta = MaxGt(tempValue2, 0.0);
         prevGain += gainDelta;
         prevLoss += gainDelta - tempValue2;
         prevLoss *= sp.invPeriod;
         prevGain *= sp.invPeriod;
         tempValue1 = prevGain + prevLoss;
         if( tempValue1 > 0.0 ) {
            rsiValue = 100.0 * (prevGain / tempValue1);
         } else {
            rsiValue = 50.0;
         }
         ema1 = Math.FusedMultiplyAdd(sp.beta1, ema1, sp.k1 * rsiValue);
         ema2 = Math.FusedMultiplyAdd(sp.beta2, ema2, sp.k2 * ema1);
         sumSignal = sumSignal + ema2;
         cur_outReal = ema2 - sumSignal / (double)sp.optInSignalPeriod;
         return cur_outReal;
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public DoscStream Clone()
      {
         return new DoscStream(this);
      }
   }

   private void DoscStepImpl( DoscStream sp, double inReal )
   {
      double gainDelta = 0.0;
      double tempValue1 = 0.0;
      double tempValue2 = 0.0;
      double rsiValue = 0.0;
      tempValue1 = inReal;
      tempValue2 = tempValue1 - sp.prevValue;
      sp.prevValue = tempValue1;
      sp.prevLoss *= (double)(sp.optInTimePeriod - 1);
      sp.prevGain *= (double)(sp.optInTimePeriod - 1);
      gainDelta = MaxGt(tempValue2, 0.0);
      sp.prevGain += gainDelta;
      sp.prevLoss += gainDelta - tempValue2;
      sp.prevLoss *= sp.invPeriod;
      sp.prevGain *= sp.invPeriod;
      tempValue1 = sp.prevGain + sp.prevLoss;
      if( tempValue1 > 0.0 ) {
         rsiValue = 100.0 * (sp.prevGain / tempValue1);
      } else {
         rsiValue = 50.0;
      }
      sp.ema1 = Math.FusedMultiplyAdd(sp.beta1, sp.ema1, sp.k1 * rsiValue);
      sp.ema2 = Math.FusedMultiplyAdd(sp.beta2, sp.ema2, sp.k2 * sp.ema1);
      sp.cb_dsBuffer[sp.dsBuffer_Idx] = sp.ema2;
      sp.sumSignal = sp.sumSignal + sp.ema2;
      sp.cur_outReal = sp.ema2 - sp.sumSignal / (double)sp.optInSignalPeriod;
      sp.dsBuffer_Idx = sp.dsBuffer_Idx + 1;
      if( sp.dsBuffer_Idx > sp.maxIdx_dsBuffer ) {
         sp.dsBuffer_Idx = 0;
      }
      sp.sumSignal = sp.sumSignal - sp.cb_dsBuffer[sp.dsBuffer_Idx];
   }

   private RetCode DoscOpenImpl( DoscStream sp, ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, int optInFirstPeriod, int optInSecondPeriod, int optInSignalPeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double k1 = 0;
      double beta1 = 0;
      double k2 = 0;
      double beta2 = 0;
      double invPeriod = 0;
      double prevGain = 0;
      double prevLoss = 0;
      double prevValue = 0;
      double gainDelta = 0;
      double tempValue1 = 0;
      double tempValue2 = 0;
      double rsiValue = 0;
      double ema1 = 0;
      double ema2 = 0;
      double sum1 = 0;
      double sum2 = 0;
      double sumSignal = 0;
      int lookbackTotal = 0;
      int lookbackRSI = 0;
      int lookbackEMA1 = 0;
      int lookbackEMA2 = 0;
      int skipRSI = 0;
      int today = 0;
      int i = 0;
      int outIdx = 0;
      int rsiBar = 0;
      int nRsi = 0;
      int n1 = 0;
      int n2 = 0;
      double[] dsBuffer = [];
      int dsBuffer_Idx = 0;
      int maxIdx_dsBuffer = (32)-1;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > IndexMax + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 14;
      } else if( optInTimePeriod < 2 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInFirstPeriod == int.MinValue ) {
         optInFirstPeriod = 5;
      } else if( optInFirstPeriod < 2 || optInFirstPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInSecondPeriod == int.MinValue ) {
         optInSecondPeriod = 3;
      } else if( optInSecondPeriod < 2 || optInSecondPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInSignalPeriod == int.MinValue ) {
         optInSignalPeriod = 9;
      } else if( optInSignalPeriod < 2 || optInSignalPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      /* Constance Brown's "triple smoothed derivative of RSI plotted as a
       * histogram" (MTA Journal, 1994): MACD's histogram construction applied to
       * a double-smoothed RSI.
       *
       *    S1_t   = EMA(RSI(x, t), f)_t
       *    DS_t   = EMA(S1, s)_t
       *    DOSC_t = DS_t - SMA(DS, g)_t
       *
       * The output must stay bit-identical to
       * TA_RSI -> TA_EMA -> TA_EMA -> TA_SMA -> TA_SUB, so every stage keeps its
       * callee's operation order, and every stage boundary is the callee's
       * LOOKBACK, not (period-1): a warm unstable period then folds in.
       *
       * Compare the counters BEFORE subtracting them: the Rust backend renders
       * them usize, where `n = nRsi - skipRSI; if( n >= 0 )` underflows.
       */
      /* This ptr will point on a circular buffer of at least
       * "optInSignalPeriod" element.
       */
      lookbackTotal = DoscLookback(optInTimePeriod, optInFirstPeriod, optInSecondPeriod, optInSignalPeriod);
      /* Move up the start index if there is not
       * enough initial data.
       */
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      if( optInSignalPeriod < 1 ) return RetCode.InternalError;
      dsBuffer = new double[optInSignalPeriod];
      maxIdx_dsBuffer = (optInSignalPeriod)-1;
      dsBuffer_Idx = 0;
      lookbackRSI = RsiLookback(optInTimePeriod);
      lookbackEMA1 = EmaLookback(optInFirstPeriod);
      lookbackEMA2 = EmaLookback(optInSecondPeriod);
      /* The RSI values the composed chain never publishes. Derive the count
       * from the lookback, never from TA_GetUnstablePeriod: under the Auto
       * levels it is a function of the period.
       */
      skipRSI = lookbackRSI - optInTimePeriod;
      /* k and beta must sum to exactly 1.0, or a flat input drifts off its
       * level. Each subtraction is exact only from an operand in [0.5,1): at a
       * period of 2 that is k, above it beta. Above it beta stays as the divide
       * wrote it: a register last written by a subtraction costs each FMA
       * reading it one more cycle on Intel P-cores.
       */
      beta1 = (double)(optInFirstPeriod - 1) / (double)(optInFirstPeriod + 1);
      k1 = 1.0 - beta1;
      if( beta1 < 0.5 ) {
         beta1 = 1.0 - k1;
      }
      beta2 = (double)(optInSecondPeriod - 1) / (double)(optInSecondPeriod + 1);
      k2 = 1.0 - beta2;
      if( beta2 < 0.5 ) {
         beta2 = 1.0 - k2;
      }
      ema1 = 0.0;
      ema2 = 0.0;
      sum1 = 0.0;
      sum2 = 0.0;
      sumSignal = 0.0;
      nRsi = 0;
      invPeriod = 1.0 / (double)optInTimePeriod;
      today = startIdx - lookbackTotal;
      rsiBar = today + optInTimePeriod;
      prevValue = inReal[today];
      prevGain = 0.0;
      prevLoss = 0.0;
      today = today + 1;
      for( i = optInTimePeriod; i > 0; i -= 1 ) {
         tempValue1 = inReal[today];
         today = today + 1;
         tempValue2 = tempValue1 - prevValue;
         prevValue = tempValue1;
         gainDelta = MaxGt(tempValue2, 0.0);
         prevGain += gainDelta;
         prevLoss += gainDelta - tempValue2;
      }
      prevLoss *= invPeriod;
      prevGain *= invPeriod;
      tempValue1 = prevGain + prevLoss;
      if( tempValue1 > 0.0 ) {
         rsiValue = 100.0 * (prevGain / tempValue1);
      } else {
         rsiValue = 50.0;
      }
      /* Warm-up. Feeds every RSI value before startIdx through the chain and
       * leaves rsiValue holding startIdx's own. Nothing is emitted here: the
       * first bar whose signal window is full is startIdx, by construction of
       * the lookback.
       */
      while( rsiBar < startIdx ) {
         if( nRsi >= skipRSI ) {
            n1 = nRsi - skipRSI;
            if( n1 < optInFirstPeriod ) {
               sum1 = sum1 + rsiValue;
               if( n1 == optInFirstPeriod - 1 ) {
                  ema1 = sum1 / optInFirstPeriod;
               }
            } else {
               ema1 = Math.FusedMultiplyAdd(beta1, ema1, k1 * rsiValue);
            }
            if( n1 >= lookbackEMA1 ) {
               n2 = n1 - lookbackEMA1;
               if( n2 < optInSecondPeriod ) {
                  sum2 = sum2 + ema1;
                  if( n2 == optInSecondPeriod - 1 ) {
                     ema2 = sum2 / optInSecondPeriod;
                  }
               } else {
                  ema2 = Math.FusedMultiplyAdd(beta2, ema2, k2 * ema1);
               }
               if( n2 >= lookbackEMA2 ) {
                  dsBuffer[dsBuffer_Idx] = ema2;
                  sumSignal = sumSignal + ema2;
                  dsBuffer_Idx++;
                  if( dsBuffer_Idx > maxIdx_dsBuffer ) { dsBuffer_Idx = 0; }
               }
            }
         }
         nRsi = nRsi + 1;
         tempValue1 = inReal[today];
         today = today + 1;
         tempValue2 = tempValue1 - prevValue;
         prevValue = tempValue1;
         prevLoss *= (double)(optInTimePeriod - 1);
         prevGain *= (double)(optInTimePeriod - 1);
         gainDelta = MaxGt(tempValue2, 0.0);
         prevGain += gainDelta;
         prevLoss += gainDelta - tempValue2;
         prevLoss *= invPeriod;
         prevGain *= invPeriod;
         tempValue1 = prevGain + prevLoss;
         if( tempValue1 > 0.0 ) {
            rsiValue = 100.0 * (prevGain / tempValue1);
         } else {
            rsiValue = 50.0;
         }
         rsiBar = rsiBar + 1;
      }
      /* The first output. Every stage is past its seed here, even at periods
       * 2/2/2/2, so the store below and the one in the stable loop are
       * unconditional. Keep them so: under a guard, the managed peek frames
       * seed a dead output local.
       */
      ema1 = Math.FusedMultiplyAdd(beta1, ema1, k1 * rsiValue);
      ema2 = Math.FusedMultiplyAdd(beta2, ema2, k2 * ema1);
      dsBuffer[dsBuffer_Idx] = ema2;
      sumSignal = sumSignal + ema2;
      outReal[0 * outStride] = ema2 - sumSignal / (double)optInSignalPeriod;
      outIdx = 1;
      dsBuffer_Idx++;
      if( dsBuffer_Idx > maxIdx_dsBuffer ) { dsBuffer_Idx = 0; }
      sumSignal = sumSignal - dsBuffer[dsBuffer_Idx];
      /* Stable zone. */
      while( today <= endIdx ) {
         tempValue1 = inReal[today];
         today = today + 1;
         tempValue2 = tempValue1 - prevValue;
         prevValue = tempValue1;
         prevLoss *= (double)(optInTimePeriod - 1);
         prevGain *= (double)(optInTimePeriod - 1);
         gainDelta = MaxGt(tempValue2, 0.0);
         prevGain += gainDelta;
         prevLoss += gainDelta - tempValue2;
         prevLoss *= invPeriod;
         prevGain *= invPeriod;
         tempValue1 = prevGain + prevLoss;
         if( tempValue1 > 0.0 ) {
            rsiValue = 100.0 * (prevGain / tempValue1);
         } else {
            rsiValue = 50.0;
         }
         ema1 = Math.FusedMultiplyAdd(beta1, ema1, k1 * rsiValue);
         ema2 = Math.FusedMultiplyAdd(beta2, ema2, k2 * ema1);
         dsBuffer[dsBuffer_Idx] = ema2;
         sumSignal = sumSignal + ema2;
         outReal[outIdx * outStride] = ema2 - sumSignal / (double)optInSignalPeriod;
         outIdx = outIdx + 1;
         dsBuffer_Idx++;
         if( dsBuffer_Idx > maxIdx_dsBuffer ) { dsBuffer_Idx = 0; }
         sumSignal = sumSignal - dsBuffer[dsBuffer_Idx];
      }
      outNBElement = outIdx;
      outBegIdx = startIdx;
      /* Capture the live batch state into the handle. */
      int capCb_dsBuffer = maxIdx_dsBuffer + 1;
      if( capCb_dsBuffer > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      sp.optInTimePeriod = optInTimePeriod;
      sp.optInFirstPeriod = optInFirstPeriod;
      sp.optInSecondPeriod = optInSecondPeriod;
      sp.optInSignalPeriod = optInSignalPeriod;
      sp.k1 = k1;
      sp.beta1 = beta1;
      sp.k2 = k2;
      sp.beta2 = beta2;
      sp.invPeriod = invPeriod;
      sp.prevGain = prevGain;
      sp.prevLoss = prevLoss;
      sp.prevValue = prevValue;
      sp.ema1 = ema1;
      sp.ema2 = ema2;
      sp.sumSignal = sumSignal;
      sp.dsBuffer_Idx = dsBuffer_Idx;
      sp.maxIdx_dsBuffer = maxIdx_dsBuffer;
      sp.cbSize_dsBuffer = capCb_dsBuffer;
      sp.cb_dsBuffer = dsBuffer;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* DoscOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal DoscStream DoscOpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, int optInFirstPeriod, int optInSecondPeriod, int optInSignalPeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      DoscStream sp = new DoscStream(this);
      RetCode retCode = DoscOpenImpl(sp, inReal, startIdx, optInTimePeriod, optInFirstPeriod, optInSecondPeriod, optInSignalPeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("DOSC", "openAndFill", nameof(inReal), inReal.Length, startIdx, DoscLookback(optInTimePeriod, optInFirstPeriod, optInSecondPeriod, optInSignalPeriod));
      }
      throw StreamFailure("DOSC", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind DoscOpen (composition seam). */
   internal DoscStream DoscOpenInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, int optInFirstPeriod, int optInSecondPeriod, int optInSignalPeriod )
   {
      DoscStream sp = new DoscStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = DoscOpenImpl(sp, inReal, startIdx, optInTimePeriod, optInFirstPeriod, optInSecondPeriod, optInSignalPeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("DOSC", "open", nameof(inReal), inReal.Length, startIdx, DoscLookback(optInTimePeriod, optInFirstPeriod, optInSecondPeriod, optInSignalPeriod));
      }
      throw StreamFailure("DOSC", "open", retCode);
   }

   /// <summary>Open a live <c>DOSC</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="DoscStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>DOSC</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>DoscLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>DoscOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">Input series, usually the close. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="DoscLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInFirstPeriod">As in the batch call; see <see cref="DoscLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSecondPeriod">As in the batch call; see <see cref="DoscLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSignalPeriod">As in the batch call; see <see cref="DoscLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>DoscLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public DoscStream DoscOpen( ReadOnlySpan<double> inReal, int optInTimePeriod, int optInFirstPeriod, int optInSecondPeriod, int optInSignalPeriod )
   {
      if( inReal.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "DOSC open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "DOSC open: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      return DoscOpenInternal(inReal, 0, optInTimePeriod, optInFirstPeriod, optInSecondPeriod, optInSignalPeriod);
   }

   /// <summary><c>DoscOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>DOSC</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - DoscLookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="DoscStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">Input series, usually the close. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="DoscLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInFirstPeriod">As in the batch call; see <see cref="DoscLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSecondPeriod">As in the batch call; see <see cref="DoscLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSignalPeriod">As in the batch call; see <see cref="DoscLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Derivative Oscillator, in RSI points, centred on zero. Must hold at least
   /// <c>historyLen - DoscLookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>DoscLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public DoscStream DoscOpenAndFill( ReadOnlySpan<double> inReal, int optInTimePeriod, int optInFirstPeriod, int optInSecondPeriod, int optInSignalPeriod, Span<double> outReal )
   {
      if( inReal.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "DOSC openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "DOSC openAndFill: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      int guardOutLen = OpenFillCount("DOSC", "openAndFill", inReal.Length, DoscLookback(optInTimePeriod, optInFirstPeriod, optInSecondPeriod, optInSignalPeriod));
      RequireFillLength("DOSC", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( SameBuffer(outReal, inReal) ) {
         throw StreamFailure("DOSC", "openAndFill", RetCode.BadParam);
      }
      if( guardOutLen > 0 && ( outReal.Overlaps(inReal) ) ) {
         throw StreamFailure("DOSC", "openAndFill", RetCode.BadParam);
      }
      return DoscOpenAndFillInternal(inReal, 0, optInTimePeriod, optInFirstPeriod, optInSecondPeriod, optInSignalPeriod, out _, out _, outReal);
   }
