      /// bar's output too. For a bar the caller leaves out: one an <c>Update</c>
      /// rejected and that will not be re-fed, or a session with no print. Without
      /// it two handles on one feed drift a bar apart when only one of them skips.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, the last one the batch tier
      /// can address and the last this handle will count. <c>Update</c> throws the
      /// same there.</para>
      /// </remarks>
      public void Advance()
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("SWAK_BUTTER", "advance", RetCode.OutOfRangeEndIndex);
         outRangeCount++;
      }

      internal SwakButterStream( SwakButterStream other )
      {
         this.core = other.core;
         this.optInTimePeriod = other.optInTimePeriod;
         this.c0 = other.c0;
         this.a1 = other.a1;
         this.a2 = other.a2;
         this.x1 = other.x1;
         this.x2 = other.x2;
         this.y1 = other.y1;
         this.y2 = other.y2;
         this.cur_outReal = other.cur_outReal;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so nothing moves — <see cref="OutRange"/> included — and
      /// <see cref="Value"/> still answers the previous value. Re-feed the bar when
      /// a corrected value arrives, or call <see cref="Advance"/> to count it and
      /// carry on; two handles on one feed drift a bar apart if neither happens.
      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, which no re-feed clears: the
      /// handle has run out of index domain and only a shorter history can start a
      /// new one.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inReal )
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("SWAK_BUTTER", "update", RetCode.OutOfRangeEndIndex);
         if( !double.IsFinite(inReal) ) throw Core.NonFiniteBar("SWAK_BUTTER", "update", nameof(inReal));
         core.SwakButterStepImpl(this, inReal);
         outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.IndexMax"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public double Peek( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.NonFiniteBar("SWAK_BUTTER", "peek", nameof(inReal));
         SwakButterStream sp = this;
         double x0 = 0.0;
         double y = 0.0;
         double cur_outReal = 0.0;
         double x1 = sp.x1;
         double x2 = sp.x2;
         double y1 = sp.y1;
         double y2 = sp.y2;
         /* a1*y1 stays the outermost term. y1 is the newest output, so the bar
          * rate is the latency of whatever y1 crosses to become y: outermost, that
          * is one fused step. Nested inside, it is three, and every backend's last
          * bit moves with it.
          */
         x0 = inReal;
         y = Math.FusedMultiplyAdd(sp.a1, y1, Math.FusedMultiplyAdd(sp.a2, y2, sp.c0 * (Math.FusedMultiplyAdd(2.0, x1, x0) + x2)));
         x2 = x1;
         x1 = x0;
         y2 = y1;
         y1 = y;
         cur_outReal = y;
         return cur_outReal;
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public SwakButterStream Clone()
      {
         return new SwakButterStream(this);
      }
   }

   private void SwakButterStepImpl( SwakButterStream sp, double inReal )
   {
      double x0 = 0.0;
      double y = 0.0;
      /* a1*y1 stays the outermost term. y1 is the newest output, so the bar
       * rate is the latency of whatever y1 crosses to become y: outermost, that
       * is one fused step. Nested inside, it is three, and every backend's last
       * bit moves with it.
       */
      x0 = inReal;
      y = Math.FusedMultiplyAdd(sp.a1, sp.y1, Math.FusedMultiplyAdd(sp.a2, sp.y2, sp.c0 * (Math.FusedMultiplyAdd(2.0, sp.x1, x0) + sp.x2)));
      sp.x2 = sp.x1;
      sp.x1 = x0;
      sp.y2 = sp.y1;
      sp.y1 = y;
      sp.cur_outReal = y;
   }

   private RetCode SwakButterOpenImpl( SwakButterStream sp, ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      int i = 0;
      int outIdx = 0;
      int today = 0;
      int lookbackTotal = 0;
      double s = 0;
      double b2p = 0;
      double a2p = 0;
      double om = 0;
      double c0 = 0;
      double a1 = 0;
      double a2 = 0;
      double x0 = 0;
      double x1 = 0;
      double x2 = 0;
      double y = 0;
      double y1 = 0;
      double y2 = 0;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > IndexMax + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 20;
      } else if( optInTimePeriod < 2 || optInTimePeriod > 10000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      outBegIdx = 0;
      outNBElement = 0;
      lookbackTotal = SwakButterLookback(optInTimePeriod);
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      if( startIdx > endIdx ) {
         return RetCode.InsufficientHistory ;
      }
      /* The two-pole alpha of Ehlers' "Swiss Army Knife Indicator", Figure 5. The
       * paper's 360/P is a full turn, so 2*pi/P.
       *
       * Keep 1 - cos(w) as 2*sin(w/2)^2: the subtraction cancels more of b2p's
       * digits the longer the period, and the cutoff drifts with them.
       */
      s = Math.Sin(3.141592653589793 / (double)optInTimePeriod);
      b2p = 2.415 * (2.0 * s * s);
      a2p = -b2p + Math.Sqrt(Math.FusedMultiplyAdd(b2p, b2p, 2.0 * b2p));
      /* The Butterworth row: the Gaussian's double real pole with two zeros added
       * at Nyquist, which is what the (1, 2, 1) numerator is. The quarter in c0
       * keeps the DC gain at 1 against that numerator's weight of 4.
       */
      om = 1.0 - a2p;
      c0 = a2p * a2p / 4.0;
      a1 = 2.0 * om;
      a2 = -(om * om);
      today = startIdx - lookbackTotal;
      /* Start in the steady state of a constant input equal to the first bar.
       * Unlike the Gaussian row this one has non-zero b1 and b2, so the two input
       * slots are carried in locals and never re-read from inReal: outReal may
       * alias inReal, and an aliased write would already have overwritten the
       * earlier bars this recurrence needs.
       */
      x0 = inReal[today];
      x1 = x0;
      x2 = x0;
      y1 = x0;
      y2 = x0;
      /* Skip the unstable period: run the recurrence but publish nothing. */
      i = lookbackTotal;
      while( i != 0 ) {
         x0 = inReal[today];
         y = Math.FusedMultiplyAdd(a1, y1, Math.FusedMultiplyAdd(a2, y2, c0 * (Math.FusedMultiplyAdd(2.0, x1, x0) + x2)));
         x2 = x1;
         x1 = x0;
         y2 = y1;
         y1 = y;
         today += 1;
         i -= 1;
      }
      outIdx = 0;
      while( today <= endIdx ) {
         /* a1*y1 stays the outermost term. y1 is the newest output, so the bar
          * rate is the latency of whatever y1 crosses to become y: outermost, that
          * is one fused step. Nested inside, it is three, and every backend's last
          * bit moves with it.
          */
         x0 = inReal[today];
         y = Math.FusedMultiplyAdd(a1, y1, Math.FusedMultiplyAdd(a2, y2, c0 * (Math.FusedMultiplyAdd(2.0, x1, x0) + x2)));
         x2 = x1;
         x1 = x0;
         y2 = y1;
         y1 = y;
         outReal[outIdx * outStride] = y;
         outIdx = outIdx + 1;
         today += 1;
      }
      outNBElement = outIdx;
      outBegIdx = startIdx;
      /* Capture the live batch state into the handle. */
      sp.optInTimePeriod = optInTimePeriod;
      sp.c0 = c0;
      sp.a1 = a1;
      sp.a2 = a2;
      sp.x1 = x1;
      sp.x2 = x2;
      sp.y1 = y1;
      sp.y2 = y2;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* SwakButterOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal SwakButterStream SwakButterOpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      SwakButterStream sp = new SwakButterStream(this);
      RetCode retCode = SwakButterOpenImpl(sp, inReal, startIdx, optInTimePeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("SWAK_BUTTER", "openAndFill", nameof(inReal), inReal.Length, startIdx, SwakButterLookback(optInTimePeriod));
      }
      throw StreamFailure("SWAK_BUTTER", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind SwakButterOpen (composition seam). */
   internal SwakButterStream SwakButterOpenInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod )
   {
      SwakButterStream sp = new SwakButterStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = SwakButterOpenImpl(sp, inReal, startIdx, optInTimePeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("SWAK_BUTTER", "open", nameof(inReal), inReal.Length, startIdx, SwakButterLookback(optInTimePeriod));
      }
      throw StreamFailure("SWAK_BUTTER", "open", retCode);
   }

   /// <summary>Open a live <c>SWAK_BUTTER</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="SwakButterStream.Value"/> starts at the last
   /// history bar's value — bit-identical to what <c>SWAK_BUTTER</c> reports for
   /// that bar.</para>
   /// <para>The history must hold at least <c>SwakButterLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>SwakButterOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">The series to filter; Ehlers' default is the bar midpoint <c>(H+L)/2</c>,
   /// which the caller passes as <c>TA_MEDPRICE</c> output. The warm-up history,
   /// oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="SwakButterLookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>SwakButterLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public SwakButterStream SwakButterOpen( ReadOnlySpan<double> inReal, int optInTimePeriod )
   {
      if( inReal.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "SWAK_BUTTER open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "SWAK_BUTTER open: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      return SwakButterOpenInternal(inReal, 0, optInTimePeriod);
   }

   /// <summary><c>SwakButterOpen</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>SWAK_BUTTER</c> produces
   /// over the same series, so no separate batch call is needed for the warm-up
   /// plot.</para>
   /// <para>Output arrays must hold <c>historyLen - SwakButterLookback(...)</c> values
   /// and must not alias the inputs or each other — this path writes the outputs
   /// and then reads the input tail to seed its rings, so the batch tier's
   /// in-place allowance does not carry over here. Both are checked before
   /// anything is written, so an undersized span is an <c>ArgumentException</c>
   /// naming it rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="SwakButterStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">The series to filter; Ehlers' default is the bar midpoint <c>(H+L)/2</c>,
   /// which the caller passes as <c>TA_MEDPRICE</c> output. The warm-up history,
   /// oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="SwakButterLookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">The filtered line, on the same scale as the input. Must hold at least
   /// <c>historyLen - SwakButterLookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>SwakButterLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public SwakButterStream SwakButterOpenAndFill( ReadOnlySpan<double> inReal, int optInTimePeriod, Span<double> outReal )
   {
      if( inReal.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "SWAK_BUTTER openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "SWAK_BUTTER openAndFill: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      int guardOutLen = OpenFillCount("SWAK_BUTTER", "openAndFill", inReal.Length, SwakButterLookback(optInTimePeriod));
      RequireFillLength("SWAK_BUTTER", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( SameBuffer(outReal, inReal) ) {
         throw StreamFailure("SWAK_BUTTER", "openAndFill", RetCode.BadParam);
      }
      if( guardOutLen > 0 && ( outReal.Overlaps(inReal) ) ) {
         throw StreamFailure("SWAK_BUTTER", "openAndFill", RetCode.BadParam);
      }
      return SwakButterOpenAndFillInternal(inReal, 0, optInTimePeriod, out _, out _, outReal);
   }
