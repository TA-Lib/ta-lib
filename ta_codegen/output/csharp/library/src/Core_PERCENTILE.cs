      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Allocates nothing — neither handle state nor a return value.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so no state moves, <see cref="Value"/> still answers the previous value,
      /// and the stream stays usable — just carry on with the next bar.
      /// <see cref="OutRange"/> does advance: the bar happened, so it is counted,
      /// which keeps two handles fed the same series positionally aligned when only
      /// one of them rejects a bar. This is the one place the streaming tier is
      /// stricter than the batch API, which computes on whatever it is given: a
      /// handle retains its state, so a single non-finite bar would poison every
      /// later value it produces.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inReal )
      {
         if( !double.IsFinite(inReal) )
         {
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
            throw Core.StreamFailure("PERCENTILE", "update", RetCode.BadParam);
         }
         core.PercentileStepImpl(this, inReal);
         if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It copies nothing: the frame runs against this handle, reading its buffers
      /// and holding what the step would commit in locals. The cost does not grow
      /// with the period, and <c>Peek</c> never allocates.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>What <see cref="Update"/> would return for this bar.</returns>
      public double Peek( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.StreamFailure("PERCENTILE", "peek", RetCode.BadParam);
         PercentileStream sp = this;
         double newValue = 0.0;
         double result = 0.0;
         int pos = 0;
         double cur_outReal = 0.0;
         newValue = inReal;
         pos = 0;
         while( pos < sp.lookbackTotal && sp.cb_sorted[pos] <= newValue ) {
            pos += 1;
         }
         if( sp.rank - 1 < pos ) {
            result = sp.cb_sorted[sp.rank - 1];
         } else if( sp.rank - 1 == pos ) {
            result = newValue;
         } else {
            result = sp.cb_sorted[sp.rank - 2];
         }
         cur_outReal = result;
         return cur_outReal;
      }

      /// <summary>Commit <c>n</c> closed bars and write their <c>n</c> values, in one call.</summary>
      /// <remarks>
      /// <para>Exactly <c>n</c> back-to-back <see cref="Update"/> calls, with one set of
      /// argument checks instead of <c>n</c>. The outputs must hold at least
      /// <c>n</c> values and must not overlap an input or each other.</para>
      /// <para><see cref="OutRange"/> counts what this call took in, which is what makes
      /// a rejection readable: a non-finite bar <c>k</c> throws
      /// <see cref="System.ArgumentException"/> exactly as <see cref="Update"/>
      /// would, with the bars before <c>k</c> committed and written, bar <c>k</c>
      /// and everything after it not written, and the count advanced by <c>k +
      /// 1</c> — the committed bars plus the rejected one, so the last bar counted
      /// is the one that failed.</para>
      /// </remarks>
      /// <param name="inReal">Closed bars for <c>inReal</c>, oldest first.</param>
      /// <param name="outReal">Receives one <c>outReal</c> value per bar committed.</param>
      public void UpdateAndFill( ReadOnlySpan<double> inReal, Span<double> outReal )
      {
         int barCount = inReal.Length;
         if( outReal.Length < barCount || outReal.Overlaps(inReal) ) throw Core.StreamFailure("PERCENTILE", "updateAndFill", RetCode.BadParam);
         for( int i = 0; i < barCount; i++ )
         {
            if( !double.IsFinite(inReal[i]) )
            {
               if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
               throw Core.StreamFailure("PERCENTILE", "updateAndFill", RetCode.BadParam);
            }
            core.PercentileStepImpl(this, inReal[i]);
            outReal[i] = cur_outReal;
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         }
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public PercentileStream Clone()
      {
         return new PercentileStream(this);
      }
   }

   internal void PercentileStepImpl( PercentileStream sp, double inReal )
   {
      double newValue = 0.0;
      double oldValue = 0.0;
      double result = 0.0;
      int j = 0;
      int pos = 0;
      newValue = inReal;
      pos = 0;
      while( pos < sp.lookbackTotal && sp.cb_sorted[pos] <= newValue ) {
         pos += 1;
      }
      if( sp.rank - 1 < pos ) {
         result = sp.cb_sorted[sp.rank - 1];
      } else if( sp.rank - 1 == pos ) {
         result = newValue;
      } else {
         result = sp.cb_sorted[sp.rank - 2];
      }
      sp.cur_outReal = result;
      /* Shifting only the strictly greater entries leaves equal values in
       * insertion order, which is age order -- that is what lets the delete
       * below evict the oldest of a run by value alone, with no slot array.
       */
      j = sp.lookbackTotal;
      while( j > pos ) {
         sp.cb_sorted[j] = sp.cb_sorted[j - 1];
         j -= 1;
      }
      sp.cb_sorted[pos] = newValue;
      sp.cb_ring[sp.ring_Idx] = newValue;
      sp.ring_Idx = sp.ring_Idx + 1;
      if( sp.ring_Idx > sp.maxIdx_ring ) {
         sp.ring_Idx = 0;
      }
      oldValue = sp.cb_ring[sp.ring_Idx];
      j = 0;
      while( j < sp.lookbackTotal && sp.cb_sorted[j] < oldValue ) {
         j += 1;
      }
      while( j < sp.lookbackTotal ) {
         sp.cb_sorted[j] = sp.cb_sorted[j + 1];
         j += 1;
      }
   }

   private RetCode PercentileOpenImpl( PercentileStream sp, ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, double optInPercentile, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double newValue = 0;
      double oldValue = 0;
      double result = 0;
      int lookbackTotal = 0;
      int outIdx = 0;
      int i = 0;
      int j = 0;
      int pos = 0;
      int nbSorted = 0;
      int rank = 0;
      double[] ring = [];
      int ring_Idx = 0;
      int maxIdx_ring = (30)-1;
      double[] sorted = [];
      int sorted_Idx = 0;
      int maxIdx_sorted = (30)-1;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 30;
      } else if( optInTimePeriod < 2 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInPercentile == TA_REAL_DEFAULT ) {
         optInPercentile = 5e1;
      } else if( !(optInPercentile >= 0e0 && optInPercentile <= 1e2) ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      /* The window is carried twice: "ring" by age, "sorted" by value. */
      lookbackTotal = optInTimePeriod - 1;
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      if( optInTimePeriod < 1 ) return RetCode.InternalError;
      ring = new double[optInTimePeriod];
      maxIdx_ring = (optInTimePeriod)-1;
      ring_Idx = 0;
      if( optInTimePeriod < 1 ) return RetCode.InternalError;
      sorted = new double[optInTimePeriod];
      maxIdx_sorted = (optInTimePeriod)-1;
      sorted_Idx = 0;
      /* Keep the multiply left of the divide. (P*n)/100 reproduces exact integer
       * arithmetic; P/100 is inexact in binary64 and lands the product just above
       * an integer, one order statistic too high, at exactly the round
       * percentages a caller types.
       */
      rank = (int)Math.Ceiling(optInPercentile * (double)optInTimePeriod / 100.0);
      if( rank < 1 ) {
         rank = 1;
      }
      if( rank > optInTimePeriod ) {
         rank = optInTimePeriod;
      }
      nbSorted = 0;
      i = startIdx - lookbackTotal;
      while( i < startIdx ) {
         newValue = inReal[i];
         j = nbSorted;
         while( j > 0 && sorted[j - 1] > newValue ) {
            sorted[j] = sorted[j - 1];
            j -= 1;
         }
         sorted[j] = newValue;
         nbSorted += 1;
         ring[ring_Idx] = newValue;
         i += 1;
         ring_Idx++;
         if( ring_Idx > maxIdx_ring ) { ring_Idx = 0; }
      }
      /* Both scratch buffers hold copies and inReal is never read below i, so
       * inReal and outReal may be the same buffer.
       *
       * Every buffer store sits BELOW the output store on purpose: deriving the
       * whole answer read-only above it is what lets the streaming peek frame drop
       * the state update rather than shadow a shift loop, which it cannot do.
       */
      outIdx = 0;
      do {
         newValue = inReal[i];
         pos = 0;
         while( pos < lookbackTotal && sorted[pos] <= newValue ) {
            pos += 1;
         }
         if( rank - 1 < pos ) {
            result = sorted[rank - 1];
         } else if( rank - 1 == pos ) {
            result = newValue;
         } else {
            result = sorted[rank - 2];
         }
         outReal[outIdx * outStride] = result;
         outIdx += 1;
         /* Shifting only the strictly greater entries leaves equal values in
          * insertion order, which is age order -- that is what lets the delete
          * below evict the oldest of a run by value alone, with no slot array.
          */
         j = lookbackTotal;
         while( j > pos ) {
            sorted[j] = sorted[j - 1];
            j -= 1;
         }
         sorted[pos] = newValue;
         ring[ring_Idx] = newValue;
         ring_Idx++;
         if( ring_Idx > maxIdx_ring ) { ring_Idx = 0; }
         oldValue = ring[ring_Idx];
         j = 0;
         while( j < lookbackTotal && sorted[j] < oldValue ) {
            j += 1;
         }
         while( j < lookbackTotal ) {
            sorted[j] = sorted[j + 1];
            j += 1;
         }
         i += 1;
      } while( i <= endIdx );
      outNBElement = outIdx;
      outBegIdx = startIdx;
      /* Capture the live batch state into the handle. */
      int capCb_ring = maxIdx_ring + 1;
      if( capCb_ring > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      int capCb_sorted = maxIdx_sorted + 1;
      if( capCb_sorted > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      sp.optInTimePeriod = optInTimePeriod;
      sp.optInPercentile = optInPercentile;
      sp.lookbackTotal = lookbackTotal;
      sp.rank = rank;
      sp.ring_Idx = ring_Idx;
      sp.maxIdx_ring = maxIdx_ring;
      sp.sorted_Idx = sorted_Idx;
      sp.maxIdx_sorted = maxIdx_sorted;
      sp.cbSize_ring = capCb_ring;
      sp.cb_ring = ring;
      sp.cbSize_sorted = capCb_sorted;
      sp.cb_sorted = sorted;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* PercentileOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal PercentileStream PercentileOpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, double optInPercentile, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      PercentileStream sp = new PercentileStream(this);
      RetCode retCode = PercentileOpenImpl(sp, inReal, startIdx, optInTimePeriod, optInPercentile, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("PERCENTILE", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind PercentileOpen (composition seam). */
   internal PercentileStream PercentileOpenInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, double optInPercentile )
   {
      PercentileStream sp = new PercentileStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = PercentileOpenImpl(sp, inReal, startIdx, optInTimePeriod, optInPercentile, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("PERCENTILE", "open", retCode);
   }

   /// <summary>Open a live <c>PERCENTILE</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="PercentileStream.Value"/> starts at the last
   /// history bar's value — bit-identical to what <c>PERCENTILE</c> reports for
   /// that bar.</para>
   /// <para>The history must hold at least <c>PERCENTILE_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>PercentileOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">Source series to take the percentile of. The warm-up history, oldest bar
   /// first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="PERCENTILE_Lookback"/> for its
   /// default and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInPercentile">As in the batch call; see <see cref="PERCENTILE_Lookback"/> for its
   /// default and range (<c>-4e37</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>PERCENTILE_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public PercentileStream PercentileOpen( ReadOnlySpan<double> inReal, int optInTimePeriod, double optInPercentile )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "PERCENTILE open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "PERCENTILE open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      return PercentileOpenInternal(inReal, 0, optInTimePeriod, optInPercentile);
   }

   /// <summary><c>PercentileOpen</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>PERCENTILE</c> produces
   /// over the same series, so no separate batch call is needed for the warm-up
   /// plot.</para>
   /// <para>Output arrays must hold <c>historyLen - PERCENTILE_Lookback(...)</c>
   /// values and must not alias the inputs or each other — this path writes the
   /// outputs and then reads the input tail to seed its rings, so the batch
   /// tier's in-place allowance does not carry over here. Both are checked
   /// before anything is written, so an undersized span is an
   /// <c>ArgumentException</c> naming it rather than a fault from inside the
   /// fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="PercentileStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">Source series to take the percentile of. The warm-up history, oldest bar
   /// first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="PERCENTILE_Lookback"/> for its
   /// default and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInPercentile">As in the batch call; see <see cref="PERCENTILE_Lookback"/> for its
   /// default and range (<c>-4e37</c> selects the default).</param>
   /// <param name="outReal">The value at the requested rank within the trailing window. Must hold at
   /// least <c>historyLen - PERCENTILE_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>PERCENTILE_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public PercentileStream PercentileOpenAndFill( ReadOnlySpan<double> inReal, int optInTimePeriod, double optInPercentile, Span<double> outReal )
   {
      if( inReal.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "PERCENTILE openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inReal), "PERCENTILE openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      int guardOutLen = OpenFillCount("PERCENTILE", "openAndFill", inReal.Length, PERCENTILE_Lookback(optInTimePeriod, optInPercentile));
      RequireFillLength("PERCENTILE", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( outReal.Overlaps(inReal) ) {
         throw StreamFailure("PERCENTILE", "openAndFill", RetCode.BadParam);
      }
      return PercentileOpenAndFillInternal(inReal, 0, optInTimePeriod, optInPercentile, out _, out _, outReal);
   }
