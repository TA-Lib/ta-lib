   /// <summary>One <c>FISHER</c> output set, in batch output order.</summary>
   /// <remarks>
   /// <para>Equality is the compiler-generated record-struct equality, which compares
   /// each component with <see cref="System.Double.Equals(System.Double)"/>, not
   /// <c>==</c>: any two <c>NaN</c> payloads compare equal, and <c>0.0</c>
   /// equals <c>-0.0</c>. Compare
   /// <see cref="System.BitConverter.DoubleToInt64Bits(double)"/> per component
   /// when bit-level identity is what you mean.</para>
   /// </remarks>
   /// <param name="Fisher">Fisher Transform value.</param>
   /// <param name="Trigger">Fisher value of the previous bar.</param>
   public readonly record struct FisherValue( double Fisher, double Trigger );

   /// <summary>A live <c>FISHER</c> stream: one value per closed bar, bit-identical to
   /// <c>FISHER</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.FisherOpen"/>. There is no close and nothing to
   /// dispose — the handle is ordinary managed state, and an unreferenced handle
   /// is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class FisherStream
   {
      internal Core core;
      internal int optInTimePeriod;
      internal double highest;
      internal double lowest;
      internal double smoothed;
      internal double prevFish;
      internal int trailingIdx;
      internal int highestIdx;
      internal int lowestIdx;
      internal int i;
      internal int today;
      internal int xMask;
      internal double[] x_inHigh = [];
      internal double[] x_inLow = [];
      internal double cur_outFisher;
      internal double cur_outTrigger;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal FisherStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Fisher</c> reports over the same bars: the opener sets
      /// it to <c>(lookback, historyLen - lookback)</c>, every accepted
      /// <c>Update</c> adds one to the count — a rejected one changes nothing, and
      /// neither does <c>Peek</c> — and <c>Clone</c> carries it verbatim. A plain
      /// <c>Open</c> hands back only the last value, a subset of this range,
      /// because the caller chose not to take the fill.</para>
      /// <para>The last bar it can reach is <see cref="Core.IndexMax"/>; past that
      /// <c>Update</c> and <c>Advance</c> throw.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      /// <summary>Count one bar this stream was not fed: <see cref="OutRange"/> advances by
      /// one and nothing else moves.</summary>
      /// <remarks>
      /// <para><see cref="Value"/> keeps answering the previous output, which is this
      /// bar's output too. For a bar the caller leaves out: one an <c>Update</c>
      /// rejected and that will not be re-fed, or a session with no print. Without
      /// it two handles on one feed drift a bar apart when only one of them skips.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, the last one the batch tier
      /// can address and the last this handle will count. <c>Update</c> throws the
      /// same there.</para>
      /// </remarks>
      public void Advance()
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("FISHER", "advance", RetCode.OutOfRangeEndIndex);
         outRangeCount++;
      }

      internal FisherStream( FisherStream other )
      {
         this.core = other.core;
         this.optInTimePeriod = other.optInTimePeriod;
         this.highest = other.highest;
         this.lowest = other.lowest;
         this.smoothed = other.smoothed;
         this.prevFish = other.prevFish;
         this.trailingIdx = other.trailingIdx;
         this.highestIdx = other.highestIdx;
         this.lowestIdx = other.lowestIdx;
         this.i = other.i;
         this.today = other.today;
         this.xMask = other.xMask;
         this.x_inHigh = new double[other.x_inHigh.Length];
         Array.Copy( other.x_inHigh, this.x_inHigh, other.x_inHigh.Length );
         this.x_inLow = new double[other.x_inLow.Length];
         Array.Copy( other.x_inLow, this.x_inLow, other.x_inLow.Length );
         this.cur_outFisher = other.cur_outFisher;
         this.cur_outTrigger = other.cur_outTrigger;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so nothing moves — <see cref="OutRange"/> included — and
      /// <see cref="Value"/> still answers the previous value. Re-feed the bar when
      /// a corrected value arrives, or call <see cref="Advance"/> to count it and
      /// carry on; two handles on one feed drift a bar apart if neither happens.
      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, which no re-feed clears: the
      /// handle has run out of index domain and only a shorter history can start a
      /// new one.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <returns>The value at the bar just committed.</returns>
      public FisherValue Update( double inHigh, double inLow )
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("FISHER", "update", RetCode.OutOfRangeEndIndex);
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) ) throw Core.NonFiniteBar("FISHER", "update", !double.IsFinite(inHigh) ? nameof(inHigh) : nameof(inLow));
         core.FisherStepImpl(this, inHigh, inLow);
         outRangeCount++;
         return new FisherValue(cur_outFisher, cur_outTrigger);
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.IndexMax"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public FisherValue Peek( double inHigh, double inLow )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) ) throw Core.NonFiniteBar("FISHER", "peek", !double.IsFinite(inHigh) ? nameof(inHigh) : nameof(inLow));
         FisherStream sp = this;
         double price = 0.0;
         double ratio = 0.0;
         double fish = 0.0;
         double tempReal = 0.0;
         double tempHigh = 0.0;
         double tempLow = 0.0;
         double cur_outFisher = 0.0;
         double cur_outTrigger = 0.0;
         double highest = sp.highest;
         int highestIdx = sp.highestIdx;
         int i = sp.i;
         double lowest = sp.lowest;
         int lowestIdx = sp.lowestIdx;
         double smoothed = sp.smoothed;
         int pkSlot0 = -1;
         double pkVal0 = 0.0;
         int pkSlot1 = -1;
         double pkVal1 = 0.0;
         pkSlot0 = sp.today & sp.xMask;
         pkVal0 = inHigh;
         pkSlot1 = sp.today & sp.xMask;
         pkVal1 = inLow;
         /* The channel, over the midpoints rather than over the highs and the
          * lows separately: this indicator reads one series, which happens to be
          * (H+L)/2, so both extremes come from that same series. STOCH's shape,
          * with the midpoint recomputed on the rare rescan rather than held in a
          * buffer the caller would have to own.
          */
         price = ((((sp.today & sp.xMask) != pkSlot0) ? sp.x_inHigh[sp.today & sp.xMask] : pkVal0) + (((sp.today & sp.xMask) != pkSlot1) ? sp.x_inLow[sp.today & sp.xMask] : pkVal1)) / 2.0;
         if( highestIdx < sp.trailingIdx ) {
            highestIdx = sp.trailingIdx;
            tempHigh = ((highestIdx & sp.xMask) != pkSlot0) ? sp.x_inHigh[highestIdx & sp.xMask] : pkVal0;
            tempLow = ((highestIdx & sp.xMask) != pkSlot1) ? sp.x_inLow[highestIdx & sp.xMask] : pkVal1;
            highest = (tempHigh + tempLow) / 2.0;
            i = highestIdx;
            while( ++i <= sp.today ) {
               tempHigh = ((i & sp.xMask) != pkSlot0) ? sp.x_inHigh[i & sp.xMask] : pkVal0;
               tempLow = ((i & sp.xMask) != pkSlot1) ? sp.x_inLow[i & sp.xMask] : pkVal1;
               tempReal = (tempHigh + tempLow) / 2.0;
               if( tempReal > highest ) {
                  highestIdx = i;
                  highest = tempReal;
               }
            }
         } else if( price >= highest ) {
            highestIdx = sp.today;
            highest = price;
         }
         if( lowestIdx < sp.trailingIdx ) {
            lowestIdx = sp.trailingIdx;
            tempHigh = ((lowestIdx & sp.xMask) != pkSlot0) ? sp.x_inHigh[lowestIdx & sp.xMask] : pkVal0;
            tempLow = ((lowestIdx & sp.xMask) != pkSlot1) ? sp.x_inLow[lowestIdx & sp.xMask] : pkVal1;
            lowest = (tempHigh + tempLow) / 2.0;
            i = lowestIdx;
            while( ++i <= sp.today ) {
               tempHigh = ((i & sp.xMask) != pkSlot0) ? sp.x_inHigh[i & sp.xMask] : pkVal0;
               tempLow = ((i & sp.xMask) != pkSlot1) ? sp.x_inLow[i & sp.xMask] : pkVal1;
               tempReal = (tempHigh + tempLow) / 2.0;
               if( tempReal < lowest ) {
                  lowestIdx = i;
                  lowest = tempReal;
               }
            }
         } else if( price <= lowest ) {
            lowestIdx = sp.today;
            lowest = price;
         }
         /* A flat window answers the neutral position rather than dividing by
          * its own zero range. The band is the range against its own two
          * extremes, STOCH's test: a fixed constant answers "flat" for every
          * window of an instrument quoted below it (#253), and an exact test
          * divides a machine-flat window into noise (#107). At 0.5 the bar
          * contributes nothing and both recursions decay on their own
          * coefficients.
          */
         tempReal = highest - lowest;
         if( !(Math.Abs(tempReal) <= 0.00000000000001 * (Math.Abs(highest) + Math.Abs(lowest))) ) {
            ratio = (price - lowest) / tempReal;
         } else {
            ratio = 0.5;
         }
         /* The listing's .33*2*(r-.5) + .67*Value1[1]. */
         smoothed = Math.FusedMultiplyAdd(0.67, smoothed, 0.33 * 2.0 * (ratio - 0.5));
         /* The clamp is what keeps atanh finite, and the CLAMPED smoothed is what
          * the next bar's smoothing reads -- the listing assigns it back to
          * Value1 rather than holding it for the transform alone.
          */
         if( smoothed > 0.99 ) {
            smoothed = 0.999;
         }
         if( smoothed < -0.99 ) {
            smoothed = -0.999;
         }
         fish = Math.FusedMultiplyAdd(0.5, Math.Log((1.0 + smoothed) / (1.0 - smoothed)), 0.5 * sp.prevFish);
         cur_outFisher = fish;
         /* The author's second plot is Fish[1]: the previous bar's smoothed,
          * which at the first output bar is the zero seed when no unstable
          * period was discarded, and the computed smoothed of the bar before it
          * when one was.
          */
         cur_outTrigger = sp.prevFish;
         return new FisherValue(cur_outFisher, cur_outTrigger);
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public FisherValue Value => new FisherValue(cur_outFisher, cur_outTrigger);

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public FisherStream Clone()
      {
         return new FisherStream(this);
      }
   }

   private void FisherStepImpl( FisherStream sp, double inHigh, double inLow )
   {
      double price = 0.0;
      double ratio = 0.0;
      double fish = 0.0;
      double tempReal = 0.0;
      double tempHigh = 0.0;
      double tempLow = 0.0;
      sp.x_inHigh[sp.today & sp.xMask] = inHigh;
      sp.x_inLow[sp.today & sp.xMask] = inLow;
      /* The channel, over the midpoints rather than over the highs and the
       * lows separately: this indicator reads one series, which happens to be
       * (H+L)/2, so both extremes come from that same series. STOCH's shape,
       * with the midpoint recomputed on the rare rescan rather than held in a
       * buffer the caller would have to own.
       */
      price = (sp.x_inHigh[sp.today & sp.xMask] + sp.x_inLow[sp.today & sp.xMask]) / 2.0;
      if( sp.highestIdx < sp.trailingIdx ) {
         sp.highestIdx = sp.trailingIdx;
         tempHigh = sp.x_inHigh[sp.highestIdx & sp.xMask];
         tempLow = sp.x_inLow[sp.highestIdx & sp.xMask];
         sp.highest = (tempHigh + tempLow) / 2.0;
         sp.i = sp.highestIdx;
         while( ++sp.i <= sp.today ) {
            tempHigh = sp.x_inHigh[sp.i & sp.xMask];
            tempLow = sp.x_inLow[sp.i & sp.xMask];
            tempReal = (tempHigh + tempLow) / 2.0;
            if( tempReal > sp.highest ) {
               sp.highestIdx = sp.i;
               sp.highest = tempReal;
            }
         }
      } else if( price >= sp.highest ) {
         sp.highestIdx = sp.today;
         sp.highest = price;
      }
      if( sp.lowestIdx < sp.trailingIdx ) {
         sp.lowestIdx = sp.trailingIdx;
         tempHigh = sp.x_inHigh[sp.lowestIdx & sp.xMask];
         tempLow = sp.x_inLow[sp.lowestIdx & sp.xMask];
         sp.lowest = (tempHigh + tempLow) / 2.0;
         sp.i = sp.lowestIdx;
         while( ++sp.i <= sp.today ) {
            tempHigh = sp.x_inHigh[sp.i & sp.xMask];
            tempLow = sp.x_inLow[sp.i & sp.xMask];
            tempReal = (tempHigh + tempLow) / 2.0;
            if( tempReal < sp.lowest ) {
               sp.lowestIdx = sp.i;
               sp.lowest = tempReal;
            }
         }
      } else if( price <= sp.lowest ) {
         sp.lowestIdx = sp.today;
         sp.lowest = price;
      }
      /* A flat window answers the neutral position rather than dividing by
       * its own zero range. The band is the range against its own two
       * extremes, STOCH's test: a fixed constant answers "flat" for every
       * window of an instrument quoted below it (#253), and an exact test
       * divides a machine-flat window into noise (#107). At 0.5 the bar
       * contributes nothing and both recursions decay on their own
       * coefficients.
       */
      tempReal = sp.highest - sp.lowest;
      if( !(Math.Abs(tempReal) <= 0.00000000000001 * (Math.Abs(sp.highest) + Math.Abs(sp.lowest))) ) {
         ratio = (price - sp.lowest) / tempReal;
      } else {
         ratio = 0.5;
      }
      /* The listing's .33*2*(r-.5) + .67*Value1[1]. */
      sp.smoothed = Math.FusedMultiplyAdd(0.67, sp.smoothed, 0.33 * 2.0 * (ratio - 0.5));
      /* The clamp is what keeps atanh finite, and the CLAMPED smoothed is what
       * the next bar's smoothing reads -- the listing assigns it back to
       * Value1 rather than holding it for the transform alone.
       */
      if( sp.smoothed > 0.99 ) {
         sp.smoothed = 0.999;
      }
      if( sp.smoothed < -0.99 ) {
         sp.smoothed = -0.999;
      }
      fish = Math.FusedMultiplyAdd(0.5, Math.Log((1.0 + sp.smoothed) / (1.0 - sp.smoothed)), 0.5 * sp.prevFish);
      sp.cur_outFisher = fish;
      /* The author's second plot is Fish[1]: the previous bar's smoothed,
       * which at the first output bar is the zero seed when no unstable
       * period was discarded, and the computed smoothed of the bar before it
       * when one was.
       */
      sp.cur_outTrigger = sp.prevFish;
      sp.prevFish = fish;
      sp.trailingIdx += 1;
      sp.today += 1;
   }

   private RetCode FisherOpenImpl( FisherStream sp, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outFisher, Span<double> outTrigger, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double price = 0;
      double highest = 0;
      double lowest = 0;
      double ratio = 0;
      double smoothed = 0;
      double fish = 0;
      double prevFish = 0;
      double tempReal = 0;
      double tempHigh = 0;
      double tempLow = 0;
      int outIdx = 0;
      int lookbackTotal = 0;
      int unstablePeriod = 0;
      int nbInitialElementNeeded = 0;
      int today = 0;
      int trailingIdx = 0;
      int highestIdx = 0;
      int lowestIdx = 0;
      int i = 0;
      int historyLen = inHigh.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > IndexMax + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inLow.Length != inHigh.Length ) {
         return RetCode.BadParam;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 10;
      } else if( optInTimePeriod < 2 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      nbInitialElementNeeded = FisherLookback(optInTimePeriod);
      if( startIdx < nbInitialElementNeeded ) {
         startIdx = nbInitialElementNeeded;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      lookbackTotal = optInTimePeriod - 1;
      unstablePeriod = nbInitialElementNeeded - lookbackTotal;
      /* John F. Ehlers, "Using The Fisher Transform", Stocks & Commodities
       * V.20:11 (November 2002), pp.40-42, the EasyLanguage listing in Figure 4.
       *
       * The bar's midpoint is located in its rolling n-bar channel, rescaled to
       * (-1, +1), smoothed, clamped, and passed through atanh. What the
       * transform buys is the tail: a channel position is close to uniformly
       * distributed, and the Fisher transform of a uniform variable is close to
       * normal, so an extreme reading is rare rather than routine and a turn is
       * a sharp corner rather than a drift.
       *
       * Both recursions start from the author's zero seed and decay at their own
       * coefficient -- 0.67 for the smoothing, 0.5 for the transform -- so the
       * first bars carry the seed rather than the series. That is what the
       * unstable period discards.
       */
      smoothed = 0.0;
      prevFish = 0.0;
      today = startIdx - unstablePeriod;
      trailingIdx = today - lookbackTotal;
      highestIdx = -1;
      highest = 0.0;
      lowestIdx = -1;
      lowest = 0.0;
      outIdx = 0;
      while( today <= endIdx ) {
         /* The channel, over the midpoints rather than over the highs and the
          * lows separately: this indicator reads one series, which happens to be
          * (H+L)/2, so both extremes come from that same series. STOCH's shape,
          * with the midpoint recomputed on the rare rescan rather than held in a
          * buffer the caller would have to own.
          */
         price = (inHigh[today] + inLow[today]) / 2.0;
         if( highestIdx < trailingIdx ) {
            highestIdx = trailingIdx;
            tempHigh = inHigh[highestIdx];
            tempLow = inLow[highestIdx];
            highest = (tempHigh + tempLow) / 2.0;
            i = highestIdx;
            while( ++i <= today ) {
               tempHigh = inHigh[i];
               tempLow = inLow[i];
               tempReal = (tempHigh + tempLow) / 2.0;
               if( tempReal > highest ) {
                  highestIdx = i;
                  highest = tempReal;
               }
            }
         } else if( price >= highest ) {
            highestIdx = today;
            highest = price;
         }
         if( lowestIdx < trailingIdx ) {
            lowestIdx = trailingIdx;
            tempHigh = inHigh[lowestIdx];
            tempLow = inLow[lowestIdx];
            lowest = (tempHigh + tempLow) / 2.0;
            i = lowestIdx;
            while( ++i <= today ) {
               tempHigh = inHigh[i];
               tempLow = inLow[i];
               tempReal = (tempHigh + tempLow) / 2.0;
               if( tempReal < lowest ) {
                  lowestIdx = i;
                  lowest = tempReal;
               }
            }
         } else if( price <= lowest ) {
            lowestIdx = today;
            lowest = price;
         }
         /* A flat window answers the neutral position rather than dividing by
          * its own zero range. The band is the range against its own two
          * extremes, STOCH's test: a fixed constant answers "flat" for every
          * window of an instrument quoted below it (#253), and an exact test
          * divides a machine-flat window into noise (#107). At 0.5 the bar
          * contributes nothing and both recursions decay on their own
          * coefficients.
          */
         tempReal = highest - lowest;
         if( !(Math.Abs(tempReal) <= 0.00000000000001 * (Math.Abs(highest) + Math.Abs(lowest))) ) {
            ratio = (price - lowest) / tempReal;
         } else {
            ratio = 0.5;
         }
         /* The listing's .33*2*(r-.5) + .67*Value1[1]. */
         smoothed = Math.FusedMultiplyAdd(0.67, smoothed, 0.33 * 2.0 * (ratio - 0.5));
         /* The clamp is what keeps atanh finite, and the CLAMPED smoothed is what
          * the next bar's smoothing reads -- the listing assigns it back to
          * Value1 rather than holding it for the transform alone.
          */
         if( smoothed > 0.99 ) {
            smoothed = 0.999;
         }
         if( smoothed < -0.99 ) {
            smoothed = -0.999;
         }
         fish = Math.FusedMultiplyAdd(0.5, Math.Log((1.0 + smoothed) / (1.0 - smoothed)), 0.5 * prevFish);
         if( today >= startIdx ) {
            outFisher[outIdx * outStride] = fish;
            /* The author's second plot is Fish[1]: the previous bar's smoothed,
             * which at the first output bar is the zero seed when no unstable
             * period was discarded, and the computed smoothed of the bar before it
             * when one was.
             */
            outTrigger[outIdx * outStride] = prevFish;
            outIdx = outIdx + 1;
         }
         prevFish = fish;
         trailingIdx += 1;
         today += 1;
      }
      outNBElement = outIdx;
      outBegIdx = startIdx;
      /* Capture the live batch state into the handle. */
      int capX = today - trailingIdx + 1;
      if( capX < 1 || capX > historyLen ) {
         return RetCode.InternalError;
      }
      int physX = 1;
      while( physX < capX ) {
         physX <<= 1;
      }
      double[] capX_inHigh = new double[physX];
      double[] capX_inLow = new double[physX];
      for( int fillJ = historyLen - capX; fillJ < historyLen; fillJ++ ) {
         capX_inHigh[fillJ & (physX - 1)] = inHigh[fillJ];
         capX_inLow[fillJ & (physX - 1)] = inLow[fillJ];
      }
      sp.optInTimePeriod = optInTimePeriod;
      sp.highest = highest;
      sp.lowest = lowest;
      sp.smoothed = smoothed;
      sp.prevFish = prevFish;
      sp.trailingIdx = trailingIdx;
      sp.highestIdx = highestIdx;
      sp.lowestIdx = lowestIdx;
      sp.i = i;
      sp.today = today;
      sp.xMask = physX - 1;
      sp.x_inHigh = capX_inHigh;
      sp.x_inLow = capX_inLow;
      sp.cur_outFisher = outFisher[(outNBElement - 1) * outStride];
      sp.cur_outTrigger = outTrigger[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* FisherOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal FisherStream FisherOpenAndFillInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outFisher, Span<double> outTrigger )
   {
      FisherStream sp = new FisherStream(this);
      RetCode retCode = FisherOpenImpl(sp, inHigh, inLow, startIdx, optInTimePeriod, out outBegIdx, out outNBElement, outFisher, outTrigger, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("FISHER", "openAndFill", nameof(inHigh), inHigh.Length, startIdx, FisherLookback(optInTimePeriod));
      }
      throw StreamFailure("FISHER", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind FisherOpen (composition seam). */
   internal FisherStream FisherOpenInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int startIdx, int optInTimePeriod )
   {
      FisherStream sp = new FisherStream(this);
      double[] sink_outFisher = new double[1];
      double[] sink_outTrigger = new double[1];
      RetCode retCode = FisherOpenImpl(sp, inHigh, inLow, startIdx, optInTimePeriod, out int outBegIdx, out int outNBElement, sink_outFisher, sink_outTrigger, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("FISHER", "open", nameof(inHigh), inHigh.Length, startIdx, FisherLookback(optInTimePeriod));
      }
      throw StreamFailure("FISHER", "open", retCode);
   }

   /// <summary>Open a live <c>FISHER</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="FisherStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>FISHER</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>FisherLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>FisherOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="FisherLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>FisherLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public FisherStream FisherOpen( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int optInTimePeriod )
   {
      if( inHigh.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "FISHER open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "FISHER open: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TALibArgumentException("FISHER open: inLow is empty", nameof(inLow), RetCode.BadParam);
      RequireHistoryLength("FISHER", "open", "inLow", inLow.Length, inHigh.Length);
      return FisherOpenInternal(inHigh, inLow, 0, optInTimePeriod);
   }

   /// <summary><c>FisherOpen</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>FISHER</c> produces over
   /// the same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - FisherLookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="FisherStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="FisherLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outFisher">Fisher Transform value. Must hold at least <c>historyLen -
   /// FisherLookback(...)</c> values.</param>
   /// <param name="outTrigger">Fisher value of the previous bar. Must hold at least <c>historyLen -
   /// FisherLookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>FisherLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public FisherStream FisherOpenAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int optInTimePeriod, Span<double> outFisher, Span<double> outTrigger )
   {
      if( inHigh.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "FISHER openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "FISHER openAndFill: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TALibArgumentException("FISHER openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      int guardOutLen = OpenFillCount("FISHER", "openAndFill", inHigh.Length, FisherLookback(optInTimePeriod));
      RequireHistoryLength("FISHER", "openAndFill", "inLow", inLow.Length, inHigh.Length);
      RequireFillLength("FISHER", "openAndFill", "outFisher", outFisher.Length, guardOutLen);
      RequireFillLength("FISHER", "openAndFill", "outTrigger", outTrigger.Length, guardOutLen);
      if( SameBuffer(outFisher, inHigh) || SameBuffer(outFisher, inLow) || SameBuffer(outTrigger, inHigh) || SameBuffer(outTrigger, inLow) || SameBuffer(outFisher, outTrigger) ) {
         throw StreamFailure("FISHER", "openAndFill", RetCode.BadParam);
      }
      if( guardOutLen > 0 && ( outFisher.Overlaps(inHigh) || outFisher.Overlaps(inLow) || outTrigger.Overlaps(inHigh) || outTrigger.Overlaps(inLow) || OutputsAlias(outFisher, outTrigger) ) ) {
         throw StreamFailure("FISHER", "openAndFill", RetCode.BadParam);
      }
      return FisherOpenAndFillInternal(inHigh, inLow, 0, optInTimePeriod, out _, out _, outFisher, outTrigger);
   }
