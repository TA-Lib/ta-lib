      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.IndexMax"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public double Peek( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.NonFiniteBar("MCGD", "peek", nameof(inReal));
         McgdStream sp = this;
         double tempMD = 0.0;
         double tempReal = 0.0;
         double ratio = 0.0;
         double cur_outReal = 0.0;
         double prevMD = sp.prevMD;
         tempReal = inReal;
         ratio = tempReal / prevMD;
         tempMD = prevMD + (tempReal - prevMD) / (sp.period * (ratio * ratio * (ratio * ratio)));
         if( (double.IsFinite(tempMD)) ) {
            prevMD = tempMD;
         }
         cur_outReal = prevMD;
         return cur_outReal;
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public McgdStream Clone()
      {
         return new McgdStream(this);
      }
   }

   private void McgdStepImpl( McgdStream sp, double inReal )
   {
      double tempMD = 0.0;
      double tempReal = 0.0;
      double ratio = 0.0;
      tempReal = inReal;
      ratio = tempReal / sp.prevMD;
      tempMD = sp.prevMD + (tempReal - sp.prevMD) / (sp.period * (ratio * ratio * (ratio * ratio)));
      if( (double.IsFinite(tempMD)) ) {
         sp.prevMD = tempMD;
      }
      sp.cur_outReal = sp.prevMD;
   }

   private RetCode McgdOpenImpl( McgdStream sp, ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      int i = 0;
      int outIdx = 0;
      int today = 0;
      int lookbackTotal = 0;
      int nbMCGD = 0;
      double prevMD = 0;
      double tempMD = 0;
      double tempReal = 0;
      double ratio = 0;
      double period = 0;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > IndexMax + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 14;
      } else if( optInTimePeriod < 2 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      outBegIdx = 0;
      outNBElement = 0;
      lookbackTotal = McgdLookback(optInTimePeriod);
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      if( startIdx > endIdx ) {
         return RetCode.InsufficientHistory ;
      }
      period = (double)optInTimePeriod;
      /* Keep the denominator free of pow(): a transcendental would break the
       * four languages' bit-identity.
       *
       * A step whose value is not finite (a zero price, a zero line meeting a
       * zero price, or a price so small against the line that the step
       * overflows) holds the previous value, since every later bar reads it.
       */
      today = startIdx - lookbackTotal;
      prevMD = inReal[today];
      today += 1;
      i = lookbackTotal;
      while( i != 0 ) {
         tempReal = inReal[today];
         ratio = tempReal / prevMD;
         tempMD = prevMD + (tempReal - prevMD) / (period * (ratio * ratio * (ratio * ratio)));
         if( (double.IsFinite(tempMD)) ) {
            prevMD = tempMD;
         }
         today += 1;
         i -= 1;
      }
      outIdx = 1;
      outReal[0 * outStride] = prevMD;
      nbMCGD = endIdx - startIdx + 1;
      while( --nbMCGD != 0 ) {
         tempReal = inReal[today];
         ratio = tempReal / prevMD;
         tempMD = prevMD + (tempReal - prevMD) / (period * (ratio * ratio * (ratio * ratio)));
         if( (double.IsFinite(tempMD)) ) {
            prevMD = tempMD;
         }
         outReal[outIdx++ * outStride] = prevMD;
         today += 1;
      }
      outBegIdx = startIdx;
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      sp.optInTimePeriod = optInTimePeriod;
      sp.prevMD = prevMD;
      sp.period = period;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* McgdOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal McgdStream McgdOpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      McgdStream sp = new McgdStream(this);
      RetCode retCode = McgdOpenImpl(sp, inReal, startIdx, optInTimePeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("MCGD", "openAndFill", nameof(inReal), inReal.Length, startIdx, McgdLookback(optInTimePeriod));
      }
      throw StreamFailure("MCGD", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind McgdOpen (composition seam). */
   internal McgdStream McgdOpenInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod )
   {
      McgdStream sp = new McgdStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = McgdOpenImpl(sp, inReal, startIdx, optInTimePeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("MCGD", "open", nameof(inReal), inReal.Length, startIdx, McgdLookback(optInTimePeriod));
      }
      throw StreamFailure("MCGD", "open", retCode);
   }

   /// <summary>Open a live <c>MCGD</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="McgdStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>MCGD</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>McgdLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>McgdOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">Data on which to compute the average. The warm-up history, oldest bar
   /// first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="McgdLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>McgdLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public McgdStream McgdOpen( ReadOnlySpan<double> inReal, int optInTimePeriod )
   {
      if( inReal.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "MCGD open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "MCGD open: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      return McgdOpenInternal(inReal, 0, optInTimePeriod);
   }

   /// <summary><c>McgdOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>MCGD</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - McgdLookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="McgdStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">Data on which to compute the average. The warm-up history, oldest bar
   /// first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="McgdLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">McGinley Dynamic line. Must hold at least <c>historyLen -
   /// McgdLookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>McgdLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public McgdStream McgdOpenAndFill( ReadOnlySpan<double> inReal, int optInTimePeriod, Span<double> outReal )
   {
      if( inReal.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "MCGD openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "MCGD openAndFill: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      int guardOutLen = OpenFillCount("MCGD", "openAndFill", inReal.Length, McgdLookback(optInTimePeriod));
      RequireFillLength("MCGD", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( outReal.Overlaps(inReal) ) {
         throw StreamFailure("MCGD", "openAndFill", RetCode.BadParam);
      }
      return McgdOpenAndFillInternal(inReal, 0, optInTimePeriod, out _, out _, outReal);
   }
