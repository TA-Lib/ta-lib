      internal int cbSize_mfv;
      internal double[] cb_mfv_flow = [];
      internal double[] cb_mfv_volume = [];
      internal double cur_outReal;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal CmfStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Cmf</c> reports over the same bars: the opener sets it
      /// to <c>(lookback, historyLen - lookback)</c>, every <c>Update</c> adds one
      /// to the count — a non-finite bar is rejected but still counted, because the
      /// bar happened — <c>Peek</c> leaves it alone, and <c>Clone</c> carries it
      /// verbatim. A plain <c>Open</c> hands back only the last value, a subset of
      /// this range, because the caller chose not to take the fill.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      internal CmfStream( CmfStream other )
      {
         this.core = other.core;
         this.optInTimePeriod = other.optInTimePeriod;
         this.sumMFV = other.sumMFV;
         this.sumVol = other.sumVol;
         this.mfv_Idx = other.mfv_Idx;
         this.maxIdx_mfv = other.maxIdx_mfv;
         this.cbSize_mfv = other.cbSize_mfv;
         this.cb_mfv_flow = new double[other.cb_mfv_flow.Length];
         Array.Copy( other.cb_mfv_flow, this.cb_mfv_flow, other.cb_mfv_flow.Length );
         this.cb_mfv_volume = new double[other.cb_mfv_volume.Length];
         Array.Copy( other.cb_mfv_volume, this.cb_mfv_volume, other.cb_mfv_volume.Length );
         this.cur_outReal = other.cur_outReal;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Allocates nothing — neither handle state nor a return value.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so no state moves, <see cref="Value"/> still answers the previous value,
      /// and the stream stays usable — just carry on with the next bar.
      /// <see cref="OutRange"/> does advance: the bar happened, so it is counted,
      /// which keeps two handles fed the same series positionally aligned when only
      /// one of them rejects a bar. This is the one place the streaming tier is
      /// stricter than the batch API, which computes on whatever it is given: a
      /// handle retains its state, so a single non-finite bar would poison every
      /// later value it produces.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <param name="inVolume">This bar's volume.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inHigh, double inLow, double inClose, double inVolume )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) || !double.IsFinite(inVolume) )
         {
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
            throw Core.StreamFailure("CMF", "update", RetCode.BadParam);
         }
         core.CmfStepImpl(this, inHigh, inLow, inClose, inVolume);
         if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It copies nothing: the frame runs against this handle, reading its buffers
      /// and holding what the step would commit in locals. The cost does not grow
      /// with the period, and <c>Peek</c> never allocates.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <param name="inVolume">This bar's volume.</param>
      /// <returns>What <see cref="Update"/> would return for this bar.</returns>
      public double Peek( double inHigh, double inLow, double inClose, double inVolume )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) || !double.IsFinite(inVolume) ) throw Core.StreamFailure("CMF", "peek", RetCode.BadParam);
         CmfStream sp = this;
         double high = 0.0;
         double low = 0.0;
         double close = 0.0;
         double tmp = 0.0;
         double mfv = 0.0;
         double cur_outReal = 0.0;
         double sumMFV = sp.sumMFV;
         double sumVol = sp.sumVol;
         sumMFV -= sp.cb_mfv_flow[sp.mfv_Idx];
         sumVol -= sp.cb_mfv_volume[sp.mfv_Idx];
         high = inHigh;
         low = inLow;
         close = inClose;
         tmp = high - low;
         if( tmp > 0.0 ) {
            mfv = (close - low - (high - close)) / tmp * inVolume;
         } else {
            mfv = 0.0;
         }
         sumMFV += mfv;
         sumVol += inVolume;
         if( sumVol > 0.0 ) {
            cur_outReal = sumMFV / sumVol;
         } else {
            cur_outReal = 0.0;
         }
         return cur_outReal;
      }

      /// <summary>Commit <c>n</c> closed bars and write their <c>n</c> values, in one call.</summary>
      /// <remarks>
      /// <para>Exactly <c>n</c> back-to-back <see cref="Update"/> calls, with one set of
      /// argument checks instead of <c>n</c>. The outputs must hold at least
      /// <c>n</c> values and must not overlap an input or each other.</para>
      /// <para><see cref="OutRange"/> counts what this call took in, which is what makes
      /// a rejection readable: a non-finite bar <c>k</c> throws
      /// <see cref="System.ArgumentException"/> exactly as <see cref="Update"/>
      /// would, with the bars before <c>k</c> committed and written, bar <c>k</c>
      /// and everything after it not written, and the count advanced by <c>k +
      /// 1</c> — the committed bars plus the rejected one, so the last bar counted
      /// is the one that failed.</para>
      /// </remarks>
      /// <param name="inHigh">Closed bars for <c>inHigh</c>, oldest first.</param>
      /// <param name="inLow">Closed bars for <c>inLow</c>, oldest first.</param>
      /// <param name="inClose">Closed bars for <c>inClose</c>, oldest first.</param>
      /// <param name="inVolume">Closed bars for <c>inVolume</c>, oldest first.</param>
      /// <param name="outReal">Receives one <c>outReal</c> value per bar committed.</param>
      public void UpdateAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, ReadOnlySpan<double> inVolume, Span<double> outReal )
      {
         int barCount = inHigh.Length;
         if( inLow.Length != barCount || inClose.Length != barCount || inVolume.Length != barCount || outReal.Length < barCount || outReal.Overlaps(inHigh) || outReal.Overlaps(inLow) || outReal.Overlaps(inClose) || outReal.Overlaps(inVolume) ) throw Core.StreamFailure("CMF", "updateAndFill", RetCode.BadParam);
         for( int i = 0; i < barCount; i++ )
         {
            if( !double.IsFinite(inHigh[i]) || !double.IsFinite(inLow[i]) || !double.IsFinite(inClose[i]) || !double.IsFinite(inVolume[i]) )
            {
               if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
               throw Core.StreamFailure("CMF", "updateAndFill", RetCode.BadParam);
            }
            core.CmfStepImpl(this, inHigh[i], inLow[i], inClose[i], inVolume[i]);
            outReal[i] = cur_outReal;
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         }
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public CmfStream Clone()
      {
         return new CmfStream(this);
      }
   }

   internal void CmfStepImpl( CmfStream sp, double inHigh, double inLow, double inClose, double inVolume )
   {
      double high = 0.0;
      double low = 0.0;
      double close = 0.0;
      double tmp = 0.0;
      double mfv = 0.0;
      sp.sumMFV -= sp.cb_mfv_flow[sp.mfv_Idx];
      sp.sumVol -= sp.cb_mfv_volume[sp.mfv_Idx];
      high = inHigh;
      low = inLow;
      close = inClose;
      tmp = high - low;
      if( tmp > 0.0 ) {
         mfv = (close - low - (high - close)) / tmp * inVolume;
      } else {
         mfv = 0.0;
      }
      sp.cb_mfv_flow[sp.mfv_Idx] = mfv;
      sp.cb_mfv_volume[sp.mfv_Idx] = inVolume;
      sp.sumMFV += mfv;
      sp.sumVol += inVolume;
      if( sp.sumVol > 0.0 ) {
         sp.cur_outReal = sp.sumMFV / sp.sumVol;
      } else {
         sp.cur_outReal = 0.0;
      }
      sp.mfv_Idx = sp.mfv_Idx + 1;
      if( sp.mfv_Idx > sp.maxIdx_mfv ) {
         sp.mfv_Idx = 0;
      }
   }

   private RetCode CmfOpenImpl( CmfStream sp, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, ReadOnlySpan<double> inVolume, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double sumMFV = 0;
      double sumVol = 0;
      double high = 0;
      double low = 0;
      double close = 0;
      double tmp = 0;
      double mfv = 0;
      int lookbackTotal = 0;
      int outIdx = 0;
      int i = 0;
      int today = 0;
      double[] mfv_flow = [];
      double[] mfv_volume = [];
      int mfv_Idx = 0;
      int maxIdx_mfv = (50)-1;
      int historyLen = inHigh.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inLow.Length != inHigh.Length || inClose.Length != inHigh.Length || inVolume.Length != inHigh.Length ) {
         return RetCode.BadParam;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 20;
      } else if( optInTimePeriod < 2 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      /* Both the per-bar money flow volume and the volume that produced it are
       * carried in the circular buffer. Keeping the volume here rather than
       * re-reading inVolume[] at the trailing index is what makes outReal safe to
       * alias any input: once a bar has been consumed it is never read again.
       */
      /* Id, Type, Static Size */
      outBegIdx = 0;
      outNBElement = 0;
      /* Identify the minimum number of price bar needed
       * to calculate at least one output.
       */
      lookbackTotal = optInTimePeriod - 1;
      /* Move up the start index if there is not
       * enough initial data.
       */
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         return RetCode.InsufficientHistory ;
      }
      if( optInTimePeriod < 1 ) return RetCode.InternalError;
      mfv_flow = new double[optInTimePeriod];
      mfv_volume = new double[optInTimePeriod];
      maxIdx_mfv = (optInTimePeriod)-1;
      mfv_Idx = 0;
      outIdx = 0;
      /* Accumulate the money flow volume and the volume over the first
       * complete window, filling the circular buffer as we go.
       *
       * The per-bar multiplier is written exactly as in ta_AD.c so that the
       * Chaikin money flow volume has one definition in the library.
       */
      today = startIdx - lookbackTotal;
      sumMFV = 0.0;
      sumVol = 0.0;
      for( i = optInTimePeriod; i > 0; i -= 1 ) {
         high = inHigh[today];
         low = inLow[today];
         close = inClose[today];
         tmp = high - low;
         if( tmp > 0.0 ) {
            mfv = (close - low - (high - close)) / tmp * inVolume[today];
         } else {
            mfv = 0.0;
         }
         mfv_flow[mfv_Idx] = mfv;
         mfv_volume[mfv_Idx] = inVolume[today];
         sumMFV += mfv;
         sumVol += inVolume[today];
         today += 1;
         mfv_Idx++;
         if( mfv_Idx > maxIdx_mfv ) { mfv_Idx = 0; }
      }
      /* The first full window is complete: emit its output for startIdx here,
       * then slide the window over the remaining bars below.
       *
       * A window whose volume is entirely zero has no money flow to distribute;
       * report 0.0 rather than propagating a division by zero (issue #112).
       */
      if( sumVol > 0.0 ) {
         outReal[outIdx++ * outStride] = sumMFV / sumVol;
      } else {
         outReal[outIdx++ * outStride] = 0.0;
      }
      /* Now continue processing the remaining bars. */
      while( today <= endIdx ) {
         sumMFV -= mfv_flow[mfv_Idx];
         sumVol -= mfv_volume[mfv_Idx];
         high = inHigh[today];
         low = inLow[today];
         close = inClose[today];
         tmp = high - low;
         if( tmp > 0.0 ) {
            mfv = (close - low - (high - close)) / tmp * inVolume[today];
         } else {
            mfv = 0.0;
         }
         mfv_flow[mfv_Idx] = mfv;
         mfv_volume[mfv_Idx] = inVolume[today];
         sumMFV += mfv;
         sumVol += inVolume[today];
         today += 1;
         if( sumVol > 0.0 ) {
            outReal[outIdx++ * outStride] = sumMFV / sumVol;
         } else {
            outReal[outIdx++ * outStride] = 0.0;
         }
         mfv_Idx++;
         if( mfv_Idx > maxIdx_mfv ) { mfv_Idx = 0; }
      }
      outBegIdx = startIdx;
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      int capCb_mfv = maxIdx_mfv + 1;
      if( capCb_mfv > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      sp.optInTimePeriod = optInTimePeriod;
      sp.sumMFV = sumMFV;
      sp.sumVol = sumVol;
      sp.mfv_Idx = mfv_Idx;
      sp.maxIdx_mfv = maxIdx_mfv;
      sp.cbSize_mfv = capCb_mfv;
      sp.cb_mfv_flow = mfv_flow;
      sp.cb_mfv_volume = mfv_volume;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* CmfOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal CmfStream CmfOpenAndFillInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, ReadOnlySpan<double> inVolume, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      CmfStream sp = new CmfStream(this);
      RetCode retCode = CmfOpenImpl(sp, inHigh, inLow, inClose, inVolume, startIdx, optInTimePeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("CMF", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind CmfOpen (composition seam). */
   internal CmfStream CmfOpenInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, ReadOnlySpan<double> inVolume, int startIdx, int optInTimePeriod )
   {
      CmfStream sp = new CmfStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = CmfOpenImpl(sp, inHigh, inLow, inClose, inVolume, startIdx, optInTimePeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("CMF", "open", retCode);
   }

   /// <summary>Open a live <c>CMF</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="CmfStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>CMF</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>CMF_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>CmfOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inVolume">Volume of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="CMF_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>CMF_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public CmfStream CmfOpen( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, ReadOnlySpan<double> inVolume, int optInTimePeriod )
   {
      if( inHigh.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "CMF open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "CMF open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("CMF open: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TaLibArgumentException("CMF open: inClose is empty", nameof(inClose), RetCode.BadParam);
      if( inVolume.IsEmpty ) throw new TaLibArgumentException("CMF open: inVolume is empty", nameof(inVolume), RetCode.BadParam);
      RequireHistoryLength("CMF", "open", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("CMF", "open", "inClose", inClose.Length, inHigh.Length);
      RequireHistoryLength("CMF", "open", "inVolume", inVolume.Length, inHigh.Length);
      return CmfOpenInternal(inHigh, inLow, inClose, inVolume, 0, optInTimePeriod);
   }

   /// <summary><c>CmfOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>CMF</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - CMF_Lookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="CmfStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inVolume">Volume of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="CMF_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Chaikin money flow, in the range -1 to +1. Must hold at least
   /// <c>historyLen - CMF_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>CMF_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public CmfStream CmfOpenAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, ReadOnlySpan<double> inVolume, int optInTimePeriod, Span<double> outReal )
   {
      if( inHigh.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "CMF openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "CMF openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("CMF openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TaLibArgumentException("CMF openAndFill: inClose is empty", nameof(inClose), RetCode.BadParam);
      if( inVolume.IsEmpty ) throw new TaLibArgumentException("CMF openAndFill: inVolume is empty", nameof(inVolume), RetCode.BadParam);
      int guardOutLen = OpenFillCount("CMF", "openAndFill", inHigh.Length, CMF_Lookback(optInTimePeriod));
      RequireHistoryLength("CMF", "openAndFill", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("CMF", "openAndFill", "inClose", inClose.Length, inHigh.Length);
      RequireHistoryLength("CMF", "openAndFill", "inVolume", inVolume.Length, inHigh.Length);
      RequireFillLength("CMF", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( outReal.Overlaps(inHigh) || outReal.Overlaps(inLow) || outReal.Overlaps(inClose) || outReal.Overlaps(inVolume) ) {
         throw StreamFailure("CMF", "openAndFill", RetCode.BadParam);
      }
      return CmfOpenAndFillInternal(inHigh, inLow, inClose, inVolume, 0, optInTimePeriod, out _, out _, outReal);
   }
