   /// <summary>A live <c>PERCENTB</c> stream: one value per closed bar, bit-identical to
   /// <c>PERCENTB</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.PercentbOpen"/>. There is no close and nothing
   /// to dispose — the handle is ordinary managed state, and an unreferenced
   /// handle is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class PercentbStream
   {
      internal Core core;
      internal int optInTimePeriod;
      internal double optInNbDevUp;
      internal double optInNbDevDn;
      internal MAType optInMAType;
      internal double cur_outReal;
      internal MaStream sub0 = null!;
      internal VarStream sub1 = null!;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal PercentbStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Percentb</c> reports over the same bars: the opener
      /// sets it to <c>(lookback, historyLen - lookback)</c>, every accepted
      /// <c>Update</c> adds one to the count — a rejected one changes nothing, and
      /// neither does <c>Peek</c> — and <c>Clone</c> carries it verbatim. A plain
      /// <c>Open</c> hands back only the last value, a subset of this range,
      /// because the caller chose not to take the fill.</para>
      /// <para>The last bar it can reach is <see cref="Core.IndexMax"/>; past that
      /// <c>Update</c> and <c>Advance</c> throw.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      /// <summary>Count one bar this stream was not fed: <see cref="OutRange"/> advances by
      /// one and nothing else moves.</summary>
      /// <remarks>
      /// <para><see cref="Value"/> keeps answering the previous output, which is this
      /// bar's output too. For a bar the caller leaves out: one an <c>Update</c>
      /// rejected and that will not be re-fed, or a session with no print. Without
      /// it two handles on one feed drift a bar apart when only one of them skips.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, the last one the batch tier
      /// can address and the last this handle will count. <c>Update</c> throws the
      /// same there.</para>
      /// </remarks>
      public void Advance()
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("PERCENTB", "advance", RetCode.OutOfRangeEndIndex);
         outRangeCount++;
      }

      internal PercentbStream( PercentbStream other )
      {
         this.core = other.core;
         this.optInTimePeriod = other.optInTimePeriod;
         this.optInNbDevUp = other.optInNbDevUp;
         this.optInNbDevDn = other.optInNbDevDn;
         this.optInMAType = other.optInMAType;
         this.cur_outReal = other.cur_outReal;
         this.sub0 = new MaStream(other.sub0);
         this.sub1 = new VarStream(other.sub1);
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Allocates nothing — neither handle state nor a return value.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so nothing moves — <see cref="OutRange"/> included — and
      /// <see cref="Value"/> still answers the previous value. Re-feed the bar when
      /// a corrected value arrives, or call <see cref="Advance"/> to count it and
      /// carry on; two handles on one feed drift a bar apart if neither happens.
      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, which no re-feed clears: the
      /// handle has run out of index domain and only a shorter history can start a
      /// new one.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inReal )
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("PERCENTB", "update", RetCode.OutOfRangeEndIndex);
         if( !double.IsFinite(inReal) ) throw Core.NonFiniteBar("PERCENTB", "update", nameof(inReal));
         core.PercentbStepImpl(this, inReal);
         outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.IndexMax"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public double Peek( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.NonFiniteBar("PERCENTB", "peek", nameof(inReal));
         PercentbStream sp = this;
         double den = 0.0;
         double deviation = 0.0;
         double lower = 0.0;
         double middle = 0.0;
         double tempReal = 0.0;
         double upper = 0.0;
         double cur_tempX = 0.0;
         double cur_tempMA = 0.0;
         double cur_outReal = 0.0;
         cur_tempX = inReal;
         /* Pipeline the new bar through the sub-streams (batch tail order). */
         cur_tempMA = sp.sub0.Peek(inReal);
         cur_outReal = sp.sub1.Peek(inReal);
         /* Combine map (batch tail, per bar). */
         if( sp.optInNbDevUp == sp.optInNbDevDn ) {
            middle = cur_tempMA;
            tempReal = Math.Sqrt(cur_outReal) * sp.optInNbDevUp;
            upper = middle + tempReal;
            lower = middle - tempReal;
            den = upper - lower;
            cur_outReal = (cur_tempX - lower) / den;
            if( den == 0.0 ) {
               cur_outReal = 0.5;
            }
         } else {
            middle = cur_tempMA;
            deviation = Math.Sqrt(cur_outReal);
            upper = Math.FusedMultiplyAdd(deviation, sp.optInNbDevUp, middle);
            lower = middle - deviation * sp.optInNbDevDn;
            den = upper - lower;
            cur_outReal = (cur_tempX - lower) / den;
            if( den == 0.0 ) {
               cur_outReal = 0.5;
            }
         }
         return cur_outReal;
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public PercentbStream Clone()
      {
         return new PercentbStream(this);
      }
   }

   private void PercentbStepImpl( PercentbStream sp, double inReal )
   {
      double den = 0.0;
      double deviation = 0.0;
      double lower = 0.0;
      double middle = 0.0;
      double tempReal = 0.0;
      double upper = 0.0;
      double cur_tempX = 0.0;
      double cur_tempMA = 0.0;
      double cur_outReal = 0.0;
      cur_tempX = inReal;
      /* Pipeline the new bar through the sub-streams (batch tail order). */
      cur_tempMA = sp.sub0.Update(inReal);
      cur_outReal = sp.sub1.Update(inReal);
      /* Combine map (batch tail, per bar). */
      if( sp.optInNbDevUp == sp.optInNbDevDn ) {
         middle = cur_tempMA;
         tempReal = Math.Sqrt(cur_outReal) * sp.optInNbDevUp;
         upper = middle + tempReal;
         lower = middle - tempReal;
         den = upper - lower;
         cur_outReal = (cur_tempX - lower) / den;
         if( den == 0.0 ) {
            cur_outReal = 0.5;
         }
      } else {
         middle = cur_tempMA;
         deviation = Math.Sqrt(cur_outReal);
         upper = Math.FusedMultiplyAdd(deviation, sp.optInNbDevUp, middle);
         lower = middle - deviation * sp.optInNbDevDn;
         den = upper - lower;
         cur_outReal = (cur_tempX - lower) / den;
         if( den == 0.0 ) {
            cur_outReal = 0.5;
         }
      }
      sp.cur_outReal = cur_outReal;
   }

   private RetCode PercentbOpenImpl( PercentbStream sp, ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, double optInNbDevUp, double optInNbDevDn, MAType optInMAType, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      RetCode retCode;
      int i = 0;
      int lookbackTotal = 0;
      int firstIdx = 0;
      int today = 0;
      int outIdx = 0;
      int maBegIdx = 0;
      int maNbElement = 0;
      int offset = 0;
      double middle = 0;
      double deviation = 0;
      double tempReal = 0;
      double upper = 0;
      double lower = 0;
      double den = 0;
      Span<double> tempMA;
      Span<double> tempX;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > IndexMax + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 20;
      } else if( optInTimePeriod < 2 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInNbDevUp == RealDefault ) {
         optInNbDevUp = 2e0;
      } else if( !(optInNbDevUp >= RealMin && optInNbDevUp <= RealMax) ) {
         return RetCode.BadParam;
      }
      if( optInNbDevDn == RealDefault ) {
         optInNbDevDn = 2e0;
      } else if( !(optInNbDevDn >= RealMin && optInNbDevDn <= RealMax) ) {
         return RetCode.BadParam;
      }
      if( (int)optInMAType == int.MinValue || optInMAType == MAType.DEFAULT ) {
         optInMAType = MAType.SMA;
      } else if( (int)optInMAType < MATypes.Min || (int)optInMAType > MATypes.Max ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      if( historyLen < PercentbLookback(optInTimePeriod, optInNbDevUp, optInNbDevDn, optInMAType) + 1 ) {
         return RetCode.InsufficientHistory;
      }
      Span<double> sc_outReal = outStride == 1 ? outReal : new double[historyLen];
      lookbackTotal = PercentbLookback(optInTimePeriod, optInNbDevUp, optInNbDevDn, optInMAType);
      firstIdx = startIdx;
      if( firstIdx < lookbackTotal ) {
         firstIdx = lookbackTotal;
      }
      if( firstIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      tempX = new double[(int)((endIdx - firstIdx + 1) * 1)];
      tempMA = new double[(int)((endIdx - startIdx + 1) * 1)];
      outIdx = 0;
      today = firstIdx;
      while( today <= endIdx ) {
         tempX[outIdx++] = inReal[today];
         today += 1;
      }
      /* Sub-stream 0: ma over `inReal`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      MaStream sub0 = MaOpenAndFillInternal(inReal, startIdx, optInTimePeriod, optInMAType, out maBegIdx, out maNbElement, tempMA);
      retCode = RetCode.Success;
      /* Sub-stream 1: var over `inReal`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      VarStream sub1 = VarOpenAndFillInternal(inReal, maBegIdx, optInTimePeriod, 1.0, out outBegIdx, out outNBElement, sc_outReal);
      retCode = RetCode.Success;
      offset = maNbElement - outNBElement;
      if( optInNbDevUp == optInNbDevDn ) {
         for( i = 0; i < (int)outNBElement; i += 1 ) {
            middle = tempMA[i + offset];
            tempReal = Math.Sqrt(sc_outReal[i]) * optInNbDevUp;
            upper = middle + tempReal;
            lower = middle - tempReal;
            den = upper - lower;
            sc_outReal[i] = (tempX[i] - lower) / den;
            if( den == 0.0 ) {
               sc_outReal[i] = 0.5;
            }
         }
      } else {
         for( i = 0; i < (int)outNBElement; i += 1 ) {
            middle = tempMA[i + offset];
            deviation = Math.Sqrt(sc_outReal[i]);
            upper = Math.FusedMultiplyAdd(deviation, optInNbDevUp, middle);
            lower = middle - deviation * optInNbDevDn;
            den = upper - lower;
            sc_outReal[i] = (tempX[i] - lower) / den;
            if( den == 0.0 ) {
               sc_outReal[i] = 0.5;
            }
         }
      }
      /* Capture the live producer state + sub handles. */
      if( outNBElement < 1 ) {
         return RetCode.InsufficientHistory;
      }
      /* Capture the live batch state into the handle. */
      sp.optInTimePeriod = optInTimePeriod;
      sp.optInNbDevUp = optInNbDevUp;
      sp.optInNbDevDn = optInNbDevDn;
      sp.optInMAType = optInMAType;
      sp.sub0 = sub0;
      sp.sub1 = sub1;
      sp.cur_outReal = sc_outReal[outNBElement - 1];
      return RetCode.Success;
   }

   /* PercentbOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal PercentbStream PercentbOpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, double optInNbDevUp, double optInNbDevDn, MAType optInMAType, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      PercentbStream sp = new PercentbStream(this);
      RetCode retCode = PercentbOpenImpl(sp, inReal, startIdx, optInTimePeriod, optInNbDevUp, optInNbDevDn, optInMAType, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("PERCENTB", "openAndFill", nameof(inReal), inReal.Length, startIdx, PercentbLookback(optInTimePeriod, optInNbDevUp, optInNbDevDn, optInMAType));
      }
      throw StreamFailure("PERCENTB", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind PercentbOpen (composition seam). */
   internal PercentbStream PercentbOpenInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, double optInNbDevUp, double optInNbDevDn, MAType optInMAType )
   {
      PercentbStream sp = new PercentbStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = PercentbOpenImpl(sp, inReal, startIdx, optInTimePeriod, optInNbDevUp, optInNbDevDn, optInMAType, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("PERCENTB", "open", nameof(inReal), inReal.Length, startIdx, PercentbLookback(optInTimePeriod, optInNbDevUp, optInNbDevDn, optInMAType));
      }
      throw StreamFailure("PERCENTB", "open", retCode);
   }

   /// <summary>Open a live <c>PERCENTB</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="PercentbStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>PERCENTB</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>PercentbLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>PercentbOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">Input data series. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="PercentbLookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInNbDevUp">As in the batch call; see <see cref="PercentbLookback"/> for its default
   /// and range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <param name="optInNbDevDn">As in the batch call; see <see cref="PercentbLookback"/> for its default
   /// and range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <param name="optInMAType">As in the batch call; see <see cref="PercentbLookback"/> for its default
   /// and range (<c>MAType.DEFAULT</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>PercentbLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules S1 and S2).</exception>
   public PercentbStream PercentbOpen( ReadOnlySpan<double> inReal, int optInTimePeriod, double optInNbDevUp, double optInNbDevDn, MAType optInMAType )
   {
      if( inReal.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "PERCENTB open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "PERCENTB open: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      return PercentbOpenInternal(inReal, 0, optInTimePeriod, optInNbDevUp, optInNbDevDn, optInMAType);
   }

   /// <summary><c>PercentbOpen</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>PERCENTB</c> produces over
   /// the same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - PercentbLookback(...)</c> values
   /// and must not alias the inputs or each other — this path writes the outputs
   /// and then reads the input tail to seed its rings, so the batch tier's
   /// in-place allowance does not carry over here. Both are checked before
   /// anything is written, so an undersized span is an <c>ArgumentException</c>
   /// naming it rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="PercentbStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">Input data series. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="PercentbLookback"/> for its default
   /// and range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInNbDevUp">As in the batch call; see <see cref="PercentbLookback"/> for its default
   /// and range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <param name="optInNbDevDn">As in the batch call; see <see cref="PercentbLookback"/> for its default
   /// and range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <param name="optInMAType">As in the batch call; see <see cref="PercentbLookback"/> for its default
   /// and range (<c>MAType.DEFAULT</c> selects the default).</param>
   /// <param name="outReal">Position of the input between the lower band (0) and the upper band (1)
   /// Must hold at least <c>historyLen - PercentbLookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>PercentbLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules S1 and S2).</exception>
   public PercentbStream PercentbOpenAndFill( ReadOnlySpan<double> inReal, int optInTimePeriod, double optInNbDevUp, double optInNbDevDn, MAType optInMAType, Span<double> outReal )
   {
      if( inReal.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "PERCENTB openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "PERCENTB openAndFill: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      int guardOutLen = OpenFillCount("PERCENTB", "openAndFill", inReal.Length, PercentbLookback(optInTimePeriod, optInNbDevUp, optInNbDevDn, optInMAType));
      RequireFillLength("PERCENTB", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( outReal.Overlaps(inReal) ) {
         throw StreamFailure("PERCENTB", "openAndFill", RetCode.BadParam);
      }
      return PercentbOpenAndFillInternal(inReal, 0, optInTimePeriod, optInNbDevUp, optInNbDevDn, optInMAType, out _, out _, outReal);
   }
