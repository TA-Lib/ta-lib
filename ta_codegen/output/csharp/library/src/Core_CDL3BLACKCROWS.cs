   /// <summary>Open a live <c>CDL3BLACKCROWS</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="Cdl3blackcrowsStream.Value"/> starts at the last
   /// history bar's value — bit-identical to what <c>CDL3BLACKCROWS</c> reports
   /// for that bar.</para>
   /// <para>The history must hold at least <c>CDL3BLACKCROWS_Lookback(...) + 1</c>
   /// bars (unstable-period aware). Nothing is written to any caller array; use
   /// <c>Cdl3blackcrowsOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inOpen">Open price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>CDL3BLACKCROWS_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public Cdl3blackcrowsStream Cdl3blackcrowsOpen( ReadOnlySpan<double> inOpen, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose )
   {
      if( inOpen.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inOpen), "CDL3BLACKCROWS open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inOpen.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inOpen), "CDL3BLACKCROWS open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inHigh.IsEmpty ) throw new TaLibArgumentException("CDL3BLACKCROWS open: inHigh is empty", nameof(inHigh), RetCode.BadParam);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("CDL3BLACKCROWS open: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TaLibArgumentException("CDL3BLACKCROWS open: inClose is empty", nameof(inClose), RetCode.BadParam);
      RequireHistoryLength("CDL3BLACKCROWS", "open", "inHigh", inHigh.Length, inOpen.Length);
      RequireHistoryLength("CDL3BLACKCROWS", "open", "inLow", inLow.Length, inOpen.Length);
      RequireHistoryLength("CDL3BLACKCROWS", "open", "inClose", inClose.Length, inOpen.Length);
      return Cdl3blackcrowsOpenInternal(inOpen, inHigh, inLow, inClose, 0);
   }

   /// <summary><c>Cdl3blackcrowsOpen</c> that also fills the output array(s) over the
   /// whole history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>CDL3BLACKCROWS</c>
   /// produces over the same series, so no separate batch call is needed for the
   /// warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - CDL3BLACKCROWS_Lookback(...)</c>
   /// values and must not alias the inputs or each other — this path writes the
   /// outputs and then reads the input tail to seed its rings, so the batch
   /// tier's in-place allowance does not carry over here. Both are checked
   /// before anything is written, so an undersized span is an
   /// <c>ArgumentException</c> naming it rather than a fault from inside the
   /// fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="Cdl3blackcrowsStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inOpen">Open price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="outInteger">-100 when the bearish pattern is detected, 0 otherwise. Never emits +100.
   /// Must hold at least <c>historyLen - CDL3BLACKCROWS_Lookback(...)</c>
   /// values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>CDL3BLACKCROWS_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public Cdl3blackcrowsStream Cdl3blackcrowsOpenAndFill( ReadOnlySpan<double> inOpen, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, Span<int> outInteger )
   {
      if( inOpen.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inOpen), "CDL3BLACKCROWS openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inOpen.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inOpen), "CDL3BLACKCROWS openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inHigh.IsEmpty ) throw new TaLibArgumentException("CDL3BLACKCROWS openAndFill: inHigh is empty", nameof(inHigh), RetCode.BadParam);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("CDL3BLACKCROWS openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TaLibArgumentException("CDL3BLACKCROWS openAndFill: inClose is empty", nameof(inClose), RetCode.BadParam);
      int guardOutLen = OpenFillCount("CDL3BLACKCROWS", "openAndFill", inOpen.Length, CDL3BLACKCROWS_Lookback());
      RequireHistoryLength("CDL3BLACKCROWS", "openAndFill", "inHigh", inHigh.Length, inOpen.Length);
      RequireHistoryLength("CDL3BLACKCROWS", "openAndFill", "inLow", inLow.Length, inOpen.Length);
      RequireHistoryLength("CDL3BLACKCROWS", "openAndFill", "inClose", inClose.Length, inOpen.Length);
      RequireFillLength("CDL3BLACKCROWS", "openAndFill", "outInteger", outInteger.Length, guardOutLen);
      return Cdl3blackcrowsOpenAndFillInternal(inOpen, inHigh, inLow, inClose, 0, out _, out _, outInteger);
   }
