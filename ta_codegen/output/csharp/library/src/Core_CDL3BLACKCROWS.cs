      RetCode retCode = CDL3BLACKCROWS_Impl(startIdx, endIdx, inOpen, inHigh, inLow, inClose, out int outBegIdx, out int outNBElement, outInteger);
      if( retCode != RetCode.Success ) {
         throw Failure("CDL3BLACKCROWS", retCode);
      }
      return new OutRange(outBegIdx, outNBElement);
   }
   /// <summary>
   /// A four-bar pattern: a white candle followed by three consecutive black
   /// (down) candles with successively lower closes, each opening inside the
   /// prior black's real body. It is a bearish reversal signal. A hit (-100)
   /// signals a bearish reversal.
   /// </summary>
   /// <remarks>
   /// <list type="bullet">
   /// <item><description>Does not verify the prior mature uptrend the pattern classically assumes for significance.</description></item>
   /// </list>
   /// <para>
   /// This is the <c>float[]</c> overload: input elements are widened to
   /// <c>double</c> as they are read and all arithmetic is performed in
   /// <c>double</c>, so a result beyond <c>float</c> range is still
   /// representable.
   /// </para>
   /// <para>
   /// Values are written only where the indicator is defined. The returned
   /// <see cref="OutRange"/> says where they start and how many there are;
   /// nothing outside that range is touched, and the library never pads with
   /// NaN. A valid range shorter than <c>CDL3BLACKCROWS_Lookback</c> is a
   /// <b>success with no values</b> (<c>Count == 0</c>), not an error.
   /// </para>
   /// </remarks>
   /// <param name="startIdx">First bar of the requested range (inclusive).</param>
   /// <param name="endIdx">Last bar of the requested range (inclusive).</param>
   /// <param name="inOpen">Open price of each bar.</param>
   /// <param name="inHigh">High price of each bar.</param>
   /// <param name="inLow">Low price of each bar.</param>
   /// <param name="inClose">Close price of each bar.</param>
   /// <param name="outInteger">-100 when the bearish pattern is detected, 0 otherwise. Never emits +100.
   /// Must hold at least <c>endIdx - startIdx + 1</c> values.</param>
   /// <returns>The range written: <c>BegIdx</c> is the first bar with a value,
   /// <c>Count</c> how many were written.</returns>
   /// <exception cref="System.ArgumentOutOfRangeException"><c>startIdx</c> or <c>endIdx</c> is negative or above
   /// <see cref="Core.MAX_INDEX"/>, or <c>endIdx &lt; startIdx</c>.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or two outputs
   /// share one array.</exception>
   /// <exception cref="System.ArgumentException">A span is too short for the range requested: any input this function
   /// <i>declares</i> that does not reach <c>endIdx</c>, or an output that
   /// cannot hold the values produced. Checked before anything is written, so a
   /// rejected call leaves every buffer untouched. Declared, not read: a few
   /// candlestick patterns take an OHLC series they never index, and it is
   /// required all the same. An empty span — which is what a null array becomes,
   /// since a span cannot be null — is rejected on the same terms and no others:
   /// it is too short whenever the range produces a value, and fine when it
   /// produces none, and on an output this function documents as declinable it
   /// is how you decline.</exception>
   /// <exception cref="System.ArgumentException">Two output buffers overlap, or an output partially overlaps an input.
   /// Computing wholly in place (an output that IS an input) is allowed.</exception>
   public OutRange CDL3BLACKCROWS( int startIdx,
                                   int endIdx,
                                   ReadOnlySpan<float> inOpen,
                                   ReadOnlySpan<float> inHigh,
                                   ReadOnlySpan<float> inLow,
                                   ReadOnlySpan<float> inClose,
                                   Span<int> outInteger )
   {
      int guardStart = ClampedStart(startIdx, endIdx, CDL3BLACKCROWS_Lookback());
      int guardInLen = guardStart < 0 ? 0 : endIdx + 1;
      int guardOutLen = guardStart < 0 || guardStart > endIdx ? 0 : endIdx - guardStart + 1;
      RequireLength("CDL3BLACKCROWS", "inOpen", inOpen.Length, guardInLen);
      RequireLength("CDL3BLACKCROWS", "inHigh", inHigh.Length, guardInLen);
      RequireLength("CDL3BLACKCROWS", "inLow", inLow.Length, guardInLen);
      RequireLength("CDL3BLACKCROWS", "inClose", inClose.Length, guardInLen);
      RequireLength("CDL3BLACKCROWS", "outInteger", outInteger.Length, guardOutLen);
      RetCode retCode = CDL3BLACKCROWS_Impl(startIdx, endIdx, inOpen, inHigh, inLow, inClose, out int outBegIdx, out int outNBElement, outInteger);
      if( retCode != RetCode.Success ) {
         throw Failure("CDL3BLACKCROWS", retCode);
      }
      return new OutRange(outBegIdx, outNBElement);
   }
