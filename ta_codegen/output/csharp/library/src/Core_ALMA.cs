   /// <summary>A live <c>ALMA</c> stream: one value per closed bar, bit-identical to
   /// <c>ALMA</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.AlmaOpen"/>. There is no close and nothing to
   /// dispose — the handle is ordinary managed state, and an unreferenced handle
   /// is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class AlmaStream
   {
      internal Core core;
      internal int optInTimePeriod;
      internal double optInSigma;
      internal double optInOffset;
      internal int lookbackTotal;
      internal int weights_Idx;
      internal int maxIdx_weights;
      internal int winPos_j;
      internal int winCap_j;
      internal double[] win_j_inReal = [];
      internal int cbSize_weights;
      internal double[] cb_weights = [];
      internal double cur_outReal;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal AlmaStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Alma</c> reports over the same bars: the opener sets it
      /// to <c>(lookback, historyLen - lookback)</c>, every accepted <c>Update</c>
      /// adds one to the count — a rejected one changes nothing, and neither does
      /// <c>Peek</c> — and <c>Clone</c> carries it verbatim. A plain <c>Open</c>
      /// hands back only the last value, a subset of this range, because the caller
      /// chose not to take the fill.</para>
      /// <para>The last bar it can reach is <see cref="Core.IndexMax"/>; past that
      /// <c>Update</c> and <c>Advance</c> throw.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      /// <summary>Count one bar this stream was not fed: <see cref="OutRange"/> advances by
      /// one and nothing else moves.</summary>
      /// <remarks>
      /// <para><see cref="Value"/> keeps answering the previous output, which is this
      /// bar's output too. For a bar the caller leaves out: one an <c>Update</c>
      /// rejected and that will not be re-fed, or a session with no print. Without
      /// it two handles on one feed drift a bar apart when only one of them skips.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, the last one the batch tier
      /// can address and the last this handle will count. <c>Update</c> throws the
      /// same there.</para>
      /// </remarks>
      public void Advance()
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("ALMA", "advance", RetCode.OutOfRangeEndIndex);
         outRangeCount++;
      }

      internal AlmaStream( AlmaStream other )
      {
         this.core = other.core;
         this.optInTimePeriod = other.optInTimePeriod;
         this.optInSigma = other.optInSigma;
         this.optInOffset = other.optInOffset;
         this.lookbackTotal = other.lookbackTotal;
         this.weights_Idx = other.weights_Idx;
         this.maxIdx_weights = other.maxIdx_weights;
         this.winPos_j = other.winPos_j;
         this.winCap_j = other.winCap_j;
         this.win_j_inReal = new double[other.win_j_inReal.Length];
         Array.Copy( other.win_j_inReal, this.win_j_inReal, other.win_j_inReal.Length );
         this.cbSize_weights = other.cbSize_weights;
         this.cb_weights = new double[other.cb_weights.Length];
         Array.Copy( other.cb_weights, this.cb_weights, other.cb_weights.Length );
         this.cur_outReal = other.cur_outReal;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so nothing moves — <see cref="OutRange"/> included — and
      /// <see cref="Value"/> still answers the previous value. Re-feed the bar when
      /// a corrected value arrives, or call <see cref="Advance"/> to count it and
      /// carry on; two handles on one feed drift a bar apart if neither happens.
      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, which no re-feed clears: the
      /// handle has run out of index domain and only a shorter history can start a
      /// new one.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inReal )
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("ALMA", "update", RetCode.OutOfRangeEndIndex);
         if( !double.IsFinite(inReal) ) throw Core.NonFiniteBar("ALMA", "update", nameof(inReal));
         core.AlmaStepImpl(this, inReal);
         outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.IndexMax"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public double Peek( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.NonFiniteBar("ALMA", "peek", nameof(inReal));
         AlmaStream sp = this;
         double sum = 0.0;
         int j = 0;
         int w = 0;
         double cur_outReal = 0.0;
         int pkSlot0 = -1;
         double pkVal0 = 0.0;
         if( sp.optInTimePeriod == 1 ) {
            cur_outReal = inReal;
            return cur_outReal ;
         }
         pkSlot0 = sp.winPos_j;
         pkVal0 = inReal;
         sum = 0.0;
         w = 0;
         for( j = sp.lookbackTotal; j >= 0; j -= 1 ) {
            sum += sp.cb_weights[w] * ((((sp.winPos_j + sp.winCap_j - j >= sp.winCap_j) ? sp.winPos_j + sp.winCap_j - j - sp.winCap_j : sp.winPos_j + sp.winCap_j - j) != pkSlot0) ? sp.win_j_inReal[(sp.winPos_j + sp.winCap_j - j >= sp.winCap_j) ? sp.winPos_j + sp.winCap_j - j - sp.winCap_j : sp.winPos_j + sp.winCap_j - j] : pkVal0);
            w += 1;
         }
         cur_outReal = sum;
         return cur_outReal;
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public AlmaStream Clone()
      {
         return new AlmaStream(this);
      }
   }

   private void AlmaStepImpl( AlmaStream sp, double inReal )
   {
      double sum = 0.0;
      int j = 0;
      int w = 0;
      if( sp.optInTimePeriod == 1 ) {
         sp.cur_outReal = inReal;
         return ;
      }
      sp.win_j_inReal[sp.winPos_j] = inReal;
      sum = 0.0;
      w = 0;
      for( j = sp.lookbackTotal; j >= 0; j -= 1 ) {
         sum += sp.cb_weights[w] * sp.win_j_inReal[(sp.winPos_j + sp.winCap_j - j >= sp.winCap_j) ? sp.winPos_j + sp.winCap_j - j - sp.winCap_j : sp.winPos_j + sp.winCap_j - j];
         w += 1;
      }
      sp.cur_outReal = sum;
      sp.winPos_j = sp.winPos_j + 1;
      if( sp.winPos_j >= sp.winCap_j ) {
         sp.winPos_j = 0;
      }
   }

   private RetCode AlmaOpenImpl( AlmaStream sp, ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, double optInSigma, double optInOffset, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double sum = 0;
      double s = 0;
      double twoSSq = 0;
      double d = 0;
      double norm = 0;
      int lookbackTotal = 0;
      int outIdx = 0;
      int i = 0;
      int j = 0;
      int w = 0;
      int m = 0;
      double[] weights = [];
      int weights_Idx = 0;
      int maxIdx_weights = (30)-1;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > IndexMax + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 9;
      } else if( optInTimePeriod < 1 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInSigma == RealDefault ) {
         optInSigma = 6e0;
      } else if( !(optInSigma >= 1e-2 && optInSigma <= RealMax) ) {
         return RetCode.BadParam;
      }
      if( optInOffset == RealDefault ) {
         optInOffset = 8.5e-1;
      } else if( !(optInOffset >= 0e0 && optInOffset <= 1e0) ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      if( optInTimePeriod == 1 ) {
         int fillLb = AlmaLookback(optInTimePeriod, optInSigma, optInOffset);
         if( startIdx > fillLb ) fillLb = startIdx;
         if( historyLen < fillLb + 1 ) {
            return RetCode.InsufficientHistory;
         }
         sp.optInTimePeriod = optInTimePeriod;
         sp.optInSigma = optInSigma;
         sp.optInOffset = optInOffset;
         sp.lookbackTotal = 0;
         sp.weights_Idx = 0;
         sp.maxIdx_weights = 0;
         sp.winPos_j = 0;
         sp.winCap_j = 1;
         sp.win_j_inReal = new double[1];
         sp.cbSize_weights = 0;
         sp.cb_weights = new double[1];
         outBegIdx = fillLb;
         outNBElement = historyLen - fillLb;
         if( outStride == 0 ) {
            outReal[0] = inReal[historyLen - 1];
         } else {
            for( int fillIdx = 0; fillIdx < historyLen - fillLb; fillIdx++ ) {
               outReal[fillIdx] = inReal[fillLb + fillIdx];
            }
         }
         sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
         return RetCode.Success;
      }
      /* Filled once and read as a plain array. */
      lookbackTotal = optInTimePeriod - 1;
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      if( optInTimePeriod < 1 ) return RetCode.InternalError;
      weights = new double[optInTimePeriod];
      maxIdx_weights = (optInTimePeriod)-1;
      weights_Idx = 0;
      /* The expression order is the spec: it is what makes the output bitwise
       * equal to Tulip's beta/alma.c. Keep the floor in binary64 and (j-m) squared
       * in double (an int square overflows at large periods).
       */
      m = (int)Math.Floor(optInOffset * (double)lookbackTotal);
      s = (double)optInTimePeriod / optInSigma;
      twoSSq = 2.0 * s * s;
      norm = 0.0;
      for( j = 0; j < optInTimePeriod; j += 1 ) {
         d = (double)(j - m);
         weights[j] = Math.Exp(-(d * d) / twoSSq);
         norm += weights[j];
      }
      for( j = 0; j < optInTimePeriod; j += 1 ) {
         weights[j] = weights[j] / norm;
      }
      /* Weight 0 is the oldest bar. Each output is written after its window is
       * read, and the next window starts past it, so outReal may alias inReal.
       */
      outIdx = 0;
      i = startIdx;
      while( i <= endIdx ) {
         sum = 0.0;
         w = 0;
         for( j = i - lookbackTotal; j <= i; j += 1 ) {
            sum += weights[w] * inReal[j];
            w += 1;
         }
         outReal[outIdx * outStride] = sum;
         outIdx += 1;
         i += 1;
      }
      outNBElement = outIdx;
      outBegIdx = startIdx;
      /* Capture the live batch state into the handle. */
      int cap_j = (int)(lookbackTotal + 1);
      if( cap_j < 1 || cap_j > historyLen ) {
         return RetCode.InternalError;
      }
      double[] capWin_j_inReal = new double[cap_j];
      inReal.Slice(historyLen - cap_j, cap_j).CopyTo(capWin_j_inReal);
      int capCb_weights = maxIdx_weights + 1;
      if( capCb_weights > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      sp.optInTimePeriod = optInTimePeriod;
      sp.optInSigma = optInSigma;
      sp.optInOffset = optInOffset;
      sp.lookbackTotal = lookbackTotal;
      sp.weights_Idx = weights_Idx;
      sp.maxIdx_weights = maxIdx_weights;
      sp.winPos_j = 0;
      sp.winCap_j = cap_j;
      sp.win_j_inReal = capWin_j_inReal;
      sp.cbSize_weights = capCb_weights;
      sp.cb_weights = weights;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* AlmaOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal AlmaStream AlmaOpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, double optInSigma, double optInOffset, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      AlmaStream sp = new AlmaStream(this);
      RetCode retCode = AlmaOpenImpl(sp, inReal, startIdx, optInTimePeriod, optInSigma, optInOffset, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("ALMA", "openAndFill", nameof(inReal), inReal.Length, startIdx, AlmaLookback(optInTimePeriod, optInSigma, optInOffset));
      }
      throw StreamFailure("ALMA", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind AlmaOpen (composition seam). */
   internal AlmaStream AlmaOpenInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, double optInSigma, double optInOffset )
   {
      AlmaStream sp = new AlmaStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = AlmaOpenImpl(sp, inReal, startIdx, optInTimePeriod, optInSigma, optInOffset, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("ALMA", "open", nameof(inReal), inReal.Length, startIdx, AlmaLookback(optInTimePeriod, optInSigma, optInOffset));
      }
      throw StreamFailure("ALMA", "open", retCode);
   }

   /// <summary>Open a live <c>ALMA</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="AlmaStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>ALMA</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>AlmaLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>AlmaOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">Data on which to compute the average. The warm-up history, oldest bar
   /// first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="AlmaLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSigma">As in the batch call; see <see cref="AlmaLookback"/> for its default and
   /// range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <param name="optInOffset">As in the batch call; see <see cref="AlmaLookback"/> for its default and
   /// range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>AlmaLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules S1 and S2).</exception>
   public AlmaStream AlmaOpen( ReadOnlySpan<double> inReal, int optInTimePeriod, double optInSigma, double optInOffset )
   {
      if( inReal.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "ALMA open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "ALMA open: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      return AlmaOpenInternal(inReal, 0, optInTimePeriod, optInSigma, optInOffset);
   }

   /// <summary><c>AlmaOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>ALMA</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - AlmaLookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="AlmaStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">Data on which to compute the average. The warm-up history, oldest bar
   /// first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="AlmaLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSigma">As in the batch call; see <see cref="AlmaLookback"/> for its default and
   /// range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <param name="optInOffset">As in the batch call; see <see cref="AlmaLookback"/> for its default and
   /// range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <param name="outReal">Arnaud Legoux Moving Average line. Must hold at least <c>historyLen -
   /// AlmaLookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>AlmaLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules S1 and S2).</exception>
   public AlmaStream AlmaOpenAndFill( ReadOnlySpan<double> inReal, int optInTimePeriod, double optInSigma, double optInOffset, Span<double> outReal )
   {
      if( inReal.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "ALMA openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "ALMA openAndFill: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      int guardOutLen = OpenFillCount("ALMA", "openAndFill", inReal.Length, AlmaLookback(optInTimePeriod, optInSigma, optInOffset));
      RequireFillLength("ALMA", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( outReal.Overlaps(inReal) ) {
         throw StreamFailure("ALMA", "openAndFill", RetCode.BadParam);
      }
      return AlmaOpenAndFillInternal(inReal, 0, optInTimePeriod, optInSigma, optInOffset, out _, out _, outReal);
   }

   private double AlmaStepTape( AlmaStream sp, ReadOnlySpan<double> tape, int tapeBase, int tapeMask, double inReal )
   {
      double sum = 0.0;
      int j = 0;
      int w = 0;
      sum = 0.0;
      w = 0;
      for( j = sp.lookbackTotal; j >= 0; j -= 1 ) {
         sum += sp.cb_weights[w] * tape[(tapeBase - j) & tapeMask];
         w += 1;
      }
      sp.cur_outReal = sum;
      sp.outRangeCount++;
      return sp.cur_outReal;
   }

   private double AlmaPeekTape( AlmaStream sp, ReadOnlySpan<double> tape, int tapeBase, int tapeMask, double inReal )
   {
      double sum = 0.0;
      int j = 0;
      int w = 0;
      double cur_outReal = 0.0;
      int pkSlot0 = -1;
      double pkVal0 = 0.0;
      pkSlot0 = tapeBase & tapeMask;
      pkVal0 = inReal;
      sum = 0.0;
      w = 0;
      for( j = sp.lookbackTotal; j >= 0; j -= 1 ) {
         sum += sp.cb_weights[w] * ((((tapeBase - j) & tapeMask) != pkSlot0) ? tape[(tapeBase - j) & tapeMask] : pkVal0);
         w += 1;
      }
      cur_outReal = sum;
      return cur_outReal;
   }

   private int AlmaTapeDetach( AlmaStream sp )
   {
      int reach = 0;
      sp.win_j_inReal = [];
      if( sp.winCap_j - 1 > reach ) {
         reach = sp.winCap_j - 1;
      }
      return reach;
   }
