   /// <summary>A live <c>MASSI</c> stream: one value per closed bar, bit-identical to
   /// <c>MASSI</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.MassiOpen"/>. There is no close and nothing to
   /// dispose — the handle is ordinary managed state, and an unreferenced handle
   /// is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class MassiStream
   {
      internal Core core;
      internal int optInFastPeriod;
      internal int optInSlowPeriod;
      internal double optInK_1;
      internal double ema1;
      internal double ema2;
      internal double total;
      internal int ratioRing_Idx;
      internal int maxIdx_ratioRing;
      internal int cbSize_ratioRing;
      internal double[] cb_ratioRing = [];
      internal double cur_outReal;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal MassiStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Massi</c> reports over the same bars: the opener sets
      /// it to <c>(lookback, historyLen - lookback)</c>, every <c>Update</c> adds
      /// one to the count — a non-finite bar is rejected but still counted, because
      /// the bar happened — <c>Peek</c> leaves it alone, and <c>Clone</c> carries
      /// it verbatim. A plain <c>Open</c> hands back only the last value, a subset
      /// of this range, because the caller chose not to take the fill.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      internal MassiStream( MassiStream other )
      {
         this.core = other.core;
         this.optInFastPeriod = other.optInFastPeriod;
         this.optInSlowPeriod = other.optInSlowPeriod;
         this.optInK_1 = other.optInK_1;
         this.ema1 = other.ema1;
         this.ema2 = other.ema2;
         this.total = other.total;
         this.ratioRing_Idx = other.ratioRing_Idx;
         this.maxIdx_ratioRing = other.maxIdx_ratioRing;
         this.cbSize_ratioRing = other.cbSize_ratioRing;
         this.cb_ratioRing = new double[other.cb_ratioRing.Length];
         Array.Copy( other.cb_ratioRing, this.cb_ratioRing, other.cb_ratioRing.Length );
         this.cur_outReal = other.cur_outReal;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Allocates nothing — neither handle state nor a return value.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so no state moves, <see cref="Value"/> still answers the previous value,
      /// and the stream stays usable — just carry on with the next bar.
      /// <see cref="OutRange"/> does advance: the bar happened, so it is counted,
      /// which keeps two handles fed the same series positionally aligned when only
      /// one of them rejects a bar. This is the one place the streaming tier is
      /// stricter than the batch API, which computes on whatever it is given: a
      /// handle retains its state, so a single non-finite bar would poison every
      /// later value it produces.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inHigh, double inLow )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) )
         {
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
            throw Core.StreamFailure("MASSI", "update", RetCode.BadParam);
         }
         core.MassiStepImpl(this, inHigh, inLow);
         if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It copies nothing: the frame runs against this handle, reading its buffers
      /// and holding what the step would commit in locals. The cost does not grow
      /// with the period, and <c>Peek</c> never allocates.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <returns>What <see cref="Update"/> would return for this bar.</returns>
      public double Peek( double inHigh, double inLow )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) ) throw Core.StreamFailure("MASSI", "peek", RetCode.BadParam);
         MassiStream sp = this;
         double hl = 0.0;
         double ratio = 0.0;
         double tempReal = 0.0;
         double cur_outReal = 0.0;
         double ema1 = sp.ema1;
         double ema2 = sp.ema2;
         int ratioRing_Idx = sp.ratioRing_Idx;
         double total = sp.total;
         int pkSlot0 = -1;
         double pkVal0 = 0.0;
         hl = inHigh - inLow;
         ema1 = Math.FusedMultiplyAdd(hl - ema1, sp.optInK_1, ema1);
         ema2 = Math.FusedMultiplyAdd(ema1 - ema2, sp.optInK_1, ema2);
         if( ema2 == 0.0 ) {
            ratio = 1.0;
         } else {
            ratio = ema1 / ema2;
         }
         pkSlot0 = ratioRing_Idx;
         pkVal0 = ratio;
         total = total + ratio;
         ratioRing_Idx = ratioRing_Idx + 1;
         if( ratioRing_Idx > sp.maxIdx_ratioRing ) {
            ratioRing_Idx = 0;
         }
         tempReal = total;
         total = total - ((ratioRing_Idx != pkSlot0) ? sp.cb_ratioRing[ratioRing_Idx] : pkVal0);
         cur_outReal = tempReal;
         return cur_outReal;
      }

      /// <summary>Commit <c>n</c> closed bars and write their <c>n</c> values, in one call.</summary>
      /// <remarks>
      /// <para>Exactly <c>n</c> back-to-back <see cref="Update"/> calls, with one set of
      /// argument checks instead of <c>n</c>. The outputs must hold at least
      /// <c>n</c> values and must not overlap an input or each other.</para>
      /// <para><see cref="OutRange"/> counts what this call took in, which is what makes
      /// a rejection readable: a non-finite bar <c>k</c> throws
      /// <see cref="System.ArgumentException"/> exactly as <see cref="Update"/>
      /// would, with the bars before <c>k</c> committed and written, bar <c>k</c>
      /// and everything after it not written, and the count advanced by <c>k +
      /// 1</c> — the committed bars plus the rejected one, so the last bar counted
      /// is the one that failed.</para>
      /// </remarks>
      /// <param name="inHigh">Closed bars for <c>inHigh</c>, oldest first.</param>
      /// <param name="inLow">Closed bars for <c>inLow</c>, oldest first.</param>
      /// <param name="outReal">Receives one <c>outReal</c> value per bar committed.</param>
      public void UpdateAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, Span<double> outReal )
      {
         int barCount = inHigh.Length;
         if( inLow.Length != barCount || outReal.Length < barCount || outReal.Overlaps(inHigh) || outReal.Overlaps(inLow) ) throw Core.StreamFailure("MASSI", "updateAndFill", RetCode.BadParam);
         for( int i = 0; i < barCount; i++ )
         {
            if( !double.IsFinite(inHigh[i]) || !double.IsFinite(inLow[i]) )
            {
               if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
               throw Core.StreamFailure("MASSI", "updateAndFill", RetCode.BadParam);
            }
            core.MassiStepImpl(this, inHigh[i], inLow[i]);
            outReal[i] = cur_outReal;
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         }
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public MassiStream Clone()
      {
         return new MassiStream(this);
      }
   }

   internal void MassiStepImpl( MassiStream sp, double inHigh, double inLow )
   {
      double hl = 0.0;
      double ratio = 0.0;
      double tempReal = 0.0;
      hl = inHigh - inLow;
      sp.ema1 = Math.FusedMultiplyAdd(hl - sp.ema1, sp.optInK_1, sp.ema1);
      sp.ema2 = Math.FusedMultiplyAdd(sp.ema1 - sp.ema2, sp.optInK_1, sp.ema2);
      if( sp.ema2 == 0.0 ) {
         ratio = 1.0;
      } else {
         ratio = sp.ema1 / sp.ema2;
      }
      sp.cb_ratioRing[sp.ratioRing_Idx] = ratio;
      sp.total = sp.total + ratio;
      sp.ratioRing_Idx = sp.ratioRing_Idx + 1;
      if( sp.ratioRing_Idx > sp.maxIdx_ratioRing ) {
         sp.ratioRing_Idx = 0;
      }
      tempReal = sp.total;
      sp.total = sp.total - sp.cb_ratioRing[sp.ratioRing_Idx];
      sp.cur_outReal = tempReal;
   }

   private RetCode MassiOpenImpl( MassiStream sp, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int startIdx, int optInFastPeriod, int optInSlowPeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double optInK_1 = 0;
      double hl = 0;
      double ema1 = 0;
      double ema2 = 0;
      double sum1 = 0;
      double sum2 = 0;
      double ratio = 0;
      double total = 0;
      double tempReal = 0;
      int lookbackTotal = 0;
      int lookbackEma = 0;
      int lookbackEma2 = 0;
      int today = 0;
      int outIdx = 0;
      int nBar = 0;
      int n2 = 0;
      double[] ratioRing = [];
      int ratioRing_Idx = 0;
      int maxIdx_ratioRing = (32)-1;
      int historyLen = inHigh.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inLow.Length != inHigh.Length ) {
         return RetCode.BadParam;
      }
      if( optInFastPeriod == int.MinValue ) {
         optInFastPeriod = 9;
      } else if( optInFastPeriod < 2 || optInFastPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInSlowPeriod == int.MinValue ) {
         optInSlowPeriod = 25;
      } else if( optInSlowPeriod < 2 || optInSlowPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      lookbackEma = EMA_Lookback(optInFastPeriod);
      lookbackEma2 = lookbackEma * 2;
      lookbackTotal = lookbackEma2 + (optInSlowPeriod - 1);
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      if( optInSlowPeriod < 1 ) return RetCode.InternalError;
      ratioRing = new double[optInSlowPeriod];
      maxIdx_ratioRing = (optInSlowPeriod)-1;
      ratioRing_Idx = 0;
      outBegIdx = startIdx;
      /* Dorsey's pipeline in one pass: EMA of the high-low range, EMA of that,
       * their ratio summed over a trailing window.
       *
       * Each stage seeds the way ema.c does -- a simple average of that stage's
       * first optInFastPeriod inputs -- and its boundary below is the callee
       * LOOKBACK, never (optInFastPeriod - 1). The two coincide exactly at
       * unstable period 0, which is where every cross-language gate runs, so
       * confusing them is invisible until TA_SetUnstablePeriod(TA_FUNC_UNST_EMA)
       * is warmed. The seed sums accumulate from 0.0 in production order; do not
       * reorder or fuse them (0.0+x is not x for x=-0.0).
       *
       * Seed from the SMA arm only: ema.c's TA_COMPATIBILITY_METASTOCK arm is
       * unreachable from the Rust, Java and C# APIs, so consulting
       * TA_GetCompatibility() here would make C diverge from three backends for a
       * setting they cannot read.
       */
      optInK_1 = 2.0 / (double)(optInFastPeriod + 1);
      ema1 = 0.0;
      ema2 = 0.0;
      sum1 = 0.0;
      sum2 = 0.0;
      total = 0.0;
      tempReal = 0.0;
      today = startIdx - lookbackTotal;
      nBar = 0;
      /* Runs through startIdx inclusive: that last pass fills the summation
       * window and so produces the first output.
       */
      while( today <= startIdx ) {
         hl = inHigh[today] - inLow[today];
         if( nBar < optInFastPeriod ) {
            sum1 = sum1 + hl;
            if( nBar == optInFastPeriod - 1 ) {
               ema1 = sum1 / optInFastPeriod;
            }
         } else {
            ema1 = Math.FusedMultiplyAdd(hl - ema1, optInK_1, ema1);
         }
         /* The stage counter is compared BEFORE it is subtracted, never after.
          * `n2 = nBar - lookbackEma; if( n2 >= 0 )` is correct in C and broken
          * everywhere else: the Rust backend renders these as usize, so the
          * subtraction underflows for the first lookbackEma bars.
          */
         if( nBar >= lookbackEma ) {
            n2 = nBar - lookbackEma;
            if( n2 < optInFastPeriod ) {
               sum2 = sum2 + ema1;
               if( n2 == optInFastPeriod - 1 ) {
                  ema2 = sum2 / optInFastPeriod;
               }
            } else {
               ema2 = Math.FusedMultiplyAdd(ema1 - ema2, optInK_1, ema2);
            }
         }
         if( nBar >= lookbackEma2 ) {
            /* A flat market is the ratio's continuous limit, 1.0, not the zero
             * that an oscillator centred on zero would report: MASSI's own
             * neutral is optInSlowPeriod. Test ema2 exactly and never through an
             * epsilon band -- a smoothed price range carries the quote unit, so a
             * fixed band would pin the whole index at optInSlowPeriod for any
             * instrument quoted under it (issue #253).
             */
            if( ema2 == 0.0 ) {
               ratio = 1.0;
            } else {
               ratio = ema1 / ema2;
            }
            /* TA_SUM's accumulation order -- add, publish, subtract -- reproduced
             * over a ring: the slot written here was emptied out of `total` at the
             * end of the previous bar, so nothing has to be read before the store.
             */
            ratioRing[ratioRing_Idx] = ratio;
            total = total + ratio;
            ratioRing_Idx++;
            if( ratioRing_Idx > maxIdx_ratioRing ) { ratioRing_Idx = 0; }
            if( nBar == lookbackTotal ) {
               tempReal = total;
               total = total - ratioRing[ratioRing_Idx];
            }
         }
         nBar = nBar + 1;
         today = today + 1;
      }
      /* In-place safe: this store lands lookbackTotal bars behind the input
       * cursor, so no bar is written under a read still owed to it.
       */
      outReal[0 * outStride] = tempReal;
      outIdx = 1;
      while( today <= endIdx ) {
         hl = inHigh[today] - inLow[today];
         ema1 = Math.FusedMultiplyAdd(hl - ema1, optInK_1, ema1);
         ema2 = Math.FusedMultiplyAdd(ema1 - ema2, optInK_1, ema2);
         if( ema2 == 0.0 ) {
            ratio = 1.0;
         } else {
            ratio = ema1 / ema2;
         }
         ratioRing[ratioRing_Idx] = ratio;
         total = total + ratio;
         ratioRing_Idx++;
         if( ratioRing_Idx > maxIdx_ratioRing ) { ratioRing_Idx = 0; }
         tempReal = total;
         total = total - ratioRing[ratioRing_Idx];
         outReal[outIdx * outStride] = tempReal;
         outIdx = outIdx + 1;
         today = today + 1;
      }
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      int capCb_ratioRing = maxIdx_ratioRing + 1;
      if( capCb_ratioRing > historyLen + 1 ) {
         return RetCode.InternalError;
      }
      sp.optInFastPeriod = optInFastPeriod;
      sp.optInSlowPeriod = optInSlowPeriod;
      sp.optInK_1 = optInK_1;
      sp.ema1 = ema1;
      sp.ema2 = ema2;
      sp.total = total;
      sp.ratioRing_Idx = ratioRing_Idx;
      sp.maxIdx_ratioRing = maxIdx_ratioRing;
      sp.cbSize_ratioRing = capCb_ratioRing;
      sp.cb_ratioRing = ratioRing;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* MassiOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal MassiStream MassiOpenAndFillInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int startIdx, int optInFastPeriod, int optInSlowPeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      MassiStream sp = new MassiStream(this);
      RetCode retCode = MassiOpenImpl(sp, inHigh, inLow, startIdx, optInFastPeriod, optInSlowPeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("MASSI", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind MassiOpen (composition seam). */
   internal MassiStream MassiOpenInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int startIdx, int optInFastPeriod, int optInSlowPeriod )
   {
      MassiStream sp = new MassiStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = MassiOpenImpl(sp, inHigh, inLow, startIdx, optInFastPeriod, optInSlowPeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("MASSI", "open", retCode);
   }

   /// <summary>Open a live <c>MASSI</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="MassiStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>MASSI</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>MASSI_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>MassiOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inHigh">High price. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price. The warm-up history, oldest bar first.</param>
   /// <param name="optInFastPeriod">As in the batch call; see <see cref="MASSI_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowPeriod">As in the batch call; see <see cref="MASSI_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>MASSI_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public MassiStream MassiOpen( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int optInFastPeriod, int optInSlowPeriod )
   {
      if( inHigh.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "MASSI open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "MASSI open: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("MASSI open: inLow is empty", nameof(inLow), RetCode.BadParam);
      RequireHistoryLength("MASSI", "open", "inLow", inLow.Length, inHigh.Length);
      return MassiOpenInternal(inHigh, inLow, 0, optInFastPeriod, optInSlowPeriod);
   }

   /// <summary><c>MassiOpen</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>MASSI</c> produces over
   /// the same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - MASSI_Lookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="MassiStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inHigh">High price. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price. The warm-up history, oldest bar first.</param>
   /// <param name="optInFastPeriod">As in the batch call; see <see cref="MASSI_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInSlowPeriod">As in the batch call; see <see cref="MASSI_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Summed ratio of the two smoothed high-low ranges. Must hold at least
   /// <c>historyLen - MASSI_Lookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>MASSI_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MAX_INDEX"/> + 1,
   /// the two index faults an opener can have (rules S1 and S2).</exception>
   public MassiStream MassiOpenAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int optInFastPeriod, int optInSlowPeriod, Span<double> outReal )
   {
      if( inHigh.IsEmpty ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "MASSI openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > MAX_INDEX + 1 ) throw new TaLibArgumentOutOfRangeException(nameof(inHigh), "MASSI openAndFill: history is longer than MAX_INDEX + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TaLibArgumentException("MASSI openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      int guardOutLen = OpenFillCount("MASSI", "openAndFill", inHigh.Length, MASSI_Lookback(optInFastPeriod, optInSlowPeriod));
      RequireHistoryLength("MASSI", "openAndFill", "inLow", inLow.Length, inHigh.Length);
      RequireFillLength("MASSI", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( outReal.Overlaps(inHigh) || outReal.Overlaps(inLow) ) {
         throw StreamFailure("MASSI", "openAndFill", RetCode.BadParam);
      }
      return MassiOpenAndFillInternal(inHigh, inLow, 0, optInFastPeriod, optInSlowPeriod, out _, out _, outReal);
   }
