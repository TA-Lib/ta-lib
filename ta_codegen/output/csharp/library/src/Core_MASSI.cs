   /// <exception cref="System.ArgumentException">Two output buffers overlap, or an output partially overlaps an input.
   /// Computing wholly in place (an output that IS an input) is allowed.</exception>
   public OutRange MASSI( int startIdx,
                          int endIdx,
                          ReadOnlySpan<float> inHigh,
                          ReadOnlySpan<float> inLow,
                          int optInFastPeriod,
                          int optInSlowPeriod,
                          Span<double> outReal )
   {
      int guardStart = ClampedStart(startIdx, endIdx, MASSI_Lookback(optInFastPeriod, optInSlowPeriod));
      int guardInLen = guardStart < 0 ? 0 : endIdx + 1;
      int guardOutLen = guardStart < 0 || guardStart > endIdx ? 0 : endIdx - guardStart + 1;
      RequireLength("MASSI", "inHigh", inHigh.Length, guardInLen);
      RequireLength("MASSI", "inLow", inLow.Length, guardInLen);
      RequireLength("MASSI", "outReal", outReal.Length, guardOutLen);
      RetCode retCode = MASSI_Impl(startIdx, endIdx, inHigh, inLow, optInFastPeriod, optInSlowPeriod, out int outBegIdx, out int outNBElement, outReal);
      if( retCode != RetCode.Success ) {
         throw Failure("MASSI", retCode);
      }
      return new OutRange(outBegIdx, outNBElement);
   }
