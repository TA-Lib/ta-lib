                              int endIdx,
                              ReadOnlySpan<double> inOpen,
                              ReadOnlySpan<double> inHigh,
                              ReadOnlySpan<double> inLow,
                              ReadOnlySpan<double> inClose,
                              Span<int> outInteger )
   {
      int guardStart = ClampedStart(startIdx, endIdx, CDLTAKURI_Lookback());
      int guardInLen = guardStart < 0 ? 0 : endIdx + 1;
      int guardOutLen = guardStart < 0 || guardStart > endIdx ? 0 : endIdx - guardStart + 1;
      RequireLength("CDLTAKURI", "inOpen", inOpen.Length, guardInLen);
      RequireLength("CDLTAKURI", "inHigh", inHigh.Length, guardInLen);
      RequireLength("CDLTAKURI", "inLow", inLow.Length, guardInLen);
      RequireLength("CDLTAKURI", "inClose", inClose.Length, guardInLen);
      RequireLength("CDLTAKURI", "outInteger", outInteger.Length, guardOutLen);
