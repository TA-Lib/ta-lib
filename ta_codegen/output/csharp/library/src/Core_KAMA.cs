                         ReadOnlySpan<float> inReal,
                         int optInTimePeriod,
                         Span<double> outReal )
   {
      int guardStart = ClampedStart(startIdx, endIdx, KAMA_Lookback(optInTimePeriod));
      int guardInLen = guardStart < 0 ? 0 : endIdx + 1;
      int guardOutLen = guardStart < 0 || guardStart > endIdx ? 0 : endIdx - guardStart + 1;
      RequireLength("KAMA", "inReal", inReal.Length, guardInLen);
      RequireLength("KAMA", "outReal", outReal.Length, guardOutLen);
      RetCode retCode = KAMA_Impl(startIdx, endIdx, inReal, optInTimePeriod, out int outBegIdx, out int outNBElement, outReal);
      if( retCode != RetCode.Success ) {
         throw Failure("KAMA", retCode);
      }
      return new OutRange(outBegIdx, outNBElement);
   }
   /**** Streaming API *****/

   /// <summary>A live <c>KAMA</c> stream: one value per closed bar, bit-identical to
   /// <c>KAMA</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.KamaOpen"/>. There is no close and nothing to
   /// dispose — the handle is ordinary managed state, and an unreferenced handle
   /// is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class KamaStream
   {
      internal Core core;
      internal int optInTimePeriod;
      internal double constMax;
      internal double constDiff;
      internal double sumROC1;
      internal double prevKAMA;
      internal int nullRun;
      internal double trailingValue;
      internal double lag1_inReal;
      internal int ringPos_trailingIdx;
      internal int ringCap_trailingIdx;
      internal double[] ring_trailingIdx_inReal = [];
      internal double cur_outReal;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal KamaStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Kama</c> reports over the same bars: the opener sets it
      /// to <c>(lookback, historyLen - lookback)</c>, every <c>Update</c> adds one
      /// to the count — a non-finite bar is rejected but still counted, because the
      /// bar happened — <c>Peek</c> leaves it alone, and <c>Clone</c> carries it
      /// verbatim. A plain <c>Open</c> hands back only the last value, a subset of
      /// this range, because the caller chose not to take the fill.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      internal KamaStream( KamaStream other )
      {
         this.core = other.core;
         this.optInTimePeriod = other.optInTimePeriod;
         this.constMax = other.constMax;
         this.constDiff = other.constDiff;
         this.sumROC1 = other.sumROC1;
         this.prevKAMA = other.prevKAMA;
         this.nullRun = other.nullRun;
         this.trailingValue = other.trailingValue;
         this.lag1_inReal = other.lag1_inReal;
         this.ringPos_trailingIdx = other.ringPos_trailingIdx;
         this.ringCap_trailingIdx = other.ringCap_trailingIdx;
         this.ring_trailingIdx_inReal = new double[other.ring_trailingIdx_inReal.Length];
         Array.Copy( other.ring_trailingIdx_inReal, this.ring_trailingIdx_inReal, other.ring_trailingIdx_inReal.Length );
         this.cur_outReal = other.cur_outReal;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Allocates nothing — neither handle state nor a return value.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so no state moves, <see cref="Value"/> still answers the previous value,
      /// and the stream stays usable — just carry on with the next bar.
      /// <see cref="OutRange"/> does advance: the bar happened, so it is counted,
      /// which keeps two handles fed the same series positionally aligned when only
      /// one of them rejects a bar. This is the one place the streaming tier is
      /// stricter than the batch API, which computes on whatever it is given: a
      /// handle retains its state, so a single non-finite bar would poison every
      /// later value it produces.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inReal )
      {
         if( !double.IsFinite(inReal) )
         {
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
            throw Core.StreamFailure("KAMA", "update", RetCode.BadParam);
         }
         core.KamaStepImpl(this, inReal);
         if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It copies nothing: the frame runs against this handle, reading its buffers
      /// and holding what the step would commit in locals. The cost does not grow
      /// with the period, and <c>Peek</c> never allocates.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>What <see cref="Update"/> would return for this bar.</returns>
      public double Peek( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.StreamFailure("KAMA", "peek", RetCode.BadParam);
         KamaStream sp = this;
         double tempReal = 0.0;
         double tempReal2 = 0.0;
         double periodROC = 0.0;
         double cur_outReal = 0.0;
         int nullRun = sp.nullRun;
         double prevKAMA = sp.prevKAMA;
         double sumROC1 = sp.sumROC1;
         double trailingValue = sp.trailingValue;
         int pkSlot0 = -1;
         double pkVal0 = 0.0;
         if( sp.optInTimePeriod == 1 ) {
            cur_outReal = inReal;
            return cur_outReal ;
         }
         if( sp.ringCap_trailingIdx == 0 ) {
            pkSlot0 = 0;
            pkVal0 = inReal;
         }
         tempReal = inReal;
         tempReal2 = (sp.ringPos_trailingIdx != pkSlot0) ? sp.ring_trailingIdx_inReal[sp.ringPos_trailingIdx] : pkVal0;
         periodROC = tempReal - tempReal2;
         /* Adjust sumROC1:
          *  - Remove trailing ROC1
          *  - Add new ROC1
          */
         sumROC1 -= Math.Abs(trailingValue - tempReal2);
         sumROC1 += Math.Abs(tempReal - sp.lag1_inReal);
         /* Once a whole window of flat bars has gone by, every 1-day change it
          * spans is exactly zero, so the sum is known to be exactly zero and the
          * residue can be dropped. That is what lets the efficiency ratio be
          * decided by `sumROC1 <= periodROC` alone: a window that flat has
          * periodROC == 0 too, so the test is 0 <= 0 and the ratio is 1.
          */
         if( tempReal - sp.lag1_inReal == 0.0 ) {
            nullRun += 1;
         } else {
            nullRun = 0;
         }
         if( nullRun >= sp.optInTimePeriod ) {
            nullRun = sp.optInTimePeriod;
            sumROC1 = 0.0;
         }
         /* Save the trailing value. Do this because inReal
          * and outReal can be pointers to the same buffer.
          */
         trailingValue = tempReal2;
         /* Calculate the efficiency ratio */
         if( sumROC1 <= periodROC ) {
            tempReal = 1.0;
         } else {
            tempReal = Math.Abs(periodROC / sumROC1);
         }
         /* Calculate the smoothing constant */
         tempReal = Math.FusedMultiplyAdd(tempReal, sp.constDiff, sp.constMax);
         tempReal *= tempReal;
         /* Calculate the KAMA like an EMA, using the
          * smoothing constant as the adaptive factor.
          */
         prevKAMA = Math.FusedMultiplyAdd(inReal - prevKAMA, tempReal, prevKAMA);
         cur_outReal = prevKAMA;
         return cur_outReal;
      }

      /// <summary>Commit <c>n</c> closed bars and write their <c>n</c> values, in one call.</summary>
      /// <remarks>
      /// <para>Exactly <c>n</c> back-to-back <see cref="Update"/> calls, with one set of
      /// argument checks instead of <c>n</c>. The outputs must hold at least
      /// <c>n</c> values and must not overlap an input or each other.</para>
      /// <para><see cref="OutRange"/> counts what this call took in, which is what makes
      /// a rejection readable: a non-finite bar <c>k</c> throws
      /// <see cref="System.ArgumentException"/> exactly as <see cref="Update"/>
      /// would, with the bars before <c>k</c> committed and written, bar <c>k</c>
      /// and everything after it not written, and the count advanced by <c>k +
      /// 1</c> — the committed bars plus the rejected one, so the last bar counted
      /// is the one that failed.</para>
      /// </remarks>
      /// <param name="inReal">Closed bars for <c>inReal</c>, oldest first.</param>
      /// <param name="outReal">Receives one <c>outReal</c> value per bar committed.</param>
      public void UpdateAndFill( ReadOnlySpan<double> inReal, Span<double> outReal )
      {
         int barCount = inReal.Length;
         if( outReal.Length < barCount || outReal.Overlaps(inReal) ) throw Core.StreamFailure("KAMA", "updateAndFill", RetCode.BadParam);
         for( int i = 0; i < barCount; i++ )
         {
            if( !double.IsFinite(inReal[i]) )
            {
               if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
               throw Core.StreamFailure("KAMA", "updateAndFill", RetCode.BadParam);
            }
            core.KamaStepImpl(this, inReal[i]);
            outReal[i] = cur_outReal;
            if( outRangeCount < Core.MAX_INDEX ) outRangeCount++;
         }
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public KamaStream Clone()
      {
         return new KamaStream(this);
      }
   }

   internal void KamaStepImpl( KamaStream sp, double inReal )
   {
      double tempReal = 0.0;
      double tempReal2 = 0.0;
      double periodROC = 0.0;
      if( sp.optInTimePeriod == 1 ) {
         sp.cur_outReal = inReal;
         return ;
      }
      if( sp.ringCap_trailingIdx == 0 ) {
         sp.ring_trailingIdx_inReal[0] = inReal;
      }
      tempReal = inReal;
      tempReal2 = sp.ring_trailingIdx_inReal[sp.ringPos_trailingIdx];
      periodROC = tempReal - tempReal2;
      /* Adjust sumROC1:
       *  - Remove trailing ROC1
       *  - Add new ROC1
       */
      sp.sumROC1 -= Math.Abs(sp.trailingValue - tempReal2);
      sp.sumROC1 += Math.Abs(tempReal - sp.lag1_inReal);
      /* Once a whole window of flat bars has gone by, every 1-day change it
       * spans is exactly zero, so the sum is known to be exactly zero and the
       * residue can be dropped. That is what lets the efficiency ratio be
       * decided by `sumROC1 <= periodROC` alone: a window that flat has
       * periodROC == 0 too, so the test is 0 <= 0 and the ratio is 1.
       */
      if( tempReal - sp.lag1_inReal == 0.0 ) {
         sp.nullRun += 1;
      } else {
         sp.nullRun = 0;
      }
      if( sp.nullRun >= sp.optInTimePeriod ) {
         sp.nullRun = sp.optInTimePeriod;
         sp.sumROC1 = 0.0;
      }
      /* Save the trailing value. Do this because inReal
       * and outReal can be pointers to the same buffer.
       */
      sp.trailingValue = tempReal2;
      /* Calculate the efficiency ratio */
      if( sp.sumROC1 <= periodROC ) {
         tempReal = 1.0;
      } else {
         tempReal = Math.Abs(periodROC / sp.sumROC1);
      }
      /* Calculate the smoothing constant */
      tempReal = Math.FusedMultiplyAdd(tempReal, sp.constDiff, sp.constMax);
      tempReal *= tempReal;
      /* Calculate the KAMA like an EMA, using the
       * smoothing constant as the adaptive factor.
       */
      sp.prevKAMA = Math.FusedMultiplyAdd(inReal - sp.prevKAMA, tempReal, sp.prevKAMA);
      sp.cur_outReal = sp.prevKAMA;
      sp.lag1_inReal = inReal;
      sp.ring_trailingIdx_inReal[sp.ringPos_trailingIdx] = inReal;
      sp.ringPos_trailingIdx = sp.ringPos_trailingIdx + 1;
      if( sp.ringPos_trailingIdx >= sp.ringCap_trailingIdx ) {
         sp.ringPos_trailingIdx = 0;
      }
   }

   private RetCode KamaOpenImpl( KamaStream sp, ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double constMax = 0;
      double constDiff = 0;
      double tempReal = 0;
      double tempReal2 = 0;
      double sumROC1 = 0;
      double periodROC = 0;
      double prevKAMA = 0;
      int i = 0;
      int today = 0;
      int outIdx = 0;
      int lookbackTotal = 0;
      int trailingIdx = 0;
      int nullRun = 0;
      double trailingValue = 0;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 30;
      } else if( optInTimePeriod < 1 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      if( optInTimePeriod == 1 ) {
         int fillLb = KAMA_Lookback(optInTimePeriod);
         if( startIdx > fillLb ) fillLb = startIdx;
         if( historyLen < fillLb + 1 ) {
            return RetCode.InsufficientHistory;
         }
         sp.optInTimePeriod = optInTimePeriod;
         sp.constMax = 0.0;
         sp.constDiff = 0.0;
         sp.sumROC1 = 0.0;
         sp.prevKAMA = 0.0;
         sp.nullRun = 0;
         sp.trailingValue = 0.0;
         sp.lag1_inReal = 0.0;
         sp.ringPos_trailingIdx = 0;
         sp.ringCap_trailingIdx = 0;
         sp.ring_trailingIdx_inReal = new double[1];
         outBegIdx = fillLb;
         outNBElement = historyLen - fillLb;
         if( outStride == 0 ) {
            outReal[0] = inReal[historyLen - 1];
         } else {
            for( int fillIdx = 0; fillIdx < historyLen - fillLb; fillIdx++ ) {
               outReal[fillIdx] = inReal[fillLb + fillIdx];
            }
         }
         sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
         return RetCode.Success;
      }
      constMax = 2.0 / (30.0 + 1.0);
      constDiff = 2.0 / (2.0 + 1.0) - constMax;
      /* Default return values */
      outBegIdx = 0;
      outNBElement = 0;
      /* Identify the minimum number of price bar needed
       * to calculate at least one output.
       */
      lookbackTotal = optInTimePeriod + this.unstablePeriod[(int)FuncUnstId.KAMA];
      /* Move up the start index if there is not
       * enough initial data.
       */
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      /* Initialize the variables by going through
       * the lookback period.
       */
      sumROC1 = 0.0;
      /* Consecutive 1-day changes of exactly zero, counted so that a flat window
       * can be recognized exactly (the shape #244 needed for MFI). sumROC1 cannot
       * answer that question itself once the window starts sliding: it is
       * maintained by add-then-subtract, so a window that has gone flat leaves it
       * holding rounding residue of arbitrary sign rather than zero, and the
       * efficiency ratio then divides that residue into itself.
       */
      nullRun = 0;
      today = startIdx - lookbackTotal;
      trailingIdx = today;
      i = optInTimePeriod;
      while( i-- > 0 ) {
         tempReal = inReal[today++];
         tempReal -= inReal[today];
         sumROC1 += Math.Abs(tempReal);
         if( tempReal == 0.0 ) {
            nullRun += 1;
         } else {
            nullRun = 0;
         }
      }
      /* At this point sumROC1 represent the
       * summation of the 1-day price difference
       * over the (optInTimePeriod-1)
       */
      /* Calculate the first KAMA */
      /* The yesterday price is used here as the previous KAMA. */
      prevKAMA = inReal[today - 1];
      tempReal = inReal[today];
      tempReal2 = inReal[trailingIdx++];
      periodROC = tempReal - tempReal2;
      /* Save the trailing value. Do this because inReal
       * and outReal can be pointers to the same buffer.
       */
      trailingValue = tempReal2;
      /* Calculate the efficiency ratio.
       *
       * The only threshold is `sumROC1 <= periodROC`, and it is scale-consistent:
       * both sides carry the quote unit. The fixed TA_IS_ZERO band that used to
       * sit beside it was not -- it declared the window flat, and forced the
       * fastest adaptation, for every window of an instrument quoted below it
       * (issue #253). A genuinely flat window is now recognized by the exact bar
       * count above instead.
       */
      if( sumROC1 <= periodROC ) {
         tempReal = 1.0;
      } else {
         tempReal = Math.Abs(periodROC / sumROC1);
      }
      /* Calculate the smoothing constant */
      tempReal = Math.FusedMultiplyAdd(tempReal, constDiff, constMax);
      tempReal *= tempReal;
      /* Calculate the KAMA like an EMA, using the
       * smoothing constant as the adaptive factor.
       */
      prevKAMA = Math.FusedMultiplyAdd(inReal[today++] - prevKAMA, tempReal, prevKAMA);
      /* 'today' keep track of where the processing is within the
       * input.
       */
      /* Skip the unstable period. Do the whole processing
       * needed for KAMA, but do not write it in the output.
       */
      while( today <= startIdx ) {
         tempReal = inReal[today];
         tempReal2 = inReal[trailingIdx++];
         periodROC = tempReal - tempReal2;
         /* Adjust sumROC1:
          *  - Remove trailing ROC1
          *  - Add new ROC1
          */
         sumROC1 -= Math.Abs(trailingValue - tempReal2);
         sumROC1 += Math.Abs(tempReal - inReal[today - 1]);
         /* Once a whole window of flat bars has gone by, every 1-day change it
          * spans is exactly zero, so the sum is known to be exactly zero and the
          * residue can be dropped. That is what lets the efficiency ratio be
          * decided by `sumROC1 <= periodROC` alone: a window that flat has
          * periodROC == 0 too, so the test is 0 <= 0 and the ratio is 1.
          */
         if( tempReal - inReal[today - 1] == 0.0 ) {
            nullRun += 1;
         } else {
            nullRun = 0;
         }
         if( nullRun >= optInTimePeriod ) {
            nullRun = optInTimePeriod;
            sumROC1 = 0.0;
         }
         /* Save the trailing value. Do this because inReal
          * and outReal can be pointers to the same buffer.
          */
         trailingValue = tempReal2;
         /* Calculate the efficiency ratio */
         if( sumROC1 <= periodROC ) {
            tempReal = 1.0;
         } else {
            tempReal = Math.Abs(periodROC / sumROC1);
         }
         /* Calculate the smoothing constant */
         tempReal = Math.FusedMultiplyAdd(tempReal, constDiff, constMax);
         tempReal *= tempReal;
         /* Calculate the KAMA like an EMA, using the
          * smoothing constant as the adaptive factor.
          */
         prevKAMA = Math.FusedMultiplyAdd(inReal[today++] - prevKAMA, tempReal, prevKAMA);
      }
      /* Write the first value. */
      outReal[0 * outStride] = prevKAMA;
      outIdx = 1;
      outBegIdx = today - 1;
      /* Do the KAMA calculation for the requested range. */
      while( today <= endIdx ) {
         tempReal = inReal[today];
         tempReal2 = inReal[trailingIdx++];
         periodROC = tempReal - tempReal2;
         /* Adjust sumROC1:
          *  - Remove trailing ROC1
          *  - Add new ROC1
          */
         sumROC1 -= Math.Abs(trailingValue - tempReal2);
         sumROC1 += Math.Abs(tempReal - inReal[today - 1]);
         /* Once a whole window of flat bars has gone by, every 1-day change it
          * spans is exactly zero, so the sum is known to be exactly zero and the
          * residue can be dropped. That is what lets the efficiency ratio be
          * decided by `sumROC1 <= periodROC` alone: a window that flat has
          * periodROC == 0 too, so the test is 0 <= 0 and the ratio is 1.
          */
         if( tempReal - inReal[today - 1] == 0.0 ) {
            nullRun += 1;
         } else {
            nullRun = 0;
         }
         if( nullRun >= optInTimePeriod ) {
            nullRun = optInTimePeriod;
            sumROC1 = 0.0;
         }
         /* Save the trailing value. Do this because inReal
          * and outReal can be pointers to the same buffer.
          */
         trailingValue = tempReal2;
         /* Calculate the efficiency ratio */
         if( sumROC1 <= periodROC ) {
            tempReal = 1.0;
         } else {
            tempReal = Math.Abs(periodROC / sumROC1);
         }
         /* Calculate the smoothing constant */
         tempReal = Math.FusedMultiplyAdd(tempReal, constDiff, constMax);
         tempReal *= tempReal;
         /* Calculate the KAMA like an EMA, using the
          * smoothing constant as the adaptive factor.
          */
         prevKAMA = Math.FusedMultiplyAdd(inReal[today++] - prevKAMA, tempReal, prevKAMA);
         outReal[outIdx++ * outStride] = prevKAMA;
      }
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      int cap_trailingIdx = today - trailingIdx;
      if( cap_trailingIdx < 0 || cap_trailingIdx > historyLen ) {
         return RetCode.InternalError;
      }
      int allocN_trailingIdx = (cap_trailingIdx > 0)? cap_trailingIdx : 1;
      double[] capRing_trailingIdx_inReal = new double[allocN_trailingIdx];
      inReal.Slice(historyLen - cap_trailingIdx, cap_trailingIdx).CopyTo(capRing_trailingIdx_inReal);
      sp.optInTimePeriod = optInTimePeriod;
      sp.constMax = constMax;
      sp.constDiff = constDiff;
      sp.sumROC1 = sumROC1;
      sp.prevKAMA = prevKAMA;
      sp.nullRun = nullRun;
      sp.trailingValue = trailingValue;
      sp.lag1_inReal = inReal[historyLen - 1];
      sp.ringPos_trailingIdx = 0;
      sp.ringCap_trailingIdx = cap_trailingIdx;
      sp.ring_trailingIdx_inReal = capRing_trailingIdx_inReal;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* KamaOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal KamaStream KamaOpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      KamaStream sp = new KamaStream(this);
      RetCode retCode = KamaOpenImpl(sp, inReal, startIdx, optInTimePeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("KAMA", "openAndFill", retCode);
   }

