      }
      return new OutRange(outBegIdx, outNBElement);
   }
   /// <summary>
   /// Premier Stochastic Oscillator: a short-period Fast %K, recentred on zero
   /// and rescaled, double-smoothed and then squashed into the open interval -1
   /// to +1. Leibfarth's reading is that the plain stochastic spends most of its
   /// life pinned at one end or the other, so the extremes stop meaning
   /// anything; the two exponential passes strip the bar-to-bar noise out of it,
   /// and the squash gives back a scale on which the extremes are rare again.
   /// Readings beyond ±0.9 are the extremes, and ±0.2 the band Leibfarth watches
   /// for the crossing back toward the middle.
   /// </summary>
   /// <remarks>
   /// <para>
   /// Formula and more info at
   /// <see href="https://ta-lib.org/functions/pso">ta-lib.org/functions/pso</see>.
   /// </para>
   /// <list type="bullet">
   /// <item><description>The affine step comes before the smoothing, as the author's listing spells it. Smoothing first and recentring after is the same value in real arithmetic and differs in the last bit or two in doubles.</description></item>
   /// <item><description>The squash is computed as <c>tanh(SS/2)</c>, which is the published quotient rewritten. The quotient form is <c>inf/inf</c> once <c>SS</c> exceeds 709.78, which a bar whose close lies outside its own high/low range can reach; <c>tanh</c> saturates at ±1 instead.</description></item>
   /// <item><description>A Fast-K window whose range is zero reads 50, the midpoint, so a flat market reads PSO 0 rather than the near-extreme the Fast-K convention of 0 would give it. The flatness test is the one STOCHF applies, against the window's own extremes rather than a fixed band.</description></item>
   /// <item><description>Each exponential pass is seeded with a simple average of its own first inputs, the same seeding TA-Lib's EMA uses, and the second pass seeds on what the first publishes. <c>TA_SetUnstablePeriod(TA_FUNC_UNST_EMA, ...)</c> discards more of that warm-up, through both passes. Implementations seeding each pass from a single first sample differ over the transient and agree once it decays.</description></item>
   /// <item><description>Leibfarth parameterises the smoothing as the square root of a longer period, 25 by default, which is 5. The length is taken here directly, as an integer, because the sources that follow the square root disagree over how to round it.</description></item>
   /// </list>
   /// <para>
   /// This is the <c>float[]</c> overload: input elements are widened to
   /// <c>double</c> as they are read and all arithmetic is performed in
   /// <c>double</c>, so a result beyond <c>float</c> range is still
   /// representable.
   /// </para>
   /// <para>
   /// Values are written only where the indicator is defined. The returned
   /// <see cref="OutRange"/> says where they start and how many there are, and
   /// the library never pads with NaN. A valid range that ends before
   /// <c>PsoLookback</c> is a <b>success with no values</b> (<c>Count == 0</c>),
   /// not an error.
   /// </para>
   /// <para>
   /// Every exception it throws, except the runtime's own
   /// <c>OutOfMemoryException</c>, implements <see cref="ITALibFailure"/>, which
   /// carries the <see cref="RetCode"/>.
   /// </para>
   /// </remarks>
   /// <param name="startIdx">First bar of the requested range (inclusive).</param>
   /// <param name="endIdx">Last bar of the requested range (inclusive).</param>
   /// <param name="inHigh">High price series.</param>
   /// <param name="inLow">Low price series.</param>
   /// <param name="inClose">Close price series.</param>
   /// <param name="optInFastK_Period">Time period for building the Fast-K line (default 8; range 1..100000;
   /// <c>int.MinValue</c> selects the default).</param>
   /// <param name="optInEMAPeriod">Period of each of the two smoothing passes (default 5; range 1..100000;
   /// <c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Premier Stochastic Oscillator, -1 to +1. Must hold at least <c>endIdx -
   /// max(startIdx, PsoLookback(...)) + 1</c> values, and never be empty: an
   /// empty span is an absent output.</param>
   /// <returns>The range written: <c>BegIdx</c> is the first bar with a value,
   /// <c>Count</c> how many were written.</returns>
   /// <exception cref="System.ArgumentOutOfRangeException"><c>startIdx</c> or <c>endIdx</c> is negative or above
   /// <see cref="Core.IndexMax"/>, or <c>endIdx &lt; startIdx</c>.</exception>
   /// <exception cref="System.ArgumentException">
   /// One of the following, checked before anything is written, so a rejected
   /// call leaves every buffer untouched:
   /// <list type="bullet">
   /// <item><description>An optional parameter is outside its documented range.</description></item>
   /// <item><description>A span is too short for the range requested: any input this function
   /// <i>declares</i> that does not reach <c>endIdx</c>, or an output that
   /// cannot hold the values produced. Declared, not read: a few candlestick
   /// patterns take an OHLC series they never index, and it is required all the
   /// same. A null array arrives as an empty span, and an empty span is an
   /// absent argument: for an input, or an output that cannot be declined, it is
   /// rejected even when the call would produce nothing.</description></item>
   /// <item><description>Two outputs overlap or are one array
   /// (<see href="https://ta-lib.org/spec/errors/#rb6">rule rB6</see>), or an
   /// output overlaps an input. An output and a real input never share an
   /// element type in this overload, so the two can never be the same span:
   /// there is no in-place case to allow, and any overlap of their byte ranges
   /// is rejected.</description></item>
   /// </list>
   /// </exception>
   /// <seealso cref="Core.Stochf(int, int, ReadOnlySpan{double}, ReadOnlySpan{double}, ReadOnlySpan{double}, int, int, MAType, Span{double}, Span{double})"/>
   /// <seealso cref="Core.Stoch(int, int, ReadOnlySpan{double}, ReadOnlySpan{double}, ReadOnlySpan{double}, int, int, MAType, int, MAType, Span{double}, Span{double})"/>
   /// <seealso cref="Core.Smi(int, int, ReadOnlySpan{double}, ReadOnlySpan{double}, ReadOnlySpan{double}, int, int, int, int, Span{double}, Span{double})"/>
   /// <seealso cref="Core.Willr(int, int, ReadOnlySpan{double}, ReadOnlySpan{double}, ReadOnlySpan{double}, int, Span{double})"/>
   public OutRange Pso( int startIdx,
                        int endIdx,
                        ReadOnlySpan<float> inHigh,
                        ReadOnlySpan<float> inLow,
                        ReadOnlySpan<float> inClose,
                        int optInFastK_Period,
                        int optInEMAPeriod,
                        Span<double> outReal )
   {
      int guardStart = ClampedStart(startIdx, endIdx, PsoLookback(optInFastK_Period, optInEMAPeriod));
      int guardInLen = guardStart < 0 ? 0 : endIdx + 1;
      int guardOutLen = guardStart < 0 || guardStart > endIdx ? 0 : endIdx - guardStart + 1;
