   /**** Streaming API *****/

   /// <summary>A live <c>PSO</c> stream: one value per closed bar, bit-identical to
   /// <c>PSO</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.PsoOpen"/>. There is no close and nothing to
   /// dispose — the handle is ordinary managed state, and an unreferenced handle
   /// is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class PsoStream
   {
      internal Core core;
      internal int optInFastK_Period;
      internal int optInEMAPeriod;
      internal double emaK;
      internal double emaBeta;
      internal double highest;
      internal double lowest;
      internal double ema1;
      internal double ema2;
      internal int trailingIdx;
      internal int highestIdx;
      internal int lowestIdx;
      internal int i;
      internal int today;
      internal int xMask;
      internal double[] x_inHigh = [];
      internal double[] x_inLow = [];
      internal double[] x_inClose = [];
      internal double cur_outReal;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal PsoStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Pso</c> reports over the same bars: the opener sets it
      /// to <c>(lookback, historyLen - lookback)</c>, every accepted <c>Update</c>
      /// adds one to the count — a rejected one changes nothing, and neither does
      /// <c>Peek</c> — and <c>Clone</c> carries it verbatim. A plain <c>Open</c>
      /// hands back only the last value, a subset of this range, because the caller
      /// chose not to take the fill.</para>
      /// <para>The last bar it can reach is <see cref="Core.IndexMax"/>; past that
      /// <c>Update</c> and <c>Advance</c> throw.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      /// <summary>Count one bar this stream was not fed: <see cref="OutRange"/> advances by
      /// one and nothing else moves.</summary>
      /// <remarks>
      /// <para><see cref="Value"/> keeps answering the previous output, which is this
      /// bar's output too. For a bar the caller leaves out: one an <c>Update</c>
      /// rejected and that will not be re-fed, or a session with no print. Without
      /// it two handles on one feed drift a bar apart when only one of them skips.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, the last one the batch tier
      /// can address and the last this handle will count. <c>Update</c> throws the
      /// same there.</para>
      /// </remarks>
      public void Advance()
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("PSO", "advance", RetCode.OutOfRangeEndIndex);
         outRangeCount++;
      }

      internal PsoStream( PsoStream other )
      {
         this.core = other.core;
         this.optInFastK_Period = other.optInFastK_Period;
         this.optInEMAPeriod = other.optInEMAPeriod;
         this.emaK = other.emaK;
         this.emaBeta = other.emaBeta;
         this.highest = other.highest;
         this.lowest = other.lowest;
         this.ema1 = other.ema1;
         this.ema2 = other.ema2;
         this.trailingIdx = other.trailingIdx;
         this.highestIdx = other.highestIdx;
         this.lowestIdx = other.lowestIdx;
         this.i = other.i;
         this.today = other.today;
         this.xMask = other.xMask;
         this.x_inHigh = new double[other.x_inHigh.Length];
         Array.Copy( other.x_inHigh, this.x_inHigh, other.x_inHigh.Length );
         this.x_inLow = new double[other.x_inLow.Length];
         Array.Copy( other.x_inLow, this.x_inLow, other.x_inLow.Length );
         this.x_inClose = new double[other.x_inClose.Length];
         Array.Copy( other.x_inClose, this.x_inClose, other.x_inClose.Length );
         this.cur_outReal = other.cur_outReal;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so nothing moves — <see cref="OutRange"/> included — and
      /// <see cref="Value"/> still answers the previous value. Re-feed the bar when
      /// a corrected value arrives, or call <see cref="Advance"/> to count it and
      /// carry on; two handles on one feed drift a bar apart if neither happens.
      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, which no re-feed clears: the
      /// handle has run out of index domain and only a shorter history can start a
      /// new one.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inHigh, double inLow, double inClose )
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("PSO", "update", RetCode.OutOfRangeEndIndex);
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) ) throw Core.NonFiniteBar("PSO", "update", !double.IsFinite(inHigh) ? nameof(inHigh) : !double.IsFinite(inLow) ? nameof(inLow) : nameof(inClose));
         core.PsoStepImpl(this, inHigh, inLow, inClose);
         outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.IndexMax"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <param name="inClose">This bar's close price.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public double Peek( double inHigh, double inLow, double inClose )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) || !double.IsFinite(inClose) ) throw Core.NonFiniteBar("PSO", "peek", !double.IsFinite(inHigh) ? nameof(inHigh) : !double.IsFinite(inLow) ? nameof(inLow) : nameof(inClose));
         PsoStream sp = this;
         double tmp = 0.0;
         double fastK = 0.0;
         double nsk = 0.0;
         double cur_outReal = 0.0;
         double ema1 = sp.ema1;
         double ema2 = sp.ema2;
         double highest = sp.highest;
         int highestIdx = sp.highestIdx;
         int i = sp.i;
         double lowest = sp.lowest;
         int lowestIdx = sp.lowestIdx;
         int pkSlot0 = -1;
         double pkVal0 = 0.0;
         int pkSlot1 = -1;
         double pkVal1 = 0.0;
         int pkSlot2 = -1;
         double pkVal2 = 0.0;
         pkSlot0 = sp.today & sp.xMask;
         pkVal0 = inHigh;
         pkSlot1 = sp.today & sp.xMask;
         pkVal1 = inLow;
         pkSlot2 = sp.today & sp.xMask;
         pkVal2 = inClose;
         /* Set the lowest low */
         tmp = ((sp.today & sp.xMask) != pkSlot1) ? sp.x_inLow[sp.today & sp.xMask] : pkVal1;
         if( lowestIdx < sp.trailingIdx ) {
            lowestIdx = sp.trailingIdx;
            lowest = ((lowestIdx & sp.xMask) != pkSlot1) ? sp.x_inLow[lowestIdx & sp.xMask] : pkVal1;
            i = lowestIdx;
            while( ++i <= sp.today ) {
               tmp = ((i & sp.xMask) != pkSlot1) ? sp.x_inLow[i & sp.xMask] : pkVal1;
               if( tmp < lowest ) {
                  lowestIdx = i;
                  lowest = tmp;
               }
            }
         } else if( tmp <= lowest ) {
            lowestIdx = sp.today;
            lowest = tmp;
         }
         /* Set the highest high */
         tmp = ((sp.today & sp.xMask) != pkSlot0) ? sp.x_inHigh[sp.today & sp.xMask] : pkVal0;
         if( highestIdx < sp.trailingIdx ) {
            highestIdx = sp.trailingIdx;
            highest = ((highestIdx & sp.xMask) != pkSlot0) ? sp.x_inHigh[highestIdx & sp.xMask] : pkVal0;
            i = highestIdx;
            while( ++i <= sp.today ) {
               tmp = ((i & sp.xMask) != pkSlot0) ? sp.x_inHigh[i & sp.xMask] : pkVal0;
               if( tmp > highest ) {
                  highestIdx = i;
                  highest = tmp;
               }
            }
         } else if( tmp >= highest ) {
            highestIdx = sp.today;
            highest = tmp;
         }
         if( !(Math.Abs(highest - lowest) <= 0.00000000000001 * (Math.Abs(highest) + Math.Abs(lowest))) ) {
            fastK = ((((sp.today & sp.xMask) != pkSlot2) ? sp.x_inClose[sp.today & sp.xMask] : pkVal2) - lowest) / (highest - lowest) * 100.0;
         } else {
            fastK = 50.0;
         }
         nsk = 0.1 * (fastK - 50.0);
         ema1 = Math.FusedMultiplyAdd(sp.emaBeta, ema1, sp.emaK * nsk);
         ema2 = Math.FusedMultiplyAdd(sp.emaBeta, ema2, sp.emaK * ema1);
         cur_outReal = Math.Tanh(0.5 * ema2);
         return cur_outReal;
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public PsoStream Clone()
      {
         return new PsoStream(this);
      }
   }

   private void PsoStepImpl( PsoStream sp, double inHigh, double inLow, double inClose )
   {
      double tmp = 0.0;
      double fastK = 0.0;
      double nsk = 0.0;
      sp.x_inHigh[sp.today & sp.xMask] = inHigh;
      sp.x_inLow[sp.today & sp.xMask] = inLow;
      sp.x_inClose[sp.today & sp.xMask] = inClose;
      /* Set the lowest low */
      tmp = sp.x_inLow[sp.today & sp.xMask];
      if( sp.lowestIdx < sp.trailingIdx ) {
         sp.lowestIdx = sp.trailingIdx;
         sp.lowest = sp.x_inLow[sp.lowestIdx & sp.xMask];
         sp.i = sp.lowestIdx;
         while( ++sp.i <= sp.today ) {
            tmp = sp.x_inLow[sp.i & sp.xMask];
            if( tmp < sp.lowest ) {
               sp.lowestIdx = sp.i;
               sp.lowest = tmp;
            }
         }
      } else if( tmp <= sp.lowest ) {
         sp.lowestIdx = sp.today;
         sp.lowest = tmp;
      }
      /* Set the highest high */
      tmp = sp.x_inHigh[sp.today & sp.xMask];
      if( sp.highestIdx < sp.trailingIdx ) {
         sp.highestIdx = sp.trailingIdx;
         sp.highest = sp.x_inHigh[sp.highestIdx & sp.xMask];
         sp.i = sp.highestIdx;
         while( ++sp.i <= sp.today ) {
            tmp = sp.x_inHigh[sp.i & sp.xMask];
            if( tmp > sp.highest ) {
               sp.highestIdx = sp.i;
               sp.highest = tmp;
            }
         }
      } else if( tmp >= sp.highest ) {
         sp.highestIdx = sp.today;
         sp.highest = tmp;
      }
      if( !(Math.Abs(sp.highest - sp.lowest) <= 0.00000000000001 * (Math.Abs(sp.highest) + Math.Abs(sp.lowest))) ) {
         fastK = (sp.x_inClose[sp.today & sp.xMask] - sp.lowest) / (sp.highest - sp.lowest) * 100.0;
      } else {
         fastK = 50.0;
      }
      nsk = 0.1 * (fastK - 50.0);
      sp.ema1 = Math.FusedMultiplyAdd(sp.emaBeta, sp.ema1, sp.emaK * nsk);
      sp.ema2 = Math.FusedMultiplyAdd(sp.emaBeta, sp.ema2, sp.emaK * sp.ema1);
      sp.cur_outReal = Math.Tanh(0.5 * sp.ema2);
      sp.trailingIdx = sp.trailingIdx + 1;
      sp.today = sp.today + 1;
   }

   private RetCode PsoOpenImpl( PsoStream sp, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInFastK_Period, int optInEMAPeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double emaK = 0;
      double emaBeta = 0;
      double highest = 0;
      double lowest = 0;
      double tmp = 0;
      double fastK = 0;
      double nsk = 0;
      double ema1 = 0;
      double ema2 = 0;
      double sum1 = 0;
      double sum2 = 0;
      int lookbackTotal = 0;
      int lookbackEMA = 0;
      int today = 0;
      int trailingIdx = 0;
      int highestIdx = 0;
      int lowestIdx = 0;
      int i = 0;
      int outIdx = 0;
      int nBar = 0;
      int n2 = 0;
      int historyLen = inHigh.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > IndexMax + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inLow.Length != inHigh.Length || inClose.Length != inHigh.Length ) {
         return RetCode.BadParam;
      }
      if( optInFastK_Period == int.MinValue ) {
         optInFastK_Period = 8;
      } else if( optInFastK_Period < 1 || optInFastK_Period > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInEMAPeriod == int.MinValue ) {
         optInEMAPeriod = 5;
      } else if( optInEMAPeriod < 1 || optInEMAPeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      lookbackTotal = PsoLookback(optInFastK_Period, optInEMAPeriod);
      /* Move up the start index if there is not
       * enough initial data.
       */
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      /* Make sure there is still something to evaluate. */
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      outBegIdx = startIdx;
      /* Leibfarth's pipeline in one pass: a Fast-K window, the affine step that
       * centres it on zero, two EMA passes and the squash.
       *
       * The affine step comes BEFORE the smoothing, as the article's listing
       * spells it. Moving it after is equal in real arithmetic and differs by up
       * to 6.0e-16 absolute in doubles, which no golden at a sane tolerance can
       * see; only the composite gate against TA_STOCHF + TA_EMA + TA_EMA can.
       *
       * Each pass seeds the way ema.c does -- a simple average of that pass's
       * first optInEMAPeriod inputs, summed from 0.0 in production order -- so
       * the result is bit-identical to that composed chain. The stage boundary
       * below is the callee LOOKBACK, not (period-1), so that a warm
       * TA_SetUnstablePeriod(TA_FUNC_UNST_EMA) folds in: the second pass then
       * seeds from the values the first would have published, exactly as the
       * composed form does.
       *
       * At optInEMAPeriod == 1 ema.c takes an explicit copy path, because its
       * recursion at a k of 1.0 and a beta of 0.0 does not keep the sign of a
       * -0.0 input. The recursion below is left to run instead: its input is
       * 0.1*(fastK - 50.0), and x - x is +0.0 in every rounding mode, so -0.0
       * cannot reach it. The composite gate runs 5/1 and compares bitwise.
       */
      emaBeta = (double)(optInEMAPeriod - 1) / (double)(optInEMAPeriod + 1);
      emaK = 1.0 - emaBeta;
      emaBeta = 1.0 - emaK;
      lookbackEMA = EmaLookback(optInEMAPeriod);
      ema1 = 0.0;
      ema2 = 0.0;
      sum1 = 0.0;
      sum2 = 0.0;
      highest = 0.0;
      lowest = 0.0;
      highestIdx = -1;
      lowestIdx = -1;
      /* The first bar carrying a full Fast-K window. */
      trailingIdx = startIdx - lookbackTotal;
      today = trailingIdx + (optInFastK_Period - 1);
      nBar = 0;
      /* Warm-up. Runs through startIdx inclusive: the last pass here is the one
       * that completes the second pass's seed, so it produces the first output.
       */
      while( today <= startIdx ) {
         /* Set the lowest low */
         tmp = inLow[today];
         if( lowestIdx < trailingIdx ) {
            lowestIdx = trailingIdx;
            lowest = inLow[lowestIdx];
            i = lowestIdx;
            while( ++i <= today ) {
               tmp = inLow[i];
               if( tmp < lowest ) {
                  lowestIdx = i;
                  lowest = tmp;
               }
            }
         } else if( tmp <= lowest ) {
            lowestIdx = today;
            lowest = tmp;
         }
         /* Set the highest high */
         tmp = inHigh[today];
         if( highestIdx < trailingIdx ) {
            highestIdx = trailingIdx;
            highest = inHigh[highestIdx];
            i = highestIdx;
            while( ++i <= today ) {
               tmp = inHigh[i];
               if( tmp > highest ) {
                  highestIdx = i;
                  highest = tmp;
               }
            }
         } else if( tmp >= highest ) {
            highestIdx = today;
            highest = tmp;
         }
         /* Fast-K, spelled as stochf.c spells it: divide by the range itself and
          * scale by 100.0 after, guarded by the very expression the division
          * uses, against ITS OWN two extremes rather than a fixed constant
          * (issue #253).
          *
          * Where STOCHF answers 0.0 on a flat window, PSO answers 50.0, the
          * Fast-K midpoint, so that a flat market reads PSO 0 instead of
          * -tanh(2.5) = -0.9866, a near-extreme oversold reading that nothing in
          * the window supports (#473 Q4, the neutral-point rule of #112).
          */
         if( !(Math.Abs(highest - lowest) <= 0.00000000000001 * (Math.Abs(highest) + Math.Abs(lowest))) ) {
            fastK = (inClose[today] - lowest) / (highest - lowest) * 100.0;
         } else {
            fastK = 50.0;
         }
         nsk = 0.1 * (fastK - 50.0);
         /* Pass 1, over the normalised Fast-K. */
         if( nBar < optInEMAPeriod ) {
            sum1 = sum1 + nsk;
            if( nBar == optInEMAPeriod - 1 ) {
               ema1 = sum1 / optInEMAPeriod;
            }
         } else {
            ema1 = Math.FusedMultiplyAdd(emaBeta, ema1, emaK * nsk);
         }
         /* Pass 2, over what pass 1 publishes.
          *
          * The stage counter is compared BEFORE it is subtracted, never after.
          * Writing this as `n2 = nBar - lookbackEMA; if( n2 >= 0 )` is correct in
          * C, where the counters are signed, and broken everywhere else: the Rust
          * backend renders them as usize, so the subtraction underflows for the
          * first lookbackEMA bars -- a panic in a debug build and a wrap in
          * release (the lesson smi.c records).
          */
         if( nBar >= lookbackEMA ) {
            n2 = nBar - lookbackEMA;
            if( n2 < optInEMAPeriod ) {
               sum2 = sum2 + ema1;
               if( n2 == optInEMAPeriod - 1 ) {
                  ema2 = sum2 / optInEMAPeriod;
               }
            } else {
               ema2 = Math.FusedMultiplyAdd(emaBeta, ema2, emaK * ema1);
            }
         }
         nBar = nBar + 1;
         trailingIdx = trailingIdx + 1;
         today = today + 1;
      }
      /* tanh(ss/2) rather than the published (e^ss - 1)/(e^ss + 1): the same
       * function, equal within 2.2e-16 on normal data, exactly odd and well
       * conditioned at zero. TA-Lib does not validate that a close lies inside
       * its bar, so ss is only bounded by [-5, 5] on well-formed input; the
       * literal form emits NaN from a successful call once ss exceeds 709.78,
       * which the house rule of #112 forbids (#473 Q3).
       */
      outReal[0 * outStride] = Math.Tanh(0.5 * ema2);
      outIdx = 1;
      /* Stable zone. Both passes are pure recursions from here on. */
      while( today <= endIdx ) {
         /* Set the lowest low */
         tmp = inLow[today];
         if( lowestIdx < trailingIdx ) {
            lowestIdx = trailingIdx;
            lowest = inLow[lowestIdx];
            i = lowestIdx;
            while( ++i <= today ) {
               tmp = inLow[i];
               if( tmp < lowest ) {
                  lowestIdx = i;
                  lowest = tmp;
               }
            }
         } else if( tmp <= lowest ) {
            lowestIdx = today;
            lowest = tmp;
         }
         /* Set the highest high */
         tmp = inHigh[today];
         if( highestIdx < trailingIdx ) {
            highestIdx = trailingIdx;
            highest = inHigh[highestIdx];
            i = highestIdx;
            while( ++i <= today ) {
               tmp = inHigh[i];
               if( tmp > highest ) {
                  highestIdx = i;
                  highest = tmp;
               }
            }
         } else if( tmp >= highest ) {
            highestIdx = today;
            highest = tmp;
         }
         if( !(Math.Abs(highest - lowest) <= 0.00000000000001 * (Math.Abs(highest) + Math.Abs(lowest))) ) {
            fastK = (inClose[today] - lowest) / (highest - lowest) * 100.0;
         } else {
            fastK = 50.0;
         }
         nsk = 0.1 * (fastK - 50.0);
         ema1 = Math.FusedMultiplyAdd(emaBeta, ema1, emaK * nsk);
         ema2 = Math.FusedMultiplyAdd(emaBeta, ema2, emaK * ema1);
         outReal[outIdx * outStride] = Math.Tanh(0.5 * ema2);
         outIdx = outIdx + 1;
         trailingIdx = trailingIdx + 1;
         today = today + 1;
      }
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      int capX = today - trailingIdx + 1;
      if( capX < 1 || capX > historyLen ) {
         return RetCode.InternalError;
      }
      int physX = 1;
      while( physX < capX ) {
         physX <<= 1;
      }
      double[] capX_inHigh = new double[physX];
      double[] capX_inLow = new double[physX];
      double[] capX_inClose = new double[physX];
      for( int fillJ = historyLen - capX; fillJ < historyLen; fillJ++ ) {
         capX_inHigh[fillJ & (physX - 1)] = inHigh[fillJ];
         capX_inLow[fillJ & (physX - 1)] = inLow[fillJ];
         capX_inClose[fillJ & (physX - 1)] = inClose[fillJ];
      }
      sp.optInFastK_Period = optInFastK_Period;
      sp.optInEMAPeriod = optInEMAPeriod;
      sp.emaK = emaK;
      sp.emaBeta = emaBeta;
      sp.highest = highest;
      sp.lowest = lowest;
      sp.ema1 = ema1;
      sp.ema2 = ema2;
      sp.trailingIdx = trailingIdx;
      sp.highestIdx = highestIdx;
      sp.lowestIdx = lowestIdx;
      sp.i = i;
      sp.today = today;
      sp.xMask = physX - 1;
      sp.x_inHigh = capX_inHigh;
      sp.x_inLow = capX_inLow;
      sp.x_inClose = capX_inClose;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* PsoOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal PsoStream PsoOpenAndFillInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInFastK_Period, int optInEMAPeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      PsoStream sp = new PsoStream(this);
      RetCode retCode = PsoOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInFastK_Period, optInEMAPeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("PSO", "openAndFill", nameof(inHigh), inHigh.Length, startIdx, PsoLookback(optInFastK_Period, optInEMAPeriod));
      }
      throw StreamFailure("PSO", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind PsoOpen (composition seam). */
   internal PsoStream PsoOpenInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int startIdx, int optInFastK_Period, int optInEMAPeriod )
   {
      PsoStream sp = new PsoStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = PsoOpenImpl(sp, inHigh, inLow, inClose, startIdx, optInFastK_Period, optInEMAPeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("PSO", "open", nameof(inHigh), inHigh.Length, startIdx, PsoLookback(optInFastK_Period, optInEMAPeriod));
      }
      throw StreamFailure("PSO", "open", retCode);
   }

   /// <summary>Open a live <c>PSO</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="PsoStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>PSO</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>PsoLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>PsoOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inHigh">High price series. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price series. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price series. The warm-up history, oldest bar first.</param>
   /// <param name="optInFastK_Period">As in the batch call; see <see cref="PsoLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInEMAPeriod">As in the batch call; see <see cref="PsoLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>PsoLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public PsoStream PsoOpen( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInFastK_Period, int optInEMAPeriod )
   {
      if( inHigh.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "PSO open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "PSO open: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TALibArgumentException("PSO open: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TALibArgumentException("PSO open: inClose is empty", nameof(inClose), RetCode.BadParam);
      RequireHistoryLength("PSO", "open", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("PSO", "open", "inClose", inClose.Length, inHigh.Length);
      return PsoOpenInternal(inHigh, inLow, inClose, 0, optInFastK_Period, optInEMAPeriod);
   }

   /// <summary><c>PsoOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>PSO</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - PsoLookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="PsoStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inHigh">High price series. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price series. The warm-up history, oldest bar first.</param>
   /// <param name="inClose">Close price series. The warm-up history, oldest bar first.</param>
   /// <param name="optInFastK_Period">As in the batch call; see <see cref="PsoLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="optInEMAPeriod">As in the batch call; see <see cref="PsoLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Premier Stochastic Oscillator, -1 to +1. Must hold at least <c>historyLen
   /// - PsoLookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>PsoLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public PsoStream PsoOpenAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, ReadOnlySpan<double> inClose, int optInFastK_Period, int optInEMAPeriod, Span<double> outReal )
   {
      if( inHigh.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "PSO openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "PSO openAndFill: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TALibArgumentException("PSO openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      if( inClose.IsEmpty ) throw new TALibArgumentException("PSO openAndFill: inClose is empty", nameof(inClose), RetCode.BadParam);
      int guardOutLen = OpenFillCount("PSO", "openAndFill", inHigh.Length, PsoLookback(optInFastK_Period, optInEMAPeriod));
      RequireHistoryLength("PSO", "openAndFill", "inLow", inLow.Length, inHigh.Length);
      RequireHistoryLength("PSO", "openAndFill", "inClose", inClose.Length, inHigh.Length);
      RequireFillLength("PSO", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( SameBuffer(outReal, inHigh) || SameBuffer(outReal, inLow) || SameBuffer(outReal, inClose) ) {
         throw StreamFailure("PSO", "openAndFill", RetCode.BadParam);
      }
      if( guardOutLen > 0 && ( outReal.Overlaps(inHigh) || outReal.Overlaps(inLow) || outReal.Overlaps(inClose) ) ) {
         throw StreamFailure("PSO", "openAndFill", RetCode.BadParam);
      }
      return PsoOpenAndFillInternal(inHigh, inLow, inClose, 0, optInFastK_Period, optInEMAPeriod, out _, out _, outReal);
   }
