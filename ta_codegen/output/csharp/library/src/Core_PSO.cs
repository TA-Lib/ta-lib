   /// <seealso cref="Core.Willr(int, int, ReadOnlySpan{double}, ReadOnlySpan{double}, ReadOnlySpan{double}, int, Span{double})"/>
   public OutRange Pso( int startIdx,
                        int endIdx,
                        ReadOnlySpan<double> inHigh,
                        ReadOnlySpan<double> inLow,
                        ReadOnlySpan<double> inClose,
                        int optInFastK_Period,
                        int optInEMAPeriod,
                        Span<double> outReal )
   {
      int guardStart = ClampedStart(startIdx, endIdx, PsoLookback(optInFastK_Period, optInEMAPeriod));
      int guardInLen = guardStart < 0 ? 0 : endIdx + 1;
      int guardOutLen = guardStart < 0 || guardStart > endIdx ? 0 : endIdx - guardStart + 1;
      RequireLength("PSO", "inHigh", inHigh.Length, guardInLen);
      RequireLength("PSO", "inLow", inLow.Length, guardInLen);
      RequireLength("PSO", "inClose", inClose.Length, guardInLen);
      if( guardStart >= 0 ) RequirePresent("PSO", "outReal", outReal.Length);
      RequireLength("PSO", "outReal", outReal.Length, guardOutLen);
      RetCode retCode = PsoImpl(startIdx, endIdx, inHigh, inLow, inClose, optInFastK_Period, optInEMAPeriod, out int outBegIdx, out int outNBElement, outReal);
      if( retCode != RetCode.Success ) {
