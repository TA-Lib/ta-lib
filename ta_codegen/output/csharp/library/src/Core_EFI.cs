      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public EFI_Stream Clone()
      {
         return new EFI_Stream(this);
      }
   }

   internal void EFI_StreamStep( EFI_Stream sp, double inClose, double inVolume )
   {
      if( sp.optInTimePeriod == 1 ) {
         double force = 0.0;
         force = (inClose - sp.prevClose) * inVolume;
         sp.prevClose = inClose;
         sp.cur_outReal = force;
      } else {
         double force = 0.0;
         force = (inClose - sp.prevClose) * inVolume;
         sp.prevClose = inClose;
         sp.prevMA = Math.FusedMultiplyAdd(force - sp.prevMA, sp.optInK_1, sp.prevMA);
         sp.cur_outReal = sp.prevMA;
      }
   }

   private RetCode EFI_OpenPass( EFI_Stream sp, ReadOnlySpan<double> inClose, ReadOnlySpan<double> inVolume, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      int historyLen = inClose.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 || inVolume.Length != inClose.Length ) {
         return RetCode.BadParam;
      }
      if( historyLen > MAX_INDEX + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 13;
      } else if( optInTimePeriod < 1 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInTimePeriod == 1 ) {
         double optInK_1 = 0;
         double tempReal = 0;
         double prevMA = 0;
         double prevClose = 0;
         double force = 0;
         int i = 0;
         int today = 0;
         int outIdx = 0;
         int lookbackTotal = 0;
         optInK_1 = 2.0 / (double)(optInTimePeriod + 1);
         /* Alexander Elder's Force Index (Trading for a Living, 1993): the one-bar
          * close-to-close move weighted by that bar's volume, then smoothed with an
          * EMA. Elder's 2-period reading is the short-term form and 13 the
          * intermediate-term one -- that is the parameter, not a second formula.
          *
          *    force[t] = ( close[t] - close[t-1] ) * volume[t]
          *    EFI      = EMA( force, optInTimePeriod )
          *
          * The arithmetic below is ema.c's with inReal[t] replaced by force[t], kept
          * in exactly that shape on purpose: the seed accumulates from 0.0 in the
          * same order, and the recurrence is (x - prevMA)*k + prevMA rather than the
          * algebraically equal k*x + (1-k)*prevMA. That order IS the bit-exactness
          * contract against the composed reference in test_composite.c -- MOM, then
          * MULT, then EMA -- so do not tidy it. TRIX carries the same warning.
          *
          * Nothing on the data path divides by an input, so issue #112 is satisfied
          * structurally: a flat close gives force exactly 0.0 and output exactly
          * 0.0, and zero volume likewise. The only division is by the period, a
          * positive integer parameter.
          *
          * prevClose is carried in a scalar rather than re-read from inClose[t-1]
          * because the C API allows outReal to alias an input: at bar t the slot
          * holding close[t-1] may already have been overwritten by the output
          * written a bar earlier. cmou.c carries its trailing value for the same
          * reason.
          */
         /* Identify the minimum number of price bar needed
          * to calculate at least one output.
          */
         lookbackTotal = EFI_Lookback(optInTimePeriod);
         /* Move up the start index if there is not
          * enough initial data.
          */
         if( startIdx < lookbackTotal ) {
            startIdx = lookbackTotal;
         }
         /* Make sure there is still something to evaluate. */
         if( startIdx > endIdx ) {
            outBegIdx = 0;
            outNBElement = 0;
            return RetCode.InsufficientHistory ;
         }
         /* No smoothing at a period of 1: the output is the raw Force Index.
          * Explicit for the reason spelled out in ema.c -- at period 1 optInK_1 is
          * exactly 1.0, so the recursion reduces to (x-prev)+prev, which returns x
          * only while consecutive values stay within a factor of two of each other.
          * Force values swing by orders of magnitude, far more than the prices EMA
          * warns about.
          */
         outBegIdx = startIdx;
         outIdx = 0;
         today = startIdx;
         prevClose = inClose[today - 1];
         while( today <= endIdx ) {
            force = (inClose[today] - prevClose) * inVolume[today];
            prevClose = inClose[today];
            outReal[outIdx * outStride] = force;
            outIdx = outIdx + 1;
            today = today + 1;
         }
         outNBElement = outIdx;
         /* Capture the live batch state into the handle. */
         sp.optInTimePeriod = optInTimePeriod;
         sp.prevClose = prevClose;
         sp.optInK_1 = optInK_1;
         sp.prevMA = prevMA;
         sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
         return RetCode.Success;
      } else {
         double optInK_1 = 0;
         double tempReal = 0;
         double prevMA = 0;
         double prevClose = 0;
         double force = 0;
         int i = 0;
         int today = 0;
         int outIdx = 0;
         int lookbackTotal = 0;
         optInK_1 = 2.0 / (double)(optInTimePeriod + 1);
         /* Alexander Elder's Force Index (Trading for a Living, 1993): the one-bar
          * close-to-close move weighted by that bar's volume, then smoothed with an
          * EMA. Elder's 2-period reading is the short-term form and 13 the
          * intermediate-term one -- that is the parameter, not a second formula.
          *
          *    force[t] = ( close[t] - close[t-1] ) * volume[t]
          *    EFI      = EMA( force, optInTimePeriod )
          *
          * The arithmetic below is ema.c's with inReal[t] replaced by force[t], kept
          * in exactly that shape on purpose: the seed accumulates from 0.0 in the
          * same order, and the recurrence is (x - prevMA)*k + prevMA rather than the
          * algebraically equal k*x + (1-k)*prevMA. That order IS the bit-exactness
          * contract against the composed reference in test_composite.c -- MOM, then
          * MULT, then EMA -- so do not tidy it. TRIX carries the same warning.
          *
          * Nothing on the data path divides by an input, so issue #112 is satisfied
          * structurally: a flat close gives force exactly 0.0 and output exactly
          * 0.0, and zero volume likewise. The only division is by the period, a
          * positive integer parameter.
          *
          * prevClose is carried in a scalar rather than re-read from inClose[t-1]
          * because the C API allows outReal to alias an input: at bar t the slot
          * holding close[t-1] may already have been overwritten by the output
          * written a bar earlier. cmou.c carries its trailing value for the same
          * reason.
          */
         /* Identify the minimum number of price bar needed
          * to calculate at least one output.
          */
         lookbackTotal = EFI_Lookback(optInTimePeriod);
         /* Move up the start index if there is not
          * enough initial data.
          */
         if( startIdx < lookbackTotal ) {
            startIdx = lookbackTotal;
         }
         /* Make sure there is still something to evaluate. */
         if( startIdx > endIdx ) {
            outBegIdx = 0;
            outNBElement = 0;
            return RetCode.InsufficientHistory ;
         }
         /* No smoothing at a period of 1: the output is the raw Force Index.
          * Explicit for the reason spelled out in ema.c -- at period 1 optInK_1 is
          * exactly 1.0, so the recursion reduces to (x-prev)+prev, which returns x
          * only while consecutive values stay within a factor of two of each other.
          * Force values swing by orders of magnitude, far more than the prices EMA
          * warns about.
          */
         outBegIdx = startIdx;
         /* The first EMA value is a simple average of the first 'period' force
          * values; it then seeds the recursion. This is ema.c's CLASSIC seeding
          * applied to the force series rather than to the input array.
          *
          * TA_GetCompatibility() is deliberately NOT consulted. ema.c still carries
          * a TA_COMPATIBILITY_METASTOCK seeding arm, but that capability is being
          * deprecated: it is preserved for the functions that already shipped with
          * it and dropped from new ones, and it is not reachable at all from the
          * Rust, Java and C# APIs, which expose no TA_SetCompatibility. Honouring it
          * here would make EFI's C output diverge from the other three backends for
          * a setting they cannot even read.
          */
         today = startIdx - lookbackTotal + 1;
         prevClose = inClose[today - 1];
         i = optInTimePeriod;
         tempReal = 0.0;
         while( i-- > 0 ) {
            force = (inClose[today] - prevClose) * inVolume[today];
            prevClose = inClose[today];
            tempReal += force;
            today = today + 1;
         }
         prevMA = tempReal / optInTimePeriod;
         while( today <= startIdx ) {
            force = (inClose[today] - prevClose) * inVolume[today];
            prevClose = inClose[today];
            prevMA = Math.FusedMultiplyAdd(force - prevMA, optInK_1, prevMA);
            today = today + 1;
         }
         outReal[0 * outStride] = prevMA;
         outIdx = 1;
         while( today <= endIdx ) {
            force = (inClose[today] - prevClose) * inVolume[today];
            prevClose = inClose[today];
            prevMA = Math.FusedMultiplyAdd(force - prevMA, optInK_1, prevMA);
            outReal[outIdx * outStride] = prevMA;
            outIdx = outIdx + 1;
            today = today + 1;
         }
         outNBElement = outIdx;
         /* Capture the live batch state into the handle. */
         sp.optInTimePeriod = optInTimePeriod;
         sp.prevClose = prevClose;
         sp.optInK_1 = optInK_1;
         sp.prevMA = prevMA;
         sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
         return RetCode.Success;
      }
   }

   private RetCode EFI_OpenImpl( EFI_Stream sp, ReadOnlySpan<double> inClose, ReadOnlySpan<double> inVolume, int startIdx, int optInTimePeriod )
   {
      double[] sink_outReal = new double[1];
      return EFI_OpenPass( sp, inClose, inVolume, startIdx, optInTimePeriod, out _, out _, sink_outReal, 0 );
   }

   private RetCode EFI_OpenAndFillImpl( EFI_Stream sp, ReadOnlySpan<double> inClose, ReadOnlySpan<double> inVolume, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      outBegIdx = 0;
      outNBElement = 0;
      if( outReal.Overlaps(inClose) || outReal.Overlaps(inVolume) ) {
         return RetCode.BadParam;
      }
      return EFI_OpenPass( sp, inClose, inVolume, 0, optInTimePeriod, out outBegIdx, out outNBElement, outReal, 1 );
   }

   private RetCode EFI_OpenAndFillInternalImpl( EFI_Stream sp, ReadOnlySpan<double> inClose, ReadOnlySpan<double> inVolume, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      return EFI_OpenPass(sp, inClose, inVolume, startIdx, optInTimePeriod, out outBegIdx, out outNBElement, outReal, 1);
   }

   /* EFI_OpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal EFI_Stream EFI_OpenAndFillInternal( ReadOnlySpan<double> inClose, ReadOnlySpan<double> inVolume, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      EFI_Stream sp = new EFI_Stream(this);
      RetCode retCode = EFI_OpenAndFillInternalImpl(sp, inClose, inVolume, startIdx, optInTimePeriod, out outBegIdx, out outNBElement, outReal);
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("EFI", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind EFI_Open (composition seam). */
   internal EFI_Stream EFI_OpenInternal( ReadOnlySpan<double> inClose, ReadOnlySpan<double> inVolume, int startIdx, int optInTimePeriod )
   {
      EFI_Stream sp = new EFI_Stream(this);
      RetCode retCode = EFI_OpenImpl(sp, inClose, inVolume, startIdx, optInTimePeriod);
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("EFI", "open", retCode);
   }

   /// <summary>Open a live <c>EFI</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="EFI_Stream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>EFI</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>EFI_Lookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>EFI_OpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inVolume">Volume of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="EFI_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>EFI_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentException">An input series is empty — which is what a null array becomes, since a
   /// span cannot be null.</exception>
   public EFI_Stream EFI_Open( ReadOnlySpan<double> inClose, ReadOnlySpan<double> inVolume, int optInTimePeriod )
   {
      if( inClose.IsEmpty ) throw new TaLibArgumentException("inClose is empty", nameof(inClose), RetCode.BadParam);
      if( inVolume.IsEmpty ) throw new TaLibArgumentException("inVolume is empty", nameof(inVolume), RetCode.BadParam);
      return EFI_OpenInternal(inClose, inVolume, 0, optInTimePeriod);
   }

   /// <summary><c>EFI_Open</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>EFI</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - EFI_Lookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="EFI_Stream.FillRange"/>.</para>
   /// </remarks>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inVolume">Volume of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="EFI_Lookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Smoothed force. Must hold at least <c>historyLen - EFI_Lookback(...)</c>
   /// values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>EFI_Lookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, or an output array aliases an input or another
   /// output.</exception>
   /// <exception cref="System.ArgumentException">An input series is empty, or an output overlaps an input or another
   /// output.</exception>
   public EFI_Stream EFI_OpenAndFill( ReadOnlySpan<double> inClose, ReadOnlySpan<double> inVolume, int optInTimePeriod, Span<double> outReal )
   {
      if( inClose.IsEmpty ) throw new TaLibArgumentException("inClose is empty", nameof(inClose), RetCode.BadParam);
      if( inVolume.IsEmpty ) throw new TaLibArgumentException("inVolume is empty", nameof(inVolume), RetCode.BadParam);
      EFI_Stream sp = new EFI_Stream(this);
      RetCode retCode = EFI_OpenAndFillImpl(sp, inClose, inVolume, optInTimePeriod, out int outBegIdx, out int outNBElement, outReal);
      sp.fillRange = new OutRange(outBegIdx, outNBElement);
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("EFI", "openAndFill", retCode);
   }
