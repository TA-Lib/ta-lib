      /// <para>It is what <c>Core.Efi</c> reports over the same bars: the opener sets it
      /// to <c>(lookback, historyLen - lookback)</c>, every accepted <c>Update</c>
      /// adds one to the count — a rejected one changes nothing, and neither does
      /// <c>Peek</c> — and <c>Clone</c> carries it verbatim. A plain <c>Open</c>
      /// hands back only the last value, a subset of this range, because the caller
      /// chose not to take the fill.</para>
      /// <para>The last bar it can reach is <see cref="Core.IndexMax"/>; past that
      /// <c>Update</c> and <c>Advance</c> throw.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      /// <summary>Count one bar this stream was not fed: <see cref="OutRange"/> advances by
      /// one and nothing else moves.</summary>
      /// <remarks>
      /// <para><see cref="Value"/> keeps answering the previous output, which is this
      /// bar's output too. For a bar the caller leaves out: one an <c>Update</c>
      /// rejected and that will not be re-fed, or a session with no print. Without
      /// it two handles on one feed drift a bar apart when only one of them skips.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, the last one the batch tier
      /// can address and the last this handle will count. <c>Update</c> throws the
      /// same there.</para>
      /// </remarks>
      public void Advance()
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("EFI", "advance", RetCode.OutOfRangeEndIndex);
         outRangeCount++;
      }

      internal EfiStream( EfiStream other )
      {
         this.core = other.core;
         this.optInTimePeriod = other.optInTimePeriod;
         this.prevClose = other.prevClose;
         this.emaBeta = other.emaBeta;
         this.optInK_1 = other.optInK_1;
         this.prevMA = other.prevMA;
         this.cur_outReal = other.cur_outReal;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so nothing moves — <see cref="OutRange"/> included — and
      /// <see cref="Value"/> still answers the previous value. Re-feed the bar when
      /// a corrected value arrives, or call <see cref="Advance"/> to count it and
      /// carry on; two handles on one feed drift a bar apart if neither happens.
      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, which no re-feed clears: the
      /// handle has run out of index domain and only a shorter history can start a
      /// new one.</para>
      /// </remarks>
      /// <param name="inClose">This bar's close price.</param>
      /// <param name="inVolume">This bar's volume.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inClose, double inVolume )
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("EFI", "update", RetCode.OutOfRangeEndIndex);
         if( !double.IsFinite(inClose) || !double.IsFinite(inVolume) ) throw Core.NonFiniteBar("EFI", "update", !double.IsFinite(inClose) ? nameof(inClose) : nameof(inVolume));
         core.EfiStepImpl(this, inClose, inVolume);
         outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.IndexMax"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inClose">This bar's close price.</param>
      /// <param name="inVolume">This bar's volume.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public double Peek( double inClose, double inVolume )
      {
         if( !double.IsFinite(inClose) || !double.IsFinite(inVolume) ) throw Core.NonFiniteBar("EFI", "peek", !double.IsFinite(inClose) ? nameof(inClose) : nameof(inVolume));
         EfiStream sp = this;
         double cur_outReal = 0.0;
         if( sp.optInTimePeriod == 1 ) {
            double force = 0.0;
            double prevClose = sp.prevClose;
            force = (inClose - prevClose) * inVolume;
            prevClose = inClose;
            cur_outReal = force;
         } else {
            double force = 0.0;
            double prevClose = sp.prevClose;
            double prevMA = sp.prevMA;
            force = (inClose - prevClose) * inVolume;
            prevClose = inClose;
            prevMA = Math.FusedMultiplyAdd(sp.emaBeta, prevMA, sp.optInK_1 * force);
            cur_outReal = prevMA;
         }
         return cur_outReal;
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public EfiStream Clone()
      {
         return new EfiStream(this);
      }
   }

   private void EfiStepImpl( EfiStream sp, double inClose, double inVolume )
   {
      if( sp.optInTimePeriod == 1 ) {
         double force = 0.0;
         force = (inClose - sp.prevClose) * inVolume;
         sp.prevClose = inClose;
         sp.cur_outReal = force;
      } else {
         double force = 0.0;
         force = (inClose - sp.prevClose) * inVolume;
         sp.prevClose = inClose;
         sp.prevMA = Math.FusedMultiplyAdd(sp.emaBeta, sp.prevMA, sp.optInK_1 * force);
         sp.cur_outReal = sp.prevMA;
      }
   }

   private RetCode EfiOpenImpl( EfiStream sp, ReadOnlySpan<double> inClose, ReadOnlySpan<double> inVolume, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      int historyLen = inClose.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > IndexMax + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inVolume.Length != inClose.Length ) {
         return RetCode.BadParam;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 13;
      } else if( optInTimePeriod < 1 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( optInTimePeriod == 1 ) {
         double emaBeta = 0;
         double optInK_1 = 0;
         double tempReal = 0;
         double prevMA = 0;
         double prevClose = 0;
         double force = 0;
         int i = 0;
         int today = 0;
         int outIdx = 0;
         int lookbackTotal = 0;
         /* Alexander Elder's Force Index (Trading for a Living, 1993): the one-bar
          * close-to-close move weighted by that bar's volume, then smoothed with an
          * EMA. Elder's 2-period reading is the short-term form and 13 the
          * intermediate-term one -- that is the parameter, not a second formula.
          *
          *    force[t] = ( close[t] - close[t-1] ) * volume[t]
          *    EFI      = EMA( force, optInTimePeriod )
          *
          * The arithmetic below is ema.c's with inReal[t] replaced by force[t], kept
          * in exactly that shape on purpose: the seed accumulates from 0.0 in the
          * same order, and the recurrence is k*x + beta*prevMA with ema.c's k and
          * beta. That order IS the bit-exactness contract against the composed
          * reference in test_composite.c -- MOM, then MULT, then EMA -- so do not
          * tidy it. TRIX carries the same warning.
          *
          * Nothing on the data path divides by an input, so issue #112 is satisfied
          * structurally: a flat close gives force exactly 0.0 and output exactly
          * 0.0, and zero volume likewise. The only division is by the period, a
          * positive integer parameter.
          *
          * prevClose is carried in a scalar rather than re-read from inClose[t-1]
          * because the C API allows outReal to alias an input: at bar t the slot
          * holding close[t-1] may already have been overwritten by the output
          * written a bar earlier. cmou.c carries its trailing value for the same
          * reason.
          */
         /* Identify the minimum number of price bar needed
          * to calculate at least one output.
          */
         lookbackTotal = EfiLookback(optInTimePeriod);
         /* After the lookback call: a double live across a call is saved and
          * restored around every fma call of the loops below, one more instruction
          * per bar.
          */
         emaBeta = (double)(optInTimePeriod - 1) / (double)(optInTimePeriod + 1);
         optInK_1 = 1.0 - emaBeta;
         if( emaBeta < 0.5 ) {
            emaBeta = 1.0 - optInK_1;
         }
         /* Move up the start index if there is not
          * enough initial data.
          */
         if( startIdx < lookbackTotal ) {
            startIdx = lookbackTotal;
         }
         /* Make sure there is still something to evaluate. */
         if( startIdx > endIdx ) {
            outBegIdx = 0;
            outNBElement = 0;
            return RetCode.InsufficientHistory ;
         }
         /* No smoothing at a period of 1: the output is the raw Force Index.
          * Explicit because the recursion, at a k of 1.0 and a beta of 0.0, does
          * not keep the sign of a -0.0 force: a down bar on zero volume.
          */
         outBegIdx = startIdx;
         outIdx = 0;
         today = startIdx;
         prevClose = inClose[today - 1];
         while( today <= endIdx ) {
            force = (inClose[today] - prevClose) * inVolume[today];
            prevClose = inClose[today];
            outReal[outIdx * outStride] = force;
            outIdx = outIdx + 1;
            today = today + 1;
         }
         outNBElement = outIdx;
         /* Capture the live batch state into the handle. */
         sp.optInTimePeriod = optInTimePeriod;
         sp.prevClose = prevClose;
         sp.emaBeta = emaBeta;
         sp.optInK_1 = optInK_1;
         sp.prevMA = prevMA;
         sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
         return RetCode.Success;
      } else {
         double emaBeta = 0;
         double optInK_1 = 0;
         double tempReal = 0;
         double prevMA = 0;
         double prevClose = 0;
         double force = 0;
         int i = 0;
         int today = 0;
         int outIdx = 0;
         int lookbackTotal = 0;
         /* Alexander Elder's Force Index (Trading for a Living, 1993): the one-bar
          * close-to-close move weighted by that bar's volume, then smoothed with an
          * EMA. Elder's 2-period reading is the short-term form and 13 the
          * intermediate-term one -- that is the parameter, not a second formula.
          *
          *    force[t] = ( close[t] - close[t-1] ) * volume[t]
          *    EFI      = EMA( force, optInTimePeriod )
          *
          * The arithmetic below is ema.c's with inReal[t] replaced by force[t], kept
          * in exactly that shape on purpose: the seed accumulates from 0.0 in the
          * same order, and the recurrence is k*x + beta*prevMA with ema.c's k and
          * beta. That order IS the bit-exactness contract against the composed
          * reference in test_composite.c -- MOM, then MULT, then EMA -- so do not
          * tidy it. TRIX carries the same warning.
          *
          * Nothing on the data path divides by an input, so issue #112 is satisfied
          * structurally: a flat close gives force exactly 0.0 and output exactly
          * 0.0, and zero volume likewise. The only division is by the period, a
          * positive integer parameter.
          *
          * prevClose is carried in a scalar rather than re-read from inClose[t-1]
          * because the C API allows outReal to alias an input: at bar t the slot
          * holding close[t-1] may already have been overwritten by the output
          * written a bar earlier. cmou.c carries its trailing value for the same
          * reason.
          */
         /* Identify the minimum number of price bar needed
          * to calculate at least one output.
          */
         lookbackTotal = EfiLookback(optInTimePeriod);
         /* After the lookback call: a double live across a call is saved and
          * restored around every fma call of the loops below, one more instruction
          * per bar.
          */
         emaBeta = (double)(optInTimePeriod - 1) / (double)(optInTimePeriod + 1);
         optInK_1 = 1.0 - emaBeta;
         if( emaBeta < 0.5 ) {
            emaBeta = 1.0 - optInK_1;
         }
         /* Move up the start index if there is not
          * enough initial data.
          */
         if( startIdx < lookbackTotal ) {
            startIdx = lookbackTotal;
         }
         /* Make sure there is still something to evaluate. */
         if( startIdx > endIdx ) {
            outBegIdx = 0;
            outNBElement = 0;
            return RetCode.InsufficientHistory ;
         }
         /* No smoothing at a period of 1: the output is the raw Force Index.
          * Explicit because the recursion, at a k of 1.0 and a beta of 0.0, does
          * not keep the sign of a -0.0 force: a down bar on zero volume.
          */
         outBegIdx = startIdx;
         /* The first EMA value is a simple average of the first 'period' force
          * values; it then seeds the recursion. This is ema.c's seeding applied
          * to the force series rather than to the input array.
          */
         today = startIdx - lookbackTotal + 1;
         prevClose = inClose[today - 1];
         i = optInTimePeriod;
         tempReal = 0.0;
         while( i-- > 0 ) {
            force = (inClose[today] - prevClose) * inVolume[today];
            prevClose = inClose[today];
            tempReal += force;
            today = today + 1;
         }
         prevMA = tempReal / optInTimePeriod;
         while( today <= startIdx ) {
            force = (inClose[today] - prevClose) * inVolume[today];
            prevClose = inClose[today];
            prevMA = Math.FusedMultiplyAdd(emaBeta, prevMA, optInK_1 * force);
            today = today + 1;
         }
         outReal[0 * outStride] = prevMA;
         outIdx = 1;
         while( today <= endIdx ) {
            force = (inClose[today] - prevClose) * inVolume[today];
            prevClose = inClose[today];
            prevMA = Math.FusedMultiplyAdd(emaBeta, prevMA, optInK_1 * force);
            outReal[outIdx * outStride] = prevMA;
            outIdx = outIdx + 1;
            today = today + 1;
         }
         outNBElement = outIdx;
         /* Capture the live batch state into the handle. */
         sp.optInTimePeriod = optInTimePeriod;
         sp.prevClose = prevClose;
         sp.emaBeta = emaBeta;
         sp.optInK_1 = optInK_1;
         sp.prevMA = prevMA;
         sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
         return RetCode.Success;
      }
   }

   /* EfiOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal EfiStream EfiOpenAndFillInternal( ReadOnlySpan<double> inClose, ReadOnlySpan<double> inVolume, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      EfiStream sp = new EfiStream(this);
      RetCode retCode = EfiOpenImpl(sp, inClose, inVolume, startIdx, optInTimePeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("EFI", "openAndFill", nameof(inClose), inClose.Length, startIdx, EfiLookback(optInTimePeriod));
      }
      throw StreamFailure("EFI", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind EfiOpen (composition seam). */
   internal EfiStream EfiOpenInternal( ReadOnlySpan<double> inClose, ReadOnlySpan<double> inVolume, int startIdx, int optInTimePeriod )
   {
      EfiStream sp = new EfiStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = EfiOpenImpl(sp, inClose, inVolume, startIdx, optInTimePeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("EFI", "open", nameof(inClose), inClose.Length, startIdx, EfiLookback(optInTimePeriod));
      }
      throw StreamFailure("EFI", "open", retCode);
   }

   /// <summary>Open a live <c>EFI</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="EfiStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>EFI</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>EfiLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>EfiOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inVolume">Volume of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="EfiLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>EfiLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public EfiStream EfiOpen( ReadOnlySpan<double> inClose, ReadOnlySpan<double> inVolume, int optInTimePeriod )
   {
      if( inClose.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inClose), "EFI open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inClose.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inClose), "EFI open: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( inVolume.IsEmpty ) throw new TALibArgumentException("EFI open: inVolume is empty", nameof(inVolume), RetCode.BadParam);
      RequireHistoryLength("EFI", "open", "inVolume", inVolume.Length, inClose.Length);
      return EfiOpenInternal(inClose, inVolume, 0, optInTimePeriod);
   }

   /// <summary><c>EfiOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>EFI</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - EfiLookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="EfiStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inClose">Close price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inVolume">Volume of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="EfiLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Smoothed force. Must hold at least <c>historyLen - EfiLookback(...)</c>
   /// values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>EfiLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public EfiStream EfiOpenAndFill( ReadOnlySpan<double> inClose, ReadOnlySpan<double> inVolume, int optInTimePeriod, Span<double> outReal )
   {
      if( inClose.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inClose), "EFI openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inClose.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inClose), "EFI openAndFill: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( inVolume.IsEmpty ) throw new TALibArgumentException("EFI openAndFill: inVolume is empty", nameof(inVolume), RetCode.BadParam);
      int guardOutLen = OpenFillCount("EFI", "openAndFill", inClose.Length, EfiLookback(optInTimePeriod));
      RequireHistoryLength("EFI", "openAndFill", "inVolume", inVolume.Length, inClose.Length);
      RequireFillLength("EFI", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( SameBuffer(outReal, inClose) || SameBuffer(outReal, inVolume) ) {
         throw StreamFailure("EFI", "openAndFill", RetCode.BadParam);
      }
      if( guardOutLen > 0 && ( outReal.Overlaps(inClose) || outReal.Overlaps(inVolume) ) ) {
         throw StreamFailure("EFI", "openAndFill", RetCode.BadParam);
      }
      return EfiOpenAndFillInternal(inClose, inVolume, 0, optInTimePeriod, out _, out _, outReal);
   }
