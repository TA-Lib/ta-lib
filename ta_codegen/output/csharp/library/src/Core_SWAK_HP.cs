      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, which no re-feed clears: the
      /// handle has run out of index domain and only a shorter history can start a
      /// new one.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inReal )
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("SWAK_HP", "update", RetCode.OutOfRangeEndIndex);
         if( !double.IsFinite(inReal) ) throw Core.NonFiniteBar("SWAK_HP", "update", nameof(inReal));
         core.SwakHpStepImpl(this, inReal);
         outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.IndexMax"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public double Peek( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.NonFiniteBar("SWAK_HP", "peek", nameof(inReal));
         SwakHpStream sp = this;
         double x0 = 0.0;
         double y = 0.0;
         double cur_outReal = 0.0;
         double x1 = sp.x1;
         double y1 = sp.y1;
         /* The evaluation order is the bit-exactness contract across backends:
          * the numerator as c0*(x0 - x1), then the a1 feedback. This row's a2 is
          * zero and the term is dropped rather than added, which is also what
          * fixes the sign of a zero result.
          */
         x0 = inReal;
         y = Math.FusedMultiplyAdd(sp.c0, x0 - x1, sp.a1 * y1);
         x1 = x0;
         y1 = y;
         cur_outReal = y;
         return cur_outReal;
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public SwakHpStream Clone()
      {
         return new SwakHpStream(this);
      }
   }

   private void SwakHpStepImpl( SwakHpStream sp, double inReal )
   {
      double x0 = 0.0;
      double y = 0.0;
      /* The evaluation order is the bit-exactness contract across backends:
       * the numerator as c0*(x0 - x1), then the a1 feedback. This row's a2 is
       * zero and the term is dropped rather than added, which is also what
       * fixes the sign of a zero result.
       */
      x0 = inReal;
      y = Math.FusedMultiplyAdd(sp.c0, x0 - sp.x1, sp.a1 * sp.y1);
      sp.x1 = x0;
      sp.y1 = y;
      sp.cur_outReal = y;
   }

   private RetCode SwakHpOpenImpl( SwakHpStream sp, ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      int i = 0;
      int outIdx = 0;
      int today = 0;
      int lookbackTotal = 0;
      double w = 0;
      double cw = 0;
      double a1p = 0;
      double c0 = 0;
      double a1 = 0;
      double x0 = 0;
      double x1 = 0;
      double y = 0;
      double y1 = 0;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > IndexMax + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 20;
      } else if( optInTimePeriod < 5 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      outBegIdx = 0;
      outNBElement = 0;
      lookbackTotal = SwakHpLookback(optInTimePeriod);
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      if( startIdx > endIdx ) {
         return RetCode.InsufficientHistory ;
      }
      /* The one-pole alpha (Ehlers, Stocks & Commodities January 2006, Figure 5).
       * The paper says this one "is computed exactly the same as it is for the
       * EMA" (p.5) -- meaning the cutoff-period formula below, not TA_EMA's
       * 2/(n+1). The paper's 360/P is a full turn, so 2*pi/P.
       *
       * The period range starts at 5 because of what this expression does below
       * it, not for taste: at P = 4, cos(w) is 6.1e-17 and `cos w + sin w - 1`
       * rounds to exactly 0.0, so a1p is 0, c0 and a1 are both 1, and the filter
       * degenerates into the integrator x - x[s]. At P = 2, cos(w) is -1 and c0
       * is 0, a dead filter. No contiguous range below 5 avoids both.
       */
      w = 2.0 * 3.141592653589793 / (double)optInTimePeriod;
      cw = Math.Cos(w);
      a1p = (cw + Math.Sin(w) - 1.0) / cw;
      /* The high-pass row: a (1, -1) numerator, so its DC gain is 0 and the line
       * is centred on zero rather than on price.
       */
      c0 = 1.0 - a1p / 2.0;
      a1 = 1.0 - a1p;
      today = startIdx - lookbackTotal;
      /* Start in the steady state of a constant input equal to the first bar: a
       * DC-gain-0 row answers 0 for a constant, so the output slot starts there
       * while the input slot holds the bar. The input slot is carried in a local
       * and never re-read from inReal, because outReal may alias it.
       */
      x1 = inReal[today];
      y1 = 0.0;
      /* Skip the unstable period: run the recurrence but publish nothing. */
      i = lookbackTotal;
      while( i != 0 ) {
         x0 = inReal[today];
         y = Math.FusedMultiplyAdd(c0, x0 - x1, a1 * y1);
         x1 = x0;
         y1 = y;
         today += 1;
         i -= 1;
      }
      outIdx = 0;
      while( today <= endIdx ) {
         /* The evaluation order is the bit-exactness contract across backends:
          * the numerator as c0*(x0 - x1), then the a1 feedback. This row's a2 is
          * zero and the term is dropped rather than added, which is also what
          * fixes the sign of a zero result.
          */
         x0 = inReal[today];
         y = Math.FusedMultiplyAdd(c0, x0 - x1, a1 * y1);
         x1 = x0;
         y1 = y;
         outReal[outIdx * outStride] = y;
         outIdx = outIdx + 1;
         today += 1;
      }
      outNBElement = outIdx;
      outBegIdx = startIdx;
      /* Capture the live batch state into the handle. */
      sp.optInTimePeriod = optInTimePeriod;
      sp.c0 = c0;
      sp.a1 = a1;
      sp.x1 = x1;
      sp.y1 = y1;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* SwakHpOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal SwakHpStream SwakHpOpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      SwakHpStream sp = new SwakHpStream(this);
      RetCode retCode = SwakHpOpenImpl(sp, inReal, startIdx, optInTimePeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("SWAK_HP", "openAndFill", nameof(inReal), inReal.Length, startIdx, SwakHpLookback(optInTimePeriod));
      }
      throw StreamFailure("SWAK_HP", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind SwakHpOpen (composition seam). */
   internal SwakHpStream SwakHpOpenInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod )
   {
      SwakHpStream sp = new SwakHpStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = SwakHpOpenImpl(sp, inReal, startIdx, optInTimePeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("SWAK_HP", "open", nameof(inReal), inReal.Length, startIdx, SwakHpLookback(optInTimePeriod));
      }
      throw StreamFailure("SWAK_HP", "open", retCode);
   }

   /// <summary>Open a live <c>SWAK_HP</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="SwakHpStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>SWAK_HP</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>SwakHpLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>SwakHpOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">The series to detrend; Ehlers' default is the bar midpoint <c>(H+L)/2</c>,
   /// which the caller passes as <c>TA_MEDPRICE</c> output. The warm-up history,
   /// oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="SwakHpLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>SwakHpLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public SwakHpStream SwakHpOpen( ReadOnlySpan<double> inReal, int optInTimePeriod )
   {
      if( inReal.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "SWAK_HP open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "SWAK_HP open: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      return SwakHpOpenInternal(inReal, 0, optInTimePeriod);
   }

   /// <summary><c>SwakHpOpen</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>SWAK_HP</c> produces over
   /// the same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - SwakHpLookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="SwakHpStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">The series to detrend; Ehlers' default is the bar midpoint <c>(H+L)/2</c>,
   /// which the caller passes as <c>TA_MEDPRICE</c> output. The warm-up history,
   /// oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="SwakHpLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">The detrended line, centred on zero. Must hold at least <c>historyLen -
   /// SwakHpLookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>SwakHpLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public SwakHpStream SwakHpOpenAndFill( ReadOnlySpan<double> inReal, int optInTimePeriod, Span<double> outReal )
   {
      if( inReal.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "SWAK_HP openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "SWAK_HP openAndFill: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      int guardOutLen = OpenFillCount("SWAK_HP", "openAndFill", inReal.Length, SwakHpLookback(optInTimePeriod));
      RequireFillLength("SWAK_HP", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( SameBuffer(outReal, inReal) ) {
         throw StreamFailure("SWAK_HP", "openAndFill", RetCode.BadParam);
      }
      if( guardOutLen > 0 && ( outReal.Overlaps(inReal) ) ) {
         throw StreamFailure("SWAK_HP", "openAndFill", RetCode.BadParam);
      }
      return SwakHpOpenAndFillInternal(inReal, 0, optInTimePeriod, out _, out _, outReal);
   }
