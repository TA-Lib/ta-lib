   /// <summary>One <c>ZIGZAG</c> output set, in batch output order.</summary>
   /// <remarks>
   /// <para>Equality is the compiler-generated record-struct equality, which compares
   /// each component with <see cref="System.Double.Equals(System.Double)"/>, not
   /// <c>==</c>: any two <c>NaN</c> payloads compare equal, and <c>0.0</c>
   /// equals <c>-0.0</c>. Compare
   /// <see cref="System.BitConverter.DoubleToInt64Bits(double)"/> per component
   /// when bit-level identity is what you mean.</para>
   /// </remarks>
   /// <param name="ZigZag">Price of the swing extreme currently being tracked.</param>
   /// <param name="Trend">+1 while the leg is up, -1 while it is down.</param>
   /// <param name="PivotIdx">Absolute index, into the input, of the bar that extreme sits on.</param>
   public readonly record struct ZigzagValue( double ZigZag, int Trend, int PivotIdx );

   /// <summary>A live <c>ZIGZAG</c> stream: one value per closed bar, bit-identical to
   /// <c>ZIGZAG</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.ZigzagOpen"/>. There is no close and nothing to
   /// dispose — the handle is ordinary managed state, and an unreferenced handle
   /// is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// <para>This indicator reports absolute bar indices. In the streaming tier they
   /// count bars fed to this stream rather than positions in an array — so treat
   /// an index as a position within this handle's own window, not as one you can
   /// compare against an index a different handle reported.</para>
   /// </remarks>
   public sealed class ZigzagStream
   {
      internal Core core;
      internal double optInSensitivity;
      internal int optInMinTrendLength;
      internal int trend;
      internal int pivotIdx;
      internal int barsSincePivot;
      internal int barIdx;
      internal double up;
      internal double dn;
      internal double pivot;
      internal double cur_outZigZag;
      internal int cur_outTrend;
      internal int cur_outPivotIdx;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal ZigzagStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Zigzag</c> reports over the same bars: the opener sets
      /// it to <c>(lookback, historyLen - lookback)</c>, every accepted
      /// <c>Update</c> adds one to the count — a rejected one changes nothing, and
      /// neither does <c>Peek</c> — and <c>Clone</c> carries it verbatim. A plain
      /// <c>Open</c> hands back only the last value, a subset of this range,
      /// because the caller chose not to take the fill.</para>
      /// <para>The last bar it can reach is <see cref="Core.IndexMax"/>; past that
      /// <c>Update</c> and <c>Advance</c> throw.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      /// <summary>Count one bar this stream was not fed: <see cref="OutRange"/> advances by
      /// one and nothing else moves.</summary>
      /// <remarks>
      /// <para><see cref="Value"/> keeps answering the previous output, which is this
      /// bar's output too. For a bar the caller leaves out: one an <c>Update</c>
      /// rejected and that will not be re-fed, or a session with no print. Without
      /// it two handles on one feed drift a bar apart when only one of them skips.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, the last one the batch tier
      /// can address and the last this handle will count. <c>Update</c> throws the
      /// same there.</para>
      /// </remarks>
      public void Advance()
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("ZIGZAG", "advance", RetCode.OutOfRangeEndIndex);
         outRangeCount++;
      }

      internal ZigzagStream( ZigzagStream other )
      {
         this.core = other.core;
         this.optInSensitivity = other.optInSensitivity;
         this.optInMinTrendLength = other.optInMinTrendLength;
         this.trend = other.trend;
         this.pivotIdx = other.pivotIdx;
         this.barsSincePivot = other.barsSincePivot;
         this.barIdx = other.barIdx;
         this.up = other.up;
         this.dn = other.dn;
         this.pivot = other.pivot;
         this.cur_outZigZag = other.cur_outZigZag;
         this.cur_outTrend = other.cur_outTrend;
         this.cur_outPivotIdx = other.cur_outPivotIdx;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so nothing moves — <see cref="OutRange"/> included — and
      /// <see cref="Value"/> still answers the previous value. Re-feed the bar when
      /// a corrected value arrives, or call <see cref="Advance"/> to count it and
      /// carry on; two handles on one feed drift a bar apart if neither happens.
      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.IndexMax"/>, which no re-feed clears: the
      /// handle has run out of index domain and only a shorter history can start a
      /// new one.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <returns>The value at the bar just committed.</returns>
      public ZigzagValue Update( double inHigh, double inLow )
      {
         if( outRangeBegIdx + outRangeCount > Core.IndexMax )
            throw Core.StreamFailure("ZIGZAG", "update", RetCode.OutOfRangeEndIndex);
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) ) throw Core.NonFiniteBar("ZIGZAG", "update", !double.IsFinite(inHigh) ? nameof(inHigh) : nameof(inLow));
         core.ZigzagStepImpl(this, inHigh, inLow);
         outRangeCount++;
         return new ZigzagValue(cur_outZigZag, cur_outTrend, cur_outPivotIdx);
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.IndexMax"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inHigh">This bar's high price.</param>
      /// <param name="inLow">This bar's low price.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public ZigzagValue Peek( double inHigh, double inLow )
      {
         if( !double.IsFinite(inHigh) || !double.IsFinite(inLow) ) throw Core.NonFiniteBar("ZIGZAG", "peek", !double.IsFinite(inHigh) ? nameof(inHigh) : nameof(inLow));
         ZigzagStream sp = this;
         int barIdx = sp.barIdx;
         int barsSincePivot = sp.barsSincePivot;
         int cur_outPivotIdx = 0;
         int cur_outTrend = 0;
         double cur_outZigZag = 0.0;
         double pivot = sp.pivot;
         int pivotIdx = sp.pivotIdx;
         int trend = sp.trend;
         /* Bars since the pivot's own bar, carried rather than recomputed as
          * `today - pivotIdx`: a difference of two absolute indices has no meaning
          * to a stream, which sees one bar at a time. talipp's gate is written the
          * same way (`len(input) - pivot.position`), and the counter resets with
          * the pivot so the two expressions are equal at every bar.
          *
          * barIdx is the absolute bar number the index output names, carried in
          * its own right rather than read off the loop cursor. A stream has a
          * cursor only into its own history, so the cursor cannot survive into the
          * per-bar transition; outPivotIdx still has to name the bar the pivot
          * sits on, and this is what lets it.
          */
         barsSincePivot = barsSincePivot + 1;
         barIdx = barIdx + 1;
         /* Reversal is tested BEFORE extension. On an outside bar that both makes
          * a new extreme and clears the threshold, the leg reverses and the old
          * pivot stays where it was; testing extension first would move the pivot
          * and lose the reversal, which is a whole leg of difference rather than a
          * rounding.
          */
         if( trend == -1 ) {
            if( inHigh >= pivot * sp.up && barsSincePivot >= sp.optInMinTrendLength ) {
               trend = 1;
               pivot = inHigh;
               pivotIdx = barIdx;
               barsSincePivot = 0;
            } else if( inLow <= pivot ) {
               /* Ties extend. At an equal price the pivot moves to the LATER bar,
                * so outZigZag does not change and outPivotIdx does: that movement
                * is the only thing the index output carries and the price output
                * cannot.
                */
               pivot = inLow;
               pivotIdx = barIdx;
               barsSincePivot = 0;
            }
         } else if( inLow <= pivot * sp.dn && barsSincePivot >= sp.optInMinTrendLength ) {
            trend = -1;
            pivot = inLow;
            pivotIdx = barIdx;
            barsSincePivot = 0;
         } else if( inHigh >= pivot ) {
            pivot = inHigh;
            pivotIdx = barIdx;
            barsSincePivot = 0;
         }
         cur_outZigZag = pivot;
         cur_outTrend = trend;
         cur_outPivotIdx = pivotIdx;
         return new ZigzagValue(cur_outZigZag, cur_outTrend, cur_outPivotIdx);
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public ZigzagValue Value => new ZigzagValue(cur_outZigZag, cur_outTrend, cur_outPivotIdx);

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public ZigzagStream Clone()
      {
         return new ZigzagStream(this);
      }
   }

   private void ZigzagStepImpl( ZigzagStream sp, double inHigh, double inLow )
   {
      /* Bars since the pivot's own bar, carried rather than recomputed as
       * `today - pivotIdx`: a difference of two absolute indices has no meaning
       * to a stream, which sees one bar at a time. talipp's gate is written the
       * same way (`len(input) - pivot.position`), and the counter resets with
       * the pivot so the two expressions are equal at every bar.
       *
       * barIdx is the absolute bar number the index output names, carried in
       * its own right rather than read off the loop cursor. A stream has a
       * cursor only into its own history, so the cursor cannot survive into the
       * per-bar transition; outPivotIdx still has to name the bar the pivot
       * sits on, and this is what lets it.
       */
      sp.barsSincePivot = sp.barsSincePivot + 1;
      sp.barIdx = sp.barIdx + 1;
      /* Reversal is tested BEFORE extension. On an outside bar that both makes
       * a new extreme and clears the threshold, the leg reverses and the old
       * pivot stays where it was; testing extension first would move the pivot
       * and lose the reversal, which is a whole leg of difference rather than a
       * rounding.
       */
      if( sp.trend == -1 ) {
         if( inHigh >= sp.pivot * sp.up && sp.barsSincePivot >= sp.optInMinTrendLength ) {
            sp.trend = 1;
            sp.pivot = inHigh;
            sp.pivotIdx = sp.barIdx;
            sp.barsSincePivot = 0;
         } else if( inLow <= sp.pivot ) {
            /* Ties extend. At an equal price the pivot moves to the LATER bar,
             * so outZigZag does not change and outPivotIdx does: that movement
             * is the only thing the index output carries and the price output
             * cannot.
             */
            sp.pivot = inLow;
            sp.pivotIdx = sp.barIdx;
            sp.barsSincePivot = 0;
         }
      } else if( inLow <= sp.pivot * sp.dn && sp.barsSincePivot >= sp.optInMinTrendLength ) {
         sp.trend = -1;
         sp.pivot = inLow;
         sp.pivotIdx = sp.barIdx;
         sp.barsSincePivot = 0;
      } else if( inHigh >= sp.pivot ) {
         sp.pivot = inHigh;
         sp.pivotIdx = sp.barIdx;
         sp.barsSincePivot = 0;
      }
      sp.cur_outZigZag = sp.pivot;
      sp.cur_outTrend = sp.trend;
      sp.cur_outPivotIdx = sp.pivotIdx;
   }

   private RetCode ZigzagOpenImpl( ZigzagStream sp, ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int startIdx, double optInSensitivity, int optInMinTrendLength, out int outBegIdx, out int outNBElement, Span<double> outZigZag, Span<int> outTrend, Span<int> outPivotIdx, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      int lookbackTotal = 0;
      int today = 0;
      int outIdx = 0;
      int trend = 0;
      int pivotIdx = 0;
      int barsSincePivot = 0;
      int barIdx = 0;
      double s = 0;
      double up = 0;
      double dn = 0;
      double pivot = 0;
      int historyLen = inHigh.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > IndexMax + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( inLow.Length != inHigh.Length ) {
         return RetCode.BadParam;
      }
      if( optInSensitivity == RealDefault ) {
         optInSensitivity = 5e0;
      } else if( !(optInSensitivity >= 0e0 && optInSensitivity <= 1e2) ) {
         return RetCode.BadParam;
      }
      if( optInMinTrendLength == int.MinValue ) {
         optInMinTrendLength = 1;
      } else if( optInMinTrendLength < 1 || optInMinTrendLength > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      lookbackTotal = ZigzagLookback(optInSensitivity, optInMinTrendLength);
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      /* Percent in, fraction inside. Each factor is rounded once, here, rather
       * than rebuilt per bar: the threshold is `pivot * up` in binary64, which is
       * the expression order the oracle uses.
       */
      s = optInSensitivity / 100.0;
      up = 1.0 + s;
      dn = 1.0 - s;
      /* The seed: a down leg whose extreme is the low of the bar
       * optInMinTrendLength before the first output. Because the gate counts the
       * seed bar like every other pivot, the first reversal can fire exactly at
       * the first output bar, not one later.
       */
      today = startIdx - lookbackTotal;
      trend = -1;
      pivot = inLow[today];
      barIdx = today;
      pivotIdx = barIdx;
      barsSincePivot = 0;
      today = today + 1;
      outIdx = 0;
      while( today <= endIdx ) {
         /* Bars since the pivot's own bar, carried rather than recomputed as
          * `today - pivotIdx`: a difference of two absolute indices has no meaning
          * to a stream, which sees one bar at a time. talipp's gate is written the
          * same way (`len(input) - pivot.position`), and the counter resets with
          * the pivot so the two expressions are equal at every bar.
          *
          * barIdx is the absolute bar number the index output names, carried in
          * its own right rather than read off the loop cursor. A stream has a
          * cursor only into its own history, so the cursor cannot survive into the
          * per-bar transition; outPivotIdx still has to name the bar the pivot
          * sits on, and this is what lets it.
          */
         barsSincePivot = barsSincePivot + 1;
         barIdx = barIdx + 1;
         /* Reversal is tested BEFORE extension. On an outside bar that both makes
          * a new extreme and clears the threshold, the leg reverses and the old
          * pivot stays where it was; testing extension first would move the pivot
          * and lose the reversal, which is a whole leg of difference rather than a
          * rounding.
          */
         if( trend == -1 ) {
            if( inHigh[today] >= pivot * up && barsSincePivot >= optInMinTrendLength ) {
               trend = 1;
               pivot = inHigh[today];
               pivotIdx = barIdx;
               barsSincePivot = 0;
            } else if( inLow[today] <= pivot ) {
               /* Ties extend. At an equal price the pivot moves to the LATER bar,
                * so outZigZag does not change and outPivotIdx does: that movement
                * is the only thing the index output carries and the price output
                * cannot.
                */
               pivot = inLow[today];
               pivotIdx = barIdx;
               barsSincePivot = 0;
            }
         } else if( inLow[today] <= pivot * dn && barsSincePivot >= optInMinTrendLength ) {
            trend = -1;
            pivot = inLow[today];
            pivotIdx = barIdx;
            barsSincePivot = 0;
         } else if( inHigh[today] >= pivot ) {
            pivot = inHigh[today];
            pivotIdx = barIdx;
            barsSincePivot = 0;
         }
         if( today >= startIdx ) {
            outZigZag[outIdx * outStride] = pivot;
            outTrend[outIdx * outStride] = trend;
            outPivotIdx[outIdx * outStride] = pivotIdx;
            outIdx = outIdx + 1;
         }
         today = today + 1;
      }
      outBegIdx = startIdx;
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      sp.optInSensitivity = optInSensitivity;
      sp.optInMinTrendLength = optInMinTrendLength;
      sp.trend = trend;
      sp.pivotIdx = pivotIdx;
      sp.barsSincePivot = barsSincePivot;
      sp.barIdx = barIdx;
      sp.up = up;
      sp.dn = dn;
      sp.pivot = pivot;
      sp.cur_outZigZag = outZigZag[(outNBElement - 1) * outStride];
      sp.cur_outTrend = outTrend[(outNBElement - 1) * outStride];
      sp.cur_outPivotIdx = outPivotIdx[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* ZigzagOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal ZigzagStream ZigzagOpenAndFillInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int startIdx, double optInSensitivity, int optInMinTrendLength, out int outBegIdx, out int outNBElement, Span<double> outZigZag, Span<int> outTrend, Span<int> outPivotIdx )
   {
      ZigzagStream sp = new ZigzagStream(this);
      RetCode retCode = ZigzagOpenImpl(sp, inHigh, inLow, startIdx, optInSensitivity, optInMinTrendLength, out outBegIdx, out outNBElement, outZigZag, outTrend, outPivotIdx, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("ZIGZAG", "openAndFill", nameof(inHigh), inHigh.Length, startIdx, ZigzagLookback(optInSensitivity, optInMinTrendLength));
      }
      throw StreamFailure("ZIGZAG", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind ZigzagOpen (composition seam). */
   internal ZigzagStream ZigzagOpenInternal( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, int startIdx, double optInSensitivity, int optInMinTrendLength )
   {
      ZigzagStream sp = new ZigzagStream(this);
      double[] sink_outZigZag = new double[1];
      int[] sink_outTrend = new int[1];
      int[] sink_outPivotIdx = new int[1];
      RetCode retCode = ZigzagOpenImpl(sp, inHigh, inLow, startIdx, optInSensitivity, optInMinTrendLength, out int outBegIdx, out int outNBElement, sink_outZigZag, sink_outTrend, sink_outPivotIdx, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      if( retCode == RetCode.InsufficientHistory ) {
         throw InsufficientHistory("ZIGZAG", "open", nameof(inHigh), inHigh.Length, startIdx, ZigzagLookback(optInSensitivity, optInMinTrendLength));
      }
      throw StreamFailure("ZIGZAG", "open", retCode);
   }

   /// <summary>Open a live <c>ZIGZAG</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="ZigzagStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>ZIGZAG</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>ZigzagLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>ZigzagOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInSensitivity">As in the batch call; see <see cref="ZigzagLookback"/> for its default and
   /// range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <param name="optInMinTrendLength">As in the batch call; see <see cref="ZigzagLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>ZigzagLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, or the input series
   /// have different lengths.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public ZigzagStream ZigzagOpen( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, double optInSensitivity, int optInMinTrendLength )
   {
      if( inHigh.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "ZIGZAG open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "ZIGZAG open: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TALibArgumentException("ZIGZAG open: inLow is empty", nameof(inLow), RetCode.BadParam);
      RequireHistoryLength("ZIGZAG", "open", "inLow", inLow.Length, inHigh.Length);
      return ZigzagOpenInternal(inHigh, inLow, 0, optInSensitivity, optInMinTrendLength);
   }

   /// <summary><c>ZigzagOpen</c> that also fills the output array(s) over the whole
   /// history in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>ZIGZAG</c> produces over
   /// the same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - ZigzagLookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="ZigzagStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inHigh">High price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="inLow">Low price of each bar. The warm-up history, oldest bar first.</param>
   /// <param name="optInSensitivity">As in the batch call; see <see cref="ZigzagLookback"/> for its default and
   /// range (<see cref="Core.RealDefault"/> selects the default).</param>
   /// <param name="optInMinTrendLength">As in the batch call; see <see cref="ZigzagLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outZigZag">Price of the swing extreme currently being tracked. Must hold at least
   /// <c>historyLen - ZigzagLookback(...)</c> values.</param>
   /// <param name="outTrend">+1 while the leg is up, -1 while it is down. Must hold at least
   /// <c>historyLen - ZigzagLookback(...)</c> values.</param>
   /// <param name="outPivotIdx">Absolute index, into the input, of the bar that extreme sits on. Must hold
   /// at least <c>historyLen - ZigzagLookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>ZigzagLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.IndexMax"/> + 1, the
   /// two index faults an opener can have (rules rS1 and rS2).</exception>
   public ZigzagStream ZigzagOpenAndFill( ReadOnlySpan<double> inHigh, ReadOnlySpan<double> inLow, double optInSensitivity, int optInMinTrendLength, Span<double> outZigZag, Span<int> outTrend, Span<int> outPivotIdx )
   {
      if( inHigh.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "ZIGZAG openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inHigh.Length > IndexMax + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inHigh), "ZIGZAG openAndFill: history is longer than IndexMax + 1", RetCode.OutOfRangeEndIndex);
      if( inLow.IsEmpty ) throw new TALibArgumentException("ZIGZAG openAndFill: inLow is empty", nameof(inLow), RetCode.BadParam);
      int guardOutLen = OpenFillCount("ZIGZAG", "openAndFill", inHigh.Length, ZigzagLookback(optInSensitivity, optInMinTrendLength));
      RequireHistoryLength("ZIGZAG", "openAndFill", "inLow", inLow.Length, inHigh.Length);
      RequireFillLength("ZIGZAG", "openAndFill", "outZigZag", outZigZag.Length, guardOutLen);
      RequireFillLength("ZIGZAG", "openAndFill", "outTrend", outTrend.Length, guardOutLen);
      RequireFillLength("ZIGZAG", "openAndFill", "outPivotIdx", outPivotIdx.Length, guardOutLen);
      if( SameBuffer(outZigZag, inHigh) || SameBuffer(outZigZag, inLow) || SameBuffer(System.Runtime.InteropServices.MemoryMarshal.AsBytes(outTrend), System.Runtime.InteropServices.MemoryMarshal.AsBytes(inHigh)) || SameBuffer(System.Runtime.InteropServices.MemoryMarshal.AsBytes(outTrend), System.Runtime.InteropServices.MemoryMarshal.AsBytes(inLow)) || SameBuffer(System.Runtime.InteropServices.MemoryMarshal.AsBytes(outPivotIdx), System.Runtime.InteropServices.MemoryMarshal.AsBytes(inHigh)) || SameBuffer(System.Runtime.InteropServices.MemoryMarshal.AsBytes(outPivotIdx), System.Runtime.InteropServices.MemoryMarshal.AsBytes(inLow)) || SameBuffer(System.Runtime.InteropServices.MemoryMarshal.AsBytes(outZigZag), System.Runtime.InteropServices.MemoryMarshal.AsBytes(outTrend)) || SameBuffer(System.Runtime.InteropServices.MemoryMarshal.AsBytes(outZigZag), System.Runtime.InteropServices.MemoryMarshal.AsBytes(outPivotIdx)) || SameBuffer(outTrend, outPivotIdx) ) {
         throw StreamFailure("ZIGZAG", "openAndFill", RetCode.BadParam);
      }
      if( guardOutLen > 0 && ( outZigZag.Overlaps(inHigh) || outZigZag.Overlaps(inLow) || System.Runtime.InteropServices.MemoryMarshal.AsBytes(outTrend).Overlaps(System.Runtime.InteropServices.MemoryMarshal.AsBytes(inHigh)) || System.Runtime.InteropServices.MemoryMarshal.AsBytes(outTrend).Overlaps(System.Runtime.InteropServices.MemoryMarshal.AsBytes(inLow)) || System.Runtime.InteropServices.MemoryMarshal.AsBytes(outPivotIdx).Overlaps(System.Runtime.InteropServices.MemoryMarshal.AsBytes(inHigh)) || System.Runtime.InteropServices.MemoryMarshal.AsBytes(outPivotIdx).Overlaps(System.Runtime.InteropServices.MemoryMarshal.AsBytes(inLow)) || OutputsAlias(System.Runtime.InteropServices.MemoryMarshal.AsBytes(outZigZag), System.Runtime.InteropServices.MemoryMarshal.AsBytes(outTrend)) || OutputsAlias(System.Runtime.InteropServices.MemoryMarshal.AsBytes(outZigZag), System.Runtime.InteropServices.MemoryMarshal.AsBytes(outPivotIdx)) || OutputsAlias(outTrend, outPivotIdx) ) ) {
         throw StreamFailure("ZIGZAG", "openAndFill", RetCode.BadParam);
      }
      return ZigzagOpenAndFillInternal(inHigh, inLow, 0, optInSensitivity, optInMinTrendLength, out _, out _, outZigZag, outTrend, outPivotIdx);
   }
