   /// <item><description><b>Ties extend.</b> The comparisons are <c>&lt;=</c> and <c>&gt;=</c>, so at an equal price the pivot moves to the later bar: <c>outZigZag</c> does not change and <c>outPivotIdx</c> does. That movement is the only thing the index output carries and the price output cannot.</description></item>
   /// <item><description><b>The gate counts from the pivot's own bar, the seed included.</b> No reversal can fire before the first output bar; the first one can fire exactly there.</description></item>
   /// <item><description><b>The seed is a low.</b> A series that only rises therefore reports an up leg from its first reversal and never returns to a down leg.</description></item>
   /// <item><description>The lookback is <c>optInMinTrendLength</c> and does not depend on the sensitivity: the threshold decides whether a reversal fires, never how early it may.</description></item>
   /// <item><description><c>optInSensitivity</c> is a percent, as Achelis, StockCharts, TTR, Skender and TradingView take it. 0 and 1 are degenerate but defined: at 0 a reversal fires on almost every bar the gate allows, and at 100 no downward reversal fires on positive prices.</description></item>
   /// <item><description>The value at a bar depends on where the caller started, through the seed; the function is <c>path_dependent</c> for that reason, as SAR and SUPERTREND are.</description></item>
   /// </list>
   /// <para>
   /// This is the <c>float[]</c> overload: input elements are widened to
   /// <c>double</c> as they are read and all arithmetic is performed in
   /// <c>double</c>, so a result beyond <c>float</c> range is still
   /// representable.
   /// </para>
   /// <para>
   /// Values are written only where the indicator is defined. The returned
   /// <see cref="OutRange"/> says where they start and how many there are, and
   /// the library never pads with NaN. A valid range that ends before
   /// <c>ZigzagLookback</c> is a <b>success with no values</b> (<c>Count ==
   /// 0</c>), not an error.
   /// </para>
   /// <para>
   /// Every exception it throws, except the runtime's own
   /// <c>OutOfMemoryException</c>, implements <see cref="ITALibFailure"/>, which
   /// carries the <see cref="RetCode"/>.
   /// </para>
   /// </remarks>
   /// <param name="startIdx">First bar of the requested range (inclusive).</param>
   /// <param name="endIdx">Last bar of the requested range (inclusive).</param>
   /// <param name="inHigh">High price of each bar.</param>
   /// <param name="inLow">Low price of each bar.</param>
   /// <param name="optInSensitivity">Minimum move away from the current extreme that reverses the leg, in
   /// percent (default 5; range 0..100; <see cref="Core.RealDefault"/> selects
   /// the default).</param>
   /// <param name="optInMinTrendLength">Minimum number of bars between two pivots (default 1; range 1..100000;
   /// <c>int.MinValue</c> selects the default).</param>
   /// <param name="outZigZag">Price of the swing extreme currently being tracked. Must hold at least
   /// <c>endIdx - max(startIdx, ZigzagLookback(...)) + 1</c> values, and never
   /// be empty: an empty span is an absent output.</param>
   /// <param name="outTrend">+1 while the leg is up, -1 while it is down. Must hold at least <c>endIdx
   /// - max(startIdx, ZigzagLookback(...)) + 1</c> values, and never be empty:
   /// an empty span is an absent output.</param>
   /// <param name="outPivotIdx">Absolute index, into the input, of the bar that extreme sits on. Must hold
   /// at least <c>endIdx - max(startIdx, ZigzagLookback(...)) + 1</c> values,
   /// and never be empty: an empty span is an absent output.</param>
   /// <returns>The range written: <c>BegIdx</c> is the first bar with a value,
   /// <c>Count</c> how many were written.</returns>
   /// <exception cref="System.ArgumentOutOfRangeException"><c>startIdx</c> or <c>endIdx</c> is negative or above
   /// <see cref="Core.IndexMax"/>, or <c>endIdx &lt; startIdx</c>.</exception>
   /// <exception cref="System.ArgumentException">
   /// One of the following, checked before anything is written, so a rejected
   /// call leaves every buffer untouched:
   /// <list type="bullet">
   /// <item><description>An optional parameter is outside its documented range.</description></item>
   /// <item><description>A span is too short for the range requested: any input this function
   /// <i>declares</i> that does not reach <c>endIdx</c>, or an output that
   /// cannot hold the values produced. Declared, not read: a few candlestick
   /// patterns take an OHLC series they never index, and it is required all the
   /// same. A null array arrives as an empty span, and an empty span is an
   /// absent argument: for an input, or an output that cannot be declined, it is
   /// rejected even when the call would produce nothing.</description></item>
   /// <item><description>Two outputs overlap or are one array
   /// (<see href="https://ta-lib.org/spec/errors/#rb6">rule rB6</see>), or an
   /// output overlaps an input. An output and a real input never share an
   /// element type in this overload, so the two can never be the same span:
   /// there is no in-place case to allow, and any overlap of their byte ranges
   /// is rejected.</description></item>
   /// </list>
   /// </exception>
   /// <seealso cref="Core.Sar(int, int, ReadOnlySpan{double}, ReadOnlySpan{double}, double, double, Span{double})"/>
   /// <seealso cref="Core.Supertrend(int, int, ReadOnlySpan{double}, ReadOnlySpan{double}, ReadOnlySpan{double}, int, double, Span{double}, Span{int})"/>
   /// <seealso cref="Core.Minmaxindex(int, int, ReadOnlySpan{double}, int, Span{int}, Span{int})"/>
   /// <seealso cref="Core.Midprice(int, int, ReadOnlySpan{double}, ReadOnlySpan{double}, int, Span{double})"/>
   public OutRange Zigzag( int startIdx,
                           int endIdx,
                           ReadOnlySpan<float> inHigh,
                           ReadOnlySpan<float> inLow,
                           double optInSensitivity,
                           int optInMinTrendLength,
                           Span<double> outZigZag,
                           Span<int> outTrend,
                           Span<int> outPivotIdx )
   {
      int guardStart = ClampedStart(startIdx, endIdx, ZigzagLookback(optInSensitivity, optInMinTrendLength));
      int guardInLen = guardStart < 0 ? 0 : endIdx + 1;
      int guardOutLen = guardStart < 0 || guardStart > endIdx ? 0 : endIdx - guardStart + 1;
      RequireLength("ZIGZAG", "inHigh", inHigh.Length, guardInLen);
      RequireLength("ZIGZAG", "inLow", inLow.Length, guardInLen);
      if( guardStart >= 0 ) RequirePresent("ZIGZAG", "outZigZag", outZigZag.Length);
      RequireLength("ZIGZAG", "outZigZag", outZigZag.Length, guardOutLen);
      if( guardStart >= 0 ) RequirePresent("ZIGZAG", "outTrend", outTrend.Length);
      RequireLength("ZIGZAG", "outTrend", outTrend.Length, guardOutLen);
      if( guardStart >= 0 ) RequirePresent("ZIGZAG", "outPivotIdx", outPivotIdx.Length);
      RequireLength("ZIGZAG", "outPivotIdx", outPivotIdx.Length, guardOutLen);
      RetCode retCode = ZigzagImpl(startIdx, endIdx, inHigh, inLow, optInSensitivity, optInMinTrendLength, out int outBegIdx, out int outNBElement, outZigZag, outTrend, outPivotIdx);
      if( retCode != RetCode.Success ) {
         throw Failure("ZIGZAG", retCode);
      }
      return new OutRange(outBegIdx, outNBElement);
   }
