   /// <summary>A live <c>CTI</c> stream: one value per closed bar, bit-identical to
   /// <c>CTI</c> over the same series.</summary>
   /// <remarks>
   /// <para>Open with <see cref="Core.CtiOpen"/>. There is no close and nothing to
   /// dispose — the handle is ordinary managed state, and an unreferenced handle
   /// is simply collected.</para>
   /// <para>Concurrency: a handle is single-writer — <see cref="Update"/>,
   /// <see cref="Peek"/>, <see cref="Value"/> and <see cref="Clone"/> must not
   /// race with an <c>Update</c> on the same handle. With no concurrent
   /// <c>Update</c>, <c>Peek</c>, <c>Value</c> and <c>Clone</c> never write the
   /// handle. Independent handles (a <c>Clone</c> result included) are fully
   /// independent.</para>
   /// <para>Not serializable by design, and the constructors are internal so no
   /// partially built handle can be minted: to checkpoint, retain the history
   /// and re-open — the result is bit-identical by contract.</para>
   /// </remarks>
   public sealed class CtiStream
   {
      internal Core core;
      internal int optInTimePeriod;
      internal double sumX;
      internal double sumX2;
      internal double sumXY;
      internal double leavingX;
      internal double shift;
      internal double invPeriod;
      internal double dPeriod;
      internal double sumY;
      internal double ssY;
      internal int lookbackTotal;
      internal int trailingIdx;
      internal int barsSinceReseed;
      internal int j;
      internal int today;
      internal int xMask;
      internal double[] x_inReal = [];
      internal double cur_outReal;
      internal int outRangeBegIdx;
      internal int outRangeCount;

      internal CtiStream( Core core ) { this.core = core; }

      /// <summary>The bars this stream has an output for, in the input series' coordinates:
      /// <c>[BegIdx, BegIdx + Count)</c>.</summary>
      /// <remarks>
      /// <para>It is what <c>Core.Cti</c> reports over the same bars: the opener sets it
      /// to <c>(lookback, historyLen - lookback)</c>, every accepted <c>Update</c>
      /// adds one to the count — a rejected one changes nothing, and neither does
      /// <c>Peek</c> — and <c>Clone</c> carries it verbatim. A plain <c>Open</c>
      /// hands back only the last value, a subset of this range, because the caller
      /// chose not to take the fill.</para>
      /// <para>The last bar it can reach is <see cref="Core.MaxIndex"/>; past that
      /// <c>Update</c> and <c>Advance</c> throw.</para>
      /// </remarks>
      public OutRange OutRange => new OutRange(outRangeBegIdx, outRangeCount);

      /// <summary>Count one bar this stream was not fed: <see cref="OutRange"/> advances by
      /// one and nothing else moves.</summary>
      /// <remarks>
      /// <para><see cref="Value"/> keeps answering the previous output, which is this
      /// bar's output too. For a bar the caller leaves out: one an <c>Update</c>
      /// rejected and that will not be re-fed, or a session with no print. Without
      /// it two handles on one feed drift a bar apart when only one of them skips.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.MaxIndex"/>, the last one the batch tier
      /// can address and the last this handle will count. <c>Update</c> throws the
      /// same there.</para>
      /// </remarks>
      public void Advance()
      {
         if( outRangeBegIdx + outRangeCount > Core.MaxIndex )
            throw Core.StreamFailure("CTI", "advance", RetCode.OutOfRangeEndIndex);
         outRangeCount++;
      }

      internal CtiStream( CtiStream other )
      {
         this.core = other.core;
         this.optInTimePeriod = other.optInTimePeriod;
         this.sumX = other.sumX;
         this.sumX2 = other.sumX2;
         this.sumXY = other.sumXY;
         this.leavingX = other.leavingX;
         this.shift = other.shift;
         this.invPeriod = other.invPeriod;
         this.dPeriod = other.dPeriod;
         this.sumY = other.sumY;
         this.ssY = other.ssY;
         this.lookbackTotal = other.lookbackTotal;
         this.trailingIdx = other.trailingIdx;
         this.barsSinceReseed = other.barsSinceReseed;
         this.j = other.j;
         this.today = other.today;
         this.xMask = other.xMask;
         this.x_inReal = new double[other.x_inReal.Length];
         Array.Copy( other.x_inReal, this.x_inReal, other.x_inReal.Length );
         this.cur_outReal = other.cur_outReal;
         this.outRangeBegIdx = other.outRangeBegIdx;
         this.outRangeCount = other.outRangeCount;
      }

      /// <summary>Commit one closed bar, returning the new current value.</summary>
      /// <remarks>
      /// <para>Allocates nothing — neither handle state nor a return value.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> if any bar value is not
      /// finite (NaN or an infinity). That check runs before anything is written,
      /// so nothing moves — <see cref="OutRange"/> included — and
      /// <see cref="Value"/> still answers the previous value. Re-feed the bar when
      /// a corrected value arrives, or call <see cref="Advance"/> to count it and
      /// carry on; two handles on one feed drift a bar apart if neither happens.
      /// This is the one place the streaming tier is stricter than the batch API,
      /// which computes on whatever it is given: a handle retains its state, so a
      /// single non-finite bar would poison every later value it produces.</para>
      /// <para>Throws <see cref="System.ArgumentException"/> once <see cref="OutRange"/>
      /// has reached bar <see cref="Core.MaxIndex"/>, which no re-feed clears: the
      /// handle has run out of index domain and only a shorter history can start a
      /// new one.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value at the bar just committed.</returns>
      public double Update( double inReal )
      {
         if( outRangeBegIdx + outRangeCount > Core.MaxIndex )
            throw Core.StreamFailure("CTI", "update", RetCode.OutOfRangeEndIndex);
         if( !double.IsFinite(inReal) ) throw Core.StreamFailure("CTI", "update", RetCode.BadParam);
         core.CtiStepImpl(this, inReal);
         outRangeCount++;
         return cur_outReal;
      }

      /// <summary>Evaluate a forming bar without committing it.</summary>
      /// <remarks>
      /// <para>Bit-identical to what the next <see cref="Update"/> with the same bar
      /// would return — the same transition, with every store it would make carried
      /// in a local instead. Never writes this handle, so peeks may run
      /// concurrently with each other.</para>
      /// <para>Its cost does not grow with the period.</para>
      /// <para>It counts no bar, so it keeps answering past the
      /// <see cref="Core.MaxIndex"/> ceiling <c>Update</c> stops at.</para>
      /// </remarks>
      /// <param name="inReal">This bar's value for <c>inReal</c>.</param>
      /// <returns>The value <see cref="Update"/> would return for this bar, when it takes
      /// it.</returns>
      public double Peek( double inReal )
      {
         if( !double.IsFinite(inReal) ) throw Core.StreamFailure("CTI", "peek", RetCode.BadParam);
         CtiStream sp = this;
         double x = 0.0;
         double ssX = 0.0;
         double spXY = 0.0;
         double tempReal = 0.0;
         int windowStart = 0;
         int barsSinceReseed = sp.barsSinceReseed;
         double cur_outReal = 0.0;
         int j = sp.j;
         double shift = sp.shift;
         double sumX = sp.sumX;
         double sumX2 = sp.sumX2;
         double sumXY = sp.sumXY;
         int trailingIdx = sp.trailingIdx;
         int pkSlot0 = -1;
         double pkVal0 = 0.0;
         pkSlot0 = sp.today & sp.xMask;
         pkVal0 = inReal;
         /* The incoming bar is zero bars ago, so it moves sumX and sumX2 and
          * leaves sumXY alone.
          */
         x = (((sp.today & sp.xMask) != pkSlot0) ? sp.x_inReal[sp.today & sp.xMask] : pkVal0) - shift;
         sumX += x;
         sumX2 += x * x;
         ssX = sumX2 - sumX * sumX * sp.invPeriod;
         spXY = sumXY - sumX * sp.sumY * sp.invPeriod;
         /* Re-anchor and rebuild when the shift has gone stale: the price sum of
          * squares has shrunk below 1e-6 of the squared deviations it is extracted
          * from; OR the value the PREVIOUS bar removed sat so far from the shift
          * that its squared term dwarfs what remains; OR at least every 32
          * windows. Same three triggers as correl.c, watching the price side only
          * -- the ramp side is exact constants and cannot drift.
          *
          * A vanishing spXY is NOT a trigger. It is a legitimate answer, a window
          * with no linear trend, and reseeding on it would rebuild on every bar of
          * ordinary sideways data.
          */
         barsSinceReseed -= 1;
         if( ssX < 0.000001 * sumX2 || sp.leavingX > 1000000.0 * sumX2 || barsSinceReseed <= 0 ) {
            barsSinceReseed = 32 * sp.optInTimePeriod;
            windowStart = sp.today - sp.lookbackTotal;
            tempReal = 0.0;
            for( j = windowStart; j <= sp.today; j += 1 ) {
               tempReal += ((j & sp.xMask) != pkSlot0) ? sp.x_inReal[j & sp.xMask] : pkVal0;
            }
            shift = tempReal * sp.invPeriod;
            sumXY = 0.0;
            sumX2 = sumXY;
            sumX = sumX2;
            for( j = windowStart; j <= sp.today; j += 1 ) {
               x = (((j & sp.xMask) != pkSlot0) ? sp.x_inReal[j & sp.xMask] : pkVal0) - shift;
               sumX += x;
               sumX2 += x * x;
               sumXY += x * (double)(sp.today - j);
            }
            ssX = sumX2 - sumX * sumX * sp.invPeriod;
            spXY = sumXY - sumX * sp.sumY * sp.invPeriod;
            /* A sum of squares is non-negative by definition, but this one is
             * extracted as a difference, so its SIGN is not guaranteed on a window
             * sitting inside a flat stretch. Enforced here rather than at the
             * divide, exactly as correl.c does: a negative ssX always reseeds on
             * the same bar, so the divide below can rely on it being >= 0.
             */
            if( ssX < 0.0 ) {
               ssX = 0.0;
            }
         }
         trailingIdx += 1;
         /* THE SIGN. y here is BARS AGO, so it runs backward in time and a rising
          * series correlates NEGATIVELY with it. Ehlers' listing counts the same
          * way and takes Y = -count, which is the positively-sloped line the
          * indicator is defined against; negating the coefficient once is the same
          * thing, and it keeps the O(1) slide identity below written the way
          * linearreg.c:102-114 states it. Dropping this negation silently inverts
          * the whole indicator -- Pearson r is odd in either variable -- and a
          * magnitude or |r| assertion cannot see it.
          *
          * ssY is a positive constant, so only ssX can make the window degenerate.
          * It is tested against its own scale rather than an absolute band: the
          * product carries the fourth power of the window's spread, so a fixed
          * threshold rejects a well-defined correlation as soon as the data is
          * small. The product is tested on its own because neither factor's test
          * implies it -- at that fourth power it can underflow to exactly 0.0
          * while both are still ordinary normals, and a zero divisor there gives
          * NaN, which the clamp does not catch.
          *
          * An all-flat window therefore emits exactly 0.0 rather than NaN, which
          * is correl.c's precedent and what #112 requires of a successful call.
          */
         if( ssX > 0.00000000000001 * sumX2 && ssX * sp.ssY > 0.0 ) {
            tempReal = (0 - spXY) / Math.Sqrt(ssX * sp.ssY);
            /* A correlation coefficient cannot leave [-1,1]; rounding in the
             * three sums can still put it a few ulp outside.
             */
            if( tempReal > 1.0 ) {
               tempReal = 1.0;
            } else if( tempReal < 0 - 1.0 ) {
               tempReal = 0 - 1.0;
            }
            cur_outReal = tempReal;
         } else {
            cur_outReal = 0.0;
         }
         return cur_outReal;
      }

      /// <summary>The value at the last bar this stream counted — the bar
      /// <see cref="OutRange"/> ends on. The last history bar right after open,
      /// then whatever the latest accepted <see cref="Update"/> returned.</summary>
      /// <remarks>
      /// <para><see cref="Peek"/> does not change it.</para>
      /// </remarks>
      public double Value => cur_outReal;

      /// <summary>An independent deep copy of this stream: both evolve separately from here
      /// on.</summary>
      /// <returns>The new, independent handle.</returns>
      public CtiStream Clone()
      {
         return new CtiStream(this);
      }
   }

   internal void CtiStepImpl( CtiStream sp, double inReal )
   {
      double x = 0.0;
      double trailingX = 0.0;
      double ssX = 0.0;
      double spXY = 0.0;
      double tempReal = 0.0;
      int windowStart = 0;
      sp.x_inReal[sp.today & sp.xMask] = inReal;
      /* The incoming bar is zero bars ago, so it moves sumX and sumX2 and
       * leaves sumXY alone.
       */
      x = sp.x_inReal[sp.today & sp.xMask] - sp.shift;
      sp.sumX += x;
      sp.sumX2 += x * x;
      ssX = sp.sumX2 - sp.sumX * sp.sumX * sp.invPeriod;
      spXY = sp.sumXY - sp.sumX * sp.sumY * sp.invPeriod;
      /* Re-anchor and rebuild when the shift has gone stale: the price sum of
       * squares has shrunk below 1e-6 of the squared deviations it is extracted
       * from; OR the value the PREVIOUS bar removed sat so far from the shift
       * that its squared term dwarfs what remains; OR at least every 32
       * windows. Same three triggers as correl.c, watching the price side only
       * -- the ramp side is exact constants and cannot drift.
       *
       * A vanishing spXY is NOT a trigger. It is a legitimate answer, a window
       * with no linear trend, and reseeding on it would rebuild on every bar of
       * ordinary sideways data.
       */
      sp.barsSinceReseed -= 1;
      if( ssX < 0.000001 * sp.sumX2 || sp.leavingX > 1000000.0 * sp.sumX2 || sp.barsSinceReseed <= 0 ) {
         sp.barsSinceReseed = 32 * sp.optInTimePeriod;
         windowStart = sp.today - sp.lookbackTotal;
         tempReal = 0.0;
         for( sp.j = windowStart; sp.j <= sp.today; sp.j += 1 ) {
            tempReal += sp.x_inReal[sp.j & sp.xMask];
         }
         sp.shift = tempReal * sp.invPeriod;
         sp.sumXY = 0.0;
         sp.sumX2 = sp.sumXY;
         sp.sumX = sp.sumX2;
         for( sp.j = windowStart; sp.j <= sp.today; sp.j += 1 ) {
            x = sp.x_inReal[sp.j & sp.xMask] - sp.shift;
            sp.sumX += x;
            sp.sumX2 += x * x;
            sp.sumXY += x * (double)(sp.today - sp.j);
         }
         ssX = sp.sumX2 - sp.sumX * sp.sumX * sp.invPeriod;
         spXY = sp.sumXY - sp.sumX * sp.sumY * sp.invPeriod;
         /* A sum of squares is non-negative by definition, but this one is
          * extracted as a difference, so its SIGN is not guaranteed on a window
          * sitting inside a flat stretch. Enforced here rather than at the
          * divide, exactly as correl.c does: a negative ssX always reseeds on
          * the same bar, so the divide below can rely on it being >= 0.
          */
         if( ssX < 0.0 ) {
            ssX = 0.0;
         }
      }
      /* Save the trailing value before writing the output, since the input and
       * output might be the same array.
       */
      trailingX = sp.x_inReal[sp.trailingIdx & sp.xMask] - sp.shift;
      sp.trailingIdx += 1;
      /* THE SIGN. y here is BARS AGO, so it runs backward in time and a rising
       * series correlates NEGATIVELY with it. Ehlers' listing counts the same
       * way and takes Y = -count, which is the positively-sloped line the
       * indicator is defined against; negating the coefficient once is the same
       * thing, and it keeps the O(1) slide identity below written the way
       * linearreg.c:102-114 states it. Dropping this negation silently inverts
       * the whole indicator -- Pearson r is odd in either variable -- and a
       * magnitude or |r| assertion cannot see it.
       *
       * ssY is a positive constant, so only ssX can make the window degenerate.
       * It is tested against its own scale rather than an absolute band: the
       * product carries the fourth power of the window's spread, so a fixed
       * threshold rejects a well-defined correlation as soon as the data is
       * small. The product is tested on its own because neither factor's test
       * implies it -- at that fourth power it can underflow to exactly 0.0
       * while both are still ordinary normals, and a zero divisor there gives
       * NaN, which the clamp does not catch.
       *
       * An all-flat window therefore emits exactly 0.0 rather than NaN, which
       * is correl.c's precedent and what #112 requires of a successful call.
       */
      if( ssX > 0.00000000000001 * sp.sumX2 && ssX * sp.ssY > 0.0 ) {
         tempReal = (0 - spXY) / Math.Sqrt(ssX * sp.ssY);
         /* A correlation coefficient cannot leave [-1,1]; rounding in the
          * three sums can still put it a few ulp outside.
          */
         if( tempReal > 1.0 ) {
            tempReal = 1.0;
         } else if( tempReal < 0 - 1.0 ) {
            tempReal = 0 - 1.0;
         }
         sp.cur_outReal = tempReal;
      } else {
         sp.cur_outReal = 0.0;
      }
      /* Slide the window one bar in O(1). Advancing it ages every retained
       * value by one bar, which raises each of their weights by 1 and so adds
       * the whole deviation sum; the departing value leaves at the full weight
       * optInTimePeriod-1 and also loses its place in that sum, which is the
       * remaining -1. The two together are exactly -optInTimePeriod*trailingX,
       * and sumX must still be the COMPLETE window's sum when it is read here
       * -- it is decremented on the line below, not above.
       */
      sp.leavingX = trailingX * trailingX;
      sp.sumXY = sp.sumXY + sp.sumX - sp.dPeriod * trailingX;
      sp.sumX -= trailingX;
      sp.sumX2 -= sp.leavingX;
      sp.today += 1;
   }

   private RetCode CtiOpenImpl( CtiStream sp, ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal, int outStride )
   {
      outBegIdx = 0;
      outNBElement = 0;
      double sumX = 0;
      double sumX2 = 0;
      double sumXY = 0;
      double x = 0;
      double trailingX = 0;
      double leavingX = 0;
      double shift = 0;
      double ssX = 0;
      double spXY = 0;
      double tempReal = 0;
      double invPeriod = 0;
      double dPeriod = 0;
      double sumY = 0;
      double ssY = 0;
      int lookbackTotal = 0;
      int outIdx = 0;
      int today = 0;
      int trailingIdx = 0;
      int windowStart = 0;
      int j = 0;
      int barsSinceReseed = 0;
      int historyLen = inReal.Length;
      int endIdx = historyLen - 1;
      if( historyLen < 1 ) {
         return RetCode.OutOfRangeStartIndex;
      }
      if( historyLen > MaxIndex + 1 ) {
         return RetCode.OutOfRangeEndIndex;
      }
      if( optInTimePeriod == int.MinValue ) {
         optInTimePeriod = 20;
      } else if( optInTimePeriod < 2 || optInTimePeriod > 100000 ) {
         return RetCode.BadParam;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory;
      }
      lookbackTotal = optInTimePeriod - 1;
      if( startIdx < lookbackTotal ) {
         startIdx = lookbackTotal;
      }
      if( startIdx > endIdx ) {
         outBegIdx = 0;
         outNBElement = 0;
         return RetCode.InsufficientHistory ;
      }
      outBegIdx = startIdx;
      trailingIdx = startIdx - lookbackTotal;
      dPeriod = (double)optInTimePeriod;
      invPeriod = 1.0 / dPeriod;
      /* The ramp side is data-independent and collapses to two constants. With y
       * running 0..optInTimePeriod-1 as BARS AGO,
       *
       *    sumY = n(n-1)/2            ssY = sumY2 - sumY*sumY/n = n(n*n-1)/12
       *
       * Both are computed in double because their integer forms overflow: at the
       * top of the parameter range n*n*n is 1e15, far past what an int holds, and
       * the product would wrap silently rather than fail. ssY is strictly positive
       * for every n >= 2, which is why only the price side can make a window
       * degenerate.
       */
      sumY = dPeriod * (dPeriod - 1.0) * 0.5;
      ssY = dPeriod * (dPeriod * dPeriod - 1.0) / 12.0;
      /* Measure the price side against a shift near the window, as correl.c does
       * (#242). Transcribing the author's listing literally would carry
       * n*Sxx - Sx*Sx on raw price levels, which is the quantity that returned 0,
       * -1 and -1.73 from a perfectly correlated pair: MEASURED on the card, the
       * naive form errs by 5.7e-03 at a 1e2 price level with a 1e-5 spread, on an
       * indicator whose entire range is [-1, +1].
       *
       * Anchor on the first window value here; every later re-anchor uses the
       * window mean, which is better centred but costs a pass this one cannot
       * afford before the sums exist.
       */
      shift = inReal[trailingIdx];
      /* The initial window, less its last bar. This bar's y is startIdx-j, since
       * the first output is computed with `today` at startIdx.
       */
      sumXY = 0.0;
      sumX2 = sumXY;
      sumX = sumX2;
      for( j = trailingIdx; j < startIdx; j += 1 ) {
         x = inReal[j] - shift;
         sumX += x;
         sumX2 += x * x;
         sumXY += x * (double)(startIdx - j);
      }
      today = startIdx;
      outIdx = 0;
      barsSinceReseed = 32 * optInTimePeriod;
      leavingX = 0.0;
      do {
         /* The incoming bar is zero bars ago, so it moves sumX and sumX2 and
          * leaves sumXY alone.
          */
         x = inReal[today] - shift;
         sumX += x;
         sumX2 += x * x;
         ssX = sumX2 - sumX * sumX * invPeriod;
         spXY = sumXY - sumX * sumY * invPeriod;
         /* Re-anchor and rebuild when the shift has gone stale: the price sum of
          * squares has shrunk below 1e-6 of the squared deviations it is extracted
          * from; OR the value the PREVIOUS bar removed sat so far from the shift
          * that its squared term dwarfs what remains; OR at least every 32
          * windows. Same three triggers as correl.c, watching the price side only
          * -- the ramp side is exact constants and cannot drift.
          *
          * A vanishing spXY is NOT a trigger. It is a legitimate answer, a window
          * with no linear trend, and reseeding on it would rebuild on every bar of
          * ordinary sideways data.
          */
         barsSinceReseed -= 1;
         if( ssX < 0.000001 * sumX2 || leavingX > 1000000.0 * sumX2 || barsSinceReseed <= 0 ) {
            barsSinceReseed = 32 * optInTimePeriod;
            windowStart = today - lookbackTotal;
            tempReal = 0.0;
            for( j = windowStart; j <= today; j += 1 ) {
               tempReal += inReal[j];
            }
            shift = tempReal * invPeriod;
            sumXY = 0.0;
            sumX2 = sumXY;
            sumX = sumX2;
            for( j = windowStart; j <= today; j += 1 ) {
               x = inReal[j] - shift;
               sumX += x;
               sumX2 += x * x;
               sumXY += x * (double)(today - j);
            }
            ssX = sumX2 - sumX * sumX * invPeriod;
            spXY = sumXY - sumX * sumY * invPeriod;
            /* A sum of squares is non-negative by definition, but this one is
             * extracted as a difference, so its SIGN is not guaranteed on a window
             * sitting inside a flat stretch. Enforced here rather than at the
             * divide, exactly as correl.c does: a negative ssX always reseeds on
             * the same bar, so the divide below can rely on it being >= 0.
             */
            if( ssX < 0.0 ) {
               ssX = 0.0;
            }
         }
         /* Save the trailing value before writing the output, since the input and
          * output might be the same array.
          */
         trailingX = inReal[trailingIdx] - shift;
         trailingIdx += 1;
         /* THE SIGN. y here is BARS AGO, so it runs backward in time and a rising
          * series correlates NEGATIVELY with it. Ehlers' listing counts the same
          * way and takes Y = -count, which is the positively-sloped line the
          * indicator is defined against; negating the coefficient once is the same
          * thing, and it keeps the O(1) slide identity below written the way
          * linearreg.c:102-114 states it. Dropping this negation silently inverts
          * the whole indicator -- Pearson r is odd in either variable -- and a
          * magnitude or |r| assertion cannot see it.
          *
          * ssY is a positive constant, so only ssX can make the window degenerate.
          * It is tested against its own scale rather than an absolute band: the
          * product carries the fourth power of the window's spread, so a fixed
          * threshold rejects a well-defined correlation as soon as the data is
          * small. The product is tested on its own because neither factor's test
          * implies it -- at that fourth power it can underflow to exactly 0.0
          * while both are still ordinary normals, and a zero divisor there gives
          * NaN, which the clamp does not catch.
          *
          * An all-flat window therefore emits exactly 0.0 rather than NaN, which
          * is correl.c's precedent and what #112 requires of a successful call.
          */
         if( ssX > 0.00000000000001 * sumX2 && ssX * ssY > 0.0 ) {
            tempReal = (0 - spXY) / Math.Sqrt(ssX * ssY);
            /* A correlation coefficient cannot leave [-1,1]; rounding in the
             * three sums can still put it a few ulp outside.
             */
            if( tempReal > 1.0 ) {
               tempReal = 1.0;
            } else if( tempReal < 0 - 1.0 ) {
               tempReal = 0 - 1.0;
            }
            outReal[outIdx++ * outStride] = tempReal;
         } else {
            outReal[outIdx++ * outStride] = 0.0;
         }
         /* Slide the window one bar in O(1). Advancing it ages every retained
          * value by one bar, which raises each of their weights by 1 and so adds
          * the whole deviation sum; the departing value leaves at the full weight
          * optInTimePeriod-1 and also loses its place in that sum, which is the
          * remaining -1. The two together are exactly -optInTimePeriod*trailingX,
          * and sumX must still be the COMPLETE window's sum when it is read here
          * -- it is decremented on the line below, not above.
          */
         leavingX = trailingX * trailingX;
         sumXY = sumXY + sumX - dPeriod * trailingX;
         sumX -= trailingX;
         sumX2 -= leavingX;
         today += 1;
      } while( today <= endIdx );
      outNBElement = outIdx;
      /* Capture the live batch state into the handle. */
      int capX = today - trailingIdx + 1;
      if( capX < 1 || capX > historyLen ) {
         return RetCode.InternalError;
      }
      int physX = 1;
      while( physX < capX ) {
         physX <<= 1;
      }
      double[] capX_inReal = new double[physX];
      for( int fillJ = historyLen - capX; fillJ < historyLen; fillJ++ ) {
         capX_inReal[fillJ & (physX - 1)] = inReal[fillJ];
      }
      sp.optInTimePeriod = optInTimePeriod;
      sp.sumX = sumX;
      sp.sumX2 = sumX2;
      sp.sumXY = sumXY;
      sp.leavingX = leavingX;
      sp.shift = shift;
      sp.invPeriod = invPeriod;
      sp.dPeriod = dPeriod;
      sp.sumY = sumY;
      sp.ssY = ssY;
      sp.lookbackTotal = lookbackTotal;
      sp.trailingIdx = trailingIdx;
      sp.barsSinceReseed = barsSinceReseed;
      sp.j = j;
      sp.today = today;
      sp.xMask = physX - 1;
      sp.x_inReal = capX_inReal;
      sp.cur_outReal = outReal[(outNBElement - 1) * outStride];
      return RetCode.Success;
   }

   /* CtiOpenAndFill anchored at startIdx — the composed-open fusion seam. */
   internal CtiStream CtiOpenAndFillInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod, out int outBegIdx, out int outNBElement, Span<double> outReal )
   {
      CtiStream sp = new CtiStream(this);
      RetCode retCode = CtiOpenImpl(sp, inReal, startIdx, optInTimePeriod, out outBegIdx, out outNBElement, outReal, 1);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("CTI", "openAndFill", retCode);
   }

   /* Internal startIdx-anchored open behind CtiOpen (composition seam). */
   internal CtiStream CtiOpenInternal( ReadOnlySpan<double> inReal, int startIdx, int optInTimePeriod )
   {
      CtiStream sp = new CtiStream(this);
      double[] sink_outReal = new double[1];
      RetCode retCode = CtiOpenImpl(sp, inReal, startIdx, optInTimePeriod, out int outBegIdx, out int outNBElement, sink_outReal, 0);
      sp.outRangeBegIdx = outBegIdx;
      sp.outRangeCount = outNBElement;
      if( retCode == RetCode.Success ) {
         return sp;
      }
      throw StreamFailure("CTI", "open", retCode);
   }

   /// <summary>Open a live <c>CTI</c> stream over the warm-up history.</summary>
   /// <remarks>
   /// <para>The handle's <see cref="CtiStream.Value"/> starts at the last history
   /// bar's value — bit-identical to what <c>CTI</c> reports for that bar.</para>
   /// <para>The history must hold at least <c>CtiLookback(...) + 1</c> bars
   /// (unstable-period aware). Nothing is written to any caller array; use
   /// <c>CtiOpenAndFill</c> to get the warm-up values as well.</para>
   /// </remarks>
   /// <param name="inReal">The series to measure the trend of. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="CtiLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <returns>The open stream handle.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>CtiLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MaxIndex"/> + 1, the
   /// two index faults an opener can have (rules S1 and S2).</exception>
   public CtiStream CtiOpen( ReadOnlySpan<double> inReal, int optInTimePeriod )
   {
      if( inReal.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "CTI open: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MaxIndex + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "CTI open: history is longer than MaxIndex + 1", RetCode.OutOfRangeEndIndex);
      return CtiOpenInternal(inReal, 0, optInTimePeriod);
   }

   /// <summary><c>CtiOpen</c> that also fills the output array(s) over the whole history
   /// in the same single pass.</summary>
   /// <remarks>
   /// <para>The values written are bit-identical to what <c>CTI</c> produces over the
   /// same series, so no separate batch call is needed for the warm-up plot.</para>
   /// <para>Output arrays must hold <c>historyLen - CtiLookback(...)</c> values and
   /// must not alias the inputs or each other — this path writes the outputs and
   /// then reads the input tail to seed its rings, so the batch tier's in-place
   /// allowance does not carry over here. Both are checked before anything is
   /// written, so an undersized span is an <c>ArgumentException</c> naming it
   /// rather than a fault from inside the fill.</para>
   /// <para>The range written is reported on the returned handle:
   /// <see cref="CtiStream.OutRange"/>.</para>
   /// </remarks>
   /// <param name="inReal">The series to measure the trend of. The warm-up history, oldest bar first.</param>
   /// <param name="optInTimePeriod">As in the batch call; see <see cref="CtiLookback"/> for its default and
   /// range (<c>int.MinValue</c> selects the default).</param>
   /// <param name="outReal">Correlation against the ramp, in -1..+1. Must hold at least <c>historyLen
   /// - CtiLookback(...)</c> values.</param>
   /// <returns>The open stream handle, with its fill range set.</returns>
   /// <exception cref="InsufficientHistoryException">The history holds fewer than <c>CtiLookback(...) + 1</c> bars.</exception>
   /// <exception cref="System.ArgumentException">An optional parameter is outside its documented range, the input series
   /// have different lengths, an output is shorter than the values the fill
   /// writes, or an output array aliases an input or another output.</exception>
   /// <exception cref="System.ArgumentOutOfRangeException">The history is empty — which is what a null array becomes, since a span
   /// cannot be null — or it is longer than <see cref="Core.MaxIndex"/> + 1, the
   /// two index faults an opener can have (rules S1 and S2).</exception>
   public CtiStream CtiOpenAndFill( ReadOnlySpan<double> inReal, int optInTimePeriod, Span<double> outReal )
   {
      if( inReal.IsEmpty ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "CTI openAndFill: history is empty", RetCode.OutOfRangeStartIndex);
      if( inReal.Length > MaxIndex + 1 ) throw new TALibArgumentOutOfRangeException(nameof(inReal), "CTI openAndFill: history is longer than MaxIndex + 1", RetCode.OutOfRangeEndIndex);
      int guardOutLen = OpenFillCount("CTI", "openAndFill", inReal.Length, CtiLookback(optInTimePeriod));
      RequireFillLength("CTI", "openAndFill", "outReal", outReal.Length, guardOutLen);
      if( outReal.Overlaps(inReal) ) {
         throw StreamFailure("CTI", "openAndFill", RetCode.BadParam);
      }
      return CtiOpenAndFillInternal(inReal, 0, optInTimePeriod, out _, out _, outReal);
   }
