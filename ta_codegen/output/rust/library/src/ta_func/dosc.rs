    /// * `optInTimePeriod` — Period of the RSI (default 14, range 2..=100000)
    /// * `optInFirstPeriod` — Period of the first smoothing, applied to the RSI (default 5, range
    ///   2..=100000)
    /// * `optInSecondPeriod` — Period of the second smoothing, applied to the first (default 3,
    ///   range 2..=100000)
    /// * `optInSignalPeriod` — Period of the simple average subtracted from the smoothed line
