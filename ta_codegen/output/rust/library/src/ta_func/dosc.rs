    ///
    /// # See also
    ///
    /// [`RSI`](Core::rsi) · [`STOCHRSI`](Core::stochrsi) · [`MACD`](Core::macd) ·
    /// [`AC`](Core::ac)
    ///
    /// # References
    ///
    /// * Constance M. Brown, "The Derivative Oscillator: A New Approach for an Old Problem", *MTA
