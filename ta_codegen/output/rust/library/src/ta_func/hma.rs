#[allow(unused_parens)]
impl Core {
    fn hma_step_impl(sp: &mut HmaStreamState, inReal: f64, outReal: &mut f64) {
        if sp.optInTimePeriod == 1 {
            (*outReal) = inReal;
            return;
        }
        if sp.optInTimePeriod == 2 || sp.optInTimePeriod == 3 {
            let mut tempReal: f64 = 0.0_f64;
            let mut fullOut: f64 = 0.0_f64;
            let mut jFull: usize = 0_usize;
            let mut rw: usize = 0_usize;
            let mut tempReal2: f64 = 0.0_f64;
            if sp.ringCap_trailingIdxFull == 0 {
                sp.ring_trailingIdxFull_inReal[0] = inReal;
            }
            sp.win_jFull_inReal[sp.winPos_jFull] = inReal;
            tempReal = inReal;
            sp.periodSubFull += tempReal;
            sp.periodSubFull -= sp.trailingFull;
            sp.periodSumFull += tempReal * ((sp.optInTimePeriod) as f64);
            sp.barsSinceReseedFull -= 1;
            if sp.barsSinceReseedFull <= 0 {
                sp.barsSinceReseedFull = (8 * sp.optInTimePeriod) as usize;
                sp.periodSubFull = 0.0;
                sp.periodSumFull = 0.0;
                rw = 1;
                // for( jFull = sp.lookbackFull; jFull >= 0; jFull -= 1 )
                jFull = sp.lookbackFull;
                loop {
                    tempReal2 = sp.win_jFull_inReal[((if sp.winPos_jFull + sp.winCap_jFull - jFull >= sp.winCap_jFull { sp.winPos_jFull + sp.winCap_jFull - jFull - sp.winCap_jFull } else { sp.winPos_jFull + sp.winCap_jFull - jFull })) as usize];
                    sp.periodSubFull += tempReal2;
                    sp.periodSumFull += tempReal2 * ((rw) as f64);
                    rw += 1;
                    if jFull == 0 { break; }
                    jFull -= 1;
                }
            }
            sp.trailingFull = sp.ring_trailingIdxFull_inReal[sp.ringPos_trailingIdxFull];
            fullOut = sp.periodSumFull / sp.dividerFull;
            sp.periodSumFull -= sp.periodSubFull;
            (*outReal) = 2.0 * tempReal - fullOut;
            sp.ring_trailingIdxFull_inReal[sp.ringPos_trailingIdxFull] = inReal;
            sp.ringPos_trailingIdxFull = sp.ringPos_trailingIdxFull + 1;
            if sp.ringPos_trailingIdxFull >= sp.ringCap_trailingIdxFull {
                sp.ringPos_trailingIdxFull = 0;
            }
            sp.winPos_jFull = sp.winPos_jFull + 1;
            if sp.winPos_jFull >= sp.winCap_jFull {
                sp.winPos_jFull = 0;
            }
        } else {
            let mut tempReal: f64 = 0.0_f64;
            let mut fullOut: f64 = 0.0_f64;
            let mut halfOut: f64 = 0.0_f64;
            let mut diffReal: f64 = 0.0_f64;
            let mut jFull: usize = 0_usize;
            let mut jHalf: usize = 0_usize;
            let mut q: usize = 0_usize;
            let mut rw: usize = 0_usize;
            let mut ringWalk: usize = 0_usize;
            let mut tempReal2: f64 = 0.0_f64;
            if sp.ringCap_trailingIdxFull == 0 {
                sp.ring_trailingIdxFull_inReal[0] = inReal;
            }
            if sp.ringCap_trailingIdxHalf == 0 {
                sp.ring_trailingIdxHalf_inReal[0] = inReal;
            }
            sp.win_jFull_inReal[sp.winPos_jFull] = inReal;
            sp.win_jHalf_inReal[sp.winPos_jHalf] = inReal;
            tempReal = inReal;
            sp.periodSubFull += tempReal;
            sp.periodSubFull -= sp.trailingFull;
            sp.periodSumFull += tempReal * ((sp.optInTimePeriod) as f64);
            sp.barsSinceReseedFull -= 1;
            if sp.barsSinceReseedFull <= 0 {
                sp.barsSinceReseedFull = (8 * sp.optInTimePeriod) as usize;
                sp.periodSubFull = 0.0;
                sp.periodSumFull = 0.0;
                rw = 1;
                // for( jFull = sp.lookbackFull; jFull >= 0; jFull -= 1 )
                jFull = sp.lookbackFull;
                loop {
                    tempReal2 = sp.win_jFull_inReal[((if sp.winPos_jFull + sp.winCap_jFull - jFull >= sp.winCap_jFull { sp.winPos_jFull + sp.winCap_jFull - jFull - sp.winCap_jFull } else { sp.winPos_jFull + sp.winCap_jFull - jFull })) as usize];
                    sp.periodSubFull += tempReal2;
                    sp.periodSumFull += tempReal2 * ((rw) as f64);
                    rw += 1;
                    if jFull == 0 { break; }
                    jFull -= 1;
                }
            }
            sp.trailingFull = sp.ring_trailingIdxFull_inReal[sp.ringPos_trailingIdxFull];
            fullOut = sp.periodSumFull / sp.dividerFull;
            sp.periodSumFull -= sp.periodSubFull;
            sp.periodSubHalf += tempReal;
            sp.periodSubHalf -= sp.trailingHalf;
            sp.periodSumHalf += tempReal * ((sp.halfPeriod) as f64);
            sp.barsSinceReseedHalf -= 1;
            if sp.barsSinceReseedHalf <= 0 {
                sp.barsSinceReseedHalf = 8 * sp.halfPeriod;
                sp.periodSubHalf = 0.0;
                sp.periodSumHalf = 0.0;
                rw = 1;
                // for( jHalf = sp.lookbackHalf; jHalf >= 0; jHalf -= 1 )
                jHalf = sp.lookbackHalf;
                loop {
                    tempReal2 = sp.win_jHalf_inReal[((if sp.winPos_jHalf + sp.winCap_jHalf - jHalf >= sp.winCap_jHalf { sp.winPos_jHalf + sp.winCap_jHalf - jHalf - sp.winCap_jHalf } else { sp.winPos_jHalf + sp.winCap_jHalf - jHalf })) as usize];
                    sp.periodSubHalf += tempReal2;
                    sp.periodSumHalf += tempReal2 * ((rw) as f64);
                    rw += 1;
                    if jHalf == 0 { break; }
                    jHalf -= 1;
                }
            }
            sp.trailingHalf = sp.ring_trailingIdxHalf_inReal[sp.ringPos_trailingIdxHalf];
            halfOut = sp.periodSumHalf / sp.dividerHalf;
            sp.periodSumHalf -= sp.periodSubHalf;
            diffReal = 2.0 * halfOut - fullOut;
            sp.periodSubSqrt += diffReal;
            sp.periodSubSqrt -= sp.trailingSqrt;
            sp.periodSumSqrt += diffReal * ((sp.sqrtPeriod) as f64);
            // The outer WMA consumes a DERIVED series that is never
            // materialised, so its rescan walks the de-lag ring: dRing_Idx is
            // the oldest slot (the one about to expire) and diffReal is the
            // newest value, which together are the whole window. Oldest first,
            // weight counting up from 1 -- the priming order above.
            sp.barsSinceReseedSqrt -= 1;
            if sp.barsSinceReseedSqrt <= 0 {
                sp.barsSinceReseedSqrt = 8 * sp.sqrtPeriod;
                sp.periodSubSqrt = 0.0;
                sp.periodSumSqrt = 0.0;
                rw = 1;
                ringWalk = sp.dRing_Idx;
                // for( q = 0; q < sp.ringSize; q += 1 )
                q = 0;
                while q < sp.ringSize {
                    tempReal2 = sp.cb_dRing[ringWalk];
                    sp.periodSubSqrt += tempReal2;
                    sp.periodSumSqrt += tempReal2 * ((rw) as f64);
                    rw += 1;
                    ringWalk += 1;
                    if ringWalk >= sp.ringSize {
                        ringWalk = 0;
                    }
                    q += 1;
                }
                sp.periodSubSqrt += diffReal;
                sp.periodSumSqrt += diffReal * ((sp.sqrtPeriod) as f64);
            }
            sp.trailingSqrt = sp.cb_dRing[sp.dRing_Idx];
            sp.cb_dRing[sp.dRing_Idx] = diffReal;
            sp.dRing_Idx = sp.dRing_Idx + 1;
            if sp.dRing_Idx > sp.maxIdx_dRing {
                sp.dRing_Idx = 0;
            }
            (*outReal) = sp.periodSumSqrt / sp.dividerSqrt;
            sp.periodSumSqrt -= sp.periodSubSqrt;
            sp.ring_trailingIdxFull_inReal[sp.ringPos_trailingIdxFull] = inReal;
            sp.ringPos_trailingIdxFull = sp.ringPos_trailingIdxFull + 1;
            if sp.ringPos_trailingIdxFull >= sp.ringCap_trailingIdxFull {
                sp.ringPos_trailingIdxFull = 0;
            }
            sp.ring_trailingIdxHalf_inReal[sp.ringPos_trailingIdxHalf] = inReal;
            sp.ringPos_trailingIdxHalf = sp.ringPos_trailingIdxHalf + 1;
            if sp.ringPos_trailingIdxHalf >= sp.ringCap_trailingIdxHalf {
                sp.ringPos_trailingIdxHalf = 0;
            }
            sp.winPos_jFull = sp.winPos_jFull + 1;
            if sp.winPos_jFull >= sp.winCap_jFull {
                sp.winPos_jFull = 0;
            }
            sp.winPos_jHalf = sp.winPos_jHalf + 1;
            if sp.winPos_jHalf >= sp.winCap_jHalf {
                sp.winPos_jHalf = 0;
            }
        }
    }

    /// The single whole-history transcription behind [`Core::hma_open_internal`]
    /// (stride 0, scalar sink) and [`Core::hma_open_and_fill`] (stride 1, caller slices).
    pub(crate) fn hma_open_impl(
        &self, inReal: &[f64], startIdx: usize, mut optInTimePeriod: i32, outBegIdx: &mut usize, outNBElement: &mut usize, outReal: &mut [f64], outStride: usize,
    ) -> Result<HmaStream, RetCode> {
        if inReal.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inReal.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        if ((optInTimePeriod) as i32) == (i32::MIN) {
            optInTimePeriod = 20;
        } else if (((optInTimePeriod) as i32) < 1) || (((optInTimePeriod) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        let historyLen: usize = inReal.len();
        let endIdx: usize = historyLen - 1;
        let mut startIdx = startIdx;
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        if optInTimePeriod == 1 {
            let fillLb: usize = self.HMA_Lookback(optInTimePeriod)?;
            let fillLb = if startIdx > fillLb { startIdx } else { fillLb };
            if historyLen < fillLb + 1 {
                return Err(RetCode::InsufficientHistory);
            }
            let state = HmaStreamState {
                optInTimePeriod: optInTimePeriod,
                dividerFull: 0.0_f64,
                periodSubFull: 0.0_f64,
                periodSumFull: 0.0_f64,
                trailingFull: 0.0_f64,
                lookbackFull: 0_usize,
                barsSinceReseedFull: 0_usize,
                halfPeriod: 0_usize,
                sqrtPeriod: 0_usize,
                ringSize: 0_usize,
                dividerHalf: 0.0_f64,
                dividerSqrt: 0.0_f64,
                periodSubHalf: 0.0_f64,
                periodSumHalf: 0.0_f64,
                trailingHalf: 0.0_f64,
                periodSubSqrt: 0.0_f64,
                periodSumSqrt: 0.0_f64,
                trailingSqrt: 0.0_f64,
                lookbackHalf: 0_usize,
                barsSinceReseedHalf: 0_usize,
                barsSinceReseedSqrt: 0_usize,
                dRing_Idx: 0_usize,
                maxIdx_dRing: 0_usize,
                ringPos_trailingIdxFull: 0_usize,
                ringCap_trailingIdxFull: 0_usize,
                ring_trailingIdxFull_inReal: vec![0.0_f64; 1],
                winPos_jFull: 0_usize,
                winCap_jFull: 1_usize,
                win_jFull_inReal: vec![0.0_f64; 1],
                ringPos_trailingIdxHalf: 0_usize,
                ringCap_trailingIdxHalf: 0_usize,
                ring_trailingIdxHalf_inReal: vec![0.0_f64; 1],
                winPos_jHalf: 0_usize,
                winCap_jHalf: 1_usize,
                win_jHalf_inReal: vec![0.0_f64; 1],
                cbSize_dRing: 0_usize,
                cb_dRing: Vec::new(),
            };
            (*outBegIdx) = fillLb;
            (*outNBElement) = historyLen - fillLb;
            if outStride == 0 {
                outReal[0] = inReal[historyLen - 1];
            } else {
                let mut fillIdx: usize = 0;
                while fillIdx < historyLen - fillLb {
                    outReal[fillIdx] = inReal[fillLb + fillIdx];
                    fillIdx += 1;
                }
            }
            return Ok(HmaStream { state, out: OutRange { beg_idx: *outBegIdx, count: *outNBElement } });
        }
        if optInTimePeriod == 2 || optInTimePeriod == 3 {
            let mut lookbackTotal: usize = 0_usize;
            let mut lookbackSqrt: usize = 0_usize;
            let mut halfPeriod: usize = 0_usize;
            let mut sqrtPeriod: usize = 0_usize;
            let mut ringSize: usize = 0_usize;
            let mut wmaStartIdx: usize = 0_usize;
            let mut today: usize = 0_usize;
            let mut outIdx: usize = 0_usize;
            let mut i: usize = 0_usize;
            let mut w: usize = 0_usize;
            let mut dividerFull: f64 = 0.0_f64;
            let mut dividerHalf: f64 = 0.0_f64;
            let mut dividerSqrt: f64 = 0.0_f64;
            let mut trailingIdxFull: usize = 0_usize;
            let mut trailingIdxHalf: usize = 0_usize;
            let mut periodSubFull: f64 = 0.0_f64;
            let mut periodSumFull: f64 = 0.0_f64;
            let mut trailingFull: f64 = 0.0_f64;
            let mut periodSubHalf: f64 = 0.0_f64;
            let mut periodSumHalf: f64 = 0.0_f64;
            let mut trailingHalf: f64 = 0.0_f64;
            let mut periodSubSqrt: f64 = 0.0_f64;
            let mut periodSumSqrt: f64 = 0.0_f64;
            let mut trailingSqrt: f64 = 0.0_f64;
            let mut tempReal: f64 = 0.0_f64;
            let mut fullOut: f64 = 0.0_f64;
            let mut halfOut: f64 = 0.0_f64;
            let mut diffReal: f64 = 0.0_f64;
            let mut jFull: usize = 0_usize;
            let mut jHalf: usize = 0_usize;
            let mut q: usize = 0_usize;
            let mut rw: usize = 0_usize;
            let mut ringWalk: usize = 0_usize;
            let mut lookbackFull: usize = 0_usize;
            let mut lookbackHalf: usize = 0_usize;
            let mut barsSinceReseedFull: usize = 0_usize;
            let mut barsSinceReseedHalf: usize = 0_usize;
            let mut barsSinceReseedSqrt: usize = 0_usize;
            let mut tempReal2: f64 = 0.0_f64;
            let mut dRing: Vec<f64> = Vec::new();
            let mut dRing_Idx: usize = 0;
            let mut maxIdx_dRing: usize = 49;
            // The de-lagged series needs only its last sqrt(n) values, so the whole
            // computation runs in one pass over a single window into the input:
            // three interleaved WMA rolling sums plus this small ring. The ring has
            // sqrt(n)-1 slots: on the stack while that fits the 50-slot prolog
            // (optInTimePeriod <= 2703), TA_Malloc from optInTimePeriod = 2704 up.
            // Hull Moving Average (Alan Hull, 2005):
            //
            //    HMA(n) = WMA( 2*WMA(price, Integer(n/2)) - WMA(price, n), Integer(SquareRoot(n)) )
            //
            // Both derived periods use the author's Integer() truncation; some other
            // published sources round to nearest instead, which is a visibly different
            // line. See hma.md and issue #139.
            //
            // Each of the three WMAs keeps TA_WMA's exact accumulation order
            // (periodSub/periodSum, lagged trailing subtract), so this fused pass is
            // BIT-IDENTICAL to composing three TA_WMA calls -- the composite
            // differential in test_composite.c holds it to that, memcmp-exact.
            halfPeriod = (optInTimePeriod / 2) as usize;
            sqrtPeriod = ((optInTimePeriod as f64).sqrt() as usize) as usize;
            lookbackSqrt = self.WMA_Lookback((sqrtPeriod) as i32)?;
            lookbackTotal = self.WMA_Lookback(optInTimePeriod)? + lookbackSqrt;
            // Move up the start index if there is not
            // enough initial data.
            if startIdx < lookbackTotal {
                startIdx = lookbackTotal;
            }
            // Make sure there is still something to evaluate.
            if startIdx > endIdx {
                (*outBegIdx) = 0;
                (*outNBElement) = 0;
                return Err(RetCode::InsufficientHistory);
            }
            // The two price WMAs are anchored where the first de-lagged value is
            // needed: lookbackSqrt bars before the first requested output.
            // wmaStartIdx >= optInTimePeriod-1 is implied by the clamp above.
            wmaStartIdx = startIdx - lookbackSqrt;
            dividerFull = (optInTimePeriod as f64) * (((optInTimePeriod + 1)) as f64) / 2.0;
            // Prime the full-period WMA over the optInTimePeriod-1 bars before
            // wmaStartIdx, exactly as TA_WMA does (weights 1..period-1).
            lookbackFull = (optInTimePeriod - 1) as usize;
            periodSubFull = 0.0;
            periodSumFull = 0.0;
            trailingIdxFull = wmaStartIdx - lookbackFull;
            i = trailingIdxFull;
            w = 1;
            while i < wmaStartIdx {
                tempReal = inReal[i];
                i += 1;
                periodSubFull += tempReal;
                periodSumFull += tempReal * ((w) as f64);
                w += 1;
            }
            barsSinceReseedFull = (8 * optInTimePeriod) as usize;
            trailingFull = 0.0;
            outIdx = 0;
            // sqrtPeriod == 1 exactly when optInTimePeriod is 2 or 3; stated on the
            // param so the stream analyzer sees a param-pure dual-mode split.
            // Degenerate regime, optInTimePeriod 2 or 3 only: halfPeriod and
            // sqrtPeriod are both 1, and a period-1 WMA is the identity (TA_WMA's
            // own short-circuit). The whole formula collapses to
            //    HMA[t] = 2*price[t] - WMA(price, n)[t]
            // with no de-lag ring at all. In-place note: the output store lands on
            // the SAME slot the trailing read just consumed (zero margin), so the
            // read stays ordered before the store.
            for today in (startIdx as usize)..(endIdx as usize) + 1 {
                tempReal = inReal[today];
                periodSubFull += tempReal;
                periodSubFull -= trailingFull;
                periodSumFull += tempReal * ((optInTimePeriod) as f64);
                barsSinceReseedFull -= 1;
                if barsSinceReseedFull <= 0 {
                    barsSinceReseedFull = (8 * optInTimePeriod) as usize;
                    periodSubFull = 0.0;
                    periodSumFull = 0.0;
                    rw = 1;
                    for jFull in (today - lookbackFull as usize)..(today as usize) + 1 {
                        tempReal2 = inReal[jFull];
                        periodSubFull += tempReal2;
                        periodSumFull += tempReal2 * ((rw) as f64);
                        rw += 1;
                    }
                    jFull = (today as usize) + 1;
                }
                trailingFull = inReal[trailingIdxFull];
                trailingIdxFull += 1;
                fullOut = periodSumFull / dividerFull;
                periodSumFull -= periodSubFull;
                outReal[({ let _v = outIdx; outIdx += 1; _v } * outStride) as usize] = 2.0 * tempReal - fullOut;
            }
            today = (endIdx as usize) + 1;
            (*outBegIdx) = startIdx;
            (*outNBElement) = outIdx;

            // Capture the live batch state into the handle.
            let cap_trailingIdxFull: i64 = (today as i64) - (trailingIdxFull as i64);
            if cap_trailingIdxFull < 0 || cap_trailingIdxFull > historyLen as i64 {
                return Err(RetCode::InternalError);
            }
            let allocN_trailingIdxFull: usize = if cap_trailingIdxFull > 0 { cap_trailingIdxFull as usize } else { 1 };
            let mut ring_trailingIdxFull_inReal: Vec<f64> = vec![0.0_f64; allocN_trailingIdxFull];
            ring_trailingIdxFull_inReal[..cap_trailingIdxFull as usize]
                .copy_from_slice(&inReal[historyLen - cap_trailingIdxFull as usize..]);
            let cap_jFull: i64 = (lookbackFull + 1) as i64;
            if cap_jFull < 1 || cap_jFull > historyLen as i64 {
                return Err(RetCode::InternalError);
            }
            let mut win_jFull_inReal: Vec<f64> = vec![0.0_f64; cap_jFull as usize];
            win_jFull_inReal.copy_from_slice(&inReal[historyLen - cap_jFull as usize..]);
            let state = HmaStreamState {
                optInTimePeriod,
                dividerFull,
                periodSubFull,
                periodSumFull,
                trailingFull,
                lookbackFull,
                barsSinceReseedFull,
                halfPeriod,
                sqrtPeriod,
                ringSize,
                dividerHalf,
                dividerSqrt,
                periodSubHalf,
                periodSumHalf,
                trailingHalf,
                periodSubSqrt,
                periodSumSqrt,
                trailingSqrt,
                lookbackHalf,
                barsSinceReseedHalf,
                barsSinceReseedSqrt,
                dRing_Idx,
                maxIdx_dRing,
                ringPos_trailingIdxFull: 0_usize,
                ringCap_trailingIdxFull: cap_trailingIdxFull as usize,
                ring_trailingIdxFull_inReal,
                winPos_jFull: 0_usize,
                winCap_jFull: cap_jFull as usize,
                win_jFull_inReal,
                ringPos_trailingIdxHalf: 0_usize,
                ringCap_trailingIdxHalf: 0_usize,
                ring_trailingIdxHalf_inReal: vec![0.0_f64; 1],
                winPos_jHalf: 0_usize,
                winCap_jHalf: 1_usize,
                win_jHalf_inReal: vec![0.0_f64; 1],
                cbSize_dRing: 0_usize,
                cb_dRing: Vec::new(),
            };
            Ok(HmaStream { state, out: OutRange { beg_idx: *outBegIdx, count: *outNBElement } })
        } else {
            let mut lookbackTotal: usize = 0_usize;
            let mut lookbackSqrt: usize = 0_usize;
            let mut halfPeriod: usize = 0_usize;
            let mut sqrtPeriod: usize = 0_usize;
            let mut ringSize: usize = 0_usize;
            let mut wmaStartIdx: usize = 0_usize;
            let mut today: usize = 0_usize;
            let mut outIdx: usize = 0_usize;
            let mut i: usize = 0_usize;
            let mut w: usize = 0_usize;
            let mut dividerFull: f64 = 0.0_f64;
            let mut dividerHalf: f64 = 0.0_f64;
            let mut dividerSqrt: f64 = 0.0_f64;
            let mut trailingIdxFull: usize = 0_usize;
            let mut trailingIdxHalf: usize = 0_usize;
            let mut periodSubFull: f64 = 0.0_f64;
            let mut periodSumFull: f64 = 0.0_f64;
            let mut trailingFull: f64 = 0.0_f64;
            let mut periodSubHalf: f64 = 0.0_f64;
            let mut periodSumHalf: f64 = 0.0_f64;
            let mut trailingHalf: f64 = 0.0_f64;
            let mut periodSubSqrt: f64 = 0.0_f64;
            let mut periodSumSqrt: f64 = 0.0_f64;
            let mut trailingSqrt: f64 = 0.0_f64;
            let mut tempReal: f64 = 0.0_f64;
            let mut fullOut: f64 = 0.0_f64;
            let mut halfOut: f64 = 0.0_f64;
            let mut diffReal: f64 = 0.0_f64;
            let mut jFull: usize = 0_usize;
            let mut jHalf: usize = 0_usize;
            let mut q: usize = 0_usize;
            let mut rw: usize = 0_usize;
            let mut ringWalk: usize = 0_usize;
            let mut lookbackFull: usize = 0_usize;
            let mut lookbackHalf: usize = 0_usize;
            let mut barsSinceReseedFull: usize = 0_usize;
            let mut barsSinceReseedHalf: usize = 0_usize;
            let mut barsSinceReseedSqrt: usize = 0_usize;
            let mut tempReal2: f64 = 0.0_f64;
            let mut dRing: Vec<f64> = Vec::new();
            let mut dRing_Idx: usize = 0;
            let mut maxIdx_dRing: usize = 49;
            // The de-lagged series needs only its last sqrt(n) values, so the whole
            // computation runs in one pass over a single window into the input:
            // three interleaved WMA rolling sums plus this small ring. The ring has
            // sqrt(n)-1 slots: on the stack while that fits the 50-slot prolog
            // (optInTimePeriod <= 2703), TA_Malloc from optInTimePeriod = 2704 up.
            // Hull Moving Average (Alan Hull, 2005):
            //
            //    HMA(n) = WMA( 2*WMA(price, Integer(n/2)) - WMA(price, n), Integer(SquareRoot(n)) )
            //
            // Both derived periods use the author's Integer() truncation; some other
            // published sources round to nearest instead, which is a visibly different
            // line. See hma.md and issue #139.
            //
            // Each of the three WMAs keeps TA_WMA's exact accumulation order
            // (periodSub/periodSum, lagged trailing subtract), so this fused pass is
            // BIT-IDENTICAL to composing three TA_WMA calls -- the composite
            // differential in test_composite.c holds it to that, memcmp-exact.
            halfPeriod = (optInTimePeriod / 2) as usize;
            sqrtPeriod = ((optInTimePeriod as f64).sqrt() as usize) as usize;
            lookbackSqrt = self.WMA_Lookback((sqrtPeriod) as i32)?;
            lookbackTotal = self.WMA_Lookback(optInTimePeriod)? + lookbackSqrt;
            // Move up the start index if there is not
            // enough initial data.
            if startIdx < lookbackTotal {
                startIdx = lookbackTotal;
            }
            // Make sure there is still something to evaluate.
            if startIdx > endIdx {
                (*outBegIdx) = 0;
                (*outNBElement) = 0;
                return Err(RetCode::InsufficientHistory);
            }
            // The two price WMAs are anchored where the first de-lagged value is
            // needed: lookbackSqrt bars before the first requested output.
            // wmaStartIdx >= optInTimePeriod-1 is implied by the clamp above.
            wmaStartIdx = startIdx - lookbackSqrt;
            dividerFull = (optInTimePeriod as f64) * (((optInTimePeriod + 1)) as f64) / 2.0;
            // Prime the full-period WMA over the optInTimePeriod-1 bars before
            // wmaStartIdx, exactly as TA_WMA does (weights 1..period-1).
            lookbackFull = (optInTimePeriod - 1) as usize;
            periodSubFull = 0.0;
            periodSumFull = 0.0;
            trailingIdxFull = wmaStartIdx - lookbackFull;
            i = trailingIdxFull;
            w = 1;
            while i < wmaStartIdx {
                tempReal = inReal[i];
                i += 1;
                periodSubFull += tempReal;
                periodSumFull += tempReal * ((w) as f64);
                w += 1;
            }
            barsSinceReseedFull = (8 * optInTimePeriod) as usize;
            trailingFull = 0.0;
            outIdx = 0;
            // sqrtPeriod == 1 exactly when optInTimePeriod is 2 or 3; stated on the
            // param so the stream analyzer sees a param-pure dual-mode split.
            // General regime: optInTimePeriod >= 4, so halfPeriod >= 2 and
            // sqrtPeriod >= 2 -- no period-1 special cases below this point.
            dividerHalf = (halfPeriod as f64) * (((halfPeriod + 1)) as f64) / 2.0;
            dividerSqrt = (sqrtPeriod as f64) * (((sqrtPeriod + 1)) as f64) / 2.0;
            // Prime the half-period WMA the same way.
            lookbackHalf = halfPeriod - 1;
            periodSubHalf = 0.0;
            periodSumHalf = 0.0;
            trailingIdxHalf = wmaStartIdx - lookbackHalf;
            i = trailingIdxHalf;
            w = 1;
            while i < wmaStartIdx {
                tempReal = inReal[i];
                i += 1;
                periodSubHalf += tempReal;
                periodSumHalf += tempReal * ((w) as f64);
                w += 1;
            }
            barsSinceReseedHalf = 8 * halfPeriod;
            trailingHalf = 0.0;
            // The de-lagged value computed at bar t is consumed as the outer WMA's
            // trailing value sqrtPeriod-1 bars later, so a single-cursor ring of
            // sqrtPeriod-1 slots is enough: read the expiring value, overwrite the
            // slot with the current one, advance.
            ringSize = sqrtPeriod - 1;
            if ringSize < 1 { return Err(RetCode::InternalError); }
            dRing = vec![0.0_f64; (ringSize) as usize];
            maxIdx_dRing = ((ringSize) as usize) - 1;
            dRing_Idx = 0;
            // Warm-up: the sqrtPeriod-1 de-lagged values before the first output
            // prime the outer WMA (weights 1..sqrtPeriod-1) and fill the ring.
            periodSubSqrt = 0.0;
            periodSumSqrt = 0.0;
            trailingSqrt = 0.0;
            w = 1;
            // for( today = wmaStartIdx; today < startIdx; today += 1 )
            today = wmaStartIdx;
            while today < startIdx {
                tempReal = inReal[today];
                periodSubFull += tempReal;
                periodSubFull -= trailingFull;
                periodSumFull += tempReal * ((optInTimePeriod) as f64);
                barsSinceReseedFull -= 1;
                if barsSinceReseedFull <= 0 {
                    barsSinceReseedFull = (8 * optInTimePeriod) as usize;
                    periodSubFull = 0.0;
                    periodSumFull = 0.0;
                    rw = 1;
                    for jFull in (today - lookbackFull as usize)..(today as usize) + 1 {
                        tempReal2 = inReal[jFull];
                        periodSubFull += tempReal2;
                        periodSumFull += tempReal2 * ((rw) as f64);
                        rw += 1;
                    }
                    jFull = (today as usize) + 1;
                }
                trailingFull = inReal[trailingIdxFull];
                trailingIdxFull += 1;
                fullOut = periodSumFull / dividerFull;
                periodSumFull -= periodSubFull;
                periodSubHalf += tempReal;
                periodSubHalf -= trailingHalf;
                periodSumHalf += tempReal * ((halfPeriod) as f64);
                barsSinceReseedHalf -= 1;
                if barsSinceReseedHalf <= 0 {
                    barsSinceReseedHalf = 8 * halfPeriod;
                    periodSubHalf = 0.0;
                    periodSumHalf = 0.0;
                    rw = 1;
                    for jHalf in (today - lookbackHalf as usize)..(today as usize) + 1 {
                        tempReal2 = inReal[jHalf];
                        periodSubHalf += tempReal2;
                        periodSumHalf += tempReal2 * ((rw) as f64);
                        rw += 1;
                    }
                    jHalf = (today as usize) + 1;
                }
                trailingHalf = inReal[trailingIdxHalf];
                trailingIdxHalf += 1;
                halfOut = periodSumHalf / dividerHalf;
                periodSumHalf -= periodSubHalf;
                diffReal = 2.0 * halfOut - fullOut;
                periodSubSqrt += diffReal;
                periodSumSqrt += diffReal * ((w) as f64);
                w += 1;
                dRing[dRing_Idx] = diffReal;
                dRing_Idx += 1;
                if dRing_Idx > maxIdx_dRing { dRing_Idx = 0; }
                today += 1;
            }
            barsSinceReseedSqrt = 8 * sqrtPeriod;
            // Steady state: one pass, three rolling WMAs. Writes trail every read by
            // at least sqrtPeriod-1 slots (the lookback clamp), so outReal == inReal
            // stays safe.
            for today in (startIdx as usize)..(endIdx as usize) + 1 {
                tempReal = inReal[today];
                periodSubFull += tempReal;
                periodSubFull -= trailingFull;
                periodSumFull += tempReal * ((optInTimePeriod) as f64);
                barsSinceReseedFull -= 1;
                if barsSinceReseedFull <= 0 {
                    barsSinceReseedFull = (8 * optInTimePeriod) as usize;
                    periodSubFull = 0.0;
                    periodSumFull = 0.0;
                    rw = 1;
                    for jFull in (today - lookbackFull as usize)..(today as usize) + 1 {
                        tempReal2 = inReal[jFull];
                        periodSubFull += tempReal2;
                        periodSumFull += tempReal2 * ((rw) as f64);
                        rw += 1;
                    }
                    jFull = (today as usize) + 1;
                }
                trailingFull = inReal[trailingIdxFull];
                trailingIdxFull += 1;
                fullOut = periodSumFull / dividerFull;
                periodSumFull -= periodSubFull;
                periodSubHalf += tempReal;
                periodSubHalf -= trailingHalf;
                periodSumHalf += tempReal * ((halfPeriod) as f64);
                barsSinceReseedHalf -= 1;
                if barsSinceReseedHalf <= 0 {
                    barsSinceReseedHalf = 8 * halfPeriod;
                    periodSubHalf = 0.0;
                    periodSumHalf = 0.0;
                    rw = 1;
                    for jHalf in (today - lookbackHalf as usize)..(today as usize) + 1 {
                        tempReal2 = inReal[jHalf];
                        periodSubHalf += tempReal2;
                        periodSumHalf += tempReal2 * ((rw) as f64);
                        rw += 1;
                    }
                    jHalf = (today as usize) + 1;
                }
                trailingHalf = inReal[trailingIdxHalf];
                trailingIdxHalf += 1;
                halfOut = periodSumHalf / dividerHalf;
                periodSumHalf -= periodSubHalf;
                diffReal = 2.0 * halfOut - fullOut;
                periodSubSqrt += diffReal;
                periodSubSqrt -= trailingSqrt;
                periodSumSqrt += diffReal * ((sqrtPeriod) as f64);
                // The outer WMA consumes a DERIVED series that is never
                // materialised, so its rescan walks the de-lag ring: dRing_Idx is
                // the oldest slot (the one about to expire) and diffReal is the
                // newest value, which together are the whole window. Oldest first,
                // weight counting up from 1 -- the priming order above.
                barsSinceReseedSqrt -= 1;
                if barsSinceReseedSqrt <= 0 {
                    barsSinceReseedSqrt = 8 * sqrtPeriod;
                    periodSubSqrt = 0.0;
                    periodSumSqrt = 0.0;
                    rw = 1;
                    ringWalk = dRing_Idx;
                    // for( q = 0; q < ringSize; q += 1 )
                    q = 0;
                    while q < ringSize {
                        tempReal2 = dRing[ringWalk];
                        periodSubSqrt += tempReal2;
                        periodSumSqrt += tempReal2 * ((rw) as f64);
                        rw += 1;
                        ringWalk += 1;
                        if ringWalk >= ringSize {
                            ringWalk = 0;
                        }
                        q += 1;
                    }
                    periodSubSqrt += diffReal;
                    periodSumSqrt += diffReal * ((sqrtPeriod) as f64);
                }
                trailingSqrt = dRing[dRing_Idx];
                dRing[dRing_Idx] = diffReal;
                dRing_Idx += 1;
                if dRing_Idx > maxIdx_dRing { dRing_Idx = 0; }
                outReal[({ let _v = outIdx; outIdx += 1; _v } * outStride) as usize] = periodSumSqrt / dividerSqrt;
                periodSumSqrt -= periodSubSqrt;
            }
            today = (endIdx as usize) + 1;
            (*outBegIdx) = startIdx;
            (*outNBElement) = outIdx;

            // Capture the live batch state into the handle.
            let cap_trailingIdxFull: i64 = (today as i64) - (trailingIdxFull as i64);
            if cap_trailingIdxFull < 0 || cap_trailingIdxFull > historyLen as i64 {
                return Err(RetCode::InternalError);
            }
            let allocN_trailingIdxFull: usize = if cap_trailingIdxFull > 0 { cap_trailingIdxFull as usize } else { 1 };
            let mut ring_trailingIdxFull_inReal: Vec<f64> = vec![0.0_f64; allocN_trailingIdxFull];
            ring_trailingIdxFull_inReal[..cap_trailingIdxFull as usize]
                .copy_from_slice(&inReal[historyLen - cap_trailingIdxFull as usize..]);
            let cap_trailingIdxHalf: i64 = (today as i64) - (trailingIdxHalf as i64);
            if cap_trailingIdxHalf < 0 || cap_trailingIdxHalf > historyLen as i64 {
                return Err(RetCode::InternalError);
            }
            let allocN_trailingIdxHalf: usize = if cap_trailingIdxHalf > 0 { cap_trailingIdxHalf as usize } else { 1 };
            let mut ring_trailingIdxHalf_inReal: Vec<f64> = vec![0.0_f64; allocN_trailingIdxHalf];
            ring_trailingIdxHalf_inReal[..cap_trailingIdxHalf as usize]
                .copy_from_slice(&inReal[historyLen - cap_trailingIdxHalf as usize..]);
            let cap_jFull: i64 = (lookbackFull + 1) as i64;
            if cap_jFull < 1 || cap_jFull > historyLen as i64 {
                return Err(RetCode::InternalError);
            }
            let mut win_jFull_inReal: Vec<f64> = vec![0.0_f64; cap_jFull as usize];
            win_jFull_inReal.copy_from_slice(&inReal[historyLen - cap_jFull as usize..]);
            let cap_jHalf: i64 = (lookbackHalf + 1) as i64;
            if cap_jHalf < 1 || cap_jHalf > historyLen as i64 {
                return Err(RetCode::InternalError);
            }
            let mut win_jHalf_inReal: Vec<f64> = vec![0.0_f64; cap_jHalf as usize];
            win_jHalf_inReal.copy_from_slice(&inReal[historyLen - cap_jHalf as usize..]);
            let cbSize_dRing: usize = maxIdx_dRing + 1;
            if cbSize_dRing > historyLen + 1 {
                return Err(RetCode::InternalError);
            }
            let state = HmaStreamState {
                optInTimePeriod,
                dividerFull,
                periodSubFull,
                periodSumFull,
                trailingFull,
                lookbackFull,
                barsSinceReseedFull,
                halfPeriod,
                sqrtPeriod,
                ringSize,
                dividerHalf,
                dividerSqrt,
                periodSubHalf,
                periodSumHalf,
                trailingHalf,
                periodSubSqrt,
                periodSumSqrt,
                trailingSqrt,
                lookbackHalf,
                barsSinceReseedHalf,
                barsSinceReseedSqrt,
                dRing_Idx,
                maxIdx_dRing,
                ringPos_trailingIdxFull: 0_usize,
                ringCap_trailingIdxFull: cap_trailingIdxFull as usize,
                ring_trailingIdxFull_inReal,
                ringPos_trailingIdxHalf: 0_usize,
                ringCap_trailingIdxHalf: cap_trailingIdxHalf as usize,
                ring_trailingIdxHalf_inReal,
                winPos_jFull: 0_usize,
                winCap_jFull: cap_jFull as usize,
                win_jFull_inReal,
                winPos_jHalf: 0_usize,
                winCap_jHalf: cap_jHalf as usize,
                win_jHalf_inReal,
                cbSize_dRing: cbSize_dRing,
                cb_dRing: dRing,
            };
            Ok(HmaStream { state, out: OutRange { beg_idx: *outBegIdx, count: *outNBElement } })
        }
    }

    /// Internal startIdx-anchored open behind [`Core::hma_open`] (composition seam).
    pub(crate) fn hma_open_internal(
        &self, inReal: &[f64], startIdx: usize, mut optInTimePeriod: i32,
    ) -> Result<(HmaStream, f64), RetCode> {
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut sink_outReal = [0.0_f64; 1];
        let handle = self.hma_open_impl(inReal, startIdx, optInTimePeriod, &mut dummyBegIdx, &mut dummyNBElement, &mut sink_outReal, 0)?;
        Ok((handle, sink_outReal[0]))
    }

    /// Open a live HMA stream over the warm-up history; returns the handle and
    /// the value at the last history bar — bit-identical to [`Core::HMA`] at that bar.
    ///
    /// # Errors
    ///
    /// [`RetCode::InsufficientHistory`] when the history holds fewer than
    /// `lookback + 1` bars — the one failure here worth retrying, since another
    /// bar fixes it. [`RetCode::OutOfRangeStartIndex`] when the history is empty.
    /// [`RetCode::BadParam`] when a parameter is out of range or the input
    /// lengths differ.
    ///
    /// ```
    /// use ta_lib::Core;
    /// let data: Vec<f64> = (0..252).map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    ///
    /// let core = Core::new();
    /// let (mut s, _last) = core.hma_open(&data, 20).expect("enough history");
    /// let r0 = s.out_range();
    /// let peeked = s.peek(100.9).expect("a finite bar");
    /// assert_eq!(s.out_range().count, r0.count); // a peek commits nothing
    /// let updated = s.update(100.9).expect("a finite bar");
    /// assert_eq!(s.out_range().beg_idx, r0.beg_idx);
    /// assert_eq!(s.out_range().count, r0.count + 1);
    /// assert_eq!(peeked.to_bits(), updated.to_bits());
    /// ```
    #[doc(alias = "TA_HMA_Open")]
    pub fn hma_open(&self, inReal: &[f64], optInTimePeriod: i32) -> Result<(HmaStream, f64), RetCode> {
        self.hma_open_internal(inReal, 0, optInTimePeriod)
    }

    /// [`Core::hma_open`] that also fills the output array(s) bit-identically to
    /// [`Core::HMA`] over `0..len` in the same single pass, and reports the range it
    /// wrote as the [`OutRange`] beside the handle.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] when an output slice holds fewer than `len - lookback`
    /// values — the batch tier's sizing rule, checked here as it is there (rule S5) —
    /// or when two of them are the same slice. Everything [`Core::hma_open`] rejects
    /// is rejected here too.
    ///
    /// # Examples
    ///
    /// ```
    /// use ta_lib::Core;
    /// let data: Vec<f64> = (0..252).map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    ///
    /// let core = Core::new();
    /// let mut batch_out = vec![0.0; 252];
    /// let batch = core.HMA(0, data.len() - 1, &data, 20, &mut batch_out)?;
    ///
    /// let mut out = vec![0.0; 252];
    /// let (_stream, filled) = core.hma_open_and_fill(&data, 20, &mut out)?;
    ///
    /// assert_eq!(filled.beg_idx, batch.beg_idx);
    /// assert_eq!(filled.count, batch.count);
    /// assert!(out[..filled.count].iter().zip(&batch_out[..batch.count])
    ///     .all(|(a, b)| a.to_bits() == b.to_bits()));
    /// # Ok::<(), ta_lib::RetCode>(())
    /// ```
    #[doc(alias = "TA_HMA_OpenAndFill")]
    pub fn hma_open_and_fill(
        &self, inReal: &[f64], mut optInTimePeriod: i32, outReal: &mut [f64],
    ) -> Result<(HmaStream, OutRange), RetCode> {
        if inReal.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inReal.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        let _guardLb = self.HMA_Lookback(optInTimePeriod)?;
        let _guardOutLen = inReal.len().saturating_sub(_guardLb);
        if outReal.len() < _guardOutLen {
            return Err(RetCode::BadParam);
        }
        let mut outBegIdx: usize = 0;
        let mut outNBElement: usize = 0;
        let handle = self.hma_open_and_fill_internal(inReal, 0, optInTimePeriod, &mut outBegIdx, &mut outNBElement, outReal)?;
        Ok((handle, OutRange { beg_idx: outBegIdx, count: outNBElement }))
    }

    /// [`Core::hma_open_and_fill`] anchored at `startIdx` — the composed-open
    /// fusion seam (issue #192), not a public entry point.
    pub(crate) fn hma_open_and_fill_internal(
        &self, inReal: &[f64], startIdx: usize, mut optInTimePeriod: i32, outBegIdx: &mut usize, outNBElement: &mut usize, outReal: &mut [f64],
    ) -> Result<HmaStream, RetCode> {
        self.hma_open_impl(inReal, startIdx, optInTimePeriod, outBegIdx, outNBElement, outReal, 1)
    }

}

thread_local! {
    /// `peek`'s reusable scratch state (see `HmaStreamState::restore_from`).
    /// Taken for the duration of the step and put back after, so a
    /// panicking step costs the scratch, never leaves it borrowed.
    static HMA_PEEK_SCRATCH: std::cell::Cell<Option<Box<HmaStreamState>>> =
        const { std::cell::Cell::new(None) };
}

#[allow(non_snake_case)]
#[allow(unused_variables)]
impl HmaStream {
    /// Commit one closed bar. Never allocates.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite (NaN or ±Inf).
    /// That check runs before anything is written, so the handle is left
    /// exactly as it was and the stream stays usable:
    /// skip the bar, or close and re-open on a clean history. This is the
    /// one place the streaming tier is stricter than the batch API, which
    /// computes on whatever it is given — a handle retains its state, so a
    /// single non-finite bar would poison every later value it produces.
    #[doc(alias = "TA_HMA_Update")]
    pub fn update(&mut self, inReal: f64) -> Result<f64, RetCode> {
        if !inReal.is_finite() {
            return Err(RetCode::BadParam);
        }
        let mut outReal: f64 = 0.0_f64;
        Core::hma_step_impl(&mut self.state, inReal, &mut outReal);
        if self.out.count < Core::MAX_INDEX {
            self.out.count += 1;
        }
        Ok(outReal)
    }

    /// Commit `n` closed bars and write their `n` values, in one call —
    /// exactly `n` back-to-back [`Self::update`] calls, with one set of
    /// argument checks instead of `n`. `n` is `inReal.len()`; the outputs must
    /// hold at least that many. Never allocates.
    ///
    /// [`Self::out_range`] counts what was committed, which is what makes the
    /// rejection below readable: there is no second out-parameter for it.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if the input slices differ in length, if an output
    /// is shorter than the bar count — neither commits anything — or if a bar
    /// is not finite. A non-finite bar `k` is rejected exactly as `update`
    /// rejects it: bars `0..k` stay committed and their values written, bar `k`
    /// and everything after it is not, and `out_range().count` has advanced by
    /// `k`.
    #[doc(alias = "TA_HMA_UpdateAndFill")]
    pub fn update_and_fill(&mut self, inReal: &[f64], outReal: &mut [f64]) -> Result<(), RetCode> {
        let barCount = inReal.len();
        if outReal.len() < barCount {
            return Err(RetCode::BadParam);
        }
        for i in 0..barCount {
            if !inReal[i].is_finite() {
                return Err(RetCode::BadParam);
            }
            Core::hma_step_impl(&mut self.state, inReal[i], &mut outReal[i]);
            if self.out.count < Core::MAX_INDEX {
                self.out.count += 1;
            }
        }
        Ok(())
    }

    /// Evaluate a forming bar without committing — bit-identical to what the
    /// next `update` with the same bar would return (it is the same code, run
    /// on a scratch copy of the state). Never writes the handle, so peeks may
    /// run concurrently with each other. The copy it runs on is held per thread and reused,
    /// so only the first peek of this function on a thread allocates.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite, exactly as
    /// `update` rejects it.
    #[doc(alias = "TA_HMA_Peek")]
    pub fn peek(&self, inReal: f64) -> Result<f64, RetCode> {
        if !inReal.is_finite() {
            return Err(RetCode::BadParam);
        }
        HMA_PEEK_SCRATCH.with(|cell| {
            let mut scratch = cell.take().unwrap_or_else(|| Box::new(self.state.clone()));
            scratch.restore_from(&self.state);
            let mut outReal: f64 = 0.0_f64;
            Core::hma_step_impl(&mut scratch, inReal, &mut outReal);
            cell.set(Some(scratch));
            Ok(outReal)
        })
    }

    /// The bars this stream has produced a value for, in the input series'
    /// coordinates: `[beg_idx, beg_idx + count)`.
    ///
    /// It is what [`Core::HMA`] reports over the same bars: the opener sets it
    /// to `(lookback, historyLen - lookback)`, every accepted `update` adds one
    /// to the count, `peek` leaves it alone, and a clone carries it verbatim.
    /// A plain `Open` hands back only the last value, a subset of this range,
    /// because the caller chose not to take the fill.
    #[doc(alias = "TA_StreamOutRange")]
    pub fn out_range(&self) -> OutRange {
        self.out
    }
}

