    fn aroon_step_impl(sp: &mut AroonStreamState, inHigh: f64, inLow: f64, outAroonDown: &mut f64, outAroonUp: &mut f64) {
        let mut tmp: f64 = 0.0_f64;
        if sp.today >= 1073741824 {
            let rebaseShift: i32 = sp.trailingIdx & !sp.xMask;
            sp.today -= rebaseShift;
            sp.trailingIdx -= rebaseShift;
            sp.highestIdx -= rebaseShift;
            sp.i -= rebaseShift;
            sp.lowestIdx -= rebaseShift;
        }
        sp.x_inHigh[(sp.today & sp.xMask) as usize] = inHigh;
        sp.x_inLow[(sp.today & sp.xMask) as usize] = inLow;
        // Keep track of the lowestIdx
        tmp = sp.x_inLow[(sp.today & sp.xMask) as usize];
        if sp.lowestIdx < sp.trailingIdx {
            sp.lowestIdx = sp.trailingIdx;
            sp.lowest = sp.x_inLow[(sp.lowestIdx & sp.xMask) as usize];
            sp.i = sp.lowestIdx;
            while (({ sp.i += 1; sp.i }) as i32) <= sp.today {
                tmp = sp.x_inLow[(sp.i & sp.xMask) as usize];
                if tmp <= sp.lowest {
                    sp.lowestIdx = sp.i;
                    sp.lowest = tmp;
                }
            }
        } else if tmp <= sp.lowest {
            sp.lowestIdx = sp.today;
            sp.lowest = tmp;
        }
        // Keep track of the highestIdx
        tmp = sp.x_inHigh[(sp.today & sp.xMask) as usize];
        if sp.highestIdx < sp.trailingIdx {
            sp.highestIdx = sp.trailingIdx;
            sp.highest = sp.x_inHigh[(sp.highestIdx & sp.xMask) as usize];
            sp.i = sp.highestIdx;
            while (({ sp.i += 1; sp.i }) as i32) <= sp.today {
                tmp = sp.x_inHigh[(sp.i & sp.xMask) as usize];
                if tmp >= sp.highest {
                    sp.highestIdx = sp.i;
                    sp.highest = tmp;
                }
            }
        } else if tmp >= sp.highest {
            sp.highestIdx = sp.today;
            sp.highest = tmp;
        }
        // Note: Do not forget that input and output buffer can be the same,
        //       so writing to the output is the last thing being done here.
        (*outAroonUp) = sp.factor * (((sp.optInTimePeriod - (sp.today - sp.highestIdx))) as f64);
        (*outAroonDown) = sp.factor * (((sp.optInTimePeriod - (sp.today - sp.lowestIdx))) as f64);
        sp.trailingIdx += 1;
        sp.today += 1;
        sp.cur_outAroonDown = (*outAroonDown);
        sp.cur_outAroonUp = (*outAroonUp);
    }

