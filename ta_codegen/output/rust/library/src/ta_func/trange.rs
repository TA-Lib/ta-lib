    /// True Range: the greatest of today's high-low span and the two gaps between yesterday's close
    /// and today's high/low. Base volatility measure used to build ATR/NATR. Larger values mean
    /// wider or gappier bars (higher volatility).
    ///
    /// # Formula
    ///
    /// ```text
    /// TR = max( high - low, |prevClose - high|, |prevClose - low| )
    /// ```
    ///
    /// # Notes
    ///
    /// * The first bar produces no value because it has no prior close; unlike some definitions, it
    ///   does not fall back to the high-low range for that bar.
    ///
    /// # Arguments
    ///
    /// * `startIdx` — Start index of the requested calculation range.
    /// * `endIdx` — End index of the requested calculation range (inclusive).
    /// * `inHigh` — High price of each bar.
    /// * `inLow` — Low price of each bar.
    /// * `inClose` — Close price of each bar.
    /// * `outBegIdx` — Set to the input index of the first output value.
    /// * `outNBElement` — Set to the number of output values written.
    /// * `outReal` — True Range value per bar.
    ///
    /// # Errors
    ///
    /// Returns [`RetCode::OutOfRangeStartIndex`] when `startIdx` exceeds [`MAX_INDEX`], and
    /// [`RetCode::OutOfRangeEndIndex`] when `endIdx` exceeds it or is below `startIdx`.
    ///
    /// # Panics
    ///
    /// Input slices must cover `startIdx..=endIdx` and output slices must hold the number of values
    /// produced for that range; an undersized slice panics. Sizing every output slice to the input
    /// length is always sufficient.
    ///
    /// # Examples
    ///
    /// ```
    /// use ta_lib::{Core, RetCode};
    ///
    /// let high: Vec<f64> = (0..252).map(|i| 101.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    /// let low: Vec<f64> = (0..252).map(|i| 99.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    /// let close: Vec<f64> = (0..252)
    ///     .map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin() + 0.8 * (0.7 * i as f64).sin())
    ///     .collect();
    ///
    /// let core = Core::new();
    /// let mut out_beg = 0;
    /// let mut out_nb = 0;
    /// let mut out = vec![0.0; 252];
    ///
    /// let ret = core.TRANGE(
    ///     0, high.len() - 1, &high, &low, &close,
    ///     &mut out_beg, &mut out_nb, &mut out,
    /// );
    /// assert_eq!(ret, RetCode::Success);
    /// assert!(out_nb > 0);
    /// assert!(out[..out_nb].iter().all(|v| v.is_finite()));
    /// ```
    ///
    /// # See also
    ///
    /// [`Core::ATR`] · [`Core::NATR`]
    ///
    /// # References
    ///
    /// * J. Welles Wilder, *New Concepts in Technical Trading Systems*, Trend Research (ISBN
    ///   0894590278)
    ///
    /// Further reading: [ta-lib.org/functions/trange](https://ta-lib.org/functions/trange)
    #[doc(alias = "TrueRange")]
    #[doc(alias = "TR")]
    pub fn TRANGE(
        &self,
        startIdx: usize,
        endIdx: usize,
        inHigh: &[f64],
        inLow: &[f64],
        inClose: &[f64],
        outBegIdx: &mut usize,
        outNBElement: &mut usize,
        outReal: &mut [f64],
    ) -> RetCode {
        if startIdx > MAX_INDEX {
            return RetCode::OutOfRangeStartIndex;
        }
        if endIdx > MAX_INDEX || endIdx < startIdx {
            return RetCode::OutOfRangeEndIndex;
        }
        let _assertLb = self.TRANGE_Lookback();
        let _assertStart = if startIdx > _assertLb { startIdx } else { _assertLb };
        assert!(_assertStart > endIdx || endIdx < inHigh.len());
        assert!(_assertStart > endIdx || endIdx < inLow.len());
        assert!(_assertStart > endIdx || endIdx < inClose.len());
        assert!(_assertStart > endIdx || endIdx - _assertStart < outReal.len());
        let mut startIdx = startIdx;
        let mut today: usize = 0_usize;
        let mut outIdx: usize = 0_usize;
        let mut val2: f64 = 0.0_f64;
        let mut val3: f64 = 0.0_f64;
        let mut greatest: f64 = 0.0_f64;
        let mut tempCY: f64 = 0.0_f64;
        let mut tempLT: f64 = 0.0_f64;
        let mut tempHT: f64 = 0.0_f64;
        // True Range is the greatest of the following:
        //
        //  val1 = distance from today's high to today's low.
        //  val2 = distance from yesterday's close to today's high.
        //  val3 = distance from yesterday's close to today's low.
        //
        // Some books and software makes the first TR value to be
        // the (high - low) of the first bar. This function instead
        // ignore the first price bar, and only output starting at the
        // second price bar are valid. This is done for avoiding
        // inconsistency.
        // Move up the start index if there is not
        // enough initial data.
        // Always one price bar gets consumed.
        if startIdx < 1 {
            startIdx = 1;
        }
        // Make sure there is still something to evaluate.
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return RetCode::Success;
        }
        outIdx = 0;
        today = startIdx;
        while today <= endIdx {
            // Find the greatest of the 3 values.
            tempLT = inLow[today];
            tempHT = inHigh[today];
            tempCY = inClose[today - 1];
            greatest = tempHT - tempLT;
            // val1
            val2 = (tempCY - tempHT).abs();
            if val2 > greatest {
                greatest = val2;
            }
            val3 = (tempCY - tempLT).abs();
            if val3 > greatest {
                greatest = val3;
            }
            outReal[outIdx] = greatest;
            outIdx += 1;
            today += 1;
        }
        (*outNBElement) = outIdx;
        (*outBegIdx) = startIdx;
        return RetCode::Success;
    }
