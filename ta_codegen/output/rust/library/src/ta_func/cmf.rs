    fn cmf_step_internal(&self, sp: &mut CmfStreamState, inHigh: f64, inLow: f64, inClose: f64, inVolume: f64, outReal: &mut f64) {
        sp.sumMFV -= sp.cb_mfv_flow[sp.mfv_Idx];
        sp.sumVol -= sp.cb_mfv_volume[sp.mfv_Idx];
        sp.high = inHigh;
        sp.low = inLow;
        sp.close = inClose;
        sp.tmp = sp.high - sp.low;
        if sp.tmp > 0.0 {
            sp.mfv = (sp.close - sp.low - (sp.high - sp.close)) / sp.tmp * inVolume;
        } else {
            sp.mfv = 0.0;
        }
        sp.cb_mfv_flow[sp.mfv_Idx] = sp.mfv;
        sp.cb_mfv_volume[sp.mfv_Idx] = inVolume;
        sp.sumMFV += sp.mfv;
        sp.sumVol += inVolume;
        if sp.sumVol > 0.0 {
            (*outReal) = sp.sumMFV / sp.sumVol;
        } else {
            (*outReal) = 0.0;
        }
        sp.mfv_Idx = sp.mfv_Idx + 1;
        if sp.mfv_Idx > sp.maxIdx_mfv {
            sp.mfv_Idx = 0;
        }
    }

