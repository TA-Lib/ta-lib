    pub fn rvol_open_and_fill(
        &self, inVolume: &[f64], mut optInTimePeriod: i32, outReal: &mut [f64],
    ) -> Result<(RvolStream, OutRange), RetCode> {
        if inVolume.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inVolume.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        let _guardLb = self.RVOL_Lookback(optInTimePeriod)?;
        let _guardOutLen = inVolume.len().saturating_sub(_guardLb);
        if outReal.len() < _guardOutLen {
            return Err(RetCode::BadParam);
        }
        let mut outBegIdx: usize = 0;
        let mut outNBElement: usize = 0;
        let handle = self.rvol_open_and_fill_internal(inVolume, 0, optInTimePeriod, &mut outBegIdx, &mut outNBElement, outReal)?;
        Ok((handle, OutRange { beg_idx: outBegIdx, count: outNBElement }))
    }

