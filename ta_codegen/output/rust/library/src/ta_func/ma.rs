/// Live MA stream: one value per closed bar, bit-identical to [`Core::MA`]
/// over the same series. Open with [`Core::ma_open`]; dropping the handle
/// closes the stream. Cloning it forks an independent stream.
///
/// [`Self::out_range`] reports the bars this handle has an output for.
#[must_use = "a stream does nothing unless updated; dropping it closes the stream"]
#[derive(Debug, Clone)]
#[doc(alias = "TA_MA_Stream")]
pub struct MaStream {
    state: MaStreamState,
    /// The bars this handle has an output for — see [`Self::out_range`].
    out: OutRange,
}

#[derive(Debug, Clone)]
#[allow(non_snake_case, dead_code)]
struct MaStreamState {
    optInTimePeriod: i32,
    optInMAType: MAType,
    // Sub-stream, tagged by optInMAType; `MaSub::Identity` on the identity path.
    sub: MaSub,
    cur_outReal: f64,
}

#[derive(Debug, Clone)]
enum MaSub {
    Identity,
    Sma(SmaStream),
    Ema(EmaStream),
    Wma(WmaStream),
    Dema(DemaStream),
    Tema(TemaStream),
    Trima(TrimaStream),
    Kama(KamaStream),
    Mama(MamaStream),
    T3(T3Stream),
    Hma(HmaStream),
}

