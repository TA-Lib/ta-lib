            let mut todaySum: f64 = 0.0_f64;
            let mut todayDev: f64 = 0.0_f64;
            let mut i: usize = 0_usize;
            todaySum = 0.0;
            // for( i = 0; i < ((optInTimePeriod) as usize); i += 1 )
            i = 0;
            while i < ((optInTimePeriod) as usize) {
                todaySum += inReal[today - i];
                i += 1;
            }
            todayDev = 0.0;
            // for( i = 0; i < ((optInTimePeriod) as usize); i += 1 )
            i = 0;
