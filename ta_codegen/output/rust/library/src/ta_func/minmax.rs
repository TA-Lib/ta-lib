    fn minmax_step_impl(sp: &mut MinmaxStreamState, inReal: f64, outMin: &mut f64, outMax: &mut f64) {
        let mut tmpHigh: f64 = 0.0_f64;
        let mut tmpLow: f64 = 0.0_f64;
        if sp.today >= 1073741824 {
            let rebaseShift: i32 = sp.trailingIdx & !sp.xMask;
            sp.today -= rebaseShift;
            sp.trailingIdx -= rebaseShift;
            sp.highestIdx -= rebaseShift;
            sp.i -= rebaseShift;
            sp.lowestIdx -= rebaseShift;
        }
        sp.x_inReal[(sp.today & sp.xMask) as usize] = inReal;
        tmpHigh = sp.x_inReal[(sp.today & sp.xMask) as usize];
        tmpLow = tmpHigh;
        if sp.highestIdx < sp.trailingIdx {
            sp.highestIdx = sp.trailingIdx;
            sp.highest = sp.x_inReal[(sp.highestIdx & sp.xMask) as usize];
            sp.i = sp.highestIdx;
            while (({ sp.i += 1; sp.i }) as i32) <= sp.today {
                tmpHigh = sp.x_inReal[(sp.i & sp.xMask) as usize];
                if tmpHigh > sp.highest {
                    sp.highestIdx = sp.i;
                    sp.highest = tmpHigh;
                }
            }
        } else if tmpHigh >= sp.highest {
            sp.highestIdx = sp.today;
            sp.highest = tmpHigh;
        }
        if sp.lowestIdx < sp.trailingIdx {
            sp.lowestIdx = sp.trailingIdx;
            sp.lowest = sp.x_inReal[(sp.lowestIdx & sp.xMask) as usize];
            sp.i = sp.lowestIdx;
            while (({ sp.i += 1; sp.i }) as i32) <= sp.today {
                tmpLow = sp.x_inReal[(sp.i & sp.xMask) as usize];
                if tmpLow < sp.lowest {
                    sp.lowestIdx = sp.i;
                    sp.lowest = tmpLow;
                }
            }
        } else if tmpLow <= sp.lowest {
            sp.lowestIdx = sp.today;
            sp.lowest = tmpLow;
        }
        (*outMax) = sp.highest;
        (*outMin) = sp.lowest;
        sp.trailingIdx += 1;
        sp.today += 1;
    }

    /// The single whole-history transcription behind [`Core::minmax_open_internal`]
    /// (stride 0, scalar sink) and [`Core::minmax_open_and_fill`] (stride 1, caller slices).
