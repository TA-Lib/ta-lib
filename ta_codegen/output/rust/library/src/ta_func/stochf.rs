/// Live STOCHF stream: one value per closed bar, bit-identical to [`Core::STOCHF`]
/// over the same series. Open with [`Core::stochf_open`]; dropping the handle
/// closes the stream. Cloning it forks an independent stream.
///
/// [`Self::out_range`] reports the bars this handle has an output for.
#[must_use = "a stream does nothing unless updated; dropping it closes the stream"]
#[derive(Debug, Clone)]
#[doc(alias = "TA_STOCHF_Stream")]
pub struct StochfStream {
    state: StochfStreamState,
    /// The bars this handle has an output for — see [`Self::out_range`].
    out: OutRange,
}

#[derive(Debug, Clone)]
#[allow(non_snake_case, dead_code)]
struct StochfStreamState {
    optInFastK_Period: i32,
    optInFastD_Period: i32,
    optInFastD_MAType: MAType,
    lowest: f64,
    highest: f64,
    diff: f64,
    lowestIdx: i32,
    highestIdx: i32,
    trailingIdx: i32,
    i: i32,
    today: i32,
    xMask: i32,
    x_inHigh: Vec<f64>,
    x_inLow: Vec<f64>,
    x_inClose: Vec<f64>,
    sub0: MaStream,
    cur_outFastK: f64,
    cur_outFastD: f64,
}

#[allow(unused_variables)]
#[allow(dead_code)]
#[allow(unused_mut)]
#[allow(unused_assignments)]
#[allow(unused_parens)]
impl Core {
    fn stochf_step_impl(sp: &mut StochfStreamState, inHigh: f64, inLow: f64, inClose: f64, outFastK: &mut f64, outFastD: &mut f64) -> Result<(), RetCode> {
        let mut tmp: f64 = 0.0_f64;
        let mut cur_tempBuffer: f64 = 0.0_f64;
        let mut cur_outFastD: f64 = 0.0_f64;
        if sp.today >= 1073741824 {
            let rebaseShift: i32 = sp.trailingIdx & !sp.xMask;
            sp.today -= rebaseShift;
            sp.trailingIdx -= rebaseShift;
            sp.highestIdx -= rebaseShift;
            sp.i -= rebaseShift;
            sp.lowestIdx -= rebaseShift;
        }
        sp.x_inHigh[(sp.today & sp.xMask) as usize] = inHigh;
        sp.x_inLow[(sp.today & sp.xMask) as usize] = inLow;
        sp.x_inClose[(sp.today & sp.xMask) as usize] = inClose;
        // Set the lowest low
        tmp = sp.x_inLow[(sp.today & sp.xMask) as usize];
        if sp.lowestIdx < sp.trailingIdx {
            sp.lowestIdx = sp.trailingIdx;
            sp.lowest = sp.x_inLow[(sp.lowestIdx & sp.xMask) as usize];
            sp.i = sp.lowestIdx;
            while (({ sp.i += 1; sp.i }) as i32) <= sp.today {
                tmp = sp.x_inLow[(sp.i & sp.xMask) as usize];
                if tmp < sp.lowest {
                    sp.lowestIdx = sp.i;
                    sp.lowest = tmp;
                }
            }
            sp.diff = (sp.highest - sp.lowest) / 100.0;
        } else if tmp <= sp.lowest {
            sp.lowestIdx = sp.today;
            sp.lowest = tmp;
            sp.diff = (sp.highest - sp.lowest) / 100.0;
        }
        // Set the highest high
        tmp = sp.x_inHigh[(sp.today & sp.xMask) as usize];
        if sp.highestIdx < sp.trailingIdx {
            sp.highestIdx = sp.trailingIdx;
            sp.highest = sp.x_inHigh[(sp.highestIdx & sp.xMask) as usize];
            sp.i = sp.highestIdx;
            while (({ sp.i += 1; sp.i }) as i32) <= sp.today {
                tmp = sp.x_inHigh[(sp.i & sp.xMask) as usize];
                if tmp > sp.highest {
                    sp.highestIdx = sp.i;
                    sp.highest = tmp;
                }
            }
            sp.diff = (sp.highest - sp.lowest) / 100.0;
        } else if tmp >= sp.highest {
            sp.highestIdx = sp.today;
            sp.highest = tmp;
            sp.diff = (sp.highest - sp.lowest) / 100.0;
        }
        // Calculate stochastic. The guard is not an exact `diff != 0.0`: a
        // machine-flat window leaves a sub-epsilon residue that an exact check
        // would divide into [0,100] noise (issue #107 / STOCHRSI). It is the
        // range against ITS OWN two extremes, not against a fixed band: the range
        // carries the quote unit, so a constant put against it answers "flat" for
        // every window of an instrument quoted below it and zeroed the whole
        // output (issue #253).
        if !(((sp.highest - sp.lowest).abs() <= 1e-14 * ((sp.highest).abs() + (sp.lowest).abs()))) {
            cur_tempBuffer = (sp.x_inClose[(sp.today & sp.xMask) as usize] - sp.lowest) / sp.diff;
        } else {
            cur_tempBuffer = 0.0;
        }
        sp.trailingIdx += 1;
        sp.today += 1;

        // Pipeline the new bar through the sub-streams (batch tail order).
        cur_outFastD = sp.sub0.update(cur_tempBuffer)?;
        (*outFastK) = cur_tempBuffer;
        (*outFastD) = cur_outFastD;
        Ok(())
    }

    /// The single whole-history transcription behind [`Core::stochf_open_internal`]
    /// (stride 0, scalar sink) and [`Core::stochf_open_and_fill`] (stride 1, caller slices).
    pub(crate) fn stochf_open_impl(
        &self, inHigh: &[f64], inLow: &[f64], inClose: &[f64], startIdx: usize, mut optInFastK_Period: i32, mut optInFastD_Period: i32, mut optInFastD_MAType: MAType, outBegIdx: &mut usize, outNBElement: &mut usize, outFastK: &mut [f64], outFastD: &mut [f64], outStride: usize,
    ) -> Result<StochfStream, RetCode> {
        if inHigh.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inHigh.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        if ((optInFastK_Period) as i32) == (i32::MIN) {
            optInFastK_Period = 5;
        } else if (((optInFastK_Period) as i32) < 1) || (((optInFastK_Period) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        if ((optInFastD_Period) as i32) == (i32::MIN) {
            optInFastD_Period = 3;
        } else if (((optInFastD_Period) as i32) < 1) || (((optInFastD_Period) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        if optInFastD_MAType == MAType::DEFAULT {
            optInFastD_MAType = MAType::SMA;
        }
        if inLow.len() != inHigh.len() || inClose.len() != inHigh.len() {
            return Err(RetCode::BadParam);
        }
        let historyLen: usize = inHigh.len();
        let endIdx: usize = historyLen - 1;
        let mut startIdx = startIdx;
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut owned_sc_outFastK: Vec<f64> =
            if outStride == 1 { Vec::new() } else { vec![0.0_f64; historyLen] };
        let sc_outFastK: &mut [f64] =
            if outStride == 1 { &mut *outFastK } else { &mut owned_sc_outFastK };
        let mut owned_sc_outFastD: Vec<f64> =
            if outStride == 1 { Vec::new() } else { vec![0.0_f64; historyLen] };
        let sc_outFastD: &mut [f64] =
            if outStride == 1 { &mut *outFastD } else { &mut owned_sc_outFastD };
        let mut retCode: RetCode = RetCode::Success;
        let mut lowest: f64 = 0.0_f64;
        let mut highest: f64 = 0.0_f64;
        let mut tmp: f64 = 0.0_f64;
        let mut diff: f64 = 0.0_f64;
        let mut tempBuffer: Vec<f64> = Vec::new();
        let mut outIdx: usize = 0_usize;
        let mut lowestIdx: i32 = 0_i32;
        let mut highestIdx: i32 = 0_i32;
        let mut lookbackTotal: usize = 0_usize;
        let mut lookbackK: usize = 0_usize;
        let mut lookbackFastD: usize = 0_usize;
        let mut trailingIdx: usize = 0_usize;
        let mut today: usize = 0_usize;
        let mut i: usize = 0_usize;
        let mut bufferIsAllocated: usize = 0_usize;
        // With stochastic, there is a total of 4 different lines that
        // are defined: FASTK, FASTD, SLOWK and SLOWD.
        //
        // The D is the signal line usually drawn over its
        // corresponding K function.
        //
        //                    (Today's Close - LowestLow)
        //  FASTK(Kperiod) =  --------------------------- * 100
        //                     (HighestHigh - LowestLow)
        //
        //  FASTD(FastDperiod, MA type) = MA Smoothed FASTK over FastDperiod
        //
        //  SLOWK(SlowKperiod, MA type) = MA Smoothed FASTK over SlowKperiod
        //
        //  SLOWD(SlowDperiod, MA Type) = MA Smoothed SLOWK over SlowDperiod
        //
        // The HighestHigh and LowestLow are the extreme values among the
        // last 'Kperiod'.
        //
        // SLOWK and FASTD are equivalent when using the same period.
        //
        // The following shows how these four lines are made available in TA-LIB:
        //
        //  TA_STOCH  : Returns the SLOWK and SLOWD
        //  TA_STOCHF : Returns the FASTK and FASTD
        //
        // The TA_STOCH function correspond to the more widely implemented version
        // found in many software/charting package. The TA_STOCHF is more rarely
        // used because its higher volatility cause often whipsaws.
        // Identify the lookback needed.
        lookbackK = (optInFastK_Period - 1) as usize;
        lookbackFastD = self.MA_Lookback(optInFastD_Period, optInFastD_MAType)?;
        lookbackTotal = lookbackK + lookbackFastD;
        // Move up the start index if there is not
        // enough initial data.
        if startIdx < lookbackTotal {
            startIdx = lookbackTotal;
        }
        // Make sure there is still something to evaluate.
        if startIdx > endIdx {
            // Succeed... but no data in the output.
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        // Do the K calculation:
        //
        //    Kt = 100 x ((Ct-Lt)/(Ht-Lt))
        //
        // Kt is today stochastic
        // Ct is today closing price.
        // Lt is the lowest price of the last K Period (including today)
        // Ht is the highest price of the last K Period (including today)
        // Proceed with the calculation for the requested range.
        // Note that this algorithm allows the input and
        // output to be the same buffer.
        outIdx = 0;
        // Calculate just enough K for ending up with the caller
        // requested range. (The range of k must consider all
        // the lookback involve with the smoothing).
        trailingIdx = startIdx - lookbackTotal;
        today = trailingIdx + lookbackK;
        highestIdx = 0 - 1;
        lowestIdx = highestIdx;
        lowest = 0.0;
        highest = lowest;
        diff = highest;
        // Allocate a temporary buffer large enough to
        // store the K.
        //
        // When outFastK aliases a price input the caller buffer doubles as the
        // scratch, saving one allocation: the K writes trail the min/max window
        // reads, and the final memmove is overlap-safe. outFastD must NOT be
        // elected: the %D ma() below would then run in place over the raw K
        // that the memmove into outFastK still needs (issue #130).
        bufferIsAllocated = 0;
        if sc_outFastK.as_ptr() == inHigh.as_ptr() || sc_outFastK.as_ptr() == inLow.as_ptr() || sc_outFastK.as_ptr() == inClose.as_ptr() {
            tempBuffer = sc_outFastK.to_vec();
        } else {
            bufferIsAllocated = 1;
            tempBuffer = vec![0.0_f64; ((endIdx - today + 1) * 1) as usize];
        }
        // Do the K calculation
        while today <= endIdx {
            // Set the lowest low
            tmp = inLow[today];
            if lowestIdx < ((trailingIdx) as i32) {
                lowestIdx = (trailingIdx) as i32;
                lowest = inLow[(lowestIdx) as usize];
                i = (lowestIdx) as usize;
                while { i += 1; i } <= today {
                    tmp = inLow[i];
                    if tmp < lowest {
                        lowestIdx = (i) as i32;
                        lowest = tmp;
                    }
                }
                diff = (highest - lowest) / 100.0;
            } else if tmp <= lowest {
                lowestIdx = (today) as i32;
                lowest = tmp;
                diff = (highest - lowest) / 100.0;
            }
            // Set the highest high
            tmp = inHigh[today];
            if highestIdx < ((trailingIdx) as i32) {
                highestIdx = (trailingIdx) as i32;
                highest = inHigh[(highestIdx) as usize];
                i = (highestIdx) as usize;
                while { i += 1; i } <= today {
                    tmp = inHigh[i];
                    if tmp > highest {
                        highestIdx = (i) as i32;
                        highest = tmp;
                    }
                }
                diff = (highest - lowest) / 100.0;
            } else if tmp >= highest {
                highestIdx = (today) as i32;
                highest = tmp;
                diff = (highest - lowest) / 100.0;
            }
            // Calculate stochastic. The guard is not an exact `diff != 0.0`: a
            // machine-flat window leaves a sub-epsilon residue that an exact check
            // would divide into [0,100] noise (issue #107 / STOCHRSI). It is the
            // range against ITS OWN two extremes, not against a fixed band: the range
            // carries the quote unit, so a constant put against it answers "flat" for
            // every window of an instrument quoted below it and zeroed the whole
            // output (issue #253).
            if !(((highest - lowest).abs() <= 1e-14 * ((highest).abs() + (lowest).abs()))) {
                tempBuffer[outIdx] = (inClose[today] - lowest) / diff;
                outIdx += 1;
            } else {
                tempBuffer[outIdx] = 0.0;
                outIdx += 1;
            }
            trailingIdx += 1;
            today += 1;
        }
        // Fast-K calculation completed. This K calculation is returned
        // to the caller. It is smoothed to become Fast-D.
        // Sub-stream 0: ma over `tempBuffer`, warmed from bar 0 up to the
        // sub-call's own startIdx (the seeding point).
        let sub0 = self.ma_open_and_fill_internal(&tempBuffer[..((outIdx - 1) as usize) + 1], ((0) as usize), optInFastD_Period, optInFastD_MAType, outBegIdx, outNBElement, &mut sc_outFastD[..])?;
        retCode = RetCode::Success;
        if ((*outNBElement) as usize) == 0 {
            // Something wrong happen? No further data?
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        // Copy tempBuffer into the caller buffer.
        // (Calculation could not be done directly in the
        //  caller buffer because more input data then the
        //  requested range was needed for doing %D).
        // memmove, not memcpy: tempBuffer aliases outFastK when the caller buffer is
        // reused as scratch, so source and destination overlap (issue #94).
        {
            let _n = (((((*outNBElement) as usize)) as usize) * 1) as usize;
            let _di = (0) as usize;
            let _si = (lookbackFastD) as usize;
            sc_outFastK[_di.._di + _n].copy_from_slice(&tempBuffer[_si.._si + _n]);
        };
        // Note: Keep the outBegIdx relative to the
        //       caller input before returning.
        (*outBegIdx) = startIdx;

        // Capture the live producer state + sub handles.
        if *outNBElement < 1 {
            return Err(RetCode::InsufficientHistory);
        }
        let capX: i64 = (today as i64) - (trailingIdx as i64) + 1;
        if capX < 1 || capX > historyLen as i64 {
            return Err(RetCode::InternalError);
        }
        let mut physX: i64 = 1;
        while physX < capX {
            physX <<= 1;
        }
        let mut x_inHigh: Vec<f64> = vec![0.0_f64; physX as usize];
        let mut x_inLow: Vec<f64> = vec![0.0_f64; physX as usize];
        let mut x_inClose: Vec<f64> = vec![0.0_f64; physX as usize];
        {
            let mut fillJ: usize = historyLen - capX as usize;
            while fillJ < historyLen {
                x_inHigh[fillJ & (physX as usize - 1)] = inHigh[fillJ];
                x_inLow[fillJ & (physX as usize - 1)] = inLow[fillJ];
                x_inClose[fillJ & (physX as usize - 1)] = inClose[fillJ];
                fillJ += 1;
            }
        }
        let state = StochfStreamState {
            optInFastK_Period,
            optInFastD_Period,
            optInFastD_MAType,
            lowest,
            highest,
            diff,
            lowestIdx: (lowestIdx) as i32,
            highestIdx: (highestIdx) as i32,
            trailingIdx: (trailingIdx) as i32,
            i: (i) as i32,
            today: (today) as i32,
            cur_outFastK: sc_outFastK[*outNBElement - 1],
            cur_outFastD: sc_outFastD[*outNBElement - 1],
            xMask: (physX - 1) as i32,
            x_inHigh,
            x_inLow,
            x_inClose,
            sub0,
        };
        if outStride != 1 && *outNBElement > 0 {
            let last_sc_outFastK = sc_outFastK[*outNBElement - 1];
            outFastK[0] = last_sc_outFastK;
        }
        if outStride != 1 && *outNBElement > 0 {
            let last_sc_outFastD = sc_outFastD[*outNBElement - 1];
            outFastD[0] = last_sc_outFastD;
        }
        Ok(StochfStream { state, out: OutRange { beg_idx: *outBegIdx, count: *outNBElement } })
    }

    /// Internal startIdx-anchored open behind [`Core::stochf_open`] (composition seam).
    pub(crate) fn stochf_open_internal(
        &self, inHigh: &[f64], inLow: &[f64], inClose: &[f64], startIdx: usize, mut optInFastK_Period: i32, mut optInFastD_Period: i32, mut optInFastD_MAType: MAType,
    ) -> Result<(StochfStream, (f64, f64)), RetCode> {
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut sink_outFastK = [0.0_f64; 1];
        let mut sink_outFastD = [0.0_f64; 1];
        let handle = self.stochf_open_impl(inHigh, inLow, inClose, startIdx, optInFastK_Period, optInFastD_Period, optInFastD_MAType, &mut dummyBegIdx, &mut dummyNBElement, &mut sink_outFastK, &mut sink_outFastD, 0)?;
        Ok((handle, (sink_outFastK[0], sink_outFastD[0])))
    }

    /// Open a live STOCHF stream over the warm-up history; returns the handle and
    /// the value at the last history bar — bit-identical to [`Core::STOCHF`] at that bar.
    ///
    /// # Errors
    ///
    /// [`RetCode::InsufficientHistory`] when the history holds fewer than
    /// `lookback + 1` bars — the one failure here worth retrying, since another
    /// bar fixes it. [`RetCode::OutOfRangeStartIndex`] when the history is empty.
    /// [`RetCode::BadParam`] when a parameter is out of range or the input
    /// lengths differ.
    ///
    /// ```
    /// use ta_lib::{Core, MAType};
    /// let high: Vec<f64> = (0..252).map(|i| 101.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    /// let low: Vec<f64> = (0..252).map(|i| 99.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    /// let close: Vec<f64> = (0..252)
    ///     .map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin() + 0.8 * (0.7 * i as f64).sin())
    ///     .collect();
    ///
    /// let core = Core::new();
    /// let (mut s, _last) = core.stochf_open(&high, &low, &close, 5, 3, MAType::SMA).expect("enough history");
    /// let r0 = s.out_range();
    /// let peeked = s.peek(101.4, 99.1, 100.9).expect("a finite bar");
    /// assert_eq!(s.out_range().count, r0.count); // a peek commits nothing
    /// let updated = s.update(101.4, 99.1, 100.9).expect("a finite bar");
    /// assert_eq!(s.out_range().beg_idx, r0.beg_idx);
    /// assert_eq!(s.out_range().count, r0.count + 1);
    /// assert_eq!(peeked.0.to_bits(), updated.0.to_bits());
    /// assert_eq!(peeked.1.to_bits(), updated.1.to_bits());
    /// ```
    #[doc(alias = "TA_STOCHF_Open")]
    pub fn stochf_open(&self, inHigh: &[f64], inLow: &[f64], inClose: &[f64], optInFastK_Period: i32, optInFastD_Period: i32, optInFastD_MAType: MAType) -> Result<(StochfStream, (f64, f64)), RetCode> {
        self.stochf_open_internal(inHigh, inLow, inClose, 0, optInFastK_Period, optInFastD_Period, optInFastD_MAType)
    }

    /// [`Core::stochf_open`] that also fills the output array(s) bit-identically to
    /// [`Core::STOCHF`] over `0..len` in the same single pass, and reports the range it
    /// wrote as the [`OutRange`] beside the handle.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] when an output slice holds fewer than `len - lookback`
    /// values — the batch tier's sizing rule, checked here as it is there (rule S5) —
    /// or when two of them are the same slice. Everything [`Core::stochf_open`] rejects
    /// is rejected here too.
    ///
    /// # Examples
    ///
    /// ```
    /// use ta_lib::{Core, MAType};
    /// let high: Vec<f64> = (0..252).map(|i| 101.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    /// let low: Vec<f64> = (0..252).map(|i| 99.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    /// let close: Vec<f64> = (0..252)
    ///     .map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin() + 0.8 * (0.7 * i as f64).sin())
    ///     .collect();
    ///
    /// let core = Core::new();
    /// let mut batch_fast_k = vec![0.0; 252];
    /// let mut batch_fast_d = vec![0.0; 252];
    /// let batch = core.STOCHF(0, high.len() - 1, &high, &low, &close, 5, 3, MAType::SMA, &mut batch_fast_k, &mut batch_fast_d)?;
    ///
    /// let mut fast_k = vec![0.0; 252];
    /// let mut fast_d = vec![0.0; 252];
    /// let (_stream, filled) = core.stochf_open_and_fill(&high, &low, &close, 5, 3, MAType::SMA, &mut fast_k, &mut fast_d)?;
    ///
    /// assert_eq!(filled.beg_idx, batch.beg_idx);
    /// assert_eq!(filled.count, batch.count);
    /// assert!(fast_k[..filled.count].iter().zip(&batch_fast_k[..batch.count])
    ///     .all(|(a, b)| a.to_bits() == b.to_bits()));
    /// assert!(fast_d[..filled.count].iter().zip(&batch_fast_d[..batch.count])
    ///     .all(|(a, b)| a.to_bits() == b.to_bits()));
    /// # Ok::<(), ta_lib::RetCode>(())
    /// ```
    #[doc(alias = "TA_STOCHF_OpenAndFill")]
    pub fn stochf_open_and_fill(
        &self, inHigh: &[f64], inLow: &[f64], inClose: &[f64], mut optInFastK_Period: i32, mut optInFastD_Period: i32, mut optInFastD_MAType: MAType, outFastK: &mut [f64], outFastD: &mut [f64],
    ) -> Result<(StochfStream, OutRange), RetCode> {
        if inHigh.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inHigh.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        let _guardLb = self.STOCHF_Lookback(optInFastK_Period, optInFastD_Period, optInFastD_MAType)?;
        if inLow.len() != inHigh.len() || inClose.len() != inHigh.len() {
            return Err(RetCode::BadParam);
        }
        let _guardOutLen = inHigh.len().saturating_sub(_guardLb);
        if outFastK.len() < _guardOutLen {
            return Err(RetCode::BadParam);
        }
        if outFastD.len() < _guardOutLen {
            return Err(RetCode::BadParam);
        }
        if !outFastK.is_empty() && !outFastD.is_empty() && outFastK.as_ptr() == outFastD.as_ptr() {
            return Err(RetCode::BadParam);
        }
        let mut outBegIdx: usize = 0;
        let mut outNBElement: usize = 0;
        let handle = self.stochf_open_and_fill_internal(inHigh, inLow, inClose, 0, optInFastK_Period, optInFastD_Period, optInFastD_MAType, &mut outBegIdx, &mut outNBElement, outFastK, outFastD)?;
        Ok((handle, OutRange { beg_idx: outBegIdx, count: outNBElement }))
    }

    /// [`Core::stochf_open_and_fill`] anchored at `startIdx` — the composed-open
    /// fusion seam (issue #192), not a public entry point.
    pub(crate) fn stochf_open_and_fill_internal(
        &self, inHigh: &[f64], inLow: &[f64], inClose: &[f64], startIdx: usize, mut optInFastK_Period: i32, mut optInFastD_Period: i32, mut optInFastD_MAType: MAType, outBegIdx: &mut usize, outNBElement: &mut usize, outFastK: &mut [f64], outFastD: &mut [f64],
    ) -> Result<StochfStream, RetCode> {
        self.stochf_open_impl(inHigh, inLow, inClose, startIdx, optInFastK_Period, optInFastD_Period, optInFastD_MAType, outBegIdx, outNBElement, outFastK, outFastD, 1)
    }

}

#[allow(non_snake_case)]
#[allow(unused_variables)]
#[allow(unused_mut)]
#[allow(unused_assignments)]
#[allow(unused_parens)]
impl StochfStream {
    /// Commit one closed bar. Never allocates.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite (NaN or ±Inf).
    /// That check runs before anything is written, so the handle's state is
    /// left exactly as it was and the stream stays usable: skip the bar, or
    /// close and re-open on a clean history. This is the one place the
    /// streaming tier is stricter than the batch API, which computes on
    /// whatever it is given — a handle retains its state, so a single
    /// non-finite bar would poison every later value it produces.
    ///
    /// [`Self::out_range`] counts the rejected bar all the same: it happened,
    /// so two handles fed the same series stay positionally aligned even when
    /// one rejects a bar the other accepts.
    #[doc(alias = "TA_STOCHF_Update")]
    pub fn update(&mut self, inHigh: f64, inLow: f64, inClose: f64) -> Result<(f64, f64), RetCode> {
        if !inHigh.is_finite() || !inLow.is_finite() || !inClose.is_finite() {
            if self.out.count < Core::MAX_INDEX {
                self.out.count += 1;
            }
            return Err(RetCode::BadParam);
        }
        let mut outFastK: f64 = 0.0_f64;
        let mut outFastD: f64 = 0.0_f64;
        Core::stochf_step_impl(&mut self.state, inHigh, inLow, inClose, &mut outFastK, &mut outFastD)?;
        self.state.cur_outFastK = outFastK;
        self.state.cur_outFastD = outFastD;
        if self.out.count < Core::MAX_INDEX {
            self.out.count += 1;
        }
        Ok((outFastK, outFastD))
    }

    /// Commit `n` closed bars and write their `n` values, in one call —
    /// exactly `n` back-to-back [`Self::update`] calls, with one set of
    /// argument checks instead of `n`. `n` is `inHigh.len()`; the outputs must
    /// hold at least that many. Never allocates.
    ///
    /// [`Self::out_range`] counts what this call took in, which is what makes the
    /// rejection below readable: there is no second out-parameter for it.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if the input slices differ in length, if an output
    /// is shorter than the bar count — neither commits anything — or if a bar
    /// is not finite. A non-finite bar `k` is rejected exactly as `update`
    /// rejects it: bars `0..k` stay committed and their values written, bar `k`
    /// and everything after it is not, and `out_range().count` has advanced by
    /// `k + 1` — the committed bars, plus the rejected one, which is counted
    /// but never written.
    #[doc(alias = "TA_STOCHF_UpdateAndFill")]
    pub fn update_and_fill(&mut self, inHigh: &[f64], inLow: &[f64], inClose: &[f64], outFastK: &mut [f64], outFastD: &mut [f64]) -> Result<(), RetCode> {
        let barCount = inHigh.len();
        if inLow.len() != inHigh.len() || inClose.len() != inHigh.len() || outFastK.len() < barCount || outFastD.len() < barCount {
            return Err(RetCode::BadParam);
        }
        for i in 0..barCount {
            if !inHigh[i].is_finite() || !inLow[i].is_finite() || !inClose[i].is_finite() {
                if self.out.count < Core::MAX_INDEX {
                    self.out.count += 1;
                }
                return Err(RetCode::BadParam);
            }
            Core::stochf_step_impl(&mut self.state, inHigh[i], inLow[i], inClose[i], &mut outFastK[i], &mut outFastD[i])?;
            self.state.cur_outFastK = outFastK[i];
            self.state.cur_outFastD = outFastD[i];
            if self.out.count < Core::MAX_INDEX {
                self.out.count += 1;
            }
        }
        Ok(())
    }

    /// Evaluate a forming bar without committing — bit-identical to what the
    /// next `update` with the same bar would return: the same transition,
    /// rewritten so every store it would make lives in a local instead. It
    /// allocates nothing and copies no buffer, so its cost does not grow with
    /// the period, and it writes no part of the handle — peeks may run
    /// concurrently with each other.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite, on the same test
    /// `update` applies — but a rejected peek changes nothing at all, where a
    /// rejected `update` still counts the bar in [`Self::out_range`].
    #[doc(alias = "TA_STOCHF_Peek")]
    pub fn peek(&self, inHigh: f64, inLow: f64, inClose: f64) -> Result<(f64, f64), RetCode> {
        if !inHigh.is_finite() || !inLow.is_finite() || !inClose.is_finite() {
            return Err(RetCode::BadParam);
        }
        let mut outFastK: f64 = 0.0_f64;
        let mut outFastD: f64 = 0.0_f64;
        {
            let sp = &self.state;
            let outFastK = &mut outFastK;
            let outFastD = &mut outFastD;
            let mut cur_tempBuffer: f64 = 0.0_f64;
            let mut cur_outFastD: f64 = 0.0_f64;
            let mut tmp: f64 = 0.0_f64;
            let mut diff = sp.diff;
            let mut highest = sp.highest;
            let mut highestIdx = sp.highestIdx;
            let mut i = sp.i;
            let mut lowest = sp.lowest;
            let mut lowestIdx = sp.lowestIdx;
            let mut today = sp.today;
            let mut trailingIdx = sp.trailingIdx;
            let mut pkSlot0: usize = usize::MAX;
            let mut pkVal0: f64 = 0.0_f64;
            let mut pkSlot1: usize = usize::MAX;
            let mut pkVal1: f64 = 0.0_f64;
            let mut pkSlot2: usize = usize::MAX;
            let mut pkVal2: f64 = 0.0_f64;
            if today >= 1073741824 {
                let rebaseShift: i32 = trailingIdx & !sp.xMask;
                today -= rebaseShift;
                trailingIdx -= rebaseShift;
                highestIdx -= rebaseShift;
                i -= rebaseShift;
                lowestIdx -= rebaseShift;
            }
            pkSlot0 = (today & sp.xMask) as usize;
            pkVal0 = inHigh;
            pkSlot1 = (today & sp.xMask) as usize;
            pkVal1 = inLow;
            pkSlot2 = (today & sp.xMask) as usize;
            pkVal2 = inClose;
            // Set the lowest low
            tmp = (if ((today & sp.xMask) as usize) != pkSlot1 { sp.x_inLow[(today & sp.xMask) as usize] } else { pkVal1 });
            if lowestIdx < trailingIdx {
                lowestIdx = trailingIdx;
                lowest = (if ((lowestIdx & sp.xMask) as usize) != pkSlot1 { sp.x_inLow[(lowestIdx & sp.xMask) as usize] } else { pkVal1 });
                i = lowestIdx;
                while (({ i += 1; i }) as i32) <= today {
                    tmp = (if ((i & sp.xMask) as usize) != pkSlot1 { sp.x_inLow[(i & sp.xMask) as usize] } else { pkVal1 });
                    if tmp < lowest {
                        lowestIdx = i;
                        lowest = tmp;
                    }
                }
                diff = (highest - lowest) / 100.0;
            } else if tmp <= lowest {
                lowestIdx = today;
                lowest = tmp;
                diff = (highest - lowest) / 100.0;
            }
            // Set the highest high
            tmp = (if ((today & sp.xMask) as usize) != pkSlot0 { sp.x_inHigh[(today & sp.xMask) as usize] } else { pkVal0 });
            if highestIdx < trailingIdx {
                highestIdx = trailingIdx;
                highest = (if ((highestIdx & sp.xMask) as usize) != pkSlot0 { sp.x_inHigh[(highestIdx & sp.xMask) as usize] } else { pkVal0 });
                i = highestIdx;
                while (({ i += 1; i }) as i32) <= today {
                    tmp = (if ((i & sp.xMask) as usize) != pkSlot0 { sp.x_inHigh[(i & sp.xMask) as usize] } else { pkVal0 });
                    if tmp > highest {
                        highestIdx = i;
                        highest = tmp;
                    }
                }
                diff = (highest - lowest) / 100.0;
            } else if tmp >= highest {
                highestIdx = today;
                highest = tmp;
                diff = (highest - lowest) / 100.0;
            }
            // Calculate stochastic. The guard is not an exact `diff != 0.0`: a
            // machine-flat window leaves a sub-epsilon residue that an exact check
            // would divide into [0,100] noise (issue #107 / STOCHRSI). It is the
            // range against ITS OWN two extremes, not against a fixed band: the range
            // carries the quote unit, so a constant put against it answers "flat" for
            // every window of an instrument quoted below it and zeroed the whole
            // output (issue #253).
            if !(((highest - lowest).abs() <= 1e-14 * ((highest).abs() + (lowest).abs()))) {
                cur_tempBuffer = ((if ((today & sp.xMask) as usize) != pkSlot2 { sp.x_inClose[(today & sp.xMask) as usize] } else { pkVal2 }) - lowest) / diff;
            } else {
                cur_tempBuffer = 0.0;
            }
            trailingIdx += 1;
            today += 1;

            // Pipeline the new bar through the sub-streams (batch tail order).
            cur_outFastD = sp.sub0.peek(cur_tempBuffer)?;
            (*outFastK) = cur_tempBuffer;
            (*outFastD) = cur_outFastD;
        }
        Ok((outFastK, outFastD))
    }

    /// The value(s) at the last bar the stream counted — the bar
    /// [`Self::out_range`] ends on — without recomputing. Seeded by the opener,
    /// refreshed by every accepted `update` and `update_and_fill`, and left
    /// alone by `peek`.
    ///
    /// A clone carries them verbatim, so a forked handle can be asked its
    /// current value without committing a bar to find out.
    #[must_use]
    #[doc(alias = "TA_STOCHF_Value")]
    pub fn value(&self) -> (f64, f64) {
        (self.state.cur_outFastK, self.state.cur_outFastD)
    }

    /// The bars this stream has an output for, in the input series'
    /// coordinates: `[beg_idx, beg_idx + count)`.
    ///
    /// It is what [`Core::STOCHF`] reports over the same bars: the opener sets it
    /// to `(lookback, historyLen - lookback)`, every `update` adds one to the
    /// count — a bar rejected for being non-finite included, because it still
    /// happened — `peek` leaves it alone, and a clone carries it verbatim.
    /// A plain `Open` hands back only the last value, a subset of this range,
    /// because the caller chose not to take the fill.
    #[doc(alias = "TA_StreamOutRange")]
    pub fn out_range(&self) -> OutRange {
        self.out
    }
}

