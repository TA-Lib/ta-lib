struct AdxrStreamState {
    optInTimePeriod: i32,
    sub0: AdxStream,
    lagRingPos_adx: usize,
    lagRingCap_adx: usize,
    lagRing_adx: Vec<f64>,
    cur_outReal: f64,
}

