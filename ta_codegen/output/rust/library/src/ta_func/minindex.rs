    fn minindex_step_impl(sp: &mut MinindexStreamState, inReal: f64, outInteger: &mut i32) {
        let mut tmp: f64 = 0.0_f64;
        if sp.today >= 1073741824 {
            let rebaseShift: i32 = sp.trailingIdx & !sp.xMask;
            sp.today -= rebaseShift;
            sp.trailingIdx -= rebaseShift;
            sp.i -= rebaseShift;
            sp.lowestIdx -= rebaseShift;
        }
        sp.x_inReal[(sp.today & sp.xMask) as usize] = inReal;
        tmp = sp.x_inReal[(sp.today & sp.xMask) as usize];
        if sp.lowestIdx < sp.trailingIdx {
            sp.lowestIdx = sp.trailingIdx;
            sp.lowest = sp.x_inReal[(sp.lowestIdx & sp.xMask) as usize];
            sp.i = sp.lowestIdx;
            while (({ sp.i += 1; sp.i }) as i32) <= sp.today {
                tmp = sp.x_inReal[(sp.i & sp.xMask) as usize];
                if tmp < sp.lowest {
                    sp.lowestIdx = sp.i;
                    sp.lowest = tmp;
                }
            }
        } else if tmp <= sp.lowest {
            sp.lowestIdx = sp.today;
            sp.lowest = tmp;
        }
        (*outInteger) = (sp.lowestIdx) as i32;
        sp.trailingIdx += 1;
        sp.today += 1;
        sp.cur_outInteger = (*outInteger);
    }

    /// The single whole-history transcription behind [`Core::minindex_open_internal`]
    /// (stride 0, scalar sink) and [`Core::minindex_open_and_fill`] (stride 1, caller slices).
    pub(crate) fn minindex_open_impl(
        &self, inReal: &[f64], startIdx: usize, mut optInTimePeriod: i32, outBegIdx: &mut usize, outNBElement: &mut usize, outInteger: &mut [i32], outStride: usize,
    ) -> Result<MinindexStream, RetCode> {
        if inReal.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inReal.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        if ((optInTimePeriod) as i32) == (i32::MIN) {
            optInTimePeriod = 30;
        } else if (((optInTimePeriod) as i32) < 2) || (((optInTimePeriod) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        let historyLen: usize = inReal.len();
        let endIdx: usize = historyLen - 1;
        let mut startIdx = startIdx;
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut lowest: f64 = 0.0_f64;
        let mut tmp: f64 = 0.0_f64;
        let mut outIdx: usize = 0_usize;
        let mut nbInitialElementNeeded: usize = 0_usize;
        let mut trailingIdx: usize = 0_usize;
        let mut lowestIdx: i32 = 0_i32;
        let mut today: usize = 0_usize;
        let mut i: usize = 0_usize;
        // Identify the minimum number of price bar needed
        // to identify at least one output over the specified
        // period.
        nbInitialElementNeeded = (optInTimePeriod - 1) as usize;
        // Move up the start index if there is not
        // enough initial data.
        if startIdx < nbInitialElementNeeded {
            startIdx = nbInitialElementNeeded;
        }
        // Make sure there is still something to evaluate.
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        // Proceed with the calculation for the requested range.
        // (The integer output can never share the real input's buffer —
        // different element type; issue #130.)
        outIdx = 0;
        today = startIdx;
        trailingIdx = startIdx - nbInitialElementNeeded;
        lowestIdx = 0 - 1;
        lowest = 0.0;
        while today <= endIdx {
            tmp = inReal[today];
            if lowestIdx < ((trailingIdx) as i32) {
                lowestIdx = (trailingIdx) as i32;
                lowest = inReal[(lowestIdx) as usize];
                i = (lowestIdx) as usize;
                while { i += 1; i } <= today {
                    tmp = inReal[i];
                    if tmp < lowest {
                        lowestIdx = (i) as i32;
                        lowest = tmp;
                    }
                }
            } else if tmp <= lowest {
                lowestIdx = (today) as i32;
                lowest = tmp;
            }
            outInteger[({ let _v = outIdx; outIdx += 1; _v } * outStride) as usize] = (lowestIdx) as i32;
            trailingIdx += 1;
            today += 1;
        }
        // Keep the outBegIdx relative to the
        // caller input before returning.
        (*outBegIdx) = startIdx;
        (*outNBElement) = outIdx;

        // Capture the live batch state into the handle.
        let capX: i64 = (today as i64) - (trailingIdx as i64) + 1;
        if capX < 1 || capX > historyLen as i64 {
            return Err(RetCode::InternalError);
        }
        let mut physX: i64 = 1;
        while physX < capX {
            physX <<= 1;
        }
        let mut x_inReal: Vec<f64> = vec![0.0_f64; physX as usize];
        {
            let mut fillJ: usize = historyLen - capX as usize;
            while fillJ < historyLen {
                x_inReal[fillJ & (physX as usize - 1)] = inReal[fillJ];
                fillJ += 1;
            }
        }
        let state = MinindexStreamState {
            optInTimePeriod,
            lowest,
            trailingIdx: (trailingIdx) as i32,
            lowestIdx: (lowestIdx) as i32,
            i: (i) as i32,
            today: (today) as i32,
            cur_outInteger: outInteger[(*outNBElement - 1) * outStride],
            xMask: (physX - 1) as i32,
            x_inReal,
        };
        Ok(MinindexStream { state, out: OutRange { beg_idx: *outBegIdx, count: *outNBElement } })
    }

