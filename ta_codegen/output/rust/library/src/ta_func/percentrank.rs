    /// fusion seam (issue #192), not a public entry point.
    pub(crate) fn percentrank_open_and_fill_internal(
        &self, inReal: &[f64], startIdx: usize, mut optInTimePeriod: i32, outBegIdx: &mut usize, outNBElement: &mut usize, outReal: &mut [f64],
    ) -> Result<PercentrankStream, RetCode> {
        self.percentrank_open_impl(inReal, startIdx, optInTimePeriod, outBegIdx, outNBElement, outReal, 1)
    }

