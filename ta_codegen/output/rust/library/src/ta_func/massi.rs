    fn massi_step_impl(sp: &mut MassiStreamState, inHigh: f64, inLow: f64, outReal: &mut f64) {
        let mut hl: f64 = 0.0_f64;
        let mut ratio: f64 = 0.0_f64;
        let mut tempReal: f64 = 0.0_f64;
        hl = inHigh - inLow;
        sp.ema1 = (hl - sp.ema1 as f64).mul_add(sp.optInK_1, sp.ema1);
        sp.ema2 = (sp.ema1 - sp.ema2 as f64).mul_add(sp.optInK_1, sp.ema2);
        if sp.ema2 == 0.0 {
            ratio = 1.0;
        } else {
            ratio = sp.ema1 / sp.ema2;
        }
        sp.cb_ratioRing[sp.ratioRing_Idx] = ratio;
        sp.total = sp.total + ratio;
        sp.ratioRing_Idx = sp.ratioRing_Idx + 1;
        if sp.ratioRing_Idx > sp.maxIdx_ratioRing {
            sp.ratioRing_Idx = 0;
        }
        tempReal = sp.total;
        sp.total = sp.total - sp.cb_ratioRing[sp.ratioRing_Idx];
        (*outReal) = tempReal;
        sp.cur_outReal = (*outReal);
    }

