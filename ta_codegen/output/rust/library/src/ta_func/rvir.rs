/// Live RVIR stream: one value per closed bar, bit-identical to [`Core::RVIR`]
/// over the same series. Open with [`Core::rvir_open`]; dropping the handle
/// closes the stream. Cloning it forks an independent stream.
///
/// [`Self::out_range`] reports the bars this handle has an output for.
#[must_use = "a stream does nothing unless updated; dropping it closes the stream"]
#[derive(Debug, Clone)]
#[doc(alias = "TA_RVIR_Stream")]
pub struct RvirStream {
    state: RvirStreamState,
    /// The bars this handle has an output for — see [`Self::out_range`].
    out: OutRange,
}

#[derive(Debug, Clone)]
#[allow(non_snake_case, dead_code)]
struct RvirStreamState {
    optInTimePeriod: i32,
    optInStdDevPeriod: i32,
    sub0: RviStream,
    sub1: RviStream,
    cur_outReal: f64,
}

