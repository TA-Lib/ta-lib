#[allow(unused_variables)]
#[allow(unused_mut)]
#[allow(unused_assignments)]
#[allow(unused_parens)]
impl FisherStream {
    /// Commit one closed bar.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite (NaN or ±Inf).
    /// That check runs before anything is written, so the handle's state is
    /// left exactly as it was and the stream stays usable. This is the one
    /// place the streaming tier is stricter than the batch API, which computes
    /// on whatever it is given: a handle retains its state, so a single
    /// non-finite bar would poison every later value it produces.
    ///
    /// A rejection leaves [`Self::out_range`] alone too. Re-feed the bar when
    /// a corrected value arrives, or call [`Self::advance`] to count it and
    /// carry on — two handles on one feed drift a bar apart if neither
    /// happens.
    ///
    /// [`RetCode::OutOfRangeEndIndex`] once [`Self::out_range`] has reached
    /// bar [`Core::INDEX_MAX`], which no re-feed clears: the handle has run
    /// out of index domain and only a shorter history can start a new one.
    #[doc(alias = "TA_FISHER_Update")]
    pub fn update(&mut self, inHigh: f64, inLow: f64) -> Result<(f64, f64), RetCode> {
        if self.out.beg_idx + self.out.count > Core::INDEX_MAX {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        if !inHigh.is_finite() || !inLow.is_finite() {
            return Err(RetCode::BadParam);
        }
        let mut outFisher: f64 = 0.0_f64;
        let mut outTrigger: f64 = 0.0_f64;
        Core::fisher_step_impl(&mut self.state, inHigh, inLow, &mut outFisher, &mut outTrigger);
        self.out.count += 1;
        Ok((outFisher, outTrigger))
    }

    /// Evaluate a forming bar without committing — bit-identical to what the
    /// next `update` with the same bar would return: the same transition,
    /// rewritten so every store it would make lives in a local instead. It
    /// writes no part of the handle, so peeks may run concurrently with each
    /// other.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite, on the same test
    /// `update` applies, and a rejected peek changes nothing at all. Not
    /// [`RetCode::OutOfRangeEndIndex`]: `peek` counts no bar, so it keeps
    /// answering past the [`Core::INDEX_MAX`] ceiling `update` stops at.
    #[doc(alias = "TA_FISHER_Peek")]
    pub fn peek(&self, inHigh: f64, inLow: f64) -> Result<(f64, f64), RetCode> {
        if !inHigh.is_finite() || !inLow.is_finite() {
            return Err(RetCode::BadParam);
        }
        let mut outFisher: f64 = 0.0_f64;
        let mut outTrigger: f64 = 0.0_f64;
        {
            let sp = &self.state;
            let outFisher = &mut outFisher;
            let outTrigger = &mut outTrigger;
            let mut price: f64 = 0.0_f64;
            let mut ratio: f64 = 0.0_f64;
            let mut fish: f64 = 0.0_f64;
            let mut tempReal: f64 = 0.0_f64;
            let mut tempHigh: f64 = 0.0_f64;
            let mut tempLow: f64 = 0.0_f64;
            let mut highest = sp.highest;
            let mut highestIdx = sp.highestIdx;
            let mut i = sp.i;
            let mut lowest = sp.lowest;
            let mut lowestIdx = sp.lowestIdx;
            let mut smoothed = sp.smoothed;
            let mut pkSlot0: usize = usize::MAX;
            let mut pkVal0: f64 = 0.0_f64;
            let mut pkSlot1: usize = usize::MAX;
            let mut pkVal1: f64 = 0.0_f64;
            pkSlot0 = (sp.today & sp.xMask) as usize;
            pkVal0 = inHigh;
            pkSlot1 = (sp.today & sp.xMask) as usize;
            pkVal1 = inLow;
            // The channel, over the midpoints rather than over the highs and the
            // lows separately: this indicator reads one series, which happens to be
            // (H+L)/2, so both extremes come from that same series. STOCH's shape,
            // with the midpoint recomputed on the rare rescan rather than held in a
            // buffer the caller would have to own.
            price = ((if ((sp.today & sp.xMask) as usize) != pkSlot0 { sp.x_inHigh[(sp.today & sp.xMask) as usize] } else { pkVal0 }) + (if ((sp.today & sp.xMask) as usize) != pkSlot1 { sp.x_inLow[(sp.today & sp.xMask) as usize] } else { pkVal1 })) / 2.0;
            if highestIdx < sp.trailingIdx {
                highestIdx = sp.trailingIdx;
                tempHigh = (if ((highestIdx & sp.xMask) as usize) != pkSlot0 { sp.x_inHigh[(highestIdx & sp.xMask) as usize] } else { pkVal0 });
                tempLow = (if ((highestIdx & sp.xMask) as usize) != pkSlot1 { sp.x_inLow[(highestIdx & sp.xMask) as usize] } else { pkVal1 });
                highest = (tempHigh + tempLow) / 2.0;
                i = highestIdx;
                while (({ i += 1; i }) as i32) <= sp.today {
                    tempHigh = (if ((i & sp.xMask) as usize) != pkSlot0 { sp.x_inHigh[(i & sp.xMask) as usize] } else { pkVal0 });
                    tempLow = (if ((i & sp.xMask) as usize) != pkSlot1 { sp.x_inLow[(i & sp.xMask) as usize] } else { pkVal1 });
                    tempReal = (tempHigh + tempLow) / 2.0;
                    if tempReal > highest {
                        highestIdx = i;
                        highest = tempReal;
                    }
                }
            } else if price >= highest {
                highestIdx = sp.today;
                highest = price;
            }
            if lowestIdx < sp.trailingIdx {
                lowestIdx = sp.trailingIdx;
                tempHigh = (if ((lowestIdx & sp.xMask) as usize) != pkSlot0 { sp.x_inHigh[(lowestIdx & sp.xMask) as usize] } else { pkVal0 });
                tempLow = (if ((lowestIdx & sp.xMask) as usize) != pkSlot1 { sp.x_inLow[(lowestIdx & sp.xMask) as usize] } else { pkVal1 });
                lowest = (tempHigh + tempLow) / 2.0;
                i = lowestIdx;
                while (({ i += 1; i }) as i32) <= sp.today {
                    tempHigh = (if ((i & sp.xMask) as usize) != pkSlot0 { sp.x_inHigh[(i & sp.xMask) as usize] } else { pkVal0 });
                    tempLow = (if ((i & sp.xMask) as usize) != pkSlot1 { sp.x_inLow[(i & sp.xMask) as usize] } else { pkVal1 });
                    tempReal = (tempHigh + tempLow) / 2.0;
                    if tempReal < lowest {
                        lowestIdx = i;
                        lowest = tempReal;
                    }
                }
            } else if price <= lowest {
                lowestIdx = sp.today;
                lowest = price;
            }
            // A flat window answers the neutral position rather than dividing by
            // its own zero range. The band is the range against its own two
            // extremes, STOCH's test: a fixed constant answers "flat" for every
            // window of an instrument quoted below it (#253), and an exact test
            // divides a machine-flat window into noise (#107). At 0.5 the bar
            // contributes nothing and both recursions decay on their own
            // coefficients.
            tempReal = highest - lowest;
            if !(((tempReal).abs() <= 1e-14 * ((highest).abs() + (lowest).abs()))) {
                ratio = (price - lowest) / tempReal;
            } else {
                ratio = 0.5;
            }
            // The listing's .33*2*(r-.5) + .67*Value1[1].
            smoothed = (0.67 as f64).mul_add(smoothed, 0.33 * 2.0 * (ratio - 0.5));
            // The clamp is what keeps atanh finite, and the CLAMPED smoothed is what
            // the next bar's smoothing reads -- the listing assigns it back to
            // Value1 rather than holding it for the transform alone.
            if smoothed > 0.99 {
                smoothed = 0.999;
            }
            if smoothed < -0.99 {
                smoothed = -0.999;
            }
            fish = (0.5 as f64).mul_add(((1.0 + smoothed) / (1.0 - smoothed)).ln(), 0.5 * sp.prevFish);
            (*outFisher) = fish;
            // The author's second plot is Fish[1]: the previous bar's smoothed,
            // which at the first output bar is the zero seed when no unstable
            // period was discarded, and the computed smoothed of the bar before it
            // when one was.
            (*outTrigger) = sp.prevFish;
        }
        Ok((outFisher, outTrigger))
    }

    /// The value(s) at the last bar the stream counted — the bar
    /// [`Self::out_range`] ends on — without recomputing. Seeded by the opener,
    /// refreshed by every accepted `update`, and left
    /// alone by `peek`.
    ///
    /// A clone carries them verbatim, so a forked handle can be asked its
    /// current value without committing a bar to find out.
    #[must_use]
    #[doc(alias = "TA_FISHER_Value")]
    pub fn value(&self) -> (f64, f64) {
        (self.state.cur_outFisher, self.state.cur_outTrigger)
    }

    /// The bars this stream has an output for, in the input series'
    /// coordinates: `[beg_idx, beg_idx + count)`.
    ///
    /// It is what [`Core::fisher`] reports over the same bars: the opener sets it
    /// to `(lookback, historyLen - lookback)`, every accepted `update` adds
    /// one to the count — a rejected one changes nothing, and neither does
    /// `peek` — and a clone carries it verbatim. A plain `Open` hands back
    /// only the last value, a subset of this range, because the caller chose
    /// not to take the fill.
    ///
    /// The last bar it can reach is [`Core::INDEX_MAX`]; past that `update`
    /// and `advance` answer [`RetCode::OutOfRangeEndIndex`].
    #[doc(alias = "TA_FISHER_OutRange")]
    pub fn out_range(&self) -> OutRange {
        self.out
    }

    /// Count one bar this stream was not fed: [`Self::out_range`] advances by
    /// one and nothing else moves — [`Self::value`] keeps answering the
    /// previous output, which is this bar's output too.
    ///
    /// For a bar the caller leaves out: one an `update` rejected and that
    /// will not be re-fed, or a session with no print. Without it two handles
    /// on one feed drift a bar apart when only one of them skips.
    ///
    /// # Errors
    ///
    /// [`RetCode::OutOfRangeEndIndex`] once [`Self::out_range`] has reached
    /// bar [`Core::INDEX_MAX`] — the last one the batch tier can address, and
    /// the last this handle will count. `update` answers the same there.
    #[doc(alias = "TA_FISHER_Advance")]
    pub fn advance(&mut self) -> Result<(), RetCode> {
        if self.out.beg_idx + self.out.count > Core::INDEX_MAX {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        self.out.count += 1;
        Ok(())
    }
}

