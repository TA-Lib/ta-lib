impl Core {
    fn stc_step_impl(sp: &mut StcStreamScalars, cb_lineRing: &mut [f64], cb_lineSufHi: &mut [f64], cb_lineSufLo: &mut [f64], cb_pfRing: &mut [f64], cb_pfSufHi: &mut [f64], cb_pfSufLo: &mut [f64], inReal: f64, outReal: &mut f64) {
        let mut tempReal: f64 = 0.0_f64;
        let mut lineValue: f64 = 0.0_f64;
        let mut lowest: f64 = 0.0_f64;
        let mut highest: f64 = 0.0_f64;
        let mut range: f64 = 0.0_f64;
        let mut sufHi: f64 = 0.0_f64;
        let mut sufLo: f64 = 0.0_f64;
        let mut i: usize = 0_usize;
        tempReal = inReal;
        sp.prevFast = (sp.fastBeta as f64).mul_add(sp.prevFast, sp.fastK * tempReal);
        sp.prevSlow = (sp.slowBeta as f64).mul_add(sp.prevSlow, sp.slowK * tempReal);
        lineValue = sp.prevFast - sp.prevSlow;
        cb_lineRing[sp.lineRing_Idx] = lineValue;
        if sp.lineRing_Idx == 0 {
            sp.lineHi = lineValue;
            sp.lineLo = lineValue;
        } else {
            sp.lineHi = c_max(lineValue, sp.lineHi);
            sp.lineLo = c_min(lineValue, sp.lineLo);
        }
        highest = sp.lineHi;
        lowest = sp.lineLo;
        if sp.lineRing_Idx < sp.lastIdx {
            tempReal = cb_lineSufHi[sp.lineRing_Idx + 1];
            highest = c_max(tempReal, highest);
            tempReal = cb_lineSufLo[sp.lineRing_Idx + 1];
            lowest = c_min(tempReal, lowest);
        }
        sp.lineRing_Idx = sp.lineRing_Idx + 1;
        if sp.lineRing_Idx > sp.maxIdx_lineRing {
            sp.lineRing_Idx = 0;
        }
        if sp.lineRing_Idx == 0 {
            sufHi = cb_lineRing[sp.lastIdx];
            sufLo = sufHi;
            cb_lineSufHi[sp.lastIdx] = sufHi;
            cb_lineSufLo[sp.lastIdx] = sufLo;
            i = sp.lastIdx;
            while i > 0 {
                i -= 1;
                tempReal = cb_lineRing[i];
                sufHi = c_max(tempReal, sufHi);
                sufLo = c_min(tempReal, sufLo);
                cb_lineSufHi[i] = sufHi;
                cb_lineSufLo[i] = sufLo;
            }
        }
        range = highest - lowest;
        if range > 0.0 {
            sp.frac1 = (lineValue - lowest) / range * 100.0;
        } else {
            cold_arm();
        }
        sp.pf = (0.5 as f64).mul_add(sp.frac1 - sp.pf, sp.pf);
        cb_pfRing[sp.pfRing_Idx] = sp.pf;
        if sp.pfRing_Idx == 0 {
            sp.pfHi = sp.pf;
            sp.pfLo = sp.pf;
        } else {
            sp.pfHi = c_max(sp.pf, sp.pfHi);
            sp.pfLo = c_min(sp.pf, sp.pfLo);
        }
        highest = sp.pfHi;
        lowest = sp.pfLo;
        if sp.pfRing_Idx < sp.lastIdx {
            tempReal = cb_pfSufHi[sp.pfRing_Idx + 1];
            highest = c_max(tempReal, highest);
            tempReal = cb_pfSufLo[sp.pfRing_Idx + 1];
            lowest = c_min(tempReal, lowest);
        }
        sp.pfRing_Idx = sp.pfRing_Idx + 1;
        if sp.pfRing_Idx > sp.maxIdx_pfRing {
            sp.pfRing_Idx = 0;
        }
        if sp.pfRing_Idx == 0 {
            sufHi = cb_pfRing[sp.lastIdx];
            sufLo = sufHi;
            cb_pfSufHi[sp.lastIdx] = sufHi;
            cb_pfSufLo[sp.lastIdx] = sufLo;
            i = sp.lastIdx;
            while i > 0 {
                i -= 1;
                tempReal = cb_pfRing[i];
                sufHi = c_max(tempReal, sufHi);
                sufLo = c_min(tempReal, sufLo);
                cb_pfSufHi[i] = sufHi;
                cb_pfSufLo[i] = sufLo;
            }
        }
        range = highest - lowest;
        if range > 0.0 {
            sp.frac2 = (sp.pf - lowest) / range * 100.0;
        } else {
            cold_arm();
        }
        sp.pff = (0.5 as f64).mul_add(sp.frac2 - sp.pff, sp.pff);
        (*outReal) = sp.pff;
        sp.cur_outReal = (*outReal);
    }

    /// The single whole-history transcription behind [`Core::stc_open_internal`]
    /// (stride 0, scalar sink) and [`Core::stc_open_and_fill`] (stride 1, caller slices).
    pub(crate) fn stc_open_impl(
        &self, inReal: &[f64], startIdx: usize, mut optInFastPeriod: i32, mut optInSlowPeriod: i32, mut optInCyclePeriod: i32, outBegIdx: &mut usize, outNBElement: &mut usize, outReal: &mut [f64], outStride: usize,
    ) -> Result<StcStream, RetCode> {
        if inReal.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inReal.len() > Self::INDEX_MAX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        if ((optInFastPeriod) as i32) == (i32::MIN) {
            optInFastPeriod = 23;
        } else if (((optInFastPeriod) as i32) < 2) || (((optInFastPeriod) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        if ((optInSlowPeriod) as i32) == (i32::MIN) {
            optInSlowPeriod = 50;
        } else if (((optInSlowPeriod) as i32) < 2) || (((optInSlowPeriod) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        if ((optInCyclePeriod) as i32) == (i32::MIN) {
            optInCyclePeriod = 10;
        } else if (((optInCyclePeriod) as i32) < 2) || (((optInCyclePeriod) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        let historyLen: usize = inReal.len();
        let endIdx: usize = historyLen - 1;
        let mut startIdx = startIdx;
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut lineRing: Vec<f64> = Vec::new();
        let mut lineRing_Idx: usize = 0;
        let mut maxIdx_lineRing: usize = 29;
        let mut lineSufHi: Vec<f64> = Vec::new();
        let mut lineSufHi_Idx: usize = 0;
        let mut maxIdx_lineSufHi: usize = 29;
        let mut lineSufLo: Vec<f64> = Vec::new();
        let mut lineSufLo_Idx: usize = 0;
        let mut maxIdx_lineSufLo: usize = 29;
        let mut pfRing: Vec<f64> = Vec::new();
        let mut pfRing_Idx: usize = 0;
        let mut maxIdx_pfRing: usize = 29;
        let mut pfSufHi: Vec<f64> = Vec::new();
        let mut pfSufHi_Idx: usize = 0;
        let mut maxIdx_pfSufHi: usize = 29;
        let mut pfSufLo: Vec<f64> = Vec::new();
        let mut pfSufLo_Idx: usize = 0;
        let mut maxIdx_pfSufLo: usize = 29;
        let mut prevFast: f64 = 0.0_f64;
        let mut prevSlow: f64 = 0.0_f64;
        let mut fastK: f64 = 0.0_f64;
        let mut slowK: f64 = 0.0_f64;
        let mut tempReal: f64 = 0.0_f64;
        let mut lineValue: f64 = 0.0_f64;
        let mut fastBeta: f64 = 0.0_f64;
        let mut slowBeta: f64 = 0.0_f64;
        let mut lowest: f64 = 0.0_f64;
        let mut highest: f64 = 0.0_f64;
        let mut range: f64 = 0.0_f64;
        let mut frac1: f64 = 0.0_f64;
        let mut frac2: f64 = 0.0_f64;
        let mut pf: f64 = 0.0_f64;
        let mut pff: f64 = 0.0_f64;
        let mut lineHi: f64 = 0.0_f64;
        let mut lineLo: f64 = 0.0_f64;
        let mut pfHi: f64 = 0.0_f64;
        let mut pfLo: f64 = 0.0_f64;
        let mut sufHi: f64 = 0.0_f64;
        let mut sufLo: f64 = 0.0_f64;
        let mut i: usize = 0_usize;
        let mut today: usize = 0_usize;
        let mut lineStart: usize = 0_usize;
        let mut outIdx: usize = 0_usize;
        let mut tempInteger: usize = 0_usize;
        let mut lookbackTotal: usize = 0_usize;
        let mut lastIdx: usize = 0_usize;
        let mut nLine: usize = 0_usize;
        let mut nPF: usize = 0_usize;
        if optInSlowPeriod < optInFastPeriod {
            tempInteger = (optInSlowPeriod) as usize;
            optInSlowPeriod = optInFastPeriod;
            optInFastPeriod = (tempInteger) as i32;
        }
        lookbackTotal = self.stc_lookback(optInFastPeriod, optInSlowPeriod, optInCyclePeriod)?;
        if startIdx < lookbackTotal {
            startIdx = lookbackTotal;
        }
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        (*outBegIdx) = startIdx;
        fastBeta = ((optInFastPeriod - 1) as f64) / ((optInFastPeriod + 1) as f64);
        fastK = 1.0 - fastBeta;
        fastBeta = 1.0 - fastK;
        slowBeta = ((optInSlowPeriod - 1) as f64) / ((optInSlowPeriod + 1) as f64);
        slowK = 1.0 - slowBeta;
        slowBeta = 1.0 - slowK;
        // Rolling extrema, van Herk / Gil-Werman: the window ending in slot j is
        // the current block's prefix extremum joined with the previous block's
        // suffix extremum from slot j+1. The extrema are exact, so the output must
        // stay bit-identical to a full rescan of each window.
        if optInCyclePeriod < 1 { return Err(RetCode::InternalError); }
        lineRing = vec![0.0_f64; (optInCyclePeriod) as usize];
        maxIdx_lineRing = ((optInCyclePeriod) as usize) - 1;
        lineRing_Idx = 0;
        if optInCyclePeriod < 1 { return Err(RetCode::InternalError); }
        lineSufHi = vec![0.0_f64; (optInCyclePeriod) as usize];
        maxIdx_lineSufHi = ((optInCyclePeriod) as usize) - 1;
        lineSufHi_Idx = 0;
        if optInCyclePeriod < 1 { return Err(RetCode::InternalError); }
        lineSufLo = vec![0.0_f64; (optInCyclePeriod) as usize];
        maxIdx_lineSufLo = ((optInCyclePeriod) as usize) - 1;
        lineSufLo_Idx = 0;
        if optInCyclePeriod < 1 { return Err(RetCode::InternalError); }
        pfRing = vec![0.0_f64; (optInCyclePeriod) as usize];
        maxIdx_pfRing = ((optInCyclePeriod) as usize) - 1;
        pfRing_Idx = 0;
        if optInCyclePeriod < 1 { return Err(RetCode::InternalError); }
        pfSufHi = vec![0.0_f64; (optInCyclePeriod) as usize];
        maxIdx_pfSufHi = ((optInCyclePeriod) as usize) - 1;
        pfSufHi_Idx = 0;
        if optInCyclePeriod < 1 { return Err(RetCode::InternalError); }
        pfSufLo = vec![0.0_f64; (optInCyclePeriod) as usize];
        maxIdx_pfSufLo = ((optInCyclePeriod) as usize) - 1;
        pfSufLo_Idx = 0;
        lastIdx = (optInCyclePeriod - 1) as usize;
        // The line is TA_MACD's: co-terminal SMA seeds, then both EMAs advanced
        // through TA_FUNC_UNST_EMA to lineStart, so that from lineStart on it is
        // TA_EMA(fast) - TA_EMA(slow) bit for bit. The chain is fed from
        // lineStart, not from the EMA seed: TA_FUNC_UNST_EMA then reaches only the
        // line, while TA_FUNC_UNST_STC moves the whole chain back and so warms the
        // line and both smoothers.
        lineStart = startIdx - (lookbackTotal - self.ema_lookback(optInSlowPeriod)?);
        today = startIdx - lookbackTotal;
        tempReal = 0.0;
        i = (optInSlowPeriod - optInFastPeriod) as usize;
        while { let _v = i; i = i.wrapping_sub(1); _v } > 0 {
            tempReal += inReal[{ let _v = today; today += 1; _v }];
        }
        prevFast = 0.0;
        i = (optInFastPeriod) as usize;
        while { let _v = i; i = i.wrapping_sub(1); _v } > 0 {
            prevFast += inReal[today];
            tempReal += inReal[{ let _v = today; today += 1; _v }];
        }
        prevSlow = tempReal / ((optInSlowPeriod) as f64);
        prevFast = prevFast / ((optInFastPeriod) as f64);
        while today <= lineStart {
            tempReal = inReal[{ let _v = today; today += 1; _v }];
            prevFast = (fastBeta as f64).mul_add(prevFast, fastK * tempReal);
            prevSlow = (slowBeta as f64).mul_add(prevSlow, slowK * tempReal);
        }
        // A zero range holds the previous fraction (0.0 before any), and the test
        // is exact: in a sustained trend PF saturates at 100 and the second
        // range reaches exactly 0 while the output must stay at 100.
        frac1 = 0.0;
        frac2 = 0.0;
        pf = 0.0;
        pff = 0.0;
        pfHi = 0.0;
        pfLo = 0.0;
        nPF = 0;
        lineValue = prevFast - prevSlow;
        lineRing[lineRing_Idx] = lineValue;
        lineRing_Idx += 1;
        if lineRing_Idx > maxIdx_lineRing { lineRing_Idx = 0; }
        lineHi = lineValue;
        lineLo = lineValue;
        nLine = 1;
        // Warm-up, through startIdx inclusive. Each stage starts once its
        // window is full, and each smoother is seeded on its first input.
        while today <= startIdx {
            tempReal = inReal[today];
            prevFast = (fastBeta as f64).mul_add(prevFast, fastK * tempReal);
            prevSlow = (slowBeta as f64).mul_add(prevSlow, slowK * tempReal);
            lineValue = prevFast - prevSlow;
            nLine = nLine + 1;
            lineRing[lineRing_Idx] = lineValue;
            if lineRing_Idx == 0 {
                lineHi = lineValue;
                lineLo = lineValue;
            } else {
                lineHi = c_max(lineValue, lineHi);
                lineLo = c_min(lineValue, lineLo);
            }
            highest = lineHi;
            lowest = lineLo;
            if nLine >= ((optInCyclePeriod) as usize) && lineRing_Idx < lastIdx {
                tempReal = lineSufHi[lineRing_Idx + 1];
                highest = c_max(tempReal, highest);
                tempReal = lineSufLo[lineRing_Idx + 1];
                lowest = c_min(tempReal, lowest);
            }
            lineRing_Idx += 1;
            if lineRing_Idx > maxIdx_lineRing { lineRing_Idx = 0; }
            if lineRing_Idx == 0 {
                sufHi = lineRing[lastIdx];
                sufLo = sufHi;
                lineSufHi[lastIdx] = sufHi;
                lineSufLo[lastIdx] = sufLo;
                i = lastIdx;
                while i > 0 {
                    i -= 1;
                    tempReal = lineRing[i];
                    sufHi = c_max(tempReal, sufHi);
                    sufLo = c_min(tempReal, sufLo);
                    lineSufHi[i] = sufHi;
                    lineSufLo[i] = sufLo;
                }
            }
            if nLine >= ((optInCyclePeriod) as usize) {
                range = highest - lowest;
                if range > 0.0 {
                    frac1 = (lineValue - lowest) / range * 100.0;
                } else {
                    cold_arm();
                }
                if nPF == 0 {
                    pf = frac1;
                } else {
                    pf = (0.5 as f64).mul_add(frac1 - pf, pf);
                }
                nPF = nPF + 1;
                pfRing[pfRing_Idx] = pf;
                if pfRing_Idx == 0 {
                    pfHi = pf;
                    pfLo = pf;
                } else {
                    pfHi = c_max(pf, pfHi);
                    pfLo = c_min(pf, pfLo);
                }
                highest = pfHi;
                lowest = pfLo;
                if nPF >= ((optInCyclePeriod) as usize) && pfRing_Idx < lastIdx {
                    tempReal = pfSufHi[pfRing_Idx + 1];
                    highest = c_max(tempReal, highest);
                    tempReal = pfSufLo[pfRing_Idx + 1];
                    lowest = c_min(tempReal, lowest);
                }
                pfRing_Idx += 1;
                if pfRing_Idx > maxIdx_pfRing { pfRing_Idx = 0; }
                if pfRing_Idx == 0 {
                    sufHi = pfRing[lastIdx];
                    sufLo = sufHi;
                    pfSufHi[lastIdx] = sufHi;
                    pfSufLo[lastIdx] = sufLo;
                    i = lastIdx;
                    while i > 0 {
                        i -= 1;
                        tempReal = pfRing[i];
                        sufHi = c_max(tempReal, sufHi);
                        sufLo = c_min(tempReal, sufLo);
                        pfSufHi[i] = sufHi;
                        pfSufLo[i] = sufLo;
                    }
                }
                if nPF >= ((optInCyclePeriod) as usize) {
                    range = highest - lowest;
                    if range > 0.0 {
                        frac2 = (pf - lowest) / range * 100.0;
                    } else {
                        cold_arm();
                    }
                    if nPF == ((optInCyclePeriod) as usize) {
                        pff = frac2;
                    } else {
                        pff = (0.5 as f64).mul_add(frac2 - pff, pff);
                    }
                }
            }
            today = today + 1;
        }
        outReal[(0 * outStride) as usize] = pff;
        outIdx = 1;
        while today <= endIdx {
            tempReal = inReal[today];
            prevFast = (fastBeta as f64).mul_add(prevFast, fastK * tempReal);
            prevSlow = (slowBeta as f64).mul_add(prevSlow, slowK * tempReal);
            lineValue = prevFast - prevSlow;
            lineRing[lineRing_Idx] = lineValue;
            if lineRing_Idx == 0 {
                lineHi = lineValue;
                lineLo = lineValue;
            } else {
                lineHi = c_max(lineValue, lineHi);
                lineLo = c_min(lineValue, lineLo);
            }
            highest = lineHi;
            lowest = lineLo;
            if lineRing_Idx < lastIdx {
                tempReal = lineSufHi[lineRing_Idx + 1];
                highest = c_max(tempReal, highest);
                tempReal = lineSufLo[lineRing_Idx + 1];
                lowest = c_min(tempReal, lowest);
            }
            lineRing_Idx += 1;
            if lineRing_Idx > maxIdx_lineRing { lineRing_Idx = 0; }
            if lineRing_Idx == 0 {
                sufHi = lineRing[lastIdx];
                sufLo = sufHi;
                lineSufHi[lastIdx] = sufHi;
                lineSufLo[lastIdx] = sufLo;
                i = lastIdx;
                while i > 0 {
                    i -= 1;
                    tempReal = lineRing[i];
                    sufHi = c_max(tempReal, sufHi);
                    sufLo = c_min(tempReal, sufLo);
                    lineSufHi[i] = sufHi;
                    lineSufLo[i] = sufLo;
                }
            }
            range = highest - lowest;
            if range > 0.0 {
                frac1 = (lineValue - lowest) / range * 100.0;
            } else {
                cold_arm();
            }
            pf = (0.5 as f64).mul_add(frac1 - pf, pf);
            pfRing[pfRing_Idx] = pf;
            if pfRing_Idx == 0 {
                pfHi = pf;
                pfLo = pf;
            } else {
                pfHi = c_max(pf, pfHi);
                pfLo = c_min(pf, pfLo);
            }
            highest = pfHi;
            lowest = pfLo;
            if pfRing_Idx < lastIdx {
                tempReal = pfSufHi[pfRing_Idx + 1];
                highest = c_max(tempReal, highest);
                tempReal = pfSufLo[pfRing_Idx + 1];
                lowest = c_min(tempReal, lowest);
            }
            pfRing_Idx += 1;
            if pfRing_Idx > maxIdx_pfRing { pfRing_Idx = 0; }
            if pfRing_Idx == 0 {
                sufHi = pfRing[lastIdx];
                sufLo = sufHi;
                pfSufHi[lastIdx] = sufHi;
                pfSufLo[lastIdx] = sufLo;
                i = lastIdx;
                while i > 0 {
                    i -= 1;
                    tempReal = pfRing[i];
                    sufHi = c_max(tempReal, sufHi);
                    sufLo = c_min(tempReal, sufLo);
                    pfSufHi[i] = sufHi;
                    pfSufLo[i] = sufLo;
                }
            }
            range = highest - lowest;
            if range > 0.0 {
                frac2 = (pf - lowest) / range * 100.0;
            } else {
                cold_arm();
            }
            pff = (0.5 as f64).mul_add(frac2 - pff, pff);
            outReal[({ let _v = outIdx; outIdx += 1; _v } * outStride) as usize] = pff;
            today = today + 1;
        }
        (*outNBElement) = outIdx;

        // Capture the live batch state into the handle.
        let cbSize_lineRing: usize = maxIdx_lineRing + 1;
        if cbSize_lineRing > historyLen + 1 {
            return Err(RetCode::InternalError);
        }
        let cbSize_lineSufHi: usize = maxIdx_lineSufHi + 1;
        if cbSize_lineSufHi > historyLen + 1 {
            return Err(RetCode::InternalError);
        }
        let cbSize_lineSufLo: usize = maxIdx_lineSufLo + 1;
        if cbSize_lineSufLo > historyLen + 1 {
            return Err(RetCode::InternalError);
        }
        let cbSize_pfRing: usize = maxIdx_pfRing + 1;
        if cbSize_pfRing > historyLen + 1 {
            return Err(RetCode::InternalError);
        }
        let cbSize_pfSufHi: usize = maxIdx_pfSufHi + 1;
        if cbSize_pfSufHi > historyLen + 1 {
            return Err(RetCode::InternalError);
        }
        let cbSize_pfSufLo: usize = maxIdx_pfSufLo + 1;
        if cbSize_pfSufLo > historyLen + 1 {
            return Err(RetCode::InternalError);
        }
        let state = StcStreamState {
            scalars: StcStreamScalars {
                optInFastPeriod,
                optInSlowPeriod,
                optInCyclePeriod,
                prevFast,
                prevSlow,
                fastK,
                slowK,
                fastBeta,
                slowBeta,
                frac1,
                frac2,
                pf,
                pff,
                lineHi,
                lineLo,
                pfHi,
                pfLo,
                lastIdx,
                lineRing_Idx,
                pfRing_Idx,
                maxIdx_lineRing,
                lineSufHi_Idx,
                maxIdx_lineSufHi,
                lineSufLo_Idx,
                maxIdx_lineSufLo,
                maxIdx_pfRing,
                pfSufHi_Idx,
                maxIdx_pfSufHi,
                pfSufLo_Idx,
                maxIdx_pfSufLo,
                cur_outReal: outReal[(*outNBElement - 1) * outStride],
                cbSize_lineRing: cbSize_lineRing,
                cbSize_lineSufHi: cbSize_lineSufHi,
                cbSize_lineSufLo: cbSize_lineSufLo,
                cbSize_pfRing: cbSize_pfRing,
                cbSize_pfSufHi: cbSize_pfSufHi,
                cbSize_pfSufLo: cbSize_pfSufLo,
            },
            cb_lineRing: lineRing,
            cb_lineSufHi: lineSufHi,
            cb_lineSufLo: lineSufLo,
            cb_pfRing: pfRing,
            cb_pfSufHi: pfSufHi,
            cb_pfSufLo: pfSufLo,
        };
        Ok(StcStream { state, out: OutRange { beg_idx: *outBegIdx, count: *outNBElement } })
    }

    /// Internal startIdx-anchored open behind [`Core::stc_open`] (composition seam).
    pub(crate) fn stc_open_internal(
        &self, inReal: &[f64], startIdx: usize, mut optInFastPeriod: i32, mut optInSlowPeriod: i32, mut optInCyclePeriod: i32,
    ) -> Result<(StcStream, f64), RetCode> {
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut sink_outReal = [0.0_f64; 1];
        let handle = self.stc_open_impl(inReal, startIdx, optInFastPeriod, optInSlowPeriod, optInCyclePeriod, &mut dummyBegIdx, &mut dummyNBElement, &mut sink_outReal, 0)?;
        Ok((handle, sink_outReal[0]))
    }

    /// Open a live STC stream over the warm-up history; returns the handle and
    /// the value at the last history bar — bit-identical to [`Core::stc`] at that bar.
    ///
    /// # Errors
    ///
    /// [`RetCode::InsufficientHistory`] when the history holds fewer than
    /// `lookback + 1` bars — the one failure here worth retrying, since another
    /// bar fixes it. [`RetCode::OutOfRangeStartIndex`] when the history is empty.
    /// [`RetCode::BadParam`] when a parameter is out of range or the input
    /// lengths differ.
    ///
    /// ```
    /// use ta_lib::Core;
    /// let data: Vec<f64> = (0..252).map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    ///
    /// let core = Core::new();
    /// let (mut s, _last) = core.stc_open(&data, 23, 50, 10).expect("enough history");
    /// let r0 = s.out_range();
    /// let peeked = s.peek(100.9).expect("a finite bar");
    /// assert_eq!(s.out_range().count, r0.count); // a peek commits nothing
    /// let updated = s.update(100.9).expect("a finite bar");
    /// assert_eq!(s.out_range().beg_idx, r0.beg_idx);
    /// assert_eq!(s.out_range().count, r0.count + 1);
    /// assert_eq!(peeked.to_bits(), updated.to_bits());
    /// ```
    #[doc(alias = "TA_STC_Open")]
    pub fn stc_open(&self, inReal: &[f64], optInFastPeriod: i32, optInSlowPeriod: i32, optInCyclePeriod: i32) -> Result<(StcStream, f64), RetCode> {
        self.stc_open_internal(inReal, 0, optInFastPeriod, optInSlowPeriod, optInCyclePeriod)
    }

    /// [`Core::stc_open`] that also fills the output array(s) bit-identically to
    /// [`Core::stc`] over `0..len` in the same single pass, and reports the range it
    /// wrote as the [`OutRange`] beside the handle.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] when an output slice holds fewer than `len - lookback`
    /// values — the batch tier's sizing rule, checked here as it is there (rule rS5).
    /// Everything [`Core::stc_open`] rejects is rejected here too.
    ///
    /// # Examples
    ///
    /// ```
    /// use ta_lib::Core;
    /// let data: Vec<f64> = (0..252).map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    ///
    /// let core = Core::new();
    /// let mut batch_out = vec![0.0; 252];
    /// let batch = core.stc(0, data.len() - 1, &data, 23, 50, 10, &mut batch_out)?;
    ///
    /// let mut out = vec![0.0; 252];
    /// let (_stream, filled) = core.stc_open_and_fill(&data, 23, 50, 10, &mut out)?;
    ///
    /// assert_eq!(filled.beg_idx, batch.beg_idx);
    /// assert_eq!(filled.count, batch.count);
    /// assert!(out[..filled.count].iter().zip(&batch_out[..batch.count])
    ///     .all(|(a, b)| a.to_bits() == b.to_bits()));
    /// # Ok::<(), ta_lib::RetCode>(())
    /// ```
    #[doc(alias = "TA_STC_OpenAndFill")]
    pub fn stc_open_and_fill(
        &self, inReal: &[f64], mut optInFastPeriod: i32, mut optInSlowPeriod: i32, mut optInCyclePeriod: i32, outReal: &mut [f64],
    ) -> Result<(StcStream, OutRange), RetCode> {
        if inReal.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inReal.len() > Self::INDEX_MAX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        let _guardLb = self.stc_lookback(optInFastPeriod, optInSlowPeriod, optInCyclePeriod)?;
        let _guardOutLen = inReal.len().saturating_sub(_guardLb);
        if outReal.is_empty() || outReal.len() < _guardOutLen {
            return Err(RetCode::BadParam);
        }
        let mut outBegIdx: usize = 0;
        let mut outNBElement: usize = 0;
        let handle = self.stc_open_and_fill_internal(inReal, 0, optInFastPeriod, optInSlowPeriod, optInCyclePeriod, &mut outBegIdx, &mut outNBElement, outReal)?;
        Ok((handle, OutRange { beg_idx: outBegIdx, count: outNBElement }))
    }

    /// [`Core::stc_open_and_fill`] anchored at `startIdx` — the composed-open
    /// fusion seam (issue #192), not a public entry point.
    pub(crate) fn stc_open_and_fill_internal(
        &self, inReal: &[f64], startIdx: usize, mut optInFastPeriod: i32, mut optInSlowPeriod: i32, mut optInCyclePeriod: i32, outBegIdx: &mut usize, outNBElement: &mut usize, outReal: &mut [f64],
    ) -> Result<StcStream, RetCode> {
        self.stc_open_impl(inReal, startIdx, optInFastPeriod, optInSlowPeriod, optInCyclePeriod, outBegIdx, outNBElement, outReal, 1)
    }

}

#[allow(non_snake_case)]
#[allow(unused_variables)]
#[allow(unused_mut)]
#[allow(unused_assignments)]
#[allow(unused_parens)]
impl StcStream {
    /// Commit one closed bar.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite (NaN or ±Inf).
    /// That check runs before anything is written, so the handle's state is
    /// left exactly as it was and the stream stays usable. This is the one
    /// place the streaming tier is stricter than the batch API, which computes
    /// on whatever it is given: a handle retains its state, so a single
    /// non-finite bar would poison every later value it produces.
    ///
    /// A rejection leaves [`Self::out_range`] alone too. Re-feed the bar when
    /// a corrected value arrives, or call [`Self::advance`] to count it and
    /// carry on — two handles on one feed drift a bar apart if neither
    /// happens.
    ///
    /// [`RetCode::OutOfRangeEndIndex`] once [`Self::out_range`] has reached
    /// bar [`Core::INDEX_MAX`], which no re-feed clears: the handle has run
    /// out of index domain and only a shorter history can start a new one.
    #[doc(alias = "TA_STC_Update")]
    pub fn update(&mut self, inReal: f64) -> Result<f64, RetCode> {
        if self.out.beg_idx + self.out.count > Core::INDEX_MAX {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        if !inReal.is_finite() {
            return Err(RetCode::BadParam);
        }
        let mut outReal: f64 = 0.0_f64;
        Core::stc_step_impl(&mut self.state.scalars, &mut self.state.cb_lineRing, &mut self.state.cb_lineSufHi, &mut self.state.cb_lineSufLo, &mut self.state.cb_pfRing, &mut self.state.cb_pfSufHi, &mut self.state.cb_pfSufLo, inReal, &mut outReal);
        self.out.count += 1;
        Ok(outReal)
    }

    /// Evaluate a forming bar without committing — bit-identical to what the
    /// next `update` with the same bar would return: the same transition,
    /// rewritten so every store it would make lives in a local instead. It
    /// writes no part of the handle, so peeks may run concurrently with each
    /// other.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite, on the same test
    /// `update` applies, and a rejected peek changes nothing at all. Not
    /// [`RetCode::OutOfRangeEndIndex`]: `peek` counts no bar, so it keeps
    /// answering past the [`Core::INDEX_MAX`] ceiling `update` stops at.
    #[doc(alias = "TA_STC_Peek")]
    pub fn peek(&self, inReal: f64) -> Result<f64, RetCode> {
        if !inReal.is_finite() {
            return Err(RetCode::BadParam);
        }
        let mut outReal: f64 = 0.0_f64;
        {
            let sp = &self.state.scalars;
            let cb_lineRing = &self.state.cb_lineRing;
            let cb_lineSufHi = &self.state.cb_lineSufHi;
            let cb_lineSufLo = &self.state.cb_lineSufLo;
            let cb_pfRing = &self.state.cb_pfRing;
            let cb_pfSufHi = &self.state.cb_pfSufHi;
            let cb_pfSufLo = &self.state.cb_pfSufLo;
            let outReal = &mut outReal;
            let mut tempReal: f64 = 0.0_f64;
            let mut lineValue: f64 = 0.0_f64;
            let mut lowest: f64 = 0.0_f64;
            let mut highest: f64 = 0.0_f64;
            let mut range: f64 = 0.0_f64;
            let mut sufHi: f64 = 0.0_f64;
            let mut sufLo: f64 = 0.0_f64;
            let mut i: usize = 0_usize;
            let mut frac1 = sp.frac1;
            let mut frac2 = sp.frac2;
            let mut lineHi = sp.lineHi;
            let mut lineLo = sp.lineLo;
            let mut lineRing_Idx = sp.lineRing_Idx;
            let mut pf = sp.pf;
            let mut pfHi = sp.pfHi;
            let mut pfLo = sp.pfLo;
            let mut pfRing_Idx = sp.pfRing_Idx;
            let mut pff = sp.pff;
            let mut prevFast = sp.prevFast;
            let mut prevSlow = sp.prevSlow;
            let mut pkSlot0: usize = usize::MAX;
            let mut pkVal0: f64 = 0.0_f64;
            let mut pkSlot1: usize = usize::MAX;
            let mut pkVal1: f64 = 0.0_f64;
            tempReal = inReal;
            prevFast = (sp.fastBeta as f64).mul_add(prevFast, sp.fastK * tempReal);
            prevSlow = (sp.slowBeta as f64).mul_add(prevSlow, sp.slowK * tempReal);
            lineValue = prevFast - prevSlow;
            pkSlot0 = lineRing_Idx as usize;
            pkVal0 = lineValue;
            if lineRing_Idx == 0 {
                lineHi = lineValue;
                lineLo = lineValue;
            } else {
                lineHi = c_max(lineValue, lineHi);
                lineLo = c_min(lineValue, lineLo);
            }
            highest = lineHi;
            lowest = lineLo;
            if lineRing_Idx < sp.lastIdx {
                tempReal = cb_lineSufHi[lineRing_Idx + 1];
                highest = c_max(tempReal, highest);
                tempReal = cb_lineSufLo[lineRing_Idx + 1];
                lowest = c_min(tempReal, lowest);
            }
            lineRing_Idx = lineRing_Idx + 1;
            if lineRing_Idx > sp.maxIdx_lineRing {
                lineRing_Idx = 0;
            }
            if lineRing_Idx == 0 {
                sufHi = (if (sp.lastIdx as usize) != pkSlot0 { cb_lineRing[sp.lastIdx] } else { pkVal0 });
                sufLo = sufHi;
                i = sp.lastIdx;
                while i > 0 {
                    i -= 1;
                    tempReal = (if (i as usize) != pkSlot0 { cb_lineRing[i] } else { pkVal0 });
                    sufHi = c_max(tempReal, sufHi);
                    sufLo = c_min(tempReal, sufLo);
                }
            }
            range = highest - lowest;
            if range > 0.0 {
                frac1 = (lineValue - lowest) / range * 100.0;
            } else {
                cold_arm();
            }
            pf = (0.5 as f64).mul_add(frac1 - pf, pf);
            pkSlot1 = pfRing_Idx as usize;
            pkVal1 = pf;
            if pfRing_Idx == 0 {
                pfHi = pf;
                pfLo = pf;
            } else {
                pfHi = c_max(pf, pfHi);
                pfLo = c_min(pf, pfLo);
            }
            highest = pfHi;
            lowest = pfLo;
            if pfRing_Idx < sp.lastIdx {
                tempReal = cb_pfSufHi[pfRing_Idx + 1];
                highest = c_max(tempReal, highest);
                tempReal = cb_pfSufLo[pfRing_Idx + 1];
                lowest = c_min(tempReal, lowest);
            }
            pfRing_Idx = pfRing_Idx + 1;
            if pfRing_Idx > sp.maxIdx_pfRing {
                pfRing_Idx = 0;
            }
            if pfRing_Idx == 0 {
                sufHi = (if (sp.lastIdx as usize) != pkSlot1 { cb_pfRing[sp.lastIdx] } else { pkVal1 });
                sufLo = sufHi;
                i = sp.lastIdx;
                while i > 0 {
                    i -= 1;
                    tempReal = (if (i as usize) != pkSlot1 { cb_pfRing[i] } else { pkVal1 });
                    sufHi = c_max(tempReal, sufHi);
                    sufLo = c_min(tempReal, sufLo);
                }
            }
            range = highest - lowest;
            if range > 0.0 {
                frac2 = (pf - lowest) / range * 100.0;
            } else {
                cold_arm();
            }
            pff = (0.5 as f64).mul_add(frac2 - pff, pff);
            (*outReal) = pff;
        }
        Ok(outReal)
    }

    /// The value(s) at the last bar the stream counted — the bar
    /// [`Self::out_range`] ends on — without recomputing. Seeded by the opener,
    /// refreshed by every accepted `update`, and left
    /// alone by `peek`.
    ///
    /// A clone carries them verbatim, so a forked handle can be asked its
    /// current value without committing a bar to find out.
    #[must_use]
    #[doc(alias = "TA_STC_Value")]
    pub fn value(&self) -> f64 {
        self.state.scalars.cur_outReal
    }

    /// The bars this stream has an output for, in the input series'
    /// coordinates: `[beg_idx, beg_idx + count)`.
    ///
    /// It is what [`Core::stc`] reports over the same bars: the opener sets it
    /// to `(lookback, historyLen - lookback)`, every accepted `update` adds
    /// one to the count — a rejected one changes nothing, and neither does
    /// `peek` — and a clone carries it verbatim. A plain `Open` hands back
    /// only the last value, a subset of this range, because the caller chose
    /// not to take the fill.
    ///
    /// The last bar it can reach is [`Core::INDEX_MAX`]; past that `update`
    /// and `advance` answer [`RetCode::OutOfRangeEndIndex`].
    #[doc(alias = "TA_STC_OutRange")]
    pub fn out_range(&self) -> OutRange {
        self.out
    }

    /// Count one bar this stream was not fed: [`Self::out_range`] advances by
    /// one and nothing else moves — [`Self::value`] keeps answering the
    /// previous output, which is this bar's output too.
    ///
    /// For a bar the caller leaves out: one an `update` rejected and that
    /// will not be re-fed, or a session with no print. Without it two handles
    /// on one feed drift a bar apart when only one of them skips.
    ///
    /// # Errors
    ///
    /// [`RetCode::OutOfRangeEndIndex`] once [`Self::out_range`] has reached
    /// bar [`Core::INDEX_MAX`] — the last one the batch tier can address, and
    /// the last this handle will count. `update` answers the same there.
    #[doc(alias = "TA_STC_Advance")]
    pub fn advance(&mut self) -> Result<(), RetCode> {
        if self.out.beg_idx + self.out.count > Core::INDEX_MAX {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        self.out.count += 1;
        Ok(())
    }
}

