impl Core {
    fn HT_PHASOR_step_impl(sp: &mut HT_PHASOR_StreamState, inReal: f64, outInPhase: &mut f64, outQuadrature: &mut f64) {
        let mut tempReal: f64 = 0.0_f64;
        let mut tempReal2: f64 = 0.0_f64;
        let mut adjustedPrevPeriod: f64 = 0.0_f64;
        let mut smoothedValue: f64 = 0.0_f64;
        let mut hilbertTempReal: f64 = 0.0_f64;
        let mut detrender: f64 = 0.0_f64;
        let mut Q1: f64 = 0.0_f64;
        let mut jI: f64 = 0.0_f64;
        let mut jQ: f64 = 0.0_f64;
        let mut Q2: f64 = 0.0_f64;
        let mut I2: f64 = 0.0_f64;
        let mut todayValue: f64 = 0.0_f64;
        if sp.ringCap_trailingWMAIdx == 0 {
            sp.ring_trailingWMAIdx_inReal[0] = inReal;
        }
        adjustedPrevPeriod = (0.075 as f64).mul_add(sp.period, 0.54);
        todayValue = inReal;
        sp.periodWMASub += todayValue;
        sp.periodWMASub -= sp.trailingWMAValue;
        sp.periodWMASum += todayValue * 4.0;
        sp.trailingWMAValue = sp.ring_trailingWMAIdx_inReal[sp.ringPos_trailingWMAIdx];
        smoothedValue = sp.periodWMASum * 0.1;
        sp.periodWMASum -= sp.periodWMASub;
        if sp.streamParity == 0 {
            // Do the Hilbert Transforms for even price bar
            hilbertTempReal = sp.a * smoothedValue;
            detrender = 0_f64 - sp.detrender_Even[sp.hilbertIdx];
            sp.detrender_Even[sp.hilbertIdx] = hilbertTempReal;
            detrender += hilbertTempReal;
            detrender -= sp.prev_detrender_Even;
            sp.prev_detrender_Even = sp.b * sp.prev_detrender_input_Even;
            detrender += sp.prev_detrender_Even;
            sp.prev_detrender_input_Even = smoothedValue;
            detrender *= adjustedPrevPeriod;
            hilbertTempReal = sp.a * detrender;
            Q1 = 0_f64 - sp.Q1_Even[sp.hilbertIdx];
            sp.Q1_Even[sp.hilbertIdx] = hilbertTempReal;
            Q1 += hilbertTempReal;
            Q1 -= sp.prev_Q1_Even;
            sp.prev_Q1_Even = sp.b * sp.prev_Q1_input_Even;
            Q1 += sp.prev_Q1_Even;
            sp.prev_Q1_input_Even = detrender;
            Q1 *= adjustedPrevPeriod;
            (*outQuadrature) = Q1;
            (*outInPhase) = sp.I1ForEvenPrev3;
            hilbertTempReal = sp.a * sp.I1ForEvenPrev3;
            jI = 0_f64 - sp.jI_Even[sp.hilbertIdx];
            sp.jI_Even[sp.hilbertIdx] = hilbertTempReal;
            jI += hilbertTempReal;
            jI -= sp.prev_jI_Even;
            sp.prev_jI_Even = sp.b * sp.prev_jI_input_Even;
            jI += sp.prev_jI_Even;
            sp.prev_jI_input_Even = sp.I1ForEvenPrev3;
            jI *= adjustedPrevPeriod;
            hilbertTempReal = sp.a * Q1;
            jQ = 0_f64 - sp.jQ_Even[sp.hilbertIdx];
            sp.jQ_Even[sp.hilbertIdx] = hilbertTempReal;
            jQ += hilbertTempReal;
            jQ -= sp.prev_jQ_Even;
            sp.prev_jQ_Even = sp.b * sp.prev_jQ_input_Even;
            jQ += sp.prev_jQ_Even;
            sp.prev_jQ_input_Even = Q1;
            jQ *= adjustedPrevPeriod;
            if { sp.hilbertIdx += 1; sp.hilbertIdx } == 3 {
                sp.hilbertIdx = 0;
            }
            Q2 = (0.2 as f64).mul_add(Q1 + jI, 0.8 * sp.prevQ2);
            I2 = (0.2 as f64).mul_add(sp.I1ForEvenPrev3 - jQ, 0.8 * sp.prevI2);
            // The variable I1 is the detrender delayed for
            // 3 price bars.
            //
            // Save the current detrender value for being
            // used by the "odd" logic later.
            sp.I1ForOddPrev3 = sp.I1ForOddPrev2;
            sp.I1ForOddPrev2 = detrender;
        } else {
            // Do the Hilbert Transforms for odd price bar
            hilbertTempReal = sp.a * smoothedValue;
            detrender = 0_f64 - sp.detrender_Odd[sp.hilbertIdx];
            sp.detrender_Odd[sp.hilbertIdx] = hilbertTempReal;
            detrender += hilbertTempReal;
            detrender -= sp.prev_detrender_Odd;
            sp.prev_detrender_Odd = sp.b * sp.prev_detrender_input_Odd;
            detrender += sp.prev_detrender_Odd;
            sp.prev_detrender_input_Odd = smoothedValue;
            detrender *= adjustedPrevPeriod;
            hilbertTempReal = sp.a * detrender;
            Q1 = 0_f64 - sp.Q1_Odd[sp.hilbertIdx];
            sp.Q1_Odd[sp.hilbertIdx] = hilbertTempReal;
            Q1 += hilbertTempReal;
            Q1 -= sp.prev_Q1_Odd;
            sp.prev_Q1_Odd = sp.b * sp.prev_Q1_input_Odd;
            Q1 += sp.prev_Q1_Odd;
            sp.prev_Q1_input_Odd = detrender;
            Q1 *= adjustedPrevPeriod;
            (*outQuadrature) = Q1;
            (*outInPhase) = sp.I1ForOddPrev3;
            hilbertTempReal = sp.a * sp.I1ForOddPrev3;
            jI = 0_f64 - sp.jI_Odd[sp.hilbertIdx];
            sp.jI_Odd[sp.hilbertIdx] = hilbertTempReal;
            jI += hilbertTempReal;
            jI -= sp.prev_jI_Odd;
            sp.prev_jI_Odd = sp.b * sp.prev_jI_input_Odd;
            jI += sp.prev_jI_Odd;
            sp.prev_jI_input_Odd = sp.I1ForOddPrev3;
            jI *= adjustedPrevPeriod;
            hilbertTempReal = sp.a * Q1;
            jQ = 0_f64 - sp.jQ_Odd[sp.hilbertIdx];
            sp.jQ_Odd[sp.hilbertIdx] = hilbertTempReal;
            jQ += hilbertTempReal;
            jQ -= sp.prev_jQ_Odd;
            sp.prev_jQ_Odd = sp.b * sp.prev_jQ_input_Odd;
            jQ += sp.prev_jQ_Odd;
            sp.prev_jQ_input_Odd = Q1;
            jQ *= adjustedPrevPeriod;
            Q2 = (0.2 as f64).mul_add(Q1 + jI, 0.8 * sp.prevQ2);
            I2 = (0.2 as f64).mul_add(sp.I1ForOddPrev3 - jQ, 0.8 * sp.prevI2);
            // The varaiable I1 is the detrender delayed for
            // 3 price bars.
            //
            // Save the current detrender value for being
            // used by the "even" logic later.
            sp.I1ForEvenPrev3 = sp.I1ForEvenPrev2;
            sp.I1ForEvenPrev2 = detrender;
        }
        // Adjust the period for next price bar
        sp.Re = (0.8 as f64).mul_add(sp.Re, 0.2 * ((I2 as f64).mul_add(sp.prevI2, Q2 * sp.prevQ2)));
        sp.Im = (0.8 as f64).mul_add(sp.Im, 0.2 * (I2 * sp.prevQ2 - Q2 * sp.prevI2));
        sp.prevQ2 = Q2;
        sp.prevI2 = I2;
        tempReal = sp.period;
        if sp.Im != 0.0 && sp.Re != 0.0 {
            sp.period = 360.0 / ((sp.Im / sp.Re).atan() * sp.rad2Deg);
        }
        tempReal2 = 1.5 * tempReal;
        if sp.period > tempReal2 {
            sp.period = tempReal2;
        }
        tempReal2 = 0.67 * tempReal;
        if sp.period < tempReal2 {
            sp.period = tempReal2;
        }
        if sp.period < 6_f64 {
            sp.period = 6.0;
        } else if sp.period > 50_f64 {
            sp.period = 50.0;
        }
        sp.period = (0.2 as f64).mul_add(sp.period, 0.8 * tempReal);
        // Ooof... let's do the next price bar now!
        sp.ring_trailingWMAIdx_inReal[sp.ringPos_trailingWMAIdx] = inReal;
        sp.ringPos_trailingWMAIdx = sp.ringPos_trailingWMAIdx + 1;
        if sp.ringPos_trailingWMAIdx >= sp.ringCap_trailingWMAIdx {
            sp.ringPos_trailingWMAIdx = 0;
        }
        sp.streamParity = 1 - sp.streamParity;
    }

    /// The single whole-history transcription behind [`Core::HT_PHASOR_OpenInternal`]
    /// (stride 0, scalar sink) and [`Core::HT_PHASOR_OpenAndFill`] (stride 1, caller slices).
    pub(crate) fn HT_PHASOR_OpenImpl(
        &self, inReal: &[f64], startIdx: usize, outBegIdx: &mut usize, outNBElement: &mut usize, outInPhase: &mut [f64], outQuadrature: &mut [f64], outStride: usize,
    ) -> Result<HT_PHASOR_Stream, RetCode> {
        if inReal.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inReal.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        let historyLen: usize = inReal.len();
        let endIdx: usize = historyLen - 1;
        let mut startIdx = startIdx;
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut outIdx: usize = 0_usize;
        let mut i: usize = 0_usize;
        let mut lookbackTotal: usize = 0_usize;
        let mut today: usize = 0_usize;
        let mut tempReal: f64 = 0.0_f64;
        let mut tempReal2: f64 = 0.0_f64;
        let mut adjustedPrevPeriod: f64 = 0.0_f64;
        let mut period: f64 = 0.0_f64;
        let mut trailingWMAIdx: usize = 0_usize;
        let mut periodWMASum: f64 = 0.0_f64;
        let mut periodWMASub: f64 = 0.0_f64;
        let mut trailingWMAValue: f64 = 0.0_f64;
        let mut smoothedValue: f64 = 0.0_f64;
        let mut a: f64 = 0.0_f64;
        let mut b: f64 = 0.0_f64;
        let mut hilbertTempReal: f64 = 0.0_f64;
        let mut hilbertIdx: usize = 0_usize;
        let mut detrender_Odd: [f64; 3 as usize] = [0.0_f64; 3 as usize];
        let mut detrender_Even: [f64; 3 as usize] = [0.0_f64; 3 as usize];
        let mut detrender: f64 = 0.0_f64;
        let mut prev_detrender_Odd: f64 = 0.0_f64;
        let mut prev_detrender_Even: f64 = 0.0_f64;
        let mut prev_detrender_input_Odd: f64 = 0.0_f64;
        let mut prev_detrender_input_Even: f64 = 0.0_f64;
        let mut Q1_Odd: [f64; 3 as usize] = [0.0_f64; 3 as usize];
        let mut Q1_Even: [f64; 3 as usize] = [0.0_f64; 3 as usize];
        let mut Q1: f64 = 0.0_f64;
        let mut prev_Q1_Odd: f64 = 0.0_f64;
        let mut prev_Q1_Even: f64 = 0.0_f64;
        let mut prev_Q1_input_Odd: f64 = 0.0_f64;
        let mut prev_Q1_input_Even: f64 = 0.0_f64;
        let mut jI_Odd: [f64; 3 as usize] = [0.0_f64; 3 as usize];
        let mut jI_Even: [f64; 3 as usize] = [0.0_f64; 3 as usize];
        let mut jI: f64 = 0.0_f64;
        let mut prev_jI_Odd: f64 = 0.0_f64;
        let mut prev_jI_Even: f64 = 0.0_f64;
        let mut prev_jI_input_Odd: f64 = 0.0_f64;
        let mut prev_jI_input_Even: f64 = 0.0_f64;
        let mut jQ_Odd: [f64; 3 as usize] = [0.0_f64; 3 as usize];
        let mut jQ_Even: [f64; 3 as usize] = [0.0_f64; 3 as usize];
        let mut jQ: f64 = 0.0_f64;
        let mut prev_jQ_Odd: f64 = 0.0_f64;
        let mut prev_jQ_Even: f64 = 0.0_f64;
        let mut prev_jQ_input_Odd: f64 = 0.0_f64;
        let mut prev_jQ_input_Even: f64 = 0.0_f64;
        let mut Q2: f64 = 0.0_f64;
        let mut I2: f64 = 0.0_f64;
        let mut prevQ2: f64 = 0.0_f64;
        let mut prevI2: f64 = 0.0_f64;
        let mut Re: f64 = 0.0_f64;
        let mut Im: f64 = 0.0_f64;
        let mut I1ForOddPrev2: f64 = 0.0_f64;
        let mut I1ForOddPrev3: f64 = 0.0_f64;
        let mut I1ForEvenPrev2: f64 = 0.0_f64;
        let mut I1ForEvenPrev3: f64 = 0.0_f64;
        let mut rad2Deg: f64 = 0.0_f64;
        let mut todayValue: f64 = 0.0_f64;
        a = 0.0962;
        b = 0.5769;
        // Variable used for the price smoother (a weighted moving average).
        // Variables used for the Hilbert Transormation
        // Constant
        rad2Deg = 180.0 / (4.0 * (1_f64).atan());
        // Identify the minimum number of price bar needed
        // to calculate at least one output.
        lookbackTotal = (32 + self.unstable_period[FuncUnstId::HT_PHASOR as usize]) as usize;
        // Move up the start index if there is not
        // enough initial data.
        if startIdx < lookbackTotal {
            startIdx = lookbackTotal;
        }
        // Make sure there is still something to evaluate.
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        (*outBegIdx) = startIdx;
        // Initialize the price smoother, which is simply a weighted
        // moving average of the price.
        // To understand this algorithm, I strongly suggest to understand
        // first how TA_WMA is done.
        trailingWMAIdx = startIdx - lookbackTotal;
        today = trailingWMAIdx;
        // Initialization is same as WMA, except loop is unrolled
        // for speed optimization.
        tempReal = inReal[{ let _v = today; today += 1; _v }];
        periodWMASub = tempReal;
        periodWMASum = tempReal;
        tempReal = inReal[{ let _v = today; today += 1; _v }];
        periodWMASub += tempReal;
        periodWMASum += tempReal * 2.0;
        tempReal = inReal[{ let _v = today; today += 1; _v }];
        periodWMASub += tempReal;
        periodWMASum += tempReal * 3.0;
        trailingWMAValue = 0.0;
        // Subsequent WMA value are evaluated by using
        // the DO_PRICE_WMA macro.
        i = 9;
        loop {
            tempReal = inReal[{ let _v = today; today += 1; _v }];
            periodWMASub += tempReal;
            periodWMASub -= trailingWMAValue;
            periodWMASum += tempReal * 4.0;
            trailingWMAValue = inReal[{ let _v = trailingWMAIdx; trailingWMAIdx += 1; _v }];
            smoothedValue = periodWMASum * 0.1;
            periodWMASum -= periodWMASub;
            if !({ i = i.wrapping_sub(1); i } != 0) { break; }
        }
        // Initialize the circular buffers used by the hilbert
        // transform logic.
        // A buffer is used for odd day and another for even days.
        // This minimize the number of memory access and floating point
        // operations needed (note also that by using static circular buffer,
        // no large dynamic memory allocation is needed for storing
        // intermediate calculation!).
        hilbertIdx = 0;
        detrender_Odd[0] = 0.0;
        detrender_Odd[1] = 0.0;
        detrender_Odd[2] = 0.0;
        detrender_Even[0] = 0.0;
        detrender_Even[1] = 0.0;
        detrender_Even[2] = 0.0;
        detrender = 0.0;
        prev_detrender_Odd = 0.0;
        prev_detrender_Even = 0.0;
        prev_detrender_input_Odd = 0.0;
        prev_detrender_input_Even = 0.0;
        Q1_Odd[0] = 0.0;
        Q1_Odd[1] = 0.0;
        Q1_Odd[2] = 0.0;
        Q1_Even[0] = 0.0;
        Q1_Even[1] = 0.0;
        Q1_Even[2] = 0.0;
        Q1 = 0.0;
        prev_Q1_Odd = 0.0;
        prev_Q1_Even = 0.0;
        prev_Q1_input_Odd = 0.0;
        prev_Q1_input_Even = 0.0;
        jI_Odd[0] = 0.0;
        jI_Odd[1] = 0.0;
        jI_Odd[2] = 0.0;
        jI_Even[0] = 0.0;
        jI_Even[1] = 0.0;
        jI_Even[2] = 0.0;
        jI = 0.0;
        prev_jI_Odd = 0.0;
        prev_jI_Even = 0.0;
        prev_jI_input_Odd = 0.0;
        prev_jI_input_Even = 0.0;
        jQ_Odd[0] = 0.0;
        jQ_Odd[1] = 0.0;
        jQ_Odd[2] = 0.0;
        jQ_Even[0] = 0.0;
        jQ_Even[1] = 0.0;
        jQ_Even[2] = 0.0;
        jQ = 0.0;
        prev_jQ_Odd = 0.0;
        prev_jQ_Even = 0.0;
        prev_jQ_input_Odd = 0.0;
        prev_jQ_input_Even = 0.0;
        period = 0.0;
        outIdx = 0;
        prevQ2 = 0.0;
        prevI2 = prevQ2;
        Im = 0.0;
        Re = Im;
        I1ForEvenPrev3 = 0.0;
        I1ForOddPrev3 = I1ForEvenPrev3;
        I1ForEvenPrev2 = 0.0;
        I1ForOddPrev2 = I1ForEvenPrev2;
        // The code is speed optimized and is most likely very
        // hard to follow if you do not already know well the
        // original algorithm.
        // To understadn better, it is strongly suggested to look
        // first at the Excel implementation in "test_MAMA.xls" included
        // in this package.
        while today <= endIdx {
            adjustedPrevPeriod = (0.075 as f64).mul_add(period, 0.54);
            todayValue = inReal[today];
            periodWMASub += todayValue;
            periodWMASub -= trailingWMAValue;
            periodWMASum += todayValue * 4.0;
            trailingWMAValue = inReal[{ let _v = trailingWMAIdx; trailingWMAIdx += 1; _v }];
            smoothedValue = periodWMASum * 0.1;
            periodWMASum -= periodWMASub;
            if today % 2 == 0 {
                // Do the Hilbert Transforms for even price bar
                hilbertTempReal = a * smoothedValue;
                detrender = 0_f64 - detrender_Even[hilbertIdx];
                detrender_Even[hilbertIdx] = hilbertTempReal;
                detrender += hilbertTempReal;
                detrender -= prev_detrender_Even;
                prev_detrender_Even = b * prev_detrender_input_Even;
                detrender += prev_detrender_Even;
                prev_detrender_input_Even = smoothedValue;
                detrender *= adjustedPrevPeriod;
                hilbertTempReal = a * detrender;
                Q1 = 0_f64 - Q1_Even[hilbertIdx];
                Q1_Even[hilbertIdx] = hilbertTempReal;
                Q1 += hilbertTempReal;
                Q1 -= prev_Q1_Even;
                prev_Q1_Even = b * prev_Q1_input_Even;
                Q1 += prev_Q1_Even;
                prev_Q1_input_Even = detrender;
                Q1 *= adjustedPrevPeriod;
                if today >= startIdx {
                    outQuadrature[(outIdx * outStride) as usize] = Q1;
                    outInPhase[({ let _v = outIdx; outIdx += 1; _v } * outStride) as usize] = I1ForEvenPrev3;
                }
                hilbertTempReal = a * I1ForEvenPrev3;
                jI = 0_f64 - jI_Even[hilbertIdx];
                jI_Even[hilbertIdx] = hilbertTempReal;
                jI += hilbertTempReal;
                jI -= prev_jI_Even;
                prev_jI_Even = b * prev_jI_input_Even;
                jI += prev_jI_Even;
                prev_jI_input_Even = I1ForEvenPrev3;
                jI *= adjustedPrevPeriod;
                hilbertTempReal = a * Q1;
                jQ = 0_f64 - jQ_Even[hilbertIdx];
                jQ_Even[hilbertIdx] = hilbertTempReal;
                jQ += hilbertTempReal;
                jQ -= prev_jQ_Even;
                prev_jQ_Even = b * prev_jQ_input_Even;
                jQ += prev_jQ_Even;
                prev_jQ_input_Even = Q1;
                jQ *= adjustedPrevPeriod;
                if { hilbertIdx += 1; hilbertIdx } == 3 {
                    hilbertIdx = 0;
                }
                Q2 = (0.2 as f64).mul_add(Q1 + jI, 0.8 * prevQ2);
                I2 = (0.2 as f64).mul_add(I1ForEvenPrev3 - jQ, 0.8 * prevI2);
                // The variable I1 is the detrender delayed for
                // 3 price bars.
                //
                // Save the current detrender value for being
                // used by the "odd" logic later.
                I1ForOddPrev3 = I1ForOddPrev2;
                I1ForOddPrev2 = detrender;
            } else {
                // Do the Hilbert Transforms for odd price bar
                hilbertTempReal = a * smoothedValue;
                detrender = 0_f64 - detrender_Odd[hilbertIdx];
                detrender_Odd[hilbertIdx] = hilbertTempReal;
                detrender += hilbertTempReal;
                detrender -= prev_detrender_Odd;
                prev_detrender_Odd = b * prev_detrender_input_Odd;
                detrender += prev_detrender_Odd;
                prev_detrender_input_Odd = smoothedValue;
                detrender *= adjustedPrevPeriod;
                hilbertTempReal = a * detrender;
                Q1 = 0_f64 - Q1_Odd[hilbertIdx];
                Q1_Odd[hilbertIdx] = hilbertTempReal;
                Q1 += hilbertTempReal;
                Q1 -= prev_Q1_Odd;
                prev_Q1_Odd = b * prev_Q1_input_Odd;
                Q1 += prev_Q1_Odd;
                prev_Q1_input_Odd = detrender;
                Q1 *= adjustedPrevPeriod;
                if today >= startIdx {
                    outQuadrature[(outIdx * outStride) as usize] = Q1;
                    outInPhase[({ let _v = outIdx; outIdx += 1; _v } * outStride) as usize] = I1ForOddPrev3;
                }
                hilbertTempReal = a * I1ForOddPrev3;
                jI = 0_f64 - jI_Odd[hilbertIdx];
                jI_Odd[hilbertIdx] = hilbertTempReal;
                jI += hilbertTempReal;
                jI -= prev_jI_Odd;
                prev_jI_Odd = b * prev_jI_input_Odd;
                jI += prev_jI_Odd;
                prev_jI_input_Odd = I1ForOddPrev3;
                jI *= adjustedPrevPeriod;
                hilbertTempReal = a * Q1;
                jQ = 0_f64 - jQ_Odd[hilbertIdx];
                jQ_Odd[hilbertIdx] = hilbertTempReal;
                jQ += hilbertTempReal;
                jQ -= prev_jQ_Odd;
                prev_jQ_Odd = b * prev_jQ_input_Odd;
                jQ += prev_jQ_Odd;
                prev_jQ_input_Odd = Q1;
                jQ *= adjustedPrevPeriod;
                Q2 = (0.2 as f64).mul_add(Q1 + jI, 0.8 * prevQ2);
                I2 = (0.2 as f64).mul_add(I1ForOddPrev3 - jQ, 0.8 * prevI2);
                // The varaiable I1 is the detrender delayed for
                // 3 price bars.
                //
                // Save the current detrender value for being
                // used by the "even" logic later.
                I1ForEvenPrev3 = I1ForEvenPrev2;
                I1ForEvenPrev2 = detrender;
            }
            // Adjust the period for next price bar
            Re = (0.8 as f64).mul_add(Re, 0.2 * ((I2 as f64).mul_add(prevI2, Q2 * prevQ2)));
            Im = (0.8 as f64).mul_add(Im, 0.2 * (I2 * prevQ2 - Q2 * prevI2));
            prevQ2 = Q2;
            prevI2 = I2;
            tempReal = period;
            if Im != 0.0 && Re != 0.0 {
                period = 360.0 / ((Im / Re).atan() * rad2Deg);
            }
            tempReal2 = 1.5 * tempReal;
            if period > tempReal2 {
                period = tempReal2;
            }
            tempReal2 = 0.67 * tempReal;
            if period < tempReal2 {
                period = tempReal2;
            }
            if period < 6_f64 {
                period = 6.0;
            } else if period > 50_f64 {
                period = 50.0;
            }
            period = (0.2 as f64).mul_add(period, 0.8 * tempReal);
            // Ooof... let's do the next price bar now!
            today += 1;
        }
        // Default return values
        (*outNBElement) = outIdx;

        // Capture the live batch state into the handle.
        let cap_trailingWMAIdx: i64 = (today as i64) - (trailingWMAIdx as i64);
        if cap_trailingWMAIdx < 0 || cap_trailingWMAIdx > historyLen as i64 {
            return Err(RetCode::InternalError);
        }
        let allocN_trailingWMAIdx: usize = if cap_trailingWMAIdx > 0 { cap_trailingWMAIdx as usize } else { 1 };
        let mut ring_trailingWMAIdx_inReal: Vec<f64> = vec![0.0_f64; allocN_trailingWMAIdx];
        ring_trailingWMAIdx_inReal[..cap_trailingWMAIdx as usize]
            .copy_from_slice(&inReal[historyLen - cap_trailingWMAIdx as usize..]);
        let state = HT_PHASOR_StreamState {
            period,
            periodWMASum,
            periodWMASub,
            trailingWMAValue,
            a,
            b,
            hilbertIdx,
            detrender_Odd,
            detrender_Even,
            prev_detrender_Odd,
            prev_detrender_Even,
            prev_detrender_input_Odd,
            prev_detrender_input_Even,
            Q1_Odd,
            Q1_Even,
            prev_Q1_Odd,
            prev_Q1_Even,
            prev_Q1_input_Odd,
            prev_Q1_input_Even,
            jI_Odd,
            jI_Even,
            prev_jI_Odd,
            prev_jI_Even,
            prev_jI_input_Odd,
            prev_jI_input_Even,
            jQ_Odd,
            jQ_Even,
            prev_jQ_Odd,
            prev_jQ_Even,
            prev_jQ_input_Odd,
            prev_jQ_input_Even,
            prevQ2,
            prevI2,
            Re,
            Im,
            I1ForOddPrev2,
            I1ForOddPrev3,
            I1ForEvenPrev2,
            I1ForEvenPrev3,
            rad2Deg,
            streamParity: historyLen % 2,
            ringPos_trailingWMAIdx: 0_usize,
            ringCap_trailingWMAIdx: cap_trailingWMAIdx as usize,
            ring_trailingWMAIdx_inReal,
        };
        Ok(HT_PHASOR_Stream { state, out: OutRange { beg_idx: *outBegIdx, count: *outNBElement } })
    }

    /// Internal startIdx-anchored open behind [`Core::HT_PHASOR_Open`] (composition seam).
    pub(crate) fn HT_PHASOR_OpenInternal(
        &self, inReal: &[f64], startIdx: usize,
    ) -> Result<(HT_PHASOR_Stream, (f64, f64)), RetCode> {
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut sink_outInPhase = [0.0_f64; 1];
        let mut sink_outQuadrature = [0.0_f64; 1];
        let handle = self.HT_PHASOR_OpenImpl(inReal, startIdx, &mut dummyBegIdx, &mut dummyNBElement, &mut sink_outInPhase, &mut sink_outQuadrature, 0)?;
        Ok((handle, (sink_outInPhase[0], sink_outQuadrature[0])))
    }

    /// Open a live HT_PHASOR stream over the warm-up history; returns the handle and
    /// the value at the last history bar — bit-identical to [`Core::HT_PHASOR`] at that bar.
    ///
    /// # Errors
    ///
    /// [`RetCode::InsufficientHistory`] when the history holds fewer than
    /// `lookback + 1` bars — the one failure here worth retrying, since another
    /// bar fixes it. [`RetCode::OutOfRangeStartIndex`] when the history is empty.
    /// [`RetCode::BadParam`] when a parameter is out of range or the input
    /// lengths differ.
    ///
    /// ```
    /// use ta_lib::Core;
    /// let data: Vec<f64> = (0..252).map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    ///
    /// let core = Core::new();
    /// let (mut s, _last) = core.HT_PHASOR_Open(&data).expect("enough history");
    /// let r0 = s.out_range();
    /// let peeked = s.peek(100.9).expect("a finite bar");
    /// assert_eq!(s.out_range().count, r0.count); // a peek commits nothing
    /// let updated = s.update(100.9).expect("a finite bar");
    /// assert_eq!(s.out_range().beg_idx, r0.beg_idx);
    /// assert_eq!(s.out_range().count, r0.count + 1);
    /// assert_eq!(peeked.0.to_bits(), updated.0.to_bits());
    /// assert_eq!(peeked.1.to_bits(), updated.1.to_bits());
    /// ```
    #[doc(alias = "TA_HT_PHASOR_Open")]
    pub fn HT_PHASOR_Open(&self, inReal: &[f64], ) -> Result<(HT_PHASOR_Stream, (f64, f64)), RetCode> {
        self.HT_PHASOR_OpenInternal(inReal, 0)
    }

    /// [`Core::HT_PHASOR_Open`] that also fills the output array(s) bit-identically to
    /// [`Core::HT_PHASOR`] over `0..len` in the same single pass, and reports the range it
    /// wrote as the [`OutRange`] beside the handle.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] when an output slice holds fewer than `len - lookback`
    /// values — the batch tier's sizing rule, checked here as it is there (rule S5) —
    /// or when two of them are the same slice. Everything [`Core::HT_PHASOR_Open`] rejects
    /// is rejected here too.
    #[doc(alias = "TA_HT_PHASOR_OpenAndFill")]
    pub fn HT_PHASOR_OpenAndFill(
        &self, inReal: &[f64], outInPhase: &mut [f64], outQuadrature: &mut [f64],
    ) -> Result<(HT_PHASOR_Stream, OutRange), RetCode> {
        if inReal.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inReal.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        let _guardLb = self.HT_PHASOR_Lookback()?;
        let _guardOutLen = inReal.len().saturating_sub(_guardLb);
        if outInPhase.len() < _guardOutLen {
            return Err(RetCode::BadParam);
        }
        if outQuadrature.len() < _guardOutLen {
            return Err(RetCode::BadParam);
        }
        if !outInPhase.is_empty() && !outQuadrature.is_empty() && outInPhase.as_ptr() == outQuadrature.as_ptr() {
            return Err(RetCode::BadParam);
        }
        let mut outBegIdx: usize = 0;
        let mut outNBElement: usize = 0;
        let handle = self.HT_PHASOR_OpenAndFillInternal(inReal, 0, &mut outBegIdx, &mut outNBElement, outInPhase, outQuadrature)?;
        Ok((handle, OutRange { beg_idx: outBegIdx, count: outNBElement }))
    }

    /// [`Core::HT_PHASOR_OpenAndFill`] anchored at `startIdx` — the composed-open
    /// fusion seam (issue #192), not a public entry point.
    pub(crate) fn HT_PHASOR_OpenAndFillInternal(
        &self, inReal: &[f64], startIdx: usize, outBegIdx: &mut usize, outNBElement: &mut usize, outInPhase: &mut [f64], outQuadrature: &mut [f64],
    ) -> Result<HT_PHASOR_Stream, RetCode> {
        self.HT_PHASOR_OpenImpl(inReal, startIdx, outBegIdx, outNBElement, outInPhase, outQuadrature, 1)
    }

}

#[allow(non_snake_case)]
#[allow(unused_variables)]
impl HT_PHASOR_Stream {
    /// Commit one closed bar. Never allocates.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite (NaN or ±Inf).
    /// That check runs before anything is written, so the handle is left
    /// exactly as it was and the stream stays usable:
    /// skip the bar, or close and re-open on a clean history. This is the
    /// one place the streaming tier is stricter than the batch API, which
    /// computes on whatever it is given — a handle retains its state, so a
    /// single non-finite bar would poison every later value it produces.
    #[doc(alias = "TA_HT_PHASOR_Update")]
    pub fn update(&mut self, inReal: f64) -> Result<(f64, f64), RetCode> {
        if !inReal.is_finite() {
            return Err(RetCode::BadParam);
        }
        let mut outInPhase: f64 = 0.0_f64;
        let mut outQuadrature: f64 = 0.0_f64;
        Core::HT_PHASOR_step_impl(&mut self.state, inReal, &mut outInPhase, &mut outQuadrature);
        if self.out.count < Core::MAX_INDEX {
            self.out.count += 1;
        }
        Ok((outInPhase, outQuadrature))
    }

    /// Commit `n` closed bars and write their `n` values, in one call —
    /// exactly `n` back-to-back [`Self::update`] calls, with one set of
    /// argument checks instead of `n`. `n` is `inReal.len()`; the outputs must
    /// hold at least that many. Never allocates.
    ///
    /// [`Self::out_range`] counts what was committed, which is what makes the
    /// rejection below readable: there is no second out-parameter for it.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if the input slices differ in length, if an output
    /// is shorter than the bar count — neither commits anything — or if a bar
    /// is not finite. A non-finite bar `k` is rejected exactly as `update`
    /// rejects it: bars `0..k` stay committed and their values written, bar `k`
    /// and everything after it is not, and `out_range().count` has advanced by
    /// `k`.
    #[doc(alias = "TA_HT_PHASOR_UpdateAndFill")]
    pub fn update_and_fill(&mut self, inReal: &[f64], outInPhase: &mut [f64], outQuadrature: &mut [f64]) -> Result<(), RetCode> {
        let barCount = inReal.len();
        if outInPhase.len() < barCount || outQuadrature.len() < barCount {
            return Err(RetCode::BadParam);
        }
        for i in 0..barCount {
            if !inReal[i].is_finite() {
                return Err(RetCode::BadParam);
            }
            Core::HT_PHASOR_step_impl(&mut self.state, inReal[i], &mut outInPhase[i], &mut outQuadrature[i]);
            if self.out.count < Core::MAX_INDEX {
                self.out.count += 1;
            }
        }
        Ok(())
    }

    /// Evaluate a forming bar without committing — bit-identical to what the
    /// next `update` with the same bar would return (it is the same code, run
    /// on a scratch copy of the state). Never writes the handle, so peeks may
    /// run concurrently with each other. The copy is a throwaway. Its buffer clone is
    /// often removed outright by the optimizer, which is why nothing is
    /// reused here, but that is not a guarantee: budget for a clone of the
    /// buffers it does own and prefer `update` on a `clone()` in a hot loop.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite, exactly as
    /// `update` rejects it.
    #[doc(alias = "TA_HT_PHASOR_Peek")]
    pub fn peek(&self, inReal: f64) -> Result<(f64, f64), RetCode> {
        if !inReal.is_finite() {
            return Err(RetCode::BadParam);
        }
        let mut scratch = self.clone();
        scratch.update(inReal)
    }

    /// The bars this stream has produced a value for, in the input series'
    /// coordinates: `[beg_idx, beg_idx + count)`.
    ///
    /// It is what [`Core::HT_PHASOR`] reports over the same bars: the opener sets it
    /// to `(lookback, historyLen - lookback)`, every accepted `update` adds one
    /// to the count, `peek` leaves it alone, and a clone carries it verbatim.
    /// A plain `Open` hands back only the last value, a subset of this range,
    /// because the caller chose not to take the fill.
    #[doc(alias = "TA_StreamOutRange")]
    pub fn out_range(&self) -> OutRange {
        self.out
    }
}

