impl Core {
    fn pvt_step_impl(sp: &mut PvtStreamState, inClose: f64, inVolume: f64, outReal: &mut f64) {
        let mut tempClose: f64 = 0.0_f64;
        tempClose = inClose;
        // Exact test, never an epsilon band: a band carries the quote unit and
        // would zero the indicator for every instrument priced under it (#253).
        // A zero previous close contributes nothing rather than Inf/NaN (#112).
        if sp.prevClose != 0.0 {
            sp.prevPVT += (tempClose - sp.prevClose) / sp.prevClose * inVolume;
        }
        (*outReal) = sp.prevPVT;
        sp.prevClose = tempClose;
        sp.cur_outReal = (*outReal);
    }

    /// The single whole-history transcription behind [`Core::pvt_open_internal`]
    /// (stride 0, scalar sink) and [`Core::pvt_open_and_fill`] (stride 1, caller slices).
    pub(crate) fn pvt_open_impl(
        &self, inClose: &[f64], inVolume: &[f64], startIdx: usize, outBegIdx: &mut usize, outNBElement: &mut usize, outReal: &mut [f64], outStride: usize,
    ) -> Result<PvtStream, RetCode> {
        if inClose.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inClose.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        if inVolume.len() != inClose.len() {
            return Err(RetCode::BadParam);
        }
        let historyLen: usize = inClose.len();
        let endIdx: usize = historyLen - 1;
        let mut startIdx = startIdx;
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut i: usize = 0_usize;
        let mut outIdx: usize = 0_usize;
        let mut prevPVT: f64 = 0.0_f64;
        let mut prevClose: f64 = 0.0_f64;
        let mut tempClose: f64 = 0.0_f64;
        prevPVT = 0.0;
        prevClose = inClose[startIdx];
        outIdx = 0;
        for i in (startIdx as usize)..(endIdx as usize) + 1 {
            tempClose = inClose[i];
            // Exact test, never an epsilon band: a band carries the quote unit and
            // would zero the indicator for every instrument priced under it (#253).
            // A zero previous close contributes nothing rather than Inf/NaN (#112).
            if prevClose != 0.0 {
                prevPVT += (tempClose - prevClose) / prevClose * inVolume[i];
            }
            outReal[({ let _v = outIdx; outIdx += 1; _v } * outStride) as usize] = prevPVT;
            prevClose = tempClose;
        }
        i = (endIdx as usize) + 1;
        (*outBegIdx) = startIdx;
        (*outNBElement) = outIdx;

        // Capture the live batch state into the handle.
        let state = PvtStreamState {
            prevPVT,
            prevClose,
            cur_outReal: outReal[(*outNBElement - 1) * outStride],
        };
        Ok(PvtStream { state, out: OutRange { beg_idx: *outBegIdx, count: *outNBElement } })
    }

    /// Internal startIdx-anchored open behind [`Core::pvt_open`] (composition seam).
    pub(crate) fn pvt_open_internal(
        &self, inClose: &[f64], inVolume: &[f64], startIdx: usize,
    ) -> Result<(PvtStream, f64), RetCode> {
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut sink_outReal = [0.0_f64; 1];
        let handle = self.pvt_open_impl(inClose, inVolume, startIdx, &mut dummyBegIdx, &mut dummyNBElement, &mut sink_outReal, 0)?;
        Ok((handle, sink_outReal[0]))
    }

    /// Open a live PVT stream over the warm-up history; returns the handle and
    /// the value at the last history bar — bit-identical to [`Core::PVT`] at that bar.
    ///
    /// # Errors
    ///
    /// [`RetCode::InsufficientHistory`] when the history holds fewer than
    /// `lookback + 1` bars — the one failure here worth retrying, since another
    /// bar fixes it. [`RetCode::OutOfRangeStartIndex`] when the history is empty.
    /// [`RetCode::BadParam`] when a parameter is out of range or the input
    /// lengths differ.
    ///
    /// ```
    /// use ta_lib::Core;
    /// let close: Vec<f64> = (0..252)
    ///     .map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin() + 0.8 * (0.7 * i as f64).sin())
    ///     .collect();
    /// let volume: Vec<f64> = (0..252)
    ///     .map(|i| 10_000.0 + 100.0 * i as f64 + 2_000.0 * (0.3 * i as f64).sin())
    ///     .collect();
    ///
    /// let core = Core::new();
    /// let (mut s, _last) = core.pvt_open(&close, &volume).expect("enough history");
    /// let r0 = s.out_range();
    /// let peeked = s.peek(100.9, 12_345.0).expect("a finite bar");
    /// assert_eq!(s.out_range().count, r0.count); // a peek commits nothing
    /// let updated = s.update(100.9, 12_345.0).expect("a finite bar");
    /// assert_eq!(s.out_range().beg_idx, r0.beg_idx);
    /// assert_eq!(s.out_range().count, r0.count + 1);
    /// assert_eq!(peeked.to_bits(), updated.to_bits());
    /// ```
    #[doc(alias = "TA_PVT_Open")]
    pub fn pvt_open(&self, inClose: &[f64], inVolume: &[f64], ) -> Result<(PvtStream, f64), RetCode> {
        self.pvt_open_internal(inClose, inVolume, 0)
    }

    /// [`Core::pvt_open`] that also fills the output array(s) bit-identically to
    /// [`Core::PVT`] over `0..len` in the same single pass, and reports the range it
    /// wrote as the [`OutRange`] beside the handle.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] when an output slice holds fewer than `len - lookback`
    /// values — the batch tier's sizing rule, checked here as it is there (rule S5) —
    /// or when two of them are the same slice. Everything [`Core::pvt_open`] rejects
    /// is rejected here too.
    ///
    /// # Examples
    ///
    /// ```
    /// use ta_lib::Core;
    /// let close: Vec<f64> = (0..252)
    ///     .map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin() + 0.8 * (0.7 * i as f64).sin())
    ///     .collect();
    /// let volume: Vec<f64> = (0..252)
    ///     .map(|i| 10_000.0 + 100.0 * i as f64 + 2_000.0 * (0.3 * i as f64).sin())
    ///     .collect();
    ///
    /// let core = Core::new();
    /// let mut batch_out = vec![0.0; 252];
    /// let batch = core.PVT(0, close.len() - 1, &close, &volume, &mut batch_out)?;
    ///
    /// let mut out = vec![0.0; 252];
    /// let (_stream, filled) = core.pvt_open_and_fill(&close, &volume, &mut out)?;
    ///
    /// assert_eq!(filled.beg_idx, batch.beg_idx);
    /// assert_eq!(filled.count, batch.count);
    /// assert!(out[..filled.count].iter().zip(&batch_out[..batch.count])
    ///     .all(|(a, b)| a.to_bits() == b.to_bits()));
    /// # Ok::<(), ta_lib::RetCode>(())
    /// ```
    #[doc(alias = "TA_PVT_OpenAndFill")]
    pub fn pvt_open_and_fill(
        &self, inClose: &[f64], inVolume: &[f64], outReal: &mut [f64],
    ) -> Result<(PvtStream, OutRange), RetCode> {
        if inClose.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inClose.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        let _guardLb = self.PVT_Lookback()?;
        if inVolume.len() != inClose.len() {
            return Err(RetCode::BadParam);
        }
        let _guardOutLen = inClose.len().saturating_sub(_guardLb);
        if outReal.len() < _guardOutLen {
            return Err(RetCode::BadParam);
        }
        let mut outBegIdx: usize = 0;
        let mut outNBElement: usize = 0;
        let handle = self.pvt_open_and_fill_internal(inClose, inVolume, 0, &mut outBegIdx, &mut outNBElement, outReal)?;
        Ok((handle, OutRange { beg_idx: outBegIdx, count: outNBElement }))
    }

    /// [`Core::pvt_open_and_fill`] anchored at `startIdx` — the composed-open
    /// fusion seam (issue #192), not a public entry point.
    pub(crate) fn pvt_open_and_fill_internal(
        &self, inClose: &[f64], inVolume: &[f64], startIdx: usize, outBegIdx: &mut usize, outNBElement: &mut usize, outReal: &mut [f64],
    ) -> Result<PvtStream, RetCode> {
        self.pvt_open_impl(inClose, inVolume, startIdx, outBegIdx, outNBElement, outReal, 1)
    }

}

