/// Live PVT stream: one value per closed bar, bit-identical to [`Core::PVT`]
/// over the same series. Open with [`Core::pvt_open`]; dropping the handle
/// closes the stream. Cloning it forks an independent stream.
///
/// [`Self::out_range`] reports the bars this handle has an output for.
#[must_use = "a stream does nothing unless updated; dropping it closes the stream"]
#[derive(Debug, Clone)]
#[doc(alias = "TA_PVT_Stream")]
pub struct PvtStream {
    state: PvtStreamState,
    /// The bars this handle has an output for — see [`Self::out_range`].
    out: OutRange,
}

#[derive(Debug, Clone)]
#[allow(non_snake_case, dead_code)]
struct PvtStreamState {
    prevPVT: f64,
    prevClose: f64,
    cur_outReal: f64,
}

