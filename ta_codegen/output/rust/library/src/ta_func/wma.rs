    /// Linearly weighted moving average: each of the last N prices is weighted by its position,
    /// oldest getting weight 1 and newest weight N. Smooths price while emphasizing recent bars.
    ///
    /// # Formula
    ///
    /// ```text
    /// WMA = ( sum_{k=1..N} k * P_k ) / (N(N+1)/2), where P_N is the most recent bar
    /// ```
    ///
    /// # Notes
    ///
    /// * A period of 1 performs no smoothing: the output is a copy of the input. Allowed since
    ///   0.6.5 (issues #48/#59).
    ///
    /// # Arguments
    ///
    /// * `startIdx` — Start index of the requested calculation range.
    /// * `endIdx` — End index of the requested calculation range (inclusive).
    /// * `inReal` — Source price/data series.
    /// * `optInTimePeriod` — Number of bars in the weighting window (default 30, range
    ///   1..=100000)
    /// * `outBegIdx` — Set to the input index of the first output value.
    /// * `outNBElement` — Set to the number of output values written.
    /// * `outReal` — Weighted moving average series.
    ///
    /// Integer parameters accept `i32::MIN` to select their default value.
    ///
    /// # Errors
    ///
    /// Returns [`RetCode::OutOfRangeStartIndex`] when `startIdx` exceeds [`MAX_INDEX`],
    /// [`RetCode::OutOfRangeEndIndex`] when `endIdx` exceeds it or is below `startIdx`, and
    /// [`RetCode::BadParam`] when an optional parameter is outside its documented range.
    ///
    /// # Panics
    ///
    /// Input slices must cover `startIdx..=endIdx` and output slices must hold the number of values
    /// produced for that range; an undersized slice panics. Sizing every output slice to the input
    /// length is always sufficient.
    ///
    /// # Examples
    ///
    /// ```
    /// use ta_lib::{Core, RetCode};
    ///
    /// let data: Vec<f64> = (0..252).map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    ///
    /// let core = Core::new();
    /// let mut out_beg = 0;
    /// let mut out_nb = 0;
    /// let mut out = vec![0.0; 252];
    ///
    /// let ret = core.WMA(0, data.len() - 1, &data, 30, &mut out_beg, &mut out_nb, &mut out);
    /// assert_eq!(ret, RetCode::Success);
    /// assert!(out_nb > 0);
    /// assert!(out[..out_nb].iter().all(|v| v.is_finite()));
    /// ```
    ///
    /// # See also
    ///
    /// [`Core::SMA`] · [`Core::EMA`] · [`Core::MA`] · [`Core::DEMA`] · [`Core::TEMA`]
    ///
    /// Further reading: [ta-lib.org/functions/wma](https://ta-lib.org/functions/wma)
    #[doc(alias = "WeightedMovingAverage")]
    #[doc(alias = "LinearlyWeightedMovingAverage")]
    #[doc(alias = "LWMA")]
    pub fn WMA(
        &self,
        startIdx: usize,
        endIdx: usize,
        inReal: &[f64],
        mut optInTimePeriod: i32,
        outBegIdx: &mut usize,
        outNBElement: &mut usize,
        outReal: &mut [f64],
    ) -> RetCode {
        if startIdx > MAX_INDEX {
            return RetCode::OutOfRangeStartIndex;
        }
        if endIdx > MAX_INDEX || endIdx < startIdx {
            return RetCode::OutOfRangeEndIndex;
        }
        if ((optInTimePeriod) as i32) == (i32::MIN) {
            optInTimePeriod = 30;
        } else if (((optInTimePeriod) as i32) < 1) || (((optInTimePeriod) as i32) > 100000) {
            return RetCode::BadParam;
        }
        let _assertLb = self.WMA_Lookback(optInTimePeriod);
        let _assertStart = if startIdx > _assertLb { startIdx } else { _assertLb };
        assert!(_assertStart > endIdx || endIdx < inReal.len());
        assert!(_assertStart > endIdx || endIdx - _assertStart < outReal.len());
        let mut startIdx = startIdx;
        let mut inIdx: usize = 0_usize;
        let mut outIdx: usize = 0_usize;
        let mut i: usize = 0_usize;
        let mut trailingIdx: usize = 0_usize;
        let mut periodSum: f64 = 0.0_f64;
        let mut periodSub: f64 = 0.0_f64;
        let mut tempReal: f64 = 0.0_f64;
        let mut trailingValue: f64 = 0.0_f64;
        let mut divider: f64 = 0.0_f64;
        let mut lookbackTotal: usize = 0_usize;
        lookbackTotal = (optInTimePeriod - 1) as usize;
        // Move up the start index if there is not
        // enough initial data.
        if startIdx < lookbackTotal {
            startIdx = lookbackTotal;
        }
        // Make sure there is still something to evaluate.
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return RetCode::Success;
        }
        // To make the rest more efficient, handle exception
        // case where the user is asking for a period of '1'.
        // In that case outputs equals inputs for the requested
        // range.
        if optInTimePeriod == 1 {
            (*outBegIdx) = startIdx;
            (*outNBElement) = endIdx - startIdx + 1;
            // Element loop, not a block copy: the C single-precision variant reads a
            // float array, so a double-sized byte copy would reinterpret and
            // over-read it (#137). Forward order keeps the in-place case correct (#94).
            inIdx = startIdx;
            // for( i = 0; i < ((((*outNBElement) as usize)) as usize); i += 1 )
            i = 0;
            while i < ((((*outNBElement) as usize)) as usize) {
                outReal[i] = ((inReal[{ let _v = inIdx; inIdx += 1; _v }]) as f64);
                i += 1;
            }
            return RetCode::Success;
        }
        // Weighted denominator 1+2+...+n = n(n+1)/2. Computed in double: the
        // int product n*(n+1) overflows int32 at n>=46341 (#142).
        divider = (optInTimePeriod as f64) * (((optInTimePeriod + 1)) as f64) / 2.0;
        // The algo used here use a very basic property of
        // multiplication/addition: (x*2) = x+x
        //
        // As an example, a 3 period weighted can be
        // interpreted in two way:
        //  (x1*1)+(x2*2)+(x3*3)
        //      OR
        //  x1+x2+x2+x3+x3+x3 (this is the periodSum)
        //
        // When you move forward in the time serie
        // you can quickly adjust the periodSum for the
        // period by substracting:
        //   x1+x2+x3 (This is the periodSub)
        // Making the new periodSum equals to:
        //   x2+x3+x3
        //
        // You can then add the new price bar
        // which is x4+x4+x4 giving:
        //   x2+x3+x3+x4+x4+x4
        //
        // At this point one iteration is completed and you can
        // see that we are back to the step 1 of this example.
        //
        // Why making it so un-intuitive? The number of memory
        // access and floating point operations are kept to a
        // minimum with this algo.
        outIdx = 0;
        trailingIdx = startIdx - lookbackTotal;
        // Evaluate the initial periodSum/periodSub and trailingValue.
        periodSub = 0.0 as f64;
        periodSum = periodSub;
        inIdx = trailingIdx;
        i = 1;
        while inIdx < startIdx {
            tempReal = inReal[{ let _v = inIdx; inIdx += 1; _v }];
            periodSub += tempReal;
            periodSum += tempReal * ((i) as f64);
            i += 1;
        }
        trailingValue = 0.0;
        // Tight loop for the requested range.
        while inIdx <= endIdx {
            // Add the current price bar to the sum
            // who are carried through the iterations.
            tempReal = inReal[{ let _v = inIdx; inIdx += 1; _v }];
            periodSub += tempReal;
            periodSub -= trailingValue;
            periodSum += tempReal * ((optInTimePeriod) as f64);
            // Save the trailing value for being substract at
            // the next iteration.
            // (must be saved here just in case outReal and
            //  inReal are the same buffer).
            trailingValue = inReal[{ let _v = trailingIdx; trailingIdx += 1; _v }];
            // Calculate the WMA for this price bar.
            outReal[outIdx] = periodSum / divider;
            outIdx += 1;
            // Prepare the periodSum for the next iteration.
            periodSum -= periodSub;
        }
        // Set output limits.
        (*outNBElement) = outIdx;
        (*outBegIdx) = startIdx;
        return RetCode::Success;
    }
