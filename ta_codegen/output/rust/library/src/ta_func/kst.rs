        let mut prior: f64 = 0.0_f64;
        let mut roc: f64 = 0.0_f64;
        let mut kst: f64 = 0.0_f64;
        let mut sig: f64 = 0.0_f64;
        let mut rcma1: f64 = 0.0_f64;
        let mut rcma2: f64 = 0.0_f64;
        let mut rcma3: f64 = 0.0_f64;
        let mut rcma4: f64 = 0.0_f64;
        if sp.ringCap_den1 == 0 {
            sp.ring_den1_inReal[0] = inReal;
        }
        if sp.ringCap_den2 == 0 {
            sp.ring_den2_inReal[0] = inReal;
        }
        if sp.ringCap_den3 == 0 {
            sp.ring_den3_inReal[0] = inReal;
        }
        if sp.ringCap_den4 == 0 {
            sp.ring_den4_inReal[0] = inReal;
        }
        prior = sp.ring_den1_inReal[sp.ringPos_den1];
        roc = (if prior != 0.0 { (inReal / prior - 1.0) * 100.0 } else { 0.0 });
        sp.total1 += roc;
