    fn ssf_step_impl(sp: &mut SsfStreamState, inReal: f64, outReal: &mut f64) {
        let mut x0: f64 = 0.0_f64;
        let mut y: f64 = 0.0_f64;
        if sp.optInTimePeriod == 1 {
            *outReal = inReal;
            sp.cur_outReal = *outReal;
            return;
        }
        // c2*y1 stays the outermost term: y1 is the newest output, so that keeps
        // the bar rate at one fused step.
        x0 = inReal;
        y = fmadd!(sp.c2, sp.y1, fmadd!(sp.c3, sp.y2, sp.c1h * (x0 + sp.x1)));
        sp.x1 = x0;
        sp.y2 = sp.y1;
        sp.y1 = y;
        *outReal = y;
        sp.cur_outReal = *outReal;
    }

