impl Core {
    fn ht_trendline_step_impl(sp: &mut HtTrendlineStreamState, inReal: f64, outReal: &mut f64) {
        let mut i: usize = 0_usize;
        let mut tempReal: f64 = 0.0_f64;
        let mut tempReal2: f64 = 0.0_f64;
        let mut adjustedPrevPeriod: f64 = 0.0_f64;
        let mut smoothedValue: f64 = 0.0_f64;
        let mut hilbertTempReal: f64 = 0.0_f64;
        let mut detrender: f64 = 0.0_f64;
        let mut Q1: f64 = 0.0_f64;
        let mut jI: f64 = 0.0_f64;
        let mut jQ: f64 = 0.0_f64;
        let mut Q2: f64 = 0.0_f64;
        let mut I2: f64 = 0.0_f64;
        let mut todayValue: f64 = 0.0_f64;
        let mut DCPeriodInt: i32 = 0_i32;
        let mut DCPeriod: f64 = 0.0_f64;
        if sp.ringCap_trailingWMAIdx == 0 {
            sp.ring_trailingWMAIdx_inReal[0] = inReal;
        }
        sp.win_i_inReal[sp.winPos_i] = inReal;
        adjustedPrevPeriod = (0.075 as f64).mul_add(sp.period, 0.54);
        todayValue = inReal;
        sp.periodWMASub += todayValue;
        sp.periodWMASub -= sp.trailingWMAValue;
        sp.periodWMASum += todayValue * 4.0;
        sp.trailingWMAValue = sp.ring_trailingWMAIdx_inReal[sp.ringPos_trailingWMAIdx];
        smoothedValue = sp.periodWMASum * 0.1;
        sp.periodWMASum -= sp.periodWMASub;
        if sp.streamParity == 0 {
            // Do the Hilbert Transforms for even price bar
            hilbertTempReal = sp.a * smoothedValue;
            detrender = 0_f64 - sp.detrender_Even[sp.hilbertIdx];
            sp.detrender_Even[sp.hilbertIdx] = hilbertTempReal;
            detrender += hilbertTempReal;
            detrender -= sp.prev_detrender_Even;
            sp.prev_detrender_Even = sp.b * sp.prev_detrender_input_Even;
            detrender += sp.prev_detrender_Even;
            sp.prev_detrender_input_Even = smoothedValue;
            detrender *= adjustedPrevPeriod;
            hilbertTempReal = sp.a * detrender;
            Q1 = 0_f64 - sp.Q1_Even[sp.hilbertIdx];
            sp.Q1_Even[sp.hilbertIdx] = hilbertTempReal;
            Q1 += hilbertTempReal;
            Q1 -= sp.prev_Q1_Even;
            sp.prev_Q1_Even = sp.b * sp.prev_Q1_input_Even;
            Q1 += sp.prev_Q1_Even;
            sp.prev_Q1_input_Even = detrender;
            Q1 *= adjustedPrevPeriod;
            hilbertTempReal = sp.a * sp.I1ForEvenPrev3;
            jI = 0_f64 - sp.jI_Even[sp.hilbertIdx];
            sp.jI_Even[sp.hilbertIdx] = hilbertTempReal;
            jI += hilbertTempReal;
            jI -= sp.prev_jI_Even;
            sp.prev_jI_Even = sp.b * sp.prev_jI_input_Even;
            jI += sp.prev_jI_Even;
            sp.prev_jI_input_Even = sp.I1ForEvenPrev3;
            jI *= adjustedPrevPeriod;
            hilbertTempReal = sp.a * Q1;
            jQ = 0_f64 - sp.jQ_Even[sp.hilbertIdx];
            sp.jQ_Even[sp.hilbertIdx] = hilbertTempReal;
            jQ += hilbertTempReal;
            jQ -= sp.prev_jQ_Even;
            sp.prev_jQ_Even = sp.b * sp.prev_jQ_input_Even;
            jQ += sp.prev_jQ_Even;
            sp.prev_jQ_input_Even = Q1;
            jQ *= adjustedPrevPeriod;
            if { sp.hilbertIdx += 1; sp.hilbertIdx } == 3 {
                sp.hilbertIdx = 0;
            }
            Q2 = (0.2 as f64).mul_add(Q1 + jI, 0.8 * sp.prevQ2);
            I2 = (0.2 as f64).mul_add(sp.I1ForEvenPrev3 - jQ, 0.8 * sp.prevI2);
            // The variable I1 is the detrender delayed for
            // 3 price bars.
            //
            // Save the current detrender value for being
            // used by the "odd" logic later.
            sp.I1ForOddPrev3 = sp.I1ForOddPrev2;
            sp.I1ForOddPrev2 = detrender;
        } else {
            // Do the Hilbert Transforms for odd price bar
            hilbertTempReal = sp.a * smoothedValue;
            detrender = 0_f64 - sp.detrender_Odd[sp.hilbertIdx];
            sp.detrender_Odd[sp.hilbertIdx] = hilbertTempReal;
            detrender += hilbertTempReal;
            detrender -= sp.prev_detrender_Odd;
            sp.prev_detrender_Odd = sp.b * sp.prev_detrender_input_Odd;
            detrender += sp.prev_detrender_Odd;
            sp.prev_detrender_input_Odd = smoothedValue;
            detrender *= adjustedPrevPeriod;
            hilbertTempReal = sp.a * detrender;
            Q1 = 0_f64 - sp.Q1_Odd[sp.hilbertIdx];
            sp.Q1_Odd[sp.hilbertIdx] = hilbertTempReal;
            Q1 += hilbertTempReal;
            Q1 -= sp.prev_Q1_Odd;
            sp.prev_Q1_Odd = sp.b * sp.prev_Q1_input_Odd;
            Q1 += sp.prev_Q1_Odd;
            sp.prev_Q1_input_Odd = detrender;
            Q1 *= adjustedPrevPeriod;
            hilbertTempReal = sp.a * sp.I1ForOddPrev3;
            jI = 0_f64 - sp.jI_Odd[sp.hilbertIdx];
            sp.jI_Odd[sp.hilbertIdx] = hilbertTempReal;
            jI += hilbertTempReal;
            jI -= sp.prev_jI_Odd;
            sp.prev_jI_Odd = sp.b * sp.prev_jI_input_Odd;
            jI += sp.prev_jI_Odd;
            sp.prev_jI_input_Odd = sp.I1ForOddPrev3;
            jI *= adjustedPrevPeriod;
            hilbertTempReal = sp.a * Q1;
            jQ = 0_f64 - sp.jQ_Odd[sp.hilbertIdx];
            sp.jQ_Odd[sp.hilbertIdx] = hilbertTempReal;
            jQ += hilbertTempReal;
            jQ -= sp.prev_jQ_Odd;
            sp.prev_jQ_Odd = sp.b * sp.prev_jQ_input_Odd;
            jQ += sp.prev_jQ_Odd;
            sp.prev_jQ_input_Odd = Q1;
            jQ *= adjustedPrevPeriod;
            Q2 = (0.2 as f64).mul_add(Q1 + jI, 0.8 * sp.prevQ2);
            I2 = (0.2 as f64).mul_add(sp.I1ForOddPrev3 - jQ, 0.8 * sp.prevI2);
            // The varaiable I1 is the detrender delayed for
            // 3 price bars.
            //
            // Save the current detrender value for being
            // used by the "even" logic later.
            sp.I1ForEvenPrev3 = sp.I1ForEvenPrev2;
            sp.I1ForEvenPrev2 = detrender;
        }
        // Adjust the period for next price bar
        sp.Re = (0.8 as f64).mul_add(sp.Re, 0.2 * ((I2 as f64).mul_add(sp.prevI2, Q2 * sp.prevQ2)));
        sp.Im = (0.8 as f64).mul_add(sp.Im, 0.2 * (I2 * sp.prevQ2 - Q2 * sp.prevI2));
        sp.prevQ2 = Q2;
        sp.prevI2 = I2;
        tempReal = sp.period;
        if sp.Im != 0.0 && sp.Re != 0.0 {
            sp.period = 360.0 / ((sp.Im / sp.Re).atan() * sp.rad2Deg);
        }
        tempReal2 = 1.5 * tempReal;
        if sp.period > tempReal2 {
            sp.period = tempReal2;
        }
        tempReal2 = 0.67 * tempReal;
        if sp.period < tempReal2 {
            sp.period = tempReal2;
        }
        if sp.period < 6_f64 {
            sp.period = 6.0;
        } else if sp.period > 50_f64 {
            sp.period = 50.0;
        }
        sp.period = (0.2 as f64).mul_add(sp.period, 0.8 * tempReal);
        sp.smoothPeriod = (0.67 as f64).mul_add(sp.smoothPeriod, 0.33 * sp.period);
        // Compute Trendline
        DCPeriod = sp.smoothPeriod + 0.5;
        DCPeriodInt = (DCPeriod) as i32;
        // Average the RAW price over the dominant cycle period
        // (Ehlers, "Rocket Science for Traders": the Instantaneous
        // Trendline sums Price — not SmoothPrice, which only feeds
        // the Hilbert detrender above). See issue #88.
        // Sum the last DCPeriodInt (<= 50) raw prices. The fixed 50-iteration
        // loop with an inner guard is a streaming-friendly rewrite of the
        // data-dependent backward scan `for(i<DCPeriodInt) sum += inReal[idx--]`
        // (idx starting at today): identical terms in identical order, so
        // bit-for-bit unchanged, but the constant cap lets the rescan-window
        // machinery bound the window (DCPeriod is clamped to [6.5, 50.5]).
        tempReal = 0.0;
        // for( i = 0; i < 50; i += 1 )
        i = 0;
        while i < 50 {
            if ((i) as i32) < DCPeriodInt {
                tempReal += sp.win_i_inReal[((if sp.winPos_i + sp.winCap_i - i >= sp.winCap_i { sp.winPos_i + sp.winCap_i - i - sp.winCap_i } else { sp.winPos_i + sp.winCap_i - i })) as usize];
            }
            i += 1;
        }
        if DCPeriodInt > 0 {
            tempReal = tempReal / (DCPeriodInt as f64);
        }
        tempReal2 = ((2.0 as f64).mul_add(sp.iTrend2, (4.0 as f64).mul_add(tempReal, 3.0 * sp.iTrend1)) + sp.iTrend3) / 10.0;
        sp.iTrend3 = sp.iTrend2;
        sp.iTrend2 = sp.iTrend1;
        sp.iTrend1 = tempReal;
        (*outReal) = tempReal2;
        // Ooof... let's do the next price bar now!
        sp.cur_outReal = (*outReal);
        sp.ring_trailingWMAIdx_inReal[sp.ringPos_trailingWMAIdx] = inReal;
        sp.ringPos_trailingWMAIdx = sp.ringPos_trailingWMAIdx + 1;
        if sp.ringPos_trailingWMAIdx >= sp.ringCap_trailingWMAIdx {
            sp.ringPos_trailingWMAIdx = 0;
        }
        sp.winPos_i = sp.winPos_i + 1;
        if sp.winPos_i >= sp.winCap_i {
            sp.winPos_i = 0;
        }
        sp.streamParity = 1 - sp.streamParity;
    }

    /// The single whole-history transcription behind [`Core::ht_trendline_open_internal`]
    /// (stride 0, scalar sink) and [`Core::ht_trendline_open_and_fill`] (stride 1, caller slices).
    pub(crate) fn ht_trendline_open_impl(
        &self, inReal: &[f64], startIdx: usize, outBegIdx: &mut usize, outNBElement: &mut usize, outReal: &mut [f64], outStride: usize,
    ) -> Result<HtTrendlineStream, RetCode> {
        if inReal.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inReal.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        let historyLen: usize = inReal.len();
        let endIdx: usize = historyLen - 1;
        let mut startIdx = startIdx;
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut outIdx: usize = 0_usize;
        let mut i: usize = 0_usize;
        let mut lookbackTotal: usize = 0_usize;
        let mut today: usize = 0_usize;
        let mut tempReal: f64 = 0.0_f64;
        let mut tempReal2: f64 = 0.0_f64;
        let mut adjustedPrevPeriod: f64 = 0.0_f64;
        let mut period: f64 = 0.0_f64;
        let mut trailingWMAIdx: usize = 0_usize;
        let mut periodWMASum: f64 = 0.0_f64;
        let mut periodWMASub: f64 = 0.0_f64;
        let mut trailingWMAValue: f64 = 0.0_f64;
        let mut smoothedValue: f64 = 0.0_f64;
        let mut iTrend1: f64 = 0.0_f64;
        let mut iTrend2: f64 = 0.0_f64;
        let mut iTrend3: f64 = 0.0_f64;
        let mut a: f64 = 0.0_f64;
        let mut b: f64 = 0.0_f64;
        let mut hilbertTempReal: f64 = 0.0_f64;
        let mut hilbertIdx: usize = 0_usize;
        let mut detrender_Odd: [f64; 3 as usize] = [0.0_f64; 3 as usize];
        let mut detrender_Even: [f64; 3 as usize] = [0.0_f64; 3 as usize];
        let mut detrender: f64 = 0.0_f64;
        let mut prev_detrender_Odd: f64 = 0.0_f64;
        let mut prev_detrender_Even: f64 = 0.0_f64;
        let mut prev_detrender_input_Odd: f64 = 0.0_f64;
        let mut prev_detrender_input_Even: f64 = 0.0_f64;
        let mut Q1_Odd: [f64; 3 as usize] = [0.0_f64; 3 as usize];
        let mut Q1_Even: [f64; 3 as usize] = [0.0_f64; 3 as usize];
        let mut Q1: f64 = 0.0_f64;
        let mut prev_Q1_Odd: f64 = 0.0_f64;
        let mut prev_Q1_Even: f64 = 0.0_f64;
        let mut prev_Q1_input_Odd: f64 = 0.0_f64;
        let mut prev_Q1_input_Even: f64 = 0.0_f64;
        let mut jI_Odd: [f64; 3 as usize] = [0.0_f64; 3 as usize];
        let mut jI_Even: [f64; 3 as usize] = [0.0_f64; 3 as usize];
        let mut jI: f64 = 0.0_f64;
        let mut prev_jI_Odd: f64 = 0.0_f64;
        let mut prev_jI_Even: f64 = 0.0_f64;
        let mut prev_jI_input_Odd: f64 = 0.0_f64;
        let mut prev_jI_input_Even: f64 = 0.0_f64;
        let mut jQ_Odd: [f64; 3 as usize] = [0.0_f64; 3 as usize];
        let mut jQ_Even: [f64; 3 as usize] = [0.0_f64; 3 as usize];
        let mut jQ: f64 = 0.0_f64;
        let mut prev_jQ_Odd: f64 = 0.0_f64;
        let mut prev_jQ_Even: f64 = 0.0_f64;
        let mut prev_jQ_input_Odd: f64 = 0.0_f64;
        let mut prev_jQ_input_Even: f64 = 0.0_f64;
        let mut Q2: f64 = 0.0_f64;
        let mut I2: f64 = 0.0_f64;
        let mut prevQ2: f64 = 0.0_f64;
        let mut prevI2: f64 = 0.0_f64;
        let mut Re: f64 = 0.0_f64;
        let mut Im: f64 = 0.0_f64;
        let mut I1ForOddPrev2: f64 = 0.0_f64;
        let mut I1ForOddPrev3: f64 = 0.0_f64;
        let mut I1ForEvenPrev2: f64 = 0.0_f64;
        let mut I1ForEvenPrev3: f64 = 0.0_f64;
        let mut rad2Deg: f64 = 0.0_f64;
        let mut todayValue: f64 = 0.0_f64;
        let mut smoothPeriod: f64 = 0.0_f64;
        let mut DCPeriodInt: i32 = 0_i32;
        let mut DCPeriod: f64 = 0.0_f64;
        a = 0.0962;
        b = 0.5769;
        // Variable used for the price smoother (a weighted moving average).
        // Variable to keep track of the last 3 ITrend
        // Variables used for the Hilbert Transormation
        // Variable used to calculate the dominant cycle phase
        // circular buffer already declared
        iTrend3 = 0.0;
        iTrend2 = iTrend3;
        iTrend1 = iTrend2;
        // Constant
        tempReal = (1_f64).atan();
        rad2Deg = 45.0 / tempReal;
        // Identify the minimum number of price bar needed
        // to calculate at least one output.
        lookbackTotal = (63 + self.unstable_period[FuncUnstId::HT_TRENDLINE as usize]) as usize;
        // Move up the start index if there is not
        // enough initial data.
        if startIdx < lookbackTotal {
            startIdx = lookbackTotal;
        }
        // Make sure there is still something to evaluate.
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        (*outBegIdx) = startIdx;
        // Initialize the price smoother, which is simply a weighted
        // moving average of the price.
        // To understand this algorithm, I strongly suggest to understand
        // first how TA_WMA is done.
        trailingWMAIdx = startIdx - lookbackTotal;
        today = trailingWMAIdx;
        // Initialization is same as WMA, except loop is unrolled
        // for speed optimization.
        tempReal = inReal[{ let _v = today; today += 1; _v }];
        periodWMASub = tempReal;
        periodWMASum = tempReal;
        tempReal = inReal[{ let _v = today; today += 1; _v }];
        periodWMASub += tempReal;
        periodWMASum += tempReal * 2.0;
        tempReal = inReal[{ let _v = today; today += 1; _v }];
        periodWMASub += tempReal;
        periodWMASum += tempReal * 3.0;
        trailingWMAValue = 0.0;
        // Subsequent WMA value are evaluated by using
        // the DO_PRICE_WMA macro.
        i = 34;
        loop {
            tempReal = inReal[{ let _v = today; today += 1; _v }];
            periodWMASub += tempReal;
            periodWMASub -= trailingWMAValue;
            periodWMASum += tempReal * 4.0;
            trailingWMAValue = inReal[{ let _v = trailingWMAIdx; trailingWMAIdx += 1; _v }];
            smoothedValue = periodWMASum * 0.1;
            periodWMASum -= periodWMASub;
            if !({ i = i.wrapping_sub(1); i } != 0) { break; }
        }
        // Initialize the circular buffers used by the hilbert
        // transform logic.
        // A buffer is used for odd day and another for even days.
        // This minimize the number of memory access and floating point
        // operations needed (note also that by using static circular buffer,
        // no large dynamic memory allocation is needed for storing
        // intermediate calculation!).
        hilbertIdx = 0;
        detrender_Odd[0] = 0.0;
        detrender_Odd[1] = 0.0;
        detrender_Odd[2] = 0.0;
        detrender_Even[0] = 0.0;
        detrender_Even[1] = 0.0;
        detrender_Even[2] = 0.0;
        detrender = 0.0;
        prev_detrender_Odd = 0.0;
        prev_detrender_Even = 0.0;
        prev_detrender_input_Odd = 0.0;
        prev_detrender_input_Even = 0.0;
        Q1_Odd[0] = 0.0;
        Q1_Odd[1] = 0.0;
        Q1_Odd[2] = 0.0;
        Q1_Even[0] = 0.0;
        Q1_Even[1] = 0.0;
        Q1_Even[2] = 0.0;
        Q1 = 0.0;
        prev_Q1_Odd = 0.0;
        prev_Q1_Even = 0.0;
        prev_Q1_input_Odd = 0.0;
        prev_Q1_input_Even = 0.0;
        jI_Odd[0] = 0.0;
        jI_Odd[1] = 0.0;
        jI_Odd[2] = 0.0;
        jI_Even[0] = 0.0;
        jI_Even[1] = 0.0;
        jI_Even[2] = 0.0;
        jI = 0.0;
        prev_jI_Odd = 0.0;
        prev_jI_Even = 0.0;
        prev_jI_input_Odd = 0.0;
        prev_jI_input_Even = 0.0;
        jQ_Odd[0] = 0.0;
        jQ_Odd[1] = 0.0;
        jQ_Odd[2] = 0.0;
        jQ_Even[0] = 0.0;
        jQ_Even[1] = 0.0;
        jQ_Even[2] = 0.0;
        jQ = 0.0;
        prev_jQ_Odd = 0.0;
        prev_jQ_Even = 0.0;
        prev_jQ_input_Odd = 0.0;
        prev_jQ_input_Even = 0.0;
        period = 0.0;
        outIdx = 0;
        prevQ2 = 0.0;
        prevI2 = prevQ2;
        Im = 0.0;
        Re = Im;
        I1ForEvenPrev3 = 0.0;
        I1ForOddPrev3 = I1ForEvenPrev3;
        I1ForEvenPrev2 = 0.0;
        I1ForOddPrev2 = I1ForEvenPrev2;
        smoothPeriod = 0.0;
        // The code is speed optimized and is most likely very
        // hard to follow if you do not already know well the
        // original algorithm.
        // To understadn better, it is strongly suggested to look
        // first at the Excel implementation in "test_MAMA.xls" included
        // in this package.
        while today <= endIdx {
            adjustedPrevPeriod = (0.075 as f64).mul_add(period, 0.54);
            todayValue = inReal[today];
            periodWMASub += todayValue;
            periodWMASub -= trailingWMAValue;
            periodWMASum += todayValue * 4.0;
            trailingWMAValue = inReal[{ let _v = trailingWMAIdx; trailingWMAIdx += 1; _v }];
            smoothedValue = periodWMASum * 0.1;
            periodWMASum -= periodWMASub;
            if today % 2 == 0 {
                // Do the Hilbert Transforms for even price bar
                hilbertTempReal = a * smoothedValue;
                detrender = 0_f64 - detrender_Even[hilbertIdx];
                detrender_Even[hilbertIdx] = hilbertTempReal;
                detrender += hilbertTempReal;
                detrender -= prev_detrender_Even;
                prev_detrender_Even = b * prev_detrender_input_Even;
                detrender += prev_detrender_Even;
                prev_detrender_input_Even = smoothedValue;
                detrender *= adjustedPrevPeriod;
                hilbertTempReal = a * detrender;
                Q1 = 0_f64 - Q1_Even[hilbertIdx];
                Q1_Even[hilbertIdx] = hilbertTempReal;
                Q1 += hilbertTempReal;
                Q1 -= prev_Q1_Even;
                prev_Q1_Even = b * prev_Q1_input_Even;
                Q1 += prev_Q1_Even;
                prev_Q1_input_Even = detrender;
                Q1 *= adjustedPrevPeriod;
                hilbertTempReal = a * I1ForEvenPrev3;
                jI = 0_f64 - jI_Even[hilbertIdx];
                jI_Even[hilbertIdx] = hilbertTempReal;
                jI += hilbertTempReal;
                jI -= prev_jI_Even;
                prev_jI_Even = b * prev_jI_input_Even;
                jI += prev_jI_Even;
                prev_jI_input_Even = I1ForEvenPrev3;
                jI *= adjustedPrevPeriod;
                hilbertTempReal = a * Q1;
                jQ = 0_f64 - jQ_Even[hilbertIdx];
                jQ_Even[hilbertIdx] = hilbertTempReal;
                jQ += hilbertTempReal;
                jQ -= prev_jQ_Even;
                prev_jQ_Even = b * prev_jQ_input_Even;
                jQ += prev_jQ_Even;
                prev_jQ_input_Even = Q1;
                jQ *= adjustedPrevPeriod;
                if { hilbertIdx += 1; hilbertIdx } == 3 {
                    hilbertIdx = 0;
                }
                Q2 = (0.2 as f64).mul_add(Q1 + jI, 0.8 * prevQ2);
                I2 = (0.2 as f64).mul_add(I1ForEvenPrev3 - jQ, 0.8 * prevI2);
                // The variable I1 is the detrender delayed for
                // 3 price bars.
                //
                // Save the current detrender value for being
                // used by the "odd" logic later.
                I1ForOddPrev3 = I1ForOddPrev2;
                I1ForOddPrev2 = detrender;
            } else {
                // Do the Hilbert Transforms for odd price bar
                hilbertTempReal = a * smoothedValue;
                detrender = 0_f64 - detrender_Odd[hilbertIdx];
                detrender_Odd[hilbertIdx] = hilbertTempReal;
                detrender += hilbertTempReal;
                detrender -= prev_detrender_Odd;
                prev_detrender_Odd = b * prev_detrender_input_Odd;
                detrender += prev_detrender_Odd;
                prev_detrender_input_Odd = smoothedValue;
                detrender *= adjustedPrevPeriod;
                hilbertTempReal = a * detrender;
                Q1 = 0_f64 - Q1_Odd[hilbertIdx];
                Q1_Odd[hilbertIdx] = hilbertTempReal;
                Q1 += hilbertTempReal;
                Q1 -= prev_Q1_Odd;
                prev_Q1_Odd = b * prev_Q1_input_Odd;
                Q1 += prev_Q1_Odd;
                prev_Q1_input_Odd = detrender;
                Q1 *= adjustedPrevPeriod;
                hilbertTempReal = a * I1ForOddPrev3;
                jI = 0_f64 - jI_Odd[hilbertIdx];
                jI_Odd[hilbertIdx] = hilbertTempReal;
                jI += hilbertTempReal;
                jI -= prev_jI_Odd;
                prev_jI_Odd = b * prev_jI_input_Odd;
                jI += prev_jI_Odd;
                prev_jI_input_Odd = I1ForOddPrev3;
                jI *= adjustedPrevPeriod;
                hilbertTempReal = a * Q1;
                jQ = 0_f64 - jQ_Odd[hilbertIdx];
                jQ_Odd[hilbertIdx] = hilbertTempReal;
                jQ += hilbertTempReal;
                jQ -= prev_jQ_Odd;
                prev_jQ_Odd = b * prev_jQ_input_Odd;
                jQ += prev_jQ_Odd;
                prev_jQ_input_Odd = Q1;
                jQ *= adjustedPrevPeriod;
                Q2 = (0.2 as f64).mul_add(Q1 + jI, 0.8 * prevQ2);
                I2 = (0.2 as f64).mul_add(I1ForOddPrev3 - jQ, 0.8 * prevI2);
                // The varaiable I1 is the detrender delayed for
                // 3 price bars.
                //
                // Save the current detrender value for being
                // used by the "even" logic later.
                I1ForEvenPrev3 = I1ForEvenPrev2;
                I1ForEvenPrev2 = detrender;
            }
            // Adjust the period for next price bar
            Re = (0.8 as f64).mul_add(Re, 0.2 * ((I2 as f64).mul_add(prevI2, Q2 * prevQ2)));
            Im = (0.8 as f64).mul_add(Im, 0.2 * (I2 * prevQ2 - Q2 * prevI2));
            prevQ2 = Q2;
            prevI2 = I2;
            tempReal = period;
            if Im != 0.0 && Re != 0.0 {
                period = 360.0 / ((Im / Re).atan() * rad2Deg);
            }
            tempReal2 = 1.5 * tempReal;
            if period > tempReal2 {
                period = tempReal2;
            }
            tempReal2 = 0.67 * tempReal;
            if period < tempReal2 {
                period = tempReal2;
            }
            if period < 6_f64 {
                period = 6.0;
            } else if period > 50_f64 {
                period = 50.0;
            }
            period = (0.2 as f64).mul_add(period, 0.8 * tempReal);
            smoothPeriod = (0.67 as f64).mul_add(smoothPeriod, 0.33 * period);
            // Compute Trendline
            DCPeriod = smoothPeriod + 0.5;
            DCPeriodInt = (DCPeriod) as i32;
            // Average the RAW price over the dominant cycle period
            // (Ehlers, "Rocket Science for Traders": the Instantaneous
            // Trendline sums Price — not SmoothPrice, which only feeds
            // the Hilbert detrender above). See issue #88.
            // Sum the last DCPeriodInt (<= 50) raw prices. The fixed 50-iteration
            // loop with an inner guard is a streaming-friendly rewrite of the
            // data-dependent backward scan `for(i<DCPeriodInt) sum += inReal[idx--]`
            // (idx starting at today): identical terms in identical order, so
            // bit-for-bit unchanged, but the constant cap lets the rescan-window
            // machinery bound the window (DCPeriod is clamped to [6.5, 50.5]).
            tempReal = 0.0;
            // for( i = 0; i < 50; i += 1 )
            i = 0;
            while i < 50 {
                if ((i) as i32) < DCPeriodInt {
                    tempReal += inReal[today - i];
                }
                i += 1;
            }
            if DCPeriodInt > 0 {
                tempReal = tempReal / (DCPeriodInt as f64);
            }
            tempReal2 = ((2.0 as f64).mul_add(iTrend2, (4.0 as f64).mul_add(tempReal, 3.0 * iTrend1)) + iTrend3) / 10.0;
            iTrend3 = iTrend2;
            iTrend2 = iTrend1;
            iTrend1 = tempReal;
            if today >= startIdx {
                outReal[({ let _v = outIdx; outIdx += 1; _v } * outStride) as usize] = tempReal2;
            }
            // Ooof... let's do the next price bar now!
            today += 1;
        }
        (*outNBElement) = outIdx;

        // Capture the live batch state into the handle.
        let cap_trailingWMAIdx: i64 = (today as i64) - (trailingWMAIdx as i64);
        if cap_trailingWMAIdx < 0 || cap_trailingWMAIdx > historyLen as i64 {
            return Err(RetCode::InternalError);
        }
        let allocN_trailingWMAIdx: usize = if cap_trailingWMAIdx > 0 { cap_trailingWMAIdx as usize } else { 1 };
        let mut ring_trailingWMAIdx_inReal: Vec<f64> = vec![0.0_f64; allocN_trailingWMAIdx];
        ring_trailingWMAIdx_inReal[..cap_trailingWMAIdx as usize]
            .copy_from_slice(&inReal[historyLen - cap_trailingWMAIdx as usize..]);
        let cap_i: i64 = (50) as i64;
        if cap_i < 1 || cap_i > historyLen as i64 {
            return Err(RetCode::InternalError);
        }
        let mut win_i_inReal: Vec<f64> = vec![0.0_f64; cap_i as usize];
        win_i_inReal.copy_from_slice(&inReal[historyLen - cap_i as usize..]);
        let state = HtTrendlineStreamState {
            period,
            periodWMASum,
            periodWMASub,
            trailingWMAValue,
            iTrend1,
            iTrend2,
            iTrend3,
            a,
            b,
            hilbertIdx,
            detrender_Odd,
            detrender_Even,
            prev_detrender_Odd,
            prev_detrender_Even,
            prev_detrender_input_Odd,
            prev_detrender_input_Even,
            Q1_Odd,
            Q1_Even,
            prev_Q1_Odd,
            prev_Q1_Even,
            prev_Q1_input_Odd,
            prev_Q1_input_Even,
            jI_Odd,
            jI_Even,
            prev_jI_Odd,
            prev_jI_Even,
            prev_jI_input_Odd,
            prev_jI_input_Even,
            jQ_Odd,
            jQ_Even,
            prev_jQ_Odd,
            prev_jQ_Even,
            prev_jQ_input_Odd,
            prev_jQ_input_Even,
            prevQ2,
            prevI2,
            Re,
            Im,
            I1ForOddPrev2,
            I1ForOddPrev3,
            I1ForEvenPrev2,
            I1ForEvenPrev3,
            rad2Deg,
            smoothPeriod,
            streamParity: historyLen % 2,
            cur_outReal: outReal[(*outNBElement - 1) * outStride],
            ringPos_trailingWMAIdx: 0_usize,
            ringCap_trailingWMAIdx: cap_trailingWMAIdx as usize,
            ring_trailingWMAIdx_inReal,
            winPos_i: 0_usize,
            winCap_i: cap_i as usize,
            win_i_inReal,
        };
        Ok(HtTrendlineStream { state, out: OutRange { beg_idx: *outBegIdx, count: *outNBElement } })
    }

    /// Internal startIdx-anchored open behind [`Core::ht_trendline_open`] (composition seam).
    pub(crate) fn ht_trendline_open_internal(
        &self, inReal: &[f64], startIdx: usize,
    ) -> Result<(HtTrendlineStream, f64), RetCode> {
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut sink_outReal = [0.0_f64; 1];
        let handle = self.ht_trendline_open_impl(inReal, startIdx, &mut dummyBegIdx, &mut dummyNBElement, &mut sink_outReal, 0)?;
        Ok((handle, sink_outReal[0]))
    }

    /// Open a live HT_TRENDLINE stream over the warm-up history; returns the handle and
    /// the value at the last history bar — bit-identical to [`Core::HT_TRENDLINE`] at that bar.
    ///
    /// # Errors
    ///
    /// [`RetCode::InsufficientHistory`] when the history holds fewer than
    /// `lookback + 1` bars — the one failure here worth retrying, since another
    /// bar fixes it. [`RetCode::OutOfRangeStartIndex`] when the history is empty.
    /// [`RetCode::BadParam`] when a parameter is out of range or the input
    /// lengths differ.
    ///
    /// ```
    /// use ta_lib::Core;
    /// let data: Vec<f64> = (0..252).map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    ///
    /// let core = Core::new();
    /// let (mut s, _last) = core.ht_trendline_open(&data).expect("enough history");
    /// let r0 = s.out_range();
    /// let peeked = s.peek(100.9).expect("a finite bar");
    /// assert_eq!(s.out_range().count, r0.count); // a peek commits nothing
    /// let updated = s.update(100.9).expect("a finite bar");
    /// assert_eq!(s.out_range().beg_idx, r0.beg_idx);
    /// assert_eq!(s.out_range().count, r0.count + 1);
    /// assert_eq!(peeked.to_bits(), updated.to_bits());
    /// ```
    #[doc(alias = "TA_HT_TRENDLINE_Open")]
    pub fn ht_trendline_open(&self, inReal: &[f64], ) -> Result<(HtTrendlineStream, f64), RetCode> {
        self.ht_trendline_open_internal(inReal, 0)
    }

    /// [`Core::ht_trendline_open`] that also fills the output array(s) bit-identically to
    /// [`Core::HT_TRENDLINE`] over `0..len` in the same single pass, and reports the range it
    /// wrote as the [`OutRange`] beside the handle.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] when an output slice holds fewer than `len - lookback`
    /// values — the batch tier's sizing rule, checked here as it is there (rule S5) —
    /// or when two of them are the same slice. Everything [`Core::ht_trendline_open`] rejects
    /// is rejected here too.
    ///
    /// # Examples
    ///
    /// ```
    /// use ta_lib::Core;
    /// let data: Vec<f64> = (0..252).map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    ///
    /// let core = Core::new();
    /// let mut batch_out = vec![0.0; 252];
    /// let batch = core.HT_TRENDLINE(0, data.len() - 1, &data, &mut batch_out)?;
    ///
    /// let mut out = vec![0.0; 252];
    /// let (_stream, filled) = core.ht_trendline_open_and_fill(&data, &mut out)?;
    ///
    /// assert_eq!(filled.beg_idx, batch.beg_idx);
    /// assert_eq!(filled.count, batch.count);
    /// assert!(out[..filled.count].iter().zip(&batch_out[..batch.count])
    ///     .all(|(a, b)| a.to_bits() == b.to_bits()));
    /// # Ok::<(), ta_lib::RetCode>(())
    /// ```
    #[doc(alias = "TA_HT_TRENDLINE_OpenAndFill")]
    pub fn ht_trendline_open_and_fill(
        &self, inReal: &[f64], outReal: &mut [f64],
    ) -> Result<(HtTrendlineStream, OutRange), RetCode> {
        if inReal.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inReal.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        let _guardLb = self.HT_TRENDLINE_Lookback()?;
        let _guardOutLen = inReal.len().saturating_sub(_guardLb);
        if outReal.len() < _guardOutLen {
            return Err(RetCode::BadParam);
        }
        let mut outBegIdx: usize = 0;
        let mut outNBElement: usize = 0;
        let handle = self.ht_trendline_open_and_fill_internal(inReal, 0, &mut outBegIdx, &mut outNBElement, outReal)?;
        Ok((handle, OutRange { beg_idx: outBegIdx, count: outNBElement }))
    }

    /// [`Core::ht_trendline_open_and_fill`] anchored at `startIdx` — the composed-open
    /// fusion seam (issue #192), not a public entry point.
    pub(crate) fn ht_trendline_open_and_fill_internal(
        &self, inReal: &[f64], startIdx: usize, outBegIdx: &mut usize, outNBElement: &mut usize, outReal: &mut [f64],
    ) -> Result<HtTrendlineStream, RetCode> {
        self.ht_trendline_open_impl(inReal, startIdx, outBegIdx, outNBElement, outReal, 1)
    }

}

#[allow(non_snake_case)]
#[allow(unused_variables)]
#[allow(unused_mut)]
#[allow(unused_assignments)]
#[allow(unused_parens)]
impl HtTrendlineStream {
    /// Commit one closed bar. Never allocates.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite (NaN or ±Inf).
    /// That check runs before anything is written, so the handle's state is
    /// left exactly as it was and the stream stays usable: skip the bar, or
    /// close and re-open on a clean history. This is the one place the
    /// streaming tier is stricter than the batch API, which computes on
    /// whatever it is given — a handle retains its state, so a single
    /// non-finite bar would poison every later value it produces.
    ///
    /// A rejection leaves [`Self::out_range`] alone too. Re-feed the bar when
    /// a corrected value arrives, or call [`Self::advance`] to count it and
    /// carry on — two handles on one feed drift a bar apart if neither
    /// happens.
    #[doc(alias = "TA_HT_TRENDLINE_Update")]
    pub fn update(&mut self, inReal: f64) -> Result<f64, RetCode> {
        if !inReal.is_finite() {
            return Err(RetCode::BadParam);
        }
        let mut outReal: f64 = 0.0_f64;
        Core::ht_trendline_step_impl(&mut self.state, inReal, &mut outReal);
        if self.out.count < Core::MAX_INDEX {
            self.out.count += 1;
        }
        Ok(outReal)
    }

    /// Evaluate a forming bar without committing — bit-identical to what the
    /// next `update` with the same bar would return: the same transition,
    /// rewritten so every store it would make lives in a local instead. It
    /// allocates nothing and copies no buffer, so its cost does not grow with
    /// the period, and it writes no part of the handle — peeks may run
    /// concurrently with each other.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite, on the same test
    /// `update` applies, and a rejected peek changes nothing at all.
    #[doc(alias = "TA_HT_TRENDLINE_Peek")]
    pub fn peek(&self, inReal: f64) -> Result<f64, RetCode> {
        if !inReal.is_finite() {
            return Err(RetCode::BadParam);
        }
        let mut outReal: f64 = 0.0_f64;
        {
            let sp = &self.state;
            let outReal = &mut outReal;
            let mut i: usize = 0_usize;
            let mut tempReal: f64 = 0.0_f64;
            let mut tempReal2: f64 = 0.0_f64;
            let mut adjustedPrevPeriod: f64 = 0.0_f64;
            let mut smoothedValue: f64 = 0.0_f64;
            let mut hilbertTempReal: f64 = 0.0_f64;
            let mut detrender: f64 = 0.0_f64;
            let mut Q1: f64 = 0.0_f64;
            let mut jI: f64 = 0.0_f64;
            let mut jQ: f64 = 0.0_f64;
            let mut Q2: f64 = 0.0_f64;
            let mut I2: f64 = 0.0_f64;
            let mut todayValue: f64 = 0.0_f64;
            let mut DCPeriodInt: i32 = 0_i32;
            let mut DCPeriod: f64 = 0.0_f64;
            let mut I1ForEvenPrev2 = sp.I1ForEvenPrev2;
            let mut I1ForEvenPrev3 = sp.I1ForEvenPrev3;
            let mut I1ForOddPrev2 = sp.I1ForOddPrev2;
            let mut I1ForOddPrev3 = sp.I1ForOddPrev3;
            let mut Im = sp.Im;
            let mut Re = sp.Re;
            let mut hilbertIdx = sp.hilbertIdx;
            let mut iTrend1 = sp.iTrend1;
            let mut iTrend2 = sp.iTrend2;
            let mut iTrend3 = sp.iTrend3;
            let mut period = sp.period;
            let mut periodWMASub = sp.periodWMASub;
            let mut periodWMASum = sp.periodWMASum;
            let mut prevI2 = sp.prevI2;
            let mut prevQ2 = sp.prevQ2;
            let mut prev_Q1_Even = sp.prev_Q1_Even;
            let mut prev_Q1_Odd = sp.prev_Q1_Odd;
            let mut prev_Q1_input_Even = sp.prev_Q1_input_Even;
            let mut prev_Q1_input_Odd = sp.prev_Q1_input_Odd;
            let mut prev_detrender_Even = sp.prev_detrender_Even;
            let mut prev_detrender_Odd = sp.prev_detrender_Odd;
            let mut prev_detrender_input_Even = sp.prev_detrender_input_Even;
            let mut prev_detrender_input_Odd = sp.prev_detrender_input_Odd;
            let mut prev_jI_Even = sp.prev_jI_Even;
            let mut prev_jI_Odd = sp.prev_jI_Odd;
            let mut prev_jI_input_Even = sp.prev_jI_input_Even;
            let mut prev_jI_input_Odd = sp.prev_jI_input_Odd;
            let mut prev_jQ_Even = sp.prev_jQ_Even;
            let mut prev_jQ_Odd = sp.prev_jQ_Odd;
            let mut prev_jQ_input_Even = sp.prev_jQ_input_Even;
            let mut prev_jQ_input_Odd = sp.prev_jQ_input_Odd;
            let mut smoothPeriod = sp.smoothPeriod;
            let mut trailingWMAValue = sp.trailingWMAValue;
            let mut pkSlot0: usize = usize::MAX;
            let mut pkVal0: f64 = 0.0_f64;
            let mut pkSlot1: usize = usize::MAX;
            let mut pkVal1: f64 = 0.0_f64;
            if sp.ringCap_trailingWMAIdx == 0 {
                pkSlot0 = 0;
                pkVal0 = inReal;
            }
            pkSlot1 = sp.winPos_i as usize;
            pkVal1 = inReal;
            adjustedPrevPeriod = (0.075 as f64).mul_add(period, 0.54);
            todayValue = inReal;
            periodWMASub += todayValue;
            periodWMASub -= trailingWMAValue;
            periodWMASum += todayValue * 4.0;
            trailingWMAValue = (if (sp.ringPos_trailingWMAIdx as usize) != pkSlot0 { sp.ring_trailingWMAIdx_inReal[sp.ringPos_trailingWMAIdx] } else { pkVal0 });
            smoothedValue = periodWMASum * 0.1;
            periodWMASum -= periodWMASub;
            if sp.streamParity == 0 {
                // Do the Hilbert Transforms for even price bar
                hilbertTempReal = sp.a * smoothedValue;
                detrender = 0_f64 - sp.detrender_Even[hilbertIdx];
                detrender += hilbertTempReal;
                detrender -= prev_detrender_Even;
                prev_detrender_Even = sp.b * prev_detrender_input_Even;
                detrender += prev_detrender_Even;
                prev_detrender_input_Even = smoothedValue;
                detrender *= adjustedPrevPeriod;
                hilbertTempReal = sp.a * detrender;
                Q1 = 0_f64 - sp.Q1_Even[hilbertIdx];
                Q1 += hilbertTempReal;
                Q1 -= prev_Q1_Even;
                prev_Q1_Even = sp.b * prev_Q1_input_Even;
                Q1 += prev_Q1_Even;
                prev_Q1_input_Even = detrender;
                Q1 *= adjustedPrevPeriod;
                hilbertTempReal = sp.a * I1ForEvenPrev3;
                jI = 0_f64 - sp.jI_Even[hilbertIdx];
                jI += hilbertTempReal;
                jI -= prev_jI_Even;
                prev_jI_Even = sp.b * prev_jI_input_Even;
                jI += prev_jI_Even;
                prev_jI_input_Even = I1ForEvenPrev3;
                jI *= adjustedPrevPeriod;
                hilbertTempReal = sp.a * Q1;
                jQ = 0_f64 - sp.jQ_Even[hilbertIdx];
                jQ += hilbertTempReal;
                jQ -= prev_jQ_Even;
                prev_jQ_Even = sp.b * prev_jQ_input_Even;
                jQ += prev_jQ_Even;
                prev_jQ_input_Even = Q1;
                jQ *= adjustedPrevPeriod;
                if { hilbertIdx += 1; hilbertIdx } == 3 {
                    hilbertIdx = 0;
                }
                Q2 = (0.2 as f64).mul_add(Q1 + jI, 0.8 * prevQ2);
                I2 = (0.2 as f64).mul_add(I1ForEvenPrev3 - jQ, 0.8 * prevI2);
                // The variable I1 is the detrender delayed for
                // 3 price bars.
                //
                // Save the current detrender value for being
                // used by the "odd" logic later.
                I1ForOddPrev3 = I1ForOddPrev2;
                I1ForOddPrev2 = detrender;
            } else {
                // Do the Hilbert Transforms for odd price bar
                hilbertTempReal = sp.a * smoothedValue;
                detrender = 0_f64 - sp.detrender_Odd[hilbertIdx];
                detrender += hilbertTempReal;
                detrender -= prev_detrender_Odd;
                prev_detrender_Odd = sp.b * prev_detrender_input_Odd;
                detrender += prev_detrender_Odd;
                prev_detrender_input_Odd = smoothedValue;
                detrender *= adjustedPrevPeriod;
                hilbertTempReal = sp.a * detrender;
                Q1 = 0_f64 - sp.Q1_Odd[hilbertIdx];
                Q1 += hilbertTempReal;
                Q1 -= prev_Q1_Odd;
                prev_Q1_Odd = sp.b * prev_Q1_input_Odd;
                Q1 += prev_Q1_Odd;
                prev_Q1_input_Odd = detrender;
                Q1 *= adjustedPrevPeriod;
                hilbertTempReal = sp.a * I1ForOddPrev3;
                jI = 0_f64 - sp.jI_Odd[hilbertIdx];
                jI += hilbertTempReal;
                jI -= prev_jI_Odd;
                prev_jI_Odd = sp.b * prev_jI_input_Odd;
                jI += prev_jI_Odd;
                prev_jI_input_Odd = I1ForOddPrev3;
                jI *= adjustedPrevPeriod;
                hilbertTempReal = sp.a * Q1;
                jQ = 0_f64 - sp.jQ_Odd[hilbertIdx];
                jQ += hilbertTempReal;
                jQ -= prev_jQ_Odd;
                prev_jQ_Odd = sp.b * prev_jQ_input_Odd;
                jQ += prev_jQ_Odd;
                prev_jQ_input_Odd = Q1;
                jQ *= adjustedPrevPeriod;
                Q2 = (0.2 as f64).mul_add(Q1 + jI, 0.8 * prevQ2);
                I2 = (0.2 as f64).mul_add(I1ForOddPrev3 - jQ, 0.8 * prevI2);
                // The varaiable I1 is the detrender delayed for
                // 3 price bars.
                //
                // Save the current detrender value for being
                // used by the "even" logic later.
                I1ForEvenPrev3 = I1ForEvenPrev2;
                I1ForEvenPrev2 = detrender;
            }
            // Adjust the period for next price bar
            Re = (0.8 as f64).mul_add(Re, 0.2 * ((I2 as f64).mul_add(prevI2, Q2 * prevQ2)));
            Im = (0.8 as f64).mul_add(Im, 0.2 * (I2 * prevQ2 - Q2 * prevI2));
            prevQ2 = Q2;
            prevI2 = I2;
            tempReal = period;
            if Im != 0.0 && Re != 0.0 {
                period = 360.0 / ((Im / Re).atan() * sp.rad2Deg);
            }
            tempReal2 = 1.5 * tempReal;
            if period > tempReal2 {
                period = tempReal2;
            }
            tempReal2 = 0.67 * tempReal;
            if period < tempReal2 {
                period = tempReal2;
            }
            if period < 6_f64 {
                period = 6.0;
            } else if period > 50_f64 {
                period = 50.0;
            }
            period = (0.2 as f64).mul_add(period, 0.8 * tempReal);
            smoothPeriod = (0.67 as f64).mul_add(smoothPeriod, 0.33 * period);
            // Compute Trendline
            DCPeriod = smoothPeriod + 0.5;
            DCPeriodInt = (DCPeriod) as i32;
            // Average the RAW price over the dominant cycle period
            // (Ehlers, "Rocket Science for Traders": the Instantaneous
            // Trendline sums Price — not SmoothPrice, which only feeds
            // the Hilbert detrender above). See issue #88.
            // Sum the last DCPeriodInt (<= 50) raw prices. The fixed 50-iteration
            // loop with an inner guard is a streaming-friendly rewrite of the
            // data-dependent backward scan `for(i<DCPeriodInt) sum += inReal[idx--]`
            // (idx starting at today): identical terms in identical order, so
            // bit-for-bit unchanged, but the constant cap lets the rescan-window
            // machinery bound the window (DCPeriod is clamped to [6.5, 50.5]).
            tempReal = 0.0;
            // for( i = 0; i < 50; i += 1 )
            i = 0;
            while i < 50 {
                if ((i) as i32) < DCPeriodInt {
                    tempReal += (if ((if sp.winPos_i + sp.winCap_i - i >= sp.winCap_i { sp.winPos_i + sp.winCap_i - i - sp.winCap_i } else { sp.winPos_i + sp.winCap_i - i }) as usize) != pkSlot1 { sp.win_i_inReal[((if sp.winPos_i + sp.winCap_i - i >= sp.winCap_i { sp.winPos_i + sp.winCap_i - i - sp.winCap_i } else { sp.winPos_i + sp.winCap_i - i })) as usize] } else { pkVal1 });
                }
                i += 1;
            }
            if DCPeriodInt > 0 {
                tempReal = tempReal / (DCPeriodInt as f64);
            }
            tempReal2 = ((2.0 as f64).mul_add(iTrend2, (4.0 as f64).mul_add(tempReal, 3.0 * iTrend1)) + iTrend3) / 10.0;
            iTrend3 = iTrend2;
            iTrend2 = iTrend1;
            iTrend1 = tempReal;
            (*outReal) = tempReal2;
        }
        Ok(outReal)
    }

    /// The value(s) at the last bar the stream counted — the bar
    /// [`Self::out_range`] ends on — without recomputing. Seeded by the opener,
    /// refreshed by every accepted `update`, and left
    /// alone by `peek`.
    ///
    /// A clone carries them verbatim, so a forked handle can be asked its
    /// current value without committing a bar to find out.
    #[must_use]
    #[doc(alias = "TA_HT_TRENDLINE_Value")]
    pub fn value(&self) -> f64 {
        self.state.cur_outReal
    }

    /// The bars this stream has an output for, in the input series'
    /// coordinates: `[beg_idx, beg_idx + count)`.
    ///
    /// It is what [`Core::HT_TRENDLINE`] reports over the same bars: the opener sets it
    /// to `(lookback, historyLen - lookback)`, every accepted `update` adds
    /// one to the count — a rejected one changes nothing, and neither does
    /// `peek` — and a clone carries it verbatim. A plain `Open` hands back
    /// only the last value, a subset of this range, because the caller chose
    /// not to take the fill.
    #[doc(alias = "TA_HT_TRENDLINE_OutRange")]
    pub fn out_range(&self) -> OutRange {
        self.out
    }

    /// Count one bar this stream was not fed: [`Self::out_range`] advances by
    /// one and nothing else moves — [`Self::value`] keeps answering the
    /// previous output, which is this bar's output too.
    ///
    /// For a bar the caller leaves out: one an `update` rejected and that
    /// will not be re-fed, or a session with no print. Without it two handles
    /// on one feed drift a bar apart when only one of them skips.
    #[doc(alias = "TA_HT_TRENDLINE_Advance")]
    pub fn advance(&mut self) {
        if self.out.count < Core::MAX_INDEX {
            self.out.count += 1;
        }
    }
}

