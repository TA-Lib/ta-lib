        let mut mid: f64 = 0.0_f64;
        let mut range: f64 = 0.0_f64;
        let mut boxRatio: f64 = 0.0_f64;
        let mut raw: f64 = 0.0_f64;
        let mut tempReal: f64 = 0.0_f64;
