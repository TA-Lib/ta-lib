    /// assert_eq!(s.out_range().beg_idx, r0.beg_idx);
    /// assert_eq!(s.out_range().count, r0.count + 1);
    /// assert_eq!(peeked.to_bits(), updated.to_bits());
    /// ```
    #[doc(alias = "TA_IBS_Open")]
    pub fn ibs_open(&self, inHigh: &[f64], inLow: &[f64], inClose: &[f64], ) -> Result<(IbsStream, f64), RetCode> {
        self.ibs_open_internal(inHigh, inLow, inClose, 0)
    }

