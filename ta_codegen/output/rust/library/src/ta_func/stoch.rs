impl Core {
    fn stoch_step_impl(sp: &mut StochStreamState, inHigh: f64, inLow: f64, inClose: f64, outSlowK: &mut f64, outSlowD: &mut f64) -> Result<(), RetCode> {
        let mut tmp: f64 = 0.0_f64;
        let mut cur_tempBuffer: f64 = 0.0_f64;
        let mut cur_outSlowD: f64 = 0.0_f64;
        if sp.today >= 1073741824 {
            let rebaseShift: i32 = sp.trailingIdx & !sp.xMask;
            sp.today -= rebaseShift;
            sp.trailingIdx -= rebaseShift;
            sp.highestIdx -= rebaseShift;
            sp.i -= rebaseShift;
            sp.lowestIdx -= rebaseShift;
        }
        sp.x_inHigh[(sp.today & sp.xMask) as usize] = inHigh;
        sp.x_inLow[(sp.today & sp.xMask) as usize] = inLow;
        sp.x_inClose[(sp.today & sp.xMask) as usize] = inClose;
        // Set the lowest low
        tmp = sp.x_inLow[(sp.today & sp.xMask) as usize];
        if sp.lowestIdx < sp.trailingIdx {
            sp.lowestIdx = sp.trailingIdx;
            sp.lowest = sp.x_inLow[(sp.lowestIdx & sp.xMask) as usize];
            sp.i = sp.lowestIdx;
            while (({ sp.i += 1; sp.i }) as i32) <= sp.today {
                tmp = sp.x_inLow[(sp.i & sp.xMask) as usize];
                if tmp < sp.lowest {
                    sp.lowestIdx = sp.i;
                    sp.lowest = tmp;
                }
            }
            sp.diff = (sp.highest - sp.lowest) / 100.0;
        } else if tmp <= sp.lowest {
            sp.lowestIdx = sp.today;
            sp.lowest = tmp;
            sp.diff = (sp.highest - sp.lowest) / 100.0;
        }
        // Set the highest high
        tmp = sp.x_inHigh[(sp.today & sp.xMask) as usize];
        if sp.highestIdx < sp.trailingIdx {
            sp.highestIdx = sp.trailingIdx;
            sp.highest = sp.x_inHigh[(sp.highestIdx & sp.xMask) as usize];
            sp.i = sp.highestIdx;
            while (({ sp.i += 1; sp.i }) as i32) <= sp.today {
                tmp = sp.x_inHigh[(sp.i & sp.xMask) as usize];
                if tmp > sp.highest {
                    sp.highestIdx = sp.i;
                    sp.highest = tmp;
                }
            }
            sp.diff = (sp.highest - sp.lowest) / 100.0;
        } else if tmp >= sp.highest {
            sp.highestIdx = sp.today;
            sp.highest = tmp;
            sp.diff = (sp.highest - sp.lowest) / 100.0;
        }
        // Calculate stochastic. The guard is not an exact `diff != 0.0`: a
        // machine-flat window leaves a sub-epsilon residue that an exact check
        // would divide into [0,100] noise (issue #107 / STOCHRSI). It is the
        // range against ITS OWN two extremes, not against a fixed band: the range
        // carries the quote unit, so a constant put against it answers "flat" for
        // every window of an instrument quoted below it and zeroed the whole
        // output (issue #253).
        if !(((sp.highest - sp.lowest).abs() <= 1e-14 * ((sp.highest).abs() + (sp.lowest).abs()))) {
            cur_tempBuffer = (sp.x_inClose[(sp.today & sp.xMask) as usize] - sp.lowest) / sp.diff;
        } else {
            cur_tempBuffer = 0.0;
        }
        sp.trailingIdx += 1;
        sp.today += 1;

        // Pipeline the new bar through the sub-streams (batch tail order).
        cur_tempBuffer = sp.sub0.update(cur_tempBuffer)?;
        cur_outSlowD = sp.sub1.update(cur_tempBuffer)?;
        (*outSlowK) = cur_tempBuffer;
        (*outSlowD) = cur_outSlowD;
        Ok(())
    }

    /// The single whole-history transcription behind [`Core::stoch_open_internal`]
    /// (stride 0, scalar sink) and [`Core::stoch_open_and_fill`] (stride 1, caller slices).
    pub(crate) fn stoch_open_impl(
        &self, inHigh: &[f64], inLow: &[f64], inClose: &[f64], startIdx: usize, mut optInFastK_Period: i32, mut optInSlowK_Period: i32, mut optInSlowK_MAType: MAType, mut optInSlowD_Period: i32, mut optInSlowD_MAType: MAType, outBegIdx: &mut usize, outNBElement: &mut usize, outSlowK: &mut [f64], outSlowD: &mut [f64], outStride: usize,
    ) -> Result<StochStream, RetCode> {
        if inHigh.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inHigh.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        if ((optInFastK_Period) as i32) == (i32::MIN) {
            optInFastK_Period = 5;
        } else if (((optInFastK_Period) as i32) < 1) || (((optInFastK_Period) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        if ((optInSlowK_Period) as i32) == (i32::MIN) {
            optInSlowK_Period = 3;
        } else if (((optInSlowK_Period) as i32) < 1) || (((optInSlowK_Period) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        if optInSlowK_MAType == MAType::DEFAULT {
            optInSlowK_MAType = MAType::SMA;
        }
        if ((optInSlowD_Period) as i32) == (i32::MIN) {
            optInSlowD_Period = 3;
        } else if (((optInSlowD_Period) as i32) < 1) || (((optInSlowD_Period) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        if optInSlowD_MAType == MAType::DEFAULT {
            optInSlowD_MAType = MAType::SMA;
        }
        if inLow.len() != inHigh.len() || inClose.len() != inHigh.len() {
            return Err(RetCode::BadParam);
        }
        let historyLen: usize = inHigh.len();
        let endIdx: usize = historyLen - 1;
        let mut startIdx = startIdx;
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut owned_sc_outSlowK: Vec<f64> =
            if outStride == 1 { Vec::new() } else { vec![0.0_f64; historyLen] };
        let sc_outSlowK: &mut [f64] =
            if outStride == 1 { &mut *outSlowK } else { &mut owned_sc_outSlowK };
        let mut owned_sc_outSlowD: Vec<f64> =
            if outStride == 1 { Vec::new() } else { vec![0.0_f64; historyLen] };
        let sc_outSlowD: &mut [f64] =
            if outStride == 1 { &mut *outSlowD } else { &mut owned_sc_outSlowD };
        let mut retCode: RetCode = RetCode::Success;
        let mut lowest: f64 = 0.0_f64;
        let mut highest: f64 = 0.0_f64;
        let mut tmp: f64 = 0.0_f64;
        let mut diff: f64 = 0.0_f64;
        let mut tempBuffer: Vec<f64> = Vec::new();
        let mut outIdx: usize = 0_usize;
        let mut lowestIdx: i32 = 0_i32;
        let mut highestIdx: i32 = 0_i32;
        let mut lookbackTotal: usize = 0_usize;
        let mut lookbackK: usize = 0_usize;
        let mut lookbackKSlow: usize = 0_usize;
        let mut lookbackDSlow: usize = 0_usize;
        let mut trailingIdx: usize = 0_usize;
        let mut today: usize = 0_usize;
        let mut i: usize = 0_usize;
        let mut bufferIsAllocated: usize = 0_usize;
        // With stochastic, there is a total of 4 different lines that
        // are defined: FASTK, FASTD, SLOWK and SLOWD.
        //
        // The D is the signal line usually drawn over its
        // corresponding K function.
        //
        //                    (Today's Close - LowestLow)
        //  FASTK(Kperiod) =  --------------------------- * 100
        //                     (HighestHigh - LowestLow)
        //
        //  FASTD(FastDperiod, MA type) = MA Smoothed FASTK over FastDperiod
        //
        //  SLOWK(SlowKperiod, MA type) = MA Smoothed FASTK over SlowKperiod
        //
        //  SLOWD(SlowDperiod, MA Type) = MA Smoothed SLOWK over SlowDperiod
        //
        // The HighestHigh and LowestLow are the extreme values among the
        // last 'Kperiod'.
        //
        // SLOWK and FASTD are equivalent when using the same period.
        //
        // The following shows how these four lines are made available in TA-LIB:
        //
        //  TA_STOCH  : Returns the SLOWK and SLOWD
        //  TA_STOCHF : Returns the FASTK and FASTD
        //
        // The TA_STOCH function correspond to the more widely implemented version
        // found in many software/charting package. The TA_STOCHF is more rarely
        // used because its higher volatility cause often whipsaws.
        // Identify the lookback needed.
        lookbackK = (optInFastK_Period - 1) as usize;
        lookbackKSlow = self.MA_Lookback(optInSlowK_Period, optInSlowK_MAType)?;
        lookbackDSlow = self.MA_Lookback(optInSlowD_Period, optInSlowD_MAType)?;
        lookbackTotal = lookbackK + lookbackDSlow + lookbackKSlow;
        // Move up the start index if there is not
        // enough initial data.
        if startIdx < lookbackTotal {
            startIdx = lookbackTotal;
        }
        // Make sure there is still something to evaluate.
        if startIdx > endIdx {
            // Succeed... but no data in the output.
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        // Do the K calculation:
        //
        //    Kt = 100 x ((Ct-Lt)/(Ht-Lt))
        //
        // Kt is today stochastic
        // Ct is today closing price.
        // Lt is the lowest price of the last K Period (including today)
        // Ht is the highest price of the last K Period (including today)
        // Proceed with the calculation for the requested range.
        // Note that this algorithm allows the input and
        // output to be the same buffer.
        outIdx = 0;
        // Calculate just enough K for ending up with the caller
        // requested range. (The range of k must consider all
        // the lookback involve with the smoothing).
        trailingIdx = startIdx - lookbackTotal;
        today = trailingIdx + lookbackK;
        highestIdx = 0 - 1;
        lowestIdx = highestIdx;
        lowest = 0.0;
        highest = lowest;
        diff = highest;
        // Allocate a temporary buffer large enough to
        // store the K.
        //
        // When outSlowK aliases a price input the caller buffer doubles as the
        // scratch, saving one allocation: the K writes trail the min/max window
        // reads, and the final memmove is overlap-safe. outSlowD must NOT be
        // elected: the %D ma() below would then run in place over the smoothed K
        // that the memmove into outSlowK still needs (issue #130).
        bufferIsAllocated = 0;
        if sc_outSlowK.as_ptr() == inHigh.as_ptr() || sc_outSlowK.as_ptr() == inLow.as_ptr() || sc_outSlowK.as_ptr() == inClose.as_ptr() {
            tempBuffer = sc_outSlowK.to_vec();
        } else {
            bufferIsAllocated = 1;
            tempBuffer = vec![0.0_f64; ((endIdx - today + 1) * 1) as usize];
        }
        // Do the K calculation
        while today <= endIdx {
            // Set the lowest low
            tmp = inLow[today];
            if lowestIdx < ((trailingIdx) as i32) {
                lowestIdx = (trailingIdx) as i32;
                lowest = inLow[(lowestIdx) as usize];
                i = (lowestIdx) as usize;
                while { i += 1; i } <= today {
                    tmp = inLow[i];
                    if tmp < lowest {
                        lowestIdx = (i) as i32;
                        lowest = tmp;
                    }
                }
                diff = (highest - lowest) / 100.0;
            } else if tmp <= lowest {
                lowestIdx = (today) as i32;
                lowest = tmp;
                diff = (highest - lowest) / 100.0;
            }
            // Set the highest high
            tmp = inHigh[today];
            if highestIdx < ((trailingIdx) as i32) {
                highestIdx = (trailingIdx) as i32;
                highest = inHigh[(highestIdx) as usize];
                i = (highestIdx) as usize;
                while { i += 1; i } <= today {
                    tmp = inHigh[i];
                    if tmp > highest {
                        highestIdx = (i) as i32;
                        highest = tmp;
                    }
                }
                diff = (highest - lowest) / 100.0;
            } else if tmp >= highest {
                highestIdx = (today) as i32;
                highest = tmp;
                diff = (highest - lowest) / 100.0;
            }
            // Calculate stochastic. The guard is not an exact `diff != 0.0`: a
            // machine-flat window leaves a sub-epsilon residue that an exact check
            // would divide into [0,100] noise (issue #107 / STOCHRSI). It is the
            // range against ITS OWN two extremes, not against a fixed band: the range
            // carries the quote unit, so a constant put against it answers "flat" for
            // every window of an instrument quoted below it and zeroed the whole
            // output (issue #253).
            if !(((highest - lowest).abs() <= 1e-14 * ((highest).abs() + (lowest).abs()))) {
                tempBuffer[outIdx] = (inClose[today] - lowest) / diff;
                outIdx += 1;
            } else {
                tempBuffer[outIdx] = 0.0;
                outIdx += 1;
            }
            trailingIdx += 1;
            today += 1;
        }
        // Un-smoothed K calculation completed. This K calculation is not returned
        // to the caller. It is always smoothed and then return.
        // Some documentation will refer to the smoothed version as being
        // "K-Slow", but often this end up to be shorten to "K".
        // Sub-stream 0: ma over `tempBuffer`, warmed from bar 0 up to the
        // sub-call's own startIdx (the seeding point).
        let (sub0, _) = self.ma_open_internal(&tempBuffer[..((outIdx - 1) as usize) + 1], ((0) as usize), optInSlowK_Period, optInSlowK_MAType)?;
        let _xr0 = match ({ let mut _tempBuffer_alias: Vec<f64> = vec![0.0_f64; tempBuffer.len()]; let _rc = self.MA(0, outIdx - 1, &tempBuffer, optInSlowK_Period, optInSlowK_MAType, &mut _tempBuffer_alias[..]); std::mem::swap(&mut tempBuffer, &mut _tempBuffer_alias); _rc }) { Ok(_r) => _r, Err(_e) => return Err(_e) };
        (*outBegIdx) = _xr0.beg_idx;
        (*outNBElement) = _xr0.count;
        retCode = RetCode::Success;
        if ((*outNBElement) as usize) == 0 {
            // Something wrong happen? No further data?
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        // Calculate the %D which is simply a moving average of
        // the already smoothed %K.
        // Sub-stream 1: ma over `tempBuffer`, warmed from bar 0 up to the
        // sub-call's own startIdx (the seeding point).
        let sub1 = self.ma_open_and_fill_internal(&tempBuffer[..((((*outNBElement) as usize) - 1) as usize) + 1], ((0) as usize), optInSlowD_Period, optInSlowD_MAType, outBegIdx, outNBElement, &mut sc_outSlowD[..])?;
        retCode = RetCode::Success;
        // Copy tempBuffer into the caller buffer.
        // (Calculation could not be done directly in the
        //  caller buffer because more input data then the
        //  requested range was needed for doing %D).
        // memmove, not memcpy: tempBuffer aliases outSlowK when the caller buffer is
        // reused as scratch, so source and destination overlap (issue #94).
        {
            let _n = (((((*outNBElement) as usize)) as usize) * 1) as usize;
            let _di = (0) as usize;
            let _si = (lookbackDSlow) as usize;
            sc_outSlowK[_di.._di + _n].copy_from_slice(&tempBuffer[_si.._si + _n]);
        };
        // Note: Keep the outBegIdx relative to the
        //       caller input before returning.
        (*outBegIdx) = startIdx;

        // Capture the live producer state + sub handles.
        if *outNBElement < 1 {
            return Err(RetCode::InsufficientHistory);
        }
        let capX: i64 = (today as i64) - (trailingIdx as i64) + 1;
        if capX < 1 || capX > historyLen as i64 {
            return Err(RetCode::InternalError);
        }
        let mut physX: i64 = 1;
        while physX < capX {
            physX <<= 1;
        }
        let mut x_inHigh: Vec<f64> = vec![0.0_f64; physX as usize];
        let mut x_inLow: Vec<f64> = vec![0.0_f64; physX as usize];
        let mut x_inClose: Vec<f64> = vec![0.0_f64; physX as usize];
        {
            let mut fillJ: usize = historyLen - capX as usize;
            while fillJ < historyLen {
                x_inHigh[fillJ & (physX as usize - 1)] = inHigh[fillJ];
                x_inLow[fillJ & (physX as usize - 1)] = inLow[fillJ];
                x_inClose[fillJ & (physX as usize - 1)] = inClose[fillJ];
                fillJ += 1;
            }
        }
        let state = StochStreamState {
            optInFastK_Period,
            optInSlowK_Period,
            optInSlowK_MAType,
            optInSlowD_Period,
            optInSlowD_MAType,
            lowest,
            highest,
            diff,
            lowestIdx: (lowestIdx) as i32,
            highestIdx: (highestIdx) as i32,
            trailingIdx: (trailingIdx) as i32,
            i: (i) as i32,
            today: (today) as i32,
            xMask: (physX - 1) as i32,
            x_inHigh,
            x_inLow,
            x_inClose,
            sub0,
            sub1,
        };
        if outStride != 1 && *outNBElement > 0 {
            let last_sc_outSlowK = sc_outSlowK[*outNBElement - 1];
            outSlowK[0] = last_sc_outSlowK;
        }
        if outStride != 1 && *outNBElement > 0 {
            let last_sc_outSlowD = sc_outSlowD[*outNBElement - 1];
            outSlowD[0] = last_sc_outSlowD;
        }
        Ok(StochStream { state, out: OutRange { beg_idx: *outBegIdx, count: *outNBElement } })
    }

    /// Internal startIdx-anchored open behind [`Core::stoch_open`] (composition seam).
    pub(crate) fn stoch_open_internal(
        &self, inHigh: &[f64], inLow: &[f64], inClose: &[f64], startIdx: usize, mut optInFastK_Period: i32, mut optInSlowK_Period: i32, mut optInSlowK_MAType: MAType, mut optInSlowD_Period: i32, mut optInSlowD_MAType: MAType,
    ) -> Result<(StochStream, (f64, f64)), RetCode> {
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut sink_outSlowK = [0.0_f64; 1];
        let mut sink_outSlowD = [0.0_f64; 1];
        let handle = self.stoch_open_impl(inHigh, inLow, inClose, startIdx, optInFastK_Period, optInSlowK_Period, optInSlowK_MAType, optInSlowD_Period, optInSlowD_MAType, &mut dummyBegIdx, &mut dummyNBElement, &mut sink_outSlowK, &mut sink_outSlowD, 0)?;
        Ok((handle, (sink_outSlowK[0], sink_outSlowD[0])))
    }

    /// Open a live STOCH stream over the warm-up history; returns the handle and
    /// the value at the last history bar — bit-identical to [`Core::STOCH`] at that bar.
    ///
    /// # Errors
    ///
    /// [`RetCode::InsufficientHistory`] when the history holds fewer than
    /// `lookback + 1` bars — the one failure here worth retrying, since another
    /// bar fixes it. [`RetCode::OutOfRangeStartIndex`] when the history is empty.
    /// [`RetCode::BadParam`] when a parameter is out of range or the input
    /// lengths differ.
    ///
    /// ```
    /// use ta_lib::{Core, MAType};
    /// let high: Vec<f64> = (0..252).map(|i| 101.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    /// let low: Vec<f64> = (0..252).map(|i| 99.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    /// let close: Vec<f64> = (0..252)
    ///     .map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin() + 0.8 * (0.7 * i as f64).sin())
    ///     .collect();
    ///
    /// let core = Core::new();
    /// let (mut s, _last) = core.stoch_open(&high, &low, &close, 5, 3, MAType::SMA, 3, MAType::SMA).expect("enough history");
    /// let r0 = s.out_range();
    /// let peeked = s.peek(101.4, 99.1, 100.9).expect("a finite bar");
    /// assert_eq!(s.out_range().count, r0.count); // a peek commits nothing
    /// let updated = s.update(101.4, 99.1, 100.9).expect("a finite bar");
    /// assert_eq!(s.out_range().beg_idx, r0.beg_idx);
    /// assert_eq!(s.out_range().count, r0.count + 1);
    /// assert_eq!(peeked.0.to_bits(), updated.0.to_bits());
    /// assert_eq!(peeked.1.to_bits(), updated.1.to_bits());
    /// ```
    #[doc(alias = "TA_STOCH_Open")]
    pub fn stoch_open(&self, inHigh: &[f64], inLow: &[f64], inClose: &[f64], optInFastK_Period: i32, optInSlowK_Period: i32, optInSlowK_MAType: MAType, optInSlowD_Period: i32, optInSlowD_MAType: MAType) -> Result<(StochStream, (f64, f64)), RetCode> {
        self.stoch_open_internal(inHigh, inLow, inClose, 0, optInFastK_Period, optInSlowK_Period, optInSlowK_MAType, optInSlowD_Period, optInSlowD_MAType)
    }

    /// [`Core::stoch_open`] that also fills the output array(s) bit-identically to
    /// [`Core::STOCH`] over `0..len` in the same single pass, and reports the range it
    /// wrote as the [`OutRange`] beside the handle.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] when an output slice holds fewer than `len - lookback`
    /// values — the batch tier's sizing rule, checked here as it is there (rule S5) —
    /// or when two of them are the same slice. Everything [`Core::stoch_open`] rejects
    /// is rejected here too.
    ///
    /// # Examples
    ///
    /// ```
    /// use ta_lib::{Core, MAType};
    /// let high: Vec<f64> = (0..252).map(|i| 101.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    /// let low: Vec<f64> = (0..252).map(|i| 99.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    /// let close: Vec<f64> = (0..252)
    ///     .map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin() + 0.8 * (0.7 * i as f64).sin())
    ///     .collect();
    ///
    /// let core = Core::new();
    /// let mut batch_slow_k = vec![0.0; 252];
    /// let mut batch_slow_d = vec![0.0; 252];
    /// let batch = core.STOCH(0, high.len() - 1, &high, &low, &close, 5, 3, MAType::SMA, 3, MAType::SMA, &mut batch_slow_k, &mut batch_slow_d)?;
    ///
    /// let mut slow_k = vec![0.0; 252];
    /// let mut slow_d = vec![0.0; 252];
    /// let (_stream, filled) = core.stoch_open_and_fill(&high, &low, &close, 5, 3, MAType::SMA, 3, MAType::SMA, &mut slow_k, &mut slow_d)?;
    ///
    /// assert_eq!(filled.beg_idx, batch.beg_idx);
    /// assert_eq!(filled.count, batch.count);
    /// assert!(slow_k[..filled.count].iter().zip(&batch_slow_k[..batch.count])
    ///     .all(|(a, b)| a.to_bits() == b.to_bits()));
    /// assert!(slow_d[..filled.count].iter().zip(&batch_slow_d[..batch.count])
    ///     .all(|(a, b)| a.to_bits() == b.to_bits()));
    /// # Ok::<(), ta_lib::RetCode>(())
    /// ```
    #[doc(alias = "TA_STOCH_OpenAndFill")]
    pub fn stoch_open_and_fill(
        &self, inHigh: &[f64], inLow: &[f64], inClose: &[f64], mut optInFastK_Period: i32, mut optInSlowK_Period: i32, mut optInSlowK_MAType: MAType, mut optInSlowD_Period: i32, mut optInSlowD_MAType: MAType, outSlowK: &mut [f64], outSlowD: &mut [f64],
    ) -> Result<(StochStream, OutRange), RetCode> {
        if inHigh.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inHigh.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        let _guardLb = self.STOCH_Lookback(optInFastK_Period, optInSlowK_Period, optInSlowK_MAType, optInSlowD_Period, optInSlowD_MAType)?;
        if inLow.len() != inHigh.len() || inClose.len() != inHigh.len() {
            return Err(RetCode::BadParam);
        }
        let _guardOutLen = inHigh.len().saturating_sub(_guardLb);
        if outSlowK.len() < _guardOutLen {
            return Err(RetCode::BadParam);
        }
        if outSlowD.len() < _guardOutLen {
            return Err(RetCode::BadParam);
        }
        if !outSlowK.is_empty() && !outSlowD.is_empty() && outSlowK.as_ptr() == outSlowD.as_ptr() {
            return Err(RetCode::BadParam);
        }
        let mut outBegIdx: usize = 0;
        let mut outNBElement: usize = 0;
        let handle = self.stoch_open_and_fill_internal(inHigh, inLow, inClose, 0, optInFastK_Period, optInSlowK_Period, optInSlowK_MAType, optInSlowD_Period, optInSlowD_MAType, &mut outBegIdx, &mut outNBElement, outSlowK, outSlowD)?;
        Ok((handle, OutRange { beg_idx: outBegIdx, count: outNBElement }))
    }

    /// [`Core::stoch_open_and_fill`] anchored at `startIdx` — the composed-open
    /// fusion seam (issue #192), not a public entry point.
    pub(crate) fn stoch_open_and_fill_internal(
        &self, inHigh: &[f64], inLow: &[f64], inClose: &[f64], startIdx: usize, mut optInFastK_Period: i32, mut optInSlowK_Period: i32, mut optInSlowK_MAType: MAType, mut optInSlowD_Period: i32, mut optInSlowD_MAType: MAType, outBegIdx: &mut usize, outNBElement: &mut usize, outSlowK: &mut [f64], outSlowD: &mut [f64],
    ) -> Result<StochStream, RetCode> {
        self.stoch_open_impl(inHigh, inLow, inClose, startIdx, optInFastK_Period, optInSlowK_Period, optInSlowK_MAType, optInSlowD_Period, optInSlowD_MAType, outBegIdx, outNBElement, outSlowK, outSlowD, 1)
    }

}

thread_local! {
    /// `peek`'s reusable scratch state (see `StochStreamState::restore_from`).
    /// Taken for the duration of the step and put back after, so a
    /// panicking step costs the scratch, never leaves it borrowed.
    static STOCH_PEEK_SCRATCH: std::cell::Cell<Option<Box<StochStreamState>>> =
        const { std::cell::Cell::new(None) };
}

#[allow(non_snake_case)]
#[allow(unused_variables)]
impl StochStream {
    /// Commit one closed bar. Never allocates.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite (NaN or ±Inf).
    /// That check runs before anything is written, so the handle is left
    /// exactly as it was and the stream stays usable:
    /// skip the bar, or close and re-open on a clean history. This is the
    /// one place the streaming tier is stricter than the batch API, which
    /// computes on whatever it is given — a handle retains its state, so a
    /// single non-finite bar would poison every later value it produces.
    #[doc(alias = "TA_STOCH_Update")]
    pub fn update(&mut self, inHigh: f64, inLow: f64, inClose: f64) -> Result<(f64, f64), RetCode> {
        if !inHigh.is_finite() || !inLow.is_finite() || !inClose.is_finite() {
            return Err(RetCode::BadParam);
        }
        let mut outSlowK: f64 = 0.0_f64;
        let mut outSlowD: f64 = 0.0_f64;
        Core::stoch_step_impl(&mut self.state, inHigh, inLow, inClose, &mut outSlowK, &mut outSlowD)?;
        if self.out.count < Core::MAX_INDEX {
            self.out.count += 1;
        }
        Ok((outSlowK, outSlowD))
    }

    /// Commit `n` closed bars and write their `n` values, in one call —
    /// exactly `n` back-to-back [`Self::update`] calls, with one set of
    /// argument checks instead of `n`. `n` is `inHigh.len()`; the outputs must
    /// hold at least that many. Never allocates.
    ///
    /// [`Self::out_range`] counts what was committed, which is what makes the
    /// rejection below readable: there is no second out-parameter for it.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if the input slices differ in length, if an output
    /// is shorter than the bar count — neither commits anything — or if a bar
    /// is not finite. A non-finite bar `k` is rejected exactly as `update`
    /// rejects it: bars `0..k` stay committed and their values written, bar `k`
    /// and everything after it is not, and `out_range().count` has advanced by
    /// `k`.
    #[doc(alias = "TA_STOCH_UpdateAndFill")]
    pub fn update_and_fill(&mut self, inHigh: &[f64], inLow: &[f64], inClose: &[f64], outSlowK: &mut [f64], outSlowD: &mut [f64]) -> Result<(), RetCode> {
        let barCount = inHigh.len();
        if inLow.len() != inHigh.len() || inClose.len() != inHigh.len() || outSlowK.len() < barCount || outSlowD.len() < barCount {
            return Err(RetCode::BadParam);
        }
        for i in 0..barCount {
            if !inHigh[i].is_finite() || !inLow[i].is_finite() || !inClose[i].is_finite() {
                return Err(RetCode::BadParam);
            }
            Core::stoch_step_impl(&mut self.state, inHigh[i], inLow[i], inClose[i], &mut outSlowK[i], &mut outSlowD[i])?;
            if self.out.count < Core::MAX_INDEX {
                self.out.count += 1;
            }
        }
        Ok(())
    }

    /// Evaluate a forming bar without committing — bit-identical to what the
    /// next `update` with the same bar would return (it is the same code, run
    /// on a scratch copy of the state). Never writes the handle, so peeks may
    /// run concurrently with each other. The copy it runs on is held per thread and reused,
    /// so only the first peek of this function on a thread allocates.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite, exactly as
    /// `update` rejects it.
    #[doc(alias = "TA_STOCH_Peek")]
    pub fn peek(&self, inHigh: f64, inLow: f64, inClose: f64) -> Result<(f64, f64), RetCode> {
        if !inHigh.is_finite() || !inLow.is_finite() || !inClose.is_finite() {
            return Err(RetCode::BadParam);
        }
        STOCH_PEEK_SCRATCH.with(|cell| {
            let mut scratch = cell.take().unwrap_or_else(|| Box::new(self.state.clone()));
            scratch.restore_from(&self.state);
            let mut outSlowK: f64 = 0.0_f64;
            let mut outSlowD: f64 = 0.0_f64;
            let stepped = Core::stoch_step_impl(&mut scratch, inHigh, inLow, inClose, &mut outSlowK, &mut outSlowD);
            cell.set(Some(scratch));
            stepped?;
            Ok((outSlowK, outSlowD))
        })
    }

    /// The bars this stream has produced a value for, in the input series'
    /// coordinates: `[beg_idx, beg_idx + count)`.
    ///
    /// It is what [`Core::STOCH`] reports over the same bars: the opener sets it
    /// to `(lookback, historyLen - lookback)`, every accepted `update` adds one
    /// to the count, `peek` leaves it alone, and a clone carries it verbatim.
    /// A plain `Open` hands back only the last value, a subset of this range,
    /// because the caller chose not to take the fill.
    #[doc(alias = "TA_StreamOutRange")]
    pub fn out_range(&self) -> OutRange {
        self.out
    }
}

