impl VidyaStream {
    pub(crate) fn step_tape(&mut self, tape: &[f64], tapeBase: usize, tapeMask: usize, inReal: f64) -> f64 {
        let mut outReal: f64 = 0.0_f64;
        Core::vidya_step_tape_impl(&mut self.state, tape, tapeBase, tapeMask, inReal, &mut outReal);
        self.out.count += 1;
        outReal
    }

    pub(crate) fn peek_tape(&self, tape: &[f64], tapeBase: usize, tapeMask: usize, inReal: f64) -> Result<f64, RetCode> {
        let mut outReal: f64 = 0.0_f64;
        {
            let sp = &self.state;
            let outReal = &mut outReal;
            let mut sum: f64 = 0.0_f64;
            let mut diff: f64 = 0.0_f64;
            let mut tempReal: f64 = 0.0_f64;
            let mut k: f64 = 0.0_f64;
            let mut downSum = sp.downSum;
            let mut nullRun = sp.nullRun;
            let mut prevVIDYA = sp.prevVIDYA;
            let mut prevValue = sp.prevValue;
            let mut trailingValue = sp.trailingValue;
            let mut upSum = sp.upSum;
            tempReal = tape[(tapeBase - sp.ringCap_trailingIdx & tapeMask) as usize];
            diff = tempReal - trailingValue;
            trailingValue = tempReal;
            if diff > 0.0 {
                upSum -= diff;
            } else if diff < 0.0 {
                downSum += diff;
            }
            tempReal = inReal;
            diff = tempReal - prevValue;
            prevValue = tempReal;
            if diff > 0.0 {
                upSum += diff;
            } else if diff < 0.0 {
                downSum -= diff;
            }
            if diff == 0.0 {
                nullRun += 1;
            } else {
                nullRun = 0;
            }
            if nullRun >= ((sp.optInCMOPeriod) as usize) {
                nullRun = (sp.optInCMOPeriod) as usize;
                upSum = 0.0;
                downSum = 0.0;
            }
            sum = upSum + downSum;
            if sum > 0.0 {
                k = sp.alpha * ((100.0 * (upSum - downSum) / sum).abs() / 100.0);
            } else {
                k = 0.0;
            }
            prevVIDYA = (prevValue - prevVIDYA as f64).mul_add(k, prevVIDYA);
            (*outReal) = prevVIDYA;
        }
        Ok(outReal)
    }

    pub(crate) fn tape_detach(&mut self) -> usize {
        let mut reach: usize = 0;
        self.state.ring_trailingIdx_inReal = Vec::new();
        if self.state.ringCap_trailingIdx > reach {
            reach = self.state.ringCap_trailingIdx;
        }
        reach
    }
}

