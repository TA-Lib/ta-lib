#[allow(unused_parens)]
impl Core {
    fn sarext_step_impl(sp: &mut SarextStreamState, inHigh: f64, inLow: f64, outReal: &mut f64) {
        let mut prevHigh: f64 = 0.0_f64;
        let mut prevLow: f64 = 0.0_f64;
        prevLow = sp.newLow;
        prevHigh = sp.newHigh;
        sp.newLow = inLow;
        sp.newHigh = inHigh;
        if sp.isLong == 1 {
            // Switch to short if the low penetrates the SAR value.
            if sp.newLow <= sp.sar {
                // Switch and Overide the SAR with the ep
                sp.isLong = 0;
                sp.sar = sp.ep;
                // Make sure the overide SAR is within
                // yesterday's and today's range.
                if sp.sar < prevHigh {
                    sp.sar = prevHigh;
                }
                if sp.sar < sp.newHigh {
                    sp.sar = sp.newHigh;
                }
                // Output the overide SAR
                if sp.optInOffsetOnReverse != 0.0 {
                    sp.sar += sp.sar * sp.optInOffsetOnReverse;
                }
                (*outReal) = 0_f64 - sp.sar;
                // Adjust afShort and ep
                sp.afShort = sp.optInAccelerationInitShort;
                sp.ep = sp.newLow;
                // Calculate the new SAR
                sp.sar = (sp.afShort as f64).mul_add(sp.ep - sp.sar, sp.sar);
                // Make sure the new SAR is within
                // yesterday's and today's range.
                if sp.sar < prevHigh {
                    sp.sar = prevHigh;
                }
                if sp.sar < sp.newHigh {
                    sp.sar = sp.newHigh;
                }
            } else {
                // No switch
                // Output the SAR (was calculated in the previous iteration)
                (*outReal) = sp.sar;
                // Adjust afLong and ep.
                if sp.newHigh > sp.ep {
                    sp.ep = sp.newHigh;
                    sp.afLong += sp.optInAccelerationLong;
                    if sp.afLong > sp.optInAccelerationMaxLong {
                        sp.afLong = sp.optInAccelerationMaxLong;
                    }
                }
                // Calculate the new SAR
                sp.sar = (sp.afLong as f64).mul_add(sp.ep - sp.sar, sp.sar);
                // Make sure the new SAR is within
                // yesterday's and today's range.
                if sp.sar > prevLow {
                    sp.sar = prevLow;
                }
                if sp.sar > sp.newLow {
                    sp.sar = sp.newLow;
                }
            }
        // Switch to long if the high penetrates the SAR value.
        } else if sp.newHigh >= sp.sar {
            // Switch and Overide the SAR with the ep
            sp.isLong = 1;
            sp.sar = sp.ep;
            // Make sure the overide SAR is within
            // yesterday's and today's range.
            if sp.sar > prevLow {
                sp.sar = prevLow;
            }
            if sp.sar > sp.newLow {
                sp.sar = sp.newLow;
            }
            // Output the overide SAR
            if sp.optInOffsetOnReverse != 0.0 {
                sp.sar -= sp.sar * sp.optInOffsetOnReverse;
            }
            (*outReal) = sp.sar;
            // Adjust afLong and ep
            sp.afLong = sp.optInAccelerationInitLong;
            sp.ep = sp.newHigh;
            // Calculate the new SAR
            sp.sar = (sp.afLong as f64).mul_add(sp.ep - sp.sar, sp.sar);
            // Make sure the new SAR is within
            // yesterday's and today's range.
            if sp.sar > prevLow {
                sp.sar = prevLow;
            }
            if sp.sar > sp.newLow {
                sp.sar = sp.newLow;
            }
        } else {
            // No switch
            // Output the SAR (was calculated in the previous iteration)
            (*outReal) = 0_f64 - sp.sar;
            // Adjust afShort and ep.
            if sp.newLow < sp.ep {
                sp.ep = sp.newLow;
                sp.afShort += sp.optInAccelerationShort;
                if sp.afShort > sp.optInAccelerationMaxShort {
                    sp.afShort = sp.optInAccelerationMaxShort;
                }
            }
            // Calculate the new SAR
            sp.sar = (sp.afShort as f64).mul_add(sp.ep - sp.sar, sp.sar);
            // Make sure the new SAR is within
            // yesterday's and today's range.
            if sp.sar < prevHigh {
                sp.sar = prevHigh;
            }
            if sp.sar < sp.newHigh {
                sp.sar = sp.newHigh;
            }
        }
        sp.cur_outReal = (*outReal);
    }

    /// The single whole-history transcription behind [`Core::sarext_open_internal`]
    /// (stride 0, scalar sink) and [`Core::sarext_open_and_fill`] (stride 1, caller slices).
    pub(crate) fn sarext_open_impl(
        &self, inHigh: &[f64], inLow: &[f64], startIdx: usize, mut optInStartValue: f64, mut optInOffsetOnReverse: f64, mut optInAccelerationInitLong: f64, mut optInAccelerationLong: f64, mut optInAccelerationMaxLong: f64, mut optInAccelerationInitShort: f64, mut optInAccelerationShort: f64, mut optInAccelerationMaxShort: f64, outBegIdx: &mut usize, outNBElement: &mut usize, outReal: &mut [f64], outStride: usize,
    ) -> Result<SarextStream, RetCode> {
        if inHigh.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inHigh.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        if optInStartValue == Self::REAL_DEFAULT {
            optInStartValue = 0e0;
        } else if !((optInStartValue >= Self::REAL_MIN) && (optInStartValue <= Self::REAL_MAX)) {
            return Err(RetCode::BadParam);
        }
        if optInOffsetOnReverse == Self::REAL_DEFAULT {
            optInOffsetOnReverse = 0e0;
        } else if !((optInOffsetOnReverse >= 0e0) && (optInOffsetOnReverse <= Self::REAL_MAX)) {
            return Err(RetCode::BadParam);
        }
        if optInAccelerationInitLong == Self::REAL_DEFAULT {
            optInAccelerationInitLong = 2e-2;
        } else if !((optInAccelerationInitLong >= 0e0) && (optInAccelerationInitLong <= Self::REAL_MAX)) {
            return Err(RetCode::BadParam);
        }
        if optInAccelerationLong == Self::REAL_DEFAULT {
            optInAccelerationLong = 2e-2;
        } else if !((optInAccelerationLong >= 0e0) && (optInAccelerationLong <= Self::REAL_MAX)) {
            return Err(RetCode::BadParam);
        }
        if optInAccelerationMaxLong == Self::REAL_DEFAULT {
            optInAccelerationMaxLong = 2e-1;
        } else if !((optInAccelerationMaxLong >= 0e0) && (optInAccelerationMaxLong <= Self::REAL_MAX)) {
            return Err(RetCode::BadParam);
        }
        if optInAccelerationInitShort == Self::REAL_DEFAULT {
            optInAccelerationInitShort = 2e-2;
        } else if !((optInAccelerationInitShort >= 0e0) && (optInAccelerationInitShort <= Self::REAL_MAX)) {
            return Err(RetCode::BadParam);
        }
        if optInAccelerationShort == Self::REAL_DEFAULT {
            optInAccelerationShort = 2e-2;
        } else if !((optInAccelerationShort >= 0e0) && (optInAccelerationShort <= Self::REAL_MAX)) {
            return Err(RetCode::BadParam);
        }
        if optInAccelerationMaxShort == Self::REAL_DEFAULT {
            optInAccelerationMaxShort = 2e-1;
        } else if !((optInAccelerationMaxShort >= 0e0) && (optInAccelerationMaxShort <= Self::REAL_MAX)) {
            return Err(RetCode::BadParam);
        }
        if inLow.len() != inHigh.len() {
            return Err(RetCode::BadParam);
        }
        let historyLen: usize = inHigh.len();
        let endIdx: usize = historyLen - 1;
        let mut startIdx = startIdx;
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut retCode: RetCode = RetCode::Success;
        let mut isLong: usize = 0_usize;
        let mut todayIdx: usize = 0_usize;
        let mut outIdx: usize = 0_usize;
        let mut tempInt: usize = 0_usize;
        let mut newHigh: f64 = 0.0_f64;
        let mut newLow: f64 = 0.0_f64;
        let mut prevHigh: f64 = 0.0_f64;
        let mut prevLow: f64 = 0.0_f64;
        let mut afLong: f64 = 0.0_f64;
        let mut afShort: f64 = 0.0_f64;
        let mut ep: f64 = 0.0_f64;
        let mut sar: f64 = 0.0_f64;
        let mut ep_temp: [f64; 1 as usize] = [0.0_f64; 1 as usize];
        // > 0 indicates long. == 0 indicates short
        // This function is the same as TA_SAR, except that the caller has
        // greater control on the SAR dynamic and initial state.
        //
        // In additon, the TA_SAREXT returns negative values when the position
        // is short. This allow to distinguish when the SAR do actually reverse.
        // Implementation of the SAR has been a little bit open to interpretation
        // since Wilder (the original author) did not define a precise algorithm
        // on how to bootstrap the algorithm. Take any existing software application
        // and you will see slight variation on how the algorithm was adapted.
        //
        // What is the initial trade direction? Long or short?
        // ===================================================
        // The interpretation of what should be the initial SAR values is
        // open to interpretation, particularly since the caller to the function
        // does not specify the initial direction of the trade.
        //
        // In TA-Lib, the following default logic is used:
        //  - Calculate +DM and -DM between the first and
        //    second bar. The highest directional indication will
        //    indicate the assumed direction of the trade for the second
        //    price bar.
        //  - In the case of a tie between +DM and -DM,
        //    the direction is LONG by default.
        //
        // What is the initial "extreme point" and thus SAR?
        // =================================================
        // The following shows how different people took different approach:
        //  - Metastock use the first price bar high/low depending of
        //    the direction. No SAR is calculated for the first price
        //    bar.
        //  - Tradestation use the closing price of the second bar. No
        //    SAR are calculated for the first price bar.
        //  - Wilder (the original author) use the SIP from the
        //    previous trade (cannot be implement here since the
        //    direction and length of the previous trade is unknonw).
        //  - The Magazine TASC seems to follow Wilder approach which
        //    is not practical here.
        //
        // TA-Lib "consume" the first price bar and use its high/low as the
        // initial SAR of the second price bar. I found that approach to be
        // the closest to Wilders idea of having the first entry day use
        // the previous extreme point, except that here the extreme point is
        // derived solely from the first price bar. I found the same approach
        // to be used by Metastock.
        //
        //
        // Can I force the initial SAR?
        // ============================
        // Yes. Using the optInStartValue_0 parameter:
        //  optInStartValue_0 >  0 : SAR is long at optInStartValue_0.
        //  optInStartValue_0 <  0 : SAR is short at fabs(optInStartValue_0).
        //
        // And when optInStartValue_0 == 0, the logic is the same as for TA_SAR
        // (See previous two sections).
        // Identify the minimum number of price bar needed
        // to calculate at least one output.
        //
        // Move up the start index if there is not
        // enough initial data.
        if startIdx < 1 {
            startIdx = 1;
        }
        // Make sure there is still something to evaluate.
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        // Check if the acceleration factors are being defined by the user.
        // Make sure the acceleration and maximum are coherent.
        // If not, correct the acceleration.
        // Default afLong = 0.02
        // Default afShort = 0.02
        afLong = optInAccelerationInitLong;
        afShort = optInAccelerationInitShort;
        if afLong > optInAccelerationMaxLong {
            optInAccelerationInitLong = optInAccelerationMaxLong;
            afLong = optInAccelerationInitLong;
        }
        if optInAccelerationLong > optInAccelerationMaxLong {
            optInAccelerationLong = optInAccelerationMaxLong;
        }
        if afShort > optInAccelerationMaxShort {
            optInAccelerationInitShort = optInAccelerationMaxShort;
            afShort = optInAccelerationInitShort;
        }
        if optInAccelerationShort > optInAccelerationMaxShort {
            optInAccelerationShort = optInAccelerationMaxShort;
        }
        // Initialise SAR calculations
        if optInStartValue == 0_f64 {
            // Default action
            // Identify if the initial direction is long or short.
            // (ep is just used as a temp buffer here, the name
            //  of the parameter is not significant).
            let _xr0 = match self.MINUS_DM(startIdx, startIdx, inHigh, inLow, 1, &mut ep_temp) { Ok(_r) => _r, Err(_e) => return Err(_e) };
            tempInt = _xr0.beg_idx;
            tempInt = _xr0.count;
            retCode = RetCode::Success;
            if ep_temp[0] > 0_f64 {
                isLong = 0;
            } else {
                isLong = 1;
            }
        } else if optInStartValue > 0_f64 {
            // Start Long
            isLong = 1;
        } else {
            // optInStartValue_0 < 0 => Start Short
            isLong = 0;
        }
        (*outBegIdx) = startIdx;
        outIdx = 0;
        // Write the first SAR.
        todayIdx = startIdx;
        newHigh = inHigh[todayIdx - 1];
        newLow = inLow[todayIdx - 1];
        if optInStartValue == 0_f64 {
            // Default action
            if isLong == 1 {
                ep = inHigh[todayIdx];
                sar = newLow;
            } else {
                ep = inLow[todayIdx];
                sar = newHigh;
            }
        } else if optInStartValue > 0_f64 {
            // Start Long at specified value.
            ep = inHigh[todayIdx];
            sar = optInStartValue;
        } else {
            // if optInStartValue < 0 => Start Short at specified value.
            ep = inLow[todayIdx];
            sar = (optInStartValue).abs();
        }
        // Cheat on the newLow and newHigh for the
        // first iteration.
        newLow = inLow[todayIdx];
        newHigh = inHigh[todayIdx];
        while todayIdx <= endIdx {
            prevLow = newLow;
            prevHigh = newHigh;
            newLow = inLow[todayIdx];
            newHigh = inHigh[todayIdx];
            todayIdx += 1;
            if isLong == 1 {
                // Switch to short if the low penetrates the SAR value.
                if newLow <= sar {
                    // Switch and Overide the SAR with the ep
                    isLong = 0;
                    sar = ep;
                    // Make sure the overide SAR is within
                    // yesterday's and today's range.
                    if sar < prevHigh {
                        sar = prevHigh;
                    }
                    if sar < newHigh {
                        sar = newHigh;
                    }
                    // Output the overide SAR
                    if optInOffsetOnReverse != 0.0 {
                        sar += sar * optInOffsetOnReverse;
                    }
                    outReal[({ let _v = outIdx; outIdx += 1; _v } * outStride) as usize] = 0_f64 - sar;
                    // Adjust afShort and ep
                    afShort = optInAccelerationInitShort;
                    ep = newLow;
                    // Calculate the new SAR
                    sar = (afShort as f64).mul_add(ep - sar, sar);
                    // Make sure the new SAR is within
                    // yesterday's and today's range.
                    if sar < prevHigh {
                        sar = prevHigh;
                    }
                    if sar < newHigh {
                        sar = newHigh;
                    }
                } else {
                    // No switch
                    // Output the SAR (was calculated in the previous iteration)
                    outReal[({ let _v = outIdx; outIdx += 1; _v } * outStride) as usize] = sar;
                    // Adjust afLong and ep.
                    if newHigh > ep {
                        ep = newHigh;
                        afLong += optInAccelerationLong;
                        if afLong > optInAccelerationMaxLong {
                            afLong = optInAccelerationMaxLong;
                        }
                    }
                    // Calculate the new SAR
                    sar = (afLong as f64).mul_add(ep - sar, sar);
                    // Make sure the new SAR is within
                    // yesterday's and today's range.
                    if sar > prevLow {
                        sar = prevLow;
                    }
                    if sar > newLow {
                        sar = newLow;
                    }
                }
            // Switch to long if the high penetrates the SAR value.
            } else if newHigh >= sar {
                // Switch and Overide the SAR with the ep
                isLong = 1;
                sar = ep;
                // Make sure the overide SAR is within
                // yesterday's and today's range.
                if sar > prevLow {
                    sar = prevLow;
                }
                if sar > newLow {
                    sar = newLow;
                }
                // Output the overide SAR
                if optInOffsetOnReverse != 0.0 {
                    sar -= sar * optInOffsetOnReverse;
                }
                outReal[({ let _v = outIdx; outIdx += 1; _v } * outStride) as usize] = sar;
                // Adjust afLong and ep
                afLong = optInAccelerationInitLong;
                ep = newHigh;
                // Calculate the new SAR
                sar = (afLong as f64).mul_add(ep - sar, sar);
                // Make sure the new SAR is within
                // yesterday's and today's range.
                if sar > prevLow {
                    sar = prevLow;
                }
                if sar > newLow {
                    sar = newLow;
                }
            } else {
                // No switch
                // Output the SAR (was calculated in the previous iteration)
                outReal[({ let _v = outIdx; outIdx += 1; _v } * outStride) as usize] = 0_f64 - sar;
                // Adjust afShort and ep.
                if newLow < ep {
                    ep = newLow;
                    afShort += optInAccelerationShort;
                    if afShort > optInAccelerationMaxShort {
                        afShort = optInAccelerationMaxShort;
                    }
                }
                // Calculate the new SAR
                sar = (afShort as f64).mul_add(ep - sar, sar);
                // Make sure the new SAR is within
                // yesterday's and today's range.
                if sar < prevHigh {
                    sar = prevHigh;
                }
                if sar < newHigh {
                    sar = newHigh;
                }
            }
        }
        (*outNBElement) = outIdx;

        // Capture the live batch state into the handle.
        let state = SarextStreamState {
            optInStartValue,
            optInOffsetOnReverse,
            optInAccelerationInitLong,
            optInAccelerationLong,
            optInAccelerationMaxLong,
            optInAccelerationInitShort,
            optInAccelerationShort,
            optInAccelerationMaxShort,
            isLong,
            newHigh,
            newLow,
            afLong,
            afShort,
            ep,
            sar,
            cur_outReal: outReal[(*outNBElement - 1) * outStride],
        };
        Ok(SarextStream { state, out: OutRange { beg_idx: *outBegIdx, count: *outNBElement } })
    }

    /// Internal startIdx-anchored open behind [`Core::sarext_open`] (composition seam).
    pub(crate) fn sarext_open_internal(
        &self, inHigh: &[f64], inLow: &[f64], startIdx: usize, mut optInStartValue: f64, mut optInOffsetOnReverse: f64, mut optInAccelerationInitLong: f64, mut optInAccelerationLong: f64, mut optInAccelerationMaxLong: f64, mut optInAccelerationInitShort: f64, mut optInAccelerationShort: f64, mut optInAccelerationMaxShort: f64,
    ) -> Result<(SarextStream, f64), RetCode> {
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut sink_outReal = [0.0_f64; 1];
        let handle = self.sarext_open_impl(inHigh, inLow, startIdx, optInStartValue, optInOffsetOnReverse, optInAccelerationInitLong, optInAccelerationLong, optInAccelerationMaxLong, optInAccelerationInitShort, optInAccelerationShort, optInAccelerationMaxShort, &mut dummyBegIdx, &mut dummyNBElement, &mut sink_outReal, 0)?;
        Ok((handle, sink_outReal[0]))
    }

    /// Open a live SAREXT stream over the warm-up history; returns the handle and
    /// the value at the last history bar — bit-identical to [`Core::SAREXT`] at that bar.
    ///
    /// # Errors
    ///
    /// [`RetCode::InsufficientHistory`] when the history holds fewer than
    /// `lookback + 1` bars — the one failure here worth retrying, since another
    /// bar fixes it. [`RetCode::OutOfRangeStartIndex`] when the history is empty.
    /// [`RetCode::BadParam`] when a parameter is out of range or the input
    /// lengths differ.
    ///
    /// ```
    /// use ta_lib::Core;
    /// let high: Vec<f64> = (0..252).map(|i| 101.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    /// let low: Vec<f64> = (0..252).map(|i| 99.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    ///
    /// let core = Core::new();
    /// let (mut s, _last) = core.sarext_open(&high, &low, 0.0, 0.0, 0.02, 0.02, 0.2, 0.02, 0.02, 0.2).expect("enough history");
    /// let r0 = s.out_range();
    /// let peeked = s.peek(101.4, 99.1).expect("a finite bar");
    /// assert_eq!(s.out_range().count, r0.count); // a peek commits nothing
    /// let updated = s.update(101.4, 99.1).expect("a finite bar");
    /// assert_eq!(s.out_range().beg_idx, r0.beg_idx);
    /// assert_eq!(s.out_range().count, r0.count + 1);
    /// assert_eq!(peeked.to_bits(), updated.to_bits());
    /// ```
    #[doc(alias = "TA_SAREXT_Open")]
    pub fn sarext_open(&self, inHigh: &[f64], inLow: &[f64], optInStartValue: f64, optInOffsetOnReverse: f64, optInAccelerationInitLong: f64, optInAccelerationLong: f64, optInAccelerationMaxLong: f64, optInAccelerationInitShort: f64, optInAccelerationShort: f64, optInAccelerationMaxShort: f64) -> Result<(SarextStream, f64), RetCode> {
        self.sarext_open_internal(inHigh, inLow, 0, optInStartValue, optInOffsetOnReverse, optInAccelerationInitLong, optInAccelerationLong, optInAccelerationMaxLong, optInAccelerationInitShort, optInAccelerationShort, optInAccelerationMaxShort)
    }

    /// [`Core::sarext_open`] that also fills the output array(s) bit-identically to
    /// [`Core::SAREXT`] over `0..len` in the same single pass, and reports the range it
    /// wrote as the [`OutRange`] beside the handle.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] when an output slice holds fewer than `len - lookback`
    /// values — the batch tier's sizing rule, checked here as it is there (rule S5) —
    /// or when two of them are the same slice. Everything [`Core::sarext_open`] rejects
    /// is rejected here too.
    ///
    /// # Examples
    ///
    /// ```
    /// use ta_lib::Core;
    /// let high: Vec<f64> = (0..252).map(|i| 101.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    /// let low: Vec<f64> = (0..252).map(|i| 99.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    ///
    /// let core = Core::new();
    /// let mut batch_out = vec![0.0; 252];
    /// let batch = core.SAREXT(0, high.len() - 1, &high, &low, 0.0, 0.0, 0.02, 0.02, 0.2, 0.02, 0.02, 0.2, &mut batch_out)?;
    ///
    /// let mut out = vec![0.0; 252];
    /// let (_stream, filled) = core.sarext_open_and_fill(&high, &low, 0.0, 0.0, 0.02, 0.02, 0.2, 0.02, 0.02, 0.2, &mut out)?;
    ///
    /// assert_eq!(filled.beg_idx, batch.beg_idx);
    /// assert_eq!(filled.count, batch.count);
    /// assert!(out[..filled.count].iter().zip(&batch_out[..batch.count])
    ///     .all(|(a, b)| a.to_bits() == b.to_bits()));
    /// # Ok::<(), ta_lib::RetCode>(())
    /// ```
    #[doc(alias = "TA_SAREXT_OpenAndFill")]
    pub fn sarext_open_and_fill(
        &self, inHigh: &[f64], inLow: &[f64], mut optInStartValue: f64, mut optInOffsetOnReverse: f64, mut optInAccelerationInitLong: f64, mut optInAccelerationLong: f64, mut optInAccelerationMaxLong: f64, mut optInAccelerationInitShort: f64, mut optInAccelerationShort: f64, mut optInAccelerationMaxShort: f64, outReal: &mut [f64],
    ) -> Result<(SarextStream, OutRange), RetCode> {
        if inHigh.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inHigh.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        let _guardLb = self.SAREXT_Lookback(optInStartValue, optInOffsetOnReverse, optInAccelerationInitLong, optInAccelerationLong, optInAccelerationMaxLong, optInAccelerationInitShort, optInAccelerationShort, optInAccelerationMaxShort)?;
        if inLow.len() != inHigh.len() {
            return Err(RetCode::BadParam);
        }
        let _guardOutLen = inHigh.len().saturating_sub(_guardLb);
        if outReal.len() < _guardOutLen {
            return Err(RetCode::BadParam);
        }
        let mut outBegIdx: usize = 0;
        let mut outNBElement: usize = 0;
        let handle = self.sarext_open_and_fill_internal(inHigh, inLow, 0, optInStartValue, optInOffsetOnReverse, optInAccelerationInitLong, optInAccelerationLong, optInAccelerationMaxLong, optInAccelerationInitShort, optInAccelerationShort, optInAccelerationMaxShort, &mut outBegIdx, &mut outNBElement, outReal)?;
        Ok((handle, OutRange { beg_idx: outBegIdx, count: outNBElement }))
    }

    /// [`Core::sarext_open_and_fill`] anchored at `startIdx` — the composed-open
    /// fusion seam (issue #192), not a public entry point.
    pub(crate) fn sarext_open_and_fill_internal(
        &self, inHigh: &[f64], inLow: &[f64], startIdx: usize, mut optInStartValue: f64, mut optInOffsetOnReverse: f64, mut optInAccelerationInitLong: f64, mut optInAccelerationLong: f64, mut optInAccelerationMaxLong: f64, mut optInAccelerationInitShort: f64, mut optInAccelerationShort: f64, mut optInAccelerationMaxShort: f64, outBegIdx: &mut usize, outNBElement: &mut usize, outReal: &mut [f64],
    ) -> Result<SarextStream, RetCode> {
        self.sarext_open_impl(inHigh, inLow, startIdx, optInStartValue, optInOffsetOnReverse, optInAccelerationInitLong, optInAccelerationLong, optInAccelerationMaxLong, optInAccelerationInitShort, optInAccelerationShort, optInAccelerationMaxShort, outBegIdx, outNBElement, outReal, 1)
    }

}

#[allow(non_snake_case)]
#[allow(unused_variables)]
#[allow(unused_mut)]
#[allow(unused_assignments)]
#[allow(unused_parens)]
impl SarextStream {
    /// Commit one closed bar. Never allocates.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite (NaN or ±Inf).
    /// That check runs before anything is written, so the handle's state is
    /// left exactly as it was and the stream stays usable: skip the bar, or
    /// close and re-open on a clean history. This is the one place the
    /// streaming tier is stricter than the batch API, which computes on
    /// whatever it is given — a handle retains its state, so a single
    /// non-finite bar would poison every later value it produces.
    ///
    /// A rejection leaves [`Self::out_range`] alone too. Re-feed the bar when
    /// a corrected value arrives, or call [`Self::advance`] to count it and
    /// carry on — two handles on one feed drift a bar apart if neither
    /// happens.
    #[doc(alias = "TA_SAREXT_Update")]
    pub fn update(&mut self, inHigh: f64, inLow: f64) -> Result<f64, RetCode> {
        if !inHigh.is_finite() || !inLow.is_finite() {
            return Err(RetCode::BadParam);
        }
        let mut outReal: f64 = 0.0_f64;
        Core::sarext_step_impl(&mut self.state, inHigh, inLow, &mut outReal);
        if self.out.count < Core::MAX_INDEX {
            self.out.count += 1;
        }
        Ok(outReal)
    }

    /// Evaluate a forming bar without committing — bit-identical to what the
    /// next `update` with the same bar would return: the same transition,
    /// rewritten so every store it would make lives in a local instead. It
    /// allocates nothing and copies no buffer, so its cost does not grow with
    /// the period, and it writes no part of the handle — peeks may run
    /// concurrently with each other.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite, on the same test
    /// `update` applies, and a rejected peek changes nothing at all.
    #[doc(alias = "TA_SAREXT_Peek")]
    pub fn peek(&self, inHigh: f64, inLow: f64) -> Result<f64, RetCode> {
        if !inHigh.is_finite() || !inLow.is_finite() {
            return Err(RetCode::BadParam);
        }
        let mut outReal: f64 = 0.0_f64;
        {
            let sp = &self.state;
            let outReal = &mut outReal;
            let mut prevHigh: f64 = 0.0_f64;
            let mut prevLow: f64 = 0.0_f64;
            let mut afLong = sp.afLong;
            let mut afShort = sp.afShort;
            let mut ep = sp.ep;
            let mut isLong = sp.isLong;
            let mut newHigh = sp.newHigh;
            let mut newLow = sp.newLow;
            let mut sar = sp.sar;
            prevLow = newLow;
            prevHigh = newHigh;
            newLow = inLow;
            newHigh = inHigh;
            if isLong == 1 {
                // Switch to short if the low penetrates the SAR value.
                if newLow <= sar {
                    // Switch and Overide the SAR with the ep
                    isLong = 0;
                    sar = ep;
                    // Make sure the overide SAR is within
                    // yesterday's and today's range.
                    if sar < prevHigh {
                        sar = prevHigh;
                    }
                    if sar < newHigh {
                        sar = newHigh;
                    }
                    // Output the overide SAR
                    if sp.optInOffsetOnReverse != 0.0 {
                        sar += sar * sp.optInOffsetOnReverse;
                    }
                    (*outReal) = 0_f64 - sar;
                    // Adjust afShort and ep
                    afShort = sp.optInAccelerationInitShort;
                    ep = newLow;
                    // Calculate the new SAR
                    sar = (afShort as f64).mul_add(ep - sar, sar);
                    // Make sure the new SAR is within
                    // yesterday's and today's range.
                    if sar < prevHigh {
                        sar = prevHigh;
                    }
                    if sar < newHigh {
                        sar = newHigh;
                    }
                } else {
                    // No switch
                    // Output the SAR (was calculated in the previous iteration)
                    (*outReal) = sar;
                    // Adjust afLong and ep.
                    if newHigh > ep {
                        ep = newHigh;
                        afLong += sp.optInAccelerationLong;
                        if afLong > sp.optInAccelerationMaxLong {
                            afLong = sp.optInAccelerationMaxLong;
                        }
                    }
                    // Calculate the new SAR
                    sar = (afLong as f64).mul_add(ep - sar, sar);
                    // Make sure the new SAR is within
                    // yesterday's and today's range.
                    if sar > prevLow {
                        sar = prevLow;
                    }
                    if sar > newLow {
                        sar = newLow;
                    }
                }
            // Switch to long if the high penetrates the SAR value.
            } else if newHigh >= sar {
                // Switch and Overide the SAR with the ep
                isLong = 1;
                sar = ep;
                // Make sure the overide SAR is within
                // yesterday's and today's range.
                if sar > prevLow {
                    sar = prevLow;
                }
                if sar > newLow {
                    sar = newLow;
                }
                // Output the overide SAR
                if sp.optInOffsetOnReverse != 0.0 {
                    sar -= sar * sp.optInOffsetOnReverse;
                }
                (*outReal) = sar;
                // Adjust afLong and ep
                afLong = sp.optInAccelerationInitLong;
                ep = newHigh;
                // Calculate the new SAR
                sar = (afLong as f64).mul_add(ep - sar, sar);
                // Make sure the new SAR is within
                // yesterday's and today's range.
                if sar > prevLow {
                    sar = prevLow;
                }
                if sar > newLow {
                    sar = newLow;
                }
            } else {
                // No switch
                // Output the SAR (was calculated in the previous iteration)
                (*outReal) = 0_f64 - sar;
                // Adjust afShort and ep.
                if newLow < ep {
                    ep = newLow;
                    afShort += sp.optInAccelerationShort;
                    if afShort > sp.optInAccelerationMaxShort {
                        afShort = sp.optInAccelerationMaxShort;
                    }
                }
                // Calculate the new SAR
                sar = (afShort as f64).mul_add(ep - sar, sar);
                // Make sure the new SAR is within
                // yesterday's and today's range.
                if sar < prevHigh {
                    sar = prevHigh;
                }
                if sar < newHigh {
                    sar = newHigh;
                }
            }
        }
        Ok(outReal)
    }

    /// The value(s) at the last bar the stream counted — the bar
    /// [`Self::out_range`] ends on — without recomputing. Seeded by the opener,
    /// refreshed by every accepted `update`, and left
    /// alone by `peek`.
    ///
    /// A clone carries them verbatim, so a forked handle can be asked its
    /// current value without committing a bar to find out.
    #[must_use]
    #[doc(alias = "TA_SAREXT_Value")]
    pub fn value(&self) -> f64 {
        self.state.cur_outReal
    }

    /// The bars this stream has an output for, in the input series'
    /// coordinates: `[beg_idx, beg_idx + count)`.
    ///
    /// It is what [`Core::SAREXT`] reports over the same bars: the opener sets it
    /// to `(lookback, historyLen - lookback)`, every accepted `update` adds
    /// one to the count — a rejected one changes nothing, and neither does
    /// `peek` — and a clone carries it verbatim. A plain `Open` hands back
    /// only the last value, a subset of this range, because the caller chose
    /// not to take the fill.
    #[doc(alias = "TA_SAREXT_OutRange")]
    pub fn out_range(&self) -> OutRange {
        self.out
    }

    /// Count one bar this stream was not fed: [`Self::out_range`] advances by
    /// one and nothing else moves — [`Self::value`] keeps answering the
    /// previous output, which is this bar's output too.
    ///
    /// For a bar the caller leaves out: one an `update` rejected and that
    /// will not be re-fed, or a session with no print. Without it two handles
    /// on one feed drift a bar apart when only one of them skips.
    #[doc(alias = "TA_SAREXT_Advance")]
    pub fn advance(&mut self) {
        if self.out.count < Core::MAX_INDEX {
            self.out.count += 1;
        }
    }
}

