#[allow(unused_variables)]
#[allow(unused_mut)]
#[allow(unused_assignments)]
#[allow(unused_parens)]
impl RviStream {
    /// Commit one closed bar. Never allocates.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite (NaN or ±Inf).
    /// That check runs before anything is written, so the handle's state is
    /// left exactly as it was and the stream stays usable: skip the bar, or
    /// close and re-open on a clean history. This is the one place the
    /// streaming tier is stricter than the batch API, which computes on
    /// whatever it is given — a handle retains its state, so a single
    /// non-finite bar would poison every later value it produces.
    ///
    /// A rejection leaves [`Self::out_range`] alone too. Re-feed the bar when
    /// a corrected value arrives, or call [`Self::advance`] to count it and
    /// carry on — two handles on one feed drift a bar apart if neither
    /// happens.
    #[doc(alias = "TA_RVI_Update")]
    pub fn update(&mut self, inReal: f64) -> Result<f64, RetCode> {
        if !inReal.is_finite() {
            return Err(RetCode::BadParam);
        }
        let mut outReal: f64 = 0.0_f64;
        Core::rvi_step_impl(&mut self.state, inReal, &mut outReal);
        if self.out.count < Core::MAX_INDEX {
            self.out.count += 1;
        }
        Ok(outReal)
    }

    /// Evaluate a forming bar without committing — bit-identical to what the
    /// next `update` with the same bar would return: the same transition,
    /// rewritten so every store it would make lives in a local instead. It
    /// allocates nothing and copies no buffer, so its cost does not grow with
    /// the period, and it writes no part of the handle — peeks may run
    /// concurrently with each other.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite, on the same test
    /// `update` applies, and a rejected peek changes nothing at all.
    #[doc(alias = "TA_RVI_Peek")]
    pub fn peek(&self, inReal: f64) -> Result<f64, RetCode> {
        if !inReal.is_finite() {
            return Err(RetCode::BadParam);
        }
        let mut outReal: f64 = 0.0_f64;
        {
            let sp = &self.state;
            let outReal = &mut outReal;
            let mut tempReal: f64 = 0.0_f64;
            let mut meanValue1: f64 = 0.0_f64;
            let mut variance: f64 = 0.0_f64;
            let mut sigma: f64 = 0.0_f64;
            let mut delta: f64 = 0.0_f64;
            let mut upValue: f64 = 0.0_f64;
            let mut dnValue: f64 = 0.0_f64;
            let mut total: f64 = 0.0_f64;
            let mut barsSinceReseed = sp.barsSinceReseed;
            let mut j = sp.j;
            let mut periodTotal1 = sp.periodTotal1;
            let mut periodTotal2 = sp.periodTotal2;
            let mut prevDn = sp.prevDn;
            let mut prevUp = sp.prevUp;
            let mut shift = sp.shift;
            let mut today = sp.today;
            let mut trailingIdx = sp.trailingIdx;
            let mut windowStart = sp.windowStart;
            let mut pkSlot0: usize = usize::MAX;
            let mut pkVal0: f64 = 0.0_f64;
            if today >= 1073741824 {
                let rebaseShift: i32 = trailingIdx & !sp.xMask;
                today -= rebaseShift;
                trailingIdx -= rebaseShift;
                j -= rebaseShift;
                windowStart -= rebaseShift;
            }
            pkSlot0 = (today & sp.xMask) as usize;
            pkVal0 = inReal;
            tempReal = (if ((today & sp.xMask) as usize) != pkSlot0 { sp.x_inReal[(today & sp.xMask) as usize] } else { pkVal0 }) - shift;
            periodTotal1 += tempReal;
            tempReal *= tempReal;
            periodTotal2 += tempReal;
            meanValue1 = periodTotal1 * sp.invPeriod;
            variance = periodTotal2 * sp.invPeriod - meanValue1 * meanValue1;
            tempReal = (if ((trailingIdx & sp.xMask) as usize) != pkSlot0 { sp.x_inReal[(trailingIdx & sp.xMask) as usize] } else { pkVal0 }) - shift;
            periodTotal1 -= tempReal;
            tempReal *= tempReal;
            periodTotal2 -= tempReal;
            trailingIdx += 1;
            barsSinceReseed -= 1;
            if variance < 0.000001 * (periodTotal2 * sp.invPeriod) || tempReal > 1000000.0 * periodTotal2 || barsSinceReseed <= 0 {
                barsSinceReseed = (32 * sp.optInStdDevPeriod) as usize;
                windowStart = today - ((sp.nbInitialElementNeeded) as i32);
                tempReal = 0.0;
                // for( j = windowStart; j <= today; j += 1 )
                j = windowStart;
                while j <= today {
                    tempReal += (if ((j & sp.xMask) as usize) != pkSlot0 { sp.x_inReal[(j & sp.xMask) as usize] } else { pkVal0 });
                    j += 1;
                }
                shift = tempReal * sp.invPeriod;
                periodTotal1 = 0.0;
                periodTotal2 = 0.0;
                // for( j = windowStart; j <= today; j += 1 )
                j = windowStart;
                while j <= today {
                    tempReal = (if ((j & sp.xMask) as usize) != pkSlot0 { sp.x_inReal[(j & sp.xMask) as usize] } else { pkVal0 }) - shift;
                    periodTotal1 += tempReal;
                    tempReal *= tempReal;
                    periodTotal2 += tempReal;
                    j += 1;
                }
                meanValue1 = periodTotal1 * sp.invPeriod;
                variance = periodTotal2 * sp.invPeriod - meanValue1 * meanValue1;
                if variance < 0.000000000001 * (periodTotal2 * sp.invPeriod) {
                    variance = 0.0;
                }
                tempReal = (if ((windowStart & sp.xMask) as usize) != pkSlot0 { sp.x_inReal[(windowStart & sp.xMask) as usize] } else { pkVal0 }) - shift;
                periodTotal1 -= tempReal;
                tempReal *= tempReal;
                periodTotal2 -= tempReal;
            }
            sigma = (variance).sqrt();
            delta = (if ((today & sp.xMask) as usize) != pkSlot0 { sp.x_inReal[(today & sp.xMask) as usize] } else { pkVal0 }) - (if ((today - 1 & sp.xMask) as usize) != pkSlot0 { sp.x_inReal[(today - 1 & sp.xMask) as usize] } else { pkVal0 });
            upValue = 0.0;
            dnValue = 0.0;
            if delta > 0.0 {
                upValue = sigma;
            } else if delta < 0.0 {
                dnValue = sigma;
            }
            prevUp = (sp.wBeta as f64).mul_add(prevUp, sp.wAlpha * upValue);
            prevDn = (sp.wBeta as f64).mul_add(prevDn, sp.wAlpha * dnValue);
            total = prevUp + prevDn;
            (*outReal) = (if total == 0.0 { 50.0 } else { 100.0 * (prevUp / total) });
        }
        Ok(outReal)
    }

    /// The value(s) at the last bar the stream counted — the bar
    /// [`Self::out_range`] ends on — without recomputing. Seeded by the opener,
    /// refreshed by every accepted `update`, and left
    /// alone by `peek`.
    ///
    /// A clone carries them verbatim, so a forked handle can be asked its
    /// current value without committing a bar to find out.
    #[must_use]
    #[doc(alias = "TA_RVI_Value")]
    pub fn value(&self) -> f64 {
        self.state.cur_outReal
    }

    /// The bars this stream has an output for, in the input series'
    /// coordinates: `[beg_idx, beg_idx + count)`.
    ///
    /// It is what [`Core::RVI`] reports over the same bars: the opener sets it
    /// to `(lookback, historyLen - lookback)`, every accepted `update` adds
    /// one to the count — a rejected one changes nothing, and neither does
    /// `peek` — and a clone carries it verbatim. A plain `Open` hands back
    /// only the last value, a subset of this range, because the caller chose
    /// not to take the fill.
    #[doc(alias = "TA_RVI_OutRange")]
    pub fn out_range(&self) -> OutRange {
        self.out
    }

    /// Count one bar this stream was not fed: [`Self::out_range`] advances by
    /// one and nothing else moves — [`Self::value`] keeps answering the
    /// previous output, which is this bar's output too.
    ///
    /// For a bar the caller leaves out: one an `update` rejected and that
    /// will not be re-fed, or a session with no print. Without it two handles
    /// on one feed drift a bar apart when only one of them skips.
    #[doc(alias = "TA_RVI_Advance")]
    pub fn advance(&mut self) {
        if self.out.count < Core::MAX_INDEX {
            self.out.count += 1;
        }
    }
}

