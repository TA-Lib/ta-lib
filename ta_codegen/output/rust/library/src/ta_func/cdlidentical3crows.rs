    /// Open a live CDLIDENTICAL3CROWS stream over the warm-up history; returns the handle and
    /// the value at the last history bar — bit-identical to [`Core::CDLIDENTICAL3CROWS`] at that bar.
    ///
    /// # Errors
    ///
    /// [`RetCode::InsufficientHistory`] when the history holds fewer than
    /// `lookback + 1` bars — the one failure here worth retrying, since another
    /// bar fixes it. [`RetCode::OutOfRangeStartIndex`] when the history is empty.
    /// [`RetCode::BadParam`] when a parameter is out of range or the input
    /// lengths differ.
    ///
    /// ```
    /// use ta_lib::Core;
    /// let open: Vec<f64> = (0..252)
    ///     .map(|i| 100.0 + 10.0 * (0.1 * i as f64 - 0.05).sin())
    ///     .collect();
    /// let high: Vec<f64> = (0..252).map(|i| 101.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    /// let low: Vec<f64> = (0..252).map(|i| 99.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    /// let close: Vec<f64> = (0..252)
    ///     .map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin() + 0.8 * (0.7 * i as f64).sin())
    ///     .collect();
    ///
    /// let core = Core::new();
    /// let (mut s, _last) = core.cdlidentical3crows_open(&open, &high, &low, &close).expect("enough history");
    /// let r0 = s.out_range();
    /// let peeked = s.peek(100.2, 101.4, 99.1, 100.9).expect("a finite bar");
    /// assert_eq!(s.out_range().count, r0.count); // a peek commits nothing
    /// let updated = s.update(100.2, 101.4, 99.1, 100.9).expect("a finite bar");
    /// assert_eq!(s.out_range().beg_idx, r0.beg_idx);
    /// assert_eq!(s.out_range().count, r0.count + 1);
    /// assert_eq!(peeked, updated);
    /// ```
    #[doc(alias = "TA_CDLIDENTICAL3CROWS_Open")]
    pub fn cdlidentical3crows_open(&self, inOpen: &[f64], inHigh: &[f64], inLow: &[f64], inClose: &[f64], ) -> Result<(Cdlidentical3crowsStream, i32), RetCode> {
        self.cdlidentical3crows_open_internal(inOpen, inHigh, inLow, inClose, 0)
    }

    /// [`Core::cdlidentical3crows_open`] that also fills the output array(s) bit-identically to
    /// [`Core::CDLIDENTICAL3CROWS`] over `0..len` in the same single pass, and reports the range it
    /// wrote as the [`OutRange`] beside the handle.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] when an output slice holds fewer than `len - lookback`
    /// values — the batch tier's sizing rule, checked here as it is there (rule S5) —
    /// or when two of them are the same slice. Everything [`Core::cdlidentical3crows_open`] rejects
    /// is rejected here too.
    ///
    /// # Examples
    ///
    /// ```
    /// use ta_lib::Core;
    /// let open: Vec<f64> = (0..252)
    ///     .map(|i| 100.0 + 10.0 * (0.1 * i as f64 - 0.05).sin())
    ///     .collect();
    /// let high: Vec<f64> = (0..252).map(|i| 101.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    /// let low: Vec<f64> = (0..252).map(|i| 99.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    /// let close: Vec<f64> = (0..252)
    ///     .map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin() + 0.8 * (0.7 * i as f64).sin())
    ///     .collect();
    ///
    /// let core = Core::new();
    /// let mut batch_out = vec![0_i32; 252];
    /// let batch = core.CDLIDENTICAL3CROWS(0, open.len() - 1, &open, &high, &low, &close, &mut batch_out)?;
    ///
    /// let mut out = vec![0_i32; 252];
    /// let (_stream, filled) = core.cdlidentical3crows_open_and_fill(&open, &high, &low, &close, &mut out)?;
    ///
    /// assert_eq!(filled.beg_idx, batch.beg_idx);
    /// assert_eq!(filled.count, batch.count);
    /// assert_eq!(out[..filled.count], batch_out[..batch.count]);
    /// # Ok::<(), ta_lib::RetCode>(())
    /// ```
    #[doc(alias = "TA_CDLIDENTICAL3CROWS_OpenAndFill")]
    pub fn cdlidentical3crows_open_and_fill(
        &self, inOpen: &[f64], inHigh: &[f64], inLow: &[f64], inClose: &[f64], outInteger: &mut [i32],
    ) -> Result<(Cdlidentical3crowsStream, OutRange), RetCode> {
        if inOpen.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inOpen.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        let _guardLb = self.CDLIDENTICAL3CROWS_Lookback()?;
        if inHigh.len() != inOpen.len() || inLow.len() != inOpen.len() || inClose.len() != inOpen.len() {
            return Err(RetCode::BadParam);
        }
        let _guardOutLen = inOpen.len().saturating_sub(_guardLb);
        if outInteger.len() < _guardOutLen {
            return Err(RetCode::BadParam);
        }
        let mut outBegIdx: usize = 0;
        let mut outNBElement: usize = 0;
        let handle = self.cdlidentical3crows_open_and_fill_internal(inOpen, inHigh, inLow, inClose, 0, &mut outBegIdx, &mut outNBElement, outInteger)?;
        Ok((handle, OutRange { beg_idx: outBegIdx, count: outNBElement }))
    }

