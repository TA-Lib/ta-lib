thread_local! {
    /// `peek`'s reusable scratch handle (see `CDLIDENTICAL3CROWS_StreamState::restore_from`).
    /// Taken for the duration of the step and put back after, so a
    /// panicking step costs the scratch, never leaves it borrowed.
    static CDLIDENTICAL3CROWS_PEEK_SCRATCH: std::cell::Cell<Option<Box<CDLIDENTICAL3CROWS_Stream>>> =
        const { std::cell::Cell::new(None) };
}

#[allow(non_snake_case)]
#[allow(unused_variables)]
impl CDLIDENTICAL3CROWS_Stream {
    /// Commit one closed bar. Never allocates.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite (NaN or ±Inf).
    /// That check runs before anything is written, so the handle is left
    /// exactly as it was and the stream stays usable:
    /// skip the bar, or close and re-open on a clean history. This is the
    /// one place the streaming tier is stricter than the batch API, which
    /// computes on whatever it is given — a handle retains its state, so a
    /// single non-finite bar would poison every later value it produces.
    #[doc(alias = "TA_CDLIDENTICAL3CROWS_Update")]
    pub fn update(&mut self, inOpen: f64, inHigh: f64, inLow: f64, inClose: f64) -> Result<i32, RetCode> {
        if !inOpen.is_finite() || !inHigh.is_finite() || !inLow.is_finite() || !inClose.is_finite() {
            return Err(RetCode::BadParam);
        }
        let mut outInteger: i32 = 0_i32;
        Core::CDLIDENTICAL3CROWS_step_impl(&mut self.state, &self.cs_equal, &self.cs_shadow_very_short, inOpen, inHigh, inLow, inClose, &mut outInteger);
        if self.out.count < Core::MAX_INDEX {
            self.out.count += 1;
        }
        Ok(outInteger)
    }

    /// Commit `n` closed bars and write their `n` values, in one call —
    /// exactly `n` back-to-back [`Self::update`] calls, with one set of
    /// argument checks instead of `n`. `n` is `inOpen.len()`; the outputs must
    /// hold at least that many. Never allocates.
    ///
    /// [`Self::out_range`] counts what was committed, which is what makes the
    /// rejection below readable: there is no second out-parameter for it.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if the input slices differ in length, if an output
    /// is shorter than the bar count — neither commits anything — or if a bar
    /// is not finite. A non-finite bar `k` is rejected exactly as `update`
    /// rejects it: bars `0..k` stay committed and their values written, bar `k`
    /// and everything after it is not, and `out_range().count` has advanced by
    /// `k`.
    #[doc(alias = "TA_CDLIDENTICAL3CROWS_UpdateAndFill")]
    pub fn update_and_fill(&mut self, inOpen: &[f64], inHigh: &[f64], inLow: &[f64], inClose: &[f64], outInteger: &mut [i32]) -> Result<(), RetCode> {
        let barCount = inOpen.len();
        if inHigh.len() != inOpen.len() || inLow.len() != inOpen.len() || inClose.len() != inOpen.len() || outInteger.len() < barCount {
            return Err(RetCode::BadParam);
        }
        for i in 0..barCount {
            if !inOpen[i].is_finite() || !inHigh[i].is_finite() || !inLow[i].is_finite() || !inClose[i].is_finite() {
                return Err(RetCode::BadParam);
            }
            Core::CDLIDENTICAL3CROWS_step_impl(&mut self.state, &self.cs_equal, &self.cs_shadow_very_short, inOpen[i], inHigh[i], inLow[i], inClose[i], &mut outInteger[i]);
            if self.out.count < Core::MAX_INDEX {
                self.out.count += 1;
            }
        }
        Ok(())
    }

    /// Evaluate a forming bar without committing — bit-identical to what the
    /// next `update` with the same bar would return (it is the same code, run
    /// on a scratch copy of the state). Never writes the handle, so peeks may
    /// run concurrently with each other. The copy it runs on is held per thread and reused,
    /// so only the first peek of this function on a thread allocates.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite, exactly as
    /// `update` rejects it.
    #[doc(alias = "TA_CDLIDENTICAL3CROWS_Peek")]
    pub fn peek(&self, inOpen: f64, inHigh: f64, inLow: f64, inClose: f64) -> Result<i32, RetCode> {
        if !inOpen.is_finite() || !inHigh.is_finite() || !inLow.is_finite() || !inClose.is_finite() {
            return Err(RetCode::BadParam);
        }
        CDLIDENTICAL3CROWS_PEEK_SCRATCH.with(|cell| {
            let mut scratch = cell.take().unwrap_or_else(|| Box::new(self.clone()));
            scratch.restore_from(self);
            let value = scratch.update(inOpen, inHigh, inLow, inClose);
            cell.set(Some(scratch));
            value
        })
    }

    /// The bars this stream has produced a value for, in the input series'
    /// coordinates: `[beg_idx, beg_idx + count)`.
    ///
    /// It is what [`Core::CDLIDENTICAL3CROWS`] reports over the same bars: the opener sets it
    /// to `(lookback, historyLen - lookback)`, every accepted `update` adds one
    /// to the count, `peek` leaves it alone, and a clone carries it verbatim.
    /// A plain `Open` hands back only the last value, a subset of this range,
    /// because the caller chose not to take the fill.
    #[doc(alias = "TA_StreamOutRange")]
    pub fn out_range(&self) -> OutRange {
        self.out
    }
}

