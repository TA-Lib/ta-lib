    /// # References
    ///
    /// * J. Welles Wilder, *New Concepts in Technical Trading Systems*, Trend Research (ISBN
    ///   0894590278)
    #[doc(alias = "TA_ADX")]
    #[doc(alias = "AverageDirectionalMovementIndex")]
    #[doc(alias = "AverageDirectionalIndex")]
    pub fn ADX(
        &self,
        startIdx: usize,
        endIdx: usize,
        inHigh: &[f64],
        inLow: &[f64],
        inClose: &[f64],
        optInTimePeriod: i32,
        outReal: &mut [f64],
    ) -> Result<OutRange, RetCode> {
        if startIdx > Self::MAX_INDEX {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if endIdx > Self::MAX_INDEX || endIdx < startIdx {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        let _guardLb = self.ADX_Lookback(optInTimePeriod)?;
        let _guardStart = if startIdx > _guardLb { startIdx } else { _guardLb };
        if inHigh.len() < endIdx + 1 {
            return Err(RetCode::BadParam);
        }
        if inLow.len() < endIdx + 1 {
            return Err(RetCode::BadParam);
        }
        if inClose.len() < endIdx + 1 {
            return Err(RetCode::BadParam);
        }
        let _guardOutLen = if _guardStart > endIdx { 0 } else { endIdx - _guardStart + 1 };
        if outReal.len() < _guardOutLen {
            return Err(RetCode::BadParam);
        }
        let mut outBegIdx: usize = 0;
        let mut outNBElement: usize = 0;
        let retCode = self.ADX_Impl(
            startIdx,
            endIdx,
            inHigh,
            inLow,
            inClose,
            optInTimePeriod,
            &mut outBegIdx,
            &mut outNBElement,
            outReal,
        );
        match retCode {
            RetCode::Success => Ok(OutRange { beg_idx: outBegIdx, count: outNBElement }),
            e => Err(e),
        }
    }

