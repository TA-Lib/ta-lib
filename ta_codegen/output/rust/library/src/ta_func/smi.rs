/// Live SMI stream: one value per closed bar, bit-identical to [`Core::SMI`]
/// over the same series. Open with [`Core::smi_open`]; dropping the handle
/// closes the stream. Cloning it forks an independent stream.
///
/// [`Self::out_range`] reports the bars this handle has an output for.
#[must_use = "a stream does nothing unless updated; dropping it closes the stream"]
#[derive(Debug, Clone)]
#[doc(alias = "TA_SMI_Stream")]
pub struct SmiStream {
    state: SmiStreamState,
    /// The bars this handle has an output for — see [`Self::out_range`].
    out: OutRange,
}

#[derive(Debug, Clone)]
#[allow(non_snake_case, dead_code)]
struct SmiStreamState {
    optInTimePeriod: i32,
    optInFastPeriod: i32,
    optInSlowPeriod: i32,
    optInSignalPeriod: i32,
    kSlow: f64,
    kFast: f64,
    kSignal: f64,
    highest: f64,
    lowest: f64,
    emaSlowNum: f64,
    emaSlowDen: f64,
    emaFastNum: f64,
    emaFastDen: f64,
    prevSignal: f64,
    trailingIdx: i32,
    highestIdx: i32,
    lowestIdx: i32,
    i: i32,
    today: i32,
    xMask: i32,
    x_inHigh: Vec<f64>,
    x_inLow: Vec<f64>,
    x_inClose: Vec<f64>,
    cur_outSMI: f64,
    cur_outSMISignal: f64,
}

#[allow(unused_variables)]
#[allow(dead_code)]
#[allow(unused_mut)]
#[allow(unused_assignments)]
#[allow(unused_parens)]
impl Core {
    fn smi_step_impl(sp: &mut SmiStreamState, inHigh: f64, inLow: f64, inClose: f64, outSMI: &mut f64, outSMISignal: &mut f64) {
        let mut tmp: f64 = 0.0_f64;
        let mut num: f64 = 0.0_f64;
        let mut den: f64 = 0.0_f64;
        let mut halfDen: f64 = 0.0_f64;
        let mut smiValue: f64 = 0.0_f64;
        if sp.today >= 1073741824 {
            let rebaseShift: i32 = sp.trailingIdx & !sp.xMask;
            sp.today -= rebaseShift;
            sp.trailingIdx -= rebaseShift;
            sp.highestIdx -= rebaseShift;
            sp.i -= rebaseShift;
            sp.lowestIdx -= rebaseShift;
        }
        sp.x_inHigh[(sp.today & sp.xMask) as usize] = inHigh;
        sp.x_inLow[(sp.today & sp.xMask) as usize] = inLow;
        sp.x_inClose[(sp.today & sp.xMask) as usize] = inClose;
        // Set the lowest low
        tmp = sp.x_inLow[(sp.today & sp.xMask) as usize];
        if sp.lowestIdx < sp.trailingIdx {
            sp.lowestIdx = sp.trailingIdx;
            sp.lowest = sp.x_inLow[(sp.lowestIdx & sp.xMask) as usize];
            sp.i = sp.lowestIdx;
            while (({ sp.i += 1; sp.i }) as i32) <= sp.today {
                tmp = sp.x_inLow[(sp.i & sp.xMask) as usize];
                if tmp < sp.lowest {
                    sp.lowestIdx = sp.i;
                    sp.lowest = tmp;
                }
            }
        } else if tmp <= sp.lowest {
            sp.lowestIdx = sp.today;
            sp.lowest = tmp;
        }
        // Set the highest high
        tmp = sp.x_inHigh[(sp.today & sp.xMask) as usize];
        if sp.highestIdx < sp.trailingIdx {
            sp.highestIdx = sp.trailingIdx;
            sp.highest = sp.x_inHigh[(sp.highestIdx & sp.xMask) as usize];
            sp.i = sp.highestIdx;
            while (({ sp.i += 1; sp.i }) as i32) <= sp.today {
                tmp = sp.x_inHigh[(sp.i & sp.xMask) as usize];
                if tmp > sp.highest {
                    sp.highestIdx = sp.i;
                    sp.highest = tmp;
                }
            }
        } else if tmp >= sp.highest {
            sp.highestIdx = sp.today;
            sp.highest = tmp;
        }
        den = sp.highest - sp.lowest;
        num = sp.x_inClose[(sp.today & sp.xMask) as usize] - (sp.highest + sp.lowest) * 0.5;
        sp.emaSlowNum = (num - sp.emaSlowNum as f64).mul_add(sp.kSlow, sp.emaSlowNum);
        sp.emaSlowDen = (den - sp.emaSlowDen as f64).mul_add(sp.kSlow, sp.emaSlowDen);
        sp.emaFastNum = (sp.emaSlowNum - sp.emaFastNum as f64).mul_add(sp.kFast, sp.emaFastNum);
        sp.emaFastDen = (sp.emaSlowDen - sp.emaFastDen as f64).mul_add(sp.kFast, sp.emaFastDen);
        // The denominator is an EMA of an EMA of the high-low range: every term
        // is non-negative and every weight is positive, so it carries no
        // cancellation residue and is zero only when every range that reached it
        // was exactly zero -- 0/0, since a window of H == L bars makes num zero
        // too, reported as the neutral 0.0 by the CCI (#7) and IMI (#112)
        // convention. Test it exactly: the range carries the quote unit, so the
        // fixed TA_IS_ZERO band this used to be zeroed the oscillator for any
        // instrument quoted below it (issue #253). Issue #107's machine-flat
        // window is caught by the exact test as well, since the residue an
        // EMA leaves there is zero, not sub-epsilon.
        halfDen = 0.5 * sp.emaFastDen;
        if halfDen > 0.0 {
            smiValue = 100.0 * sp.emaFastNum / halfDen;
        } else {
            smiValue = 0.0;
        }
        sp.prevSignal = (smiValue - sp.prevSignal as f64).mul_add(sp.kSignal, sp.prevSignal);
        (*outSMI) = smiValue;
        (*outSMISignal) = sp.prevSignal;
        sp.trailingIdx = sp.trailingIdx + 1;
        sp.today = sp.today + 1;
        sp.cur_outSMI = (*outSMI);
        sp.cur_outSMISignal = (*outSMISignal);
    }

    /// The single whole-history transcription behind [`Core::smi_open_internal`]
    /// (stride 0, scalar sink) and [`Core::smi_open_and_fill`] (stride 1, caller slices).
    pub(crate) fn smi_open_impl(
        &self, inHigh: &[f64], inLow: &[f64], inClose: &[f64], startIdx: usize, mut optInTimePeriod: i32, mut optInFastPeriod: i32, mut optInSlowPeriod: i32, mut optInSignalPeriod: i32, outBegIdx: &mut usize, outNBElement: &mut usize, outSMI: &mut [f64], outSMISignal: &mut [f64], outStride: usize,
    ) -> Result<SmiStream, RetCode> {
        if inHigh.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inHigh.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        if ((optInTimePeriod) as i32) == (i32::MIN) {
            optInTimePeriod = 13;
        } else if (((optInTimePeriod) as i32) < 2) || (((optInTimePeriod) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        if ((optInFastPeriod) as i32) == (i32::MIN) {
            optInFastPeriod = 2;
        } else if (((optInFastPeriod) as i32) < 2) || (((optInFastPeriod) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        if ((optInSlowPeriod) as i32) == (i32::MIN) {
            optInSlowPeriod = 25;
        } else if (((optInSlowPeriod) as i32) < 2) || (((optInSlowPeriod) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        if ((optInSignalPeriod) as i32) == (i32::MIN) {
            optInSignalPeriod = 9;
        } else if (((optInSignalPeriod) as i32) < 2) || (((optInSignalPeriod) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        if inLow.len() != inHigh.len() || inClose.len() != inHigh.len() {
            return Err(RetCode::BadParam);
        }
        let historyLen: usize = inHigh.len();
        let endIdx: usize = historyLen - 1;
        let mut startIdx = startIdx;
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut kSlow: f64 = 0.0_f64;
        let mut kFast: f64 = 0.0_f64;
        let mut kSignal: f64 = 0.0_f64;
        let mut highest: f64 = 0.0_f64;
        let mut lowest: f64 = 0.0_f64;
        let mut tmp: f64 = 0.0_f64;
        let mut emaSlowNum: f64 = 0.0_f64;
        let mut emaSlowDen: f64 = 0.0_f64;
        let mut emaFastNum: f64 = 0.0_f64;
        let mut emaFastDen: f64 = 0.0_f64;
        let mut sumSlowNum: f64 = 0.0_f64;
        let mut sumSlowDen: f64 = 0.0_f64;
        let mut sumFastNum: f64 = 0.0_f64;
        let mut sumFastDen: f64 = 0.0_f64;
        let mut sumSignal: f64 = 0.0_f64;
        let mut num: f64 = 0.0_f64;
        let mut den: f64 = 0.0_f64;
        let mut halfDen: f64 = 0.0_f64;
        let mut smiValue: f64 = 0.0_f64;
        let mut prevSignal: f64 = 0.0_f64;
        let mut lookbackTotal: usize = 0_usize;
        let mut lookbackSlow: usize = 0_usize;
        let mut lookbackFast: usize = 0_usize;
        let mut today: usize = 0_usize;
        let mut trailingIdx: usize = 0_usize;
        let mut highestIdx: i32 = 0_i32;
        let mut lowestIdx: i32 = 0_i32;
        let mut i: usize = 0_usize;
        let mut outIdx: usize = 0_usize;
        let mut nBar: usize = 0_usize;
        let mut nFast: usize = 0_usize;
        let mut nSignal: usize = 0_usize;
        lookbackTotal = self.SMI_Lookback(optInTimePeriod, optInFastPeriod, optInSlowPeriod, optInSignalPeriod)?;
        if startIdx < lookbackTotal {
            startIdx = lookbackTotal;
        }
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        (*outBegIdx) = startIdx;
        // Blau's pipeline in one pass. A composed form is not available: the
        // streaming producer model carries exactly one intermediate series
        // (streaming.rs:2076) and SMI has two, the numerator and the denominator,
        // which must be smoothed separately before they are divided.
        //
        // Each of the three stages seeds the way ema.c does -- a simple average of
        // that stage's first 'period' inputs -- so the result is bit-identical to
        // TA_MAX + TA_MIN followed by four TA_EMA calls. The stage boundaries below
        // are the callee LOOKBACKS, not (period-1), so that a warm
        // TA_SetUnstablePeriod(TA_FUNC_UNST_EMA) folds in: each stage then seeds
        // from the values its predecessor would have published, exactly as the
        // composed form does. The seed sums accumulate from 0.0 in production
        // order; do not reorder or fuse them (0.0+x is not x for x=-0.0).
        //
        // TA_GetCompatibility() is deliberately NOT consulted, for the reason
        // spelled out in efi.c: ema.c's TA_COMPATIBILITY_METASTOCK seeding arm is
        // preserved for the functions that already shipped with it and dropped from
        // new ones, and it is not reachable at all from the Rust, Java and C# APIs.
        // The seeding choice itself is measured in docs/studies/ema-seeding/README.md.
        kSlow = 2.0 / ((optInSlowPeriod + 1) as f64);
        kFast = 2.0 / ((optInFastPeriod + 1) as f64);
        kSignal = 2.0 / ((optInSignalPeriod + 1) as f64);
        lookbackSlow = self.EMA_Lookback(optInSlowPeriod)?;
        lookbackFast = self.EMA_Lookback(optInFastPeriod)?;
        emaSlowNum = 0.0;
        emaSlowDen = 0.0;
        emaFastNum = 0.0;
        emaFastDen = 0.0;
        prevSignal = 0.0;
        smiValue = 0.0;
        sumSlowNum = 0.0;
        sumSlowDen = 0.0;
        sumFastNum = 0.0;
        sumFastDen = 0.0;
        sumSignal = 0.0;
        highest = 0.0;
        lowest = 0.0;
        highestIdx = 0 - 1;
        lowestIdx = 0 - 1;
        // The first bar carrying a full high/low window.
        trailingIdx = startIdx - lookbackTotal;
        today = trailingIdx + (((optInTimePeriod - 1)) as usize);
        nBar = 0;
        // Warm-up. Runs through startIdx inclusive: the last pass here is the one
        // that completes the signal seed, so it produces the first output pair.
        while today <= startIdx {
            // Set the lowest low
            tmp = inLow[today];
            if lowestIdx < ((trailingIdx) as i32) {
                lowestIdx = (trailingIdx) as i32;
                lowest = inLow[(lowestIdx) as usize];
                i = (lowestIdx) as usize;
                while { i += 1; i } <= today {
                    tmp = inLow[i];
                    if tmp < lowest {
                        lowestIdx = (i) as i32;
                        lowest = tmp;
                    }
                }
            } else if tmp <= lowest {
                lowestIdx = (today) as i32;
                lowest = tmp;
            }
            // Set the highest high
            tmp = inHigh[today];
            if highestIdx < ((trailingIdx) as i32) {
                highestIdx = (trailingIdx) as i32;
                highest = inHigh[(highestIdx) as usize];
                i = (highestIdx) as usize;
                while { i += 1; i } <= today {
                    tmp = inHigh[i];
                    if tmp > highest {
                        highestIdx = (i) as i32;
                        highest = tmp;
                    }
                }
            } else if tmp >= highest {
                highestIdx = (today) as i32;
                highest = tmp;
            }
            den = highest - lowest;
            num = inClose[today] - (highest + lowest) * 0.5;
            // Stage 1: the slow EMA, over the raw momentum.
            if nBar < ((optInSlowPeriod) as usize) {
                sumSlowNum = sumSlowNum + num;
                sumSlowDen = sumSlowDen + den;
                if nBar == ((optInSlowPeriod - 1) as usize) {
                    emaSlowNum = sumSlowNum / ((optInSlowPeriod) as f64);
                    emaSlowDen = sumSlowDen / ((optInSlowPeriod) as f64);
                }
            } else {
                emaSlowNum = (num - emaSlowNum as f64).mul_add(kSlow, emaSlowNum);
                emaSlowDen = (den - emaSlowDen as f64).mul_add(kSlow, emaSlowDen);
            }
            // Stage 2: the fast EMA, over what stage 1 publishes.
            //
            // The stage counters are compared BEFORE they are subtracted, never
            // after. Writing this as `nFast = nBar - lookbackSlow; if( nFast >= 0 )`
            // is correct in C, where the counters are signed, and broken everywhere
            // else: the Rust backend renders them as `usize`, so the subtraction
            // underflows for the first lookbackSlow bars -- a panic in a debug build
            // and a wrap in release. It would also be invisible to the cross-language
            // gate, which runs release servers at unstable period 0, where the branch
            // the wrap wrongly takes happens to be a no-op because both accumulators
            // are still 0.0.
            if nBar >= lookbackSlow {
                nFast = nBar - lookbackSlow;
                if nFast < ((optInFastPeriod) as usize) {
                    sumFastNum = sumFastNum + emaSlowNum;
                    sumFastDen = sumFastDen + emaSlowDen;
                    if nFast == ((optInFastPeriod - 1) as usize) {
                        emaFastNum = sumFastNum / ((optInFastPeriod) as f64);
                        emaFastDen = sumFastDen / ((optInFastPeriod) as f64);
                    }
                } else {
                    emaFastNum = (emaSlowNum - emaFastNum as f64).mul_add(kFast, emaFastNum);
                    emaFastDen = (emaSlowDen - emaFastDen as f64).mul_add(kFast, emaFastDen);
                }
            }
            // Stage 3: the SMI line, then the signal EMA over it.
            if nBar >= lookbackSlow + lookbackFast {
                nSignal = nBar - lookbackSlow - lookbackFast;
                halfDen = 0.5 * emaFastDen;
                if halfDen > 0.0 {
                    smiValue = 100.0 * emaFastNum / halfDen;
                } else {
                    smiValue = 0.0;
                }
                if nSignal < ((optInSignalPeriod) as usize) {
                    sumSignal = sumSignal + smiValue;
                    if nSignal == ((optInSignalPeriod - 1) as usize) {
                        prevSignal = sumSignal / ((optInSignalPeriod) as f64);
                    }
                } else {
                    prevSignal = (smiValue - prevSignal as f64).mul_add(kSignal, prevSignal);
                }
            }
            nBar = nBar + 1;
            trailingIdx = trailingIdx + 1;
            today = today + 1;
        }
        outSMI[(0 * outStride) as usize] = smiValue;
        outSMISignal[(0 * outStride) as usize] = prevSignal;
        outIdx = 1;
        // Stable zone. Every stage is a pure recursion from here on.
        while today <= endIdx {
            // Set the lowest low
            tmp = inLow[today];
            if lowestIdx < ((trailingIdx) as i32) {
                lowestIdx = (trailingIdx) as i32;
                lowest = inLow[(lowestIdx) as usize];
                i = (lowestIdx) as usize;
                while { i += 1; i } <= today {
                    tmp = inLow[i];
                    if tmp < lowest {
                        lowestIdx = (i) as i32;
                        lowest = tmp;
                    }
                }
            } else if tmp <= lowest {
                lowestIdx = (today) as i32;
                lowest = tmp;
            }
            // Set the highest high
            tmp = inHigh[today];
            if highestIdx < ((trailingIdx) as i32) {
                highestIdx = (trailingIdx) as i32;
                highest = inHigh[(highestIdx) as usize];
                i = (highestIdx) as usize;
                while { i += 1; i } <= today {
                    tmp = inHigh[i];
                    if tmp > highest {
                        highestIdx = (i) as i32;
                        highest = tmp;
                    }
                }
            } else if tmp >= highest {
                highestIdx = (today) as i32;
                highest = tmp;
            }
            den = highest - lowest;
            num = inClose[today] - (highest + lowest) * 0.5;
            emaSlowNum = (num - emaSlowNum as f64).mul_add(kSlow, emaSlowNum);
            emaSlowDen = (den - emaSlowDen as f64).mul_add(kSlow, emaSlowDen);
            emaFastNum = (emaSlowNum - emaFastNum as f64).mul_add(kFast, emaFastNum);
            emaFastDen = (emaSlowDen - emaFastDen as f64).mul_add(kFast, emaFastDen);
            // The denominator is an EMA of an EMA of the high-low range: every term
            // is non-negative and every weight is positive, so it carries no
            // cancellation residue and is zero only when every range that reached it
            // was exactly zero -- 0/0, since a window of H == L bars makes num zero
            // too, reported as the neutral 0.0 by the CCI (#7) and IMI (#112)
            // convention. Test it exactly: the range carries the quote unit, so the
            // fixed TA_IS_ZERO band this used to be zeroed the oscillator for any
            // instrument quoted below it (issue #253). Issue #107's machine-flat
            // window is caught by the exact test as well, since the residue an
            // EMA leaves there is zero, not sub-epsilon.
            halfDen = 0.5 * emaFastDen;
            if halfDen > 0.0 {
                smiValue = 100.0 * emaFastNum / halfDen;
            } else {
                smiValue = 0.0;
            }
            prevSignal = (smiValue - prevSignal as f64).mul_add(kSignal, prevSignal);
            outSMI[(outIdx * outStride) as usize] = smiValue;
            outSMISignal[(outIdx * outStride) as usize] = prevSignal;
            outIdx = outIdx + 1;
            trailingIdx = trailingIdx + 1;
            today = today + 1;
        }
        (*outNBElement) = outIdx;

        // Capture the live batch state into the handle.
        let capX: i64 = (today as i64) - (trailingIdx as i64) + 1;
        if capX < 1 || capX > historyLen as i64 {
            return Err(RetCode::InternalError);
        }
        let mut physX: i64 = 1;
        while physX < capX {
            physX <<= 1;
        }
        let mut x_inHigh: Vec<f64> = vec![0.0_f64; physX as usize];
        let mut x_inLow: Vec<f64> = vec![0.0_f64; physX as usize];
        let mut x_inClose: Vec<f64> = vec![0.0_f64; physX as usize];
        {
            let mut fillJ: usize = historyLen - capX as usize;
            while fillJ < historyLen {
                x_inHigh[fillJ & (physX as usize - 1)] = inHigh[fillJ];
                x_inLow[fillJ & (physX as usize - 1)] = inLow[fillJ];
                x_inClose[fillJ & (physX as usize - 1)] = inClose[fillJ];
                fillJ += 1;
            }
        }
        let state = SmiStreamState {
            optInTimePeriod,
            optInFastPeriod,
            optInSlowPeriod,
            optInSignalPeriod,
            kSlow,
            kFast,
            kSignal,
            highest,
            lowest,
            emaSlowNum,
            emaSlowDen,
            emaFastNum,
            emaFastDen,
            prevSignal,
            trailingIdx: (trailingIdx) as i32,
            highestIdx: (highestIdx) as i32,
            lowestIdx: (lowestIdx) as i32,
            i: (i) as i32,
            today: (today) as i32,
            cur_outSMI: outSMI[(*outNBElement - 1) * outStride],
            cur_outSMISignal: outSMISignal[(*outNBElement - 1) * outStride],
            xMask: (physX - 1) as i32,
            x_inHigh,
            x_inLow,
            x_inClose,
        };
        Ok(SmiStream { state, out: OutRange { beg_idx: *outBegIdx, count: *outNBElement } })
    }

    /// Internal startIdx-anchored open behind [`Core::smi_open`] (composition seam).
    pub(crate) fn smi_open_internal(
        &self, inHigh: &[f64], inLow: &[f64], inClose: &[f64], startIdx: usize, mut optInTimePeriod: i32, mut optInFastPeriod: i32, mut optInSlowPeriod: i32, mut optInSignalPeriod: i32,
    ) -> Result<(SmiStream, (f64, f64)), RetCode> {
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut sink_outSMI = [0.0_f64; 1];
        let mut sink_outSMISignal = [0.0_f64; 1];
        let handle = self.smi_open_impl(inHigh, inLow, inClose, startIdx, optInTimePeriod, optInFastPeriod, optInSlowPeriod, optInSignalPeriod, &mut dummyBegIdx, &mut dummyNBElement, &mut sink_outSMI, &mut sink_outSMISignal, 0)?;
        Ok((handle, (sink_outSMI[0], sink_outSMISignal[0])))
    }

    /// Open a live SMI stream over the warm-up history; returns the handle and
    /// the value at the last history bar — bit-identical to [`Core::SMI`] at that bar.
    ///
    /// # Errors
    ///
    /// [`RetCode::InsufficientHistory`] when the history holds fewer than
    /// `lookback + 1` bars — the one failure here worth retrying, since another
    /// bar fixes it. [`RetCode::OutOfRangeStartIndex`] when the history is empty.
    /// [`RetCode::BadParam`] when a parameter is out of range or the input
    /// lengths differ.
    ///
    /// ```
    /// use ta_lib::Core;
    /// let high: Vec<f64> = (0..252).map(|i| 101.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    /// let low: Vec<f64> = (0..252).map(|i| 99.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    /// let close: Vec<f64> = (0..252)
    ///     .map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin() + 0.8 * (0.7 * i as f64).sin())
    ///     .collect();
    ///
    /// let core = Core::new();
    /// let (mut s, _last) = core.smi_open(&high, &low, &close, 13, 2, 25, 9).expect("enough history");
    /// let r0 = s.out_range();
    /// let peeked = s.peek(101.4, 99.1, 100.9).expect("a finite bar");
    /// assert_eq!(s.out_range().count, r0.count); // a peek commits nothing
    /// let updated = s.update(101.4, 99.1, 100.9).expect("a finite bar");
    /// assert_eq!(s.out_range().beg_idx, r0.beg_idx);
    /// assert_eq!(s.out_range().count, r0.count + 1);
    /// assert_eq!(peeked.0.to_bits(), updated.0.to_bits());
    /// assert_eq!(peeked.1.to_bits(), updated.1.to_bits());
    /// ```
    #[doc(alias = "TA_SMI_Open")]
    pub fn smi_open(&self, inHigh: &[f64], inLow: &[f64], inClose: &[f64], optInTimePeriod: i32, optInFastPeriod: i32, optInSlowPeriod: i32, optInSignalPeriod: i32) -> Result<(SmiStream, (f64, f64)), RetCode> {
        self.smi_open_internal(inHigh, inLow, inClose, 0, optInTimePeriod, optInFastPeriod, optInSlowPeriod, optInSignalPeriod)
    }

    /// [`Core::smi_open`] that also fills the output array(s) bit-identically to
    /// [`Core::SMI`] over `0..len` in the same single pass, and reports the range it
    /// wrote as the [`OutRange`] beside the handle.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] when an output slice holds fewer than `len - lookback`
    /// values — the batch tier's sizing rule, checked here as it is there (rule S5) —
    /// or when two of them are the same slice. Everything [`Core::smi_open`] rejects
    /// is rejected here too.
    ///
    /// # Examples
    ///
    /// ```
    /// use ta_lib::Core;
    /// let high: Vec<f64> = (0..252).map(|i| 101.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    /// let low: Vec<f64> = (0..252).map(|i| 99.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    /// let close: Vec<f64> = (0..252)
    ///     .map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin() + 0.8 * (0.7 * i as f64).sin())
    ///     .collect();
    ///
    /// let core = Core::new();
    /// let mut batch_smi = vec![0.0; 252];
    /// let mut batch_smi_signal = vec![0.0; 252];
    /// let batch = core.SMI(0, high.len() - 1, &high, &low, &close, 13, 2, 25, 9, &mut batch_smi, &mut batch_smi_signal)?;
    ///
    /// let mut smi = vec![0.0; 252];
    /// let mut smi_signal = vec![0.0; 252];
    /// let (_stream, filled) = core.smi_open_and_fill(&high, &low, &close, 13, 2, 25, 9, &mut smi, &mut smi_signal)?;
    ///
    /// assert_eq!(filled.beg_idx, batch.beg_idx);
    /// assert_eq!(filled.count, batch.count);
    /// assert!(smi[..filled.count].iter().zip(&batch_smi[..batch.count])
    ///     .all(|(a, b)| a.to_bits() == b.to_bits()));
    /// assert!(smi_signal[..filled.count].iter().zip(&batch_smi_signal[..batch.count])
    ///     .all(|(a, b)| a.to_bits() == b.to_bits()));
    /// # Ok::<(), ta_lib::RetCode>(())
    /// ```
    #[doc(alias = "TA_SMI_OpenAndFill")]
    pub fn smi_open_and_fill(
        &self, inHigh: &[f64], inLow: &[f64], inClose: &[f64], mut optInTimePeriod: i32, mut optInFastPeriod: i32, mut optInSlowPeriod: i32, mut optInSignalPeriod: i32, outSMI: &mut [f64], outSMISignal: &mut [f64],
    ) -> Result<(SmiStream, OutRange), RetCode> {
        if inHigh.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inHigh.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        let _guardLb = self.SMI_Lookback(optInTimePeriod, optInFastPeriod, optInSlowPeriod, optInSignalPeriod)?;
        if inLow.len() != inHigh.len() || inClose.len() != inHigh.len() {
            return Err(RetCode::BadParam);
        }
        let _guardOutLen = inHigh.len().saturating_sub(_guardLb);
        if outSMI.len() < _guardOutLen {
            return Err(RetCode::BadParam);
        }
        if outSMISignal.len() < _guardOutLen {
            return Err(RetCode::BadParam);
        }
        if !outSMI.is_empty() && !outSMISignal.is_empty() && outSMI.as_ptr() == outSMISignal.as_ptr() {
            return Err(RetCode::BadParam);
        }
        let mut outBegIdx: usize = 0;
        let mut outNBElement: usize = 0;
        let handle = self.smi_open_and_fill_internal(inHigh, inLow, inClose, 0, optInTimePeriod, optInFastPeriod, optInSlowPeriod, optInSignalPeriod, &mut outBegIdx, &mut outNBElement, outSMI, outSMISignal)?;
        Ok((handle, OutRange { beg_idx: outBegIdx, count: outNBElement }))
    }

    /// [`Core::smi_open_and_fill`] anchored at `startIdx` — the composed-open
    /// fusion seam (issue #192), not a public entry point.
    pub(crate) fn smi_open_and_fill_internal(
        &self, inHigh: &[f64], inLow: &[f64], inClose: &[f64], startIdx: usize, mut optInTimePeriod: i32, mut optInFastPeriod: i32, mut optInSlowPeriod: i32, mut optInSignalPeriod: i32, outBegIdx: &mut usize, outNBElement: &mut usize, outSMI: &mut [f64], outSMISignal: &mut [f64],
    ) -> Result<SmiStream, RetCode> {
        self.smi_open_impl(inHigh, inLow, inClose, startIdx, optInTimePeriod, optInFastPeriod, optInSlowPeriod, optInSignalPeriod, outBegIdx, outNBElement, outSMI, outSMISignal, 1)
    }

}

#[allow(non_snake_case)]
#[allow(unused_variables)]
#[allow(unused_mut)]
#[allow(unused_assignments)]
#[allow(unused_parens)]
impl SmiStream {
    /// Commit one closed bar. Never allocates.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite (NaN or ±Inf).
    /// That check runs before anything is written, so the handle's state is
    /// left exactly as it was and the stream stays usable: skip the bar, or
    /// close and re-open on a clean history. This is the one place the
    /// streaming tier is stricter than the batch API, which computes on
    /// whatever it is given — a handle retains its state, so a single
    /// non-finite bar would poison every later value it produces.
    ///
    /// [`Self::out_range`] counts the rejected bar all the same: it happened,
    /// so two handles fed the same series stay positionally aligned even when
    /// one rejects a bar the other accepts.
    #[doc(alias = "TA_SMI_Update")]
    pub fn update(&mut self, inHigh: f64, inLow: f64, inClose: f64) -> Result<(f64, f64), RetCode> {
        if !inHigh.is_finite() || !inLow.is_finite() || !inClose.is_finite() {
            if self.out.count < Core::MAX_INDEX {
                self.out.count += 1;
            }
            return Err(RetCode::BadParam);
        }
        let mut outSMI: f64 = 0.0_f64;
        let mut outSMISignal: f64 = 0.0_f64;
        Core::smi_step_impl(&mut self.state, inHigh, inLow, inClose, &mut outSMI, &mut outSMISignal);
        if self.out.count < Core::MAX_INDEX {
            self.out.count += 1;
        }
        Ok((outSMI, outSMISignal))
    }

    /// Commit `n` closed bars and write their `n` values, in one call —
    /// exactly `n` back-to-back [`Self::update`] calls, with one set of
    /// argument checks instead of `n`. `n` is `inHigh.len()`; the outputs must
    /// hold at least that many. Never allocates.
    ///
    /// [`Self::out_range`] counts what this call took in, which is what makes the
    /// rejection below readable: there is no second out-parameter for it.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if the input slices differ in length, if an output
    /// is shorter than the bar count — neither commits anything — or if a bar
    /// is not finite. A non-finite bar `k` is rejected exactly as `update`
    /// rejects it: bars `0..k` stay committed and their values written, bar `k`
    /// and everything after it is not, and `out_range().count` has advanced by
    /// `k + 1` — the committed bars, plus the rejected one, which is counted
    /// but never written.
    #[doc(alias = "TA_SMI_UpdateAndFill")]
    pub fn update_and_fill(&mut self, inHigh: &[f64], inLow: &[f64], inClose: &[f64], outSMI: &mut [f64], outSMISignal: &mut [f64]) -> Result<(), RetCode> {
        let barCount = inHigh.len();
        if inLow.len() != inHigh.len() || inClose.len() != inHigh.len() || outSMI.len() < barCount || outSMISignal.len() < barCount {
            return Err(RetCode::BadParam);
        }
        for i in 0..barCount {
            if !inHigh[i].is_finite() || !inLow[i].is_finite() || !inClose[i].is_finite() {
                if self.out.count < Core::MAX_INDEX {
                    self.out.count += 1;
                }
                return Err(RetCode::BadParam);
            }
            Core::smi_step_impl(&mut self.state, inHigh[i], inLow[i], inClose[i], &mut outSMI[i], &mut outSMISignal[i]);
            if self.out.count < Core::MAX_INDEX {
                self.out.count += 1;
            }
        }
        Ok(())
    }

    /// Evaluate a forming bar without committing — bit-identical to what the
    /// next `update` with the same bar would return: the same transition,
    /// rewritten so every store it would make lives in a local instead. It
    /// allocates nothing and copies no buffer, so its cost does not grow with
    /// the period, and it writes no part of the handle — peeks may run
    /// concurrently with each other.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite, on the same test
    /// `update` applies — but a rejected peek changes nothing at all, where a
    /// rejected `update` still counts the bar in [`Self::out_range`].
    #[doc(alias = "TA_SMI_Peek")]
    pub fn peek(&self, inHigh: f64, inLow: f64, inClose: f64) -> Result<(f64, f64), RetCode> {
        if !inHigh.is_finite() || !inLow.is_finite() || !inClose.is_finite() {
            return Err(RetCode::BadParam);
        }
        let mut outSMI: f64 = 0.0_f64;
        let mut outSMISignal: f64 = 0.0_f64;
        {
            let sp = &self.state;
            let outSMI = &mut outSMI;
            let outSMISignal = &mut outSMISignal;
            let mut tmp: f64 = 0.0_f64;
            let mut num: f64 = 0.0_f64;
            let mut den: f64 = 0.0_f64;
            let mut halfDen: f64 = 0.0_f64;
            let mut smiValue: f64 = 0.0_f64;
            let mut cur_outSMI = sp.cur_outSMI;
            let mut cur_outSMISignal = sp.cur_outSMISignal;
            let mut emaFastDen = sp.emaFastDen;
            let mut emaFastNum = sp.emaFastNum;
            let mut emaSlowDen = sp.emaSlowDen;
            let mut emaSlowNum = sp.emaSlowNum;
            let mut highest = sp.highest;
            let mut highestIdx = sp.highestIdx;
            let mut i = sp.i;
            let mut lowest = sp.lowest;
            let mut lowestIdx = sp.lowestIdx;
            let mut prevSignal = sp.prevSignal;
            let mut today = sp.today;
            let mut trailingIdx = sp.trailingIdx;
            let mut pkSlot0: usize = usize::MAX;
            let mut pkVal0: f64 = 0.0_f64;
            let mut pkSlot1: usize = usize::MAX;
            let mut pkVal1: f64 = 0.0_f64;
            let mut pkSlot2: usize = usize::MAX;
            let mut pkVal2: f64 = 0.0_f64;
            if today >= 1073741824 {
                let rebaseShift: i32 = trailingIdx & !sp.xMask;
                today -= rebaseShift;
                trailingIdx -= rebaseShift;
                highestIdx -= rebaseShift;
                i -= rebaseShift;
                lowestIdx -= rebaseShift;
            }
            pkSlot0 = (today & sp.xMask) as usize;
            pkVal0 = inHigh;
            pkSlot1 = (today & sp.xMask) as usize;
            pkVal1 = inLow;
            pkSlot2 = (today & sp.xMask) as usize;
            pkVal2 = inClose;
            // Set the lowest low
            tmp = (if ((today & sp.xMask) as usize) != pkSlot1 { sp.x_inLow[(today & sp.xMask) as usize] } else { pkVal1 });
            if lowestIdx < trailingIdx {
                lowestIdx = trailingIdx;
                lowest = (if ((lowestIdx & sp.xMask) as usize) != pkSlot1 { sp.x_inLow[(lowestIdx & sp.xMask) as usize] } else { pkVal1 });
                i = lowestIdx;
                while (({ i += 1; i }) as i32) <= today {
                    tmp = (if ((i & sp.xMask) as usize) != pkSlot1 { sp.x_inLow[(i & sp.xMask) as usize] } else { pkVal1 });
                    if tmp < lowest {
                        lowestIdx = i;
                        lowest = tmp;
                    }
                }
            } else if tmp <= lowest {
                lowestIdx = today;
                lowest = tmp;
            }
            // Set the highest high
            tmp = (if ((today & sp.xMask) as usize) != pkSlot0 { sp.x_inHigh[(today & sp.xMask) as usize] } else { pkVal0 });
            if highestIdx < trailingIdx {
                highestIdx = trailingIdx;
                highest = (if ((highestIdx & sp.xMask) as usize) != pkSlot0 { sp.x_inHigh[(highestIdx & sp.xMask) as usize] } else { pkVal0 });
                i = highestIdx;
                while (({ i += 1; i }) as i32) <= today {
                    tmp = (if ((i & sp.xMask) as usize) != pkSlot0 { sp.x_inHigh[(i & sp.xMask) as usize] } else { pkVal0 });
                    if tmp > highest {
                        highestIdx = i;
                        highest = tmp;
                    }
                }
            } else if tmp >= highest {
                highestIdx = today;
                highest = tmp;
            }
            den = highest - lowest;
            num = (if ((today & sp.xMask) as usize) != pkSlot2 { sp.x_inClose[(today & sp.xMask) as usize] } else { pkVal2 }) - (highest + lowest) * 0.5;
            emaSlowNum = (num - emaSlowNum as f64).mul_add(sp.kSlow, emaSlowNum);
            emaSlowDen = (den - emaSlowDen as f64).mul_add(sp.kSlow, emaSlowDen);
            emaFastNum = (emaSlowNum - emaFastNum as f64).mul_add(sp.kFast, emaFastNum);
            emaFastDen = (emaSlowDen - emaFastDen as f64).mul_add(sp.kFast, emaFastDen);
            // The denominator is an EMA of an EMA of the high-low range: every term
            // is non-negative and every weight is positive, so it carries no
            // cancellation residue and is zero only when every range that reached it
            // was exactly zero -- 0/0, since a window of H == L bars makes num zero
            // too, reported as the neutral 0.0 by the CCI (#7) and IMI (#112)
            // convention. Test it exactly: the range carries the quote unit, so the
            // fixed TA_IS_ZERO band this used to be zeroed the oscillator for any
            // instrument quoted below it (issue #253). Issue #107's machine-flat
            // window is caught by the exact test as well, since the residue an
            // EMA leaves there is zero, not sub-epsilon.
            halfDen = 0.5 * emaFastDen;
            if halfDen > 0.0 {
                smiValue = 100.0 * emaFastNum / halfDen;
            } else {
                smiValue = 0.0;
            }
            prevSignal = (smiValue - prevSignal as f64).mul_add(sp.kSignal, prevSignal);
            (*outSMI) = smiValue;
            (*outSMISignal) = prevSignal;
            trailingIdx = trailingIdx + 1;
            today = today + 1;
            cur_outSMI = (*outSMI);
            cur_outSMISignal = (*outSMISignal);
        }
        Ok((outSMI, outSMISignal))
    }

    /// The value(s) at the last bar the stream counted — the bar
    /// [`Self::out_range`] ends on — without recomputing. Seeded by the opener,
    /// refreshed by every accepted `update` and `update_and_fill`, and left
    /// alone by `peek`.
    ///
    /// A clone carries them verbatim, so a forked handle can be asked its
    /// current value without committing a bar to find out.
    #[must_use]
    #[doc(alias = "TA_SMI_Value")]
    pub fn value(&self) -> (f64, f64) {
        (self.state.cur_outSMI, self.state.cur_outSMISignal)
    }

    /// The bars this stream has an output for, in the input series'
    /// coordinates: `[beg_idx, beg_idx + count)`.
    ///
    /// It is what [`Core::SMI`] reports over the same bars: the opener sets it
    /// to `(lookback, historyLen - lookback)`, every `update` adds one to the
    /// count — a bar rejected for being non-finite included, because it still
    /// happened — `peek` leaves it alone, and a clone carries it verbatim.
    /// A plain `Open` hands back only the last value, a subset of this range,
    /// because the caller chose not to take the fill.
    #[doc(alias = "TA_StreamOutRange")]
    pub fn out_range(&self) -> OutRange {
        self.out
    }
}

