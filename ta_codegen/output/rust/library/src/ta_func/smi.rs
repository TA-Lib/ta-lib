    /// separately with two exponential averages before dividing, which is what buys the low-lag,
    /// smooth-contoured curve. The result runs -100 to +100 rather than 0 to 100, so the zero line
    /// is the reference: positive means the close is above the midpoint of its range, negative
    /// below. Extreme readings mark overbought and oversold conditions, and crossings of the signal
