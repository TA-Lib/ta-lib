    fn adr_step_impl(sp: &mut AdrStreamState, inHigh: f64, inLow: f64, outReal: &mut f64) {
        let mut tempReal: f64 = 0.0_f64;
        if sp.ringCap_trailingIdx == 0 {
            sp.ring_trailingIdx_derived[0] = (inHigh - inLow) as f64;
        }
        sp.periodTotal += (inHigh - inLow) as f64;
        tempReal = sp.periodTotal;
        sp.periodTotal -= sp.ring_trailingIdx_derived[sp.ringPos_trailingIdx];
        (*outReal) = tempReal / (sp.optInTimePeriod as f64);
        sp.cur_outReal = (*outReal);
        sp.ring_trailingIdx_derived[sp.ringPos_trailingIdx] = (inHigh - inLow) as f64;
        sp.ringPos_trailingIdx = sp.ringPos_trailingIdx + 1;
        if sp.ringPos_trailingIdx >= sp.ringCap_trailingIdx {
            sp.ringPos_trailingIdx = 0;
        }
    }

