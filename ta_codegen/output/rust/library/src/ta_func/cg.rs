    /// assert!(out[..out_range.count].iter().all(|v| v.is_finite()));
    /// # Ok::<(), ta_lib::RetCode>(())
    /// ```
    ///
    /// # See also
    ///
    /// [`WMA`](Core::wma) · [`MEDPRICE`](Core::medprice) · [`CTI`](Core::cti)
    ///
    /// # References
    ///
    /// * John F. Ehlers, "The CG Oscillator", MESA Software, [author's
    ///   PDF](https://mesasoftware.com/papers/TheCGOscillator.pdf); published as "The Center Of
