    /// John Ehlers' Center of Gravity oscillator: the balance point of the last `optInTimePeriod`
    /// values, each weighted by its value and placed at its position counting back from the current
    /// bar, which is position 1, negated so that it rises with price. It is smooth and has
    /// essentially no lag. Ehlers reads turning points from it and trades its crossings with a copy
    /// of itself delayed by one bar. For a positive series it stays between -optInTimePeriod and
