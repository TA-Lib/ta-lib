#[allow(non_snake_case)]
#[allow(unused_variables)]
#[allow(unused_mut)]
#[allow(unused_assignments)]
#[allow(unused_parens)]
impl CdlclosingmarubozuStream {
    /// Commit one closed bar. Never allocates.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite (NaN or ±Inf).
    /// That check runs before anything is written, so the handle's state is
    /// left exactly as it was and the stream stays usable: skip the bar, or
    /// close and re-open on a clean history. This is the one place the
    /// streaming tier is stricter than the batch API, which computes on
    /// whatever it is given — a handle retains its state, so a single
    /// non-finite bar would poison every later value it produces.
    ///
    /// [`Self::out_range`] counts the rejected bar all the same: it happened,
    /// so two handles fed the same series stay positionally aligned even when
    /// one rejects a bar the other accepts.
    #[doc(alias = "TA_CDLCLOSINGMARUBOZU_Update")]
    pub fn update(&mut self, inOpen: f64, inHigh: f64, inLow: f64, inClose: f64) -> Result<i32, RetCode> {
        if !inOpen.is_finite() || !inHigh.is_finite() || !inLow.is_finite() || !inClose.is_finite() {
            if self.out.count < Core::MAX_INDEX {
                self.out.count += 1;
            }
            return Err(RetCode::BadParam);
        }
        let mut outInteger: i32 = 0_i32;
        Core::cdlclosingmarubozu_step_impl(&mut self.state, &self.cs_body_long, &self.cs_shadow_very_short, inOpen, inHigh, inLow, inClose, &mut outInteger);
        if self.out.count < Core::MAX_INDEX {
            self.out.count += 1;
        }
        Ok(outInteger)
    }

    /// Commit `n` closed bars and write their `n` values, in one call —
    /// exactly `n` back-to-back [`Self::update`] calls, with one set of
    /// argument checks instead of `n`. `n` is `inOpen.len()`; the outputs must
    /// hold at least that many. Never allocates.
    ///
    /// [`Self::out_range`] counts what this call took in, which is what makes the
    /// rejection below readable: there is no second out-parameter for it.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if the input slices differ in length, if an output
    /// is shorter than the bar count — neither commits anything — or if a bar
    /// is not finite. A non-finite bar `k` is rejected exactly as `update`
    /// rejects it: bars `0..k` stay committed and their values written, bar `k`
    /// and everything after it is not, and `out_range().count` has advanced by
    /// `k + 1` — the committed bars, plus the rejected one, which is counted
    /// but never written.
    #[doc(alias = "TA_CDLCLOSINGMARUBOZU_UpdateAndFill")]
    pub fn update_and_fill(&mut self, inOpen: &[f64], inHigh: &[f64], inLow: &[f64], inClose: &[f64], outInteger: &mut [i32]) -> Result<(), RetCode> {
        let barCount = inOpen.len();
        if inHigh.len() != inOpen.len() || inLow.len() != inOpen.len() || inClose.len() != inOpen.len() || outInteger.len() < barCount {
            return Err(RetCode::BadParam);
        }
        for i in 0..barCount {
            if !inOpen[i].is_finite() || !inHigh[i].is_finite() || !inLow[i].is_finite() || !inClose[i].is_finite() {
                if self.out.count < Core::MAX_INDEX {
                    self.out.count += 1;
                }
                return Err(RetCode::BadParam);
            }
            Core::cdlclosingmarubozu_step_impl(&mut self.state, &self.cs_body_long, &self.cs_shadow_very_short, inOpen[i], inHigh[i], inLow[i], inClose[i], &mut outInteger[i]);
            if self.out.count < Core::MAX_INDEX {
                self.out.count += 1;
            }
        }
        Ok(())
    }

    /// Evaluate a forming bar without committing — bit-identical to what the
    /// next `update` with the same bar would return: the same transition,
    /// rewritten so every store it would make lives in a local instead. It
    /// allocates nothing and copies no buffer, so its cost does not grow with
    /// the period, and it writes no part of the handle — peeks may run
    /// concurrently with each other.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite, on the same test
    /// `update` applies — but a rejected peek changes nothing at all, where a
    /// rejected `update` still counts the bar in [`Self::out_range`].
    #[doc(alias = "TA_CDLCLOSINGMARUBOZU_Peek")]
    pub fn peek(&self, inOpen: f64, inHigh: f64, inLow: f64, inClose: f64) -> Result<i32, RetCode> {
        if !inOpen.is_finite() || !inHigh.is_finite() || !inLow.is_finite() || !inClose.is_finite() {
            return Err(RetCode::BadParam);
        }
        let mut outInteger: i32 = 0_i32;
        {
            let sp = &self.state;
            let outInteger = &mut outInteger;
            #[allow(non_snake_case)]
            let BodyLong_rangeType: i32 = self.cs_body_long.range_type as i32;
            #[allow(non_snake_case)]
            let BodyLong_avgPeriod: i32 = self.cs_body_long.avg_period;
            #[allow(non_snake_case)]
            let BodyLong_factor: f64 = self.cs_body_long.factor;
            #[allow(non_snake_case)]
            let ShadowVeryShort_rangeType: i32 = self.cs_shadow_very_short.range_type as i32;
            #[allow(non_snake_case)]
            let ShadowVeryShort_avgPeriod: i32 = self.cs_shadow_very_short.avg_period;
            #[allow(non_snake_case)]
            let ShadowVeryShort_factor: f64 = self.cs_shadow_very_short.factor;
            if (inClose - inOpen).abs() > ((BodyLong_factor) * (if (BodyLong_avgPeriod) != 0 { (sp.BodyLongPeriodTotal) / (BodyLong_avgPeriod as f64) } else { match BodyLong_rangeType { 0 => ((inClose) - (inOpen)).abs(), 1 => (inHigh) - (inLow), 2 => ((inHigh) - (if (inClose) >= (inOpen) { (inClose) } else { (inOpen) })) + ((if (inClose) >= (inOpen) { (inOpen) } else { (inClose) }) - (inLow)), _ => 0.0 } }) / (if (BodyLong_rangeType) == 2 { 2.0 } else { 1.0 })) && // long body
               ((if inClose >= inOpen { 1 } else { 0 - 1 }) == 1 &&                // white body and very short upper shadow
                 (inHigh - (if inClose >= inOpen { inClose } else { inOpen })) < ((ShadowVeryShort_factor) * (if (ShadowVeryShort_avgPeriod) != 0 { (sp.ShadowVeryShortPeriodTotal) / (ShadowVeryShort_avgPeriod as f64) } else { match ShadowVeryShort_rangeType { 0 => ((inClose) - (inOpen)).abs(), 1 => (inHigh) - (inLow), 2 => ((inHigh) - (if (inClose) >= (inOpen) { (inClose) } else { (inOpen) })) + ((if (inClose) >= (inOpen) { (inOpen) } else { (inClose) }) - (inLow)), _ => 0.0 } }) / (if (ShadowVeryShort_rangeType) == 2 { 2.0 } else { 1.0 })) ||
                (((if inClose >= inOpen { 1 } else { 0 - 1 })) as i32) == 0 - 1 && // black body and very short lower shadow
                 ((if inClose >= inOpen { inOpen } else { inClose }) - inLow) < ((ShadowVeryShort_factor) * (if (ShadowVeryShort_avgPeriod) != 0 { (sp.ShadowVeryShortPeriodTotal) / (ShadowVeryShort_avgPeriod as f64) } else { match ShadowVeryShort_rangeType { 0 => ((inClose) - (inOpen)).abs(), 1 => (inHigh) - (inLow), 2 => ((inHigh) - (if (inClose) >= (inOpen) { (inClose) } else { (inOpen) })) + ((if (inClose) >= (inOpen) { (inOpen) } else { (inClose) }) - (inLow)), _ => 0.0 } }) / (if (ShadowVeryShort_rangeType) == 2 { 2.0 } else { 1.0 })))
            {
                (*outInteger) = ((if inClose >= inOpen { 1 } else { 0 - 1 }) * 100) as i32;
            } else {
                (*outInteger) = 0;
            }
        }
        Ok(outInteger)
    }

    /// The value(s) at the last bar the stream counted — the bar
    /// [`Self::out_range`] ends on — without recomputing. Seeded by the opener,
    /// refreshed by every accepted `update` and `update_and_fill`, and left
    /// alone by `peek`.
    ///
    /// A clone carries them verbatim, so a forked handle can be asked its
    /// current value without committing a bar to find out.
    #[must_use]
    #[doc(alias = "TA_CDLCLOSINGMARUBOZU_Value")]
    pub fn value(&self) -> i32 {
        self.state.cur_outInteger
    }

    /// The bars this stream has an output for, in the input series'
    /// coordinates: `[beg_idx, beg_idx + count)`.
    ///
    /// It is what [`Core::CDLCLOSINGMARUBOZU`] reports over the same bars: the opener sets it
    /// to `(lookback, historyLen - lookback)`, every `update` adds one to the
    /// count — a bar rejected for being non-finite included, because it still
    /// happened — `peek` leaves it alone, and a clone carries it verbatim.
    /// A plain `Open` hands back only the last value, a subset of this range,
    /// because the caller chose not to take the fill.
    #[doc(alias = "TA_StreamOutRange")]
    pub fn out_range(&self) -> OutRange {
        self.out
    }
}

