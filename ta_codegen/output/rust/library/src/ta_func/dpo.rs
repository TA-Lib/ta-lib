/// Live DPO stream: one value per closed bar, bit-identical to [`Core::DPO`]
/// over the same series. Open with [`Core::dpo_open`]; dropping the handle
/// closes the stream. Cloning it forks an independent stream.
///
/// [`Self::out_range`] reports the bars this handle has an output for.
#[must_use = "a stream does nothing unless updated; dropping it closes the stream"]
#[derive(Debug, Clone)]
#[doc(alias = "TA_DPO_Stream")]
pub struct DpoStream {
    state: DpoStreamState,
    /// The bars this handle has an output for — see [`Self::out_range`].
    out: OutRange,
}

#[derive(Debug, Clone)]
#[allow(non_snake_case, dead_code)]
struct DpoStreamState {
    optInTimePeriod: i32,
    periodTotal: f64,
    ringPos_dispIdx: usize,
    ringCap_dispIdx: usize,
    ring_dispIdx_inReal: Vec<f64>,
    ringPos_trailingIdx: usize,
    ringCap_trailingIdx: usize,
    ring_trailingIdx_inReal: Vec<f64>,
    cur_outReal: f64,
}

