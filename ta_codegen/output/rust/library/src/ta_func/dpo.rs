impl Core {
    fn dpo_step_impl(sp: &mut DpoStreamState, inReal: f64, outReal: &mut f64) {
        let mut tempReal: f64 = 0.0_f64;
        let mut dispVal: f64 = 0.0_f64;
        if sp.ringCap_dispIdx == 0 {
            sp.ring_dispIdx_inReal[0] = inReal;
        }
        if sp.ringCap_trailingIdx == 0 {
            sp.ring_trailingIdx_inReal[0] = inReal;
        }
        sp.periodTotal += inReal;
        tempReal = sp.periodTotal;
        sp.periodTotal -= sp.ring_trailingIdx_inReal[sp.ringPos_trailingIdx];
        // Both reads precede the store. Either cursor can EQUAL outIdx -- the
        // displaced one whenever startIdx equals the displacement, the trailing
        // one whenever startIdx sits at the lookback -- so a store hoisted above
        // them would read back what it had just overwritten when the caller
        // aliases outReal over inReal.
        dispVal = sp.ring_dispIdx_inReal[sp.ringPos_dispIdx];
        (*outReal) = dispVal - tempReal / (sp.optInTimePeriod as f64);
        sp.cur_outReal = (*outReal);
        sp.ring_dispIdx_inReal[sp.ringPos_dispIdx] = inReal;
        sp.ringPos_dispIdx = sp.ringPos_dispIdx + 1;
        if sp.ringPos_dispIdx >= sp.ringCap_dispIdx {
            sp.ringPos_dispIdx = 0;
        }
        sp.ring_trailingIdx_inReal[sp.ringPos_trailingIdx] = inReal;
        sp.ringPos_trailingIdx = sp.ringPos_trailingIdx + 1;
        if sp.ringPos_trailingIdx >= sp.ringCap_trailingIdx {
            sp.ringPos_trailingIdx = 0;
        }
    }

    /// The single whole-history transcription behind [`Core::dpo_open_internal`]
    /// (stride 0, scalar sink) and [`Core::dpo_open_and_fill`] (stride 1, caller slices).
    pub(crate) fn dpo_open_impl(
        &self, inReal: &[f64], startIdx: usize, mut optInTimePeriod: i32, outBegIdx: &mut usize, outNBElement: &mut usize, outReal: &mut [f64], outStride: usize,
    ) -> Result<DpoStream, RetCode> {
        if inReal.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inReal.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        if ((optInTimePeriod) as i32) == (i32::MIN) {
            optInTimePeriod = 20;
        } else if (((optInTimePeriod) as i32) < 2) || (((optInTimePeriod) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        let historyLen: usize = inReal.len();
        let endIdx: usize = historyLen - 1;
        let mut startIdx = startIdx;
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut periodTotal: f64 = 0.0_f64;
        let mut tempReal: f64 = 0.0_f64;
        let mut dispVal: f64 = 0.0_f64;
        let mut i: usize = 0_usize;
        let mut outIdx: usize = 0_usize;
        let mut trailingIdx: usize = 0_usize;
        let mut dispIdx: usize = 0_usize;
        let mut lookbackTotal: usize = 0_usize;
        // The running sum is accumulated, snapshot and divided in exactly the order
        // ta_codegen/input/sma/sma.c uses, so this fused loop is bit-for-bit equal
        // to a TA_SMA anchored at the same startIdx. That equality is what makes
        // the composite differential in test_dpo.c a memcmp instead of a tolerance
        // argument, and it is lost by dividing once into a reciprocal or by
        // reordering the add/snapshot/subtract.
        lookbackTotal = self.DPO_Lookback(optInTimePeriod)?;
        if startIdx < lookbackTotal {
            startIdx = lookbackTotal;
        }
        // Make sure there is still something to evaluate.
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        periodTotal = 0.0;
        trailingIdx = startIdx - (((optInTimePeriod - 1)) as usize);
        dispIdx = startIdx - (((optInTimePeriod / 2 + 1)) as usize);
        i = trailingIdx;
        while i < startIdx {
            periodTotal += inReal[i];
            i = i + 1;
        }
        outIdx = 0;
        while i <= endIdx {
            periodTotal += inReal[i];
            i = i + 1;
            tempReal = periodTotal;
            periodTotal -= inReal[trailingIdx];
            trailingIdx = trailingIdx + 1;
            // Both reads precede the store. Either cursor can EQUAL outIdx -- the
            // displaced one whenever startIdx equals the displacement, the trailing
            // one whenever startIdx sits at the lookback -- so a store hoisted above
            // them would read back what it had just overwritten when the caller
            // aliases outReal over inReal.
            dispVal = inReal[dispIdx];
            dispIdx = dispIdx + 1;
            outReal[(outIdx * outStride) as usize] = dispVal - tempReal / (optInTimePeriod as f64);
            outIdx = outIdx + 1;
        }
        (*outNBElement) = outIdx;
        (*outBegIdx) = startIdx;

        // Capture the live batch state into the handle.
        let cap_dispIdx: i64 = (i as i64) - (dispIdx as i64);
        if cap_dispIdx < 0 || cap_dispIdx > historyLen as i64 {
            return Err(RetCode::InternalError);
        }
        let allocN_dispIdx: usize = if cap_dispIdx > 0 { cap_dispIdx as usize } else { 1 };
        let mut ring_dispIdx_inReal: Vec<f64> = vec![0.0_f64; allocN_dispIdx];
        ring_dispIdx_inReal[..cap_dispIdx as usize]
            .copy_from_slice(&inReal[historyLen - cap_dispIdx as usize..]);
        let cap_trailingIdx: i64 = (i as i64) - (trailingIdx as i64);
        if cap_trailingIdx < 0 || cap_trailingIdx > historyLen as i64 {
            return Err(RetCode::InternalError);
        }
        let allocN_trailingIdx: usize = if cap_trailingIdx > 0 { cap_trailingIdx as usize } else { 1 };
        let mut ring_trailingIdx_inReal: Vec<f64> = vec![0.0_f64; allocN_trailingIdx];
        ring_trailingIdx_inReal[..cap_trailingIdx as usize]
            .copy_from_slice(&inReal[historyLen - cap_trailingIdx as usize..]);
        let state = DpoStreamState {
            optInTimePeriod,
            periodTotal,
            cur_outReal: outReal[(*outNBElement - 1) * outStride],
            ringPos_dispIdx: 0_usize,
            ringCap_dispIdx: cap_dispIdx as usize,
            ring_dispIdx_inReal,
            ringPos_trailingIdx: 0_usize,
            ringCap_trailingIdx: cap_trailingIdx as usize,
            ring_trailingIdx_inReal,
        };
        Ok(DpoStream { state, out: OutRange { beg_idx: *outBegIdx, count: *outNBElement } })
    }

    /// Internal startIdx-anchored open behind [`Core::dpo_open`] (composition seam).
    pub(crate) fn dpo_open_internal(
        &self, inReal: &[f64], startIdx: usize, mut optInTimePeriod: i32,
    ) -> Result<(DpoStream, f64), RetCode> {
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut sink_outReal = [0.0_f64; 1];
        let handle = self.dpo_open_impl(inReal, startIdx, optInTimePeriod, &mut dummyBegIdx, &mut dummyNBElement, &mut sink_outReal, 0)?;
        Ok((handle, sink_outReal[0]))
    }

    /// Open a live DPO stream over the warm-up history; returns the handle and
    /// the value at the last history bar — bit-identical to [`Core::DPO`] at that bar.
    ///
    /// # Errors
    ///
    /// [`RetCode::InsufficientHistory`] when the history holds fewer than
    /// `lookback + 1` bars — the one failure here worth retrying, since another
    /// bar fixes it. [`RetCode::OutOfRangeStartIndex`] when the history is empty.
    /// [`RetCode::BadParam`] when a parameter is out of range or the input
    /// lengths differ.
    ///
    /// ```
    /// use ta_lib::Core;
    /// let data: Vec<f64> = (0..252).map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    ///
    /// let core = Core::new();
    /// let (mut s, _last) = core.dpo_open(&data, 20).expect("enough history");
    /// let r0 = s.out_range();
    /// let peeked = s.peek(100.9).expect("a finite bar");
    /// assert_eq!(s.out_range().count, r0.count); // a peek commits nothing
    /// let updated = s.update(100.9).expect("a finite bar");
    /// assert_eq!(s.out_range().beg_idx, r0.beg_idx);
    /// assert_eq!(s.out_range().count, r0.count + 1);
    /// assert_eq!(peeked.to_bits(), updated.to_bits());
    /// ```
    #[doc(alias = "TA_DPO_Open")]
    pub fn dpo_open(&self, inReal: &[f64], optInTimePeriod: i32) -> Result<(DpoStream, f64), RetCode> {
        self.dpo_open_internal(inReal, 0, optInTimePeriod)
    }

    /// [`Core::dpo_open`] that also fills the output array(s) bit-identically to
    /// [`Core::DPO`] over `0..len` in the same single pass, and reports the range it
    /// wrote as the [`OutRange`] beside the handle.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] when an output slice holds fewer than `len - lookback`
    /// values — the batch tier's sizing rule, checked here as it is there (rule S5) —
    /// or when two of them are the same slice. Everything [`Core::dpo_open`] rejects
    /// is rejected here too.
    ///
    /// # Examples
    ///
    /// ```
    /// use ta_lib::Core;
    /// let data: Vec<f64> = (0..252).map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    ///
    /// let core = Core::new();
    /// let mut batch_out = vec![0.0; 252];
    /// let batch = core.DPO(0, data.len() - 1, &data, 20, &mut batch_out)?;
    ///
    /// let mut out = vec![0.0; 252];
    /// let (_stream, filled) = core.dpo_open_and_fill(&data, 20, &mut out)?;
    ///
    /// assert_eq!(filled.beg_idx, batch.beg_idx);
    /// assert_eq!(filled.count, batch.count);
    /// assert!(out[..filled.count].iter().zip(&batch_out[..batch.count])
    ///     .all(|(a, b)| a.to_bits() == b.to_bits()));
    /// # Ok::<(), ta_lib::RetCode>(())
    /// ```
    #[doc(alias = "TA_DPO_OpenAndFill")]
    pub fn dpo_open_and_fill(
        &self, inReal: &[f64], mut optInTimePeriod: i32, outReal: &mut [f64],
    ) -> Result<(DpoStream, OutRange), RetCode> {
        if inReal.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inReal.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        let _guardLb = self.DPO_Lookback(optInTimePeriod)?;
        let _guardOutLen = inReal.len().saturating_sub(_guardLb);
        if outReal.len() < _guardOutLen {
            return Err(RetCode::BadParam);
        }
        let mut outBegIdx: usize = 0;
        let mut outNBElement: usize = 0;
        let handle = self.dpo_open_and_fill_internal(inReal, 0, optInTimePeriod, &mut outBegIdx, &mut outNBElement, outReal)?;
        Ok((handle, OutRange { beg_idx: outBegIdx, count: outNBElement }))
    }

    /// [`Core::dpo_open_and_fill`] anchored at `startIdx` — the composed-open
    /// fusion seam (issue #192), not a public entry point.
    pub(crate) fn dpo_open_and_fill_internal(
        &self, inReal: &[f64], startIdx: usize, mut optInTimePeriod: i32, outBegIdx: &mut usize, outNBElement: &mut usize, outReal: &mut [f64],
    ) -> Result<DpoStream, RetCode> {
        self.dpo_open_impl(inReal, startIdx, optInTimePeriod, outBegIdx, outNBElement, outReal, 1)
    }

}

