    fn kdj_step_impl(sp: &mut KdjStreamState, inHigh: f64, inLow: f64, inClose: f64, outK: &mut f64, outD: &mut f64, outJ: &mut f64) -> Result<(), RetCode> {
        let mut cur_outK: f64 = 0.0_f64;
        let mut cur_outD: f64 = 0.0_f64;
        let mut cur_outJ: f64 = 0.0_f64;

        // Pipeline the new bar through the sub-streams (batch tail order).
        {
            let _sub_out = sp.sub0.update(inHigh, inLow, inClose)?;
            cur_outK = _sub_out.0;
            cur_outD = _sub_out.1;
        }
        // Combine map (batch tail, per bar).
        cur_outJ = 3.0 * cur_outK - 2.0 * cur_outD;
        (*outK) = cur_outK;
        (*outD) = cur_outD;
        (*outJ) = cur_outJ;
        Ok(())
    }

