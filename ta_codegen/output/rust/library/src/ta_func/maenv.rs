    fn maenv_step_impl(sp: &mut MaenvStreamState, inReal: f64, outRealUpperBand: &mut f64, outRealMiddleBand: &mut f64, outRealLowerBand: &mut f64) -> Result<(), RetCode> {
        let mut middle: f64 = 0.0_f64;
        let mut cur_outRealMiddleBand: f64 = 0.0_f64;
        let mut cur_outRealUpperBand: f64 = 0.0_f64;
        let mut cur_outRealLowerBand: f64 = 0.0_f64;

        // Pipeline the new bar through the sub-streams (batch tail order).
        cur_outRealMiddleBand = sp.sub0.update(inReal)?;
        let dnFactor: f64 = sp.dnFactor;
        let upFactor: f64 = sp.upFactor;
        // Combine map (batch tail, per bar).
        middle = cur_outRealMiddleBand;
        cur_outRealUpperBand = middle * upFactor;
        cur_outRealLowerBand = middle * dnFactor;
        *outRealUpperBand = cur_outRealUpperBand;
        *outRealMiddleBand = cur_outRealMiddleBand;
        *outRealLowerBand = cur_outRealLowerBand;
        Ok(())
    }

    /// The single whole-history transcription behind [`Core::maenv_open_internal`]
    /// (stride 0, scalar sink) and [`Core::maenv_open_and_fill`] (stride 1, caller slices).
    pub(crate) fn maenv_open_impl(
        &self, inReal: &[f64], startIdx: usize, mut optInTimePeriod: i32, mut optInPercentUp: f64, mut optInPercentDn: f64, mut optInMAType: MAType, outBegIdx: &mut usize, outNBElement: &mut usize, outRealUpperBand: &mut [f64], outRealMiddleBand: &mut [f64], outRealLowerBand: &mut [f64], outStride: usize,
    ) -> Result<MaenvStream, RetCode> {
        if inReal.len() > Self::INDEX_MAX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        if optInTimePeriod == i32::MIN {
            optInTimePeriod = 20;
        } else if optInTimePeriod < 1 || optInTimePeriod > 100000 {
            return Err(RetCode::BadParam);
        }
        if optInPercentUp == Self::REAL_DEFAULT {
            optInPercentUp = 1e1;
        } else if !((optInPercentUp >= Self::REAL_MIN) && (optInPercentUp <= Self::REAL_MAX)) {
            return Err(RetCode::BadParam);
        }
        if optInPercentDn == Self::REAL_DEFAULT {
            optInPercentDn = 1e1;
        } else if !((optInPercentDn >= Self::REAL_MIN) && (optInPercentDn <= Self::REAL_MAX)) {
            return Err(RetCode::BadParam);
        }
        if optInMAType == MAType::DEFAULT {
            optInMAType = MAType::SMA;
        }
        let historyLen: usize = inReal.len();
        if startIdx >= historyLen {
            *outBegIdx = 0;
            *outNBElement = 0;
            return Err(RetCode::InsufficientHistory);
        }
        let endIdx: usize = historyLen - 1;
        let mut owned_sc_outRealUpperBand: Vec<f64> =
            if outStride == 1 { Vec::new() } else { vec![0.0_f64; historyLen] };
        let sc_outRealUpperBand: &mut [f64] =
            if outStride == 1 { &mut *outRealUpperBand } else { &mut owned_sc_outRealUpperBand };
        let mut owned_sc_outRealMiddleBand: Vec<f64> =
            if outStride == 1 { Vec::new() } else { vec![0.0_f64; historyLen] };
        let sc_outRealMiddleBand: &mut [f64] =
            if outStride == 1 { &mut *outRealMiddleBand } else { &mut owned_sc_outRealMiddleBand };
        let mut owned_sc_outRealLowerBand: Vec<f64> =
            if outStride == 1 { Vec::new() } else { vec![0.0_f64; historyLen] };
        let sc_outRealLowerBand: &mut [f64] =
            if outStride == 1 { &mut *outRealLowerBand } else { &mut owned_sc_outRealLowerBand };
        let mut i: usize = 0_usize;
        let mut upFactor: f64 = 0.0_f64;
        let mut dnFactor: f64 = 0.0_f64;
        let mut middle: f64 = 0.0_f64;
        if self.ma_lookback(optInTimePeriod, optInMAType)? > endIdx {
            *outBegIdx = 0;
            *outNBElement = 0;
            return Err(RetCode::InsufficientHistory);
        }
        // Sub-stream 0: ma over `inReal`, warmed from bar 0 up to the
        // sub-call's own startIdx (the seeding point).
        let sub0 = self.ma_open_and_fill_internal(&inReal[..(endIdx as usize) + 1], startIdx as usize, optInTimePeriod, optInMAType, outBegIdx, outNBElement, &mut sc_outRealMiddleBand[..])?;
        upFactor = 1.0 + (optInPercentUp as f64) / 100.0;
        dnFactor = 1.0 - (optInPercentDn as f64) / 100.0;
        // for( i = 0; i < ((((*outNBElement) as usize)) as usize); i += 1 )
        i = 0;
        while i < ((*outNBElement as usize) as usize) {
            middle = sc_outRealMiddleBand[i];
            sc_outRealUpperBand[i] = middle * upFactor;
            sc_outRealLowerBand[i] = middle * dnFactor;
            i += 1;
        }

        // Capture the live producer state + sub handles.
        if *outNBElement < 1 {
            return Err(RetCode::InsufficientHistory);
        }
        let mut state = MaenvStreamState {
            cur_outRealUpperBand: 0.0_f64,
            cur_outRealMiddleBand: 0.0_f64,
            cur_outRealLowerBand: 0.0_f64,
            sub0,
            dnFactor,
            upFactor,
        };
        state.cur_outRealUpperBand = sc_outRealUpperBand[*outNBElement - 1];
        state.cur_outRealMiddleBand = sc_outRealMiddleBand[*outNBElement - 1];
        state.cur_outRealLowerBand = sc_outRealLowerBand[*outNBElement - 1];
        if outStride != 1 && *outNBElement > 0 {
            let last_sc_outRealUpperBand = sc_outRealUpperBand[*outNBElement - 1];
            outRealUpperBand[0] = last_sc_outRealUpperBand;
        }
        if outStride != 1 && *outNBElement > 0 {
            let last_sc_outRealMiddleBand = sc_outRealMiddleBand[*outNBElement - 1];
            outRealMiddleBand[0] = last_sc_outRealMiddleBand;
        }
        if outStride != 1 && *outNBElement > 0 {
            let last_sc_outRealLowerBand = sc_outRealLowerBand[*outNBElement - 1];
            outRealLowerBand[0] = last_sc_outRealLowerBand;
        }
        Ok(MaenvStream { state, out: OutRange { beg_idx: *outBegIdx, count: *outNBElement } })
    }

