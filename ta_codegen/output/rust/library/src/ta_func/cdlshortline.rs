thread_local! {
    /// `peek`'s reusable scratch handle (see `CDLSHORTLINE_StreamState::restore_from`).
    /// Taken for the duration of the step and put back after, so a
    /// panicking step costs the scratch, never leaves it borrowed.
    static CDLSHORTLINE_PEEK_SCRATCH: std::cell::Cell<Option<Box<CDLSHORTLINE_Stream>>> =
        const { std::cell::Cell::new(None) };
}

#[allow(non_snake_case)]
#[allow(unused_variables)]
impl CDLSHORTLINE_Stream {
    /// Commit one closed bar. Never allocates.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite (NaN or ±Inf).
    /// That check runs before anything is written, so the handle is left
    /// exactly as it was and the stream stays usable:
    /// skip the bar, or close and re-open on a clean history. This is the
    /// one place the streaming tier is stricter than the batch API, which
    /// computes on whatever it is given — a handle retains its state, so a
    /// single non-finite bar would poison every later value it produces.
    #[doc(alias = "TA_CDLSHORTLINE_Update")]
    pub fn update(&mut self, inOpen: f64, inHigh: f64, inLow: f64, inClose: f64) -> Result<i32, RetCode> {
        if !inOpen.is_finite() || !inHigh.is_finite() || !inLow.is_finite() || !inClose.is_finite() {
            return Err(RetCode::BadParam);
        }
        let mut outInteger: i32 = 0_i32;
        self.core.CDLSHORTLINE_step_internal(&mut self.state, inOpen, inHigh, inLow, inClose, &mut outInteger);
        Ok(outInteger)
    }

    /// Evaluate a forming bar without committing — bit-identical to what the
    /// next `update` with the same bar would return (it is the same code, run
    /// on a scratch copy of the state). Never writes the handle, so peeks may
    /// run concurrently with each other. The copy it runs on is held per thread and reused,
    /// so only the first peek of this function on a thread allocates.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite, exactly as
    /// `update` rejects it.
    #[doc(alias = "TA_CDLSHORTLINE_Peek")]
    pub fn peek(&self, inOpen: f64, inHigh: f64, inLow: f64, inClose: f64) -> Result<i32, RetCode> {
        if !inOpen.is_finite() || !inHigh.is_finite() || !inLow.is_finite() || !inClose.is_finite() {
            return Err(RetCode::BadParam);
        }
        CDLSHORTLINE_PEEK_SCRATCH.with(|cell| {
            let mut scratch = cell.take().unwrap_or_else(|| Box::new(self.clone()));
            scratch.restore_from(self);
            let value = scratch.update(inOpen, inHigh, inLow, inClose);
            cell.set(Some(scratch));
            value
        })
    }
}

