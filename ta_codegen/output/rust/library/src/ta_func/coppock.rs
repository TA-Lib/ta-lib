impl Core {
    fn coppock_step_impl(sp: &mut CoppockStreamState, inReal: f64, outReal: &mut f64) {
        let mut q: usize = 0_usize;
        let mut rw: usize = 0_usize;
        let mut ringWalk: usize = 0_usize;
        let mut tempReal: f64 = 0.0_f64;
        let mut tempReal2: f64 = 0.0_f64;
        let mut base1: f64 = 0.0_f64;
        let mut base2: f64 = 0.0_f64;
        let mut roc1: f64 = 0.0_f64;
        let mut roc2: f64 = 0.0_f64;
        if sp.ringCap_roc1Idx == 0 {
            sp.ring_roc1Idx_inReal[0] = inReal;
        }
        if sp.ringCap_roc2Idx == 0 {
            sp.ring_roc2Idx_inReal[0] = inReal;
        }
        base1 = sp.ring_roc1Idx_inReal[sp.ringPos_roc1Idx];
        base2 = sp.ring_roc2Idx_inReal[sp.ringPos_roc2Idx];
        roc1 = (if base1 != 0.0 { (inReal / base1 - 1.0) * 100.0 } else { 0.0 });
        roc2 = (if base2 != 0.0 { (inReal / base2 - 1.0) * 100.0 } else { 0.0 });
        tempReal = roc1 + roc2;
        sp.periodSub += tempReal;
        sp.periodSub -= sp.trailingValue;
        sp.periodSum += tempReal * ((sp.optInWMAPeriod) as f64);
        // Re-anchor every 8*w bars: rebuild both totals from the window
        // itself -- TA_WMA's #254 fix, same single trigger, same interval.
        // The window lives in the ring (w-1 prior S values, sRing_Idx the
        // oldest) plus the current bar's tempReal at weight w.
        sp.barsSinceReseed -= 1;
        if sp.barsSinceReseed <= 0 {
            sp.barsSinceReseed = (8 * sp.optInWMAPeriod) as usize;
            sp.periodSub = 0.0 as f64;
            sp.periodSum = 0.0 as f64;
            rw = 1;
            ringWalk = sp.sRing_Idx;
            // for( q = 0; q < sp.ringSize; q += 1 )
            q = 0;
            while q < sp.ringSize {
                tempReal2 = sp.cb_sRing[ringWalk];
                sp.periodSub += tempReal2;
                sp.periodSum += tempReal2 * ((rw) as f64);
                rw += 1;
                ringWalk += 1;
                if ringWalk >= sp.ringSize {
                    ringWalk = 0;
                }
                q += 1;
            }
            sp.periodSub += tempReal;
            sp.periodSum += tempReal * ((sp.optInWMAPeriod) as f64);
        }
        // Read the expiring S value BEFORE overwriting its slot with the
        // current one -- the ring is the aliasing-safe stand-in for TA_WMA's
        // "save the trailing value before the store" rule.
        sp.trailingValue = sp.cb_sRing[sp.sRing_Idx];
        sp.cb_sRing[sp.sRing_Idx] = tempReal;
        sp.sRing_Idx = sp.sRing_Idx + 1;
        if sp.sRing_Idx > sp.maxIdx_sRing {
            sp.sRing_Idx = 0;
        }
        // Load-bearing, not a rounding nicety: keep it. WMA(1) is the identity
        // and TA_WMA ships an exact copy fast path, but the recurrence here is
        // off by a whole term at w == 1 -- ringSize clamps to 1, so the
        // read-before-write ring hands back the wrong trailing value. Deleting
        // this arm moves TA_SREF bar 16 at (1,11,14) from -11.311839169954585
        // to -6.4591709868291103.
        if sp.optInWMAPeriod == 1 {
            (*outReal) = tempReal;
        } else {
            (*outReal) = sp.periodSum / sp.divider;
        }
        sp.periodSum -= sp.periodSub;
        sp.cur_outReal = (*outReal);
        sp.ring_roc1Idx_inReal[sp.ringPos_roc1Idx] = inReal;
        sp.ringPos_roc1Idx = sp.ringPos_roc1Idx + 1;
        if sp.ringPos_roc1Idx >= sp.ringCap_roc1Idx {
            sp.ringPos_roc1Idx = 0;
        }
        sp.ring_roc2Idx_inReal[sp.ringPos_roc2Idx] = inReal;
        sp.ringPos_roc2Idx = sp.ringPos_roc2Idx + 1;
        if sp.ringPos_roc2Idx >= sp.ringCap_roc2Idx {
            sp.ringPos_roc2Idx = 0;
        }
    }

    /// The single whole-history transcription behind [`Core::coppock_open_internal`]
    /// (stride 0, scalar sink) and [`Core::coppock_open_and_fill`] (stride 1, caller slices).
    pub(crate) fn coppock_open_impl(
        &self, inReal: &[f64], startIdx: usize, mut optInWMAPeriod: i32, mut optInROC1Period: i32, mut optInROC2Period: i32, outBegIdx: &mut usize, outNBElement: &mut usize, outReal: &mut [f64], outStride: usize,
    ) -> Result<CoppockStream, RetCode> {
        if inReal.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inReal.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        if ((optInWMAPeriod) as i32) == (i32::MIN) {
            optInWMAPeriod = 10;
        } else if (((optInWMAPeriod) as i32) < 1) || (((optInWMAPeriod) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        if ((optInROC1Period) as i32) == (i32::MIN) {
            optInROC1Period = 11;
        } else if (((optInROC1Period) as i32) < 1) || (((optInROC1Period) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        if ((optInROC2Period) as i32) == (i32::MIN) {
            optInROC2Period = 14;
        } else if (((optInROC2Period) as i32) < 1) || (((optInROC2Period) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        let historyLen: usize = inReal.len();
        let endIdx: usize = historyLen - 1;
        let mut startIdx = startIdx;
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut outIdx: usize = 0_usize;
        let mut inIdx: usize = 0_usize;
        let mut lookbackTotal: usize = 0_usize;
        let mut i: usize = 0_usize;
        let mut q: usize = 0_usize;
        let mut rw: usize = 0_usize;
        let mut ringWalk: usize = 0_usize;
        let mut ringSize: usize = 0_usize;
        let mut barsSinceReseed: usize = 0_usize;
        let mut roc1Idx: usize = 0_usize;
        let mut roc2Idx: usize = 0_usize;
        let mut periodSum: f64 = 0.0_f64;
        let mut periodSub: f64 = 0.0_f64;
        let mut tempReal: f64 = 0.0_f64;
        let mut tempReal2: f64 = 0.0_f64;
        let mut trailingValue: f64 = 0.0_f64;
        let mut divider: f64 = 0.0_f64;
        let mut base1: f64 = 0.0_f64;
        let mut base2: f64 = 0.0_f64;
        let mut roc1: f64 = 0.0_f64;
        let mut roc2: f64 = 0.0_f64;
        let mut sRing: Vec<f64> = Vec::new();
        let mut sRing_Idx: usize = 0;
        let mut maxIdx_sRing: usize = 49;
        // Coppock Curve: a WMA(optInWMAPeriod) of the SUM of two rates of change,
        // ROC(optInROC1Period) + ROC(optInROC2Period). The sum, not the mean:
        // every published definition sums them; Tulip's beta/copp.c averages and
        // therefore reads at exactly half this amplitude. A clean 2.000000x ratio
        // against Tulip is Tulip's variant, not a defect here (issue #362).
        //
        // The smoothed series is the inline expression
        //    S(j) = R(j,p1) + R(j,p2)
        //    R(j,p) = (inReal[j-p] != 0.0) ? ((inReal[j]/inReal[j-p])-1.0)*100.0
        //                                  : 0.0
        // -- TA_ROC's own zero guard included, so a zero price yields 0.0 exactly
        // where TA_ROC yields 0.0, never an inf that pollutes the window. Each
        // lagged denominator goes through its own trailing cursor advanced in
        // lock-step (TA_ROC's own shape) -- a parameter-sized lag subscript is
        // outside the stream classifier's index grammar.
        //
        // The WMA stage reproduces TA_WMA's recurrence verbatim -- the triangle
        // divider computed in double (#142), the periodSum/periodSub carry and the
        // 8*w re-anchor (#254) -- because anything short of verbatim breaks the
        // bit-exact composite differential against TA_ROC + TA_ROC + TA_WMA. S is
        // a DERIVED series that is never materialised, so, exactly as in TA_HMA's
        // outer stage, each S value is computed once and carried in a
        // (optInWMAPeriod-1)-slot ring: the trailing subtraction reads the
        // expiring slot and the re-anchor walks the ring, oldest first, weight
        // counting up from 1, then adds the current bar at weight w.
        lookbackTotal = self.COPPOCK_Lookback(optInWMAPeriod, optInROC1Period, optInROC2Period)?;
        if startIdx < lookbackTotal {
            startIdx = lookbackTotal;
        }
        // Make sure there is still something to evaluate.
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        // Triangle divider in double: the int product w*(w+1) overflows int32 at
        // w >= 46341 (#142), exactly as in TA_WMA.
        divider = (optInWMAPeriod as f64) * (((optInWMAPeriod + 1)) as f64) / 2.0;
        outIdx = 0;
        // The S value computed at bar t expires optInWMAPeriod-1 bars later, so a
        // single-cursor ring of optInWMAPeriod-1 slots is enough: read the
        // expiring value, overwrite the slot, advance. At w == 1 the recurrence's
        // state is never consumed (see the identity output below), but the ring
        // still needs one slot for the reads to stay in bounds.
        ringSize = (optInWMAPeriod - 1) as usize;
        if ringSize < 1 {
            ringSize = 1;
        }
        if ringSize < 1 { return Err(RetCode::InternalError); }
        sRing = vec![0.0_f64; (ringSize) as usize];
        maxIdx_sRing = ((ringSize) as usize) - 1;
        sRing_Idx = 0;
        // At w == 1 the priming loop below never runs, so the first trailing read
        // would see an undefined slot; at w > 1 priming overwrites every slot.
        sRing[0] = 0.0;
        // One trailing cursor per ROC denominator, advanced in lock-step from the
        // priming scan onward.
        inIdx = startIdx - (((optInWMAPeriod - 1)) as usize);
        roc1Idx = inIdx - ((optInROC1Period) as usize);
        roc2Idx = inIdx - ((optInROC2Period) as usize);
        // Priming: the w-1 S values before the first output, oldest first with
        // the weight counting up from 1 -- TA_WMA's own priming order, which the
        // re-anchor below must reproduce. They also fill the ring.
        periodSub = 0.0 as f64;
        periodSum = periodSub;
        i = 1;
        while inIdx < startIdx {
            base1 = inReal[roc1Idx];
            roc1Idx += 1;
            base2 = inReal[roc2Idx];
            roc2Idx += 1;
            roc1 = (if base1 != 0.0 { (inReal[inIdx] / base1 - 1.0) * 100.0 } else { 0.0 });
            roc2 = (if base2 != 0.0 { (inReal[inIdx] / base2 - 1.0) * 100.0 } else { 0.0 });
            tempReal = roc1 + roc2;
            periodSub += tempReal;
            periodSum += tempReal * ((i) as f64);
            i += 1;
            sRing[sRing_Idx] = tempReal;
            sRing_Idx += 1;
            if sRing_Idx > maxIdx_sRing { sRing_Idx = 0; }
            inIdx += 1;
        }
        barsSinceReseed = (8 * optInWMAPeriod) as usize;
        trailingValue = 0.0;
        // Tight loop for the requested range.
        while inIdx <= endIdx {
            base1 = inReal[roc1Idx];
            roc1Idx += 1;
            base2 = inReal[roc2Idx];
            roc2Idx += 1;
            roc1 = (if base1 != 0.0 { (inReal[inIdx] / base1 - 1.0) * 100.0 } else { 0.0 });
            roc2 = (if base2 != 0.0 { (inReal[inIdx] / base2 - 1.0) * 100.0 } else { 0.0 });
            tempReal = roc1 + roc2;
            periodSub += tempReal;
            periodSub -= trailingValue;
            periodSum += tempReal * ((optInWMAPeriod) as f64);
            // Re-anchor every 8*w bars: rebuild both totals from the window
            // itself -- TA_WMA's #254 fix, same single trigger, same interval.
            // The window lives in the ring (w-1 prior S values, sRing_Idx the
            // oldest) plus the current bar's tempReal at weight w.
            barsSinceReseed -= 1;
            if barsSinceReseed <= 0 {
                barsSinceReseed = (8 * optInWMAPeriod) as usize;
                periodSub = 0.0 as f64;
                periodSum = 0.0 as f64;
                rw = 1;
                ringWalk = sRing_Idx;
                // for( q = 0; q < ringSize; q += 1 )
                q = 0;
                while q < ringSize {
                    tempReal2 = sRing[ringWalk];
                    periodSub += tempReal2;
                    periodSum += tempReal2 * ((rw) as f64);
                    rw += 1;
                    ringWalk += 1;
                    if ringWalk >= ringSize {
                        ringWalk = 0;
                    }
                    q += 1;
                }
                periodSub += tempReal;
                periodSum += tempReal * ((optInWMAPeriod) as f64);
            }
            // Read the expiring S value BEFORE overwriting its slot with the
            // current one -- the ring is the aliasing-safe stand-in for TA_WMA's
            // "save the trailing value before the store" rule.
            trailingValue = sRing[sRing_Idx];
            sRing[sRing_Idx] = tempReal;
            sRing_Idx += 1;
            if sRing_Idx > maxIdx_sRing { sRing_Idx = 0; }
            // Load-bearing, not a rounding nicety: keep it. WMA(1) is the identity
            // and TA_WMA ships an exact copy fast path, but the recurrence here is
            // off by a whole term at w == 1 -- ringSize clamps to 1, so the
            // read-before-write ring hands back the wrong trailing value. Deleting
            // this arm moves TA_SREF bar 16 at (1,11,14) from -11.311839169954585
            // to -6.4591709868291103.
            if optInWMAPeriod == 1 {
                outReal[(outIdx * outStride) as usize] = tempReal;
            } else {
                outReal[(outIdx * outStride) as usize] = periodSum / divider;
            }
            outIdx += 1;
            periodSum -= periodSub;
            inIdx += 1;
        }
        (*outBegIdx) = startIdx;
        (*outNBElement) = outIdx;

        // Capture the live batch state into the handle.
        let cap_roc1Idx: i64 = (inIdx as i64) - (roc1Idx as i64);
        if cap_roc1Idx < 0 || cap_roc1Idx > historyLen as i64 {
            return Err(RetCode::InternalError);
        }
        let allocN_roc1Idx: usize = if cap_roc1Idx > 0 { cap_roc1Idx as usize } else { 1 };
        let mut ring_roc1Idx_inReal: Vec<f64> = vec![0.0_f64; allocN_roc1Idx];
        ring_roc1Idx_inReal[..cap_roc1Idx as usize]
            .copy_from_slice(&inReal[historyLen - cap_roc1Idx as usize..]);
        let cap_roc2Idx: i64 = (inIdx as i64) - (roc2Idx as i64);
        if cap_roc2Idx < 0 || cap_roc2Idx > historyLen as i64 {
            return Err(RetCode::InternalError);
        }
        let allocN_roc2Idx: usize = if cap_roc2Idx > 0 { cap_roc2Idx as usize } else { 1 };
        let mut ring_roc2Idx_inReal: Vec<f64> = vec![0.0_f64; allocN_roc2Idx];
        ring_roc2Idx_inReal[..cap_roc2Idx as usize]
            .copy_from_slice(&inReal[historyLen - cap_roc2Idx as usize..]);
        let cbSize_sRing: usize = maxIdx_sRing + 1;
        if cbSize_sRing > historyLen + 1 {
            return Err(RetCode::InternalError);
        }
        let state = CoppockStreamState {
            optInWMAPeriod,
            optInROC1Period,
            optInROC2Period,
            ringSize,
            barsSinceReseed,
            periodSum,
            periodSub,
            trailingValue,
            divider,
            sRing_Idx,
            maxIdx_sRing,
            cur_outReal: outReal[(*outNBElement - 1) * outStride],
            ringPos_roc1Idx: 0_usize,
            ringCap_roc1Idx: cap_roc1Idx as usize,
            ring_roc1Idx_inReal,
            ringPos_roc2Idx: 0_usize,
            ringCap_roc2Idx: cap_roc2Idx as usize,
            ring_roc2Idx_inReal,
            cbSize_sRing: cbSize_sRing,
            cb_sRing: sRing,
        };
        Ok(CoppockStream { state, out: OutRange { beg_idx: *outBegIdx, count: *outNBElement } })
    }

    /// Internal startIdx-anchored open behind [`Core::coppock_open`] (composition seam).
    pub(crate) fn coppock_open_internal(
        &self, inReal: &[f64], startIdx: usize, mut optInWMAPeriod: i32, mut optInROC1Period: i32, mut optInROC2Period: i32,
    ) -> Result<(CoppockStream, f64), RetCode> {
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut sink_outReal = [0.0_f64; 1];
        let handle = self.coppock_open_impl(inReal, startIdx, optInWMAPeriod, optInROC1Period, optInROC2Period, &mut dummyBegIdx, &mut dummyNBElement, &mut sink_outReal, 0)?;
        Ok((handle, sink_outReal[0]))
    }

    /// Open a live COPPOCK stream over the warm-up history; returns the handle and
    /// the value at the last history bar — bit-identical to [`Core::COPPOCK`] at that bar.
    ///
    /// # Errors
    ///
    /// [`RetCode::InsufficientHistory`] when the history holds fewer than
    /// `lookback + 1` bars — the one failure here worth retrying, since another
    /// bar fixes it. [`RetCode::OutOfRangeStartIndex`] when the history is empty.
    /// [`RetCode::BadParam`] when a parameter is out of range or the input
    /// lengths differ.
    ///
    /// ```
    /// use ta_lib::Core;
    /// let data: Vec<f64> = (0..252).map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    ///
    /// let core = Core::new();
    /// let (mut s, _last) = core.coppock_open(&data, 10, 11, 14).expect("enough history");
    /// let r0 = s.out_range();
    /// let peeked = s.peek(100.9).expect("a finite bar");
    /// assert_eq!(s.out_range().count, r0.count); // a peek commits nothing
    /// let updated = s.update(100.9).expect("a finite bar");
    /// assert_eq!(s.out_range().beg_idx, r0.beg_idx);
    /// assert_eq!(s.out_range().count, r0.count + 1);
    /// assert_eq!(peeked.to_bits(), updated.to_bits());
    /// ```
    #[doc(alias = "TA_COPPOCK_Open")]
    pub fn coppock_open(&self, inReal: &[f64], optInWMAPeriod: i32, optInROC1Period: i32, optInROC2Period: i32) -> Result<(CoppockStream, f64), RetCode> {
        self.coppock_open_internal(inReal, 0, optInWMAPeriod, optInROC1Period, optInROC2Period)
    }

    /// [`Core::coppock_open`] that also fills the output array(s) bit-identically to
    /// [`Core::COPPOCK`] over `0..len` in the same single pass, and reports the range it
    /// wrote as the [`OutRange`] beside the handle.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] when an output slice holds fewer than `len - lookback`
    /// values — the batch tier's sizing rule, checked here as it is there (rule S5) —
    /// or when two of them are the same slice. Everything [`Core::coppock_open`] rejects
    /// is rejected here too.
    ///
    /// # Examples
    ///
    /// ```
    /// use ta_lib::Core;
    /// let data: Vec<f64> = (0..252).map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    ///
    /// let core = Core::new();
    /// let mut batch_out = vec![0.0; 252];
    /// let batch = core.COPPOCK(0, data.len() - 1, &data, 10, 11, 14, &mut batch_out)?;
    ///
    /// let mut out = vec![0.0; 252];
    /// let (_stream, filled) = core.coppock_open_and_fill(&data, 10, 11, 14, &mut out)?;
    ///
    /// assert_eq!(filled.beg_idx, batch.beg_idx);
    /// assert_eq!(filled.count, batch.count);
    /// assert!(out[..filled.count].iter().zip(&batch_out[..batch.count])
    ///     .all(|(a, b)| a.to_bits() == b.to_bits()));
    /// # Ok::<(), ta_lib::RetCode>(())
    /// ```
    #[doc(alias = "TA_COPPOCK_OpenAndFill")]
    pub fn coppock_open_and_fill(
        &self, inReal: &[f64], mut optInWMAPeriod: i32, mut optInROC1Period: i32, mut optInROC2Period: i32, outReal: &mut [f64],
    ) -> Result<(CoppockStream, OutRange), RetCode> {
        if inReal.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inReal.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        let _guardLb = self.COPPOCK_Lookback(optInWMAPeriod, optInROC1Period, optInROC2Period)?;
        let _guardOutLen = inReal.len().saturating_sub(_guardLb);
        if outReal.len() < _guardOutLen {
            return Err(RetCode::BadParam);
        }
        let mut outBegIdx: usize = 0;
        let mut outNBElement: usize = 0;
        let handle = self.coppock_open_and_fill_internal(inReal, 0, optInWMAPeriod, optInROC1Period, optInROC2Period, &mut outBegIdx, &mut outNBElement, outReal)?;
        Ok((handle, OutRange { beg_idx: outBegIdx, count: outNBElement }))
    }

    /// [`Core::coppock_open_and_fill`] anchored at `startIdx` — the composed-open
    /// fusion seam (issue #192), not a public entry point.
    pub(crate) fn coppock_open_and_fill_internal(
        &self, inReal: &[f64], startIdx: usize, mut optInWMAPeriod: i32, mut optInROC1Period: i32, mut optInROC2Period: i32, outBegIdx: &mut usize, outNBElement: &mut usize, outReal: &mut [f64],
    ) -> Result<CoppockStream, RetCode> {
        self.coppock_open_impl(inReal, startIdx, optInWMAPeriod, optInROC1Period, optInROC2Period, outBegIdx, outNBElement, outReal, 1)
    }

}

#[allow(non_snake_case)]
#[allow(unused_variables)]
#[allow(unused_mut)]
#[allow(unused_assignments)]
#[allow(unused_parens)]
impl CoppockStream {
    /// Commit one closed bar. Never allocates.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite (NaN or ±Inf).
    /// That check runs before anything is written, so the handle's state is
    /// left exactly as it was and the stream stays usable: skip the bar, or
    /// close and re-open on a clean history. This is the one place the
    /// streaming tier is stricter than the batch API, which computes on
    /// whatever it is given — a handle retains its state, so a single
    /// non-finite bar would poison every later value it produces.
    ///
    /// A rejection leaves [`Self::out_range`] alone too. Re-feed the bar when
    /// a corrected value arrives, or call [`Self::advance`] to count it and
    /// carry on — two handles on one feed drift a bar apart if neither
    /// happens.
    #[doc(alias = "TA_COPPOCK_Update")]
    pub fn update(&mut self, inReal: f64) -> Result<f64, RetCode> {
        if !inReal.is_finite() {
            return Err(RetCode::BadParam);
        }
        let mut outReal: f64 = 0.0_f64;
        Core::coppock_step_impl(&mut self.state, inReal, &mut outReal);
        if self.out.count < Core::MAX_INDEX {
            self.out.count += 1;
        }
        Ok(outReal)
    }

    /// Evaluate a forming bar without committing — bit-identical to what the
    /// next `update` with the same bar would return: the same transition,
    /// rewritten so every store it would make lives in a local instead. It
    /// allocates nothing and copies no buffer, so its cost does not grow with
    /// the period, and it writes no part of the handle — peeks may run
    /// concurrently with each other.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite, on the same test
    /// `update` applies, and a rejected peek changes nothing at all.
    #[doc(alias = "TA_COPPOCK_Peek")]
    pub fn peek(&self, inReal: f64) -> Result<f64, RetCode> {
        if !inReal.is_finite() {
            return Err(RetCode::BadParam);
        }
        let mut outReal: f64 = 0.0_f64;
        {
            let sp = &self.state;
            let outReal = &mut outReal;
            let mut q: usize = 0_usize;
            let mut rw: usize = 0_usize;
            let mut ringWalk: usize = 0_usize;
            let mut tempReal: f64 = 0.0_f64;
            let mut tempReal2: f64 = 0.0_f64;
            let mut base1: f64 = 0.0_f64;
            let mut base2: f64 = 0.0_f64;
            let mut roc1: f64 = 0.0_f64;
            let mut roc2: f64 = 0.0_f64;
            let mut barsSinceReseed = sp.barsSinceReseed;
            let mut periodSub = sp.periodSub;
            let mut periodSum = sp.periodSum;
            let mut sRing_Idx = sp.sRing_Idx;
            let mut trailingValue = sp.trailingValue;
            let mut pkSlot0: usize = usize::MAX;
            let mut pkVal0: f64 = 0.0_f64;
            let mut pkSlot1: usize = usize::MAX;
            let mut pkVal1: f64 = 0.0_f64;
            if sp.ringCap_roc1Idx == 0 {
                pkSlot0 = 0;
                pkVal0 = inReal;
            }
            if sp.ringCap_roc2Idx == 0 {
                pkSlot1 = 0;
                pkVal1 = inReal;
            }
            base1 = (if (sp.ringPos_roc1Idx as usize) != pkSlot0 { sp.ring_roc1Idx_inReal[sp.ringPos_roc1Idx] } else { pkVal0 });
            base2 = (if (sp.ringPos_roc2Idx as usize) != pkSlot1 { sp.ring_roc2Idx_inReal[sp.ringPos_roc2Idx] } else { pkVal1 });
            roc1 = (if base1 != 0.0 { (inReal / base1 - 1.0) * 100.0 } else { 0.0 });
            roc2 = (if base2 != 0.0 { (inReal / base2 - 1.0) * 100.0 } else { 0.0 });
            tempReal = roc1 + roc2;
            periodSub += tempReal;
            periodSub -= trailingValue;
            periodSum += tempReal * ((sp.optInWMAPeriod) as f64);
            // Re-anchor every 8*w bars: rebuild both totals from the window
            // itself -- TA_WMA's #254 fix, same single trigger, same interval.
            // The window lives in the ring (w-1 prior S values, sRing_Idx the
            // oldest) plus the current bar's tempReal at weight w.
            barsSinceReseed -= 1;
            if barsSinceReseed <= 0 {
                barsSinceReseed = (8 * sp.optInWMAPeriod) as usize;
                periodSub = 0.0 as f64;
                periodSum = 0.0 as f64;
                rw = 1;
                ringWalk = sRing_Idx;
                // for( q = 0; q < sp.ringSize; q += 1 )
                q = 0;
                while q < sp.ringSize {
                    tempReal2 = sp.cb_sRing[ringWalk];
                    periodSub += tempReal2;
                    periodSum += tempReal2 * ((rw) as f64);
                    rw += 1;
                    ringWalk += 1;
                    if ringWalk >= sp.ringSize {
                        ringWalk = 0;
                    }
                    q += 1;
                }
                periodSub += tempReal;
                periodSum += tempReal * ((sp.optInWMAPeriod) as f64);
            }
            // Read the expiring S value BEFORE overwriting its slot with the
            // current one -- the ring is the aliasing-safe stand-in for TA_WMA's
            // "save the trailing value before the store" rule.
            trailingValue = sp.cb_sRing[sRing_Idx];
            sRing_Idx = sRing_Idx + 1;
            if sRing_Idx > sp.maxIdx_sRing {
                sRing_Idx = 0;
            }
            // Load-bearing, not a rounding nicety: keep it. WMA(1) is the identity
            // and TA_WMA ships an exact copy fast path, but the recurrence here is
            // off by a whole term at w == 1 -- ringSize clamps to 1, so the
            // read-before-write ring hands back the wrong trailing value. Deleting
            // this arm moves TA_SREF bar 16 at (1,11,14) from -11.311839169954585
            // to -6.4591709868291103.
            if sp.optInWMAPeriod == 1 {
                (*outReal) = tempReal;
            } else {
                (*outReal) = periodSum / sp.divider;
            }
        }
        Ok(outReal)
    }

    /// The value(s) at the last bar the stream counted — the bar
    /// [`Self::out_range`] ends on — without recomputing. Seeded by the opener,
    /// refreshed by every accepted `update`, and left
    /// alone by `peek`.
    ///
    /// A clone carries them verbatim, so a forked handle can be asked its
    /// current value without committing a bar to find out.
    #[must_use]
    #[doc(alias = "TA_COPPOCK_Value")]
    pub fn value(&self) -> f64 {
        self.state.cur_outReal
    }

    /// The bars this stream has an output for, in the input series'
    /// coordinates: `[beg_idx, beg_idx + count)`.
    ///
    /// It is what [`Core::COPPOCK`] reports over the same bars: the opener sets it
    /// to `(lookback, historyLen - lookback)`, every accepted `update` adds
    /// one to the count — a rejected one changes nothing, and neither does
    /// `peek` — and a clone carries it verbatim. A plain `Open` hands back
    /// only the last value, a subset of this range, because the caller chose
    /// not to take the fill.
    #[doc(alias = "TA_COPPOCK_OutRange")]
    pub fn out_range(&self) -> OutRange {
        self.out
    }

    /// Count one bar this stream was not fed: [`Self::out_range`] advances by
    /// one and nothing else moves — [`Self::value`] keeps answering the
    /// previous output, which is this bar's output too.
    ///
    /// For a bar the caller leaves out: one an `update` rejected and that
    /// will not be re-fed, or a session with no print. Without it two handles
    /// on one feed drift a bar apart when only one of them skips.
    #[doc(alias = "TA_COPPOCK_Advance")]
    pub fn advance(&mut self) {
        if self.out.count < Core::MAX_INDEX {
            self.out.count += 1;
        }
    }
}

