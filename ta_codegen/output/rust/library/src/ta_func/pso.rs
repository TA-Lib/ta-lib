    /// assert!(out[..out_range.count].iter().all(|v| v.is_finite()));
    /// # Ok::<(), ta_lib::RetCode>(())
    /// ```
    ///
    /// # See also
    ///
    /// [`STOCHF`](Core::stochf) · [`STOCH`](Core::stoch) · [`SMI`](Core::smi) ·
    /// [`WILLR`](Core::willr)
    ///
    /// # References
    ///
    /// * Lee Leibfarth, "Premier Stochastic Oscillator", *Technical Analysis of Stocks &
    ///   Commodities*, v26:8 (August 2008), pp. 30-36
    #[doc(alias = "TA_PSO")]
    #[doc(alias = "premierstochasticoscillator")]
    #[doc(alias = "premierstochastic")]
    pub fn pso(
        &self,
        startIdx: usize,
        endIdx: usize,
        inHigh: &[f64],
        inLow: &[f64],
        inClose: &[f64],
        optInFastK_Period: i32,
        optInEMAPeriod: i32,
        outReal: &mut [f64],
    ) -> Result<OutRange, RetCode> {
        if startIdx > Self::INDEX_MAX {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if endIdx > Self::INDEX_MAX || endIdx < startIdx {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        let _guardLb = self.pso_lookback(optInFastK_Period, optInEMAPeriod)?;
        let _guardStart = if startIdx > _guardLb { startIdx } else { _guardLb };
        if inHigh.len() < endIdx + 1 {
            return Err(RetCode::BadParam);
        }
        if inLow.len() < endIdx + 1 {
            return Err(RetCode::BadParam);
        }
        if inClose.len() < endIdx + 1 {
            return Err(RetCode::BadParam);
        }
        let _guardOutLen = if _guardStart > endIdx { 0 } else { endIdx - _guardStart + 1 };
        if outReal.is_empty() || outReal.len() < _guardOutLen {
            return Err(RetCode::BadParam);
        }
        let mut outBegIdx: usize = 0;
        let mut outNBElement: usize = 0;
        let retCode = self.pso_impl(
            startIdx,
            endIdx,
            inHigh,
            inLow,
            inClose,
            optInFastK_Period,
            optInEMAPeriod,
            &mut outBegIdx,
            &mut outNBElement,
            outReal,
        );
        match retCode {
            RetCode::Success => Ok(OutRange { beg_idx: outBegIdx, count: outNBElement }),
            e => Err(e),
        }
    }

