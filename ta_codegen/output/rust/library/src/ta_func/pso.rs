    /// * `inLow` — Low price series.
    /// * `inClose` — Close price series.
    /// * `optInFastK_Period` — Time period for building the Fast-K line (default 8, range
    ///   1..=100000)
    /// * `optInEMAPeriod` — Period of each of the two smoothing passes (default 5, range
    ///   1..=100000)
    /// * `outReal` — Premier Stochastic Oscillator, -1 to +1.
