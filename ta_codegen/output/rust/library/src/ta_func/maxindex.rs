        let mut dummyNBElement: usize = 0;
        let mut sink_outInteger = [0_i32; 1];
        let handle = self.maxindex_open_impl(inReal, startIdx, optInTimePeriod, &mut dummyBegIdx, &mut dummyNBElement, &mut sink_outInteger, 0)?;
