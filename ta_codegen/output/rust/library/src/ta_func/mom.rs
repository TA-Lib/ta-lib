impl Core {
    fn mom_step_impl(sp: &mut MomStreamState, inReal: f64, outReal: &mut f64) {
        if sp.ringCap_trailingIdx == 0 {
            sp.ring_trailingIdx_inReal[0] = inReal;
        }
        (*outReal) = inReal - sp.ring_trailingIdx_inReal[sp.ringPos_trailingIdx];
        sp.ring_trailingIdx_inReal[sp.ringPos_trailingIdx] = inReal;
        sp.ringPos_trailingIdx = sp.ringPos_trailingIdx + 1;
        if sp.ringPos_trailingIdx >= sp.ringCap_trailingIdx {
            sp.ringPos_trailingIdx = 0;
        }
    }

    /// The single whole-history transcription behind [`Core::mom_open_internal`]
    /// (stride 0, scalar sink) and [`Core::mom_open_and_fill`] (stride 1, caller slices).
    pub(crate) fn mom_open_impl(
        &self, inReal: &[f64], startIdx: usize, mut optInTimePeriod: i32, outBegIdx: &mut usize, outNBElement: &mut usize, outReal: &mut [f64], outStride: usize,
    ) -> Result<MomStream, RetCode> {
        if inReal.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inReal.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        if ((optInTimePeriod) as i32) == (i32::MIN) {
            optInTimePeriod = 10;
        } else if (((optInTimePeriod) as i32) < 1) || (((optInTimePeriod) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        let historyLen: usize = inReal.len();
        let endIdx: usize = historyLen - 1;
        let mut startIdx = startIdx;
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut inIdx: usize = 0_usize;
        let mut outIdx: usize = 0_usize;
        let mut trailingIdx: usize = 0_usize;
        // The interpretation of the rate of change varies widely depending
        // which software and/or books you are refering to.
        //
        // The following is the table of Rate-Of-Change implemented in TA-LIB:
        //       MOM     = (price - prevPrice)         [Momentum]
        //       ROC     = ((price/prevPrice)-1)*100   [Rate of change]
        //       ROCP    = (price-prevPrice)/prevPrice [Rate of change Percentage]
        //       ROCR    = (price/prevPrice)           [Rate of change ratio]
        //       ROCR100 = (price/prevPrice)*100       [Rate of change ratio 100 Scale]
        //
        // Here are the equivalent function in other software:
        //       TA-Lib  |   Tradestation   |    Metastock
        //       =================================================
        //       MOM     |   Momentum       |    ROC (Point)
        //       ROC     |   ROC            |    ROC (Percent)
        //       ROCP    |   PercentChange  |    -
        //       ROCR    |   -              |    -
        //       ROCR100 |   -              |    MO
        //
        // The MOM function is the only one who is not normalized, and thus
        // should be avoided for comparing different time serie of prices.
        //
        // ROC and ROCP are centered at zero and can have positive and negative
        // value. Here are some equivalence:
        //    ROC = ROCP/100
        //        = ((price-prevPrice)/prevPrice)/100
        //        = ((price/prevPrice)-1)*100
        //
        // ROCR and ROCR100 are ratio respectively centered at 1 and 100 and are
        // always positive values.
        // Move up the start index if there is not
        // enough initial data.
        if startIdx < ((optInTimePeriod) as usize) {
            startIdx = (optInTimePeriod) as usize;
        }
        // Make sure there is still something to evaluate.
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        // Calculate Momentum:
        //    Just substract the value from 'period' ago from
        //    current value.
        outIdx = 0;
        inIdx = startIdx;
        trailingIdx = startIdx - ((optInTimePeriod) as usize);
        while inIdx <= endIdx {
            outReal[({ let _v = outIdx; outIdx += 1; _v } * outStride) as usize] = ((inReal[{ let _v = inIdx; inIdx += 1; _v }] - inReal[{ let _v = trailingIdx; trailingIdx += 1; _v }]) as f64);
        }
        // Set output limits.
        (*outNBElement) = outIdx;
        (*outBegIdx) = startIdx;

        // Capture the live batch state into the handle.
        let cap_trailingIdx: i64 = (inIdx as i64) - (trailingIdx as i64);
        if cap_trailingIdx < 0 || cap_trailingIdx > historyLen as i64 {
            return Err(RetCode::InternalError);
        }
        let allocN_trailingIdx: usize = if cap_trailingIdx > 0 { cap_trailingIdx as usize } else { 1 };
        let mut ring_trailingIdx_inReal: Vec<f64> = vec![0.0_f64; allocN_trailingIdx];
        ring_trailingIdx_inReal[..cap_trailingIdx as usize]
            .copy_from_slice(&inReal[historyLen - cap_trailingIdx as usize..]);
        let state = MomStreamState {
            optInTimePeriod,
            ringPos_trailingIdx: 0_usize,
            ringCap_trailingIdx: cap_trailingIdx as usize,
            ring_trailingIdx_inReal,
        };
        Ok(MomStream { state, out: OutRange { beg_idx: *outBegIdx, count: *outNBElement } })
    }

    /// Internal startIdx-anchored open behind [`Core::mom_open`] (composition seam).
    pub(crate) fn mom_open_internal(
        &self, inReal: &[f64], startIdx: usize, mut optInTimePeriod: i32,
    ) -> Result<(MomStream, f64), RetCode> {
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut sink_outReal = [0.0_f64; 1];
        let handle = self.mom_open_impl(inReal, startIdx, optInTimePeriod, &mut dummyBegIdx, &mut dummyNBElement, &mut sink_outReal, 0)?;
        Ok((handle, sink_outReal[0]))
    }

    /// Open a live MOM stream over the warm-up history; returns the handle and
    /// the value at the last history bar — bit-identical to [`Core::MOM`] at that bar.
    ///
    /// # Errors
    ///
    /// [`RetCode::InsufficientHistory`] when the history holds fewer than
    /// `lookback + 1` bars — the one failure here worth retrying, since another
    /// bar fixes it. [`RetCode::OutOfRangeStartIndex`] when the history is empty.
    /// [`RetCode::BadParam`] when a parameter is out of range or the input
    /// lengths differ.
    ///
    /// ```
    /// use ta_lib::Core;
    /// let data: Vec<f64> = (0..252).map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    ///
    /// let core = Core::new();
    /// let (mut s, _last) = core.mom_open(&data, 10).expect("enough history");
    /// let r0 = s.out_range();
    /// let peeked = s.peek(100.9).expect("a finite bar");
    /// assert_eq!(s.out_range().count, r0.count); // a peek commits nothing
    /// let updated = s.update(100.9).expect("a finite bar");
    /// assert_eq!(s.out_range().beg_idx, r0.beg_idx);
    /// assert_eq!(s.out_range().count, r0.count + 1);
    /// assert_eq!(peeked.to_bits(), updated.to_bits());
    /// ```
    #[doc(alias = "TA_MOM_Open")]
    pub fn mom_open(&self, inReal: &[f64], optInTimePeriod: i32) -> Result<(MomStream, f64), RetCode> {
        self.mom_open_internal(inReal, 0, optInTimePeriod)
    }

    /// [`Core::mom_open`] that also fills the output array(s) bit-identically to
    /// [`Core::MOM`] over `0..len` in the same single pass, and reports the range it
    /// wrote as the [`OutRange`] beside the handle.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] when an output slice holds fewer than `len - lookback`
    /// values — the batch tier's sizing rule, checked here as it is there (rule S5) —
    /// or when two of them are the same slice. Everything [`Core::mom_open`] rejects
    /// is rejected here too.
    ///
    /// # Examples
    ///
    /// ```
    /// use ta_lib::Core;
    /// let data: Vec<f64> = (0..252).map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    ///
    /// let core = Core::new();
    /// let mut batch_out = vec![0.0; 252];
    /// let batch = core.MOM(0, data.len() - 1, &data, 10, &mut batch_out)?;
    ///
    /// let mut out = vec![0.0; 252];
    /// let (_stream, filled) = core.mom_open_and_fill(&data, 10, &mut out)?;
    ///
    /// assert_eq!(filled.beg_idx, batch.beg_idx);
    /// assert_eq!(filled.count, batch.count);
    /// assert!(out[..filled.count].iter().zip(&batch_out[..batch.count])
    ///     .all(|(a, b)| a.to_bits() == b.to_bits()));
    /// # Ok::<(), ta_lib::RetCode>(())
    /// ```
    #[doc(alias = "TA_MOM_OpenAndFill")]
    pub fn mom_open_and_fill(
        &self, inReal: &[f64], mut optInTimePeriod: i32, outReal: &mut [f64],
    ) -> Result<(MomStream, OutRange), RetCode> {
        if inReal.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inReal.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        let _guardLb = self.MOM_Lookback(optInTimePeriod)?;
        let _guardOutLen = inReal.len().saturating_sub(_guardLb);
        if outReal.len() < _guardOutLen {
            return Err(RetCode::BadParam);
        }
        let mut outBegIdx: usize = 0;
        let mut outNBElement: usize = 0;
        let handle = self.mom_open_and_fill_internal(inReal, 0, optInTimePeriod, &mut outBegIdx, &mut outNBElement, outReal)?;
        Ok((handle, OutRange { beg_idx: outBegIdx, count: outNBElement }))
    }

    /// [`Core::mom_open_and_fill`] anchored at `startIdx` — the composed-open
    /// fusion seam (issue #192), not a public entry point.
    pub(crate) fn mom_open_and_fill_internal(
        &self, inReal: &[f64], startIdx: usize, mut optInTimePeriod: i32, outBegIdx: &mut usize, outNBElement: &mut usize, outReal: &mut [f64],
    ) -> Result<MomStream, RetCode> {
        self.mom_open_impl(inReal, startIdx, optInTimePeriod, outBegIdx, outNBElement, outReal, 1)
    }

}

#[allow(non_snake_case)]
#[allow(unused_variables)]
impl MomStream {
    /// Commit one closed bar. Never allocates.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite (NaN or ±Inf).
    /// That check runs before anything is written, so the handle is left
    /// exactly as it was and the stream stays usable:
    /// skip the bar, or close and re-open on a clean history. This is the
    /// one place the streaming tier is stricter than the batch API, which
    /// computes on whatever it is given — a handle retains its state, so a
    /// single non-finite bar would poison every later value it produces.
    #[doc(alias = "TA_MOM_Update")]
    pub fn update(&mut self, inReal: f64) -> Result<f64, RetCode> {
        if !inReal.is_finite() {
            return Err(RetCode::BadParam);
        }
        let mut outReal: f64 = 0.0_f64;
        Core::mom_step_impl(&mut self.state, inReal, &mut outReal);
        if self.out.count < Core::MAX_INDEX {
            self.out.count += 1;
        }
        Ok(outReal)
    }

    /// Commit `n` closed bars and write their `n` values, in one call —
    /// exactly `n` back-to-back [`Self::update`] calls, with one set of
    /// argument checks instead of `n`. `n` is `inReal.len()`; the outputs must
    /// hold at least that many. Never allocates.
    ///
    /// [`Self::out_range`] counts what was committed, which is what makes the
    /// rejection below readable: there is no second out-parameter for it.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if the input slices differ in length, if an output
    /// is shorter than the bar count — neither commits anything — or if a bar
    /// is not finite. A non-finite bar `k` is rejected exactly as `update`
    /// rejects it: bars `0..k` stay committed and their values written, bar `k`
    /// and everything after it is not, and `out_range().count` has advanced by
    /// `k`.
    #[doc(alias = "TA_MOM_UpdateAndFill")]
    pub fn update_and_fill(&mut self, inReal: &[f64], outReal: &mut [f64]) -> Result<(), RetCode> {
        let barCount = inReal.len();
        if outReal.len() < barCount {
            return Err(RetCode::BadParam);
        }
        for i in 0..barCount {
            if !inReal[i].is_finite() {
                return Err(RetCode::BadParam);
            }
            Core::mom_step_impl(&mut self.state, inReal[i], &mut outReal[i]);
            if self.out.count < Core::MAX_INDEX {
                self.out.count += 1;
            }
        }
        Ok(())
    }

    /// Evaluate a forming bar without committing — bit-identical to what the
    /// next `update` with the same bar would return (it is the same code, run
    /// on a scratch copy of the state). Never writes the handle, so peeks may
    /// run concurrently with each other. The copy is a throwaway. Its buffer clone is
    /// often removed outright by the optimizer, which is why nothing is
    /// reused here, but that is not a guarantee: budget for a clone of the
    /// buffers it does own and prefer `update` on a `clone()` in a hot loop.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite, exactly as
    /// `update` rejects it.
    #[doc(alias = "TA_MOM_Peek")]
    pub fn peek(&self, inReal: f64) -> Result<f64, RetCode> {
        if !inReal.is_finite() {
            return Err(RetCode::BadParam);
        }
        let mut scratch = self.clone();
        scratch.update(inReal)
    }

    /// The bars this stream has produced a value for, in the input series'
    /// coordinates: `[beg_idx, beg_idx + count)`.
    ///
    /// It is what [`Core::MOM`] reports over the same bars: the opener sets it
    /// to `(lookback, historyLen - lookback)`, every accepted `update` adds one
    /// to the count, `peek` leaves it alone, and a clone carries it verbatim.
    /// A plain `Open` hands back only the last value, a subset of this range,
    /// because the caller chose not to take the fill.
    #[doc(alias = "TA_StreamOutRange")]
    pub fn out_range(&self) -> OutRange {
        self.out
    }
}

