impl Core {
    fn cdlcounterattack_step_impl(sp: &mut CdlcounterattackStreamState, cs_body_long: &CandleSetting, cs_equal: &CandleSetting, inOpen: f64, inHigh: f64, inLow: f64, inClose: f64, outInteger: &mut i32) {
        let mut totIdx: usize = 0_usize;
        #[allow(non_snake_case)]
        let BodyLong_rangeType: i32 = cs_body_long.range_type as i32;
        #[allow(non_snake_case)]
        let BodyLong_avgPeriod: i32 = cs_body_long.avg_period;
        #[allow(non_snake_case)]
        let BodyLong_factor: f64 = cs_body_long.factor;
        #[allow(non_snake_case)]
        let Equal_rangeType: i32 = cs_equal.range_type as i32;
        #[allow(non_snake_case)]
        let Equal_avgPeriod: i32 = cs_equal.avg_period;
        #[allow(non_snake_case)]
        let Equal_factor: f64 = cs_equal.factor;
        let mut _candlerange_0: f64;
        match BodyLong_rangeType {
            0 => {
                _candlerange_0 = (inClose - inOpen).abs();
            }
            1 => {
                _candlerange_0 = inHigh - inLow;
            }
            2 => {
                _candlerange_0 = (inHigh - (if inClose >= inOpen { inClose } else { inOpen })) + ((if inClose >= inOpen { inOpen } else { inClose }) - inLow);
            }
            _ => {
                _candlerange_0 = 0.0;
            }
        }
        sp.ring_BodyLongTrailingIdx_derived[sp.ringPos_BodyLongTrailingIdx] = _candlerange_0;
        let mut _candlerange_1: f64;
        match Equal_rangeType {
            0 => {
                _candlerange_1 = (inClose - inOpen).abs();
            }
            1 => {
                _candlerange_1 = inHigh - inLow;
            }
            2 => {
                _candlerange_1 = (inHigh - (if inClose >= inOpen { inClose } else { inOpen })) + ((if inClose >= inOpen { inOpen } else { inClose }) - inLow);
            }
            _ => {
                _candlerange_1 = 0.0;
            }
        }
        sp.ring_EqualTrailingIdx_derived[sp.ringPos_EqualTrailingIdx] = _candlerange_1;
        if (if sp.lag1_inClose >= sp.lag1_inOpen { 1 } else { 0 - 1 }) == 0 - (if inClose >= inOpen { 1 } else { 0 - 1 }) && // opposite candles
           (sp.lag1_inClose - sp.lag1_inOpen).abs() > ((BodyLong_factor) * (if (BodyLong_avgPeriod) != 0 { (sp.BodyLongPeriodTotal[1]) / (BodyLong_avgPeriod as f64) } else { match BodyLong_rangeType { 0 => ((sp.lag1_inClose) - (sp.lag1_inOpen)).abs(), 1 => (sp.lag1_inHigh) - (sp.lag1_inLow), 2 => ((sp.lag1_inHigh) - (if (sp.lag1_inClose) >= (sp.lag1_inOpen) { (sp.lag1_inClose) } else { (sp.lag1_inOpen) })) + ((if (sp.lag1_inClose) >= (sp.lag1_inOpen) { (sp.lag1_inOpen) } else { (sp.lag1_inClose) }) - (sp.lag1_inLow)), _ => 0.0 } }) / (if (BodyLong_rangeType) == 2 { 2.0 } else { 1.0 })) && // 1st long
           (inClose - inOpen).abs() > ((BodyLong_factor) * (if (BodyLong_avgPeriod) != 0 { (sp.BodyLongPeriodTotal[0]) / (BodyLong_avgPeriod as f64) } else { match BodyLong_rangeType { 0 => ((inClose) - (inOpen)).abs(), 1 => (inHigh) - (inLow), 2 => ((inHigh) - (if (inClose) >= (inOpen) { (inClose) } else { (inOpen) })) + ((if (inClose) >= (inOpen) { (inOpen) } else { (inClose) }) - (inLow)), _ => 0.0 } }) / (if (BodyLong_rangeType) == 2 { 2.0 } else { 1.0 })) && // 2nd long
           inClose <= sp.lag1_inClose + ((Equal_factor) * (if (Equal_avgPeriod) != 0 { (sp.EqualPeriodTotal) / (Equal_avgPeriod as f64) } else { match Equal_rangeType { 0 => ((sp.lag1_inClose) - (sp.lag1_inOpen)).abs(), 1 => (sp.lag1_inHigh) - (sp.lag1_inLow), 2 => ((sp.lag1_inHigh) - (if (sp.lag1_inClose) >= (sp.lag1_inOpen) { (sp.lag1_inClose) } else { (sp.lag1_inOpen) })) + ((if (sp.lag1_inClose) >= (sp.lag1_inOpen) { (sp.lag1_inOpen) } else { (sp.lag1_inClose) }) - (sp.lag1_inLow)), _ => 0.0 } }) / (if (Equal_rangeType) == 2 { 2.0 } else { 1.0 })) && // equal closes
           inClose >= sp.lag1_inClose - ((Equal_factor) * (if (Equal_avgPeriod) != 0 { (sp.EqualPeriodTotal) / (Equal_avgPeriod as f64) } else { match Equal_rangeType { 0 => ((sp.lag1_inClose) - (sp.lag1_inOpen)).abs(), 1 => (sp.lag1_inHigh) - (sp.lag1_inLow), 2 => ((sp.lag1_inHigh) - (if (sp.lag1_inClose) >= (sp.lag1_inOpen) { (sp.lag1_inClose) } else { (sp.lag1_inOpen) })) + ((if (sp.lag1_inClose) >= (sp.lag1_inOpen) { (sp.lag1_inOpen) } else { (sp.lag1_inClose) }) - (sp.lag1_inLow)), _ => 0.0 } }) / (if (Equal_rangeType) == 2 { 2.0 } else { 1.0 }))
        {
            (*outInteger) = ((if inClose >= inOpen { 1 } else { 0 - 1 }) * 100) as i32;
        } else {
            (*outInteger) = 0;
        }
        // add the current range and subtract the first range: this is done after the pattern recognition
        // when avgPeriod is not 0, that means "compare with the previous candles" (it excludes the current candle)
        let mut _candlerange_2: f64;
        match Equal_rangeType {
            0 => {
                _candlerange_2 = (sp.lag1_inClose - sp.lag1_inOpen).abs();
            }
            1 => {
                _candlerange_2 = sp.lag1_inHigh - sp.lag1_inLow;
            }
            2 => {
                _candlerange_2 = (sp.lag1_inHigh - (if sp.lag1_inClose >= sp.lag1_inOpen { sp.lag1_inClose } else { sp.lag1_inOpen })) + ((if sp.lag1_inClose >= sp.lag1_inOpen { sp.lag1_inOpen } else { sp.lag1_inClose }) - sp.lag1_inLow);
            }
            _ => {
                _candlerange_2 = 0.0;
            }
        }
        sp.EqualPeriodTotal += _candlerange_2 - sp.ring_EqualTrailingIdx_derived[((sp.ringPos_EqualTrailingIdx + sp.ringCap_EqualTrailingIdx - sp.ringLag_EqualTrailingIdx - 1) % sp.ringCap_EqualTrailingIdx) as usize];
        // for( totIdx = 1; totIdx >= 0; totIdx -= 1 )
        totIdx = 1;
        loop {
            sp.BodyLongPeriodTotal[totIdx] = sp.BodyLongPeriodTotal[totIdx] + (sp.ring_BodyLongTrailingIdx_derived[((if sp.ringPos_BodyLongTrailingIdx + sp.ringCap_BodyLongTrailingIdx - totIdx >= sp.ringCap_BodyLongTrailingIdx { sp.ringPos_BodyLongTrailingIdx + sp.ringCap_BodyLongTrailingIdx - totIdx - sp.ringCap_BodyLongTrailingIdx } else { sp.ringPos_BodyLongTrailingIdx + sp.ringCap_BodyLongTrailingIdx - totIdx })) as usize] - sp.ring_BodyLongTrailingIdx_derived[((sp.ringPos_BodyLongTrailingIdx + sp.ringCap_BodyLongTrailingIdx - sp.ringLag_BodyLongTrailingIdx - totIdx) % sp.ringCap_BodyLongTrailingIdx) as usize]);
            if totIdx == 0 { break; }
            totIdx -= 1;
        }
        sp.lag1_inOpen = inOpen;
        sp.lag1_inHigh = inHigh;
        sp.lag1_inLow = inLow;
        sp.lag1_inClose = inClose;
        sp.ringPos_BodyLongTrailingIdx = sp.ringPos_BodyLongTrailingIdx + 1;
        if sp.ringPos_BodyLongTrailingIdx >= sp.ringCap_BodyLongTrailingIdx {
            sp.ringPos_BodyLongTrailingIdx = 0;
        }
        sp.ringPos_EqualTrailingIdx = sp.ringPos_EqualTrailingIdx + 1;
        if sp.ringPos_EqualTrailingIdx >= sp.ringCap_EqualTrailingIdx {
            sp.ringPos_EqualTrailingIdx = 0;
        }
    }

    /// The single whole-history transcription behind [`Core::cdlcounterattack_open_internal`]
    /// (stride 0, scalar sink) and [`Core::cdlcounterattack_open_and_fill`] (stride 1, caller slices).
    pub(crate) fn cdlcounterattack_open_impl(
        &self, inOpen: &[f64], inHigh: &[f64], inLow: &[f64], inClose: &[f64], startIdx: usize, outBegIdx: &mut usize, outNBElement: &mut usize, outInteger: &mut [i32], outStride: usize,
    ) -> Result<CdlcounterattackStream, RetCode> {
        if inOpen.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inOpen.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        if inHigh.len() != inOpen.len() || inLow.len() != inOpen.len() || inClose.len() != inOpen.len() {
            return Err(RetCode::BadParam);
        }
        let historyLen: usize = inOpen.len();
        let endIdx: usize = historyLen - 1;
        let mut startIdx = startIdx;
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut EqualPeriodTotal: f64 = 0.0_f64;
        let mut BodyLongPeriodTotal: [f64; 2 as usize] = [0.0_f64; 2 as usize];
        let mut i: usize = 0_usize;
        let mut outIdx: usize = 0_usize;
        let mut totIdx: usize = 0_usize;
        let mut EqualTrailingIdx: usize = 0_usize;
        let mut BodyLongTrailingIdx: usize = 0_usize;
        let mut lookbackTotal: usize = 0_usize;
        #[allow(non_snake_case)]
        let BodyLong_rangeType: i32 = self.candle_settings.body_long.range_type as i32;
        #[allow(non_snake_case)]
        let BodyLong_avgPeriod: i32 = self.candle_settings.body_long.avg_period;
        #[allow(non_snake_case)]
        let BodyLong_factor: f64 = self.candle_settings.body_long.factor;
        #[allow(non_snake_case)]
        let Equal_rangeType: i32 = self.candle_settings.equal.range_type as i32;
        #[allow(non_snake_case)]
        let Equal_avgPeriod: i32 = self.candle_settings.equal.avg_period;
        #[allow(non_snake_case)]
        let Equal_factor: f64 = self.candle_settings.equal.factor;
        // Identify the minimum number of price bar needed
        // to calculate at least one output.
        lookbackTotal = self.CDLCOUNTERATTACK_Lookback()?;
        // Move up the start index if there is not
        // enough initial data.
        if startIdx < lookbackTotal {
            startIdx = lookbackTotal;
        }
        // Make sure there is still something to evaluate.
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        // Do the calculation using tight loops.
        // Add-up the initial period, except for the last value.
        EqualPeriodTotal = 0.0;
        EqualTrailingIdx = startIdx - ((Equal_avgPeriod) as usize);
        BodyLongPeriodTotal[1] = 0.0;
        BodyLongPeriodTotal[0] = 0.0;
        BodyLongTrailingIdx = startIdx - ((BodyLong_avgPeriod) as usize);
        i = EqualTrailingIdx;
        while i < startIdx {
            let mut _candlerange_3: f64;
            match Equal_rangeType {
                0 => {
                    _candlerange_3 = (inClose[i - 1] - inOpen[i - 1]).abs();
                }
                1 => {
                    _candlerange_3 = inHigh[i - 1] - inLow[i - 1];
                }
                2 => {
                    _candlerange_3 = (inHigh[i - 1] - (if inClose[i - 1] >= inOpen[i - 1] { inClose[i - 1] } else { inOpen[i - 1] })) + ((if inClose[i - 1] >= inOpen[i - 1] { inOpen[i - 1] } else { inClose[i - 1] }) - inLow[i - 1]);
                }
                _ => {
                    _candlerange_3 = 0.0;
                }
            }
            EqualPeriodTotal += _candlerange_3;
            i += 1;
        }
        i = BodyLongTrailingIdx;
        while i < startIdx {
            let mut _candlerange_4: f64;
            match BodyLong_rangeType {
                0 => {
                    _candlerange_4 = (inClose[i - 1] - inOpen[i - 1]).abs();
                }
                1 => {
                    _candlerange_4 = inHigh[i - 1] - inLow[i - 1];
                }
                2 => {
                    _candlerange_4 = (inHigh[i - 1] - (if inClose[i - 1] >= inOpen[i - 1] { inClose[i - 1] } else { inOpen[i - 1] })) + ((if inClose[i - 1] >= inOpen[i - 1] { inOpen[i - 1] } else { inClose[i - 1] }) - inLow[i - 1]);
                }
                _ => {
                    _candlerange_4 = 0.0;
                }
            }
            BodyLongPeriodTotal[1] = BodyLongPeriodTotal[1] + _candlerange_4;
            let mut _candlerange_5: f64;
            match BodyLong_rangeType {
                0 => {
                    _candlerange_5 = (inClose[i] - inOpen[i]).abs();
                }
                1 => {
                    _candlerange_5 = inHigh[i] - inLow[i];
                }
                2 => {
                    _candlerange_5 = (inHigh[i] - (if inClose[i] >= inOpen[i] { inClose[i] } else { inOpen[i] })) + ((if inClose[i] >= inOpen[i] { inOpen[i] } else { inClose[i] }) - inLow[i]);
                }
                _ => {
                    _candlerange_5 = 0.0;
                }
            }
            BodyLongPeriodTotal[0] = BodyLongPeriodTotal[0] + _candlerange_5;
            i += 1;
        }
        i = startIdx;
        // Proceed with the calculation for the requested range.
        // Must have:
        // - first candle: long black (white)
        // - second candle: long white (black) with close equal to the prior close
        // The meaning of "equal" and "long" is specified with TA_SetCandleSettings
        // outInteger is positive (1 to 100) when bullish or negative (-1 to -100) when bearish;
        // the user should consider that counterattack is significant in a trend, while this function does not consider it
        outIdx = 0;
        loop {
            if (if inClose[i - 1] >= inOpen[i - 1] { 1 } else { 0 - 1 }) == 0 - (if inClose[i] >= inOpen[i] { 1 } else { 0 - 1 }) && // opposite candles
               (inClose[i - 1] - inOpen[i - 1]).abs() > ((BodyLong_factor) * (if (BodyLong_avgPeriod) != 0 { (BodyLongPeriodTotal[1]) / (BodyLong_avgPeriod as f64) } else { match BodyLong_rangeType { 0 => ((inClose[i - 1]) - (inOpen[i - 1])).abs(), 1 => (inHigh[i - 1]) - (inLow[i - 1]), 2 => ((inHigh[i - 1]) - (if (inClose[i - 1]) >= (inOpen[i - 1]) { (inClose[i - 1]) } else { (inOpen[i - 1]) })) + ((if (inClose[i - 1]) >= (inOpen[i - 1]) { (inOpen[i - 1]) } else { (inClose[i - 1]) }) - (inLow[i - 1])), _ => 0.0 } }) / (if (BodyLong_rangeType) == 2 { 2.0 } else { 1.0 })) && // 1st long
               (inClose[i] - inOpen[i]).abs() > ((BodyLong_factor) * (if (BodyLong_avgPeriod) != 0 { (BodyLongPeriodTotal[0]) / (BodyLong_avgPeriod as f64) } else { match BodyLong_rangeType { 0 => ((inClose[i]) - (inOpen[i])).abs(), 1 => (inHigh[i]) - (inLow[i]), 2 => ((inHigh[i]) - (if (inClose[i]) >= (inOpen[i]) { (inClose[i]) } else { (inOpen[i]) })) + ((if (inClose[i]) >= (inOpen[i]) { (inOpen[i]) } else { (inClose[i]) }) - (inLow[i])), _ => 0.0 } }) / (if (BodyLong_rangeType) == 2 { 2.0 } else { 1.0 })) && // 2nd long
               inClose[i] <= inClose[i - 1] + ((Equal_factor) * (if (Equal_avgPeriod) != 0 { (EqualPeriodTotal) / (Equal_avgPeriod as f64) } else { match Equal_rangeType { 0 => ((inClose[i - 1]) - (inOpen[i - 1])).abs(), 1 => (inHigh[i - 1]) - (inLow[i - 1]), 2 => ((inHigh[i - 1]) - (if (inClose[i - 1]) >= (inOpen[i - 1]) { (inClose[i - 1]) } else { (inOpen[i - 1]) })) + ((if (inClose[i - 1]) >= (inOpen[i - 1]) { (inOpen[i - 1]) } else { (inClose[i - 1]) }) - (inLow[i - 1])), _ => 0.0 } }) / (if (Equal_rangeType) == 2 { 2.0 } else { 1.0 })) && // equal closes
               inClose[i] >= inClose[i - 1] - ((Equal_factor) * (if (Equal_avgPeriod) != 0 { (EqualPeriodTotal) / (Equal_avgPeriod as f64) } else { match Equal_rangeType { 0 => ((inClose[i - 1]) - (inOpen[i - 1])).abs(), 1 => (inHigh[i - 1]) - (inLow[i - 1]), 2 => ((inHigh[i - 1]) - (if (inClose[i - 1]) >= (inOpen[i - 1]) { (inClose[i - 1]) } else { (inOpen[i - 1]) })) + ((if (inClose[i - 1]) >= (inOpen[i - 1]) { (inOpen[i - 1]) } else { (inClose[i - 1]) }) - (inLow[i - 1])), _ => 0.0 } }) / (if (Equal_rangeType) == 2 { 2.0 } else { 1.0 }))
            {
                outInteger[({ let _v = outIdx; outIdx += 1; _v } * outStride) as usize] = ((if inClose[i] >= inOpen[i] { 1 } else { 0 - 1 }) * 100) as i32;
            } else {
                outInteger[({ let _v = outIdx; outIdx += 1; _v } * outStride) as usize] = 0;
            }
            // add the current range and subtract the first range: this is done after the pattern recognition
            // when avgPeriod is not 0, that means "compare with the previous candles" (it excludes the current candle)
            let mut _candlerange_6: f64;
            match Equal_rangeType {
                0 => {
                    _candlerange_6 = (inClose[i - 1] - inOpen[i - 1]).abs();
                }
                1 => {
                    _candlerange_6 = inHigh[i - 1] - inLow[i - 1];
                }
                2 => {
                    _candlerange_6 = (inHigh[i - 1] - (if inClose[i - 1] >= inOpen[i - 1] { inClose[i - 1] } else { inOpen[i - 1] })) + ((if inClose[i - 1] >= inOpen[i - 1] { inOpen[i - 1] } else { inClose[i - 1] }) - inLow[i - 1]);
                }
                _ => {
                    _candlerange_6 = 0.0;
                }
            }
            let mut _candlerange_7: f64;
            match Equal_rangeType {
                0 => {
                    _candlerange_7 = (inClose[EqualTrailingIdx - 1] - inOpen[EqualTrailingIdx - 1]).abs();
                }
                1 => {
                    _candlerange_7 = inHigh[EqualTrailingIdx - 1] - inLow[EqualTrailingIdx - 1];
                }
                2 => {
                    _candlerange_7 = (inHigh[EqualTrailingIdx - 1] - (if inClose[EqualTrailingIdx - 1] >= inOpen[EqualTrailingIdx - 1] { inClose[EqualTrailingIdx - 1] } else { inOpen[EqualTrailingIdx - 1] })) + ((if inClose[EqualTrailingIdx - 1] >= inOpen[EqualTrailingIdx - 1] { inOpen[EqualTrailingIdx - 1] } else { inClose[EqualTrailingIdx - 1] }) - inLow[EqualTrailingIdx - 1]);
                }
                _ => {
                    _candlerange_7 = 0.0;
                }
            }
            EqualPeriodTotal += _candlerange_6 - _candlerange_7;
            // for( totIdx = 1; totIdx >= 0; totIdx -= 1 )
            totIdx = 1;
            loop {
                let mut _candlerange_8: f64;
                match BodyLong_rangeType {
                    0 => {
                        _candlerange_8 = (inClose[i - totIdx] - inOpen[i - totIdx]).abs();
                    }
                    1 => {
                        _candlerange_8 = inHigh[i - totIdx] - inLow[i - totIdx];
                    }
                    2 => {
                        _candlerange_8 = (inHigh[i - totIdx] - (if inClose[i - totIdx] >= inOpen[i - totIdx] { inClose[i - totIdx] } else { inOpen[i - totIdx] })) + ((if inClose[i - totIdx] >= inOpen[i - totIdx] { inOpen[i - totIdx] } else { inClose[i - totIdx] }) - inLow[i - totIdx]);
                    }
                    _ => {
                        _candlerange_8 = 0.0;
                    }
                }
                let mut _candlerange_9: f64;
                match BodyLong_rangeType {
                    0 => {
                        _candlerange_9 = (inClose[BodyLongTrailingIdx - totIdx] - inOpen[BodyLongTrailingIdx - totIdx]).abs();
                    }
                    1 => {
                        _candlerange_9 = inHigh[BodyLongTrailingIdx - totIdx] - inLow[BodyLongTrailingIdx - totIdx];
                    }
                    2 => {
                        _candlerange_9 = (inHigh[BodyLongTrailingIdx - totIdx] - (if inClose[BodyLongTrailingIdx - totIdx] >= inOpen[BodyLongTrailingIdx - totIdx] { inClose[BodyLongTrailingIdx - totIdx] } else { inOpen[BodyLongTrailingIdx - totIdx] })) + ((if inClose[BodyLongTrailingIdx - totIdx] >= inOpen[BodyLongTrailingIdx - totIdx] { inOpen[BodyLongTrailingIdx - totIdx] } else { inClose[BodyLongTrailingIdx - totIdx] }) - inLow[BodyLongTrailingIdx - totIdx]);
                    }
                    _ => {
                        _candlerange_9 = 0.0;
                    }
                }
                BodyLongPeriodTotal[totIdx] = BodyLongPeriodTotal[totIdx] + (_candlerange_8 - _candlerange_9);
                if totIdx == 0 { break; }
                totIdx -= 1;
            }
            i += 1;
            EqualTrailingIdx += 1;
            BodyLongTrailingIdx += 1;
            if !(i <= endIdx) { break; }
        }
        // All done. Indicate the output limits and return.
        (*outNBElement) = outIdx;
        (*outBegIdx) = startIdx;

        // Capture the live batch state into the handle.
        let capLag_BodyLongTrailingIdx: i64 = (i as i64) - (BodyLongTrailingIdx as i64);
        let cap_BodyLongTrailingIdx: i64 = capLag_BodyLongTrailingIdx + 2;
        if capLag_BodyLongTrailingIdx < 0 || cap_BodyLongTrailingIdx > historyLen as i64 {
            return Err(RetCode::InternalError);
        }
        let allocN_BodyLongTrailingIdx: usize = if cap_BodyLongTrailingIdx > 0 { cap_BodyLongTrailingIdx as usize } else { 1 };
        let mut ring_BodyLongTrailingIdx_derived: Vec<f64> = vec![0.0_f64; allocN_BodyLongTrailingIdx];
        {
            let mut fillJ: usize = historyLen - cap_BodyLongTrailingIdx as usize;
            while fillJ < historyLen {
                ring_BodyLongTrailingIdx_derived[fillJ % cap_BodyLongTrailingIdx as usize] = (match BodyLong_rangeType { 0 => ((inClose[(fillJ) as usize]) - (inOpen[(fillJ) as usize])).abs(), 1 => (inHigh[(fillJ) as usize]) - (inLow[(fillJ) as usize]), 2 => ((inHigh[(fillJ) as usize]) - (if (inClose[(fillJ) as usize]) >= (inOpen[(fillJ) as usize]) { (inClose[(fillJ) as usize]) } else { (inOpen[(fillJ) as usize]) })) + ((if (inClose[(fillJ) as usize]) >= (inOpen[(fillJ) as usize]) { (inOpen[(fillJ) as usize]) } else { (inClose[(fillJ) as usize]) }) - (inLow[(fillJ) as usize])), _ => 0.0 });
                fillJ += 1;
            }
        }
        let capLag_EqualTrailingIdx: i64 = (i as i64) - (EqualTrailingIdx as i64);
        let cap_EqualTrailingIdx: i64 = capLag_EqualTrailingIdx + 2;
        if capLag_EqualTrailingIdx < 0 || cap_EqualTrailingIdx > historyLen as i64 {
            return Err(RetCode::InternalError);
        }
        let allocN_EqualTrailingIdx: usize = if cap_EqualTrailingIdx > 0 { cap_EqualTrailingIdx as usize } else { 1 };
        let mut ring_EqualTrailingIdx_derived: Vec<f64> = vec![0.0_f64; allocN_EqualTrailingIdx];
        {
            let mut fillJ: usize = historyLen - cap_EqualTrailingIdx as usize;
            while fillJ < historyLen {
                ring_EqualTrailingIdx_derived[fillJ % cap_EqualTrailingIdx as usize] = (match Equal_rangeType { 0 => ((inClose[(fillJ) as usize]) - (inOpen[(fillJ) as usize])).abs(), 1 => (inHigh[(fillJ) as usize]) - (inLow[(fillJ) as usize]), 2 => ((inHigh[(fillJ) as usize]) - (if (inClose[(fillJ) as usize]) >= (inOpen[(fillJ) as usize]) { (inClose[(fillJ) as usize]) } else { (inOpen[(fillJ) as usize]) })) + ((if (inClose[(fillJ) as usize]) >= (inOpen[(fillJ) as usize]) { (inOpen[(fillJ) as usize]) } else { (inClose[(fillJ) as usize]) }) - (inLow[(fillJ) as usize])), _ => 0.0 });
                fillJ += 1;
            }
        }
        let state = CdlcounterattackStreamState {
            EqualPeriodTotal,
            BodyLongPeriodTotal,
            lag1_inOpen: inOpen[historyLen - 1],
            lag1_inHigh: inHigh[historyLen - 1],
            lag1_inLow: inLow[historyLen - 1],
            lag1_inClose: inClose[historyLen - 1],
            ringPos_BodyLongTrailingIdx: historyLen % cap_BodyLongTrailingIdx as usize,
            ringCap_BodyLongTrailingIdx: cap_BodyLongTrailingIdx as usize,
            ringLag_BodyLongTrailingIdx: capLag_BodyLongTrailingIdx as usize,
            ring_BodyLongTrailingIdx_derived,
            ringPos_EqualTrailingIdx: historyLen % cap_EqualTrailingIdx as usize,
            ringCap_EqualTrailingIdx: cap_EqualTrailingIdx as usize,
            ringLag_EqualTrailingIdx: capLag_EqualTrailingIdx as usize,
            ring_EqualTrailingIdx_derived,
        };
        Ok(CdlcounterattackStream { cs_body_long: self.candle_settings.body_long, cs_equal: self.candle_settings.equal, state, out: OutRange { beg_idx: *outBegIdx, count: *outNBElement } })
    }

    /// Internal startIdx-anchored open behind [`Core::cdlcounterattack_open`] (composition seam).
    pub(crate) fn cdlcounterattack_open_internal(
        &self, inOpen: &[f64], inHigh: &[f64], inLow: &[f64], inClose: &[f64], startIdx: usize,
    ) -> Result<(CdlcounterattackStream, i32), RetCode> {
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut sink_outInteger = [0_i32; 1];
        let handle = self.cdlcounterattack_open_impl(inOpen, inHigh, inLow, inClose, startIdx, &mut dummyBegIdx, &mut dummyNBElement, &mut sink_outInteger, 0)?;
        Ok((handle, sink_outInteger[0]))
    }

    /// Open a live CDLCOUNTERATTACK stream over the warm-up history; returns the handle and
    /// the value at the last history bar — bit-identical to [`Core::CDLCOUNTERATTACK`] at that bar.
    ///
    /// # Errors
    ///
    /// [`RetCode::InsufficientHistory`] when the history holds fewer than
    /// `lookback + 1` bars — the one failure here worth retrying, since another
    /// bar fixes it. [`RetCode::OutOfRangeStartIndex`] when the history is empty.
    /// [`RetCode::BadParam`] when a parameter is out of range or the input
    /// lengths differ.
    ///
    /// ```
    /// use ta_lib::Core;
    /// let open: Vec<f64> = (0..252)
    ///     .map(|i| 100.0 + 10.0 * (0.1 * i as f64 - 0.05).sin())
    ///     .collect();
    /// let high: Vec<f64> = (0..252).map(|i| 101.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    /// let low: Vec<f64> = (0..252).map(|i| 99.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    /// let close: Vec<f64> = (0..252)
    ///     .map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin() + 0.8 * (0.7 * i as f64).sin())
    ///     .collect();
    ///
    /// let core = Core::new();
    /// let (mut s, _last) = core.cdlcounterattack_open(&open, &high, &low, &close).expect("enough history");
    /// let r0 = s.out_range();
    /// let peeked = s.peek(100.2, 101.4, 99.1, 100.9).expect("a finite bar");
    /// assert_eq!(s.out_range().count, r0.count); // a peek commits nothing
    /// let updated = s.update(100.2, 101.4, 99.1, 100.9).expect("a finite bar");
    /// assert_eq!(s.out_range().beg_idx, r0.beg_idx);
    /// assert_eq!(s.out_range().count, r0.count + 1);
    /// assert_eq!(peeked, updated);
    /// ```
    #[doc(alias = "TA_CDLCOUNTERATTACK_Open")]
    pub fn cdlcounterattack_open(&self, inOpen: &[f64], inHigh: &[f64], inLow: &[f64], inClose: &[f64], ) -> Result<(CdlcounterattackStream, i32), RetCode> {
        self.cdlcounterattack_open_internal(inOpen, inHigh, inLow, inClose, 0)
    }

    /// [`Core::cdlcounterattack_open`] that also fills the output array(s) bit-identically to
    /// [`Core::CDLCOUNTERATTACK`] over `0..len` in the same single pass, and reports the range it
    /// wrote as the [`OutRange`] beside the handle.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] when an output slice holds fewer than `len - lookback`
    /// values — the batch tier's sizing rule, checked here as it is there (rule S5) —
    /// or when two of them are the same slice. Everything [`Core::cdlcounterattack_open`] rejects
    /// is rejected here too.
    ///
    /// # Examples
    ///
    /// ```
    /// use ta_lib::Core;
    /// let open: Vec<f64> = (0..252)
    ///     .map(|i| 100.0 + 10.0 * (0.1 * i as f64 - 0.05).sin())
    ///     .collect();
    /// let high: Vec<f64> = (0..252).map(|i| 101.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    /// let low: Vec<f64> = (0..252).map(|i| 99.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    /// let close: Vec<f64> = (0..252)
    ///     .map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin() + 0.8 * (0.7 * i as f64).sin())
    ///     .collect();
    ///
    /// let core = Core::new();
    /// let mut batch_out = vec![0_i32; 252];
    /// let batch = core.CDLCOUNTERATTACK(0, open.len() - 1, &open, &high, &low, &close, &mut batch_out)?;
    ///
    /// let mut out = vec![0_i32; 252];
    /// let (_stream, filled) = core.cdlcounterattack_open_and_fill(&open, &high, &low, &close, &mut out)?;
    ///
    /// assert_eq!(filled.beg_idx, batch.beg_idx);
    /// assert_eq!(filled.count, batch.count);
    /// assert_eq!(out[..filled.count], batch_out[..batch.count]);
    /// # Ok::<(), ta_lib::RetCode>(())
    /// ```
    #[doc(alias = "TA_CDLCOUNTERATTACK_OpenAndFill")]
    pub fn cdlcounterattack_open_and_fill(
        &self, inOpen: &[f64], inHigh: &[f64], inLow: &[f64], inClose: &[f64], outInteger: &mut [i32],
    ) -> Result<(CdlcounterattackStream, OutRange), RetCode> {
        if inOpen.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inOpen.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        let _guardLb = self.CDLCOUNTERATTACK_Lookback()?;
        if inHigh.len() != inOpen.len() || inLow.len() != inOpen.len() || inClose.len() != inOpen.len() {
            return Err(RetCode::BadParam);
        }
        let _guardOutLen = inOpen.len().saturating_sub(_guardLb);
        if outInteger.len() < _guardOutLen {
            return Err(RetCode::BadParam);
        }
        let mut outBegIdx: usize = 0;
        let mut outNBElement: usize = 0;
        let handle = self.cdlcounterattack_open_and_fill_internal(inOpen, inHigh, inLow, inClose, 0, &mut outBegIdx, &mut outNBElement, outInteger)?;
        Ok((handle, OutRange { beg_idx: outBegIdx, count: outNBElement }))
    }

    /// [`Core::cdlcounterattack_open_and_fill`] anchored at `startIdx` — the composed-open
    /// fusion seam (issue #192), not a public entry point.
    pub(crate) fn cdlcounterattack_open_and_fill_internal(
        &self, inOpen: &[f64], inHigh: &[f64], inLow: &[f64], inClose: &[f64], startIdx: usize, outBegIdx: &mut usize, outNBElement: &mut usize, outInteger: &mut [i32],
    ) -> Result<CdlcounterattackStream, RetCode> {
        self.cdlcounterattack_open_impl(inOpen, inHigh, inLow, inClose, startIdx, outBegIdx, outNBElement, outInteger, 1)
    }

}

thread_local! {
    /// `peek`'s reusable scratch state (see `CdlcounterattackStreamState::restore_from`).
    /// Taken for the duration of the step and put back after, so a
    /// panicking step costs the scratch, never leaves it borrowed.
    static CDLCOUNTERATTACK_PEEK_SCRATCH: std::cell::Cell<Option<Box<CdlcounterattackStreamState>>> =
        const { std::cell::Cell::new(None) };
}

#[allow(non_snake_case)]
#[allow(unused_variables)]
impl CdlcounterattackStream {
    /// Commit one closed bar. Never allocates.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite (NaN or ±Inf).
    /// That check runs before anything is written, so the handle is left
    /// exactly as it was and the stream stays usable:
    /// skip the bar, or close and re-open on a clean history. This is the
    /// one place the streaming tier is stricter than the batch API, which
    /// computes on whatever it is given — a handle retains its state, so a
    /// single non-finite bar would poison every later value it produces.
    #[doc(alias = "TA_CDLCOUNTERATTACK_Update")]
    pub fn update(&mut self, inOpen: f64, inHigh: f64, inLow: f64, inClose: f64) -> Result<i32, RetCode> {
        if !inOpen.is_finite() || !inHigh.is_finite() || !inLow.is_finite() || !inClose.is_finite() {
            return Err(RetCode::BadParam);
        }
        let mut outInteger: i32 = 0_i32;
        Core::cdlcounterattack_step_impl(&mut self.state, &self.cs_body_long, &self.cs_equal, inOpen, inHigh, inLow, inClose, &mut outInteger);
        if self.out.count < Core::MAX_INDEX {
            self.out.count += 1;
        }
        Ok(outInteger)
    }

    /// Commit `n` closed bars and write their `n` values, in one call —
    /// exactly `n` back-to-back [`Self::update`] calls, with one set of
    /// argument checks instead of `n`. `n` is `inOpen.len()`; the outputs must
    /// hold at least that many. Never allocates.
    ///
    /// [`Self::out_range`] counts what was committed, which is what makes the
    /// rejection below readable: there is no second out-parameter for it.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if the input slices differ in length, if an output
    /// is shorter than the bar count — neither commits anything — or if a bar
    /// is not finite. A non-finite bar `k` is rejected exactly as `update`
    /// rejects it: bars `0..k` stay committed and their values written, bar `k`
    /// and everything after it is not, and `out_range().count` has advanced by
    /// `k`.
    #[doc(alias = "TA_CDLCOUNTERATTACK_UpdateAndFill")]
    pub fn update_and_fill(&mut self, inOpen: &[f64], inHigh: &[f64], inLow: &[f64], inClose: &[f64], outInteger: &mut [i32]) -> Result<(), RetCode> {
        let barCount = inOpen.len();
        if inHigh.len() != inOpen.len() || inLow.len() != inOpen.len() || inClose.len() != inOpen.len() || outInteger.len() < barCount {
            return Err(RetCode::BadParam);
        }
        for i in 0..barCount {
            if !inOpen[i].is_finite() || !inHigh[i].is_finite() || !inLow[i].is_finite() || !inClose[i].is_finite() {
                return Err(RetCode::BadParam);
            }
            Core::cdlcounterattack_step_impl(&mut self.state, &self.cs_body_long, &self.cs_equal, inOpen[i], inHigh[i], inLow[i], inClose[i], &mut outInteger[i]);
            if self.out.count < Core::MAX_INDEX {
                self.out.count += 1;
            }
        }
        Ok(())
    }

    /// Evaluate a forming bar without committing — bit-identical to what the
    /// next `update` with the same bar would return (it is the same code, run
    /// on a scratch copy of the state). Never writes the handle, so peeks may
    /// run concurrently with each other. The copy it runs on is held per thread and reused,
    /// so only the first peek of this function on a thread allocates.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite, exactly as
    /// `update` rejects it.
    #[doc(alias = "TA_CDLCOUNTERATTACK_Peek")]
    pub fn peek(&self, inOpen: f64, inHigh: f64, inLow: f64, inClose: f64) -> Result<i32, RetCode> {
        if !inOpen.is_finite() || !inHigh.is_finite() || !inLow.is_finite() || !inClose.is_finite() {
            return Err(RetCode::BadParam);
        }
        CDLCOUNTERATTACK_PEEK_SCRATCH.with(|cell| {
            let mut scratch = cell.take().unwrap_or_else(|| Box::new(self.state.clone()));
            scratch.restore_from(&self.state);
            let mut outInteger: i32 = 0_i32;
            Core::cdlcounterattack_step_impl(&mut scratch, &self.cs_body_long, &self.cs_equal, inOpen, inHigh, inLow, inClose, &mut outInteger);
            cell.set(Some(scratch));
            Ok(outInteger)
        })
    }

    /// The bars this stream has produced a value for, in the input series'
    /// coordinates: `[beg_idx, beg_idx + count)`.
    ///
    /// It is what [`Core::CDLCOUNTERATTACK`] reports over the same bars: the opener sets it
    /// to `(lookback, historyLen - lookback)`, every accepted `update` adds one
    /// to the count, `peek` leaves it alone, and a clone carries it verbatim.
    /// A plain `Open` hands back only the last value, a subset of this range,
    /// because the caller chose not to take the fill.
    #[doc(alias = "TA_StreamOutRange")]
    pub fn out_range(&self) -> OutRange {
        self.out
    }
}

