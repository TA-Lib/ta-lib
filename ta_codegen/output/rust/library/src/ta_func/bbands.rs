                    _tempReal = 0.0;
                    for _j in (_windowStart as usize)..(_i as usize) + 1 {
                        _tempReal += inReal[_j];
                    }
                    _j = (_i as usize) + 1;
                    shift = _tempReal * _invPeriod;
                    varTotal1 = 0.0;
                    varTotal2 = 0.0;
                    for _j in (_windowStart as usize)..(_i as usize) + 1 {
                        _tempReal = inReal[_j] - shift;
                        varTotal1 += _tempReal;
                        _tempReal *= _tempReal;
                        varTotal2 += _tempReal;
                    }
                    _j = (_i as usize) + 1;
                    meanValue1 = varTotal1 * _invPeriod;
