                    // dead-zone, so the square root below can be unconditional.
                    if variance < 0.000000000001 * (varTotal2 * _invPeriod) {
                        variance = 0.0;
                    }
                    _tempReal = inReal[_windowStart] - shift;
                    varTotal1 -= _tempReal;
                    _tempReal *= _tempReal;
                    varTotal2 -= _tempReal;
