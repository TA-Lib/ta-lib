                // declared domain can tell the two apart -- but there is no reason
                // to buy the disagreement, and `!= 0.0` is what this is for.
                outRealUpperBand[_outIdx] = (if variance != 0.0 { (variance).sqrt() } else { 0.0 });
                _outIdx += 1;
                _i += 1;
                if !(_i <= endIdx) { break; }
