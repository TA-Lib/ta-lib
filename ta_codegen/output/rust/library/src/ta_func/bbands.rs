            _trailingIdx = startIdx - _lookbackTotal;
            shift = inReal[_trailingIdx];
            maTotal = 0.0;
            varTotal1 = 0.0;
            varTotal2 = 0.0;
            // for( _j = _trailingIdx; _j < startIdx; _j += 1 )
