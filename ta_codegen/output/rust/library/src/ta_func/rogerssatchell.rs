    ///
    /// [`ATR`](Core::atr) · [`NATR`](Core::natr) · [`VAR`](Core::var)
    ///
    /// # References
    ///
    /// * Rogers, L. C. G. and Satchell, S. E. "Estimating Variance From High, Low and Closing
    ///   Prices." *The Annals of Applied Probability* 1(4):504-512, November 1991.
