    /// Rogers-Satchell volatility: a range-based estimator that reads one bar's open, high, low and
    /// close as a single unbiased estimate of that bar's variance, then reports the root of the
    /// mean over the last `n` bars, scaled to periods per year. What separates it from the other
    /// range estimators is that it is unbiased **whatever the drift**. A bar that opens at its low
    /// and closes at its high has travelled in one direction and dispersed nothing around that
    /// path, and this estimator reads it as exactly zero, where Parkinson and Garman-Klass read a
    /// wide range as volatility. The price of that is a blind spot of its own: the estimator has no
    /// close-to-open term, so overnight gaps are invisible to it. Read the output as a fraction in
    /// log-return units, not price units and not percent. At an `optInAnnualization` of 252 it is
    /// an annualised figure for daily bars; pass 1 to leave the per-bar figure, 52 for weekly bars,
    /// 12 for monthly.
    ///
    /// Formula and more info at
    /// [ta-lib.org/functions/rogerssatchell](https://ta-lib.org/functions/rogerssatchell).
    ///
    /// # Arguments
    ///
    /// * `startIdx` — Start index of the requested calculation range.
    /// * `endIdx` — End index of the requested calculation range (inclusive).
    /// * `inOpen` — Open price of each bar.
    /// * `inHigh` — High price of each bar.
    /// * `inLow` — Low price of each bar.
    /// * `inClose` — Close price of each bar.
    /// * `optInTimePeriod` — Number of bars in the window. `n = 1` is the paper's own single-bar
    ///   estimator. (default 10, range 1..=100000)
    /// * `optInAnnualization` — Periods per year. Pass 1 for the per-bar figure. (default 252,
    ///   minimum 0)
    /// * `outReal` — Estimated volatility, in log-return units.
    ///
    /// Integer parameters accept [`Core::INTEGER_DEFAULT`], and real parameters
    /// [`Core::REAL_DEFAULT`], to select their default value.
    ///
    /// # Returns
    ///
    /// On success, an [`OutRange`]: `beg_idx` is the index of the first value written, in the input
    /// series' coordinates, and `count` is how many were written. A range that ends before the
    /// lookback succeeds with `count == 0`.
    ///
    /// # Errors
    ///
    /// Returns [`Err`] carrying [`RetCode::OutOfRangeStartIndex`] when `startIdx` exceeds
    /// [`Core::INDEX_MAX`], [`RetCode::OutOfRangeEndIndex`] when `endIdx` exceeds it or is below
    /// `startIdx`, and [`RetCode::BadParam`] when an optional parameter is outside its documented
