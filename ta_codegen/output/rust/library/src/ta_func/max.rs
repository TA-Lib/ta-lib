    fn max_step_impl(sp: &mut MaxStreamState, inReal: f64, outReal: &mut f64) {
        let mut tmp: f64 = 0.0_f64;
        if sp.today >= 1073741824 {
            let rebaseShift: i32 = sp.trailingIdx & !sp.xMask;
            sp.today -= rebaseShift;
            sp.trailingIdx -= rebaseShift;
            sp.highestIdx -= rebaseShift;
            sp.i -= rebaseShift;
        }
        sp.x_inReal[(sp.today & sp.xMask) as usize] = inReal;
        tmp = sp.x_inReal[(sp.today & sp.xMask) as usize];
        if sp.highestIdx < sp.trailingIdx {
            sp.highestIdx = sp.trailingIdx;
            sp.highest = sp.x_inReal[(sp.highestIdx & sp.xMask) as usize];
            sp.i = sp.highestIdx;
            while (({ sp.i += 1; sp.i }) as i32) <= sp.today {
                tmp = sp.x_inReal[(sp.i & sp.xMask) as usize];
                if tmp > sp.highest {
                    sp.highestIdx = sp.i;
                    sp.highest = tmp;
                }
            }
        } else if tmp >= sp.highest {
            sp.highestIdx = sp.today;
            sp.highest = tmp;
        }
        (*outReal) = sp.highest;
        sp.trailingIdx += 1;
        sp.today += 1;
        sp.cur_outReal = (*outReal);
    }

    /// The single whole-history transcription behind [`Core::max_open_internal`]
    /// (stride 0, scalar sink) and [`Core::max_open_and_fill`] (stride 1, caller slices).
    pub(crate) fn max_open_impl(
        &self, inReal: &[f64], startIdx: usize, mut optInTimePeriod: i32, outBegIdx: &mut usize, outNBElement: &mut usize, outReal: &mut [f64], outStride: usize,
    ) -> Result<MaxStream, RetCode> {
        if inReal.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inReal.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        if ((optInTimePeriod) as i32) == (i32::MIN) {
            optInTimePeriod = 30;
        } else if (((optInTimePeriod) as i32) < 2) || (((optInTimePeriod) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        let historyLen: usize = inReal.len();
        let endIdx: usize = historyLen - 1;
        let mut startIdx = startIdx;
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut highest: f64 = 0.0_f64;
        let mut tmp: f64 = 0.0_f64;
        let mut outIdx: usize = 0_usize;
        let mut nbInitialElementNeeded: usize = 0_usize;
        let mut trailingIdx: usize = 0_usize;
        let mut today: usize = 0_usize;
        let mut i: usize = 0_usize;
        let mut highestIdx: i32 = 0_i32;
        // Identify the minimum number of price bar needed
        // to identify at least one output over the specified
        // period.
        nbInitialElementNeeded = (optInTimePeriod - 1) as usize;
        // Move up the start index if there is not
        // enough initial data.
        if startIdx < nbInitialElementNeeded {
            startIdx = nbInitialElementNeeded;
        }
        // Make sure there is still something to evaluate.
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        // Proceed with the calculation for the requested range.
        // Note that this algorithm allows the input and
        // output to be the same buffer.
        //
        // The highest value of the window is cached with its index; the window is
        // rescanned only when the cached extremum drops out of it. That is O(1)
        // per bar while the extremum sits away from the trailing edge, but it is
        // not amortized O(1): an extremum on the oldest in-window bar drops out
        // on the very next bar, so the rescan repeats and the cost stays
        // O(period) per bar for as long as that persists.
        //
        // Slower than the block scan the batch tier runs; it is here because one
        // bar at a time is exactly what the streaming tier needs. See issue #147.
        outIdx = 0;
        today = startIdx;
        trailingIdx = startIdx - nbInitialElementNeeded;
        highestIdx = 0 - 1;
        highest = 0.0;
        while today <= endIdx {
            tmp = inReal[today];
            if highestIdx < ((trailingIdx) as i32) {
                highestIdx = (trailingIdx) as i32;
                highest = inReal[(highestIdx) as usize];
                i = (highestIdx) as usize;
                while { i += 1; i } <= today {
                    tmp = inReal[i];
                    if tmp > highest {
                        highestIdx = (i) as i32;
                        highest = tmp;
                    }
                }
            } else if tmp >= highest {
                highestIdx = (today) as i32;
                highest = tmp;
            }
            outReal[({ let _v = outIdx; outIdx += 1; _v } * outStride) as usize] = highest;
            trailingIdx += 1;
            today += 1;
        }
        // Keep the outBegIdx relative to the
        // caller input before returning.
        (*outBegIdx) = startIdx;
        (*outNBElement) = outIdx;

        // Capture the live batch state into the handle.
        let capX: i64 = (today as i64) - (trailingIdx as i64) + 1;
        if capX < 1 || capX > historyLen as i64 {
            return Err(RetCode::InternalError);
        }
        let mut physX: i64 = 1;
        while physX < capX {
            physX <<= 1;
        }
        let mut x_inReal: Vec<f64> = vec![0.0_f64; physX as usize];
        {
            let mut fillJ: usize = historyLen - capX as usize;
            while fillJ < historyLen {
                x_inReal[fillJ & (physX as usize - 1)] = inReal[fillJ];
                fillJ += 1;
            }
        }
        let state = MaxStreamState {
            optInTimePeriod,
            highest,
            trailingIdx: (trailingIdx) as i32,
            highestIdx: (highestIdx) as i32,
            i: (i) as i32,
            today: (today) as i32,
            cur_outReal: outReal[(*outNBElement - 1) * outStride],
            xMask: (physX - 1) as i32,
            x_inReal,
        };
        Ok(MaxStream { state, out: OutRange { beg_idx: *outBegIdx, count: *outNBElement } })
    }

    /// Internal startIdx-anchored open behind [`Core::max_open`] (composition seam).
    pub(crate) fn max_open_internal(
        &self, inReal: &[f64], startIdx: usize, mut optInTimePeriod: i32,
    ) -> Result<(MaxStream, f64), RetCode> {
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut sink_outReal = [0.0_f64; 1];
        let handle = self.max_open_impl(inReal, startIdx, optInTimePeriod, &mut dummyBegIdx, &mut dummyNBElement, &mut sink_outReal, 0)?;
        Ok((handle, sink_outReal[0]))
    }

