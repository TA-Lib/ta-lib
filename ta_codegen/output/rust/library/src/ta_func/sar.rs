    fn SAR_step_impl(&self, sp: &mut SAR_StreamState, inHigh: f64, inLow: f64, outReal: &mut f64) {
        let mut prevHigh: f64 = 0.0_f64;
        let mut prevLow: f64 = 0.0_f64;
        prevLow = sp.newLow;
        prevHigh = sp.newHigh;
        sp.newLow = inLow;
        sp.newHigh = inHigh;
        if sp.isLong == 1 {
            // Switch to short if the low penetrates the SAR value.
            if sp.newLow <= sp.sar {
                // Switch and Overide the SAR with the ep
                sp.isLong = 0;
                sp.sar = sp.ep;
                // Make sure the overide SAR is within
                // yesterday's and today's range.
                if sp.sar < prevHigh {
                    sp.sar = prevHigh;
                }
                if sp.sar < sp.newHigh {
                    sp.sar = sp.newHigh;
                }
                // Output the overide SAR
                (*outReal) = sp.sar;
                // Adjust af and ep
                sp.af = sp.optInAcceleration;
                sp.ep = sp.newLow;
                // Calculate the new SAR
                sp.sar = (sp.af as f64).mul_add(sp.ep - sp.sar, sp.sar);
                // Make sure the new SAR is within
                // yesterday's and today's range.
                if sp.sar < prevHigh {
                    sp.sar = prevHigh;
                }
                if sp.sar < sp.newHigh {
                    sp.sar = sp.newHigh;
                }
            } else {
                // No switch
                // Output the SAR (was calculated in the previous iteration)
                (*outReal) = sp.sar;
                // Adjust af and ep.
                if sp.newHigh > sp.ep {
                    sp.ep = sp.newHigh;
                    sp.af += sp.optInAcceleration;
                    if sp.af > sp.optInMaximum {
                        sp.af = sp.optInMaximum;
                    }
                }
                // Calculate the new SAR
                sp.sar = (sp.af as f64).mul_add(sp.ep - sp.sar, sp.sar);
                // Make sure the new SAR is within
                // yesterday's and today's range.
                if sp.sar > prevLow {
                    sp.sar = prevLow;
                }
                if sp.sar > sp.newLow {
                    sp.sar = sp.newLow;
                }
            }
        // Switch to long if the high penetrates the SAR value.
        } else if sp.newHigh >= sp.sar {
            // Switch and Overide the SAR with the ep
            sp.isLong = 1;
            sp.sar = sp.ep;
            // Make sure the overide SAR is within
            // yesterday's and today's range.
            if sp.sar > prevLow {
                sp.sar = prevLow;
            }
            if sp.sar > sp.newLow {
                sp.sar = sp.newLow;
            }
            // Output the overide SAR
            (*outReal) = sp.sar;
            // Adjust af and ep
            sp.af = sp.optInAcceleration;
            sp.ep = sp.newHigh;
            // Calculate the new SAR
            sp.sar = (sp.af as f64).mul_add(sp.ep - sp.sar, sp.sar);
            // Make sure the new SAR is within
            // yesterday's and today's range.
            if sp.sar > prevLow {
                sp.sar = prevLow;
            }
            if sp.sar > sp.newLow {
                sp.sar = sp.newLow;
            }
        } else {
            // No switch
            // Output the SAR (was calculated in the previous iteration)
            (*outReal) = sp.sar;
            // Adjust af and ep.
            if sp.newLow < sp.ep {
                sp.ep = sp.newLow;
                sp.af += sp.optInAcceleration;
                if sp.af > sp.optInMaximum {
                    sp.af = sp.optInMaximum;
                }
            }
            // Calculate the new SAR
            sp.sar = (sp.af as f64).mul_add(sp.ep - sp.sar, sp.sar);
            // Make sure the new SAR is within
            // yesterday's and today's range.
            if sp.sar < prevHigh {
                sp.sar = prevHigh;
            }
            if sp.sar < sp.newHigh {
                sp.sar = sp.newHigh;
            }
        }
    }

