    fn vhf_step_impl(sp: &mut VhfStreamState, inReal: f64, outReal: &mut f64) {
        let mut i: usize = 0_usize;
        let mut highest: f64 = 0.0_f64;
        let mut lowest: f64 = 0.0_f64;
        let mut sumChange: f64 = 0.0_f64;
        let mut prev: f64 = 0.0_f64;
        let mut tempReal: f64 = 0.0_f64;
        sp.win_i_inReal[sp.winPos_i] = inReal;
        // The two windows are NOT co-terminal: the extrema span the
        // optInTimePeriod newest closes, while the optInTimePeriod changes reach
        // one bar further back. That is what makes the lookback optInTimePeriod
        // rather than optInTimePeriod-1.
        highest = inReal;
        lowest = highest;
        prev = highest;
        sumChange = 0.0;
        // for( i = sp.optInTimePeriod; i >= 0; i -= 1 )
        i = (sp.optInTimePeriod) as usize;
        loop {
            tempReal = sp.win_i_inReal[((if sp.winPos_i + sp.winCap_i - i >= sp.winCap_i { sp.winPos_i + sp.winCap_i - i - sp.winCap_i } else { sp.winPos_i + sp.winCap_i - i })) as usize];
            if i < ((sp.optInTimePeriod) as usize) {
                sumChange += (tempReal - prev).abs();
                if tempReal > highest {
                    highest = tempReal;
                }
                if tempReal < lowest {
                    lowest = tempReal;
                }
            }
            prev = tempReal;
            if i == 0 { break; }
            i -= 1;
        }
        // A fresh sum of non-negative magnitudes is exactly zero only on an
        // exactly flat window, which forces highest-lowest to zero too. Guard on
        // exact zero, never an epsilon band: a band carries the quote unit and
        // zeroes the filter for anything priced under it (issue #253).
        if sumChange > 0.0 {
            (*outReal) = (highest - lowest) / sumChange;
        } else {
            (*outReal) = 0.0;
        }
        sp.cur_outReal = (*outReal);
        sp.winPos_i = sp.winPos_i + 1;
        if sp.winPos_i >= sp.winCap_i {
            sp.winPos_i = 0;
        }
    }

