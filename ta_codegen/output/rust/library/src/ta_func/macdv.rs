/// Live MACDV stream: one value per closed bar, bit-identical to [`Core::macdv`]
/// over the same series. Open with [`Core::macdv_open`]; dropping the handle
/// closes the stream. Cloning it forks an independent stream.
///
/// [`Self::out_range`] reports the bars this handle has an output for.
#[must_use = "a stream does nothing unless updated; dropping it closes the stream"]
#[derive(Debug, Clone)]
#[doc(alias = "TA_MACDV_Stream")]
pub struct MacdvStream {
    state: MacdvStreamState,
    /// The bars this handle has an output for — see [`Self::out_range`].
    out: OutRange,
}

#[derive(Debug, Clone)]
#[allow(non_snake_case, dead_code)]
struct MacdvStreamState {
    optInFastPeriod: i32,
    optInSlowPeriod: i32,
    optInSignalPeriod: i32,
    prevFast: f64,
    prevSlow: f64,
    prevATR: f64,
    prevSignal: f64,
    slowK: f64,
    fastK: f64,
    signalK: f64,
    slowBeta: f64,
    fastBeta: f64,
    signalBeta: f64,
    wAlpha: f64,
    wBeta: f64,
    periodScale: f64,
    lag1_inClose: f64,
    cur_outMACDV: f64,
    cur_outMACDVSignal: f64,
    cur_outMACDVHist: f64,
}

#[allow(unused_variables)]
#[allow(dead_code)]
#[allow(unused_mut)]
#[allow(unused_assignments)]
#[allow(unused_parens)]
impl Core {
    #[inline(always)]
    fn macdv_step_impl(sp: &mut MacdvStreamState, inHigh: f64, inLow: f64, inClose: f64, outMACDV: &mut f64, outMACDVSignal: &mut f64, outMACDVHist: &mut f64) {
        let mut lineValue: f64 = 0.0_f64;
        let mut tempReal: f64 = 0.0_f64;
        let mut val2: f64 = 0.0_f64;
        let mut val3: f64 = 0.0_f64;
        let mut greatest: f64 = 0.0_f64;
        let mut spread: f64 = 0.0_f64;
        let mut bandScale: f64 = 0.0_f64;
        let mut tempCY: f64 = 0.0_f64;
        let mut tempLT: f64 = 0.0_f64;
        let mut tempHT: f64 = 0.0_f64;
        tempLT = inLow;
        tempHT = inHigh;
        tempCY = sp.lag1_inClose;
        tempReal = inClose;
        greatest = tempHT - tempLT;
        // val1
        val2 = (tempCY - tempHT).abs();
        greatest = c_max(val2, greatest);
        val3 = (tempCY - tempLT).abs();
        greatest = c_max(val3, greatest);
        sp.prevATR = (sp.wBeta as f64).mul_add(sp.prevATR, sp.wAlpha * greatest);
        sp.prevFast = (sp.fastBeta as f64).mul_add(sp.prevFast, sp.fastK * tempReal);
        sp.prevSlow = (sp.slowBeta as f64).mul_add(sp.prevSlow, sp.slowK * tempReal);
        spread = sp.prevFast - sp.prevSlow;
        bandScale = (sp.prevFast).abs();
        if (sp.prevSlow).abs() > bandScale {
            bandScale = (sp.prevSlow).abs();
        }
        bandScale = bandScale * sp.periodScale;
        lineValue = 0.0;
        if !(((spread).abs() <= 1e-14 * (bandScale))) && !(((sp.prevATR).abs() <= 1e-14 * (bandScale))) && sp.prevATR >= 2.2250738585072014e-308 {
            lineValue = spread / sp.prevATR * 100.0;
        }
        if sp.optInSignalPeriod == 1 {
            sp.prevSignal = lineValue;
        } else {
            sp.prevSignal = (sp.signalBeta as f64).mul_add(sp.prevSignal, sp.signalK * lineValue);
        }
        (*outMACDV) = lineValue;
        (*outMACDVSignal) = sp.prevSignal;
        (*outMACDVHist) = lineValue - sp.prevSignal;
        sp.cur_outMACDV = (*outMACDV);
        sp.cur_outMACDVSignal = (*outMACDVSignal);
        sp.cur_outMACDVHist = (*outMACDVHist);
        sp.lag1_inClose = inClose;
    }

    /// The single whole-history transcription behind [`Core::macdv_open_internal`]
    /// (stride 0, scalar sink) and [`Core::macdv_open_and_fill`] (stride 1, caller slices).
    pub(crate) fn macdv_open_impl(
        &self, inHigh: &[f64], inLow: &[f64], inClose: &[f64], startIdx: usize, optInFastPeriod: i32, optInSlowPeriod: i32, optInSignalPeriod: i32, outBegIdx: &mut usize, outNBElement: &mut usize, outMACDV: &mut [f64], outMACDVSignal: &mut [f64], outMACDVHist: &mut [f64], outStride: usize,
    ) -> Result<MacdvStream, RetCode> {
        #[cfg(target_arch = "x86_64")]
        return ta_lib_dispatch::dispatch_fma!(self, macdv_open_impl_fma, macdv_open_impl_scalar, (inHigh, inLow, inClose, startIdx, optInFastPeriod, optInSlowPeriod, optInSignalPeriod, outBegIdx, outNBElement, outMACDV, outMACDVSignal, outMACDVHist, outStride));
        #[cfg(not(target_arch = "x86_64"))]
        self.macdv_open_impl_scalar(inHigh, inLow, inClose, startIdx, optInFastPeriod, optInSlowPeriod, optInSignalPeriod, outBegIdx, outNBElement, outMACDV, outMACDVSignal, outMACDVHist, outStride)
    }

    #[cfg(target_arch = "x86_64")]
    #[target_feature(enable = "fma")]
    fn macdv_open_impl_fma(
        &self, inHigh: &[f64], inLow: &[f64], inClose: &[f64], startIdx: usize, optInFastPeriod: i32, optInSlowPeriod: i32, optInSignalPeriod: i32, outBegIdx: &mut usize, outNBElement: &mut usize, outMACDV: &mut [f64], outMACDVSignal: &mut [f64], outMACDVHist: &mut [f64], outStride: usize,
    ) -> Result<MacdvStream, RetCode> {
        self.macdv_open_impl_scalar(inHigh, inLow, inClose, startIdx, optInFastPeriod, optInSlowPeriod, optInSignalPeriod, outBegIdx, outNBElement, outMACDV, outMACDVSignal, outMACDVHist, outStride)
    }

    #[inline(always)]
    fn macdv_open_impl_scalar(
        &self, inHigh: &[f64], inLow: &[f64], inClose: &[f64], startIdx: usize, mut optInFastPeriod: i32, mut optInSlowPeriod: i32, mut optInSignalPeriod: i32, outBegIdx: &mut usize, outNBElement: &mut usize, outMACDV: &mut [f64], outMACDVSignal: &mut [f64], outMACDVHist: &mut [f64], outStride: usize,
    ) -> Result<MacdvStream, RetCode> {
        if inHigh.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inHigh.len() > Self::INDEX_MAX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        if ((optInFastPeriod) as i32) == (i32::MIN) {
            optInFastPeriod = 12;
        } else if (((optInFastPeriod) as i32) < 2) || (((optInFastPeriod) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        if ((optInSlowPeriod) as i32) == (i32::MIN) {
            optInSlowPeriod = 26;
        } else if (((optInSlowPeriod) as i32) < 2) || (((optInSlowPeriod) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        if ((optInSignalPeriod) as i32) == (i32::MIN) {
            optInSignalPeriod = 9;
        } else if (((optInSignalPeriod) as i32) < 1) || (((optInSignalPeriod) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        if inLow.len() != inHigh.len() || inClose.len() != inHigh.len() {
            return Err(RetCode::BadParam);
        }
        let historyLen: usize = inHigh.len();
        let endIdx: usize = historyLen - 1;
        let mut startIdx = startIdx;
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut prevFast: f64 = 0.0_f64;
        let mut prevSlow: f64 = 0.0_f64;
        let mut prevATR: f64 = 0.0_f64;
        let mut prevSignal: f64 = 0.0_f64;
        let mut lineValue: f64 = 0.0_f64;
        let mut tempReal: f64 = 0.0_f64;
        let mut slowK: f64 = 0.0_f64;
        let mut fastK: f64 = 0.0_f64;
        let mut signalK: f64 = 0.0_f64;
        let mut slowBeta: f64 = 0.0_f64;
        let mut fastBeta: f64 = 0.0_f64;
        let mut signalBeta: f64 = 0.0_f64;
        let mut wAlpha: f64 = 0.0_f64;
        let mut wBeta: f64 = 0.0_f64;
        let mut periodTotal: f64 = 0.0_f64;
        let mut val2: f64 = 0.0_f64;
        let mut val3: f64 = 0.0_f64;
        let mut greatest: f64 = 0.0_f64;
        let mut spread: f64 = 0.0_f64;
        let mut bandScale: f64 = 0.0_f64;
        let mut periodScale: f64 = 0.0_f64;
        let mut tempCY: f64 = 0.0_f64;
        let mut tempLT: f64 = 0.0_f64;
        let mut tempHT: f64 = 0.0_f64;
        let mut i: usize = 0_usize;
        let mut today: usize = 0_usize;
        let mut outIdx: usize = 0_usize;
        let mut tempInteger: usize = 0_usize;
        let mut lookbackTotal: usize = 0_usize;
        let mut lookbackSignal: usize = 0_usize;
        let mut lookbackSlow: usize = 0_usize;
        let mut lookbackFast: usize = 0_usize;
        let mut lookbackATR: usize = 0_usize;
        let mut lineIdx: usize = 0_usize;
        // Make sure slow is really slower than
        // the fast period! if not, swap...
        if optInSlowPeriod < optInFastPeriod {
            // swap
            tempInteger = (optInSlowPeriod) as usize;
            optInSlowPeriod = optInFastPeriod;
            optInFastPeriod = (tempInteger) as i32;
        }
        // ema.c's k and beta for the three EMA, macd.c's spelling.
        slowBeta = ((optInSlowPeriod - 1) as f64) / ((optInSlowPeriod + 1) as f64);
        slowK = 1.0 - slowBeta;
        if slowBeta < 0.5 {
            slowBeta = 1.0 - slowK;
        }
        fastBeta = ((optInFastPeriod - 1) as f64) / ((optInFastPeriod + 1) as f64);
        fastK = 1.0 - fastBeta;
        if fastBeta < 0.5 {
            fastBeta = 1.0 - fastK;
        }
        // A signal period of 1 disables signal-line smoothing: the signal IS the
        // MACD-V line and the histogram is exactly zero. The recursion below, at a
        // k of 1.0 and a beta of 0.0, does not keep the sign of a -0.0 line value;
        // hence the explicit arm at each step.
        signalBeta = ((optInSignalPeriod - 1) as f64) / ((optInSignalPeriod + 1) as f64);
        signalK = 1.0 - signalBeta;
        if signalBeta < 0.5 {
            signalBeta = 1.0 - signalK;
        }
        // atr.c's Wilder coefficients: wAlpha derived FROM wBeta, never the
        // reverse, so that the pair is the one TA_ATR runs.
        wBeta = ((optInSlowPeriod - 1) as f64) / (optInSlowPeriod as f64);
        wAlpha = 1.0 - wBeta;
        // An EMA of a constant can settle short of it by a number of ulps that
        // grows in proportion to the period.
        periodScale = (optInSlowPeriod + 1) as f64;
        lookbackSignal = self.ema_lookback(optInSignalPeriod)?;
        lookbackSlow = self.ema_lookback(optInSlowPeriod)?;
        lookbackFast = self.ema_lookback(optInFastPeriod)?;
        lookbackATR = self.atr_lookback(optInSlowPeriod)?;
        lookbackTotal = self.macdv_lookback(optInFastPeriod, optInSlowPeriod, optInSignalPeriod)?;
        // Move up the start index if there is not
        // enough initial data.
        if startIdx < lookbackTotal {
            startIdx = lookbackTotal;
        }
        // Make sure there is still something to evaluate.
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        // Everything is computed in a single lockstep pass: each bar advances the
        // fast EMA, the slow EMA and the Average True Range, the scaled quotient
        // is the MACD-V line, and each line value is immediately fed into the
        // signal EMA. No temporary buffers.
        //
        // The arithmetic order below is the bit-exactness contract with TA_EMA,
        // TA_MACD and TA_ATR (do not reorder or fuse operations):
        //  - EMA recursion: k*x + beta*prev, with ema.c's k and beta.
        //  - True Range: start from high-low, then compare/replace with the two
        //    previous-close distances, in that order; Wilder smoothing in ONE
        //    statement.
        //  - Each recursion is seeded with the sum of its first 'period' inputs,
        //    accumulated from 0.0 in input order, divided by the period. The
        //    signal EMA is seeded the same way from the first 'signal period'
        //    line values.
        //  - The line is the spread divided by the Average True Range, then
        //    scaled: what a caller dividing TA_MACD by TA_ATR computes.
        //
        // In-place (an output == an input) is supported: outputs at [outIdx] are
        // written only after every input at or before bar startIdx+outIdx was
        // read, and the previous close is re-read from the input one bar back,
        // which no output store has reached.
        // Each leg is seeded at its OWN lookback and warmed up to lineIdx, the
        // first MACD-V line bar, so each is the shipped function entered at that
        // bar and nothing here over-warms the shorter one: a caller who wants a
        // leg converged sets that function's unstable period, exactly as when
        // calling it directly.
        lineIdx = startIdx - lookbackSignal;
        // Slow EMA.
        today = lineIdx - lookbackSlow;
        tempReal = 0.0;
        i = (optInSlowPeriod) as usize;
        while { let _v = i; i = i.wrapping_sub(1); _v } > 0 {
            tempReal += inClose[{ let _v = today; today += 1; _v }];
        }
        prevSlow = tempReal / ((optInSlowPeriod) as f64);
        while today <= lineIdx {
            tempReal = inClose[{ let _v = today; today += 1; _v }];
            prevSlow = (slowBeta as f64).mul_add(prevSlow, slowK * tempReal);
        }
        // Fast EMA.
        today = lineIdx - lookbackFast;
        tempReal = 0.0;
        i = (optInFastPeriod) as usize;
        while { let _v = i; i = i.wrapping_sub(1); _v } > 0 {
            tempReal += inClose[{ let _v = today; today += 1; _v }];
        }
        prevFast = tempReal / ((optInFastPeriod) as f64);
        while today <= lineIdx {
            tempReal = inClose[{ let _v = today; today += 1; _v }];
            prevFast = (fastBeta as f64).mul_add(prevFast, fastK * tempReal);
        }
        // Average True Range: the first True Range consumes a previous close.
        today = lineIdx - lookbackATR + 1;
        periodTotal = 0.0;
        i = (optInSlowPeriod) as usize;
        while { let _v = i; i = i.wrapping_sub(1); _v } > 0 {
            tempLT = inLow[today];
            tempHT = inHigh[today];
            tempCY = inClose[today - 1];
            greatest = tempHT - tempLT;
            // val1
            val2 = (tempCY - tempHT).abs();
            greatest = c_max(val2, greatest);
            val3 = (tempCY - tempLT).abs();
            greatest = c_max(val3, greatest);
            periodTotal += greatest;
            today += 1;
        }
        prevATR = periodTotal / ((optInSlowPeriod) as f64);
        while today <= lineIdx {
            tempLT = inLow[today];
            tempHT = inHigh[today];
            tempCY = inClose[today - 1];
            greatest = tempHT - tempLT;
            // val1
            val2 = (tempCY - tempHT).abs();
            greatest = c_max(val2, greatest);
            val3 = (tempCY - tempLT).abs();
            greatest = c_max(val3, greatest);
            prevATR = (wBeta as f64).mul_add(prevATR, wAlpha * greatest);
            today += 1;
        }
        // Without price movement the line answers its neutral point, 0.0 (#570).
        // In a flat run the Wilder average only decays, to a subnormal floor,
        // while the spread stalls at the EMAs' rounding residue, so an exact test
        // lets their quotient grow until it overflows. Both are therefore tested
        // against the EMAs' own magnitude times the residue's period factor: that
        // also bounds |line| for any finite input, which a scale taken from the
        // close cannot, since a close may lie outside its bar and be zero.
        spread = prevFast - prevSlow;
        bandScale = (prevFast).abs();
        if (prevSlow).abs() > bandScale {
            bandScale = (prevSlow).abs();
        }
        bandScale = bandScale * periodScale;
        lineValue = 0.0;
        if !(((spread).abs() <= 1e-14 * (bandScale))) && !(((prevATR).abs() <= 1e-14 * (bandScale))) && prevATR >= 2.2250738585072014e-308 {
            lineValue = spread / prevATR * 100.0;
        }
        // Seed the signal EMA with a simple average of the first 'signal period'
        // line values, accumulated as they are produced.
        prevSignal = 0.0;
        prevSignal += lineValue;
        i = (optInSignalPeriod - 1) as usize;
        while { let _v = i; i = i.wrapping_sub(1); _v } > 0 {
            tempLT = inLow[today];
            tempHT = inHigh[today];
            tempCY = inClose[today - 1];
            tempReal = inClose[today];
            greatest = tempHT - tempLT;
            // val1
            val2 = (tempCY - tempHT).abs();
            greatest = c_max(val2, greatest);
            val3 = (tempCY - tempLT).abs();
            greatest = c_max(val3, greatest);
            prevATR = (wBeta as f64).mul_add(prevATR, wAlpha * greatest);
            prevFast = (fastBeta as f64).mul_add(prevFast, fastK * tempReal);
            prevSlow = (slowBeta as f64).mul_add(prevSlow, slowK * tempReal);
            spread = prevFast - prevSlow;
            bandScale = (prevFast).abs();
            if (prevSlow).abs() > bandScale {
                bandScale = (prevSlow).abs();
            }
            bandScale = bandScale * periodScale;
            lineValue = 0.0;
            if !(((spread).abs() <= 1e-14 * (bandScale))) && !(((prevATR).abs() <= 1e-14 * (bandScale))) && prevATR >= 2.2250738585072014e-308 {
                lineValue = spread / prevATR * 100.0;
            }
            prevSignal += lineValue;
            today += 1;
        }
        prevSignal = prevSignal / ((optInSignalPeriod) as f64);
        // Advance everything in lockstep through the unstable period of the
        // signal EMA, up to the first output bar.
        while today <= startIdx {
            tempLT = inLow[today];
            tempHT = inHigh[today];
            tempCY = inClose[today - 1];
            tempReal = inClose[today];
            greatest = tempHT - tempLT;
            // val1
            val2 = (tempCY - tempHT).abs();
            greatest = c_max(val2, greatest);
            val3 = (tempCY - tempLT).abs();
            greatest = c_max(val3, greatest);
            prevATR = (wBeta as f64).mul_add(prevATR, wAlpha * greatest);
            prevFast = (fastBeta as f64).mul_add(prevFast, fastK * tempReal);
            prevSlow = (slowBeta as f64).mul_add(prevSlow, slowK * tempReal);
            spread = prevFast - prevSlow;
            bandScale = (prevFast).abs();
            if (prevSlow).abs() > bandScale {
                bandScale = (prevSlow).abs();
            }
            bandScale = bandScale * periodScale;
            lineValue = 0.0;
            if !(((spread).abs() <= 1e-14 * (bandScale))) && !(((prevATR).abs() <= 1e-14 * (bandScale))) && prevATR >= 2.2250738585072014e-308 {
                lineValue = spread / prevATR * 100.0;
            }
            if optInSignalPeriod == 1 {
                prevSignal = lineValue;
            } else {
                prevSignal = (signalBeta as f64).mul_add(prevSignal, signalK * lineValue);
            }
            today += 1;
        }
        // Stable zone: keep advancing in lockstep and write the three outputs.
        outMACDV[(0 * outStride) as usize] = lineValue;
        outMACDVSignal[(0 * outStride) as usize] = prevSignal;
        outMACDVHist[(0 * outStride) as usize] = lineValue - prevSignal;
        outIdx = 1;
        while today <= endIdx {
            tempLT = inLow[today];
            tempHT = inHigh[today];
            tempCY = inClose[today - 1];
            tempReal = inClose[today];
            greatest = tempHT - tempLT;
            // val1
            val2 = (tempCY - tempHT).abs();
            greatest = c_max(val2, greatest);
            val3 = (tempCY - tempLT).abs();
            greatest = c_max(val3, greatest);
            prevATR = (wBeta as f64).mul_add(prevATR, wAlpha * greatest);
            prevFast = (fastBeta as f64).mul_add(prevFast, fastK * tempReal);
            prevSlow = (slowBeta as f64).mul_add(prevSlow, slowK * tempReal);
            spread = prevFast - prevSlow;
            bandScale = (prevFast).abs();
            if (prevSlow).abs() > bandScale {
                bandScale = (prevSlow).abs();
            }
            bandScale = bandScale * periodScale;
            lineValue = 0.0;
            if !(((spread).abs() <= 1e-14 * (bandScale))) && !(((prevATR).abs() <= 1e-14 * (bandScale))) && prevATR >= 2.2250738585072014e-308 {
                lineValue = spread / prevATR * 100.0;
            }
            if optInSignalPeriod == 1 {
                prevSignal = lineValue;
            } else {
                prevSignal = (signalBeta as f64).mul_add(prevSignal, signalK * lineValue);
            }
            outMACDV[(outIdx * outStride) as usize] = lineValue;
            outMACDVSignal[(outIdx * outStride) as usize] = prevSignal;
            outMACDVHist[(outIdx * outStride) as usize] = lineValue - prevSignal;
            outIdx += 1;
            today += 1;
        }
        // All done! Indicate the output limits and return success.
        (*outBegIdx) = startIdx;
        (*outNBElement) = outIdx;

        // Capture the live batch state into the handle.
        let state = MacdvStreamState {
            optInFastPeriod,
            optInSlowPeriod,
            optInSignalPeriod,
            prevFast,
            prevSlow,
            prevATR,
            prevSignal,
            slowK,
            fastK,
            signalK,
            slowBeta,
            fastBeta,
            signalBeta,
            wAlpha,
            wBeta,
            periodScale,
            cur_outMACDV: outMACDV[(*outNBElement - 1) * outStride],
            cur_outMACDVSignal: outMACDVSignal[(*outNBElement - 1) * outStride],
            cur_outMACDVHist: outMACDVHist[(*outNBElement - 1) * outStride],
            lag1_inClose: inClose[historyLen - 1],
        };
        Ok(MacdvStream { state, out: OutRange { beg_idx: *outBegIdx, count: *outNBElement } })
    }

    /// Internal startIdx-anchored open behind [`Core::macdv_open`] (composition seam).
    pub(crate) fn macdv_open_internal(
        &self, inHigh: &[f64], inLow: &[f64], inClose: &[f64], startIdx: usize, mut optInFastPeriod: i32, mut optInSlowPeriod: i32, mut optInSignalPeriod: i32,
    ) -> Result<(MacdvStream, (f64, f64, f64)), RetCode> {
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut sink_outMACDV = [0.0_f64; 1];
        let mut sink_outMACDVSignal = [0.0_f64; 1];
        let mut sink_outMACDVHist = [0.0_f64; 1];
        let handle = self.macdv_open_impl(inHigh, inLow, inClose, startIdx, optInFastPeriod, optInSlowPeriod, optInSignalPeriod, &mut dummyBegIdx, &mut dummyNBElement, &mut sink_outMACDV, &mut sink_outMACDVSignal, &mut sink_outMACDVHist, 0)?;
        Ok((handle, (sink_outMACDV[0], sink_outMACDVSignal[0], sink_outMACDVHist[0])))
    }

    /// Open a live MACDV stream over the warm-up history; returns the handle and
    /// the value at the last history bar — bit-identical to [`Core::macdv`] at that bar.
    ///
    /// # Errors
    ///
    /// [`RetCode::InsufficientHistory`] when the history holds fewer than
    /// `lookback + 1` bars — the one failure here worth retrying, since another
    /// bar fixes it. [`RetCode::OutOfRangeStartIndex`] when the history is empty.
    /// [`RetCode::BadParam`] when a parameter is out of range or the input
    /// lengths differ.
    ///
    /// ```
    /// use ta_lib::Core;
    /// let high: Vec<f64> = (0..252).map(|i| 101.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    /// let low: Vec<f64> = (0..252).map(|i| 99.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    /// let close: Vec<f64> = (0..252)
    ///     .map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin() + 0.8 * (0.7 * i as f64).sin())
    ///     .collect();
    ///
    /// let core = Core::new();
    /// let (mut s, _last) = core.macdv_open(&high, &low, &close, 12, 26, 9).expect("enough history");
    /// let r0 = s.out_range();
    /// let peeked = s.peek(101.4, 99.1, 100.9).expect("a finite bar");
    /// assert_eq!(s.out_range().count, r0.count); // a peek commits nothing
    /// let updated = s.update(101.4, 99.1, 100.9).expect("a finite bar");
    /// assert_eq!(s.out_range().beg_idx, r0.beg_idx);
    /// assert_eq!(s.out_range().count, r0.count + 1);
    /// assert_eq!(peeked.0.to_bits(), updated.0.to_bits());
    /// assert_eq!(peeked.1.to_bits(), updated.1.to_bits());
    /// assert_eq!(peeked.2.to_bits(), updated.2.to_bits());
    /// ```
    #[doc(alias = "TA_MACDV_Open")]
    pub fn macdv_open(&self, inHigh: &[f64], inLow: &[f64], inClose: &[f64], optInFastPeriod: i32, optInSlowPeriod: i32, optInSignalPeriod: i32) -> Result<(MacdvStream, (f64, f64, f64)), RetCode> {
        self.macdv_open_internal(inHigh, inLow, inClose, 0, optInFastPeriod, optInSlowPeriod, optInSignalPeriod)
    }

    /// [`Core::macdv_open`] that also fills the output array(s) bit-identically to
    /// [`Core::macdv`] over `0..len` in the same single pass, and reports the range it
    /// wrote as the [`OutRange`] beside the handle.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] when an output slice holds fewer than `len - lookback`
    /// values — the batch tier's sizing rule, checked here as it is there (rule rS5).
    /// Everything [`Core::macdv_open`] rejects is rejected here too.
    ///
    /// # Examples
    ///
    /// ```
    /// use ta_lib::Core;
    /// let high: Vec<f64> = (0..252).map(|i| 101.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    /// let low: Vec<f64> = (0..252).map(|i| 99.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    /// let close: Vec<f64> = (0..252)
    ///     .map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin() + 0.8 * (0.7 * i as f64).sin())
    ///     .collect();
    ///
    /// let core = Core::new();
    /// let mut batch_macdv = vec![0.0; 252];
    /// let mut batch_macdv_signal = vec![0.0; 252];
    /// let mut batch_macdv_hist = vec![0.0; 252];
    /// let batch = core.macdv(0, high.len() - 1, &high, &low, &close, 12, 26, 9, &mut batch_macdv, &mut batch_macdv_signal, &mut batch_macdv_hist)?;
    ///
    /// let mut macdv = vec![0.0; 252];
    /// let mut macdv_signal = vec![0.0; 252];
    /// let mut macdv_hist = vec![0.0; 252];
    /// let (_stream, filled) = core.macdv_open_and_fill(&high, &low, &close, 12, 26, 9, &mut macdv, &mut macdv_signal, &mut macdv_hist)?;
    ///
    /// assert_eq!(filled.beg_idx, batch.beg_idx);
    /// assert_eq!(filled.count, batch.count);
    /// assert!(macdv[..filled.count].iter().zip(&batch_macdv[..batch.count])
    ///     .all(|(a, b)| a.to_bits() == b.to_bits()));
    /// assert!(macdv_signal[..filled.count].iter().zip(&batch_macdv_signal[..batch.count])
    ///     .all(|(a, b)| a.to_bits() == b.to_bits()));
    /// assert!(macdv_hist[..filled.count].iter().zip(&batch_macdv_hist[..batch.count])
    ///     .all(|(a, b)| a.to_bits() == b.to_bits()));
    /// # Ok::<(), ta_lib::RetCode>(())
    /// ```
    #[doc(alias = "TA_MACDV_OpenAndFill")]
    pub fn macdv_open_and_fill(
        &self, inHigh: &[f64], inLow: &[f64], inClose: &[f64], mut optInFastPeriod: i32, mut optInSlowPeriod: i32, mut optInSignalPeriod: i32, outMACDV: &mut [f64], outMACDVSignal: &mut [f64], outMACDVHist: &mut [f64],
    ) -> Result<(MacdvStream, OutRange), RetCode> {
        if inHigh.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inHigh.len() > Self::INDEX_MAX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        let _guardLb = self.macdv_lookback(optInFastPeriod, optInSlowPeriod, optInSignalPeriod)?;
        if inLow.len() != inHigh.len() || inClose.len() != inHigh.len() {
            return Err(RetCode::BadParam);
        }
        let _guardOutLen = inHigh.len().saturating_sub(_guardLb);
        if outMACDV.is_empty() || outMACDV.len() < _guardOutLen {
            return Err(RetCode::BadParam);
        }
        if outMACDVSignal.is_empty() || outMACDVSignal.len() < _guardOutLen {
            return Err(RetCode::BadParam);
        }
        if outMACDVHist.is_empty() || outMACDVHist.len() < _guardOutLen {
            return Err(RetCode::BadParam);
        }
        let mut outBegIdx: usize = 0;
        let mut outNBElement: usize = 0;
        let handle = self.macdv_open_and_fill_internal(inHigh, inLow, inClose, 0, optInFastPeriod, optInSlowPeriod, optInSignalPeriod, &mut outBegIdx, &mut outNBElement, outMACDV, outMACDVSignal, outMACDVHist)?;
        Ok((handle, OutRange { beg_idx: outBegIdx, count: outNBElement }))
    }

    /// [`Core::macdv_open_and_fill`] anchored at `startIdx` — the composed-open
    /// fusion seam (issue #192), not a public entry point.
    pub(crate) fn macdv_open_and_fill_internal(
        &self, inHigh: &[f64], inLow: &[f64], inClose: &[f64], startIdx: usize, mut optInFastPeriod: i32, mut optInSlowPeriod: i32, mut optInSignalPeriod: i32, outBegIdx: &mut usize, outNBElement: &mut usize, outMACDV: &mut [f64], outMACDVSignal: &mut [f64], outMACDVHist: &mut [f64],
    ) -> Result<MacdvStream, RetCode> {
        self.macdv_open_impl(inHigh, inLow, inClose, startIdx, optInFastPeriod, optInSlowPeriod, optInSignalPeriod, outBegIdx, outNBElement, outMACDV, outMACDVSignal, outMACDVHist, 1)
    }

}

#[allow(non_snake_case)]
#[allow(unused_variables)]
#[allow(unused_mut)]
#[allow(unused_assignments)]
#[allow(unused_parens)]
impl MacdvStream {
    /// Commit one closed bar.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite (NaN or ±Inf).
    /// That check runs before anything is written, so the handle's state is
    /// left exactly as it was and the stream stays usable. This is the one
    /// place the streaming tier is stricter than the batch API, which computes
    /// on whatever it is given: a handle retains its state, so a single
    /// non-finite bar would poison every later value it produces.
    ///
    /// A rejection leaves [`Self::out_range`] alone too. Re-feed the bar when
    /// a corrected value arrives, or call [`Self::advance`] to count it and
    /// carry on — two handles on one feed drift a bar apart if neither
    /// happens.
    ///
    /// [`RetCode::OutOfRangeEndIndex`] once [`Self::out_range`] has reached
    /// bar [`Core::INDEX_MAX`], which no re-feed clears: the handle has run
    /// out of index domain and only a shorter history can start a new one.
    #[doc(alias = "TA_MACDV_Update")]
    pub fn update(&mut self, inHigh: f64, inLow: f64, inClose: f64) -> Result<(f64, f64, f64), RetCode> {
        #[cfg(target_arch = "x86_64")]
        return ta_lib_dispatch::dispatch_fma!(self, update_fma, update_scalar, (inHigh, inLow, inClose));
        #[cfg(not(target_arch = "x86_64"))]
        self.update_scalar(inHigh, inLow, inClose)
    }

    #[cfg(target_arch = "x86_64")]
    #[target_feature(enable = "fma")]
    fn update_fma(&mut self, inHigh: f64, inLow: f64, inClose: f64) -> Result<(f64, f64, f64), RetCode> {
        self.update_scalar(inHigh, inLow, inClose)
    }

    #[inline(always)]
    fn update_scalar(&mut self, inHigh: f64, inLow: f64, inClose: f64) -> Result<(f64, f64, f64), RetCode> {
        if self.out.beg_idx + self.out.count > Core::INDEX_MAX {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        if !inHigh.is_finite() || !inLow.is_finite() || !inClose.is_finite() {
            return Err(RetCode::BadParam);
        }
        let mut outMACDV: f64 = 0.0_f64;
        let mut outMACDVSignal: f64 = 0.0_f64;
        let mut outMACDVHist: f64 = 0.0_f64;
        Core::macdv_step_impl(&mut self.state, inHigh, inLow, inClose, &mut outMACDV, &mut outMACDVSignal, &mut outMACDVHist);
        self.out.count += 1;
        Ok((outMACDV, outMACDVSignal, outMACDVHist))
    }

    /// Evaluate a forming bar without committing — bit-identical to what the
    /// next `update` with the same bar would return: the same transition,
    /// rewritten so every store it would make lives in a local instead. It
    /// writes no part of the handle, so peeks may run concurrently with each
    /// other.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite, on the same test
    /// `update` applies, and a rejected peek changes nothing at all. Not
    /// [`RetCode::OutOfRangeEndIndex`]: `peek` counts no bar, so it keeps
    /// answering past the [`Core::INDEX_MAX`] ceiling `update` stops at.
    #[doc(alias = "TA_MACDV_Peek")]
    pub fn peek(&self, inHigh: f64, inLow: f64, inClose: f64) -> Result<(f64, f64, f64), RetCode> {
        if !inHigh.is_finite() || !inLow.is_finite() || !inClose.is_finite() {
            return Err(RetCode::BadParam);
        }
        let mut outMACDV: f64 = 0.0_f64;
        let mut outMACDVSignal: f64 = 0.0_f64;
        let mut outMACDVHist: f64 = 0.0_f64;
        {
            let sp = &self.state;
            let outMACDV = &mut outMACDV;
            let outMACDVSignal = &mut outMACDVSignal;
            let outMACDVHist = &mut outMACDVHist;
            let mut lineValue: f64 = 0.0_f64;
            let mut tempReal: f64 = 0.0_f64;
            let mut val2: f64 = 0.0_f64;
            let mut val3: f64 = 0.0_f64;
            let mut greatest: f64 = 0.0_f64;
            let mut spread: f64 = 0.0_f64;
            let mut bandScale: f64 = 0.0_f64;
            let mut tempCY: f64 = 0.0_f64;
            let mut tempLT: f64 = 0.0_f64;
            let mut tempHT: f64 = 0.0_f64;
            let mut prevATR = sp.prevATR;
            let mut prevFast = sp.prevFast;
            let mut prevSignal = sp.prevSignal;
            let mut prevSlow = sp.prevSlow;
            tempLT = inLow;
            tempHT = inHigh;
            tempCY = sp.lag1_inClose;
            tempReal = inClose;
            greatest = tempHT - tempLT;
            // val1
            val2 = (tempCY - tempHT).abs();
            greatest = c_max(val2, greatest);
            val3 = (tempCY - tempLT).abs();
            greatest = c_max(val3, greatest);
            prevATR = (sp.wBeta as f64).mul_add(prevATR, sp.wAlpha * greatest);
            prevFast = (sp.fastBeta as f64).mul_add(prevFast, sp.fastK * tempReal);
            prevSlow = (sp.slowBeta as f64).mul_add(prevSlow, sp.slowK * tempReal);
            spread = prevFast - prevSlow;
            bandScale = (prevFast).abs();
            if (prevSlow).abs() > bandScale {
                bandScale = (prevSlow).abs();
            }
            bandScale = bandScale * sp.periodScale;
            lineValue = 0.0;
            if !(((spread).abs() <= 1e-14 * (bandScale))) && !(((prevATR).abs() <= 1e-14 * (bandScale))) && prevATR >= 2.2250738585072014e-308 {
                lineValue = spread / prevATR * 100.0;
            }
            if sp.optInSignalPeriod == 1 {
                prevSignal = lineValue;
            } else {
                prevSignal = (sp.signalBeta as f64).mul_add(prevSignal, sp.signalK * lineValue);
            }
            (*outMACDV) = lineValue;
            (*outMACDVSignal) = prevSignal;
            (*outMACDVHist) = lineValue - prevSignal;
        }
        Ok((outMACDV, outMACDVSignal, outMACDVHist))
    }

    /// The value(s) at the last bar the stream counted — the bar
    /// [`Self::out_range`] ends on — without recomputing. Seeded by the opener,
    /// refreshed by every accepted `update`, and left
    /// alone by `peek`.
    ///
    /// A clone carries them verbatim, so a forked handle can be asked its
    /// current value without committing a bar to find out.
    #[must_use]
    #[doc(alias = "TA_MACDV_Value")]
    pub fn value(&self) -> (f64, f64, f64) {
        (self.state.cur_outMACDV, self.state.cur_outMACDVSignal, self.state.cur_outMACDVHist)
    }

    /// The bars this stream has an output for, in the input series'
    /// coordinates: `[beg_idx, beg_idx + count)`.
    ///
    /// It is what [`Core::macdv`] reports over the same bars: the opener sets it
    /// to `(lookback, historyLen - lookback)`, every accepted `update` adds
    /// one to the count — a rejected one changes nothing, and neither does
    /// `peek` — and a clone carries it verbatim. A plain `Open` hands back
    /// only the last value, a subset of this range, because the caller chose
    /// not to take the fill.
    ///
    /// The last bar it can reach is [`Core::INDEX_MAX`]; past that `update`
    /// and `advance` answer [`RetCode::OutOfRangeEndIndex`].
    #[doc(alias = "TA_MACDV_OutRange")]
    pub fn out_range(&self) -> OutRange {
        self.out
    }

    /// Count one bar this stream was not fed: [`Self::out_range`] advances by
    /// one and nothing else moves — [`Self::value`] keeps answering the
    /// previous output, which is this bar's output too.
    ///
    /// For a bar the caller leaves out: one an `update` rejected and that
    /// will not be re-fed, or a session with no print. Without it two handles
    /// on one feed drift a bar apart when only one of them skips.
    ///
    /// # Errors
    ///
    /// [`RetCode::OutOfRangeEndIndex`] once [`Self::out_range`] has reached
    /// bar [`Core::INDEX_MAX`] — the last one the batch tier can address, and
    /// the last this handle will count. `update` answers the same there.
    #[doc(alias = "TA_MACDV_Advance")]
    pub fn advance(&mut self) -> Result<(), RetCode> {
        if self.out.beg_idx + self.out.count > Core::INDEX_MAX {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        self.out.count += 1;
        Ok(())
    }
}

