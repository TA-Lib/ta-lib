    /// # See also
    ///
    /// [`Core::EMA`] · [`Core::DEMA`] · [`Core::T3`]
    ///
    /// # References
    ///
    /// * Patrick G. Mulloy, *Smoothing Data with Faster Moving Averages*, Technical Analysis of
    ///   Stocks & Commodities, V.12:1 (January 1994)
