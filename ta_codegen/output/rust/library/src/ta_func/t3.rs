impl Core {
    fn T3_step_impl(sp: &mut T3_StreamState, inReal: f64, outReal: &mut f64) {
        if sp.optInTimePeriod == 1 {
            (*outReal) = inReal;
            return;
        }
        sp.e1 = (sp.one_minus_k as f64).mul_add(sp.e1, sp.k * inReal);
        sp.e2 = (sp.one_minus_k as f64).mul_add(sp.e2, sp.k * sp.e1);
        sp.e3 = (sp.one_minus_k as f64).mul_add(sp.e3, sp.k * sp.e2);
        sp.e4 = (sp.one_minus_k as f64).mul_add(sp.e4, sp.k * sp.e3);
        sp.e5 = (sp.one_minus_k as f64).mul_add(sp.e5, sp.k * sp.e4);
        sp.e6 = (sp.one_minus_k as f64).mul_add(sp.e6, sp.k * sp.e5);
        (*outReal) = (sp.c4 as f64).mul_add(sp.e3, (sp.c3 as f64).mul_add(sp.e4, (sp.c1 as f64).mul_add(sp.e6, sp.c2 * sp.e5)));
    }

    /// The single whole-history transcription behind [`Core::T3_OpenInternal`]
    /// (stride 0, scalar sink) and [`Core::T3_OpenAndFill`] (stride 1, caller slices).
    pub(crate) fn T3_OpenImpl(
        &self, inReal: &[f64], startIdx: usize, mut optInTimePeriod: i32, mut optInVFactor: f64, outBegIdx: &mut usize, outNBElement: &mut usize, outReal: &mut [f64], outStride: usize,
    ) -> Result<T3_Stream, RetCode> {
        if inReal.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inReal.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        if ((optInTimePeriod) as i32) == (i32::MIN) {
            optInTimePeriod = 5;
        } else if (((optInTimePeriod) as i32) < 1) || (((optInTimePeriod) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        if optInVFactor == Self::REAL_DEFAULT {
            optInVFactor = 7e-1;
        } else if !((optInVFactor >= 0e0) && (optInVFactor <= 1e0)) {
            return Err(RetCode::BadParam);
        }
        let historyLen: usize = inReal.len();
        let endIdx: usize = historyLen - 1;
        let mut startIdx = startIdx;
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        if optInTimePeriod == 1 {
            let fillLb: usize = self.T3_Lookback(optInTimePeriod, optInVFactor)?;
            let fillLb = if startIdx > fillLb { startIdx } else { fillLb };
            if historyLen < fillLb + 1 {
                return Err(RetCode::InsufficientHistory);
            }
            let state = T3_StreamState {
                optInTimePeriod: optInTimePeriod,
                optInVFactor: optInVFactor,
                k: 0.0_f64,
                one_minus_k: 0.0_f64,
                e1: 0.0_f64,
                e2: 0.0_f64,
                e3: 0.0_f64,
                e4: 0.0_f64,
                e5: 0.0_f64,
                e6: 0.0_f64,
                c1: 0.0_f64,
                c2: 0.0_f64,
                c3: 0.0_f64,
                c4: 0.0_f64,
            };
            (*outBegIdx) = fillLb;
            (*outNBElement) = historyLen - fillLb;
            if outStride == 0 {
                outReal[0] = inReal[historyLen - 1];
            } else {
                let mut fillIdx: usize = 0;
                while fillIdx < historyLen - fillLb {
                    outReal[fillIdx] = inReal[fillLb + fillIdx];
                    fillIdx += 1;
                }
            }
            return Ok(T3_Stream { state, out: OutRange { beg_idx: *outBegIdx, count: *outNBElement } });
        }
        let mut outIdx: usize = 0_usize;
        let mut lookbackTotal: usize = 0_usize;
        let mut today: usize = 0_usize;
        let mut i: usize = 0_usize;
        let mut k: f64 = 0.0_f64;
        let mut one_minus_k: f64 = 0.0_f64;
        let mut e1: f64 = 0.0_f64;
        let mut e2: f64 = 0.0_f64;
        let mut e3: f64 = 0.0_f64;
        let mut e4: f64 = 0.0_f64;
        let mut e5: f64 = 0.0_f64;
        let mut e6: f64 = 0.0_f64;
        let mut c1: f64 = 0.0_f64;
        let mut c2: f64 = 0.0_f64;
        let mut c3: f64 = 0.0_f64;
        let mut c4: f64 = 0.0_f64;
        let mut tempReal: f64 = 0.0_f64;
        // For an explanation of this function, please read:
        //
        // Magazine articles written by Tim Tillson
        //
        // Essentially, a T3 of time serie 't' is:
        //   EMA1(x,Period) = EMA(x,Period)
        //   EMA2(x,Period) = EMA(EMA1(x,Period),Period)
        //   GD(x,Period,vFactor) = (EMA1(x,Period)*(1+vFactor)) - (EMA2(x,Period)*vFactor)
        //   T3 = GD (GD ( GD(t, Period, vFactor), Period, vFactor), Period, vFactor);
        //
        // T3 offers a moving average with less lags then the
        // traditional EMA.
        //
        // Do not confuse a T3 with EMA3. Both are called "Triple EMA"
        // in the litterature.
        lookbackTotal = (6 * (optInTimePeriod - 1) + self.unstable_period[FuncUnstId::T3 as usize]) as usize;
        if startIdx <= lookbackTotal {
            startIdx = lookbackTotal;
        }
        // Make sure there is still something to evaluate.
        if startIdx > endIdx {
            (*outNBElement) = 0;
            (*outBegIdx) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        (*outBegIdx) = startIdx;
        today = startIdx - lookbackTotal;
        k = 2.0 / (((optInTimePeriod) as f64) + 1.0);
        one_minus_k = 1.0 - k;
        // Initialize e1
        tempReal = inReal[{ let _v = today; today += 1; _v }];
        // for( i = (optInTimePeriod - 1) as usize; i > 0; i -= 1 )
        i = (optInTimePeriod - 1) as usize;
        while i > 0 {
            tempReal += inReal[{ let _v = today; today += 1; _v }];
            i -= 1;
        }
        e1 = tempReal / ((optInTimePeriod) as f64);
        // Initialize e2
        tempReal = e1;
        // for( i = (optInTimePeriod - 1) as usize; i > 0; i -= 1 )
        i = (optInTimePeriod - 1) as usize;
        while i > 0 {
            e1 = (one_minus_k as f64).mul_add(e1, k * inReal[{ let _v = today; today += 1; _v }]);
            tempReal += e1;
            i -= 1;
        }
        e2 = tempReal / ((optInTimePeriod) as f64);
        // Initialize e3
        tempReal = e2;
        // for( i = (optInTimePeriod - 1) as usize; i > 0; i -= 1 )
        i = (optInTimePeriod - 1) as usize;
        while i > 0 {
            e1 = (one_minus_k as f64).mul_add(e1, k * inReal[{ let _v = today; today += 1; _v }]);
            e2 = (one_minus_k as f64).mul_add(e2, k * e1);
            tempReal += e2;
            i -= 1;
        }
        e3 = tempReal / ((optInTimePeriod) as f64);
        // Initialize e4
        tempReal = e3;
        // for( i = (optInTimePeriod - 1) as usize; i > 0; i -= 1 )
        i = (optInTimePeriod - 1) as usize;
        while i > 0 {
            e1 = (one_minus_k as f64).mul_add(e1, k * inReal[{ let _v = today; today += 1; _v }]);
            e2 = (one_minus_k as f64).mul_add(e2, k * e1);
            e3 = (one_minus_k as f64).mul_add(e3, k * e2);
            tempReal += e3;
            i -= 1;
        }
        e4 = tempReal / ((optInTimePeriod) as f64);
        // Initialize e5
        tempReal = e4;
        // for( i = (optInTimePeriod - 1) as usize; i > 0; i -= 1 )
        i = (optInTimePeriod - 1) as usize;
        while i > 0 {
            e1 = (one_minus_k as f64).mul_add(e1, k * inReal[{ let _v = today; today += 1; _v }]);
            e2 = (one_minus_k as f64).mul_add(e2, k * e1);
            e3 = (one_minus_k as f64).mul_add(e3, k * e2);
            e4 = (one_minus_k as f64).mul_add(e4, k * e3);
            tempReal += e4;
            i -= 1;
        }
        e5 = tempReal / ((optInTimePeriod) as f64);
        // Initialize e6
        tempReal = e5;
        // for( i = (optInTimePeriod - 1) as usize; i > 0; i -= 1 )
        i = (optInTimePeriod - 1) as usize;
        while i > 0 {
            e1 = (one_minus_k as f64).mul_add(e1, k * inReal[{ let _v = today; today += 1; _v }]);
            e2 = (one_minus_k as f64).mul_add(e2, k * e1);
            e3 = (one_minus_k as f64).mul_add(e3, k * e2);
            e4 = (one_minus_k as f64).mul_add(e4, k * e3);
            e5 = (one_minus_k as f64).mul_add(e5, k * e4);
            tempReal += e5;
            i -= 1;
        }
        e6 = tempReal / ((optInTimePeriod) as f64);
        // Skip the unstable period
        while today <= startIdx {
            // Do the calculation but do not write the output
            e1 = (one_minus_k as f64).mul_add(e1, k * inReal[{ let _v = today; today += 1; _v }]);
            e2 = (one_minus_k as f64).mul_add(e2, k * e1);
            e3 = (one_minus_k as f64).mul_add(e3, k * e2);
            e4 = (one_minus_k as f64).mul_add(e4, k * e3);
            e5 = (one_minus_k as f64).mul_add(e5, k * e4);
            e6 = (one_minus_k as f64).mul_add(e6, k * e5);
        }
        // Calculate the constants
        tempReal = optInVFactor * optInVFactor;
        c1 = 0_f64 - tempReal * optInVFactor;
        c2 = 3.0 * (tempReal - c1);
        c3 = (0_f64 - 6.0) * tempReal - 3.0 * (optInVFactor - c1);
        c4 = (3.0 as f64).mul_add(tempReal, (3.0 as f64).mul_add(optInVFactor, 1.0) - c1);
        // Write the first output
        outIdx = 0;
        outReal[({ let _v = outIdx; outIdx += 1; _v } * outStride) as usize] = (c4 as f64).mul_add(e3, (c3 as f64).mul_add(e4, (c1 as f64).mul_add(e6, c2 * e5)));
        // Calculate and output the remaining of the range.
        while today <= endIdx {
            e1 = (one_minus_k as f64).mul_add(e1, k * inReal[{ let _v = today; today += 1; _v }]);
            e2 = (one_minus_k as f64).mul_add(e2, k * e1);
            e3 = (one_minus_k as f64).mul_add(e3, k * e2);
            e4 = (one_minus_k as f64).mul_add(e4, k * e3);
            e5 = (one_minus_k as f64).mul_add(e5, k * e4);
            e6 = (one_minus_k as f64).mul_add(e6, k * e5);
            outReal[({ let _v = outIdx; outIdx += 1; _v } * outStride) as usize] = (c4 as f64).mul_add(e3, (c3 as f64).mul_add(e4, (c1 as f64).mul_add(e6, c2 * e5)));
        }
        // Indicates to the caller the number of output
        // successfully calculated.
        (*outNBElement) = outIdx;

        // Capture the live batch state into the handle.
        let state = T3_StreamState {
            optInTimePeriod,
            optInVFactor,
            k,
            one_minus_k,
            e1,
            e2,
            e3,
            e4,
            e5,
            e6,
            c1,
            c2,
            c3,
            c4,
        };
        Ok(T3_Stream { state, out: OutRange { beg_idx: *outBegIdx, count: *outNBElement } })
    }

    /// Internal startIdx-anchored open behind [`Core::T3_Open`] (composition seam).
    pub(crate) fn T3_OpenInternal(
        &self, inReal: &[f64], startIdx: usize, mut optInTimePeriod: i32, mut optInVFactor: f64,
    ) -> Result<(T3_Stream, f64), RetCode> {
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut sink_outReal = [0.0_f64; 1];
        let handle = self.T3_OpenImpl(inReal, startIdx, optInTimePeriod, optInVFactor, &mut dummyBegIdx, &mut dummyNBElement, &mut sink_outReal, 0)?;
        Ok((handle, sink_outReal[0]))
    }

    /// Open a live T3 stream over the warm-up history; returns the handle and
    /// the value at the last history bar — bit-identical to [`Core::T3`] at that bar.
    ///
    /// # Errors
    ///
    /// [`RetCode::InsufficientHistory`] when the history holds fewer than
    /// `lookback + 1` bars — the one failure here worth retrying, since another
    /// bar fixes it. [`RetCode::OutOfRangeStartIndex`] when the history is empty.
    /// [`RetCode::BadParam`] when a parameter is out of range or the input
    /// lengths differ.
    ///
    /// ```
    /// use ta_lib::Core;
    /// let data: Vec<f64> = (0..252).map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    ///
    /// let core = Core::new();
    /// let (mut s, _last) = core.T3_Open(&data, 5, 0.7).expect("enough history");
    /// let r0 = s.out_range();
    /// let peeked = s.peek(100.9).expect("a finite bar");
    /// assert_eq!(s.out_range().count, r0.count); // a peek commits nothing
    /// let updated = s.update(100.9).expect("a finite bar");
    /// assert_eq!(s.out_range().beg_idx, r0.beg_idx);
    /// assert_eq!(s.out_range().count, r0.count + 1);
    /// assert_eq!(peeked.to_bits(), updated.to_bits());
    /// ```
    #[doc(alias = "TA_T3_Open")]
    pub fn T3_Open(&self, inReal: &[f64], optInTimePeriod: i32, optInVFactor: f64) -> Result<(T3_Stream, f64), RetCode> {
        self.T3_OpenInternal(inReal, 0, optInTimePeriod, optInVFactor)
    }

    /// [`Core::T3_Open`] that also fills the output array(s) bit-identically to
    /// [`Core::T3`] over `0..len` in the same single pass, and reports the range it
    /// wrote as the [`OutRange`] beside the handle.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] when an output slice holds fewer than `len - lookback`
    /// values — the batch tier's sizing rule, checked here as it is there (rule S5) —
    /// or when two of them are the same slice. Everything [`Core::T3_Open`] rejects
    /// is rejected here too.
    #[doc(alias = "TA_T3_OpenAndFill")]
    pub fn T3_OpenAndFill(
        &self, inReal: &[f64], mut optInTimePeriod: i32, mut optInVFactor: f64, outReal: &mut [f64],
    ) -> Result<(T3_Stream, OutRange), RetCode> {
        if inReal.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inReal.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        let _guardLb = self.T3_Lookback(optInTimePeriod, optInVFactor)?;
        let _guardOutLen = inReal.len().saturating_sub(_guardLb);
        if outReal.len() < _guardOutLen {
            return Err(RetCode::BadParam);
        }
        let mut outBegIdx: usize = 0;
        let mut outNBElement: usize = 0;
        let handle = self.T3_OpenAndFillInternal(inReal, 0, optInTimePeriod, optInVFactor, &mut outBegIdx, &mut outNBElement, outReal)?;
        Ok((handle, OutRange { beg_idx: outBegIdx, count: outNBElement }))
    }

    /// [`Core::T3_OpenAndFill`] anchored at `startIdx` — the composed-open
    /// fusion seam (issue #192), not a public entry point.
    pub(crate) fn T3_OpenAndFillInternal(
        &self, inReal: &[f64], startIdx: usize, mut optInTimePeriod: i32, mut optInVFactor: f64, outBegIdx: &mut usize, outNBElement: &mut usize, outReal: &mut [f64],
    ) -> Result<T3_Stream, RetCode> {
        self.T3_OpenImpl(inReal, startIdx, optInTimePeriod, optInVFactor, outBegIdx, outNBElement, outReal, 1)
    }

}

#[allow(non_snake_case)]
#[allow(unused_variables)]
impl T3_Stream {
    /// Commit one closed bar. Never allocates.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite (NaN or ±Inf).
    /// That check runs before anything is written, so the handle is left
    /// exactly as it was and the stream stays usable:
    /// skip the bar, or close and re-open on a clean history. This is the
    /// one place the streaming tier is stricter than the batch API, which
    /// computes on whatever it is given — a handle retains its state, so a
    /// single non-finite bar would poison every later value it produces.
    #[doc(alias = "TA_T3_Update")]
    pub fn update(&mut self, inReal: f64) -> Result<f64, RetCode> {
        if !inReal.is_finite() {
            return Err(RetCode::BadParam);
        }
        let mut outReal: f64 = 0.0_f64;
        Core::T3_step_impl(&mut self.state, inReal, &mut outReal);
        if self.out.count < Core::MAX_INDEX {
            self.out.count += 1;
        }
        Ok(outReal)
    }

    /// Commit `n` closed bars and write their `n` values, in one call —
    /// exactly `n` back-to-back [`Self::update`] calls, with one set of
    /// argument checks instead of `n`. `n` is `inReal.len()`; the outputs must
    /// hold at least that many. Never allocates.
    ///
    /// [`Self::out_range`] counts what was committed, which is what makes the
    /// rejection below readable: there is no second out-parameter for it.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if the input slices differ in length, if an output
    /// is shorter than the bar count — neither commits anything — or if a bar
    /// is not finite. A non-finite bar `k` is rejected exactly as `update`
    /// rejects it: bars `0..k` stay committed and their values written, bar `k`
    /// and everything after it is not, and `out_range().count` has advanced by
    /// `k`.
    #[doc(alias = "TA_T3_UpdateAndFill")]
    pub fn update_and_fill(&mut self, inReal: &[f64], outReal: &mut [f64]) -> Result<(), RetCode> {
        let barCount = inReal.len();
        if outReal.len() < barCount {
            return Err(RetCode::BadParam);
        }
        for i in 0..barCount {
            if !inReal[i].is_finite() {
                return Err(RetCode::BadParam);
            }
            Core::T3_step_impl(&mut self.state, inReal[i], &mut outReal[i]);
            if self.out.count < Core::MAX_INDEX {
                self.out.count += 1;
            }
        }
        Ok(())
    }

    /// Evaluate a forming bar without committing — bit-identical to what the
    /// next `update` with the same bar would return (it is the same code, run
    /// on a scratch copy of the state). Never writes the handle, so peeks may
    /// run concurrently with each other. This handle holds only scalars, so the copy is a
    /// few machine words and `peek` never allocates.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite, exactly as
    /// `update` rejects it.
    #[doc(alias = "TA_T3_Peek")]
    pub fn peek(&self, inReal: f64) -> Result<f64, RetCode> {
        if !inReal.is_finite() {
            return Err(RetCode::BadParam);
        }
        let mut scratch = self.clone();
        scratch.update(inReal)
    }

    /// The bars this stream has produced a value for, in the input series'
    /// coordinates: `[beg_idx, beg_idx + count)`.
    ///
    /// It is what [`Core::T3`] reports over the same bars: the opener sets it
    /// to `(lookback, historyLen - lookback)`, every accepted `update` adds one
    /// to the count, `peek` leaves it alone, and a clone carries it verbatim.
    /// A plain `Open` hands back only the last value, a subset of this range,
    /// because the caller chose not to take the fill.
    #[doc(alias = "TA_StreamOutRange")]
    pub fn out_range(&self) -> OutRange {
        self.out
    }
}

