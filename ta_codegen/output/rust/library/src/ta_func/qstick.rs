    fn QSTICK_step_internal(&self, sp: &mut QSTICK_StreamState, inOpen: f64, inClose: f64, outReal: &mut f64) {
        if sp.ringCap_trailingIdx == 0 {
            sp.ring_trailingIdx_inOpen[0] = inOpen;
            sp.ring_trailingIdx_inClose[0] = inClose;
        }
        sp.periodTotal += (inClose - inOpen) as f64;
        sp.tempReal = sp.periodTotal;
        sp.periodTotal -= (sp.ring_trailingIdx_inClose[sp.ringPos_trailingIdx] - sp.ring_trailingIdx_inOpen[sp.ringPos_trailingIdx]) as f64;
        (*outReal) = sp.tempReal / (sp.optInTimePeriod as f64);
        sp.ring_trailingIdx_inOpen[sp.ringPos_trailingIdx] = inOpen;
        sp.ring_trailingIdx_inClose[sp.ringPos_trailingIdx] = inClose;
        sp.ringPos_trailingIdx = sp.ringPos_trailingIdx + 1;
        if sp.ringPos_trailingIdx >= sp.ringCap_trailingIdx {
            sp.ringPos_trailingIdx = 0;
        }
    }

    /// The single whole-history transcription behind [`Core::QSTICK_OpenInternal`]
    /// (stride 0, scalar sink) and [`Core::QSTICK_OpenAndFill`] (stride 1, caller slices).
    pub(crate) fn QSTICK_OpenCore(
        &self, inOpen: &[f64], inClose: &[f64], startIdx: usize, mut optInTimePeriod: i32, outBegIdx: &mut usize, outNBElement: &mut usize, outReal: &mut [f64], outStride: usize,
    ) -> Result<QSTICK_Stream, RetCode> {
        if inOpen.is_empty() || inClose.is_empty() || inClose.len() != inOpen.len() {
            return Err(RetCode::BadParam);
        }
        if inOpen.len() > MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        if ((optInTimePeriod) as i32) == (i32::MIN) {
            optInTimePeriod = 10;
        } else if (((optInTimePeriod) as i32) < 1) || (((optInTimePeriod) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        let historyLen: usize = inOpen.len();
        let endIdx: usize = historyLen - 1;
        let mut startIdx = startIdx;
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut periodTotal: f64 = 0.0_f64;
        let mut tempReal: f64 = 0.0_f64;
        let mut i: usize = 0_usize;
        let mut outIdx: usize = 0_usize;
        let mut trailingIdx: usize = 0_usize;
        let mut lookbackTotal: usize = 0_usize;
        // Qstick (Chande & Kroll, The New Technical Trader, 1994): a simple moving
        // average of the candle body, close minus open. Above zero means bodies
        // were predominantly bullish over the window; the zero crossings are the
        // signal.
        //
        // This is ta_codegen/input/sma/sma.c with inReal[x] replaced by
        // (inClose[x] - inOpen[x]), and deliberately nothing else: the same
        // running-sum order, the same read-before-write of the trailing term, and
        // the same divide by the period. Keeping the arithmetic identical is what
        // makes the composed reference in test_composite.c -- TA_SUB followed by
        // TA_SMA -- bit-exact rather than merely close, so any future drift in
        // either path is a hard failure instead of a tolerance argument.
        //
        // In particular the last statement divides; it does NOT multiply by a
        // precomputed 1/period. Tulip's qstick.c multiplies, which costs it up to
        // one ULP against TA_SMA. Dividing buys the memcmp differential, which is
        // the stronger of the two gates.
        // Identify the minimum number of price bar needed
        // to calculate at least one output.
        lookbackTotal = (optInTimePeriod - 1) as usize;
        // Move up the start index if there is not
        // enough initial data.
        if startIdx < lookbackTotal {
            startIdx = lookbackTotal;
        }
        // Make sure there is still something to evaluate.
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::BadParam);
        }
        // Do the MA calculation using tight loops.
        // Add-up the initial period, except for the last value.
        periodTotal = 0.0;
        trailingIdx = startIdx - lookbackTotal;
        i = trailingIdx;
        if optInTimePeriod > 1 {
            while i < startIdx {
                periodTotal += (inClose[i] - inOpen[i]) as f64;
                i = i + 1;
            }
        }
        // Proceed with the calculation for the requested range.
        // Note that this algorithm allows outReal to be the same
        // buffer as either input.
        outIdx = 0;
        while i <= endIdx {
            periodTotal += (inClose[i] - inOpen[i]) as f64;
            i = i + 1;
            tempReal = periodTotal;
            periodTotal -= (inClose[trailingIdx] - inOpen[trailingIdx]) as f64;
            trailingIdx = trailingIdx + 1;
            outReal[(outIdx * outStride) as usize] = tempReal / (optInTimePeriod as f64);
            outIdx = outIdx + 1;
        }
        // All done. Indicate the output limits and return.
        (*outNBElement) = outIdx;
        (*outBegIdx) = startIdx;

        // Capture the live batch state into the handle.
        let cap_trailingIdx: i64 = (i as i64) - (trailingIdx as i64);
        if cap_trailingIdx < 0 || cap_trailingIdx > historyLen as i64 {
            return Err(RetCode::InternalError);
        }
        let allocN_trailingIdx: usize = if cap_trailingIdx > 0 { cap_trailingIdx as usize } else { 1 };
        let mut ring_trailingIdx_inOpen: Vec<f64> = vec![0.0_f64; allocN_trailingIdx];
        ring_trailingIdx_inOpen[..cap_trailingIdx as usize]
            .copy_from_slice(&inOpen[historyLen - cap_trailingIdx as usize..]);
        let mut ring_trailingIdx_inClose: Vec<f64> = vec![0.0_f64; allocN_trailingIdx];
        ring_trailingIdx_inClose[..cap_trailingIdx as usize]
            .copy_from_slice(&inClose[historyLen - cap_trailingIdx as usize..]);
        let state = QSTICK_StreamState {
            optInTimePeriod,
            periodTotal,
            tempReal,
            ringPos_trailingIdx: 0_usize,
            ringCap_trailingIdx: cap_trailingIdx as usize,
            ring_trailingIdx_inOpen,
            ring_trailingIdx_inClose,
        };
        Ok(QSTICK_Stream { core: self.clone(), state })
    }

    /// Internal startIdx-anchored open behind [`Core::QSTICK_Open`] (composition seam).
    pub(crate) fn QSTICK_OpenInternal(
        &self, inOpen: &[f64], inClose: &[f64], startIdx: usize, mut optInTimePeriod: i32,
    ) -> Result<(QSTICK_Stream, f64), RetCode> {
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut sink_outReal = [0.0_f64; 1];
        let handle = self.QSTICK_OpenCore(inOpen, inClose, startIdx, optInTimePeriod, &mut dummyBegIdx, &mut dummyNBElement, &mut sink_outReal, 0)?;
        Ok((handle, sink_outReal[0]))
    }

    /// Open a live QSTICK stream over the warm-up history; returns the handle and
    /// the value at the last history bar — bit-identical to [`Core::QSTICK`] at that bar.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] when a parameter is out of range, an input is empty or
    /// input lengths differ, or the history is shorter than `lookback + 1` bars.
    ///
    /// ```
    /// use ta_lib::Core;
    /// let open: Vec<f64> = (0..252)
    ///     .map(|i| 100.0 + 10.0 * (0.1 * i as f64 - 0.05).sin())
    ///     .collect();
    /// let close: Vec<f64> = (0..252)
    ///     .map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin() + 0.8 * (0.7 * i as f64).sin())
