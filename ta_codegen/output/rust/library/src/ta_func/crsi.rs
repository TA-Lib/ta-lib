    fn crsi_step_impl(sp: &mut CrsiStreamState, inReal: f64, outReal: &mut f64) -> Result<(), RetCode> {
        let mut close: f64 = 0.0_f64;
        let mut cur_tempStreak: f64 = 0.0_f64;
        let mut cur_tempStreakRSI: f64 = 0.0_f64;
        let mut cur_tempRSI: f64 = 0.0_f64;
        let mut cur_outReal: f64 = 0.0_f64;
        close = inReal;
        if close > sp.prevClose {
            sp.streak = (if sp.streak > 0.0 { sp.streak + 1.0 } else { 1.0 });
        } else if close < sp.prevClose {
            sp.streak = (if sp.streak < 0.0 { sp.streak - 1.0 } else { 0_f64 - 1.0 });
        } else {
            sp.streak = 0.0;
        }
        cur_tempStreak = sp.streak;
        sp.prevClose = close;

        // Pipeline the new bar through the sub-streams (batch tail order).
        cur_tempStreakRSI = sp.sub0.update(cur_tempStreak)?;
        cur_tempRSI = sp.sub1.update(inReal)?;
        cur_tempStreak = sp.sub2.update(inReal)?;
        cur_outReal = sp.sub3.update(cur_tempStreak)?;
        // Combine map (batch tail, per bar).
        cur_outReal = (cur_tempRSI + cur_tempStreakRSI + cur_outReal) / 3.0;
        (*outReal) = cur_outReal;
        Ok(())
    }

