    /// let data: Vec<f64> = (0..252).map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    ///
    /// let core = Core::new();
    /// let (mut s, _last) = core.stddev_open(&data, 5, 1.0).expect("enough history");
    /// let r0 = s.out_range();
