    fn STDDEV_step_internal(&self, sp: &mut STDDEV_StreamState, inReal: f64, outReal: &mut f64) -> Result<(), RetCode> {
        let mut tempReal: f64 = 0.0_f64;
        let mut cur_outReal: f64 = 0.0_f64;

        // Pipeline the new bar through the sub-streams (batch tail order).
        cur_outReal = sp.sub0.update(inReal)?;
        // Combine map (batch tail, per bar).
        if sp.optInNbDev != 1.0 {
            tempReal = cur_outReal;
            if !((tempReal) < 1e-14) {
                cur_outReal = (tempReal).sqrt() * sp.optInNbDev;
            } else {
                cur_outReal = 0.0 as f64;
            }
        } else {
            tempReal = cur_outReal;
            if !((tempReal) < 1e-14) {
                cur_outReal = (tempReal).sqrt();
            } else {
                cur_outReal = 0.0 as f64;
            }
        }
        (*outReal) = cur_outReal;
        Ok(())
    }

    /// The single whole-history transcription behind [`Core::STDDEV_OpenInternal`]
    /// (stride 0, scalar sink) and [`Core::STDDEV_OpenAndFill`] (stride 1, caller slices).
    pub(crate) fn STDDEV_OpenPass(
        &self, inReal: &[f64], startIdx: usize, mut optInTimePeriod: i32, mut optInNbDev: f64, outBegIdx: &mut usize, outNBElement: &mut usize, outReal: &mut [f64], outStride: usize,
    ) -> Result<STDDEV_Stream, RetCode> {
        if inReal.is_empty() {
            return Err(RetCode::BadParam);
        }
        if inReal.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        if ((optInTimePeriod) as i32) == (i32::MIN) {
            optInTimePeriod = 5;
        } else if (((optInTimePeriod) as i32) < 2) || (((optInTimePeriod) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        if optInNbDev == Self::REAL_DEFAULT {
            optInNbDev = 1e0;
        } else if !((optInNbDev >= Self::REAL_MIN) && (optInNbDev <= Self::REAL_MAX)) {
            return Err(RetCode::BadParam);
        }
        let historyLen: usize = inReal.len();
        let endIdx: usize = historyLen - 1;
        let mut startIdx = startIdx;
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut owned_sc_outReal: Vec<f64> =
            if outStride == 1 { Vec::new() } else { vec![0.0_f64; historyLen] };
        let sc_outReal: &mut [f64] =
            if outStride == 1 { &mut *outReal } else { &mut owned_sc_outReal };
        let mut i: usize = 0_usize;
        let mut retCode: RetCode = RetCode::Success;
        let mut tempReal: f64 = 0.0_f64;
        // Nothing to produce: the range is shorter than the lookback. Return before
        // touching anything.
        //
        // Same shape as the guard in apo and bbands: the variance below runs on the
        // same range and its lookback IS stddev's, so it declines and yields 0,0
        // without reading. Observably identical, but it makes "a range shorter than
        // the lookback reads nothing" true of stddev itself rather than only of var.
        // Pinned by the zero-length no-I/O probe over every guarded core.
        if self.STDDEV_Lookback(optInTimePeriod, optInNbDev) > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        // Calculate the variance.
        // Sub-stream 0: var over `inReal`, warmed from bar 0 up to the
        // sub-call's own startIdx (the seeding point).
        let sub0 = self.VAR_OpenAndFillInternal(&inReal[..((endIdx) as usize) + 1], ((startIdx) as usize), optInTimePeriod, 1.0, outBegIdx, outNBElement, &mut sc_outReal[..])?;
        retCode = RetCode::Success;
        if retCode != RetCode::Success {
            return Err(retCode);
        }
        // Calculate the square root of each variance, this
        // is the standard deviation.
        //
        // Multiply also by the ratio specified.
        if optInNbDev != 1.0 {
            // for( i = 0; i < ((((*outNBElement) as usize)) as usize); i += 1 )
            i = 0;
            while i < ((((*outNBElement) as usize)) as usize) {
                tempReal = sc_outReal[i];
                if !((tempReal) < 1e-14) {
                    sc_outReal[i] = (tempReal).sqrt() * optInNbDev;
                } else {
                    sc_outReal[i] = 0.0 as f64;
                }
                i += 1;
            }
        } else {
            // for( i = 0; i < ((((*outNBElement) as usize)) as usize); i += 1 )
            i = 0;
            while i < ((((*outNBElement) as usize)) as usize) {
                tempReal = sc_outReal[i];
                if !((tempReal) < 1e-14) {
                    sc_outReal[i] = (tempReal).sqrt();
                } else {
                    sc_outReal[i] = 0.0 as f64;
                }
                i += 1;
            }
        }

        // Capture the live producer state + sub handles.
        if *outNBElement < 1 {
            return Err(RetCode::InsufficientHistory);
        }
        let state = STDDEV_StreamState {
            optInTimePeriod,
            optInNbDev,
            sub0,
        };
        if outStride != 1 && *outNBElement > 0 {
            let last_sc_outReal = sc_outReal[*outNBElement - 1];
            outReal[0] = last_sc_outReal;
        }
        Ok(STDDEV_Stream { core: self.clone(), state })
    }

    /// Internal startIdx-anchored open behind [`Core::STDDEV_Open`] (composition seam).
    pub(crate) fn STDDEV_OpenInternal(
        &self, inReal: &[f64], startIdx: usize, mut optInTimePeriod: i32, mut optInNbDev: f64,
    ) -> Result<(STDDEV_Stream, f64), RetCode> {
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut sink_outReal = [0.0_f64; 1];
        let handle = self.STDDEV_OpenPass(inReal, startIdx, optInTimePeriod, optInNbDev, &mut dummyBegIdx, &mut dummyNBElement, &mut sink_outReal, 0)?;
        Ok((handle, sink_outReal[0]))
    }

    /// Open a live STDDEV stream over the warm-up history; returns the handle and
    /// the value at the last history bar — bit-identical to [`Core::STDDEV`] at that bar.
    ///
    /// # Errors
    ///
    /// [`RetCode::InsufficientHistory`] when the history holds fewer than
    /// `lookback + 1` bars — the one failure here worth retrying, since another
    /// bar fixes it. [`RetCode::BadParam`] when a parameter is out of range, an
    /// input is empty, or input lengths differ.
    ///
    /// ```
    /// use ta_lib::Core;
    /// let data: Vec<f64> = (0..252).map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    ///
    /// let core = Core::new();
    /// let (mut s, _last) = core.STDDEV_Open(&data, 5, 1.0).expect("enough history");
    /// let peeked = s.peek(100.9).expect("a finite bar");
    /// let updated = s.update(100.9).expect("a finite bar");
    /// assert_eq!(peeked.to_bits(), updated.to_bits());
    /// ```
