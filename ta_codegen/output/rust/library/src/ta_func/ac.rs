impl Core {
    fn AC_step_internal(&self, sp: &mut AC_StreamState, inHigh: f64, inLow: f64, outReal: &mut f64) {
        let mut medianPrice: f64 = 0.0_f64;
        if sp.ringCap_trailingFastIdx == 0 {
            sp.ring_trailingFastIdx_derived[0] = (inHigh + inLow) / 2.0;
        }
        if sp.ringCap_trailingSlowIdx == 0 {
            sp.ring_trailingSlowIdx_derived[0] = (inHigh + inLow) / 2.0;
        }
        medianPrice = (inHigh + inLow) / 2.0;
        sp.sumFast += medianPrice;
        sp.sumSlow += medianPrice;
        // Snapshot the oscillator before either total drops its trailing bar,
        // mirroring the add-new / snapshot / subtract-old order of TA_SMA.
        sp.osc = sp.sumFast / (sp.optInFastPeriod as f64) - sp.sumSlow / (sp.optInSlowPeriod as f64);
        sp.sumFast -= sp.ring_trailingFastIdx_derived[sp.ringPos_trailingFastIdx];
        sp.sumSlow -= sp.ring_trailingSlowIdx_derived[sp.ringPos_trailingSlowIdx];
        // Today's oscillator enters the signal window at its own slot, and the
        // bar leaving that window is read only after the ring has advanced onto
        // it -- writing first is what makes the slot the loop is about to
        // overwrite the newest value rather than the oldest one.
        sp.cb_oscBuffer[sp.oscBuffer_Idx] = sp.osc;
        sp.sumSignal += sp.osc;
        sp.tempReal = sp.osc - sp.sumSignal / (sp.optInSignalPeriod as f64);
        sp.oscBuffer_Idx = sp.oscBuffer_Idx + 1;
        if sp.oscBuffer_Idx > sp.maxIdx_oscBuffer {
            sp.oscBuffer_Idx = 0;
        }
        sp.sumSignal -= sp.cb_oscBuffer[sp.oscBuffer_Idx];
        // Every input read for this bar is done above, so the store is safe
        // when the caller aliases outReal over inHigh or inLow. Unlike ao.c
        // there is slack here -- the signal window puts both trailing indices
        // at least optInSignalPeriod-1 bars ahead of outIdx, so no reachable
        // parameter makes them collide -- but the order is kept anyway, so
        // that admitting a signal period of 1 would not silently reintroduce
        // the collision ao.c has to guard against.
        (*outReal) = sp.tempReal;
        sp.ring_trailingFastIdx_derived[sp.ringPos_trailingFastIdx] = (inHigh + inLow) / 2.0;
        sp.ringPos_trailingFastIdx = sp.ringPos_trailingFastIdx + 1;
        if sp.ringPos_trailingFastIdx >= sp.ringCap_trailingFastIdx {
            sp.ringPos_trailingFastIdx = 0;
        }
        sp.ring_trailingSlowIdx_derived[sp.ringPos_trailingSlowIdx] = (inHigh + inLow) / 2.0;
        sp.ringPos_trailingSlowIdx = sp.ringPos_trailingSlowIdx + 1;
        if sp.ringPos_trailingSlowIdx >= sp.ringCap_trailingSlowIdx {
            sp.ringPos_trailingSlowIdx = 0;
        }
    }

    /// The single whole-history transcription behind [`Core::AC_OpenInternal`]
    /// (stride 0, scalar sink) and [`Core::AC_OpenAndFill`] (stride 1, caller slices).
    pub(crate) fn AC_OpenPass(
        &self, inHigh: &[f64], inLow: &[f64], startIdx: usize, mut optInFastPeriod: i32, mut optInSlowPeriod: i32, mut optInSignalPeriod: i32, outBegIdx: &mut usize, outNBElement: &mut usize, outReal: &mut [f64], outStride: usize,
    ) -> Result<AC_Stream, RetCode> {
        if inHigh.is_empty() || inLow.is_empty() || inLow.len() != inHigh.len() {
            return Err(RetCode::BadParam);
        }
        if inHigh.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        if ((optInFastPeriod) as i32) == (i32::MIN) {
            optInFastPeriod = 5;
        } else if (((optInFastPeriod) as i32) < 2) || (((optInFastPeriod) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        if ((optInSlowPeriod) as i32) == (i32::MIN) {
            optInSlowPeriod = 34;
        } else if (((optInSlowPeriod) as i32) < 2) || (((optInSlowPeriod) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        if ((optInSignalPeriod) as i32) == (i32::MIN) {
            optInSignalPeriod = 5;
        } else if (((optInSignalPeriod) as i32) < 2) || (((optInSignalPeriod) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        let historyLen: usize = inHigh.len();
        let endIdx: usize = historyLen - 1;
        let mut startIdx = startIdx;
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut sumFast: f64 = 0.0_f64;
        let mut sumSlow: f64 = 0.0_f64;
        let mut sumSignal: f64 = 0.0_f64;
        let mut medianPrice: f64 = 0.0_f64;
        let mut osc: f64 = 0.0_f64;
        let mut tempReal: f64 = 0.0_f64;
        let mut i: usize = 0_usize;
        let mut outIdx: usize = 0_usize;
        let mut trailingFastIdx: usize = 0_usize;
        let mut trailingSlowIdx: usize = 0_usize;
        let mut oscStartIdx: usize = 0_usize;
        let mut lookbackTotal: usize = 0_usize;
        let mut oscBuffer: Vec<f64> = Vec::new();
        let mut oscBuffer_Idx: usize = 0;
        let mut maxIdx_oscBuffer: usize = 31;
        // Bill Williams' Accelerator/Decelerator Oscillator (New Trading
        // Dimensions, 1998): how fast the Awesome Oscillator is itself
        // accelerating, drawn as a zero-centred histogram.
        //
        //    AO_t = SMA(median, fast)_t - SMA(median, slow)_t
        //    AC_t = AO_t - SMA(AO, signal)_t
        //
        // Every leg is a plain SMA, so there is no seeding convention to get wrong
        // and no cross-library divergence of the kind an EMA brings.
        //
        // This is ta_codegen/input/ao/ao.c walking one derived series with a third
        // running sum layered on top: the oscillator is never materialised into an
        // array, it goes straight into a ring of the last `signal` values. The
        // order is the one ta_codegen/input/sma/sma.c uses -- add the new value,
        // snapshot the total, subtract the bar leaving the window, divide by the
        // period -- for all three sums, which is what makes the composed reference
        // in test_composite.c (TA_AO, TA_SMA and TA_SUB) bit-exact rather than
        // merely close. Any future drift in either path is then a hard failure
        // instead of a tolerance argument.
        //
        // Each total is DIVIDED by its period; it is not multiplied by a
        // precomputed 1/period, for the reason spelled out in ao.c and #117/#118.
        // This ptr will point on a circular buffer of at least
        // "optInSignalPeriod" element.
        // Identify the minimum number of price bar needed
        // to calculate at least one output.
        lookbackTotal = self.AC_Lookback(optInFastPeriod, optInSlowPeriod, optInSignalPeriod);
        // Move up the start index if there is not
        // enough initial data.
        if startIdx < lookbackTotal {
            startIdx = lookbackTotal;
        }
        // Make sure there is still something to evaluate.
        if startIdx > endIdx {
            (*outBegIdx) = 0;
            (*outNBElement) = 0;
            return Err(RetCode::InsufficientHistory);
        }
        // Allocate a circular buffer equal to the requested signal period.
        if optInSignalPeriod < 1 { return Err(RetCode::InternalError); }
        oscBuffer = vec![0.0_f64; (optInSignalPeriod) as usize];
        maxIdx_oscBuffer = ((optInSignalPeriod) as usize) - 1;
        oscBuffer_Idx = 0;
        // The first bar the oscillator is evaluated on for this call. It trails
        // the first output by the signal window, because that many oscillator
        // values have to exist before their average does.
        oscStartIdx = startIdx - (((optInSignalPeriod - 1)) as usize);
        sumFast = 0.0;
        sumSlow = 0.0;
        sumSignal = 0.0;
        trailingFastIdx = oscStartIdx - (((optInFastPeriod - 1)) as usize);
        trailingSlowIdx = oscStartIdx - (((optInSlowPeriod - 1)) as usize);
        // Add-up both initial periods, except for the last value.
        //
        // One pass over the longer warm-up window replaces two overlapping passes.
        // A bar inside the shorter window is added to that total as it is reached,
        // so each total still accumulates exactly the same bars in exactly the same
        // ascending order two separate loops would have given it -- which is what
        // keeps each leg bit-identical to the TA_SMA that TA_AO would have called
        // had it been started at oscStartIdx.
        i = startIdx - lookbackTotal;
        while i < oscStartIdx {
            medianPrice = (inHigh[i] + inLow[i]) / 2.0;
            if i >= trailingFastIdx {
                sumFast += medianPrice;
            }
            if i >= trailingSlowIdx {
                sumSlow += medianPrice;
            }
            i = i + 1;
        }
        // Fill the signal ring with the oscillator values that precede the first
        // output. This is the same body as the main loop below minus the store --
        // the window is not full yet, so there is nothing to emit.
        while i < startIdx {
            medianPrice = (inHigh[i] + inLow[i]) / 2.0;
            sumFast += medianPrice;
            sumSlow += medianPrice;
            osc = sumFast / (optInFastPeriod as f64) - sumSlow / (optInSlowPeriod as f64);
            sumFast -= (inHigh[trailingFastIdx] + inLow[trailingFastIdx]) / 2.0;
            sumSlow -= (inHigh[trailingSlowIdx] + inLow[trailingSlowIdx]) / 2.0;
            trailingFastIdx = trailingFastIdx + 1;
            trailingSlowIdx = trailingSlowIdx + 1;
            i = i + 1;
            oscBuffer[oscBuffer_Idx] = osc;
            sumSignal += osc;
            oscBuffer_Idx += 1;
            if oscBuffer_Idx > maxIdx_oscBuffer { oscBuffer_Idx = 0; }
        }
        // Proceed with the calculation for the requested range.
        // Note that this algorithm allows outReal to be the same
        // buffer as either input.
        outIdx = 0;
        while i <= endIdx {
            medianPrice = (inHigh[i] + inLow[i]) / 2.0;
            sumFast += medianPrice;
            sumSlow += medianPrice;
            // Snapshot the oscillator before either total drops its trailing bar,
            // mirroring the add-new / snapshot / subtract-old order of TA_SMA.
            osc = sumFast / (optInFastPeriod as f64) - sumSlow / (optInSlowPeriod as f64);
            sumFast -= (inHigh[trailingFastIdx] + inLow[trailingFastIdx]) / 2.0;
            sumSlow -= (inHigh[trailingSlowIdx] + inLow[trailingSlowIdx]) / 2.0;
            trailingFastIdx = trailingFastIdx + 1;
            trailingSlowIdx = trailingSlowIdx + 1;
            i = i + 1;
            // Today's oscillator enters the signal window at its own slot, and the
            // bar leaving that window is read only after the ring has advanced onto
            // it -- writing first is what makes the slot the loop is about to
            // overwrite the newest value rather than the oldest one.
            oscBuffer[oscBuffer_Idx] = osc;
            sumSignal += osc;
            tempReal = osc - sumSignal / (optInSignalPeriod as f64);
            oscBuffer_Idx += 1;
            if oscBuffer_Idx > maxIdx_oscBuffer { oscBuffer_Idx = 0; }
            sumSignal -= oscBuffer[oscBuffer_Idx];
            // Every input read for this bar is done above, so the store is safe
            // when the caller aliases outReal over inHigh or inLow. Unlike ao.c
            // there is slack here -- the signal window puts both trailing indices
            // at least optInSignalPeriod-1 bars ahead of outIdx, so no reachable
            // parameter makes them collide -- but the order is kept anyway, so
            // that admitting a signal period of 1 would not silently reintroduce
            // the collision ao.c has to guard against.
            outReal[(outIdx * outStride) as usize] = tempReal;
            outIdx = outIdx + 1;
        }
        // All done. Indicate the output limits and return.
        (*outNBElement) = outIdx;
        (*outBegIdx) = startIdx;

        // Capture the live batch state into the handle.
        let cap_trailingFastIdx: i64 = (i as i64) - (trailingFastIdx as i64);
        if cap_trailingFastIdx < 0 || cap_trailingFastIdx > historyLen as i64 {
            return Err(RetCode::InternalError);
        }
        let allocN_trailingFastIdx: usize = if cap_trailingFastIdx > 0 { cap_trailingFastIdx as usize } else { 1 };
        let mut ring_trailingFastIdx_derived: Vec<f64> = vec![0.0_f64; allocN_trailingFastIdx];
        {
            let mut fillJ: usize = historyLen - cap_trailingFastIdx as usize;
            while fillJ < historyLen {
                ring_trailingFastIdx_derived[fillJ - (historyLen - cap_trailingFastIdx as usize)] = (inHigh[(fillJ) as usize] + inLow[(fillJ) as usize]) / 2.0;
                fillJ += 1;
            }
        }
        let cap_trailingSlowIdx: i64 = (i as i64) - (trailingSlowIdx as i64);
        if cap_trailingSlowIdx < 0 || cap_trailingSlowIdx > historyLen as i64 {
            return Err(RetCode::InternalError);
        }
        let allocN_trailingSlowIdx: usize = if cap_trailingSlowIdx > 0 { cap_trailingSlowIdx as usize } else { 1 };
        let mut ring_trailingSlowIdx_derived: Vec<f64> = vec![0.0_f64; allocN_trailingSlowIdx];
        {
            let mut fillJ: usize = historyLen - cap_trailingSlowIdx as usize;
            while fillJ < historyLen {
                ring_trailingSlowIdx_derived[fillJ - (historyLen - cap_trailingSlowIdx as usize)] = (inHigh[(fillJ) as usize] + inLow[(fillJ) as usize]) / 2.0;
                fillJ += 1;
            }
        }
        let cbSize_oscBuffer: usize = maxIdx_oscBuffer + 1;
        if cbSize_oscBuffer > historyLen + 1 {
            return Err(RetCode::InternalError);
        }
        let state = AC_StreamState {
            optInFastPeriod,
            optInSlowPeriod,
            optInSignalPeriod,
            sumFast,
            sumSlow,
            sumSignal,
            osc,
            tempReal,
            oscBuffer_Idx,
            maxIdx_oscBuffer,
            ringPos_trailingFastIdx: 0_usize,
            ringCap_trailingFastIdx: cap_trailingFastIdx as usize,
            ring_trailingFastIdx_derived,
            ringPos_trailingSlowIdx: 0_usize,
            ringCap_trailingSlowIdx: cap_trailingSlowIdx as usize,
            ring_trailingSlowIdx_derived,
            cbSize_oscBuffer: cbSize_oscBuffer,
            cb_oscBuffer: oscBuffer,
        };
        Ok(AC_Stream { core: self.clone(), state })
    }

    /// Internal startIdx-anchored open behind [`Core::AC_Open`] (composition seam).
    pub(crate) fn AC_OpenInternal(
        &self, inHigh: &[f64], inLow: &[f64], startIdx: usize, mut optInFastPeriod: i32, mut optInSlowPeriod: i32, mut optInSignalPeriod: i32,
    ) -> Result<(AC_Stream, f64), RetCode> {
        let mut dummyBegIdx: usize = 0;
        let mut dummyNBElement: usize = 0;
        let mut sink_outReal = [0.0_f64; 1];
        let handle = self.AC_OpenPass(inHigh, inLow, startIdx, optInFastPeriod, optInSlowPeriod, optInSignalPeriod, &mut dummyBegIdx, &mut dummyNBElement, &mut sink_outReal, 0)?;
        Ok((handle, sink_outReal[0]))
    }

    /// Open a live AC stream over the warm-up history; returns the handle and
    /// the value at the last history bar — bit-identical to [`Core::AC`] at that bar.
    ///
    /// # Errors
    ///
    /// [`RetCode::InsufficientHistory`] when the history holds fewer than
    /// `lookback + 1` bars — the one failure here worth retrying, since another
    /// bar fixes it. [`RetCode::BadParam`] when a parameter is out of range, an
    /// input is empty, or input lengths differ.
    ///
    /// ```
    /// use ta_lib::Core;
    /// let high: Vec<f64> = (0..252).map(|i| 101.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    /// let low: Vec<f64> = (0..252).map(|i| 99.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    ///
    /// let core = Core::new();
    /// let (mut s, _last) = core.AC_Open(&high, &low, 5, 34, 5).expect("enough history");
    /// let peeked = s.peek(101.4, 99.1).expect("a finite bar");
    /// let updated = s.update(101.4, 99.1).expect("a finite bar");
    /// assert_eq!(peeked.to_bits(), updated.to_bits());
    /// ```
    #[doc(alias = "TA_AC_Open")]
    pub fn AC_Open(&self, inHigh: &[f64], inLow: &[f64], optInFastPeriod: i32, optInSlowPeriod: i32, optInSignalPeriod: i32) -> Result<(AC_Stream, f64), RetCode> {
        self.AC_OpenInternal(inHigh, inLow, 0, optInFastPeriod, optInSlowPeriod, optInSignalPeriod)
    }

    /// [`Core::AC_Open`] that also fills the output array(s) bit-identically to
    /// [`Core::AC`] over `0..len` in the same single pass, and reports the range it
    /// wrote as the [`OutRange`] beside the handle. Output slices must hold
    /// `len - lookback` values; undersized slices panic (the batch sizing contract).
    #[doc(alias = "TA_AC_OpenAndFill")]
    pub fn AC_OpenAndFill(
        &self, inHigh: &[f64], inLow: &[f64], mut optInFastPeriod: i32, mut optInSlowPeriod: i32, mut optInSignalPeriod: i32, outReal: &mut [f64],
    ) -> Result<(AC_Stream, OutRange), RetCode> {
        let mut outBegIdx: usize = 0;
        let mut outNBElement: usize = 0;
        let handle = self.AC_OpenPass(inHigh, inLow, 0, optInFastPeriod, optInSlowPeriod, optInSignalPeriod, &mut outBegIdx, &mut outNBElement, outReal, 1)?;
        Ok((handle, OutRange { beg_idx: outBegIdx, count: outNBElement }))
    }

    /// [`Core::AC_OpenAndFill`] anchored at `startIdx` — the composed-open
    /// fusion seam (issue #192), not a public entry point.
    pub(crate) fn AC_OpenAndFillInternal(
        &self, inHigh: &[f64], inLow: &[f64], startIdx: usize, mut optInFastPeriod: i32, mut optInSlowPeriod: i32, mut optInSignalPeriod: i32, outBegIdx: &mut usize, outNBElement: &mut usize, outReal: &mut [f64],
    ) -> Result<AC_Stream, RetCode> {
        self.AC_OpenPass(inHigh, inLow, startIdx, optInFastPeriod, optInSlowPeriod, optInSignalPeriod, outBegIdx, outNBElement, outReal, 1)
    }

}

thread_local! {
    /// `peek`'s reusable scratch handle (see `AC_StreamState::restore_from`).
    /// Taken for the duration of the step and put back after, so a
    /// panicking step costs the scratch, never leaves it borrowed.
    static AC_PEEK_SCRATCH: std::cell::Cell<Option<Box<AC_Stream>>> =
        const { std::cell::Cell::new(None) };
}

#[allow(non_snake_case)]
#[allow(unused_variables)]
impl AC_Stream {
    /// Commit one closed bar. Never allocates.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite (NaN or ±Inf).
    /// That check runs before anything is written, so the handle is left
    /// exactly as it was and the stream stays usable:
    /// skip the bar, or close and re-open on a clean history. This is the
    /// one place the streaming tier is stricter than the batch API, which
    /// computes on whatever it is given — a handle retains its state, so a
    /// single non-finite bar would poison every later value it produces.
    #[doc(alias = "TA_AC_Update")]
    pub fn update(&mut self, inHigh: f64, inLow: f64) -> Result<f64, RetCode> {
        if !inHigh.is_finite() || !inLow.is_finite() {
            return Err(RetCode::BadParam);
        }
        let mut outReal: f64 = 0.0_f64;
        self.core.AC_step_internal(&mut self.state, inHigh, inLow, &mut outReal);
        Ok(outReal)
    }

    /// Evaluate a forming bar without committing — bit-identical to what the
    /// next `update` with the same bar would return (it is the same code, run
    /// on a scratch copy of the state). Never writes the handle, so peeks may
    /// run concurrently with each other. The copy it runs on is held per thread and reused,
    /// so only the first peek of this function on a thread allocates.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite, exactly as
    /// `update` rejects it.
    #[doc(alias = "TA_AC_Peek")]
    pub fn peek(&self, inHigh: f64, inLow: f64) -> Result<f64, RetCode> {
        if !inHigh.is_finite() || !inLow.is_finite() {
            return Err(RetCode::BadParam);
        }
        AC_PEEK_SCRATCH.with(|cell| {
            let mut scratch = cell.take().unwrap_or_else(|| Box::new(self.clone()));
            scratch.restore_from(self);
            let value = scratch.update(inHigh, inLow);
            cell.set(Some(scratch));
            value
        })
    }
}

