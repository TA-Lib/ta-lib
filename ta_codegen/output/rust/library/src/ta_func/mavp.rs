/// Live MAVP stream: one value per closed bar, bit-identical to [`Core::MAVP`]
/// over the same series. Open with [`Core::mavp_open`]; dropping the handle
/// closes the stream. Cloning it forks an independent stream.
///
/// [`Self::out_range`] reports the bars this handle has an output for.
#[must_use = "a stream does nothing unless updated; dropping it closes the stream"]
#[derive(Debug, Clone)]
#[doc(alias = "TA_MAVP_Stream")]
pub struct MavpStream {
    state: MavpStreamState,
    /// The bars this handle has an output for — see [`Self::out_range`].
    out: OutRange,
}

#[derive(Debug, Clone)]
#[allow(non_snake_case, dead_code)]
struct MavpStreamState {
    optInMinPeriod: i32,
    optInMaxPeriod: i32,
    optInMAType: MAType,
    // One sub-MA stream per period in [optInMinPeriod, optInMaxPeriod], advanced in lockstep.
    bank: Vec<MaStream>,
    cur_outReal: f64,
}

#[allow(unused_variables)]
#[allow(dead_code)]
#[allow(unused_mut)]
#[allow(unused_assignments)]
#[allow(unused_parens)]
impl Core {
    fn mavp_step_impl(sp: &mut MavpStreamState, inReal: f64, inPeriods: f64, outReal: &mut f64) -> Result<(), RetCode> {
        let mut cp: i32 = inPeriods as i32;
        if cp < sp.optInMinPeriod {
            cp = sp.optInMinPeriod;
        } else if cp > sp.optInMaxPeriod {
            cp = sp.optInMaxPeriod;
        }
        let slot: usize = (cp - sp.optInMinPeriod) as usize;
        for (bankIdx, sub) in sp.bank.iter_mut().enumerate() {
            let subValue = sub.update(inReal)?;
            if bankIdx == slot {
                (*outReal) = subValue;
            }
        }
        Ok(())
    }

    /// Internal startIdx-anchored open behind [`Core::mavp_open`] (composition seam).
    pub(crate) fn mavp_open_internal(
        &self, inReal: &[f64], inPeriods: &[f64], startIdx: usize, mut optInMinPeriod: i32, mut optInMaxPeriod: i32, mut optInMAType: MAType,
    ) -> Result<(MavpStream, f64), RetCode> {
        if inReal.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inReal.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        if ((optInMinPeriod) as i32) == (i32::MIN) {
            optInMinPeriod = 2;
        } else if (((optInMinPeriod) as i32) < 1) || (((optInMinPeriod) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        if ((optInMaxPeriod) as i32) == (i32::MIN) {
            optInMaxPeriod = 30;
        } else if (((optInMaxPeriod) as i32) < 1) || (((optInMaxPeriod) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        if optInMAType == MAType::DEFAULT {
            optInMAType = MAType::SMA;
        }
        if inPeriods.len() != inReal.len() {
            return Err(RetCode::BadParam);
        }
        // An inverted [min, max] period window is invalid (batch rejects).
        if optInMinPeriod > optInMaxPeriod {
            return Err(RetCode::BadParam);
        }
        let historyLen: usize = inReal.len();
        // Seed EVERY sub-MA at the SHARED max-period lookback, exactly as the
        // batch does: it clamps startIdx up to lookback(maxPeriod) and calls the
        // callee with that same start for every period. Seeding each sub at its
        // OWN (smaller) lookback would seed the recurrence from a different bar
        // and diverge for every period < maxPeriod (order-1 for recursive MAs,
        // running-sum residue for stable ones).
        let lookbackTotal: usize = self.MA_Lookback(optInMaxPeriod, optInMAType)?;
        let subStart: usize = if startIdx < lookbackTotal { lookbackTotal } else { startIdx };
        if historyLen < subStart + 1 {
            return Err(RetCode::InsufficientHistory);
        }
        let nBank: usize = (optInMaxPeriod - optInMinPeriod + 1) as usize;
        let mut bank: Vec<MaStream> = Vec::with_capacity(nBank);
        let mut scratch: Vec<f64> = Vec::with_capacity(nBank);
        for bankIdx in 0..nBank {
            let (sub, subValue) = self.ma_open_internal(inReal, subStart, optInMinPeriod + (bankIdx as i32), optInMAType)?;
            bank.push(sub);
            scratch.push(subValue);
        }
        let mut cp: i32 = inPeriods[historyLen - 1] as i32;
        if cp < optInMinPeriod {
            cp = optInMinPeriod;
        } else if cp > optInMaxPeriod {
            cp = optInMaxPeriod;
        }
        let lastValue_outReal: f64 = scratch[(cp - optInMinPeriod) as usize];
        let state = MavpStreamState { optInMinPeriod, optInMaxPeriod, optInMAType, bank, cur_outReal: lastValue_outReal };
        Ok((MavpStream { state, out: OutRange { beg_idx: subStart, count: historyLen - subStart } }, lastValue_outReal))
    }

    /// Open a live MAVP stream over the warm-up history; returns the handle and
    /// the value at the last history bar — bit-identical to [`Core::MAVP`] at that bar.
    ///
    /// # Errors
    ///
    /// [`RetCode::InsufficientHistory`] when the history holds fewer than
    /// `lookback + 1` bars — the one failure here worth retrying, since another
    /// bar fixes it. [`RetCode::OutOfRangeStartIndex`] when the history is empty.
    /// [`RetCode::BadParam`] when a parameter is out of range or the input
    /// lengths differ.
    ///
    /// ```
    /// use ta_lib::{Core, MAType};
    /// let data: Vec<f64> = (0..252).map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    /// let periods: Vec<f64> = (0..252).map(|i| 5.0 + (i % 10) as f64).collect();
    ///
    /// let core = Core::new();
    /// let (mut s, _last) = core.mavp_open(&data, &periods, 2, 30, MAType::SMA).expect("enough history");
    /// let r0 = s.out_range();
    /// let peeked = s.peek(100.9, 14.0).expect("a finite bar");
    /// assert_eq!(s.out_range().count, r0.count); // a peek commits nothing
    /// let updated = s.update(100.9, 14.0).expect("a finite bar");
    /// assert_eq!(s.out_range().beg_idx, r0.beg_idx);
    /// assert_eq!(s.out_range().count, r0.count + 1);
    /// assert_eq!(peeked.to_bits(), updated.to_bits());
    /// ```
    #[doc(alias = "TA_MAVP_Open")]
    pub fn mavp_open(&self, inReal: &[f64], inPeriods: &[f64], optInMinPeriod: i32, optInMaxPeriod: i32, optInMAType: MAType) -> Result<(MavpStream, f64), RetCode> {
        self.mavp_open_internal(inReal, inPeriods, 0, optInMinPeriod, optInMaxPeriod, optInMAType)
    }

    /// [`Core::mavp_open`] that also fills the output array(s) bit-identically to
    /// [`Core::MAVP`] over `0..len` in the same single pass, and reports the range it
    /// wrote as the [`OutRange`] beside the handle.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] when an output slice holds fewer than `len - lookback`
    /// values — the batch tier's sizing rule, checked here as it is there (rule S5) —
    /// or when two of them are the same slice. Everything [`Core::mavp_open`] rejects
    /// is rejected here too.
    ///
    /// # Examples
    ///
    /// ```
    /// use ta_lib::{Core, MAType};
    /// let data: Vec<f64> = (0..252).map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    /// let periods: Vec<f64> = (0..252).map(|i| 5.0 + (i % 10) as f64).collect();
    ///
    /// let core = Core::new();
    /// let mut batch_out = vec![0.0; 252];
    /// let batch = core.MAVP(0, data.len() - 1, &data, &periods, 2, 30, MAType::SMA, &mut batch_out)?;
    ///
    /// let mut out = vec![0.0; 252];
    /// let (_stream, filled) = core.mavp_open_and_fill(&data, &periods, 2, 30, MAType::SMA, &mut out)?;
    ///
    /// assert_eq!(filled.beg_idx, batch.beg_idx);
    /// assert_eq!(filled.count, batch.count);
    /// assert!(out[..filled.count].iter().zip(&batch_out[..batch.count])
    ///     .all(|(a, b)| a.to_bits() == b.to_bits()));
    /// # Ok::<(), ta_lib::RetCode>(())
    /// ```
    #[doc(alias = "TA_MAVP_OpenAndFill")]
    pub fn mavp_open_and_fill(
        &self, inReal: &[f64], inPeriods: &[f64], mut optInMinPeriod: i32, mut optInMaxPeriod: i32, mut optInMAType: MAType, outReal: &mut [f64],
    ) -> Result<(MavpStream, OutRange), RetCode> {
        if inReal.is_empty() {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if inReal.len() > Self::MAX_INDEX + 1 {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        if ((optInMinPeriod) as i32) == (i32::MIN) {
            optInMinPeriod = 2;
        } else if (((optInMinPeriod) as i32) < 1) || (((optInMinPeriod) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        if ((optInMaxPeriod) as i32) == (i32::MIN) {
            optInMaxPeriod = 30;
        } else if (((optInMaxPeriod) as i32) < 1) || (((optInMaxPeriod) as i32) > 100000) {
            return Err(RetCode::BadParam);
        }
        if optInMAType == MAType::DEFAULT {
            optInMAType = MAType::SMA;
        }
        if inPeriods.len() != inReal.len() {
            return Err(RetCode::BadParam);
        }
        let _guardLb = self.MAVP_Lookback(optInMinPeriod, optInMaxPeriod, optInMAType)?;
        let _guardOutLen = inReal.len().saturating_sub(_guardLb);
        if outReal.len() < _guardOutLen {
            return Err(RetCode::BadParam);
        }
        // An inverted [min, max] period window is invalid (batch rejects).
        if optInMinPeriod > optInMaxPeriod {
            return Err(RetCode::BadParam);
        }
        let historyLen: usize = inReal.len();
        let lookbackTotal: usize = self.MA_Lookback(optInMaxPeriod, optInMAType)?;
        if historyLen < lookbackTotal + 1 {
            return Err(RetCode::InsufficientHistory);
        }
        let nBank: usize = (optInMaxPeriod - optInMinPeriod + 1) as usize;
        // Seed each sub-MA at the first output bar (lookbackTotal), NOT the last.
        let mut bank: Vec<MaStream> = Vec::with_capacity(nBank);
        let mut scratch: Vec<f64> = Vec::with_capacity(nBank);
        for bankIdx in 0..nBank {
            let (sub, subValue) = self.ma_open_internal(&inReal[..lookbackTotal + 1], lookbackTotal, optInMinPeriod + (bankIdx as i32), optInMAType)?;
            bank.push(sub);
            scratch.push(subValue);
        }
        // First output bar (lookbackTotal), then replay the remaining history.
        let mut cp: i32 = inPeriods[lookbackTotal] as i32;
        if cp < optInMinPeriod {
            cp = optInMinPeriod;
        } else if cp > optInMaxPeriod {
            cp = optInMaxPeriod;
        }
        outReal[0] = scratch[(cp - optInMinPeriod) as usize];
        let mut t: usize = lookbackTotal + 1;
        while t < historyLen {
            for (bankIdx, sub) in bank.iter_mut().enumerate() {
                scratch[bankIdx] = sub.update(inReal[t])?;
            }
            cp = inPeriods[t] as i32;
            if cp < optInMinPeriod {
                cp = optInMinPeriod;
            } else if cp > optInMaxPeriod {
                cp = optInMaxPeriod;
            }
            outReal[t - lookbackTotal] = scratch[(cp - optInMinPeriod) as usize];
            t += 1;
        }
        let state = MavpStreamState { optInMinPeriod, optInMaxPeriod, optInMAType, bank, cur_outReal: outReal[historyLen - lookbackTotal - 1] };
        Ok((MavpStream { state, out: OutRange { beg_idx: lookbackTotal, count: historyLen - lookbackTotal } }, OutRange { beg_idx: lookbackTotal, count: historyLen - lookbackTotal }))
    }

}

#[allow(non_snake_case)]
#[allow(unused_variables)]
#[allow(unused_mut)]
#[allow(unused_assignments)]
#[allow(unused_parens)]
impl MavpStream {
    /// Commit one closed bar. Never allocates.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite (NaN or ±Inf).
    /// That check runs before anything is written, so the handle's state is
    /// left exactly as it was and the stream stays usable: skip the bar, or
    /// close and re-open on a clean history. This is the one place the
    /// streaming tier is stricter than the batch API, which computes on
    /// whatever it is given — a handle retains its state, so a single
    /// non-finite bar would poison every later value it produces.
    ///
    /// A rejection leaves [`Self::out_range`] alone too. Re-feed the bar when
    /// a corrected value arrives, or call [`Self::advance`] to count it and
    /// carry on — two handles on one feed drift a bar apart if neither
    /// happens.
    #[doc(alias = "TA_MAVP_Update")]
    pub fn update(&mut self, inReal: f64, inPeriods: f64) -> Result<f64, RetCode> {
        if !inReal.is_finite() || !inPeriods.is_finite() {
            return Err(RetCode::BadParam);
        }
        let mut outReal: f64 = 0.0_f64;
        Core::mavp_step_impl(&mut self.state, inReal, inPeriods, &mut outReal)?;
        self.state.cur_outReal = outReal;
        if self.out.count < Core::MAX_INDEX {
            self.out.count += 1;
        }
        Ok(outReal)
    }

    /// Evaluate a forming bar without committing — bit-identical to what the
    /// next `update` with the same bar would return: the same transition,
    /// rewritten so every store it would make lives in a local instead. It
    /// allocates nothing and copies no buffer, so its cost does not grow with
    /// the period, and it writes no part of the handle — peeks may run
    /// concurrently with each other.
    ///
    /// # Errors
    ///
    /// [`RetCode::BadParam`] if any bar value is not finite, on the same test
    /// `update` applies, and a rejected peek changes nothing at all.
    #[doc(alias = "TA_MAVP_Peek")]
    pub fn peek(&self, inReal: f64, inPeriods: f64) -> Result<f64, RetCode> {
        if !inReal.is_finite() || !inPeriods.is_finite() {
            return Err(RetCode::BadParam);
        }
        let mut outReal: f64 = 0.0_f64;
        {
            let sp = &self.state;
            let mut cp: i32 = inPeriods as i32;
            if cp < sp.optInMinPeriod {
                cp = sp.optInMinPeriod;
            } else if cp > sp.optInMaxPeriod {
                cp = sp.optInMaxPeriod;
            }
            let slot: usize = (cp - sp.optInMinPeriod) as usize;
            outReal = sp.bank[slot].peek(inReal)?;
        }
        Ok(outReal)
    }

    /// The value(s) at the last bar the stream counted — the bar
    /// [`Self::out_range`] ends on — without recomputing. Seeded by the opener,
    /// refreshed by every accepted `update`, and left
    /// alone by `peek`.
    ///
    /// A clone carries them verbatim, so a forked handle can be asked its
    /// current value without committing a bar to find out.
    #[must_use]
    #[doc(alias = "TA_MAVP_Value")]
    pub fn value(&self) -> f64 {
        self.state.cur_outReal
    }

    /// The bars this stream has an output for, in the input series'
    /// coordinates: `[beg_idx, beg_idx + count)`.
    ///
    /// It is what [`Core::MAVP`] reports over the same bars: the opener sets it
    /// to `(lookback, historyLen - lookback)`, every accepted `update` adds
    /// one to the count — a rejected one changes nothing, and neither does
    /// `peek` — and a clone carries it verbatim. A plain `Open` hands back
    /// only the last value, a subset of this range, because the caller chose
    /// not to take the fill.
    #[doc(alias = "TA_MAVP_OutRange")]
    pub fn out_range(&self) -> OutRange {
        self.out
    }

    /// Count one bar this stream was not fed: [`Self::out_range`] advances by
    /// one and nothing else moves — [`Self::value`] keeps answering the
    /// previous output, which is this bar's output too.
    ///
    /// For a bar the caller leaves out: one an `update` rejected and that
    /// will not be re-fed, or a session with no print. Without it two handles
    /// on one feed drift a bar apart when only one of them skips.
    #[doc(alias = "TA_MAVP_Advance")]
    pub fn advance(&mut self) {
        if self.out.count < Core::MAX_INDEX {
            self.out.count += 1;
        }
    }
}

