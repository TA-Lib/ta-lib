    /// assert!(out[..out_range.count].iter().all(|v| v.is_finite()));
    /// # Ok::<(), ta_lib::RetCode>(())
    /// ```
    ///
    /// # See also
    ///
    /// [`Core::MA`] · [`Core::SMA`] · [`Core::MAMA`] · [`Core::T3`]
    #[doc(alias = "TA_MAVP")]
    #[doc(alias = "MovingAverageVariablePeriod")]
    #[doc(alias = "VariablePeriodMovingAverage")]
    pub fn MAVP(
        &self,
        startIdx: usize,
        endIdx: usize,
        inReal: &[f64],
        inPeriods: &[f64],
        optInMinPeriod: i32,
        optInMaxPeriod: i32,
        optInMAType: MAType,
        outReal: &mut [f64],
    ) -> Result<OutRange, RetCode> {
        if startIdx > Self::MAX_INDEX {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if endIdx > Self::MAX_INDEX || endIdx < startIdx {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        let _guardLb = self.MAVP_Lookback(optInMinPeriod, optInMaxPeriod, optInMAType)?;
        let _guardStart = if startIdx > _guardLb { startIdx } else { _guardLb };
        if inReal.len() < endIdx + 1 {
            return Err(RetCode::BadParam);
        }
        if inPeriods.len() < endIdx + 1 {
            return Err(RetCode::BadParam);
        }
        let _guardOutLen = if _guardStart > endIdx { 0 } else { endIdx - _guardStart + 1 };
        if outReal.len() < _guardOutLen {
            return Err(RetCode::BadParam);
        }
        let mut outBegIdx: usize = 0;
        let mut outNBElement: usize = 0;
        let retCode = self.MAVP_Impl(
            startIdx,
            endIdx,
            inReal,
            inPeriods,
            optInMinPeriod,
            optInMaxPeriod,
            optInMAType,
            &mut outBegIdx,
            &mut outNBElement,
            outReal,
        );
        match retCode {
            RetCode::Success => Ok(OutRange { beg_idx: outBegIdx, count: outNBElement }),
            e => Err(e),
        }
    }

