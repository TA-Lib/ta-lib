    /// divided by the downside deviation, over a trailing window, scaled to a year. It is the
    /// Sharpe ratio with upside volatility taken out of the denominator: only returns below the MAR
    /// count as risk. Above 0 the window's returns beat the MAR on average; the larger the value,
    /// the more return per unit of downside.
    ///
    /// Formula and more info at
    /// [ta-lib.org/functions/sortino](https://ta-lib.org/functions/sortino).
    ///
    /// # Arguments
    ///
    /// * `startIdx` — Start index of the requested calculation range.
    /// * `endIdx` — End index of the requested calculation range (inclusive).
    /// * `inReal` — The price series; its returns are computed internally.
    /// * `optInTimePeriod` — Number of returns in the window; one price more is read (default 20,
    ///   range 2..=100000)
    /// * `optInMAR` — Minimum acceptable return per bar; returns below it are the downside
    ///   (default 0)
    /// * `optInAnnualization` — Bars per year; the per-bar ratio is multiplied by its square root
    ///   (default 252, minimum 0)
    /// * `outReal` — Annualized Sortino ratio of the trailing window, or +Inf or NaN where the
    ///   window has no return below the MAR.
    ///
    /// Integer parameters accept [`Core::INTEGER_DEFAULT`], and real parameters
    /// [`Core::REAL_DEFAULT`], to select their default value.
    ///
    /// # Returns
    ///
    /// On success, an [`OutRange`]: `beg_idx` is the index of the first value written, in the input
    /// series' coordinates, and `count` is how many were written. A range that ends before the
    /// lookback succeeds with `count == 0`.
    ///
    /// # Errors
    ///
    /// Returns [`Err`] carrying [`RetCode::OutOfRangeStartIndex`] when `startIdx` exceeds
    /// [`Core::INDEX_MAX`], [`RetCode::OutOfRangeEndIndex`] when `endIdx` exceeds it or is below
    /// `startIdx`, and [`RetCode::BadParam`] when an optional parameter is outside its documented
    /// range. A range that ends before the lookback is not an error: it is [`Ok`] with a zero
    /// [`OutRange::count`].
    ///
    /// Also [`RetCode::BadParam`] when a slice is too short: every input must cover
    /// `startIdx..=endIdx`, and every output must hold the number of values produced for that
    /// range. An empty output slice is refused on every range, one that produces nothing included.
    /// Sizing every output slice to the input length is always sufficient.
    ///
    /// # Examples
    ///
    /// ```
    /// use ta_lib::Core;
    ///
    /// let data: Vec<f64> = (0..252).map(|i| 100.0 + 10.0 * (0.1 * i as f64).sin()).collect();
    ///
    /// let core = Core::new();
    /// let mut out = vec![0.0; 252];
    ///
    /// let out_range = core.sortino(0, data.len() - 1, &data, 20, 0.0, 252.0, &mut out)?;
    /// assert!(out_range.count > 0);
    /// assert!(out[..out_range.count].iter().any(|v| v.is_finite()));
    /// # Ok::<(), ta_lib::RetCode>(())
    /// ```
    ///
    /// # See also
    ///
    /// [`SHARPE`](Core::sharpe) · [`STDDEV`](Core::stddev) · [`VAR`](Core::var) ·
    /// [`ROCP`](Core::rocp)
    ///
    /// # References
    ///
    /// * Sortino, F. A. and Price, L. N. "Performance Measurement in a Downside Risk Framework."
    ///   *The Journal of Investing*, 3(3), Fall 1994, 59-64.
    /// * Bacon, C. R. *Practical Portfolio Performance Measurement and Attribution*, 2nd ed. Wiley,
    ///   2008.
    #[doc(alias = "TA_SORTINO")]
    #[doc(alias = "SortinoRatio")]
    #[doc(alias = "RollingSortino")]
    #[doc(alias = "DownsideRisk-AdjustedReturn")]
    pub fn sortino(
        &self,
        startIdx: usize,
        endIdx: usize,
        inReal: &[f64],
        optInTimePeriod: i32,
        optInMAR: f64,
        optInAnnualization: f64,
        outReal: &mut [f64],
    ) -> Result<OutRange, RetCode> {
        if startIdx > Self::INDEX_MAX {
            return Err(RetCode::OutOfRangeStartIndex);
        }
        if endIdx > Self::INDEX_MAX || endIdx < startIdx {
            return Err(RetCode::OutOfRangeEndIndex);
        }
        let _guardLb = self.sortino_lookback(optInTimePeriod, optInMAR, optInAnnualization)?;
        let _guardStart = if startIdx > _guardLb { startIdx } else { _guardLb };
        if inReal.len() < endIdx + 1 {
            return Err(RetCode::BadParam);
        }
        let _guardOutLen = if _guardStart > endIdx { 0 } else { endIdx - _guardStart + 1 };
        if outReal.is_empty() || outReal.len() < _guardOutLen {
            return Err(RetCode::BadParam);
        }
        let mut outBegIdx: usize = 0;
        let mut outNBElement: usize = 0;
        let retCode = self.sortino_impl(
            startIdx,
            endIdx,
            inReal,
            optInTimePeriod,
            optInMAR,
            optInAnnualization,
            &mut outBegIdx,
            &mut outNBElement,
            outReal,
        );
        match retCode {
            RetCode::Success => Ok(OutRange { beg_idx: outBegIdx, count: outNBElement }),
            e => Err(e),
        }
    }

