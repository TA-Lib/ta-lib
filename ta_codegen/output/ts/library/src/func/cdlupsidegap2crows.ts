/** @internal */
export function cdlupsidegap2crowsOpenAndFillPositional(
  inOpen: ArrayLike<number>,
  inHigh: ArrayLike<number>,
  inLow: ArrayLike<number>,
  inClose: ArrayLike<number>,
  outInteger: Int32Array,
  core: Core = Core.DEFAULT,
): Cdlupsidegap2crowsStream {
  requireArgument('CDLUPSIDEGAP2CROWS openAndFill', 'prices.open', inOpen);
  requireHistory('CDLUPSIDEGAP2CROWS openAndFill', 'prices.open', inOpen.length);
  requireArgument('CDLUPSIDEGAP2CROWS openAndFill', 'prices.high', inHigh);
  requireArgument('CDLUPSIDEGAP2CROWS openAndFill', 'prices.low', inLow);
  requireArgument('CDLUPSIDEGAP2CROWS openAndFill', 'prices.close', inClose);
  const guardOutLen = openFillCount('CDLUPSIDEGAP2CROWS openAndFill', inOpen.length, cdlupsidegap2crowsLookbackPositional(core));
  requireHistoryLength('CDLUPSIDEGAP2CROWS openAndFill', 'prices.high', inHigh.length, inOpen.length);
  requireHistoryLength('CDLUPSIDEGAP2CROWS openAndFill', 'prices.low', inLow.length, inOpen.length);
  requireHistoryLength('CDLUPSIDEGAP2CROWS openAndFill', 'prices.close', inClose.length, inOpen.length);
  requireOutput('CDLUPSIDEGAP2CROWS openAndFill', 'outInteger', outInteger, guardOutLen, Int32Array);
  const inOpenF64 = float64(inOpen);
  const inHighF64 = float64(inHigh);
  const inLowF64 = float64(inLow);
  const inCloseF64 = float64(inClose);
  if (outInteger.buffer === inOpenF64.buffer && outInteger.byteOffset === inOpenF64.byteOffset) {
    throw sharedMemory('CDLUPSIDEGAP2CROWS openAndFill', 'outInteger', 'prices.open');
  }
  if (outInteger.buffer === inHighF64.buffer && outInteger.byteOffset === inHighF64.byteOffset) {
    throw sharedMemory('CDLUPSIDEGAP2CROWS openAndFill', 'outInteger', 'prices.high');
  }
  if (outInteger.buffer === inLowF64.buffer && outInteger.byteOffset === inLowF64.byteOffset) {
    throw sharedMemory('CDLUPSIDEGAP2CROWS openAndFill', 'outInteger', 'prices.low');
  }
  if (outInteger.buffer === inCloseF64.buffer && outInteger.byteOffset === inCloseF64.byteOffset) {
    throw sharedMemory('CDLUPSIDEGAP2CROWS openAndFill', 'outInteger', 'prices.close');
  }
  if (guardOutLen > 0 && overlaps(outInteger, inOpenF64)) {
    throw sharedMemory('CDLUPSIDEGAP2CROWS openAndFill', 'outInteger', 'prices.open');
  }
  if (guardOutLen > 0 && overlaps(outInteger, inHighF64)) {
    throw sharedMemory('CDLUPSIDEGAP2CROWS openAndFill', 'outInteger', 'prices.high');
  }
  if (guardOutLen > 0 && overlaps(outInteger, inLowF64)) {
    throw sharedMemory('CDLUPSIDEGAP2CROWS openAndFill', 'outInteger', 'prices.low');
  }
  if (guardOutLen > 0 && overlaps(outInteger, inCloseF64)) {
    throw sharedMemory('CDLUPSIDEGAP2CROWS openAndFill', 'outInteger', 'prices.close');
  }
  return cdlupsidegap2crowsOpenAndFillInternal(core, inOpenF64, inHighF64, inLowF64, inCloseF64, 0, new MInteger(), new MInteger(), outInteger);
}

/**
 * Opens a live CDLUPSIDEGAP2CROWS stream over the warm-up history: `value()`
 * starts at the last history bar, bit-identical to {@link cdlupsidegap2crows}
 * there.
 *
 * @param prices - Warm-up history. One series per price component this function
 *   reads, all of one length; other components may be present and are ignored.
 *   `open`: Open price of each bar. `high`: High price of each bar. `low`: Low price
 *   of each bar. `close`: Close price of each bar.
 * @param options - The parameters and `core`; other keys are ignored. See
 *   {@link Cdlupsidegap2crowsOptions}.
 * @returns The stream, positioned on the last history bar.
 * @throws `TALibError` with code `TA_INSUFFICIENT_HISTORY` for a history shorter
 *   than `cdlupsidegap2crowsLookback(...) + 1` bars, an empty one included, and
 *   `TA_BAD_PARAM` for options that are not an object, a `core` that is not a
 *   `Core`, an absent input or histories of different lengths.
 *
 * @example
 * ```ts
 * import { cdlupsidegap2crowsOpen } from 'ta-lib';
 *
 * const open = Float64Array.from({ length: 252 }, (_, i) =>
 *   100 + 10 * Math.sin(0.1 * i - 0.05));
 * const high = Float64Array.from({ length: 252 }, (_, i) =>
 *   101 + 10 * Math.sin(0.1 * i));
 * const low = Float64Array.from({ length: 252 }, (_, i) =>
 *   99 + 10 * Math.sin(0.1 * i));
 * const close = Float64Array.from({ length: 252 }, (_, i) =>
 *   100 + 10 * Math.sin(0.1 * i) + 0.8 * Math.sin(0.7 * i));
 * const stream = cdlupsidegap2crowsOpen({ open, high, low, close });
 * const peeked = stream.peek(100.2, 101.4, 99.1, 100.9); // a forming bar: commits nothing
 * const updated = stream.update(100.2, 101.4, 99.1, 100.9); // the bar closes
 * ```
 */
export function cdlupsidegap2crowsOpen(prices: { open: ArrayLike<number>; high: ArrayLike<number>; low: ArrayLike<number>; close: ArrayLike<number>; volume?: ArrayLike<number> | undefined; openInterest?: ArrayLike<number> | undefined }, options?: Cdlupsidegap2crowsOptions): Cdlupsidegap2crowsStream {
  requireArgument('CDLUPSIDEGAP2CROWS open', 'prices', prices);
  const o = optionsOf('CDLUPSIDEGAP2CROWS open', options);
  const core = coreOf('CDLUPSIDEGAP2CROWS open', o.core);
  return cdlupsidegap2crowsOpenPositional(prices.open, prices.high, prices.low, prices.close, core);
}

/**
 * {@link cdlupsidegap2crowsOpen} that also computes the outputs over the whole
 * history in the same pass, bit-identically to {@link cdlupsidegap2crows}.
 *
 * @param prices - Warm-up history. One series per price component this function
 *   reads, all of one length; other components may be present and are ignored.
 *   `open`: Open price of each bar. `high`: High price of each bar. `low`: Low price
 *   of each bar. `close`: Close price of each bar.
 * @param options - The parameters, `core` and output buffers; other keys are
 *   ignored. See {@link Cdlupsidegap2crowsOptions}.
 * @returns The stream, positioned on the last history bar, with `begIdx` and the
 *   values over the history as {@link cdlupsidegap2crows} returns them; the range is
 *   the stream's `outRange()`.
 * @throws `TALibError` with code `TA_INSUFFICIENT_HISTORY` for a history shorter
 *   than `cdlupsidegap2crowsLookback(...) + 1` bars, an empty one included, and
 *   `TA_BAD_PARAM` for options that are not an object, a `core` that is not a
 *   `Core`, an absent input, histories of different lengths or a buffer too short,
 *   of the wrong type or starting where another buffer or a `Float64Array` input
 *   starts, or, on a history long enough to open, one sharing memory with another
 *   buffer or a `Float64Array` input.
 *
 * @example
 * ```ts
 * import { cdlupsidegap2crowsOpenAndFill } from 'ta-lib';
 *
 * const open = Float64Array.from({ length: 252 }, (_, i) =>
 *   100 + 10 * Math.sin(0.1 * i - 0.05));
 * const high = Float64Array.from({ length: 252 }, (_, i) =>
 *   101 + 10 * Math.sin(0.1 * i));
 * const low = Float64Array.from({ length: 252 }, (_, i) =>
 *   99 + 10 * Math.sin(0.1 * i));
 * const close = Float64Array.from({ length: 252 }, (_, i) =>
 *   100 + 10 * Math.sin(0.1 * i) + 0.8 * Math.sin(0.7 * i));
 * const { stream, begIdx, values } = cdlupsidegap2crowsOpenAndFill({ open, high, low, close });
 * // values[k] is the value at bar begIdx + k
 * ```
 */
export function cdlupsidegap2crowsOpenAndFill(prices: { open: ArrayLike<number>; high: ArrayLike<number>; low: ArrayLike<number>; close: ArrayLike<number>; volume?: ArrayLike<number> | undefined; openInterest?: ArrayLike<number> | undefined }, options?: Cdlupsidegap2crowsOptions): Cdlupsidegap2crowsResult & { stream: Cdlupsidegap2crowsStream } {
  requireArgument('CDLUPSIDEGAP2CROWS openAndFill', 'prices', prices);
  const o = optionsOf('CDLUPSIDEGAP2CROWS openAndFill', options);
  const core = coreOf('CDLUPSIDEGAP2CROWS openAndFill', o.core);
  const capacity = fillCapacity(cdlupsidegap2crowsLookbackPositional(core), prices.open, prices.high, prices.low, prices.close);
  const outInteger = o.outInteger === undefined ? new Int32Array(capacity) : o.outInteger;
  const stream = cdlupsidegap2crowsOpenAndFillPositional(prices.open, prices.high, prices.low, prices.close, outInteger, core);
  const range = stream.outRange();
  return { stream, begIdx: range.begIdx, values: outInteger.subarray(0, range.count) };
}
