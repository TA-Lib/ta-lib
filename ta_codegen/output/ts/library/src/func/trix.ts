/** @internal */
export function trixOpenAndFillInternal(
  core: Core,
  inReal: Float64Array,
  startIdx: number,
  optInTimePeriod: number,
  outBegIdx: MInteger,
  outNBElement: MInteger,
  outReal: Float64Array,
): TrixStream {
  const sp = TrixStream.of(core);
  const retCode = trixOpenImpl(sp, inReal, startIdx, optInTimePeriod, outBegIdx, outNBElement, outReal, 1);
  sp.outRangeBegIdx = outBegIdx.value;
  sp.outRangeCount = outNBElement.value;
  if (retCode === RetCode.SUCCESS) {
    return sp;
  }
  if (retCode === RetCode.INSUFFICIENT_HISTORY) {
    throw insufficientHistory('TRIX openAndFill', inReal.length, startIdx, trixLookbackPositional(optInTimePeriod, core));
  }
  if (retCode === RetCode.BAD_PARAM && trixLookbackPositional(optInTimePeriod, core) < 0) {
    throw rejectedParams('TRIX openAndFill', PARAM_RANGES, optInTimePeriod);
  }
  throw streamFailure('TRIX openAndFill', retCode);
}

