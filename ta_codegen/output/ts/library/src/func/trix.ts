/** @internal */
export function trixOpenAndFillPositional(
  inReal: ArrayLike<number>,
  optInTimePeriod: number,
  outReal: Float64Array,
  core: Core = Core.DEFAULT,
): TrixStream {
  optInTimePeriod = requireInt32('TRIX openAndFill', 'timePeriod', optInTimePeriod);
  requireArgument('TRIX openAndFill', 'real', inReal);
  requireHistory('TRIX openAndFill', 'real', inReal.length);
  const guardLookback = trixLookbackPositional(optInTimePeriod, core);
  if (guardLookback < 0) {
    throw rejectedParams('TRIX openAndFill', PARAM_RANGES, optInTimePeriod);
  }
  const guardOutLen = openFillCount('TRIX openAndFill', inReal.length, guardLookback);
  requireOutput('TRIX openAndFill', 'outReal', outReal, guardOutLen, Float64Array);
  const inRealF64 = float64(inReal);
  if (outReal.buffer === inRealF64.buffer && outReal.byteOffset === inRealF64.byteOffset) {
    throw sharedMemory('TRIX openAndFill', 'outReal', 'real');
  }
  if (guardOutLen > 0 && overlaps(outReal, inRealF64)) {
    throw sharedMemory('TRIX openAndFill', 'outReal', 'real');
  }
  return trixOpenAndFillInternal(core, inRealF64, 0, optInTimePeriod, new MInteger(), new MInteger(), outReal);
}

/**
 * Opens a live TRIX stream over the warm-up history: `value()` starts at the last
 * history bar, bit-identical to {@link trix} there.
 *
 * @param real - Warm-up history. Source series to smooth.
 * @param options - The parameters and `core`; other keys are ignored. See
 *   {@link TrixOptions}.
 * @returns The stream, positioned on the last history bar.
 * @throws `TALibError` with code `TA_INSUFFICIENT_HISTORY` for a history shorter
 *   than `trixLookback(...) + 1` bars, an empty one included, and `TA_BAD_PARAM` for
 *   options that are not an object, a `core` that is not a `Core`, an absent input,
 *   an integer parameter that is not an int32 or a parameter outside its range.
 *
 * @example
 * ```ts
 * import { trixOpen } from 'ta-lib';
 *
 * const data = Float64Array.from({ length: 252 }, (_, i) =>
 *   100 + 10 * Math.sin(0.1 * i));
 * const stream = trixOpen(data, { timePeriod: 30 });
 * const peeked = stream.peek(100.9); // a forming bar: commits nothing
 * const updated = stream.update(100.9); // the bar closes
 * ```
 */
export function trixOpen(real: ArrayLike<number>, options?: TrixOptions): TrixStream {
  const o = optionsOf('TRIX open', options);
  const optInTimePeriod = orDefault(o.timePeriod, Core.INTEGER_DEFAULT);
  const core = coreOf('TRIX open', o.core);
  return trixOpenPositional(real, optInTimePeriod, core);
}

/**
 * {@link trixOpen} that also computes the outputs over the whole history in the
 * same pass, bit-identically to {@link trix}.
 *
 * @param real - Warm-up history. Source series to smooth.
 * @param options - The parameters, `core` and output buffers; other keys are
 *   ignored. See {@link TrixOptions}.
 * @returns The stream, positioned on the last history bar, with `begIdx` and the
 *   values over the history as {@link trix} returns them; the range is the stream's
 *   `outRange()`.
 * @throws `TALibError` with code `TA_INSUFFICIENT_HISTORY` for a history shorter
 *   than `trixLookback(...) + 1` bars, an empty one included, and `TA_BAD_PARAM` for
 *   options that are not an object, a `core` that is not a `Core`, an absent input,
 *   an integer parameter that is not an int32, a parameter outside its range or a
 *   buffer too short, of the wrong type or starting where another buffer or a
 *   `Float64Array` input starts, or, on a history long enough to open, one sharing
 *   memory with another buffer or a `Float64Array` input.
 *
 * @example
 * ```ts
 * import { trixOpenAndFill } from 'ta-lib';
 *
 * const data = Float64Array.from({ length: 252 }, (_, i) =>
 *   100 + 10 * Math.sin(0.1 * i));
 * const { stream, begIdx, values } = trixOpenAndFill(data, { timePeriod: 30 });
 * // values[k] is the value at bar begIdx + k
 * ```
 */
export function trixOpenAndFill(real: ArrayLike<number>, options?: TrixOptions): TrixResult & { stream: TrixStream } {
  const o = optionsOf('TRIX openAndFill', options);
  const optInTimePeriod = orDefault(o.timePeriod, Core.INTEGER_DEFAULT);
  const core = coreOf('TRIX openAndFill', o.core);
  const capacity = fillCapacity(trixLookbackPositional(optInTimePeriod, core), real);
  const outReal = o.outReal === undefined ? new Float64Array(capacity) : o.outReal;
  const stream = trixOpenAndFillPositional(real, optInTimePeriod, outReal, core);
  const range = stream.outRange();
  return { stream, begIdx: range.begIdx, values: outReal.subarray(0, range.count) };
}
