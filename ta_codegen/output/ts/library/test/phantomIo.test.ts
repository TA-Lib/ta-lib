// The body over a range ending below the lookback, every array zero-length:
// a documented success with no values, so any access is a phantom one.
// Control: one bar longer must touch an array, or this sweep proves nothing.
test('a sub-lookback range touches no array', () => {
  const failures: string[] = [];
  const live = new Set<string>();
  let probed = 0;
  let noQuiet = 0;
  let quietCalls = 0;
  for (const p of PROBES) {
    for (const [label, ...opts] of p.vectors) {
      const lb = lookbackOf(p, opts);
      if (lb < 0) continue;
      const control = callBody(p, lb, opts, inputs(p, 0), outputs(p, 0));
      if (control.kind === 'access' || control.kind === 'thrown') live.add(p.name);
      else failures.push(`${p.name}[${label}] at endIdx == lookback ${lb} touched no array: ${show(control)}`);
      if (lb < 1) {
        if (label === 'defaults') noQuiet++;
        continue;
      }
      if (label === 'defaults') probed++;
      quietCalls++;
      const quiet = callBody(p, lb - 1, opts, inputs(p, 0), outputs(p, 0));
      if (quiet.kind !== 'ok' || quiet.count !== 0) {
        failures.push(`${p.name}[${label}] (lookback ${lb}, endIdx ${lb - 1}): ${show(quiet)}`);
      }
    }
  }
  assert.deepEqual(failures, []);
  assert.equal(probed + noQuiet, PROBES.length, 'every function probed or counted at its defaults');
  assert.ok(probed > 0 && noQuiet > 0, `both outcomes occur (${probed} probed, ${noQuiet} with lookback 0)`);
  assert.ok(quietCalls > 0);
  assert.deepEqual(PROBES.map((p) => p.name).filter((n) => !live.has(n)), [], 'the control fired for every function');
});

// The public tier with every input exactly `endIdx + 1` long and every output
// exactly the count it reports: a read past `endIdx` or a write past the count
// throws instead of reading undefined or dropping the store.
test('exactly sized batch arrays are never indexed out of range', () => {
  const failures: string[] = [];
  const touched = new Set<string>();
  let calls = 0;
  for (const p of PROBES) {
    const r0 = seen.reads;
    const w0 = seen.writes;
    for (const [label, ...opts] of p.vectors) {
      const lb = lookbackOf(p, opts);
      if (lb < 0) continue;
      const ranges: [number, number][] = [[0, lb], [0, lb + 5], [lb, lb + 4], [lb + 3, lb + 7], [lb + 4, lb + 4]];
      for (const [s, e] of ranges) {
        const beg = s > lb ? s : lb;
        const count = e - beg + 1;
        calls++;
        const got = callBatch(p, s, e, opts, inputs(p, e + 1), outputs(p, count));
        if (got.kind !== 'ok' || got.begIdx !== beg || got.count !== count) {
          failures.push(`${p.name}[${label}] over [${s}, ${e}] (lookback ${lb}): ${show(got)}, expected begIdx ${beg} count ${count}`);
        }
      }
    }
    if (seen.reads > r0 && seen.writes > w0) touched.add(p.name);
  }
  assert.deepEqual(failures, []);
  assert.ok(calls > PROBES.length);
  const untouched = PROBES.filter((p) => p.ins.length > 0 && !touched.has(p.name)).map((p) => p.name);
  assert.deepEqual(untouched, [], 'the body read a guarded input and wrote a guarded output for every function');
});

// Open and OpenAndFill over a history exactly `lookback + 1` and `lookback + 6`
// bars long, the fill outputs exactly `historyLen - lookback`.
test('exactly sized stream history and fill outputs are never indexed out of range', () => {
  const failures: string[] = [];
  const touched = new Set<string>();
  let refused = 0;
  let opened = 0;
  for (const p of PROBES) {
    if (p.open === null || p.fill === null) continue;
    const r0 = seen.reads;
    const w0 = seen.writes;
    for (const [label, ...opts] of p.vectors) {
      const lb = lookbackOf(p, opts);
      if (lb < 0) continue;
      for (const h of [lb + 1, lb + 6]) {
        const open = callStream(p.open, [...inputs(p, h), ...opts]);
        if (open.kind === 'thrown' && open.code === 'TA_BAD_PARAM' && label.includes('=')) {
          refused++;
          continue;
        }
        const fill = callStream(p.fill, [...inputs(p, h), ...opts, ...outputs(p, h - lb)]);
        for (const [what, got] of [['open', open], ['openAndFill', fill]] as const) {
          if (got.kind !== 'ok' || got.begIdx !== lb || got.count !== h - lb) {
            failures.push(`${p.name}[${label}] ${what} over ${h} bars (lookback ${lb}): ${show(got)}`);
          }
        }
        opened++;
      }
    }
    if (seen.reads > r0 && seen.writes > w0) touched.add(p.name);
  }
  assert.deepEqual(failures, []);
  assert.ok(opened > refused, `${opened} opened, ${refused} refused`);
  const untouched = PROBES.filter((p) => p.open !== null && p.ins.length > 0 && !touched.has(p.name)).map((p) => p.name);
  assert.deepEqual(untouched, [], 'the opener read a guarded history and filled a guarded output for every function');
  assert.ok(seen.methods > 0, 'no guarded subarray or set call was seen');
});

// At the defaults, one input or output one element short: the public tier must
// reject it before the body runs. Control: every array sized must produce values.
