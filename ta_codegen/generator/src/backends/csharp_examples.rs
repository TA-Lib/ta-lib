//! The C# sample on each function page, and `ExamplesTest`, the suite that compiles
//! and runs every one on the synthetic series.

use super::examples::{self, hidden, shown, Snippet, LEN};
use crate::ir::{EnumDef, FuncDef, ParamType};
use std::collections::{BTreeSet, HashMap};
use std::fmt::Write as _;
use std::path::Path;

const WRAP: usize = 100;

const SYNTAX: examples::Syntax<'static> = examples::Syntax {
    real: super::doc_meta::fmt_real,
    bar: "i",
    sin: |x| format!("Math.Sin({x})"),
    modulo: |m| format!("(i % {m})"),
};

/// The batch call through the public tier, `Core.Default`.
#[allow(clippy::implicit_hasher)]
#[must_use]
pub fn example(func: &FuncDef, enums: &HashMap<String, EnumDef>) -> Option<Snippet> {
    let series = examples::all_series(func)?;
    let first = series.first()?.var;
    let name = &func.name;
    let method = super::common::pascal_words(name);

    let imports = vec!["using System;".to_string(), "using TALib;".to_string()];
    let mut body = Vec::new();
    for s in &series {
        body.push(shown(format!("var {} = new double[{LEN}]; // {}", s.var, s.comment)));
        body.push(hidden(format!(
            "for (int i = 0; i < {LEN}; i++) {}[i] = {};",
            s.var,
            examples::render(s, &SYNTAX)
        )));
    }
    // `out` is a C# keyword, so a lone output keeps its own name (`outReal`).
    let out_vars: Vec<String> = examples::output_vars(func)
        .into_iter()
        .zip(&func.outputs)
        .map(|(v, o)| if v == "out" { o.name.clone() } else { v })
        .collect();
    for (output, var) in func.outputs.iter().zip(&out_vars) {
        let ty = if output.param_type == ParamType::Integer { "int" } else { "double" };
        body.push(shown(format!("var {var} = new {ty}[{LEN}];")));
    }
    body.push(shown(""));
    body.push(shown("var core = Core.Default;"));
    let mut args = vec!["0".to_string(), format!("{first}.Length - 1")];
    args.extend(series.iter().map(|s| s.var.to_string()));
    args.extend(func.optional_inputs.iter().map(|opt| {
        examples::opt_literal(opt, enums, super::rust_doc::fmt_real_literal, |e, v| format!("{}.{v}", e.name))
    }));
    body.extend(
        examples::wrap_call(&format!("OutRange r = core.{method}("), &args, &out_vars, ");", WRAP).into_iter().map(shown),
    );
    body.push(hidden(format!("if (!Check(\"{name}\", r.Count > 0)) return;")));
    let printed = &out_vars[0];
    body.push(shown(format!(
        "Console.WriteLine($\"{{r.Count}} values from bar {{r.BegIdx}}; last {printed} = {{{printed}[r.Count - 1]}}\");"
    )));
    if let Some((_, var)) = func.outputs.iter().zip(&out_vars).find(|(o, _)| o.param_type != ParamType::Integer) {
        let helper = if examples::allows_infinity(func) { "NoNaN" } else { "AllFinite" };
        body.push(hidden(format!("Check(\"{name}\", {helper}({var}, r.Count));")));
    }
    Some(Snippet { imports, body })
}

/// The suite: one method per function holding its sample verbatim, run by `Run`,
/// which `AllTests` discovers by the class name.
#[allow(clippy::implicit_hasher)]
#[must_use]
pub fn render_test(funcs: &[FuncDef], enums: &HashMap<String, EnumDef>) -> String {
    let mut funcs: Vec<&FuncDef> = funcs.iter().collect();
    funcs.sort_by(|a, b| a.name.cmp(&b.name));
    let samples: Vec<(&FuncDef, Snippet)> =
        funcs.iter().filter_map(|f| example(f, enums).map(|s| (*f, s))).collect();
    let imports: BTreeSet<&String> = samples.iter().flat_map(|(_, s)| s.imports.iter()).collect();

    let mut out = String::from(super::ta_abstract_c::LICENSE);
    out.push_str(
        "\n/* Generated by ta_codegen (backends/csharp_examples.rs) from\n\
         \x20* ta_codegen/input/ \u{2014} do not edit.\n\
         \x20* MF,CC\n */\n\n\
         #nullable enable\n\n",
    );
    for import in imports {
        let _ = writeln!(out, "{import}");
    }
    out.push_str(
        "\nnamespace TALib.Test;\n\n\
         /// <summary>\n\
         /// Every function page's C# sample, run on the synthetic series: the call\n\
         /// answers a non-empty range whose values are finite.\n\
         /// </summary>\n\
         public static class ExamplesTest\n\
         {\n\
         \x20   private static int _failures;\n\
         \x20   private static int _checks;\n\n\
         \x20   private static bool Check(string name, bool ok)\n\
         \x20   {\n\
         \x20       _checks++;\n\
         \x20       if (!ok)\n\
         \x20       {\n\
         \x20           _failures++;\n\
         \x20           Console.WriteLine($\"  FAIL: {name} example\");\n\
         \x20       }\n\
         \x20       return ok;\n\
         \x20   }\n\n\
         \x20   private static bool AllFinite(double[] a, int n)\n\
         \x20   {\n\
         \x20       for (int i = 0; i < n; i++)\n\
         \x20       {\n\
         \x20           if (!double.IsFinite(a[i]))\n\
         \x20           {\n\
         \x20               return false;\n\
         \x20           }\n\
         \x20       }\n\
         \x20       return true;\n\
         \x20   }\n\n\
         \x20   private static bool NoNaN(double[] a, int n)\n\
         \x20   {\n\
         \x20       for (int i = 0; i < n; i++)\n\
         \x20       {\n\
         \x20           if (double.IsNaN(a[i]))\n\
         \x20           {\n\
         \x20               return false;\n\
         \x20           }\n\
         \x20       }\n\
         \x20       return true;\n\
         \x20   }\n",
    );
    for (func, snippet) in &samples {
        let _ = writeln!(out, "\n    private static void {}()\n    {{", super::common::pascal_words(&func.name));
        for line in snippet.body_text() {
            if line.is_empty() {
                out.push('\n');
            } else {
                let _ = writeln!(out, "        {line}");
            }
        }
        out.push_str("    }\n");
    }
    out.push_str("\n    public static int Run()\n    {\n");
    for (func, _) in &samples {
        let _ = writeln!(out, "        {}();", super::common::pascal_words(&func.name));
    }
    out.push_str(
        "\n        if (_failures == 0)\n\
         \x20       {\n\
         \x20           Console.WriteLine($\"ExamplesTest: ALL PASS ({_checks} checks)\");\n\
         \x20           return 0;\n\
         \x20       }\n\
         \x20       Console.WriteLine($\"ExamplesTest: {_failures} of {_checks} checks FAILED\");\n\
         \x20       return 1;\n\
         \x20   }\n\
         }\n",
    );
    out
}

#[allow(clippy::implicit_hasher)]
pub fn write(funcs: &[FuncDef], enums: &HashMap<String, EnumDef>, path: &Path) {
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir).unwrap_or_else(|e| panic!("creating {}: {e}", dir.display()));
    }
    super::write_if_changed_silent(path, &render_test(funcs, enums));
    println!("  C# examples test -> {}", path.display());
}
