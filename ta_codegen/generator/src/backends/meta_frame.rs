//! Generate `src/tools/ta_regtest/ta_meta_frame.h`: a wrapper around every
//! `TA_<N>` / `TA_S_<N>` that hands each successful call to `ta_regtest`'s
//! metadata ride (`meta_ride.c`), then renames the function to its wrapper.
//!
//! The rename is an object-like macro, so a function pointer and a `TA_##x`
//! paste are wrapped like a plain call. The bodies are emitted once, under
//! `TA_META_FRAME_IMPL`, with external linkage: a `static` copy per translation
//! unit would give one function a different address in each.

use std::fmt::Write as _;
use std::path::Path;

use super::variant_frame::flat_inputs;
use super::write_if_changed;
use crate::ir::{FuncDef, ParamType};

fn opt_decl(func: &FuncDef) -> Vec<String> {
    func.optional_inputs
        .iter()
        .map(|opt| {
            let ty = match &opt.param_type {
                ParamType::Real => "double",
                ParamType::Enum(_) => "TA_MAType",
                _ => "int",
            };
            format!("{ty} {}", opt.name)
        })
        .collect()
}

fn out_decl(func: &FuncDef) -> Vec<String> {
    func.outputs
        .iter()
        .map(|out| {
            let ty = if out.param_type == ParamType::Integer { "int" } else { "double" };
            format!("{ty} {}[]", out.name)
        })
        .collect()
}

fn signature(func: &FuncDef, callee: &str, elem: &str) -> String {
    let mut params: Vec<String> = vec!["int startIdx".into(), "int endIdx".into()];
    params.extend(flat_inputs(func).iter().map(|(_, n)| format!("const {elem} {n}[]")));
    params.extend(opt_decl(func));
    params.push("int *outBegIdx".into());
    params.push("int *outNBElement".into());
    params.extend(out_decl(func));
    format!("TA_RetCode {callee}_MetaRide( {} )", params.join(", "))
}

fn emit_body(o: &mut String, func: &FuncDef, idx: usize, callee: &str, elem: &str) {
    let inputs: Vec<String> = flat_inputs(func).into_iter().map(|(_, n)| n).collect();
    let opts: Vec<String> = func.optional_inputs.iter().map(|opt| opt.name.clone()).collect();
    let outs: Vec<String> = func.outputs.iter().map(|out| out.name.clone()).collect();
    let name = &func.name;

    let mut args: Vec<String> = vec!["startIdx".into(), "endIdx".into()];
    args.extend(inputs.iter().cloned());
    args.extend(opts.iter().cloned());
    args.push("outBegIdx".into());
    args.push("outNBElement".into());
    args.extend(outs.iter().cloned());

    let opt_args = |tail: &str| {
        let mut a = opts.clone();
        if !tail.is_empty() {
            a.push(tail.into());
        }
        a.join(", ")
    };
    let shifts: Vec<String> = (0..outs.len())
        .map(|i| format!("TA_{name}_DisplayShift( {} )", opt_args(&i.to_string())))
        .collect();

    let _ = writeln!(
        o,
        "{}\n{{\n\
         \x20  TA_RetCode retCode = {callee}( {} );\n\
         \x20  if( retCode == TA_SUCCESS )\n\
         \x20  {{\n\
         \x20     const void *in[] = {{ {} }};\n\
         \x20     const void *out[] = {{ {} }};\n\
         \x20     int shift[] = {{ {} }};\n\
         \x20     meta_ride_check( {idx}, {}, startIdx, endIdx, in, {},\n\
         \x20                      *outBegIdx, *outNBElement,\n\
         \x20                      TA_{name}_Lookback( {} ), shift, out );\n\
         \x20  }}\n\
         \x20  return retCode;\n\
         }}",
        signature(func, callee, elem),
        args.join(", "),
        inputs.join(", "),
        outs.join(", "),
        shifts.join(", "),
        i32::from(elem == "float"),
        inputs.len(),
        opt_args(""),
    );
}

/// Build the whole `ta_meta_frame.h` for `funcs`.
pub fn render(funcs: &[FuncDef]) -> String {
    let mut o = String::new();
    o.push_str(super::variant_frame::LICENSE);
    o.push_str(
        "/* AUTO-GENERATED by ta_codegen — DO NOT EDIT.\n\
         * Source of truth: ta_codegen/generator/src/backends/meta_frame.rs\n\
         * (regenerate: cd ta_codegen/generator && cargo run -- generate)\n\
         *\n\
         * Including this header routes every TA_<N> and TA_S_<N> call of the\n\
         * translation unit through meta_ride_check (meta_ride.h). Exactly one\n\
         * unit defines TA_META_FRAME_IMPL first, and holds the wrappers.\n\
         */\n\n",
    );
    o.push_str("#ifndef TA_META_FRAME_H\n#define TA_META_FRAME_H\n\n");
    o.push_str("#ifndef TA_FUNC_H\n   #include \"ta_func.h\"\n#endif\n\n");
    let _ = writeln!(o, "#define TA_META_FRAME_SIZE {}\n", funcs.len());

    for func in funcs {
        for (callee, elem) in [
            (format!("TA_{}", func.name), "double"),
            (format!("TA_S_{}", func.name), "float"),
        ] {
            let _ = writeln!(o, "{};", signature(func, &callee, elem));
        }
    }

    o.push_str(
        "\n#ifdef TA_META_FRAME_IMPL\n\n\
         const char *const TA_MetaFrameName[TA_META_FRAME_SIZE] = {\n",
    );
    for func in funcs {
        let _ = writeln!(o, "   \"{}\",", func.name);
    }
    o.push_str("};\n\n");
    for (idx, func) in funcs.iter().enumerate() {
        for (callee, elem) in [
            (format!("TA_{}", func.name), "double"),
            (format!("TA_S_{}", func.name), "float"),
        ] {
            emit_body(&mut o, func, idx, &callee, elem);
        }
        o.push('\n');
    }
    o.push_str("#endif /* TA_META_FRAME_IMPL */\n\n");

    for func in funcs {
        let n = &func.name;
        let _ = writeln!(o, "#define TA_{n} TA_{n}_MetaRide\n#define TA_S_{n} TA_S_{n}_MetaRide");
    }
    o.push_str("\n#endif /* TA_META_FRAME_H */\n");
    o
}

/// Write `src/tools/ta_regtest/ta_meta_frame.h`.
pub fn generate(funcs: &[FuncDef], root: &Path) {
    let path = root.join("src/tools/ta_regtest/ta_meta_frame.h");
    write_if_changed(&path, &render(funcs), "ta_meta_frame.h", funcs.len());
}
