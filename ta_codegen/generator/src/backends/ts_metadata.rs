fn code_object(s: &mut String, name: &str, doc: &str, members: &[(&str, &str)]) {
    let _ = writeln!(s, "/** {doc} */\nexport const {name} = Object.freeze({{");
    for (i, (member, mdoc)) in members.iter().enumerate() {
        let _ = writeln!(s, "  /** {mdoc} */\n  {member}: {i},");
    }
    let _ = writeln!(
        s,
        "}} as const);\n/** One {{@link {name}}} value. */\nexport type {name} = (typeof {name})[keyof typeof {name}];\n"
    );
}

fn flag_object(s: &mut String, name: &str, doc: &str, members: &[(String, u32, &str)]) {
    let _ = writeln!(s, "/** {doc} */\nexport const {name} = Object.freeze({{");
    for (member, bits, mdoc) in members {
        let _ = writeln!(s, "  /** {mdoc} */\n  {member}: 0x{bits:08X},");
    }
    s.push_str("} as const);\n\n");
}

