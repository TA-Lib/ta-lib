fn functions(rows: &[FuncRow]) -> String {
    let mut s = header();
    s.push_str(
        "import { FuncInfo } from './funcInfo.ts';\n\
         import { InputType, OptInputType, OutputType } from './flags.ts';\n\n\
         const ALL: readonly FuncInfo[] = Object.freeze([\n",
    );
    for r in rows {
        emit_row(&mut s, r);
    }
    s.push_str(
        r"]);

const BY_NAME: ReadonlyMap<string, FuncInfo> = new Map(ALL.map((f) => [f.name, f]));

const GROUPS: readonly string[] = Object.freeze([...new Set(ALL.map((f) => f.group))]);

// String.prototype.toUpperCase maps U+017F and U+0131 onto ASCII letters.
function asciiUpper(s: string): string {
  return s.replace(/[a-z]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 32));
}

/** The catalogue of every function, for an application that picks one at run time. */
export const Functions = Object.freeze({
  /** Every function, in name order. */
  all(): readonly FuncInfo[] {
    return ALL;
  },
  /**
   * One function by name in any ASCII casing (`'SMA'`, `'sma'`), or `undefined`.
   *
   * @param name - The function's registry name.
   */
  byName(name: string): FuncInfo | undefined {
    return typeof name === 'string' ? BY_NAME.get(asciiUpper(name)) : undefined;
  },
  /** The distinct group names, in first-appearance order. */
  groups(): readonly string[] {
    return GROUPS;
  },
});
",
    );
    s
}

fn emit_row(s: &mut String, r: &FuncRow) {
    let _ = writeln!(
        s,
        "  FuncInfo.of({}, {}, {}, 0x{:08X},",
        lit(&r.name),
        lit(r.group.as_str()),
        lit(&r.hint),
        r.flags
    );
    let inputs: Vec<String> = r
        .inputs
        .iter()
        .map(|i| {
            let ty = match i.kind {
                InputKind::Price => "PRICE",
                InputKind::Real => "REAL",
                InputKind::Integer => "INTEGER",
            };
            format!(
                "{{ type: InputType.{ty}, paramName: {}, flags: 0x{:08X} }}",
                lit(&i.param_name),
                i.flags
            )
        })
        .collect();
    let opts: Vec<String> = r
        .opt_inputs
        .iter()
        .map(|o| {
            let common = format!(
                "paramName: {}, flags: 0x{:08X}, displayName: {}, hint: {}, defaultValue: {}",
                lit(&o.param_name),
                o.flags,
                lit(&o.display_name),
                lit(&o.hint),
                num(o.domain.default_as_f64())
            );
            match &o.domain {
                OptDomain::RealRange { min, max, precision, suggested, .. } => format!(
                    "{{ type: OptInputType.REAL_RANGE, {common}, min: {}, max: {}, precision: {precision}, \
                     suggestedStart: {}, suggestedEnd: {}, suggestedIncrement: {} }}",
                    num(*min),
                    num(*max),
                    num(suggested.0),
                    num(suggested.1),
                    num(suggested.2)
                ),
                OptDomain::IntegerRange { min, max, suggested, .. } => format!(
                    "{{ type: OptInputType.INTEGER_RANGE, {common}, min: {min}, max: {max}, \
                     suggestedStart: {}, suggestedEnd: {}, suggestedIncrement: {} }}",
                    suggested.0, suggested.1, suggested.2
                ),
                OptDomain::IntegerList { values, .. } => {
                    let v: Vec<String> = values
                        .iter()
                        .map(|(v, n)| format!("{{ value: {v}, name: {} }}", lit(n)))
                        .collect();
                    format!("{{ type: OptInputType.INTEGER_LIST, {common}, values: [{}] }}", v.join(", "))
                }
                OptDomain::RealList { values, .. } => {
                    let v: Vec<String> = values
                        .iter()
                        .map(|(v, n)| format!("{{ value: {}, name: {} }}", num(*v), lit(n)))
                        .collect();
                    format!("{{ type: OptInputType.REAL_LIST, {common}, values: [{}] }}", v.join(", "))
                }
            }
        })
        .collect();
    let outputs: Vec<String> = r
        .outputs
        .iter()
        .map(|o| {
            let ty = match o.kind {
                OutputKind::Real => "REAL",
                OutputKind::Integer => "INTEGER",
            };
            format!(
                "{{ type: OutputType.{ty}, paramName: {}, flags: 0x{:08X} }}",
                lit(&o.param_name),
                o.flags
            )
        })
        .collect();
    for (items, last) in [(&inputs, false), (&opts, false), (&outputs, true)] {
        let close = if last { ")," } else { "," };
        if items.is_empty() {
            let _ = writeln!(s, "    []{close}");
        } else {
            s.push_str("    [\n");
            for it in items {
                let _ = writeln!(s, "      {it},");
            }
            let _ = writeln!(s, "    ]{close}");
        }
    }
}

