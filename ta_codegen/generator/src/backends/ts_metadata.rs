const PARAM_HOLDER: &str = r"import { Core } from '../runtime/core.ts';
import { RetCode, TALibError } from '../runtime/errors.ts';
import type { OutRange } from '../runtime/outRange.ts';
import type { Thunks } from './dispatch.ts';
import type { FuncInfo, OptInputInfo } from './funcInfo.ts';
import { InputFlags, InputType, OptInputType, OutputType } from './flags.ts';

/** The OHLCV components of a price input. Omit any the input's `flags` do not name. */
export interface PriceInput {
  /** Open prices. */
  readonly open?: ArrayLike<number>;
  /** High prices. */
  readonly high?: ArrayLike<number>;
  /** Low prices. */
  readonly low?: ArrayLike<number>;
  /** Close prices. */
  readonly close?: ArrayLike<number>;
  /** Volumes. */
  readonly volume?: ArrayLike<number>;
  /** Open interest. */
  readonly openInterest?: ArrayLike<number>;
}

const COMPONENTS = [
  ['open', InputFlags.PRICE_OPEN],
  ['high', InputFlags.PRICE_HIGH],
  ['low', InputFlags.PRICE_LOW],
  ['close', InputFlags.PRICE_CLOSE],
  ['volume', InputFlags.PRICE_VOLUME],
  ['openInterest', InputFlags.PRICE_OPENINTEREST],
] as const;

function isSeries(v: unknown): v is ArrayLike<number> {
  return typeof v === 'object' && v !== null && typeof (v as { length?: unknown }).length === 'number';
}

function bad(code: typeof RetCode.BAD_PARAM | typeof RetCode.INVALID_PARAM_HOLDER_TYPE, message: string): TALibError {
  return new TALibError(code, message);
}

function checkIndex(name: string, what: string, idx: number, count: number): void {
  if (!Number.isInteger(idx) || idx < 0 || idx >= count) {
    throw bad(RetCode.BAD_PARAM, `${name}: ${what} index ${idx} out of range [0, ${count})`);
  }
}

function unsetValue(o: OptInputInfo): number {
  return o.type === OptInputType.REAL_RANGE || o.type === OptInputType.REAL_LIST
    ? Core.REAL_DEFAULT
    : Core.INTEGER_DEFAULT;
}

/**
 * Binds arguments to a function chosen at run time, then calls it: the
 * counterpart of C's `TA_ParamHolder`. Obtain one from `FuncInfo.newCall`.
 *
 * Every setter checks its argument against the function's row before it writes,
 * so a rejected call leaves the holder as it was. A rejection throws
 * {@link TALibError}: `TA_BAD_PARAM` for an index out of range or a missing or
 * malformed value, `TA_INVALID_PARAM_HOLDER_TYPE` for a slot of another kind.
 * An unset optional parameter takes its default.
 *
 * Not safe to share between concurrent callers that bind different arguments.
 */
export class ParamHolder {
  /** The function this holder calls. */
  readonly info: FuncInfo;
  /** The settings the call runs with. */
  readonly core: Core;
  /** @internal */
  readonly thunks: Thunks;
  /** @internal */
  readonly inputs: (ArrayLike<number> | null)[];
  /** @internal */
  readonly prices: ((ArrayLike<number> | undefined)[] | null)[];
  /** @internal */
  readonly opts: number[];
  /** @internal */
  readonly outputs: (Float64Array | Int32Array | null)[];

  private constructor(info: FuncInfo, core: Core, thunks: Thunks) {
    this.info = info;
    this.core = core;
    this.thunks = thunks;
    this.inputs = info.inputs.map(() => null);
    this.prices = info.inputs.map(() => null);
    this.opts = info.optInputs.map(unsetValue);
    this.outputs = info.outputs.map(() => null);
  }

  /** @internal */
  static create(info: FuncInfo, core: Core, thunks: Thunks): ParamHolder {
    return new ParamHolder(info, core, thunks);
  }

  /**
   * Binds a real or integer input.
   *
   * @param idx - The input's position in `FuncInfo.inputs`.
   * @param series - The input's values.
   */
  setInput(idx: number, series: ArrayLike<number>): this {
    const name = this.info.name;
    checkIndex(name, 'input', idx, this.info.inputs.length);
    if (this.info.inputs[idx].type === InputType.PRICE) {
      throw bad(RetCode.INVALID_PARAM_HOLDER_TYPE, `${name}: input ${idx} is a price input; use setPriceInput`);
    }
    if (!isSeries(series)) {
      throw bad(RetCode.BAD_PARAM, `${name}: input ${idx} is not an array`);
    }
    this.inputs[idx] = series;
    return this;
  }

  /**
   * Binds a price input. Every component the input's `flags` name must be present.
   *
   * @param idx - The input's position in `FuncInfo.inputs`.
   * @param price - The components, by name.
   */
  setPriceInput(idx: number, price: PriceInput): this {
    const name = this.info.name;
    checkIndex(name, 'input', idx, this.info.inputs.length);
    const info = this.info.inputs[idx];
    if (info.type !== InputType.PRICE) {
      throw bad(RetCode.INVALID_PARAM_HOLDER_TYPE, `${name}: input ${idx} is not a price input; use setInput`);
    }
    if (typeof price !== 'object' || price === null) {
      throw bad(RetCode.BAD_PARAM, `${name}: input ${idx} needs a PriceInput`);
    }
    const given = COMPONENTS.map(([key, bit]) => ((info.flags & bit) !== 0 ? price[key] : undefined));
    for (let k = 0; k < COMPONENTS.length; k++) {
      if ((info.flags & COMPONENTS[k][1]) !== 0 && !isSeries(given[k])) {
        throw bad(RetCode.BAD_PARAM, `${name}: input ${idx} requires ${COMPONENTS[k][0]}`);
      }
    }
    this.prices[idx] = given;
    return this;
  }

  /**
   * Binds an optional parameter. An integer domain takes an int32, and
   * `Core.INTEGER_DEFAULT` selects the default; a real domain takes any number,
   * and `Core.REAL_DEFAULT` selects the default.
   *
   * @param idx - The parameter's position in `FuncInfo.optInputs`.
   * @param value - The parameter's value, or the domain's default sentinel.
   */
  setOptInput(idx: number, value: number): this {
    const name = this.info.name;
    checkIndex(name, 'optInput', idx, this.info.optInputs.length);
    const type = this.info.optInputs[idx].type;
    if (type === OptInputType.INTEGER_RANGE || type === OptInputType.INTEGER_LIST) {
      if (typeof value !== 'number' || (value | 0) !== value) {
        throw bad(RetCode.BAD_PARAM, `${name}: optInput ${idx} needs an int32, got ${String(value)}`);
      }
    } else if (typeof value !== 'number') {
      throw bad(RetCode.BAD_PARAM, `${name}: optInput ${idx} needs a number`);
    }
    this.opts[idx] = value;
    return this;
  }

  /**
   * Binds an output: a `Float64Array` for a real output, an `Int32Array` for an integer one.
   *
   * @param idx - The output's position in `FuncInfo.outputs`.
   * @param out - The array the call writes the output into.
   */
  setOutput(idx: number, out: Float64Array | Int32Array): this {
    const name = this.info.name;
    checkIndex(name, 'output', idx, this.info.outputs.length);
    if (typeof out !== 'object' || out === null) {
      throw bad(RetCode.BAD_PARAM, `${name}: output ${idx} is not an array`);
    }
    const real = this.info.outputs[idx].type === OutputType.REAL;
    if (real ? !(out instanceof Float64Array) : !(out instanceof Int32Array)) {
      throw bad(RetCode.INVALID_PARAM_HOLDER_TYPE, `${name}: output ${idx} needs ${real ? 'a Float64Array' : 'an Int32Array'}`);
    }
    this.outputs[idx] = out;
    return this;
  }

  /**
   * The function's lookback for the optional parameters bound so far, or -1 if
   * one is out of range. Inputs and outputs need not be bound.
   */
  lookback(): number {
    return this.thunks.lookback(this);
  }

  /**
   * How many bars ahead (positive) or behind (negative) of the bar that computed
   * it a chart draws output `outputIdx`, for the optional parameters bound so
   * far: 0 for an output without `OutputFlags.DISPLAY_SHIFT`, and -2147483648 if
   * a parameter is out of range or the index names no output.
   *
   * @param outputIdx - The output's position in `FuncInfo.outputs`.
   */
  displayShift(outputIdx: number): number {
    return this.thunks.displayShift(this, outputIdx);
  }

  /**
   * Calls the function over `[startIdx, endIdx]` through its public batch form,
   * which then throws exactly as a direct call does.
   *
   * @param startIdx - First bar of the requested range (inclusive).
   * @param endIdx - Last bar of the requested range (inclusive).
   * @throws {@link TALibError} `TA_INPUT_NOT_ALL_INITIALIZE` or
   *   `TA_OUTPUT_NOT_ALL_INITIALIZE` for an unbound input or output.
   */
  call(startIdx: number, endIdx: number): OutRange {
    const name = this.info.name;
    for (let i = 0; i < this.info.inputs.length; i++) {
      const bound = this.info.inputs[i].type === InputType.PRICE ? this.prices[i] !== null : this.inputs[i] !== null;
      if (!bound) {
        throw new TALibError(RetCode.INPUT_NOT_ALL_INITIALIZE, `${name}: input ${i} is not set`);
      }
    }
    for (let i = 0; i < this.info.outputs.length; i++) {
      if (this.outputs[i] === null) {
        throw new TALibError(RetCode.OUTPUT_NOT_ALL_INITIALIZE, `${name}: output ${i} is not set`);
      }
    }
    return this.thunks.call(this, startIdx, endIdx);
  }
}
";

