/// The real XML, so the server's length and checksum are measured from shipped bytes.
fn function_description(funcs: &[FuncDef]) -> String {
    let xml = super::func_api_xml::generate_string(funcs);
    assert!(xml.is_ascii(), "ta_func_api.xml is no longer ASCII; the server's byte checksum reads UTF-16 code units");
    let mut s = header();
    s.push_str("const LINES: readonly string[] = [\n");
    for line in xml.split('\n') {
        let _ = writeln!(s, "  {},", lit(line));
    }
    s.push_str(
        "];\n\n\
         /** The machine-readable description of every function. */\n\
         export const FunctionDescription = Object.freeze({\n\
         \x20 /** The XML document C's `TA_FunctionDescriptionXML()` returns, byte for byte. */\n\
         \x20 xml(): string {\n\
         \x20   return LINES.join('\\n');\n\
         \x20 },\n\
         });\n",
    );
    s
}

