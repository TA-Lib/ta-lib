const MARKER: &str = "/* Generated by ta_codegen (generator/src/backends/ts_metadata.rs) \u{2014} do not edit. */";

#[allow(clippy::implicit_hasher)]
pub fn generate(funcs: &[FuncDef], enums: &HashMap<String, EnumDef>, dir: &Path) {
    std::fs::create_dir_all(dir).unwrap_or_else(|e| panic!("creating {}: {e}", dir.display()));
    let files = render_all(funcs, enums);
    for (name, body) in &files {
        super::write_if_changed_silent(&dir.join(name), body);
    }
    let keep: Vec<&str> = files.iter().map(|(n, _)| *n).collect();
    clean_stale(dir, &keep);
    println!("  ts metadata registry -> {} ({} functions)", dir.display(), funcs.len());
}

/// Every emitted file, by name.
#[allow(clippy::implicit_hasher)]
#[must_use]
pub fn render_all(funcs: &[FuncDef], enums: &HashMap<String, EnumDef>) -> Vec<(&'static str, String)> {
    let rows = rows(funcs, enums);
    let by_name: HashMap<&str, &FuncDef> = funcs.iter().map(|f| (f.name.as_str(), f)).collect();
    vec![
        ("flags.ts", flags()),
        ("funcInfo.ts", func_info()),
        ("paramHolder.ts", render_param_holder()),
        ("dispatch.ts", dispatch(&rows, &by_name)),
        ("functions.ts", functions(&rows)),
        ("functionDescription.ts", function_description(funcs)),
        ("runtimeInfo.ts", runtime_info()),
        ("index.ts", index()),
    ]
}

fn clean_stale(dir: &Path, keep: &[&str]) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let name = entry.file_name().to_string_lossy().to_string();
        let is_ts = Path::new(&name).extension().is_some_and(|e| e.eq_ignore_ascii_case("ts"));
        if !is_ts || keep.contains(&name.as_str()) {
            continue;
        }
        let generated = std::fs::read_to_string(entry.path()).is_ok_and(|t| t.contains(MARKER));
        if generated {
            std::fs::remove_file(entry.path()).ok();
            println!("  removed stale TS metadata file {name}");
        }
    }
}

fn header() -> String {
    format!("{}\n{MARKER}\n\n", super::ta_abstract_c::LICENSE)
}

/// A single-quoted TS string literal.
fn lit(s: &str) -> String {
    let mut o = String::from("'");
    for c in s.chars() {
        match c {
            '\'' => o.push_str("\\'"),
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            '\r' => o.push_str("\\r"),
            '\t' => o.push_str("\\t"),
            c if (c as u32) < 0x20 => {
                let _ = write!(o, "\\u{:04x}", c as u32);
            }
            c => o.push(c),
        }
    }
    o.push('\'');
    o
}

/// The shortest round-tripping literal; Rust's `Debug` form is valid TS.
fn num(v: f64) -> String {
    format!("{v:?}")
}

