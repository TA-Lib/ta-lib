/// One thunk triple per function, each calling the function's public tier.
fn dispatch(rows: &[FuncRow], by_name: &HashMap<&str, &FuncDef>) -> String {
    let mut s = header();
    let mut enum_types: Vec<&str> = rows
        .iter()
        .flat_map(|r| by_name[r.name.as_str()].optional_inputs.iter())
        .filter_map(|o| match &o.param_type {
            ParamType::Enum(e) => Some(e.as_str()),
            _ => None,
        })
        .collect();
    enum_types.sort_unstable();
    enum_types.dedup();
    s.push_str("import type { OutRange } from '../runtime/outRange.ts';\n");
    if !enum_types.is_empty() {
        let _ = writeln!(s, "import type {{ {} }} from '../enums.ts';", enum_types.join(", "));
    }
    s.push_str("import type { ParamHolder } from './paramHolder.ts';\n");
    for r in rows {
        let _ = writeln!(
            s,
            "import * as {} from '../func/{}.ts';",
            r.name,
            super::ts::ts_names(&r.name).module
        );
    }
    s.push_str(
        "\n/** @internal */\n\
         export interface Thunks {\n\
         \x20 readonly lookback: (h: ParamHolder) => number;\n\
         \x20 readonly displayShift: (h: ParamHolder, outputIdx: number) => number;\n\
         \x20 readonly call: (h: ParamHolder, startIdx: number, endIdx: number) => OutRange;\n\
         }\n\n\
         /** @internal */\n\
         export const DISPATCH: ReadonlyMap<string, Thunks> = new Map<string, Thunks>([\n",
    );
    for r in rows {
        let def = by_name[r.name.as_str()];
        let n = super::ts::ts_names(&r.name);
        let m = &r.name;
        let opts: Vec<String> = def
            .optional_inputs
            .iter()
            .enumerate()
            .map(|(k, o)| match &o.param_type {
                ParamType::Enum(e) => format!("h.opts[{k}] as {e}"),
                _ => format!("h.opts[{k}]"),
            })
            .collect();
        let mut lb = opts.clone();
        lb.push("h.core".into());
        let mut ds = opts.clone();
        ds.push("o".into());
        ds.push("h.core".into());
        let mut call: Vec<String> = vec!["s".into(), "e".into()];
        for (slot, inp) in r.inputs.iter().enumerate() {
            match inp.kind {
                InputKind::Price => {
                    for c in &inp.signature_components {
                        call.push(format!("h.prices[{slot}]![{}]!", *c as usize));
                    }
                }
                InputKind::Real | InputKind::Integer => call.push(format!("h.inputs[{slot}]!")),
            }
        }
        call.extend(opts);
        for (k, out) in r.outputs.iter().enumerate() {
            call.push(match out.kind {
                OutputKind::Real => format!("h.outputs[{k}] as Float64Array"),
                OutputKind::Integer => format!("h.outputs[{k}] as Int32Array"),
            });
        }
        call.push("h.core".into());
        let _ = writeln!(s, "  ['{m}', {{");
        let _ = writeln!(s, "    lookback: (h) => {m}.{}({}),", n.lookback, lb.join(", "));
        let _ = writeln!(s, "    displayShift: (h, o) => {m}.{}({}),", n.display_shift, ds.join(", "));
        let _ = writeln!(s, "    call: (h, s, e) => {m}.{}({}),", n.public, call.join(", "));
        s.push_str("  }],\n");
    }
    s.push_str("]);\n");
    s
}

