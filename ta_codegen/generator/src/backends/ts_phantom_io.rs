//! Generate `library/test/phantomIo.test.ts`: the TypeScript phantom-I/O sweep
//! (H14). A typed array read past its end gives `undefined` and a write past it
//! is dropped, so only a guard that throws makes such an access visible.
//!
//! The guard is a `Proxy` that still passes `instanceof Float64Array`, so the
//! public tier hands it to the body instead of copying it: every leg below
//! reaches the body with guarded inputs and outputs.
//!
//! Whole-corpus, like `rust_phantom_io`, and on the same parameter vectors: a
//! sweep a filtered run could shrink would fail open.

use super::rust_phantom_io::{leg_kind, vectors, VectorSpelling};
use super::ts::{module_stem, ts_names};
use crate::ir::{EnumDef, FuncDef, OptInput, ParamType};
use std::collections::HashMap;
use std::fmt::Write as _;
use std::path::Path;

struct TsSpelling;

impl VectorSpelling for TsSpelling {
    fn default(&self, opt: &OptInput) -> String {
        match &opt.param_type {
            ParamType::Real => "Core.REAL_DEFAULT".to_string(),
            ParamType::Enum(name) => format!("{name}.DEFAULT"),
            ParamType::Integer | ParamType::Price(_) => "Core.INTEGER_DEFAULT".to_string(),
        }
    }
    fn real(&self, v: f64) -> String {
        format!("{v:?}")
    }
    fn int(&self, v: i64) -> String {
        v.to_string()
    }
    fn member(&self, enum_name: &str, variant: &str) -> String {
        format!("{enum_name}.{variant}")
    }
}

fn out_kind(t: &ParamType) -> &'static str {
    match t {
        ParamType::Real => "f",
        ParamType::Integer | ParamType::Enum(_) | ParamType::Price(_) => "i",
    }
}

fn module_alias(func: &FuncDef) -> String {
    format!("m_{}", module_stem(func))
}

fn emit_probe(o: &mut String, func: &FuncDef, enums: &HashMap<String, EnumDef>) {
    let n = ts_names(&func.name);
    let m = module_alias(func);
    let quoted = |v: Vec<String>| v.iter().map(|s| format!("'{s}'")).collect::<Vec<_>>().join(", ");
    let ins = quoted(func.inputs.iter().map(|i| leg_kind(&i.name).to_string()).collect());
    let outs = quoted(func.outputs.iter().map(|x| out_kind(&x.param_type).to_string()).collect());
    let (open, fill) = if func.streaming {
        (format!("{m}.{}", n.open), format!("{m}.{}", n.open_and_fill))
    } else {
        ("null".to_string(), "null".to_string())
    };
    let _ = writeln!(o, "  {{");
    let _ = writeln!(o, "    name: '{}',", func.name);
    let _ = writeln!(o, "    batch: {m}.{},", n.public);
    let _ = writeln!(o, "    body: {m}.{},", n.body);
    let _ = writeln!(o, "    lookback: {m}.{},", n.lookback);
    let _ = writeln!(o, "    open: {open},");
    let _ = writeln!(o, "    fill: {fill},");
    let _ = writeln!(o, "    ins: [{ins}],");
    let _ = writeln!(o, "    outs: [{outs}],");
    let _ = writeln!(o, "    vectors: [");
    for v in vectors(func, enums, &TsSpelling) {
        let mut row = vec![format!("'{}'", v.label)];
        row.extend(v.values);
        let _ = writeln!(o, "      [{}],", row.join(", "));
    }
    let _ = writeln!(o, "    ],");
    let _ = writeln!(o, "  }},");
}

/// Write `<test_dir>/phantomIo.test.ts`.
#[allow(clippy::implicit_hasher)]
pub fn generate(funcs: &[FuncDef], enums: &HashMap<String, EnumDef>, test_dir: &Path) {
    let mut sorted: Vec<&FuncDef> = funcs.iter().collect();
    sorted.sort_by_key(|f| module_stem(f));

    let mut used: Vec<&String> = funcs
        .iter()
        .flat_map(|f| f.optional_inputs.iter())
        .filter_map(|p| match &p.param_type {
            ParamType::Enum(n) => Some(n),
            _ => None,
        })
        .collect();
    used.sort_unstable();
    used.dedup();

    let mut o = String::from(super::ta_abstract_c::LICENSE);
    o.push_str("\n/* Generated by ta_codegen \u{2014} do not edit. */\n\n");
    o.push_str("import assert from 'node:assert/strict';\n");
    o.push_str("import { readdirSync } from 'node:fs';\n");
    o.push_str("import { test } from 'node:test';\n\n");
    let mut runtime = vec!["Core", "RetCode", "TALibError"];
    runtime.extend(used.iter().map(|s| s.as_str()));
    runtime.sort_unstable();
    let _ = writeln!(o, "import {{ {} }} from '../src/index.ts';", runtime.join(", "));
    o.push_str("import { MInteger } from '../src/runtime/mInteger.ts';\n");
    for f in &sorted {
        let _ = writeln!(o, "import * as {} from '../src/func/{}.ts';", module_alias(f), module_stem(f));
    }
    o.push('\n');
    o.push_str(HARNESS);
    o.push_str("\nconst PROBES: Probe[] = [\n");
    for f in &sorted {
        emit_probe(&mut o, f, enums);
    }
    o.push_str("];\n\n");
    let _ = writeln!(o, "const CORPUS = {};", sorted.len());
    o.push_str(DRIVER);

    std::fs::create_dir_all(test_dir).unwrap();
    super::write_if_changed(&test_dir.join("phantomIo.test.ts"), &o, "phantomIo.test.ts", sorted.len());
}

const HARNESS: &str = r"type Fn = (...args: any[]) => any;
type Leg = 'open' | 'high' | 'low' | 'close' | 'volume' | 'inPeriods' | 'real';
type Probe = {
  name: string;
  batch: Fn;
  body: Fn;
  lookback: Fn;
  open: Fn | null;
  fill: Fn | null;
  ins: Leg[];
  outs: ('f' | 'i')[];
  vectors: [string, ...number[]][];
};
type Arr = Float64Array | Int32Array;

class PhantomAccess extends Error {}

const seen = { reads: 0, writes: 0, methods: 0 };
const violations: string[] = [];

function violate(msg: string): never {
  violations.push(msg);
  throw new PhantomAccess(msg);
}

/** The element index a property key names, or null: typed arrays treat every canonical numeric string as one. */
function elementIndex(key: string | symbol): number | null {
  if (typeof key !== 'string') return null;
  if (key === '-0') return -0;
  const n = Number(key);
  return String(n) === key ? n : null;
}

function inBounds(i: number, len: number): boolean {
  return Number.isInteger(i) && !Object.is(i, -0) && i >= 0 && i < len;
}

/** A method's index argument; a negative one is legal JS that counts from the end, which no body means. */
function bound(v: unknown, dflt: number, len: number, what: string): number {
  const x = v === undefined ? dflt : v;
  if (typeof x !== 'number' || !Number.isInteger(x) || x < 0 || x > len) {
    violate(`${what}: ${String(v)} outside 0..${len}`);
  }
  return x;
}

function guard<T extends Arr>(t: T, label: string): T {
  const len = t.length;
  const methods: Record<string, Fn> = {
    subarray(b?: number, e?: number): Arr {
      const lo = bound(b, 0, len, `${label}.subarray begin`);
      const hi = bound(e, len, len, `${label}.subarray end`);
      if (hi < lo) violate(`${label}.subarray(${lo}, ${hi})`);
      seen.methods++;
      return guard(t.subarray(lo, hi), `${label}[${lo}..${hi})`);
    },
    slice(b?: number, e?: number): Arr {
      const lo = bound(b, 0, len, `${label}.slice begin`);
      const hi = bound(e, len, len, `${label}.slice end`);
      if (hi < lo) violate(`${label}.slice(${lo}, ${hi})`);
      seen.methods++;
      return t.slice(lo, hi);
    },
    set(src: ArrayLike<number>, off?: number): void {
      const at = bound(off, 0, len, `${label}.set offset`);
      if (at + src.length > len) violate(`${label}.set: ${src.length} values at ${at}, length ${len}`);
      seen.methods++;
      t.set(src, at);
    },
    fill(v: number, b?: number, e?: number): T {
      const lo = bound(b, 0, len, `${label}.fill start`);
      const hi = bound(e, len, len, `${label}.fill end`);
      if (hi < lo) violate(`${label}.fill(${lo}, ${hi})`);
      seen.methods++;
      t.fill(v, lo, hi);
      return proxy;
    },
    copyWithin(to: number, b: number, e?: number): T {
      const dst = bound(to, 0, len, `${label}.copyWithin target`);
      const lo = bound(b, 0, len, `${label}.copyWithin start`);
      const hi = bound(e, len, len, `${label}.copyWithin end`);
      if (hi < lo || dst + (hi - lo) > len) violate(`${label}.copyWithin(${dst}, ${lo}, ${hi})`);
      seen.methods++;
      t.copyWithin(dst, lo, hi);
      return proxy;
    },
  };
  const proxy = new Proxy(t, {
    get(target, key) {
      const i = elementIndex(key);
      if (i !== null) {
        if (!inBounds(i, len)) violate(`${label}: read of [${String(key)}], length ${len}`);
        seen.reads++;
        return target[i];
      }
      if (typeof key === 'string' && Object.hasOwn(methods, key)) return methods[key];
      const v: unknown = Reflect.get(target, key, target);
      return typeof v === 'function' ? v.bind(target) : v;
    },
    set(target, key, value) {
      const i = elementIndex(key);
      if (i !== null) {
        if (!inBounds(i, len)) violate(`${label}: write of [${String(key)}], length ${len}`);
        seen.writes++;
        target[i] = value as number;
        return true;
      }
      return Reflect.set(target, key, value, target);
    },
  });
  return proxy;
}

function bar(leg: Leg, i: number): number {
  const base = 100 + 10 * Math.sin(i / 7) + 3 * Math.cos(i / 3);
  switch (leg) {
    case 'open':
      return base - 0.5;
    case 'high':
      return base + 2;
    case 'low':
      return base - 2;
    case 'close':
      return base + 0.5;
    case 'volume':
      return 1000 + i;
    case 'inPeriods':
      return i % 3 === 0 ? 1e5 : 5 + (i % 7);
    default:
      return base;
  }
}

function inputs(p: Probe, len: number, short = -1): Float64Array[] {
  return p.ins.map((leg, k) => {
    const n = k === short ? len - 1 : len;
    return guard(Float64Array.from({ length: n }, (_, i) => bar(leg, i)), `${p.name}.in${k}`);
  });
}

function outputs(p: Probe, len: number, short = -1): Arr[] {
  return p.outs.map((kind, k) => {
    const n = k === short ? len - 1 : len;
    return guard(kind === 'f' ? new Float64Array(n) : new Int32Array(n), `${p.name}.out${k}`);
  });
}

type Outcome =
  | { kind: 'ok'; begIdx: number; count: number }
  | { kind: 'code'; retCode: number }
  | { kind: 'thrown'; code: string }
  | { kind: 'access'; msg: string }
  | { kind: 'other'; msg: string };

function run(f: () => Outcome): Outcome {
  const before = violations.length;
  let out: Outcome;
  try {
    out = f();
  } catch (e) {
    if (e instanceof PhantomAccess) return { kind: 'access', msg: e.message };
    if (e instanceof TALibError) out = { kind: 'thrown', code: e.code };
    else out = { kind: 'other', msg: String(e) };
  }
  return violations.length > before ? { kind: 'access', msg: violations[before] } : out;
}

function callBody(p: Probe, endIdx: number, opts: number[], ins: Arr[], outs: Arr[]): Outcome {
  return run(() => {
    const beg = new MInteger();
    const nb = new MInteger();
    const rc = p.body(Core.DEFAULT, 0, endIdx, ...ins, ...opts, beg, nb, ...outs) as number;
    return rc === RetCode.SUCCESS ? { kind: 'ok', begIdx: beg.value, count: nb.value } : { kind: 'code', retCode: rc };
  });
}

function callBatch(p: Probe, startIdx: number, endIdx: number, opts: number[], ins: Arr[], outs: Arr[]): Outcome {
  return run(() => {
    const r = p.batch(startIdx, endIdx, ...ins, ...opts, ...outs) as { begIdx: number; count: number };
    return { kind: 'ok', begIdx: r.begIdx, count: r.count };
  });
}

function callStream(f: Fn, args: unknown[]): Outcome {
  return run(() => {
    const s = f(...args) as { outRange(): { begIdx: number; count: number } };
    const r = s.outRange();
    return { kind: 'ok', begIdx: r.begIdx, count: r.count };
  });
}

function show(o: Outcome): string {
  return JSON.stringify(o);
}

function lookbackOf(p: Probe, opts: number[]): number {
  return p.lookback(...opts) as number;
}
";

const DRIVER: &str = r"
test('the sweep covers every function module', () => {
  const modules = readdirSync(new URL('../src/func/', import.meta.url)).filter((f) => f.endsWith('.ts')).length;
  assert.equal(PROBES.length, CORPUS, 'probe count');
  assert.equal(PROBES.length, modules, 'a probe per module under src/func');
});

// The body over a range ending below the lookback, every array zero-length:
// a documented success with no values, so any access is a phantom one.
// Control: one bar longer must touch an array, or this sweep proves nothing.
test('a sub-lookback range touches no array', () => {
  const failures: string[] = [];
  const live = new Set<string>();
  let probed = 0;
  let noQuiet = 0;
  let quietCalls = 0;
  for (const p of PROBES) {
    for (const [label, ...opts] of p.vectors) {
      const lb = lookbackOf(p, opts);
      if (lb < 0) continue;
      const control = callBody(p, lb, opts, inputs(p, 0), outputs(p, 0));
      if (control.kind === 'access' || control.kind === 'thrown') live.add(p.name);
      else failures.push(`${p.name}[${label}] at endIdx == lookback ${lb} touched no array: ${show(control)}`);
      if (lb < 1) {
        if (label === 'defaults') noQuiet++;
        continue;
      }
      if (label === 'defaults') probed++;
      quietCalls++;
      const quiet = callBody(p, lb - 1, opts, inputs(p, 0), outputs(p, 0));
      if (quiet.kind !== 'ok' || quiet.count !== 0) {
        failures.push(`${p.name}[${label}] (lookback ${lb}, endIdx ${lb - 1}): ${show(quiet)}`);
      }
    }
  }
  assert.deepEqual(failures, []);
  assert.equal(probed + noQuiet, PROBES.length, 'every function probed or counted at its defaults');
  assert.ok(probed > 0 && noQuiet > 0, `both outcomes occur (${probed} probed, ${noQuiet} with lookback 0)`);
  assert.ok(quietCalls > 0);
  assert.deepEqual(PROBES.map((p) => p.name).filter((n) => !live.has(n)), [], 'the control fired for every function');
});

// The public tier with every input exactly `endIdx + 1` long and every output
// exactly the count it reports: a read past `endIdx` or a write past the count
// throws instead of reading undefined or dropping the store.
test('exactly sized batch arrays are never indexed out of range', () => {
  const failures: string[] = [];
  const touched = new Set<string>();
  let calls = 0;
  for (const p of PROBES) {
    const r0 = seen.reads;
    const w0 = seen.writes;
    for (const [label, ...opts] of p.vectors) {
      const lb = lookbackOf(p, opts);
      if (lb < 0) continue;
      const ranges: [number, number][] = [[0, lb], [0, lb + 5], [lb, lb + 4], [lb + 3, lb + 7], [lb + 4, lb + 4]];
      for (const [s, e] of ranges) {
        const beg = s > lb ? s : lb;
        const count = e - beg + 1;
        calls++;
        const got = callBatch(p, s, e, opts, inputs(p, e + 1), outputs(p, count));
        if (got.kind !== 'ok' || got.begIdx !== beg || got.count !== count) {
          failures.push(`${p.name}[${label}] over [${s}, ${e}] (lookback ${lb}): ${show(got)}, expected begIdx ${beg} count ${count}`);
        }
      }
    }
    if (seen.reads > r0 && seen.writes > w0) touched.add(p.name);
  }
  assert.deepEqual(failures, []);
  assert.ok(calls > PROBES.length);
  const untouched = PROBES.filter((p) => p.ins.length > 0 && !touched.has(p.name)).map((p) => p.name);
  assert.deepEqual(untouched, [], 'the body read a guarded input and wrote a guarded output for every function');
});

// Open and OpenAndFill over a history exactly `lookback + 1` and `lookback + 6`
// bars long, the fill outputs exactly `historyLen - lookback`.
test('exactly sized stream history and fill outputs are never indexed out of range', () => {
  const failures: string[] = [];
  const touched = new Set<string>();
  let refused = 0;
  let opened = 0;
  for (const p of PROBES) {
    if (p.open === null || p.fill === null) continue;
    const r0 = seen.reads;
    const w0 = seen.writes;
    for (const [label, ...opts] of p.vectors) {
      const lb = lookbackOf(p, opts);
      if (lb < 0) continue;
      for (const h of [lb + 1, lb + 6]) {
        const open = callStream(p.open, [...inputs(p, h), ...opts]);
        if (open.kind === 'thrown' && open.code === 'TA_BAD_PARAM' && label.includes('=')) {
          refused++;
          continue;
        }
        const fill = callStream(p.fill, [...inputs(p, h), ...opts, ...outputs(p, h - lb)]);
        for (const [what, got] of [['open', open], ['openAndFill', fill]] as const) {
          if (got.kind !== 'ok' || got.begIdx !== lb || got.count !== h - lb) {
            failures.push(`${p.name}[${label}] ${what} over ${h} bars (lookback ${lb}): ${show(got)}`);
          }
        }
        opened++;
      }
    }
    if (seen.reads > r0 && seen.writes > w0) touched.add(p.name);
  }
  assert.deepEqual(failures, []);
  assert.ok(opened > refused, `${opened} opened, ${refused} refused`);
  const untouched = PROBES.filter((p) => p.open !== null && p.ins.length > 0 && !touched.has(p.name)).map((p) => p.name);
  assert.deepEqual(untouched, [], 'the opener read a guarded history and filled a guarded output for every function');
  assert.ok(seen.methods > 0, 'no guarded subarray or set call was seen');
});

// At the defaults, one input or output one element short: the public tier must
// reject it before the body runs. Control: every array sized must produce values.
test('every declared input and output is length-checked before the body', () => {
  const failures: string[] = [];
  let legs = 0;
  let swept = 0;
  for (const p of PROBES) {
    const opts = p.vectors[0].slice(1) as number[];
    const lb = lookbackOf(p, opts);
    if (lb < 0) {
      failures.push(`${p.name}: the lookback rejects its own defaults`);
      continue;
    }
    const [s, e] = [lb, lb + 4];
    const control = callBatch(p, s, e, opts, inputs(p, e + 1), outputs(p, 5));
    if (control.kind !== 'ok' || control.count !== 5) {
      failures.push(`${p.name} with every array sized: ${show(control)}`);
      continue;
    }
    swept++;
    const cases: [string, Arr[], Arr[]][] = [
      ...p.ins.map((_, k): [string, Arr[], Arr[]] => [`in${k}`, inputs(p, e + 1, k), outputs(p, 5)]),
      ...p.outs.map((_, k): [string, Arr[], Arr[]] => [`out${k}`, inputs(p, e + 1), outputs(p, 5, k)]),
    ];
    for (const [what, ins, outs] of cases) {
      legs++;
      const got = callBatch(p, s, e, opts, ins, outs);
      if (got.kind !== 'thrown' || got.code !== 'TA_BAD_PARAM') {
        failures.push(`${p.name}.${what} one element short: ${show(got)}, expected TA_BAD_PARAM`);
      }
    }
  }
  assert.deepEqual(failures, []);
  assert.equal(swept, PROBES.length);
  assert.ok(legs > PROBES.length);
});
";
