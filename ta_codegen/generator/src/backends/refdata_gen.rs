//! Generate `src/tools/ta_refdata/ta_refdata_domains.h`: every real input that
//! declares a synthetic `series`, with its kind and `domain`, as a C table
//! `ta_refdata` builds the input column from.

use std::fmt::Write as _;
use std::path::Path;

use super::write_if_changed;
use crate::ir::{FuncDef, Series};

/// `(function, input, series, lo, hi)` for every input with a synthetic series,
/// sorted by function then input name.
fn rows(funcs: &[FuncDef]) -> Vec<(&str, &str, Series, f64, f64)> {
    let mut rows: Vec<(&str, &str, Series, f64, f64)> = funcs
        .iter()
        .flat_map(|f| {
            f.inputs.iter().filter_map(move |i| {
                i.domain.map(|(lo, hi)| (f.name.as_str(), i.name.as_str(), i.series, lo, hi))
            })
        })
        .collect();
    rows.sort_by(|a, b| (a.0, a.1).cmp(&(b.0, b.1)));
    rows
}

/// A `NULL` row terminates the table, so the C side needs no `sizeof` and an empty
/// set is still a well-formed initializer. The series is its YAML token's first
/// letter: `'r'` ramp, `'s'` sine.
fn render(rows: &[(&str, &str, Series, f64, f64)]) -> String {
    let mut o = String::from("/* Generated by ta_codegen: do not edit */\n");
    o.push_str("static const struct { const char *func, *input; char series; double lo, hi; } REFDATA_DOMAIN[] = {\n");
    for (func, input, series, lo, hi) in rows {
        let kind = series.token().chars().next().unwrap_or('?');
        let _ = writeln!(o, "    {{ \"{func}\", \"{input}\", '{kind}', {lo:?}, {hi:?} }},");
    }
    o.push_str("    { NULL, NULL, 0, 0.0, 0.0 }\n};\n");
    o
}

/// Write `src/tools/ta_refdata/ta_refdata_domains.h`.
pub fn generate(funcs: &[FuncDef], root: &Path) {
    let rows = rows(funcs);
    let path = root.join("src/tools/ta_refdata/ta_refdata_domains.h");
    write_if_changed(&path, &render(&rows), "ta_refdata_domains.h", rows.len());
}

#[cfg(test)]
mod tests {
    use super::render;
    use crate::ir::Series;

    #[test]
    fn rows_render_as_c_initializers_with_a_null_terminator() {
        let text = render(&[("ACOS", "inReal", Series::Ramp, -1.0, 1.0), ("ADD", "inReal0", Series::Sine, 90.0, 110.0)]);
        assert!(text.starts_with("/* Generated by ta_codegen: do not edit */\n"));
        assert!(text.contains("char series; double lo, hi; } REFDATA_DOMAIN[] = {\n"));
        assert!(text.contains("    { \"ACOS\", \"inReal\", 'r', -1.0, 1.0 },\n"));
        assert!(text.contains("    { \"ADD\", \"inReal0\", 's', 90.0, 110.0 },\n"));
        assert!(text.ends_with("    { NULL, NULL, 0, 0.0, 0.0 }\n};\n"));
    }

    #[test]
    fn an_empty_set_is_still_a_valid_initializer() {
        let text = render(&[]);
        assert!(text.contains("[] = {\n    { NULL, NULL, 0, 0.0, 0.0 }\n};\n"));
    }
}
