//! Generate `src/tools/ta_refdata/ta_refdata_domains.h`: the `domain` of every
//! real input that declares one, as a C table `ta_refdata` maps the close into.

use std::fmt::Write as _;
use std::path::Path;

use super::write_if_changed;
use crate::ir::FuncDef;

/// `(function, input, lo, hi)` for every input carrying a `domain`, sorted by function
/// then input name.
fn rows(funcs: &[FuncDef]) -> Vec<(&str, &str, f64, f64)> {
    let mut rows: Vec<(&str, &str, f64, f64)> = funcs
        .iter()
        .flat_map(|f| {
            f.inputs
                .iter()
                .filter_map(move |i| i.domain.map(|(lo, hi)| (f.name.as_str(), i.name.as_str(), lo, hi)))
        })
        .collect();
    rows.sort_by(|a, b| (a.0, a.1).cmp(&(b.0, b.1)));
    rows
}

/// A `NULL` row terminates the table, so the C side needs no `sizeof` and an empty
/// set is still a well-formed initializer.
fn render(rows: &[(&str, &str, f64, f64)]) -> String {
    let mut o = String::from("/* Generated by ta_codegen: do not edit */\n");
    o.push_str("static const struct { const char *func, *input; double lo, hi; } REFDATA_DOMAIN[] = {\n");
    for (func, input, lo, hi) in rows {
        let _ = writeln!(o, "    {{ \"{func}\", \"{input}\", {lo:?}, {hi:?} }},");
    }
    o.push_str("    { NULL, NULL, 0.0, 0.0 }\n};\n");
    o
}

/// Write `src/tools/ta_refdata/ta_refdata_domains.h`.
pub fn generate(funcs: &[FuncDef], root: &Path) {
    let rows = rows(funcs);
    let path = root.join("src/tools/ta_refdata/ta_refdata_domains.h");
    write_if_changed(&path, &render(&rows), "ta_refdata_domains.h", rows.len());
}

#[cfg(test)]
mod tests {
    use super::render;

    #[test]
    fn rows_render_as_c_initializers_with_a_null_terminator() {
        let text = render(&[("ACOS", "inReal", -1.0, 1.0), ("TANH", "inReal", -3.0, 3.0)]);
        assert!(text.starts_with("/* Generated by ta_codegen: do not edit */\n"));
        assert!(text.contains("    { \"ACOS\", \"inReal\", -1.0, 1.0 },\n"));
        assert!(text.contains("    { \"TANH\", \"inReal\", -3.0, 3.0 },\n"));
        assert!(text.ends_with("    { NULL, NULL, 0.0, 0.0 }\n};\n"));
    }

    #[test]
    fn an_empty_set_is_still_a_valid_initializer() {
        let text = render(&[]);
        assert!(text.contains("[] = {\n    { NULL, NULL, 0.0, 0.0 }\n};\n"));
    }
}
