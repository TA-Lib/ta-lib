//! Generates the TypeScript `src/enums.ts`: `MAType` and `FuncUnstId` as
//! `as const` objects, each with its sibling `<Name>s` bounds object.

use crate::ir::{EnumDef, FuncDef};
use crate::registry::Lang;
use std::collections::HashMap;
use std::fmt::Write as _;
use std::path::Path;

#[allow(clippy::implicit_hasher)]
pub fn generate(funcs: &[FuncDef], enums: &HashMap<String, EnumDef>, path: &Path) {
    let s = render(funcs, enums);
    super::write_if_changed(path, &s, "enums.ts", enums.len());
}

/// Both enums in one module: the function modules and `core.ts` import them
/// together, and neither carries logic.
#[allow(clippy::implicit_hasher)]
#[must_use]
pub fn render(funcs: &[FuncDef], enums: &HashMap<String, EnumDef>) -> String {
    let ma = enums.get("MAType").expect("MAType enum missing from enums.yaml");
    let fu = enums.get("FuncUnstId").expect("FuncUnstId enum missing from enums.yaml");

    let mut s = super::ts::ts_license();
    s.push_str("\n/* Generated by ta_codegen from enums.yaml \u{2014} do not edit. */\n\n");

    s.push_str("/** Moving-average type, the value of a `maType` option. */\n");
    s.push_str("export const MAType = Object.freeze({\n");
    for (i, v) in ma.variants.iter().enumerate() {
        assert_eq!(
            i32::try_from(i).unwrap(),
            v.value,
            "MAType values must be contiguous from 0 ({} breaks the sequence)",
            v.c_name
        );
        let summary = super::common::ma_pseudo_member_doc(&v.name).map_or_else(
            || {
                funcs
                    .iter()
                    .find(|f| f.name == v.name)
                    .and_then(|f| f.hint.as_deref())
                    .map_or_else(|| format!("The `{}` moving average.", v.c_name), |h| format!("{h}."))
            },
            str::to_string,
        );
        let _ = writeln!(s, "  /** {summary} */\n  {}: {},", v.name, v.value);
    }
    s.push_str("} as const);\n");
    s.push_str("/** A member of {@link MAType}. */\n");
    s.push_str("export type MAType = (typeof MAType)[keyof typeof MAType];\n");
    if super::common::param_enum_names(funcs).contains(&ma.name) {
        s.push_str(&render_limits(ma));
    }

    s.push_str("\n/** Identifies a function whose unstable period can be set. */\n");
    s.push_str("export const FuncUnstId = Object.freeze({\n");
    for (i, v) in fu.variants.iter().enumerate() {
        assert_eq!(
            i32::try_from(i).unwrap(),
            v.value,
            "FuncUnstId values must be contiguous from 0 ({} breaks the sequence)",
            v.c_name
        );
        if v.reserved {
            continue;
        }
        let _ = writeln!(
            s,
            "  /** Unstable-period id of `{}`. */\n  {}: {},",
            super::ts::func_ident(&v.name),
            v.name,
            v.value
        );
    }
    s.push_str("  /** Wildcard: every function at once. Pinned, so adding an indicator never moves it. */\n");
    s.push_str("  ALL: 65535,\n");
    s.push_str("} as const);\n");
    s.push_str("/** A member of {@link FuncUnstId}. */\n");
    s.push_str("export type FuncUnstId = (typeof FuncUnstId)[keyof typeof FuncUnstId];\n\n");
    s.push_str("/** @internal */\n");
    s.push_str("export const FuncUnstIds = Object.freeze({\n");
    s.push_str("  /** Size of the unstable-period table; mirrors C's `TA_FUNC_UNST_COUNT`. */\n");
    let _ = writeln!(s, "  Count: {},", fu.variants.len());
    s.push_str("} as const);\n");
    s
}

fn render_limits(def: &EnumDef) -> String {
    let (lo, hi) = super::common::enum_value_bounds_of(def).expect("a parameter enum has members");
    let (min_name, max_name) =
        super::common::enum_limit_names_of(def, Lang::Ts).expect("TS declares enum limits");
    let (object, min_member) = min_name.split_once('.').expect("qualified limit name");
    let (_, max_member) = max_name.split_once('.').expect("qualified limit name");
    let ty = &def.name;
    format!(
        "\n/** @internal Bounds of the domain a {{@link {ty}}} parameter accepts; not members. */\n\
         export const {object} = Object.freeze({{\n  {min_member}: {lo},\n  {max_member}: {hi},\n}} as const);\n"
    )
}
