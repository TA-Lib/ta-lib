//! Assembles the shipped `java/library/src/io/github/talib/Core.java` GENCODE section
//! from the per-indicator Java methods — ta_codegen's takeover of gen_code's role
//! for the shipped Java library.
//!
//! The per-indicator method text is the SAME output the JSON-RPC Java server
//! inlines (so numerical correctness is already proven by `ta_regtest --codegen`);
//! here it is spliced between the `GENCODE SECTION 1` markers, preserving the
//! hand-written scaffolding (license, immutable fields, builder entry points,
//! candle/unstable-period accessors) outside them. Each indicator contributes a
//! public lookback, the package-private `xxxInternal` core (and, where
//! applicable, `xxxPrivate`), plus the public `OutRange`-returning `xxx`
//! wrapper over it.

use std::collections::HashMap;
use std::path::Path;

use crate::helper_registry::HelperRegistry;
use crate::ir::{EnumDef, FuncDef};
use crate::registry::Registry;

const CORE_START: &str = "/**** START GENCODE SECTION 1 - DO NOT DELETE THIS LINE ****/";
const CORE_END: &str = "/**** END GENCODE SECTION 1 - DO NOT DELETE THIS LINE ****/";

/// Digest of the generated Java method text, as the stamp both artifacts carry.
///
/// FNV-1a over RAW bytes: the fragments concatenate byte-identically to the
/// GENCODE section, so there is nothing to normalize away and a whitespace-only
/// drift is caught rather than excused. Not a cryptographic hash and must not
/// become one -- nothing here defends against a forged stamp, it only has to
/// move when the text moves.
pub fn gencode_digest(text: &str) -> String {
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for b in text.as_bytes() {
        h ^= u64::from(*b);
        h = h.wrapping_mul(0x0000_0100_0000_01b3);
    }
    format!("{h:016x}")
}

/// Concatenate the on-disk fragments the Java server splices, in `funcs` order.
///
/// The server's stamp is computed from THIS, and `Core.java`'s from the freshly
/// rendered section, so the two agree only when the shipped library really is
/// the text the server was spliced from. Reading the disk rather than
/// re-rendering is the whole point: a re-render could not see staleness.
pub fn fragments_text(frag_dir: &Path, funcs: &[FuncDef]) -> String {
    let mut all = String::new();
    for func in funcs {
        let path = frag_dir.join(format!("Core_{}.java", func.name));
        match std::fs::read_to_string(&path) {
            Ok(text) => all.push_str(&text),
            // A missing fragment must not silently shorten the digest into
            // some other tree's value: make it its own text, so the stamp
            // still differs from the shipped one and the gate names it.
            Err(e) => all.push_str(&format!("<<missing {}: {e}>>", path.display())),
        }
    }
    all
}

/// Emit `BuildStamp.java` -- the shipped half of the pair `ta_regtest` compares.
///
/// A file of its own because the digest covers the GENCODE section: a constant
/// inside that section would be hashing itself, and everything outside the
/// markers in `Core.java` is hand-written and preserved. Public because the
/// Java server reaches it from the default package (#322).
pub fn generate_build_stamp(digest: &str, pkg_dir: &Path) {
    let text = format!(
        "/* Auto-generated by ta_codegen. DO NOT EDIT. */\n\
         package io.github.talib;\n\
         \n\
         /**\n\
         \x20* Build provenance for the generated indicator methods in {{@link Core}}.\n\
         \x20*\n\
         \x20* <p>The cross-language harness compares this against the copy spliced into\n\
         \x20* its Java server: equal means the server really is measuring this library.\n\
         \x20*/\n\
         public final class BuildStamp {{\n\
         \x20   /** Digest of the generated {{@code Core}} method text this build carries. */\n\
         \x20   public static final String GENCODE_DIGEST = \"{digest}\";\n\
         \n\
         \x20   private BuildStamp() {{\n\
         \x20   }}\n\
         }}\n"
    );
    super::write_if_changed(&pkg_dir.join("BuildStamp.java"), &text, "BuildStamp.java", 1);
}

/// Fail if the shipped stamp is not the one these fragments hash to.
///
/// Absent stamp is NOT a failure: a fresh tree has none until `generate_core`
/// writes one, and a full run writes it before this is reached.
pub fn assert_stamp_matches(out_base: &Path, digest: &str) {
    let path = out_base.join("java/library/src/main/java/io/github/talib/BuildStamp.java");
    let Ok(text) = std::fs::read_to_string(&path) else {
        return;
    };
    let Some(shipped) = text
        .split_once("GENCODE_DIGEST = \"")
        .and_then(|(_, rest)| rest.split_once('"'))
        .map(|(v, _)| v)
    else {
        return;
    };
    assert!(
        shipped == digest,
        "the shipped Java library is not the text this server is being spliced from \
         (fragments {digest}, {} {shipped}).\n  A `generate --func=<NAME>` run \
         deliberately skips Core.java, which is how the two part.\n  Recover with: \
         scripts/build.py generate",
        path.display()
    );
}

/// Splice the generated indicator methods into `Core.java`'s GENCODE section.
#[allow(clippy::implicit_hasher)]
pub fn generate_core(
    funcs: &[FuncDef],
    enums: &HashMap<String, EnumDef>,
    registry: &Registry,
    helpers: &HelperRegistry,
    core_path: &Path,
) {
    let mut section = String::new();
    for func in funcs {
        section.push_str(&super::java::generate(func, enums, registry, helpers));
    }

    let existing = std::fs::read_to_string(core_path)
        .unwrap_or_else(|e| panic!("reading {}: {e}", core_path.display()));
    let start = existing
        .find(CORE_START)
        .unwrap_or_else(|| panic!("START GENCODE marker missing in {}", core_path.display()));
    // Keep everything up to and including the START marker line (the marker text
    // is preceded by its hand-written 3-space indent, which stays untouched).
    let after_start = existing[start..]
        .find('\n')
        .map_or(existing.len(), |i| start + i + 1);
    let end = existing
        .find(CORE_END)
        .unwrap_or_else(|| panic!("END GENCODE marker missing in {}", core_path.display()));
    // Resume at the start of the END marker line, preserving its indent + the rest.
    let end_line = existing[..end].rfind('\n').map_or(0, |i| i + 1);

    let new = format!("{}{}{}", &existing[..after_start], section, &existing[end_line..]);
    super::write_if_changed(core_path, &new, "Core.java (GENCODE)", funcs.len());

    // Stamp what was just written. Computed from `section` -- the text actually
    // spliced in -- so the constant cannot outlive the methods it describes.
    if let Some(pkg_dir) = core_path.parent() {
        generate_build_stamp(&gencode_digest(&section), pkg_dir);
    }
}

