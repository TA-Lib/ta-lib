/* Description:
 *
 *   Test TA_BBW (Bollinger BandWidth): (upper - lower) / middle over the
 *   bands TA_BBANDS returns, and +0.0 where the middle band is 0.
 *
 *   Legs:
 *     1. Goldens: the exact value, from code that never runs TA-Lib.
 *     2. Composition: bitwise equal to (U - L) / M over TA_BBANDS' outputs
 *        at every MA type, deviation pair, startIdx and unstable period, and
 *        TA_S_BBW against TA_S_BBANDS. Only this leg sees a change that moves
 *        the last bit.
 *     3. Bollinger's rule 18, through TA_STDDEV and TA_MA.
 *     4. The lookback tier against TA_BBANDS_Lookback, unstable periods too.
 *     5. In-place, across a periodic rebuild and a tile boundary.
 *     6. startIdx-anchored calls equal the series cut at startIdx - lookback.
 *     7. The parameter ranges and the defaults.
 *     8. Flat, zero and alternating windows, bar by bar, sign included.
 *
 *   WHAT EACH LEG CAN SEE, measured by mutating ta_codegen/input/bbw/bbw.c
 *   (the default, bbw.yaml) and regenerating: every leg that went red.
 *
 *     SMA window's trailing index one bar late     1 2 3 8
 *     general path's variance over n-1 bars        1 2 3 4 8
 *     width over the upper band                    1 2 3
 *     middle band as maTotal * (1/n)               2
 *     middle == 0 guard dropped, SMA path          1 2 8, test_abstract
 *     middle == 0 guard dropped, general path      2 8
 *     sample variance, n/(n-1)                     1 2 3
 *     startIdx summed twice into the seed          1 2 3 8
 *     newest bar dropped from a rebuild            1 2 3
 *     default period 21                            3 7
 *     lookback + 1                                 2 4 6 7, test_abstract
 *     lookback restated as n - 1                   2 3 4 8
 *     variance entered at startIdx                 1 2 3 4 8
 *     the fold (kUp + kDn) * sd / M                2
 *     equal-k branch dropped                       2
 *     offset 0 on the general path                 2 3
 *     |middle| < 1e-14 as the guard                1 2
 *     middle <= 0 as the guard                     1 2 8
 *     variance slot stored before a rebuild        5
 *     2*kUp in place of kUp + kDn                  1 2 3
 *
 *   No leg sees 255-bar tiles for 256: the tile only sets where the width
 *   pass splits the output.
 *
 *   SERVER_VERIFY: every golden call but the two 100500-bar ones, which do not
 *   fit server_verify's 256 KB request; leg 2 routes the 3000-bar walk once per
 *   MA type and under each unstable period, leg 6 one anchored call per MA
 *   type.
 */

