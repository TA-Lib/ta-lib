static ErrorNumber bbw_route( const char *tag, int startIdx, int endIdx,
                              const double *x, int nbBars,
                              int n, double kUp, double kDn, TA_MAType maType,
                              TA_RetCode retCode, int beg, int nb, const double *out )
{
   double optIn[4];
   int before;
   ErrorNumber err;

   if( !server_verify_active() )
      return TA_TEST_PASS;

   optIn[0] = (double)n;
   optIn[1] = kUp;
   optIn[2] = kDn;
   optIn[3] = (double)maType;
   before = server_verify_value_comparisons();
   err = server_verify( "BBW", startIdx, endIdx, nbBars, retCode, beg, nb,
                        (const TA_Real*[]){ x, NULL }, optIn, 4,
                        (const TA_Real*[]){ out, NULL }, NULL );
   if( err != TA_TEST_PASS )
      return err;
   if( server_verify_value_comparisons() == before )
   {
      printf( "BBW %s: server_verify compared no server despite live pipes\n", tag );
      return TA_SV_ROUTED_VACUOUS;
   }
   return TA_TEST_PASS;
}

/* (1) */
static ErrorNumber test_bbw_goldens( void )
{
   static double out[BBW_CAP];
   TA_RetCode retCode;
   TA_Integer beg, nb;
   ErrorNumber err;
   int k, r;

   for( k = 0; k < NB_BBW_GOLDENS; k++ )
   {
      const BbwGolden *g = &bbwGoldens[k];
      const BbwSeries *s = &bbwSeries[g->series];

      TA_SetUnstablePeriod( TA_FUNC_UNST_EMA, g->unstEma );
      beg = nb = -1;
      retCode = TA_BBW( g->startIdx, g->endIdx, s->x, g->n, g->kUp, g->kDn, g->maType,
                        &beg, &nb, out );
      if( retCode != TA_SUCCESS || beg != g->beg || nb != g->nb )
      {
         printf( "BBW golden Fail [%s]: rc=%d (%d,%d), expected (%d,%d)\n",
                 g->tag, (int)retCode, beg, nb, g->beg, g->nb );
         return TA_TESTUTIL_TFRR_BAD_BEGIDX;
      }

      for( r = 0; r < g->nbRows; r++ )
      {
         const BbwRow *row = &g->rows[r];
         double got;

         if( row->bar < beg || row->bar - beg >= nb )
         {
            printf( "BBW golden Fail [%s]: golden bar %d is outside the output [%d..%d]\n",
                    g->tag, row->bar, beg, beg + nb - 1 );
            return TA_TESTUTIL_TFRR_BAD_PARAM;
         }
         got = out[row->bar - beg];

         g_bbwGoldenCmp++;
         if( ( row->mid0 || row->tol == 0.0 )
             ? !bbw_same( got, row->exact )
             : !( fabs( got - row->exact ) <= row->tol ) )
         {
            printf( "BBW golden Fail [%s] at bar %d: got %.17g, exact %.17g "
                    "(capture_447_bbw.py; |diff| %.3g over %.3g%s)\n",
                    g->tag, row->bar, got, row->exact, fabs( got - row->exact ), row->tol,
                    row->mid0 ? ", middle == 0 is +0.0" : ( row->tol == 0.0 ? ", bitwise" : "" ) );
            return TA_TESTUTIL_TFRR_BAD_CALCULATION;
         }
      }

      if( s->nbBars <= BBW_SV_MAX_BARS )
      {
         err = bbw_route( g->tag, g->startIdx, g->endIdx, s->x, s->nbBars, g->n, g->kUp,
                          g->kDn, g->maType, retCode, beg, nb, out );
         if( err != TA_TEST_PASS )
            return err;
      }
      TA_SetUnstablePeriod( TA_FUNC_UNST_EMA, 0 );
   }

   return TA_TEST_PASS;
}

/* TA_BBW against ((U - L) / M) * 100 over TA_BBANDS' outputs, bitwise; +0.0
 * where M == 0.0, the one bar the composition cannot give (it is +-Inf or NaN
 * there). */
static ErrorNumber bbw_vs_bbands( const char *tag, const BbwSeries *s,
                                  int startIdx, int endIdx, int n,
                                  double kUp, double kDn, TA_MAType maType )
{
   static double up[BBW_CAP], mid[BBW_CAP], lo[BBW_CAP], got[BBW_CAP];
   TA_RetCode rcB, rcW;
   TA_Integer begB, nbB, begW, nbW;
   double want;
   int i;

   rcB = TA_BBANDS( startIdx, endIdx, s->x, n, kUp, kDn, maType, &begB, &nbB, up, mid, lo );
   begW = nbW = -1;
   rcW = TA_BBW( startIdx, endIdx, s->x, n, kUp, kDn, maType, &begW, &nbW, got );
   if( rcB != TA_SUCCESS || rcW != rcB || begW != begB || nbW != nbB )
   {
      printf( "BBW %s Fail [%s n=%d k=(%g,%g) matype=%d start=%d end=%d]: BBW rc=%d (%d,%d), "
              "BBANDS rc=%d (%d,%d)\n", tag, s->name, n, kUp, kDn, (int)maType, startIdx,
              endIdx, (int)rcW, begW, nbW, (int)rcB, begB, nbB );
      return TA_TESTUTIL_TFRR_BAD_BEGIDX;
   }

   for( i = 0; i < nbB; i++ )
   {
      want = ( mid[i] == 0.0 ) ? 0.0 : ( ( up[i] - lo[i] ) / mid[i] ) * 100.0;
      if( mid[i] == 0.0 )
         g_bbwDiffMid0++;
      g_bbwDiffCmp++;
      if( !bbw_same( got[i], want ) )
      {
         printf( "BBW %s Fail [%s n=%d k=(%g,%g) matype=%d start=%d end=%d] at bar %d: "
                 "%.17g, TA_BBANDS gives %.17g (U %.17g, M %.17g, L %.17g)\n", tag,
                 s->name, n, kUp, kDn, (int)maType, startIdx, endIdx, begB + i, got[i],
                 want, up[i], mid[i], lo[i] );
         return TA_TESTUTIL_TFRR_BAD_CALCULATION;
      }
   }

   return TA_TEST_PASS;
}

/* The 3000-bar walk crosses the SMA path's tiles and a 32n rebuild. MAMA
 * sends Java down the element-by-element compare, which takes at most 512
 * outputs. */
static ErrorNumber bbw_route_walk( const char *tag, TA_MAType maType )
{
   static double out[BBW_CAP];
   const BbwSeries *s = &bbwSeries[BBW_WALK];
   const int endIdx = maType == TA_MAType_MAMA ? 540 : BBW_WALK_N-1;
   TA_Integer beg, nb;
   TA_RetCode rc;

   if( !server_verify_active() )
      return TA_TEST_PASS;
   rc = TA_BBW( 0, endIdx, s->x, 20, 2.5, 1.5, maType, &beg, &nb, out );
   return bbw_route( tag, 0, endIdx, s->x, BBW_WALK_N, 20, 2.5, 1.5, maType, rc, beg, nb, out );
}

static int bbw_starts( int n, int lookback, int last, int *starts )
{
   const int cand[8] = { 0, 1, n-1, n, lookback, lookback+1, 300, last };
   int k, j, m = 0;

   for( k = 0; k < 8; k++ )
   {
      if( cand[k] < 0 || cand[k] > last )
         continue;
      for( j = 0; j < m && starts[j] != cand[k]; j++ )
         ;
      if( j == m )
         starts[m++] = cand[k];
   }
   return m;
}

/* (2) The decisive leg. Every tolerance-based leg passes the algebraic fold
 * (kUp + kDn) * sd * 100 / M, the width scaled before the divide, a dropped
 * equal-k branch and a multiply by 1/n for the middle band's divide. */
static ErrorNumber test_bbw_composition( void )
{
   static const int counts[] = { 1, 255, 256, 257, 511, 512, 513 };
   static float xf[252];
   const BbwSeries *s;
   ErrorNumber err;
   int d, mt, k, p, t, u, m, n, lookback, last, nbStarts, starts[8];

   for( d = 0; d < NB_BBW_DIFF_SERIES; d++ )
   {
      s = &bbwSeries[bbwDiffSeries[d]];
      last = s->nbBars - 1;
      for( mt = 0; mt < BBW_NB_MATYPE; mt++ )
      for( k = 0; k < NB_BBW_K; k++ )
      for( p = 0; p < NB_BBW_PERIODS; p++ )
      {
         n = bbwPeriods[p];
         lookback = TA_BBANDS_Lookback( n, bbwK[k][0], bbwK[k][1], (TA_MAType)mt );
         nbStarts = bbw_starts( n, lookback, last, starts );
         for( t = 0; t < nbStarts; t++ )
         {
            err = bbw_vs_bbands( "composition", s, starts[t], last, n,
                                 bbwK[k][0], bbwK[k][1], (TA_MAType)mt );
            if( err != TA_TEST_PASS )
               return err;
         }
      }
   }

   /* The SMA path's 256-bar tile, on each side of one and two boundaries. */
   s = &bbwSeries[BBW_WALK];
   for( p = 0; p < 2; p++ )
   for( t = 0; t < 2; t++ )
   for( m = 0; m < (int)(sizeof(counts)/sizeof(counts[0])); m++ )
   {
      int startIdx = t == 0 ? 0 : 300;
      int first = startIdx < 19 ? 19 : startIdx;

      k = bbwKBranch[p];
      err = bbw_vs_bbands( "tile", s, startIdx, first + counts[m] - 1, 20,
                           bbwK[k][0], bbwK[k][1], TA_MAType_SMA );
      if( err != TA_TEST_PASS )
         return err;
   }

   /* startIdx 0 below a warmed-up lookback is where the variance must be
    * entered at the moving average's begIdx, not at startIdx. */
   for( u = 0; u < NB_BBW_UNST; u++ )
   {
      static const unsigned int periods[] = { 3, 40 };
      static const int ns[] = { 5, 20, 34 };
      int up, dd, np;

      for( up = 0; up < 2; up++ )
      {
         TA_SetUnstablePeriod( bbwUnst[u].id, periods[up] );
         for( dd = 0; dd < 2; dd++ )
         for( np = 0; np < 3; np++ )
         for( m = 0; m < 2; m++ )
         {
            k = bbwKBranch[m];
            s = &bbwSeries[dd == 0 ? BBW_CORPUS : BBW_WALK];
            last = s->nbBars - 1;
            n = ns[np];
            lookback = TA_BBANDS_Lookback( n, bbwK[k][0], bbwK[k][1], bbwUnst[u].maType );
            nbStarts = bbw_starts( n, lookback, last, starts );
            for( t = 0; t < nbStarts; t++ )
            {
               err = bbw_vs_bbands( "unstable composition", s, starts[t], last, n,
                                    bbwK[k][0], bbwK[k][1], bbwUnst[u].maType );
               if( err != TA_TEST_PASS )
                  return err;
            }
         }

         if( up == 1 )
         {
            err = bbw_route_walk( "walk, unstable 40", bbwUnst[u].maType );
            if( err != TA_TEST_PASS )
               return err;
         }
         TA_SetUnstablePeriod( bbwUnst[u].id, 0 );
      }
   }

   /* The period at its maximum. */
   s = &bbwSeries[BBW_LONG];
   for( t = 0; t < 3; t++ )
   {
      static const int longStarts[] = { 0, 99999, 100250 };

      err = bbw_vs_bbands( "n=100000", s, longStarts[t], BBW_LONG_N-1, 100000, 2.0, 2.0,
                           TA_MAType_SMA );
      if( err != TA_TEST_PASS )
         return err;
      err = bbw_vs_bbands( "n=100000", s, longStarts[t], BBW_LONG_N-1, 100000, 2.5, 1.5,
                           TA_MAType_EMA );
      if( err != TA_TEST_PASS )
         return err;
   }

   for( mt = 0; mt < BBW_NB_MATYPE; mt++ )
   {
      err = bbw_route_walk( "walk", (TA_MAType)mt );
      if( err != TA_TEST_PASS )
         return err;
   }

   /* The single-precision tier against its own TA_S_BBANDS. */
   for( k = 0; k < 252; k++ )
      xf[k] = (float)bbwSeries[BBW_CORPUS].x[k];
   for( mt = 0; mt < BBW_NB_MATYPE; mt++ )
   for( m = 0; m < 2; m++ )
   for( p = 1; p <= 2; p++ )
   for( t = 0; t < 2; t++ )
   {
      static double up[BBW_CAP], mid[BBW_CAP], lo[BBW_CAP], got[BBW_CAP];
      TA_Integer begB, nbB, begW, nbW;
      TA_RetCode rcB, rcW;
      double want;
      int i, startIdx;

      k = bbwKBranch[m];
      n = bbwPeriods[p];
      lookback = TA_BBANDS_Lookback( n, bbwK[k][0], bbwK[k][1], (TA_MAType)mt );
      startIdx = t == 0 ? 0 : lookback + 1;
      rcB = TA_S_BBANDS( startIdx, 251, xf, n, bbwK[k][0], bbwK[k][1], (TA_MAType)mt,
                         &begB, &nbB, up, mid, lo );
      begW = nbW = -1;
      rcW = TA_S_BBW( startIdx, 251, xf, n, bbwK[k][0], bbwK[k][1], (TA_MAType)mt,
                      &begW, &nbW, got );
      if( rcB != TA_SUCCESS || rcW != rcB || begW != begB || nbW != nbB )
      {
         printf( "BBW float Fail [n=%d k=(%g,%g) matype=%d start=%d]: TA_S_BBW rc=%d (%d,%d), "
                 "TA_S_BBANDS rc=%d (%d,%d)\n", n, bbwK[k][0], bbwK[k][1], mt, startIdx,
                 (int)rcW, begW, nbW, (int)rcB, begB, nbB );
         return TA_TESTUTIL_TFRR_BAD_BEGIDX;
      }
      for( i = 0; i < nbB; i++ )
      {
         want = ( mid[i] == 0.0 ) ? 0.0 : ( ( up[i] - lo[i] ) / mid[i] ) * 100.0;
         g_bbwFloatCmp++;
         if( !bbw_same( got[i], want ) )
         {
            printf( "BBW float Fail [n=%d k=(%g,%g) matype=%d start=%d] at bar %d: %.17g, "
                    "TA_S_BBANDS gives %.17g\n", n, bbwK[k][0], bbwK[k][1], mt, startIdx,
                    begB + i, got[i], want );
            return TA_TESTUTIL_TFRR_BAD_CALCULATION;
         }
      }
   }

   return TA_TEST_PASS;
}

/* (3) Bollinger's rule 18 read at every MA type: BBW is 100 times
 * TA_STDDEV(n, kUp + kDn) over TA_MA, aligned by bar, so 400 * STDDEV / SMA
 * at the defaults. TA_STDDEV enters at BBW's outBegIdx, where BBW's own
 * deviation takes its rolling-sum anchor; TA_MA enters at startIdx, as BBW's
 * middle band does (a recursive MA entered later is another series). Nothing
 * here comes from TA_BBANDS but the tolerance: the literal form's
 * cancellation is about 100u*(|U|+|L|)/|M| absolute, and the two sides round
 * apart by a few u relative. Worst measured: 0.24 of the bound. */
#define BBW_IDENT_ABS 400.0
#define BBW_IDENT_REL 8.0
static ErrorNumber test_bbw_identity( void )
{
   static const double kPairs[][2] = { {2.0,2.0}, {1.0,3.0}, {2.0,1.0}, {2.5,1.5}, {0.1,0.2} };
   static const int ns[] = { 5, 20, 50 };
   static double got[BBW_CAP], up[BBW_CAP], mid[BBW_CAP], lo[BBW_CAP];
   static double sd[BBW_CAP], ma[BBW_CAP];
   TA_Integer beg, nb, begB, nbB, begS, nbS, begM, nbM;
   TA_RetCode rc;
   int d, mt, k, p, i, last, n;
   double kUp, kDn, fold, bound;

   for( d = 0; d < 2; d++ )
   {
      const BbwSeries *s = &bbwSeries[d == 0 ? BBW_CORPUS : BBW_WALK];

      last = s->nbBars - 1;
      for( mt = -1; mt < BBW_NB_MATYPE; mt++ )
      for( k = 0; k < 5; k++ )
      for( p = 0; p < 3; p++ )
      {
         TA_MAType maType = mt < 0 ? TA_MAType_SMA : (TA_MAType)mt;

         n   = ns[p];
         kUp = kPairs[k][0];
         kDn = kPairs[k][1];

         /* mt == -1: the defaults, all four resolved by the prologue. */
         if( mt < 0 && ( k != 0 || n != 20 ) )
            continue;
         if( mt < 0 )
            rc = TA_BBW( 0, last, s->x, TA_INTEGER_DEFAULT, TA_REAL_DEFAULT, TA_REAL_DEFAULT,
                         (TA_MAType)TA_INTEGER_DEFAULT, &beg, &nb, got );
         else
            rc = TA_BBW( 0, last, s->x, n, kUp, kDn, maType, &beg, &nb, got );
         if( rc != TA_SUCCESS )
         {
            printf( "BBW rule 18 Fail [%s n=%d matype=%d]: rc=%d\n", s->name, n, mt, (int)rc );
            return TA_TESTUTIL_TFRR_BAD_RETCODE;
         }
         if( nb == 0 )
            continue;

         rc = TA_BBANDS( 0, last, s->x, n, kUp, kDn, maType, &begB, &nbB, up, mid, lo );
         if( rc != TA_SUCCESS || begB != beg || nbB != nb )
         {
            printf( "BBW rule 18 Fail [%s n=%d matype=%d]: BBANDS rc=%d (%d,%d), BBW (%d,%d)\n",
                    s->name, n, mt, (int)rc, begB, nbB, beg, nb );
            return TA_TESTUTIL_TFRR_BAD_BEGIDX;
         }
         rc = TA_STDDEV( beg, last, s->x, n, kUp + kDn, &begS, &nbS, sd );
         if( rc != TA_SUCCESS || begS != beg || nbS != nb )
         {
            printf( "BBW rule 18 Fail [%s n=%d matype=%d]: STDDEV rc=%d (%d,%d)\n",
                    s->name, n, mt, (int)rc, begS, nbS );
            return TA_TESTUTIL_TFRR_BAD_BEGIDX;
         }
         rc = TA_MA( 0, last, s->x, n, maType, &begM, &nbM, ma );
         if( rc != TA_SUCCESS || begM > beg || begM + nbM != last + 1 )
         {
            printf( "BBW rule 18 Fail [%s n=%d matype=%d]: MA rc=%d (%d,%d)\n",
                    s->name, n, mt, (int)rc, begM, nbM );
            return TA_TESTUTIL_TFRR_BAD_BEGIDX;
         }

         for( i = 0; i < nb; i++ )
         {
            fold  = 100.0 * sd[i] / ma[beg + i - begM];
            bound = BBW_ULP * ( BBW_IDENT_ABS * ( fabs( up[i] ) + fabs( lo[i] ) ) / fabs( mid[i] )
                                + BBW_IDENT_REL * fabs( fold ) );
            g_bbwIdentCmp++;
            if( !( fabs( got[i] - fold ) <= bound ) )
            {
               printf( "BBW rule 18 Fail [%s n=%d k=(%g,%g) matype=%d] at bar %d: %.17g, "
                       "100 * TA_STDDEV(n, kUp+kDn) / TA_MA gives %.17g (|diff| %.3g over %.3g)\n",
                       s->name, n, kUp, kDn, mt, beg + i, got[i], fold,
                       fabs( got[i] - fold ), bound );
               return TA_TESTUTIL_TFRR_BAD_CALCULATION;
            }
         }
      }
   }

   return TA_TEST_PASS;
}

/* (4) No value comparison sees a lookback that disagrees with the batch call
 * only in the count a caller sizes its buffer by. */
static ErrorNumber test_bbw_lookback( void )
{
   static const int ns[] = { 2, 20, 33, 34, 100, 100000 };
   static const unsigned int us[] = { 0, 1, 7, 40 };
   static const TA_FuncUnstId ids[] = { TA_FUNC_UNST_EMA, TA_FUNC_UNST_KAMA, TA_FUNC_UNST_MAMA,
                                        TA_FUNC_UNST_T3, TA_FUNC_UNST_RMA };
   static const struct { int n; TA_MAType maType; unsigned int unstEma; int want; } known[] = {
      {      2, TA_MAType_SMA,       0,     1 }, {     20, TA_MAType_SMA,       0,    19 },
      { 100000, TA_MAType_SMA,       0, 99999 }, {     20, TA_MAType_EMA,      15,    34 },
      {     20, TA_MAType_EMA,     100,   119 }, {     20, TA_MAType_DEMA,      0,    38 },
      {     33, TA_MAType_MAMA,      0,    32 }, {     34, TA_MAType_MAMA,      0,    33 },
      {     20, TA_MAType_DISABLED,  0,    19 }, {     20, TA_MAType_DEFAULT,   0,    19 },
   };
   static double out[BBW_CAP];
   const BbwSeries *s = &bbwSeries[BBW_WALK];
   TA_Integer beg, nb;
   TA_RetCode rc;
   int d, j, mt, p, lb, lbB;
   unsigned int k;

   for( k = 0; k < sizeof(known)/sizeof(known[0]); k++ )
   {
      TA_SetUnstablePeriod( TA_FUNC_UNST_EMA, known[k].unstEma );
      lb = TA_BBW_Lookback( known[k].n, 2.0, 2.0, known[k].maType );
      TA_SetUnstablePeriod( TA_FUNC_UNST_EMA, 0 );
      g_bbwLookbackCmp++;
      if( lb != known[k].want )
      {
         printf( "BBW lookback Fail [n=%d matype=%d unstable %u]: %d, expected %d\n",
                 known[k].n, (int)known[k].maType, known[k].unstEma, lb, known[k].want );
         return TA_TESTUTIL_TFRR_BAD_CALCULATION;
      }
   }

   for( d = 0; d < (int)(sizeof(ids)/sizeof(ids[0])); d++ )
   for( j = 0; j < (int)(sizeof(us)/sizeof(us[0])); j++ )
   {
      TA_SetUnstablePeriod( ids[d], us[j] );
      for( mt = 0; mt < BBW_NB_MATYPE; mt++ )
      {
         for( p = 0; p < (int)(sizeof(ns)/sizeof(ns[0])); p++ )
         {
            lb  = TA_BBW_Lookback( ns[p], 2.5, 1.5, (TA_MAType)mt );
            lbB = TA_BBANDS_Lookback( ns[p], 2.5, 1.5, (TA_MAType)mt );
            g_bbwLookbackCmp++;
            if( lb != lbB || lb < 0 )
            {
               printf( "BBW lookback Fail [n=%d matype=%d unstable id %d = %u]: %d, "
                       "TA_BBANDS_Lookback %d\n", ns[p], mt, (int)ids[d], us[j], lb, lbB );
               TA_SetUnstablePeriod( ids[d], 0 );
               return TA_TESTUTIL_TFRR_BAD_CALCULATION;
            }
         }

         /* The first output lands on the lookback bar, and a range one bar
          * shorter is empty. */
         lb = TA_BBW_Lookback( 20, 2.5, 1.5, (TA_MAType)mt );
         rc = TA_BBW( 0, BBW_WALK_N-1, s->x, 20, 2.5, 1.5, (TA_MAType)mt, &beg, &nb, out );
         g_bbwLookbackCmp++;
         if( rc != TA_SUCCESS || beg != lb || nb != BBW_WALK_N - lb )
         {
            printf( "BBW lookback Fail [n=20 matype=%d unstable id %d = %u]: rc=%d (%d,%d), "
                    "lookback %d\n", mt, (int)ids[d], us[j], (int)rc, beg, nb, lb );
            TA_SetUnstablePeriod( ids[d], 0 );
            return TA_TESTUTIL_TFRR_BAD_BEGIDX;
         }
         beg = nb = -1;
         rc = TA_BBW( 0, lb - 1, s->x, 20, 2.5, 1.5, (TA_MAType)mt, &beg, &nb, out );
         g_bbwLookbackCmp++;
         if( rc != TA_SUCCESS || beg != 0 || nb != 0 )
         {
            printf( "BBW lookback Fail [n=20 matype=%d unstable id %d = %u]: [0,%d] gave "
                    "rc=%d (%d,%d), expected TA_SUCCESS (0,0)\n", mt, (int)ids[d], us[j],
                    lb - 1, (int)rc, beg, nb );
            TA_SetUnstablePeriod( ids[d], 0 );
            return TA_TESTUTIL_TFRR_BAD_BEGIDX;
         }
         rc = TA_BBW( 0, lb, s->x, 20, 2.5, 1.5, (TA_MAType)mt, &beg, &nb, out );
         g_bbwLookbackCmp++;
         if( rc != TA_SUCCESS || beg != lb || nb != 1 )
         {
            printf( "BBW lookback Fail [n=20 matype=%d unstable id %d = %u]: [0,%d] gave "
                    "rc=%d (%d,%d), expected (%d,1)\n", mt, (int)ids[d], us[j], lb,
                    (int)rc, beg, nb, lb );
            TA_SetUnstablePeriod( ids[d], 0 );
            return TA_TESTUTIL_TFRR_BAD_BEGIDX;
         }
      }
      TA_SetUnstablePeriod( ids[d], 0 );
   }

   return TA_TEST_PASS;
}

/* (5) outReal == inReal. At startIdx n-1 the first output slot is the first
 * bar a rebuild re-reads, and 3000 bars take every period here past a 32n
 * rebuild and a tile boundary inside the aliased run; the peg series collapses
 * the variance and forces rebuilds that the walk does not. */
static ErrorNumber test_bbw_alias( void )
{
   static const int ns[] = { 5, 20, 50 };
   static double clean[BBW_CAP], alias[BBW_CAP];
   TA_Integer beg, nb, beg2, nb2;
   TA_RetCode rc;
   int d, mt, p, k, t, i, n, startIdx;

   for( d = 0; d < 2; d++ )
   {
      const BbwSeries *s = &bbwSeries[d == 0 ? BBW_WALK : BBW_PEG];
      int nbBars = s->nbBars;

      for( mt = 0; mt < BBW_NB_MATYPE; mt++ )
      for( p = 0; p < 3; p++ )
      for( k = 0; k < 2; k++ )
      for( t = 0; t < 4; t++ )
      {
         double kUp = bbwK[bbwKBranch[k]][0], kDn = bbwK[bbwKBranch[k]][1];

         if( d == 1 && mt != TA_MAType_SMA )
            continue;
         n = ns[p];
         startIdx = t == 0 ? 0 : t == 1 ? n-1 : t == 2 ? n : 300;

         rc = TA_BBW( startIdx, nbBars-1, s->x, n, kUp, kDn, (TA_MAType)mt, &beg, &nb, clean );
         if( rc != TA_SUCCESS )
         {
            printf( "BBW in-place Fail [%s n=%d matype=%d start=%d]: rc=%d\n", s->name, n, mt,
                    startIdx, (int)rc );
            return TA_TESTUTIL_TFRR_BAD_RETCODE;
         }
         memcpy( alias, s->x, (size_t)nbBars * sizeof(double) );
         rc = TA_BBW( startIdx, nbBars-1, alias, n, kUp, kDn, (TA_MAType)mt, &beg2, &nb2, alias );
         if( rc != TA_SUCCESS || beg2 != beg || nb2 != nb )
         {
            printf( "BBW in-place Fail [%s n=%d matype=%d start=%d]: rc=%d (%d,%d) vs (%d,%d)\n",
                    s->name, n, mt, startIdx, (int)rc, beg2, nb2, beg, nb );
            return TA_TESTUTIL_TFRR_BAD_BEGIDX;
         }
         for( i = 0; i < nb; i++ )
         {
            g_bbwAliasCmp++;
            if( !bbw_same( clean[i], alias[i] ) )
            {
               printf( "BBW in-place Fail [%s n=%d k=(%g,%g) matype=%d start=%d] at bar %d: "
                       "separate %.17g, in-place %.17g\n", s->name, n, kUp, kDn, mt, startIdx,
                       beg + i, clean[i], alias[i] );
               return TA_TESTUTIL_TFRR_BAD_CALCULATION;
            }
         }
      }
   }

   return TA_TEST_PASS;
}

/* (6) A call reads nothing before startIdx - lookback and keys every rolling
 * sum on its own start, so from startIdx s it is, bit for bit, the call from
 * the lookback bar on the series cut at s - lookback. */
static ErrorNumber test_bbw_anchor( void )
{
   static const int ns[] = { 5, 20 };
   static double got[BBW_CAP], cut[BBW_CAP];
   TA_Integer beg, nb, cutBeg, cutNb;
   TA_RetCode rc;
   ErrorNumber err;
   int d, mt, p, pass, i, n, lb, s0, e, a, last;

   for( d = 0; d < 2; d++ )
   {
      const BbwSeries *s = &bbwSeries[d == 0 ? BBW_CORPUS : BBW_WALK];

      last = d == 0 ? s->nbBars - 1 : 699;
      for( mt = 0; mt < BBW_NB_MATYPE; mt++ )
      for( p = 0; p < 2; p++ )
      {
         n  = ns[p];
         lb = TA_BBANDS_Lookback( n, 2.5, 1.5, (TA_MAType)mt );
         for( s0 = lb; s0 <= last; s0 = ( s0 == last ) ? last + 1 : ( s0 + 23 < last ? s0 + 23 : last ) )
         for( pass = 0; pass < 2; pass++ )
         {
            e = pass == 0 ? s0 : last;
            if( pass == 1 && e == s0 )
               continue;
            a = s0 - lb;

            rc = TA_BBW( s0, e, s->x, n, 2.5, 1.5, (TA_MAType)mt, &beg, &nb, got );
            if( rc != TA_SUCCESS || beg != s0 || nb != e - s0 + 1 )
            {
               printf( "BBW anchor Fail [%s n=%d matype=%d] [%d,%d]: rc=%d (%d,%d)\n",
                       s->name, n, mt, s0, e, (int)rc, beg, nb );
               return TA_TESTUTIL_TFRR_BAD_BEGIDX;
            }
            rc = TA_BBW( lb, e - a, s->x + a, n, 2.5, 1.5, (TA_MAType)mt, &cutBeg, &cutNb, cut );
            if( rc != TA_SUCCESS || cutBeg != lb || cutNb != nb )
            {
               printf( "BBW anchor Fail [%s n=%d matype=%d] [%d,%d]: the series cut at %d gave "
                       "rc=%d (%d,%d)\n", s->name, n, mt, s0, e, a, (int)rc, cutBeg, cutNb );
               return TA_TESTUTIL_TFRR_BAD_BEGIDX;
            }
            for( i = 0; i < nb; i++ )
            {
               g_bbwAnchorCmp++;
               if( !bbw_same( got[i], cut[i] ) )
               {
                  printf( "BBW anchor Fail [%s n=%d matype=%d] [%d,%d] at bar %d: %.17g, the "
                          "series cut at %d gives %.17g\n", s->name, n, mt, s0, e, s0 + i,
                          got[i], a, cut[i] );
                  return TA_TESTUTIL_TFRR_BAD_CALCULATION;
               }
            }
         }

         if( d == 0 && p == 1 )
         {
            s0 = lb + 23;
            rc = TA_BBW( s0, last, s->x, n, 2.5, 1.5, (TA_MAType)mt, &beg, &nb, got );
            err = bbw_route( "anchored", s0, last, s->x, s->nbBars, n, 2.5, 1.5,
                             (TA_MAType)mt, rc, beg, nb, got );
            if( err != TA_TEST_PASS )
               return err;
         }
      }
   }

   return TA_TEST_PASS;
}

/* (7) The declared ranges are ABI, and each default resolves to the value
 * the YAML declares: 20, 2, 2, SMA. */
static ErrorNumber test_bbw_params( void )
{
   static double out[BBW_CAP], want[BBW_CAP];
   const BbwSeries *s = &bbwSeries[BBW_CORPUS];
   const double kOver  = nextafter( TA_REAL_MAX, INFINITY );
   const double kUnder = nextafter( TA_REAL_MIN, -INFINITY );
   const struct { int n; double kUp, kDn; int maType; int ok; } v[] = {
      {     -1,      2.0,      2.0,   0, 0 }, {      0,      2.0,      2.0,   0, 0 },
      {      1,      2.0,      2.0,   0, 0 }, { 100001,      2.0,      2.0,   0, 0 },
      {     20,    kOver,      2.0,   0, 0 }, {     20,      2.0,    kOver,   0, 0 },
      {     20,   kUnder,      2.0,   0, 0 }, {     20,      2.0,   kUnder,   0, 0 },
      {     20, INFINITY,      2.0,   0, 0 }, {     20,      2.0, INFINITY,   0, 0 },
      {     20,-INFINITY,      2.0,   0, 0 }, {     20,      2.0,-INFINITY,   0, 0 },
      {     20,      NAN,      2.0,   0, 0 }, {     20,      2.0,      NAN,   0, 0 },
      {     20,      2.0,      2.0,  -1, 0 }, {     20,      2.0,      2.0,  14, 0 },
      {     20,      2.0,      2.0, 100, 0 },
      {      2,      2.0,      2.0,   0, 1 }, { 100000,      2.0,      2.0,   0, 1 },
      {     20, TA_REAL_MAX, TA_REAL_MIN, 1, 1 }, {     20, TA_REAL_MIN, TA_REAL_MAX, 1, 1 },
      {     20,      2.0,      2.0,  13, 1 },
   };
   const int nbV = (int)(sizeof(v)/sizeof(v[0]));
   TA_Integer beg, nb, begW, nbW;
   TA_RetCode rc;
   int i, j, lb;

   for( i = 0; i < nbV; i++ )
   {
      lb = TA_BBW_Lookback( v[i].n, v[i].kUp, v[i].kDn, (TA_MAType)v[i].maType );
      rc = TA_BBW( 0, 251, s->x, v[i].n, v[i].kUp, v[i].kDn, (TA_MAType)v[i].maType,
                   &beg, &nb, out );
      g_bbwParamCmp++;
      if( v[i].ok ? ( rc != TA_SUCCESS || lb < 0 ) : ( rc != TA_BAD_PARAM || lb != -1 ) )
      {
         printf( "BBW parameter Fail [n=%d k=(%.17g,%.17g) matype=%d]: rc=%d, lookback %d, "
                 "expected %s\n", v[i].n, v[i].kUp, v[i].kDn, v[i].maType, (int)rc, lb,
                 v[i].ok ? "TA_SUCCESS" : "TA_BAD_PARAM and -1" );
         return TA_TESTUTIL_TFRR_BAD_PARAM;
      }
      if( server_verify_active() && isfinite( v[i].kUp ) && isfinite( v[i].kDn ) )
      {
         const double optIn[4] = { (double)v[i].n, v[i].kUp, v[i].kDn, (double)v[i].maType };
         ErrorNumber err = server_verify_lookback_parity( "BBW", 0, 251, 252,
                                                          (const TA_Real*[]){ s->x, NULL },
                                                          optIn, 4 );
         if( err != TA_TEST_PASS )
            return err;
      }
   }

   rc = TA_BBW( -1, 251, s->x, 20, 2.0, 2.0, TA_MAType_SMA, &beg, &nb, out );
   g_bbwParamCmp++;
   if( rc != TA_OUT_OF_RANGE_START_INDEX )
   {
      printf( "BBW parameter Fail: startIdx -1 gave rc=%d\n", (int)rc );
      return TA_TESTUTIL_TFRR_BAD_RETCODE;
   }
   rc = TA_BBW( 30, 29, s->x, 20, 2.0, 2.0, TA_MAType_SMA, &beg, &nb, out );
   g_bbwParamCmp++;
   if( rc != TA_OUT_OF_RANGE_END_INDEX )
   {
      printf( "BBW parameter Fail: endIdx < startIdx gave rc=%d\n", (int)rc );
      return TA_TESTUTIL_TFRR_BAD_RETCODE;
   }

   /* Each default alone, against the explicit value, bitwise. */
   for( j = 0; j < 5; j++ )
   {
      int    n   = j == 0 ? TA_INTEGER_DEFAULT : 20;
      double kUp = j == 1 ? TA_REAL_DEFAULT : 2.5;
      double kDn = j == 2 ? TA_REAL_DEFAULT : 1.5;
      int    mat = j == 3 ? TA_INTEGER_DEFAULT : j == 4 ? TA_MAType_DEFAULT : TA_MAType_SMA;
      double eUp = j == 1 ? 2.0 : 2.5;
      double eDn = j == 2 ? 2.0 : 1.5;

      rc = TA_BBW( 0, 251, s->x, 20, eUp, eDn, TA_MAType_SMA, &begW, &nbW, want );
      if( rc != TA_SUCCESS )
      {
         printf( "BBW default Fail [%d]: the explicit call gave rc=%d\n", j, (int)rc );
         return TA_TESTUTIL_TFRR_BAD_RETCODE;
      }
      rc = TA_BBW( 0, 251, s->x, n, kUp, kDn, (TA_MAType)mat, &beg, &nb, out );
      lb = TA_BBW_Lookback( n, kUp, kDn, (TA_MAType)mat );
      g_bbwParamCmp++;
      if( rc != TA_SUCCESS || beg != begW || nb != nbW || lb != 19 )
      {
         printf( "BBW default Fail [%d]: rc=%d (%d,%d) lookback %d, the explicit call gives "
                 "(%d,%d) and 19\n", j, (int)rc, beg, nb, lb, begW, nbW );
         return TA_TESTUTIL_TFRR_BAD_BEGIDX;
      }
      for( i = 0; i < nb; i++ )
      {
         g_bbwParamCmp++;
         if( !bbw_same( out[i], want[i] ) )
         {
            printf( "BBW default Fail [%d] at bar %d: %.17g, the explicit call gives %.17g\n",
                    j, beg + i, out[i], want[i] );
            return TA_TESTUTIL_TFRR_BAD_CALCULATION;
         }
      }
   }

   return TA_TEST_PASS;
}

/* (8) A flat window is (0 / middle) * 100, so -0.0 at a negative level, and
 * an all-zero window is +0.0 through the middle == 0 guard, both at every MA
 * type. Only the SMA of an even window of alternating +-1 is exactly 0, so
 * +0.0 there whatever the width. */
static ErrorNumber test_bbw_degenerate( void )
{
   static const int ids[4] = { BBW_FLATPOS, BBW_FLATNEG, BBW_ZERO, BBW_ALT };
   static const int ns[] = { 2, 4, 20 };
   static double out[BBW_CAP];
   TA_Integer beg, nb;
   TA_RetCode rc;
   int c, mt, p, k, i, lb, wantNb;

   for( c = 0; c < 4; c++ )
   for( mt = 0; mt < BBW_NB_MATYPE; mt++ )
   for( p = 0; p < 3; p++ )
   for( k = 0; k < NB_BBW_K; k++ )
   {
      const BbwSeries *s = &bbwSeries[ids[c]];
      const double want = ids[c] == BBW_FLATNEG ? -0.0 : 0.0;

      if( ids[c] == BBW_ALT && mt != TA_MAType_SMA )
         continue;
      lb = TA_BBANDS_Lookback( ns[p], bbwK[k][0], bbwK[k][1], (TA_MAType)mt );
      wantNb = lb < s->nbBars ? s->nbBars - lb : 0;
      rc = TA_BBW( 0, s->nbBars-1, s->x, ns[p], bbwK[k][0], bbwK[k][1], (TA_MAType)mt,
                   &beg, &nb, out );
      if( rc != TA_SUCCESS || nb != wantNb || ( nb > 0 && beg != lb ) )
      {
         printf( "BBW degenerate Fail [%s n=%d matype=%d]: rc=%d (%d,%d), lookback %d\n",
                 s->name, ns[p], mt, (int)rc, beg, nb, lb );
         return TA_TESTUTIL_TFRR_BAD_BEGIDX;
      }
      for( i = 0; i < nb; i++ )
      {
         g_bbwDegenCmp++;
         if( !bbw_same( out[i], want ) )
         {
            printf( "BBW degenerate Fail [%s n=%d k=(%g,%g) matype=%d] at bar %d: %.17g, "
                    "expected exactly %.1f\n", s->name, ns[p], bbwK[k][0], bbwK[k][1], mt,
                    beg + i, out[i], want );
            return TA_TESTUTIL_TFRR_BAD_CALCULATION;
         }
      }
   }

   return TA_TEST_PASS;
}
