/* Leg 1. Captured by ta-lib-oracles/capture_447_bbw.py at commit
 * 97a7012f130ae603269a94591d88f0117a16c2a6, which regenerates these rows
 * (its goldens.md) and never runs TA-Lib. `bar` is the ABSOLUTE bar index.
 * Every column is in percent.
 *
 *   exact : 100 * (kUp + kDn) * sqrt(V) / M over the exact input doubles, in
 *           rational arithmetic, rounded once: proved the nearest double
 *           (Python 3.12.3). M is the exact SMA, WMA, EMA or DEMA, seeded
 *           where TA_MA seeds.
 *   ts    : trading-signals 8.3.0 BollingerBandsWidth (node v22.21.1), a
 *           ratio, times 100 in double. SMA middle, one multiplier.
 *   ta4j  : ta4j 0.22.6 BollingerBandWidthIndicator, DoubleNum (OpenJDK
 *           21.0.12.1). The only arm with a k per band.
 *   lean  : LEAN 2.5.18090 (commit 5b0c9975d3189efe4353e5071374b77ab9681bdb)
 *           BollingerBands(n, k, type).BandWidth, System.Decimal.
 *
 * ts, ta4j and lean are provenance, not compared: the capture froze a value
 * only within its arm gate of exact, and tsAbs, ta4jAbs and leanAbs in
 * bbwGoldens are each arm's largest distance from exact over the group,
 * printed to 3 significant digits (not a bound). NAN: the arm does not
 * compute that bar, or sits outside that gate there. Pine (PyneCore 6.8.14)
 * and pandas-ta-classic 0.6.52 were compared and are not frozen: Pine's
 * q/n - m^2 deviation misses narrow bands by up to 8.5e7 times the gate, and
 * pandas-ta-classic adds float epsilon to every width of a series once one
 * width is 0.
 *
 * TOLERANCE, exact: |got - exact| <= tol, the row's last column:
 * rel*|exact| + 800u*(|U|+|L|)/|M| on the exact bands, rounded up, rel =
 * 1e-12 from n = 20, 5e-12 at n = 5, 1e-10 at n = 2. The second term is the
 * literal form's cancellation, about 200u absolute on any series: without it
 * the 1e8 + 0.01 rows (6.8e-7 relative) could not be frozen. The multiply by
 * 100 rounds once more, well inside rel.
 * tol == 0 compares bitwise, sign included: a zero-width window gives
 * (0.0 / middle) * 100, and a middle == 0 bar gives +0.0 (no arm computes
 * that). Measured on EVERY bar of every group, not only the rows below, with
 * the capture's exact arithmetic: the worst is 0.40 of the bound (dema-n20,
 * bar 168), 0.37 at n = 2, 0.21 at n = 5 and 0.06 at n = 100000.
 */
typedef struct { int bar; double exact, ts, ta4j, lean, tol; int mid0; } BbwRow;

typedef struct
{
   const char *tag;
   int series, startIdx, endIdx, n;
   double kUp, kDn;
   TA_MAType maType;
   unsigned int unstEma;
   int beg, nb;
   double tsAbs, ta4jAbs, leanAbs;
   const BbwRow *rows;
   int nbRows;
} BbwGolden;

