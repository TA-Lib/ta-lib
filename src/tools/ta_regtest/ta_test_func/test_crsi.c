static ErrorNumber crsiRoute( const char *tag, int startIdx, int endIdx,
                              const TA_Real *in, int nbBars,
                              int m1, int m2, int P,
                              TA_RetCode retCode, int beg, int nb,
                              const TA_Real *out )
{
   double optIn[3];
   int before;
   ErrorNumber err;

   if( !server_verify_active() )
      return TA_TEST_PASS;

   optIn[0] = (double)m1;
   optIn[1] = (double)m2;
   optIn[2] = (double)P;
   before = server_verify_value_comparisons();
   err = server_verify( "CRSI", startIdx, endIdx, nbBars, retCode, beg, nb,
                        (const TA_Real*[]){ in, NULL }, optIn, 3,
                        (const TA_Real*[]){ out, NULL }, NULL );
   if( err != TA_TEST_PASS )
      return err;
   if( server_verify_value_comparisons() == before )
   {
      printf( "CRSI %s: server_verify compared no server despite live pipes\n", tag );
      return TA_SV_ROUTED_VACUOUS;
   }
   return TA_TEST_PASS;
}

static int crsiMax3( int a, int b, int c )
{
   int m = a > b ? a : b;
   return m > c ? m : c;
}

