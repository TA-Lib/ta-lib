/* Description:
 *
 *   Test TA_FRAMA (Fractal Adaptive Moving Average).
 *
 *   Legs:
 *     1. Frozen goldens on the issue's 1500-bar synthetic series, 1e-12
 *        relative. The early rows are the ones the seed bar moves.
 *     2. Ehlers' own TradeStation output, at its 2-decimal print precision,
 *        for Filt and for TL = TA_ADD(F, TA_MOM(F, N/2)).
 *     3. Collapsed input TA_FRAMA(c, c, 16) against trading-signals 8.3.0.
 *     4. Every bar with a flat half, and every bar where the upper clamp binds,
 *        returns the price bitwise. A fully flat series never yields NaN.
 *     5. Lookback, unstable period, odd-period rejection (batch and Open).
 *     6. A per-bar O(N) brute force over periods, unstable periods, sub-ranges
 *        and aliased outputs. This is the leg that sees the seed-only loop and
 *        the output loop drift apart.
 */

