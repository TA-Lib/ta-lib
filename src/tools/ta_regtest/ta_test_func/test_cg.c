/* Leg 3. Captured by ta-lib-oracles/capture_450_cg.py at commit
 * 399b3e890df202986147ac5b664f54757b5617ef, with its arm drivers
 * pandas_serve/capture_450_cg.py, pine_serve/capture_450_cg.py (with
 * pine_serve/cg_450_arm.py) and trading_signals_serve/capture_450_cg.mjs. It
 * regenerates these rows value for value (its goldens.md) and never runs
 * TA-Lib. `bar` is the ABSOLUTE bar index.
 *
 *   exact  : -Num/Den over the exact input doubles in integer arithmetic,
 *            rounded once (Python 3.12.3). -(n+1)/2 where Den == 0, which no
 *            arm computes: the rows where every arm is NAN at that value.
 *   pandas : pandas-ta-classic 0.6.52 ta.cg (pandas 3.0.3, numpy 2.5.1), talib
 *            blocked from import.
 *   ts     : trading-signals 8.3.0 CG(n, 1) (node v22.21.1), raw. Its weights
 *            are reversed, so it gives CG + (n+1) where Den > 0 and 0 elsewhere.
 *   pine   : Pine ta.cog on PyneCore 6.8.14: O(1) running sums, never
 *            re-anchored, and no period above 5000.
 *
 * NAN: the arm does not compute that bar, or sits outside the gate there.
 *
 * TOLERANCE, exact: |got - exact| <= tol, the row's last column:
 * 1e-12*|exact| + 3nu(W + |exact|S)/|Den| over the window, rounded up, with
 * u = 2^-53, S = sum |x| and W = sum (i+1)|x|. The second term bounds
 * recursive summation in any order plus the divide; on a same-sign window it
 * is 6nu relative. tol == 0 compares with ==: every partial sum of the window
 * is exact, so only the divide rounds, and an exact 0 has no pinned sign.
 *
 * TOLERANCE, arms: |got - arm| <= tol + armAbs + u|exact|, ts compared as
 * ts - (n+1) in double. armAbs is the arm's largest distance over the group
 * from the unrounded ratio, so the exact column's own rounding is the third
 * term. Worst measured: TA_CG 0.02 of tol, an arm 0.05 of its gate
 * (pine, close-n2).
 */
typedef struct { int bar; double exact, pandas, ts, pine, tol; } CgRow;

