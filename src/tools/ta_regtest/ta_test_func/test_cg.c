static int cg_same( double a, double b )
{
   return memcmp( &a, &b, sizeof(double) ) == 0;
}

/* Replays TA_CG( startIdx, endIdx, x, n ) on every language server. The
 * servers get endIdx+1 bars, or the series cut at startIdx - lookback when
 * that is too long for one request: the same windows. */
static ErrorNumber cg_route( const char *tag, int startIdx, int endIdx, const double *x, int n,
                             TA_RetCode retCode, int beg, int nb, const double *out )
{
   static double cut[CG_CAP];
   TA_Integer cutBeg, cutNb;
   double optIn[1];
   int a, before;
   ErrorNumber err;

   if( !server_verify_active() )
      return TA_TEST_PASS;

   if( endIdx + 1 > CG_SV_MAX_BARS )
   {
      a = startIdx - ( n - 1 );
      if( a < 0 || endIdx + 1 - a > CG_SV_MAX_BARS )
         return TA_TEST_PASS;
      x += a;
      startIdx -= a;
      endIdx   -= a;
      retCode = TA_CG( startIdx, endIdx, x, n, &cutBeg, &cutNb, cut );
      beg = cutBeg;
      nb  = cutNb;
      out = cut;
   }

   optIn[0] = (double)n;
   before = server_verify_value_comparisons();
   err = server_verify( "CG", startIdx, endIdx, endIdx + 1, retCode, beg, nb,
                        (const TA_Real*[]){ x, NULL }, optIn, 1,
                        (const TA_Real*[]){ out, NULL }, NULL );
   if( err != TA_TEST_PASS )
      return err;
   if( server_verify_value_comparisons() == before )
   {
      printf( "CG %s: server_verify compared no server despite live pipes\n", tag );
      return TA_SV_ROUTED_VACUOUS;
   }
   return TA_TEST_PASS;
}

/* (1) */
static ErrorNumber test_cg_differential( void )
{
   static const int ids[2] = { CG_CLOSE, CG_MED };
   static double wma[CG_CAP], sma[CG_CAP], out[CG_CAP];
   TA_Integer begW, nbW, begS, nbS, beg, nb;
   TA_RetCode rcW, rcS, rc;
   int d, n, i;

   for( d = 0; d < 2; d++ )
   {
      const CgSeries *s = &cgSeries[ids[d]];

      for( n = 2; n <= CG_MAX_PER; n++ )
      {
         rcW = TA_WMA( 0, s->nbBars-1, s->x, n, &begW, &nbW, wma );
         rcS = TA_SMA( 0, s->nbBars-1, s->x, n, &begS, &nbS, sma );
         rc  = TA_CG( 0, s->nbBars-1, s->x, n, &beg, &nb, out );
         if( rcW != TA_SUCCESS || rcS != TA_SUCCESS || rc != TA_SUCCESS
             || beg != n-1 || nb != s->nbBars - (n-1)
             || begW != beg || nbW != nb || begS != beg || nbS != nb )
         {
            printf( "CG differential Fail [%s n=%d]: CG rc=%d (%d,%d), WMA (%d,%d), "
                    "SMA (%d,%d)\n", s->name, n, (int)rc, beg, nb, begW, nbW, begS, nbS );
            return TA_TESTUTIL_TFRR_BAD_BEGIDX;
         }

         for( i = 0; i < nb; i++ )
         {
            double want = ( (double)( n + 1 ) * 0.5 ) * ( wma[i] / sma[i] ) - (double)( n + 1 );

            g_cgDiffCmp++;
            if( !( fabs( out[i] - want ) <= CG_DIFF_REL * fabs( want ) ) )
            {
               printf( "CG differential Fail [%s n=%d] at bar %d: %.17g, "
                       "((n+1)/2)*WMA/SMA - (n+1) gives %.17g (rel %.3g, tol %g)\n",
                       s->name, n, beg + i, out[i], want,
                       fabs( out[i] - want ) / fabs( want ), CG_DIFF_REL );
               return TA_TESTUTIL_TFRR_BAD_CALCULATION;
            }
         }
      }
   }

   return TA_TEST_PASS;
}

/* -Num/Den with Num and Den in long long, so only the divide rounds. */
static double cg_int_reference( const double *x, int t, int n, long long *denOut )
{
   long long num = 0, den = 0, v;
   int i;

   for( i = 0; i < n; i++ )
   {
      v = (long long)x[t-i];
      den += v;
      num += (long long)( i + 1 ) * v;
   }
   *denOut = den;
   if( den == 0 )
      return -( (double)n + 1.0 ) * 0.5;
   return -(double)num / (double)den;
}

static ErrorNumber cg_int_check( const CgSeries *s, int startIdx, int endIdx, int n )
{
   static double out[CG_CAP];
   TA_Integer beg, nb;
   TA_RetCode rc;
   long long den;
   int i, wantBeg = startIdx > n-1 ? startIdx : n-1;

   rc = TA_CG( startIdx, endIdx, s->x, n, &beg, &nb, out );
   if( rc != TA_SUCCESS || beg != wantBeg || nb != endIdx - wantBeg + 1 )
   {
      printf( "CG integer Fail [%s n=%d]: rc=%d (%d,%d), expected (%d,%d)\n",
              s->name, n, (int)rc, beg, nb, wantBeg, endIdx - wantBeg + 1 );
      return TA_TESTUTIL_TFRR_BAD_BEGIDX;
   }

   for( i = 0; i < nb; i++ )
   {
      double want = cg_int_reference( s->x, beg + i, n, &den );

      g_cgIntCmp++;
      if( den == 0 )
         g_cgIntDen0++;
      else if( den < 0 )
         g_cgIntDenNeg++;
      if( !( out[i] == want ) )
      {
         printf( "CG integer Fail [%s n=%d] at bar %d: %.17g, the exact ratio is %.17g "
                 "(Den %lld)\n", s->name, n, beg + i, out[i], want, den );
         return TA_TESTUTIL_TFRR_BAD_CALCULATION;
      }
   }

   return cg_route( "integer", startIdx, endIdx, s->x, n, rc, beg, nb, out );
}

