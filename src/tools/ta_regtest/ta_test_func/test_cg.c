/* (3) */
static ErrorNumber test_cg_goldens( void )
{
   static const char *armName[3] = { "pandas-ta-classic 0.6.52", "trading-signals 8.3.0",
                                     "PyneCore 6.8.14 ta.cog" };
   static double out[CG_CAP];
   TA_RetCode retCode;
   TA_Integer beg, nb;
   ErrorNumber err;
   int k, r, a;

   for( k = 0; k < NB_CG_GOLDENS; k++ )
   {
      const CgGolden *g = &cgGoldens[k];
      const CgSeries *s = &cgSeries[g->series];

      beg = nb = -1;
      retCode = TA_CG( g->startIdx, g->endIdx, s->x, g->n, &beg, &nb, out );
      if( retCode != TA_SUCCESS || beg != g->beg || nb != g->nb )
      {
         printf( "CG golden Fail [%s]: rc=%d (%d,%d), expected (%d,%d)\n",
                 g->tag, (int)retCode, beg, nb, g->beg, g->nb );
         return TA_TESTUTIL_TFRR_BAD_BEGIDX;
      }

      for( r = 0; r < g->nbRows; r++ )
      {
         const CgRow *row = &g->rows[r];
         const double arm[3]    = { row->pandas, row->ts - (double)( g->n + 1 ), row->pine };
         const double armAbs[3] = { g->pandasAbs, g->tsAbs, g->pineAbs };
         double got;

         if( row->bar < beg || row->bar - beg >= nb )
         {
            printf( "CG golden Fail [%s]: golden bar %d is outside the output [%d..%d]\n",
                    g->tag, row->bar, beg, beg + nb - 1 );
            return TA_TESTUTIL_TFRR_BAD_PARAM;
         }
         got = out[row->bar - beg];

         g_cgGoldenCmp++;
         if( row->tol == 0.0 ? !( got == row->exact )
                             : !( fabs( got - row->exact ) <= row->tol ) )
         {
            printf( "CG golden Fail [%s] at bar %d: got %.17g, exact %.17g "
                    "(capture_450_cg.py; |diff| %.3g over %.3g%s)\n",
                    g->tag, row->bar, got, row->exact, fabs( got - row->exact ), row->tol,
                    row->tol == 0.0 ? ", exact sums: only the divide rounds" : "" );
            return TA_TESTUTIL_TFRR_BAD_CALCULATION;
         }

         for( a = 0; a < 3; a++ )
         {
            const double bound = row->tol + armAbs[a] + CG_U * fabs( row->exact );

            if( isnan( arm[a] ) )
               continue;
            g_cgArmCmp++;
            if( !( fabs( got - arm[a] ) <= bound ) )
            {
               printf( "CG golden Fail [%s] at bar %d: got %.17g, %s gives %.17g%s "
                       "(|diff| %.3g over %.3g)\n", g->tag, row->bar, got, armName[a],
                       arm[a], a == 1 ? " after - (n+1)" : "", fabs( got - arm[a] ), bound );
               return TA_TESTUTIL_TFRR_BAD_CALCULATION;
            }
         }
      }

      err = cg_route( g->tag, g->startIdx, g->endIdx, s->x, g->n, retCode, beg, nb, out );
      if( err != TA_TEST_PASS )
         return err;
   }

   return TA_TEST_PASS;
}

/* (4) The stream is opened on n bars that are not the window, then the
 * window's first n-1, so its ring holds none of the window's last bar until
 * Peek and Update hand it over. */
static ErrorNumber test_cg_edges( void )
{
   static double hist[2000];
   TA_CG_Stream *stream;
   TA_Integer beg, nb, begF, nbF;
   TA_RetCode rc;
   double out[1], fill[1], last, peeked, updated;
   ErrorNumber err;
   int k, i;

   peeked = updated = 0.0;
   for( k = 0; k < NB_CG_EDGES; k++ )
   {
      const CgEdge *e = &cgEdges[k];
      const double *w = cgSeries[e->series].x;
      const int n = e->n;

      beg = nb = -1;
      rc = TA_CG( 0, n-1, w, n, &beg, &nb, out );
      if( rc != TA_SUCCESS || beg != n-1 || nb != 1 )
      {
         printf( "CG edge Fail [%s n=%d]: rc=%d (%d,%d)\n", e->name, n, (int)rc, beg, nb );
         return TA_TESTUTIL_TFRR_BAD_BEGIDX;
      }
      g_cgEdgeCmp++;
      if( e->rel == 0.0 ? !( out[0] == e->want )
                        : !( fabs( out[0] - e->want ) <= e->rel * fabs( e->want ) ) )
      {
         printf( "CG edge Fail [%s n=%d]: %.17g, expected %.17g%s\n", e->name, n, out[0],
                 e->want, e->rel == 0.0 ? " exactly" : " within 1e-12 relative" );
         return TA_TESTUTIL_TFRR_BAD_CALCULATION;
      }
      err = cg_route( e->name, 0, n-1, w, n, rc, beg, nb, out );
      if( err != TA_TEST_PASS )
         return err;

      stream = NULL;
      begF = nbF = -1;
      rc = TA_CG_OpenAndFill( &stream, w, n, n, &begF, &nbF, fill );
      if( rc != TA_SUCCESS || !stream || begF != n-1 || nbF != 1 )
      {
         printf( "CG edge Fail [%s n=%d]: TA_CG_OpenAndFill rc=%d (%d,%d)\n",
                 e->name, n, (int)rc, begF, nbF );
         if( stream )
            TA_CG_Close( stream );
         return TA_TESTUTIL_TFRR_BAD_RETCODE;
      }
      TA_CG_Close( stream );
      g_cgEdgeCmp++;
      if( !cg_same( fill[0], out[0] ) )
      {
         printf( "CG edge Fail [%s n=%d]: TA_CG_OpenAndFill %.17g, batch %.17g\n",
                 e->name, n, fill[0], out[0] );
         return TA_TESTUTIL_TFRR_BAD_CALCULATION;
      }

      for( i = 0; i < n; i++ )
         hist[i] = 1000.0 + (double)i;
      for( i = 0; i < n-1; i++ )
         hist[n+i] = w[i];
      stream = NULL;
      rc = TA_CG_Open( &stream, hist, 2*n-1, n, &last );
      if( rc != TA_SUCCESS || !stream )
      {
         printf( "CG edge Fail [%s n=%d]: TA_CG_Open on %d bars rc=%d\n",
                 e->name, n, 2*n-1, (int)rc );
         return TA_TESTUTIL_TFRR_BAD_RETCODE;
      }
      rc = TA_CG_Peek( stream, w[n-1], &peeked );
      if( rc == TA_SUCCESS )
         rc = TA_CG_Update( stream, w[n-1], &updated );
      TA_CG_Close( stream );
      g_cgEdgeCmp++;
      if( rc != TA_SUCCESS || !cg_same( peeked, out[0] ) || !cg_same( updated, out[0] ) )
      {
         printf( "CG edge Fail [%s n=%d]: rc=%d, Peek %.17g, Update %.17g, batch %.17g\n",
                 e->name, n, (int)rc, peeked, updated, out[0] );
         return TA_TESTUTIL_TFRR_BAD_CALCULATION;
      }
   }

   return TA_TEST_PASS;
}

/* (5) Negating every input negates every partial sum exactly, so a nonzero
 * output keeps its bits. A zero's sign follows Den, which flips. */
static ErrorNumber test_cg_negation( void )
{
   static double neg[CG_INT_N], out[CG_CAP], outNeg[CG_CAP];
   TA_Integer beg, nb, begN, nbN;
   TA_RetCode rc, rcN;
   int d, n, i, nbBars;

   for( d = 0; d < 2; d++ )
   {
      const CgSeries *s = &cgSeries[d == 0 ? CG_CLOSE : CG_INTDIFF];

      nbBars = d == 0 ? s->nbBars : CG_INT_N;
      for( i = 0; i < nbBars; i++ )
         neg[i] = -s->x[i];

      for( n = 2; n <= CG_MAX_PER; n++ )
      {
         rc  = TA_CG( 0, nbBars-1, s->x, n, &beg, &nb, out );
         rcN = TA_CG( 0, nbBars-1, neg, n, &begN, &nbN, outNeg );
         if( rc != TA_SUCCESS || rcN != TA_SUCCESS || begN != beg || nbN != nb )
         {
            printf( "CG negation Fail [%s n=%d]: rc=%d (%d,%d), negated rc=%d (%d,%d)\n",
                    s->name, n, (int)rc, beg, nb, (int)rcN, begN, nbN );
            return TA_TESTUTIL_TFRR_BAD_BEGIDX;
         }
         for( i = 0; i < nb; i++ )
         {
            g_cgNegCmp++;
            if( out[i] == 0.0 ? !( outNeg[i] == 0.0 ) : !cg_same( outNeg[i], out[i] ) )
            {
               printf( "CG negation Fail [%s n=%d] at bar %d: CG(X) %.17g, CG(-X) %.17g\n",
                       s->name, n, beg + i, out[i], outNeg[i] );
               return TA_TESTUTIL_TFRR_BAD_CALCULATION;
            }
         }
      }
   }

   return TA_TEST_PASS;
}

/* (6) With startIdx at the lookback, a bar's store lands on its own window's
 * oldest input. */
static ErrorNumber test_cg_alias( void )
{
   static double clean[CG_CAP], alias[CG_CAP];
   TA_Integer beg, nb, beg2, nb2;
   TA_RetCode rc;
   int d, n, i, nbBars;

   for( d = 0; d < 2; d++ )
   {
      const CgSeries *s = &cgSeries[d == 0 ? CG_CLOSE : CG_INTDIFF];

      nbBars = d == 0 ? s->nbBars : CG_INT_N;
      for( n = 2; n <= CG_MAX_PER; n++ )
      {
         rc = TA_CG( 0, nbBars-1, s->x, n, &beg, &nb, clean );
         if( rc != TA_SUCCESS )
         {
            printf( "CG in-place Fail [%s n=%d]: rc=%d\n", s->name, n, (int)rc );
            return TA_TESTUTIL_TFRR_BAD_RETCODE;
         }
         memcpy( alias, s->x, (size_t)nbBars * sizeof(double) );
         rc = TA_CG( 0, nbBars-1, alias, n, &beg2, &nb2, alias );
         if( rc != TA_SUCCESS || beg2 != beg || nb2 != nb )
         {
            printf( "CG in-place Fail [%s n=%d]: rc=%d (%d,%d) vs (%d,%d)\n",
                    s->name, n, (int)rc, beg2, nb2, beg, nb );
            return TA_TESTUTIL_TFRR_BAD_BEGIDX;
         }
         for( i = 0; i < nb; i++ )
         {
            g_cgAliasCmp++;
            if( !cg_same( clean[i], alias[i] ) )
            {
               printf( "CG in-place Fail [%s n=%d] at bar %d: separate %.17g, in-place "
                       "%.17g\n", s->name, n, beg + i, clean[i], alias[i] );
               return TA_TESTUTIL_TFRR_BAD_CALCULATION;
            }
         }
      }
   }

   return TA_TEST_PASS;
}

/* (7) Every output is a function of its own window, so a call from startIdx s
 * is, bit for bit, the full call's tail and the call from the lookback bar on
 * the series cut at s - lookback. */
static ErrorNumber test_cg_locality( void )
{
   static double full[CG_CAP], got[CG_CAP], cut[CG_CAP], holed[252];
   const CgSeries *s = &cgSeries[CG_CLOSE];
   TA_Integer begFull, nbFull, beg, nb, cutBeg, cutNb;
   TA_RetCode rc;
   ErrorNumber err;
   int p, n, lb, s0, e, pass, a, i, k, t;

   for( p = 0; p < 3; p++ )
   {
      n  = cgLocalPeriods[p];
      lb = n - 1;
      rc = TA_CG( 0, 251, s->x, n, &begFull, &nbFull, full );
      if( rc != TA_SUCCESS || begFull != lb || nbFull != 252 - lb )
      {
         printf( "CG anchor Fail [n=%d]: full call rc=%d (%d,%d)\n", n, (int)rc,
                 begFull, nbFull );
         return TA_TESTUTIL_TFRR_BAD_BEGIDX;
      }

      for( s0 = 0; s0 <= 251; s0++ )
      for( pass = 0; pass < 2; pass++ )
      {
         int first = s0 > lb ? s0 : lb;

         e = pass == 0 ? 251 : ( first + 9 < 251 ? first + 9 : 251 );
         rc = TA_CG( s0, e, s->x, n, &beg, &nb, got );
         if( rc != TA_SUCCESS || beg != first || nb != e - first + 1 )
         {
            printf( "CG anchor Fail [n=%d] [%d,%d]: rc=%d (%d,%d), expected (%d,%d)\n",
                    n, s0, e, (int)rc, beg, nb, first, e - first + 1 );
            return TA_TESTUTIL_TFRR_BAD_BEGIDX;
         }
         a = first - lb;
         rc = TA_CG( lb, e - a, s->x + a, n, &cutBeg, &cutNb, cut );
         if( rc != TA_SUCCESS || cutBeg != lb || cutNb != nb )
         {
            printf( "CG anchor Fail [n=%d] [%d,%d]: the series cut at %d gave rc=%d (%d,%d)\n",
                    n, s0, e, a, (int)rc, cutBeg, cutNb );
            return TA_TESTUTIL_TFRR_BAD_BEGIDX;
         }
         for( i = 0; i < nb; i++ )
         {
            g_cgLocalCmp++;
            if( !cg_same( got[i], full[first - lb + i] ) || !cg_same( cut[i], got[i] ) )
            {
               printf( "CG anchor Fail [n=%d] [%d,%d] at bar %d: %.17g, the full call "
                       "gives %.17g, the series cut at %d %.17g\n", n, s0, e, first + i,
                       got[i], full[first - lb + i], a, cut[i] );
               return TA_TESTUTIL_TFRR_BAD_CALCULATION;
            }
         }
      }

      rc = TA_CG( 100, 251, s->x, n, &beg, &nb, got );
      err = cg_route( "anchored", 100, 251, s->x, n, rc, beg, nb, got );
      if( err != TA_TEST_PASS )
         return err;

      for( k = 0; k < 4; k++ )
      {
         const int bad = k == 0 ? 0 : k == 1 ? lb : k == 2 ? 120 : 251;

         memcpy( holed, s->x, sizeof(holed) );
         holed[bad] = NAN;
         rc = TA_CG( 0, 251, holed, n, &beg, &nb, got );
         if( rc != TA_SUCCESS || beg != begFull || nb != nbFull )
         {
            printf( "CG NaN Fail [n=%d, NaN at %d]: rc=%d (%d,%d)\n", n, bad, (int)rc, beg, nb );
            return TA_TESTUTIL_TFRR_BAD_BEGIDX;
         }
         for( i = 0; i < nb; i++ )
         {
            t = beg + i;
            g_cgNanCmp++;
            if( ( t >= bad && t < bad + n ) ? !isnan( got[i] ) : !cg_same( got[i], full[i] ) )
            {
               printf( "CG NaN Fail [n=%d, NaN at %d] at bar %d: %.17g, clean %.17g; only "
                       "bars %d..%d read it\n", n, bad, t, got[i], full[i], bad, bad + n - 1 );
               return TA_TESTUTIL_TFRR_BAD_CALCULATION;
            }
         }
      }
   }

   return TA_TEST_PASS;
}

/* (8) The range is ABI, and TA_INTEGER_DEFAULT resolves to 10. */
static ErrorNumber test_cg_params( void )
{
   static const struct { int n; int lookback; } known[] = {
      {      2,     1 }, {      3,     2 }, {     10,     9 }, {     14,    13 },
      {     57,    56 }, {   1000,   999 }, { 100000, 99999 }, { TA_INTEGER_DEFAULT, 9 },
      {     -1,    -1 }, {      0,    -1 }, {      1,    -1 }, { 100001,    -1 },
      { INT_MAX,   -1 },
   };
   static double out[CG_CAP], want[CG_CAP];
   const CgSeries *s = &cgSeries[CG_CLOSE];
   TA_CG_Stream *stream;
   TA_Integer beg, nb, begW, nbW;
   TA_RetCode rc;
   double v, w;
   int k, i, n, lb, ok;

   for( k = 0; k < (int)(sizeof(known)/sizeof(known[0])); k++ )
   {
      n  = known[k].n;
      ok = known[k].lookback >= 0;
      lb = TA_CG_Lookback( n );
      beg = nb = -1;
      rc = TA_CG( 0, 251, s->x, n, &beg, &nb, out );
      g_cgParamCmp++;
      if( lb != known[k].lookback || ( ok ? rc != TA_SUCCESS : rc != TA_BAD_PARAM ) )
      {
         printf( "CG parameter Fail [n=%d]: lookback %d, rc=%d, expected %d and %s\n",
                 n, lb, (int)rc, known[k].lookback, ok ? "TA_SUCCESS" : "TA_BAD_PARAM" );
         return TA_TESTUTIL_TFRR_BAD_PARAM;
      }
      if( ok && ( lb <= 251 ? ( beg != lb || nb != 252 - lb ) : ( beg != 0 || nb != 0 ) ) )
      {
         printf( "CG parameter Fail [n=%d]: (%d,%d) on 252 bars, lookback %d\n",
                 n, beg, nb, lb );
         return TA_TESTUTIL_TFRR_BAD_BEGIDX;
      }

      stream = NULL;
      rc = TA_CG_Open( &stream, s->x, 252, n, &v );
      if( stream )
         TA_CG_Close( stream );
      g_cgParamCmp++;
      if( ok ? ( lb <= 251 ? rc != TA_SUCCESS || !stream : rc != TA_INSUFFICIENT_HISTORY || stream )
             : ( rc != TA_BAD_PARAM || stream ) )
      {
         printf( "CG parameter Fail [n=%d]: TA_CG_Open on 252 bars rc=%d, handle %s\n",
                 n, (int)rc, stream ? "set" : "NULL" );
         return TA_TESTUTIL_TFRR_BAD_PARAM;
      }

      if( server_verify_active() && n != TA_INTEGER_DEFAULT )
      {
         const double optIn[1] = { (double)n };
         ErrorNumber err = server_verify_lookback_parity( "CG", 0, 251, 252,
                                                          (const TA_Real*[]){ s->x, NULL },
                                                          optIn, 1 );
         if( err != TA_TEST_PASS )
            return err;
      }
   }

   rc = TA_CG( 0, 251, s->x, 10, &begW, &nbW, want );
   rc = rc == TA_SUCCESS ? TA_CG( 0, 251, s->x, TA_INTEGER_DEFAULT, &beg, &nb, out ) : rc;
   if( rc != TA_SUCCESS || beg != begW || nb != nbW )
   {
      printf( "CG default Fail: rc=%d (%d,%d), period 10 gives (%d,%d)\n",
              (int)rc, beg, nb, begW, nbW );
      return TA_TESTUTIL_TFRR_BAD_BEGIDX;
   }
   for( i = 0; i < nb; i++ )
   {
      g_cgParamCmp++;
      if( !cg_same( out[i], want[i] ) )
      {
         printf( "CG default Fail at bar %d: %.17g, period 10 gives %.17g\n",
                 beg + i, out[i], want[i] );
         return TA_TESTUTIL_TFRR_BAD_CALCULATION;
      }
   }

   rc = TA_CG( -1, 251, s->x, 10, &beg, &nb, out );
   g_cgParamCmp++;
   if( rc != TA_OUT_OF_RANGE_START_INDEX )
   {
      printf( "CG parameter Fail: startIdx -1 gave rc=%d\n", (int)rc );
      return TA_TESTUTIL_TFRR_BAD_RETCODE;
   }
   rc = TA_CG( 30, 29, s->x, 10, &beg, &nb, out );
   g_cgParamCmp++;
   if( rc != TA_OUT_OF_RANGE_END_INDEX )
   {
      printf( "CG parameter Fail: endIdx < startIdx gave rc=%d\n", (int)rc );
      return TA_TESTUTIL_TFRR_BAD_RETCODE;
   }

   /* The first output lands on the lookback bar: a range one bar shorter is
    * empty, and a stream needs n bars to open. */
   for( k = 0; k < 3; k++ )
   {
      n  = cgLocalPeriods[k];
      lb = n - 1;

      beg = nb = -1;
      rc = TA_CG( 0, lb - 1, s->x, n, &beg, &nb, out );
      g_cgParamCmp++;
      if( rc != TA_SUCCESS || beg != 0 || nb != 0 )
      {
         printf( "CG shape Fail [n=%d]: [0,%d] gave rc=%d (%d,%d), expected TA_SUCCESS (0,0)\n",
                 n, lb - 1, (int)rc, beg, nb );
         return TA_TESTUTIL_TFRR_BAD_BEGIDX;
      }
      rc = TA_CG( 0, lb, s->x, n, &beg, &nb, out );
      rc = rc == TA_SUCCESS ? TA_CG( lb, lb, s->x, n, &begW, &nbW, want ) : rc;
      g_cgParamCmp++;
      if( rc != TA_SUCCESS || beg != lb || nb != 1 || begW != lb || nbW != 1
          || !cg_same( out[0], want[0] ) )
      {
         printf( "CG shape Fail [n=%d]: [0,%d] and [%d,%d] gave rc=%d (%d,%d) (%d,%d), "
                 "expected (%d,1) twice and one value\n", n, lb, lb, lb, (int)rc, beg, nb,
                 begW, nbW, lb );
         return TA_TESTUTIL_TFRR_BAD_BEGIDX;
      }

      stream = NULL;
      rc = TA_CG_Open( &stream, s->x, n - 1, n, &v );
      if( stream )
         TA_CG_Close( stream );
      g_cgParamCmp++;
      if( rc != TA_INSUFFICIENT_HISTORY || stream )
      {
         printf( "CG shape Fail [n=%d]: TA_CG_Open on %d bars rc=%d, handle %s\n",
                 n, n - 1, (int)rc, stream ? "set" : "NULL" );
         return TA_TESTUTIL_TFRR_BAD_RETCODE;
      }
      stream = NULL;
      rc = TA_CG_Open( &stream, s->x, n, n, &w );
      if( stream )
         TA_CG_Close( stream );
      g_cgParamCmp++;
      if( rc != TA_SUCCESS || !stream || !cg_same( w, out[0] ) )
      {
         printf( "CG shape Fail [n=%d]: TA_CG_Open on %d bars rc=%d, %.17g, batch %.17g\n",
                 n, n, (int)rc, w, out[0] );
         return TA_TESTUTIL_TFRR_BAD_RETCODE;
      }
   }

   return TA_TEST_PASS;
}

/* (9) No unstable-period id, matching the abstract metadata doRangeTestEx
 * cross-checks against the stability class. */
typedef struct { int period; const TA_Real *in; } CgRangeParam;

static TA_RetCode cgRangeTestFunction( TA_Integer startIdx, TA_Integer endIdx,
                                       TA_Real *outputBuffer, TA_Integer *outputBufferInt,
                                       TA_Integer *outBegIdx, TA_Integer *outNbElement,
                                       TA_Integer *lookback, void *opaqueData,
                                       unsigned int outputNb, unsigned int *isOutputInteger )
{
   CgRangeParam *p = (CgRangeParam *)opaqueData;

   (void)outputNb;
   (void)outputBufferInt;
   *isOutputInteger = 0;

   *lookback = TA_CG_Lookback( p->period );
   return TA_CG( startIdx, endIdx, p->in, p->period,
                 outBegIdx, outNbElement, outputBuffer );
}

static ErrorNumber test_cg_range( void )
{
   CgRangeParam param;

   param.period = 14;
   param.in     = cgSeries[CG_CLOSE].x;

   return doRangeTestEx( cgRangeTestFunction,
                         TA_STABLE_EXACT, TA_TEST_UNST_NONE,
                         (void *)&param, 1, 0 );
}
