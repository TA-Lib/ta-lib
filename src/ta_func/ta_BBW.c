/* Private function, not in public API. */
static TA_RetCode TA_BBW_StepImpl( struct TA_BBW_Stream *sp, double inReal, double *outReal )
{
   double deviation;
   double lower;
   double middle;
   double tempReal;
   double upper;
   double cur_tempBuffer = 0.0;
   double cur_outReal = 0.0;


   /* Pipeline the new bar through the sub-streams (batch tail order). */
   {
      TA_RetCode subRc = TA_MA_Update( sp->sub0, inReal, &cur_tempBuffer );
      if( subRc != TA_SUCCESS ) return subRc;
   }
   {
      TA_RetCode subRc = TA_VAR_Update( sp->sub1, inReal, &cur_outReal );
      if( subRc != TA_SUCCESS ) return subRc;
   }
   /* Combine map (batch tail, per bar). */
   if( sp->optInNbDevUp == sp->optInNbDevDn )
   {
      middle = cur_tempBuffer;
      tempReal = sqrt(cur_outReal) * sp->optInNbDevUp;
      upper = middle + tempReal;
      lower = middle - tempReal;
      cur_outReal = (upper - lower) / middle;
      if( middle == 0.0 )
      {
         cur_outReal = 0.0;
      }
   } else 
   {
      middle = cur_tempBuffer;
      deviation = sqrt(cur_outReal);
      upper = fma(deviation, sp->optInNbDevUp, middle);
      lower = middle - deviation * sp->optInNbDevDn;
      cur_outReal = (upper - lower) / middle;
      if( middle == 0.0 )
      {
         cur_outReal = 0.0;
      }
   }
   *outReal = cur_outReal;
   return TA_SUCCESS;
}

static TA_RetCode TA_BBW_OpenImpl( struct TA_BBW_Stream **stream, const double inReal[], int startIdx, int historyLen, int optInTimePeriod, double optInNbDevUp, double optInNbDevDn, TA_MAType optInMAType, int *outBegIdx, int *outNBElement, double outReal[], int outStride )
{
   struct TA_BBW_Stream *sp;
   int endIdx;
   int dummyBegIdx;
   int dummyNBElement;
   TA_RetCode subRc;
   double *sc_outReal;
   TA_MA_Stream *sub0;
   TA_VAR_Stream *sub1;

   if( !stream ) return TA_BAD_PARAM;
   *stream = NULL;
   if( historyLen < 1 ) return TA_OUT_OF_RANGE_START_INDEX;
   if( historyLen > TA_INDEX_MAX + 1 ) return TA_OUT_OF_RANGE_END_INDEX;
   if( !inReal || !outReal ) return TA_BAD_PARAM;
   if( (int)optInTimePeriod == TA_INTEGER_DEFAULT )
      optInTimePeriod = 20;
   else if( (int)optInTimePeriod < 2 || (int)optInTimePeriod > 100000 )
      return TA_BAD_PARAM;
   if( optInNbDevUp == TA_REAL_DEFAULT )
      optInNbDevUp = 2;
   else if( !(optInNbDevUp >= TA_REAL_MIN && optInNbDevUp <= TA_REAL_MAX) )
      return TA_BAD_PARAM;
   if( optInNbDevDn == TA_REAL_DEFAULT )
      optInNbDevDn = 2;
   else if( !(optInNbDevDn >= TA_REAL_MIN && optInNbDevDn <= TA_REAL_MAX) )
      return TA_BAD_PARAM;
   if( (int)optInMAType == TA_INTEGER_DEFAULT || optInMAType == TA_MAType_DEFAULT )
      optInMAType = 0;
   else if( (int)optInMAType < TA_MATYPE_MIN || (int)optInMAType > TA_MATYPE_MAX )
      return TA_BAD_PARAM;
   if( startIdx > historyLen - 1 )
   {
      *outBegIdx = 0;
      *outNBElement = 0;
      return TA_INSUFFICIENT_HISTORY;
   }

   endIdx = historyLen - 1;
   dummyBegIdx = 0;
   dummyNBElement = 0;
   subRc = TA_SUCCESS;
   sub0 = NULL;
   sub1 = NULL;
   if( outStride ) sc_outReal = outReal;
   else
   {
      sc_outReal = (double *)TA_Malloc( sizeof(double) * (size_t)historyLen );
      if( !sc_outReal ) { return TA_ALLOC_ERR; }
   }

   {
      TA_RetCode retCode;
      int i;
      int maBegIdx;
      int maNbElement;
      int offset;
      double middle;
      double deviation;
      double tempReal;
      double upper;
      double lower;
      double *tempBuffer;
      if( TA_BBW_Lookback(optInTimePeriod,optInNbDevUp,optInNbDevDn,optInMAType) > endIdx )
      {
         dummyBegIdx = 0;
         dummyNBElement = 0;
         *outBegIdx = 0; *outNBElement = 0;
         TA_MA_Close( sub0 ); TA_VAR_Close( sub1 ); if( !outStride ) TA_Free( sc_outReal );
         return TA_INSUFFICIENT_HISTORY;
      }
      tempBuffer = malloc((endIdx - startIdx + 1) * sizeof(double));
      if( !tempBuffer )
      {
         TA_MA_Close( sub0 ); TA_VAR_Close( sub1 ); if( !outStride ) TA_Free( sc_outReal );
         return TA_ALLOC_ERR;
      }
      /* Before the variance: it may be written over inReal. */
      /* Sub-stream 0: ma over `inReal`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      {
         subRc = TA_MA_OpenAndFillInternal( &sub0, inReal, (startIdx), (endIdx) + 1, optInTimePeriod, optInMAType, &maBegIdx, &maNbElement, tempBuffer );
         if( subRc != TA_SUCCESS )
         {
            free(tempBuffer);
            TA_MA_Close( sub0 ); TA_VAR_Close( sub1 ); if( !outStride ) TA_Free( sc_outReal );
            return subRc;
         }
      }
      retCode = subRc;
      if( retCode != TA_SUCCESS )
      {
         free(tempBuffer);
         dummyBegIdx = 0;
         dummyNBElement = 0;
         TA_MA_Close( sub0 ); TA_VAR_Close( sub1 ); if( !outStride ) TA_Free( sc_outReal );
         return retCode;
      }
      /* From the moving average's begIdx, as TA_BBANDS enters its deviation:
       * the variance's shift and reseed schedule are anchored on its start.
       */
      /* Sub-stream 1: var over `inReal`, warmed from bar 0 up to the
       * sub-call's own startIdx (the seeding point). */
      {
         subRc = TA_VAR_OpenAndFillInternal( &sub1, inReal, (maBegIdx), (endIdx) + 1, optInTimePeriod, 1.0, &dummyBegIdx, &dummyNBElement, sc_outReal );
         if( subRc != TA_SUCCESS )
         {
            free(tempBuffer);
            TA_MA_Close( sub0 ); TA_VAR_Close( sub1 ); if( !outStride ) TA_Free( sc_outReal );
            return subRc;
         }
      }
      retCode = subRc;
      if( retCode != TA_SUCCESS )
      {
         free(tempBuffer);
         dummyBegIdx = 0;
         dummyNBElement = 0;
         TA_MA_Close( sub0 ); TA_VAR_Close( sub1 ); if( !outStride ) TA_Free( sc_outReal );
         return retCode;
      }
      offset = maNbElement - dummyNBElement;
      if( optInNbDevUp == optInNbDevDn )
      {
         for( i = 0; i < (int)dummyNBElement; i += 1 )
         {
            middle = tempBuffer[i + offset];
            tempReal = sqrt(sc_outReal[i]) * optInNbDevUp;
            upper = middle + tempReal;
            lower = middle - tempReal;
            sc_outReal[i] = (upper - lower) / middle;
            if( middle == 0.0 )
            {
               sc_outReal[i] = 0.0;
            }
         }
      } else 
      {
         for( i = 0; i < (int)dummyNBElement; i += 1 )
         {
            middle = tempBuffer[i + offset];
            deviation = sqrt(sc_outReal[i]);
            upper = fma(deviation, optInNbDevUp, middle);
            lower = middle - deviation * optInNbDevDn;
            sc_outReal[i] = (upper - lower) / middle;
            if( middle == 0.0 )
            {
               sc_outReal[i] = 0.0;
            }
         }
      }
      free(tempBuffer);

      /* Capture the live producer state + sub handles. */
      if( dummyNBElement < 1 ) { *outBegIdx = 0; *outNBElement = 0; TA_MA_Close( sub0 ); TA_VAR_Close( sub1 ); if( !outStride ) TA_Free( sc_outReal ); return TA_INSUFFICIENT_HISTORY; }
      sp = (struct TA_BBW_Stream *)TA_Malloc( sizeof(*sp) );
      if( !sp ) { TA_MA_Close( sub0 ); TA_VAR_Close( sub1 ); if( !outStride ) TA_Free( sc_outReal ); return TA_ALLOC_ERR; }
      memset( sp, 0, sizeof(*sp) );
      sp->optInTimePeriod = optInTimePeriod;
      sp->optInNbDevUp = optInNbDevUp;
      sp->optInNbDevDn = optInNbDevDn;
      sp->optInMAType = optInMAType;
      sp->sub0 = sub0;
      sp->sub1 = sub1;
      *outBegIdx = dummyBegIdx;
      *outNBElement = dummyNBElement;
      if( !outStride ) outReal[0] = sc_outReal[dummyNBElement - 1];
      if( !outStride ) TA_Free( sc_outReal );
      sp->outRangeBegIdx = *outBegIdx;
      sp->outRangeCount = *outNBElement;
      sp->cur_outReal = outReal[(*outNBElement - 1) * outStride];
      *stream = sp;
      return TA_SUCCESS;
   }
}

/* Private function, not in public API. */
TA_RetCode TA_BBW_OpenInternal( struct TA_BBW_Stream **stream, const double inReal[], int startIdx, int historyLen, int optInTimePeriod, double optInNbDevUp, double optInNbDevDn, TA_MAType optInMAType, double *outReal )
{
   TA_RetCode retCode;
   int dummyBegIdx = 0;
   int dummyNBElement = 0;
   double sink_outReal = 0.0;
   retCode = TA_BBW_OpenImpl( stream, inReal, startIdx, historyLen, optInTimePeriod, optInNbDevUp, optInNbDevDn, optInMAType, &dummyBegIdx, &dummyNBElement, &sink_outReal, 0 );
   if( retCode == TA_SUCCESS )
   {
      *outReal = sink_outReal;
   }
   return retCode;
}

