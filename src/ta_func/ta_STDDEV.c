   if( optInNbDev == TA_REAL_DEFAULT )
      optInNbDev = 1;
   else if( !(optInNbDev >= TA_REAL_MIN && optInNbDev <= TA_REAL_MAX) )
      return TA_BAD_PARAM;
   if( !inReal )
      return TA_BAD_PARAM;
