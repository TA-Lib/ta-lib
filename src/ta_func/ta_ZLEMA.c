/* Private function, not in public API. */
static void TA_ZLEMA_ReleaseImpl( struct TA_ZLEMA_Stream *sp )
{
   if( !sp ) return;
   if( sp->ring_trailingIdx_inReal ) TA_Free( sp->ring_trailingIdx_inReal );
   TA_Free( sp );
}

/* Private function, not in public API. */
static void TA_ZLEMA_StepImpl( struct TA_ZLEMA_Stream *sp, double inReal, double *outReal )
{
   if( sp->optInTimePeriod == 1 )
   {
      *outReal= inReal;
      sp->cur_outReal = *outReal;
      return;
   }
   if( sp->ringCap_trailingIdx == 0 )
   {
      sp->ring_trailingIdx_inReal[0] = inReal;
   }
   sp->prevMA = fma(2.0 * inReal - sp->ring_trailingIdx_inReal[sp->ringPos_trailingIdx] - sp->prevMA, sp->optInK_1, sp->prevMA);
   *outReal= sp->prevMA;
   sp->cur_outReal = *outReal;
   sp->ring_trailingIdx_inReal[sp->ringPos_trailingIdx] = inReal;
   sp->ringPos_trailingIdx = sp->ringPos_trailingIdx + 1;
   if( sp->ringPos_trailingIdx >= sp->ringCap_trailingIdx )
   {
      sp->ringPos_trailingIdx = 0;
   }
}

