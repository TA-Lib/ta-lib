   double trailingSqrt;
   double tempReal;
   double fullOut;
   double halfOut;
   double diffReal;
   double local_dRing[50];
   double *dRing;
   int dRing_Idx;
   int maxIdx_dRing;

   if( startIdx < 0 )
      return TA_OUT_OF_RANGE_START_INDEX;
   if( (endIdx < 0) || (endIdx < startIdx) )
      return TA_OUT_OF_RANGE_END_INDEX;

