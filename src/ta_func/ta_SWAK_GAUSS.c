   b2p = 2.415 * (1.0 - cos(w));
   a2p = -b2p + sqrt(fma(b2p, b2p, 2.0 * b2p));
   /* The Gaussian row of Figure 5: numerator a2p^2 on the bar alone, no
    * x[i-1] or x[i-2] term. Its DC gain is 1, so the line sits on price.
    */
