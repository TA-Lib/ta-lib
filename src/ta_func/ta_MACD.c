   double prevSlow;
   double prevSignal;
   double macdValue;
   double tempReal;
   double slowK;
   double fastK;
   double signalK;
   double slowBeta;
   double fastBeta;
   double signalBeta;
   int i;
   int today;
   int outIdx;
