      prevGain *= invPeriod;
      tempValue1 = prevGain + prevLoss;
      if( tempValue1 > 0.0 )
      {
         rsiValue = 100.0 * (prevGain / tempValue1);
      } else 
      {
         rsiValue = 50.0;
      }
      ema1 = fma(beta1, ema1, k1 * rsiValue);
      ema2 = fma(beta2, ema2, k2 * ema1);
      dsBuffer[dsBuffer_Idx] = ema2;
      sumSignal = sumSignal + ema2;
