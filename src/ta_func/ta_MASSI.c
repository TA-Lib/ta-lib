/* Private function, not in public API. */
static void TA_MASSI_ReleaseImpl( struct TA_MASSI_Stream *sp )
{
   if( !sp ) return;
   if( sp->cb_ratioRing ) TA_Free( sp->cb_ratioRing );
   TA_Free( sp );
}

/* Private function, not in public API. */
static void TA_MASSI_StepImpl( struct TA_MASSI_Stream *sp, double inHigh, double inLow, double *outReal )
{
   double hl;
   double ratio;
   double tempReal;

   hl = inHigh - inLow;
   sp->ema1 = fma(hl - sp->ema1, sp->optInK_1, sp->ema1);
   sp->ema2 = fma(sp->ema1 - sp->ema2, sp->optInK_1, sp->ema2);
   if( sp->ema2 == 0.0 )
   {
      ratio = 1.0;
   } else 
   {
      ratio = sp->ema1 / sp->ema2;
   }
   sp->cb_ratioRing[sp->ratioRing_Idx] = ratio;
   sp->total = sp->total + ratio;
   sp->ratioRing_Idx = sp->ratioRing_Idx + 1;
   if( sp->ratioRing_Idx > sp->maxIdx_ratioRing )
   {
      sp->ratioRing_Idx = 0;
   }
   tempReal = sp->total;
   sp->total = sp->total - sp->cb_ratioRing[sp->ratioRing_Idx];
   *outReal= tempReal;
   sp->cur_outReal = *outReal;
}

