static void TA_ALMA_ReleaseImpl( struct TA_ALMA_Stream *sp )
{
   if( !sp ) return;
   if( sp->win_j_inReal ) TA_Free( sp->win_j_inReal );
   if( sp->cb_weights ) TA_Free( sp->cb_weights );
   TA_Free( sp );
}

/* Private function, not in public API. */
static void TA_ALMA_StepImpl( struct TA_ALMA_Stream *sp, double inReal, double *outReal )
{
   double sum;
   int j;
   int w;

   if( sp->optInTimePeriod == 1 )
   {
      *outReal= inReal;
      sp->cur_outReal = *outReal;
      return;
   }
   sp->win_j_inReal[sp->winPos_j] = inReal;
   sum = 0.0;
   w = 0;
   for( j = sp->lookbackTotal; j >= 0; j -= 1 )
   {
      sum += sp->cb_weights[w] * sp->win_j_inReal[(sp->winPos_j + sp->winCap_j - j >= sp->winCap_j) ? sp->winPos_j + sp->winCap_j - j - sp->winCap_j : sp->winPos_j + sp->winCap_j - j];
      w += 1;
   }
   *outReal= sum;
   sp->cur_outReal = *outReal;
   sp->winPos_j = sp->winPos_j + 1;
   if( sp->winPos_j >= sp->winCap_j )
   {
      sp->winPos_j = 0;
   }
}

