         TA_MEDPRICE_Close( sub0 ); TA_RMA_Close( sub1 ); TA_RMA_Close( sub2 ); TA_RMA_Close( sub3 ); TA_RMA_Close( sub4 ); if( !outStride ) TA_Free( sc_outUpper ); if( !outStride ) TA_Free( sc_outLower ); TA_Free( lagBuf0 ); TA_Free( lagBuf1 ); TA_Free( lagBuf2 ); TA_Free( lagBuf3 );
