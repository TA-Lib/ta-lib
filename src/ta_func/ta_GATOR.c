static TA_RetCode TA_GATOR_StepImpl( struct TA_GATOR_Stream *sp, double inHigh, double inLow, double *outUpper, double *outLower )
{
   double cur_tempMP = 0.0;
   double cur_tempA = 0.0;
   double cur_tempB = 0.0;
   double cur_outUpper = 0.0;
   double cur_outLower = 0.0;
   double lagIn0 = 0.0;
   double lagTap0_0 = 0.0;
   double lagIn1 = 0.0;
   double lagTap1_0 = 0.0;
   double lagIn2 = 0.0;
   double lagTap2_0 = 0.0;
   double lagIn3 = 0.0;
   double lagTap3_0 = 0.0;
   int lagCapL0 = 0;
   int lagPosL0 = 0;
   int lagCapL1 = 0;
   int lagPosL1 = 0;
   int lagCapL2 = 0;
   int lagPosL2 = 0;
   int lagCapL3 = 0;
   int lagPosL3 = 0;


   /* Pipeline the new bar through the sub-streams (batch tail order). */
   {
      TA_RetCode subRc = TA_MEDPRICE_Update( sp->sub0, inHigh, inLow, &cur_tempMP );
      if( subRc != TA_SUCCESS ) return subRc;
   }
   {
      TA_RetCode subRc = TA_RMA_Update( sp->sub1, cur_tempMP, &cur_tempA );
      if( subRc != TA_SUCCESS ) return subRc;
   }
   lagIn0 = cur_tempA;
   {
      TA_RetCode subRc = TA_RMA_Update( sp->sub2, cur_tempMP, &cur_tempB );
      if( subRc != TA_SUCCESS ) return subRc;
   }
   lagIn1 = cur_tempB;
   /* Combine map (batch tail, per bar). */
   lagTap0_0 = sp->lagBuf0[sp->lagPos0];
   lagTap0_0 = (sp->lagCap0 == 0) ? lagIn0 : lagTap0_0;
   lagTap1_0 = sp->lagBuf1[sp->lagPos1];
   lagTap1_0 = (sp->lagCap1 == 0) ? lagIn1 : lagTap1_0;
   cur_outUpper = fabs(lagTap0_0 - lagTap1_0);
   {
      TA_RetCode subRc = TA_RMA_Update( sp->sub3, cur_tempMP, &cur_tempA );
      if( subRc != TA_SUCCESS ) return subRc;
   }
   lagIn2 = cur_tempA;
   {
      TA_RetCode subRc = TA_RMA_Update( sp->sub4, cur_tempMP, &cur_tempB );
      if( subRc != TA_SUCCESS ) return subRc;
   }
   lagIn3 = cur_tempB;
   /* Combine map (batch tail, per bar). */
   lagTap2_0 = sp->lagBuf2[sp->lagPos2];
   lagTap2_0 = (sp->lagCap2 == 0) ? lagIn2 : lagTap2_0;
   lagTap3_0 = sp->lagBuf3[sp->lagPos3];
   lagTap3_0 = (sp->lagCap3 == 0) ? lagIn3 : lagTap3_0;
   cur_outLower = (lagTap2_0 < lagTap3_0) ? lagTap2_0 - lagTap3_0 : lagTap3_0 - lagTap2_0;
   lagCapL0 = sp->lagCap0;
   lagPosL0 = sp->lagPos0;
   sp->lagBuf0[lagPosL0] = lagIn0;
   lagPosL0 = lagPosL0 + 1;
   if( lagPosL0 >= lagCapL0 )
   {
      lagPosL0 = 0;
   }
   sp->lagPos0 = lagPosL0;
   lagCapL1 = sp->lagCap1;
   lagPosL1 = sp->lagPos1;
   sp->lagBuf1[lagPosL1] = lagIn1;
   lagPosL1 = lagPosL1 + 1;
   if( lagPosL1 >= lagCapL1 )
   {
      lagPosL1 = 0;
   }
   sp->lagPos1 = lagPosL1;
   lagCapL2 = sp->lagCap2;
   lagPosL2 = sp->lagPos2;
   sp->lagBuf2[lagPosL2] = lagIn2;
   lagPosL2 = lagPosL2 + 1;
   if( lagPosL2 >= lagCapL2 )
   {
      lagPosL2 = 0;
   }
   sp->lagPos2 = lagPosL2;
   lagCapL3 = sp->lagCap3;
   lagPosL3 = sp->lagPos3;
   sp->lagBuf3[lagPosL3] = lagIn3;
   lagPosL3 = lagPosL3 + 1;
   if( lagPosL3 >= lagCapL3 )
   {
      lagPosL3 = 0;
   }
   sp->lagPos3 = lagPosL3;
   *outUpper = cur_outUpper;
   *outLower = cur_outLower;
   return TA_SUCCESS;
}

