   if( startIdx >= historyLen )
   {
      *outBegIdx = 0;
      *outNBElement = 0;
      return TA_INSUFFICIENT_HISTORY;
   }

   return outStride ? TA_GATOR_OpenFillFrame( stream, inHigh, inLow, startIdx, historyLen, optInJawPeriod, optInJawShift, optInTeethPeriod, optInTeethShift, optInLipsPeriod, optInLipsShift, outBegIdx, outNBElement, outUpper, outLower ) : TA_GATOR_OpenSinkFrame( stream, inHigh, inLow, startIdx, historyLen, optInJawPeriod, optInJawShift, optInTeethPeriod, optInTeethShift, optInLipsPeriod, optInLipsShift, outBegIdx, outNBElement, outUpper, outLower );
