         tempReal = 0.0;
         for( j = windowStart; j <= i; j += 1 )
         {
            tempReal += x_inReal[j & xMask];
         }
         shift = tempReal * invPeriod;
         total1 = 0.0;
         total2 = 0.0;
         total3 = 0.0;
         for( j = windowStart; j <= i; j += 1 )
         {
            dev = x_inReal[j & xMask] - shift;
            dev2 = dev * dev;
            total1 += dev;
            total2 += dev2;
            total3 += dev2 * dev;
         }
         residue = total1 * invPeriod;
         residueSq = residue * residue;
