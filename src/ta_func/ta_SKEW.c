/* Private function, not in public API. */
TA_RetCode TA_SKEW_BlockBatch( int startIdx, int endIdx, const double inReal[], int optInTimePeriod, int *outBegIdx, int *outNBElement, double outReal[] )
{
   struct TA_SKEW_Stream *stream;
   TA_RetCode retCode;
   int lookbackTotal;
   int firstIdx;

   if( (startIdx < 0) || (startIdx > TA_INDEX_MAX) )
      return TA_OUT_OF_RANGE_START_INDEX;
   if( (endIdx < 0) || (endIdx > TA_INDEX_MAX) || (endIdx < startIdx) )
      return TA_OUT_OF_RANGE_END_INDEX;

   lookbackTotal = TA_SKEW_Lookback( optInTimePeriod );
   if( lookbackTotal < 0 )
      return TA_BAD_PARAM;
   if( !inReal )
      return TA_BAD_PARAM;
   if( !outBegIdx || !outNBElement )
      return TA_BAD_PARAM;
   if( !outReal )
      return TA_BAD_PARAM;

   firstIdx = startIdx < lookbackTotal ? lookbackTotal : startIdx;
   if( firstIdx > endIdx )
   {
      *outBegIdx = 0;
      *outNBElement = 0;
      return TA_SUCCESS;
   }
   retCode = TA_SKEW_OpenInternal( &stream, inReal, startIdx, firstIdx + 1, optInTimePeriod, outReal );
   if( retCode != TA_SUCCESS ) return retCode;
   if( endIdx > firstIdx )
   {
      TA_SKEW_KernImpl( stream, inReal + firstIdx + 1, endIdx - firstIdx, outReal + 1 );
   }
   TA_SKEW_Close( stream );
   *outBegIdx = firstIdx;
   *outNBElement = endIdx - firstIdx + 1;
   return TA_SUCCESS;
}

