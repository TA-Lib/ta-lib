static void TA_CVI_StepImpl( struct TA_CVI_Stream *sp, double inHigh, double inLow, double *outReal )
{
   double laggedEMA;
   double tempReal;
   double prevEMA;

   prevEMA = sp->prevEMA;
   tempReal = inHigh - inLow;
   prevEMA = fma(tempReal - prevEMA, sp->optInK_1, prevEMA);
   laggedEMA = sp->cb_emaRing[sp->emaRing_Idx];
   sp->cb_emaRing[sp->emaRing_Idx] = prevEMA;
   sp->emaRing_Idx = sp->emaRing_Idx + 1;
   if( sp->emaRing_Idx > sp->maxIdx_emaRing )
   {
      sp->emaRing_Idx = 0;
   }
   if( laggedEMA != 0.0 )
   {
      *outReal= 100.0 * ((prevEMA - laggedEMA) / laggedEMA);
   } else 
   {
      *outReal= 0.0;
   }
   sp->cur_outReal = *outReal;
   sp->prevEMA = prevEMA;
}

