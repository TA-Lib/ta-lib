static TA_RetCode TA_ALLIGATOR_OpenImpl( struct TA_ALLIGATOR_Stream **stream, const double inHigh[], const double inLow[], int startIdx, int historyLen, int optInJawPeriod, int optInJawShift, int optInTeethPeriod, int optInTeethShift, int optInLipsPeriod, int optInLipsShift, int *outBegIdx, int *outNBElement, double outJaw[], double outTeeth[], double outLips[], int outStride )
{
   if( !stream ) return TA_BAD_PARAM;
   *stream = NULL;
   if( historyLen > TA_INDEX_MAX + 1 ) return TA_OUT_OF_RANGE_END_INDEX;
   if( !inHigh || !inLow || !outJaw || !outTeeth || !outLips ) return TA_BAD_PARAM;
   if( (int)optInJawPeriod == TA_INTEGER_DEFAULT )
      optInJawPeriod = 13;
   else if( (int)optInJawPeriod < 1 || (int)optInJawPeriod > 100000 )
      return TA_BAD_PARAM;
   if( (int)optInJawShift == TA_INTEGER_DEFAULT )
      optInJawShift = 8;
   else if( (int)optInJawShift < 0 || (int)optInJawShift > 100000 )
      return TA_BAD_PARAM;
   if( (int)optInTeethPeriod == TA_INTEGER_DEFAULT )
      optInTeethPeriod = 8;
   else if( (int)optInTeethPeriod < 1 || (int)optInTeethPeriod > 100000 )
      return TA_BAD_PARAM;
   if( (int)optInTeethShift == TA_INTEGER_DEFAULT )
      optInTeethShift = 5;
   else if( (int)optInTeethShift < 0 || (int)optInTeethShift > 100000 )
      return TA_BAD_PARAM;
   if( (int)optInLipsPeriod == TA_INTEGER_DEFAULT )
      optInLipsPeriod = 5;
   else if( (int)optInLipsPeriod < 1 || (int)optInLipsPeriod > 100000 )
      return TA_BAD_PARAM;
   if( (int)optInLipsShift == TA_INTEGER_DEFAULT )
      optInLipsShift = 3;
   else if( (int)optInLipsShift < 0 || (int)optInLipsShift > 100000 )
      return TA_BAD_PARAM;
   if( startIdx >= historyLen )
   {
      *outBegIdx = 0;
      *outNBElement = 0;
      return TA_INSUFFICIENT_HISTORY;
   }

   return outStride ? TA_ALLIGATOR_OpenFillFrame( stream, inHigh, inLow, startIdx, historyLen, optInJawPeriod, optInJawShift, optInTeethPeriod, optInTeethShift, optInLipsPeriod, optInLipsShift, outBegIdx, outNBElement, outJaw, outTeeth, outLips ) : TA_ALLIGATOR_OpenSinkFrame( stream, inHigh, inLow, startIdx, historyLen, optInJawPeriod, optInJawShift, optInTeethPeriod, optInTeethShift, optInLipsPeriod, optInLipsShift, outBegIdx, outNBElement, outJaw, outTeeth, outLips );
}

