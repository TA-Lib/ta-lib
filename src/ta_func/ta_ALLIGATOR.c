/* Private function, not in public API. */
static TA_RetCode TA_ALLIGATOR_StepImpl( struct TA_ALLIGATOR_Stream *sp, double inHigh, double inLow, double *outJaw, double *outTeeth, double *outLips )
{
   double cur_tempMP = 0.0;
   double cur_outJaw = 0.0;
   double cur_outTeeth = 0.0;
   double cur_outLips = 0.0;


   /* Pipeline the new bar through the sub-streams (batch tail order). */
   {
      TA_RetCode subRc = TA_MEDPRICE_Update( sp->sub0, inHigh, inLow, &cur_tempMP );
      if( subRc != TA_SUCCESS ) return subRc;
   }
   {
      TA_RetCode subRc = TA_RMA_Update( sp->sub1, cur_tempMP, &cur_outJaw );
      if( subRc != TA_SUCCESS ) return subRc;
   }
   {
      TA_RetCode subRc = TA_RMA_Update( sp->sub2, cur_tempMP, &cur_outTeeth );
      if( subRc != TA_SUCCESS ) return subRc;
   }
   {
      TA_RetCode subRc = TA_RMA_Update( sp->sub3, cur_tempMP, &cur_outLips );
      if( subRc != TA_SUCCESS ) return subRc;
   }
   *outJaw = cur_outJaw;
   *outTeeth = cur_outTeeth;
   *outLips = cur_outLips;
   return TA_SUCCESS;
}

