TA_RetCode TA_FISHER_OpenInternal( struct TA_FISHER_Stream **stream, const double inHigh[], const double inLow[], int startIdx, int historyLen, int optInTimePeriod, double *outFisher, double *outTrigger )
{
   TA_RetCode retCode;
   int dummyBegIdx = 0;
   int dummyNBElement = 0;
   double sink_outFisher = 0.0;
   double sink_outTrigger = 0.0;
   retCode = TA_FMA_AVAILABLE ? TA_FISHER_OpenImplFma( stream, inHigh, inLow, startIdx, historyLen, optInTimePeriod, &dummyBegIdx, &dummyNBElement, &sink_outFisher, &sink_outTrigger, 0 ) : TA_FISHER_OpenImplPlain( stream, inHigh, inLow, startIdx, historyLen, optInTimePeriod, &dummyBegIdx, &dummyNBElement, &sink_outFisher, &sink_outTrigger, 0 );
   if( retCode == TA_SUCCESS )
   {
      *outFisher = sink_outFisher;
      *outTrigger = sink_outTrigger;
   }
   return retCode;
}

