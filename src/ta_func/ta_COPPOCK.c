TA_RetCode TA_COPPOCK_OpenInternal( struct TA_COPPOCK_Stream **stream, const double inReal[], int startIdx, int historyLen, int optInWMAPeriod, int optInROC1Period, int optInROC2Period, double *outReal )
{
   TA_RetCode retCode;
   int dummyBegIdx = 0;
   int dummyNBElement = 0;
   double sink_outReal = 0.0;
   retCode = TA_COPPOCK_OpenImpl( stream, inReal, startIdx, historyLen, optInWMAPeriod, optInROC1Period, optInROC2Period, &dummyBegIdx, &dummyNBElement, &sink_outReal, 0 );
   if( retCode == TA_SUCCESS )
   {
      *outReal = sink_outReal;
   }
   return retCode;
}

