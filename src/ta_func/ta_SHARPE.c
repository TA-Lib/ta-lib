static TA_RetCode TA_SHARPE_OpenImpl( struct TA_SHARPE_Stream **stream, const double inReal[], int startIdx, int historyLen, int optInTimePeriod, double optInRiskFreeRate, double optInAnnualization, int *outBegIdx, int *outNBElement, double outReal[], int outStride )
{
   if( !stream ) return TA_BAD_PARAM;
   *stream = NULL;
   if( historyLen > TA_INDEX_MAX + 1 ) return TA_OUT_OF_RANGE_END_INDEX;
   if( !inReal || !outReal ) return TA_BAD_PARAM;
   if( (int)optInTimePeriod == TA_INTEGER_DEFAULT )
      optInTimePeriod = 20;
   else if( (int)optInTimePeriod < 2 || (int)optInTimePeriod > 100000 )
      return TA_BAD_PARAM;
   if( optInRiskFreeRate == TA_REAL_DEFAULT )
      optInRiskFreeRate = 0;
   else if( !(optInRiskFreeRate >= TA_REAL_MIN && optInRiskFreeRate <= TA_REAL_MAX) )
      return TA_BAD_PARAM;
   if( optInAnnualization == TA_REAL_DEFAULT )
      optInAnnualization = 252;
   else if( !(optInAnnualization >= 0e0 && optInAnnualization <= TA_REAL_MAX) )
      return TA_BAD_PARAM;
   if( startIdx >= historyLen )
   {
      *outBegIdx = 0;
      *outNBElement = 0;
      return TA_INSUFFICIENT_HISTORY;
   }

   return outStride ? TA_SHARPE_OpenFillFrame( stream, inReal, startIdx, historyLen, optInTimePeriod, optInRiskFreeRate, optInAnnualization, outBegIdx, outNBElement, outReal ) : TA_SHARPE_OpenSinkFrame( stream, inReal, startIdx, historyLen, optInTimePeriod, optInRiskFreeRate, optInAnnualization, outBegIdx, outNBElement, outReal );
}

