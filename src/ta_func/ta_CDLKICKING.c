/* Private function, not in public API. */
TA_RetCode TA_CDLKICKING_BlockBatch( int startIdx, int endIdx, const double inOpen[], const double inHigh[], const double inLow[], const double inClose[], int *outBegIdx, int *outNBElement, int outInteger[] )
{
   struct TA_CDLKICKING_Stream *stream;
   TA_RetCode retCode;
   int lookbackTotal;
   int firstIdx;

   if( (startIdx < 0) || (startIdx > TA_INDEX_MAX) )
      return TA_OUT_OF_RANGE_START_INDEX;
   if( (endIdx < 0) || (endIdx > TA_INDEX_MAX) || (endIdx < startIdx) )
      return TA_OUT_OF_RANGE_END_INDEX;

   lookbackTotal = TA_CDLKICKING_Lookback(  );
   if( lookbackTotal < 0 )
      return TA_BAD_PARAM;
   if( !inOpen )
      return TA_BAD_PARAM;
   if( !inHigh )
      return TA_BAD_PARAM;
   if( !inLow )
      return TA_BAD_PARAM;
   if( !inClose )
      return TA_BAD_PARAM;
   if( !outBegIdx || !outNBElement )
      return TA_BAD_PARAM;
   if( !outInteger )
      return TA_BAD_PARAM;

   firstIdx = startIdx < lookbackTotal ? lookbackTotal : startIdx;
   if( firstIdx > endIdx )
   {
      *outBegIdx = 0;
      *outNBElement = 0;
      return TA_SUCCESS;
   }
   retCode = TA_CDLKICKING_OpenInternal( &stream, inOpen, inHigh, inLow, inClose, startIdx, firstIdx + 1, outInteger );
   if( retCode != TA_SUCCESS ) return retCode;
   if( endIdx > firstIdx )
   {
      TA_CDLKICKING_KernImpl( stream, inOpen + firstIdx + 1, inHigh + firstIdx + 1, inLow + firstIdx + 1, inClose + firstIdx + 1, endIdx - firstIdx, outInteger + 1 );
   }
   TA_CDLKICKING_Close( stream );
   *outBegIdx = firstIdx;
   *outNBElement = endIdx - firstIdx + 1;
   return TA_SUCCESS;
}

