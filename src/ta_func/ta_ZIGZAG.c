   *outTrend= sp->trend;
   *outPivotIdx= sp->barIdx - sp->barsSincePivot;
   sp->cur_outZigZag = *outZigZag;
   sp->cur_outTrend = *outTrend;
   sp->cur_outPivotIdx = *outPivotIdx;
